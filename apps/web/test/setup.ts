import { afterEach } from 'vitest';
import { cleanup, configure } from '@testing-library/react';
import dayjs from 'dayjs';
import 'dayjs/locale/ru';
import utc from 'dayjs/plugin/utc';
import timezone from 'dayjs/plugin/timezone';
import { installMatchMedia, resetViewport } from './viewport';
import { restoreContentHeights } from './clamp';
import { restoreHttpMock } from './http';
import { resetCaptcha } from './captcha';
import { __resetAuthForTests } from '../src/auth/AuthContext';
import { __resetSessionForTests } from '../src/shared/api';

/*
 * Предел ОЖИДАНИЙ testing-library — `waitFor`, `findBy*`, `findAllBy*`.
 *
 * Решение о бюджете времени проект уже принял: `testTimeout` поднят с пяти секунд до двадцати, и
 * причина записана в `vitest.config.ts` — «при параллельном прогоне на занятой машине такие тесты
 * начинали падать по таймауту, причём каждый раз разные, и падение читалось как поломка экрана».
 * Но поднят был только тот предел, который виден в конфиге. У самих ожиданий свой, спрятанный в
 * умолчании библиотеки, — ОДНА СЕКУНДА, и правка его не коснулась. Получилось, что у теста
 * бюджет двадцать секунд, а у его же ожидания — одна.
 *
 * Чем это кончалось, измерено на `vehicle-request-copy.test.tsx` (ожидание двух сообщений
 * валидации после нажатия «Сохранить»):
 *
 *   без нагрузки                       187, 194, 195 мс
 *   параллельный прогон, LA 9–17       347, 426, 442, 466 мс
 *   параллельный прогон, LA ~21        496, 564, 586, 801, 875, 1006, 1339 мс  ← двое из семи
 *                                                                                 за пределом
 *
 * Форма при этом всегда одна и та же: 24 поля, 11 заполненных до нажатия во всех семи прогонах, —
 * то есть тест ждал правильного признака и ждал его законно, ему просто не хватало секунды.
 * Внешне же это выглядело поломкой экрана: `findAllByText` сообщает «элемент не найден», а не
 * «не дождался», и на глаз неотличимо от исчезнувшей проверки формы.
 *
 * Пять секунд — не круглое число, а замер с запасом: втрое с лишним от худшего наблюдавшегося
 * (1339 мс) и вчетверо ниже `testTimeout`. Второе важно не меньше первого: пока предел ожидания
 * ниже предела теста, упавшее ожидание печатает найденное дерево и объясняет, ЧЕГО не хватило, —
 * а тест, добежавший до собственного потолка, печатает только «Test timed out».
 *
 * Утверждения это не ослабляет: ожидание проверяет ТО ЖЕ условие и падает, если оно не наступит.
 * Дольше ждёт лишь тот прогон, который и так уже красный.
 */
configure({ asyncUtilTimeout: 5_000 });

// Даты портал показывает в МСК (utils/format), а плагины dayjs подключает точка входа — в тестах
// её нет, и без этих трёх строк любой рендер с датой падает на `dayjs(...).tz is not a function`.
dayjs.extend(utc);
dayjs.extend(timezone);
dayjs.locale('ru');
dayjs.tz.setDefault('Europe/Moscow');

// jsdom не реализует ни того, ни другого, а antd опирается на оба: без заглушек падает любой
// рендер компонента с выпадающим списком. matchMedia к тому же управляемый — им же тесты
// переключают режим устройства (см. ./viewport и ADR 0030).
installMatchMedia();

// Прокрутка к полю-блокеру (ADR 0094) зовёт `element.scroll`, которого в jsdom нет вовсе: без
// заглушки любой тест на отказ формы падал бы не на смысле, а на отсутствующем методе. Проверять
// саму прокрутку в jsdom всё равно нельзя — размеры там нулевые, поэтому тесты следят за вызовом
// `scrollToField`, а не за положением экрана.
if (!Element.prototype.scroll) {
  Element.prototype.scroll = () => {};
}

/*
 * Псевдоэлементы jsdom не реализует вовсе: `getComputedStyle(el, '::before')` он не считает, а
 * печатает «Not implemented» в вывод — по строке на каждый вызов, и от одного прогона кабинета
 * водителя их набегала тысяча. Заглушка законна именно поэтому: вернуть она может только то же
 * пустое объявление, что вернул бы jsdom, — вычислять там нечего, стилей псевдоэлементов в нём
 * нет. Вызовы без псевдоэлемента идут в родной метод и считаются как раньше.
 */
const computedStyle = window.getComputedStyle.bind(window);
window.getComputedStyle = ((element: Element, pseudoElement?: string | null) =>
  pseudoElement
    ? ({ getPropertyValue: () => '' } as unknown as CSSStyleDeclaration)
    : computedStyle(element)) as typeof window.getComputedStyle;

if (!globalThis.ResizeObserver) {
  globalThis.ResizeObserver = class {
    observe() {}
    unobserve() {}
    disconnect() {}
  };
}

afterEach(() => {
  cleanup();
  resetViewport();
  /*
   * Состояние сессии живёт в модулях (токен, висящее обновление, чья сессия в кэше) и переживает
   * размонтирование дерева. Не сбросив его, второй тест файла начинал бы с чужой сессии — и
   * падал бы он, а не тот, кто её оставил.
   */
  __resetAuthForTests();
  __resetSessionForTests();
  /*
   * Капча тоже живёт вне дерева: ключ на вкладку и промис скрипта лежат в модулях, объект службы
   * Яндекса и тег `captcha.js` — в документе, подменённая навигация — в `window`. Не сняв это,
   * тест «скрипта в документе нет» проверял бы чужой тег, а тест выключенной капчи — чужой ключ
   * (см. ./captcha).
   */
  resetCaptcha();
  // Подменённый сетью тест не должен утаскивать за собой следующие: снимаем мок здесь, а не в
  // самом `mockHttp` — хук, зарегистрированный изнутри `it`, до следующего теста не доживает.
  restoreHttpMock();
  // По той же причине снимается подмена высот, которой проверяют свёрнутые ячейки: она стоит на
  // прототипе элемента и пережила бы тест, который её ставил (см. ./clamp).
  restoreContentHeights();
  /*
   * Хранилище браузера в jsdom одно на файл: свёрнутость меню, черновики водителя и наборы
   * отборов списков (ADR 0139) переживают размонтирование дерева. Не вычистив его, второй тест
   * файла открывал бы список с отборами, которые выставил первый, — и падал бы он, а не тот, кто
   * их оставил.
   */
  localStorage.clear();
});
