import {
  actsForCounterparty,
  OFFICE_EQUIPMENT_PROFILE_REGISTRY,
  PORTAL_SECTIONS,
  type AuthUser,
  type Permission,
  type PortalSectionId,
  type SectionAccess,
} from '@technic/contracts';

/**
 * ⚠️ ВРЕМЕННАЯ ЗАПЛАТКА — снимается на запуске.
 *
 * Модуль «Орг.техника» ещё дорабатывается, и до запуска раздел не должен показываться никому,
 * кроме тех, кто его и делает: администратора, держателей наборов «Оргтехника: ведение» и
 * «Оргтехника: ИТ-служба» — и подрядчика, который по этим заявкам работает (см.
 * `LOCK_KEEPER_COUNTERPARTY`). Сегодня раздел открывают `serviceRequests.read` и
 * `officeEquipment.read` (`portal-sections.ts`), а второе право есть почти у каждой роли портала —
 * то есть видят его все.
 *
 * Почему заплатка стоит **здесь, а не в реестре разделов**. Реестр лежит в контрактах и отвечает на
 * «кому раздел положен по правам» — это модель доступа, и временное «показываем не всем, пока
 * доделываем» ею не является: правь мы реестр, пришлось бы вместе с ним править матрицу прав, её
 * тесты и серверную сторону, а на запуске всё это возвращать обратно. Здесь же снятие заплатки —
 * это удаление одного файла и двух вызовов.
 *
 * ЧТО УДАЛИТЬ НА ЗАПУСКЕ:
 *   1. этот файл;
 *   2. вызов `withTemporarySectionLock` в `auth/ProtectedRoute.tsx` (`useSectionAccess`);
 *   3. вызов `withTemporarySectionLock` в `components/AppLayout.tsx` (сборка пунктов меню);
 *   4. учётку с кодом набора оргтехники в тестах, помеченных ссылкой на этот файл.
 *
 * Заплатка **интерфейсная**: она убирает раздел из меню, гейта маршрута и стартовой страницы, но
 * прав не отнимает — API по-прежнему отвечает всем, у кого право есть. Это осознанно: закрывается
 * незаконченный экран, а не дыра в доступе.
 */

/** Разделы, спрятанные до запуска. Пустой список — заплатка ничего не делает. */
const LOCKED_SECTIONS: readonly PortalSectionId[] = ['office-equipment'];

/**
 * Кому раздел остаётся видимым сверх роли администратора — тем, кто модуль и ведёт: коды наборов
 * профилей «Оператор» и «Системный администратор» (реестр профилей, Р3).
 *
 * КОДЫ, А НЕ НАДСТРОЙКИ (план профилей, Р9 и Н7). Ответ сегодня тот же — код системного набора
 * совпадает с кодом надстройки по построению, — но надстройки уходят на шаге 1e ADR 0106, и если
 * запуск случится позже него, условие на `user.addons` закрыло бы раздел ровно у тех, кто его
 * доделывает. Заплатка временная, а пережить она обязана то, что произойдёт раньше её снятия.
 *
 * Профиль «Заявитель» сюда не входит намеренно: заявитель — не тот, кто доделывает модуль, и его
 * код (Э7) раздел до запуска открывать не должен. «Сервисный центр» кодами не выдаётся вовсе —
 * он опознаётся парой «роль + тип контрагента» и стоит отдельной строкой ниже. Свободно собранный
 * набор полномочий (ADR 0106) не входит по той же причине, что и раньше: спрашивать его пришлось
 * бы по правам, а именно права здесь есть у всех.
 */
const LOCK_KEEPER_GRANTS: readonly string[] = (['operator', 'it'] as const).flatMap(
  (profile) => OFFICE_EQUIPMENT_PROFILE_REGISTRY[profile].grants,
);

/**
 * Тип контрагента, которому раздел остаётся видимым, — сервисная компания (профиль «Сервисный
 * центр», Р11 реестра профилей).
 *
 * ПОЧЕМУ ПОДРЯДЧИК — ИСКЛЮЧЕНИЕ, ХОТЯ МОДУЛЬ ДОРАБАТЫВАЮТ. Заплатка закрывает незаконченный экран
 * от тех, кому он пока не нужен, а у сервисной компании этот раздел — ЕДИНСТВЕННЫЙ: без него она
 * входит в портал и видит «Разделы портала вам пока не назначены», то есть заплатка отнимает у неё
 * не лишний пункт меню, а работу целиком. Заявки до неё доходили письмами (ADR 0153), но открыть
 * назначенную заявку, ответить в обсуждении и подшить акт можно только в разделе.
 *
 * Взят из реестра профилей, а не написан строкой: пара «роль `operator` + тип `service`» — это и
 * есть определение профиля, и `actsForCounterparty` спрашивает ровно её (роль без типа отвечает
 * уже не за тот модуль). `null` у остальных профилей делает условие ниже пустым само собой.
 */
const LOCK_KEEPER_COUNTERPARTY = OFFICE_EQUIPMENT_PROFILE_REGISTRY.service.counterpartyType;

/**
 * Права, которыми открываются закрытые разделы — и только они.
 *
 * Заплатка гасит право, а не строку реестра, потому что вопросов у портала про раздел три (меню,
 * гейт маршрута, стартовая страница), а спрашивают они одно — `isSectionOpen`, и внутрь ему видно
 * только `canUse`. Погасив право, мы отвечаем на все три сразу и не можем разойтись: спрятанный
 * раздел не станет ни пунктом меню, ни стартовой страницей, ни открытым по прямой ссылке.
 *
 * Право, которым открывается ещё и незакрытый раздел, из набора исключается: гасить его значило бы
 * спрятать заодно чужой раздел. Сегодня таких нет — `serviceRequests.read` и `officeEquipment.read`
 * не открывают ничего, кроме «Орг.техники», — но проверка стоит здесь, а не в комментарии, чтобы
 * следующая строка в `LOCKED_SECTIONS` не унесла с собой соседа молча.
 */
const LOCKED_PERMISSIONS: ReadonlySet<Permission> = new Set(
  PORTAL_SECTIONS.filter((section) => LOCKED_SECTIONS.includes(section.id))
    .flatMap((section) => section.permissions)
    .filter(
      (permission) =>
        !PORTAL_SECTIONS.some(
          (other) => !LOCKED_SECTIONS.includes(other.id) && other.permissions.includes(permission),
        ),
    ),
);

/**
 * Видит ли учётка спрятанные разделы: администратор, держатели наборов оргтехники и сервисная
 * компания, которой эти заявки и исполнять.
 */
export function keepsLockedSections(user: AuthUser | null | undefined): boolean {
  if (!user) return false;
  if (user.role === 'admin') return true;
  if (LOCK_KEEPER_COUNTERPARTY && actsForCounterparty(user, LOCK_KEEPER_COUNTERPARTY)) return true;
  return (user.grantCodes ?? []).some((code) => LOCK_KEEPER_GRANTS.includes(code));
}

/**
 * Доступ к разделам, из которого вычтены спрятанные, — обёртка над тем, что портал спрашивает у
 * реестра. Всё остальное портала не касается: действия внутри страниц по-прежнему спрашивают `can`,
 * и заплатка их не трогает.
 */
export function withTemporarySectionLock(
  user: AuthUser | null | undefined,
  access: SectionAccess,
): SectionAccess {
  if (LOCKED_PERMISSIONS.size === 0 || keepsLockedSections(user)) return access;
  return {
    ...access,
    canUse: (permission) => !LOCKED_PERMISSIONS.has(permission) && access.canUse(permission),
  };
}
