import { useAuth } from './AuthContext';

/**
 * Кому открыты экраны сообщений о технике (план `docs/office-equipment-candidate-plan.md`, Р8, §9).
 *
 * ОДНО МЕСТО НА ОБА ЭКРАНА, и это главное, ради чего заведён этот файл. Вопросов у портала два —
 * «показывать ли окно «Сообщить об аппарате» в форме заявки» и «показывать ли очередь проверки», —
 * но ответ на оба складывается из одних и тех же слагаемых. Разложенный по экранам, он разъехался
 * бы при первой же правке условия: одна половина модуля открылась бы, а вторая осталась закрытой,
 * и увидели бы это не тестом, а звонком.
 *
 * ФЛАГА `candidate_intake` ЗДЕСЬ НЕТ, И ЭТО РЕШЕНИЕ ВЛАДЕЛЬЦА, А НЕ ЗАБЫВЧИВОСТЬ. План (§14, пункт
 * 2 backlog) описывает рубильник приёма кандидатов, но серверного resolver флагов в репозитории
 * сегодня нет вовсе, и портал, спрашивающий несуществующее поле, получил бы `undefined` — то есть
 * либо закрыл бы экраны навсегда, либо открыл бы их независимо от рубильника. Оба исхода хуже
 * честного «флага пока нет».
 *
 * КУДА ЕГО ВСТАВЛЯТЬ, КОГДА ОН ПОЯВИТСЯ: ровно в `intakeOpen` ниже — одной конъюнкцией, здесь и
 * больше нигде. Экраны спрашивают этот хук, а не права напрямую, именно затем, чтобы будущий
 * рубильник стоил одной строки и не размазался по форме заявки, ссылке под полем, очереди и
 * подвкладке.
 *
 * Права до выпуска B не выданы никому (Э8), поэтому сегодня оба ответа — `false` у всех учёток:
 * экраны собраны и проверены тестами, но на глаза не попадаются.
 */
export function useCandidateIntake(): {
  /** Заявитель может сообщить об аппарате вместе со своей заявкой (`officeEquipment.propose`). */
  canPropose: boolean;
  /** Проверяющий видит очередь, правит реквизиты и принимает три решения (`officeEquipment.review`). */
  canReview: boolean;
} {
  const { can } = useAuth();
  /*
   * Место будущего рубильника приёма кандидатов: `&& flags.candidateIntake` встанет сюда, когда
   * появится серверный resolver. Рубильник гасит ВХОД, а не проверку: очередь уже принятых
   * сообщений обязана остаться доступной, иначе выключение приёма заперло бы кандидатов, которых
   * кто-то должен разобрать.
   */
  const intakeOpen = true;
  return {
    canPropose: intakeOpen && can('officeEquipment.propose'),
    canReview: can('officeEquipment.review'),
  };
}
