import { hasFeature } from '@technic/contracts';
import { useAuth } from './AuthContext';

/**
 * Кому открыты экраны сообщений о технике (план `docs/office-equipment-candidate-plan.md`, Р8, §9).
 *
 * ОДНО МЕСТО НА ОБА ЭКРАНА, и это главное, ради чего заведён этот файл. Вопросов у портала два —
 * «показывать ли окно «Сообщить об аппарате» в форме заявки» и «показывать ли очередь проверки», —
 * но ответ на оба складывается из одних и тех же слагаемых. Разложенный по экранам, он разъехался
 * бы при первой же правке условия: одна половина модуля открылась бы, а вторая осталась закрытой,
 * и увидели бы это не тестом, а звонком.
 *
 * РУБИЛЬНИК ПРИЁМА ЖИВЁТ ЗДЕСЬ, И ТОЛЬКО ЗДЕСЬ (план
 * `docs/office-equipment-request-subject-plan.md`, Р10). Раньше на его месте стояло жёсткое
 * `intakeOpen = true` с оговоркой «серверного резолвера флагов в репозитории нет»; резолвера нет и
 * сейчас, но и не нужно — заведена одна строка состояния, значение которой сервер отдаёт в ответе
 * сессии. Портал спрашивает ТОЛЬКО этот ответ: своей копии значения (env, сборочной константы,
 * локального состояния) у него нет и быть не должно — второй источник разошёлся бы с серверным
 * молча, и человеку показывалась бы дверь, за которой стоит 403.
 *
 * FAIL-CLOSED — правило `hasFeature`: ключа в списке нет, значит сервер счёл рубильник выключенным;
 * списка нет вовсе — отвечает старый сервер, который о рубильнике не знает (окно выката, когда
 * портал новее приложения). Оба случая означают «закрыто»: обратное умолчание открыло бы приём
 * ровно в том окне, ради которого рубильник и заводился, — миграция прав применяется ДО
 * перезапуска приложения.
 *
 * РУБИЛЬНИК ГАСИТ ВХОД, А НЕ ПРОВЕРКУ, и потому стоит только в `canPropose`. Очередь уже принятых
 * сообщений обязана остаться доступной: аварийное выключение прекращает приток, но заперев вместе с
 * ним и разбор, оно оставило бы кандидатов, которых кто-то должен рассмотреть, без единственной
 * двери решения.
 *
 * Права до выпуска B не выданы никому (Э8), поэтому сегодня оба ответа — `false` у всех учёток:
 * экраны собраны и проверены тестами, но на глаза не попадаются.
 */
export function useCandidateIntake(): {
  /** Заявитель может сообщить об аппарате вместе со своей заявкой (`officeEquipment.propose`). */
  canPropose: boolean;
  /** Проверяющий видит очередь, правит реквизиты и принимает три решения (`officeEquipment.review`). */
  canReview: boolean;
} {
  const { can, user } = useAuth();
  // Значение — из ответа сессии, посчитанное сервером; отсутствие поля или ключа означает «приём
  // закрыт» (`hasFeature`). Право при этом спрашивается всё равно: рубильник открывает приём для
  // тех, кому он разрешён, а не вместо разрешения.
  const intakeOpen = hasFeature(user, 'office_equipment_candidate_intake');
  return {
    canPropose: intakeOpen && can('officeEquipment.propose'),
    canReview: can('officeEquipment.review'),
  };
}
