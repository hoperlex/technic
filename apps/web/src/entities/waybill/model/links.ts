import { waybillPath, type Permission } from '@technic/contracts';

/**
 * Право на переход к путевому листу по его номеру, названному в чужом списке.
 *
 * Переход состоит из двух половин, и врозь они расходятся: адрес и право на него. Здесь вторая:
 * сам адрес живёт в контрактах (`packages/contracts/src/links.ts`), потому что спрашивают его
 * двое — портал и почта, печатающая номер в сводке; прав контракты не знают намеренно.
 *
 * Обёртка возвращает `null`, если журнал этой роли не положен: место вызова тогда рисует прежний
 * текст, а не ссылку, кончающуюся пустым экраном или сообщением «не найдено».
 */

/** Путевой лист: журнал учёта с поиском по номеру. */
export function waybillLink(
  can: (permission: Permission) => boolean,
  number: string,
): string | null {
  if (!can('waybills.read')) return null;
  return waybillPath(number);
}
