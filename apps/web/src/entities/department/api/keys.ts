import { createQueryKeys, type Query } from '@shared/api';

/**
 * Ключи запросов отделов.
 *
 * Ключ описывает **запрос**, а не сущность: у справочника два разных вопроса — страница вкладки
 * с фильтром и сортировкой и весь список действующих отделов для выпадающих списков. Под общим
 * ключом форма заявки получила бы отфильтрованную страницу таблицы, а таблица — пятьсот строк
 * мимо своих фильтров: кто спросил вторым, тот и определяет ответ обоим.
 *
 * Параметров у `options` нет намеренно: выключенный отдел не предлагают нигде — заявку заводят на
 * работающее подразделение, а у заведённой наименование приходит вместе с ней. Появится место,
 * которому нужны все, — это будет второй ключ с параметром, а не расширение этого.
 */
export const departmentKeys = createQueryKeys('departments', {
  list: (params: Query) => ['list', params],
  options: () => ['options'],
});
