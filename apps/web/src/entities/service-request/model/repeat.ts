import type { ServiceRequestRepeatDto } from '@technic/contracts';

/**
 * Как признак повторного обращения называет себя словами (план
 * `docs/office-equipment-repeat-request-plan.md`, Р10).
 *
 * ОБЩИЙ МОДУЛЬ, ПОТОМУ ЧТО ПРИЗНАК ПОКАЗЫВАЮТ ТРИ МЕСТА: тег у номера в списке, тот же тег в
 * бейджах карточки на телефоне и строка карточки заявки. Разойдись их подписи — одно и то же
 * число прочиталось бы как два разных факта, и первым делом разъехалось бы окно: «за 30 дней» в
 * подсказке против «недавно» в карточке.
 *
 * ПЕРИОД НАЗЫВАЕТСЯ ВСЕГДА, и это не оформление (§12 плана). Метка отвечает не на «то же ли
 * сломалось», а на «по этому аппарату уже была закрытая заявка за столько-то дней»; окно приходит
 * в самом признаке (`windowDays`) ровно затем, чтобы человеку было чем метку оспорить. Слово
 * «недавно» на его месте делает признак неопровержимым, а значит бесполезным.
 */

/**
 * Числительное с существительным по-русски: 1 заявка, 2–4 заявки, 5–20 заявок; 11–14 — всегда
 * последняя форма.
 *
 * Своей копией, а не общим помощником: такие же четыре строки стоят в `statusAgeLabel` рядом и в
 * `calendarDaysLabel` у заявок на технику. Свести их в одну утилиту — отдельная работа на весь
 * портал, и делать её попутно, из подписи одного тега, значило бы трогать чужие экраны.
 */
function plural(n: number, one: string, few: string, many: string): string {
  const tail = n % 100;
  if (tail >= 11 && tail <= 14) return `${n} ${many}`;
  const last = n % 10;
  if (last === 1) return `${n} ${one}`;
  if (last >= 2 && last <= 4) return `${n} ${few}`;
  return `${n} ${many}`;
}

/** Окно словами: «30 дней», «1 день». */
function daysLabel(days: number): string {
  return plural(days, 'день', 'дня', 'дней');
}

/**
 * Подсказка тега — «2 закрытые заявки по аппарату за 30 дней».
 *
 * Говорит ровно то, что посчитано (§12 плана): закрытые заявки ПО АППАРАТУ, а не «повторная
 * поломка». Совпадение считается по одной единице и одному виду работ, о том же ли отказе идёт
 * речь, признак не знает вовсе — и обещать этого подсказка не вправе.
 */
export function serviceRepeatHint(repeat: ServiceRequestRepeatDto): string {
  const requests = plural(repeat.count, 'закрытая заявка', 'закрытые заявки', 'закрытых заявок');
  return `${requests} по аппарату за ${daysLabel(repeat.windowDays)}`;
}

/** То же число для строки карточки, где слово «закрытые» уже сказано подписью: «2 заявки за 30 дней». */
export function serviceRepeatSummary(repeat: ServiceRequestRepeatDto): string {
  const requests = plural(repeat.count, 'заявка', 'заявки', 'заявок');
  return `${requests} за ${daysLabel(repeat.windowDays)}`;
}
