import {
  closingKindsForFormat,
  hasServiceClosingDocument,
  type ServiceEstimateFormat,
  type ServiceFileKind,
  serviceFileKindLabels,
  type ServiceRequestDto,
  serviceRequestNeedsClosingDocument,
} from '@technic/contracts';

/**
 * Документы заявки: чем работа подтверждена и чего не хватает (Р16).
 *
 * Вид документа заведён ровно ради этого вопроса: «закрыто, но бумаг нет» — рабочее состояние
 * (акт присылают через неделю), а не ошибка, и портал обязан уметь его показать и отобрать
 * очередью «Ожидаются документы». Планка при этом одна (Р112): хватает любого закрывающего
 * документа, и перечня недостающих видов у портала больше нет.
 */

/** Сколько документов каждого вида подшито к заявке. */
export function serviceDocumentCounts(
  files: readonly { kind: ServiceFileKind }[],
): Partial<Record<ServiceFileKind, number>> {
  const counts: Partial<Record<ServiceFileKind, number>> = {};
  for (const file of files) counts[file.kind] = (counts[file.kind] ?? 0) + 1;
  return counts;
}

/**
 * Планка словами — и ПЕРЕЧЕНЬ В НЕЙ БЕРЁТСЯ У КОНТРАКТА, а не набран в строке (Р112, Р114, Р5 плана
 * `docs/office-equipment-on-site-and-invoice-estimate-plan.md`).
 *
 * ПОЧЕМУ БОЛЬШЕ НЕ КОНСТАНТА. Прежний текст перечислял три вида всегда, и у документной заявки он
 * лгал: счёт у неё — это объём работ, которым её ОТКРЫЛИ, а закрывает её один акт (ответ В10
 * заказчика от 11.09.2026). Человек читал «нужен один из документов: акт, счёт или гарантийный
 * талон», подшивал счёт — и заявка оставалась в очереди «Ожидаются документы» без единого
 * объяснения на экране. Подсказка обязана называть причину и выход, а перечислять то, что не
 * поможет, — это ни то ни другое.
 *
 * ПЕРЕЧЕНЬ СЧИТАЕТ `closingKindsForFormat` — та самая функция, которой планку спрашивают предикат
 * очереди и сервер: своя копия перечня в тексте разошлась бы с правилом молча, и разошлась бы
 * именно так, как уже разошлась однажды.
 *
 * Формат — обязательный аргумент по той же причине, по какой он обязателен у предикатов контрактов:
 * забытый, он означал бы «счёт закрывает» — самую дорогую из двух ошибок. Зовущий пишет `?? null` и
 * этим говорит вслух, что спрашивает планку наследия.
 */
export function serviceClosingDocumentHint(format: ServiceEstimateFormat | null): string {
  const kinds = closingKindsForFormat(format);
  if (kinds.length === 1) {
    // Единственный вид — это документная подача (Р5), и текст называет ровно её причину: счётом
    // такую заявку не закрыть, потому что счётом она подана.
    return `Нужен ${lower(kinds[0]!)}: объём работ подан счётом, и закрывает заявку акт о выполненных работах`;
  }
  // Перечисление видов по отдельности («не хватает акта, счёта») читалось бы как «нужны все три»,
  // хотя очередь держит отсутствие сразу всех, — поэтому «один из документов».
  return `Нужен один из документов: ${listOf(kinds)}`;
}

/** Подпись вида со строчной буквы: в перечне она стоит внутри фразы, а не заголовком строки. */
function lower(kind: ServiceFileKind): string {
  const label = serviceFileKindLabels[kind];
  return label.charAt(0).toLowerCase() + label.slice(1);
}

/** «акт, счёт или гарантийный талон» — последний вид отделён союзом: перечень читает человек. */
function listOf(kinds: readonly ServiceFileKind[]): string {
  const labels = kinds.map(lower);
  const last = labels[labels.length - 1]!;
  return labels.length === 1 ? last : `${labels.slice(0, -1).join(', ')} или ${last}`;
}

/**
 * Ждёт ли заявка бумаг: работы предъявлены или приняты, документ ей **обязателен**, а ни одного
 * закрывающего нет.
 *
 * Спрашивается только у заявки с предъявленным фактом: до закрытия работ акта и счёта не бывает по
 * определению, и «не хватает акта» у заявки в работе читалось бы как претензия к исполнителю.
 *
 * Обе половины правила живут в контрактах и спрашиваются одними и теми же функциями, что и на
 * сервере: `serviceRequestNeedsClosingDocument` — кому бумага положена (Н8: внешний ремонт, и
 * только он), `hasServiceClosingDocument` — хватает ли любой одной (Р112). Своей копии условия
 * портал не заводит: собственное «нужен акт» у инхаус-ремонта и у заявки на расходники было бы
 * требованием, которого сервер не предъявляет, — красный тег висел бы вечно у того, кому и
 * подшивать нечего.
 *
 * После Н8 очередь означает не «нельзя принять», а «нельзя закрыть»: планка переехала с приёмки на
 * переход в «Решена», и в этом состоянии остаются заявки-наследие, уехавшие туда до выпуска 1.
 * Их же не берёт и автозакрытие — отбор пачки повторяет этот самый предикат на SQL.
 *
 * ЗАЯВИТЕЛЮ ВОПРОС НЕ ЗАДАЁТСЯ ВОВСЕ (ADR 0160, Р12), и это не сокрытие очереди, а защита от
 * ЛЖИВОГО ответа: `files` у аудитории `requester` приходят урезанными по видам (акта и счёта в них
 * нет ни при каких обстоятельствах), и посчитанный по такому списку предикат сказал бы «ни одной
 * закрывающей бумаги» у заявки, где акт подшит неделю назад. Очередь эта вдобавок рабочая — ею
 * разбирают долги перед подрядчиком, а не отвечают заказчику «что с моим принтером».
 *
 * Аудитория читается ИЗ DTO, а не считается по правам: сервер уже ответил на этот вопрос для
 * каждой строки, и второй ответ в браузере разошёлся бы с первым (ADR 0160, решение 4).
 *
 * ФОРМАТ РЕВИЗИИ ВХОДИТ В ПРОЧИТАННЫЕ ПОЛЯ, и сервер его отдаёт (Э3): планка
 * закрывающего документа читает два признака — вид файла и формат (Р5), — и очередь обязана
 * спрашивать её теми же полями, какими её спрашивают два соседних места по тому же DTO (меню
 * «Закрыть работы» и окно приёмки: они передают формат карточки). Не окажись поля в перечне,
 * передавать было бы нечего — предикат получал бы `null` навсегда, — и один портал дал бы по одной
 * заявке два ответа: тега «ожидает документы» нет, а кнопка «Закрыть работы» заперта. Сегодня
 * значение пусто и ответ прежний — расхождение появилось бы МОЛЧА, в день, когда сервер начнёт
 * отдавать формат.
 */
export function isAwaitingDocuments(
  request: Pick<
    ServiceRequestDto,
    'status' | 'files' | 'kind' | 'service' | 'audience' | 'estimateFormat'
  >,
): boolean {
  if (request.audience === 'requester') return false;
  if (request.status !== 'done' && request.status !== 'accepted') return false;
  if (
    !serviceRequestNeedsClosingDocument({
      kind: request.kind,
      // Контрагент в карточке лежит объектом, а предикату нужна ссылка: пара «вид + исполнитель»
      // одна на сервер и портал, и разбирается она на той стороне, где есть карточка.
      serviceCounterpartyId: request.service?.id ?? null,
    })
  ) {
    return false;
  }
  // `?? null` — не вежливость к типу, а ответ словами: формат приходит полем карточки, но у ответа
  // СТАРОГО приложения его нет (окно выката — портал обновляется раньше сервера), и тогда очередь
  // сознательно спрашивает планку наследия, а не «формат неизвестен, решай сама».
  return !hasServiceClosingDocument(request, request.estimateFormat ?? null);
}
