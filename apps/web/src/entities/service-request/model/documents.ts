import {
  hasServiceClosingDocument,
  type ServiceFileKind,
  type ServiceRequestDto,
} from '@technic/contracts';

/**
 * Документы заявки: чем работа подтверждена и чего не хватает (Р16).
 *
 * Вид документа заведён ровно ради этого вопроса: «закрыто, но бумаг нет» — рабочее состояние
 * (акт присылают через неделю), а не ошибка, и портал обязан уметь его показать и отобрать
 * очередью «Ожидаются документы». Планка при этом одна (Р112): хватает любого закрывающего
 * документа, и перечня недостающих видов у портала больше нет.
 */

/** Сколько документов каждого вида подшито к заявке. */
export function serviceDocumentCounts(
  files: readonly { kind: ServiceFileKind }[],
): Partial<Record<ServiceFileKind, number>> {
  const counts: Partial<Record<ServiceFileKind, number>> = {};
  for (const file of files) counts[file.kind] = (counts[file.kind] ?? 0) + 1;
  return counts;
}

/**
 * Планка одна на всё: «нужен один из документов» (Р112, Р114).
 *
 * Формулировка вынесена в константу, потому что показывают её три места — окно приёмки, вкладка
 * документов и очередь списка, — а отвечает на неё сервер тем же текстом. Перечислять виды по
 * отдельности («не хватает акта, счёта») нельзя: после Р112 это читалось бы как «нужны все три»,
 * хотя приёмку запирает отсутствие сразу всех.
 */
export const SERVICE_CLOSING_DOCUMENT_HINT =
  'Нужен один из документов: акт, счёт или гарантийный талон';

/**
 * Ждёт ли заявка бумаг: работы предъявлены или приняты, а закрывающих документов нет ни одного.
 *
 * Спрашивается только у заявки с предъявленным фактом: до закрытия работ акта и счёта не бывает по
 * определению, и «не хватает акта» у заявки в диагностике читалось бы как претензия к исполнителю.
 *
 * Сама планка живёт в контрактах (`hasServiceClosingDocument`): по ней сервер отказывает в приёмке,
 * и второй счёт на портале разошёлся бы с ним — кнопка вела бы в 422 либо блокировала разрешённое.
 * Это же условие и есть очередь «Ожидаются документы» — ровно список того, что нельзя принять.
 */
export function isAwaitingDocuments(request: Pick<ServiceRequestDto, 'status' | 'files'>): boolean {
  if (request.status !== 'done' && request.status !== 'accepted') return false;
  return !hasServiceClosingDocument(request);
}
