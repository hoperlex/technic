import type { ReactNode } from 'react';
import { Alert, Typography } from 'antd';

/**
 * Подсказка карточки и окон заявки в двух подачах (план
 * `docs/office-equipment-card-and-list-cleanup-plan.md`, Р11; просьба заказчика 08.09.2026, п. 3).
 *
 * ЧТО РЕШАЕТСЯ. Пояснительных плашек в модуле одиннадцать (§2.3 плана), и написаны они для того,
 * кто ведёт заявки: он разбирает чужую очередь, ему и нужен разбор правил на экране. Заявителю,
 * внутреннему исполнителю и оператору сервисной компании тот же текст читается как шум — они
 * работают с одной своей заявкой и правила её цикла знают. Поэтому подача разная, а текст один:
 * координатору — нынешняя плашка без изменения слов и уровня; остальным `info` и `success` не
 * рисуются вовсе, а `warning` сворачивается в мелкую серую строку с одним заголовком.
 *
 * ПОЧЕМУ СВОРАЧИВАЕТСЯ, А НЕ ИСЧЕЗАЕТ. `warning` в модуле означает причину блокировки — «правка
 * закрыта предъявлением», «нет закрывающего документа», — то есть ответ на вопрос «почему кнопка
 * не работает». Спрячь мы её, человек упёрся бы в погашенную кнопку без единого объяснения на
 * экране, и первым его действием стал бы звонок в ИТ-службу — ровно тот, ради отмены которого
 * модуль и заводился.
 *
 * ПОЧЕМУ КОМПОНЕНТ ЖИВЁТ В `entities`, А НЕ В `features`. Первым наброском был слайс
 * `features/service-hints` (находка Н14) — и он невозможен: подсказки стоят в `service-accept`,
 * `service-consumables-issue`, `estimate-editor` и на страницах карточки, а границы проекта
 * запрещают `feature → feature`. Слой сущностей ниже всех вызывающих и виден им всем.
 *
 * ПОЧЕМУ КОМПОНЕНТ НЕ СПРАШИВАЕТ ПРАВА САМ. Две причины, и каждой хватило бы одной. Первая
 * архитектурная: `entities` не имеет права импортировать `AuthContext` — нижний слой не знает, кто
 * смотрит на экран, и линт границ такой импорт не пропустит. Вторая содержательная: «кому положены
 * пояснения» — правило доступа, и живёт оно в контрактах единственной функцией
 * `canCoordinateServiceRequests`; посчитай его этот компонент по своей формуле — правило разъехалось
 * бы с сервером и с соседними экранами молча. Поэтому вызывающий берёт `user` у `useAuth`, зовёт
 * предикат контрактов и передаёт сюда готовое булево.
 *
 * ОШИБКИ ЧЕРЕЗ КОМПОНЕНТ НЕ ХОДЯТ, и это записано в типе: уровня `error` у него нет. Отказ сервера
 * и ошибку валидации читают все — свернув их в серую строку, мы спрятали бы от человека
 * единственное объяснение, почему его действие не состоялось.
 */
export function ServiceHint({
  /** Держатель `serviceRequests.assign` — считает вызывающий (`canCoordinateServiceRequests`). */
  coordinator,
  level,
  title,
  description,
}: {
  coordinator: boolean;
  /** Уровень нынешней плашки: тот же, что стоял бы у `Alert`. `error` сюда не передаётся. */
  level: 'info' | 'success' | 'warning';
  title: ReactNode;
  description?: ReactNode;
}) {
  if (coordinator) return <Alert type={level} showIcon title={title} description={description} />;
  // Пояснение и поздравление некоординатору не показываются вовсе: они рассказывают о правилах
  // цикла, а не о его заявке.
  if (level !== 'warning') return null;
  /*
   * Заголовок без описания: причину блокировки называет именно он, а описание разворачивает
   * правило — то самое, ради снятия которого волна и затевалась. Мелкой серой строкой, а не
   * плашкой: строка стоит в потоке и не отодвигает то, за чем окно открывали.
   */
  return <Typography.Text type="secondary">{title}</Typography.Text>;
}
