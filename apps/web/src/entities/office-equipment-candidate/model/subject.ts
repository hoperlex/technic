import {
  officeEquipmentCandidateStatusLabels,
  type ServiceRequestCandidateDto,
  type ServiceRequestDto,
} from '@technic/contracts';

/**
 * Предмет заявки, которого ещё нет в справочнике: состояние сообщения о технике (план
 * `docs/office-equipment-candidate-plan.md`, Р5, Р16, §9).
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ ЧТЕНИЕ ПОЛЯ ПО МЕСТУ. Один и тот же ответ нужен четырём местам:
 * плашке в блоке предмета карточки, замку приёмки в меню (Р16), строке очереди и подписи заявителю.
 * Разложенное по ним порознь, оно разъехалось бы на первом же исходе — «на проверке» в меню и
 * прочерк в карточке прочитались бы как два разных состояния.
 *
 * ЧИТАЕТСЯ НАСТОЯЩЕЕ ПОЛЕ DTO. До появления поля здесь стоял структурный `cast` — временный мост
 * на время, пока `packages/contracts/src/service-requests.ts` был занят соседней волной; мост
 * снят вместе с волной, и блок приезжает от сервера как `request.equipmentCandidate`, пройдя
 * проекцию аудитории (§9, Р9: заявителю он виден целиком — реквизиты и причина отказа не деньги).
 *
 * `?? null` ОСТАЁТСЯ, и это не остаток моста. Поле объявлено необязательным намеренно: этот бандл
 * умеет читать блок раньше, чем сервер научился его отдавать, и в окне выката ответ приходит без
 * поля. Здесь оба вида пустоты дают один ответ — показывать нечего, — и различать «кандидата нет»
 * и «сервер ещё старый» четырём местам показа незачем.
 */

/**
 * Что портал показывает про непроверенный предмет — ПСЕВДОНИМ контрактного типа, а не второе его
 * описание. Состав полей выбран на сервере (`ServiceRequestCandidateDto`): карточке заявки не
 * нужны ни версия, ни автор, ни площадка — их читают в очереди проверки, у которой своя область
 * (Р9). Здесь только то, что видно и заявителю.
 *
 * Имя оставлено своё: четыре места показа зовут это «состоянием предмета», а не «кандидатом», и
 * переименование ради совпадения с сервером стоило бы правок в них всех, ничего не объяснив.
 * Псевдоним при этом не даёт разойтись составу — новое поле контракта приезжает сюда само.
 */
export type ServiceRequestSubjectCheck = ServiceRequestCandidateDto;

/**
 * Сообщение о технике, связанное с заявкой; `null` — предмет у заявки обычный (карточка парка либо
 * заявка без аппарата вовсе, Р5).
 */
export function serviceRequestSubjectCheck(
  request: ServiceRequestDto,
): ServiceRequestSubjectCheck | null {
  return request.equipmentCandidate ?? null;
}

/**
 * Проверка ещё идёт — и это единственное состояние, которое что-либо запрещает (Р16).
 *
 * У `rejected` замка нет намеренно: проверка закончена, и заявка, по которой работу уже выполнили,
 * не должна застревать в «Решена» из-за справочника — оператор выбирает обычный допустимый ход.
 */
export function isSubjectCheckPending(request: ServiceRequestDto): boolean {
  return serviceRequestSubjectCheck(request)?.status === 'pending';
}

/**
 * Подпись предмета одной строкой: «Kyocera M3145 · SN 4711». Номер печатается тот, что назвали, —
 * обязателен хотя бы один (Р7), и оба сразу человек указывает редко.
 */
export function subjectCheckTitle(check: {
  declaredModel: string;
  serialNumber: string;
  inventoryNumber: string;
}): string {
  const num = check.inventoryNumber
    ? `инв. ${check.inventoryNumber}`
    : check.serialNumber
      ? `SN ${check.serialNumber}`
      : '';
  return num ? `${check.declaredModel} · ${num}` : check.declaredModel;
}

/**
 * Состояние предмета словами — теми же, что говорят очередь, письмо и карточка заявки.
 *
 * Причина отказа печатается ДОСЛОВНО и прямо здесь (Р15, В5): общая формулировка «подробности в
 * портале» экономила бы проверяющему слова ценой второго действия человека — он всё равно пойдёт
 * смотреть причину, а не поняв её, позвонит в ИТ-службу, то есть сделает ровно тот звонок, ради
 * отмены которого модуль и заводился.
 */
export function subjectCheckNotice(check: ServiceRequestSubjectCheck): string {
  const label = officeEquipmentCandidateStatusLabels[check.status];
  return check.status === 'rejected' && check.decisionReason
    ? `Предмет отклонён: ${check.decisionReason}`
    : `${label}: ${subjectCheckTitle(check)}`;
}
