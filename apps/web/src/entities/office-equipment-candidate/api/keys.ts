import { createQueryKeys, type Query } from '@shared/api';

/**
 * Ключи сообщений о технике, которой нет в справочнике (план
 * `docs/office-equipment-candidate-plan.md`, Р3, §9).
 *
 * СВОЙ КОРЕНЬ, А НЕ СЕМЕЙСТВО ВНУТРИ `office-equipment`, и это прямое следствие модели (Р1):
 * кандидат — не запись парка, а свидетельство о нём. Пока проверка не кончилась, карточки не
 * существует вовсе, и общий корень означал бы, что каждое сообщение из коридора гасит открытый
 * справочник, а правка кабинета — перечитывает чужую очередь проверки.
 *
 * Обратное при этом верно и обязательно (§9, инвалидация): РЕШЕНИЕ по кандидату гасит и парк, и
 * модели, и расходники — «Завести карточку» рождает единицу справочника ровно так же, как быстрое
 * создание из формы заявки. Гасит тот, кто пишет; здесь только ключи.
 *
 * Семейства два. Очередь проверки: отбор по состоянию, страница и порядок приходят в параметрах —
 * поиска у неё нет вовсе (перечень контрактов, `OFFICE_EQUIPMENT_CANDIDATE_SORT_FIELDS`). И
 * карточка по идентификатору — окно проверки открывают строкой очереди, но перечитывает оно
 * кандидата само: между открытием списка и решением коллега мог поправить реквизиты (Р12), и
 * форма, собранная из строки списка, отправила бы устаревшую версию.
 */
export const officeEquipmentCandidateKeys = createQueryKeys('office-equipment-candidates', {
  list: (params: Query) => ['list', params],
  detail: (id: string) => ['detail', id],
});
