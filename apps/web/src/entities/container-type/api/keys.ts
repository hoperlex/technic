import { createQueryKeys, type Query } from '@shared/api';

/**
 * Ключи запросов типов контейнеров.
 *
 * Ключ описывает **запрос**, а не сущность. Справочник спрашивают в трёх видах: страницей с
 * фильтрами (своя вкладка) и целиком — для выпадающих списков, причём целиком тоже по-разному:
 *  - `activeOnly: true` — то, из чего выбирают в заявке на вывоз и чем фильтруют её список:
 *    выведенный из обращения тип в новой заявке предлагать нельзя;
 *  - `activeOnly: false` — прайс: позиция могла быть заведена до деактивации типа, и при её
 *    правке выбор обязан показать сохранённое значение, а не пустоту.
 *
 * До переезда оба списка ходили под одним ключом `['container-types', 'for-select']`: кто открывал
 * свой экран вторым, тот и получал чужой ответ — в прайсе пропадали неактивные типы либо в заявке
 * появлялись. Разными ключами эта пара не пересекается вовсе.
 */
export const containerTypeKeys = createQueryKeys('container-types', {
  list: (params: Query) => ['list', params],
  options: (params: { activeOnly: boolean }) => ['options', params],
});
