import { createQueryKeys, type Query } from '@shared/api';

/**
 * Ключи запросов склада автозапчастей (план `docs/auto-parts-plan.md`, Р14, Р16).
 *
 * Корень свой, а не семейство внутри гаража: у склада своя ручка, своё право на правку и своя
 * жизнь. День среза гаража его не касается вовсе — остаток не про день (Р14), — и общий корень
 * означал бы, что шаг по календарю перезапрашивает справочник, а заведение позиции гасит срез
 * дня вместе с занятостью машин.
 *
 * Семейства два, и разводить их обязательно. Список вкладки: поиск, наличие, применимость,
 * активность, порядок и страница приходят в параметрах. И карточка по идентификатору — она
 * единственная приносит ленту журнала остатка (`stockEntries` в `AutoPartDetailDto`): в списке
 * этой ленты нет, и держать её под ключом списка значило бы тащить историю движений на каждую
 * строку справочника.
 *
 * Гасится всё это разом: правка позиции меняет и строку списка, и карточку, а движение остатка —
 * ещё и ленту, которая приходит вместе с карточкой. Поэтому после мутации достаточно погасить
 * `autoPartKeys.root` — префиксное сравнение TanStack Query накроет оба семейства.
 *
 * Обратная сторона матрицы Р16 здесь не живёт и жить не может: строки акта обслуживания двигают
 * склад, поэтому гасить `autoPartKeys.root` обязан тот, кто пишет акт (`features/vehicle-maintenance`),
 * — ключи об этом не знают, и знать им нечем.
 */
export const autoPartKeys = createQueryKeys('auto-parts', {
  list: (params: Query) => ['list', params],
  detail: (id: string) => ['detail', id],
});

/**
 * Справочники применимости — модели и типы техники, которыми размечают позицию (Р8).
 *
 * Отдельный корень, а не семейство `autoPartKeys`, по двум причинам сразу. Данные чужие: правка
 * автозапчасти перечень моделей не меняет, и гашение корня склада уносило бы в мусор два списка,
 * которые от него не зависят вовсе. И спрашивают их двое — полоса отбора вкладки и форма позиции,
 * — а один и тот же вопрос («все действующие модели») обязан иметь один ключ, иначе два экрана
 * держали бы два ответа на него.
 *
 * Почему ключи вообще здесь, а не рядом с запросом. Клиента у моделей и типов техники своего
 * слайса пока нет — они живут в неразобранном `api/resources`, куда слою сущностей ходить
 * запрещено (границы FSD), поэтому сами запросы собираются на уровне страницы. А ключ,
 * записанный там строкой, был бы сырым ключом — тем самым, который бюджет качества считает и не
 * даёт заводить заново. Переедут модели и типы в свой слайс — эти два ключа уедут вместе с ними.
 */
export const autoPartRefKeys = createQueryKeys('auto-part-refs', {
  /** Все действующие типы техники: ими размечают «всем самосвалам» (Р8). */
  vehicleTypes: () => ['vehicle-types'],
  /** Все действующие модели, всех типов сразу: деталь подходит машинам разных типов. */
  vehicleModels: () => ['vehicle-models'],
});
