import type { AuditEntryDto, ListResult } from '@technic/contracts';
import { apiFetch, type Query } from '@shared/api';

/**
 * Журнал действий с учётными записями (ADR 0088) — подвкладка «Аудит» во вкладке «Пользователи».
 *
 * Одна ручка и без карточки: строка журнала и есть карточка события, а всё, чем её сужают, —
 * фильтры списка. Набор действий уходит одним параметром через запятую (`actions`): реестр
 * закрытый и лежит в контрактах, поэтому портал не собирает его сам, а перечисляет отмеченное.
 *
 * Своим слайсом, а не полкой у `@entities/user-account`, хотя журнал ведётся о тех же учётках:
 * общего у них ровно один идентификатор, а событие приходит из контрактов целиком — тела запроса
 * учётки журналу не нужны ни одним полем. Соседями слайсы друг другу недоступны, и это здесь
 * сторож, а не помеха: экран, которому нужна лента, иначе тянул бы за собой всю форму учётки.
 * Панель пути читает и то и другое, но она страница — оба слайса она берёт сама (ADR 0109).
 */
export const auditApi = {
  list: (q: Query) => apiFetch<ListResult<AuditEntryDto>>('/audit', { query: q }),
};
