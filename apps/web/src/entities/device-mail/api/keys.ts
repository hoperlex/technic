import { createQueryKeys } from '@shared/api';

/**
 * Ключи очереди «Письма устройств» (план `docs/office-equipment-mail-telemetry-plan.md`, §10).
 *
 * СВОЙ КОРЕНЬ, А НЕ СЕМЕЙСТВО ВНУТРИ `device-telemetry`. Слайс телеметрии отвечает на вопрос «что
 * аппарат о себе рассказал», и его данные уже принадлежат карточке. Здесь предмет обратный —
 * письма, которые НИЧЕЙНЫ: аппарат не опознан, разбор не удался, курсор ящика стоит. Общий корень
 * означал бы, что привязка одного письма гасит блоки показаний всех открытых карточек, а открытие
 * карточки перечитывает служебную очередь, которой её читатель может и не видеть вовсе.
 *
 * Обратное при этом верно и обязательно: ПРИВЯЗКА ГАСИТ И ТЕЛЕМЕТРИЮ — снимок письма ложится
 * наблюдениями и событиями в карточку, и блок, оставшийся с прежним ответом, показывал бы «аппарат
 * ещё не присылал писем» ровно после того, как его письма разобрали. Гасит тот, кто пишет; здесь
 * только ключи.
 *
 * Размер страницы — часть ключа: очередь листается курсором, и две обрезки под общим ключом дали
 * бы страницу того, кто спросил первым.
 */
export const deviceMailKeys = createQueryKeys('device-mail', {
  queue: (pageSize: number) => ['queue', pageSize],
  /**
   * «Сколько писем затронет привязка» — своим семейством, а не частью очереди: ответ зависит от
   * ключа и значения, которые человек набирает прямо сейчас, и живёт ровно до подтверждения.
   */
  bindTargets: (messageId: string, kind: string, value: string) => [
    'bind-targets',
    messageId,
    kind,
    value,
  ],
  /**
   * Реестр ключей — своим семейством ПОД ТЕМ ЖЕ КОРНЕМ, что и очередь. Корень общий потому, что
   * работа одна: заведённый ключ решает письма очереди, а разобранное письмо пополняет реестр.
   * Разведи их по корням — и привязка из очереди оставила бы реестр со вчерашним ответом.
   */
  identities: (params: Record<string, unknown>) => ['identities', params],
  /** Сколько писем подберёт ключ, которого ещё нет: живёт ровно до подтверждения. */
  identityTargets: (kind: string, value: string) => ['identity-targets', kind, value],
  /** Правила разбора: один набор, без курсора и без параметров. */
  rules: () => ['rules'],
});
