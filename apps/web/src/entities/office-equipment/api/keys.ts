import { createQueryKeys, type Query } from '@shared/api';

/**
 * Ключи запросов оргтехники (ADR 0085).
 *
 * Видов запроса два, и разводить их обязательно. Страница вкладки: объект, отдел, тип, гарантия и
 * поиск приходят в параметрах. И весь список единиц — для выбора техники в заявке на обслуживание
 * (§9.3 плана: `AutoSelect` с поиском по модели и номерам). Под общим ключом форма получила бы
 * отфильтрованную страницу таблицы, а таблица — весь справочник мимо своих фильтров: кто спросил
 * вторым, тот и определил бы ответ обоим.
 */
export const officeEquipmentKeys = createQueryKeys('office-equipment', {
  list: (params: Query) => ['list', params],
  options: () => ['options'],
  /**
   * Карточка по идентификатору: только она приносит историю обслуживания и гарантии ремонтов
   * (§8.2) — в списке этого среза нет, и держать её под ключом списка значило бы либо потерять
   * секцию, либо тащить подзапрос на каждую строку справочника.
   */
  detail: (id: string) => ['detail', id],
});

/**
 * Ключи перечня типов оргтехники.
 *
 * Свой корень, а не семейство внутри `office-equipment`: у типов своя ручка и своя жизнь — их
 * ведут в окне из вкладки (Р34), а список единиц при этом не устаревает. Общий корень означал бы,
 * что правка названия типа гасит и страницу справочника, и наоборот — каждая заведённая единица
 * перезапрашивала бы перечень.
 *
 * Семейства те же два: список окна (с неактивными — их там и включают обратно) и перечень для
 * выпадающих списков вкладки.
 */
export const officeEquipmentTypeKeys = createQueryKeys('office-equipment-types', {
  list: (params: Query) => ['list', params],
  options: () => ['options'],
});
