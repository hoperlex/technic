import { createQueryKeys, type Query } from '@shared/api';

/**
 * Ключи запросов оргтехники (ADR 0085).
 *
 * Видов запроса два, и разводить их обязательно. Страница вкладки: объект, отдел, тип, гарантия и
 * поиск приходят в параметрах. И весь список единиц — для выбора техники в заявке на обслуживание
 * (§9.3 плана: `AutoSelect` с поиском по модели и номерам). Под общим ключом форма получила бы
 * отфильтрованную страницу таблицы, а таблица — весь справочник мимо своих фильтров: кто спросил
 * вторым, тот и определил бы ответ обоим.
 */
export const officeEquipmentKeys = createQueryKeys('office-equipment', {
  list: (params: Query) => ['list', params],
  options: () => ['options'],
  /**
   * Карточка по идентификатору: только она приносит историю обслуживания и гарантии ремонтов
   * (§8.2) — в списке этого среза нет, и держать её под ключом списка значило бы либо потерять
   * секцию, либо тащить подзапрос на каждую строку справочника.
   */
  detail: (id: string) => ['detail', id],
  /**
   * Лента карточки (Р62): перемещения и обслуживание. Своё семейство, а не часть карточки — она
   * приходит отдельной ручкой и устаревает в другие моменты: заявка сменила статус, единицу
   * перевезли.
   */
  history: (id: string) => ['history', id],
});

/**
 * Ключи перечня типов оргтехники.
 *
 * Свой корень, а не семейство внутри `office-equipment`: у типов своя ручка и своя жизнь — их
 * ведут в окне из вкладки (Р34), а список единиц при этом не устаревает. Общий корень означал бы,
 * что правка названия типа гасит и страницу справочника, и наоборот — каждая заведённая единица
 * перезапрашивала бы перечень.
 *
 * Семейства те же два: список окна (с неактивными — их там и включают обратно) и перечень для
 * выпадающих списков вкладки.
 */
export const officeEquipmentTypeKeys = createQueryKeys('office-equipment-types', {
  list: (params: Query) => ['list', params],
  options: () => ['options'],
});

/**
 * Ключи справочника моделей аппаратов (план `docs/office-equipment-consumables-plan.md`, Р14).
 *
 * Свой корень, а не семейство внутри `office-equipment`: у моделей своя ручка, своё окно и своя
 * жизнь — их ведут отдельно от парка. Общий корень означал бы, что каждая заведённая карточка
 * техники перезапрашивает весь перечень моделей, а правка модели — гасит страницу справочника
 * заодно с ним.
 *
 * Обратное при этом верно и обязательно (матрица Р14): правка, заведение и гашение модели гасят и
 * `office-equipment` — имя карточки с выпуска A зеркалит модель, и переименование обязано доехать
 * до строк справочника. Это делает тот, кто пишет, — здесь только ключи.
 *
 * Семейства два. Список окна: тип, активность, поиск и страница приходят в параметрах — и
 * неактивные модели там нужны не меньше активных, их в окне и включают обратно. И перечень для
 * выпадающего списка формы карточки техники — **по типу**: одноимённые принтер и МФУ это разные
 * модели (Р1), и общий ключ на все типы подсунул бы форме перечень чужого аппарата.
 */
export const officeEquipmentModelKeys = createQueryKeys('office-equipment-models', {
  list: (params: Query) => ['list', params],
  options: (equipmentTypeId: string | undefined) => ['options', equipmentTypeId ?? null],
});

/**
 * Ключи справочника расходников — картриджей и тонеров (план
 * `docs/office-equipment-consumables-plan.md`, Р14).
 *
 * Свой корень, а не семейство внутри `office-equipment`: у расходников своя ручка, своё окно и
 * своя жизнь — их ведут отдельно от парка, и заведённая карточка техники перечень картриджей не
 * меняет.
 *
 * Обратное неверно и потому прописано матрицей Р14: правка расходника, его остатка и привязки к
 * моделям гасят и `office-equipment` — карточка единицы отвечает «чем заправлять» и показывает
 * остаток (Р15), то есть держит чужие данные у себя в ответе. Гасит тот, кто пишет; здесь только
 * ключи.
 *
 * Семейства три. Список окна: поиск, модель, наличие, активность, порядок и страница приходят в
 * параметрах. Карточка по идентификатору — остаток и счётчик парка, перечитанные после правки
 * события (в строке списка они могли устареть, пока окно было открыто). И лента журнала остатка
 * своим семейством.
 */
export const officeEquipmentConsumableKeys = createQueryKeys('office-equipment-consumables', {
  list: (params: Query) => ['list', params],
  detail: (id: string) => ['detail', id],
  /**
   * Журнал остатка позиции страницами (план `docs/office-equipment-consumables-and-purchase-plan.md`,
   * Р4). Своё семейство, а не часть карточки, и это прямое следствие того, что лента уехала из
   * `GET /:id` в свою ручку: под ключом карточки страница и отбор по виду события стали бы частью
   * ключа записи — то есть каждое перелистывание журнала объявляло бы устаревшей саму позицию.
   *
   * Идентификатор стоит ПЕРЕД параметрами: журнал всегда про одну позицию (общего нет вовсе), и
   * такой порядок сегментов позволяет погасить ленту ровно одной карточки, не трогая соседние.
   */
  stockEntries: (id: string, params: Query) => ['stock-entries', id, params],
  /**
   * Отчёт по расходу за период (Р10): своё семейство с периодом в параметрах. Под ключом списка
   * он жил бы вместе с перечнем позиций — и правка остатка одной карточки перезапрашивала бы
   * отчёт за прошлый квартал, который от неё не меняется.
   */
  usage: (params: Query) => ['usage', params],
});
