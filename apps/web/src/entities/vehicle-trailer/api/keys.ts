import { createQueryKeys, type Query } from '@shared/api';

/**
 * Ключи запросов прицепного реестра.
 *
 * Семейства два, и разведены они не по красоте: список вкладки меняется от каждого отбора, а срез
 * состава машины («кто сейчас стоит в её слотах») спрашивается в окне привязки под выбранную
 * машину. Общий ключ гасил бы одно другим, а корень `trailerKeys.root` по-прежнему накрывает оба —
 * им и гасят реестр после заведения, правки, архивации и обеих команд привязки.
 */
export const trailerKeys = createQueryKeys('vehicle-trailers', {
  list: (params: Query) => ['list', params],
  /** Состав выбранной машины: `undefined` приходит, пока машину не выбрали, — запрос выключен. */
  slots: (vehicleId: string | undefined) => ['slots', vehicleId],
});

/**
 * Машины, за которые прицеп можно поставить, — под корнем **техники**, а не прицепов.
 *
 * Это не оплошность разметки: список собирается из `vehicles`, и устаревает он от правок техники —
 * машину списали, её типу сменили бланк на «форму № 3», — а гасит их `['vehicles']`, до корня
 * прицепов не достающий. Под своим корнем срез пришлось бы гасить руками из чужого модуля, и
 * забытым он оказался бы ровно тогда, когда в списке осталась машина, которой прицеп больше не
 * полагается.
 */
export const trailerHitchTargetsKey = ['vehicles', 'trailer-hitch-targets'] as const;
