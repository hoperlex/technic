/**
 * Что сказать про снятые привязки. Фразу собирает портал, а не сервер: сверх счёта говорить нечего
 * — прицеп, сошедший со списанной машины, человек только что видел в её карточке (в отличие от
 * вытесненного из чужого слота, которого сервер обязан назвать сам, `HitchTrailerResultDto`).
 * Ветки две, а не склонение по числу: граф прицепа в бланке 4-П ровно две, больше двух не снять.
 * `cause` — чем сняло: дверей у правила две (правка и уход в архив), а фраза на обе одна.
 *
 * В слайсе прицепа, а не у вкладки техники, где её зовут: это слова портала **о прицепе**, и
 * стоять им там же, где подпись прицепа в карточке машины и тексты окна привязки. Иначе одно
 * событие описывают из двух мест и правят по очереди.
 */
export const unhitchedNotice = (n: number, cause: string) =>
  n === 1
    ? `Прицеп сошёл с машины: закрепление снято ${cause}`
    : `Прицепов сошло с машины: ${n} — закрепление снято ${cause}`;
