import { createQueryKeys, type Query } from '@shared/api';

/**
 * Ключи запросов складов.
 *
 * Вид запроса пока один — страница вкладки: поставщик, активность и поиск по адресу приходят в
 * параметрах. Ключа «для выпадающего списка» здесь нет, потому что нет и такого запроса: склад
 * никуда не выбирают. Заведи его впрок — и в реестре появился бы ключ, по которому никто ничего
 * не кладёт, а значит, и не узнать, верен ли он.
 */
export const warehouseKeys = createQueryKeys('warehouses', {
  list: (params: Query) => ['list', params],
});
