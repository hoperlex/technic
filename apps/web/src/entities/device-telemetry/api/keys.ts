import { createQueryKeys } from '@shared/api';

/**
 * Ключи телеметрии аппарата (план `docs/office-equipment-mail-telemetry-plan.md`, §10).
 *
 * СВОЙ КОРЕНЬ, А НЕ СЕМЕЙСТВО ВНУТРИ `office-equipment`. Данные сюда пишет не портал, а почтовый
 * приём и будущий коллектор (Р4): правка карточки показаний не меняет, а пришедшее письмо не
 * меняет карточку. Общий корень означал бы, что каждое сохранение кабинета или гарантии гасит
 * ленту событий, — и наоборот, что обновление показаний перезапрашивает справочник.
 *
 * РАЗМЕР СТРАНИЦЫ — ЧАСТЬ КЛЮЧА, как у блоков истории: у блока и у будущей краткой врезки в
 * карточке обрезка разная, и под общим ключом ответ обоим определил бы тот, кто спросил первым.
 */
export const deviceTelemetryKeys = createQueryKeys('device-telemetry', {
  card: (equipmentId: string, pageSize: number) => ['card', equipmentId, pageSize],
});
