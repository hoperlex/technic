import type { Role } from '@technic/contracts';
import { createQueryKeys, type Query } from '@shared/api';

/**
 * Ключи каталога полномочий. Карточка отдельным семейством от списка: реестр выдач перечитывается
 * после каждой выдачи и отзыва, а каталог — только когда меняется состав или число держателей, и
 * гасить его целиком ради одной строки реестра незачем. Корень при этом накрывает и то, и другое:
 * правка набора меняет обе выборки сразу.
 *
 * `formCatalog` — третье семейство, а не `list` с другими параметрами. Отбор у него не такой, как у
 * вкладки «Права»: список формы задаёт **выбранная в форме роль** (план «полномочия назначаются в
 * окне учётки», Р2), а каталог вкладки роли не спрашивает вовсе — там ведут наборы, а не выдают их.
 * Разная у них и форма ответа: `list` отдаёт страницу, `formCatalog` — каталог целиком с признаком
 * полноты (`GrantCatalog`), и одно семейство на два таких ответа означало бы, что запись одного
 * подсовывает другому чужой тип. Корень общий намеренно: правка набора обязана погасить и список
 * вкладки, и каталог формы — состав, который форма показала подсказкой, изменился.
 */
export const grantKeys = createQueryKeys('grants', {
  list: (params: Query) => ['list', params],
  card: (id: string) => ['card', id],
  formCatalog: (role: Role) => ['form-catalog', role],
});
