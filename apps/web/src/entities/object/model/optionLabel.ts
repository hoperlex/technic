import type { ObjectDto } from '@technic/contracts';

/**
 * Подпись площадки в фильтре списка: код, наименование и адрес одной строкой.
 *
 * Адресом площадку и называют, когда ищут заявки: «что было на Ленина, 14» спрашивают чаще, чем
 * «что было на объекте С-12». Строкой, а не двумя строками разметки, по двум причинам: поиск
 * `Select` работает по `label`, и адрес в нём должен находиться наравне с названием, — а те же
 * описания фильтров уходят в шит телефона, где подпись варианта только текст.
 *
 * Адрес в справочнике необязателен: без него подпись остаётся прежней парой «код — наименование»,
 * а не строкой с висящим тире.
 */
export function objectFilterOptionLabel(o: Pick<ObjectDto, 'code' | 'name' | 'address'>): string {
  const address = o.address.trim();
  return address ? `${o.code} — ${o.name} — ${address}` : `${o.code} — ${o.name}`;
}
