import { createQueryKeys, type Query } from '@shared/api';

/**
 * Ключи журнала отправки писем (ADR 0199).
 *
 * Два семейства, и разводить их обязательно: лента отбирается каналом, видом и состоянием и живёт
 * страницами, а тело одного письма от отбора не зависит вовсе и не меняется никогда — письмо в
 * очереди неизменяемо, меняется только его исход. Общий ключ означал бы, что открытое письмо
 * перечитывается при каждой смене фильтра в списке за ним.
 */
export const mailLogKeys = createQueryKeys('mail-log', {
  list: (params: Query) => ['list', params],
  message: (id: string) => ['message', id],
});
