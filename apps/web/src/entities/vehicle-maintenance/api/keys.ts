import { createQueryKeys, type Query } from '@shared/api';

/**
 * Ключи запросов техобслуживания (план «Показания техники», Р10—Р14, Р30).
 *
 * Корень свой, а не семейство внутри показаний, — и это то же решение Р14а, только в кэше. Сводка
 * ТО живёт под своим правом и приходит своей ручкой; окажись она под корнем показаний, приём дня
 * гасил бы её вместе со статистикой, а запись ТО — статистику вместе со сводкой. Ни то, ни другое
 * не верно: числа у этих ответов разные, и устаревают они в разные моменты.
 *
 * Внутри корня — три семейства, и разводить их обязательно. У сводки машина и день среза (Р16), у
 * снапшота — целая страница гаража, у истории — только машина. Под общим ключом карточка одной
 * машины затирала бы снапшот страницы: кто спросил вторым, тот и определил бы ответ обоим.
 *
 * Зато гасится всё это разом: запись ТО меняет и сводку машины, и её историю, и колонку гаража, где
 * та же машина стоит строкой. Поэтому после любой правки достаточно погасить
 * `vehicleMaintenanceKeys.root` — префиксное сравнение TanStack Query накроет три семейства сразу,
 * и ни одному экрану не придётся знать ключи соседа.
 */
export const vehicleMaintenanceKeys = createQueryKeys('vehicle-maintenance', {
  /** Сводка одной машины на день среза: состояние, пробег с ТО, последний одометр (Р14а, Р14б). */
  summary: (vehicleId: string, params: Query) => ['summary', vehicleId, params],
  /** Состояние пакетом — колонка «ТО» страницы гаража: сотня машин одним расчётом. */
  snapshot: (params: Query) => ['snapshot', params],
  /**
   * История записей машины. Своё семейство, а не часть сводки: сводка отвечает про день среза и
   * меняется вместе с ним, а история — весь журнал акта, один и тот же при любом срезе.
   */
  history: (vehicleId: string) => ['history', vehicleId],
});
