import { createQueryKeys, type Query } from '@shared/api';

/**
 * Ключи запросов «Вывоза мусора».
 *
 * Ключ описывает **запрос**, а не сущность: о заявках модуль спрашивают десятком разных вопросов,
 * и ответы у них несовместимы. Страница рабочего списка — это не журнал закрытых (своя ручка, своих
 * заявок в списке нет вовсе), не архив удалённых, не сводка счётчиков и не «что стоит на
 * площадках». Слить их в один ключ значит показать в одном из мест не тот состав, который там
 * нужен, а заметить такое можно только глазами на экране.
 *
 * Семейства сидят под общим корнем `['waste-requests']` намеренно: любая мутация модуля гасит
 * корень целиком — и обязана, потому что всё остальное здесь посчитано из тех же заявок. Счётчики
 * шапки, присутствие контейнеров, группы присутствия, статистика месяца и итог журнала —
 * производные, и собственный корень у любого из них означал бы число, которое после закрытия
 * заявки продолжает показывать вчерашнее.
 *
 * Формы повторяют то, что экраны собирали литералами, сегмент в сегмент, — и теперь экраны зовут
 * эти семейства. Совпадение было не педантизмом переноса: сегмент — это ячейка кэша, и лишний или
 * переставленный не ломает ни типов, ни запроса — экран просто начинает читать пустую. Поэтому
 * там, где форма выглядит случайной, это сказано прямо у самого семейства, а не исправлено молча:
 * правка кэша делается отдельной, видимой человеку, а не попутной.
 *
 * `root` нужен уже снаружи страницы: ячейка колонки «Талоны» подтверждает талон прямо из строки
 * (`features/waste-ticket-review`) и обязана перечитать список, не зная ни его отбора, ни номера
 * страницы.
 */
export const wasteRequestKeys = createQueryKeys('waste-requests', {
  /**
   * Рабочий список вкладки «Заявки»: отбор целиком, как его собрал экран.
   *
   * Сегмента с именем семейства у списка нет — ключ так и остаётся `['waste-requests', отбор]`.
   * Это не забытая `list`: сегмент сменил бы ячейку кэша единственному экрану списка, ничего при
   * этом не починив, — корень `['waste-requests']` и сейчас накрывает список вместе со всем
   * остальным.
   *
   * Отбор объектом целиком, а не полями врозь: новый фильтр вкладки попадает в ключ сам, а
   * перечисленный руками список однажды забыли бы дополнить — и вкладка показала бы прежние строки
   * под новым фильтром. Приходит сюда тот же объект, что уходит в запрос, — с периодом, уже
   * разложенным на моменты: две разные границы одного дня — это два разных ответа, и ключ,
   * считанный до разложения, отдал бы одному из них чужие строки.
   */
  list: (params: Query) => [params],
  /**
   * Одна заявка по идентификатору: так её открывают ссылкой из соседнего раздела («№ заявки
   * установки» в списке площадок). Спрашивается по номеру, а не ищется в загруженном списке — та же
   * заявка может лежать на другой странице, под другим фильтром или в другой вкладке.
   *
   * Одна ячейка на три вкладки (список, журнал, архив) — это и нужно: заявка одна, ручка одна, и
   * открытая из любой вкладки она приходит одним запросом. Сегмент `'detail'` развёл бы их натрое.
   *
   * Форма при этом позиционно совпадает с `list`, и различает их только тип аргумента — строка
   * против объекта отбора. Ячейки от этого разные (TanStack Query сличает значения, а не буквы),
   * но читающему ключ глазами `['waste-requests', X]` не говорит, карточка это или страница
   * списка. Оставлено как есть: сегмент — это ячейка кэша.
   */
  detail: (id: string) => [id],
  /**
   * Счётчики над списком: сколько не обработано, сколько в работе, сколько ждёт закрытия.
   *
   * В ключе одна графа, а не весь отбор, потому что ровно по ней сервер сводку и сужает: она
   * отвечает про раздел, а не про текущую страницу. Возьми ключ отбор целиком — шапка
   * пересчитывалась бы на каждый переход по страницам и на каждую букву поиска, показывая при этом
   * те же числа.
   *
   * `undefined` — «по всем площадкам», и это отдельная ячейка от любой конкретной: числа у них
   * разные, и общий ключ подсунул бы человеку с одной площадкой итог по всему порталу.
   */
  summary: (objectId: string | undefined) => ['summary', objectId],
  /**
   * Вкладка «На площадках»: что сейчас стоит на площадках — производный вид по заявкам установки.
   *
   * Своё семейство, а не `list` с фильтром: ручка другая (`/waste-requests/present`), и состав
   * строк у неё свой — под общим ключом вкладка показала бы обычный список заявок.
   */
  present: (params: Query) => ['present', params],
  /**
   * Группы присутствия на площадке (ADR 0054): что и чьё там стоит и сколько штук. Одна выборка
   * отвечает сразу на три вопроса формы — какой контейнер меняют или снимают, каков потолок
   * количества и кого звать.
   *
   * Одно семейство на два места — форму заведения и окно назначения оператора: вопрос у них
   * дословно один и та же площадка, и кэш общий намеренно. Окно открывают сразу вслед за формой, и
   * второй ключ означал бы второй поход за уже загруженным ответом.
   *
   * `undefined` допустим: площадку ещё не выбрали — запрос тогда выключен (`enabled`), но ключ
   * собирается всё равно, и подставлять вместо `undefined` пустую строку нельзя: это была бы
   * другая ячейка кэша у формы, которая ничего не спрашивала.
   */
  presentGroups: (objectId: string | undefined) => ['present-groups', objectId],
  /**
   * Статистика отчётного месяца — вкладка «Статистика»: площадки, объём и деньги.
   *
   * Месяц в ключе обязателен: по нему сервер и считает, а ключ, о месяце не знающий, показал бы
   * январь под заголовком февраля. Отдельной ячейкой на месяц ещё и листается дёшево — уже
   * посчитанный месяц возвращается мгновенно, а не пересчитывается сводной аналитикой заново.
   */
  stats: (month: string) => ['stats', month],
  /**
   * Журнал закрытых заявок — вкладка «История» (ADR 0135): завершённые и отменённые за отбор.
   *
   * Имя `closed`, а не `history`: `history` в этом же наборе занята лентой событий ОДНОЙ заявки, и
   * два разных вопроса под одним именем путали бы читающего — а однажды и гасящего. Сегмент при
   * этом остался `'history'`: так его собирает экран и так адресована ручка, а переименование
   * сегмента сменило бы вкладке ячейку кэша, ничего не починив.
   *
   * Отбор здесь свой, не общий со списком: в рабочем списке закрытых заявок нет вовсе, и общий
   * ключ отдал бы журналу страницу, посчитанную по другим заявкам.
   */
  closed: (params: Query) => ['history', params],
  /**
   * Итог журнала по тем же фильтрам: сколько закрыто, чем закончилось, что вывезли.
   *
   * Своё семейство, а не хвост списка: итог считается по отбору целиком, без страницы и порядка, —
   * под общим ключом он пересчитывался бы на каждый переход по страницам. Отбор в ключе тот же,
   * что у списка, и это обязательно: сводка, отвечающая не про то, что человек видит перед собой,
   * вводит в заблуждение вернее, чем её отсутствие.
   */
  closedSummary: (params: Query) => ['history-summary', params],
  /**
   * Архив удалённых заявок (ADR 0070).
   *
   * Отдельное семейство, хотя ручка та же, что у списка, с `archive: 'only'`: отбор у вкладок
   * совпадает по полям и расходится по составу строк, и под общим ключом архив затирал бы страницу
   * рабочего списка — кто спросил вторым, тот и определил бы ответ обоим.
   */
  archive: (params: Query) => ['archive', params],
  /**
   * Лента событий одной заявки (ADR 0012): заведение, правки, смены статусов. Отдельно от карточки,
   * потому что приходит отдельной ручкой и устаревает в другие моменты — переход дописывает
   * событие, не трогая полей самой заявки.
   *
   * Единственная форма набора, где идентификатор стоит ПЕРЕД именем семейства — так её собрало
   * окно карточки. Последствия называю, раз уж форму не правлю: ленты всех заявок одним префиксом
   * не погасить (`['waste-requests', 'history']` — это журнал закрытых, а не они), зато `detail`
   * оказался префиксом ленты, и гашение карточки уносит её события заодно. Сегодня это и нужно —
   * событие дописывается ровно тогда, когда меняется заявка, — но правка, которая разведёт их,
   * обязана знать, что разводит связанное.
   *
   * `undefined` допустим: окно живёт и закрытым — запрос тогда выключен (`enabled`), но ключ
   * собирается всё равно.
   */
  history: (id: string | undefined) => [id, 'history'],
});
