import { createQueryKeys, type Query } from '@shared/api';

/**
 * Ключи запросов норм расхода.
 *
 * Настройки сверки стоят своим ключом, а не внутри списка: их читает и окно норм, и — после
 * правки — обязана перечитать сводка гаража, у которой свой ключ и свой период. Общий ключ
 * заставил бы сводку перезапрашиваться на каждое листание справочника.
 */
export const fuelNormKeys = createQueryKeys('fuel-norms', {
  list: (params: Query) => ['list', params],
  settings: () => ['settings'],
  count: () => ['count'],
});

/**
 * Машины для выбора в карточке нормы — под корнем **техники**, а не норм.
 *
 * Тем же порядком, что и список машин под прицеп: срез собирается из `vehicles` и устаревает от
 * правок техники (машину списали, завели новую), а гасит их `['vehicles']`. Под корнем норм его
 * пришлось бы гасить руками из чужого модуля — и забыли бы ровно тогда, когда в списке осталась
 * списанная машина.
 */
export const fuelNormVehiclePickerKey = ['vehicles', 'fuel-norm-picker'] as const;
