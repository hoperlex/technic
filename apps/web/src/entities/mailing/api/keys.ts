import { createQueryKeys } from '@shared/api';

/**
 * Ключи справочников отладочной отправки (ADR 0075): кому отправить пробное письмо, каким каналом,
 * чьё задание и чью сводку собрать.
 *
 * **Корней четыре, а не одно семейство на четверых.** Так их собрал экран, и переносом это не
 * меняется: сегмент — это ячейка кэша, а промах мимо неё типы не ловят — экран просто начинает
 * читать пустоту, и видно это только глазами. Общий корень пригодился бы, будь у этих справочников
 * общее гашение, но гасить их нечем и незачем: портал их не пишет — за всеми четырьмя стоят
 * административные ручки только на чтение, а меняются они не от действий в портале (заведут
 * администратора, выпишут рейс, настроят канал в `env` сервера).
 *
 * **Семейства у трёх из них нет, и ключом служит сам корень.** Запрос у каждого ровно один,
 * параметров у него нет, и `['mail-accounts']` — это и есть тот ключ, который собирает экран.
 * Заведи здесь семейство ради единообразия с соседями — в ключе появился бы второй сегмент, то
 * есть другая ячейка. Второе имя того же кортежа (`root` и `all()` рядом) тоже не заводится: один
 * ключ — одно написание, иначе два места разойдутся молча.
 *
 * **Почему каналы отправки живут здесь, а не у соседей по почте.** `mail-log` (ADR 0199) отвечает
 * «как оказалось» — очередь уже составленных писем, `module-mail` — «на какой ящик уходит письмо
 * по событию модуля». Канал упоминают оба: журнал им фильтрует ленту, письмо им уходит. Но вопрос
 * «какие каналы настроены на этом сервере» задаёт одна ручка — `mailingsApi.accounts()`
 * (`GET /admin/mail/accounts`, право `mailings.read`), и спрашивает её один экран — отладочная
 * отправка. Перечень каналов и их подписи приезжают из контрактов
 * (`packages/contracts/src/mail-accounts.ts`), настроенность — только от сервера, у которого лежит
 * `env`; ни журналу, ни адресатам модулей спрашивать про неё нечего.
 */

/**
 * Кому можно отправить пробное письмо: действующие администраторы с адресом. Список меняется
 * заведением учётки, а не отладкой, — поэтому ключ без параметров и без гашения.
 */
export const mailTestRecipientKeys = createQueryKeys('mail-test-recipients', {});

/**
 * Какие каналы настроены на сервере и от кого через них придёт письмо. Ненастроенный канал в
 * списке остаётся, но выбрать его нельзя: письмо легло бы в очередь и ждало настройки, а человек
 * считал бы, что проверил отправку.
 */
export const mailAccountKeys = createQueryKeys('mail-accounts', {});

/**
 * Кем можно «посмотреть» сводку по ролям. Даты в запросе нет намеренно: сводка собирается под любым
 * действующим человеком, и пустота за выбранный день — это уже её ответ, а не повод прятать его из
 * списка.
 */
export const mailDigestSampleUserKeys = createQueryKeys('mail-digest-sample-users', {});

/**
 * Водители с рейсами на дату — чьё задание собрать пробным письмом.
 *
 * Дата в ключе обязательна: рейсы есть не у всех и не каждый день, по ней сервер и отбирает, —
 * ключ, о дате не знающий, предложил бы водителя, у которого на выбранный день задания нет вовсе.
 *
 * `undefined` допустим: вид письма выбирают раньше даты — запрос тогда выключен (`enabled`), но
 * ключ собирается всё равно, и подставлять вместо `undefined` пустую строку нельзя — это была бы
 * другая ячейка кэша у формы, которая ничего не спрашивала.
 *
 * Сегмента с именем семейства нет по той же причине, что у соседей: `['mail-test-drivers', дата]`
 * — ровно то, что собирает экран.
 */
export const mailTestDriverKeys = createQueryKeys('mail-test-drivers', {
  byDate: (date: string | undefined) => [date],
});

/**
 * Расписания рассылок (ADR 0093): что портал рассылает сам, кому и по каким дням.
 *
 * Ключом служит сам корень — запрос один и без параметров, вкладка берёт расписания целиком. Гасят
 * его правки самих расписаний, и только они: список приходит одной ручкой и ни от чего другого не
 * зависит.
 */
export const mailingScheduleKeys = createQueryKeys('mailing-schedules', {});

/**
 * История запусков выбранного расписания: когда сработало, сколько писем ушло и чем кончилось.
 *
 * Расписание и страница — в ключе, потому что по ним сервер и отбирает. Отдельным корнем от самих
 * расписаний, а не семейством под ними: правка расписания меняет его карточку, но уже состоявшихся
 * запусков не трогает, — под общим корнем список запусков перечитывался бы после каждого
 * сохранения ради строк, которые не менялись.
 */
export const mailingRunKeys = createQueryKeys('mailing-runs', {
  ofSchedule: (scheduleId: string | null, page: number, pageSize: number) => [
    scheduleId,
    page,
    pageSize,
  ],
});

/**
 * Кто попадёт в рассылку при таком отборе аудитории (ADR 0093): предпросмотр состава по правам,
 * области и перечню площадок или отделов.
 *
 * Весь отбор — в ключе, и это не педантизм: вопрос «кого возьмёт планировщик» отвечается целиком
 * этими графами, и ключ, забывший хоть одну, показал бы состав для другого отбора. Отдельный корень
 * потому, что предпросмотр ничего не сохраняет: он живёт в форме до нажатия и гасить его вместе с
 * расписаниями незачем.
 */
export const mailingCandidateKeys = createQueryKeys('mailing-recipient-candidates', {
  byAudience: (
    permissions: readonly string[],
    scopeMode: string,
    objectIds: readonly string[],
    departmentIds: readonly string[],
  ) => [permissions, scopeMode, objectIds, departmentIds],
});
