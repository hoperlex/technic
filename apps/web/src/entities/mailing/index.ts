/**
 * Рассылки (ADR 0075, ADR 0111): расписания, их аудитория, история запусков и отладочная отправка —
 * «кого и когда портал выберет сам».
 *
 * Своя сущность, а не часть соседей по почте: `mail-log` (ADR 0199) отвечает «как оказалось» —
 * это очередь уже составленных писем, `module-mail` — «на какой ящик уходит письмо по событию
 * модуля», а здесь настраивают, кого и когда планировщик возьмёт сам. Общего у всех троих только
 * раздел администрирования и право доступа; ручки, адреса и таблицы у них разные, и импортировать
 * соседа отсюда нечего.
 *
 * Снаружи берут `@entities/mailing` — внутренние модули слайса не видны, и перестроить его можно,
 * не трогая потребителей.
 *
 * Ключи запросов слайс держит пока не на всё: заведены четыре справочника отладочной отправки —
 * получатели, каналы, водители с рейсами и учётки-образцы. Формы у них ровно те, что вкладка
 * собирает строками сегодня, до сегмента: сдвинуть ячейку кэша заодно с переездом ключа значило бы
 * менять поведение под видом переноса — такую правку видно только глазами на экране.
 *
 * Корни самой вкладки — расписания, история запусков и предпросмотр аудитории — заведены здесь же:
 * они жили именованными константами рядом со своими экранами, и машинный обход ключей их не видел
 * вовсе, потому что искал литералы в месте употребления.
 */
