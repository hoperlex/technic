import { createQueryKeys, type Query } from '@shared/api';

/**
 * Ключи запросов моделей механизации.
 *
 * Ключ описывает **запрос**, а не сущность. Справочник спрашивают в двух видах, и путать их
 * нельзя: страницей с отбором и сортировкой — своя вкладка «Справочников», и целиком — перечень
 * для подбора в заявке, где показывают только действующие модели и всегда по алфавиту. Один ключ
 * на оба означал бы, что открывший вкладку вторым получит в таблице чужой ответ — пятьсот
 * активных строк вместо своей страницы.
 */
export const mechModelKeys = createQueryKeys('mech-models', {
  list: (params: Query) => ['list', params],
  options: () => ['options'],
});
