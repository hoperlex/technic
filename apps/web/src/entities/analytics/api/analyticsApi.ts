import type { AnalyticsSummaryDto } from '@technic/contracts';
import { apiDownload, apiFetch, type Query } from '@shared/api';

/**
 * Клиент сводной аналитики по заказчикам (`docs/analytics-summary-export-plan.md`, Р14).
 *
 * Ручек две, и отвечают они одним и тем же счётом: книга Excel и тот же свод в JSON. Вторая
 * заведена сразу, вместе с первой, а не «когда дойдут руки до экрана»: свод считается одним слоем
 * (`apps/api/src/services/analytics/`), и второго ответа на «сколько смен за август» в проекте
 * быть не должно. Появись экран аналитики без этой ручки — он собрал бы себе третий счёт, и книга
 * с экраном разошлись бы молча.
 *
 * Формы ответа здесь не переписываются: `AnalyticsSummaryDto` и схемы запросов живут в
 * `@technic/contracts`, и обе стороны читают их оттуда.
 */

/** Общий префикс: свод — самостоятельный слой, а не подраздел показаний или заявок. */
const BASE = '/analytics';

export const analyticsApi = {
  /**
   * Книга Excel за период. `chartObjectId` кладёт вызывающий, и пустой он означает «книга без
   * листа инфографики» (Р12а): лист строится по одной площадке, а собранный по всем сразу был бы
   * ровно тем сравнительным представлением, которого в книге решено не делать.
   *
   * Имя файла приходит заголовком `content-disposition` — период и площадку знает сервер; здесь
   * только запасное, на случай потери заголовка по дороге.
   */
  exportBook: (query: Query) => apiDownload(`${BASE}/export`, 'Сводная аналитика.xlsx', { query }),
  /**
   * Тот же свод в JSON — строки, итоги, качество данных и динамика по шагам.
   *
   * Портал её пока не спрашивает: первым потребителем свода стала книга. Метод всё равно живёт
   * здесь, а не заведётся заново рядом с будущим экраном, — по той же причине, по которой слайс
   * вообще есть: клиент модуля один, и ключ кэша у него будет один.
   */
  summary: (query: Query) => apiFetch<AnalyticsSummaryDto>(`${BASE}/summary`, { query }),
};
