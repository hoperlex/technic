import { createQueryKeys } from '@shared/api';

/**
 * Ключи запросов недельных заявок на технику (ADR 0085, ADR 0101).
 *
 * **Почему заявка стоит вперёд семейства.** Обычный ключ портала — `[корень, семейство, …параметры]`
 * (`createQueryKeys`), здесь же после корня идёт идентификатор: `['weekly-vehicle-requests', id]`,
 * `[…, id, 'documents']`, `[…, id, 'history']`, `[…, id, 'correction']`. Это не описка и не
 * недосмотр: раскладка выбрана так, чтобы префикс одной заявки накрывал всё, что о ней спрошено.
 * Виза применяет неделю той же транзакцией, которой двигает сроки заказов (Р6), и после неё
 * устаревают разом карточка, перечень документов, история и предпросмотр коррекции — гасить их
 * тремя ключами по одному значит однажды забыть один и оставить на экране вчерашний ответ.
 *
 * Срез площадки (`suggestion`) — единственное семейство без заявки: он отвечает про пару «объект +
 * неделя» и живёт дольше самого черновика — его перечитывают после отказа применения, чтобы строка
 * с отменённым заказом получила свою причину.
 *
 * **Пока фабрикой пользуется не всё.** Страница заявки и вкладки по-прежнему собирают эти же
 * массивы литералами — их перевод отдельная работа. Раскладка описана здесь целиком именно поэтому:
 * пока места сборки ключа разные, форма у него обязана быть записана в одном.
 */
export const weeklyRequestKeys = createQueryKeys('weekly-vehicle-requests', {
  detail: (id: string) => [id],
  documents: (id: string) => [id, 'documents'],
  history: (id: string) => [id, 'history'],
  /**
   * Цена проведения задним числом, посчитанная сервером (ADR 0101).
   *
   * Идентификатор необязателен, и это не послабление типа: окно проведения живёт и закрытым —
   * заявки в нём тогда нет вовсе, а запрос выключен (`enabled`). Ключ при этом всё равно
   * собирается, и подставлять вместо `undefined` пустую строку нельзя: это был бы другой ключ, то
   * есть другая ячейка кэша у окна, которое ничего не спрашивало.
   */
  correction: (id: string | undefined) => [id, 'correction'],
  /** Срез площадки на неделю: что продлевать, что уезжает, что уже заказано (Р4). */
  suggestion: (objectId: string | undefined, weekStart: string | undefined) => [
    'suggestion',
    objectId,
    weekStart,
  ],
});
