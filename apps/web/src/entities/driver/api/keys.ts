import type { CredentialTypeCode } from '@technic/contracts';
import { createQueryKeys, type Query } from '@shared/api';

/**
 * Ключи запросов водителей.
 *
 * Ключ описывает **запрос**, а не сущность: справочник спрашивают несколькими разными вопросами, и
 * ответы у них несовместимы. «Весь действующий состав по алфавиту» (значения фильтров) — это не
 * «кто может сесть за эту машину в эту дату» (отбор по категории и документам, ADR 0064) и не
 * «кого предложить машинистом на эти недели» (пересечение периодов, ADR 0164). Слить их в один
 * ключ значит показать в одном из мест не тот состав, который там нужен, — а заметить такое можно
 * только глазами.
 *
 * Семейства сидят под общим корнем `['drivers']` намеренно: вкладка справочника гасит корень
 * целиком после любой правки карточки, и выборки, посчитанные из тех же карточек, обязаны уходить
 * вместе с ним. Исключение одно — категории документов, и почему, сказано у них.
 *
 * Формы ключей повторяют то, что экраны собирали литералами, до сегмента: перенос не сдвигает ни
 * одной ячейки кэша. Где нынешняя форма выглядит случайной, это сказано прямо, а не исправлено
 * молча — правка кэша заметна человеку и делается отдельно от переноса.
 */
export const driverKeys = createQueryKeys('drivers', {
  /**
   * Справочник вкладки «Водители»: отбор целиком, как его собрал экран.
   *
   * Сегмента с именем семейства у списка нет — ключ так и остаётся `['drivers', отбор]`. Это не
   * забытая `list`: сегмент сменил бы ячейку кэша единственному экрану справочника, ничего при
   * этом не починив, — корень `['drivers']` и сейчас накрывает список вместе со всем остальным.
   *
   * Отбор объектом целиком, а не полями врозь: новый фильтр экрана попадает в ключ сам, а
   * перечисленный руками список однажды забыли бы дополнить — и список показал бы прежние строки
   * под новым фильтром.
   */
  list: (params: Query) => [params],
  /**
   * Должности с числом людей — значения фильтра справочника. Под корнем водителей, а не под своим:
   * счётчики считаются по тем же карточкам, и заведённая карточка обязана обновить их вместе со
   * списком. Собственного корня хватило бы ровно до первого заведённого водителя.
   */
  jobTitles: () => ['job-titles'],
  /**
   * Весь действующий состав по алфавиту — значения фильтров списков: ни категория, ни полнота
   * документов здесь никого не убирают, это фильтр, а не подбор под машину (ADR 0064). Параметров
   * у ключа нет: выборка одна на портал, и спрашивать её дважды незачем.
   */
  options: () => ['options'],
  /**
   * Тот же состав для формы расписания рассылок — кого исключить из задания водителям.
   *
   * Выборка совпадает с `options` до буквы, а ключ разный: это наследство, а не решение. Слить их
   * значит поменять поведение кэша — форма рассылок просит справочник только открытой и только у
   * своего типа рассылки, потому что в карточках персональные данные (ADR 0037), — и общий ключ
   * раздал бы загруженное одним экраном другому. Вопрос решается правкой, видной на ревью.
   */
  mailingExclusions: () => ['mailing-exclusions'],
  /**
   * Кто может сесть за эту машину в эту дату — список выбора окон рейса, перевода в работу и
   * перегона.
   *
   * Все три графы в ключе, потому что по каждой сервер считает ответ: машина задаёт требуемую
   * категорию, дата — годность документов, прицеп — нужна ли сцепка. Никого из списка это не
   * убирает (ADR 0064), но помечает строку — и ключ, не знающий хотя бы одной графы, показал бы
   * пометки, посчитанные для другой машины или другого дня, то есть годным того, кто не годен.
   *
   * Аргумент той же формы, что у `driversApi.available`: ключ и ручка спрашивают об одном, а в
   * позиционном вызове машину с датой можно переставить местами — обе строки, и поймать подмену
   * нечем.
   *
   * `undefined` у машины и даты допустим: окно живёт и до их выбора — запрос тогда выключен
   * (`enabled`), но ключ собирается всё равно, и подставлять вместо `undefined` пустую строку
   * нельзя — это была бы другая ячейка кэша у окна, которое ничего не спрашивало.
   *
   * Прицеп называется всегда, даже перегоном, где его не бывает: `undefined` и `false` — разные
   * ячейки, и необязательная графа развела бы один и тот же вопрос по двум ключам.
   */
  available: (q: {
    vehicleId: string | undefined;
    on: string | undefined;
    withTrailer: boolean;
  }) => ['available', q.vehicleId, q.on, q.withTrailer],
  /**
   * Список выбора машиниста в окнах назначения, ремонта и смены машиниста — обычный справочник
   * целиком: в бланке ЭСМ-2 нет ни СНИЛСа, ни удостоверения, и отбирать по ним некого (ADR 0055).
   *
   * Имя сегмента историческое: за ним стоит `GET /drivers`, а не `GET /drivers/machinists`.
   * Переименовать его переносом нельзя — сменится ячейка кэша у трёх окон сразу.
   */
  machinistOptions: () => ['machinists'],
  /**
   * Кого предложить машинистом листа ЭСМ-2 на эти периоды — `GET /drivers/machinists`: отбор
   * отвечает пересечением, и у недели на стыке месяцев периодов два (ADR 0164).
   *
   * Префикс `['drivers', 'machinists']` этот ключ делит с `machinistOptions`, хотя ручки у них
   * разные: гасить по префиксу нельзя — снесёт чужой запрос. Сегодня так никто и не гасит,
   * справочник сбрасывают корнем целиком, но развести имена — та же смена ячеек кэша.
   *
   * Периоды приходят уже строкой: ровно её собирает экран сегодня. Собирать её здесь значит
   * завести второе место, где живёт формат `from..to`; первое — в самой ручке, и разойдясь на
   * запятую, они молча разведут ключ с запросом.
   */
  machinistsForPeriods: (periodsKey: string) => ['machinists', periodsKey],
});

/**
 * Категории вида документа (ADR 0095) — под собственным корнем, а не под `['drivers']`.
 *
 * Это не оплошность разметки, а тот же приём, каким разведён `vehicleTypesForTrailerKey` у рейсов:
 * справочник наполнен миграцией и только на чтение, экран берёт его один раз на вид и держит до
 * перезагрузки страницы. Под корнем водителей его сбрасывала бы каждая правка карточки — портал
 * перезапрашивал бы неизменяемый словарь ради данных, к которым тот не относится.
 *
 * Вид документа в ключе обязателен: «C» водительского и «C» тракториста — разные машины, и общий
 * ключ подсунул бы одному из двух мест экрана чужие буквы.
 */
export const licenseCategoryKeys = createQueryKeys('license-categories', {
  byType: (type: CredentialTypeCode) => [type],
});
