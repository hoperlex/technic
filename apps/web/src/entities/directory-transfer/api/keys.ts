import { createQueryKeys } from '@shared/api';

/**
 * Ключи обмена справочниками.
 *
 * Корень `directories` — не про сами справочники, а про их выгрузку и загрузку: данные здесь
 * ничьи, ответ несёт перечень ресурсов со счётчиками строк. Гасить его правкой любой отдельной
 * записи было бы неверно — счётчики пересчитывает сам обмен, и держит их одна вкладка.
 */
export const directoryTransferKeys = createQueryKeys('directories', {
  /** Перечень справочников со счётчиками — им вкладка обмена и рисуется. */
  list: () => ['transfer'],
});
