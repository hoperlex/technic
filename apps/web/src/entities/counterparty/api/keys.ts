import { createQueryKeys, type Query } from '@shared/api';

/**
 * A counterparty has one record and one type, but different readers need different subsets.
 * Active options serve new assignments; historical filters include inactive records. All families
 * share this root so a counterparty edit invalidates service, mechanization and waste selections.
 */
export const counterpartyKeys = createQueryKeys('counterparties', {
  /**
   * Вкладка «Контрагенты» справочника: отбор целиком, как его собрал экран.
   *
   * Сегмента с именем семейства у списка нет — ключ так и остаётся `['counterparties', отбор]`.
   * Это не забытая `list`: сегмент сменил бы ячейку кэша единственному экрану справочника, ничего
   * при этом не починив, — корень `['counterparties']` и сейчас накрывает список вместе со всеми
   * выборками.
   *
   * Отбор объектом целиком, а не полями врозь: новый фильтр вкладки попадает в ключ сам, а
   * перечисленный руками список однажды забыли бы дополнить — и вкладка показала бы прежние строки
   * под новым фильтром.
   */
  list: (params: Query) => [params],
  /**
   * Справочник целиком, вместе со снятыми с учёта, — фильтр журнала изменений учёток (ADR 0109).
   *
   * Недействующих не убираем намеренно: журнал читают про вчерашние действия, и контрагент, с
   * которым уже не работают, обязан называться в фильтре — иначе строку, ради которой журнал
   * открыли, нечем найти. Тип в запросе не задан вовсе: группами по типу список раскладывает сам
   * экран, а сервер отдаёт всё подряд.
   */
  options: () => ['options'],
  /**
   * Тот же справочник, но только действующие, — выбор контрагента в форме учётки исполнителя
   * (ADR 0038).
   *
   * Отдельно от `options`, хотя вопрос похож: привязка учётки — это обещание на будущее, и
   * заводить её к контрагенту, с которым уже не работают, незачем; фильтр же журнала говорит о
   * прошлом. Общий ключ подсунул бы одному из двух мест чужой состав.
   *
   * Имя — по выборке: сервер отбирает действующих контрагентов любых типов, а делить их на
   * «исполнителей» по типу — работа экрана (`COUNTERPARTY_TYPES_WITH_ACCOUNTS`), не запроса. Имя
   * сегмента при этом осталось экранным (`executors-for-select`): переименовать его переносом
   * нельзя — сменится ячейка кэша.
   */
  activeOptions: () => ['executors-for-select'],
  /**
   * Действующие операторы вывоза — выбор исполнителя в заявке и фильтр списков вывоза мусора
   * (ADR 0010).
   *
   * Только действующие: исполнителя назначают на будущую заявку, и оператор, с которым уже не
   * работают, в этом списке — приглашение к ошибке.
   */
  activeOperatorOptions: () => ['operators-for-select'],
  /** All operators, including inactive ones, remain available for historical links and tariffs. */
  operatorOptions: () => ['operators-for-objects'],
  /**
   * Поставщики — фильтр складов и выбор в их форме.
   *
   * Недействующих не убираем по той же причине, что у привязки операторов: склад у них заведён, и
   * в форме привязка осталась бы без наименования.
   */
  supplierOptions: () => ['suppliers'],
  /** Active service companies for assignment and service filters. */
  serviceOptions: () => ['service-options'],
  /** Only mechanization lessors can take a mechanization request. */
  mechLessorOptions: () => ['mech-lessor-options'],
  /** Действующие арендодатели ТС — выбор арендодателя в карточке машины. */
  activeVehicleLessorOptions: () => ['vehicle-lessors'],
  /**
   * Все арендодатели ТС, вместе с недействующими, — фильтр журнала заказов техники: по ним сводят
   * расходы на аренду, и журнал читают и про тех, с кем уже не работают.
   *
   * Сегмент `'all'` третьим — форма, как её собрал экран; соседние пары обходятся разными именами
   * второго сегмента, и выглядит она случайной. Оставлена как есть: сегмент — это ячейка кэша.
   */
  vehicleLessorOptions: () => ['vehicle-lessors', 'all'],
});
