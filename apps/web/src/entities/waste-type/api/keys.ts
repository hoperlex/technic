import { createQueryKeys } from '@shared/api';

/**
 * Ключи запросов типов мусора.
 *
 * Своей вкладки у справочника нет (ADR 0017: тип живёт строкой прайса), поэтому и списочного ключа
 * нет — спрашивают его только целиком, но в двух разных видах:
 *  - `pricedOnly: true` — то, что можно выбрать в заявке на вывоз: действующие типы с действующей
 *    ценой. Тип без тарифа кончался бы отказом «тариф не найден» уже при сохранении заявки;
 *  - `pricedOnly: false` — весь справочник: прайс показывает и неактивные типы (их правят и
 *    сносят), и по нему же форма ищет двойников, пока человек печатает название нового типа.
 *
 * Слить их в один ключ значит либо спрятать половину справочника от прайса, либо предложить в
 * заявке тип, который она не сохранит.
 */
export const wasteTypeKeys = createQueryKeys('waste-types', {
  options: (params: { pricedOnly: boolean }) => ['options', params],
});
