import type {
  CreateVehicleInput,
  DeleteVehicleResult,
  ListResult,
  UpdateVehicleInput,
  UpdateVehicleResult,
  VehicleDto,
  VehicleModelDto,
} from '@technic/contracts';
import { apiFetch, type Query } from '@shared/api';

/**
 * Парк: какая техника у компании есть — единица с госномером и марка/модель, которой она подписана
 * (ADR 0007). Соседний слайс `vehicle-type` отвечает на другой вопрос — «что за техника бывает»
 * (вид, тип, ТТХ, категория, классификатор), — и граница между слайсами проходит ровно по нему.
 *
 * Две ручки одним файлом, потому что это один справочник, а не два. Марка/модель сама по себе не
 * значит ничего: она принадлежит типу (ADR 0007, решение 1), спрашивается ровно в одном месте —
 * полем формы машины — и своей вкладки в портале не имеет. То же сказано на сервере:
 * «Read-only: список марок/моделей для селекта в форме техники (не отдельный справочник)»
 * (`apps/api/src/routes/vehicle-models.ts`). Разложенные по двум файлам, две половины одного
 * справочника разошлись бы, и первым разошёлся бы ответ на вопрос, чей это вообще слайс.
 */

/**
 * Марки/модели выбранного типа — значения поля «Марка/модель» в карточке машины.
 *
 * Ручка одна, и это не начатая работа: портал модели не заводит и не правит, справочник наполнен
 * миграцией (ADR 0007, решение 5 — импорта и парсера нет), а маршрут у сервера только читающий.
 * Заведи здесь `create` — и форма получила бы кнопку, на которую сервер отвечает 404.
 *
 * Модель спрашивают всегда под тип (`vehicleTypeId` в отборе): одинаковое имя у разных типов —
 * разные записи, и список без отбора предложил бы машине чужую марку, которую сервер не примет
 * составным ключом (ADR 0007, решение 4).
 */
export const vehicleModelsApi = {
  list: (q: Query) => apiFetch<ListResult<VehicleModelDto>>('/vehicle-models', { query: q }),
};

/**
 * Единицы парка. Архив — не удаление: `remove` убирает машину из списков, `restore` возвращает её
 * оттуда, и только `purge` стирает запись насовсем. Различие не бухгалтерское: вчерашние рейсы,
 * путевые листы и закрытые заявки ссылаются на машину, которой сегодня в строю уже нет, и список,
 * потерявший её, читался бы как поломка.
 *
 * Голый «ADR 0060» ниже — это `docs/adr/0060-directory-record-purge.md`: номер занят дважды, и
 * второй его хозяин (недельный лист ЭСМ-2) к удалению записи отношения не имеет.
 */
export const vehiclesApi = {
  list: (q: Query) => apiFetch<ListResult<VehicleDto>>('/vehicles', { query: q }),
  create: (body: CreateVehicleInput) => apiFetch<VehicleDto>('/vehicles', { method: 'POST', body }),
  /**
   * Ответы правки и архивации — обёртки с числом снятых привязок, а не карточка и не голое `{ ok }`:
   * обе двери снимают привязки прицепов (списание машины, перевод её типа на «форму № 3», уход в
   * архив), и о втором изменении в базе портал обязан сказать (`docs/vehicle-trailers-plan.md`, §4.2.3).
   */
  update: (id: string, body: UpdateVehicleInput) =>
    apiFetch<UpdateVehicleResult>(`/vehicles/${id}`, { method: 'PATCH', body }),
  remove: (id: string) => apiFetch<DeleteVehicleResult>(`/vehicles/${id}`, { method: 'DELETE' }),
  restore: (id: string) => apiFetch<VehicleDto>(`/vehicles/${id}/restore`, { method: 'POST' }),
  /** Удаление насовсем — только из архива (ADR 0060). */
  purge: (id: string) => apiFetch<{ ok: boolean }>(`/vehicles/${id}/purge`, { method: 'DELETE' }),
};
