import { createQueryKeys, type Query } from '@shared/api';

/**
 * Vehicle reads share the `vehicles` root so vehicle writes invalidate every fleet picker.
 * The fuel norm picker still declares its key in its own slice because entities cannot import
 * peer entities. The trailer hitch picker now uses `ownForCorrection`: both read the same own fleet
 * in registration order, including units no longer active.
 */
export const vehicleKeys = createQueryKeys('vehicles', {
  /**
   * Вкладка «Техника» справочника: отбор целиком, как его собрал экран.
   *
   * Сегмента с именем семейства у списка нет — ключ так и остаётся `['vehicles', отбор]`. Это не
   * забытая `list`: сегмент сменил бы ячейку кэша единственному экрану справочника, ничего при
   * этом не починив, — корень `['vehicles']` и сейчас накрывает список вместе со всеми выборками.
   *
   * Отбор объектом целиком, а не полями врозь: новый фильтр вкладки попадает в ключ сам, а
   * перечисленный руками список однажды забыли бы дополнить — и вкладка показала бы прежние
   * строки под новым фильтром.
   */
  list: (params: Query) => [params],
  /**
   * Весь парк для фильтра «назначенная машина» в списке заказов и журнале закрытых (ADR 0098).
   *
   * Отдельно от собственного парка (`ownOptions` ниже) не ради симметрии: заявку закрывают и
   * арендной машиной, и фильтр обязан её находить, — а рейс ведётся и лист выписывается только на
   * свою. Общий ключ подсунул бы одному из двух мест чужой состав. Параметров нет: выборка одна
   * на портал.
   */
  allOptions: () => ['all-options'],
  /**
   * Собственный парк целиком — фильтры маршрутов и журнала листов, отбор вкладки чеков на
   * запчасти и поле машины в строке чека.
   *
   * Только `own`: рейс ведётся, лист выписывается и чек оформляется лишь на свою машину — арендную
   * ведёт арендодатель, и в этих списках её не бывает вовсе. Списанная и стоящая в ремонте из
   * перечня не убираются: вчерашние рейсы, выданные листы и оплаченные чеки никуда не делись, а
   * отбор, не находящий собственной строки списка, читается как поломка.
   *
   * Один ключ на всех спрашивающих, потому что вопрос у них дословно один; вторая ячейка означала
   * бы вторую копию списка, переживающую переименование машины. И один носитель у ключа: пока их
   * было два — семейство в слайсе чеков и литерал на странице заказов, — ячейка была общей только
   * по набранным буквам, и разойтись им было нечем помешать.
   */
  ownOptions: () => ['own-options'],
  /**
   * Заказанный вид целиком — первая из двух страниц окна назначения. Почему страниц две, сказано
   * у самих запросов (`widgets/vehicle-assignment-dialog`): в 500 строк парк не
   * помещается, и обрезалось бы как раз заказанное.
   *
   * Вид в ключе обязателен: по нему сервер и отбирает, а ключ, о виде не знающий, отдал бы окну
   * страницу, посчитанную для соседней заявки. `null` приходит, пока заявка не открыта, — запрос
   * тогда выключен (`enabled`), но ключ собирается всё равно, и подставлять вместо `null` сегмент
   * `'all'` нельзя: это ключ второго запроса того же окна, и окно прочло бы собственный ответ на
   * другой вопрос.
   */
  forAssignment: (vehicleKindId: string | null) => ['for-assignment', vehicleKindId],
  /**
   * Вторая страница того же окна — парк без отбора по виду. Ключ соседний, а не общий: два
   * запроса живут рядом и отвечают разным, и под одним ключом один затирал бы другой.
   */
  forAssignmentWholeFleet: () => ['for-assignment', 'all'],
  /** The active own fleet serves route creation, day assignment and ESM-2 issuance. */
  ownActiveOptions: () => ['own-active-options'],
  /**
   * Парк целиком, включая списанную и стоящую в ремонте технику, — окну коррекции рейса задним
   * числом: исправляют как раз ту единицу, которую с тех пор вывели из строя.
   *
   * Два сегмента вместо одного — форма, как её собрал экран; соседние выборки обходятся одним, и
   * выглядит она случайной. Оставлена как есть: сегмент — это ячейка кэша.
   */
  ownForCorrection: () => ['own', 'correction'],
});

/**
 * Марки/модели — под СВОИМ корнем, а не семейством внутри `['vehicles']`.
 *
 * Так его собрал экран, и по существу это верно: модели наполнены миграцией и только на чтение
 * (ADR 0007), правки машин их не трогают вовсе. Под корнем техники список перечитывался бы после
 * каждого сохранения карточки — ради данных, которые от неё не зависят. Обратной заботы тоже нет:
 * гасить этот корень некому и незачем, портал моделей не пишет.
 */
export const vehicleModelKeys = createQueryKeys('vehicle-models', {
  /**
   * Марки/модели выбранного типа для поля карточки машины. Тип в ключе обязателен: одинаковое имя
   * у разных типов — разные записи (ADR 0007), и общий ключ предложил бы машине чужие марки.
   *
   * `undefined` допустим: форма живёт и до выбора типа — запрос тогда выключен (`enabled`), но
   * ключ собирается всё равно, и подставлять вместо `undefined` пустую строку нельзя — это была
   * бы другая ячейка кэша у формы, которая ничего не спрашивала.
   */
  forSelect: (vehicleTypeId: string | undefined) => ['for-select', vehicleTypeId],
});
