import { createQueryKeys, type Query } from '@shared/api';

/**
 * Ключи запросов парка машин.
 *
 * **Под корнем `['vehicles']` живут ключи трёх ЧУЖИХ слайсов**, и это не недосмотр переноса.
 * Срез парка нужен экрану соседа, а импортировать сущность из сущности граница слоя не даёт —
 * значит ключ остаётся у того, кто его спрашивает. Корень при этом наш намеренно: все три среза
 * собраны из карточек техники и устаревают от правок справочника, а гасят их `['vehicles']`; под
 * своими корнями их пришлось бы гасить руками из чужого модуля — и забыли бы ровно тогда, когда в
 * списке осталась списанная машина. Адреса, по которым за ними идти:
 *
 * - `['vehicles', 'own-options']` — `ownVehicleKeys.options()` в
 *   `apps/web/src/entities/auto-part-receipt/api/keys.ts`. Тем же литералом собран фильтр
 *   маршрутов и журнала листов (`apps/web/src/pages/vehicle/shared.tsx`): это одна ячейка кэша на
 *   двоих, и потому своего `ownOptions` здесь нет — ключ, описанный в двух местах, разошёлся бы
 *   молча, а разойдясь, развёл бы один список по двум ячейкам;
 * - `['vehicles', 'trailer-hitch-targets']` — `trailerHitchTargetsKey` в
 *   `apps/web/src/entities/vehicle-trailer/api/keys.ts`;
 * - `['vehicles', 'fuel-norm-picker']` — `fuelNormVehiclePickerKey` в
 *   `apps/web/src/entities/fuel-norm/api/keys.ts`.
 *
 * Четвёртое совпадение по буквам — мнимое, и в этот список не входит: `garageKeys.vehicles` из
 * `apps/web/src/entities/garage/api/keys.ts` описан семейством под корнем `garage`, полный ключ у
 * него `['garage', 'vehicles', отбор]`, и наш корень его не накрывает — префиксное сравнение
 * сличает сегменты с начала. Гараж гасят отдельной строкой рядом с нашей, и почему — сказано
 * там же.
 *
 * Отсюда цена двух будущих правок. «Погасить всё по корню» здесь гасит и три чужих среза —
 * сегодня так и надо. А вот переименование корня или его разделение обязано пройти по трём
 * адресам выше: иначе переименуется наш кэш, чужие срезы останутся висеть под прежним именем, и
 * гасить их после правки машины станет нечем — портал покажет списанную машину в списке выбора.
 *
 * Формы ключей повторяют то, что экраны собирают литералами, до сегмента: перенос не сдвигает ни
 * одной ячейки кэша. Где нынешняя форма выглядит случайной, это сказано прямо, а не исправлено
 * молча — правка кэша заметна человеку и делается отдельно от переноса.
 */
export const vehicleKeys = createQueryKeys('vehicles', {
  /**
   * Вкладка «Техника» справочника: отбор целиком, как его собрал экран.
   *
   * Сегмента с именем семейства у списка нет — ключ так и остаётся `['vehicles', отбор]`. Это не
   * забытая `list`: сегмент сменил бы ячейку кэша единственному экрану справочника, ничего при
   * этом не починив, — корень `['vehicles']` и сейчас накрывает список вместе со всеми выборками.
   *
   * Отбор объектом целиком, а не полями врозь: новый фильтр вкладки попадает в ключ сам, а
   * перечисленный руками список однажды забыли бы дополнить — и вкладка показала бы прежние
   * строки под новым фильтром.
   */
  list: (params: Query) => [params],
  /**
   * Весь парк для фильтра «назначенная машина» в списке заказов и журнале закрытых (ADR 0098).
   *
   * Отдельно от собственного парка (`['vehicles', 'own-options']`, чужой адрес выше) не ради
   * симметрии: заявку закрывают и арендной машиной, и фильтр обязан её находить, — а рейс ведётся
   * и лист выписывается только на свою. Общий ключ подсунул бы одному из двух мест чужой состав.
   * Параметров нет: выборка одна на портал.
   */
  allOptions: () => ['all-options'],
  /**
   * Заказанный вид целиком — первая из двух страниц окна назначения. Почему страниц две, сказано
   * у самих запросов (`apps/web/src/pages/vehicle/VehicleAssignModal.tsx`): в 500 строк парк не
   * помещается, и обрезалось бы как раз заказанное.
   *
   * Вид в ключе обязателен: по нему сервер и отбирает, а ключ, о виде не знающий, отдал бы окну
   * страницу, посчитанную для соседней заявки. `null` приходит, пока заявка не открыта, — запрос
   * тогда выключен (`enabled`), но ключ собирается всё равно, и подставлять вместо `null` сегмент
   * `'all'` нельзя: это ключ второго запроса того же окна, и окно прочло бы собственный ответ на
   * другой вопрос.
   */
  forAssignment: (vehicleKindId: string | null) => ['for-assignment', vehicleKindId],
  /**
   * Вторая страница того же окна — парк без отбора по виду. Ключ соседний, а не общий: два
   * запроса живут рядом и отвечают разным, и под одним ключом один затирал бы другой.
   */
  forAssignmentWholeFleet: () => ['for-assignment', 'all'],
  /** Собственный действующий парк для окна заведения рейса: лист на арендную выписывает арендодатель. */
  forRoutes: () => ['for-routes'],
  /**
   * Собственный действующий парк окна дня линейного заказа.
   *
   * Запрос совпадает с `esm2Issue` до буквы — тот же отбор и та же сортировка, — а ключи разные,
   * и это сегодняшний факт, а не решение: так их собрали два окна, и портал ходит за одним
   * списком дважды. Слить их можно, но это смена ячейки кэша, а не перенос: правка отдельная и
   * видимая на экране.
   */
  linearDay: () => ['linear-day'],
  /** Тот же собственный действующий парк — окну выписки ЭСМ-2 по требованию (см. `linearDay`). */
  esm2Issue: () => ['esm2-issue'],
  /**
   * Парк целиком, включая списанную и стоящую в ремонте технику, — окну коррекции рейса задним
   * числом: исправляют как раз ту единицу, которую с тех пор вывели из строя.
   *
   * Два сегмента вместо одного — форма, как её собрал экран; соседние выборки обходятся одним, и
   * выглядит она случайной. Оставлена как есть: сегмент — это ячейка кэша.
   */
  ownForCorrection: () => ['own', 'correction'],
});

/**
 * Марки/модели — под СВОИМ корнем, а не семейством внутри `['vehicles']`.
 *
 * Так его собрал экран, и по существу это верно: модели наполнены миграцией и только на чтение
 * (ADR 0007), правки машин их не трогают вовсе. Под корнем техники список перечитывался бы после
 * каждого сохранения карточки — ради данных, которые от неё не зависят. Обратной заботы тоже нет:
 * гасить этот корень некому и незачем, портал моделей не пишет.
 */
export const vehicleModelKeys = createQueryKeys('vehicle-models', {
  /**
   * Марки/модели выбранного типа для поля карточки машины. Тип в ключе обязателен: одинаковое имя
   * у разных типов — разные записи (ADR 0007), и общий ключ предложил бы машине чужие марки.
   *
   * `undefined` допустим: форма живёт и до выбора типа — запрос тогда выключен (`enabled`), но
   * ключ собирается всё равно, и подставлять вместо `undefined` пустую строку нельзя — это была
   * бы другая ячейка кэша у формы, которая ничего не спрашивала.
   */
  forSelect: (vehicleTypeId: string | undefined) => ['for-select', vehicleTypeId],
});
