import type {
  DiscrepancyResolveInput,
  DriverReportDto,
  ReadingExportKind,
  ReadingIntakeDto,
  ReadingRebaseInput,
  ReportAcceptBatchDto,
  ReportAcceptBatchInput,
  ReportItemOrderInput,
  ReportSubmitBody,
  VehicleReadingCardDto,
  VehicleReadingJournalDto,
  VehicleReadingStatsRow,
} from '@technic/contracts';
import { apiDownload, apiFetch, type Query } from '@shared/api';

/**
 * Клиент модуля показаний (ADR 0103, Р27): журнал одной машины, её карточка за период, сводка по
 * парку, реестр приёма и сам отчёт дня — со всем, что с ним делают из гаража.
 *
 * Формы ответов сюда не переписываются — они описаны в `@technic/contracts` (Р20), и сервер отдаёт
 * ровно их. Отчёт дня отвечает одним и тем же `DriverReportDto` на все четыре свои ручки: открыть,
 * внести, принять, перечитать. Это не совпадение и не экономия — состояние после действия и есть
 * ответ на него, и портал никогда не показывает результат, снятый вторым запросом.
 *
 * Ветка `/driver` рядом не лежит намеренно: там второй контур со своей узкой областью («свой
 * человек») и своим окном записи, здесь — работа персонала над чужими днями под
 * `vehicleReadings.write`.
 */

/**
 * Ответ сводки. Единственный тип слайса, не пришедший из контрактов: сервер собирает его прямо в
 * ручке (`routes/vehicle-readings-stats.ts`), и общего имени у формы пока нет. Строка сводки при
 * этом контрактная — расходится только обёртка с границами периода.
 */
export interface VehicleReadingStatsDto {
  items: VehicleReadingStatsRow[];
  from: string;
  to: string;
}

/** Общий префикс модуля: журнал, карточка, сводка и приём — его данные, гараж их только показывает. */
const BASE = '/vehicle-readings';

export const vehicleReadingsApi = {
  journal: (vehicleId: string, query: Query) =>
    apiFetch<VehicleReadingJournalDto>(`${BASE}/journal/${vehicleId}`, { query }),
  /**
   * Карточка машины: итог периода, его месяцы и последние показания счётчиков на конец периода
   * (Р16). Блока ТО в ответе нет намеренно — сводка обслуживания приходит своей ручкой под своим
   * правом, и полную карточку портал собирает композицией двух ответов (Р14а).
   */
  card: (vehicleId: string, query: Query) =>
    apiFetch<VehicleReadingCardDto>(`${BASE}/vehicles/${vehicleId}/card`, { query }),
  stats: (query: Query) => apiFetch<VehicleReadingStatsDto>(`${BASE}/stats`, { query }),
  /**
   * Реестр приёма за период: страница строк с пометками, отчёты периода целиком и серверное
   * «сегодня» (Р23). Отчёты приходят все, а не только те, чьи строки видны: пригодность к пакету
   * считается по всему отчёту (Р9а), и кнопка приёма берёт их отсюда, а не из строк страницы.
   */
  intake: (query: Query) => apiFetch<ReadingIntakeDto>(`${BASE}/intake`, { query }),
  /** Отчёт дня целиком: состав, расхождения и готовые причины, почему принять нельзя. */
  report: (reportId: string) => apiFetch<DriverReportDto>(`${BASE}/reports/${reportId}`),
  /**
   * Открыть отчёт за работника (Р26). Нужно с первого дня и ровно тем дням, которых нет: у части
   * водителей учётки не будет ещё долго, а показания их машин гаражу нужны тогда же, когда и
   * остальные. Строки ожидания заводит сервер по источникам дня — портал их состава не выдумывает.
   */
  openDay: (personId: string, date: string) =>
    apiFetch<DriverReportDto>(`${BASE}/reports/${personId}/${date}/open`, { method: 'POST' }),
  /**
   * Внести или поправить показания за работника. Причину проверяет сервис, а не схема: пустая
   * законна, пока строку заполняют впервые, и обязательна там, где правят уже сданное число.
   */
  submitDay: (personId: string, date: string, body: ReportSubmitBody) =>
    apiFetch<DriverReportDto>(`${BASE}/reports/${personId}/${date}/submit`, {
      method: 'POST',
      body,
    }),
  /**
   * Приём одного дня. Версия в теле — та, которую видел принимающий: приём подтверждает данные, а
   * не факт нажатия, и разошедшаяся версия означает, что подтверждать собирались другое.
   */
  accept: (reportId: string, version: number) =>
    apiFetch<DriverReportDto>(`${BASE}/reports/${reportId}/accept`, {
      method: 'POST',
      body: { version },
    }),
  /**
   * Пакетный приём отчётов (Р9): одна ручка, N транзакций. Версия отправляется по каждому отчёту —
   * принимают то, что видели, — и отказ по одному не отменяет приёма остальных: непринятые
   * возвращаются списком с готовой причиной.
   */
  acceptBatch: (reports: ReportAcceptBatchInput['reports']) =>
    apiFetch<ReportAcceptBatchDto>(`${BASE}/reports/accept-batch`, {
      method: 'POST',
      body: { reports },
    }),
  /**
   * Разбор расхождения (ADR 0103, решение 10). Журнал решений append-only: прежнее решение не
   * переписывается, а перекрывается следующим, и действует последнее — по версии отчёта, а не по
   * времени записи. Поэтому «изменить решение» — это такая же запись, как первая, и отдельной
   * ручки правки у неё нет и быть не должно.
   *
   * Отпечаток уходит обратно нетронутым: решение действует, пока сравниваемые поля те же, и
   * подменить его порталом значило бы подтвердить не то, что показывали.
   */
  resolveDiscrepancy: (reportId: string, body: DiscrepancyResolveInput) =>
    apiFetch<DriverReportDto>(`${BASE}/reports/${reportId}/discrepancies`, {
      method: 'POST',
      body,
    }),
  /**
   * Порядок смен машины за день (ADR 0103, решение 3).
   *
   * Адрес у ручки не отчётный, и это существенно: позиция смены принадлежит паре «машина + день», а
   * не отчёту — две смены одной машины бывают у двух разных работников, то есть в двух отчётах.
   * Поэтому уходит полный порядок вместе с ожидаемым прежним и версиями **всех** затронутых
   * отчётов: перестановка меняет чужие разности, и два диспетчера не должны молча перезаписывать
   * её друг у друга. Ответ — все отчёты, которых она коснулась.
   */
  reorderShifts: (body: ReportItemOrderInput) =>
    apiFetch<DriverReportDto[]>(`${BASE}/shift-order`, { method: 'PATCH', body }),
  /**
   * Привести снимок к источнику (ADR 0103, решение 11): рейс переназначили после отправки, и
   * строка вместе с показанием переезжает в отчёт того, кто по документу ехал. Отвечает **целевой**
   * отчёт — тот, куда строка уехала, а не тот, из которого её взяли.
   */
  rebaseItem: (itemId: string, body: ReadingRebaseInput) =>
    apiFetch<DriverReportDto>(`${BASE}/items/${itemId}/rebase`, { method: 'POST', body }),
  /**
   * Выгрузка книгой (Р18): ручка одна на все шесть вариантов, вариант едет параметром `?kind=`.
   *
   * Шесть ручек здесь были бы шестью способами задать один и тот же вопрос «покажи период книгой», а
   * различаются они только раскладкой листов — состав данных считает тот же агрегат. Период уходит
   * тот, что показан на экране: выгружают то, на что смотрят, и второй период в окне выгрузки
   * означал бы, что книга и таблица отвечают про разные отрезки.
   *
   * `vehicleId` в `query` кладёт вызывающий — по `readingExportNeedsVehicle`; клиент его не
   * подставляет, потому что «какая машина выбрана» знает экран, а не транспорт. Лишний параметр
   * сервер отвергает схемой, а не игнорирует (`readingExportQuerySchema`), — и это правильно:
   * «журнал всего парка по машине А123БВ777» звучит как отбор, которого не произойдёт.
   *
   * Имя файла приходит от сервера заголовком `content-disposition` (он один знает, какой период и
   * какая машина внутри), здесь только запасное — на случай, если заголовок потеряется по дороге.
   */
  exportBook: (kind: ReadingExportKind, query: Query) =>
    apiDownload(`${BASE}/export`, 'Показания техники.xlsx', { query: { ...query, kind } }),
};
