import { createQueryKeys, type Query } from '@shared/api';

/**
 * Ключи запросов показаний техники (ADR 0103; план «Показания техники», Р19).
 *
 * Корень один на весь модуль, и это его главное свойство. Приёмка меняет те же числа, которые
 * показывают сводка, карточка машины и журнал: правку показания за водителя вносят ровно там же,
 * где день принимают (Р27). Значит после приёма достаточно погасить `vehicleReadingKeys.root` —
 * префиксное сравнение TanStack Query накроет все три семейства разом, и ни одному экрану не
 * придётся знать ключи соседа. Разведи их по корням — и статистика, открытая рядом с реестром,
 * показывала бы вчерашние цифры до перезагрузки страницы.
 *
 * Семейства при этом разные, и разводить их обязательно: у сводки период на весь парк, у карточки
 * и журнала — своя машина, а у журнала ещё и страница (Р25). Под общим ключом карточка затирала бы
 * сводку — кто спросил вторым, тот и определил бы ответ обоим.
 *
 * Машина стоит отдельным сегментом, а не внутри параметров: `['vehicle-readings', 'card', id]`
 * гасит карточку одной машины, не трогая остальные, — этим и пользуется приём, когда исправили
 * показание по одной единице техники.
 */
export const vehicleReadingKeys = createQueryKeys('vehicle-readings', {
  journal: (vehicleId: string, params: Query) => ['journal', vehicleId, params],
  stats: (params: Query) => ['stats', params],
  card: (vehicleId: string, params: Query) => ['card', vehicleId, params],
  /**
   * Реестр приёма: период со страницей (Р25). Машины в ключе нет — реестр отвечает про весь парк
   * сразу, и семейство у него своё: страница строк приёма и сводка парка за тот же период — разные
   * ответы, и под общим ключом второй затирал бы первый.
   */
  intake: (params: Query) => ['intake', params],
  /**
   * Отчёт дня, открытый на разбор (`?report=`, Р29). Отдельное семейство от реестра, потому что
   * это другой ответ: реестр знает про отчёт три числа (состояние и счётчики строк), а карточке
   * нужен состав, расхождения и блокеры приёма — то есть весь `DriverReportDto`.
   *
   * Отчёт стоит сегментом, как машина у карточки: правка одного дня не обязана гасить соседние.
   * Гасится при этом всё равно корень (Р19) — приём и правка меняют числа сводки и журнала, — но
   * ключ обязан позволять и точечное перечитывание: после 409 перечитывают именно этот отчёт.
   */
  report: (reportId: string) => ['report', reportId],
});
