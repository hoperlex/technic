/**
 * Сессия портала: вход и выход, регистрация, подтверждение адреса, восстановление и смена пароля —
 * ручки, которыми человек заводит свою работу в портале и заканчивает её. Снаружи берут
 * `@entities/session` — внутренние модули слайса не видны, и перестроить его можно, не трогая
 * потребителей.
 *
 * Слайс отделён не потому, что у ручек общий префикс `/auth`, а потому, что он один знает, каким
 * событием сессии является каждая из них. Сам механизм — токен в памяти, номер поколения и обрыв
 * висящего обновления — живёт в `@shared/api` (`session.ts`), и второго его носителя здесь нет:
 * `authApi` ничего не хранит, он зовёт `startSession` после входа, `renewToken` после смены пароля
 * и `clear` после выхода. Различие между этими тремя вызовами доменное, и фундаменту оно
 * недоступно: транспорт не знает, что `/auth/login` — это другой человек, а `/auth/change-password`
 * — тот же. Перепутав их, портал либо признал бы своим обновление токена прежней сессии, либо
 * начал бы новое поколение там, где сессия не менялась, — а при выходе оставил бы токен в памяти
 * вкладки. Поэтому ручки лежат здесь, а состояние — в фундаменте.
 *
 * Выход чистит вкладку ДВАЖДЫ, и это страховка, а не недосмотр: `logout` здесь зовёт `clear` после
 * успешного ответа, а `AuthContext.logout` глотает отказ сети и зовёт `clear` всё равно. Иначе
 * человек, нажавший «выйти» при недоступном сервере, остался бы во вкладке вошедшим. Вызов
 * идемпотентен — поколение монотонно, токен уже пуст, — так что цена страховки нулевая, а вот
 * обратное однажды подвело: серверные комментарии о гейтах ссылались на «чистит только после
 * успешного ответа» и на этом строили вывод ручки из-под гейта.
 *
 * `api/keys.ts` в слайсе нет, и это решение, а не пропуск: учётку не кэширует react-query. Её
 * читают ровно двое — bootstrap вкладки и обновление после смены прав, — и держит её состоянием
 * `AuthProvider`, который при любой смене сессии гасит кэш целиком. Заведённый корень `['auth']`
 * был бы ячейкой, которую никто не наполняет и никто не гасит, — вторым местом того же правила.
 */
