import { createQueryKeys, type Query } from '@shared/api';

/**
 * Ключи запросов заявок на аренду механизации (план `docs/mechanization-module-plan.md`).
 *
 * Семейства разведены по виду вопроса, а не по экрану: список со своими фильтрами, карточка по
 * идентификатору (её открывают ссылкой, минуя список), история заявки, сводка над списком и
 * подсказка ранее вводившихся видов техники. Под общим ключом карточка, открытая из архива,
 * затирала бы страницу рабочего списка — кто спросил вторым, тот и определил бы ответ обоим.
 *
 * Сводка — семейство внутри заявок, а не свой корень: её четыре числа считаются по тем же
 * заявкам теми же предикатами Р2 и устаревают от тех же событий. Свой корень означал бы шапку,
 * которая после отметки выдачи продолжает показывать заявку «ждущей подачи».
 *
 * Подсказка видов (Р5) — тоже семейство внутри: перечень строится по области списка и по самим
 * заявкам, и заведение новой заявки с невиданным раньше видом обязано его пополнить.
 */
export const mechRequestKeys = createQueryKeys('mech-requests', {
  list: (params: Query) => ['list', params],
  detail: (id: string) => ['detail', id],
  history: (id: string) => ['history', id],
  summary: (params: Query) => ['summary', params],
  kinds: (search: string) => ['kinds', search],
});

/**
 * Арендодатели механизации — контрагенты двух типов сразу (Р6).
 *
 * Свой корень, а не семейство внутри заявок: перечень живёт справочником контрагентов и от хода
 * аренд не зависит. Общий корень означал бы, что каждая отметка выдачи гасит список
 * арендодателей, а правка карточки контрагента — все открытые списки заявок.
 *
 * Слайса контрагентов в портале ещё нет (справочник ведётся страницей на старом API), поэтому
 * ключ временно живёт здесь — рядом с единственным местом, которому этот перечень нужен. То же
 * решение и по той же причине принято у сервисных компаний оргтехники.
 */
export const mechLessorKeys = createQueryKeys('mech-lessors', {
  options: () => ['options'],
});
