import { errorMessage } from '@shared/lib';

/**
 * Отказ по заявке на аренду словами, которые различают две совершенно разные беды (Р21).
 *
 * Сервер разводит их кодами намеренно: **409 — «данные под тобой изменились, перечитай
 * карточку»**, **422 — «правило запрещает это действие»**. Разница не академическая. Оба ответа
 * приходят на одно и то же нажатие, и человек ведёт себя по ним противоположно: после 409 нужно
 * закрыть окно, увидеть свежую заявку и решить заново (может быть, действие уже сделал сосед),
 * после 422 — не повторять вовсе, потому что правило не изменится от второй попытки.
 *
 * Слить их в общий `errorMessage` значило бы показать оба одинаково: «Конфликт версий» звучит как
 * поломка, а «Техника выдана 04.09» после гонки — как непонятный отказ на верное действие. Здесь
 * у 409 текст свой, объясняющий, что делать, а у остальных — сообщение сервера как есть: у 422
 * оно и написано для человека (`mechTransitionBlocker`, `MECH_DELETE_RUNNING_MESSAGE`), и
 * подменять его своим значило бы потерять названную причину.
 */
export const MECH_STALE_MESSAGE =
  'Заявку изменил кто-то ещё: закройте карточку и откройте заново — вы решаете по устаревшим данным';

function statusOf(error: unknown): number | null {
  return typeof error === 'object' && error !== null && 'status' in error
    ? Number((error as { status: unknown }).status)
    : null;
}

/** Отказ по устаревшей версии (409) — единственный, после которого действие стоит повторить. */
export function isMechStaleError(error: unknown): boolean {
  return statusOf(error) === 409;
}

/** Текст отказа для тоста и для строки в окне действия. */
export function mechFailureText(error: unknown): string {
  return isMechStaleError(error) ? MECH_STALE_MESSAGE : errorMessage(error);
}
