import type { LinearDayRef, RequestAssignmentHistoryDto, RequestStatus } from '@technic/contracts';

/**
 * Портальные ответы дверей: срока, закрытия и команды машиниста. В контрактах их нет и не будет —
 * пакет держит тела запросов и общие DTO, а эти три типа живут ровно между сервером и порталом.
 *
 * Собраны вместе, потому что описывают один инвариант, а не три разных ответа (Р9): дверь отвечает
 * СОСТОЯНИЕМ ЗАЯВКИ ПОСЛЕ КОМАНДЫ, а не отчётом о ней, — версией, которой продолжать, переписанной
 * бумагой и тем, что стало со сроком. Отсюда и второе их общее свойство: повтор по тому же ключу
 * операции отвечает то же самое, работы на нём не происходит вовсе, и видно это по `repeated`.
 * Объяснённый посреди ручек, инвариант повторялся бы у каждого из трёх типов заново — так он и
 * повторялся до разреза, и первая же правка развела бы три его пересказа.
 *
 * Наружу эти типы раздаёт `vehicleRequestsApi`, а не сами: публичный вход слайса один, и знать о
 * внутреннем разрезе потребителю незачем.
 */

/** Ответ двери срока (Р9). */
export interface VehicleRequestPeriodResultDto {
  version: number;
  /** true — операцию уже выполнял этот же ключ: работы не было, версия не тронута. */
  repeated: boolean;
  dateFrom: string;
  dateTo: string | null;
  /** Что переписала сверка ЭСМ-2: сгоревшие и выписанные номера. */
  esm2: { cancelled: string[]; issued: string[] };
  /** Снят ли ожидавший визы запрос на досрочное завершение (ADR 0044). */
  earlyEndDropped: boolean;
  /** Ключ операции журнала; `null` — исход `none`, объяснять нечего (Р32). */
  operationId: string | null;
  history: RequestAssignmentHistoryDto;
}

/**
 * Ответ двери закрытия (Р9 плана периодов). Повтор по ключу виден здесь насквозь: срок, статус и
 * снимок закрытия читаются из базы и совпадают с первым ответом, а «что сгорело» и «что снято»
 * приходят пустыми.
 */
export interface VehicleRequestCompletionResultDto {
  version: number;
  /** true — операцию уже выполнял этот же ключ: работы не было, версия не тронута. */
  repeated: boolean;
  status: RequestStatus;
  /** Срок, каким он стал: у обычного закрытия конец равен фактической дате. */
  dateFrom: string;
  dateTo: string | null;
  /** Снимок закрытия: чем закрыли и что было. Оба пусты у арендодательской ветви (Р16). */
  endedOn: string | null;
  previousDateTo: string | null;
  /** Что переписала сверка: сгоревшие, выписанные и сокращённые номера. */
  esm2: { cancelled: string[]; issued: string[]; trimmed: string[] };
  /** Снят ли ожидавший визы запрос на досрочное завершение (ADR 0044). */
  earlyEndDropped: boolean;
  /** Дни, часы за которые закрытие удалило (Р10). */
  clearedShiftDays: string[];
  /** Дни линейного заказа, снятые с рейсов (Р11, Р27). */
  detachedDays: LinearDayRef[];
  /** Ключ операции журнала; `null` — исход `none`, объяснять нечего. */
  operationId: string | null;
}

/**
 * Ответ двери машиниста (Р9).
 *
 * Пересобирается из **текущего** состояния, поэтому повтор по тому же ключу операции отвечает то
 * же, что ответил бы обычный запрос. Переписанная бумага стоит рядом с историей намеренно: окно,
 * сделавшее смену, обязано узнать и то, чем продолжать (версия), и то, что случилось с номерами
 * бланков.
 */
export interface AssignmentCommandResultDto {
  version: number;
  /** true — операцию уже выполнял этот же ключ: работы не было, версия не тронута. */
  repeated: boolean;
  /** Что переписала сверка ЭСМ-2: сгоревшие и выписанные номера. */
  esm2: { cancelled: string[]; issued: string[] };
  history: RequestAssignmentHistoryDto;
}
