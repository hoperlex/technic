import { createQueryKeys } from '@shared/api';

/**
 * Ключи запросов заявок на технику — той их части, что относится к истории назначения (план
 * `docs/assignment-periods-plan.md`, §9).
 *
 * Заведены реестром, а не строками в окнах, по одной практической причине: историю читают четыре
 * экрана, а гасят её шесть мутаций из разных файлов, и разойдись они хоть одним словом — «Состав
 * по датам» показывал бы прежние отрезки после собственной же смены машиниста. Ошибка при этом
 * молчаливая: запрос не падает, он просто отвечает старым.
 *
 * `root` гасят все мутации модуля: смена машиниста, правка срока и ремонт меняют версию заявки, а
 * её показывают списки, которым про историю ничего не известно.
 */
export const vehicleRequestKeys = createQueryKeys('vehicle-requests', {
  /** История назначения заявки: из неё портал строит «Состав по датам». */
  history: (id: string) => [id, 'assignment-changes'],
  /** Осмотр двери ремонта: что в истории чинить (подэтап 6a). */
  repairState: (id: string) => [id, 'repair-state'],
  /** Последствия правки срока: ключ несёт саму команду — другой срок это другой ответ. */
  periodPreview: (id: string, command: unknown) => [id, 'period-preview', command],
});

/**
 * Путевые листы. Живут отдельным корнем, а не внутри заявки: лист заводится и от рейса, и от
 * недельной сверки, — но гасят его те же команды истории, потому что разрез переписывает бумагу.
 *
 * Лежат в ЧУЖОМ слайсе временно: ручки журнала уже уехали в `entities/waybill`, ключ едет следом,
 * отдельной правкой, и реэкспорта здесь не останется. Соблазн оставить реэкспорт ради пяти окон,
 * которые берут ключ отсюда, — единственный способ завести здесь импорт соседа по слою, который
 * границы запрещают; без него окна просто берут два ключа из двух слайсов, будучи выше обоих
 * (frontend-fsd-stage-2.md §2.5: в слайсе — только своё).
 *
 * Пятью окнами работа не ограничится, и это стоит знать заранее: журнал гасят ещё полтора десятка
 * мест литералом `['waybills']`, а списка журнала у ключа нет вовсе — `WaybillsPage` читает
 * `['waybills', отбор]` строкой. Переезд ключа — это семейство `list` плюс около двадцати точек,
 * а не пять импортов.
 */
export const waybillKeys = createQueryKeys('waybills', {});
