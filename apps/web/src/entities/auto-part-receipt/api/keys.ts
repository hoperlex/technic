import { createQueryKeys, type Query } from '@shared/api';

/**
 * Ключи запросов чеков на автозапчасти (план `docs/auto-part-receipts-plan.md`, Р18).
 *
 * Корень свой, а не семейство внутри гаража: у чеков своя ручка, своё право на ведение
 * (`autoParts.manage`) и своя жизнь. Окажись они под корнем гаража, шаг по дням среза гасил бы
 * ленту чеков, а заведённый чек — занятость машин на площадках. Ни то, ни другое не верно: числа
 * у этих ответов разные и устаревают они в разные моменты.
 *
 * Семейств пять, и разводить их обязательно — вопросы у них разные, а под общим ключом кто спросил
 * вторым, тот и определил бы ответ обоим:
 *
 * - `list` — лента вкладки с её отбором, страницей и порядком;
 * - `summary` — четыре числа под фильтрами: тот же отбор, но без страниц и сортировки (§8);
 * - `detail` — карточка чека целиком: строки и сканы приходят только ею, в ленте их нет (§6);
 * - `snapshot` — суммы пакетом на видимую страницу «Техники» (Р14): целая страница гаража, а не
 *   одна машина, — под общим с окном ключом карточка машины затирала бы снимок страницы;
 * - `vehicle-spend` — окно «Запчасти машины» и блок её карточки (Р15, Р16): машина в ключе стоит
 *   **перед** параметрами, чтобы период окна не мешал гасить всё, что относится к одной машине.
 *
 * Семейства с параметрами продублированы ключом-префиксом (`lists`, `summaries`, `snapshots`,
 * `vehicleSpends`) — им и гасят: страниц и периодов в кэше сколько угодно, и перечислить их
 * мутация не может. Префиксное сравнение TanStack Query накрывает их разом.
 */
export const autoPartReceiptKeys = createQueryKeys('auto-part-receipts', {
  /** Все страницы ленты при любом отборе — префикс для гашения. */
  lists: () => ['list'],
  list: (params: Query) => ['list', params],
  /** Сводка при любом отборе — префикс для гашения. */
  summaries: () => ['summary'],
  summary: (params: Query) => ['summary', params],
  detail: (id: string) => ['detail', id],
  /** Снимок сумм при любом наборе машин и дне среза — префикс для гашения. */
  snapshots: () => ['snapshot'],
  snapshot: (params: Query) => ['snapshot', params],
  /** Всё, что портал знает про траты на одну машину, при любом периоде — префикс для гашения. */
  vehicleSpends: (vehicleId: string) => ['vehicle-spend', vehicleId],
  vehicleSpend: (vehicleId: string, params: Query) => ['vehicle-spend', vehicleId, params],
});

/**
 * Что именно изменила мутация — вход матрицы Р18.
 *
 * Два случая, а не один, потому что пометка на удаление **не меняет цифр** (Р12): чек с пометкой
 * виден в списке и целиком входит в суммы по машинам. Гасить из-за неё окно машины значило бы
 * обещать, что пометка что-то пересчитывает.
 */
export type AutoPartReceiptCacheChange =
  /**
   * Заведение, правка и удаление чека. `vehicleIds` — все затронутые машины: и те, что в чеке
   * сейчас, и те, из которых строку убрали правкой. Вторые обязательны — иначе окно машины, у
   * которой позицию отобрали, продолжало бы показывать её в перечне и в итоге.
   */
  | { kind: 'write'; id: string; vehicleIds: readonly string[] }
  /** Пометка на удаление и её снятие: список, сводка и карточка этого чека — и больше ничего. */
  | { kind: 'mark'; id: string };

/**
 * Матрица инвалидации Р18 одним местом.
 *
 * Одним местом, а не строками по вызову, ровно потому, что мест вызова пять — форма заведения,
 * форма правки, пометка, снятие пометки и удаление, — и «погасим заодно соседа» в каждом из них
 * разъехалось бы с матрицей на первой же правке. Возвращаются готовые ключи, а не действие над
 * кэшем: слой сущностей не знает, у кого именно клиент запросов, и звать его должен тот, кто
 * держит мутацию.
 *
 * ```ts
 * for (const queryKey of autoPartReceiptInvalidation({ kind: 'write', id, vehicleIds })) {
 *   void qc.invalidateQueries({ queryKey });
 * }
 * ```
 */
export function autoPartReceiptInvalidation(
  change: AutoPartReceiptCacheChange,
): readonly (readonly unknown[])[] {
  const always = [
    autoPartReceiptKeys.lists(),
    autoPartReceiptKeys.summaries(),
    autoPartReceiptKeys.detail(change.id),
  ];
  if (change.kind === 'mark') return always;
  return [
    ...always,
    // Колонка «Запчасти, ₽» вкладки «Техника»: она считается по тем же строкам (Р14).
    autoPartReceiptKeys.snapshots(),
    // Дубли в наборе законны — одну машину чек называет несколькими строками; гасить её дважды
    // незачем, а два одинаковых ключа обошлись бы двумя обходами кэша.
    ...[...new Set(change.vehicleIds)].map((id) => autoPartReceiptKeys.vehicleSpends(id)),
  ];
}

/**
 * Ключ перечня собственной техники для отбора вкладки.
 *
 * Живёт здесь по той же причине и с той же оговоркой, что ключ арендодателей механизации: своего
 * слайса у справочника техники в портале ещё нет (он ведётся страницей на старом API), а перечень
 * нужен ровно одному экрану — фильтру «машина» на вкладке чеков.
 *
 * Корень — `vehicles`, и это не небрежность: ключ совпадает с тем, которым уже живёт такой же
 * перечень в заказах техники, то есть попадает в тот же кэш и гаснет вместе с ним от правок
 * справочника (`['vehicles']`). Свой корень означал бы вторую копию списка, переживающую
 * переименование машины.
 */
export const ownVehicleKeys = createQueryKeys('vehicles', {
  options: () => ['own-options'],
});
