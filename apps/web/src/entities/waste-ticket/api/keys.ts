import type { TicketAuditEventsQuery, TicketAuditPeriod } from '@technic/contracts';
import { createQueryKeys } from '@shared/api';

/**
 * Ключи запросов разбора талонов.
 *
 * Список талонов держится за заявкой: экран разбора открывается из карточки, и обновиться после
 * подтверждения обязан именно он. Состояние подсистемы, наоборот, общее на портал — баннер один и
 * тот же над карточкой и над реестром, и спрашивать его дважды незачем.
 */
export const wasteTicketKeys = createQueryKeys('waste-tickets', {
  list: (requestId: string) => ['list', requestId],
  /** Очередь заданий перепроверки: общая на портал и своя у каждого — сервер убирает чужое. */
  blindQueue: () => ['blind-queue'],
  health: () => ['health'],
  /**
   * Сводка аудита распознавания (ADR 0137). Период — часть ключа, и обе его границы врозь: по
   * ним же считаются числа, и один ключ на все периоды показывал бы после смены дат прежнюю
   * выборку — то есть доли, посчитанные не за то время, которое подписано в шапке.
   */
  auditSummary: (period: TicketAuditPeriod) => ['audit', 'summary', period.from, period.to],
  /**
   * Второй экран того же отчёта — сигналы по производственным когортам (§5.2). Ключ свой, а не
   * общий со сводкой: экраны спрашивают разные ручки, и один ключ на двоих отдавал бы второму
   * экрану кэш первого — то есть чужую форму ответа под видом своей.
   */
  auditCohorts: (period: TicketAuditPeriod) => ['audit', 'cohorts', period.from, period.to],
  /**
   * Лента событий (§5.3). Ключ несёт ВЕСЬ отбор целиком — период, шесть фильтров и страницу:
   * каждый из них меняет выборку, и ключ, не знающий хотя бы одного, показал бы после смены
   * фильтра прежние строки под новой подписью.
   *
   * Объектом, а не перечислением ключей врозь: порядок полей в хэше TanStack Query не важен, зато
   * новый фильтр контракта попадает в ключ сам — а перечисленный руками список однажды забыли бы
   * дополнить, и ошибка вышла бы молчаливой.
   */
  auditEvents: (query: TicketAuditEventsQuery) => ['audit', 'events', query],
  /**
   * Точность среди неисправленных подтверждённых талонов (§5.5). Период в ключе по той же причине,
   * что у сводки: по нему считаются числа, и один ключ на все периоды показывал бы после смены дат
   * прежнюю выборку — то есть процент, посчитанный не за то время, которое подписано в шапке.
   *
   * Семейство названо `accuracy`, хотя ручка зовётся `blind`: ключ различает ЭКРАНЫ, и сосед по
   * ключу — `summary`, а не путь ручки. Совпади они, переезд ручки утащил бы за собой инвалидацию.
   */
  auditAccuracy: (period: TicketAuditPeriod) => ['audit', 'accuracy', period.from, period.to],
  /**
   * Состояние подсистемы (§5.4). Единственный ключ раздела БЕЗ периода — и это не экономия: у
   * ручки его нет вовсе (очередь — снимок «сейчас», вызовы — фиксированное окно, §1.3). Положи мы
   * период сюда «для единообразия», смена дат в календаре соседнего экрана гасила бы кэш ответа,
   * который от дат не зависит, — и портал ходил бы на сервер за одним и тем же.
   */
  auditOperations: () => ['audit', 'operations'],
});
