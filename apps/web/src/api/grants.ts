import type {
  AssignGrantInput,
  CreateGrantInput,
  GrantAssignmentPreviewInput,
  GrantAssignmentResultDto,
  GrantCardDto,
  GrantDto,
  GrantImpactDto,
  GrantUpdatePreviewInput,
  ListResult,
  Role,
  UpdateGrantInput,
} from '@technic/contracts';
import { apiFetch, createQueryKeys } from '@shared/api';
import { DICTIONARY_PAGE_SIZE } from '@shared/config';

/**
 * Ручки назначаемых полномочий (ADR 0106): каталог наборов, их выдача учётке и предпросмотр
 * последствий.
 *
 * Домен отделён от реестра ресурсов, потому что связан внутри себя жёстче, чем с чем-либо снаружи:
 * ключи кэша, обе ручки предпросмотра и обе боевые операции держатся одного правила — правка идёт
 * только с отпечатком того расчёта, который показали человеку. Правило это неочевидное, и
 * объяснено оно ровно один раз, здесь; разложенное по чужим соседям, оно объяснялось бы в каждом
 * втором комментарии заново.
 *
 * Адрес выдачи при этом принадлежит учётке (`/users/:id/grants`), а не каталогу, — и это тоже
 * причина держать оба конца рядом: разъедься они по файлам, вторая половина домена читалась бы как
 * чужая ручка учёток.
 *
 * Импорт через `api/resources` остаётся рабочим: реестр реэкспортирует всё, что здесь объявлено.
 */

/** Строка запроса: набор ключей у каждой ручки свой, общего в них — только форма. */
type Query = Record<string, unknown>;

/**
 * Ключи каталога полномочий. Карточка отдельным семейством от списка: реестр выдач перечитывается
 * после каждой выдачи и отзыва, а каталог — только когда меняется состав или число держателей, и
 * гасить его целиком ради одной строки реестра незачем. Корень при этом накрывает и то, и другое:
 * правка набора меняет обе выборки сразу.
 *
 * `formCatalog` — третье семейство, а не `list` с другими параметрами. Отбор у него не такой, как у
 * вкладки «Права»: список формы задаёт **выбранная в форме роль** (план «полномочия назначаются в
 * окне учётки», Р2), а каталог вкладки роли не спрашивает вовсе — там ведут наборы, а не выдают их.
 * Разная у них и форма ответа: `list` отдаёт страницу, `formCatalog` — каталог целиком с признаком
 * полноты (`GrantCatalog`), и одно семейство на два таких ответа означало бы, что запись одного
 * подсовывает другому чужой тип. Корень общий намеренно: правка набора обязана погасить и список
 * вкладки, и каталог формы — состав, который форма показала подсказкой, изменился.
 */
export const grantKeys = createQueryKeys('grants', {
  list: (params: Query) => ['list', params],
  card: (id: string) => ['card', id],
  formCatalog: (role: Role) => ['form-catalog', role],
});

/**
 * Каталог назначаемых полномочий (ADR 0106, этап 3; план §12) — именованные наборы прав, которые
 * выдаются учётке поверх её роли.
 *
 * Предпросмотр стоит рядом с правкой, а не спрятан в неё: он отвечает на «кого это затронет и что у
 * них изменится» до нажатия и выдаёт `expectedImpactHash` — отпечаток того, из чего расчёт посчитан.
 * Правка без отпечатка невозможна по схеме сервера, и это не формальность: между показом
 * предпросмотра и сохранением набор могли выдать ещё одному человеку либо сменить роль держателю, и
 * тогда применится не то, что подтверждали (решение 7).
 */
export const grantsApi = {
  list: (q: Query) => apiFetch<ListResult<GrantDto>>('/grants', { query: q }),
  /** Карточка вместе с реестром выдач: кому выдано, кем, когда и на чём. */
  get: (id: string) => apiFetch<GrantCardDto>(`/grants/${id}`),
  create: (body: CreateGrantInput) => apiFetch<GrantCardDto>('/grants', { method: 'POST', body }),
  /**
   * Что даст правка: дельта по каждому держателю, нарушения барьеров **в теле** и отпечаток.
   * Нарушения приходят ответом, а не отказом, — иначе экран потерял бы разом и дельту, и причину.
   */
  preview: (id: string, body: GrantUpdatePreviewInput) =>
    apiFetch<GrantImpactDto>(`/grants/${id}/preview`, { method: 'POST', body }),
  update: (id: string, body: UpdateGrantInput) =>
    apiFetch<GrantCardDto>(`/grants/${id}`, { method: 'PATCH', body }),
  /** Мягкое удаление: выданный набор сервер не отдаёт (409) — сначала отзыв выдач. */
  remove: (id: string) =>
    apiFetch<{ id: string; deleted: boolean }>(`/grants/${id}`, { method: 'DELETE' }),
};

/**
 * Выдача и отзыв набора учётке. Адрес — учётки, а не каталога: цель операции она, ей поднимается
 * `authVersion`, на неё пишется журнал. Отпечаток предъявляют обе операции, и у отзыва он уходит
 * строкой запроса: тело у `DELETE` доходит не через каждый прокси, а подтверждение обязано доходить
 * всегда.
 */
export const userGrantsApi = {
  preview: (userId: string, body: GrantAssignmentPreviewInput) =>
    apiFetch<GrantImpactDto>(`/users/${userId}/grants/preview`, { method: 'POST', body }),
  assign: (userId: string, body: AssignGrantInput) =>
    apiFetch<GrantAssignmentResultDto>(`/users/${userId}/grants`, { method: 'POST', body }),
  revoke: (userId: string, grantId: string, expectedImpactHash: string) =>
    apiFetch<GrantAssignmentResultDto>(`/users/${userId}/grants/${grantId}`, {
      method: 'DELETE',
      query: { expectedImpactHash },
    }),
};

/**
 * Каталог, отобранный ролью, — то, из чего окно учётки рисует галочки полномочий (план §6).
 *
 * **Признак полноты — не диагностика, а условие работы формы.** Тело правки декларативно: строка
 * `selected: false` про управляемое назначение означает «снять», а не названное назначение сервер
 * отклоняет правилом полноты (§4.2). Поэтому список, прочитанный наполовину, нельзя ни показать
 * молча, ни отправить: гидратация не увидела бы часть выданных наборов, тело сказало бы «их сняли»,
 * и правка телефона отозвала бы полномочия. С `complete: false` форма блокирует и поле полномочий,
 * и поле роли (молчание законно лишь пока роль не переключает действие назначений), а `grants` в
 * тело не кладёт вовсе.
 *
 * Голый массив ответить здесь было бы нечестно ровно тем, что неполнота выглядела бы как короткий
 * каталог — то есть как «наборов больше нет».
 */
export interface GrantCatalog {
  /** Совместимые с ролью наборы, по названию: список читают глазами. */
  items: GrantDto[];
  /** Каталог дочитан до конца: собрано не меньше строк, чем обещал `total` последнего ответа. */
  complete: boolean;
}

/**
 * Предел числа запросов за один заход — защита от бесконечного цикла, а не бюджет каталога.
 * Страницами по `DICTIONARY_PAGE_SIZE` он покрывает пять тысяч наборов, то есть на два порядка
 * больше, чем учётке вообще можно выдать (`MAX_ASSIGNED_GRANTS` = 32); упереться в него настоящим
 * каталогом нельзя, а вот ответ, где `total` всегда больше отданного, крутил бы цикл вечно.
 * Упёрлись — это `complete: false`, и форма скажет об этом человеку, а не молча покажет часть.
 */
const MAX_CATALOG_PAGES = 10;

/**
 * Чтение каталога для формы учётки. Не метод `grantsApi` намеренно: это не ручка, а несколько
 * запросов подряд, и стоящее в одном ряду с `list` чтение читалось бы как один обмен со страничным
 * ответом.
 */
export const grantFormApi = {
  /**
   * Каталог целиком, страницами по `DICTIONARY_PAGE_SIZE`, пока собранных строк меньше `total`.
   *
   * Размер страницы именно этот: `DEFAULT_PAGE_SIZE` (100) — умолчание страницы, а не обещание
   * полноты, и форме нужно второе. Отдельной ручки «все наборы» в проекте нет ни у одного
   * справочника, и заводить её ради одного экрана значило бы завести второй способ читать каталог
   * (§6).
   *
   * Порядок задаётся явно (`name` по возрастанию), а не оставляется умолчанию сервера (`desc`):
   * страницы склеиваются по смещению, и без устойчивой сортировки соседние отдали бы пересечение и
   * дыру. Повтор строки цикл всё же переживает — набор мог переехать между страницами, если его
   * правили прямо сейчас, — и такую строку он не удваивает.
   *
   * Отказ запроса наверх не глотается: у него своё состояние в `useQuery`, и поле блокируется по
   * нему. `complete: false` отвечает за другой случай — сервер ответил, но обещанного числа строк
   * так и не отдал.
   *
   * Роль `driver` здесь не отсеивается — как и в схеме запроса: наборов она не принимает вовсе, и
   * пустой каталог честнее отказа. Поля полномочий у водителя нет по другой причине (§6), и решает
   * это форма, а не чтение.
   */
  catalog: async (role: Role): Promise<GrantCatalog> => {
    const items: GrantDto[] = [];
    const seen = new Set<string>();
    for (let page = 1; page <= MAX_CATALOG_PAGES; page += 1) {
      const chunk: ListResult<GrantDto> = await grantsApi.list({
        page,
        pageSize: DICTIONARY_PAGE_SIZE,
        role,
        sortBy: 'name',
        sortOrder: 'asc',
      });
      for (const grant of chunk.items) {
        if (seen.has(grant.id)) continue;
        seen.add(grant.id);
        items.push(grant);
      }
      if (items.length >= chunk.total) return { items, complete: true };
      // Пустая страница при недобранном `total` — дальше читать нечего: строки исчезли между
      // запросами либо ответ противоречит сам себе. И то, и другое означает неполный список.
      if (chunk.items.length === 0) break;
    }
    return { items, complete: false };
  },
};
