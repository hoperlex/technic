/**
 * Что окно назначения техники говорит про человека: машиниста ЭСМ-2 и водителя рейса.
 *
 * Отдельным файлом от самого окна, и причина не в длине. `VehicleAssignModal` — это состояние
 * формы: ветки принадлежности, подстановки, сброс полей при смене заявки. Всё, что лежит здесь, —
 * формулировки и производные от ответов сервера: они ничего не решают и ни на что не смотрят,
 * кроме своих аргументов. Держать их вперемешку с формой значит читать полстраницы текста
 * подсказки, чтобы найти, где очищается поле.
 *
 * Тексты собраны в одном месте ещё и потому, что они друг про друга знают. Поле машиниста и поле
 * водителя рейса объясняют **одну и ту же** пустоту разными словами: пустое поле означает «не
 * меняли» (ADR 0083), и оба текста обязаны назвать того, кто останется, — иначе пустота читается
 * как «человека нет». Разъехавшись по файлам, они разошлись бы и формулировкой, а человек читает
 * их подряд, в одном окне.
 *
 * Чего здесь нет: ни одного запроса и ни одного `Form.useWatch`. Списки водителей, листы заявки и
 * выбранные значения приходят аргументами — иначе модуль пришлось бы звать хуком, и он перестал бы
 * быть тем, чем он является: набором чистых функций про формулировки.
 */

/**
 * Строка списка водителей. Порядок задал сервер: пригодные первыми — сперва комплект документов,
 * затем категория (ADR 0064, ADR 0055), внутри них работавшие на этой машине (ADR 0056). Пометки в
 * строке объясняют, почему человек там, — без них список выглядел бы сбитым алфавитом.
 */
export function driverOption(d: DriverOptionDto): { value: string; label: string } {
  return {
    value: d.personId,
    label: [
      d.fullName,
      d.categories.join(', '),
      d.personnelNo && `таб. ${d.personnelNo}`,
      // Пробелы подписаны тем документом, которым человек допущен по должности (ADR 0095):
      // «без номера ВУ» и «без номера УТМ» — разные бумаги и разные люди.
      driverDocumentGapsHint(d.gaps, d.credentialTypeCode),
      d.matchesRequiredCategory ? null : DRIVER_CATEGORY_MISMATCH_HINT,
      driverWorkedOnVehicle(d) ? DRIVER_WORKED_ON_VEHICLE_HINT : null,
      d.verificationStatus === 'unverified' ? 'документ не проверен' : null,
    ]
      .filter(Boolean)
      .join(' · '),
  };
}

/**
 * Строка списка машинистов — короче водительской, и это не экономия. Ни категории, ни пробелов
 * документов в ней нет, потому что бланк ЭСМ-2 этих граф не печатает (ADR 0095, решение В1):
 * пометка «категория не подходит» под машиной, на которую категорий не бывает, называла бы
 * несуществующее расхождение.
 */
export function machinistOption(d: DriverDto): { value: string; label: string } {
  return {
    value: d.id,
    label: [d.fullName, d.personnelNo && `таб. ${d.personnelNo}`].filter(Boolean).join(' · '),
  };
}

/**
 * Спрашивается ли машинист и обязателен ли он.
 *
 * Машинисты для листов ЭСМ-2 (миграция 0087) — весь справочник водителей, без единого отбора. Это
 * не тот же список, что у водителя рейса, и намеренно. `drivers/available` требует непустой СНИЛС,
 * годное на дату удостоверение и смотрит на категорию под машину — всё это графы 4-П, без которых
 * тот лист недействителен. В бланке ЭСМ-2 их нет вовсе: граф под удостоверение и СНИЛС Госкомстат
 * в нём не разметил, и портал их туда не печатает (ADR 0095, решение В1) — хотя удостоверение
 * тракториста-машиниста он с тех пор ведёт. Поэтому годится любой действующий водитель, и ни
 * машина, ни дата на список не влияют.
 *
 * Поле спрашивается в обоих режимах окна. При смене техники (ADR 0048) человек меняется вместе с
 * машиной чаще, чем нет: заказ ведёт другая единица — за ней приходит и другой машинист, — а до
 * сих пор его меняли перевыпиской листов вручную, хотя сверка ЭСМ-2 умеет это сама (миграция
 * 0087). У аренды поля нет ни там, ни там: листы на арендную технику выписывает арендодатель, и
 * портал её машиниста не ведёт.
 *
 * Обязателен он у перевода в работу: тот тем же движением выписывает недельные ЭСМ-2 на весь срок,
 * и лист без человека недействителен. У линейного заказа — нет: листов в этот момент не рождается
 * ни одного (ADR 0100 решение 5), и требовать имя не за что. Поле остаётся: назначение хранит
 * машиниста по умолчанию — того, кто обычно выходит на этой машине.
 *
 * При смене техники — нет никогда, и это не послабление, а смысл пустого значения (ADR 0083): не
 * назвали — значит человека не меняли, и сверка возьмёт его с прежнего листа заявки. Единственный
 * случай, когда брать его неоткуда, — заявку вели арендной техникой и листов у неё не было вовсе;
 * отличить его портал по своему списку не берётся (в нём и аннулированные листы, а наследует
 * сверка с последнего выписанного), и отвечает на это сервер — отказом на поле.
 */
export function machinistFieldMode(input: {
  requestType: VehicleRequestType | undefined;
  isRental: boolean;
  reassign: boolean;
  isLinear: boolean;
}): { needsMachinist: boolean; machinistRequired: boolean } {
  const needsMachinist = input.requestType === 'special_equipment' && !input.isRental;
  return {
    needsMachinist,
    machinistRequired: needsMachinist && !input.reassign && !input.isLinear,
  };
}

/**
 * Сколько бланков израсходует перевод в работу и на какие недели: лист ЭСМ-2 выписывается на
 * каждую неделю срока (миграция 0087), и человек должен видеть это до нажатия, а не узнавать из
 * журнала. Считается тем же `esm2Periods`, которым выписывает сервер.
 *
 * У линейной заявки перечня нет, потому что нет и расхода: ни одного бланка перевод в работу по ней
 * не тратит (ADR 0100 решение 5). Обещать недели, которых не будет, здесь хуже молчания.
 *
 * У смены техники перечня нет по другой причине: считать его пришлось бы не по сроку, а по тому,
 * какие недели уже отработаны и какие листы сверка тронет, — этот ответ знает сервер, и портал
 * говорит вместо числа то, что верно всегда (см. `machinistFieldExtra`).
 */
export function plannedEsm2Weeks(input: {
  needsMachinist: boolean;
  reassign: boolean;
  isLinear: boolean;
  dateFrom: Dayjs | null | undefined;
  dateTo: Dayjs | null | undefined;
}): Esm2Period[] {
  if (!input.needsMachinist || input.reassign || input.isLinear) return [];
  const from = input.dateFrom?.format('YYYY-MM-DD');
  if (!from) return [];
  return esm2Periods(from, input.dateTo?.format('YYYY-MM-DD') ?? null);
}

/**
 * Кого называют действующие листы ЭСМ-2 заявки — тот человек и останется, если поле машиниста
 * оставить пустым. Имя нужно именно для этого: пустое поле означает «не меняли», и без имени оно
 * читалось бы как «машиниста нет».
 *
 * Берётся лист самой поздней недели, а не первый попавшийся: у обычного заказа машинист один на все
 * недели срока (сверка переписывает разошедшиеся), и разными имена бывают ровно там, где прошлое
 * уже не трогают, — в отработанных неделях. Аннулированные листы не в счёт: они рассказывают, как
 * заявку вели раньше, а под полем говорится про сейчас.
 */
export function currentMachinistName(waybills: RequestWaybillDto[] | undefined): string | null {
  return (
    (waybills ?? [])
      .filter((w) => w.formCode === 'esm2' && w.status === 'issued' && !!w.periodFrom)
      .sort((a, b) => b.periodFrom!.localeCompare(a.periodFrom!))[0]?.driverName ?? null
  );
}

/**
 * Что сказано под полем машиниста — и это разный разговор в двух режимах окна.
 *
 * При переводе в работу поле спрашивает человека впервые, и под ним стоит цена ответа: сколько
 * бланков уйдёт и на какие недели.
 *
 * При смене техники (ADR 0048) поле уже кем-то занято — прежним машинистом в листах, — но
 * подставлять его в поле нельзя (ADR 0083): подставленная фамилия читается как принятое решение,
 * её пролистывают, и в бланк она уезжает настоящей. Поэтому имя стоит текстом, а поле остаётся
 * пустым, и текст обязан объяснить, что значит эта пустота: прежний остаётся. Здесь же названа и
 * цена смены — сверка ЭСМ-2 аннулирует и перевыпишет листы неотработанных недель, а отработанные
 * не тронет: под ними подпись объекта, и переписывать их задним числом — уже другая операция
 * (ADR 0101).
 *
 * У линейного заказа разговор третий: «машиниста заявки» там не существует вовсе — его называют на
 * каждую неделю отдельно (ADR 0100 решение 6), и пустое поле оставляет каждой неделе своего
 * человека, а не общего. Назвать одно имя под этим текстом всё равно можно: тогда сверка сведёт к
 * нему неотработанные недели — ровно то же, что она делает у обычного заказа.
 */
export function machinistFieldExtra(input: {
  reassign: boolean;
  isLinear: boolean;
  currentMachinist: string | null;
  esm2Weeks: Esm2Period[];
}): string {
  const { reassign, isLinear, currentMachinist, esm2Weeks } = input;
  return reassign
    ? isLinear
      ? 'У линейного заказа машинист свой в каждом недельном листе: оставьте пустым — каждая неделя останется со своим. Выберете человека — листы неотработанных недель будут перевыписаны на него.'
      : currentMachinist
        ? `Сейчас в листах — ${currentMachinist}; оставьте пустым, чтобы он остался. Выберете другого — листы ЭСМ-2 неотработанных недель будут перевыписаны на него, отработанные останутся как есть.`
        : 'Действующих листов ЭСМ-2 у заявки нет — машиниста называют впервые: на него выпишутся листы неотработанных недель. Оставите пустым — человек возьмётся с последнего листа заявки, а если листов не было вовсе (её вели арендной техникой), портал попросит назвать имя.'
    : isLinear
      ? 'Необязательно: листов ЭСМ-2 перевод в работу не выписывает'
      : esm2Weeks.length > 0
        ? `Будет выписано листов ЭСМ-2: ${esm2Weeks.length} — ${esm2Weeks
            .map((w) => `${formatDateOnly(w.from).slice(0, 5)}–${formatDateOnly(w.to).slice(0, 5)}`)
            .join(', ')}`
        : 'На каждую неделю срока работ выписывается свой путевой лист';
}

/**
 * Что не так с выбранным водителем по части категории: машина требует одну, у человека открыты
 * другие. Пометки в строке списка мало — её читают при выборе и забывают, — а решение садить
 * человека остаётся за диспетчером (ADR 0055, ADR 0064): портал ничего не запрещает, но обе стороны
 * расхождения обязан назвать.
 *
 * У обеих сторон назван вид документа (ADR 0095): требование машины ссылается на категорию любого
 * вида, и «нужна C, а открыта C» без него читалось бы как ошибка портала.
 */
export function driverCategoryNote(
  selection: DriverSelectionDto | undefined,
  driver: DriverOptionDto | undefined,
): string | null {
  return selection?.requiredCategory &&
    selection.requiredCategoryType &&
    driver &&
    !driver.matchesRequiredCategory
    ? driverCategoryMismatchWarning(
        selection.requiredCategory,
        selection.requiredCategoryType,
        driver.categories,
        driver.credentialTypeCode,
      )
    : null;
}

/**
 * Второе, что не так с выбранным водителем: не внесены документы, которые печатает бланк. Отдельно
 * от категории, а не одним предупреждением: пустая графа бланка и чужая категория — разные вещи, и
 * первое проверяют по справочнику водителей, а второе по документу в руках.
 *
 * Пробелы названы вместе с бланком: пустая графа в 4-П и пустая графа в форме № 3 — разные графы, и
 * «касается ли это меня» человек должен понять не выходя из окна. У перегона бланк всегда 4-П
 * (миграция 0082), у рейса — тот, что закреплён за типом выбранной машины.
 */
export function driverGapsNote(
  driver: DriverOptionDto | undefined,
  formCode: WaybillFormCode | null,
): string | null {
  return driver
    ? driverDocumentGapsWarning(
        driver.gaps,
        driver.credentialTypeCode,
        formCode ? waybillFormShortLabels[formCode] : null,
      )
    : null;
}

/**
 * Что сказано под полем водителя у готового рейса — и это другой разговор, чем у нового.
 *
 * У нового поле спрашивает «кто поедет» и без ответа рейса не бывает. У готового человек уже есть,
 * и вопрос звучит иначе: «менять ли того, кто за рулём» (ADR 0048). Прежнее имя в поле не
 * подставляется (ADR 0083) — подставленная фамилия читается как принятое решение, её пролистывают,
 * а в бланк она уезжает настоящей; поэтому имя стоит текстом, а пустоту поля объясняют словами,
 * иначе она читается как «водителя нет».
 *
 * Про снятие водителя сказано ровно то, чего оно стоит. Контракт `null` принимает, но окно его не
 * предлагает: рейс общий, и «снять» здесь означало бы оставить без водителя ещё и чужие заявки.
 * Такое решение принимают правкой маршрута, где виден весь его состав (ADR 0082), — и человек
 * должен узнать дорогу туда отсюда, а не гадать, почему у поля нет пустого пункта.
 */
export function joinedRouteDriverExtra(route: VehicleRouteDto | null): string | null {
  if (!route) return null;
  return route.driverName
    ? `Сейчас за рулём ${route.driverName} — оставьте пустым, чтобы он и остался. Снимают водителя правкой маршрута; здесь его только меняют.`
    : 'За рулём этого рейса пока никого — оставьте пустым, и рейс так и останется без водителя: лист по нему не выписать, пока человека не назначат.';
}

/**
 * Предупреждение о том, что водителя меняют всему рейсу.
 *
 * Состав назван поимённо, а не числом. Рейс едет одним заданием, и водитель в нём один на все
 * заявки: смена коснётся и чужих заказов. В списке рейсов видно только «3 из 7 заявок», чьи они —
 * уже нет, и «поменял водителя своей заявке» оказалось бы сменой водителя у соседей. Номера заявок
 * дают то, чего не даёт счётчик: по ним видно, кому звонить, если решение спорное.
 *
 * Стоит, пока рейс готовый, а не только с выбранным именем: состав нужен и в тот момент, когда
 * человека ещё выбирают, — иначе «поменял водителя своей заявке» узнавалось бы уже после нажатия. С
 * выбранным именем справка становится предупреждением: у решения появилась цена, и прежний водитель
 * из рейса уходит.
 */
export function joinedRouteDriverNote(
  route: VehicleRouteDto | null,
  driverPersonId: string | undefined,
): { type: 'info' | 'warning'; message: string; description: string } | null {
  const composition = route
    ? route.requests.length > 0
      ? `Заявок в рейсе: ${route.requests.length} — ${route.requests.map((r) => r.displayNumber).join(', ')}`
      : 'Других заявок в рейсе пока нет'
    : null;
  if (!route || !composition) return null;
  // Уходящий водитель называется по имени: «прежний водитель» ничего не говорит тому, кто рейс не
  // собирал, — а решение принимают как раз про конкретного человека.
  const leaving = route.driverName ? `, а ${route.driverName} из рейса уйдёт` : '';
  return driverPersonId
    ? {
        type: 'warning',
        message: 'Водитель сменится у всего рейса',
        description: `Рейс ${route.displayNumber} едет одним заданием: выбранный водитель поедет за весь его состав, а не за одну эту заявку${leaving}. ${composition}.`,
      }
    : {
        type: 'info',
        message: 'Водитель у рейса один на все заявки',
        description: `Рейс ${route.displayNumber} едет одним заданием, и смена водителя коснётся каждой заявки в нём. ${composition}.`,
      };
}
