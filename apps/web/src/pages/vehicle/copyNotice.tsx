import type { Dayjs } from 'dayjs';
import type { ReactNode } from 'react';
import type { RequestStatus, VehicleRequestDto } from '@technic/contracts';
import { formatDateOnly } from '../../utils/date';
import { copyScheduledPlan, copyTermPlan, scheduledMoment } from './requestFormValues';

/**
 * Хвост шапки под статус источника. Полным словарём, а не разбором частных случаев: пропусти он
 * статус — и шапка молча напечатала бы `undefined` там, где человека успокаивают.
 *
 * «Завершена» у заказа техники не бывает вовсе (это статус вывоза мусора, ADR 0135), и хвоста у
 * неё нет: обещать «остаётся завершённой» про статус, которого в модуле не существует, незачем.
 */
const HEAD_TAIL: Record<RequestStatus, string> = {
  new: '',
  confirmed: ' — она остаётся в работе',
  done: ' — она остаётся выполненной',
  completed: '',
  // Отменённую копия не возобновляет: заводится новая заявка со своим номером, а отказ по старой
  // так и остаётся отказом. Сказать это надо словами — «завести такую же» звучит как «вернуть».
  cancelled: ' — копия не возобновляет отменённую',
};

/**
 * Надпись над формой копии заявки на технику (ADR 0206): что остаётся у источника и какой срок
 * предложен копии.
 *
 * Копию снимают с заявки любого статуса, и надпись — единственное место, где об этом говорят до
 * сохранения. Отвечает она на два настоящих страха разом: «сейчас я испорчу выполненную заявку» и
 * «почему в полях не те даты, что в карточке». Второе без объяснения читается как сбой формы, и
 * человек правит подставленный срок обратно в прошлое — туда, где заведение его не примет.
 *
 * Ветвится текст **по данным**, а не по статусу: срок выбирает календарь (у отменённой заявки он
 * бывает и будущим, а у «Новой» — прошедшим), строку наследства — заполненные поля. Статус
 * называет одна шапка, и та лишь повторяет словами то, что человек видит в карточке.
 *
 * Отдельным файлом от вкладки: `VehicleRequestsTab` стоит в бюджете длины (`scripts/quality.mjs`),
 * а текст о заявке — законченный вопрос, о показе не знающий ничего.
 */
export function copyNotice(r: VehicleRequestDto, minDate: Dayjs, today: string): ReactNode {
  const num = r.displayNumber;
  const extension =
    r.requestType === 'special_equipment' && r.status === 'confirmed'
      ? // Копией продлевают заказ чаще всего по ошибке: вторая заявка на ту же машину встанет
        // рядом с первой и упрётся в её занятость. Дверь тут другая, и названа она прямо.
        `Нужна та же машина дольше — копия не поможет: срок ${num} продлевают правкой даты окончания, а площадка — «Заявкой на неделю».`
      : null;
  return (
    <>
      <div>
        <strong>{`Заявка ${num} не меняется${HEAD_TAIL[r.status]}.`}</strong>
      </div>
      <div>{termLine(r, minDate, today)}</div>
      <div>{legacyLine(r)}</div>
      {extension ? <div>{extension}</div> : null}
    </>
  );
}

/** Дата срока — тем же видом, каким её печатают строка списка и карточка (`termLabel`). */
function dayText(d: Dayjs): string {
  return formatDateOnly(d.format('YYYY-MM-DD'));
}

/**
 * Предложенный срок словами. Пустая дата окончания — однодневный заказ (так же его понимает
 * сервер), и печатается он одной датой: «23.09.2026 – 23.09.2026» читается как сбой подстановки.
 *
 * Числа дней в тексте нет намеренно: счётчик календарных дней уже стоит подписью под полем «Дата
 * окончания», и второй такой же однажды разошёлся бы с первым — считали бы их разные правила.
 */
function termText(from: Dayjs, to: Dayjs | null): string {
  return to ? `${dayText(from)} – ${dayText(to)}` : dayText(from);
}

/**
 * Строка срока: её выбирает календарь заявки, а не статус (`copyTermPlan`, `copyScheduledPlan`).
 *
 * У сдвига причин две, и называются они по отдельности. Даты двигает не только прошлое: срок,
 * целиком лежащий впереди, но не дотягивающий до первого доступного дня, уезжает тем же сдвигом —
 * у заявителя первый доступный день завтрашний, а после 15:00 послезавтрашний (ADR 0104). Скажи
 * ему про «прошедший срок» на заказе, который начинается завтра, — и надпись станет неправдой
 * ровно там, где объясняют подставленные даты.
 */
function termLine(r: VehicleRequestDto, minDate: Dayjs, today: string): string {
  if (r.requestType === 'special_equipment') {
    const term = copyTermPlan(r, minDate, today);
    const proposed = termText(term.dateFrom, term.dateTo);
    if (term.kind === 'ahead')
      return `Состав перенесён из неё, срок предложен прежний: ${proposed}.`;
    if (term.kind === 'remainder')
      return `Состав перенесён из неё; прежний срок идёт до ${formatDateOnly(r.dateTo || r.dateFrom)} — копии предложен остаток: ${proposed}.`;
    const why =
      (r.dateTo || r.dateFrom) < today ? 'прежний срок прошёл' : 'технику заказывают заранее';
    return `Состав перенесён из неё; ${why} — копии предложены те же дни вперёд: ${proposed}.`;
  }
  const plan = copyScheduledPlan(r, minDate);
  const day = dayText(plan.scheduledDate);
  // Часа в тексте нет, когда его нет и в заявке (`scheduledTimeUnspecified`): «00:00» в подаче
  // означало бы согласованную полночь, которой никто не просил.
  const time = plan.scheduledTime ? `, ${plan.scheduledTime}` : '';
  if (plan.kind === 'ahead')
    return `Состав перенесён из неё, подача предложена прежняя: ${day}${time}.`;
  // День подачи в московском дне — тем же ключом, каким ветвится срок: сравнивать момент с
  // полуночью пояса браузера значило бы называть причину по чужому календарю.
  const why =
    scheduledMoment(r).format('YYYY-MM-DD') < today
      ? 'день подачи прошёл'
      : 'технику заказывают заранее';
  const kept = plan.scheduledTime ? `, время ${plan.scheduledTime} сохранено` : '';
  return `Состав перенесён из неё; ${why} — предложен ближайший день: ${day}${kept}.`;
}

/**
 * Что остаётся у источника и чего в копии не будет.
 *
 * Техника, рейс и факт называются только у той заявки, у которой они есть: обещать, что «техника
 * останется у Т-42», когда её туда и не назначали, — врать ровно там, где человек решает,
 * заводить ли копию. Вложения не переносятся ни у какой (`assertFilesAttachable`), и говорится об
 * этом до сохранения: узнать о пропаже после значило бы обнаружить её тогда, когда заявка ушла.
 */
function legacyLine(r: VehicleRequestDto): string {
  const attachments = 'вложения не переносятся — приложите их заново.';
  // Перечень собирается из заполненного, а не печатается целиком: у заказа с назначенной машиной,
  // но без рейса и без факта строка «техника, рейс и факт остаются» назвала бы две сущности,
  // которых у заявки нет, — и следующую строку про вложения человек прочёл бы с тем же доверием.
  const kept = [
    r.assignment ? 'техника' : null,
    r.route ? 'рейс' : null,
    r.completion ? 'факт' : null,
  ].filter((s): s is string => !!s);
  if (kept.length === 0) return `В${attachments.slice(1)}`;
  const last = kept[kept.length - 1]!;
  const listed = kept.length > 1 ? `${kept.slice(0, -1).join(', ')} и ${last}` : last;
  const verb = kept.length > 1 ? 'остаются' : 'остаётся';
  return `${listed[0]!.toUpperCase()}${listed.slice(1)} ${verb} у ${r.displayNumber}; ${attachments}`;
}
