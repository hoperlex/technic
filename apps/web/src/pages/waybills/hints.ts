import dayjs from 'dayjs';
import type { WaybillDto } from '@technic/contracts';

/**
 * Подписи к строке журнала, объясняющие, почему бланк не такой, каким его выдали (Р12 и Р13 плана
 * [vehicle-request-actual-end-date-plan.md](../../../../../docs/vehicle-request-actual-end-date-plan.md)).
 *
 * Отдельным файлом по той же причине, что и фильтры: журнал читается кнопками и колонками, а эти
 * две фразы — текст, который собирается из трёх полей ответа и обязан быть точным до слова.
 * Внутри страницы они утонули бы между печатью и аннулированием, а сверять их формулировку
 * (а сверять её будет бухгалтерия) удобнее там, где рядом лежит объяснение, откуда что берётся.
 */

/** Дата в журнале читается целиком, с годом: соседние строки бывают из разных лет. */
const dateLabel = (value: string) => dayjs(value).format('DD.MM.YYYY');

/**
 * Что говорит метка «коррекция» — «почему этот бланк не такой, каким выдан» (Р12).
 *
 * Источников у метки три, и подсказка обязана их различать. Два прежних объясняют **операцию с
 * номером**: лист родился коррекцией (`correctionReason`) либо был ею списан (`cancelReason`).
 * Третий — сокращение периода: номер тот же, состав тот же, а дней с конца стало меньше, потому
 * что заказ закрыли фактической датой.
 *
 * Отдельной метки у сокращения нет намеренно (решение заказчика по В3), и потому весь смысл
 * переносит именно подсказка: метка у листа, который не аннулирован и никем не заменён, без
 * объяснения читается как ошибка портала.
 *
 * Сокращение называется первым и обеими датами сразу. Первым — потому что оно описывает лист
 * **сейчас**, а операция объясняет его происхождение; лист, рождённый коррекцией и позже
 * сокращённый, читают по последней правке. Обеими датами — потому что одно слово «сокращён» не
 * отвечает на единственный практический вопрос: печатное «Период работы» на экземпляре с площадки
 * шире того, что в портале (Р13), и человек сверяет именно пару чисел.
 */
export function correctionHint(r: WaybillDto): string {
  const operation = r.correctionReason || r.cancelReason;
  if (!r.trimmedAt) return operation || 'Правка задним числом';
  // Запасная фраза стоит не ради несуществующего случая — сокращение по устройству колонок
  // (миграция 0292) живёт только у бланка с периодом, — а ради того, чтобы подсказка ни при каких
  // данных не выродилась в «Период сокращён до » с пустым местом.
  const dates =
    r.periodTo && r.periodToOriginal
      ? `Период сокращён до ${dateLabel(r.periodTo)}, в бланке напечатано по ${dateLabel(r.periodToOriginal)}`
      : 'Период сокращён после выдачи бланка';
  const trimmed = r.trimReason ? `${dates}. Причина: ${r.trimReason}` : dates;
  return operation ? `${trimmed}. ${operation}` : trimmed;
}

/**
 * Подсказка у кнопки печати сокращённого листа; `undefined` — печать обычная (Р13).
 *
 * Повторная печать даёт бланк с укороченным периодом — то есть **не копию** того экземпляра, что
 * лежит на площадке: печать всегда идёт из снимка, а снимок приведён к факту. Это не дефект и не
 * повод не печатать, поэтому текст объясняет, а не предупреждает: человеку нужно знать, что два
 * бланка с одним номером и разными периодами — законная пара, а не подделка одного из них.
 *
 * Каждая дата названа вместе с тем, где она стоит: «напечатается нынешний конец — …, а в выданном
 * экземпляре стоит …». Две даты подряд без такой привязки читаются наоборот при первом же беглом
 * взгляде — оговорка вроде «как в портале», поставленная после второй из них, приклеивается именно
 * к ней, и подсказка начинает утверждать ровно обратное тому, ради чего написана.
 */
export function trimmedPrintHint(r: WaybillDto): string | undefined {
  if (!r.trimmedAt) return undefined;
  const now = r.periodTo
    ? `напечатается нынешний конец — ${dateLabel(r.periodTo)}`
    : 'напечатается нынешний, укороченный период';
  const was = r.periodToOriginal
    ? `, а в выданном экземпляре стоит ${dateLabel(r.periodToOriginal)}`
    : '';
  return `Печать бланка. Период листа сокращён: ${now}${was}. Это не копия того листа, что лежит на площадке, а тот же номер с укороченным периодом.`;
}
