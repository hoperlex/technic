import { useAddressParam, type AddressParam } from '@shared/lib';

/**
 * Адрес вкладки «Автозапчасти» (план `docs/auto-parts-plan.md`, Р14).
 *
 * В адресе живут два предмета, и оба — переходы, а не подстройка экрана: открытая карточка
 * позиции на этой вкладке и акт обслуживания, на который ссылается лента журнала. Ссылку
 * присылают соседу («вот эта деталь», «вот по какому акту её списали»), «назад» обязано вернуть
 * на шаг, а перезагрузка — оставить открытым то же самое.
 *
 * Дня среза здесь нет вовсе: склад показывает текущее состояние, а не срез суток (Р14). Ключ
 * `?date=`, которым живут «Техника» и «Водители», вкладку не касается — она его не читает и не
 * пишет, а страница гаража сохраняет его сама.
 */

/** Ключ открытой карточки: `?tab=parts&part=<id>` (Р14). */
const PART_PARAM = 'part';

/**
 * Открытая карточка позиции.
 *
 * `allowed` — не про право: склад читают все, кому виден гараж (Р10), и своего права у списка нет.
 * Спрашивается активная вкладка: скрытые вкладки остаются смонтированными (`PageTabs`), а окно
 * рисуется порталом в тело документа — без этой проверки карточка, названная в адресе, висела бы
 * поверх соседней вкладки, где её никто не звал.
 */
export function useAutoPartAddress(allowed: boolean): AddressParam {
  return useAddressParam(PART_PARAM, allowed);
}

/**
 * Акт обслуживания, по которому прошло движение остатка: `?tab=vehicles&maintenance=<vehicleId>&record=<maintenanceId>`
 * (Р14, §8).
 *
 * Двух идентификаторов, а не одного, потому что сводку обслуживания в портале открывает **машина**:
 * ключ `?maintenance=` называет её, и приехать по нему в конкретный документ длинной истории
 * нечем. Второй ключ (`record`) называет сам акт — историю прокручивает к нему и раскрывает его
 * строки тот, кто разбирает адрес сводки (`useMaintenanceAddress`); лента склада только собирает
 * ссылку.
 *
 * Адрес собирается с нуля и с именем раздела, а не поверх текущих ключей: переход уводит на
 * соседнюю вкладку, и `part` — открытая карточка позиции — там означал бы просьбу показать заодно
 * и её. Ответ «почему стало 11» и ответ «что поставили на машину» — одна и та же запись,
 * прочитанная с двух сторон, и ссылка есть переход между ними.
 */
export function maintenanceRecordHref(vehicleId: string, maintenanceId: string): string {
  const params = new URLSearchParams({
    tab: 'vehicles',
    maintenance: vehicleId,
    record: maintenanceId,
  });
  return `/garage?${params.toString()}`;
}
