import { Space, Typography, type TableColumnType } from 'antd';
import dayjs from 'dayjs';
import type { GarageVehicleDto } from '@technic/contracts';

/**
 * Колонка «Одометр» вкладки «Техника» (план «Показания техники», Р16).
 *
 * Считает её сервер, и считает **на день среза**: показания правят задним числом (ADR 0101),
 * поэтому «последнее вообще» и «последнее на выбранный день» — разные числа, а гараж отвечает про
 * тот же день, которым показывает занятость. Портал здесь ничего не выбирает и не досчитывает: он
 * печатает пришедшее число и дату, за которую его сняли.
 *
 * **Дата рядом с числом обязательна.** Одометр без даты читается как сегодняшний и врёт тем
 * сильнее, чем дольше машина стоит: у месяц простоявшего экскаватора «128 400 км» — это про
 * позапрошлую смену, и без подписи диспетчер узнает об этом, только сверив пробег с путевым листом.
 *
 * Отдельным файлом, а не строками в `GarageVehiclesTab.tsx`: у вкладки бюджет длины
 * (`quality-budget.json`), и колонка со своим форматированием в него не помещалась.
 */

/** Неразрывный: «128 400 км» не должно переноситься на две строки посреди числа. */
const NBSP = ' ';

const SHOWN_DATE = 'DD.MM.YYYY';

/**
 * «128 400 км» — разряды пробелами. Год в дате не сокращается (в отличие от подсказки в кабине,
 * где сверяют свежее): последнее показание бывает и прошлогодним, и «12.08» без года в списке парка
 * читалось бы как этот август.
 */
function kmText(km: number): string {
  return `${String(km).replace(/\B(?=(\d{3})+(?!\d))/gu, NBSP)}${NBSP}км`;
}

/**
 * Строка карточки телефона: «одометр: 128 400 км (12.08.2026)». Пусто — показаний нет либо колонка
 * человеку не положена; в обоих случаях карточка о них молчит, а не показывает прочерк.
 */
export function odometerCardLine(row: GarageVehicleDto): string | null {
  const last = row.lastOdometer;
  if (!last) return null;
  return `одометр: ${kmText(last.km)} (${dayjs(last.measuredOn).format(SHOWN_DATE)})`;
}

/**
 * Колонка перечня. Сортировки у неё нет намеренно: сервер сортирует парк по состоянию дня и
 * госномеру (`GARAGE_VEHICLE_SORT_FIELDS`), а заголовок, который сервер не слышит, обещал бы
 * порядок, которого не случится.
 *
 * Обобщённая по строке: вкладка ведёт свой тип строки (срез плюс состояние показаний), и колонка
 * обязана вставать в него, не требуя приведения.
 */
export function odometerColumn<T extends GarageVehicleDto>(): TableColumnType<T> {
  return {
    key: 'lastOdometer',
    title: 'Одометр',
    width: 150,
    render: (_v, r) => {
      const last = r.lastOdometer;
      // Прочерк — это «показаний за машиной не числится», а не ноль на приборе: снимка не было,
      // и догадка про пробег была бы хуже пустоты.
      if (!last) return <Typography.Text type="secondary">—</Typography.Text>;
      return (
        <Space orientation="vertical" size={0}>
          <span>{kmText(last.km)}</span>
          <Typography.Text type="secondary" style={{ fontSize: 12 }}>
            снято {dayjs(last.measuredOn).format(SHOWN_DATE)}
          </Typography.Text>
        </Space>
      );
    },
  };
}
