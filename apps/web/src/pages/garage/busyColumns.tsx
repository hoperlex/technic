import { useLayoutEffect, useRef, useState } from 'react';
import { Space, Tooltip, Typography } from 'antd';
import type { GarageBusyEntry } from '@technic/contracts';
import { EntityLink } from '@shared/ui';
import {
  type BusyCellProps,
  BusyHead,
  DASH,
  OrderParts,
  SUB,
  WaybillNumber,
  busyKey,
  busyLine,
  orderParts,
  orderText,
  shortDate,
} from './shared';

/**
 * Гараж → «Водители»: день человека тремя колонками — «Рейс/путевой лист», «Техника»,
 * «Заказ/адрес». Занятость здесь та же самая, что у вкладки техники, и собраны колонки из её же
 * частей (`shared.tsx`): это другой способ прочитать один и тот же день, а не второй его разбор.
 *
 * Почему поперёк, а не списком. У машины день — это перечень работ, и машина в нём одна: она
 * названа первой графой таблицы. У человека машина в каждой работе своя, и спрашивают о нём не
 * «что за работа», а «на чём он и по какому заказу»; в сплошной колонке занятости оба ответа
 * приходилось выуживать из строки текста подряд по всей странице отбора.
 *
 * Чем за это платят. Ячейки одной строки обязаны стоять вровень — блоки разной высоты разъезжаются
 * и рвут то самое чтение поперёк, ради которого три графы и заведены, — поэтому в графах стоит
 * **одна** работа дня, а остальные считает пометка «ещё N» (`BusyMore`).
 *
 * И вот про какую именно работу колонки отвечают, соврать нельзя. Это **первая заведённая** работа
 * дня, а не та, где человек сейчас. Порядок набора задаёт сервер (`loadDriverBusy` в
 * `apps/api/src/services/garage.ts`): рейсы отсортированы по `vehicleRoutes.num` — сквозному
 * счётчику создания записи (`generatedAlwaysAsIdentity`), — а недельный лист ЭСМ-2 дописан за ними
 * хвостом. Времени выезда у рейса в схеме нет вовсе, так что упорядочить день по часам сейчас
 * нечем: рейс, заведённый вчера вечером на утро, встанет впереди заведённого сегодня на обед.
 * Спрашивающему «где он прямо сейчас» отвечает не первая графа, а пометка «ещё N»: она называет
 * скрытые работы целиком — с машиной, номером и заказом.
 */

/**
 * Занятость водителя одной строкой: машина впереди, дальше — чем работа заведена и куда едет.
 *
 * Машина в начале — не украшение. `busyLine` о ней молчит намеренно: на вкладке техники её называют
 * первая графа таблицы и заголовок карточки, и номер в каждой строке дня только двоился бы. У
 * водителя же машина в каждой работе своя, и работа без неё отвечает на половину вопроса. Больше
 * всего это видно в пометке «ещё N»: колонка «Техника» заведена ровно ради ответа «на чём», а
 * показывает она только первую работу — молчащая о машине подсказка отнимала бы у скрытых работ
 * как раз то, ради чего колонку и завели.
 *
 * Одна функция на два места — карточку телефона (`GarageDriversTab`, где строк занятости три) и
 * подсказку «ещё N»: собранные порознь, они уже успели разойтись ровно на машину.
 */
export function driverBusyLine(entry: GarageBusyEntry): string {
  return `${entry.vehicleLabel} · ${busyLine(entry)}`;
}

/**
 * Пометка «ещё N»: сколько работ дня осталось за кадром и каких именно. Стоит она в первой из трёх
 * колонок и только в ней: занятость у ячеек строки одна, и трижды повторённое число ничего бы не
 * добавило. Подсказка — теми же строками, какими день читают с телефона (`driverBusyLine`), то есть
 * с машиной впереди: скрытая работа обязана отвечать и «на чём», раз колонка «Техника» показывает
 * машину только первой из них.
 *
 * Подсказка здесь безусловная, в отличие от соседних колонок, и мерить нечего: пометка не рисуется
 * вовсе, пока за кадром ничего нет, — а появившись, она всегда прячет больше, чем показывает.
 */
function BusyMore({ entries }: BusyCellProps) {
  const rest = entries.slice(1);
  if (rest.length === 0) return null;
  const title = rest.map((entry) => <div key={busyKey(entry)}>{driverBusyLine(entry)}</div>);
  return (
    <Tooltip title={title}>
      <Typography.Text {...SUB}>ещё {rest.length}</Typography.Text>
    </Tooltip>
  );
}

/**
 * Колонка «Рейс/путевой лист»: чем заведена первая работа дня — и чем она подтверждена (выписанным
 * листом у рейса, сроком недели у ЭСМ-2). У заказа спецтехники рейса нет вовсе, и колонка отвечает
 * прочерком: в строке водителя такой занятости не бывает и подавно (заявка называет машину, а не
 * человека), но тип занятости общий на обе вкладки. Переносу разрешено рвать слово где угодно —
 * номер бланка (`260604-646-00000004897`) пробелов не имеет и иначе распирал бы колонку, отбирая
 * ширину у двух соседних.
 */
export function BusyRouteCell({ entries }: BusyCellProps) {
  const entry = entries[0];
  if (!entry) return DASH;
  return (
    <Space direction="vertical" size={0} style={{ display: 'flex', overflowWrap: 'anywhere' }}>
      {entry.kind === 'special' ? DASH : <BusyHead entry={entry} />}
      {entry.kind === 'route' && entry.waybill && (
        <Typography.Text {...SUB}>
          <WaybillNumber number={entry.waybill.number} />
        </Typography.Text>
      )}
      {entry.kind === 'esm2' && (
        <Typography.Text {...SUB}>
          {shortDate(entry.periodFrom)} – {shortDate(entry.periodTo)}
        </Typography.Text>
      )}
      <BusyMore entries={entries} />
    </Space>
  );
}

/**
 * Колонка «Техника»: на чём человек едет в первой заведённой работе дня. Адрес журнала показаний
 * спрашивается снаружи (`hrefOf`), и `null` означает ровно одно: смотрящему показания не положены —
 * тогда номер остаётся текстом. Право проверяет вызывающая сторона, второй двери мимо него здесь
 * нет.
 *
 * Строка строго одна, лишнее — многоточием. Подпись машины не всегда госномер: у арендной это
 * свободное описание, у своей с незаполненным госномером — модель, категория или тип (`vehicleLabel`
 * в `packages/contracts/src/vehicles.ts`). Пущенная в перенос, такая подпись раскладывается в
 * колонке 140 px на три-четыре строки и делает ячейку самой высокой в строке — то есть ровно то, от
 * чего «Заказ/адрес» защищён обрезом, а вся раскладка в три графы затевалась.
 *
 * Обрез отдан antd, и это осознанно проще своего замера: при одной строке `ellipsis` у него — чистый
 * CSS (`text-overflow`), содержимое в JS не режется, и ссылка внутри остаётся настоящей ссылкой —
 * её кликают, Ctrl'ом открывают вкладкой и ведёт она туда же, куда вела. Подсказка при этом
 * всплывает **по факту обреза**: antd сам сверяет ширину содержимого с шириной ячейки, и над
 * госномером, поместившимся целиком, подсказки не будет вовсе. В jsdom раскладки нет, обе ширины
 * нулевые — там эта подсказка молчит всегда, и проверять её тестами нечем.
 */
export function BusyVehicleCell({
  entries,
  hrefOf,
}: BusyCellProps & { hrefOf: (vehicleId: string) => string | null }) {
  const entry = entries[0];
  if (!entry) return DASH;
  return (
    <Typography.Text ellipsis={{ tooltip: entry.vehicleLabel }}>
      <EntityLink to={hrefOf(entry.vehicleId)} title="Открыть журнал показаний">
        {entry.vehicleLabel}
      </EntityLink>
    </Typography.Text>
  );
}

/**
 * Обрезано ли содержимое ячейки: полная высота против видимой. Клэмп задан стилями
 * (`-webkit-line-clamp`), и узнать о нём иначе нельзя — замер тот же, каким `ExpandableCell` решает,
 * показывать ли переключатель «развернуть». Наблюдатель нужен потому, что ширина колонки меняется
 * вместе с окном: состав, помещавшийся в две строки, при сужении перестаёт помещаться.
 *
 * В jsdom раскладки нет вовсе — обе высоты нулевые, — и ответ там всегда «не обрезано». Проверкам
 * это не мешает: подсказки по обрезу в тестах и не увидеть.
 */
function useClipped(content: unknown) {
  const ref = useRef<HTMLDivElement>(null);
  const [clipped, setClipped] = useState(false);
  useLayoutEffect(() => {
    const el = ref.current;
    if (!el) return;
    const measure = () => setClipped(el.scrollHeight - el.clientHeight > 1);
    measure();
    const observer = new ResizeObserver(measure);
    observer.observe(el);
    return () => observer.disconnect();
  }, [content]);
  return { ref, clipped };
}

/**
 * Колонка «Заказ/адрес»: куда едет первая заведённая работа дня — состав рейса, «откуда — куда»
 * перегона, площадка заказа со сроком и состоянием смены. Колонка узкая, а состав бывает и из трёх
 * заявок: содержимое обрезано двумя строками (`garage-busy-order`), полное едет подсказкой. Обрез,
 * а не перенос: ячейки строки стоят вровень, и разросшийся состав увёл бы соседние колонки вниз,
 * разорвав чтение поперёк.
 *
 * Подсказка — только когда есть что показать сверх видимого. У соседней «Техники» это делает сам
 * antd, а здесь замер свой, и вот почему: обрез двухстрочный, а многострочный `ellipsis` antd режет
 * текст в JS и требует строкового содержимого — здесь же внутри живые ссылки на заявки, и он
 * превратил бы их в строку. Замер по высоте (`useClipped`) обходится тем же наблюдателем, что у
 * `ExpandableCell`, и оставляет разметку нетронутой.
 */
export function BusyOrderCell({ entries }: BusyCellProps) {
  const entry = entries[0];
  const parts = entry ? orderParts(entry) : [];
  const { ref, clipped } = useClipped(entry);
  if (parts.length === 0) return DASH;
  return (
    // Обёртка стоит всегда, а пустеет заголовок: `Tooltip` без заголовка не всплывает вовсе. Снимать
    // саму обёртку по замеру нельзя — React пересоздал бы `div`, наблюдатель остался бы висеть на
    // оторванном узле, и подсказка, однажды появившись, не исчезла бы уже никогда.
    <Tooltip title={clipped ? orderText(parts) : ''}>
      <div className="garage-busy-order" ref={ref}>
        <OrderParts parts={parts} />
      </div>
    </Tooltip>
  );
}
