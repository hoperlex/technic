import { useLayoutEffect, useRef, useState } from 'react';
import { Space, Tooltip, Typography, type TableColumnType } from 'antd';
import type { GarageBusyEntry, GarageDriverDto } from '@technic/contracts';
import { EntityLink } from '@shared/ui';
import {
  type BusyCellProps,
  BusyHead,
  DASH,
  OrderParts,
  SUB,
  WaybillNumber,
  busyKey,
  busyLine,
  orderParts,
  orderText,
  shortDate,
} from './shared';

/**
 * Гараж → «Водители»: день человека тремя колонками — «Рейс/путевой лист», «Техника»,
 * «Заказ/адрес». Занятость здесь та же самая, что у вкладки техники, и собраны колонки из её же
 * частей (`shared.tsx`): это другой способ прочитать один и тот же день, а не второй его разбор.
 *
 * Почему поперёк, а не списком. У машины день — это перечень работ, и машина в нём одна: она
 * названа первой графой таблицы. У человека машина в каждой работе своя, и спрашивают о нём не
 * «что за работа», а «на чём он и по какому заказу»; в сплошной колонке занятости оба ответа
 * приходилось выуживать из строки текста подряд по всей странице отбора.
 *
 * Чем за это платят. Ячейки одной строки обязаны стоять вровень — блоки разной высоты разъезжаются
 * и рвут то самое чтение поперёк, ради которого три графы и заведены, — поэтому свёрнутая строка
 * показывает **одну** работу дня, а остальные считает пометка «ещё N» (`BusyMore`).
 *
 * Нажатие на пометку раскрывает день целиком: все три графы разом дописывают свои блоки, работа к
 * работе, — вровень их держит общая сетка (`stackClass`, `.garage-busy-stack` в `styles.css`), так
 * что вторая работа в «Технике» стоит напротив второй в «Рейсе». Раскрытие, а не подсказка при
 * наведении, как было прежде: спрятанный текст нельзя ни открыть ссылкой, ни выделить, ни оставить
 * на экране — а спрашивают «где он сейчас» ровно затем, чтобы тут же уйти в этот рейс. Развёрнутые
 * графы отвечают теми же ссылками, что и первая работа.
 *
 * И вот про какую именно работу отвечает свёрнутая строка, соврать нельзя. Это **первая заведённая**
 * работа дня, а не та, где человек сейчас. Порядок набора задаёт сервер (`loadDriverBusy` в
 * `apps/api/src/services/garage.ts`): рейсы отсортированы по `vehicleRoutes.num` — сквозному
 * счётчику создания записи (`generatedAlwaysAsIdentity`), — а недельный лист ЭСМ-2 дописан за ними
 * хвостом. Времени выезда у рейса в схеме нет вовсе, так что упорядочить день по часам сейчас
 * нечем: рейс, заведённый вчера вечером на утро, встанет впереди заведённого сегодня на обед.
 * Спрашивающему «где он прямо сейчас» отвечает поэтому не свёрнутая строка, а раскрытая.
 */

/**
 * Занятость водителя одной строкой — для карточки телефона, где места на три графы нет.
 *
 * Машина в начале — не украшение. `busyLine` о ней молчит намеренно: на вкладке техники её называют
 * первая графа таблицы и заголовок карточки, и номер в каждой строке дня только двоился бы. У
 * водителя же машина в каждой работе своя, и работа без неё отвечает на половину вопроса — на
 * десктопе на неё отвечает графа «Техника», а на телефоне отвечать нечему, кроме самой строки.
 */
export function driverBusyLine(entry: GarageBusyEntry): string {
  // Марка в скобках, а не через точку: разделитель у строки уже занят перечислением работы
  // («Р-12 · ТС-101 — Альфа-объект»), и марка встала бы в этот ряд равной ему частью — тогда как
  // она половина подписи машины, стоящей перед ней. В графе таблицы её на это место ставит вторая
  // строка, а на телефоне строк нет — есть скобки.
  const label = entry.vehicleModelName
    ? `${entry.vehicleLabel} (${entry.vehicleModelName})`
    : entry.vehicleLabel;
  return `${label} · ${busyLine(entry)}`;
}

/**
 * Какие строки дня раскрыты — по ключу на человека (`personId`). Состояние живёт у таблицы, а не у
 * ячейки: переключатель стоит в первой графе, а дописывают блоки все три, и ячейка своё соседям не
 * расскажет.
 *
 * Ключи ушедших со страницы строк остаются в наборе и просто перестают спрашиваться: чистить их
 * незачем, а раскрытие — состояние взгляда, и день с фильтром ему не хозяева.
 */
export function useBusyExpand() {
  const [open, setOpen] = useState<ReadonlySet<string>>(() => new Set());
  return {
    isOpen: (key: string) => open.has(key),
    toggle: (key: string) =>
      setOpen((prev) => {
        const next = new Set(prev);
        if (!next.delete(key)) next.add(key);
        return next;
      }),
  };
}

/** Работы, стоящие в графах: свёрнутой строке — первая заведённая, раскрытой — весь день. */
function shownEntries(entries: readonly GarageBusyEntry[], expanded: boolean) {
  return expanded ? entries : entries.slice(0, 1);
}

/**
 * Общая сетка развёрнутых работ: блок каждой работы занимает в графе одну и ту же высоту
 * (`.garage-busy-stack`), поэтому вторая работа в «Технике» стоит напротив второй в «Рейсе». Без
 * неё графы разъедутся уже на второй работе — блоки в них разной высоты, — и чтение поперёк, ради
 * которого день разложен на три колонки, кончится там же, где началось.
 *
 * Свёрнутой строке сетка не нужна и вредна: работа в графе одна, и общая высота растила бы каждую
 * строку страницы под самую высокую из трёх граф.
 */
function stackClass(shown: readonly unknown[]) {
  return shown.length > 1 ? 'garage-busy-stack' : undefined;
}

/**
 * Пометка «ещё N» — переключатель дня: сколько работ осталось за кадром, а нажатие раскрывает их
 * прямо в графах и сворачивает обратно. Стоит она в первой из трёх колонок и только в ней:
 * занятость у ячеек строки одна, трижды повторённый переключатель ничего бы не добавил, — а
 * раскрывает он все три графы разом, потому что состояние держит строка (`useBusyExpand`), а не
 * ячейка.
 *
 * Кнопка, а не подпись с обработчиком: её берут с клавиатуры и называет экранный диктор, а ведёт
 * она никуда — меняет высоту той же строки. Не рисуется вовсе, пока за кадром ничего нет.
 *
 * Кнопка своя, а не antd: у той на каждое нажатие заводится волна (`Wave`), а она спрашивает
 * вычисленные стили — в строке таблицы это заметно и на экране, и в тестах, где одно нажатие
 * стоило секунд. Вид у подписи прежний — мелкая ссылка (`.garage-busy-more` в `styles.css`),
 * приём тот же, что у переключателя `ExpandableCell`.
 */
function BusyMore({
  hidden,
  expanded,
  onToggle,
}: {
  hidden: number;
  expanded: boolean;
  onToggle: () => void;
}) {
  if (hidden <= 0) return null;
  return (
    <button type="button" className="garage-busy-more" onClick={onToggle}>
      {expanded ? 'свернуть' : `ещё ${hidden}`}
    </button>
  );
}

/** Занятость строки в графах — вместе с тем, раскрыта ли она: решают это три графы сообща. */
type BusyDayProps = BusyCellProps & { expanded: boolean };

/**
 * Колонка «Рейс/путевой лист»: чем заведена работа — и чем она подтверждена (выписанным листом у
 * рейса, сроком недели у ЭСМ-2). У заказа спецтехники рейса нет вовсе, и колонка отвечает
 * прочерком: в строке водителя такой занятости не бывает и подавно (заявка называет машину, а не
 * человека), но тип занятости общий на обе вкладки. Переносу разрешено рвать слово где угодно —
 * номер бланка (`260604-646-00000004897`) пробелов не имеет и иначе распирал бы колонку, отбирая
 * ширину у двух соседних.
 *
 * Переключатель дня стоит под сеткой, а не в ней: он относится ко всей строке, и общая высота
 * блоков ему ни к чему.
 */
export function BusyRouteCell({
  entries,
  expanded,
  onToggle,
}: BusyDayProps & { onToggle: () => void }) {
  const shown = shownEntries(entries, expanded);
  if (shown.length === 0) return DASH;
  return (
    <div style={{ overflowWrap: 'anywhere' }}>
      <div className={stackClass(shown)}>
        {shown.map((entry) => (
          <Space key={busyKey(entry)} direction="vertical" size={0} style={{ display: 'flex' }}>
            {entry.kind === 'special' ? DASH : <BusyHead entry={entry} />}
            {entry.kind === 'route' && entry.waybill && (
              <Typography.Text {...SUB}>
                <WaybillNumber number={entry.waybill.number} />
              </Typography.Text>
            )}
            {entry.kind === 'esm2' && (
              <Typography.Text {...SUB}>
                {shortDate(entry.periodFrom)} – {shortDate(entry.periodTo)}
              </Typography.Text>
            )}
          </Space>
        ))}
      </div>
      <BusyMore hidden={entries.length - 1} expanded={expanded} onToggle={onToggle} />
    </div>
  );
}

/**
 * Колонка «Техника»: на чём человек едет — в свёрнутой строке в первой заведённой работе дня, в
 * раскрытой в каждой. Адрес журнала показаний спрашивается снаружи (`hrefOf`), и `null` означает
 * ровно одно: смотрящему показания не положены — тогда номер остаётся текстом. Право проверяет
 * вызывающая сторона, второй двери мимо него здесь нет.
 *
 * Работа названа двумя строками — подписью и маркой. Одной подписи для «на чём он сегодня» мало:
 * госномер не говорит, самосвал это или автовышка, а держат его в голове по машине, не по номеру.
 * Марка приезжает полем (`vehicleModelName`), а не собирается здесь: правило «чем машина подписана»
 * живёт на сервере (`vehicleLabel`), и второй его половине место там же. `null` — марка не заведена,
 * и тогда строка одна: пустая вторая говорила бы о машине неправду видом «подпись и ничего».
 *
 * Строк на работу поэтому две, и обе — строго в одну, лишнее многоточием. Подпись машины не всегда
 * госномер: у арендной это свободное описание, у своей с незаполненным госномером — модель,
 * категория или тип (`vehicleLabel` в `packages/contracts/src/vehicles.ts`). Пущенная в перенос,
 * такая подпись раскладывается в колонке 170 px на три-четыре строки и делает ячейку самой высокой
 * в строке — то есть ровно то, от чего «Заказ/адрес» защищён обрезом, а вся раскладка в три графы
 * затевалась. Общей сетке раскрытого дня две строки не помеха: мерка блока (`.garage-busy-stack`)
 * считана под двухстрочный «Рейс/путевой лист», и «Техника» в неё теперь просто попадает ровно.
 *
 * Обрез отдан antd, и это осознанно проще своего замера: при одной строке `ellipsis` у него — чистый
 * CSS (`text-overflow`), содержимое в JS не режется, и ссылка внутри остаётся настоящей ссылкой —
 * её кликают, Ctrl'ом открывают вкладкой и ведёт она туда же, куда вела. Подсказка при этом
 * всплывает **по факту обреза**: antd сам сверяет ширину содержимого с шириной ячейки, и над
 * госномером, поместившимся целиком, подсказки не будет вовсе. В jsdom раскладки нет, обе ширины
 * нулевые — там эта подсказка молчит всегда, и проверять её тестами нечем.
 */
export function BusyVehicleCell({
  entries,
  expanded,
  hrefOf,
}: BusyDayProps & { hrefOf: (vehicleId: string) => string | null }) {
  const shown = shownEntries(entries, expanded);
  if (shown.length === 0) return DASH;
  return (
    <div className={stackClass(shown)}>
      {shown.map((entry) => (
        // Обёртка блочная (`display: flex` у `Space`): высоту сетки меряют по ней, а
        // `Typography.Text` — строчный элемент, и от его ширины по содержимому обрезаться было бы
        // нечему.
        <Space key={busyKey(entry)} direction="vertical" size={0} style={{ display: 'flex' }}>
          <Typography.Text ellipsis={{ tooltip: entry.vehicleLabel }}>
            <EntityLink to={hrefOf(entry.vehicleId)} title="Открыть журнал показаний">
              {entry.vehicleLabel}
            </EntityLink>
          </Typography.Text>
          {entry.vehicleModelName && (
            <Typography.Text {...SUB} ellipsis={{ tooltip: entry.vehicleModelName }}>
              {entry.vehicleModelName}
            </Typography.Text>
          )}
        </Space>
      ))}
    </div>
  );
}

/**
 * Обрезано ли содержимое ячейки: полная высота против видимой. Клэмп задан стилями
 * (`-webkit-line-clamp`), и узнать о нём иначе нельзя — замер тот же, каким `ExpandableCell` решает,
 * показывать ли переключатель «развернуть». Наблюдатель нужен потому, что ширина колонки меняется
 * вместе с окном: состав, помещавшийся в две строки, при сужении перестаёт помещаться.
 *
 * В jsdom раскладки нет вовсе — обе высоты нулевые, — и ответ там всегда «не обрезано». Проверкам
 * это не мешает: подсказки по обрезу в тестах и не увидеть.
 */
function useClipped(content: unknown) {
  const ref = useRef<HTMLDivElement>(null);
  const [clipped, setClipped] = useState(false);
  useLayoutEffect(() => {
    const el = ref.current;
    if (!el) return;
    const measure = () => setClipped(el.scrollHeight - el.clientHeight > 1);
    measure();
    const observer = new ResizeObserver(measure);
    observer.observe(el);
    return () => observer.disconnect();
  }, [content]);
  return { ref, clipped };
}

/**
 * Куда едет одна работа: состав рейса, «откуда — куда» перегона, площадка заказа со сроком и
 * состоянием смены. Колонка узкая, а состав бывает и из трёх заявок: содержимое обрезано двумя
 * строками (`garage-busy-order`), полное едет подсказкой. Обрез, а не перенос: ячейки строки стоят
 * вровень, и разросшийся состав увёл бы соседние колонки вниз, разорвав чтение поперёк, — а в
 * раскрытой строке ещё и развалил бы общую сетку работ.
 *
 * Подсказка — только когда есть что показать сверх видимого. У соседней «Техники» это делает сам
 * antd, а здесь замер свой, и вот почему: обрез двухстрочный, а многострочный `ellipsis` antd режет
 * текст в JS и требует строкового содержимого — здесь же внутри живые ссылки на заявки, и он
 * превратил бы их в строку. Замер по высоте (`useClipped`) обходится тем же наблюдателем, что у
 * `ExpandableCell`, и оставляет разметку нетронутой.
 *
 * Замер свой у каждой работы, поэтому работа и вынесена в отдельный компонент: хук на ячейку один,
 * а блоков в раскрытой строке столько, сколько за день работ.
 */
function OrderEntry({ entry }: { entry: GarageBusyEntry }) {
  const parts = orderParts(entry);
  const { ref, clipped } = useClipped(entry);
  return (
    // Обёртка стоит всегда, а пустеет заголовок: `Tooltip` без заголовка не всплывает вовсе. Снимать
    // саму обёртку по замеру нельзя — React пересоздал бы `div`, наблюдатель остался бы висеть на
    // оторванном узле, и подсказка, однажды появившись, не исчезла бы уже никогда.
    <Tooltip title={clipped ? orderText(parts) : ''}>
      <div className="garage-busy-order" ref={ref}>
        <OrderParts parts={parts} />
      </div>
    </Tooltip>
  );
}

/**
 * Колонка «Заказ/адрес»: куда едут работы дня — свёрнутой строкой первая, раскрытой все.
 *
 * Прочерк — ответ единственной работы, у которой «куда» нет вовсе (недельный лист без
 * заявки-основания), и ответ пустого дня. В раскрытой строке такая работа оставляет пустой блок:
 * место в общей сетке за ней, и стянись он — соседние графы съехали бы на работу вверх, то есть
 * стали бы отвечать про чужой рейс.
 */
export function BusyOrderCell({ entries, expanded }: BusyDayProps) {
  const shown = shownEntries(entries, expanded);
  const first = shown[0];
  if (!first) return DASH;
  if (shown.length === 1 && orderParts(first).length === 0) return DASH;
  return (
    <div className={stackClass(shown)}>
      {shown.map((entry) => (
        <OrderEntry key={busyKey(entry)} entry={entry} />
      ))}
    </div>
  );
}

/**
 * Три графы дня готовыми колонками таблицы. Заголовки и ширины живут здесь же, рядом с ячейками:
 * раскрытие, обрез подписи машины и переносы номера бланка считаны ровно под эти 180 и 170 px
 * (см. бюджет ширин у `GarageDriversTab`) — разойдись они по двум файлам, первая же правка ширины
 * развела бы их и по делу. Третья графа ширины не просит вовсе: она забирает остаток таблицы —
 * состав рейса и площадка заказа длиннее всего остального в строке.
 *
 * Сортировки у граф нет и быть не может: сервер сортирует водителей только по состоянию и ФИО
 * (`GARAGE_DRIVER_SORT_FIELDS`), а занятость — не поле строки, а её день.
 */
export function busyDayColumns({
  expand,
  hrefOf,
  onCell,
}: {
  /** Раскрытые дни: набор общий на три графы, поэтому и приходит снаружи (`useBusyExpand`). */
  expand: ReturnType<typeof useBusyExpand>;
  /** Адрес журнала показаний по машине; `null` — смотрящему цифры приборов не положены. */
  hrefOf: (vehicleId: string) => string | null;
  /** Оформление ячейки — общее у всех колонок дня, и задаёт его таблица. */
  onCell: () => { className: string };
}): TableColumnType<GarageDriverDto>[] {
  return [
    {
      key: 'busyRoute',
      title: 'Рейс/путевой лист',
      width: 180,
      onCell,
      render: (_v, r) => (
        <BusyRouteCell
          entries={r.busy}
          expanded={expand.isOpen(r.personId)}
          onToggle={() => expand.toggle(r.personId)}
        />
      ),
    },
    {
      key: 'busyVehicle',
      title: 'Техника',
      // 170, а не прежние 140: строк в графе стало две, и на 140 px марка обрезалась бы до двух
      // букв — сказать «самосвал это или автовышка» ей нечем. Прибавка взята у «Удостоверения»
      // (190 → 150), так что нижняя граница ширины таблицы осталась прежней.
      width: 170,
      onCell,
      render: (_v, r) => (
        <BusyVehicleCell entries={r.busy} expanded={expand.isOpen(r.personId)} hrefOf={hrefOf} />
      ),
    },
    {
      key: 'busyOrder',
      title: 'Заказ/адрес',
      onCell,
      render: (_v, r) => <BusyOrderCell entries={r.busy} expanded={expand.isOpen(r.personId)} />,
    },
  ];
}
