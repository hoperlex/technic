import { App } from 'antd';
import { useMutation, useQueryClient } from '@tanstack/react-query';
import { vehicleReadingKeys } from '@entities/vehicle-reading';
import { isApiError } from '@shared/api';
import { errorMessage } from '@shared/lib';

/**
 * Действие разбора в карточке отчёта дня: подтверждение аномалии, решение по расхождению, порядок
 * смен, приведение снимка к источнику (ADR 0103; план «Показания техники», §7, Р19).
 *
 * Обёртка заведена ради двух правил, одинаковых у всех четырёх и разъезжающихся при копировании.
 *
 * 1. **После изменения гасится корень слайса** (Р19), а не ключ карточки. Разбор меняет те же
 *    числа, которые показывают реестр, сводка парка, карточка машины и журнал: подтверждённая
 *    аномалия убирает пометку строки, перестановка смен переписывает разности, перенос уносит
 *    показание в чужой день. Оставь их на своих ключах — и соседний экран показывал бы вчерашнее до
 *    перезагрузки страницы.
 *
 * 2. **409 объясняется словами и закрывает форму.** Все четыре ручки проверяют версию отчёта под
 *    блокировками, и разошедшаяся версия означает ровно одно: подтверждать собирались другое.
 *    Повторять своё не по чему — та же версия даст тот же отказ, — поэтому карточка перечитывается,
 *    а окно закрывается. Серверный текст при этом заменяется своим: он зовёт обновить страницу, а
 *    карточка обновляет себя сама, и просьба сделать это руками читалась бы как поломка.
 *
 * Прочие отказы (400 «снимок уже соответствует источнику», 404) показываются как есть: их сервер
 * объясняет лучше портала, и своей копии этих правил у экрана быть не должно.
 */
export function useIntakeAction<TVars>({
  run,
  done,
  conflict,
  onDone,
}: {
  run: (vars: TVars) => Promise<unknown>;
  /** Что сказать, когда получилось: действие называется в прошедшем времени. */
  done: string;
  /** Чем объяснить 409 — вместе с тем, что карточка уже перечитана. */
  conflict: string;
  /** Закрыть окно действия: после успеха и после конфликта одинаково. */
  onDone?: () => void;
}) {
  const { message } = App.useApp();
  const qc = useQueryClient();

  return useMutation({
    mutationFn: run,
    onSuccess: () => {
      message.success(done);
      void qc.invalidateQueries({ queryKey: vehicleReadingKeys.root });
      onDone?.();
    },
    onError: (error) => {
      if (isApiError(error) && error.status === 409) {
        message.error(conflict);
        void qc.invalidateQueries({ queryKey: vehicleReadingKeys.root });
        onDone?.();
        return;
      }
      message.error(errorMessage(error));
    },
  });
}
