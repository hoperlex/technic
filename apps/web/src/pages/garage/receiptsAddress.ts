import { useSearchParams } from 'react-router';
import { useAddressParam, type AddressParam } from '@shared/lib';

/**
 * Адрес вкладки «Автозапчасти» (план `docs/auto-part-receipts-plan.md`, §8).
 *
 * В адресе живут три предмета, и все три — переходы, а не подстройка экрана: открытая карточка
 * чека, окно «Запчасти машины» и форма приёма чека. Обещаний у такого окна три, и даёт их только
 * адрес: ссылку присылают соседу («вот этот чек», «вот что купили на эту машину»), «назад»
 * закрывает окно, перезагрузка оставляет его открытым.
 *
 * Разбор живёт отдельным модулем, а не в самой вкладке: ключ `?spend=` читают трое — вкладка чеков
 * (техника в строке карточки), колонка «Запчасти, ₽» вкладки «Техника» и блок карточки машины
 * (Р15: окно одно на три входа), — и второй разбор того же ключа разъехался бы с первым при первой
 * правке.
 *
 * Ключ `?date=` сюда не входит вовсе: день среза принадлежит «Технике» и «Водителям», а у чеков
 * свой период — и он живёт отбором списка, а не адресом (память набора, ADR 0139).
 */

/** Открытая карточка чека: `?tab=parts&receipt=<id>` (§8). */
const RECEIPT_PARAM = 'receipt';

/** Окно «Запчасти машины»: `?spend=<vehicleId>` (Р15). Значение — машина, а не окно. */
const SPEND_PARAM = 'spend';

/**
 * Форма приёма чека: `?newReceipt=1`. Значение не смотрится — важен факт присутствия ключа, как у
 * `?routes=1` и `?ticketAudit`: заводимого чека ещё нет, и называть в адресе нечего.
 */
const NEW_RECEIPT_PARAM = 'newReceipt';

/**
 * Открытая карточка чека.
 *
 * `allowed` — не про право: чеки читают все, кому виден гараж (Р5), и своего права у карточки нет.
 * Спрашивается активная вкладка: скрытые вкладки остаются смонтированными (`PageTabs`), а окно
 * рисуется порталом в тело документа — без этой проверки карточка, названная в адресе, висела бы
 * поверх соседней вкладки, где её никто не звал.
 */
export function useReceiptAddress(allowed: boolean): AddressParam {
  return useAddressParam(RECEIPT_PARAM, allowed);
}

/**
 * Окно «Запчасти машины»: в `id` — машина, чьи покупки открыты.
 *
 * `allowed` спрашивается у каждого входа своим: окно одно, а мест, откуда его открывают, три
 * (Р15), и смонтированы они одновременно — на разных вкладках одной страницы. Отвечать на ключ
 * обязан ровно тот, кто сейчас на виду, иначе присланная ссылка открыла бы два одинаковых окна
 * друг поверх друга.
 */
export function useVehicleSpendAddress(allowed: boolean): AddressParam {
  return useAddressParam(SPEND_PARAM, allowed);
}

/** Открыта ли форма приёма чека и как ею управлять. */
export interface NewReceiptAddress {
  opened: boolean;
  open: () => void;
  close: () => void;
}

/**
 * Форма «Принять чек» (§8).
 *
 * В адресе, а не в состоянии вкладки, по той же причине, что и оба окна рядом: «назад» обязано
 * закрывать форму, а не уводить со страницы, и вернувшийся по ссылке человек должен получить то
 * же, что ему прислали. Своего идентификатора у неё нет — чек ещё не заведён, — поэтому ключ
 * работает флагом.
 *
 * `allowed` здесь **про право**, в отличие от карточки: принимает чеки держатель
 * `autoParts.manage` (Р12), и открытая по чужой ссылке форма кончалась бы отказом сервера на
 * сохранение — то есть после набора всего чека целиком.
 */
export function useNewReceiptAddress(allowed: boolean): NewReceiptAddress {
  const [params, setParams] = useSearchParams();

  const patch = (change: (next: URLSearchParams) => void, replace: boolean) => {
    const next = new URLSearchParams(params);
    change(next);
    setParams(next, { replace });
  };

  return {
    opened: allowed && params.has(NEW_RECEIPT_PARAM),
    /** Открытие — переход: «назад» после него закрывает форму, а не уводит из гаража. */
    open: () => patch((next) => next.set(NEW_RECEIPT_PARAM, '1'), false),
    /**
     * Закрытие — заменой записи в истории: «назад» после него возвращает туда, откуда пришли, а
     * не открывает форму заново — с уже потерянным вводом.
     */
    close: () => patch((next) => next.delete(NEW_RECEIPT_PARAM), true),
  };
}
