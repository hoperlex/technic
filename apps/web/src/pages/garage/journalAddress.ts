import { useAddressParam, type AddressParam } from '@shared/lib';

/**
 * Открытый журнал показаний машины в адресе вкладки «Техника»: `?tab=vehicles&date=…&journal=<id>`.
 *
 * **Читается он из самого адреса, а не из состояния таблицы**, и это не выбор места хранения.
 * Отбор вкладки живёт в `useListParams` — это обычный `useState`: положенный туда ключ в адрес не
 * попадает и из адреса не читается. Ссылка «журнал» в колонке при этом вела на `?journal=<id>` —
 * и на десктопе меняла адрес, не открывая ничего, тогда как на телефоне то же окно открывалось
 * обработчиком карточки и работало. Дефект приехал с гаражом (ADR 0076, 0103), а не с показаниями.
 *
 * Сам приём — общий (`useAddressParam`): тем же живут сводка ТО в соседней колонке и в справочнике
 * техники (`features/vehicle-maintenance`), а карточка машины и отчёт на вкладке «Показания» — их
 * собственным разбором нескольких ключей (`readingsAddress.ts`). Здесь остаётся имя ключа и
 * причина, по которой он живёт в адресе.
 */

const JOURNAL_PARAM = 'journal';

/**
 * `allowed` — есть ли у смотрящего `vehicleReadings.read`. Без права параметр не читается вовсе:
 * у среза дня своё право (`garage.read`), а цифры приборов и подписи водителей открывает модуль
 * показаний, и присланная ссылка иначе открывала бы окно, которому нечего показать.
 *
 * В `id` — машина, чей журнал открыт: ключ называет предмет окна, а не само окно.
 */
export function useJournalAddress(allowed: boolean): AddressParam {
  return useAddressParam(JOURNAL_PARAM, allowed);
}
