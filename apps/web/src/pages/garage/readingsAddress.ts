import dayjs from 'dayjs';
import { useSearchParams } from 'react-router';

/**
 * Адрес вкладки «Показания» (план «Показания техники», Р1 и Р29).
 *
 * Адрес называет предмет, а не только вкладку: подвкладку, период сводки и открытую карточку
 * машины. Половина пользы этих экранов — ссылка, которую отправляют соседу («вот эта машина за
 * июль»), и состояние, живущее в `useState`, такой ссылки не даёт: оно теряется от перезагрузки,
 * от «назад» и от пересылки.
 *
 * Разбор живёт отдельным модулем, а не в самих экранах: параметры одни, а читают их трое — сама
 * страница гаража (подвкладка), сводка (период с карточкой) и реестр приёма (период с открытым
 * отчётом), — и второй разбор тех же ключей разъехался бы с первым при первой правке.
 *
 * Ключ `?date=` сюда не входит: это день среза вкладок «Техника» и «Водители», а у показаний свой
 * период — от него отсчитывается только умолчание.
 */

const DATE = 'YYYY-MM-DD';

/**
 * Подвкладки «Показаний» (Р1): реестр приёма и сводка. Порядок — тот же, в каком они стоят полосой:
 * приём слева, потому что с него начинают день.
 */
export const READINGS_SUBS = ['intake', 'stats'] as const;
export type ReadingsSub = (typeof READINGS_SUBS)[number];

/**
 * Подвкладка из адреса. Незнакомое значение и пустое дают статистику — она умолчание (Р1): ссылки
 * `?tab=readings&sub=stats` разосланы с этапа 2, и менять умолчание молча нельзя.
 */
export function readingsSub(params: URLSearchParams): ReadingsSub {
  const raw = params.get('sub') ?? '';
  return (READINGS_SUBS as readonly string[]).includes(raw) ? (raw as ReadingsSub) : 'stats';
}

/**
 * Окно приёмки по умолчанию — неделя, кончающаяся днём среза.
 *
 * Приём открывают утром вопросом «что вчера не сдали», и одного дня для ответа мало: просрочка
 * начинается с трёх дней (`READING_OVERDUE_DAYS`), а после выходных в понедельник ждут показаний
 * сразу за пятницу, субботу и воскресенье. Неделя накрывает и то, и другое: красная строка успевает
 * покраснеть в пределах видимого окна, а не всплыть из прошлого, куда никто не смотрит. Месяц
 * сводки здесь не годится — он отвечает на вопрос «сколько проехали», а не «с кого ждём».
 */
const INTAKE_WINDOW_DAYS = 7;

/**
 * День из адреса. Формат проверяется выражением, а не строгим разбором dayjs: строгий режим живёт
 * в плагине `customParseFormat`, которого портал не подключает, и молча превратился бы в
 * нестрогий — тогда `from=вчера` стал бы «сегодня», а не умолчанием.
 */
function day(raw: string | null): string | null {
  if (!raw || !/^\d{4}-\d{2}-\d{2}$/.test(raw)) return null;
  return dayjs(raw).isValid() ? raw : null;
}

export interface ReadingsAddress {
  /** Открытая подвкладка (`?sub=`): реестр приёма либо сводка. */
  sub: ReadingsSub;
  setSub: (next: ReadingsSub) => void;
  /**
   * Период подвкладки: `[from, to]` из адреса либо умолчание — своё у каждой (месяц у сводки,
   * неделя у приёма).
   */
  period: [string, string];
  setPeriod: (from: string, to: string) => void;
  /** Машина, чья карточка открыта (`?vehicle=`), либо `null` — открытой карточки нет. */
  vehicleId: string | null;
  openVehicle: (id: string | null) => void;
  /** Отчёт дня, открытый на разбор (`?report=`, Р29), либо `null`. */
  reportId: string | null;
  openReport: (id: string | null) => void;
}

/** Умолчание периода: у подвкладок оно разное, потому что вопросы у них разные. */
function defaultPeriod(sub: ReadingsSub, date: string): [string, string] {
  if (sub === 'intake') {
    return [
      dayjs(date)
        .subtract(INTAKE_WINDOW_DAYS - 1, 'day')
        .format(DATE),
      date,
    ];
  }
  return [dayjs(date).startOf('month').format(DATE), date];
}

/**
 * Адрес карточки машины: `?tab=readings&sub=stats&vehicle=<id>&from=…&to=…` (Р2, Р29).
 *
 * Нужен он переходу из гаража: строка вкладки «Техника» ведёт в три места (§7) — в журнал
 * показаний, в сводку ТО и сюда, в статистику машины за период. Обратный путь (из сводки ТО в
 * карточку) существовал с самого начала, а этот — нет: из гаража в статистику машины попасть было
 * нельзя вовсе.
 *
 * **Период — умолчание сводки, отсчитанное от дня среза**: месяц по этот день включительно.
 * Одним днём карточку открывать нечем — «сколько проехали за 24 июля» это одна пара снимков,
 * пустая помесячная таблица и диаграмма из одного столбика, тогда как карточка отвечает на вопрос
 * «из чего сложился пробег». А конец периода — именно день среза, а не сегодня: одометр и ТО в той
 * же строке показаны не позже него (Р16), и карточка, открытая из строки, обязана говорить про то
 * же время, что и строка.
 *
 * **Период пишется в адрес числами, а не оставляется умолчанию**, хотя сегодня они совпадают:
 * ссылку отправляют соседу («вот эта машина за июль»), и отрезок в ней должен быть назван, а не
 * вычислен из соседнего ключа, который принадлежит другим вкладкам и однажды может до показаний не
 * доехать.
 *
 * Собирается адрес с нуля, а не поверх текущих ключей: общий у «Техники» и «Показаний» ровно один
 * ключ — день среза, а открытые окна вкладки (`journal`, `maintenance`) принадлежат ей, а не той,
 * куда переходят. Отбор строк в адресе не живёт вовсе (`useListParams` — это `useState`), и терять
 * с переходом нечего.
 */
export function vehicleCardHref(vehicleId: string, date: string): string {
  const [from, to] = defaultPeriod('stats', date);
  const next = new URLSearchParams({
    tab: 'readings',
    sub: 'stats',
    date,
    vehicle: vehicleId,
    from,
    to,
  });
  return `?${next.toString()}`;
}

/**
 * Подвкладка, период и открытый предмет в адресе.
 *
 * `date` — день среза страницы: от него отсчитывается умолчание периода, потому что обе подвкладки
 * открывают про то же время, которое смотрят на соседних вкладках, — сводку вопросом «что в этом
 * месяце», приём вопросом «что не сдано за последние дни». Мусор в параметрах даёт умолчание, а не
 * пустой экран: адрес приходит из закладки и из чужого сообщения, и портал обязан открыться при
 * любом.
 */
export function useReadingsAddress(date: string): ReadingsAddress {
  const [params, setParams] = useSearchParams();

  const sub = readingsSub(params);
  const from = day(params.get('from'));
  const to = day(params.get('to'));
  // Перевёрнутый период сервер не примет, а показать его нечем: обе границы уходят в умолчание —
  // так у ошибки в ссылке одна судьба, а не две («молча поменяли местами» тоже догадка).
  const ordered = from !== null && to !== null && from <= to;

  const period: [string, string] = ordered ? [from, to] : defaultPeriod(sub, date);

  const patch = (change: (next: URLSearchParams) => void, replace: boolean) => {
    const next = new URLSearchParams(params);
    change(next);
    setParams(next, { replace });
  };

  return {
    sub,
    /**
     * Переключение подвкладки уносит период с собой: у приёма и сводки разные вопросы и разные
     * окна, и месяц, выбранный для «сколько проехали», в реестре приёма означал бы просьбу показать
     * месяц ожидаемых смен — там, где спрашивают про последние дни. Уходит он в умолчание, а не в
     * запомненное значение: второй период в адресе назывался бы теми же ключами.
     *
     * Ссылке это не мешает: `?sub=intake&from=…&to=…` открывает ровно то, что в ней написано, —
     * период стирается при нажатии на полосу, а не при разборе адреса.
     */
    setSub: (next) =>
      patch((p) => {
        p.set('sub', next);
        p.delete('from');
        p.delete('to');
      }, true),

    period,
    // Перебор периодов — не история переходов: «назад» должно возвращать на предыдущий экран, а не
    // отматывать по одному выбранному отрезку. Та же причина, по которой день среза пишется
    // заменой.
    setPeriod: (nextFrom, nextTo) =>
      patch((next) => {
        next.set('from', nextFrom);
        next.set('to', nextTo);
      }, true),

    vehicleId: params.get('vehicle') || null,
    /**
     * Открытая карточка — переход, а не подстройка экрана: «назад» обязано её закрыть и вернуть к
     * списку, поэтому запись идёт в историю. Период же пишется заменой — перебор отрезков историей
     * не является.
     */
    openVehicle: (id) =>
      patch((next) => {
        if (id) next.set('vehicle', id);
        else next.delete('vehicle');
      }, false),

    reportId: params.get('report') || null,
    /**
     * Открытый на разбор отчёт (Р29). Пишется так же, как карточка машины, и по той же причине:
     * ссылку «вот этот день Петрова» отправляют соседу, а «назад» обязано закрыть разбор и вернуть
     * к реестру.
     */
    openReport: (id) =>
      patch((next) => {
        if (id) next.set('report', id);
        else next.delete('report');
      }, false),
  };
}
