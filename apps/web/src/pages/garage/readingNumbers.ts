/**
 * Как показания печатаются числом (ADR 0103; план «Показания техники», Р27, Р28).
 *
 * Отдельным модулем, а не копией в каждом экране: прочерк вместо нуля — это не оформление, а
 * утверждение о данных («пары снимков в периоде не осталось, о пробеге он не говорит»). Две копии
 * такого правила разъезжаются при первой правке, и тогда одно и то же число на сводке парка и в
 * карточке машины читалось бы по-разному — а сводка ровно из карточек и складывается.
 *
 * Производных здесь нет: ничего, поделённого на пробег или наработку. Сам расход в модуле с
 * приходом норм появился (ADR 0194) и печатается теми же `decimal`/прочерком, что остальные числа,
 * — а вот «на сто километров» так и не завелось: это самостоятельная оценка, а не подпись к числу.
 */

/** Прочерк вместо числа: неизвестное значение не притворяется нулём. */
export function decimal(value: number | null, digits = 1): string {
  return value === null ? '—' : value.toFixed(digits).replace('.', ',');
}

/**
 * Нижняя граница показателя: пары снимков были, но ряд между ними рвался.
 *
 * Прочерк и заниженное число — разные виды незнания, и до сих пор виден был только первый.
 * `distanceKm === null` значит «пар снимков не осталось вовсе»: о пробеге такой период не говорит
 * ничего, и прочерк это честно называет. А вот `distanceKm = 8340` при `odometerGaps = 2` —
 * полноценное с виду число, которое на деле **занижено**: два участка ряда в сумму не пошли, и
 * машина проехала не меньше показанного. Без оговорки его читают как точное — и сверяют с
 * путевыми листами, недоумевая, куда делись сотни километров.
 *
 * Правило одно на карточку: итог, помесячная таблица и диаграмма спрашивают отсюда, а не каждый
 * у себя. Топлива это не касается: литры не разность соседних снимков, а сумма заправок за смены,
 * и разрыв цепочки счётчика их не уменьшает.
 */
export function isLowerBound(value: number | null, gaps: number): boolean {
  return value !== null && gaps > 0;
}

/** «не меньше 8 340» — та же цифра, но с оговоркой, из-за которой её не примут за точную. */
export function boundedDecimal(value: number | null, gaps: number, digits = 1): string {
  const text = decimal(value, digits);
  return isLowerBound(value, gaps) ? `не${NBSP}меньше${NBSP}${text}` : text;
}

