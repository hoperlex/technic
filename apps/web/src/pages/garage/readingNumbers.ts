import dayjs from 'dayjs';

/**
 * Как показания печатаются числом (ADR 0103; план «Показания техники», Р27, Р28).
 *
 * Отдельным модулем, а не копией в каждом экране: прочерк вместо нуля — это не оформление, а
 * утверждение о данных («пары снимков в периоде не осталось, о пробеге он не говорит»). Две копии
 * такого правила разъезжаются при первой правке, и тогда одно и то же число на сводке парка и в
 * карточке машины читалось бы по-разному — а сводка ровно из карточек и складывается.
 *
 * Производных здесь нет и не будет: ничего, поделённого на пробег или наработку. Причина записана
 * в шапке [ReadingsStatsTab](./ReadingsStatsTab.tsx) — расход требует остатков в баке, которых
 * портал не хранит, а любая цифра «на сто километров» читается как расход независимо от подписи.
 */

/** Прочерк вместо числа: неизвестное значение не притворяется нулём. */
export function decimal(value: number | null, digits = 1): string {
  return value === null ? '—' : value.toFixed(digits).replace('.', ',');
}

/** Неразрывный: «128 400 км» не должно переноситься на две строки посреди числа. */
const NBSP = ' ';

/**
 * Нижняя граница показателя: пары снимков были, но ряд между ними рвался.
 *
 * Прочерк и заниженное число — разные виды незнания, и до сих пор виден был только первый.
 * `distanceKm === null` значит «пар снимков не осталось вовсе»: о пробеге такой период не говорит
 * ничего, и прочерк это честно называет. А вот `distanceKm = 8340` при `odometerGaps = 2` —
 * полноценное с виду число, которое на деле **занижено**: два участка ряда в сумму не пошли, и
 * машина проехала не меньше показанного. Без оговорки его читают как точное — и сверяют с
 * путевыми листами, недоумевая, куда делись сотни километров.
 *
 * Правило одно на карточку: итог, помесячная таблица и диаграмма спрашивают отсюда, а не каждый
 * у себя. Топлива это не касается: литры не разность соседних снимков, а сумма заправок за смены,
 * и разрыв цепочки счётчика их не уменьшает.
 */
export function isLowerBound(value: number | null, gaps: number): boolean {
  return value !== null && gaps > 0;
}

/** «не меньше 8 340» — та же цифра, но с оговоркой, из-за которой её не примут за точную. */
export function boundedDecimal(value: number | null, gaps: number, digits = 1): string {
  const text = decimal(value, digits);
  return isLowerBound(value, gaps) ? `не${NBSP}меньше${NBSP}${text}` : text;
}

/**
 * Почему число занижено — человеческими словами, а не «gaps > 0». Текст один на все три места:
 * в итоге, в ячейке месяца и в подсказке диаграммы он обязан звучать одинаково, иначе одно и то же
 * свойство данных читается как три разных предупреждения.
 */
export const LOWER_BOUND_HINT =
  'Показанное занижено: ряд рвался — сброшенный счётчик или смена без показаний. Участок от ' +
  'разрыва до соседнего снимка посчитать не по чему, и в число он не вошёл. На деле — не меньше ' +
  'показанного.';

/**
 * «128 400 км» — разряды пробелами. Ровно та же запись, что у колонки одометра в гараже
 * ([odometerColumn](./odometerColumn.tsx)): одно и то же показание на двух экранах обязано
 * выглядеть одинаково, иначе его начинают сверять глазами.
 */
export function kmText(km: number): string {
  return `${String(km).replace(/\B(?=(\d{3})+(?!\d))/gu, NBSP)}${NBSP}км`;
}

/**
 * «июль 2026» из `2026-07`. Месяц приходит строкой с сервера — он считается по правилу «пара
 * разностей идёт в месяц текущего снимка» (Р4), и портал его не выводит, а только называет
 * по-русски.
 */
export function monthLabel(month: string): string {
  return dayjs(`${month}-01`).format('MMMM YYYY');
}

/**
 * «июнь 26» — подпись под столбиком диаграммы. Год обрезан не для красоты: месяцев в периоде бывает
 * двенадцать, и полная запись «июнь 2026» под каждым из них либо наезжает на соседнюю, либо
 * заставляет вертеть подписи набок. Год при этом остаётся: период умеет пересекать новый год, и
 * два «января» подряд без него неразличимы.
 */
export function monthShort(month: string): string {
  return dayjs(`${month}-01`).format('MMM YY');
}
