import {
  CANDIDATE_PENDING_ACCEPT_REFUSAL,
  serviceRequestStatusLabels,
  type ServiceRequestStatus,
  type ServiceRequestDto,
  serviceResumeTarget,
} from '@technic/contracts';
import { isSubjectCheckPending } from '@entities/office-equipment-candidate';
import type { ActionSheetItem } from '@shared/ui';

/**
 * Список переходов, который открывает тег статуса (ADR 0161), — **проекция набора действий**, а не
 * второй перебор коридора.
 *
 * Почему не перебор `allowedServiceStatusTransitions` прямо в ячейке, как это сделано в «Вывозе
 * мусора» и «Заказе ТС». У тех модулей переход и есть действие: пара «откуда → куда» однозначно
 * называет и ручку, и окно, поэтому ячейка перебирает коридор, а содержание подбирает
 * маршрутизатор. У оргтехники после ADR 0125 это неверно трижды:
 *
 *  - из «В работе» в «Отменена» ведут ДВА разных действия — «Отменить заявку» (причина) и «Не
 *    согласовать объём работ» (причина, решение и пометка замены). Пара статусов их не различает;
 *  - половина главных шагов статуса не меняет вовсе (назначение, согласование), и список переходов
 *    меню действий не заменяет — он его подмножество;
 *  - цель возврата из «Отложена» динамическая (`held_from_status`), таблицей она не выражается.
 *
 * Перебор пришлось бы дополнить картой «пара статусов → окно» — второй картой правил портала,
 * которая разошлась бы с набором действий на первом же изменении цикла, и разошлась бы МОЛЧА.
 * Поэтому пункт сам говорит, куда ведёт (`toStatus`), — ровно так же, как признаком `primary` он
 * говорит, что он главный шаг состояния (Р117 плана модернизации).
 */

/** Пункт набора действий заявки, знающий, куда он заявку переведёт. */
export interface ServiceMenuItem extends ActionSheetItem {
  /**
   * Статус, в котором заявка окажется после этого действия. Поля нет — действие статуса не меняет
   * (назначение, отказ, объём работ, согласование, срочность, обсуждение, перемещение), и в списке
   * переходов ему делать нечего.
   *
   * Проставляется рядом с `onClick`, в одной строке кода с предикатом, который пункт открыл: карта
   * «ключ пункта → статус», собранная отдельно, была бы той самой второй картой правил. Забыть поле
   * можно — караул `service-status-choices.test.ts` сверяет множество целевых статусов с коридором
   * контрактов.
   */
  toStatus?: ServiceRequestStatus;
  /**
   * Как назвать действие в списке переходов, если подпись меню читается там плохо. Нужна ровно
   * там, где подпись повторила бы имя статуса: «Новая» · вернуть в «Новую».
   */
  transitionLabel?: string;
}

/**
 * Куда ведёт пункт с учётом заморозки: у возврата цель динамическая и берётся из самой заявки
 * (ADR 0125, Р104 — дугу назад показывают, а не выбирают).
 *
 * `undefined` у пункта возобновления возможен только у заявки, которая не отложена, — а такого
 * пункта в наборе не бывает: его заводит та же ветка, что читает статус `on_hold`. Ответ на этот
 * случай — «в списке переходов пункта нет»: обещать статус, которого не знаем, нельзя.
 */
function targetOf(item: ServiceMenuItem, request: ServiceRequestDto): ServiceRequestStatus | null {
  if (item.key === 'resume') return serviceResumeTarget(request);
  return item.toStatus ?? null;
}

/**
 * Пункты списка переходов: те действия набора, которые двигают статус, подписанные целевым статусом
 * и самим действием.
 *
 * Подпись — «<статус> · <действие>»: человек открыл тег вопросом «куда отсюда можно», и первым
 * словом обязан быть ответ на него; вторым — чем это делается, иначе два пути в «Отменена»
 * неразличимы. Выключенность и её причина переносятся целиком (ADR 0161, решение 5): пункт
 * «Решена · закрыть работы» у заявки без закрывающего документа виден, неактивен и объясняет себя.
 */
export function serviceStatusChoices(
  items: ServiceMenuItem[],
  request: ServiceRequestDto,
): ActionSheetItem[] {
  const choices: ActionSheetItem[] = [];
  for (const item of items) {
    const to = targetOf(item, request);
    if (!to) continue;
    const action = item.transitionLabel ?? item.label.toLowerCase();
    choices.push({
      ...item,
      label: `«${serviceRequestStatusLabels[to]}» · ${action}`,
    });
  }
  return choices;
}

/**
 * Замок приёмки, пока сообщение о технике ещё на проверке (план
 * `docs/office-equipment-candidate-plan.md`, Р16, §8 последний абзац).
 *
 * ПОЧЕМУ ЗАПРЕТ ИМЕННО НА ПРИЁМКЕ, А НЕ НА ВХОДЕ В РАБОТУ. Ремонт нельзя тормозить проверкой
 * справочника: принтер сломан сейчас, и заявка живёт обычной жизнью — её видят, назначают,
 * обсуждают, по ней едут и переводят в «Решена». Но принимать работу, пока проверка не дала ни
 * карточку, ни отказ, нельзя: исход может сменить подпись предмета и гарантийный контекст уже
 * после приёмки. Замок поздний, узкий и дешёвый; ранний стоил бы работы людям, к справочнику
 * отношения не имеющим.
 *
 * ПУНКТ ОСТАЁТСЯ ВИДИМЫМ И НЕАКТИВНЫМ — тем же приёмом, что у планки закрывающего документа:
 * спрятанный, он читался бы как «мне это не положено», а причина запрета другая и написана рядом.
 * `primary` при этом снимается: звать «Вам: примите работу» к запертой кнопке значит звать в никуда.
 *
 * ОТДЕЛЬНОЙ ФУНКЦИЕЙ РЯДОМ С ДРУГИМИ ПЕРЕВОДАМИ КАРТОЧКИ, а не тремя строками в самом пункте: слова
 * отказа общие с сервером (`CANDIDATE_PENDING_ACCEPT_REFUSAL`), и место, где они склеиваются с
 * состоянием кандидата, обязано быть одно — иначе быстрая смена статуса, переносящая `disabled` на
 * тег, соберёт замок вторым способом и разойдётся с меню.
 */
export function serviceAcceptLock(
  request: ServiceRequestDto,
): Pick<ServiceMenuItem, 'primary' | 'disabled' | 'disabledReason'> {
  const pending = isSubjectCheckPending(request);
  return {
    primary: !pending,
    disabled: pending,
    disabledReason: pending ? CANDIDATE_PENDING_ACCEPT_REFUSAL : undefined,
  };
}
