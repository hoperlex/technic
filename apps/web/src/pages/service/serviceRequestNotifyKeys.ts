/**
 * Ключи идемпотентности повторного письма службе (Р70) — по заявке, а не по набору действий
 * (ADR 0140).
 *
 * Наборов действий заявке положено два: окна списка живут на странице, окна карточки — внутри
 * карточки, и хук, который их строит, вызывается дважды. Лежи ключ в состоянии хука, у каждого
 * набора оказался бы свой — и повтор, оборвавшийся сетевой ошибкой в меню карточки, ушёл бы из
 * меню строки списка под новым ключом, то есть вторым письмом службе. Ровно от этого ключ и
 * заведён, поэтому величина у него общая: она принадлежит заявке, а не месту, откуда нажали.
 *
 * Ключ живёт до успеха: два нажатия подряд дают одно письмо, а осознанный повтор после ответа —
 * новое.
 */
const keys = new Map<string, string>();

/** Ключ текущего повтора: заводится при первом нажатии и держится до успеха. */
export function serviceNotifyKey(requestId: string): string {
  const known = keys.get(requestId);
  if (known) return known;
  const fresh = crypto.randomUUID();
  keys.set(requestId, fresh);
  return fresh;
}

/** Письмо ушло — следующий повтор будет новым письмом, а не повтором этого. */
export function forgetServiceNotifyKey(requestId: string): void {
  keys.delete(requestId);
}
