import type { ServiceMenuItem } from './serviceStatusChoices';

/**
 * Где какой пункт действий заявки показывается — и чего в каком меню нет.
 *
 * Один модуль на оба места показа, потому что вопрос один: «сколько у действия входов». Держи мы
 * эти наборы там, где они применяются, — в сетке списка и в карточке, — расходились бы они молча:
 * пункт, вычеркнутый из карточки, но забытый в списке, выглядит не ошибкой, а решением.
 *
 * Правило, которому оба набора подчиняются: **вычеркнуть пункт можно только там, где у действия
 * есть другой вход в том же месте**. Спрятать его без замены значит отнять работу, а не убрать
 * дубль. Караул `service-request-entries.test.tsx` проверяет именно это, и наборы отсюда — то, что
 * он читает.
 *
 * Сами пункты никуда не деваются: доступность считают предикаты контрактов, набор действий
 * остаётся полным, и вынесенные кнопки берут из него **готовый** пункт с его `onClick`,
 * выключенностью и причиной. Здесь решается только место показа.
 */

/**
 * Чего нет в меню списка НИ В ОДНОМ из двух его видов — ни в строке на десктопе, ни в карточке на
 * телефоне.
 *
 * Перемещение техники правит мастер-данные справочника, и делать это, не открыв заявку, — источник
 * ровно тех расхождений «где записано» и «где стоит», ради которых заведён отдельный разбор
 * (backlog §12). Поэтому вход у него один и в карточке заявки: кнопка рядом с полем «Какой
 * аппарат», там же, где реквизиты и читают.
 */
const HIDDEN_EVERYWHERE_IN_LIST = new Set<string>(['move-equipment']);

/**
 * Чего нет в меню СТРОКИ на десктопе — сверх общего списка выше.
 *
 * Назначение вычеркнуто отсюда и **только отсюда**: в строке у него есть своя кнопка
 * (`AssignButton`), а в карточке списка на телефоне кнопок нет вовсе — там ряд действий и есть шит,
 * и пункт в нём остаётся основным входом. Разделение наборов по видам списка выглядит
 * непоследовательностью ровно до того момента, пока не спросить «где человек нажмёт»: на телефоне
 * вычеркнутый пункт означал бы отнятое переназначение, а не убранный дубль.
 */
export const HIDDEN_IN_ROW_MENU = new Set<string>([...HIDDEN_EVERYWHERE_IN_LIST, 'assign']);

/** Чего нет в меню карточки СПИСКА (телефон): только общее — кнопок здесь нет ни у чего. */
export const HIDDEN_IN_CARD_LIST_MENU = new Set<string>(HIDDEN_EVERYWHERE_IN_LIST);

/**
 * Чего нет в меню КАРТОЧКИ.
 *
 * У каждого из этих пунктов в карточке есть своё место — то, где читают ответ, к которому действие
 * относится (ADR 0140): состав исполнителей правят у поля «Исполнители», номенклатуру — на её
 * вкладке, обсуждение открывают кнопкой со счётчиком (у неё ещё и счётчик непрочитанного, которого
 * меню не показывает), решения по объёму работ принимают кнопками под самой таблицей — все три,
 * включая возврат в правку, — правку заявки открывает главная кнопка подвала, а перемещение
 * записывают у реквизитов аппарата. Второй ручке к тому же действию в том же окне взяться
 * неоткуда: она заставляла бы выбирать между двумя одинаковыми дорогами.
 *
 * Условия у пункта и у его кнопки одни и те же, и это проверяется: правку открывает тот же
 * `isServiceRequestEditable` + `serviceRequests.update`, решения по объёму работ берутся из того же
 * набора действий. Разойдись они — вычеркнутый пункт остался бы без замены, и караул состава
 * (`service-request-entries.test.tsx`) покраснел бы на пустой клетке «второго входа».
 *
 * `start` здесь намеренно отсутствует: он вынесен кнопкой подвала, но из меню не вычеркнут — на
 * телефоне подвал узкий, и шит остаётся единственным надёжным адресом главного шага.
 */
export const HIDDEN_IN_CARD_MENU = new Set<string>([
  'assign',
  'chat',
  'consumables',
  'approve',
  'reject',
  'reopen',
  'edit',
  'move-equipment',
]);

/** Меню строки списка (десктоп): без того, чей вход живёт кнопкой рядом или в карточке заявки. */
export function rowMenuItems(items: ServiceMenuItem[]): ServiceMenuItem[] {
  return items.filter((item) => !HIDDEN_IN_ROW_MENU.has(item.key));
}

/** Меню карточки списка (телефон): здесь снято только то, чей вход живёт в карточке заявки. */
export function cardListMenuItems(items: ServiceMenuItem[]): ServiceMenuItem[] {
  return items.filter((item) => !HIDDEN_IN_CARD_LIST_MENU.has(item.key));
}

/** Меню карточки: набор действий без тех, у кого в самой карточке есть своё место. */
export function cardMenuItems(items: ServiceMenuItem[]): ServiceMenuItem[] {
  return items.filter((item) => !HIDDEN_IN_CARD_MENU.has(item.key));
}
