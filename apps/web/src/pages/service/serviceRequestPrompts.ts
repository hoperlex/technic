import { serviceRequestsApi } from '@entities/service-request';
import type { ServiceRequestDto } from '@technic/contracts';

/** Действие, которому нужна причина: окно одно, различаются подписи и сама ручка. */
export interface ReasonPrompt {
  title: string;
  label: string;
  okText: string;
  danger?: boolean;
  success: string;
  submit: (reason: string) => Promise<unknown>;
  /**
   * Что заявка потеряет по нажатию (ADR 0161, решение по перечню потерь). Пусто — терять нечего,
   * и блок не рисуется вовсе: пустой список «будет стёрто» читается как недогрузившийся, а не как
   * «ничего не пропадёт».
   *
   * Перечень собирается ПО САМОЙ ЗАЯВКЕ, а не по матрице сброса вообще: обещать снятие того, чего
   * у неё нет, значит пугать выдуманной потерей (приём `rollbackErases` вывоза мусора, ADR 0135).
   */
  erases?: string[];
}

/** Кто сейчас за заявкой закреплён: подрядчик строкой и поимённые исполнители. */
function assignedNames(request: ServiceRequestDto): string[] {
  return [request.service?.name, ...request.executors.map((e) => e.name)].filter(
    (name): name is string => !!name,
  );
}

/**
 * Что снимает отмена (`serviceResetOnTransition`: исполнители и снимок согласования). Заявка
 * остаётся историей того, что собирались чинить, но ни исполнителя, ни согласованной суммы у неё
 * больше нет, — и человек обязан узнать это ДО нажатия, а не из карточки после.
 *
 * Экспортируется, потому что спрашивающих двое, а правило одно: своё окно отмены (Р10) получает
 * этот перечень пропом, а возврат отменённой заявки строит на нём свой — более широкий. Посчитай
 * окно свой список само, две копии матрицы сброса разошлись бы на первой же её правке, и одна из
 * двух обещала бы человеку не то.
 */
export function cancelErases(request: ServiceRequestDto): string[] {
  const items: string[] = [];
  const names = assignedNames(request);
  if (names.length > 0) items.push(`Назначенные исполнители: ${names.join(', ')}`);
  if (request.approval) {
    items.push(`Согласование объёма работ (ревизия ${request.approval.revision})`);
  }
  return items;
}

/**
 * Что снимает возврат отменённой заявки в «Новую». Сброс там шире отмены на целый цикл: виза ИТ,
 * весь объём работ и обе пометки отказа — заявка проходит путь заново.
 */
function reopenErases(request: ServiceRequestDto): string[] {
  const items = cancelErases(request);
  if (request.items.length > 0) {
    items.push(`Объём работ: ${request.items.length} поз., ревизия ${request.estimateRevision}`);
  }
  if (request.itApproval) items.push('Виза ИТ-службы');
  if (request.replacementRecommended || request.rejectionResolution) {
    items.push('Пометка «Рекомендована замена» и решение, принятое вместо ремонта');
  }
  return items;
}

/**
 * Действия, у которых из содержания только причина (§5.3). Собраны в одном месте, потому что
 * разница между ними — в подписях и в ручке, а не в поведении: окно одно, и разъехаться они могут
 * только текстом, который человек читает перед тем, как отменить чужую работу.
 *
 * Переходами эти действия быть перестали не все: отказ и возврат объёма работ в правку статуса не
 * трогают вовсе (Р7, Р9), но причину спрашивают той же ручкой — по ней в истории и читают, почему
 * исполнителей стало меньше, а подпись под объёмом снята.
 *
 * Отмена из этого набора ушла (Р10): её содержание перестало сводиться к причине, и окно у неё
 * теперь своё. Оставшимся четырём добавить нечего — им и правда нечего спросить сверх «почему».
 */
export function serviceReasonPrompts(request: ServiceRequestDto) {
  const version = request.version;
  const id = request.id;
  return {
    /*
     * Отказ идёт одной ручкой на всех (Р7). Второй дороги — отката `/status` из «Назначенной» —
     * больше нет вовсе: назначение переходом быть перестало, дуга `assigned → new` снята вместе со
     * статусом, и выбирать между ручками стало не из чего. Кто снимается, решает сама ручка: свою
     * строку у сотрудника, всю компанию у подрядчика.
     *
     * Успех говорит про состав, а не про статус: заявка и до отказа стояла в «Новой», и «возвращена
     * оператору» звучало бы как переход, которого не было. Ждёт ли она теперь распределения или
     * оставшихся исполнителей — отвечает очередь, пересчитанная сервером (Р7).
     */
    decline: {
      title: 'Отказ от заявки',
      label: 'Причина',
      okText: 'Отказаться',
      danger: true,
      success: 'Вы сняты с заявки',
      submit: (reason: string) => serviceRequestsApi.decline(id, { reason, version }),
    },
    reopenEstimate: {
      title: 'Возврат объёма работ в правку',
      label: 'Причина',
      okText: 'Вернуть в правку',
      // Ручка снимает ОБЕ отметки (Р9): снимок согласования и само предъявление. Успех называет обе
      // — иначе исполнитель, отозвавший непогашенное предъявление, прочитал бы про снятое
      // согласование, которого не было.
      success: 'Объём работ возвращён в правку — предъявление и согласование сняты',
      submit: (reason: string) => serviceRequestsApi.reopenEstimate(id, { reason, version }),
    },
    /*
     * Открытие спора об освобождении (Р9 плана
     * `docs/office-equipment-on-site-and-invoice-estimate-plan.md`). Причина обязательна, и это не
     * общее правило «на всякий случай»: спор ОСТАНАВЛИВАЕТ заявку заморозкой, и «почему» —
     * единственное, чем остановку объясняют исполнителю, который уже работает.
     *
     * Успех называет два следствия сразу: заявка встала и по ней ждут решения того, кто спор начал.
     * Скажи он одно «спор открыт», человек искал бы заявку в прежнем статусе.
     */
    openEstimateDispute: {
      title: 'Спор об освобождении от подписи',
      label: 'Причина',
      okText: 'Оспорить',
      danger: true,
      success: 'Спор открыт — заявка отложена до его разрешения',
      submit: (reason: string) => serviceRequestsApi.openEstimateDispute(id, { reason, version }),
    },
    rollbackAcceptance: {
      title: 'Отмена приёмки',
      label: 'Причина',
      okText: 'Отменить приёмку',
      danger: true,
      success: 'Приёмка отменена',
      submit: (reason: string) =>
        serviceRequestsApi.changeStatus(id, { status: 'done', reason, version }),
    },
    reopenRequest: {
      erases: reopenErases(request),
      title: 'Возврат отменённой заявки',
      label: 'Причина',
      okText: 'Вернуть в «Новую»',
      success: 'Заявка снова в работе',
      submit: (reason: string) =>
        serviceRequestsApi.changeStatus(id, { status: 'new', reason, version }),
    },
    /*
     * Отмены здесь больше нет (Р10): у неё появилось содержание сверх причины — решение «что
     * делаем вместо ремонта» и пометка «рекомендована замена», — и живёт она своим окном
     * (`features/service-cancel`). Одно-полевой `ReasonModal` третьего поля не знает, а добавить
     * его туда значило бы принести пометку замены вывозу мусора и заказу ТС, которые тем же окном
     * спрашивают свою причину.
     */
  } satisfies Record<string, ReasonPrompt>;
}
