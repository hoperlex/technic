import { App, Button, Space, Typography } from 'antd';
import { useMutation, useQueryClient } from '@tanstack/react-query';
import {
  actsAsRequestCustomer,
  attachableServiceFileKinds,
  canCoordinateServiceRequests,
  isServiceRequestClosed,
  SERVICE_FILE_KINDS,
  serviceFileKindLabels,
  serviceFilePurposeLabels,
  type ServiceRequestDto,
  type ServiceRequestFileDto,
} from '@technic/contracts';
import {
  isAwaitingDocuments,
  serviceClosingDocumentHint,
  ServiceDocumentUpload,
  ServiceHint,
  serviceRequestKeys,
  serviceRequestsApi,
} from '@entities/service-request';
import { officeEquipmentKeys } from '@entities/office-equipment';
import { filesApi } from '../../api/resources';
import { FileLinkList } from '../../components/FileLinks';
import { useAuth } from '../../auth/AuthContext';
import {
  mayActOnServiceRequest,
  serviceActionRow,
  serviceExecutorAssignment,
  serviceRequestCustomerFacts,
} from './serviceRequestRow';
import { errorMessage } from '../../utils/format';

/**
 * Основание денежного решения (Р5): его не снимает никто и никогда (Р6, замок сервера под
 * блокировкой). Умолчание `closing_evidence` — окно выката: старое приложение роли не отдаёт, и её
 * отсутствие означает обычное вложение, а не «роль неизвестна».
 */
function isEstimateBasis(file: ServiceRequestFileDto): boolean {
  return (file.purpose ?? 'closing_evidence') === 'estimate_basis';
}

/**
 * Документы заявки по видам (§9.4). Общей кучей их держать нельзя: вопрос к этой вкладке — не
 * «что приложено», а «есть ли чем закрыть», и в списке из восьми файлов ответ на него теряется.
 *
 * Чего не хватает — сказано прямо: «закрыто, но акта нет» — рабочее состояние, из-за которого и
 * заведена очередь «Ожидаются документы».
 */
export function ServiceRequestDocuments({ request }: { request: ServiceRequestDto }) {
  const { message } = App.useApp();
  const { can, user } = useAuth();
  const qc = useQueryClient();
  /*
   * Виды подшивки считает КОНТРАКТ (ADR 0160, решение 7), а не портал: своей копии правила здесь
   * больше нет. Копий было три — таблица маршрута (`FILE_KIND_STATUSES`), эта и матрица видимости,
   * — и две из них уже разошлись: портал предлагал «Вложение» в любом незакрытом статусе, а сервер
   * принимал его только в «Новая», «В работе» и «Решена». Расхождение читалось как поломка портала
   * («выбрал вид — получил отказ»), и чинить его в третий раз копией значило бы завести четвёртую.
   *
   * ПОВЕДЕНИЕ ПОРТАЛА ОТ ЭТОГО МЕНЯЕТСЯ, и намеренно: «Вложение» здешняя копия разрешала в любом
   * незакрытом статусе, а серверная таблица — только в «Новая», «В работе» и «Решена». Разница
   * выпадает на статусы «Согласована ИТ», «Назначена», «Диагностика» и «Смета на согласовании» —
   * все четыре мёртвые (Р1, Р2, 0197), и живой заявки в них не бывает, но заявки-наследие и
   * история в них есть. Это не потеря возможности: сервер на такую подшивку и раньше отвечал
   * `422` — портал перестал обещать то, чего не бывает.
   *
   * Аудитория — второй сомножитель того же вопроса (Р9): заявителю положен единственный вид,
   * «Вложение», и берётся она из DTO, а не считается по правам. Иначе выходит «подшил и потерял» —
   * человек кладёт файл видом «Счёт», и тот исчезает из его же карточки.
   *
   * Статус — «эффективный» (Р110): у отложенной заявки виды документов считаются по тому статусу,
   * из которого её отложили. Заморозка останавливает ход заявки, а не жизнь вокруг неё — вложение
   * к отложенной «В работе» то же самое, — и тем же правилом решает сервер
   * (`assertFileKindAllowed`). Считай портал по `on_hold`, он предлагал бы вид, на котором придёт
   * отказ, а нужный не предложил бы вовсе.
   *
   * Сторона — третий сомножитель (план аудита исполнителей, Р3): акт и счёт кладёт исполнитель либо
   * тот, кто ведёт заявку, а `serviceRequests.finance` сам по себе подшивку не разрешает. Признаки
   * назначения считает общий адаптер (`serviceExecutorAssignment`) — тот же, каким их читают меню
   * действий и вкладка объёма работ; своей формулы здесь нет, иначе форма предлагала бы ИТ-службе
   * «Акт», на котором сервер ответит 403.
   *
   * Сама заявка — четвёртый сомножитель (Р5, Н17): вид «Объём работ» не предлагается там, где
   * объёма работ не бывает, — у внутреннего ремонта этап снят целиком (Р4). Пара «вид + подрядчик»
   * приходит готовой из `serviceActionRow` — того же перевода карточки, каким её читают предикаты
   * действий; собери мы её здесь литералом, признак разошёлся бы с меню и вкладкой на первой же
   * правке. Видимость УЖЕ подшитого документа этим не отнимается: `SERVICE_FILE_KINDS` ниже
   * перечисляет все виды, и историческая бумага внутренней заявки остаётся читаемой.
   */
  const kinds = attachableServiceFileKinds(
    request.heldFromStatus ?? request.status,
    request.audience,
    user,
    serviceExecutorAssignment(request, user),
    serviceActionRow(request),
  );

  /*
   * Страж стороны заказчика (план профилей оргтехники, Р6) — тот же предикат контрактов, каким
   * сервер стережёт общий вход изменяющих ручек, и подшивка с её снятием стоят там же, что правка
   * и удаление: держатель набора «Заявитель» у роли без оси кладёт бумаги только в СВОЮ заявку.
   * Чтение у такой роли глобально, и без этого условия форма загрузки висела бы на каждой чужой
   * строке, отвечая 403 после выбора файла.
   *
   * У всех прочих предикат отвечает «да» — правило сужает ровно одного субъекта, — поэтому условие
   * ничего не отбирает ни у исполнителя, ни у «Ведения», ни у распорядителя файлов.
   */
  const actsAsCustomer = actsAsRequestCustomer(user, serviceRequestCustomerFacts(request));

  /*
   * ОБЛАСТЬ ДЕЙСТВИЙ — ПЕРВЫЙ СОМНОЖИТЕЛЬ ОБЕИХ ДВЕРЕЙ (план
   * `docs/office-equipment-free-estimate-and-executor-scope-plan.md`, Р11). Подшивка и снятие —
   * такие же изменяющие ручки, как правка и переходы, и сервер закрывает их тем же общим входом.
   *
   * СЛУЧАЙ, РАДИ КОТОРОГО ОН ЗДЕСЬ: снятый исполнитель на СВОЕЙ площадке. Стражу заказчика выше
   * он по-прежнему свой — площадка действительно его, — и без второго сомножителя вкладка
   * показала бы ему форму загрузки и крестики снятия на заявке, по которой сервер отвечает 403 на
   * каждый файл. Заявку он при этом видит и в обсуждении участвует (ответ В11 заказчика от
   * 09.09.2026): область чтения шире области действий, и здесь спрашивается именно вторая.
   *
   * Предикаты ПЕРЕМНОЖАЮТСЯ, а не заменяют друг друга: этот отвечает «в моей ли заявка области
   * действий», соседний — «моя ли это сторона». Назначенному исполнителю оба отвечают «да» на
   * заявке чужой площадки, и подшить акт по ней он может ровно как прежде.
   */
  const mayAct = mayActOnServiceRequest(request, user);

  /*
   * Кому положены пояснения (Р11). Признак считается ЗДЕСЬ, у того, кому видна учётка, и уходит в
   * `ServiceHint` пропом: слой сущностей `AuthContext` не видит — линт границ такой импорт не
   * пропустит, — а своей формулы вместо предиката контрактов здесь нет: правило «кому положены
   * пояснения» обязано меняться в одном месте, иначе половина подсказок вернулась бы тем, у кого
   * их убирали.
   */
  const coordinator = canCoordinateServiceRequests(user);

  // Снятие документа после приёмки — только у распорядителя файлов: заявка закрыта, и подшитая
  // бумага из неё не исчезает по решению стороны (Р29).
  const canAttach =
    mayAct &&
    can('serviceRequests.files') &&
    kinds.length > 0 &&
    !request.deletedAt &&
    actsAsCustomer;
  const canDetach =
    mayAct &&
    !request.deletedAt &&
    actsAsCustomer &&
    (can('files.manageAny') ||
      (can('serviceRequests.files') && !isServiceRequestClosed(request.status)));

  const refresh = () => {
    void qc.invalidateQueries({ queryKey: serviceRequestKeys.root });
    void qc.invalidateQueries({ queryKey: officeEquipmentKeys.root });
  };

  const detach = useMutation({
    mutationFn: (fileId: string) => serviceRequestsApi.detachFile(request.id, fileId),
    onSuccess: () => {
      message.success('Документ снят');
      refresh();
    },
    onError: (e) => message.error(errorMessage(e)),
  });

  return (
    <Space orientation="vertical" size={16} style={{ width: '100%' }}>
      {/* Планка одна и та же везде (Р112): перечисление недостающих видов читалось бы как
          «нужны все три», а приёмку снимает любой один.

          Заявителю её нет вовсе (ADR 0160, Р12), и отдельным условием это здесь не написано:
          ответ «нет» даёт сам предикат — он спрашивает аудиторию первым делом. Вторая проверка
          рядом означала бы два правила на один вопрос, а разошлись бы они молча: плашка на
          вкладке и красный тег в списке спрашивают одну и ту же функцию.

          Подача — по Р11: это причина, по которой заявка не закроется, поэтому исполнителю и
          сервисной компании она не исчезает, а сворачивается в мелкую строку. Полностью её видит
          тот, кто ведёт заявки: разбирая чужую очередь «Ожидаются документы», он читает не «нужна
          бумага», а «почему эта строка тут стоит». */}
      {isAwaitingDocuments(request) && (
        <ServiceHint
          coordinator={coordinator}
          level="warning"
          title={serviceClosingDocumentHint(request.estimateFormat ?? null)}
          description="Пока нет ни одного, заявка стоит в очереди «Ожидаются документы»: работу сервисной компании без закрывающего документа не закрыть, и портал такую заявку не закроет сам — сутки на возражение отсчитываются от подшитой бумаги."
        />
      )}

      {SERVICE_FILE_KINDS.map((fileKind) => {
        const files = request.files.filter((file) => file.kind === fileKind);
        if (files.length === 0) return null;
        /*
         * Три судьбы у одного вида документа, и делить их приходится здесь (Р5, Р6 плана
         * освобождения от подписи).
         *
         * КАРАНТИН ИДЁТ ПЕРВЫМ, раньше роли: у такого вложения имя ПУСТОЕ, и общий список показал
         * бы пустую ссылку — «файл, у которого что-то сломалось» вместо «документ закрыт по
         * обращению». Строка при этом остаётся: «доказательство скрыто» и «доказательства не было»
         * — разные факты, и стереть первый значило бы переписать историю денежного решения.
         *
         * ОСНОВАНИЕ ОБЪЁМА РАБОТ ИДЁТ БЕЗ КНОПКИ СНЯТИЯ: сервер отказывает по нему всегда — и
         * автору, и распорядителю чужими файлами, и после возврата объёма работ в правку, — а
         * кнопка, за которой стоит один отказ, хуже отсутствующей: человек нажмёт её раньше, чем
         * прочитает отказ, и пойдёт искать обход. Причина и оба выхода названы строкой рядом.
         *
         * Роль читается с умолчанием `closing_evidence` — тем же, каким её читает предикат
         * контрактов: старое приложение поля не отдаёт вовсе, и отсутствие значения означает
         * сегодняшнее вложение, а не «роль неизвестна».
         */
        const quarantined = files.filter((file) => file.quarantined);
        const open = files.filter((file) => !file.quarantined);
        const basis = open.filter(isEstimateBasis);
        const ordinary = open.filter((file) => !isEstimateBasis(file));
        return (
          <div key={fileKind}>
            <Typography.Text strong>{serviceFileKindLabels[fileKind]}</Typography.Text>
            {ordinary.length > 0 && (
              <FileLinkList
                files={ordinary}
                maxNameWidth={420}
                onRemove={canDetach ? (file) => detach.mutate(file.id) : undefined}
              />
            )}
            {basis.length > 0 && (
              <>
                <FileLinkList files={basis} maxNameWidth={420} />
                <Typography.Text type="secondary">
                  {serviceFilePurposeLabels.estimate_basis}: этим счётом предъявлен объём работ, и
                  из заявки он не снимается никогда. Ошибочный счёт не удаляют, а перестают
                  предъявлять — предъявите объём работ заново с верным, и прежний станет
                  недействующим; секретный или чужой документ закрывают от доступа по обращению в
                  службу.
                </Typography.Text>
              </>
            )}
            {quarantined.map((file) => (
              <div key={file.id}>
                <Typography.Text type="secondary">
                  Документ закрыт по обращению: имя и ссылка скрыты, содержимое открыто только
                  разбору инцидента.
                </Typography.Text>
                {/* Снятие показывается ровно там же, где и у обычного вложения: карантин закрывает
                    ДОСТУП к содержимому, а прав на связь с заявкой не меняет, — и второе мнение
                    портала о правах здесь завело бы правило, которого нет у сервера. */}
                {canDetach && !isEstimateBasis(file) && (
                  <Button type="link" danger size="small" onClick={() => detach.mutate(file.id)}>
                    Удалить
                  </Button>
                )}
              </div>
            ))}
          </div>
        );
      })}

      {request.files.length === 0 && (
        <Typography.Text type="secondary">К заявке ничего не подшито</Typography.Text>
      )}

      {canAttach && (
        <ServiceDocumentUpload
          requestId={request.id}
          kinds={kinds}
          upload={filesApi.upload}
          // Свежая заявка из ответа вкладке не нужна — её перерисует список: карточка живёт
          // запросом, и гасить кэш здесь честнее, чем держать второй источник той же заявки.
          onUploaded={refresh}
        />
      )}
    </Space>
  );
}
