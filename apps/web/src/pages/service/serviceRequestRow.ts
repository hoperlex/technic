import {
  canActOnServiceRequest,
  hasFeature,
  type AuthUser,
  type RequestCustomerFacts,
  type ServiceActionRequest,
  type ServiceExecutorAssignment,
  type ServiceRequestDto,
} from '@technic/contracts';

/**
 * Карточка заявки в том виде, в каком её читают предикаты контрактов (Р2, Р11).
 *
 * Адаптер нужен потому, что DTO и предикаты описывают одно и то же разными словами: в карточке
 * сервисная компания лежит **объектом** (`service`), а поимённые исполнители — списком; предикатам
 * же нужны «есть ли контрагент» и «сколько строк» — ровно то, что сервер считает запросом, не
 * поднимая ни имён, ни названий. Разложи это каждое место по-своему — и `serviceHasExecutors`
 * отвечал бы в меню одно, а в форме другое.
 *
 * Второе, что склеивает адаптер, — согласование: в DTO оно лежит снимком `approval`, а предикат
 * возврата в правку спрашивает одну лишь ревизию подписи (Р9, «есть что снимать»).
 *
 * Одной функцией на все шесть зовущих: меню действий, правку заявки, повтор письма, вкладку объёма
 * работ и обе кнопки согласования. Дешевле держать один перевод, чем ловить расхождение на экране.
 */
export function serviceActionRow(request: ServiceRequestDto): ServiceActionRequest {
  return {
    kind: request.kind,
    status: request.status,
    serviceCounterpartyId: request.service?.id ?? null,
    executorCount: request.executors.length,
    estimatePendingRevision: request.estimatePendingRevision,
    approvedEstimateRevision: request.approval?.revision ?? null,
  };
}

/**
 * Признаки назначения на **эту** заявку — то, чего матрица прав не знает и знать не может.
 *
 * Ход исполнителя открывает не право, а назначение: поимённая строка вместе с
 * `serviceRequests.execute` либо своя компания в исполнителях (Н5). Сервер спрашивает то же самое
 * теми же двумя признаками, только читает их из таблиц, — поэтому меню и ответ маршрута не
 * расходятся.
 *
 * Рядом с `serviceActionRow`, потому что предмет один: перевод карточки в то, чем её видят
 * предикаты контрактов. Порознь эти два перевода разъехались бы — один считал бы исполнителей по
 * списку, другой по признаку.
 */
export function serviceExecutorAssignment(
  request: ServiceRequestDto,
  subject: AuthUser | null | undefined,
): ServiceExecutorAssignment {
  return {
    /*
     * ТОЧНЫЙ ОТВЕТ, тот же, что у сервера (Р8): «заявка отдана ИМЕННО ЭТОЙ компании» —
     * `row.serviceCounterpartyId !== null && row.serviceCounterpartyId === p.counterpartyId`.
     * Прежде здесь стояло приближение «субъект — оператор какой-то сервисной компании»: в
     * `AuthUser` не приезжал `counterpartyId`, и сузить ответ было нечем. Теперь поле приезжает
     * (`auth.ts`, все четыре ответа сессии), и вопрос задаётся тот же самый.
     *
     * Что изменилось на деле. Приближение было недостижимо не собой, а **соседним** правилом:
     * заявку, назначенную не его компании, оператор подрядчика не видит вовсе
     * (`assertExecutorScope`), — то есть единственная дыра портала закрывалась чужим замком. После
     * Р1 видимость получила третью ось (поимённое назначение), и «не вижу — значит не спрошу»
     * перестало быть верным по построению: заявка, открытая человеку назначением, могла бы прийти
     * с чужим подрядчиком в поле. Здесь этот случай отвечает «не моя», как и на сервере.
     *
     * Пустой контрагент не совпадает ни с чьим: нераспределённая заявка (`service === null`) и
     * учётка без контрагента (`counterpartyId === null`) — не пара, а два отсутствия, и равенство
     * `null === null` сделало бы исполнителем всякого, кому такая заявка видна.
     *
     * Тип контрагента здесь не спрашивается намеренно, ровно как на сервере: назначение — свойство
     * ЗАЯВКИ, а «работает ли субъект стороной подрядчика» решают предикаты контрактов
     * (`isServiceExecutor`, `actsAsServiceExecutor`) — им и передаётся эта пара признаков.
     */
    actsForAssignedCounterparty:
      request.service !== null && request.service.id === subject?.counterpartyId,
    isNamedExecutor: request.executors.some((e) => e.userId === subject?.id),
  };
}

/**
 * Признаки СТОРОНЫ ЗАКАЗЧИКА этой строки — то, чем портал зовёт страж авторства
 * `actsAsRequestCustomer` (план профилей оргтехники, Р6; §11, условие 3).
 *
 * ЗАЧЕМ ОН ПОРТАЛУ. Сервер отвечает 403 держателю набора «Заявитель» у роли без оси на ЧУЖОЙ
 * строке: набор выдан ради своей заявки, а чтение у роли без оси глобально. Портал же показывал
 * этому человеку «Редактировать», «Удалить» и подшивку на всём, что видит, — то есть обещал
 * действие, которого сервер не даст. По §11 это дефект строки матрицы, а не отдельная задача.
 *
 * АВТОРСТВО БЕРЁТСЯ ИЗ СВОДКИ ОБСУЖДЕНИЯ, И ЭТО ЕДИНСТВЕННЫЙ ДОСТУПНЫЙ ИСТОЧНИК. `ServiceRequestDto`
 * не отдаёт `createdBy` — осознанное решение соседнего плана, — а `chat.participantSides` содержит
 * `customer` РОВНО У АВТОРА: участие со стороны заказчика считается строже аудитории
 * (`matchesServiceChatSide` с `wideCustomer: false`), и посчитал его сервер по той же строке, по
 * которой судит страж. Имя автора (`createdByName`) для этого не годится вовсе: тёзка — не
 * доказательство, а сравнение подписей молча разошлось бы с сервером.
 *
 * `inCustomerScope` ПРИХОДИТ ПОЛЕМ КАРТОЧКИ, а не считается здесь (находка Н8, решение заказчика
 * 04.09.2026). Прежде он стоял здесь ложью, и это было верно: единственный сужаемый субъект —
 * роль без оси, у которой сторона заказчика не бывает истинной ни при какой заявке. С правилом
 * правки и удаления сужаемых стало двое, и у второго — держателя сквозной области — роль с осью
 * вполне бывает: сисадмин сидит на `shtab`, `site` или `department`. Ответить за него ложью
 * значило бы спрятать «Редактировать» на заявке ЕГО ЖЕ площадки, где сервер её разрешает.
 * Посчитать самому портал не может: правило области живёт на сервере (`inServiceRequestCustomerScope`),
 * и вторая его копия в браузере разошлась бы с первой молча.
 *
 * Рядом с двумя другими переводами карточки по той же причине, что и они: предмет один — DTO в то,
 * чем её видят предикаты контрактов, — и разложенный по местам вызова он разъехался бы.
 */
export function serviceRequestCustomerFacts(request: ServiceRequestDto): RequestCustomerFacts {
  return {
    isAuthor: request.chat.participantSides.includes('customer'),
    inCustomerScope: request.inCustomerScope,
  };
}

/**
 * **Можно ли этому смотрящему вообще трогать эту заявку** — первый сомножитель ВСЕХ изменяющих
 * действий портала (план `docs/office-equipment-free-estimate-and-executor-scope-plan.md`, Р11).
 *
 * ОДИН ПОМОЩНИК НА ВСЕ ВХОДЫ, И ЭТО ГЛАВНОЕ В НЁМ. Действия портала живут в пяти местах: набор
 * пунктов заявки (`serviceRequestMenu`), объём работ (`serviceRequestEstimateMenu`), расходники и
 * прочие обстоятельства (`serviceRequestExtras`), правка с удалением в списке (`RequestsTab`),
 * подшивка и снятие документов (`ServiceRequestDocuments`). Разложи мы сбор фактов по этим пяти
 * местам — они разъехались бы на первой же правке, и разъехались бы МОЛЧА: одно место показало бы
 * кнопку, за которой сервер отвечает 403, и заметил бы это не тест, а человек.
 *
 * ПРАВИЛО ЖИВЁТ В КОНТРАКТАХ, ЗДЕСЬ ТОЛЬКО ФАКТЫ. `canActOnServiceRequest` зовут и сервер (из
 * общего входа изменяющих ручек), и портал — своей копии правила у портала нет и не заводится.
 * Здесь собирается ровно то, чего чистый предикат знать не может: включён ли рубильник, автор ли
 * он и стоит ли в действующем составе исполнителей.
 *
 * РУБИЛЬНИК ЧИТАЕТСЯ ИЗ ОТВЕТА СЕССИИ (`hasFeature`), тем же способом, каким это делает соседняя
 * волна кандидатов (`auth/candidateIntake.ts`, ADR 0177): своей копии значения — env, сборочной
 * константы, локального состояния — у портала нет, второй источник разошёлся бы с серверным
 * молча. Правило `hasFeature` fail-closed: ключа нет — рубильник выключен, а выключенный означает
 * СЕГОДНЯШНЕЕ поведение, то есть `true` у всех. Старый сервер, не знающий про ключ, поэтому и
 * отвечает как прежде — портал новее приложения только в окне выката.
 *
 * АВТОРСТВО БЕРЁТСЯ ИЗ СВОДКИ ОБСУЖДЕНИЯ — тем же полем, каким его читает сторона заказчика
 * (`serviceRequestCustomerFacts`): `ServiceRequestDto` не отдаёт `createdBy` вовсе, а
 * `chat.participantSides` содержит `customer` ровно у автора. Два разных источника одного факта
 * разошлись бы, и один из двух предикатов ответил бы неверно.
 *
 * СЛУЧАЙ, РАДИ КОТОРОГО ОН И ЗАВЕДЁН: бывший исполнитель на СВОЕЙ площадке. Страж стороны
 * заказчика отвечает ему `true` по `inCustomerScope` — площадка действительно его, — а область
 * действий `false`: он не назначен и не автор. Считай портал доступность одним стражем заказчика,
 * он показал бы правку, удаление и загрузку документов там, где сервер отвечает 403 на каждую.
 * Поэтому предикаты не заменяют друг друга, а ПЕРЕМНОЖАЮТСЯ: один отвечает «моя ли это запись»,
 * второй — «в моей ли она области действий».
 *
 * ЧТЕНИЕ И ОБСУЖДЕНИЕ ЭТИМ НЕ ЗАКРЫВАЮТСЯ: снятый исполнитель заявку видит и в переписке
 * участвует (ответ В11 заказчика от 09.09.2026) — область чтения шире области действий на след
 * снятия, и смешивать их нельзя ни в одну сторону.
 */
export function mayActOnServiceRequest(
  request: ServiceRequestDto,
  user: AuthUser | null | undefined,
): boolean {
  return canActOnServiceRequest(user, {
    executorScopeEnabled: hasFeature(user, 'service_request_executor_scope'),
    isAuthor: serviceRequestCustomerFacts(request).isAuthor,
    // Назначение считается тем же адаптером, что и у стороны исполнителя: «стоит ли он в
    // ДЕЙСТВУЮЩЕМ составе» — один вопрос, и второй его разбор здесь разошёлся бы с меню.
    isNamedExecutor: serviceExecutorAssignment(request, user).isNamedExecutor,
  });
}
