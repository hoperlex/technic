import { Checkbox, Form, Input } from 'antd';

/**
 * Срочность в форме заявки (Р56): пара «галочка + причина».
 *
 * Отдельным модулем, как и соседи по этой же форме — гарантия (`ServiceRequestWarrantyClaim`),
 * техника (`ServiceRequestEquipmentField`), вложения (`ServiceRequestAttachments`). Граница та же,
 * по которой они отделены: по предмету разговора. Срочность — разговор об ОЧЕРЕДИ, а не о самой
 * заявке: она не меняет ни предмета, ни заказчика, ни контактов, у неё своя пара полей, своё
 * правило обязательности и своё право; ту же срочность отдельно от формы ведёт
 * `ServiceUrgencyModal`. Форма же спрашивает, о чём заявка, — и переживает переделки очереди без
 * единой правки.
 *
 * ПАРА, А НЕ ФЛАЖОК. Причина появляется вместе с галочкой и обязательна: без неё через месяц
 * срочными окажутся все заявки, и очередь, в которую смотрит оператор, перестанет что-либо
 * означать. Обе половины пары не принимает порознь ни схема, ни `CHECK` в базе.
 *
 * СОСТОЯНИЕ ПАРЫ — ИЗ САМОЙ ФОРМЫ (`useFormInstance`), а не пропсом снаружи: показ причины и
 * отступ под галочкой — устройство пары, и вызывающему знать о них незачем.
 */
export function ServiceRequestUrgencyFields({
  /**
   * СРОЧНОСТЬ ПРИ ПРАВКЕ ЗАПЕРТА БЕЗ СВОЕГО ПРАВА (план профилей оргтехники, Р10): сервер
   * спрашивает `serviceRequests.urgency`, как только пара расходится со строкой заявки, и кнопка,
   * ведущая в 403, — это дефект портала, а не строгость сервера (§11: портал не показывает того,
   * чего сервер не даст).
   *
   * Заперта, а не спрятана: заявитель обязан видеть, срочная его заявка или нет, — иначе исчезнувшая
   * галочка читалась бы как «срочность сняли». Меняют её отдельной ручкой те, кто ведёт заявки
   * (`ServiceUrgencyModal`), и им она отсюда не нужна.
   *
   * У ЗАВЕДЕНИЯ ПРАВА НЕ СПРАШИВАЮТ ВОВСЕ: объявить срочность при подаче — просьба заявителя, и
   * серверная дверь там открыта намеренно (Н1, §8).
   */
  locked,
}: {
  locked: boolean;
}) {
  const form = Form.useFormInstance();
  const isUrgent = Form.useWatch<boolean | undefined>('isUrgent', form);

  return (
    <>
      <Form.Item
        name="isUrgent"
        valuePropName="checked"
        style={{ marginBottom: isUrgent ? 8 : 24 }}
      >
        <Checkbox disabled={locked}>Срочная заявка</Checkbox>
      </Form.Item>
      {isUrgent && (
        <Form.Item
          name="urgencyReason"
          label="Почему срочно"
          rules={[{ required: true, message: 'Объясните, почему заявка срочная' }]}
        >
          <Input
            disabled={locked}
            maxLength={500}
            placeholder="Например: единственный принтер на площадке, встала выдача пропусков"
          />
        </Form.Item>
      )}
    </>
  );
}
