import type { App } from 'antd';
import { moduleMailOutcomeLabels, type ModuleMailOutcome } from '@technic/contracts';

/** Тосты окна: то же, что отдаёт `App.useApp()`, — свой тип антом наружу не выведен. */
type MessageApi = ReturnType<typeof App.useApp>['message'];

/**
 * Судьба письма службе после **удавшегося** действия (Р67): заявка заведена, отменена или письмо
 * послано заново — а письма нет.
 *
 * Отказом это не является: операция прошла, поля тут ни при чём, и поправить его человек не может
 * ничем, кроме обращения к администратору. Поэтому ответ — тост, а не пометка поля: у службы и у
 * подрядчика учёток в портале нет, и «обязательный адресат не оповещён» надо узнать сразу, а не
 * когда за заявкой не приехали.
 *
 * Собрано отдельным модулем ради исключения из ADR 0094: список исключений в
 * `scripts/check-form-blockers.mjs` — пофайловый, и вписать в него `ServiceRequestForm` значило бы
 * снять правило со всей формы заявки, со всех её полей разом. Здесь снимать нечего: поля нет, а
 * `ModuleMailOutcome` на входе не даёт модулю превратиться в общий вход для любых тостов.
 *
 * `queued`, `not_needed`, `event_off` и пустой исход молчат: очередь — обычный ход, `not_needed`
 * означает, что писать было не о чем (состав никого не назначил), а `null` приходит от правки
 * заявки, которая письма и не шлёт.
 *
 * `event_off` (§5.10 плана `docs/office-equipment-mail-expansion-plan.md`) молчит по той же
 * причине, но с другой стороны: письма нет не потому, что что-то не настроено, а потому, что
 * рубильник события выключен намеренно — администратором, в админке, до этого действия. Пугать
 * нажавшего кнопку тут нечем и просить его не о чем: сам он этого не поправит и поправлять не
 * должен. Событие включают, когда решают включить; аудит запись об этом хранит.
 */
export function reportServiceMail(
  message: MessageApi,
  outcome: ModuleMailOutcome | null | undefined,
): void {
  if (!outcome || outcome === 'queued' || outcome === 'not_needed' || outcome === 'event_off')
    return;
  message.warning(moduleMailOutcomeLabels[outcome]);
}
