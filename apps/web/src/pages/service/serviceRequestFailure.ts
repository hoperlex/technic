import type { App } from 'antd';
import { isApiError } from '@shared/api';
import type { FormBlockersApi } from '@shared/ui';
import { errorMessage } from '../../utils/format';

/** Тосты окна: то же, что отдаёт `App.useApp()`, — свой тип антом наружу не выведен. */
type MessageApi = ReturnType<typeof App.useApp>['message'];

/**
 * Отказ сервера при заведении и правке заявки на обслуживание — в том виде, в каком его видит
 * человек: причина под своим полем, а не тост в углу (ADR 0094).
 *
 * ТРИ КОДА ОТКАЗА У ЗАЯВКИ БЕЗ АППАРАТА (Р5, Р6 плана расходников и закупки, ADR 0146, решение 6),
 * и разбираются они по-разному:
 *
 *   * **403** — права заводить такую заявку нет. Полей в ответе нет и быть не может: отвечает
 *     страж права, а не проверка значения, — поэтому слова кладутся на поле «Какой аппарат». Оно
 *     тут не виновник, а ВЫХОД: отказ снимается тем, что аппарат называют. Тостом это сказать
 *     нельзя — он уедет в угол экрана, ничего не пометив и никуда не прокрутив;
 *   * **400** — отказ схемы (`validation_error`, поля приходят в `fields`);
 *   * **422** — отказ маршрута: чужой объект своей оси, выбор поперёк оси. Тоже с `fields`, и
 *     текст в них маршрутный — он и встаёт под полем.
 *
 * Разделять 400 и 422 порталу не нужно вовсе, и это не упрощение: форма ответа у них одна
 * (`fields` с текстом), а показывает портал то, что сказал сервер. Различие живёт на сервере, где
 * общий обработчик zod отвечает 400 там, где сама ручка ответила бы 422.
 *
 * Отдельным модулем от формы — по той же причине, что и сосед `serviceMailNotice`: разбор ответа и
 * заполнение полей отвечают на разные вопросы, а форма и без него упирается в порог длины файла.
 */
export function reportServiceRequestFailure(
  error: unknown,
  {
    withoutEquipment,
    blockers,
    message,
  }: {
    /**
     * Заводилась заявка БЕЗ аппарата: поле было пустым, и тело ушло с `officeEquipmentId: null`.
     * От этого зависят оба разбора ниже — и 403, и смысл имени `objectId` в отказе.
     *
     * Правки это не касается вовсе: аппарат там не меняют (поле выключено), и 403 на сохранение
     * говорит про заказчика, а не про предмет, — поставленный к выключенному полю, он указал бы
     * человеку на то, чего тот всё равно не поправит.
     */
    withoutEquipment: boolean;
    blockers: FormBlockersApi;
    message: MessageApi;
  },
): void {
  if (withoutEquipment && isApiError(error) && error.status === 403) {
    blockers.raise({ officeEquipmentId: error.message });
    return;
  }
  /*
   * Имена полей заказчика — оба на одно поле формы: сервер знает пару колонок (`objectId` и
   * `customerDepartmentId`), а человек видит один подбор «Для кого заявка», и без этого перевода
   * отказ по нему потерялся бы в тосте. `objectId` переводится только у заявки без аппарата: с
   * аппаратом это другое поле — «Где он на самом деле» (Р16), и оно в форме есть.
   */
  const alias: Record<string, string> = { customerDepartmentId: 'customer' };
  if (withoutEquipment) alias.objectId = 'customer';
  // 409 «по этой технике уже есть открытая заявка» (Р21) — обычный ответ, а не сбой, и поля у него
  // нет: он про заявку целиком.
  if (!blockers.fromApi(error, alias)) message.error(errorMessage(error));
}
