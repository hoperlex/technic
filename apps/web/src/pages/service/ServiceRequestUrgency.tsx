import { Checkbox, Form, Input } from 'antd';

/**
 * Срочность заявки в форме — пара «галочка + причина» (Р56) и право на неё (план
 * `docs/office-equipment-request-subject-plan.md`, Р9).
 *
 * Причина появляется вместе с галочкой и обязательна: без неё через месяц срочными окажутся все
 * заявки, и очередь, в которую смотрит оператор, перестанет что-либо означать.
 *
 * ПРИ ЗАВЕДЕНИИ пары нет вовсе у того, у кого нет `serviceRequests.urgency`: срочность назначает
 * «Ведение», разбирая очередь, а объявленная самим заявителем она через месяц стоит у половины
 * заявок. Просьбу «сделайте быстрее» человек по-прежнему пишет описанием, и она доходит до того же
 * диспетчера. Сервер закрыт той же дверью: `POST` с `isUrgent: true` без права отвечает 403, а
 * `false` принимает всегда. Спрятана, а не заперта: запертая галочка обещала бы решение, которого
 * заявитель не принимает, а «Срочная заявка» серым по серому читалась бы как «вам не положено» в
 * форме, где всё остальное положено.
 *
 * ПРИ ПРАВКЕ наоборот — ЗАПЕРТА, а не спрятана: заявитель обязан видеть, срочная его заявка или
 * нет, и исчезнувшая галочка читалась бы как «срочность сняли». Сервер спрашивает право по разнице
 * пары со строкой заявки, и кнопка, ведущая в 403, — дефект портала, а не строгость сервера (§11:
 * портал не показывает того, чего сервер не даст). Меняют срочность отдельной ручкой те, кто ведёт
 * заявки (`ServiceUrgencyModal`), и им она отсюда не нужна.
 *
 * Своим блоком, а не двумя `Form.Item` в форме: у этих полей одно правило показа на двоих, и
 * разложенные по форме порознь, они разъезжались бы — причина без галочки не значит ничего, а
 * галочка без причины не проходит ни схему, ни `CHECK` базы.
 */
export function ServiceRequestUrgency({
  editing,
  canUrgency,
}: {
  /** Правится заведённая заявка: пара показывается всегда — вопрос лишь в том, заперта ли она. */
  editing: boolean;
  /** Есть ли право `serviceRequests.urgency`. */
  canUrgency: boolean;
}) {
  const form = Form.useFormInstance();
  const isUrgent = Form.useWatch('isUrgent', form);
  if (!editing && !canUrgency) return null;
  const locked = editing && !canUrgency;

  return (
    <>
      <Form.Item
        name="isUrgent"
        valuePropName="checked"
        style={{ marginBottom: isUrgent ? 8 : 24 }}
      >
        <Checkbox disabled={locked}>Срочная заявка</Checkbox>
      </Form.Item>
      {isUrgent && (
        <Form.Item
          name="urgencyReason"
          label="Почему срочно"
          rules={[{ required: true, message: 'Объясните, почему заявка срочная' }]}
        >
          <Input
            disabled={locked}
            maxLength={500}
            placeholder="Например: единственный принтер на площадке, встала выдача пропусков"
          />
        </Form.Item>
      )}
    </>
  );
}
