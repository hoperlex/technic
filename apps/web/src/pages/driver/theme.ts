import type { CSSProperties } from 'react';
import type { ThemeConfig } from 'antd';

/**
 * Величины кабинета водителя: масштаб шрифта и тема antd под него (план кабинета Р1; план
 * `docs/driver-readings-typography-plan.md`, Р1).
 *
 * Экран читают с телефона в кабине — на солнце, в перчатках и стоя у машины, — поэтому размер
 * задаётся ОДНИМ числом на весь кабинет: подобрать его на живом телефоне должно быть работой
 * одного значения, а не поиска по файлам.
 *
 * До этого модуля масштаб доходил только до половины экрана, и это была не описка, а устройство
 * antd: `Typography` собственного размера не задаёт вовсе и наследует каркас, а `Input`, `Button`,
 * `DatePicker`, `Alert` и `Checkbox` берут его из ТОКЕНА темы. Портальная мобильная тема даёт им
 * 16 px, десктопная — 14, и экран получался вывернутым: читаемое крупнее набираемого, а число
 * одометра — единственное место, где ошибка стоит денег, — мельче окружающего текста. Поэтому
 * величина здесь одна, а расходится она двумя дорогами: переменной CSS на каркас (голый текст и
 * подписи в `em`) и токеном темы (всё, что рисует antd).
 */

/** База портала. Кабинет считается от неё же, чтобы «крупнее» было выражено одним множителем. */
export const DRIVER_BASE_FONT_PX = 16;

/**
 * Насколько кабинет крупнее портала. Величина подбирается на живом телефоне; выше 1.25 начинается
 * плата высотой — шапка кабинета (логотип с датой, ссылка на задание, строка долга) съедает у
 * телефона 360×640 около трети экрана, и на форму остаётся меньше двух блоков.
 */
export const DRIVER_FONT_SCALE = 1.25;

/**
 * Числовые поля — отдельно и крупнее прочего. Их водитель набирает пальцем и сверяет с прибором, и
 * это единственные значения экрана, ошибка в которых уезжает в учёт. Множитель второй, а не общий:
 * подняв им весь кабинет, мы получили бы ту же разницу, только выше — комментарий и подписи росли
 * бы вместе с числами и снова сравнялись бы с ними.
 */
export const DRIVER_NUMBER_SCALE = 1.4;

/**
 * Тач-цель управляющих элементов. 48, а не портальные мобильные 40: в кабинете жмут в перчатках, и
 * промах по стрелке дня стоит открытого чужого дня. От неё antd считает и крупные элементы
 * (`controlHeightLG` = 60 — высота поля ввода и кнопки «Передать»), и мелкие.
 */
export const DRIVER_CONTROL_HEIGHT = 48;

/**
 * Сколько места страница показаний оставляет под своим закреплённым подвалом. Кнопка в нём высотой
 * `controlHeightLG` (60) плюс отступы подвала (8 сверху и снизу) плюс запас на границу и вырез
 * экрана. Число живёт рядом с высотой, из которой считается: разъехавшись с ней, оно даёт кнопку
 * поверх последнего поля — ровно то, от чего подвал и закрепляли (план первого экрана, Р9).
 */
export const DRIVER_FOOTER_RESERVE = 96;

/**
 * Колонка страницы показаний: отступ снизу — то самое место под подвалом. Стиль стоит рядом с
 * числом, из которого считается: разъехавшись с ним, он даёт кнопку поверх последнего поля.
 */
export const driverContentStyle: CSSProperties = {
  display: 'flex',
  paddingBottom: DRIVER_FOOTER_RESERVE,
};

/** Базовый размер шрифта кабинета в пикселях — им же считается токен темы и переменная каркаса. */
export const DRIVER_FONT_PX = Math.round(DRIVER_BASE_FONT_PX * DRIVER_FONT_SCALE);

/**
 * Тема кабинета. Токенов ровно два: остальное antd выводит из них сам — `fontSizeSM` 16,
 * `fontSizeLG` 24, `fontSizeHeading5` 24 (заголовок дня наконец крупнее текста под ним),
 * `lineHeight` 1.4, `controlHeightLG` 60, `controlHeightSM` 36. Перечислять производные руками
 * значило бы завести десяток чисел, которые разойдутся с первой же правкой базы.
 *
 * Третий токен вынужденный и потому компонентный: ячейку календаря antd считает как
 * `controlHeightSM × 1.5` — при нашей высоте это 54 px, а панель из семи ячеек — около 394 px,
 * шире телефона в 360. Своя ширина ячейки возвращает панель в экран, не трогая ничего больше.
 *
 * Объект собран один раз на модуль: пересоздание на каждом рендере сбрасывало бы кэш стилей antd.
 * Цвета, скругления и локаль приходят из портальной темы сами — вложенный `ConfigProvider` тему
 * родителя не заменяет, а дополняет.
 */
export const driverTheme: ThemeConfig = {
  token: { fontSize: DRIVER_FONT_PX, controlHeight: DRIVER_CONTROL_HEIGHT },
  components: { DatePicker: { cellWidth: 44, cellHeight: 40 } },
};
