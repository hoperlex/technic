import { useQuery, useQueryClient } from '@tanstack/react-query';
import {
  DRIVER_SUBMIT_PAST_DAYS,
  type DriverAssignmentDto,
  type DriverPreviousReading,
  type DriverReportDto,
  type ReportItemDto,
} from '@technic/contracts';
import { errorMessage } from '@shared/lib';
import { cabinetRead, driverCabinetApi, driverKeys } from './api';
import { sourceKey } from './readingsDraft';

/**
 * Что делать с локальным черновиком в этом дне (план `docs/driver-readings-first-plan.md`, Р10).
 * Читающих режима два, и с введённым они обращаются по-разному — потому и не один признак:
 *
 * - `edit` — правка открыта: черновик кладётся прямо в поля, он новее отправленного;
 * - `aside` — окно записи закрыто, а отчёт для водителя открыт: числа сервера в полях, локальное
 *   рядом пометкой «введено, но не передано». Это его единственная копия — сдать такой день уже
 *   нельзя, а продиктовать свои цифры диспетчеру человек обязан мочь;
 * - `none` — отчёт закрыт для водителя: показываются числа сервера, локальное не накладывается,
 *   иначе экран показывал бы не то, что в учёте.
 *
 * Ни в одном из трёх черновик не удаляется: уборка бывает только по успешной отправке, по TTL и по
 * выходу из учётной записи.
 */
export type DraftUse = 'edit' | 'aside' | 'none';

/** Состояние дня: подпись, объяснение и то, что из этого следует для формы. */
export interface DayState {
  label: string;
  /** Причина словами: ею же подписан подвал там, где кнопки «Передать» нет (Р10). */
  hint: string;
  submittable: boolean;
  /** Зовётся ли `open` показом дня (Р2): только там, где открывать есть что. */
  open: boolean;
  /** Сохранённый отчёт дня — им рисуется всё, чего `open` не открывает. */
  report: DriverReportDto | null;
  draft: DraftUse;
  /** Слова вместо формы: строк на экране не будет вовсе. Пусто — рисуется форма. */
  notice: string;
}

type DayFacts = Omit<DayState, 'report'>;

const WINDOW_HINT = `Показания принимаются за сегодня и ${DRIVER_SUBMIT_PAST_DAYS} предыдущих дней`;

/** Читающий день: ввод закрыт, кнопки «Передать» нет, причину называет подвал теми же словами. */
const reading = (label: string, hint: string, draft: DraftUse): DayFacts => ({
  label,
  hint,
  submittable: false,
  open: false,
  draft,
  notice: '',
});

/** День, которому формы не положено вовсе: показывать нечего, и портал говорит это словами. */
const nothing = (notice: string): DayFacts => ({
  label: '',
  hint: '',
  submittable: false,
  open: false,
  draft: 'none',
  notice,
});

/**
 * Матрица состояний дня (план `docs/driver-readings-first-plan.md`, Р2, Р3, Р6, Р10).
 *
 * Прежде эти же слова стояли на кнопке шапки: кнопка называла состояние отчёта, а не действие —
 * «Передать» и «Передано» — разные новости. Кнопки больше нет (кабинет и так открывается формой),
 * а новость осталась, и осталась дословно: она переехала строкой над формой показаний.
 *
 * Экран собирается из двух ответов — сохранённого отчёта и задания, — и правило над матрицей одно:
 * **существующий отчёт старше живого задания**. Пустое задание никогда не прячет сохранённые
 * числа: после отправки состав заморожен, и переназначенный источник остаётся строкой отчёта.
 *
 * Порядок проверок и есть матрица, поэтому он не переставляется:
 *
 * 1. отчёт, закрытый для водителя, читается в любом окне — и `open` не зовёт даже внутри
 *    семидневного окна: состав у него заморожен, и запрос был бы тяжёлой транзакцией без единого
 *    следствия (Р2);
 * 2. отчёта нет вовсе — решает задание: пустое даёт слова вместо формы (Р6), непустое в окне
 *    записи открывает отчёт, потому что до `open` записывать некуда;
 * 3. окно записи закрыто, а отчёт открыт — читающая форма с локальным рядом (Р10);
 * 4. в окне записи `submitted` правится по сохранённому отчёту без `open` (состав заморожен), а
 *    `draft` открывается, если открывать есть что, — тот же `open` синхронизирует состав.
 */
function stateOf(
  report: DriverReportDto | null,
  hasLocalDraft: boolean,
  canSubmit: boolean,
  hasAssignment: boolean,
): DayFacts {
  // После приёмки водитель отчёт не правит (ADR 0103, Р23): правки вносит персонал, и строка это
  // говорит. Локальное на такие числа не накладывается — в учёте лежат не они (Р10).
  if (report?.state === 'accepted')
    return reading('Принято', 'Показания приняты — правки вносит диспетчер', 'none');
  if (report?.state === 'needs_reacceptance')
    return reading('На повторном приёме', 'День уже принимали — правки вносит диспетчер', 'none');
  if (report?.state === 'voided')
    return reading('Аннулирован', 'Отчёт этого дня аннулирован', 'none');

  if (!report) {
    // Пустой день формы не получает — но только когда отчёта нет вовсе (Р6): открывать нечего, и
    // «Передать показания» над пустым экраном читалось бы как поломка.
    if (!hasAssignment) return nothing('На этот день заданий нет');
    // Вне окна записи открывать нечем и незачем: день прошёл, а сдать его уже не примут.
    if (!canSubmit) return nothing('Показания за этот день не передавались');
  }

  // Окно записи уже окна чтения: читать — 30 дней назад, передавать — сегодня и семь предыдущих.
  // Держит его сервер (`canSubmit`), портал границу не вычисляет.
  if (!canSubmit)
    return reading(report?.state === 'submitted' ? 'Передано' : 'Черновик', WINDOW_HINT, 'aside');

  if (report?.state === 'submitted')
    return {
      label: 'Передано',
      hint: 'Можно поправить, пока день не приняли',
      submittable: true,
      // Состав отправленного дня заморожен, и `syncDraftItems` его не тронет: открывать нечего.
      open: false,
      draft: 'edit',
      notice: '',
    };

  /*
   * Открытый для правки день — «нет отчёта» и `draft` одной клеткой, и склеены они не для
   * краткости. С Э3 ответ `open` ложится в тот же кэш, которым живёт матрица (Р8), а сам `open`
   * уходит от показа дня (Р2) — значит `draft` перестал означать «водитель что-то заполнил»: в это
   * состояние день переводит просмотр. Строка над формой называет то, что видит человек, поэтому
   * «Заполнено, но не передано» стоит только там, где действительно заполнено, — локальным
   * черновиком или уже записанным показанием.
   */
  const rows = report?.items ?? [];
  const filled = hasLocalDraft || rows.some((item) => item.reading !== null);
  return {
    label: filled ? 'Черновик' : 'Передать показания',
    hint: filled ? 'Заполнено, но не передано' : '',
    submittable: true,
    /*
     * Вторая половина Р2 — «есть что открывать»: непустое задание или уже заведённые строки. Без
     * неё день, у которого рейсы отменили после открытия, бил бы тяжёлой транзакцией по каждой
     * загрузке страницы: отчёт остаётся `draft`, а синхронизировать в нём нечего — ни в задании,
     * ни в отчёте ни одного источника. Правку день при этом принимает: строк просто нет.
     */
    open: hasAssignment || rows.length > 0,
    draft: 'edit',
    notice: '',
  };
}

/**
 * Задание дня — вторая половина экрана и второй читающий запрос кабинета. Живёт рядом с матрицей
 * потому, что настройки чтения у обоих одни (`cabinetRead`, Р7) и гейт у обоих один: разъехавшись,
 * они дали бы день, у которого отчёт свежий, а состав — вчерашний.
 *
 * Ключ тот же, которым задание читает своя страница: второго запроса за тем же самым не будет.
 */
export function useAssignment(date: string, enabled: boolean) {
  return useQuery({
    queryKey: driverKeys.assignment(date),
    queryFn: () => driverCabinetApi.assignment(date),
    ...cabinetRead,
    enabled,
  });
}

/**
 * Предыдущий снимок счётчиков по строке отчёта. Живёт он в задании, а не в отчёте, и сопоставляется
 * источником, а не `itemId`: в задании тот появляется только после открытия отчёта. Живёт рядом с
 * самим заданием по той же причине — читается оно одним ответом на всю страницу.
 */
export function usePreviousOf(
  assignment: DriverAssignmentDto | undefined,
): (item: ReportItemDto) => DriverPreviousReading | null {
  const previous = useMemo(
    () => new Map((assignment?.entries ?? []).map((entry) => [sourceKey(entry), entry.previous])),
    [assignment],
  );
  return (item) => previous.get(sourceKey(item)) ?? null;
}

/**
 * Состояние дня для страницы показаний. `null` — «ещё неизвестно»: матрицу нельзя считать по
 * половине ответов, а показать «Передать показания» над днём, который уже приняли, значило бы
 * предложить правку там, где её не примут.
 *
 * Отчёт спрашивается по ключу `driverKeys.report(date)` — тому единственному, где отчёт и живёт
 * (Р8). Ответы `open` и `submit` кладутся туда же, поэтому матрица считается по свежему отчёту, а
 * не по снимку «до»: второй кэш разъехался бы с этим, и первой это увидела бы строка долга в шапке.
 *
 * Задание приходит от страницы, а не запрашивается здесь: тем же ответом она рисует предыдущие
 * снимки счётчиков, и второй запрос был бы за тем же самым. `undefined` — «ещё не прочитано» (или
 * не прочиталось вовсе): матрица по половине ответов не считается, а отказ показывает страница.
 *
 * `enabled` — гейт чтений (Р7): пока `open` или `submit` в полёте, читать нельзя, потому что
 * фоновый ответ, стартовавший до мутации, затёр бы её результат. Выключенный запрос не обновляется
 * и по возврату в приложение — на это и расчёт.
 *
 * `hasLocalDraft` приходит признаком, а не читается здесь из хранилища, и это не экономия строк:
 * чтение перебирает весь `localStorage` и по пути консолидирует ветки, а рендер случается на
 * каждое нажатие клавиши — на дешёвом телефоне это лаг ввода в кабине. Читатель черновика у
 * кабинета один — состояние страницы, которое обновляют смена дня, запись и событие `storage`
 * (Р11в); второй, свой, разъехался бы с ним на первой же отправке.
 *
 * «Заполнено, но не передано» считается и по записям прежнего формата: они тоже введены человеком
 * и тоже никуда не уехали — то, что портал показывает их отдельным блоком (Р14), состояния дня не
 * меняет.
 */
export function useDayState(
  date: string,
  hasLocalDraft: boolean,
  assignment: DriverAssignmentDto | undefined,
  enabled: boolean,
): DayState | null {
  const stored = useQuery({
    queryKey: driverKeys.report(date),
    queryFn: () => driverCabinetApi.report(date),
    ...cabinetRead,
    enabled,
  });
  if (stored.isPending || !assignment) return null;
  const report = stored.data ?? null;
  return {
    ...stateOf(report, hasLocalDraft, assignment.canSubmit, assignment.entries.length > 0),
    report,
  };
}

// ── Открытие отчёта: гейт, задержка, учёт открытых дат ──

/**
 * Сколько ждать, прежде чем открывать отчёт показанного дня (Р7).
 *
 * Дни листают стрелками — по нажатию на шаг, — и без паузы каждый промежуточный день на пути от
 * «сегодня» к «минус пять» открывался бы тяжёлой транзакцией с блокировками машин и источников.
 * Таймер заводится заново всякой сменой даты, поэтому `open` уходит только за тем днём, на котором
 * палец остановился.
 *
 * 400 мс — дольше, чем длится одно нажатие стрелки, и короче, чем задержка, которую человек
 * замечает как «портал думает».
 */
const OPEN_DELAY_MS = 400;

/**
 * Состав источников дня — множеством пар «вид: идентификатор». Именно им сравниваются задание и
 * отчёт: `itemId` строки ожидания переживает не всё (строку пересоздают переносом источника), а
 * рейс остаётся тем же рейсом. Порядок строк ни о чём не говорит, поэтому он снимается сортировкой.
 */
const sourcesOf = (rows: readonly { sourceKind: string; sourceId: string }[]): string =>
  [...new Set(rows.map(sourceKey))].sort().join('|');

/**
 * Гейт чтения и записи (Р7). Фоновый `GET` умеет стартовать до мутации и завершиться после неё — и
 * тогда снимок «до» ложится в кэш поверх свежего ответа, а страница показывает отчёт со старой
 * версией, то есть гарантированный 409 на следующей отправке.
 *
 * Поэтому у мутации две границы: перед запросом отменяются уже летящие чтения отчёта
 * (`cancelQueries`), а на время полёта читающие запросы кабинета выключаются — выключенный запрос
 * не обновляется и по возврату в приложение. Единственный писатель кэша в это время — сама мутация,
 * и писать она обязана внутри `run`, до того как гейт откроется.
 */
export interface ReadGate {
  /** Мутация в полёте: пока true, читающие запросы кабинета выключены. */
  busy: boolean;
  run: <T>(work: () => Promise<T>) => Promise<T>;
}

export function useReadGate(date: string): ReadGate {
  const queryClient = useQueryClient();
  // Счётчик, а не флаг: полёты умеют накладываться. Открытый черновик рисуется сохранённым отчётом
  // сразу, а его `open` уходит только через паузу — и «Передать», нажатое в этом промежутке, даёт
  // две мутации разом. Флаг открыл бы гейт на первой завершившейся, пока вторая ещё в пути.
  const [flights, setFlights] = useState(0);
  const run = useCallback(
    async <T>(work: () => Promise<T>): Promise<T> => {
      setFlights((count) => count + 1);
      try {
        await queryClient.cancelQueries({ queryKey: driverKeys.report(date) });
        return await work();
      } finally {
        setFlights((count) => count - 1);
      }
    },
    [date, queryClient],
  );
  const busy = flights > 0;
  // Ссылка на гейт стабильна, пока не менялось само состояние: она уходит в зависимости эффекта
  // открытия, и новый объект на каждый рендер заводил бы таймер заново до бесконечности.
  return useMemo(() => ({ busy, run }), [busy, run]);
}

/** Отказ открытия и способ повторить его — больше странице от протокола ничего не нужно. */
export interface OpenProtocol {
  /** Отказ словами; `null` — открывать не пробовали или получилось. */
  error: string | null;
  /** Повтор — только нажатием (Р8). */
  retry: () => void;
}

/**
 * Открытие отчёта показом дня (Р2, Р7, Р8): когда, сколько раз и что делать с отказом.
 *
 * Три правила, и каждое стоит запроса, которого не будет.
 *
 * 1. **Учёт открытых дат.** Дата помнится вместе с составом источников, с которым день открывали:
 *    повторный `open` за ту же дату не уходит. Ref, а не состояние — учёт ничего не рисует, а
 *    перерисовка от него завела бы второй `open` ровно там, где его и не нужно.
 * 2. **По фокусу `open` вслепую не повторяется** — он тяжёлый. Повторяется он тогда, когда состав
 *    источников задания разошёлся с составом строк отчёта: рейс, заведённый диспетчером в обед,
 *    приходит перечитанным по возврату заданием и включает открытие сам. Сравнение с
 *    **запомненным** составом здесь не украшение, а страховка от петли: сервер имеет право не
 *    отдать источник, занятый чужим отчётом, и тогда расхождение останется навсегда — открывать
 *    из-за него по разу в 400 мс значило бы бить по базе там, где ей и без того плохо.
 * 3. **Неудача открытием не считается.** Дата попадает в учёт только по успеху, а отказ показывается
 *    сообщением с кнопкой «Повторить». Автоповтора нет намеренно: `open` — тяжёлая транзакция с
 *    блокировками, и слепой ретрай по рвущейся сети добивает базу ровно в неподходящий момент.
 */
export function useAutoOpen(
  date: string,
  day: DayState | null,
  assignment: DriverAssignmentDto | undefined,
  gate: ReadGate,
): OpenProtocol {
  const queryClient = useQueryClient();
  const opened = useRef(new Map<string, string>());
  const [failure, setFailure] = useState<{ date: string; message: string } | null>(null);

  const sources = sourcesOf(assignment?.entries ?? []);
  const seen = opened.current.get(date);
  // Состав отчёта сверяется с составом задания: строка, уже заведённая соседней вкладкой, второго
  // открытия не стоит.
  const parted = day?.report ? sourcesOf(day.report.items) !== sources : false;
  const due = (day?.open ?? false) && (seen === undefined || (parted && seen !== sources));
  // Отказ принадлежит дню: у соседней даты своя новость, и держать над ней чужую нельзя.
  const error = failure?.date === date ? failure.message : null;

  useEffect(() => {
    if (!due || error !== null || gate.busy) return;
    const timer = window.setTimeout(() => {
      void gate
        .run(async () => {
          const dto = await driverCabinetApi.open(date);
          // Учёт и кэш обновляются внутри полёта, до того как гейт откроется: между открытием гейта
          // и записью успело бы влезть фоновое чтение — то самое, ради которого гейт и заводился.
          opened.current.set(date, sources);
          queryClient.setQueryData(driverKeys.report(date), dto);
        })
        .catch((e: unknown) => setFailure({ date, message: errorMessage(e) }));
    }, OPEN_DELAY_MS);
    return () => window.clearTimeout(timer);
  }, [date, due, error, gate, sources, queryClient]);

  return { error, retry: () => setFailure(null) };
}
