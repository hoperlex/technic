import { useEffect, useState } from 'react';

/**
 * Куда встал низ экрана при открытой клавиатуре (ADR 0103, Р14; план кабинета Р9).
 *
 * Отдельным модулем, а не строками в странице показаний: вместе они переваливают за 400 строк —
 * порог бюджета качества (`scripts/quality.mjs`). Хук ничего не знает ни о показаниях, ни о
 * кабинете: он отвечает на один вопрос браузера, и переиспользовать его сможет любой закреплённый
 * подвал.
 *
 * Android сжимает окно, и страница ужимается вместе с ним; iOS кладёт клавиатуру ПОВЕРХ страницы,
 * ничего не сжимая, — и закреплённый у нижнего края подвал уезжает под неё. Различие видит только
 * `visualViewport`: его высота и смещение и дают ту полосу, которую занимает клавиатура. Без этой
 * поправки требование «клавиатура не закрывает кнопку» (Р14) держалось бы на одной операционной
 * системе из двух.
 *
 * Возвращается одно число — на сколько поднять подвал. Высота видимой части, которую хук отдавал
 * прежде, была нужна обёртке `Drawer`: лист занимал видимую часть окна целиком. Подвал страницы
 * такой обёртки не имеет, и второе значение осталось бы неиспользуемым.
 */
export function useKeyboardInset(): number {
  const [inset, setInset] = useState(0);
  useEffect(() => {
    const viewport = window.visualViewport;
    if (!viewport) return;
    const sync = () => {
      const bottom = Math.max(0, window.innerHeight - viewport.height - viewport.offsetTop);
      // Полоса в несколько десятков пикселей — это не клавиатура, а полоса прокрутки или панель
      // браузера: подниматься над ними означало бы дёргать подвал на каждой прокрутке страницы.
      setInset(bottom > 80 ? bottom : 0);
    };
    sync();
    viewport.addEventListener('resize', sync);
    viewport.addEventListener('scroll', sync);
    return () => {
      viewport.removeEventListener('resize', sync);
      viewport.removeEventListener('scroll', sync);
    };
  }, []);
  return inset;
}
