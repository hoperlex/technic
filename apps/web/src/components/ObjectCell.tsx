import type { CSSProperties } from 'react';
import { Typography } from 'antd';

/**
 * Ширина колонки заказчика во всех списках портала. Одна на все модули: колонка отвечает на один
 * и тот же вопрос — «чья это заявка», — и разъехавшиеся ширины читались бы как разные колонки.
 */
export const OBJECT_COLUMN_WIDTH = 180;

/**
 * Наименование переносится на две строки, а не обрезается в одну: объект узнают по концу
 * названия — «…корпус 3» и «…корпус 7» различаются последним словом, — и одной строки на 180 px
 * для этого не хватает. Двумя, а не сколькими придётся: иначе строка таблицы растёт под самое
 * длинное название, а сравнивают в списке соседние строки. Что не поместилось — в подсказке.
 */
const nameBox: CSSProperties = {
  display: '-webkit-box',
  WebkitBoxOrient: 'vertical',
  WebkitLineClamp: 2,
  overflow: 'hidden',
  // Длинное слово без пробелов (номер участка, индекс) переносится внутри колонки, а не
  // растягивает её.
  overflowWrap: 'anywhere',
};

/** Адрес остаётся однострочным: он второй вопрос к списку, и высоту строки за него не отдают. */
const line: CSSProperties = { overflow: 'hidden', textOverflow: 'ellipsis', whiteSpace: 'nowrap' };

/**
 * Адрес не участвует в подборе ширины колонки: при `width: 0` его вклад в max-content нулевой
 * (процент в `minWidth` браузер считает за `auto`, пока ширина родителя неизвестна), а при
 * отрисовке `minWidth: '100%'` возвращает строке всю ширину ячейки.
 */
const addressBox: CSSProperties = { width: 0, minWidth: '100%' };

/**
 * Заказчик заявки в строке таблицы: наименование объекта (или код отдела), а под ним — адрес.
 * Адрес отвечает на «куда ехать» — второй вопрос к списку после самой заявки, — но своей колонки
 * не стоит: у заявок отдела адреса нет (ADR 0040), и колонка стояла бы пустой через строку.
 *
 * Обрезаются строки по отдельности, а не `ellipsis` самой колонки: тот рассчитан на однострочную
 * ячейку и второй строке места не оставляет. Полный текст — в подсказке наведения.
 */
export function ObjectCell({
  name,
  hint,
  address,
}: {
  name: string;
  /**
   * Что показать в подсказке вместо самого текста. Ею назван отдел: в списке он стоит кодом —
   * так его и называют в работе, — а полное наименование спрашивают наведением.
   */
  hint?: string | null;
  address?: string | null;
}) {
  // Адрес в справочнике необязателен: пустой не занимает вторую строку — иначе высота строк
  // таблицы плясала бы от того, заполнили ли объекту адрес.
  const trimmed = address?.trim();
  return (
    <div style={{ lineHeight: 1.35 }}>
      <div style={nameBox} title={hint || name}>
        {name}
      </div>
      {trimmed && (
        <div style={addressBox}>
          <Typography.Text
            type="secondary"
            style={{ ...line, display: 'block', fontSize: 12 }}
            title={trimmed}
          >
            {trimmed}
          </Typography.Text>
        </div>
      )}
    </div>
  );
}
