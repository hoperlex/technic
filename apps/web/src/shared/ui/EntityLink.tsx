import type { ReactNode } from 'react';
import { Link } from 'react-router';

/**
 * Номер чужой записи ссылкой: маршрут в строке заявки, заявка в составе маршрута, талон
 * заказчика в журнале листов. Ведёт на вкладку, где эту запись показывают, и просит открыть её
 * карточку (`?tab=…&open=…`).
 *
 * Настоящая ссылка, а не кнопка с переходом, по двум причинам. Её открывают средним щелчком и
 * Ctrl'ом — соседней вкладкой браузера, не теряя списка, из которого пришли. И клик по ней не
 * открывает заодно карточку самой строки: `DataTable` отдаёт строку нажатию только там, где под
 * курсором не оказалось ссылки или кнопки (см. `opensRow`).
 */
export function EntityLink({
  to,
  title,
  children,
}: {
  /**
   * Куда вести. `null` — некуда: раздел или вкладка этой роли не положены (см. `utils/links`), и
   * номер остаётся прежним текстом. Проверка здесь, а не у каждого вызова, потому что мест
   * вызова много, а условие у них одно.
   */
  to: string | null;
  /** Подсказка наведения: чем этот переход кончится — «Открыть маршрут», «Открыть заявку». */
  title?: string;
  children: ReactNode;
}) {
  if (!to) return <>{children}</>;
  return (
    <Link to={to} title={title} className="entity-link">
      {children}
    </Link>
  );
}
