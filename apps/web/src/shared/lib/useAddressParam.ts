import { useSearchParams } from 'react-router';

/**
 * Предмет, названный в адресе страницы одним ключом: `?journal=<id>`, `?maintenance=<id>`.
 *
 * Обещаний у такого окна три, и все три даёт только адрес: ссылку присылают коллеге («посмотри,
 * что с этой машиной»), «назад» закрывает окно, перезагрузка оставляет его открытым. Состояние
 * компонента (`useState`) не даёт ни одного из трёх — оно теряется и от перезагрузки, и от
 * «назад», и пересылке не подлежит вовсе.
 *
 * Хуком, а не строками по месту: приём был написан дословно дважды — журнал показаний в гараже и
 * сводка ТО в соседней колонке, — а третьим за ним шёл справочник техники. Копии расходятся
 * ровно на тех мелочах, из которых обещания и складываются: открытие обязано быть переходом, а
 * закрытие — заменой записи в истории.
 *
 * Ключ здесь один и без значения: «открыто ли и что» — вопрос с одним ответом. Экрану, у которого
 * в адресе живёт несколько ключей сразу (период, подвкладка, открытый предмет), нужен свой разбор
 * — как `pages/garage/readingsAddress`.
 */
export interface AddressParam {
  /** Идентификатор из адреса либо `null`: открытого предмета нет — или он не положен смотрящему. */
  id: string | null;
  open: (id: string) => void;
  close: () => void;
  /** Адрес для ссылки в строке: текущие ключи страницы плюс названный предмет. */
  href: (id: string) => string;
}

/**
 * `allowed` — положен ли предмет смотрящему. Без права ключ не читается вовсе, и это не украшение
 * к серверной проверке: у страницы и у окна права бывают разные (срез гаража открывает
 * `garage.read`, цифры приборов — `vehicleReadings.read`), и присланная ссылка иначе открывала бы
 * окно, которому нечего показать.
 */
export function useAddressParam(name: string, allowed = true): AddressParam {
  const [params, setParams] = useSearchParams();

  const patch = (change: (next: URLSearchParams) => void, replace: boolean) => {
    const next = new URLSearchParams(params);
    change(next);
    setParams(next, { replace });
  };

  return {
    id: allowed ? params.get(name) || null : null,
    /** Открытие — переход: «назад» после него обязано закрыть окно, а не увести со страницы. */
    open: (id) => patch((next) => next.set(name, id), false),
    /**
     * Закрытие — заменой записи в истории: «назад» после него возвращает туда, откуда пришли по
     * ссылке, а не открывает окно заново.
     */
    close: () => patch((next) => next.delete(name), true),
    href: (id) => {
      const next = new URLSearchParams(params);
      next.set(name, id);
      return `?${next.toString()}`;
    },
  };
}
