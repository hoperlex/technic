/**
 * Как число печатается человеку: разряды и единица, которые не должны разрываться переносом.
 *
 * В фундаменте, а не в слайсе: правила портала тут нет вовсе — есть типографика числа, одинаковая
 * для сводки показаний, колонки гаража и акта обслуживания. До этого «128 400 км» собирали в трёх
 * местах одной и той же строкой, и каждая копия несла свой неразрывный пробел.
 */

/** Неразрывный: «128 400 км» не должно переноситься на две строки посреди числа. */
export const NBSP = ' ';

/** Разряды неразрывными пробелами: `128400` → «128 400». */
export function groupDigits(value: string): string {
  return value.replace(/\B(?=(\d{3})+(?!\d))/gu, NBSP);
}

/** Пробег человеку: «128 400 км», единица от числа не отрывается. */
export function kmText(km: number): string {
  return `${groupDigits(String(km))}${NBSP}км`;
}
