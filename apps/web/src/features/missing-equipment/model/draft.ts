import type { EquipmentCandidateInput } from '@technic/contracts';
import { newIdempotencyKey } from '@shared/lib';

/**
 * Заявленный аппарат, ещё не отправленный: то, что окно «Сообщить об аппарате» кладёт в форму
 * заявки (план `docs/office-equipment-candidate-plan.md`, Р2, Р7, §9).
 *
 * ОКНО НИЧЕГО НЕ ОТПРАВЛЯЕТ САМО, и черновик — прямое следствие этого решения. Кандидат и заявка
 * рождаются одной транзакцией одного `POST /service-requests` (Р2): отдельной ручки «завести
 * кандидата» нет вовсе, и она оставляла бы кандидатов-сирот при каждом обрыве на втором шаге.
 * Поэтому окно заполняет форму и закрывается, подпись его кнопки — «Отправить с заявкой», а уходит
 * всё обычным «Сохранить» самой заявки.
 */
export interface EquipmentCandidateDraft {
  /**
   * Ключ идемпотентности ЭТОЙ попытки (§8). Живёт в черновике, а не рождается на каждое нажатие
   * «Сохранить», и это ровно требование плана: повтор после обрыва обязан нести тот же ключ, а
   * изменение сообщения — начинать новую попытку. Ключ на нажатие защищал бы только от двойного
   * клика (его и без того держит заблокированная кнопка), а от потерянного успешного ответа — нет:
   * человек нажал бы второй раз и завёл вторую заявку с вторым кандидатом.
   *
   * Правка сообщения рождает новый черновик и новый ключ: иначе изменённое тело под занятым ключом
   * получило бы 409 идемпотентности — отказ, из которого человеку нечего сделать.
   */
  intakeKey: string;
  /** Шесть реквизитов ровно в том виде, в каком они уйдут в теле заявки (Р7). */
  input: EquipmentCandidateInput;
  /** Тип словами: плашка под полем называет аппарат, а не идентификаторы справочников. */
  typeName: string;
  /**
   * Площадка заявленного аппарата — в том виде, в каком её читает подбор заказчика заявки.
   *
   * ФОРМОЙ ПОДБОРА, А НЕ ОДНОЙ ПОДПИСЬЮ, и это не удобство вызова. Заказчик заявки на обслуживание
   * считается по площадке ВЫБРАННОЙ ЕДИНИЦЫ, а единицы здесь нет вовсе — поле «Для кого заявка»
   * осталось бы запертым «до выбора техники» навсегда, то есть заявку с сообщением нельзя было бы
   * отправить в принципе. Место при этом уже названо самим человеком (Р7), и спрашивать его второй
   * раз незачем.
   *
   * `departmentId` — всегда `null`: отдела-владельца у наблюдения нет (Р7), его проставляет
   * проверяющий в форме карточки. Для роли отдела это означает, что площадка ей в подборе не
   * предложится, и заказчиком останется её отдел, — ровно то же, что делает сервер.
   */
  site: { objectId: string; objectLabel: string; departmentId: null };
}

/**
 * Собирает черновик и минтит ему ключ. Отдельной функцией, а не литералом в окне: ключ обязан
 * рождаться ровно там, где рождается сообщение, — забытый вызов в одной из будущих точек дал бы
 * черновик без ключа, то есть заявку, которую сервер отобьёт 400 уже после заполнения формы.
 */
export function equipmentCandidateDraft(
  input: EquipmentCandidateInput,
  labels: { typeName: string; objectLabel: string },
): EquipmentCandidateDraft {
  return {
    intakeKey: newIdempotencyKey(),
    input,
    typeName: labels.typeName,
    site: { objectId: input.objectId, objectLabel: labels.objectLabel, departmentId: null },
  };
}
