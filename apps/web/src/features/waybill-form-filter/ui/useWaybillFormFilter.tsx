import type { ReactNode } from 'react';
import { Select } from 'antd';
import { WAYBILL_FORM_CODES, waybillFormLabels, waybillFormShortLabels } from '@technic/contracts';
import type { FilterDefinition } from '@shared/ui';

/**
 * Фильтр по бланку работы дня — тем ли документом закрывается день: 4-П, форма № 3 или ЭСМ-2.
 *
 * Спрашивают им работу, а не справочник техники: бланк считается по самой работе дня
 * (`busyWaybillForms` в контрактах гаража) — перегон всегда 4-П, грузовой рейс идёт бланком типа
 * машины, недельный лист и заказ спецтехники — ЭСМ-2, а у арендной машины бланка нет вовсе, лист
 * на неё выписывает арендодатель. Поэтому и колонки «тип ТС» здесь мало: одна и та же машина в
 * один день закрывается разными бланками.
 *
 * Набор, а не одно значение, по той же причине, что и на сервере: у дня бывает две работы разных
 * бланков сразу — линейный заказ ведёт рейс дня (4-П) и лист ЭСМ-2 по требованию (ADR 0100), — и
 * строка проходит фильтр по пересечению своего набора с выбранным. Свободный день не проходит
 * никакой отбор по бланку: бланка у него нет, и показывать такую строку в ответе «покажи всех на
 * ЭСМ-2» значило бы отвечать не на вопрос.
 *
 * Слоем `features`, а не рядом с вкладкой гаража: тот же вопрос задаёт «Заказ ТС» → «На объекте»,
 * а импорт из соседней страницы запрещён границами слоёв — и правильно запрещён: общее двух
 * разделов не может принадлежать одному из них. Сосед по слою — `features/vehicle-maintenance`,
 * которым уже пользуются гараж и справочник.
 *
 * Хуком, хотя своего запроса у фильтра нет: справочник бланков — константы контрактов. Вид тот же,
 * что у соседнего `useVehicleClassificationFilter`, и вкладке всё равно, чем набор вариантов
 * добывается — так фильтры и ставятся в полосу одинаково.
 */

/**
 * Варианты — сам справочник бланков, а не выписанные руками три строки: заведись здесь второй
 * список значений, фильтр однажды предложил бы бланк, которым не закрывается ни одна работа.
 *
 * Подпись короткая (`waybillFormShortLabels`): выбранное показывается тегами, и три полных имени
 * в поле полосы не помещаются вовсе. Полное имя едет рядом (`title`) и всплывает подсказкой — там
 * место есть, и «Форма № 3» без пояснения «легковой автомобиль» читается не всяким.
 */
const FORM_OPTIONS = WAYBILL_FORM_CODES.map((code) => ({
  value: code,
  label: waybillFormShortLabels[code],
  title: waybillFormLabels[code],
}));

/**
 * Канонический вид набора для строки запроса: порядок задаёт справочник, а не то, в каком порядке
 * нажимали варианты, — иначе один и тот же выбор давал бы две разные строки, два ключа кэша и два
 * запроса за одним и тем же ответом. Заодно отсеивается всё, чего в справочнике нет.
 *
 * Пустой набор даёт `undefined`, а не пустую строку: для списка «фильтра нет» и «фильтр пуст» —
 * одно и то же, а лишний параметр — ещё один ключ кэша и ещё один запрос за тем же самым.
 */
function serializeWaybillForms(codes: string[]): string | undefined {
  const chosen = new Set(codes);
  const canonical = WAYBILL_FORM_CODES.filter((code) => chosen.has(code));
  return canonical.length === 0 ? undefined : canonical.join(',');
}

export function useWaybillFormFilter({
  forms,
  onChange,
}: {
  /** Набор канонической строкой — ровно тем, что уходит в запрос: разбирать его тут и негде. */
  forms: string | undefined;
  /** Правка отбора: страницу на первую возвращает список, у него же живут остальные параметры. */
  onChange: (patch: { forms?: string }) => void;
}): { controls: ReactNode; mobileFilter: FilterDefinition } {
  // Значение поля — тот же набор массивом. Справочник у бланков в памяти, ждать нечего.
  const value = forms ? forms.split(',') : [];
  const pick = (codes: string[]) => onChange({ forms: serializeWaybillForms(codes) });

  const controls = (
    <Select
      mode="multiple"
      allowClear
      placeholder="Все бланки"
      // Три коротких тега помещаются целиком; поиска у поля нет намеренно — искать в списке из
      // трёх строк нечего, а строка ввода отняла бы место у самих тегов.
      style={{ width: 220 }}
      maxTagCount="responsive"
      options={FORM_OPTIONS}
      value={value}
      onChange={pick}
    />
  );

  /**
   * Тот же фильтр описанием — для шита на телефоне (ADR 0030). Потолка набора у него нет: больше,
   * чем есть в справочнике, не выбрать, а «выбраны все три» — это тот же вопрос к списку, что и
   * «фильтр не задан».
   */
  const mobileFilter: FilterDefinition = {
    kind: 'multiSelect',
    key: 'forms',
    label: 'Бланк',
    value,
    options: FORM_OPTIONS,
    placeholder: 'Все бланки',
    onChange: pick,
  };

  return { controls, mobileFilter };
}
