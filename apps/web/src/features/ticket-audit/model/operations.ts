/**
 * Почему у экрана нет выбора периода — подписью, а не молчанием.
 *
 * Календарь стоит на четырёх экранах из пяти, и его отсутствие на пятом человек прочтёт как
 * поломку раньше, чем как замысел. А замысел прямой (§1.3): очередь — снимок «сейчас», её нельзя
 * посчитать за июль; вызовы и отказы считаются по времени вызова фиксированным окном, и растянуть
 * его календарём — значит сложить разные величины.
 */
export const OPERATIONS_NO_PERIOD_NOTE =
  `у этого экрана нет периода: очередь и состояние — снимок «сейчас», а вызовы и отказы ` +
  `считаются по времени вызова окном в ${TICKET_AUDIT_OPERATIONS_DAYS} дней. Период соседних ` +
  `экранов отбирает наблюдения, а это другая величина, и общего календаря у них быть не может`;

/** Заголовок окна вызовов: окно названо целиком, включая то, по какому времени оно считается. */
export function windowLabel(days: number): string {
  return `За ${days} дней (по времени вызова)`;
}

/**
 * Сбои за последний час. Ноль печатается словами, а не «0»: строка отвечает на вопрос дежурного
 * «сейчас-то всё хорошо?», и «сбоев не обнаружено» отвечает на него, а ноль в столбце счётчиков —
 * нет. Час назван прямо: за неделю отказы, скорее всего, были, и умолчать об окне значило бы
 * пообещать, что их не было вовсе.
 */
export function failuresLastHourView(count: number): { text: string; tone: StateTone } {
  if (count <= 0) return { text: 'Сбоев не обнаружено за последний час', tone: 'secondary' };
  return { text: `Сбоев за последний час: ${count}`, tone: 'warning' };
}

/**
 * Пара «класс × область» одной подписью: `transient/subsystem`. Пара, а не два столбца, потому что
 * читается она вместе — временный отказ подсистемы и окончательный отказ по одному талону это
 * разные беды, и различает их именно сочетание.
 *
 * Пустая половина печатается прочерком на своём месте, а не выпадает: сервер отдаёт пустую строку,
 * когда отказ себя не назвал, и `transient/` без второй половины читался бы как обрезанный текст.
 */
export function failureCodeLabel(code: { errorClass: string; errorScope: string }): string {
  return `${code.errorClass || '—'}/${code.errorScope || '—'}`;
}

/** День и время: секунды здесь не нужны — состояние читают, а не хронометрируют. */
const SHOWN_MOMENT = 'DD.MM.YYYY HH:mm';

/**
 * Последний успешный вызов. `null` — успешных не было ВОВСЕ, и сказано это словами: прочерк на
 * месте момента читается как «не знаем», а правда — «ни один вызов не дошёл до конца».
 *
 * НИКАКОГО ПЕРЕВОДА ПОЯСА, как и в ленте: сервер присылает московское время уже развёрнутым
 * (`to_char(… AT TIME ZONE …)`), без пояса в самой строке. Переведи мы его ещё раз, вкладка в
 * другом поясе показала бы момент, которого в журнале нет.
 */
export function lastSuccessLabel(at: string | null): string {
  if (at === null) return 'успешных вызовов не было';
  return dayjs(at).format(SHOWN_MOMENT);
}

/**
 * Момент ответа — и это ЕДИНСТВЕННОЕ время на экране, которое переводится в московский пояс.
 *
 * Разница не в оформлении: `generatedAt` сервер отдаёт настоящим ISO с поясом (`toISOString`), а
 * последний успешный вызов — строкой без пояса. Прочитай мы их одним правилом, одно из двух
 * съехало бы на разницу поясов вкладки, и два момента на одном экране стали бы несравнимы.
 *
 * Печатается он обязательно и с датой: без него экран читается как «прямо сейчас» и врёт вкладке,
 * открытой со вчера, — а очередь и час без сбоев тем и ценны, что они про «сейчас».
 */
export function generatedLabel(iso: string): string {
  return dayjs(iso).tz(MOSCOW_TZ).format(SHOWN_MOMENT);
}

/**
 * Возраст старейшей ждущей задачи. `null` — очередь пуста, и это сказано словами: «старейшая 0 мин»
 * читалось бы как «только что положили».
 *
 * Часы отделяются от минут, потому что счёт идёт до тысяч: «старейшая 2880 мин» глазами не
 * читается, а «2 дня» — читается, и именно по этому числу решают, встала очередь или движется.
 */
export function oldestLabel(minutes: number | null): string {
  if (minutes === null) return 'очередь пуста';
  if (minutes < 60) return `старейшая ${minutes} мин`;
  const hours = Math.floor(minutes / 60);
  if (hours < 24) return `старейшая ${hours} ч ${minutes % 60} мин`;
  return `старейшая ${Math.floor(hours / 24)} сут ${hours % 24} ч`;
}

/**
 * Очередь строкой. Ждут, выполняются, упали, мертвы — четыре разных состояния задачи, и складывать
 * их в «в очереди N» нельзя: упавшая задача повторится сама, мёртвая не повторится никогда, и
 * ровно она требует человека.
 */
