/**
 * Как читается состояние подсистемы (§5.4 плана): каким словом названо состояние, что значит ноль
 * в каждой строке и почему у этого экрана нет календаря.
 *
 * Отдельно от правил чисел (`numbers.ts`), потому что вопрос другой: там — что печатать в ячейке
 * доли, здесь — долей нет вовсе. На экране только счётчики и слово состояния, и ни одно из этих
 * чисел не является числителем чего бы то ни было: делить вызовы на разборы или отказы на очередь
 * значило бы придумать показатель, которого никто не определял (§1 — число без определения на
 * экран не попадает).
 */

/** Тон подписи. Своим типом, а не строкой antd: модель не знает разметки и знать не должна. */
export type StateTone = 'success' | 'warning' | 'danger' | 'secondary';

