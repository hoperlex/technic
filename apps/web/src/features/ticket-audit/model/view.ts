/**
 * Экран окна аудита: как он живёт в адресе.
 *
 * Отдельным модулем от периода, потому что это разные вопросы к одной ссылке: период отвечает
 * «за какие дни», экран — «с какой стороны показать». Сложи мы их в один файл, правка одного
 * заставляла бы перечитывать правила другого.
 */

/** Имя параметра адреса. То же, что нарисовано в §5 плана: `?ticketAudit=1&view=cohorts`. */
export const VIEW_PARAM = 'view';

/**
 * Экраны окна в порядке переключателя. Порядок задан здесь, а не в разметке: перечисление — это
 * ещё и порядок вкладок, и разъедься они, ссылка `view=` начала бы открывать не тот экран, который
 * человек видел слева.
 *
 * Пять и всё: сводка отвечает «сколько правят», когорты — «что менять в конвейере», лента — «какие
 * правила писать в промпт», подсистема — «работает ли вообще», точность — «насколько верно».
 * Последние два стоят в хвосте намеренно: подсистема к качеству чтения отношения не имеет вовсе, а
 * точность §5.5 запрещает ставить рядом со сводкой — её процент и доля исправлений посчитаны по
 * разным выборкам, и соседство читалось бы как два взгляда на одно.
 *
 * `blind`, а не `accuracy`, — по имени ручки и выборки: адрес называет, ОТКУДА число, а заголовок
 * экрана — что оно значит. Ссылка `view=accuracy` обещала бы точность потока, которой этой выборкой
 * не измерить (§3).
 */
export const TICKET_AUDIT_VIEWS = ['summary', 'cohorts', 'events', 'operations', 'blind'] as const;

export type TicketAuditView = (typeof TICKET_AUDIT_VIEWS)[number];

/**
 * Умолчание — сводка: окно открывают за ответом «сколько правят», а разбор по конфигурациям
 * читают следом и осознанно.
 */
export const DEFAULT_TICKET_AUDIT_VIEW: TicketAuditView = 'summary';

/** Подписи переключателя. Рядом с перечислением, чтобы новый экран нельзя было забыть подписать. */
export const TICKET_AUDIT_VIEW_LABELS: Record<TicketAuditView, string> = {
  summary: 'Сводка',
  cohorts: 'Когорты',
  events: 'Лента',
  operations: 'Подсистема',
  blind: 'Точность',
};

/**
 * Экран из адреса. Неизвестное значение кончается умолчанием, а не пустым окном: адрес правят
 * руками и присылают в письмах, и `view=когорты` из чужой раскладки должен показать сводку, а не
 * белый прямоугольник без объяснения.
 */
export function readTicketAuditView(raw: string | null): TicketAuditView {
  const known = TICKET_AUDIT_VIEWS.find((view) => view === raw);
  return known ?? DEFAULT_TICKET_AUDIT_VIEW;
}
