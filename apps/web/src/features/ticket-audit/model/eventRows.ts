/**
 * Машинное событие: его совершила модель, а не человек.
 *
 * Список здесь, а не в контракте, потому что это правило чтения ленты, а не форма ответа. Держит
 * его сервер (`waste_ticket_field_events_actor_check`): у чтения и спора автора нет вовсе, и
 * пустое имя в этих двух строках — норма, а не потерянная учётка.
 */
export function isMachineEvent(event: TicketAuditEvent): boolean {
  return event === 'recognized' || event === 'disputed';
}

/**
 * Кто в строке автора. Три случая названы врозь: модель, человек и «учётки больше нет» — разные
 * ответы, а нарисованные одним прочерком читаются как потеря данных.
 */
export type EventActorView =
  | { kind: 'machine' }
  | { kind: 'named'; name: string }
  /** Человеческое событие без имени: учётку удалили, след потерялся, событие осталось. */
  | { kind: 'lost' };

export function eventActorView(row: TicketAuditEventRow): EventActorView {
  if (isMachineEvent(row.event)) return { kind: 'machine' };
  return row.actorName ? { kind: 'named', name: row.actorName } : { kind: 'lost' };
}

export const ACTOR_MACHINE_NOTE = 'Событие машинное: чтение совершила модель, человека здесь нет';

export const ACTOR_LOST_NOTE =
  'Учётка удалена: имя не сохраняется в самом событии, а ссылка на неё обнуляется. Событие от ' +
  'этого не исчезает — исчезает только имя';

/**
 * Чем пусто значение.
 *
 * Три случая названы врозь, потому что это три разные новости. «Модель не смогла прочесть» — про
 * качество чтения, и по таким полям считается доля непрочитанного. «Графы нет» — про бланк:
 * талон простоя объёма не несёт, и в ту долю такие поля не входят вовсе (§1.4). Прочерк — про то,
 * что признак чтения к этой строке не относится: человеческие события его не несут. Слей мы их в
 * один прочерк, самая частая жалоба на модель («не читает объём») выглядела бы так же, как
 * бумага, на которой объёма и не было.
 */
export type EmptyValueView =
  /** `read_state = 'unreadable'`: чтение не состоялось, и это счётная ошибка модели. */
  | { kind: 'unreadable' }
  /** `read_state = 'not_applicable'`: графы на бланке нет. Не ошибка чтения вовсе. */
  | { kind: 'not-applicable' }
  /** Значения нет, но признак чтения о нём ничего не говорит; объясняет пустоту сама подсказка. */
  | { kind: 'blank'; hint: string };

/**
 * Строка значений: подпись слева, значение справа.
 *
 * ДВЕ СТРОКИ, А НЕ ОДНА СО СТРЕЛКОЙ (§5.3). Значение поля — это и адрес площадки в сто знаков:
 * «было → стало» одной строкой обрезается ровно там, где начинается разница, а разбор ошибки без
 * полного значения невозможен. Столбиком переносится каждое целиком.
 */
export interface EventValueLine {
  label: string;
  /** `null` — значения нет; чем именно оно отсутствует, говорит `empty`. */
  value: string | null;
  /** Что стоит вместо пустого значения. Смотрится только при `value === null`. */
  empty: EmptyValueView;
}

export const UNREADABLE_NOTE =
  'Модель не смогла прочесть поле: графа на бланке есть, а чтения нет. Это счётная ошибка ' +
  'чтения — по таким полям и считается доля непрочитанного в сводке.';

export const NOT_APPLICABLE_NOTE =
  'Графы на бланке нет: талон простоя объёма не несёт. Это не ошибка модели, и в долю ' +
  'непрочитанного такие поля не входят вовсе (§1.4).';

/**
 * Признак чтения есть у машинного события всегда (`collection_version >= 2` держит `CHECK`), и
 * пустое значение при `read` — расхождение, а не обычное дело. Прочерк здесь честнее слов: сказать
 * «не прочитано» без признака значило бы приписать модели ошибку по догадке.
 */
const READING_UNEXPLAINED_NOTE =
  'Значения нет, а признак чтения его не объясняет: не сказано ни «не прочитано», ни «графы ' +
  'нет». Судить по этой строке о качестве чтения нельзя.';

const DISPUTE_VALUES_NOTE =
  'У спора итога нет: проходы разошлись, и портал не выбирает за человека. Кандидаты обеих ' +
  'ступеней в ленту не выведены — их разбирают в самой заявке';

const EMPTY_BEFORE_NOTE = 'Поля не было: до события значение пустовало';

const EMPTY_AFTER_NOTE = 'Стало пусто. Очистка поля — тоже правка: талон простоя объёма не несёт';

const TICKET_GONE_VALUE_NOTE = 'В талоне на момент события значения не было';

const PROPOSAL_EMPTY_NOTE = 'Новый проход значения не дал: по этому полю предложение пустое';

const BASELINE_EMPTY_NOTE = 'Снимок машинного чтения пуст: на момент отбора поле пустовало';

/**
 * Пустое МАШИННОЕ чтение — по признаку с сервера, а не по догадке.
 *
 * Правило живёт здесь, а не в разметке, потому что признак читают две ячейки — таблица и карточка
 * телефона, — и разъедься они, одно и то же поле называлось бы на двух видах по-разному.
 */
function machineReadingEmpty(row: TicketAuditEventRow): EmptyValueView {
  if (row.readState === 'unreadable') return { kind: 'unreadable' };
  if (row.readState === 'not_applicable') return { kind: 'not-applicable' };
  return { kind: 'blank', hint: READING_UNEXPLAINED_NOTE };
}

/** Пустота, к признаку чтения отношения не имеющая: человеческие события его не несут вовсе. */
function blank(hint: string): EmptyValueView {
  return { kind: 'blank', hint };
}

/**
 * Что печатать в паре строк у каждого события.
 *
 * Подписи разные не для красоты: «было/стало» у правки, «в талоне/предложено» у отказа от
 * предложения и «машина/проверка» у арбитража отвечают на разные вопросы, а одна пара слов на все
 * события выдавала бы отказ от предложения за исправление машины.
 *
 * У машинных событий подпись строки — «чтение», а не «прочитано»: вместо пустого значения там
 * стоит «не прочитано», и «прочитано: не прочитано» читалось бы как оговорка портала.
 */
export function eventValueLines(row: TicketAuditEventRow): EventValueLine[] {
  switch (row.event) {
    case 'recognized':
      return [{ label: 'чтение', value: row.newValue, empty: machineReadingEmpty(row) }];
    case 'disputed':
      // Спор пуст не поэтому: итога у поля не было вовсе, а кандидаты обоих проходов в ленту не
      // выведены. Признак чтения тут ни при чём — у спора он говорит о самих кандидатах.
      return [{ label: 'чтение', value: null, empty: blank(DISPUTE_VALUES_NOTE) }];
    case 'edited':
      return [
        { label: 'было', value: row.oldValue, empty: blank(EMPTY_BEFORE_NOTE) },
        { label: 'стало', value: row.newValue, empty: blank(EMPTY_AFTER_NOTE) },
      ];
    case 'proposal':
      return [
        { label: 'в талоне', value: row.oldValue, empty: blank(TICKET_GONE_VALUE_NOTE) },
        { label: 'принято', value: row.newValue, empty: blank(PROPOSAL_EMPTY_NOTE) },
      ];
    case 'proposal_dismissed':
      return [
        { label: 'в талоне', value: row.oldValue, empty: blank(TICKET_GONE_VALUE_NOTE) },
        { label: 'предложено', value: row.newValue, empty: blank(PROPOSAL_EMPTY_NOTE) },
      ];
    case 'arbitrated':
      return [
        { label: 'машина', value: row.oldValue, empty: blank(BASELINE_EMPTY_NOTE) },
        { label: 'проверка', value: row.newValue, empty: blank(EMPTY_AFTER_NOTE) },
      ];
    case 'dismissed':
      // Снятие талона значений не меняет: показывается только то, что в нём стояло.
      return [{ label: 'в талоне', value: row.oldValue, empty: blank(TICKET_GONE_VALUE_NOTE) }];
  }
}

/** Часы и минуты; секунды в ленте не нужны — события разбирают, а не хронометрируют. */
const SHOWN_TIME = 'HH:mm';

/**
 * Момент события двумя частями: день и время.
 *
 * НИКАКОГО ПЕРЕВОДА ПОЯСА. Сервер присылает московские сутки уже развёрнутыми в местное время
 * (`to_char(… AT TIME ZONE …)`), без пояса в самой строке, и `dayjs` читает её как есть. Переведи
 * мы её ещё раз, вкладка в другом поясе показывала бы время, которого в журнале нет, — и события
 * разъехались бы с периодом, подписанным как московский.
 */
export function eventMoment(at: string): { day: string; time: string } {
  const moment = dayjs(at);
  return { day: moment.format(SHOWN_DATE), time: moment.format(SHOWN_TIME) };
}

/**
 * Имя кнопки скана для читающих экран голосом. Со страницей, когда она известна: на кадре бывает
 * два талона, а в файле — десять страниц, и «открыть скан» без номера обещает не то.
 */
export function scanAriaLabel(pageNo: number | null): string {
  return pageNo === null ? 'Открыть скан талона' : `Открыть скан талона, страница ${pageNo}`;
}

/** Заголовок окна просмотра: тот же ответ, что и у кнопки, — человек должен узнать, что открыл. */
export function scanTitle(pageNo: number | null): string {
  return pageNo === null ? 'Скан талона' : `Скан талона, страница ${pageNo}`;
}

