import type { TicketAuditCohortRow } from '@technic/contracts';

/**
 * Как читается сама когорта: чем она себя называет, чем отличается от соседней и в каком порядке
 * строки стоят.
 *
 * Отдельно от правил чисел (`numbers.ts`), потому что вопросы разные: там — что печатать в ячейке
 * доли, здесь — что печатать вместо имени модели, которого нет, и почему две пустоты в соседних
 * столбцах значат разное. Разметка и тут только рисует готовое решение.
 */

/**
 * Что стоит в ячейке модели. Три случая названы врозь намеренно: имя, «модель себя не назвала» и
 * «эскалации не было» — разные ответы, а нарисованные одним прочерком читаются одинаково, и
 * прочтёт их читатель как поломку отчёта.
 */
export type CohortModelView =
  | { kind: 'named'; name: string }
  /** Снимок наблюдения пуст: имени модели в нём нет. Законное состояние, а не потеря данных. */
  | { kind: 'unnamed' }
  /** Второй ступени в этой когорте не было вовсе — здесь нечего называть. */
  | { kind: 'absent' };

/**
 * Модель первого прохода. Пустая строка — не ошибка выгрузки: имя берётся снимком из наблюдения
 * (§2.1 плана, попытки убираются по сроку), и модель, не назвавшая себя в ответе, оставляет его
 * пустым. Печатать вместо этого имя из настроек нельзя: настройка с тех пор могла смениться, и
 * подставленное имя приписало бы чужой модели чужие ошибки.
 */
export function primaryModelView(row: TicketAuditCohortRow): CohortModelView {
  return modelSnapshotView(row.primaryModel);
}

/**
 * Снимок имени модели как таковой — им же подписана и строка ленты (§5.3): вопрос там тот же, и
 * ответ обязан быть тем же. Разъедься эти два места, один экран печатал бы пустое имя пустотой, а
 * другой — словами, и читатель решил бы, что видит разные состояния.
 */
export function modelSnapshotView(name: string): CohortModelView {
  return name ? { kind: 'named', name } : { kind: 'unnamed' };
}

/**
 * Модель второй ступени. `null` — эскалации в когорте не было, и это не «имя потерялось»: у
 * большинства разборов второй проход не включается вовсе, и когорта без него — самая обычная.
 */
export function escalationModelView(row: TicketAuditCohortRow): CohortModelView {
  if (row.escalationModel === null) return { kind: 'absent' };
  return row.escalationModel ? { kind: 'named', name: row.escalationModel } : { kind: 'unnamed' };
}

/** Подсказка к пустой основной модели: пустой снимок — законное состояние, а не сбой сбора. */
export const PRIMARY_MODEL_UNNAMED_NOTE =
  'Модель себя не назвала: имя берётся снимком из наблюдения, и в этом снимке его нет. ' +
  'Подставить имя из текущей настройки нельзя — она с тех пор могла смениться.';

/** Подсказка к прочерку в столбце эскалации: её не было, а не «не знаем какая». */
export const ESCALATION_ABSENT_NOTE =
  'Эскалации в этой когорте не было: второй проход не включался. Это не ноль и не пропуск — ' +
  'разбор кончился на первой ступени.';

/**
 * Версии промпта и подготовки одной подписью: `v3/п2` — как нарисовано в §5.2 и §5.3. Одной, а не
 * двумя колонками, потому что читают их всегда вместе: смысл имеет пара, а не каждое число врозь.
 *
 * Принимает пару чисел, а не строку когорты: ровно та же пара стоит в строке ленты, и второй
 * такой же формат разошёлся бы с первым на первой правке — «v3/п2» на одном экране против «3/2»
 * на соседнем.
 *
 * Неизвестная версия печатается прочерком на своём месте (`v3/—`), а не выпадает из подписи: иначе
 * `v3` без второй половины читался бы как «подготовки не было».
 */
export function versionsLabel(row: {
  promptVersion: number | null;
  preprocessingVersion: number | null;
}): string {
  if (row.promptVersion === null && row.preprocessingVersion === null) return '—';
  const prompt = row.promptVersion === null ? '—' : `v${row.promptVersion}`;
  const preprocessing = row.preprocessingVersion === null ? '—' : `п${row.preprocessingVersion}`;
  return `${prompt}/${preprocessing}`;
}

/**
 * Ключ строки: когорта — это вся четвёрка настроек, а не модель. Конфигурации не пересекаются
 * (§5.2), поэтому четвёрка уникальна; собери мы ключ из одной модели — две её когорты, с
 * эскалацией и без, слиплись бы в одну строку таблицы.
 */
export function cohortKey(row: TicketAuditCohortRow): string {
  return [
    row.primaryModel,
    row.escalationModel ?? '',
    row.promptVersion ?? '',
    row.preprocessingVersion ?? '',
  ].join('|');
}

/**
 * Порядок строк задаёт клиент, а не ответ: обход обязан быть устойчивым, иначе строки прыгают
 * между обновлениями и таблицу перестают читать глазами (то же решение принято для полей сводки).
 *
 * Сначала крупные когорты: строка на семьдесят разборов говорит о потоке больше, чем строка на
 * шесть, а порядок «по доле исправлений» превратил бы таблицу в турнирную — ровно то чтение,
 * против которого написана подпись под ней.
 */
export function sortCohorts(rows: readonly TicketAuditCohortRow[]): TicketAuditCohortRow[] {
  return [...rows].sort(
    (a, b) => b.runs - a.runs || cohortKey(a).localeCompare(cohortKey(b), 'ru'),
  );
}
