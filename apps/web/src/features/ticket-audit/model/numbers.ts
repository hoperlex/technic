import {
  TICKET_AUDIT_DISPUTED_FIELDS,
  TICKET_AUDIT_MIN_SAMPLE,
  accuracyDenominator,
  accuracyRight,
  wilsonInterval,
  type TicketAuditAccuracyField,
  type TicketAuditCascade,
  type TicketAuditCohortRow,
  type TicketAuditFieldRow,
  type WasteTicketField,
} from '@technic/contracts';

/**
 * Правила чисел сводки — ради них модуль и писался (§10 плана: убедительный интерфейс с неверными
 * процентами опаснее падения и медленного запроса).
 *
 * Правила собраны здесь, а не в разметке, по одной причине: в разметке они существовали бы
 * пятью копиями — по одной на столбец, — и разошлись бы на первой же правке. Разметка получает
 * готовое решение «что печатать» и только рисует его.
 */

/**
 * Что стоит в ячейке доли. Случаи названы врозь намеренно: ноль ошибок, отсутствие наблюдений,
 * маленькая выборка и показатель, не определённый для этого поля, — это разные ответы, а сложи мы
 * их в одно число, все они читались бы одинаково: «0 %».
 */
export type RatioView =
  /** Наблюдений не было вовсе: печатать нечего, и «0 %» здесь означало бы «ошибок нет». */
  | { kind: 'no-data' }
  /** Числа есть, доли нет: знаменатель меньше `TICKET_AUDIT_MIN_SAMPLE`, и это сказано словами. */
  | { kind: 'small-sample'; numerator: number; denominator: number }
  /** Только числа: доля у этого показателя не печатается по замыслу (см. `disputedView`). */
  | { kind: 'counts'; numerator: number; denominator: number }
  | { kind: 'share'; numerator: number; denominator: number; percent: number }
  /** Показатель не определён для этого поля — каскад его не сверяет. Это не ноль. */
  | { kind: 'not-measured' };

/**
 * Абсолютные числа и доля по ним.
 *
 * Процент при `n < TICKET_AUDIT_MIN_SAMPLE` не печатается вовсе (§10): при десятке наблюдений он
 * скачет на десятки процентов от одного исправления, и напечатанный — читается как измерение.
 * Знаменателя нет — нет и строки: `0 / 0` вместе с «0 %» выглядели бы как отличный результат.
 */
export function ratioView(numerator: number, denominator: number): RatioView {
  if (denominator <= 0) return { kind: 'no-data' };
  if (denominator < TICKET_AUDIT_MIN_SAMPLE)
    return { kind: 'small-sample', numerator, denominator };
  // Округление до целого процента — то же, которым сверяет макеты `waste-ticket-audit-plan.check.py`:
  // разойдись экран со сверкой, «13 %» плана и «12,9 %» портала пришлось бы объяснять руками.
  return {
    kind: 'share',
    numerator,
    denominator,
    percent: Math.round((numerator / denominator) * 100),
  };
}

/**
 * Сверяет ли каскад это поле. Только номер, дата и объём: у вида работ и адреса спора не бывает
 * по устройству, а не по случаю — и разбирать там нечего.
 */
export function cascadeCompares(field: WasteTicketField): boolean {
  return TICKET_AUDIT_DISPUTED_FIELDS.includes(field);
}

/** Подпись под таблицей: почему в двух строках стоят прочерки, а не нули. */
export const CASCADE_FIELDS_NOTE =
  'каскад сверяет только номер, дату и объём: у вида работ и адреса спор не определён';

/** Доля исправлений: знаменатель — решённые наблюдения (`corrected + accepted`), а не все (§1.4). */
export function correctedView(row: TicketAuditFieldRow): RatioView {
  return ratioView(row.corrected, row.decided);
}

/**
 * «Решено человеком» — разбор спора: портал не предложил значения, а честно попросил решить.
 * У полей вне каскада прочерк, а не ноль: спора там не бывает, и ноль читался бы как «спорили,
 * но разбирать не пришлось» (§1.4 исключает эти два поля из знаменателя вовсе).
 */
export function resolvedDisputeView(row: TicketAuditFieldRow): RatioView {
  if (!cascadeCompares(row.field)) return { kind: 'not-measured' };
  return ratioView(row.resolvedDispute, row.observations);
}

/** Доля непрочитанного считается по всем полям: пустоту модель возвращает где угодно. */
export function unreadableView(row: TicketAuditFieldRow): RatioView {
  return ratioView(row.unreadable, row.observations);
}

/**
 * Спорных — числом, без доли: так нарисован макет §5.1. Спор это событие каскада, а не оценка
 * чтения, и процент рядом с тремя соседними долями читался бы как ещё одна оценка качества модели.
 *
 * `null` от сервера и поле вне каскада дают один и тот же прочерк, но проверяются оба: сервер
 * говорит «не определено» формой ответа, а список полей — правилом, и молчаливое расхождение
 * между ними должно кончиться прочерком, а не нулём.
 */
export function disputedView(row: TicketAuditFieldRow): RatioView {
  if (!cascadeCompares(row.field) || row.disputed === null) return { kind: 'not-measured' };
  if (row.observations <= 0) return { kind: 'no-data' };
  return { kind: 'counts', numerator: row.disputed, denominator: row.observations };
}

// ── Экран когорт (§5.2) ──
//
// Числа те же по устройству: числитель, знаменатель, доля только от `TICKET_AUDIT_MIN_SAMPLE`
// наблюдений. Правила живут здесь, а не рядом с таблицей когорт, ровно по той же причине, что и
// правила сводки: две копии одного порога разошлись бы на первой же правке, и один экран начал бы
// печатать процент там, где второй печатает «данных недостаточно».

/** Доля исправлений когорты. Знаменатель тот же, что в сводке: решённые наблюдения (§1.4). */
export function cohortCorrectedView(row: TicketAuditCohortRow): RatioView {
  return ratioView(row.corrected, row.decided);
}

/** Доля непрочитанного когорты — от всех её наблюдений, а не от решённых. */
export function cohortUnreadableView(row: TicketAuditCohortRow): RatioView {
  return ratioView(row.unreadable, row.observations);
}

/**
 * Главная подпись экрана — и причина, по которой он вообще может существовать.
 *
 * Три доли, стоящие столбцом друг под другом, читаются как таблица результатов состязания, и
 * прочитанные так, они лгут: A/B не проводится, конфигурации видят разный поток (когорта живёт
 * ровно столько, сколько держится настройка), а старшая ступень видит только трудные случаи —
 * те, где первый проход промолчал или разошёлся со вторым. Её доля исправлений обязана быть выше
 * не потому, что модель хуже.
 */
export const COHORTS_INCOMPARABLE_NOTE =
  'доли когорт нельзя сравнивать напрямую: A/B не проводится, конфигурации видят разный поток, ' +
  'а старшая ступень получает только трудные случаи — те, где первый проход промолчал или ' +
  'разошёлся со вторым. Экран показывает, что происходит в каждой когорте, а не какая ' +
  'конфигурация лучше: такой вывод требует прогонки одной выборки обеими.';

/**
 * Заполнено вторым проходом — доля от пустот первого. Единственная доля каскада: она отвечает на
 * осмысленный вопрос «сколько пустот закрыла вторая ступень», и знаменатель у неё честный — те
 * самые поля, которые второму проходу и достались.
 */
export function cascadeFilledView(cascade: TicketAuditCascade): RatioView {
  return ratioView(cascade.filledBySecond, cascade.emptyAfterPrimary);
}

/**
 * Исход спора — числом при знаменателе, без доли. Так же, как «Спорных» в сводке, и по той же
 * причине: споров за месяц десятки, четыре исхода делят это число между собой, и процент рядом с
 * каждым читался бы как оценка качества ступени, которой он не является.
 *
 * Споров не было — «нет данных», а не четыре нуля: ноль исходов у ноля споров означает «спорить
 * было не о чем», а напечатанный столбцом читается как «спорили, но ничего не решили».
 */
export function cascadeOutcomeView(value: number, disputes: number): RatioView {
  if (disputes <= 0) return { kind: 'no-data' };
  return { kind: 'counts', numerator: value, denominator: disputes };
}

/**
 * Почему исходы названы операторскими и почему слова «арбитраж» в блоке каскада нет.
 *
 * Спор каскада не может дойти до независимого проверяющего: талон нельзя подтвердить, пока
 * спорное поле не разобрано, разбор ставит отметку правки, а выборка слепой перепроверки талоны с
 * правкой исключает. Сигнал полезен, но независимым не является, и назови мы его арбитражем —
 * приписали бы ему чужую доказательную силу.
 */
export const CASCADE_OUTCOMES_NOTE =
  'Исходы операторские: спор разбирает тот же человек, что подтверждает талон. Независимой ' +
  'проверки у спора каскада не бывает вовсе — подтверждение не проходит, пока спорное поле не ' +
  'разобрано, а разбор ставит отметку правки, и выборка слепой перепроверки такие талоны ' +
  'исключает. Сигнал полезен, но независимым его считать нельзя.';

// ── Экран точности (§5.5) ──
//
// Числа те же по устройству, что у сводки и когорт, и порог выборки тот же: доля печатается от
// `TICKET_AUDIT_MIN_SAMPLE` и ни наблюдением раньше. Правила стоят здесь, а не рядом с таблицей
// точности, ровно по той причине, по которой здесь стоят правила когорт: две копии одного порога
// разошлись бы на первой правке, и один экран начал бы печатать процент там, где второй печатает
// «данных недостаточно».

/**
 * Верно / n по одному полю. Числитель и знаменатель берутся ФУНКЦИЯМИ КОНТРАКТА, а не считаются
 * здесь: ровно по этим формулам считает сервер и выгрузка (§1.4), и посчитай портал по-своему —
 * два ответа об одной выборке разошлись бы молча.
 */
export function accuracyFieldView(row: TicketAuditAccuracyField): RatioView {
  return ratioView(accuracyRight(row), accuracyDenominator(row));
}

/**
 * Итог по трём полям. Числители и знаменатели уже сложены (`accuracyTotals`), и это не то же
 * самое, что среднее трёх процентов: у полей разные знаменатели, и среднее дало бы каждому полю
 * равный вес — число, которого никто не измерял.
 */
export function accuracyTotalView(totals: { right: number; n: number }): RatioView {
  return ratioView(totals.right, totals.n);
}

/**
 * Интервал Уилсона рядом с процентом — или ничего.
 *
 * Считается функцией контракта: у сервера, выгрузки и портала он обязан быть одним. Порог тот же,
 * что у самой доли, и это главное правило этой ячейки: где не печатается процент, не печатается и
 * интервал. Напечатанный при `n < 30` — «данных недостаточно, 41–98 %» — он читался бы как
 * измерение, причём тем убедительнее, чем шире.
 */
export type IntervalView =
  { kind: 'hidden' } | { kind: 'interval'; lowPercent: number; highPercent: number; n: number };

export function accuracyIntervalView(right: number, n: number): IntervalView {
  if (n < TICKET_AUDIT_MIN_SAMPLE) return { kind: 'hidden' };
  const { low, high } = wilsonInterval(right, n);
  // Округление до целого процента — то же, которым сверяет макеты `waste-ticket-audit-plan.check.py`:
  // разойдись экран со сверкой, «84–98 %» плана и «83,6–97,7 %» портала пришлось бы объяснять руками.
  return {
    kind: 'interval',
    lowPercent: Math.round(low * 100),
    highPercent: Math.round(high * 100),
    n,
  };
}

/**
 * Что интервал меряет — и, главное, чего не меряет. Подпись обязана стоять рядом с ним, а не в
 * подсказке: интервал выглядит как мера неуверенности целиком, и прочитанный так, он обещает, что
 * истина лежит между его границами. Между ними лежит только случайный разброс ЭТОЙ выборки;
 * смещение (в неё не попадают талоны, которые исправляли) двигает обе границы разом, и измерить
 * его интервалом нельзя в принципе.
 */
export const ACCURACY_INTERVAL_NOTE =
  'интервал отражает только случайный разброс внутри смещённой выборки, самого смещения — того, ' +
  'что исправленные талоны в неё не попадают, — он не измеряет и измерить не может';
