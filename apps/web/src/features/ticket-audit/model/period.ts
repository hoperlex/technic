import dayjs from 'dayjs';
import { ticketAuditPeriodSchema, type TicketAuditPeriod } from '@technic/contracts';
import { EVENTS_PARAMS } from './eventFilters';
import { VIEW_PARAM } from './view';

/**
 * Период аудита распознавания: как он живёт в адресе и чем становится по умолчанию.
 *
 * Отдельным модулем от хука, потому что чтение адреса — чистая функция: её видно целиком, и она
 * одинаково отвечает на «пришли по ссылке из письма» и «открыли кнопкой».
 */

/** Формат границ периода: сутки, а не момент. Тот же, что ждёт ручка (§1.3 плана). */
export const PERIOD_DATE = 'YYYY-MM-DD';

/** Как период показывается человеку. */
export const SHOWN_DATE = 'DD.MM.YYYY';

/**
 * Имена параметров адреса. Окно аудита открыто, пока в адресе есть `ticketAudit`, — по образцу
 * ADR 0120: состояние окна это сам адрес, и ссылку с периодом можно переслать или положить в
 * закладку. Значение ключа не смотрится: важен факт его присутствия, как у `?routes=1`.
 */
export const AUDIT_PARAM = 'ticketAudit';
export const FROM_PARAM = 'from';
export const TO_PARAM = 'to';

/**
 * Всё, что окно пишет в адрес, — и ровно это оно за собой убирает при закрытии. Под окном остался
 * реестр со своей вкладкой, открытой карточкой и фильтрами: они обязаны пережить открытие и
 * закрытие аудита.
 */
export const AUDIT_PARAMS: readonly string[] = [
  AUDIT_PARAM,
  FROM_PARAM,
  TO_PARAM,
  VIEW_PARAM,
  // Фильтры и страница ленты — тоже её ключи: оставленные в адресе, они пережили бы закрытие окна
  // и вернулись бы при следующем открытии отбором, которого человек уже не помнит.
  ...EVENTS_PARAMS,
];

/**
 * Умолчание — последние 30 дней. Не «месяц» и не «с начала месяца»: первого числа такой отчёт
 * показывал бы один день, а `TICKET_AUDIT_MIN_SAMPLE` требует тридцати наблюдений только чтобы
 * напечатать процент.
 */
export const DEFAULT_PERIOD_DAYS = 30;

export function defaultTicketAuditPeriod(today = dayjs()): TicketAuditPeriod {
  return {
    from: today.subtract(DEFAULT_PERIOD_DAYS, 'day').format(PERIOD_DATE),
    to: today.format(PERIOD_DATE),
  };
}

/**
 * Период из адреса. Проверяется схемой контракта, а не глазами: адрес правят руками и присылают
 * в письмах, и `from=вчера` или перевёрнутый период должны кончиться умолчанием, а не запросом с
 * границами, которых сервер не поймёт, — и не пустым экраном без объяснения.
 */
export function readTicketAuditPeriod(from: string | null, to: string | null): TicketAuditPeriod {
  const parsed = ticketAuditPeriodSchema.safeParse({
    from: from ?? undefined,
    to: to ?? undefined,
  });
  return parsed.success ? parsed.data : defaultTicketAuditPeriod();
}

/**
 * Чему принадлежит период на экране — и это не оформление подписи.
 *
 * Экраны метрик отбирают по времени НАБЛЮДЕНИЯ, лента — по времени СОБЫТИЯ (§1.3), точность — по
 * времени ВЫДАЧИ слепой перепроверки. Границы у всех троих одни и те же, а отвечают они на разные
 * вопросы: правка, сделанная сегодня по августовскому
 * чтению, стоит в ленте сегодняшним днём и в августовской доле исправлений одновременно. Подписи
 * лежат рядом с самим периодом, потому что различие держится только на них: перепутай мы слова —
 * и два экрана, показывающие разное, выглядели бы одинаково подписанными.
 */
export type PeriodSubject = 'observations' | 'events' | 'checks';

