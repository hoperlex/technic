import {
  TICKET_AUDIT_FIELDS,
  accuracyDenominator,
  accuracyRight,
  type TicketAuditAccuracyDto,
  type TicketAuditAccuracyField,
} from '@technic/contracts';

/**
 * Как читается точность среди неисправленных подтверждённых талонов (§3, §5.5 плана): что
 * складывается с чем, что значит каждая очередь и какими словами экран обязан признать смещение
 * своей выборки.
 *
 * Отдельно от правил чисел (`numbers.ts`) по той же границе, что у когорт: там — что печатать в
 * ячейке доли (порог выборки, проценты), здесь — из чего эта ячейка складывается и что рядом с ней
 * обязано стоять словами. Ни одна доля здесь не считается: для этого есть `ratioView`.
 */

/** Заголовок экрана целиком. Короткое «Точность» читалось бы как точность потока — а это не она. */
export const ACCURACY_TITLE = 'Точность среди неисправленных подтверждённых талонов';

/**
 * Предупреждение о смещении — дословно по §3 плана, и менять его нельзя ни словом.
 *
 * В слепую перепроверку попадают только машинные талоны, которых первый оператор не исправлял:
 * известные ошибки модели в выборку не входят вовсе. Процент, показанный без этой строки, читается
 * как точность потока и в этом качестве является неправдой — ровно той убедительной неправдой,
 * ради которой модуль и переписывался (§10).
 *
 * Не «верхняя оценка»: строгой границей это не является — оператор может исправить и уже верное
 * значение, так что общая точность потока теоретически бывает и выше.
 */
export const ACCURACY_BIAS_NOTE =
  'Выборка смещена в сторону неисправленных талонов и не оценивает общую точность потока; ' +
  'число ожидаемо оптимистично.';

/**
 * Почему совпадение идёт в числитель верных. Слепое согласие двух независимых чтений — это
 * свидетельство, и выбросить его значило бы считать точность по одним расхождениям, то есть по
 * выборке, где машина ошиблась по определению.
 */
export const ACCURACY_MATCHED_NOTE =
  'Два независимых чтения совпали. Совпадение считается верным: слепое согласие — свидетельство, ' +
  'а точность, посчитанная по одним расхождениям, мерила бы только те случаи, где кто-то ошибся.';

/**
 * Почему знаменатель не равен числу проверок. Неразобранное расхождение не считается ни верным, ни
 * неверным: верного значения по нему ещё никто не назвал, и любое из двух решений было бы выдумкой.
 */
export const ACCURACY_DENOMINATOR_NOTE =
  'Знаменатель — совпадения плюс РАЗОБРАННЫЕ расхождения. Расхождение, которого арбитр ещё не ' +
  'разобрал, не считается никак: верного значения по нему никто не называл.';

/**
 * Почему здесь слово «арбитраж» уместно, а в блоке каскада его нет.
 *
 * Спор каскада разбирает тот же человек, что подтверждает талон, — независимости там нет по
 * устройству. Здесь наоборот: перепроверка слепая (проверяющий не видит машинных значений), а
 * расхождение разбирает третий, и присылает он ЗНАЧЕНИЯ, а не выбор из двух. Отсюда и третий исход:
 * ошиблись оба.
 */
export const ACCURACY_ARBITRATION_NOTE =
  'Арбитраж здесь настоящий: перепроверка слепая — проверяющий не видит машинных значений, — а ' +
  'расхождение разбирает третий человек. Он присылает значение, а не выбор из двух, поэтому ' +
  '«ошиблись оба» — выразимый исход, а не остаток.';

/**
 * Строка очередей: почему её числа нельзя складывать.
 *
 * Ошибка макета §5.5, найденная при сверке: «выдано 24 · вернулись 18 (из них 2 ждут арбитража) ·
 * ждут проверяющего 6» читается как четыре независимых слагаемых, и 18 + 2 + 6 не сходится с 24 ни
 * при каком раскладе. На деле числа ВЛОЖЕНЫ: выданные делятся на вернувшиеся и ждущие
 * проверяющего, а ждущие арбитража — часть вернувшихся.
 */
export const ACCURACY_QUEUE_NOTE =
  'Числа вложены, а не сложены: выданные проверки делятся на вернувшиеся и ждущие проверяющего, ' +
  'а ждущие арбитража — часть вернувшихся, а не отдельная очередь. Сумма всех четырёх не значит ' +
  'ничего.';

/**
 * Очереди перепроверки в том виде, в каком их можно рисовать вложенно.
 *
 * Разбиение исчерпывающее по устройству ответа: `issued` считает все выданные за период проверки,
 * `returned` — те из них, что не в состоянии «ждёт», `waitingChecker` — оставшиеся. Поэтому
 * `returned + waitingChecker = issued` всегда, и вложенность на экране не может разъехаться с
 * числами. `waitingArbitration` живёт внутри вернувшихся: это проверки с расхождением, которое
 * ещё не разобрано.
 */
export interface AccuracyQueueView {
  issued: number;
  returned: number;
  /** Часть вернувшихся: расхождение есть, арбитр его ещё не разбирал. */
  waitingArbitration: number;
  waitingChecker: number;
}

export function accuracyQueue(data: TicketAuditAccuracyDto): AccuracyQueueView {
  return {
    issued: data.issued,
    returned: data.returned,
    waitingArbitration: data.waitingArbitration,
    waitingChecker: data.waitingChecker,
  };
}

/**
 * Итог по трём полям.
 *
 * Числители и знаменатели складываются, а средний процент не считается: у полей разные знаменатели
 * (объём чаще расходится, чем дата), и среднее трёх процентов дало бы каждому полю равный вес, то
 * есть число, которого никто не измерял.
 *
 * Ждущие арбитража поля считаются здесь же, а не берутся из очередей: `waitingArbitration` считает
 * ПРОВЕРКИ, а эта строка — ПОЛЯ, и одна проверка с двумя расхождениями даёт одну и два. Подставь
 * мы сюда число проверок, подпись «5 разобрано, 2 ждут» сравнивала бы штуки с килограммами.
 */
export interface AccuracyTotals {
  right: number;
  /** Знаменатель: совпадения плюс разобранные расхождения — тот же, что у каждой строки. */
  n: number;
  matched: number;
  diverged: number;
  arbitrated: number;
  machineRight: number;
  checkerRight: number;
  bothWrong: number;
  /** Полей с расхождением, которого арбитр ещё не разбирал. */
  awaitingFields: number;
}

export function accuracyTotals(rows: readonly TicketAuditAccuracyField[]): AccuracyTotals {
  const totals: AccuracyTotals = {
    right: 0,
    n: 0,
    matched: 0,
    diverged: 0,
    arbitrated: 0,
    machineRight: 0,
    checkerRight: 0,
    bothWrong: 0,
    awaitingFields: 0,
  };
  for (const row of rows) {
    totals.right += accuracyRight(row);
    totals.n += accuracyDenominator(row);
    totals.matched += row.matched;
    totals.diverged += row.diverged;
    totals.arbitrated += row.arbitrated;
    totals.machineRight += row.machineRight;
    totals.checkerRight += row.checkerRight;
    totals.bothWrong += row.bothWrong;
    totals.awaitingFields += row.diverged - row.arbitrated;
  }
  return totals;
}

/**
 * Порядок строк — порядок бланка, тот же, что у сводки: обход обязан быть устойчивым, иначе строки
 * прыгают между обновлениями и таблицу перестают читать глазами. Берётся он из общего списка полей
 * контракта, а не переписывается здесь: два порядка одного бланка разошлись бы на первой правке.
 */
export function sortAccuracyRows(
  rows: readonly TicketAuditAccuracyField[],
): TicketAuditAccuracyField[] {
  return [...rows].sort(
    (a, b) => TICKET_AUDIT_FIELDS.indexOf(a.field) - TICKET_AUDIT_FIELDS.indexOf(b.field),
  );
}
