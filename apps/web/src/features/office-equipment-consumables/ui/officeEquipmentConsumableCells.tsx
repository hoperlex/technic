/** Остаток числом: ноль — это ответ «заказывать», и читаться он должен с одного взгляда (§6). */
export function quantityText(consumable: OfficeEquipmentConsumableDto) {
  return consumable.quantity === 0 ? (
    <Typography.Text type="danger" strong>
      0
    </Typography.Text>
  ) : (
    <Typography.Text strong>{consumable.quantity}</Typography.Text>
  );
}

/**
 * Число, у которого ноль означает «нечего показывать»: потребность «не следим», «уже заказано»
 * пусто, дефицит «заказывать нечего».
 *
 * Прочерком, а не нулём, и это тот же приём, что у «Цвета» и «Правки остатка»: три нуля подряд в
 * строке читаются как незаполненная таблица, а прочерк — как ответ. Сам ноль при этом остаётся у
 * остатка: там он значим и тревожен («полка пуста»), и подменять его прочерком нельзя.
 */
export function zeroAsDash(value: number) {
  return value === 0 ? <Typography.Text type="secondary">—</Typography.Text> : value;
}

/**
 * Дефицит: положительный выделяется, нулевой становится прочерком.
 *
 * Выделение не украшение — по этому столбцу сортируют перечень перед закупкой (Р15), и строка, с
 * которой начинают заказ, обязана находиться глазами без чтения соседних чисел.
 */
export function deficitText(consumable: OfficeEquipmentConsumableDto) {
  return consumable.deficit === 0 ? (
    <Typography.Text type="secondary">—</Typography.Text>
  ) : (
    <Typography.Text type="warning" strong>
      {consumable.deficit}
    </Typography.Text>
  );
}

