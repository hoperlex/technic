import { Button, Space, Tag, Tooltip, Typography, type TableColumnType } from 'antd';
import {
  DeleteOutlined,
  EditOutlined,
  HistoryOutlined,
  NumberOutlined,
  ShoppingOutlined,
} from '@ant-design/icons';
import type { OfficeEquipmentConsumableDto } from '@technic/contracts';
import { actionsColumn, RowActionButton, textColumn } from '@shared/ui';
import { formatDateTime } from '../../../utils/format';
import {
  ALREADY_ORDERED_HINT,
  DEFICIT_HINT,
  deficitText,
  HAS_HISTORY_HINT,
  LAST_MANUAL_STOCK_HINT,
  PARK_COUNT_HINT,
  quantityText,
  REQUIRED_HINT,
  zeroAsDash,
} from './officeEquipmentConsumableCells';

/**
 * Как перечень картриджей и тонеров выглядит списком: колонки таблицы и карточка строки на
 * телефоне (план `docs/office-equipment-consumables-plan.md`, Р8, Р11; план
 * `docs/office-equipment-consumables-and-purchase-plan.md`, Р3, Р14, Р15; приём
 * `officeEquipmentModelGrid`).
 *
 * ОДИН НАБОР КОЛОНОК НА ОБЕ ДВЕРИ, И РАЗЛИЧИЕ ВЫРАЖЕНО ТОЛЬКО ДЕЙСТВИЯМИ (Р14). Дверей две: окно
 * «Картриджи и тонеры» в «Справочниках», где номенклатуру ведут, и вкладка «Расходники» раздела
 * «Орг.техника», где со складом работают. Они обязаны показывать одно и то же **по построению, а
 * не по договорённости**, — поэтому второго перечня колонок здесь нет вовсе и параметра «какой
 * набор показать» тоже: массив один, и добавленный столбец появляется сразу в обеих дверях.
 *
 * Разное у дверей — только то, что в строке можно СДЕЛАТЬ, и выражено оно отсутствием обработчика,
 * а не флагом: на вкладке нет заведения, правки и удаления позиций (решение заказчика), значит
 * `onOpen` и `onDelete` туда не приходят вовсе. Флаг «показывать ли кнопку» рядом с обработчиком
 * означал бы два источника правды об одном и том же и рано или поздно разошёлся бы с ним —
 * кнопка есть, а нажимать нечего.
 *
 * Отдельным модулем от самих окон: в окне остаётся работа с данными — запросы, отбор, форма,
 * мутации и подтверждения, — а описание представления читается целиком, не пролистывая их. Обе
 * фабрики принимают действия, а не берут их из контекста: строка одинакова и в таблице, и в
 * карточке, и различать их должно одно место. Подписи столбцов и разбор чисел лежат рядом, в
 * `officeEquipmentConsumableCells`.
 */

export interface OfficeEquipmentConsumableGridActions {
  /**
   * Ведение номенклатуры (Р10): заведение, правка, гашение и удаление позиции. Своё право, а не
   * общее `officeEquipment.write`: иначе человеку, ведущему один справочник картриджей, пришлось
   * бы выдать правку всего парка.
   *
   * Здесь оно задаёт ровно одно — подпись карточки: «Редактировать» у ведущего, «Открыть карточку»
   * у читателя. Показ действий им не управляется: показывает их наличие обработчика.
   */
  canManage: boolean;
  /**
   * Открыть карточку позиции — там, где она вообще есть. На вкладке «Расходники» карточки нет:
   * заведение, правка и удаление остались в «Справочниках» (Р14), и кнопка, ведущая в чтение
   * формы, обещала бы вкладке ведение, которого у неё нет.
   */
  onOpen?: (consumable: OfficeEquipmentConsumableDto) => void;
  /**
   * Ручная правка остатка — второе, независимое право (Р10): пересчитать коробки на полке и
   * завести позицию номенклатуры это разные работы, и делают их разные люди. Поэтому кнопка стоит
   * и в строке: у кладовщика без `manage` карточка не откроется на правку вовсе, а остаток
   * править ему можно.
   */
  onStock?: (consumable: OfficeEquipmentConsumableDto) => void;
  /**
   * Быстрая правка потребности (Р13) — действие вкладки, где со складом работают. В справочнике
   * той же кнопки нет: там потребность стоит полем карточки, и вторая дверь к одному числу рядом с
   * первой была бы лишней. Обе при этом ведут в ОДНУ ручку правки карточки — своей ручки у
   * потребности нет вовсе.
   */
  onRequired?: (consumable: OfficeEquipmentConsumableDto) => void;
  /**
   * Открыть журнал остатка позиции (Р4). Права рядом с ним нет и не спрашивается: у чтения журнала
   * своего права не заведено вовсе — лента не показывает ничего, чего не показывал бы сам
   * перечень, и запретить её тому, кому открыта позиция, значило бы открыть человеку число и
   * запретить смотреть, откуда оно взялось.
   */
  onHistory: (consumable: OfficeEquipmentConsumableDto) => void;
  /** Удаление — только там, где ведут номенклатуру (Р14): на вкладке его нет вовсе. */
  onDelete?: (consumable: OfficeEquipmentConsumableDto) => void;
}

export function officeEquipmentConsumableColumns({
  canManage,
  onOpen,
  onStock,
  onRequired,
  onHistory,
  onDelete,
}: OfficeEquipmentConsumableGridActions): TableColumnType<OfficeEquipmentConsumableDto>[] {
  return [
    textColumn<OfficeEquipmentConsumableDto>({
      key: 'code',
      title: 'Код',
      dataIndex: 'code',
      searchable: false,
      width: 150,
    }),
    textColumn<OfficeEquipmentConsumableDto>({
      key: 'name',
      title: 'Наименование',
      dataIndex: 'name',
      searchable: false,
      render: (_v, r) => (
        <>
          {r.name}
          {r.comment && (
            <>
              <br />
              <Typography.Text type="secondary" style={{ fontSize: 12 }}>
                {r.comment}
              </Typography.Text>
            </>
          )}
        </>
      ),
    }),
    {
      key: 'color',
      title: 'Цвет',
      dataIndex: 'color',
      width: 120,
      /*
       * Сортировки нет: среди полей контракта цвета нет, и сортируемый заголовок обещал бы
       * порядок, на который маршрут ответит 400.
       *
       * Пусто — это ответ «у чёрно-белой позиции цвета не бывает», а не «не заполнили» (Р5),
       * поэтому прочерк, а не пустая ячейка: пустую читают как недоделку справочника.
       */
      render: (value: unknown) =>
        (value as string | null) || <Typography.Text type="secondary">—</Typography.Text>,
    },
    textColumn<OfficeEquipmentConsumableDto>({
      key: 'quantity',
      title: 'Наличие',
      dataIndex: 'quantity',
      searchable: false,
      width: 110,
      // Сортировка по остатку — то, ради чего в справочник заходят перед заказом: срез «что
      // заказывать» читается снизу, с нулей (Р9). Своей подсказки у ячейки нет: почему число не
      // правится прямо здесь, сказано один раз строкой под отборами.
      render: (_v, r) => quantityText(r),
    }),
    {
      key: 'requiredQuantity',
      // Подсказка у заголовка по той же причине, что и у «Правки остатка»: короткое слово
      // «Потребность» не говорит, что ноль здесь — «не следим», а не «нужно ноль штук» (Р13).
      title: <Tooltip title={REQUIRED_HINT}>Потребность</Tooltip>,
      dataIndex: 'requiredQuantity',
      sorter: true,
      width: 130,
      render: (value: unknown) => zeroAsDash(value as number),
    },
    {
      key: 'alreadyOrdered',
      title: <Tooltip title={ALREADY_ORDERED_HINT}>Уже заказано</Tooltip>,
      dataIndex: 'alreadyOrdered',
      sorter: true,
      width: 130,
      /*
       * Стоит рядом с дефицитом, а не прячется в формулу (Р15): число, которое влияет на заказ,
       * обязано быть видно. Иначе «к закупке 0» у позиции с пустой полкой читается как ошибка
       * портала, а не как «уже везут».
       */
      render: (value: unknown) => zeroAsDash(value as number),
    },
    {
      key: 'deficit',
      // «К закупке», а не «Дефицит»: столбец отвечает не «сколько не хватает до потребности», а
      // «сколько предложит форма закупки» — уже заказанное из него вычтено (Р15).
      title: <Tooltip title={DEFICIT_HINT}>К закупке</Tooltip>,
      dataIndex: 'deficit',
      sorter: true,
      width: 120,
      render: (_value: unknown, r: OfficeEquipmentConsumableDto) => deficitText(r),
    },
    {
      key: 'lastManualStockAt',
      /*
       * Подсказка стоит у самого заголовка, а не строкой под отборами: соседние подписи объясняют
       * колонки, которые прочитают неверно один раз, а эту прочитают неверно каждый раз — «Правка
       * остатка» звучит как «когда остаток менялся», и разница между «менялся» и «правили руками»
       * и есть весь столбец.
       *
       * Заголовок из-за этого не строка, а разметка, и поле сортировки на телефоне пришлось бы
       * потерять: `sortOptionsFrom` пропускает колонку с нестроковым заголовком, чтобы не поставить
       * в шит «[object Object]». Подпись ему передаёт окно перечня третьим аргументом — там, рядом
       * с вызовом, и видно, что она есть.
       */
      title: <Tooltip title={LAST_MANUAL_STOCK_HINT}>Правка остатка</Tooltip>,
      dataIndex: 'lastManualStockAt',
      sorter: true,
      width: 150,
      /*
       * Сортируемый — ради того же, ради чего столбец и заведён (Р3): найти позиции, полку которых
       * давно не пересчитывали. Поле сортировки сервер принимает (`lastManualStockAt` в перечне
       * контракта), и пустые значения он собирает в один конец — у позиции без ручных событий даты
       * нет по построению, а не «не догрузилась».
       *
       * Пусто — ПРОЧЕРК, тем же приёмом, что у «Цвета»: у позиции, заведённой с нулём, ручных
       * событий не бывает вовсе («0 → 0» журнал не пропускает), и пустая ячейка читалась бы как
       * недогруженные данные вместо честного ответа «руками не трогали».
       *
       * До минут, а не до дня: дату ставит не человек, а событие журнала, и сверяют её с самим
       * журналом — там время у строк есть, и два разных вида точности заставили бы гадать, та ли
       * это правка.
       */
      render: (value: unknown) =>
        value ? (
          formatDateTime(value as string)
        ) : (
          <Typography.Text type="secondary">—</Typography.Text>
        ),
    },
    {
      key: 'models',
      title: 'Модели',
      width: 110,
      /*
       * Сортировки по числу моделей сервер не принимает (поля контракта — наименование, код,
       * остаток, дата, потребность, «уже заказано» и дефицит): сортируемый заголовок обещал бы
       * порядок, на который маршрут ответит 400.
       *
       * Само число — длина набора из ответа, а не отдельный счётчик: второе число, посчитанное
       * своим запросом, разошлось бы с перечнем в карточке.
       */
      render: (_value: unknown, r: OfficeEquipmentConsumableDto) =>
        r.models.length === 0 ? (
          // Ноль — не украшение строки, а дыра справочника: к чему подходит код, ИТ-служба ещё не
          // сказала, и такой расходник не найдётся отбором по модели (Р6).
          <Tooltip title="Модели не указаны: расходник не найдётся отбором «что подходит к аппарату»">
            <Tag>—</Tag>
          </Tooltip>
        ) : (
          <Tooltip title={r.models.map((m) => m.name).join(', ')}>{r.models.length}</Tooltip>
        ),
    },
    {
      key: 'equipmentCount',
      title: 'В парке',
      dataIndex: 'equipmentCount',
      width: 110,
      /*
       * Сортировки нет, и это не забывчивость: число считается в области смотрящего (Р12), и
       * порядок строк, зависящий от того, кто открыл окно, читается как ошибка портала. Сервер
       * такого поля сортировки и не принимает.
       */
      render: (value: unknown) => <Tooltip title={PARK_COUNT_HINT}>{value as number}</Tooltip>,
    },
    {
      key: 'isActive',
      title: 'Активность',
      dataIndex: 'isActive',
      width: 130,
      // Тем же поводом, что и у «Моделей»: активности среди полей сортировки контракта нет.
      render: (value: unknown) => (
        <Tag color={value ? 'green' : 'default'}>{value ? 'Активен' : 'Погашен'}</Tag>
      ),
    },
    // Строка действий есть у всех: и карточку, и журнал остатка читают по `officeEquipment.read`
    // (Р10, Р4) — подобрать картридж и узнать, куда делись прошлые, должен каждый, кому видна
    // оргтехника. Различается набор действий в ней.
    actionsColumn<OfficeEquipmentConsumableDto>(
      (r) => (
        <Space>
          {onOpen && (
            <RowActionButton
              // Подпись честная: без права ведения номенклатуры карточка открывается на чтение,
              // и обещать «Редактировать» там, где сохранить нельзя, значит звать на отказ.
              title={canManage ? 'Редактировать' : 'Открыть карточку'}
              icon={<EditOutlined />}
              onClick={() => onOpen(r)}
            />
          )}
          {/* Остаток — своим действием прямо из строки: у права `stock` карточка на правку не
                открывается, а пересчитать полку ему разрешено (Р10). */}
          {onStock && (
            <RowActionButton
              title="Изменить остаток"
              icon={<NumberOutlined />}
              onClick={() => onStock(r)}
            />
          )}
          {/* Потребность (Р13) — действие вкладки, где со складом работают: план «сколько держать
                на полке» правят, глядя на дефицит, а не открывая карточку номенклатуры. */}
          {onRequired && (
            <RowActionButton
              title="Потребность"
              icon={<ShoppingOutlined />}
              onClick={() => onRequired(r)}
            />
          )}
          {/*
           * История остатка — всем, кто видит перечень (Р4): своего права у чтения журнала нет
           * вовсе. Лента не показывает ничего, чего не показывала бы сама позиция, — те же
           * события, те же имена, те же номера заявок, — и запирать её отдельным правом значило бы
           * открыть человеку число и запретить смотреть, откуда оно взялось.
           *
           * Действием строки, а не разделом карточки: вопрос «куда делись картриджи» задают,
           * стоя в перечне, и карточка на правку у кладовщика без `manage` не откроется вовсе.
           */}
          <RowActionButton
            title="История остатка"
            icon={<HistoryOutlined />}
            onClick={() => onHistory(r)}
          />
          {/*
           * Удаление доступно, пока по расходнику нет ни одного движения остатка: так
           * убирают опечатку первого дня. Дальше историю не подчищают — её держит
           * `ON DELETE RESTRICT` журнала, а не доброта маршрута (Р11).
           *
           * Кнопка обёрнута руками: antd гасит события указателя на выключенной кнопке, и
           * своя подсказка `RowActionButton` на ней не открылась бы — запрет остался бы без
           * объяснения.
           */}
          {onDelete && (
            <Tooltip title={r.hasStockHistory ? HAS_HISTORY_HINT : 'Удалить'}>
              <span>
                <Button
                  size="small"
                  danger
                  icon={<DeleteOutlined />}
                  aria-label="Удалить"
                  disabled={r.hasStockHistory}
                  onClick={() => onDelete(r)}
                />
              </span>
            </Tooltip>
          )}
        </Space>
      ),
      160,
    ),
  ];
}
