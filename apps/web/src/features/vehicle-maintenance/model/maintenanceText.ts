import type { VehicleMaintenanceDto } from '@technic/contracts';

/**
 * Как техобслуживание печатается числом и датой (план «Показания техники», Р11в, Р16).
 *
 * Отдельным модулем, а не по месту: одни и те же числа показывают блок карточки машины и окно
 * сводки механика — то, которое открывают строки гаража и справочника техники. Правило «оговорка
 * вместо точного числа» при этом не оформление, а утверждение о данных, и две его копии
 * разъехались бы при первой правке.
 *
 * Запись разрядов повторяет `pages/garage/readingNumbers`, но импортом оттуда не берётся: тот
 * модуль живёт в слое страниц, а сюда, в сценарий, слой страниц не виден вовсе. Дублируется ровно
 * форматирование — расчёта здесь нет ни одного (Р24).
 */

/** Неразрывный: «128 400 км» не должно переноситься на две строки посреди числа. */
const NBSP = ' ';

/** «128 400 км» — разряды пробелами, как у одометра в гараже и в карточке показаний. */
export function kmText(km: number): string {
  return `${String(km).replace(/\B(?=(\d{3})+(?!\d))/gu, NBSP)}${NBSP}км`;
}

/**
 * Пробег с последнего ТО. Три состояния вместо двух, и это главное здесь (Р11в):
 *
 *   — `null` — считать не по чему: прочерк, а не ноль. Ноль означал бы «машина стояла»;
 *   — точное число — цепочка показаний цела;
 *   — «не меньше 8 340 км» — оба флага могут только увеличить фактический пробег, поэтому
 *     показанное является нижней границей. Без оговорки его читают как точное и сверяют с
 *     путевыми листами, недоумевая, куда делись сотни километров.
 */
export function kmSinceText(kmSince: number | null, lowerBound: boolean): string {
  if (kmSince === null) return '—';
  return lowerBound ? `не${NBSP}меньше${NBSP}${kmText(kmSince)}` : kmText(kmSince);
}

/** Знает ли портал пробег лишь снизу — по обоим флагам сразу: они говорят об одном и том же. */
export function isLowerBound(summary: { chainBroken: boolean; lowerBound: boolean }): boolean {
  return summary.chainBroken || summary.lowerBound;
}

/** Дата в записи ТО показывается как везде в портале. */
export const SHOWN_DATE = 'DD.MM.YYYY';

/** Дата, в которой запись живёт: `YYYY-MM-DD` — её и ждут схемы ввода. */
export const DATE = 'YYYY-MM-DD';

/**
 * Одометр предыдущего акта — тот, с которым сверяется вводимый (Р11а).
 *
 * Ищется по дате обслуживания, а не «последняя запись в списке»: акт заводят задним числом, и
 * предыдущим для 10 марта может оказаться не верхняя строка журнала. Записи без одометра
 * пропускаются — сравнивать с отсутствием нечего, и это не повод молчать о более раннем числе.
 *
 * Правимая запись из поиска исключается: сравнение самой с собой всегда даёт равенство и молчание
 * там, где счётчик действительно уехал назад.
 */
export function previousOdometerKm(
  history: readonly VehicleMaintenanceDto[],
  performedOn: string,
  exceptId?: string,
): { km: number; performedOn: string } | null {
  const earlier = history
    .filter((r) => r.id !== exceptId && r.performedOn < performedOn && r.odometerKm !== null)
    .sort((a, b) => (a.performedOn < b.performedOn ? 1 : -1));
  const previous = earlier[0];
  return previous ? { km: previous.odometerKm!, performedOn: previous.performedOn } : null;
}
