import { isApiError } from '@shared/api';
import { errorMessage } from '@shared/lib';

/**
 * Оптимистическая блокировка записи ТО глазами портала (план «Показания техники», Р30) и отказы,
 * у которых 409 говорит не про версию (план `docs/auto-parts-plan.md`, Р6).
 *
 * Правка и удаление уходят с версией, которую видел правящий, и 409 значил ровно одно: пока окно
 * было открыто, запись изменил кто-то другой. Правдой это быть перестало — тем же кодом ответа
 * приходят два доменных отказа, и путать их с версией нельзя: «обновите и откройте заново» не
 * поможет ни там, ни там, а окно закрылось бы вместе с набранным.
 *
 * Поэтому отказы разведены по коду, а не по статусу:
 *
 *   — `version_conflict` — запись подвинули: сказать словами, перечитать сводку, закрыть окно;
 *   — `maintenance_voided`, `maintenance_has_stock_movements` — экран устарел: акт закрыт или у
 *     него есть движения, и журнал нужно перечитать, чтобы кнопки стали правдой.
 *
 * Отказов по строкам расхода здесь больше нет (план `docs/auto-part-receipts-plan.md`, Р2): строк
 * портал не шлёт вовсе, и прийти им неоткуда. `maintenance_has_stock_movements` остаётся: движения
 * складского журнала пережили строки (Р3), и акт с ними по-прежнему не удаляется — объяснить это
 * человеку обязан портал.
 *
 * Текст один на все действия и живёт здесь, а не в каждом обработчике: два разных объяснения
 * одного и того же отказа читались бы как две разные поломки.
 */
export const VERSION_CONFLICT_MESSAGE =
  'Запись изменили в другом окне — обновите и откройте её заново';

/** 409, у которых причина доменная: версия здесь ни при чём, и «откройте заново» не поможет. */
const DOMAIN_CONFLICTS = new Set(['maintenance_voided', 'maintenance_has_stock_movements']);

export function isVersionConflict(e: unknown): boolean {
  return isApiError(e) && e.status === 409 && !DOMAIN_CONFLICTS.has(e.code);
}

/**
 * Отказ, после которого показанный акт заведомо устарел: его аннулировали или по нему прошли
 * движения. Кнопки строки собраны по признакам записи (`hasPartMovements`, `voidedAt`), и пока
 * журнал не перечитан, они обещают действие, которого уже нет.
 */
export function isStaleRecord(e: unknown): boolean {
  return (
    isApiError(e) &&
    (e.code === 'maintenance_voided' || e.code === 'maintenance_has_stock_movements')
  );
}

/**
 * Отказ словами сервера.
 *
 * Своего совета портал не дописывает: про аннулирование и про движения сервер договаривает сам
 * («аннулируют с причиной», «исправление вводится новым актом»), и второй совет рядом спорил бы с
 * ответом. Функция всё равно одна на все действия: обработчикам незачем знать, как читается отказ.
 */
export function maintenanceErrorText(e: unknown): string {
  return errorMessage(e);
}
