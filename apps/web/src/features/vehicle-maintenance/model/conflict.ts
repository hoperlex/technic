import { isApiError } from '@shared/api';

/**
 * Оптимистическая блокировка записи ТО глазами портала (план «Показания техники», Р30).
 *
 * Правка и удаление уходят с версией, которую видел правящий, и 409 значит ровно одно: пока окно
 * было открыто, запись изменил кто-то другой. Повторять своё не по чему — сначала нужно увидеть
 * чужое, поэтому за сообщением всегда идёт перечитка сводки и истории.
 *
 * Текст один на оба действия и живёт здесь, а не в каждом обработчике: «конфликт версий» из ответа
 * сервера человеку ничего не говорит, а два разных объяснения одного и того же отказа читались бы
 * как две разные поломки.
 */
export const VERSION_CONFLICT_MESSAGE =
  'Запись изменили в другом окне — обновите и откройте её заново';

export function isVersionConflict(e: unknown): boolean {
  return isApiError(e) && e.status === 409;
}
