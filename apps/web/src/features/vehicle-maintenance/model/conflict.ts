import { isApiError } from '@shared/api';
import { errorMessage } from '@shared/lib';

/**
 * Оптимистическая блокировка записи ТО глазами портала (план «Показания техники», Р30) и разбор
 * отказов складского расхода (план `docs/auto-parts-plan.md`, Р6, Р7, Р24).
 *
 * Правка и удаление уходят с версией, которую видел правящий, и 409 значил ровно одно: пока окно
 * было открыто, запись изменил кто-то другой. С выпуском автозапчастей это перестало быть правдой —
 * тем же кодом ответа приходят четыре доменных отказа, и путать их с версией нельзя: «обновите и
 * откройте заново» не поможет ни при нехватке остатка, ни при погашенной позиции, а окно закрылось
 * бы вместе с набранными строками.
 *
 * Поэтому отказы разведены по коду, а не по статусу:
 *
 *   — `version_conflict` — запись подвинули: сказать словами, перечитать сводку, закрыть окно;
 *   — `auto_part_shortage`, `auto_part_inactive` — про строку: окно остаётся открытым, человек
 *     правит количество прямо в нём;
 *   — `maintenance_voided`, `maintenance_has_stock_movements` — экран устарел: акт закрыт или у
 *     него появились движения, и журнал нужно перечитать, чтобы кнопки стали правдой.
 *
 * Текст один на все действия и живёт здесь, а не в каждом обработчике: два разных объяснения
 * одного и того же отказа читались бы как две разные поломки.
 */
export const VERSION_CONFLICT_MESSAGE =
  'Запись изменили в другом окне — обновите и откройте её заново';

/** 409, у которых причина доменная: версия здесь ни при чём, и «откройте заново» не поможет. */
const DOMAIN_CONFLICTS = new Set([
  'auto_part_shortage',
  'auto_part_inactive',
  'maintenance_voided',
  'maintenance_has_stock_movements',
]);

/**
 * Что делать дальше — то, чего сервер сказать не может: он отвечает про запись, а не про экран.
 * Про аннулирование и про движения он договаривает сам («аннулируют с причиной», «исправление
 * вводится новым актом»), и дописывать за ним второй совет значило бы спорить с ответом.
 */
const NEXT_STEP: Record<string, string> = {
  auto_part_shortage:
    'Уменьшите количество или сначала оприходуйте остаток на вкладке «Автозапчасти».',
  auto_part_inactive: 'Уменьшить количество по такой строке и снять её можно — увеличить нельзя.',
};

export function isVersionConflict(e: unknown): boolean {
  return isApiError(e) && e.status === 409 && !DOMAIN_CONFLICTS.has(e.code);
}

/**
 * Отказ, после которого показанный акт заведомо устарел: его аннулировали или по нему прошёл
 * расход. Кнопки строки собраны по признакам записи (`hasPartMovements`, `voidedAt`), и пока
 * журнал не перечитан, они обещают действие, которого уже нет.
 */
export function isStaleRecord(e: unknown): boolean {
  return (
    isApiError(e) &&
    (e.code === 'maintenance_voided' || e.code === 'maintenance_has_stock_movements')
  );
}

/** Сообщение отказа плюс следующий шаг, если сервер его не назвал. */
export function maintenanceErrorText(e: unknown): string {
  const step = isApiError(e) ? NEXT_STEP[e.code] : undefined;
  const text = errorMessage(e);
  return step ? `${text} ${step}` : text;
}
