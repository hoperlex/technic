import type { AutoPartDto } from '@technic/contracts';
import { apiFetch, createQueryKeys, type Query } from '@shared/api';

/**
 * Подбор автозапчасти в форме акта — временный клиент склада внутри сценария обслуживания
 * (план `docs/auto-parts-plan.md`, Р21).
 *
 * **Это заглушка, а не слайс.** Полный клиент склада (`entities/auto-part`) заводится вкладкой
 * «Автозапчасти» в гараже; здесь взято ровно две ручки, без которых форма акта не может ответить
 * на свои вопросы: «что подходит этой машине» и «сколько её осталось». Когда слайс появится,
 * этот модуль сносится, а `useAutoPartCards` начинает звать его — корень ключей выбран тем же
 * (`auto-part`), поэтому инвалидация склада из формы акта переживёт замену без правок.
 *
 * Две ручки, а не одна, потому что вопроса тоже два:
 *
 *   — **список** отвечает на подбор: сервер сортирует его рангом применимости (`vehicleId`), и
 *     досортировать пришедшую страницу на портале нельзя — подходящая деталь осталась бы на
 *     седьмой странице (Р21). Погашенные позиции в подбор не идут (Р24);
 *   — **карточка по идентификатору** отвечает про строку, которая в акте УЖЕ стоит. Её позиция
 *     бывает и погашенной, и далёкой от первой страницы подбора, а остаток и дата заведения нужны
 *     и ей: без остатка нечем показать «12 → 11», без даты заведения — предупредить о двойном
 *     списании (Р20).
 */

/** Сколько позиций тянет подбор: страница списка, дальше человек уточняет поиском. */
export const AUTO_PART_PICK_PAGE_SIZE = 50;

/**
 * Корень ключей склада. Именем сущности, а не сценария: остатки меняет и вкладка гаража, и форма
 * акта, и гасить их обе обязаны одним ключом — иначе после списания вкладка показывала бы старое
 * число до перезагрузки страницы (Р16).
 */
export const autoPartPickKeys = createQueryKeys('auto-part', {
  /** Подбор под машину: параметры целиком, включая поиск, — разные запросы кэшируются раздельно. */
  pick: (params: Query) => ['pick', params],
  /** Карточка позиции, уже стоящей строкой в акте. */
  card: (id: string) => ['card', id],
});

export const autoPartPickApi = {
  pick: (query: Query) => apiFetch<{ items: AutoPartDto[] }>('/auto-parts', { query }),
  card: (id: string) => apiFetch<AutoPartDto>(`/auto-parts/${id}`),
};
