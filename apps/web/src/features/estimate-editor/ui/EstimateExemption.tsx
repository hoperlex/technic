import { Checkbox, Input, Typography } from 'antd';

/**
 * ОСВОБОЖДЕНИЕ ОТ ПОДПИСИ: «Согласование не требуется» (Р1, Р3 плана
 * `docs/office-equipment-on-site-and-invoice-estimate-plan.md`).
 *
 * ЧЕКБОКС УТВЕРЖДАЕТ РОВНО ОДНО: под этой суммой подпись не собирают. Заявка остаётся «В работе»,
 * факт и гарантии закрываются обычным путём — это не заявление о выполнении и не закрытие работ.
 *
 * «ПО УСЛОВИЯМ ДОГОВОРА» ЗДЕСЬ НЕ ПИШЕТСЯ (ответ В12 заказчика от 11.09.2026). Политики в системе
 * нет, договор ей неизвестен, и обещание, которого она не проверяет, в подписи чекбокса было бы
 * ложью — человек прочитал бы его как «система сверила с договором».
 *
 * ПОЯСНЕНИЕ НЕОБЯЗАТЕЛЬНО и списком оснований не заменяется (ответ В4: «один пункт без выбора»):
 * перечня оснований не заводится вовсе, а сказать «мелкий ремонт на месте» исполнителю есть чем.
 *
 * КОМУ ЕГО ПОКАЗЫВАТЬ, РЕШАЕТ ПРЕДИКАТ КОНТРАКТОВ (`canDeclareExemption`), а не этот файл: здесь
 * только вид. Нарисованный шире чекбокс обещал бы денежное решение, за которым стоит 403.
 */
export function EstimateExemption({
  checked,
  note,
  applies,
  disabled = false,
  onChange,
  onNote,
}: {
  checked: boolean;
  note: string;
  /**
   * ОСВОБОЖДЕНИЕ ПРИМЕНЯЮТ ИЛИ ТОЛЬКО ЗАПИСЫВАЮТ — рубильник `service_estimate_exemption` (§7, шаг
   * 4). Не условие показа, а условие ТЕКСТА: ключ гасит исход, а не команду, и при выключенном
   * заявление всё равно проходит и ложится в след с исходом «наблюдение». Чекбокс от этого не
   * исчезает — исчезни он, служба не увидела бы до включения ни одного заявления, — но обещать
   * снятую подпись он в этом состоянии не вправе.
   */
  applies: boolean;
  /** Правка закрыта висящим предъявлением (Р9): заявление едет вместе с предъявлением, Р7. */
  disabled?: boolean;
  onChange: (next: boolean) => void;
  onNote: (next: string) => void;
}) {
  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: 8 }}>
      <Checkbox checked={checked} disabled={disabled} onChange={(e) => onChange(e.target.checked)}>
        Согласование не требуется
      </Checkbox>
      {/* Сказано до нажатия и своими словами: денежного барьера у этого решения нет вовсе (Р13) —
          ни лимита, ни проверки по договору, — а видно его потом в карточке, в письме офису и в
          споре «Ведения». Умолчи окно об этом, галочка читалась бы как формальность.

          ПРИ ВЫКЛЮЧЕННОМ РУБИЛЬНИКЕ ТЕКСТ ДРУГОЙ, И ЭТО ГЛАВНОЕ В НЁМ. Галочка в режиме наблюдения
          делает не то, что обещает её подпись: заявление записывается, а подпись всё равно
          собирают. Оставь окно прежние слова — исполнитель ушёл бы с экрана уверенным, что заявка
          принята, и узнал бы правду, лишь не дождавшись закрытия работ. */}
      <Typography.Text type={applies ? 'secondary' : 'warning'}>
        {applies
          ? 'Подпись «Ведения» под этой суммой собирать не будут: решение остаётся за сервисной компанией и видно в карточке заявки. Передумали — снимите галочку до предъявления: после него отменяет его уже не исполнитель.'
          : 'Освобождение сейчас выключено: заявление будет записано и видно службе, но подпись «Ведения» под этой суммой всё равно соберут — заявка уйдёт на согласование обычным порядком.'}
      </Typography.Text>
      {checked && (
        <Input.TextArea
          rows={2}
          maxLength={1000}
          disabled={disabled}
          value={note}
          placeholder="Пояснение, если нужно: например, мелкий ремонт сделан на месте при диагностике"
          aria-label="Пояснение к освобождению от подписи"
          onChange={(e) => onNote(e.target.value)}
        />
      )}
    </div>
  );
}
