import { useEffect, useState } from 'react';
import { App } from 'antd';
import { useMutation } from '@tanstack/react-query';
import {
  canDeclareExemption,
  hasFeature,
  type ServiceActionRequest,
  type ServiceEstimateExemptionDeclaration,
  type ServiceExecutorAssignment,
  type ServiceRequestDto,
} from '@technic/contracts';
import { errorMessage } from '@shared/lib';
import { filesApi } from '../../../api/resources';
import { useAuth } from '../../../auth/AuthContext';
import { fitsFreeMode, type EstimateRow } from './rows';

/** Страница приложенного счёта: идентификатор для тела запроса, имя — для списка на экране. */
export interface EstimateDocumentFile {
  id: string;
  name: string;
}

/**
 * ЧЕМ ПРЕДЪЯВЛЯЮТ ОБЪЁМ РАБОТ И НА КАКИХ УСЛОВИЯХ (план
 * `docs/office-equipment-on-site-and-invoice-estimate-plan.md`, Р2, Р3, Р10): способ подачи —
 * строками или приложенным счётом — и заявление об освобождении от подписи.
 *
 * ОТДЕЛЬНО ОТ `useEstimateEditor`, ХОТЯ УЕЗЖАЕТ ОДНОЙ КОМАНДОЙ. Тот хук про СОСТАВ: строки, режим
 * их набора, версия и три пути отправки. Здесь же ни одной строки не рождается — здесь решают, чем
 * ревизия будет вообще (у документной строк нет вовсе) и собирают ли под ней подпись. Вместе они
 * перерастали бюджет длины файла, а главное — читались как одна тема, каковой не являются.
 *
 * РУБИЛЬНИКА ДВА, И ДЕЙСТВУЮТ ОНИ ПО-РАЗНОМУ (§7, шаги 3 и 4; реестр ключей в контрактах).
 * `service_estimate_document_mode` гасит КОМАНДУ: до включения ручка предъявления отвечает на
 * документное тело 422, поэтому выключенный ключ означает отсутствие способа, а не погашенный
 * способ — кнопка, ведущая в 422, хуже отсутствующей. `service_estimate_exemption` гасит ИСХОД:
 * заявление проходит всегда, и при выключенном ключе оно записывается следом как `observed`, а
 * подпись собирается обычным путём. Отсюда и разное место двух ключей в этом хуке: первый стоит в
 * условии ПОКАЗА способа подачи, второй — только в ТЕКСТЕ рядом с чекбоксом.
 */
export function useEstimatePresentation({
  request,
  rows,
  breakdown,
  actionRow,
  assignment,
}: {
  request: ServiceRequestDto | null;
  /** Набранное прямо сейчас: по нему решается, не потеряется ли состав под галочкой (Р10). */
  rows: readonly EstimateRow[];
  /** Раскладка «Ведения»: ни подачи счётом, ни освобождения у неё не бывает вовсе. */
  breakdown: boolean;
  /**
   * Карточка глазами предикатов контрактов и признаки назначения на неё — ПЕРЕВОД ДЕЛАЕТ
   * ВЫЗЫВАЮЩИЙ, а не окно (Р3). Перевод в этом портале ровно один (`serviceActionRow`,
   * `serviceExecutorAssignment` на слое разделов), второй разошёлся бы с ним молча, а достать тот
   * сюда нельзя — слой сценариев разделов не видит. Не передали — чекбокса освобождения нет:
   * показанный не тому, он обещал бы денежное решение, за которым стоит 403.
   */
  actionRow?: ServiceActionRequest;
  assignment?: ServiceExecutorAssignment;
}) {
  const { message } = App.useApp();
  const { user } = useAuth();
  /*
   * ТРЕТИЙ СПОСОБ ПОДАЧИ — СВОЁ СОСТОЯНИЕ, А НЕ ТРЕТИЙ ПУНКТ ПЕРЕКЛЮЧАТЕЛЯ (Р2, Р10).
   * Переключатель выбирает, КАК НАБИРАЮТ строки, и оба его пункта дают один и тот же результат —
   * строки с суммой. Здесь же не набирают вовсе: ревизия состоит из счёта, строк у неё нет, сумма
   * неизвестна до разбора документа. Третьим пунктом того же ряда окно обещало бы трём разным
   * вещам одинаковую природу.
   */
  const [documentMode, setDocumentMode] = useState(false);
  /*
   * Загруженные страницы — идентификаторы, уже принятые хранилищем: сервер принимает основанием
   * только ДОГРУЖЕННЫЙ файл (`requireActive`, Р7), поэтому загрузка идёт до предъявления, а не
   * вместе с ним. Имя держится рядом ради списка: по идентификатору человек не отличит свой счёт
   * от чужого.
   */
  const [files, setFiles] = useState<EstimateDocumentFile[]>([]);
  const [exemption, setExemption] = useState(false);
  const [exemptionNote, setExemptionNote] = useState('');

  useEffect(() => {
    /*
     * Способ подачи, счёт и заявление сбрасываются при смене заявки — тем же порядком, что состав.
     * Окно переоткрывают по другой заявке тем же экземпляром хука (`request` — проп, а не монтаж),
     * и уцелевшая галочка «согласование не требуется» стала бы денежным решением, которого по этой
     * заявке никто не принимал, а чужой счёт — её основанием.
     */
    setDocumentMode(false);
    setFiles([]);
    setExemption(false);
    setExemptionNote('');
  }, [request]);

  /**
   * ЗАГРУЗКА СТРАНИЦЫ СЧЁТА — ОТДЕЛЬНЫМ ХОДОМ И ДО ПРЕДЪЯВЛЕНИЯ (Р7). Связь с заявкой ставит сама
   * команда предъявления одной транзакцией с ревизией: подшить страницу заранее нельзя — до
   * ревизии ей не на что сослаться.
   *
   * Загруженный, но не предъявленный файл остаётся в хранилище ничьим, и это дешевле обратного:
   * предъявление, собранное из полузагруженных страниц, отвечало бы 422 в конце длинной формы.
   */
  const uploadMutation = useMutation({
    mutationFn: (file: File) => filesApi.upload(file),
    onSuccess: (stored) => setFiles((prev) => [...prev, { id: stored.id, name: stored.filename }]),
    onError: (e) => message.error(errorMessage(e)),
  });

  const documentOffered = !breakdown && hasFeature(user, 'service_estimate_document_mode');
  /*
   * НАБРАННОЕ НЕ ТЕРЯЕТСЯ (Р10). Счёт подают ВМЕСТО состава — у документной ревизии строк нет
   * вовсе, — и спрятать под галочкой больше одной строки значило бы унести набранное молча.
   * Предикат тот же, что у свободной записи, и намеренно: он и отвечает на вопрос «помещается ли
   * набранное в одну запись», а два похожих ответа на один вопрос разошлись бы.
   */
  const documentFits = fitsFreeMode(rows);
  const documentOn = documentOffered && documentMode;
  /*
   * ПОКАЗ ЧЕКБОКСА ОСВОБОЖДЕНИЯ СЧИТАЕТ ПРЕДИКАТ КОНТРАКТОВ, И ДРУГОГО УСЛОВИЯ У НЕГО НЕТ (Р3):
   * `canDeclareExemption` — то же самое правило, которым сервер отвечает 403, и собранная порталом
   * своя копия разошлась бы с ним молча.
   *
   * РУБИЛЬНИКА В ЭТОМ УСЛОВИИ НЕТ, И ЭТО НЕ ЗАБЫВЧИВОСТЬ, А ВЕСЬ РЕЖИМ НАБЛЮДЕНИЯ (§7, реестр
   * ключей). `service_estimate_exemption` не похож на соседей по реестру: он ГАСИТ ИСХОД, А НЕ
   * КОМАНДУ — при выключенном ключе заявление проходит, записывается следом с исходом `observed`, а
   * подпись собирается обычным путём. Спрячь портал чекбокс, служба не увидела бы до самого
   * включения ни одного заявления и ни одной суммы — то есть лишилась бы единственного способа
   * узнать, во что обойдётся включение.
   *
   * Сравните с соседним `service_estimate_document_mode`: тот гасит именно КОМАНДУ (сервер отвечает
   * на документное тело 422), и его место — в условии показа способа подачи, где он и стоит.
   * Кнопка, ведущая в отказ, хуже отсутствующей; чекбокс, ведущий в записанное заявление, — нет.
   */
  const exemptionOffered =
    !breakdown &&
    actionRow !== undefined &&
    assignment !== undefined &&
    canDeclareExemption(actionRow, user, assignment);
  /*
   * ЧТО ВЫЙДЕТ ИЗ ЗАЯВЛЕНИЯ — отдельным признаком от «кому дано заявить», ровно как в контрактах
   * (`canDeclareExemption` против `evaluateExemption`). Нужен он не для показа, а для ТЕКСТА рядом:
   * при выключенном ключе галочка означает другое, и умолчи о том окно — исполнитель считал бы
   * заявку принятой, пока по ней ждут подпись.
   *
   * ВХОДОВ У ИСХОДА ДВА, И ВТОРОЙ — ПАМЯТЬ РАЗРЕШЁННОГО СПОРА (Р9). Рубильник отвечает «освобождение
   * вообще применяют», но по заявке, спор о которой разрешён исходом «нужна подпись», сервер даёт
   * `observed` при любом ключе: требование подписи переживает возврат в правку, иначе подрядчик
   * снимал бы решение «Ведения» повторным предъявлением того же счёта (находка проверяющего волны).
   *
   * Поэтому окно спрашивает оба входа. Умолчи оно о втором — исполнитель прочёл бы «подпись собирать
   * не будут» там, где её как раз и соберут, и узнал бы об этом, только не дождавшись закрытия.
   */
  const signatureRequiredByDispute =
    request?.dispute?.state === 'resolved' && request.dispute.outcome === 'require_signature';
  const exemptionApplies =
    hasFeature(user, 'service_estimate_exemption') && !signatureRequiredByDispute;
  const exemptionOn = exemptionOffered && exemption;

  return {
    documentOffered,
    documentOn,
    documentFits,
    files,
    uploading: uploadMutation.isPending,
    exemptionOffered,
    exemptionApplies,
    exemption: exemptionOn,
    exemptionNote,
    setExemptionNote,
    /*
     * Чего не хватает документной подаче — ровно одного: самого документа. Ни суммы, ни описания,
     * ни реквизитов счёта у неё не спрашивают вовсе (ответы В5 и В13), и спросить их здесь значило
     * бы придумать требование, которого нет ни в схеме, ни на сервере.
     */
    documentIssue:
      files.length === 0
        ? 'Приложите счёт: документная подача без документа — пустая ревизия'
        : null,
    /**
     * ЗАЯВЛЕНИЕ, А НЕ ИСХОД (Р3): в теле едет одно необязательное пояснение, а применено оно или
     * лишь замечено, решает сервер рубильником. Пустое пояснение не отправляется вовсе — пустая
     * строка в поле «почему» читалась бы как сказанное, а не как несказанное.
     */
    exemptionBody: (): ServiceEstimateExemptionDeclaration | undefined => {
      if (!exemptionOn) return undefined;
      const note = exemptionNote.trim();
      return note ? { note } : {};
    },
    /*
     * Заявление снимается вместе с пояснением: оставленный текст при следующей постановке галочки
     * уехал бы объяснением решения, которого человек в этот раз не объяснял.
     */
    setExemption: (next: boolean) => {
      setExemption(next);
      if (!next) setExemptionNote('');
    },
    /*
     * Переключение способа подачи (Р10). Ни строк, ни файлов оно не трогает: набранное ждёт снятия
     * галочки на месте, а уже загруженный счёт — её возврата. Скрытие потому и безопасно, что
     * состояние остаётся целым; гасить эти поля было бы вторым погашенным режимом рядом с
     * настоящим — замком висящего предъявления, который означает совсем другое.
     */
    switchDocumentMode: (next: boolean) => setDocumentMode(next),
    addFile: (file: File) => uploadMutation.mutate(file),
    /*
     * Снять страницу МОЖНО ТОЛЬКО ДО ПРЕДЪЯВЛЕНИЯ, и это единственное место, где такая кнопка
     * вообще бывает: после предъявления файл становится основанием ревизии и не снимается никогда
     * (Р6). Здесь же ошибка выбора обязана иметь выход — иначе человек, приложивший чужой счёт,
     * закрыл бы окно и начал заново.
     */
    removeFile: (id: string) => setFiles((prev) => prev.filter((file) => file.id !== id)),
  };
}
