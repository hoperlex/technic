import type {
  ServiceEstimateItemInput,
  ServiceItemKind,
  ServiceRequestItemDto,
} from '@technic/contracts';

/**
 * Строка объёма работ в редакторе. Своя от DTO: у набираемой строки ещё нет идентификатора (состав
 * уходит на сервер целиком и пересоздаётся), зато нужен ключ для React, а количество и цена
 * живут «наполовину введёнными» — поле `InputNumber` отдаёт `null`, пока в нём пусто, и
 * подменять это нулём нельзя: «0» и «не введено» отличаются как раз тем, что второе — ошибка.
 */
export interface EstimateRow {
  key: string;
  kind: ServiceItemKind;
  name: string;
  quantity: number | null;
  unitPrice: number | null;
  /** Обещанный срок гарантии в месяцах; дату от него считает сервер при закрытии работ. */
  warrantyMonths: number | null;
}

let sequence = 0;

export function newEstimateRow(kind: ServiceItemKind): EstimateRow {
  sequence += 1;
  return {
    key: `row-${sequence}`,
    kind,
    name: '',
    // Количество почти всегда единица, цена — нет: подставленный ноль читался бы как «бесплатно».
    quantity: 1,
    unitPrice: null,
    warrantyMonths: null,
  };
}

/**
 * Как набирается объём работ в окне (план
 * `docs/office-equipment-free-estimate-and-executor-scope-plan.md`, Р1 и Р8; ответ В1 заказчика от
 * 09.09.2026).
 *
 * ЭТО РЕЖИМ ВВОДА, А НЕ ВТОРОЙ ВИД ДОКУМЕНТА. В базу оба режима уходят одинаковыми строками:
 * свободная запись — обычная строка `kind = service`, `quantity = 1`, `unitPrice` = общая
 * стоимость. Признака формата в БД нет и не заводится: разложенная «Ведением» смета оставила бы
 * его ложью, а его чтение стало бы шестым местом, где объём работ описан дважды (Р8).
 *
 * ЗАЧЕМ СВОБОДНЫЙ РЕЖИМ ВООБЩЕ. Подрядчик присылает объём работ письмом — перечнем позиций с
 * количествами и одной общей суммой, цены по позициям не разложены вовсе. Набирая такое письмо по
 * графам, исполнитель придумывал бы цены, которых ему не называли; свободная запись переносит
 * письмо как есть, а разложить его по графам потом вправе «Ведение» (Р2).
 */
export type EstimateMode = 'free' | 'rows';

/** Строки уже заведённого объёма работ: черновик ревизии, которую исполнитель дописывает. */
export function rowsFromItems(items: readonly ServiceRequestItemDto[]): EstimateRow[] {
  return items.map((item) => {
    sequence += 1;
    return {
      key: `item-${item.id}-${sequence}`,
      kind: item.kind,
      name: item.name,
      quantity: item.quantity,
      unitPrice: item.unitPrice,
      warrantyMonths: item.warrantyMonths,
    };
  });
}

/**
 * Помещается ли набранное в свободную запись — то есть можно ли **сейчас** показать эту смету
 * двумя полями, ничего не потеряв (Р8).
 *
 * КОНВЕРТАЦИЯ ОДНОСТОРОННЯЯ, и этот предикат — вся её вторая половина. Свободная запись
 * разворачивается в графы всегда: описание становится наименованием, стоимость — ценой, и терять
 * при этом нечего. Обратно — только когда терять действительно нечего: строк не больше одной, а
 * единственная не несёт ни вида «Запчасть», ни срока гарантии, ни количества, отличного от
 * единицы. Склейки наименований не бывает вовсе — две строки в одну свободную запись не
 * сворачиваются ни при каком совпадении цен: их сумма и виды исчезли бы молча.
 *
 * ПУСТОЙ СПИСОК ПОДХОДИТ, и это не поблажка: у сметы, которую ещё не начинали, терять нечего
 * вовсе, а начинают её чаще всего письмом подрядчика — тем самым перечнем, ради которого режим и
 * заведён.
 *
 * НЕЗАПОЛНЕННОЕ КОЛИЧЕСТВО (`null`) СЧИТАЕТСЯ ЕДИНИЦЕЙ намеренно: поле `InputNumber` отдаёт `null`,
 * пока в нём пусто, а на сервер такая строка всё равно уходит с единицей (`rowsToPayload`).
 * Ответь предикат «не подходит», человек не смог бы вернуться в свободный режим из-за поля,
 * которое сам же и очистил.
 */
export function fitsFreeMode(rows: readonly EstimateRow[]): boolean {
  if (rows.length === 0) return true;
  if (rows.length > 1) return false;
  const row = rows[0]!;
  return (
    row.kind === 'service' &&
    (row.quantity ?? 1) === 1 &&
    row.warrantyMonths == null &&
    // Сохранённый НОЛЬ свободному режиму не подходит (ответ В10, разбор тестовой волны Д1): в
    // двух полях он читался бы как «работы бесплатны», а стоимость в этом режиме обязательна и
    // положительна — окно открылось бы двумя полями и тут же потребовало бы их поправить, не дав
    // ни увидеть, откуда ноль взялся, ни убрать саму строку (кнопки удаления у свободного режима
    // нет вовсе). Такая строка бывает законной — служебная строка гарантийного ремонта, — и по
    // графам она и читается: цена видна колонкой, а строку можно снять.
    //
    // Пустая цена (`null`) при этом подходит: это «ещё не ввели», состояние НАБОРА, а не сметы, и
    // запрет вернул бы человека в графы из-за поля, которое он сам же и очистил.
    (row.unitPrice == null || row.unitPrice > 0)
  );
}

/**
 * В каком режиме открывать окно (Р8): в свободном — только если набранное в него помещается.
 *
 * Своей отметки формата у сметы нет, поэтому режим угадывается по составу, и угадывание это
 * намеренно осторожное: ошибись оно в другую сторону — окно открылось бы двумя полями на смете из
 * пяти строк, и первое же сохранение стёрло бы четыре из них.
 */
export function initialEstimateMode(rows: readonly EstimateRow[]): EstimateMode {
  return fitsFreeMode(rows) ? 'free' : 'rows';
}

/**
 * Строки в том виде, в каком их держит свободный режим: ровно одна услуга количеством один без
 * гарантии.
 *
 * Приведение делается ПРИ ПЕРЕКЛЮЧЕНИИ, а не при отправке, и это важнее, чем кажется: итог окна
 * считается по строкам (`rowsTotal`), и строка с очищенным количеством показывала бы «0,00 ₽» под
 * заполненной стоимостью. Человек читает сумму до нажатия — она и есть предмет согласования.
 *
 * Строк больше одной сюда не приходит: переключатель в этом случае недоступен (`fitsFreeMode`), —
 * но первая всё равно берётся явно, чтобы функция была верна сама по себе, а не по договорённости
 * с вызывающим.
 */
export function toFreeRows(rows: readonly EstimateRow[]): EstimateRow[] {
  const row = rows[0] ?? newEstimateRow('service');
  return [{ ...row, kind: 'service', quantity: 1, warrantyMonths: null }];
}

/**
 * Что из набранного действительно уйдёт на сервер.
 *
 * Свободный режим держит свою строку всегда — иначе двум полям не на чём было бы стоять, — и
 * нетронутая она означает «объём работ ещё не набирали», а не строку сметы. Без этого отсева
 * «Сохранить черновик» в только что открытом окне отправлял бы строку с пустым наименованием, и
 * сервер отвечал бы 400 на действие, которое до этой волны законно сохраняло пустой черновик.
 *
 * Режим «по графам» не трогается: там пустая строка появляется только по нажатию «Добавить», то
 * есть по прямой просьбе человека, и молча выбрасывать её значило бы решать за него.
 */
export function rowsForSave(rows: readonly EstimateRow[], mode: EstimateMode): EstimateRow[] {
  if (mode !== 'free') return [...rows];
  return rows.filter((row) => row.name.trim().length > 0 || row.unitPrice != null);
}

/** Сумма строки: количество × цена. Считается на глазах — итог виден до предъявления. */
export function rowAmount(row: EstimateRow): number {
  return (row.quantity ?? 0) * (row.unitPrice ?? 0);
}

export function rowsTotal(rows: readonly EstimateRow[]): number {
  return rows.reduce((sum, row) => sum + rowAmount(row), 0);
}

/**
 * Тело `PUT /estimate`: состав целиком — объём работ документ, и по строке его не правят.
 *
 * ПОДСТАНОВКА `?? 0` ОСТАЁТСЯ ТОЛЬКО ДЛЯ ЧЕРНОВИКА ПО ГРАФАМ, и это единственное место, где она
 * законна: там пустая цена стоит видимой колонкой у конкретной строки, и сохранённый ноль человек
 * прочтёт ровно там же, где оставил пропуск. В свободном режиме до неё больше не доходит —
 * `estimateDraftIssue` не даёт сохранить начатую запись без стоимости (дефект Д1), — потому что
 * там подставленный ноль стал бы невидимым: полей два, и оба на вид заполнены.
 */
export function rowsToPayload(rows: readonly EstimateRow[]): ServiceEstimateItemInput[] {
  return rows.map((row) => ({
    kind: row.kind,
    name: row.name.trim(),
    quantity: row.quantity ?? 1,
    unitPrice: row.unitPrice ?? 0,
    warrantyMonths: row.warrantyMonths,
  }));
}

/**
 * Изменился ли состав по сравнению с тем, что лежит на сервере. Не косметика: неизменённый состав
 * не нужно перезаписывать перед предъявлением — лишний `PUT` поднял бы версию заявки и отобрал
 * бы её у того, кто в этот момент смотрит карточку.
 */
export function rowsChanged(
  rows: readonly EstimateRow[],
  items: readonly ServiceRequestItemDto[],
): boolean {
  if (rows.length !== items.length) return true;
  return rows.some((row, i) => {
    const item = items[i]!;
    return (
      row.kind !== item.kind ||
      row.name.trim() !== item.name ||
      (row.quantity ?? 0) !== item.quantity ||
      (row.unitPrice ?? 0) !== item.unitPrice ||
      (row.warrantyMonths ?? null) !== item.warrantyMonths
    );
  });
}
