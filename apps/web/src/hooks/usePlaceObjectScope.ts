import { placeObjectScopeIds } from '@technic/contracts';
import { useAuth } from '../auth/AuthContext';

/**
 * **Площадочная** область учётки (ADR 0062): у объектной роли — свои объекты, у роли отдела —
 * площадки её отделов (с ADR 0144 их бывает несколько). Устроена как `useObjectScope` и отвечает
 * на те же три вопроса: чем сузить список объектов, чем заполнить поле и когда его запереть — и
 * ветки «объектов несколько» ей не добавлялось: набор она принимала с самого начала, потому что у
 * объектной роли объектов всегда бывало много.
 *
 * Имя называет ось, а не модуль: по ней ходят вывоз мусора, механизация и — с ADR 0201 — заказ
 * спецтехники, то есть всё, где заказчиком стоит объект. Второй такой хук на модуль означал бы
 * второе описание одной области; правило живёт в контрактах (`placeObjectScopeIds`), здесь только
 * ответы формы.
 *
 * Отдельным хуком, а не веткой внутри `useObjectScope`: тот отвечает за **прямую** привязку
 * объектной роли и спрашивается там, где у роли отдела заказчиком стоит её отдел, — в заказе
 * грузоперевозки. Подмешать производные объекты туда значило бы подставить в фильтр списка объект
 * рядом с отделом, а заявки с двумя заказчиками не бывает: список вышел бы заведомо пустым.
 *
 * Портал сужает выбор, но не решает доступ: чужой объект сервер всё равно отдаёт как 403
 * (`assertPlaceObjectScope`, `assertRequestScope`), а список — как пустую выборку
 * (`placeObjectVisibilityWhere`, `vehicleRequestVisibilityWhere`).
 */
export function usePlaceObjectScope() {
  const { user } = useAuth();
  const scopeIds = placeObjectScopeIds(user);
  /** `null` — «областью не ограничен»: диспетчер, менеджер, наблюдатель, администратор. */
  const isScoped = scopeIds !== null;
  const ownObjectIds = scopeIds ?? [];

  return {
    isScoped,
    ownObjectIds,
    /**
     * Единственный объект области: им заполняются фильтр списка и поле формы. `null`, когда
     * объектов несколько — тогда выбирает человек, и подставленный за него первый попавшийся
     * завёл бы заявку не на ту площадку.
     */
    soleObjectId: ownObjectIds.length === 1 ? ownObjectIds[0]! : null,
    /** Поле объекта заперто, когда выбирать не из чего: в области ровно один объект. */
    objectFieldDisabled: isScoped && ownObjectIds.length <= 1,
    /** Оставляет в списке только свои объекты: чужие этой учётке и выбирать незачем. */
    limitObjectOptions<T extends { value: string }>(options: T[]): T[] {
      return isScoped ? options.filter((o) => ownObjectIds.includes(o.value)) : options;
    },
  };
}
