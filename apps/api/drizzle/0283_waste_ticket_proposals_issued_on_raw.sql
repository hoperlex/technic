-- Предложение перераспознавания везёт написание даты вместе с самой датой (план
-- `docs/waste-ticket-date-escalation-plan.md`, Р12; ADR 0166, п. 7; Р13 ADR 0114).
--
-- ОТКУДА НОМЕР. `ls apps/api/drizzle` перед созданием файла (07.09.2026): последними в дереве
-- стояли `0281_releases_fix_quick_status_version.sql` и `0282_releases_waste_ticket_date_year.sql`.
-- Номер живёт часы — за время этой волны параллельный поток занимал его дважды, — поэтому он
-- берётся по файлам дерева, а не по журналу базы и не по `max(seq)` из technic_dev, где часть
-- закоммиченных миграций просто не накатана.
--
-- ЗАЧЕМ. Миграция 0280 завела `waste_tickets.issued_on_raw`, и портал показывает его подписью
-- «OCR в графе: 17.08.25». Но перераспознавание ТРОНУТОГО талона в саму строку не пишет (Р13
-- ADR 0114): новое чтение ложится рядом предложением, а предложение о написании не знало вовсе.
-- Тогда принятие предложения меняло дату талона и оставляло подпись от ПРОШЛОГО прохода — то есть
-- подпись начинала объяснять не ту дату, что стоит в талоне. Дата и её написание — одна пара, и
-- ехать через предложение они обязаны вместе.
--
-- ПОЧЕМУ `NOT NULL DEFAULT ''` И БЕЗ БЭКФИЛА. Ровно по той же причине, что и в 0280: пустая строка
-- означает «написания нет» — предложения, заведённые прошлыми разборами, о графе не спрашивали, а
-- `NULL` рядом с `''` завёл бы третье состояние, которое ни маршруту, ни интерфейсу нечем отличить
-- от второго. Заполнить задним числом нечем: снимок предложения на этот вопрос не отвечает, а
-- сырьё попытки убирается по сроку (`TICKET_OCR_ATTEMPT_TTL_DAYS`) — и живёт непринятое
-- предложение как раз дольше него.
--
-- Порядок выката прежний: миграция идёт ДО воркера, который начнёт писать колонку. Старый воркер
-- её не знает и заводит предложения без неё, старый API — не читает; откат совместим.
ALTER TABLE waste_ticket_proposals
  ADD COLUMN IF NOT EXISTS issued_on_raw text NOT NULL DEFAULT '';
