-- Снимок режима заказа, застигнутого переключением признака «Линейная техника» у типа ТС.
-- План — `docs/vehicle-type-linear-switch-hotfix-plan.md`, решение Р1; ADR — «Переключение
-- признака линейности под работающими заказами».
--
-- Зачем. Признак `vehicle_types.is_linear` (миграция 0127) читается живым join'ом заказанного
-- типа: снимка в заявке нет намеренно (ADR 0100 §1) — справочник и есть то место, где на вопрос
-- «днями или неделями» отвечают. Платой за живое чтение был запрет переключать признак, пока у
-- типа есть заявки в работе: галочка в справочнике сменила бы режим документооборота каждой
-- работающей заявке мгновенно и молча — недельный ЭСМ-2 перестал бы выписываться сам, занятость
-- машины съехала бы с целого срока на отдельные дни, а распланированные дни повисли бы без смысла.
--
-- Запрет оказался недостижим ровно для той техники, ради которой признак и заводился: автовышки,
-- катки и поливомоечные работают сплошным потоком, и окна, в котором у типа не будет ни одного
-- действующего заказа, не предвидится. Поэтому переключение разрешается, а заявки, застигнутые им
-- в работе, дорабатывают по записанному здесь значению.
--
-- Колонок две, а не одна. `is_linear_frozen` отвечает «как именно ведётся эта заявка» —
-- направления два, и «прежний режим» без уточнения читателю ничего не говорит; `linear_frozen_at`
-- отвечает «с какого числа», и без него метка в карточке не объясняет, почему две заявки одного
-- типа ведут себя по-разному. Обе пишутся одним UPDATE в транзакции переключения: след атомарен и
-- не зависит от журнала действий, запись которого best-effort.
--
-- NULL в обеих — норма и умолчание: признак читается живым из справочника, как и до хотфикса.
-- Поэтому миграция аддитивна и безопасна раньше кода: до выката новой версии колонки пусты, а
-- `coalesce(is_linear_frozen, is_linear)` старому коду и не нужен.
--
-- Условие смерти. Колонки временные и уходят, когда закроется последняя застигнутая заявка:
--   SELECT count(*) FROM vehicle_requests WHERE is_linear_frozen IS NOT NULL;
-- Ноль означает, что снимать больше нечего. Уборка идёт четырьмя релизами (§9 плана): возврат
-- запрета → устойчивый ноль → снятие чтения → DROP. Сокращать нельзя: deploy накатывает миграции
-- до перезапуска, и релиз, разом вернувший запрет и переставший читать колонки, проглотил бы
-- молча заявку, замороженную старым кодом в последние минуты перед рестартом.

ALTER TABLE vehicle_requests
  ADD COLUMN is_linear_frozen boolean,
  ADD COLUMN linear_frozen_at timestamptz;

COMMENT ON COLUMN vehicle_requests.is_linear_frozen IS
  'Временный снимок признака линейности заказанного типа. NULL — норма: признак читается живым из справочника (ADR 0100 §1). Заполнено — заявку застало переключение признака у типа, и она дорабатывает по записанному значению. Снимается уходом из «В работе». Колонки удаляются релизом, следующим за обнулением: SELECT count(*) FROM vehicle_requests WHERE is_linear_frozen IS NOT NULL;';

COMMENT ON COLUMN vehicle_requests.linear_frozen_at IS
  'Когда заявку застигло переключение признака — этим числом метка в карточке объясняет, почему две заявки одного типа ведутся по-разному. Живёт и умирает вместе с is_linear_frozen.';

-- Пара честна или пуста целиком: половина снимка не отвечает ни на один из двух вопросов, ради
-- которых он заводился, а метка по такой строке напечатала бы «прежний режим, с —».
ALTER TABLE vehicle_requests
  ADD CONSTRAINT vehicle_requests_linear_frozen_check
  CHECK ((is_linear_frozen IS NULL) = (linear_frozen_at IS NULL));

-- Индекс частичный и обслуживает ровно два вопроса: «сколько заморожено у этого типа» (карточка
-- типа и предпросмотр переключения) и «пуста ли колонка» (критерий уборки). На горячих путях он не
-- нужен — эффективный признак читается по первичному ключу заявки, — и уходит вместе с колонками.
CREATE INDEX vehicle_requests_linear_frozen_idx
  ON vehicle_requests (vehicle_type_id)
  WHERE is_linear_frozen IS NOT NULL;
