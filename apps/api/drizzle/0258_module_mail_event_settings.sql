-- Рубильник события почты модуля «Орг.техника»
-- (план `docs/office-equipment-mail-expansion-plan.md`, §5.1, решение Р2; этап Э1).
--
-- Таблица `module_mail_recipients` (миграция 0141) отвечает на вопрос «кому уходит копия письма».
-- Здесь другой вопрос — «уходит ли письмо по событию вообще», и он эксплуатационный, а не
-- продуктовый: включённость события меняет администратор, а не выкат.
--
-- **Четыре новых события заводятся выключенными, и это не осторожность ради осторожности.** Раздел
-- «Орг.техника» в портале ещё закрыт временной заплаткой (`temporarySectionLock.ts`), а API открыт
-- и работает: события начали бы ставить письма раньше, чем люди увидят модуль, — и письма эти
-- уходят **наружу**, сервисной компании, у которой портала нет вовсе. Первым, кто узнал бы о
-- недоделанной аудитории, оказался бы подрядчик. Плюс два довода поменьше: события включают по
-- одному и смотрят, что приходит (этап Э8), а зашумевшее событие гасят рубильником, не откатывая
-- релиз.
--
-- Три существующих события заводятся включёнными: поведение портала эта миграция не меняет ничем.
--
-- CHECK по перечню событий здесь ставится — в отличие от адресатов, где он намеренно не ставился
-- (0141). Разница не в строгости, а в цене опечатки. Лишняя строка адресата просто никогда не
-- выстрелит; лишняя строка рубильника выглядит настройкой («событие включено»), пока настоящее
-- событие сидит без строки и молчит: отсутствие строки трактуется fail-closed, как выключенность.
-- Дешевле реестр здесь и так не станет — новое событие приходит со своей строкой, то есть с
-- миграцией. Перечень обязан совпадать с `MODULE_MAIL_EVENTS` в контрактах.
--
-- Аддитивная миграция: существующих данных не касается, протокол выката необратимых миграций
-- (`docs/schema-cutover-protocol.md`) к ней не применяется. Откат — удаление таблицы; код прошлого
-- выпуска о ней не знает.

CREATE TABLE module_mail_event_settings (
  -- Ключ строки — само событие: рубильник у события ровно один, второму взяться неоткуда.
  event text PRIMARY KEY,
  -- Умолчание выключенное: событие, добравшееся до продакшена без своей строки в миграции, обязано
  -- молчать, а не начать писать наружу.
  is_enabled boolean NOT NULL DEFAULT false,
  updated_by uuid REFERENCES users (id) ON DELETE SET NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  -- Одновременная правка двумя администраторами не должна тихо победить: проигравший узнал бы о
  -- своём щелчке по письмам, которых не ждал.
  version integer NOT NULL DEFAULT 0
);

ALTER TABLE module_mail_event_settings ADD CONSTRAINT module_mail_event_settings_event_check
  CHECK (event IN (
    'service_request_waiting_it',
    'service_request_cancelled',
    'service_request_assigned',
    'service_request_status_changed',
    'service_request_estimate',
    'service_request_document',
    'service_request_comment'
  ));

-- Строка на каждое событие реестра: пустая таблица означала бы молчание всех семи, включая три
-- работающих сегодня.
INSERT INTO module_mail_event_settings (event, is_enabled) VALUES
  ('service_request_waiting_it', true),
  ('service_request_cancelled', true),
  ('service_request_assigned', true),
  ('service_request_status_changed', false),
  ('service_request_estimate', false),
  ('service_request_document', false),
  ('service_request_comment', false);
