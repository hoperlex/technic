-- Письмо о смене адреса учётной записи (план `docs/user-email-change-plan.md`, ADR 0092).
--
-- Вид один на оба письма — на новый адрес и на прежний. Разделять их на два значения `mail_kind`
-- незачем: событие одно, и в журнале писем его ищут именно как событие; кому какое письмо ушло,
-- видно по `to_email`, а различает их `dedupe_key` (`…:new` и `…:old`).
--
-- Значение добавляется отдельной миграцией и в той же транзакции кодом не используется: раннер
-- применяет файл миграции целиком в одной транзакции (`apps/api/src/db/migration-journal.ts:94`),
-- а PostgreSQL не разрешает пользоваться новым значением enum до её фиксации. Тот же приём — в
-- миграциях 0114, 0103, 0065, 0054.
--
-- Аддитивная миграция: смысл существующих данных не меняется, протокол выката необратимых
-- миграций (`docs/schema-cutover-protocol.md`) к ней не применяется.
ALTER TYPE mail_kind ADD VALUE IF NOT EXISTS 'email_changed';
