-- Перемещение спецтехники: рейс на доставку техники на объект и на вывоз с него.
--
-- Экскаватор-погрузчик едет на площадку по городу своим ходом — это рейс, и на него выписывается
-- 4-П. Заезд и выезд с объекта — два разных дня и два документа. Ехать техника может и тралом:
-- тогда листа не выписывают вовсе, и портал об этом не спрашивает — способ доставки он не ведёт.
--
-- Почему рейс, а не «лист прямо с заявки»: лист живёт только при рейсе (0074 сделала
-- waybills.route_id NOT NULL), и второй схемы рождения документа строгой отчётности заводить
-- нельзя — журнал, аннулирование и печать держатся на одной.
--
-- Почему заявка ссылкой, а не составом рейса: vehicle_route_requests держит
-- UNIQUE (request_id) — «заявка ровно в одном рейсе», — а у доставки и вывоза рейсов два.
-- Талонов заказчиков у перегона и не бывает: заказчик один, и второй строки в задании не будет.

-- 1. Зачем этот рейс.
--
-- 'freight' — сегодняшние маршруты грузоперевозки: состав из заявок, талоны, бланк по типу ТС.
-- 'delivery' и 'pickup' — перегон одной единицы техники: состава нет, есть заявка-основание и
-- две строки «откуда — куда». Значение по умолчанию делает миграцию безопасной для истории:
-- все заведённые рейсы — грузовые.
ALTER TABLE vehicle_routes
  ADD COLUMN purpose text NOT NULL DEFAULT 'freight',
  -- RESTRICT: заявку, ради которой выписан бланк строгой отчётности, из базы не удаляют.
  ADD COLUMN source_request_id uuid REFERENCES vehicle_requests (id) ON DELETE RESTRICT,
  -- Откуда и куда едет техника. Свободные строки, а не адреса заявки: у спецтехники их нет —
  -- есть объект и период работ, — а перегон идёт с базы либо с прошлой площадки.
  ADD COLUMN move_from text NOT NULL DEFAULT '',
  ADD COLUMN move_to text NOT NULL DEFAULT '',
  ADD CONSTRAINT vehicle_routes_purpose_check
    CHECK (purpose IN ('freight', 'delivery', 'pickup')),
  -- Состав и основание не смешиваются: у грузового рейса заявки лежат в составе, у перегона
  -- заявка одна и стоит колонкой. Иначе появилось бы два ответа на «чей это рейс».
  ADD CONSTRAINT vehicle_routes_source_request_check
    CHECK (
      (purpose = 'freight' AND source_request_id IS NULL)
      OR (purpose <> 'freight' AND source_request_id IS NOT NULL)
    );

-- 2. Одна доставка и один вывоз на заявку.
--
-- Аннулированный лист рейс не отменяет: испорченный бланк списывают и выписывают новый по тому же
-- рейсу (ADR 0052). Поэтому уникальность держится на самом рейсе, а не на его документе.
CREATE UNIQUE INDEX vehicle_routes_source_request_unique
  ON vehicle_routes (source_request_id, purpose)
  WHERE purpose <> 'freight';

-- «Какие перегоны у этой заявки» — вопрос со стороны карточки заявки.
CREATE INDEX vehicle_routes_source_request_idx ON vehicle_routes (source_request_id)
  WHERE source_request_id IS NOT NULL;

-- 3. Перегон едет откуда-то куда-то.
--
-- Пустые строки в графах задания — это лист, по которому нельзя ехать: в 4-П «Место отправления»
-- и «Место назначения» и есть само задание водителю. У грузового рейса колонки остаются пустыми:
-- его задание собирается из заявок состава.
ALTER TABLE vehicle_routes
  ADD CONSTRAINT vehicle_routes_move_fields_check
    CHECK (
      purpose = 'freight'
      OR (btrim(move_from) <> '' AND btrim(move_to) <> '')
    );
