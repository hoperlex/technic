-- Индекс срочности переопределяется под отбор, а не под снятую сортировку
-- (план `docs/office-equipment-card-and-list-cleanup-plan.md`, Р2, находка Н7; парная правка
-- декларации — `apps/api/src/db/schema.ts`, `urgentIdx`).
--
-- ОТКУДА НОМЕР. `ls apps/api/drizzle/*.sql | tail -5` перед созданием файла (08.09.2026):
-- последними в дереве стоят `0284_mech_request_approval.sql` и `0285_mech_approval_grants.sql`
-- соседнего потока — на момент разбора этого плана последней была ещё `0283`, и оба номера ушли,
-- пока волна писалась. Первый свободный — 0286, он и взят. Номер спрашивается у ФАЙЛОВ дерева, а
-- не у журнала базы: на technic_dev часть закоммиченных миграций просто не накатана, и `max(seq)`
-- там врёт в меньшую сторону.
--
-- ЗАЧЕМ. Этой волной из списка заявок уходит подъём срочных над выбранной сортировкой (Р1):
-- «за что браться следующим» — решение человека, и список перестаёт принимать его сам. Индекс же
-- был написан ровно под это правило: его условие дословно повторяло условие `urgentFirst`
-- (миграция 0162), то есть исключало закрытые и отложенные заявки. Вместе с сортировкой он
-- потерял единственного потребителя, чьё условие было не шире его собственного.
--
-- ПОЧЕМУ УСЛОВИЕ ШИРЕ, А НЕ УЖЕ. Оставшийся вход срочности — отбор «Только срочные», и он
-- спрашивает другое: «покажи все срочные за период». Закрытые срочные из него не выпадают —
-- прошлое у отбора не отнимают, — а остаточное `status <> 'on_hold'` он дописывает сам. Частичный
-- индекс покрывает лишь запрос, чьё условие НЕ ШИРЕ его собственного: сохрани мы прежние три
-- статуса, отбор читал бы таблицу целиком, а вместе с ним — счётчик той же страницы и `read-all`,
-- которые ходят тем же условием.
--
-- ПОЧЕМУ ВООБЩЕ ОСТАВЛЕН. Удалить индекс без замера нельзя: отбор остаётся рабочим входом (Р1), и
-- снимать покрытие следует по `EXPLAIN` на производственной статистике, а не по догадке. На малой
-- тестовой таблице планировщик вправе выбрать последовательное чтение — это не отказ индекса.
--
-- ОБРАТИМОСТЬ: тем же `DROP INDEX` + `CREATE INDEX` с прежним условием
-- (`... AND status NOT IN ('accepted','cancelled','on_hold')`). При откате кода обратный DDL не
-- нужен вовсе: старому запросу более широкий индекс не хуже прежнего — он остаётся применимым,
-- лишь перестаёт быть узким.
--
-- DDL идёт в транзакции раннера (без `CONCURRENTLY`, как и в 0162): на время пересоздания
-- `service_requests` держится под блокировкой, поэтому выкат ставится в окно, посчитанное по
-- измеренному размеру таблицы.
DROP INDEX service_requests_urgent_idx;
CREATE INDEX service_requests_urgent_idx ON service_requests (status_changed_at)
  WHERE is_urgent AND deleted_at IS NULL;
