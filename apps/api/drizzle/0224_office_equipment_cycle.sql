-- ПЕРВЫЙ ПУНКТ ГОВОРИТ О ПРОПАВШЕМ СТАТУСЕ ПРЯМО И СРАЗУ ОБЪЯСНЯЕТ, ЧТО ДЕЛАТЬ. Человек, искавший
-- свои заявки в «Назначена», увидит пустую вкладку и решит, что заявки потерялись. Поэтому сказано
