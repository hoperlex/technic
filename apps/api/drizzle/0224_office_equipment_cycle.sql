-- отклонённой заявке через месяц начинается с нуля. Про исчезнувшую визу ИТ сказано отдельно:
-- подписей было две по порядку, стала одна, и тот, кто ждал чужой визы, обязан узнать, что ждать
-- больше нечего.
--
-- ТРЕТИЙ ПУНКТ ЗАЩИЩАЕТ ЗАЯВИТЕЛЯ ОТ ОЩУЩЕНИЯ ПОТЕРИ. Из формы расходников убран целый блок, и без
-- объяснения это читается как «сломали заведение заявок». Сказано, кто теперь заполняет состав и
-- что заказчик его по-прежнему видит.
--
-- ЧЕТВЁРТЫЙ ПОМЕЧЕН `feature`, А ОСТАЛЬНЫЕ НЕТ, И РАЗНИЦА НЕ В РАЗМЕРЕ. Сказать «аппарат стоит не
-- там, где написано» заявителю раньше было НЕЧЕМ — он писал это словами в комментарий и надеялся,
-- что прочтут. Это новая возможность. Убранные статусы, переехавшее согласование и переписанная
-- форма новых возможностей не дают никому: то же самое делалось и вчера, просто в большее число
-- нажатий.
