-- Цикл заявки оргтехники короче на два статуса: «Назначена» и «Смета на согласовании» уходят из
-- цикла, а то, что они означали, переезжает в колонки заявки. Бандл окна `--cutover` (ADR 0145,
-- план `docs/office-equipment-cycle-simplification-plan.md`, §6 «Основной путь: одно окно
-- --cutover, одна миграция»).
--
-- ЧТО ЗАКРЫВАЕТ. Два статуса из девяти означали не состояние заявки, а ОЖИДАНИЕ НАЖАТИЯ КНОПКИ:
-- «Назначена» — что распределивший уже нажал, а исполнитель ещё нет; «Смета на согласовании» — что
-- счёт предъявлен, а решения по нему нет. Оба ожидания видны и без статуса: первое — по составу
-- исполнителей заявки, второе — по непогашенному предъявлению. Отсюда три колонки этой миграции:
--
--   * `estimate_pending_revision` (Р2) — ожидание подписи под объёмом работ. СВОЕЙ колонкой, а не
--     выводом из `estimate_submitted_at` и сравнения ревизий: те же поля пишет и старый код, и
--     отличить его запись от нашей было нечем — ни возврат в правку, ни отказ по смете дату
--     предъявления сегодня не чистят. Старый код о новой колонке не знает и оставляет `NULL`, чем
--     отличие и создаётся по построению; нормализация старых данных отменяется вовсе.
--   * `rejection_resolution` (Р12) — решение при отказе по объёму работ («меняем, заявка на
--     закупку заведена»). Причина отказа уходит комментарием перехода в историю, как у всех
--     переходов с объяснением; одним полем на два вопроса не ответить.
--   * `object_overridden` (Р16) — заявитель сказал, что аппарат стоит не на том объекте, что в
--     карточке. Хранится только ЗАЯВЛЕНИЕ; само расхождение вычисляется соединением с карточкой,
--     чтобы перенос единицы в справочнике гасил его сам.
--
-- ПОЧЕМУ ОДНОЙ МИГРАЦИЕЙ И В ОКНЕ. Экспанд/контракт здесь ничего не выигрывает. Проверка
-- фактического `deploy-auto` показала, что путь, ради которого строился весь аппарат
-- совместимости, всё равно проходит через остановленное окно: `--cutover` останавливает запись
-- (шаг 2) и поднимает сервисы только на шаге 9, а границу пишет ДО подъёма кандидата. Раз окно
-- нужно в любом случае, старый код сконвертированных данных не видит вовсе — он в это время не
-- работает, — и вместе с этим исчезают отображение живых статусов, legacy-ветки предикатов,
-- материализация признака, сливные дуги и дозаполняющий запрос второго релиза.
--
-- Прецедент здесь ДЕЛОВОЙ, а не технический, и путать их нельзя. 24.08.2026 заказчик тем же
-- основанием («живых заявок в модуле единицы, окно согласуется») слил три выпуска 0197 в один
-- накат — но 0197 ехала обычным `deploy-auto` с сознательно принятым окном, в котором СТАРЫЙ код
-- работает на новой схеме, teardown у неё нет вовсе, и `--cutover` для неё не запускался. Здесь
-- окно строже: старый код в нём не работает совсем, а платой за это стала обвязка ниже —
-- teardown и верификатор, без которых `--cutover` не запускается.
--
-- ПОЧЕМУ ШАГИ ИДУТ ИМЕННО В ЭТОМ ПОРЯДКЕ — `ALTER TABLE` шага 1 стоит ДО всякого `UPDATE` статусов,
-- а перед `ALTER TABLE` шага 5 стоит `SET CONSTRAINTS ALL IMMEDIATE`. Причина одна и та же, и
-- найдена она ещё миграцией 0197 (§1а): `service_requests_executor_present` (0178) — CONSTRAINT
-- TRIGGER `DEFERRABLE INITIALLY DEFERRED` на `UPDATE OF status, held_from_status`, то есть ровно на
-- те колонки, которые правит конверсия шага 3; его проверки копятся до конца транзакции. А
-- `ALTER TABLE`, берущий ACCESS EXCLUSIVE, отказывается работать по таблице с непустой очередью
-- событий — иначе он менял бы её определение под ещё не выполненными проверками — и отвечает
-- «cannot ALTER TABLE "service_requests" because it has pending trigger events». ПУСТАЯ БАЗА ЭТОГО
-- НЕ ЛОВИТ, и в этом всё коварство: `UPDATE`, не задевший ни одной строки, в очередь ничего не
-- кладёт, и миграция проходит. Отказ ждёт ровно там, где есть что переводить, — на боевых данных.
--
-- ЗНАЧЕНИЯ ENUM НЕ УДАЛЯЮТСЯ. `ALTER TYPE … DROP VALUE` в Postgres не существует вовсе, а
-- пересоздание типа означало бы переписывание всех зависимостей — колонок, `CHECK`ов, индексов,
-- функций — при нулевом выигрыше: место в типе ничего не стоит. Главное же — история переходов эти
-- значения ХРАНИТ: строка «Новая → Назначена» от 20.08 правдива, и портал обязан её подписать.
-- Поэтому `assigned` и `estimate_review` идут тем же путём, что `it_approved` и `diagnostics` в
-- 0197: значение остаётся в типе, подпись и цвет остаются, коридоры пустеют, заявок в них не
-- бывает, а дверь шага 5 это подтверждает. Подписи мёртвых статусов при этом не переименовываются:
-- слей мы «Назначена» с «Новой» одним словом, два разных состояния слились бы в ленте истории.
--
-- БАНДЛ ОБЯЗАН ЕХАТЬ В ОКНЕ ОДИН — и это требование ЭТОГО плана, а не протокола. Протокол соседей
-- в окне допускает, `deploy-auto` о них лишь предупреждает. Но соседи отбирают `--cutover-revert`:
-- teardown снимет одну миграцию, остальные останутся в журнале без файлов в старом образе, и он не
-- стартует, — а на возможности отменить неудачный верификатор здесь держится весь смысл teardown.
-- Гейт ручной и стоит дважды — перед веткой и непосредственно перед `--cutover`, до открытия окна,
-- — и оба раза проверяет ВСЕ ЧЕТЫРЕ координаты: миграция 0224, ADR 0145, `seq = 63`, версия
-- `0.1.54.0145`. Одного номера миграции мало: параллельный поток мог занять `seq` или версию уже
-- ПРИМЕНЁННОЙ миграцией, и тогда pending-набор по-прежнему состоит из одной 0224, а падает
-- `INSERT` шага 6 — уже внутри окна, на остановленных сервисах, ради чего гейт и стоит снаружи.

-- ── 1. Колонки и ограничения вида ──
--
-- ПЕРВЫМ ШАГОМ, до конверсии статусов: см. про очередь отложенных проверок в шапке.
ALTER TABLE service_requests ADD COLUMN estimate_pending_revision integer;
ALTER TABLE service_requests ADD COLUMN rejection_resolution text NOT NULL DEFAULT '';
ALTER TABLE service_requests ADD COLUMN object_overridden boolean NOT NULL DEFAULT false;

-- Ждать можно только подписи под ТЕКУЩЕЙ ревизией: предъявление её поднимает и тут же ставит сюда
-- тот же номер, а повторное предъявление под висящим счётом запрещено (Р9). Равенство, а не `<=`
-- как у согласованной ревизии: согласованной бывает и устаревшая (подпись обесценивается новым
-- предъявлением), а ОЖИДАЮЩЕЙ — только предъявленная сейчас.
ALTER TABLE service_requests ADD CONSTRAINT service_requests_estimate_pending_check
  CHECK (estimate_pending_revision IS NULL OR estimate_pending_revision = estimate_revision);

-- Решение при отказе — объяснение отмены, а не свойство заявки, по образцу существующего
-- `service_requests_replacement_check`: у живой заявки заполненное решение означало бы «делаем
-- вместо ремонта то, о чём уже договорились», пока ремонт идёт. Отсюда обязанность матрицы сброса
-- гасить поле при откате «Отменена → Новая» — иначе откат упрётся в это ограничение.
ALTER TABLE service_requests ADD CONSTRAINT service_requests_rejection_resolution_check
  CHECK (status = 'cancelled' OR btrim(rejection_resolution) = '');

-- ── 2. Перенос ожидания подписи на новую колонку ──
--
-- Единственный момент, когда эти заявки ещё видно: через шаг статус исчезнет, и опознать их
-- станет нечем. Вторая ветка — отложенные ИЗ «Сметы на согласовании»: старый код успевал отложить и
-- предъявленную смету, и её ожидание живёт в `held_from_status`. Не перенеси мы её, заявка после
-- возобновления стала бы обычной «В работе», не ждущей подписи, и предъявленный счёт молча выпал
-- бы из очереди согласования.
--
-- Ревизия берётся ТЕКУЩАЯ, а не какая-то запомненная: заявка стоит в «Смете на согласовании»
-- ровно потому, что предъявлена её нынешняя ревизия — повторное предъявление запирал сам статус
-- (из «Сметы на согласовании» ручка предъявления недоступна). Ограничение шага 1 утверждает то же
-- самое и на будущее.
UPDATE service_requests
   SET estimate_pending_revision = estimate_revision
 WHERE status = 'estimate_review'
    OR (status = 'on_hold' AND held_from_status = 'estimate_review');

-- ── 3. Конверсия статусов — вместе со сверкой количеств, В ОДНОМ блоке с ней ──
--
-- Сверка обязана жить ЗДЕСЬ, а не в верификаторе: тот запускается отдельной командой ПОСЛЕ наката
-- (§7 протокола), когда прежних статусов уже нет и сравнивать не с чем. Здесь исходное состояние
-- ещё доступно, и проверка отвечает на настоящий вопрос — полна ли конверсия и держался ли
-- fail-fast: «Новых с исполнителями» после перевода обязано стать ровно столько, сколько было
-- «Назначенных» до него.
--
-- Проверка происхождения стоит в НАЧАЛЕ ТОГО ЖЕ блока, а не отдельным фрагментом перед ним:
-- разнесённые, они читаются так, будто проверка смотрит на уже переведённые строки и падает на
-- собственной работе.
DO $$
DECLARE anomalous integer; was_assigned integer; now_new_with_exec integer;
BEGIN
  -- Fail-fast: «Новая с исполнителями» ДО конверсии делает происхождение неотличимым от
  -- «Назначена», и teardown не сможет обратить перевод — обратное опознание идёт по составу
  -- исполнителей. Триггер 0178 такого состояния не запрещает: для эффективного статуса `new` он
  -- возвращается сразу, ничего не проверяя, — он стережёт обратное утверждение («в рабочих
  -- статусах исполнитель есть»).
  SELECT count(*) INTO anomalous FROM service_requests r
   WHERE coalesce(r.held_from_status, r.status) = 'new'
     AND (r.service_counterparty_id IS NOT NULL
          OR EXISTS (SELECT 1 FROM service_request_executors e WHERE e.request_id = r.id));
  IF anomalous > 0 THEN
    RAISE EXCEPTION 'Заявок в «Новой» с исполнителями: %. После конверсии их происхождение '
      'неотличимо от «Назначена», и teardown не обратит перевод. Разберите их до выката', anomalous;
  END IF;

  SELECT count(*) INTO was_assigned FROM service_requests
   WHERE coalesce(held_from_status, status) = 'assigned';

  -- «Назначена» была ожиданием кнопки исполнителя — её содержательный эквивалент «Новая»: заявка
  -- распределена и ждёт, когда исполнитель возьмёт её в работу. «Смета на согласовании» была
  -- ожиданием подписи в ходе работ — эквивалент «В работе», а само ожидание уже перенесено шагом 2.
  UPDATE service_requests SET status = 'new'     WHERE status = 'assigned';
  UPDATE service_requests SET status = 'in_work' WHERE status = 'estimate_review';

  -- Заморозка: значения ПРЕОБРАЗУЮТСЯ, а не очищаются. `service_requests_hold_check` требует
  -- непустой `held_from_status` у заявки в `on_hold`, и `NULL` здесь уронил бы саму миграцию.
  -- Отложенная заявка помнит, откуда её отложили, и вернуться обязана в живой статус.
  UPDATE service_requests SET held_from_status = 'new'     WHERE held_from_status = 'assigned';
  UPDATE service_requests SET held_from_status = 'in_work' WHERE held_from_status = 'estimate_review';

  SELECT count(*) INTO now_new_with_exec FROM service_requests r
   WHERE coalesce(r.held_from_status, r.status) = 'new'
     AND (r.service_counterparty_id IS NOT NULL
          OR EXISTS (SELECT 1 FROM service_request_executors e WHERE e.request_id = r.id));
  IF now_new_with_exec <> was_assigned THEN
    RAISE EXCEPTION 'После конверсии «Новых» с исполнителями %, а «Назначенных» было % — обратное '
      'отображение teardown станет неоднозначным', now_new_with_exec, was_assigned;
  END IF;
END $$;

-- История переходов НЕ ПЕРЕПИСЫВАЕТСЯ. Строка «Новая → Назначена» от 20.08 — правда о том, что
-- тогда произошло; журнал переходов — свидетельство, а не текущее состояние, и переписанный он
-- соврал бы о прошлом. Текущая строка заявки историей не является — её обратить и обязан teardown.

-- ── 4. Слив очереди отложенных проверок ──
--
-- Без этой строки `ALTER TABLE` ниже отвечает «cannot ALTER TABLE "service_requests" because it has
-- pending trigger events»: конверсия шага 3 правила ровно те колонки, на которые подписан
-- отложенный `service_requests_executor_present` (0178). `ALL IMMEDIATE` вместо имени триггера:
-- очередь надо опустошить целиком, а отложенные проверки соседних таблиц в этой транзакции всё
-- равно обязаны сойтись — иначе отказ пришёл бы на `COMMIT`, позже и без указания на виновника.
SET CONSTRAINTS ALL IMMEDIATE;

-- ── 5. Дверь ──
--
-- Перевод без запрета — половина работы: значения остаются в типе, и любой прямой `UPDATE`, скрипт
-- обслуживания или забытая ветка вернут заявку в мёртвый статус, а ходов из него у нового цикла
-- нет. Ограничение с этим именем УЖЕ ЕСТЬ — его завела 0197 на пару `it_approved`/`diagnostics`, —
-- поэтому оно снимается и ставится заново на все четыре значения, а не создаётся одноимённым.
ALTER TABLE service_requests DROP CONSTRAINT service_requests_dead_status_check;
ALTER TABLE service_requests ADD CONSTRAINT service_requests_dead_status_check CHECK (
  status NOT IN ('it_approved','diagnostics','assigned','estimate_review')
  AND (held_from_status IS NULL
       OR held_from_status NOT IN ('it_approved','diagnostics','assigned','estimate_review'))
);

COMMENT ON CONSTRAINT service_requests_dead_status_check ON service_requests IS
  'Мёртвые статусы цикла: «Согласована ИТ» и «Диагностика» (ADR 0133), «Назначена» и «Смета на '
  'согласовании» (ADR 0145). Значения остались в enum только потому, что DROP VALUE в Postgres нет.';

-- ── 6. Запись журнала обновлений (ADR 0077): выпуск 63 ──
