-- Механизация, этап Э3: написание вида техники уходит из заявки (план
-- `docs/mechanization-models-directory-plan.md`, §5; ADR 0156). Колонки `kind_name` и `kind_key`
-- снимаются, предмет аренды остаётся один — ссылка `mech_model_id` на справочник моделей.
--
-- ОТКУДА НОМЕР. Проверено `ls apps/api/drizzle/*.sql | tail -3` непосредственно перед созданием
-- файла (03.09.2026): в дереве `0253` (своя, запись выпуска Э2), `0254` и `0255` — чужая
-- параллельная работа по ТТХ оргтехники. Отсюда `0256`. Сверка сделана заново, а не взята из
-- шапки плана: номера миграций и ADR идут параллельными потоками, и между Э2 и Э3 соседи заняли
-- два номера.
--
-- ЭТО РАЗВЁРНУТОЕ РЕШЕНИЕ ЗАКАЗЧИКА, А НЕ ДОВЕДЁННЫЙ ДО КОНЦА ПЛАН. ADR 0156 в «Последствиях»
-- говорил прямо: обобщённые написания («Компрессор дизельный 5 м³/мин») в модели сами не
-- превратятся, и до уборки кто-то должен либо завести им модели, либо решить, что такие заявки
-- уходят как есть. Заказчика спросили, и он выбрал второе — **снять колонку, потеряв написания**.
-- Прежнее правило «заявка без модели показывается своим написанием» (Э2) этим отменяется, а не
-- «доживает»: с этой миграцией у такой заявки названия техники нет вовсе, и на экране на его месте
-- стоит прочерк.
--
-- ЦЕНА НАЗВАНА ВСЛУХ. Написания исчезают безвозвратно: строки `kind_name` не хранит больше ничто,
-- и восстановить их можно ТОЛЬКО из журнала аудита, который эта же миграция и пишет первым
-- действием. Приём тот же, что у `mech_request.purge` в этом модуле, — снимок реквизитов перед
-- исчезновением; и записан он не для отмены решения, а для ответа на вопрос «что именно потеряли»,
-- который зададут через месяцы, когда у заявки в карточке будет стоять прочерк.
--
-- `mech_model_id` ОСТАЁТСЯ NULLABLE, ХОТЯ ПЛАН ОБЕЩАЛ `NOT NULL`. Обещание опиралось на условие
-- «когда переносить нечего», и условие не наступило: решением заказчика заявки без модели
-- становятся законным, постоянным состоянием, а не остатком переноса. `NOT NULL` при таком выборе
-- не «строгость», а падение наката на первой же такой строке — а `deploy-auto` катит миграции ДО
-- перезапуска, то есть окно выката кончилось бы неподнявшимся сервером. Строгость выбора при этом
-- никуда не делась: её держит сервер на заведении и правке (`assertMechModelAssignable`), и
-- завести новую заявку без модели по-прежнему нельзя.
--
-- TEARDOWN НЕ ПРИВЕЗЁН, И ЗНАЧИТ ФАЙЛ ЕДЕТ ОБЫЧНЫМ `deploy-auto`, А НЕ `--cutover`
-- (`docs/schema-cutover-protocol.md`, §6: необратимость механика узнаёт по teardown в образе).
-- Причина не в том, что снятие колонки обратимо, — оно необратимо. Причина в том, что обратного
-- хода у него нет и в принципе: teardown вернул бы пустую оболочку `kind_name NOT NULL`, а
-- написания к тому моменту существуют только строками журнала, и подъём их обратно — разбор
-- руками, а не откат выкатом. Цена обычного пути тоже названа: между накатом и перезапуском
-- старый сервер ещё пишет `kind_name`, и заведение или правка заявки механизации в эти секунды
-- ответят пятисоткой. Окно короткое и на одном модуле; если выкат решат закрывать протоколом,
-- teardown приезжает отдельным файлом — и тогда обычный путь откажется от наката сам.

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 1. Снимок исчезающих написаний — ПЕРВЫМ действием, до всякого DDL.
--
-- По строке на заявку, у которой ссылки на справочник нет: именно у неё написание было
-- единственным ответом на «что арендовали». У заявки со ссылкой терять нечего — наименование
-- приходит соединением со справочником и переживает эту миграцию.
--
-- Автора у события нет: колонку правит выкат, а не человек, и подставить сюда `created_by`
-- заявки значило бы приписать уборку тому, кто её просто когда-то завёл. `NULL` в
-- `actor_user_id` — законное значение (колонка nullable), а `source` в метаданных отвечает, чья
-- это работа, — тем же приёмом, что `waybill.esm2_sync` в миграции 0236.
--
-- Архивные (`deleted_at`) в отборе не исключаются: их написание исчезает ровно так же, а вопрос
-- «чем была эта заявка» к архиву задают чаще, чем к живым.
INSERT INTO audit_log (actor_user_id, action, entity_type, entity_id, metadata)
SELECT NULL,
       'mech_request.kind_dropped',
       'mech_request',
       r.id::text,
       jsonb_build_object(
         'num', r.num,
         -- Номер тем же видом, что человеку на экране: по «МХ-14» строку журнала соотносят с
         -- карточкой, а по голому `14` — нет.
         'displayNumber', 'МХ-' || r.num,
         'kindName', r.kind_name,
         'source', 'migration 0256'
       )
  FROM mech_requests r
 WHERE r.mech_model_id IS NULL;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 2. Итог наката словами, а не догадкой по числу строк. Первое число — сколько заявок осталось без
-- названия техники вовсе (и сколько строк журнала их теперь описывают), второе — сколько заявок
-- предмет аренды сохранили. Читать их надо в выводе `deploy-auto`; на деве они посчитаны и
-- записаны в отчёт этапа.
DO $$
DECLARE
  v_dropped integer;
  v_linked integer;
  v_logged integer;
BEGIN
  SELECT count(*) FILTER (WHERE mech_model_id IS NULL),
         count(*) FILTER (WHERE mech_model_id IS NOT NULL)
    INTO v_dropped, v_linked
    FROM mech_requests;
  SELECT count(*) INTO v_logged
    FROM audit_log
   WHERE action = 'mech_request.kind_dropped'
     AND metadata ->> 'source' = 'migration 0256';
  RAISE NOTICE 'Механизация Э3: написание теряют % заявок (в журнал записано %), с моделью остаётся %',
    v_dropped, v_logged, v_linked;
END $$;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 3. Снятие.
--
-- Порядок обязателен именно такой. `kind_key` — генерируемая колонка от `kind_name`, и снятие
-- `kind_name` первым Postgres либо отвергнет, либо (с `CASCADE`) унесёт зависимое молча; своё
-- ограничение и свой индекс каждая колонка теряет вместе с собой, но названы они здесь поимённо —
-- чтобы файл читался как перечень того, что исчезает, а не как одна строка с невидимыми
-- последствиями.
ALTER TABLE mech_requests DROP CONSTRAINT mech_requests_kind_not_blank_check;

-- Вход отбора по написанию. Заменён отбором по `mech_model_id` ещё в Э2 (`mech_requests_mech_model_idx`),
-- и с исчезновением колонки терять его нечем.
DROP INDEX mech_requests_kind_key_idx;

ALTER TABLE mech_requests DROP COLUMN kind_key;
ALTER TABLE mech_requests DROP COLUMN kind_name;
