-- Техобслуживание по пробегу: признак у типа техники и журнал записей ТО.
-- План — `docs/vehicle-readings-stats-plan.md`, §3 «Модель данных» (решения Р10—Р14, Р30).
--
-- Это фундамент: ни сервисов, ни ручек, ни экранов миграция не предполагает — только место, куда
-- лягут акты обслуживания, и признак, по которому портал вообще спрашивает про ТО.
--
-- Три решения задают всю схему ниже.
--
-- 1. «ВЕДЁМ ЛИ ТО» — СВОЙСТВО ТИПА ТЕХНИКИ, А НЕ ДОГАДКА ПО ИСТОРИИ ПОКАЗАНИЙ (Р13). Вывести
--    способность машины из переданных одометров нельзя: новая машина показаний ещё не имеет, а
--    временно пустой одометр не означает, что прибора нет, — и подсветка «пробег с ТО неизвестен»
--    приезжала бы к каждой единице в первый же день её работы. Признак заводится явно.
--
-- 2. ОДОМЕТР АКТА — ГРАНИЧНЫЙ ЯКОРЬ, А НЕ ФОРМУЛА (Р11а). Он хранится потому, что показания правят
--    задним числом, а число из акта обязано остаться прежним; в расчёте он участвует ровно один
--    раз — началом первого участка цепочки. Поэтому колонка NULL-абельная: акт бывает без пробега
--    (прибор не работал), и это ОТСУТСТВИЕ ЯКОРЯ, а не ноль. Ноль в учёте счётчика — ложь, и
--    посчитанный от него «пробег с ТО» равнялся бы всему пробегу машины за её жизнь.
--
-- 3. У ЗАПИСИ ЕСТЬ ПОРЯДОК И ВЕРСИЯ (Р30). Двух ТО в один день ключ `performed_on` не различает, а
--    «последнее обслуживание» должно быть однозначным — отсюда индекс по трём колонкам. Версия —
--    оптимистическая блокировка правки: запись правят и удаляют, а правка в середине истории
--    меняет числа соседних интервалов.
--
-- УНИКАЛЬНОСТИ ПО (vehicle_id, performed_on) НЕТ намеренно. Два ТО в один день — редкость, но
-- запрет означал бы, что ошибку ввода даты исправляют только удалением записи, то есть потерей
-- скана и истории. Порядок задаёт индекс, а не запрет.
--
-- МОНОТОННОСТИ ОДОМЕТРА ТОЖЕ НЕТ (Р11а): ввод ТО с пробегом меньше предыдущего — это замена
-- прибора, а не опечатка по определению. Портал предупредит, база откажет только отрицательному.
--
-- ОБРАТИМОСТЬ. Миграция аддитивная: новый тип, новая колонка с безопасным умолчанием и две новые
-- таблицы — ни одной перезаписи данных. Умолчание `'none'` и есть та безопасность: пока справочник
-- типов не размечен, ТО не требуется ни с кого и подсветок в портале не появляется. Откат кода
-- схему не ломает — прежняя сборка этих объектов не знает. Обратной миграции репозиторий не держит
-- (`migrate.ts` только накатывает); при необходимости объекты снимаются вручную.

-- ── Признак у типа техники (Р13) ──

-- Тип создаётся здесь же и тут же используется: запрет «нельзя пользоваться значением в своей
-- транзакции» относится к `ALTER TYPE ... ADD VALUE` (миграции 0130, 0138), а не к `CREATE TYPE`.
CREATE TYPE maintenance_basis AS ENUM ('none', 'odometer');

ALTER TABLE vehicle_types
  ADD COLUMN maintenance_basis maintenance_basis NOT NULL DEFAULT 'none';

COMMENT ON COLUMN vehicle_types.maintenance_basis IS
  'По чему считается ТО машин этого типа: none — не ведётся, odometer — по пробегу (Р13). '
  'Разметка справочника — работа человека, умолчание безопасное: не размечено значит не требуется.';

-- ── Журнал записей ТО (Р10) ──
--
-- Хранится история целиком, а не «дата последнего ТО» у машины: одно поле не отвечает ни на один
-- вопрос, ради которого журнал заводят, — с каким пробегом обслуживали, по какому документу и что
-- было до этого. Правка записи в середине истории пересчитывает интервалы с обеих сторон, и без
-- соседей пересчитывать было бы нечего.
CREATE TABLE vehicle_maintenance (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- RESTRICT, как у всех учётных ссылок на технику: акт обслуживания переживает вывод машины из
  -- парка, и удалять его вместе с карточкой нельзя.
  vehicle_id      uuid NOT NULL REFERENCES vehicles(id) ON DELETE RESTRICT,
  -- Дата без времени: у акта его нет. Из этого следует правило расчёта (Р11б) — показания самого
  -- дня ТО в пробег не идут, потому что снять их могли и до обслуживания, и после.
  performed_on    date NOT NULL,
  -- Реквизит акта и граничный якорь расчёта (Р11а). NULL — «пробега в акте нет».
  odometer_km     integer,
  document_number text NOT NULL DEFAULT '',
  note            text NOT NULL DEFAULT '',
  -- Оптимистическая блокировка правки и удаления (Р30).
  version         integer NOT NULL DEFAULT 0,
  created_by      uuid NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  updated_by      uuid REFERENCES users(id) ON DELETE RESTRICT,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),

  -- Отрицательный пробег — единственное, что база про одометр акта знает наверняка. Верхней
  -- границы и монотонности здесь нет: замена прибора законна (Р11а).
  CONSTRAINT vehicle_maintenance_odometer_check CHECK (odometer_km IS NULL OR odometer_km >= 0),
  CONSTRAINT vehicle_maintenance_version_check CHECK (version >= 0)
);

-- Порядок истории машины (Р30). Три колонки после `vehicle_id`, а не одна дата: два ТО в один день
-- ключом `performed_on` неразличимы, и «последнее» тогда зависело бы от порядка чтения строк.
-- `id` замыкает порядок — `created_at` у двух записей одной транзакции совпадает (это время начала
-- транзакции), и без него ничья осталась бы неразрешённой.
CREATE INDEX vehicle_maintenance_vehicle_idx
  ON vehicle_maintenance (vehicle_id, performed_on DESC, created_at DESC, id DESC);

-- Скан акта. Как во всех модулях (ADR 0024) и по образцу `vehicle_reading_files` (0132): файл
-- живёт максимум в одном месте, кросс-модульную часть держит общий файловый сервис.
CREATE TABLE vehicle_maintenance_files (
  maintenance_id uuid NOT NULL REFERENCES vehicle_maintenance(id) ON DELETE CASCADE,
  file_id        uuid NOT NULL REFERENCES files(id) ON DELETE CASCADE,
  added_at       timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (maintenance_id, file_id)
);
CREATE UNIQUE INDEX vehicle_maintenance_files_file_unique ON vehicle_maintenance_files (file_id);

-- ── Реестр связей файла ──
--
-- Новая таблица связи обязана появиться в `file_is_linked` ТОЙ ЖЕ миграцией, что её заводит
-- (миграция 0133). Причина не в порядке кода: функцию зовут три читателя, и третий — уборка файлов
-- в воркере, которая отбирает не привязанные ни к чему файлы и ставит задачу на физическое
-- удаление объекта из S3. Цена забытой ветки здесь не «лишний доступ», а безвозвратно удалённый
-- скан акта выполненных работ — через неделю после загрузки и без единой ошибки в логе.
--
-- `CREATE OR REPLACE` с полным перечислением прежних веток: тело SQL-функции целиком заменяется, и
-- ветка, не переписанная сюда, молча исчезнет вместе со своим модулем. Сигнатура и свойства
-- (`STABLE PARALLEL SAFE`, `LANGUAGE sql`) сохранены — см. их обоснование в 0133.
--
-- `COMMENT ON FUNCTION` не повторяется: `CREATE OR REPLACE` сохраняет oid, а с ним и комментарий.
CREATE OR REPLACE FUNCTION file_is_linked(p_file_id uuid) RETURNS boolean
  LANGUAGE sql STABLE PARALLEL SAFE
AS $$
  SELECT
    -- Вложения и талоны заявок на вывоз мусора (ADR 0024): талон лежит там же, kind='ticket'.
    EXISTS (SELECT 1 FROM request_files WHERE file_id = p_file_id)
    -- Вложения заявок на технику.
    OR EXISTS (SELECT 1 FROM vehicle_request_files WHERE file_id = p_file_id)
    -- Сканы, подшитые к путевому листу (миграция 0087).
    OR EXISTS (SELECT 1 FROM waybill_files WHERE file_id = p_file_id)
    -- Документы заявок на обслуживание оргтехники (ADR 0084, миграция 0105).
    OR EXISTS (SELECT 1 FROM service_request_files WHERE file_id = p_file_id)
    -- Фотографии показаний техники: приборная панель, чеки заправки (миграция 0132).
    OR EXISTS (SELECT 1 FROM vehicle_reading_files WHERE file_id = p_file_id)
    -- Сканы документов работника (миграция 0019). Строк в таблице пока не бывает — загрузки в
    -- портале нет, — и внесена она именно поэтому: перечень собирают по внешним ключам к `files`,
    -- а не по тому, какие ручки уже написаны.
    OR EXISTS (SELECT 1 FROM person_credential_files WHERE file_id = p_file_id)
    -- Скан акта ТО (эта миграция).
    OR EXISTS (SELECT 1 FROM vehicle_maintenance_files WHERE file_id = p_file_id)
$$;
