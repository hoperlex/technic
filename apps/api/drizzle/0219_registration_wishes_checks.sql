-- Подразделение обязательно у пяти пожеланий, компания — у трёх.
--
-- Продолжение миграции 0218: значения перечисления там, ссылки на них — здесь. CHECK сравнивает
-- `requested_role` с литералом, а добавленное значение enum нельзя использовать в той же
-- транзакции, которая его добавила, — ровно так разошлись 0067 и 0068.
--
-- Смысл проверок прежний (0057): уточнение обязательно там, где без него пожелание бессмысленно и
-- заявку всё равно не рассмотреть. Сотрудник и руководитель отдела работают в пределах отдела
-- (ADR 0040) — не зная какого, учётку не активировать; представитель сервисной компании работает от
-- лица контрагента (ADR 0038, 0085), как оператор по вывозу мусора и арендодатель техники.
--
-- КОЛОНКА ПЕРЕИСПОЛЬЗУЕТСЯ, ЧЕТВЁРТАЯ НЕ ЗАВОДИТСЯ. У `requested_object` расширяется смысл: это
-- «подразделение, где человек работает», объект ИЛИ отдел. Отдельная `requested_department`
-- означала бы две колонки об одном и том же и ветвление по ним всюду, где их читают: нормализация
-- заявки, форма регистрации, карточка учётки, подстановка при активации. Различаются объект и
-- отдел не хранением, а подписью на экране («Отдел» вместо «Объект»), а подпись задаёт тип
-- уточнения в контрактах: `object` и `department` указывают на одно и то же поле. Переименовать
-- колонку тоже не стали — правка схемы, запросов и DTO ради синонима стоит дороже комментария в
-- схеме, а смысл поля («где вы работаете») не менялся.
--
-- CHECK НА НЕПУСТОТУ КОММЕНТАРИЯ ЗДЕСЬ НЕ ПОЯВЛЯЕТСЯ, хотя комментарий этим планом открывается всем
-- пожеланиям (обязательным он остаётся у одного `other`). Довод тот же, что в 0139: заявки с
-- пожеланием в таблице уже есть, дозаполнить им комментарий задним числом нечем, а такой CHECK
-- проверял бы строку при ЛЮБОМ её обновлении — старая заявка перестала бы двигаться вовсе: ни
-- активировать, ни сменить адрес. `NOT VALID` не спасает по той же причине. Обязательность держит
-- `registerSchema` в контрактах — там же, где обязательность объекта и компании.
--
-- ДАННЫХ МИГРАЦИЯ НЕ ТРОГАЕТ И СТАРЫМ СТРОКАМ НОВЫХ ТРЕБОВАНИЙ НЕ ПРЕДЪЯВЛЯЕТ. `ADD CONSTRAINT`
-- проверяет таблицу целиком — и проходит: условие сформулировано от списка пожеланий, а не от
-- «всех», прежним пожеланиям требования не меняются, а строк с новыми значениями сегодня нет ни
-- одной — выбрать их было негде до этой пары миграций. Учёток, заведённых администратором вручную
-- (`requested_role IS NULL`), проверки не касаются вовсе, как и в 0057.

-- Подразделение: три объектных пожелания плюс два отдельских.
ALTER TABLE users
  DROP CONSTRAINT users_requested_object_check,
  ADD CONSTRAINT users_requested_object_check CHECK (
    requested_role IS NULL
    OR requested_role NOT IN (
      'rukstroy', 'site_staff', 'commandant', 'department_staff', 'department_head'
    )
    OR btrim(requested_object) <> ''
  );

-- Компания: два внешних исполнителя плюс сервисная компания.
ALTER TABLE users
  DROP CONSTRAINT users_requested_company_check,
  ADD CONSTRAINT users_requested_company_check CHECK (
    requested_role IS NULL
    OR requested_role NOT IN ('waste_operator', 'vehicle_lessor', 'service_company')
    OR btrim(requested_company) <> ''
  );
