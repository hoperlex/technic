-- Руководитель отдела перестаёт быть ролью и становится признаком связи «человек ↔ отдел».
-- План — `docs/permissions-restructure-plan.md`, §11.1 и §15, этап 5.
--
-- ЧТО СЛОМАНО СЕГОДНЯ. Вопрос карточки отдела «кто здесь руководитель» выражен именем роли:
-- `users.role = 'department_head'` стоит в четырёх запросах `services/user-scopes.ts` — в выборе
-- руководителей, в проверке кандидата, в чтении прежнего набора и в удалении. Роль при этом
-- отвечает на другой вопрос — «что человек может», — и реформа прав как раз готовится роли
-- сливать. После слияния карточка отдела опустеет МОЛЧА: ни одно право не изменится, ни один тест
-- доступа не покраснеет, а список руководителей станет пустым у всех отделов сразу. Поэтому
-- развязывание идёт ОТДЕЛЬНЫМ этапом и ДО любого перевода ролей, а не вместе с ним.
--
-- Вторая причина, независимая от реформы: руководство — свойство СВЯЗИ, а не человека. Один и тот
-- же сотрудник бывает руководителем ПТО и рядовым участником снабжения; ролью, которая у учётки
-- одна, это не выражается вовсе — сегодня привязка к любому второму отделу автоматически делает
-- его руководителем и там.
--
-- ЧЕГО МИГРАЦИЯ НЕ ДЕЛАЕТ. Роль `department_head` остаётся на месте, её права не меняются, ось
-- области (`DEPARTMENT_SCOPED_ROLES`) не трогается. Это развязывание, а не слияние: после наката
-- роль по-прежнему решает, что человек может, а признак — кем он в отделе числится.

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 1. Колонка.
--
-- NOT NULL DEFAULT false заводится сразу: значение постоянное, поэтому переписывания таблицы не
-- будет (pg 11+ хранит умолчание в каталоге), а «признака нет» и «не руководитель» — это одно и то
-- же состояние, и NULL добавил бы третье, которого в предметной области не существует.
ALTER TABLE user_departments ADD COLUMN is_head boolean NOT NULL DEFAULT false;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 2. Перенос состояния: чем сегодня отвечает роль, тем завтра отвечает признак.
--
-- Правило переноса дословно повторяет запрос, который снимается с кода: связь учётки с ролью
-- «Руководитель отдела» — и есть руководство. Одна и та же учётка, привязанная к трём отделам,
-- получает признак во всех трёх: сегодня карточка каждого из них показывает её руководителем.
--
-- Удалённые учётки (`deleted_at IS NOT NULL`) переносятся НАРАВНЕ с живыми, и это не недосмотр.
-- Фильтр по `deleted_at` стоит на ЧТЕНИИ (`headsByDepartmentIds`): архивная учётка из карточки
-- отдела исчезает, но её привязка остаётся в базе и возвращается вместе с восстановлением записи.
-- Пропусти мы её здесь — восстановление из архива вернуло бы человека в отдел рядовым, и заметить
-- это было бы нечем.
UPDATE user_departments ud
SET is_head = true
FROM users u
WHERE u.id = ud.user_id AND u.role = 'department_head';

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 3. Индекс под вопрос карточки отдела.
--
-- Частичный, по одному признаку: строк-руководителей в таблице единицы на сотни строк-сотрудников,
-- и полный индекс по `is_head` был бы вчетверо больше при той же пользе. Существующий
-- `user_departments_department_idx` вопрос «кто в отделе» закрывает, но карточке нужен его узкий
-- срез — и список отделов спрашивает его пачкой на каждую страницу справочника.
CREATE INDEX user_departments_head_idx ON user_departments (department_id) WHERE is_head;

COMMENT ON COLUMN user_departments.is_head IS
  'Руководитель ЭТОГО отдела (§11.1 плана реструктуризации прав). Прав не даёт и в расчёте '
  'доступа не участвует: доступ считают роль и наборы полномочий, а признак отвечает на вопрос '
  'справочника «кто здесь главный». Свойство связи, а не человека: в одном отделе руководитель, '
  'в другом сотрудник — ролью, которая у учётки одна, это не выражается.';

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- ОБРАТИМОСТЬ. Миграция добавляет колонку и индекс, ничего не удаляя и не переписывая: откат кода
-- на предыдущую версию просто перестаёт признак читать — прежние запросы по `users.role` работают
-- как работали, потому что роль не тронута. Обратной миграции репозиторий не держит (`migrate.ts`
-- только накатывает); при необходимости колонка снимается
-- `ALTER TABLE user_departments DROP COLUMN is_head`.
--
-- ВЫКАТ. Порядок обычный — миграция до перезапуска приложения. Окно между ними безопасно в обе
-- стороны: старый код признака не знает, новый читает уже перенесённое состояние.
