-- Потребность у расходника и плановая закупка (ADR 0146, план
-- `docs/office-equipment-consumables-and-purchase-plan.md`: решения Р9–Р13, Р15, Р17, Р18 и §5
-- «Модель данных»). Этап Э5 — только схема; маршруты, контракты и портал едут следующей волной.
--
-- ЗАЧЕМ. Вопрос «чего и сколько закупить» портал сегодня не отвечает вовсе. Остаток он знает с
-- `0172`, расход по заявкам — с `0186`, а вот **сколько позиции хотим держать на полке** записать
-- негде: это число живёт в голове у ИТ-службы, и «дефицит» считается глазами по выгрузке. Отсюда
-- обе половины миграции — потребность (число намерения у карточки) и документ, которым дефицит
-- превращают в заказ снабжению.
--
-- ПОЧЕМУ СВОЯ ТАБЛИЦА, А НЕ `kind = 'purchase'` В `service_requests` (Р9). Довод ADR 0133 об одной
-- таблице заявок был конкретен: «та же техника, та же область видимости, та же история, те же
-- письма». У закупки нет первых двух. Остаток расходников **один на компанию** (граница ADR 0132:
-- мест хранения у него нет), значит потребность, дефицит и заказ по дефициту глобальны — ни
-- площадки, ни отдела у такого документа не бывает. А модуль заявок построен ровно на обратном: на
-- аппарате, его объекте и его отделе, которыми считается область, фильтруются списки и стоят
-- `INNER JOIN` базового запроса. Первая редакция плана впихивала глобальный документ в эту модель и
-- платила исключениями в семи местах — `CHECK` предмета, предикат области, триггер исполнителей,
-- вычислитель ожиданий, планирование писем, два коридора статусов, ручка приёмки. Семь «здесь наше
-- правило не действует» в одном модуле означают, что правило было не то.
--
-- ЧТО ЗАВОДИТСЯ: колонка потребности у `office_equipment_consumables`, шапка закупки
-- `office_equipment_purchases` и её строки `office_equipment_purchase_items`. Триггеров нет ни
-- одного — и это не экономия: закупка **не двигает остаток** (Р11, решение заказчика на альфу),
-- поэтому журналу остатка не нужен новый вид события, а `CHECK` направления и три триггера покрытия
-- `0172` не трогаются вовсе.
--
-- ПОРЯДОК ОТНОСИТЕЛЬНО СОСЕДЕЙ. Миграция обязана идти ПОСЛЕ `0172` — она ссылается на
-- `office_equipment_consumables` и правит её. Обратной зависимости нет; заявок (`0105`, `0186`,
-- `0224`) миграция не касается ни одной колонкой.
--
-- ОКНО ВЫКАТА НЕ НУЖНО, и единственное место, где это могло бы сломаться, закрыто умолчанием.
-- Штатный деплой накатывает миграции ДО перезапуска сервисов, то есть какое-то время старый код
-- работает на новой схеме. Двум новым таблицам это безразлично — старый код о них не знает и в них
-- не пишет. А вот `required_quantity` появляется у ЖИВОЙ таблицы, в которую старый код вставляет
-- карточки расходников, ничего не зная про колонку; без `DEFAULT 0` первая же вставка в этом окне
-- упала бы на `NOT NULL`. Умолчание при этом остаётся навсегда: «потребность неизвестна — значит не
-- следим» верно и после окна, а снятие умолчания вернуло бы ту же поломку при откате релиза.
--
-- ЗАПИСИ ВЫПУСКА (`app_releases`) ЗДЕСЬ НЕТ НАМЕРЕННО — это отступление от обычая «фича едет одним
-- файлом» (§6 протокола выката), и причина у него простая: схема едет впереди работающих ручек.
-- Пока портал не умеет ни заводить закупку, ни править потребность, рассказывать о них в журнале
-- обновлений нечего. Запись поедет отдельной миграцией в конце работы, вместе с готовой вкладкой.
--
-- POSTGRESQL 17. Version-specific здесь нет ничего: `GENERATED ALWAYS AS IDENTITY`, частичный
-- индекс по `IN`-списку и `INCLUDE`-колонки работают одинаково с 11-й версии. `ADD COLUMN` с
-- НЕволатильным умолчанием не переписывает таблицу с той же 11-й — справочник расходников
-- маленький, но правило важно назвать, чтобы следующая колонка не приехала с `now()` в умолчании.

-- ── 1. Потребность: сколько позиции хотим держать на полке (Р13) ──
--
-- Не минимум и не норматив, а именно «потребность» — как назвал это заказчик: её правят по
-- обстоятельствам, и вчерашнее число ничем не хуже сегодняшнего, просто оно вчерашнее. Отсюда два
-- следствия, оба сознательные:
--
--   * СВОЕГО ЖУРНАЛА У НЕЁ НЕТ, в отличие от остатка. Журнал заведён у остатка потому, что остаток —
--     предмет учёта: на вопрос «куда делись двенадцать картриджей» отвечает только цепочка событий.
--     Потребность — намерение, и на «кто поменял план» обычного аудита карточки достаточно.
--   * НОЛЬ ЗНАЧИТ «НЕ СЛЕДИМ», а не «нужно ноль штук». Такие позиции не попадают в предзаполнение
--     закупки вовсе — иначе форма предлагала бы заказать всё, чего нет на складе, включая то, что
--     сознательно не держат.
--
-- Дефицит (`max(0, потребность − остаток − уже заказанное)`) НЕ ХРАНИТСЯ: он меняется от каждого
-- движения склада и от каждой чужой закупки, и хранимая копия расходилась бы с правдой между двумя
-- пересчётами. Считает его сервер одним местом (Р15) — два места, считающие дефицит, разойдутся, а
-- по этому числу заказывают.
ALTER TABLE office_equipment_consumables
  ADD COLUMN required_quantity integer NOT NULL DEFAULT 0;

-- Отрицательной потребности не бывает: «нужно минус два» — это не отрицательное намерение, а
-- ошибка ввода. Правило то же и по той же причине, что у соседнего `..._quantity_check` остатка.
ALTER TABLE office_equipment_consumables
  ADD CONSTRAINT office_equipment_consumables_required_check CHECK (required_quantity >= 0);

-- ── 2. Шапка закупки (Р9, Р10, Р17) ──
--
-- ИСТОРИЯ ДОКУМЕНТА — КОЛОНКАМИ, А НЕ ЖУРНАЛОМ, и решение это принято из-за свойства общего
-- помощника аудита: `writeAudit` **глотает ошибку записи** (`catch` + `logger.error`), то есть
-- гарантией истории не является. У остального портала это осознанный компромисс — журнал не должен
-- ронять выписанный путевой лист, — но карточка, показывающая жизненный путь документа из такого
-- источника, показывала бы его с дырами. Поэтому у каждого перехода своя пара колонок: она пишется
-- той же транзакцией, что и статус, и лента карточки полна по построению. Аудит при этом пишется
-- тоже, но строгий (`writeAuditTx`) — закупка двигает деньги снабжения, и запись о ней, потерянная
-- молча, объясняла бы расхождение хуже, чем её отсутствие.
--
-- ВИДИМОСТЬ У ДОКУМЕНТА ПО ПРАВУ, А НЕ ПО ОБЛАСТИ (Р12), поэтому колонок области здесь нет вовсе —
-- ни объекта, ни отдела. Заведи мы их «на всякий случай», они обещали бы область, которой нет ни у
-- остатка, ни у потребности, по которым закупка и считается.
CREATE TABLE office_equipment_purchases (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Сквозной человекочитаемый номер; показывается как «ЗК-<num>». Тем же приёмом, что номера
  -- заявок (`0105`) и заказов ТС (`0012`): раздаёт его база, а не клиент и не счётчик в коде.
  num integer GENERATED ALWAYS AS IDENTITY,

  -- Цикл из четырёх состояний (Р10): `new` («Новая») → `in_work` («В работе», бумага у снабжения)
  -- → `closed` («Закрыта»); из первых двух — `cancelled` («Отменена») с обязательной причиной.
  -- Закрытая и отменённая конечные: ошибку исправляют новой закупкой, а не переписыванием прошлой.
  --
  -- Текстом с `CHECK`, а не своим `enum`: у типа в Postgres нет `DROP VALUE`, и мёртвое значение
  -- остаётся в нём навсегда (этот модуль уже носит четыре таких — `0197` и `0224`). Четыре
  -- состояния одной стороны — не тот случай, ради которого стоит заводить неудаляемый словарь.
  status text NOT NULL DEFAULT 'new',
  -- «К чему закупка», необязательный. Больше у формы нет ничего: ФИО, телефона, срочности и
  -- подразделения у закупки нет намеренно (Р16) — это реквизиты заявки на обслуживание, где к
  -- человеку едут. У закупки один адресат, снабжение, и он известен.
  comment text NOT NULL DEFAULT '',

  -- Версия содержимого (Р18). Состояние и версия отвечают на РАЗНЫЕ вопросы, и одним полем на два
  -- не ответить: состояние — «можно ли править», версия — «не изменил ли документ кто-то другой».
  -- Условия по статусу хватает переходам (статус в них и меняется) и НЕ хватает правке полей: она
  -- идёт внутри одного статуса, где статус неподвижен и ничего не стережёт. Двое открыли черновик
  -- на 10, первый поставил 12 и сохранил, второй ставит 8 — снимок Р17 у второго сходится (внешнее
  -- состояние не менялось, собственный вклад закупки из него и так вычитается), и «8» молча
  -- перетёрло бы «12». Растёт при каждой правке и входит в условие записи; «Провести» несёт её
  -- тоже — иначе в снабжение уезжает не тот состав, который человек видел на экране.
  --
  -- Считается с единицы, а не с нуля: заведённый документ — это уже первая редакция.
  content_version integer NOT NULL DEFAULT 1,

  -- ── Пары переходов. Пишутся той же транзакцией, что и статус (см. шапку раздела).
  -- `RESTRICT` у всех четырёх — тот же довод, что у автора события журнала остатка (`0172`): кто
  -- завёл, провёл, закрыл и отменил закупку, не должно теряться вместе с учёткой, а `SET NULL`
  -- заставил бы карточку отвечать «неизвестно» на единственный вопрос, ради которого колонка и
  -- заведена. Справочники в портале переживают увольнение своего автора (`SET NULL`), документы —
  -- нет.
  created_by uuid NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  -- «Провели» — передали в снабжение.
  submitted_by uuid REFERENCES users (id) ON DELETE RESTRICT,
  submitted_at timestamptz,
  closed_by uuid REFERENCES users (id) ON DELETE RESTRICT,
  closed_at timestamptz,
  cancelled_by uuid REFERENCES users (id) ON DELETE RESTRICT,
  cancelled_at timestamptz,
  -- Причина отмены обязательна (Р10) — но требовать её колонкой `NOT NULL` нельзя: у неотменённой
  -- закупки причины нет. Пустая строка означает «отмены не было», и `CHECK` ниже связывает её со
  -- статусом. `NULL` рядом с пустой строкой был бы вторым именем того же состояния.
  cancel_reason text NOT NULL DEFAULT '',

  -- ── Идемпотентность заведения (Р17). Образец — кабинет водителя (ADR 0103): пара «ключ клиента +
  -- отпечаток принятого тела». Тот же ключ с тем же отпечатком возвращает уже созданную закупку,
  -- тот же ключ с другим телом — это другая команда под старым ключом, и молча подтверждать её
  -- нельзя. Отличие от образца одно: там ключ ложится на СУЩЕСТВУЮЩУЮ строку дня, здесь строка ещё
  -- только создаётся, — отсюда уникальное ограничение и разбор `23505` снаружи транзакции.
  --
  -- ОБА ПОЛЯ `NOT NULL`, и это не строгость ради строгости: ручка новая, legacy-клиентов у неё нет,
  -- а необязательный ключ означал бы, что защита работает у тех, кто её попросил. У водителя ключ
  -- необязателен ровно потому, что там он приехал к работающей ручке.
  --
  -- `uuid`, как у водителя: ключ — идентификатор ПОПЫТКИ ОТПРАВКИ, который портал генерирует сам, и
  -- тип отбивает мусор в заголовке раньше маршрута.
  idempotency_key uuid NOT NULL,
  -- Отпечаток нормализованного тела: строки упорядочены по позиции, комментарий обрезан по краям.
  -- Нормализация обязательна ДО отпечатка — иначе переставленные местами строки той же закупки
  -- дали бы «другую команду под тем же ключом» и честный повтор получил бы 409.
  idempotency_fingerprint text NOT NULL,

  updated_at timestamptz NOT NULL DEFAULT now(),

  -- ── Инварианты. КАЖДЫЙ ОТДЕЛЬНЫМ ИМЕНЕМ, и держит их база, а не порядок вызовов: ручной
  -- `UPDATE`, скрипт обслуживания или забытая ветка маршрута оставили бы документ в состоянии,
  -- которого не бывает, — закрытом с причиной отмены или отменённом без причины. Отдельными, а не
  -- одной матрицей (как у дня водителя в `0132`), потому что имя сработавшего ограничения здесь
  -- читает человек: у закупки четыре независимых правила, и «нарушено office_equipment_purchases_
  -- cancelled_check» говорит, что именно не сошлось, а общее имя потребовало бы разбирать выражение.

  -- Словарь состояний. Значение вне четвёрки — это не «новый статус», а опечатка скрипта.
  CONSTRAINT office_equipment_purchases_status_check
    CHECK (status IN ('new', 'in_work', 'closed', 'cancelled')),

  -- Закрытие: пара заполнена РОВНО у `closed`. Обе стороны равенства важны — «заполнено только у
  -- закрытой» не запрещает закрытую без автора, а «у закрытой заполнено» не запрещает автора
  -- закрытия у живой.
  CONSTRAINT office_equipment_purchases_closed_check
    CHECK ((status = 'closed') = (closed_by IS NOT NULL)
       AND (status = 'closed') = (closed_at IS NOT NULL)),

  -- Отмена: тройка «кто, когда, почему» заполнена РОВНО у `cancelled`. Причина меряется `btrim`, а
  -- не `<> ''`: строка из пробелов — это отсутствие причины, набранное иначе.
  CONSTRAINT office_equipment_purchases_cancelled_check
    CHECK ((status = 'cancelled') = (cancelled_by IS NOT NULL)
       AND (status = 'cancelled') = (cancelled_at IS NOT NULL)
       AND (status = 'cancelled') = (btrim(cancel_reason) <> '')),

  -- Проведение: пара ходит парой, у «Новой» пуста, у «В работе» и «Закрытой» заполнена. У
  -- ОТМЕНЁННОЙ — свободно, и это не послабление, а единственное честное правило: отменить можно и
  -- из «Новой» (тогда проведения не было), и из «В работе» (тогда было), а по статусу `cancelled`
  -- эти два случая уже не различить — прежнее состояние в шапке не хранится. Требовать здесь
  -- «заполнено» или «пусто» значило бы запретить одну из двух законных отмен.
  CONSTRAINT office_equipment_purchases_submitted_check
    CHECK ((submitted_by IS NULL) = (submitted_at IS NULL)
       AND (status <> 'new' OR submitted_by IS NULL)
       AND (status NOT IN ('in_work', 'closed') OR submitted_by IS NOT NULL)),

  -- Версия содержимого считается с единицы и не убывает по смыслу; ноль означал бы документ, у
  -- которого ещё не было ни одной редакции, — а он создаётся сразу с составом.
  CONSTRAINT office_equipment_purchases_content_version_check
    CHECK (content_version >= 1),

  -- Пустой отпечаток сделал бы ключ бессмысленным: повтор с ЛЮБЫМ телом совпал бы с пустым
  -- отпечатком и вернул бы чужую закупку как свою.
  CONSTRAINT office_equipment_purchases_fingerprint_check
    CHECK (btrim(idempotency_fingerprint) <> ''),

  -- УНИКАЛЬНОСТЬ КЛЮЧА — ОБЫЧНАЯ И С ЯВНЫМ ИМЕНЕМ. Обычная, а не частичная: ключ обязателен, и
  -- частичный индекс по одной колонке был бы и слабее, и лукавее — он обещал бы, что ключа может не
  -- быть. Пара с автором, а не ключ сам по себе: ключ описывает попытку КОНКРЕТНОГО человека, и
  -- совпадение UUID у двоих (пусть невероятное) не должно превращать чужую закупку в «повтор».
  --
  -- Имя задано руками, и это условие работоспособности маршрута, а не стиль. Гонку двух запросов с
  -- одним ключом, но непересекающимися позициями, блокировки строк расходников не разводят вовсе —
  -- разводит только это ограничение, и ловится оно СНАРУЖИ уже прерванной транзакции по паре «код +
  -- имя»: `pg.code === '23505' && pg.constraint === 'office_equipment_purchases_idempotency_unique'`
  -- (тот же приём, что в `vehicle-request-days.ts`, `user-email.ts` и `waste-types.ts`). `23505` в
  -- этой транзакции способны дать и уникальность номера, и пара «закупка + позиция» в строках, и
  -- ограничения строгого аудита; перехвати маршрут код целиком — настоящий дефект базы вернулся бы
  -- клиенту как успешный повтор, то есть ЧУЖОЙ закупкой вместо ошибки. Сгенерированное имя сделало
  -- бы этот разбор хрупким: оно не названо нигде и меняется вместе с составом колонок.
  CONSTRAINT office_equipment_purchases_idempotency_unique UNIQUE (created_by, idempotency_key)
);

-- Номер уникален, как у заявок и заказов ТС: `GENERATED ALWAYS AS IDENTITY` раздаёт значения без
-- повторов, но уникальности сам по себе не обещает — `OVERRIDING SYSTEM VALUE` и правка счётчика
-- существуют, а «ЗК-14» на двух документах спор со снабжением сделала бы неразрешимым. Он же —
-- рабочий индекс списка: закупки читают порядком «сначала свежие».
CREATE UNIQUE INDEX office_equipment_purchases_num_unique ON office_equipment_purchases (num);

-- ГЛАВНЫЙ ИНДЕКС ЭТОЙ МИГРАЦИИ — под вопрос «сколько по этой позиции уже заказано в ОТКРЫТЫХ
-- закупках» (Р15). Его задают на каждой странице перечня расходников и в каждом предзаполнении
-- формы, а ответ на него вычитается из дефицита — то есть считается он часто и влияет на заказ.
--
-- Индекс частичный по ровно тому условию, каким открытость и определена (`new`, `in_work`), и
-- держит он ИДЕНТИФИКАТОРЫ, а не статус. Оба решения из одного соображения о том, как этот вопрос
-- задают:
--
--   * ЧАСТИЧНЫЙ — потому что закрытые и отменённые закупки из него выпадают НАВСЕГДА. Открытых в
--     любой момент единицы, а всего их за годы накопятся тысячи; индекс остаётся размером с рабочий
--     срез, и стоимость вопроса не растёт вместе с архивом. Полный индекс по статусу рос бы вместе
--     с ним, а отвечал бы на тот же вопрос.
--   * ПО `id`, А НЕ ПО `status` — потому что спрашивают у него именно идентификаторы. Открытых
--     мало при любом размере архива (снабжение возит частями, но не годами), и планировщик поэтому
--     ведёт соединение ОТ НИХ: берёт весь частичный индекс и идёт в строки ключом `(purchase_id,
--     consumable_id)`. Из индекса по `status` идентификатор пришлось бы доставать из кучи — то есть
--     делать ровно тот шаг, ради снятия которого индекс и заводится.
--
--     Проверено планом на 3008 закупках, из которых открытых шесть: `Index Only Scan using
--     office_equipment_purchases_open_idx … Heap Fetches: 0` — в таблицу шапок запрос не заглядывает
--     вовсе. Размер там же: частичный индекс 16 КБ против 88 КБ у полного индекса по номеру.
--
-- Условие индекса записано ТЕМ ЖЕ `IN`-списком, что и в запросах, и переписывать его в маршруте
-- нельзя: планировщик применяет частичный индекс, только доказав, что предикат запроса влечёт
-- предикат индекса, а `status <> 'closed' AND status <> 'cancelled'` этой проверки не проходит —
-- получился бы верный ответ по неверному плану, то есть seq scan по всему архиву.
CREATE INDEX office_equipment_purchases_open_idx
  ON office_equipment_purchases (id)
  WHERE status IN ('new', 'in_work');

-- Отдельного индекса по `created_by` не заводится: его левой колонкой начинается уникальность
-- ключа идемпотентности выше, и она же обслуживает «мои закупки» и проверку `RESTRICT` при попытке
-- удалить учётку. У трёх остальных ссылок на `users` индексов нет намеренно — их читает только
-- проверка `RESTRICT` при удалении учётки, а это действие редкое (и вообще-то запрещённое: учётки в
-- портале гасят), таблица же документов маленькая. Индекс, существующий ради одного `DELETE` в год,
-- стоит дороже, чем сам этот `DELETE`.

-- ── 3. Строки закупки (Р17) ──
CREATE TABLE office_equipment_purchase_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- `CASCADE`: строки — это СОСТАВ документа, а не его история. Тот же довод, что у строк заявки на
  -- расходники (`0186`): удалили документ — состав уходит с ним, потому что сам по себе он ничего
  -- не значит. Историю при этом каскад не уносит: истории у закупки нет отдельной таблицей, она
  -- живёт колонками переходов, то есть в самой удаляемой строке.
  purchase_id uuid NOT NULL REFERENCES office_equipment_purchases (id) ON DELETE CASCADE,
  -- `RESTRICT`: позицию, попавшую в закупку, удалить нельзя — иначе «заказали 12» осталось бы без
  -- ответа на вопрос «чего именно 12». То же правило и по той же причине, что у журнала остатка и у
  -- строк заявки. Погашенная позиция (`is_active = false`) при этом законна и в старых закупках
  -- остаётся: гашение означает «больше не покупаем», а не «этого никогда не заказывали».
  consumable_id uuid NOT NULL REFERENCES office_equipment_consumables (id) ON DELETE RESTRICT,
  -- Сколько заказываем. Человек правит это число руками, поэтому оно и хранится отдельно от
  -- посчитанного `suggested_quantity` ниже.
  quantity integer NOT NULL,

  -- ── СНИМОК РАСЧЁТА, а не только количество, и это главная колонка группы — точнее, четыре.
  -- Потребность плавающая (Р13), остаток движется каждый день, а «уже заказано» меняется от каждой
  -- соседней закупки. Без снимка через месяц на вопрос «почему заказали двенадцать» ответить
  -- НЕЧЕМ: сегодняшняя потребность к тому решению отношения уже не имеет, и пересчёт задним числом
  -- даст другое число при полностью верных данных. Приём тот же, что снимок предмета в заявке
  -- (`equipment_name` и соседи в `0105`), и по той же причине: документ обязан остаться рассказом о
  -- том, из чего исходили ТОГДА.
  --
  -- Четырьмя колонками, а не одним `jsonb`: по ним считают («заказали больше предложенного —
  -- почему?»), сравнивают и рисуют столбцы формы, а числа, которые считают, живут колонками.
  required_snapshot integer NOT NULL,
  stock_snapshot integer NOT NULL,
  already_ordered_snapshot integer NOT NULL,
  -- Что предложил портал: `max(0, потребность − остаток − уже заказанное)` на момент отправки.
  -- Хранится РЯДОМ со слагаемыми, а не выводится из них: формула Р15 может смениться, и тогда
  -- старые строки пересчитались бы по новому правилу, соврав о прошлом решении.
  suggested_quantity integer NOT NULL,

  created_at timestamptz NOT NULL DEFAULT now(),

  -- Заказывают хотя бы штуку: «заказать ноль» — это отсутствие строки, а не строка. То же правило,
  -- что у `service_request_consumables_requested_check`.
  CONSTRAINT office_equipment_purchase_items_quantity_check CHECK (quantity > 0),
  -- Снимок неотрицателен целиком. Ноль в любом из четырёх чисел законен и осмыслен: «потребность 0»
  -- — позицию дописали руками, «остаток 0» — кончилась, «уже заказано 0» — открытых закупок по ней
  -- нет, «предложено 0» — предлагать было нечего, а заказать решили всё равно. Отрицательное же —
  -- не свойство склада, а ошибка вычислителя, и записывать её в документ нельзя.
  CONSTRAINT office_equipment_purchase_items_snapshot_check
    CHECK (required_snapshot >= 0
       AND stock_snapshot >= 0
       AND already_ordered_snapshot >= 0
       AND suggested_quantity >= 0),
  -- Одна строка на позицию: две строки «Тонер Ricoh 201» в одной закупке — не два расходника, а
  -- ошибка формы, и сумма по ним удвоила бы «уже заказано» у соседа. Ограничение это, кстати, тоже
  -- умеет отдать `23505` — и потому маршрут разбирает гонку ключа по ИМЕНИ, а не по коду.
  CONSTRAINT office_equipment_purchase_items_unique UNIQUE (purchase_id, consumable_id)
);

-- Вход со стороны ПОЗИЦИИ — второй конец того же вопроса Р15 и, кроме него, ещё два постоянных
-- читателя: проверка `RESTRICT` при попытке удалить расходник и «что вообще заказывали по этой
-- позиции» в её карточке. Без индекса каждый из них означал бы seq scan по строкам ВСЕХ закупок за
-- все годы. Тот же индекс и по той же причине стоит у строк заявки (`0186`).
--
-- `INCLUDE (purchase_id, quantity)` делает его покрывающим, и это измерено, а не предположено: на
-- 60 тысячах строк запрос «строки этой позиции» идёт `Index Only Scan … Heap Fetches: 4` при трёх
-- тысячах прочитанных строк — в кучу он не заглядывает. Стоит это ничего: индекс с двумя
-- включёнными колонками (3520 КБ) вышел МЕНЬШЕ уникального ключа пары (3736 КБ).
--
-- Включёнными колонками, а не составным ключом `(consumable_id, purchase_id)`: по `purchase_id`
-- внутри позиции никто не ищет и не сортирует, а включённая колонка не участвует в сравнении ключей
-- и не удорожает разбиение страниц.
--
-- ЧЕСТНАЯ ГРАНИЦА: в самом расчёте дефицита этот индекс планировщик НЕ берёт — открытых закупок
-- мало, и он ведёт соединение от них (см. индекс шапки). Заведён он ради трёх случаев выше, а не
-- ради обещания ускорить перечень; обещай мы второе, первая же проверка плана назвала бы это
-- выдумкой.
--
-- Отдельный индекс по `purchase_id` («покажи состав этой закупки») не нужен: им начинается
-- уникальность пары выше, и она читается слева направо.
CREATE INDEX office_equipment_purchase_items_consumable_idx
  ON office_equipment_purchase_items (consumable_id)
  INCLUDE (purchase_id, quantity);
