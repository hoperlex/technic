-- Включение двух почтовых событий кандидата — `office_equipment_candidate_pending` и
-- `office_equipment_candidate_decided` (план `docs/office-equipment-request-subject-plan.md`,
-- этап Э7; план `docs/office-equipment-candidate-plan.md`, §10; ADR 0165, механика рубильника —
-- ADR 0159). Обе строки завела выключенными миграция 0273, и выключены они были не из
-- осторожности, а по делу: писать было не о чем и некому.
--
-- ОТКУДА НОМЕР. Тот же снимок `ls apps/api/drizzle`, что и у `0294_office_equipment_candidate_
-- grants.sql` (09.09.2026): последним в дереве стоял `0293_feature_flags.sql`, соседи держали 0292.
-- Свободны 0294 и 0295, оба взяты подряд одной работой — ровно затем, чтобы между правами и
-- письмами волны не встал третий поток и не развёл их по разным выкатам.
--
-- ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ ОТ ПРАВ. По границе отката, как и пара 0272/0273. Права снимаются вместе
-- с откатом контрактов и трогают каталог полномочий; письма гасятся одним `UPDATE` по живой базе,
-- без всякого выката, и держать их в одном файле значило бы связать два отката, у которых нет
-- ничего общего, кроме дня выпуска.
--
-- ЧЕГО ЭТА МИГРАЦИЯ ЖДЁТ ПЕРЕД СОБОЙ. Прав волны (0294): пока `officeEquipment.review` не выдано ни
-- одному набору, письмо `pending` уходило бы проверяющим, которых не назначено, — то есть в пустоту
-- или, хуже, живым адресатам копий, которым нечего с ним делать. Порядок внутри выпуска B такой:
-- 0294, затем этот файл, затем — уже после health и smoke — включение рубильника приёма
-- (`office_equipment_candidate_intake`, 0293) одним `UPDATE`.
--
-- ПОЧЕМУ ОБА СОБЫТИЯ СРАЗУ, ХОТЯ 0273 ОБЕЩАЛА ВКЛЮЧАТЬ ИХ ПО ОДНОМУ. Обещание было про окно
-- наблюдения, и окно у выпуска B есть — только даёт его не порядок двух строк, а рубильник приёма.
-- Пока он выключен, ни одного нового сообщения не заводится, значит ни одно из двух писем не может
-- уйти: `pending` рождается при заведении кандидата, `decided` — при решении по нему. Наблюдают
-- здесь за первыми настоящими сообщениями после включения рубильника, а не за интервалом между
-- двумя `UPDATE`, между которыми ничего не происходит. Разнеси мы их на две миграции, вторая
-- означала бы ровно одно: заявители, чьи сообщения уже разобрали, ответа не получили.
--
-- ПОРЯДОК ВНУТРИ ПАРЫ ОСТАЁТСЯ ОБЪЯВЛЕННЫМ И ЧИТАЕТСЯ В ОБРАТНУЮ СТОРОНУ ПРИ АВАРИИ: сначала
-- гасится `pending`, сразу за ним — рубильник приёма; `decided` остаётся включённым до тех пор,
-- пока последний накопленный кандидат не разобран. Иначе приток прекратился бы, а люди, уже
-- отправившие сообщение, остались бы без ответа — тот же довод, по которому очередь проверки и три
-- решения рубильником не ограждаются вовсе.
--
-- ЧТО МЕНЯЕТСЯ У ЛЮДЕЙ. `pending` — письмо тем, кто разбирает сообщения (право
-- `officeEquipment.review`, набор «Оргтехника: ведение»), плюс подтверждение автору сообщения;
-- `decided` — ответ автору о принятом решении. Адресатов сверх этого миграция не заводит: строки
-- `module_mail_recipients` (копии, скрытые копии) — работа администратора, принимаемая осознанно, а
-- не выкатом.
--
-- ЧЕГО МИГРАЦИЯ НЕ ДЕЛАЕТ: не трогает остальные семь строк рубильника (караул сверяет их со
-- снимком «до»), не заводит адресатов, не включает приём кандидатов, не меняет схему и `CHECK`
-- перечня событий — он уже содержит оба значения с 0273.
--
-- `version` БЬЁТСЯ НАМЕРЕННО. Столбец — замок одновременной правки: админка шлёт `UPDATE` с той
-- версией, которую показала форма, и не сдвинь мы её здесь, администратор, открывший экран писем до
-- выката, вернул бы рубильник в выключенное положение своим «Сохранить» — молча и не зная об этом.
-- Со сдвинутой версией его сохранение честно отвечает конфликтом. `updated_by` остаётся `NULL`, и
-- это тоже утверждение: щёлкнул не человек, а выкат, — в журнале рубильника такой строки нет, и
-- выдавать выкат за администратора нельзя.
--
-- ОБРАТИМОСТЬ. Схема не меняется, трогаются две строки одной таблицы. Откат — `UPDATE … SET
-- is_enabled = false, version = version + 1` по тем же двум ключам; строки при этом остаются, и это
-- важно: их отсутствие приложение трактует fail-closed, то есть так же молчаливо, но неотличимо от
-- «миграции не хватает». Код прошлого выпуска о событиях не знает и писем по ним не строит.

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 0. Снимок остальных семи рубильников ДО правки — ради утверждения «чужих событий не трогали».
--
-- `ON COMMIT DROP`: таблица живёт до конца транзакции миграции и в базе не остаётся. Именно снимок,
-- а не константа: три события включены с 0258, остальные четыре администратор мог щёлкнуть в любую
-- сторону в любой день, и на проде, в деве и на восстановленной из копии базе картина разная.

CREATE TEMP TABLE mail_events_0295 ON COMMIT DROP AS
SELECT event, is_enabled
FROM module_mail_event_settings
WHERE event NOT IN ('office_equipment_candidate_pending', 'office_equipment_candidate_decided');

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 1. Сами два рубильника.
--
-- Условие `is_enabled = false` — не защита от повторного наката, а защита ВЕРСИИ: без него
-- повторный накат на уже включённой базе сдвинул бы `version` ещё раз и уронил бы открытую форму
-- администратора, ничего при этом не изменив. Идемпотентность от этого не страдает: результат обоих
-- накатов один и тот же, и караул ниже проверяет именно результат, а не число обновлённых строк.

UPDATE module_mail_event_settings
   SET is_enabled = true,
       version = version + 1,
       updated_at = now()
 WHERE event IN ('office_equipment_candidate_pending', 'office_equipment_candidate_decided')
   AND is_enabled = false;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 2. Караул: оба включены, остальные семь — как были.
--
-- Страж-тест сверяет реестр событий с контрактами, но живёт он в репозитории, а этот блок — в
-- накате: оператор выката увидит расхождение сразу, а не через прогон тестов.

DO $$
DECLARE trouble text;
BEGIN
  SELECT string_agg(msg, '; ')
    INTO trouble
    FROM (
      SELECT format('рубильник «%s» не включён или его строки нет вовсе', s.event) AS msg
        FROM (VALUES ('office_equipment_candidate_pending'),
                     ('office_equipment_candidate_decided')) AS s (event)
       WHERE NOT EXISTS (
         SELECT 1 FROM module_mail_event_settings m
          WHERE m.event = s.event AND m.is_enabled)
      UNION ALL
      SELECT format('чужой рубильник «%s» изменился: было %s, стало %s',
                    b.event, b.is_enabled, m.is_enabled)
        FROM mail_events_0295 b
        JOIN module_mail_event_settings m ON m.event = b.event
       WHERE m.is_enabled <> b.is_enabled
      UNION ALL
      SELECT format('строк рубильника стало %s вместо %s: событие завелось или пропало мимо волны',
                    (SELECT count(*) FROM module_mail_event_settings),
                    (SELECT count(*) + 2 FROM mail_events_0295))
       WHERE (SELECT count(*) FROM module_mail_event_settings)
             <> (SELECT count(*) + 2 FROM mail_events_0295)
    ) AS bad;
  IF trouble IS NOT NULL THEN
    RAISE EXCEPTION
      'Включение писем о сообщениях об отсутствующей технике прошло не так, как объявлено — %',
      trouble;
  END IF;
END $$;
