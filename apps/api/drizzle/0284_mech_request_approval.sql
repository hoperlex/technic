-- Виза ответственного лица площадки у заявки на механизацию (план
-- `docs/mechanization-approval-and-grants-plan.md`, Р1 и Р3; ADR 0171).
--
-- ЧТО ЗДЕСЬ ПРОИСХОДИТ. Две колонки подписи, инвариант их парности и частичный индекс под вопрос
-- «что ждёт визы». Данные файл не меняет: у всех существующих заявок виза пуста, и это её законное
-- состояние — прошлое модуля подписью не переписывается (см. ниже).
--
-- ОТКУДА НОМЕР. `ls apps/api/drizzle` перед созданием файла (08.09.2026): последняя миграция в
-- дереве — `0283_waste_ticket_proposals_issued_on_raw.sql`. Свободны 0284 и 0285, взяты оба: этот
-- файл — схема, соседний — каталог полномочий. Разными файлами, потому что отвечают на разные
-- вопросы и откатываются порознь.
--
-- ПОЧЕМУ НЕТ CHECK «В РАБОТЕ ⇒ ЗАВИЗИРОВАНА». Соблазн велик: барьер входа в работу — главное, ради
-- чего виза заводится, и держать его базой надёжнее, чем сервером. Не годится он по причине,
-- которую видно только на живых данных: у модуля есть аренды в `confirmed` и `done`, взятые в
-- работу до появления подписи, — условие упало бы на первой такой строке в момент наката. Задним
-- числом подписать их некому: виза это решение человека, а не пометка миграции. Барьер поэтому
-- держит сервер (`mechTransitionBlocker`, `packages/contracts/src/mech-requests.ts`) — тот же
-- выбор и та же причина, что у `vehicle_requests`, где инварианта визы в схеме тоже нет.
--
-- ЧЕГО ФАЙЛ НЕ ДЕЛАЕТ. Не трогает права: `mechRequests.approve` живёт в словаре кода, а его
-- появление в наборах каталога — соседняя миграция 0285. Не заводит цикл продления: он приезжает
-- отдельным этапом (Э3 плана) со своей таблицей.
--
-- ОБРАТИМОСТЬ: снятие обеих колонок вместе с индексом и проверкой.
--
--   DROP INDEX IF EXISTS mech_requests_unapproved_idx;
--   ALTER TABLE mech_requests
--     DROP CONSTRAINT IF EXISTS mech_requests_approval_check,
--     DROP COLUMN IF EXISTS approved_at,
--     DROP COLUMN IF EXISTS approved_by;
--
-- Откат теряет проставленные подписи — других носителей у них нет, кроме журнала аудита
-- (`mech_request.approve`), поэтому откатывать стоит только сразу после выката.

ALTER TABLE mech_requests
  ADD COLUMN approved_by uuid REFERENCES users (id) ON DELETE RESTRICT,
  ADD COLUMN approved_at timestamptz;

-- Виза целиком или её нет: «подписал никто в 14:20» и «подписал Иванов неизвестно когда» —
-- одинаково бессмысленные строки, и различать их потом будет нечем.
ALTER TABLE mech_requests
  ADD CONSTRAINT mech_requests_approval_check
  CHECK ((approved_by IS NULL) = (approved_at IS NULL));

-- «Что ждёт визы» — вопрос, с которого начинает день ответственный площадки, и отбор фильтра
-- `approved=false`. Частичный: подписанных заявок со временем становится большинство, а индекс
-- отвечает ровно про неподписанные и живые.
CREATE INDEX mech_requests_unapproved_idx
  ON mech_requests (created_at DESC)
  WHERE approved_at IS NULL AND deleted_at IS NULL;
