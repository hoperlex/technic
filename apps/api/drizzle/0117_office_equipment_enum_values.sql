-- Значения перечислений для визы отдела ИТ (план `docs/office-equipment-upgrade-plan.md`, Р51, Р54).
--
-- Отдельной миграцией и без использования значений в ней самой: раннер применяет файл целиком в
-- одной транзакции (`apps/api/src/db/migration-journal.ts`), а PostgreSQL не разрешает
-- пользоваться новым значением enum до её фиксации. Тот же приём — в миграциях 0054, 0065, 0103,
-- 0114.
--
-- `AFTER 'new'` — не косметика: список заявок сортируется по колонке статуса, а порядок сортировки
-- у enum задаётся порядком объявления значений. Без `AFTER` «Согласована ИТ» встала бы в конец,
-- после «Отменена», и сортировка по статусу показывала бы цикл в неверном порядке.
ALTER TYPE service_request_status ADD VALUE IF NOT EXISTS 'it_approved' AFTER 'new';

-- Вторая надстройка роли (ADR 0086): «Согласование ИТ». Порядок значений здесь ни на что не
-- влияет — надстройки показываются по своему словарю подписей, а не по порядку типа.
ALTER TYPE role_addon ADD VALUE IF NOT EXISTS 'office_equipment_it_approver';

