-- Вид операции коррекции `weekly`: проведение недельной заявки на просроченную неделю.
-- Решение — ADR 0101 (`docs/adr/0101-backdated-correction.md`) в применении к недельной заявке
-- (ADR 0085, `docs/weekly-vehicle-request-plan.md` §8).
--
-- Неделя, которая уже началась или прошла, до сих пор была закрыта наглухо: заявку на неё нельзя
-- было ни завести, ни подать, ни завизировать (`weeklyWeekBlocker`). Это оказалось той же дырой,
-- что и запрет прошлого у дат заявок до ADR 0101: техника неделю отработала, документа-основания
-- у продления нет, и площадка либо просит продлить сроки мимо портала, либо оформляет заявку
-- «сегодняшней неделей», в которой написано не то, что было. Теперь такая неделя открывается
-- правом `waybills.correct` — с причиной, ключом операции и строкой в журнале коррекций.
--
-- Почему вид свой, а не `esm2`. У операции `esm2` предмет — бумага одной заявки: сменили машину,
-- переоформили её листы. Проведение недели одним решением двигает сроки целого состава, порождает
-- заказы с датой начала в прошлом и переоформляет листы сразу нескольких заказов. Свести их к
-- одному слову значило бы получить журнал, в котором «что делали задним числом» отвечается
-- одинаково на два разных события, а фильтр вида (Р28 ADR 0101) перестал бы что-либо отбирать.
--
-- Почему CHECK, а не enum, объяснено там же, где заведена колонка (миграция 0129): список входов
-- заднего числа прирастает этапами, реестр значений живёт в контрактах, а CHECK держит нижнюю
-- границу от опечатки. Цена этого выбора — вот такая миграция на каждый новый вид, и она дешевле
-- `ALTER TYPE`, который нельзя использовать в той же транзакции.
--
-- Аддитивная миграция: ограничение только расширяется, существующие строки под него подходят
-- тождественно (прежние шесть значений остались на месте), данные не меняются. Откат кода на
-- предыдущую версию схему не ломает — прежний код нового значения не пишет. Протокол выката
-- необратимых миграций (`docs/schema-cutover-protocol.md`) здесь не нужен.

ALTER TABLE waybill_corrections DROP CONSTRAINT waybill_corrections_kind_check;
ALTER TABLE waybill_corrections ADD CONSTRAINT waybill_corrections_kind_check
  CHECK (kind IN ('route', 'transfer', 'esm2', 'cancel', 'issue', 'request_date', 'weekly'));
