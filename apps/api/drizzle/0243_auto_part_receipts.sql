-- Чеки на автозапчасти (план `docs/auto-part-receipts-plan.md`, §5 «Модель данных», миграция A;
-- решения Р1а, Р6, Р8—Р13, Р20). Выпуск 1 — только схема; контракты, маршруты, права и портал едут
-- той же волной отдельными файлами.
--
-- ЗАЧЕМ. Склад гаража (`0187`, `0188`) отвечает на вопрос «сколько лежит», а спрашивают у портала
-- другое и каждый месяц — «сколько потратили на эту машину». Сегодня ответа нет ни у кого: покупка
-- живёт чеком в папке, остаток ведут по памяти, а «Запчасти, ₽» во вкладке техники брать неоткуда.
-- Чек отвечает на этот вопрос напрямую и без склада: бумагу заносят как бумагу, строку относят к
-- машине либо оставляют неотнесённой (Р8), суммы складываются запросом.
--
-- ЧТО ЗАВОДИТСЯ: шапка чека, его строки, связь со сканами и десятая ветвь в `file_is_linked(uuid)`.
-- Ни триггеров, ни функций правил написания здесь нет, и это отличие от склада намеренное (Р7):
-- строки чека вводятся ДОСЛОВНО, как напечатаны, справочника у них не будет вовсе, а значит нечего
-- нормализовать и не за чем следить. Ссылки на `auto_parts` тоже нет: складская карточка и позиция
-- чека — разные вещи, и связать их значило бы потребовать завести номенклатуру до ввода бумаги.
--
-- ЧЕГО ЗДЕСЬ НЕТ. Ни одной строки данных и ни одного касания склада: этим выпуском он работает
-- по-прежнему (Р22). Замораживает его выпуск 2, и схему тот не трогает ничем — это требование, а не
-- совпадение (Р26): миграция, накатанная до старта, лишила бы барьер выпуска дешёвого отката.
-- Права (`autoParts.stock`) чистит выкат 3 отдельной миграцией, когда заморозка уже развёрнута.
--
-- ОТКУДА НОМЕР. Проверено `ls apps/api/drizzle` непосредственно перед созданием файла
-- (02.09.2026): последняя миграция в дереве — `0242_releases_contractor_mail.sql`. Номера миграций
-- и ADR идут параллельными потоками, поэтому сверка сделана заново, а не взята из шапки плана: пока
-- писались его редакции, соседняя работа заняла несколько номеров, и ориентир `0243` в §5 совпал с
-- деревом случайно, а не по договорённости.
--
-- ОБРАТИМОСТЬ. Миграция аддитивная: три новые таблицы и замена тела одной функции. Существующие
-- данные не читаются и не меняются, блокировок первой строкой поэтому нет; протокол выката
-- необратимых миграций (`docs/schema-cutover-protocol.md`) к ней не применяется. Обратной миграции
-- репозиторий не держит (`migrate.ts` только накатывает); при необходимости объекты снимаются
-- вручную в порядке, обратном заведению, а функция возвращается перезаливкой тела из `0238`.

-- ── 1. Шапка чека ──
--
-- ПОЧЕМУ ЗДЕСЬ НЕТ КОЛОНКИ ИТОГА (Р11). Сумма чека в портале — это `Σ amount` его строк, и считает
-- её запрос. Итог, переписанный с бумаги отдельным полем, разошёлся бы со строками в первый же день
-- — опечаткой, недовведённой позицией, скидкой, напечатанной итогом, — и дальше в каждом отчёте
-- пришлось бы заново решать, какая из двух сумм правда. Хранимый итог, согласованный со строками
-- триггером, стоил бы складского контура ради числа, которое и так складывается. Следствие названо
-- честно: позиции, которых в портал не заносят (канцелярия, кофе), в итог портала не попадают.
CREATE TABLE auto_part_receipts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Дата документа — ХОЗЯЙСТВЕННАЯ (Р13): по ней считаются все суммы, фильтры и периоды. Служебное
  -- «когда внесли в портал» живёт в `created_at` и на расчёт не влияет никогда. Задним числом
  -- законно без ограничений; будущую дату отбивает маршрут с именем поля (ADR 0094), а не схема:
  -- «завтра» — это ошибка ввода, о которой человеку надо сказать словами, а не кодом нарушения.
  purchased_on date NOT NULL,
  -- Продавец дословно (Р7). Справочника магазинов в постановке нет, и заводить его ради чека
  -- значило бы посадить механика заполнять карточку контрагента перед вводом бумаги.
  seller_name text NOT NULL DEFAULT '',
  -- Номер чека ОБЯЗАТЕЛЕН (Р1а): чек — документ, номер есть у каждого, и пустое поле означало бы,
  -- что бумагу в руках не держали. Уникальности у него нет — это решение, а не пропуск: номер
  -- выдаёт продавец, продавец записан свободным текстом, и два чека «0001» из разных магазинов —
  -- обычное дело. Уникальность по паре «продавец + номер» держалась бы на дословном совпадении
  -- названия («ООО Автодеталь» и «Автодеталь ООО») и отбивала бы честный ввод, не поймав двойника.
  -- Сквозного номера портала у чека тоже не появляется, в отличие от заявок и талонов: свой номер
  -- на бумаге уже есть, и второй рядом читался бы как расхождение документов.
  document_number text NOT NULL,
  note text NOT NULL DEFAULT '',
  -- Оптимистическая блокировка (Р12): форма отдаёт чек целиком — шапку, строки и сканы, — как
  -- форма акта ТО, и версия здесь единственное, чем две одновременные правки различимы.
  version integer NOT NULL DEFAULT 0,
  -- ── Пометка на удаление (Р12) ──
  --
  -- Удаляет чек только администратор; остальные ПРОСЯТ. Просьба — состояние документа, а не
  -- сообщение о нём, поэтому живёт тремя колонками в самой строке, а не в переписке: помеченный чек
  -- из ленты не исчезает и суммы считать не перестаёт. `NULL` — пометки нет.
  deletion_requested_at timestamptz,
  -- `RESTRICT`, как у остальных авторов записи: «кто попросил» обязано пережить увольнение.
  deletion_requested_by uuid REFERENCES users (id) ON DELETE RESTRICT,
  -- Причина. Пустая строка, а не `NULL`, у непомеченного: поле заполнено всегда, иначе второе
  -- представление «причины нет» пришлось бы отличать в каждом чтении.
  deletion_reason text NOT NULL DEFAULT '',
  -- `RESTRICT` у обоих: «кто внёс» и «кто правил» — реквизиты документа, и увольнение человека их
  -- не отменяет. `updated_by` пуст у чека, который ещё никто не правил.
  created_by uuid NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  updated_by uuid REFERENCES users (id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  -- Пустота меряется `btrim`, а не длиной: номер из одних пробелов прошёл бы `NOT NULL` насквозь и
  -- встал бы в карточку строкой, неотличимой на экране от пустой.
  CONSTRAINT auto_part_receipts_document_number_check CHECK (btrim(document_number) <> ''),
  CONSTRAINT auto_part_receipts_version_check CHECK (version >= 0),
  -- Пара CHECK'ов дословно та же, что у аннулирования акта ТО (`vehicle_maintenance`, 0188:
  -- `..._voided_pair_check` и `..._void_reason_check`), и по той же причине: «помечен, но
  -- неизвестно кем» и «помечен молча, без причины» — не состояния документа, а дыры в записи о
  -- нём. Спросить с первой было бы некого, а вторая через год не даст ответить, почему чек
  -- собирались удалить.
  CONSTRAINT auto_part_receipts_deletion_pair_check
    CHECK ((deletion_requested_at IS NULL) = (deletion_requested_by IS NULL)),
  -- Причина есть ровно у помеченного: пустая у него — «попросили и не сказали зачем», а непустая у
  -- непомеченного — текст, который никто не прочитает и который примут за признак пометки.
  CONSTRAINT auto_part_receipts_deletion_reason_check
    CHECK ((deletion_requested_at IS NULL AND btrim(deletion_reason) = '')
        OR (deletion_requested_at IS NOT NULL AND btrim(deletion_reason) <> ''))
);

COMMENT ON TABLE auto_part_receipts IS
  'Чек на автозапчасти — шапка документа (docs/auto-part-receipts-plan.md §5, миграция A): дата '
  'покупки, продавец и обязательный номер с бумаги. Колонки итога нет намеренно (Р11): сумма чека '
  'считается как сумма amount его строк. Удаляет чек администратор, остальные помечают тройкой '
  'deletion_* (Р12).';

-- Порядок ленты. Три колонки, а не одна дата: две покупки одного дня ключом `purchased_on`
-- неразличимы, и «последний чек» зависел бы от порядка чтения строк. `id` замыкает порядок —
-- `created_at` у двух записей одной транзакции совпадает (это время её начала), и без него ничья
-- осталась бы неразрешённой. Приём тот же, что у истории ТО (`vehicle_maintenance_vehicle_idx`).
CREATE INDEX auto_part_receipts_feed_idx
  ON auto_part_receipts (purchased_on DESC, created_at DESC, id DESC);

-- Очередь администратора — отдельный вопрос к таблице («что просят удалить»), и отвечать на него
-- полным сканом ленты незачем. Индекс ЧАСТИЧНЫЙ: помеченных единицы, непомеченных — вся история
-- покупок, и класть её в индекс, который читают только ради помеченных, значит платить за неё
-- на каждой вставке чека.
CREATE INDEX auto_part_receipts_deletion_idx
  ON auto_part_receipts (deletion_requested_at)
  WHERE deletion_requested_at IS NOT NULL;

-- ── 2. Строка чека ──
--
-- ЧТО ХРАНИТСЯ, А ЧТО СЧИТАЕТСЯ (Р9). Хранится СУММА строки, цена за единицу — производная и
-- показывается справочно. Обратный порядок (хранить цену, умножать на количество) отвергнут даже
-- при целом количестве: в чеке напечатана сумма, а цена бывает уже округлённой, и «3 × 416,67 =
-- 1 250,01» расходилось бы с бумагой на копейку в каждом разговоре о цифрах.
CREATE TABLE auto_part_receipt_lines (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- `CASCADE`: строка — часть документа, а не его история. Отдельно от чека она не значит ничего,
  -- и держать её `RESTRICT`'ом значило бы запретить администратору удалить чек, не разобрав его
  -- руками по строкам.
  receipt_id uuid NOT NULL REFERENCES auto_part_receipts (id) ON DELETE CASCADE,
  -- Порядок строк как на бумаге; проставляет сервер по индексу массива формы (§6 плана). Хранится,
  -- а не выводится сортировкой по `created_at`: правка отдаёт чек целиком, все строки
  -- пересоздаются одной транзакцией, и время у них общее — порядок бумаги восстановить было бы
  -- нечем. `smallint` осознанно: строк в чеке десятки, и тип здесь заодно верхняя граница здравого
  -- смысла.
  seq smallint NOT NULL,
  -- Машина, на которую отнесли покупку. NULL — законное «не отнесено» (Р8): общий инструмент,
  -- расходники гаража, позиция, которую механик не стал разбирать. Карточка чека показывает такие
  -- строки отдельным итогом, и сумма по машинам законно МЕНЬШЕ суммы чека. Это же работает на
  -- будущее распознавание: прочитанный чек ложится в портал целиком и ничего не выдумывает, а
  -- разносит строки по машинам человек глазами.
  --
  -- `RESTRICT`, как у всех учётных ссылок на технику: строка чека — документ, и машину из-под неё
  -- не убирают выводом из парка.
  vehicle_id uuid REFERENCES vehicles (id) ON DELETE RESTRICT,
  -- Наименование ДОСЛОВНО с бумаги (Р7): ни справочника, ни ключа написания, ни ссылки на складскую
  -- позицию. Двойники здесь законны — два чека на «тот же» фильтр это две разные покупки.
  name text NOT NULL,
  -- Количество ЦЕЛОЕ и строго положительное (Р10, ответ заказчика от 02.09.2026) — то же правило,
  -- что у склада (ADR 0134 Р9): канистры и литры здесь считают штуками и упаковками, а не долями.
  -- Цена решения названа честно: «масло, 4,75 л» дословно не переписать — механик заносит одну
  -- упаковку, перенеся объём в наименование, и в чеке чаще напечатано ровно так. Дробное
  -- количество отвергнуто вместе с этим ответом: при целом сумма строки остаётся единственным
  -- местом, где живут копейки.
  quantity integer NOT NULL,
  -- Единица текстом с умолчанием «шт»: она подписывает число, а не участвует в счёте, и набор
  -- единиц заранее неизвестен.
  unit text NOT NULL DEFAULT 'шт',
  -- Сумма строки. Неотрицательная, и ноль ЗАКОНЕН (Р9): акция, замена по гарантии, «в подарок».
  amount numeric(14, 2) NOT NULL,
  note text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  -- Порядок уникален внутри чека. Ключ читается слева направо и потому отвечает ещё и на вопрос
  -- «строки этого чека» — отдельного индекса по `receipt_id` (в том числе под `CASCADE`) не нужно.
  CONSTRAINT auto_part_receipt_lines_seq_unique UNIQUE (receipt_id, seq),
  CONSTRAINT auto_part_receipt_lines_seq_check CHECK (seq > 0),
  -- Пустота имени меряется `btrim`, а не длиной: имя из одних пробелов встало бы в чек строкой,
  -- неотличимой на экране от пустой, и прошло бы `NOT NULL` насквозь.
  CONSTRAINT auto_part_receipt_lines_name_not_blank_check CHECK (btrim(name) <> ''),
  -- Ноль штук — это отсутствие строки, а не строка; отрицательное количество не значит ничего
  -- вовсе (возврат — это правка чека, а не минус в нём).
  CONSTRAINT auto_part_receipt_lines_quantity_check CHECK (quantity > 0),
  CONSTRAINT auto_part_receipt_lines_unit_not_blank_check CHECK (btrim(unit) <> ''),
  CONSTRAINT auto_part_receipt_lines_amount_check CHECK (amount >= 0)
);

COMMENT ON TABLE auto_part_receipt_lines IS
  'Строка чека на автозапчасти (docs/auto-part-receipts-plan.md §5): наименование дословно с '
  'бумаги, целое количество (Р10), сумма строки (Р9) и необязательная машина — NULL означает '
  '«не отнесено» (Р8). Порядок задаёт seq, уникальный внутри чека; связи со справочником '
  'auto_parts нет намеренно (Р7).';

-- Под суммы по машине — колонку «Запчасти, ₽» во вкладке техники, окно «Запчасти машины», блок в
-- карточке — и под сам `RESTRICT` при попытке вывести машину из парка. Индекс ЧАСТИЧНЫЙ:
-- неотнесённые строки на вопрос «что купили этой машине» не отвечают ни одной, и в индексе им
-- делать нечего, а их в чеках заметная доля.
CREATE INDEX auto_part_receipt_lines_vehicle_idx
  ON auto_part_receipt_lines (vehicle_id)
  WHERE vehicle_id IS NOT NULL;

-- ── 3. Сканы чека ──
--
-- По образцу `vehicle_maintenance_files` (0147) и, через него, `vehicle_reading_files` (0132): PK —
-- пара, `UNIQUE (file_id)` — файл живёт максимум в одном месте, `CASCADE` с обеих сторон. Кросс-
-- модульную часть уникальности держит общий файловый сервис, а не эта таблица.
--
-- Правило «без файла чека не существует» (Р6) держит МАРШРУТ, а не схема, и это названо прямо:
-- пустой парой оно не выражается, а триггер ради него навязал бы порядок вставки «сначала файл,
-- потом строки» всем, кто когда-либо будет писать в эти таблицы.
CREATE TABLE auto_part_receipt_files (
  receipt_id uuid NOT NULL REFERENCES auto_part_receipts (id) ON DELETE CASCADE,
  -- `CASCADE` на файл: строка связи без файла не значит ничего. Обратная сторона — удаление самих
  -- записей `files` при снятии скана и при удалении чека — работа маршрутов: забытый путь оставит
  -- в `files` живую и ничью строку.
  file_id uuid NOT NULL REFERENCES files (id) ON DELETE CASCADE,
  added_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (receipt_id, file_id)
);

CREATE UNIQUE INDEX auto_part_receipt_files_file_unique ON auto_part_receipt_files (file_id);

COMMENT ON TABLE auto_part_receipt_files IS
  'Скан чека на автозапчасти (docs/auto-part-receipts-plan.md Р6, Р20): связь «чек — файл», один '
  'файл максимум в одном месте. Названа в file_is_linked этой же миграцией — иначе фоновая уборка '
  'сочла бы подшитый скан сиротой. Открывается веткой visibleReceipt файлового API под '
  'garage.read (Р20).';

-- ── 4. Десятая ветвь `file_is_linked(uuid)` ──
--
-- Модуль, о котором не знает `file_is_linked(uuid)`, отдаёт свои вложения загрузившему их человеку
-- БЕССРОЧНО: `decideFileAccess` считает такой файл ничьим, а ничей файл доступен автору загрузки.
-- Фоновая уборка при этом считает его сиротой и сносит из хранилища. Однажды это уже случилось —
-- миграция 0225 чинила ровно это у сканов аудита талонов.
--
-- `CREATE OR REPLACE` повторяет полный актуальный перечень из `0238` (последней версии функции)
-- плюс новую ветку. Тело SQL-функции заменяется ЦЕЛИКОМ: пропущенная прежняя ветка молча сняла бы
-- защиту с чужого модуля — сегодня в первую очередь с механизации, чьи вложения приехали как раз
-- `0238`, — и заметили бы это не по ошибке, а по чужому файлу, открывшемуся постороннему. Перечень
-- взят из `0238`, а не из плана и не из `0225`: план описывает намерение, а функция — то, что
-- лежит в базе.
CREATE OR REPLACE FUNCTION file_is_linked(p_file_id uuid) RETURNS boolean
  LANGUAGE sql STABLE PARALLEL SAFE
AS $$
  SELECT
    -- Вложения и талоны заявок на вывоз мусора (ADR 0024).
    EXISTS (SELECT 1 FROM request_files WHERE file_id = p_file_id)
    -- Вложения заявок на технику.
    OR EXISTS (SELECT 1 FROM vehicle_request_files WHERE file_id = p_file_id)
    -- Сканы, подшитые к путевому листу (миграция 0087).
    OR EXISTS (SELECT 1 FROM waybill_files WHERE file_id = p_file_id)
    -- Документы заявок на обслуживание оргтехники (ADR 0084, миграция 0105).
    OR EXISTS (SELECT 1 FROM service_request_files WHERE file_id = p_file_id)
    -- Фотографии показаний техники (миграция 0132).
    OR EXISTS (SELECT 1 FROM vehicle_reading_files WHERE file_id = p_file_id)
    -- Сканы документов работника (миграция 0019).
    OR EXISTS (SELECT 1 FROM person_credential_files WHERE file_id = p_file_id)
    -- Сканы актов ТО (миграция 0147).
    OR EXISTS (SELECT 1 FROM vehicle_maintenance_files WHERE file_id = p_file_id)
    -- Исходный скан наблюдения качества распознавания (ADR 0137, миграция 0210).
    OR EXISTS (SELECT 1 FROM waste_ticket_field_events WHERE file_id = p_file_id)
    -- Вложения заявок на аренду малой механизации (миграция 0238).
    OR EXISTS (SELECT 1 FROM mech_request_files WHERE file_id = p_file_id)
    -- Сканы чеков на автозапчасти (эта миграция).
    OR EXISTS (SELECT 1 FROM auto_part_receipt_files WHERE file_id = p_file_id)
$$;

