-- Переход режима модуля истории назначения больше не требует автора (ADR 0198).
--
-- ЧТО МЕНЯЕТСЯ. Колонка `actor_user_id` журнала переходов перестаёт быть обязательной. Всё
-- остальное в журнале остаётся как было: время, обе стороны обоих режимов, сборка, версия
-- алгоритма, поколение сверки, аттестация и причина. То есть «чем и когда разрешён переход»
-- журнал отвечает по-прежнему; исчезает только ответ на «кем».
--
-- ПОЧЕМУ ЭТО ЗАКОННО. Автора здесь называл человек аргументом командной строки, а не портал
-- сессией: команда ходит в базу своими кредами и того, кто её запустил, не знает. Значение,
-- которое вводят руками, доказательством не является — его нельзя ни проверить, ни оспорить, и
-- ради него операция требовала существующей учётки в момент, когда портал закрыт целиком.
--
-- УЖЕ ЗАПИСАННОЕ НЕ ТРОГАЕТСЯ: прежние переходы сохраняют своего автора и ссылку на учётку с
-- ON DELETE RESTRICT — снимать её у истории нечестно, она была записана по действовавшему тогда
-- правилу.
ALTER TABLE assignment_periods_mode_transitions
  ALTER COLUMN actor_user_id DROP NOT NULL;

COMMENT ON COLUMN assignment_periods_mode_transitions.actor_user_id IS
  'Кто провёл переход, если назвал себя сам (--actor). NULL — переход проведён командой площадки без указания человека (ADR 0198).';
