-- Признак «файл привязан хоть к чему-нибудь» переезжает в БД: функция `file_is_linked(uuid)`.
-- План — `docs/driver-portal-plan.md`, §4 (решение Р18) и §7 (решение Р34).
--
-- Перечень таблиц привязки в портале один, а копий этого перечня в коде было две — намеренно, и
-- уже это требовало дисциплины: `linkedFileIds` отвечает на вопрос «можно ли привязать» (пакетно,
-- внутри транзакции привязки), `isFileLinked` — на вопрос «привязан ли уже» (поштучно, в решении о
-- доступе и в удалении файла). Разъезд этих двух списков в портале уже случался: `waybill_files`
-- была заведена в первом и забыта во втором, из-за чего скан, подшитый к путевому листу, оставался
-- виден загрузившему по прямой ссылке бессрочно и удалялся им в обход журнала.
--
-- Кабинет водителя добавляет к перечню пятую таблицу (`vehicle_reading_files` — фотографии
-- приборной панели) и, что важнее, ТРЕТЬЕГО читателя: уборку файлов в воркере. Воркер отбирает
-- файлы, не привязанные ни к чему, и ставит задачу на физическое удаление объекта из S3. Цена
-- забытой строки в первых двух копиях — лишний доступ или неудалённая строка; цена той же ошибки в
-- третьей — безвозвратно удалённый документ: акт выполненных работ, скан бланка строгой
-- отчётности, фотография показаний. Держать три списка в согласии комментарием «пополнять вместе»
-- нельзя — новый модуль с вложениями пишет тот, кто про воркер не знает вовсе.
--
-- Поэтому источник правды становится один и живёт там же, где сами таблицы: сервис, пакетная
-- проверка привязки и уборка зовут одну функцию. Новая связь заводится ровно в одном месте — здесь,
-- отдельной строкой `OR EXISTS`, в той же миграции, что создаёт саму таблицу связи.
--
-- Зависимость по порядку: функция ссылается на `vehicle_reading_files`, поэтому эта миграция
-- катится ПОСЛЕ той, что заводит таблицы модуля показаний (тело SQL-функции разбирается при
-- создании, и отсутствие таблицы обрывает миграцию явной ошибкой, а не тихо — это и нужно).
--
-- Обратимость. Миграция ничего не переписывает и не создаёт объектов, от которых зависят данные:
-- добавляется одна функция. Откат кода на предыдущую версию её просто перестаёт звать — прежние
-- запросы по таблицам продолжают работать. Обратной миграции репозиторий не держит (`migrate.ts`
-- только накатывает); при необходимости функция снимается `DROP FUNCTION file_is_linked(uuid)`.
--
-- Свойства функции.
--   * `STABLE`, а не `IMMUTABLE`: результат меняется вместе с содержимым таблиц связей, но внутри
--     одного запроса он постоянен — планировщику этого достаточно, чтобы звать её один раз на
--     строку, а `IMMUTABLE` разрешило бы кэширование между запросами и соврало бы уборке.
--   * `LANGUAGE sql`: тело встраивается в вызывающий запрос, и `NOT file_is_linked(id)` в WHERE
--     уборки превращается в обычные полуджойны по индексам `*_file_*` (у всех пяти таблиц связи
--     `file_id` покрыт индексом или уникальным ключом), а не в шесть подзапросов на строку.
--   * `EXISTS` вместо счёта: первая же найденная связь останавливает перебор.
--   * Ветки перечислены `OR`: порядок значения не имеет, но каждая подписана модулем — забыть,
--     что именно закрывает строка, здесь дороже, чем в обычном запросе.

CREATE FUNCTION file_is_linked(p_file_id uuid) RETURNS boolean
  LANGUAGE sql STABLE PARALLEL SAFE
AS $$
  SELECT
    -- Вложения и талоны заявок на вывоз мусора (ADR 0024): талон лежит там же, kind='ticket'.
    EXISTS (SELECT 1 FROM request_files WHERE file_id = p_file_id)
    -- Вложения заявок на технику.
    OR EXISTS (SELECT 1 FROM vehicle_request_files WHERE file_id = p_file_id)
    -- Сканы, подшитые к путевому листу (миграция 0087) — та самая забытая копией таблица.
    OR EXISTS (SELECT 1 FROM waybill_files WHERE file_id = p_file_id)
    -- Документы заявок на обслуживание оргтехники (ADR 0084, миграция 0105).
    OR EXISTS (SELECT 1 FROM service_request_files WHERE file_id = p_file_id)
    -- Фотографии показаний техники: приборная панель, чеки заправки (Р18, Р34).
    OR EXISTS (SELECT 1 FROM vehicle_reading_files WHERE file_id = p_file_id)
    -- Сканы документов работника (миграция 0019). Строк в таблице пока не бывает — загрузки
    -- сканов в портале нет, — и обе прежние копии перечня о ней не знали. Внесена именно потому,
    -- что заведена: перечень собирают один раз и по внешним ключам к `files`, а не по тому, какие
    -- ручки уже написаны. Появись загрузка сканов при неполном перечне — второй проход уборки
    -- счёл бы удостоверения сиротами и снёс их из хранилища через неделю после загрузки.
    OR EXISTS (SELECT 1 FROM person_credential_files WHERE file_id = p_file_id)
$$;

COMMENT ON FUNCTION file_is_linked(uuid) IS
  'Файл привязан хоть к одной сущности портала. Единственный источник правды о перечне таблиц '
  'привязки: её зовут проверка привязываемости, решение о доступе к файлу и уборка файлов в '
  'воркере. Новая таблица связи добавляется сюда в той же миграции, что создаёт саму связь — '
  'иначе уборка сочтёт подшитый документ сиротой и удалит объект из хранилища.';
