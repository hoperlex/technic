-- Право «видеть деньги заявки» в двух наборах модуля «Орг.техника» (план
-- `docs/office-equipment-requester-card-plan.md`, Р1 и Р2; ADR 0160; выпуск A, этап Э5).
--
-- ОТКУДА НОМЕР. Проверено `ls apps/api/drizzle` непосредственно перед созданием файла (03.09.2026):
-- последняя миграция в дереве — `0258_module_mail_event_settings.sql` соседнего потока (почтовое
-- расширение модуля). Свободны 0259 и 0260; 0259 достался каталогу, 0260 — записи выпуска той же
-- волны. Порядок между ними значения не имеет — таблицы у них разные, — но записан он именно так:
-- сперва право, потом строка ленты, которая о нём рассказывает.
--
-- ЗАЧЕМ. Карточка заявки сегодня одинакова для всех, кто её видит: заказчик открывает «Объём
-- работ» и читает строки сметы с ценами, итог, скидку и факт по акту, а по прямой ссылке
-- скачивает счёт. Предмет его заявки — «не работает принтер», а не «сколько это стоит»: суммы
-- модуля — отношения компании с подрядчиком. Проекция карточки, списка, истории и файлов по
-- аудитории приезжает кодом того же выпуска A, а кто остаётся с деньгами — отвечает право
-- `serviceRequests.finance`.
--
-- ПОЧЕМУ ПРАВОМ, А НЕ ПРОВЕРКОЙ НАБОРА ПО МЕСТУ. Ровно по той причине, которая записана в миграции
-- 0231: набор отвечает на вопрос «кто», право — на «что можно». Условие «у человека надстройка ИТ»,
-- написанное в маршруте, невидимо витрине прав, не снимается составом набора и не выдаётся
-- поимённо. Право же видно в сетке «Права», выдаётся и отбирается тем же способом, что остальные.
--
-- ПОЧЕМУ ПОЛОЖИТЕЛЬНЫМ ПРАВОМ, А НЕ ОТСУТСТВИЕМ ДРУГИХ. Правило «денег не видит тот, у кого нет ни
-- одного из прав цикла» ломается молча: первое же новое право модуля — а их за полгода прибавилось
-- четыре — открыло бы суммы тому, кому их не открывали, и ни один тест этого не заметил бы, потому
-- что ошибка была бы в НЕперечисленном. Здесь же дверь открывает строка, которую видно.
--
-- ПОЧЕМУ ЭТИ ДВА НАБОРА. «Ведение» — потому что оно согласует объём работ и принимает работу:
-- деньги и есть его предмет. «ИТ-служба» — потому что она решает «чинить или менять» и ведёт
-- инхаус-ремонт. Сервисная компания получает то же право типом контрагента
-- (`COUNTERPARTY_TYPE_PERMISSIONS.service`, контракты) — это её собственная смета и её счёт;
-- администратор имеет его по построению. Наблюдателю право не выдаётся решением заказчика от
-- 03.09.2026: роль заведена ради общей картины по компании, а не ради доступа к расходам.
--
-- ПОЧЕМУ ЕГО НЕТ У ВНУТРЕННЕГО ИСПОЛНИТЕЛЯ. Набора `office_equipment_executor` в дереве нет вовсе
-- (его заводит `docs/office-equipment-access-profiles-plan.md`), но решение записано заранее и не
-- изменится: класть `.finance` в него нельзя. Базовая роль заказчика тогда показала бы держателю
-- суммы всех заявок его площадки и отдела, а не тех, на которые он назначен. Деньги назначенной
-- заявки открывает вторая ветка аудитории, к правам отношения не имеющая, — «назначен поимённо
-- плюс `serviceRequests.execute`» (Р1); она работает без всякого набора.
--
-- ТРЕБОВАНИЕ `serviceRequests.read` (`PERMISSION_REQUIRES` в `packages/contracts/src/grants.ts`)
-- выполняется у держателей обоих наборов любой из трёх базовых ролей (`ROLE_ADDON_BASE_ROLES`:
-- штаб, площадка, отдел) — чтение заявок есть у каждой как у заказчика. Барьер выдачи поэтому не
-- начнёт отклонять то, что вчера выдавалось. Требование объявлено потому, что право видеть деньги
-- заявки, выданное тому, кто заявок не видит, не открывает ни одной двери и обещает то, чего нет.
--
-- ЧЕГО ЗДЕСЬ НЕТ. Ни одной строки `user_grants`: миграция правит каталог — состав наборов и их
-- описания, — а кому набор достанется, решает администратор портала поимённо, с автором, временем и
-- записью в реестре выдач (ADR 0106). Держатели у обоих наборов уже есть, и права им прибавляются
-- ровно на одно объявленное здесь — это и есть весь эффект наката на живые учётки. Новых наборов
-- (`office_equipment_requester`, `office_equipment_executor`) и новых ролей миграция тоже не
-- заводит: они предмет плана профилей, и ждать его ядру нельзя — без права держатели «Ведения» и
-- ИТ-службы потеряли бы суммы в тот же день, когда выкатится проекция.
--
-- КОГДА ПРИЕДЕТ МИГРАЦИЯ D СВОДНОГО ПЛАНА ПРОФИЛЕЙ
-- (`docs/office-equipment-access-profiles-plan.md`), она перепишет составы наборов модуля целиком
-- и заденет эти же два. Два требования к ней, и оба обязательны. Первое: её вставки
-- `serviceRequests.finance` в `office_equipment_operator` и `office_equipment_it_approver` обязаны
-- быть `ON CONFLICT DO NOTHING` — строки к тому дню уже стоят, и обычный `INSERT` уронит накат
-- дублем первичного ключа `grant_permissions_pkey`. Второе: считать это право «новым» в своём
-- блоке-карауле нельзя — оно приехало здесь, и счёт прав в обоих наборах D обязана вести от
-- девяти и семи, объявленных ниже, а не от восьми и шести, которые стояли до этой миграции. Обе
-- ошибки дают громкий отказ прямо на накате, и это лучший исход; хуже был бы караул, который
-- сойдётся по числу потому, что D заодно что-то убрала.
--
-- КОДЫ НАБОРОВ НЕ МЕНЯЮТСЯ НИ ПРИ КАКИХ УСЛОВИЯХ. По коду набор находят миграции каталога, журнал
-- действий, реестр выдач и таблица сквозной области (`GRANT_MODULE_WIDE_SCOPE`):
-- `UPDATE grants SET code = ...` не «переименовывает набор», а отвязывает его от кода. Правятся
-- название, описание и состав — здесь описания и состав.
--
-- ГДЕ ЖИВЁТ ОБЪЯВЛЕННЫЙ СОСТАВ. У обоих наборов — в `ROLE_ADDON_PERMISSIONS`
-- (`packages/contracts/src/permissions.ts`): надстройка ADR 0086 остаётся живым источником доступа
-- до шага 1e реформы, и набор в базе — её отражение. Правка надстроек едет той же волной, что эта
-- миграция, и это обязательное условие: иначе один и тот же человек получил бы разные права в
-- зависимости от того, пришёл к нему доступ надстройкой или набором. Обе стороны сверяет страж
-- `apps/api/test/grants-catalog.db.test.ts`.
--
-- СОВМЕСТИМЫЕ РОЛИ НЕ ТРОГАЮТСЯ: у обоих наборов они те же — штаб, площадка, отдел.
--
-- ОБРАТИМОСТЬ. Трогаются две таблицы каталога, схема не меняется; протокол выката необратимых
-- миграций (`docs/schema-cutover-protocol.md`) к ней не применяется. Откат — `DELETE` двух строк
-- состава и прежний текст описаний. Откатывать её в одиночку, оставив выкаченным код проекции,
-- нельзя: «Ведение» и ИТ-служба потеряют суммы, которые видели вчера, — сервер и каталог
-- откатываются согласованной парой.

-- ── 1. Описания наборов ──
--
-- Описание перечисляет, что набор умеет, и потому правится вместе с составом: набор, открывающий
-- новую возможность и молчащий о ней, заставляет администратора угадывать по списку прав. Тем
-- более здесь: после выката видимость сумм становится отличием набора от базовой роли, и не
-- сказать об этом значило бы оставить администратора без единственного объяснения, почему один
-- сотрудник видит в карточке цифры, а другой — нет. Текст переписывается целиком, а не
-- дописывается конкатенацией: `description || '…'` на повторном накате пришил бы фразу второй раз.

UPDATE grants
   SET description = 'Ведёт модуль «Орг.техника» целиком: справочник техники, распределение заявок '
                     'по исполнителям, согласование сметы, приёмку работы, срочность и заморозку. '
                     'Это единственный набор, которым заявку принимают и отменяют из любого '
                     'статуса; ходов исполнителя в нём нет — их открывает назначение. Видит суммы '
                     'и объём работ заявок: строки сметы с ценами, итог, счёт и акт, сумму ремонта '
                     'в истории обслуживания аппарата — заказчику всего этого не видно вовсе. Им '
                     'же ведут плановые закупки расходников: заводят документ для снабжения, '
                     'правят черновик, проводят, закрывают и отменяют. Им же заводят заявку без '
                     'аппарата — на работу, у которой предмета в справочнике нет вовсе. Перечень '
                     'картриджей и остаток на складе правит другой набор — «Оргтехника: '
                     'номенклатура».',
       updated_at = now()
 WHERE code = 'office_equipment_operator';

UPDATE grants
   SET description = 'Решает по смете «чинить или менять» и работает исполнителем: берёт заявку в '
                     'работу, ведёт её, откладывает, подшивает документы и передаёт внешнему '
                     'сервису. Ходы исполнителя доступны только на заявках, где держатель назначен '
                     'поимённо. Видит суммы и объём работ заявок: строки сметы с ценами, итог, '
                     'счёт и акт, сумму ремонта в истории обслуживания аппарата. Заводит заявку '
                     'без аппарата — на работу, у которой предмета в справочнике нет вовсе. Виза '
                     'ИТ и сквозная видимость модуля идут вместе с набором: подписывают по всем '
                     'площадкам сразу.',
       updated_at = now()
 WHERE code = 'office_equipment_it_approver';

-- ── 2. Состав: одно новое право, обоим наборам ──
--
-- Право хранится текстом — справочника прав в базе нет намеренно (`grant_permissions`, миграция
-- 0145): словарь `PERMISSIONS` закрыт и живёт в контрактах. `ON CONFLICT DO NOTHING` делает шаг
-- идемпотентным, а не «на всякий случай»: повторный накат на базу, восстановленную из копии, —
-- обычное дело, и он же — то, чего эта миграция требует от будущей D.

INSERT INTO grant_permissions (grant_id, permission)
SELECT g.id, s.permission
FROM grants g
JOIN (VALUES
  ('office_equipment_operator'   , 'serviceRequests.finance'),
  ('office_equipment_it_approver', 'serviceRequests.finance')
) AS s (code, permission) ON s.code = g.code
ON CONFLICT (grant_id, permission) DO NOTHING;

-- ── 3. Караул: состав в базе равен объявленному ──
--
-- Страж-тест сверяет то же самое, но живёт он в репозитории, а этот блок — в накате: оператор
-- выката увидит расхождение сразу, а не через прогон тестов. Проверяется ровно то, что миграция
-- обещала: оба набора существуют и системны, прав в «Ведении» девять (восемь после миграции 0231
-- плюс деньги заявки), в «ИТ-службе» семь (шесть после неё же плюс они же), и новое право есть в
-- каждом. Счёт ведётся ПОСЛЕ вставки, поэтому повторный накат проходит его так же, как первый.
-- Строк `user_grants` этот блок не считает: наборы живые, и держатели у них — обычное дело.
DO $$
DECLARE trouble text;
BEGIN
  SELECT string_agg(msg, '; ')
    INTO trouble
    FROM (
      SELECT format('наборов нет или они не системные (найдено строк: %s вместо двух)', count(*))
             AS msg
        FROM grants
       WHERE code IN ('office_equipment_operator', 'office_equipment_it_approver')
         AND is_system AND deleted_at IS NULL
      HAVING count(*) <> 2
      UNION ALL
      SELECT format('%s: прав %s вместо %s, деньги заявки среди них: %s',
                    g.code,
                    count(gp.permission),
                    CASE g.code WHEN 'office_equipment_operator' THEN 9 ELSE 7 END,
                    CASE WHEN count(gp.permission) FILTER (
                           WHERE gp.permission = 'serviceRequests.finance') = 1
                         THEN 'да' ELSE 'нет' END)
        FROM grants g
        LEFT JOIN grant_permissions gp ON gp.grant_id = g.id
       WHERE g.code IN ('office_equipment_operator', 'office_equipment_it_approver')
       GROUP BY g.code
      HAVING (g.code = 'office_equipment_operator'    AND count(gp.permission) <> 9)
          OR (g.code = 'office_equipment_it_approver' AND count(gp.permission) <> 7)
          OR count(gp.permission) FILTER (
               WHERE gp.permission = 'serviceRequests.finance') <> 1
    ) AS bad;
  IF trouble IS NOT NULL THEN
    RAISE EXCEPTION 'Наборы оргтехники собраны не так, как объявлены — %', trouble;
  END IF;
END $$;
