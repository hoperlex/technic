-- Правка номера версии у выпуска 82 (ADR 0077): `0.1.71.0161` → `0.1.71.0164`.
--
-- ЧТО БЫЛО НЕ ТАК. Хвост номера — это последнее решение выпуска, и ADR 0077 требует от него
-- монотонности: «`0.1.4.0071` никогда не встанет после `0.1.5.0069`». Выпуск 81 (ЭСМ-2) нёс хвост
-- `0164`, а следующий за ним 82 (статус заявки как вход в её ход) — `0161`. Хвост поехал вниз, и
-- номера версий перестали сортироваться: «а это уже с быстрым статусом?» по номеру больше не
-- читалось. Причина не в ошибке счёта, а в параллельных потоках — блок с решением 0161 закрылся
-- позже блока с решением 0164, хотя решение принято раньше.
--
-- ПОЧЕМУ ПРАВИТСЯ ХВОСТ, А НЕ ПОРЯДОК ВЫПУСКОВ. Поменять местами 81 и 82 значило бы переписать
-- ленту, которую человек мог уже прочитать: «что появилось» — рассказ о том, что происходило, и
-- переставлять в нём главы задним числом хуже, чем оставить номер, чуть менее точно называющий
-- своё решение. Поэтому порядок выпусков сохранён, а хвост поднят до `0164` — последнего решения,
-- вошедшего в ленту к этому моменту.
--
-- ЧТО ЭТА ПРАВКА ТЕРЯЕТ, СКАЗАНО ЧЕСТНО. Номер `0.1.71.0164` больше не указывает на решение самого
-- выпуска: быстрая смена статуса принята ADR 0161, и найти его по номеру версии теперь нельзя —
-- он назван в поле `adrs` записи, которое эта миграция не трогает. Сортируемость номера важнее:
-- по `adrs` решение ищется точно, а по сломанной сортировке не ищется ничего.
--
-- ОТКУДА НОМЕР ФАЙЛА. `ls apps/api/drizzle` перед созданием (07.09.2026): последняя миграция в
-- дереве — `0280_waste_tickets_issued_on_raw.sql` соседнего потока (год в дате талона). Свободен
-- `0281`, он и взят. Схему миграция не меняет и данных, кроме одной строки журнала обновлений, не
-- касается; обратима она такой же строкой с прежним значением.
UPDATE app_releases
   SET version = '0.1.71.0164'
 WHERE seq = 82
   AND version = '0.1.71.0161';
