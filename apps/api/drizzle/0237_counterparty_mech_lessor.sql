-- Арендодатель механизации как роль контрагента (план `docs/mechanization-module-plan.md`,
-- редакция 12: решения Р6 и Р18). Этап Э1, первый из двух файлов одного выката.
--
-- ОТКУДА НОМЕР. Проверено `ls apps/api/drizzle` непосредственно перед созданием файла
-- (01.09.2026): последняя миграция в дереве — `0236_esm2_month_split_backfill.sql`. Отсюда 0237 —
-- этой и 0238 — соседней, схемной. Номер решения (ADR) здесь не назван намеренно: потоки номеров
-- параллельны (§11 плана), 0151 к этому дню уже занят соседней работой, и вписанный заранее номер
-- врал бы; решение модуля получит свой в день коммита.
--
-- ЗАЧЕМ ОТДЕЛЬНЫЙ ТИП. У контрагента ровно один тип, а ИНН уникален (ADR 0010) — значит компания,
-- сдающая малую механизацию, обязана где-то лежать, и «арендодатель ТС» ей не подходит: за ним
-- заводят учётки и его подписывают под технику парка. Список прав нового типа в
-- `COUNTERPARTY_TYPE_PERMISSIONS` пуст: учёток за арендодателем механизации не заводят вовсе
-- (`COUNTERPARTY_TYPES_WITH_ACCOUNTS` считается из непустых), поэтому и размывать права нечем.
--
-- ЧТО ЭТО НЕ ЗНАЧИТ. Арендодателем заявки механизации может быть и существующий `vehicle_lessor`
-- (Р6): компания, уже заведённая арендодателем ТС, сдаёт механизацию под своим типом — смена типа
-- сломала бы права её учёток и её технику в парке. Оба допустимых типа перечислены поимённо в
-- `mech_requests_lessor_type_check` следующей миграции; здесь заводится только значение.
--
-- ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ, А НЕ СТРОКОЙ В 0238. Значение используется уже со следующей миграции —
-- в CHECK'е допустимых типов. Применить значение enum'а в той же транзакции, где оно добавлено,
-- Postgres не даёт, а раннер выполняет каждый файл целиком одной транзакцией. Приём и формулировка
-- — из 0032 (`vehicle_lessor`: тот же тип, та же причина), а до неё — из пары 0022/0023.
ALTER TYPE counterparty_type ADD VALUE IF NOT EXISTS 'mech_lessor';
