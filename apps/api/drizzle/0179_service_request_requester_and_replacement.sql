-- Подразделение заявителя и пометка «рекомендована замена» у заявки оргтехники (план
-- `docs/office-equipment-requests-rework-plan.md`, §4.1 и §5, миграция M5; решения Н11 и Н3/В21
-- набросков). Выпуск 1 «Цикл и полномочия», волна В2.
--
-- ЗАЧЕМ ПОДРАЗДЕЛЕНИЕ. Карточка заявки не отвечает на вопрос «откуда человек», хотя в ней три
-- «чьих» поля: `equipment_object_id` и `equipment_department_id` — про ТЕХНИКУ (где стоит, за кем
-- числится), `customer_department_id` — про отдел, ОТ ИМЕНИ которого заведена заявка, и он
-- выбирается руками, потому что сотрудник соседнего отдела чинит «чужой» принтер чаще, чем
-- кажется. Сам заявитель может не относиться ни к одному из трёх. Поэтому заводится своя пара
-- ссылок — отдел, а если отделов у учётки нет, то площадка.
--
-- ЗАЧЕМ СНИМОК НАЗВАНИЯ РЯДОМ СО ССЫЛКОЙ. Ссылки мало: отдел переименуют — и прошлогодняя заявка
-- покажет сегодняшнее имя. Приём тот же, которым модуль уже снимает реквизиты аппарата
-- (`equipment_name`, `equipment_inventory_number`, `0105`): ссылка отвечает «куда перейти»,
-- название — «как это называлось тогда».
--
-- ЗАЧЕМ ПОМЕТКА ЗАМЕНЫ. У сметы появляется третий исход — «ремонт нецелесообразен, аппарат под
-- замену» (В21). Отдельного статуса ему не заводят: по правилу модуля (Р53 ADR 0096) «закрыта без
-- результата» — это отмена с причиной, а не новое состояние. Пометка и отличает такую отмену от
-- любой другой: из неё собирается список «что пора менять» — аппарат, сумма отвергнутого ремонта,
-- дата.
--
-- ЧТО ЗАВОДИТСЯ: пять колонок и два `CHECK`. Триггеров здесь нет — оба правила проверяются внутри
-- собственной строки, и заглядывать в другие таблицы им не нужно.
--
-- ОКНО ВЫКАТА (§3 плана). Миграции накатываются ДО перезапуска сервисов
-- (`docs/schema-cutover-protocol.md`, §1), и в этом окне на новой схеме работает старый код. Он о
-- новых колонках не знает и получает их значения по умолчанию — обе пары пустыми и пометку
-- `false`, — а такая строка оба ограничения проходит. Ни одно его движение эта миграция не
-- запрещает.
--
-- ОБРАТИМОСТЬ. Миграция аддитивна: пять новых колонок и два ограничения, которым все существующие
-- строки удовлетворяют как есть. `ADD COLUMN … NOT NULL DEFAULT` таблицу не переписывает
-- (PostgreSQL 11+), данные не читаются и не меняются — поэтому блокировки первой строкой здесь
-- нет. Протокол выката необратимых миграций (`docs/schema-cutover-protocol.md`) к ней не
-- применяется.

ALTER TABLE service_requests
  -- Подразделение ЗАЯВИТЕЛЯ — то есть учётки `created_by` (В25). Не `responsible_name`: тот
  -- остаётся тем, кому звонить, и правка контакта задним числом не должна переписывать, от какого
  -- отдела заявка. Заполняет пару сервер, а не клиент, и в той же транзакции, что и саму заявку.
  --
  -- `RESTRICT` — как у трёх соседних «чьих» ссылок (`0105`): подразделение, к которому привязаны
  -- заявки, не удаляют молча. `SET NULL` рассыпал бы пару «ссылка + название» — осталось бы имя
  -- без адреса, то есть снимок, притворяющийся ссылкой; и ограничение ниже такое удаление всё
  -- равно отбило бы.
  ADD COLUMN requester_department_id uuid REFERENCES departments (id) ON DELETE RESTRICT,
  -- Площадка заявителя — заполняется, только если отделов у учётки нет вовсе. Обе ссылки сразу
  -- запрещены ограничением ниже: «откуда человек» — один ответ, а не два.
  ADD COLUMN requester_object_id uuid REFERENCES construction_objects (id) ON DELETE RESTRICT,
  -- Снимки названий на момент заведения. `NOT NULL DEFAULT ''`, а не nullable: «подразделения нет»
  -- и «название пустое» — одно состояние, и двух представлений у него быть не должно; пустая
  -- строка тут ровно то же, чем она уже служит у `equipment_serial_number` и `responsible_name`.
  ADD COLUMN requester_department_name text NOT NULL DEFAULT '',
  ADD COLUMN requester_object_name text NOT NULL DEFAULT '',
  -- «Ремонт нецелесообразен, аппарат под замену». Флагом, а не текстом: по нему строится список и
  -- отбор, а причина отмены и без того обязательна и живёт своей строкой.
  ADD COLUMN replacement_recommended boolean NOT NULL DEFAULT false;

-- Подразделение заявителя — ЛИБО отдел, ЛИБО площадка, и ссылка со снимком названия ходят парой.
-- Три половины одного смысла:
--
--   · обе ссылки сразу — запрещены: вопрос «откуда человек» имеет один ответ, и заявка с отделом и
--     площадкой одновременно сломала бы любой отчёт по подразделениям двойным счётом;
--   · ЭКВИВАЛЕНТНОСТЬ, а не импликация, у каждой пары: заполненная ссылка без названия — снимок,
--     который ничего не помнит (ради чего название и заводится, Н11), а название без ссылки —
--     подразделение, к которому некуда перейти и которого, возможно, никогда не было. Записано
--     через `btrim(…) <> ''`, потому что колонка `NOT NULL DEFAULT ''`: «нет названия» — это
--     пустая строка, а строка из пробелов — то же самое, набранное иначе;
--   · ОБЕ ПАРЫ ПУСТЫЕ — ЗАКОННЫ, и это не послабление на окно выката. Так выглядят все заявки,
--     заведённые до этого выпуска, и так же законно выглядит заявка учётки, у которой нет ни
--     отдела, ни площадки, — например, администратора портала (§8 плана, тест 9а). Требовать
--     заполнения хоть одной пары значило бы запретить таким учёткам заводить заявки вовсе.
ALTER TABLE service_requests ADD CONSTRAINT service_requests_requester_place_check CHECK (
  NOT (requester_department_id IS NOT NULL AND requester_object_id IS NOT NULL)
  AND (requester_department_id IS NOT NULL) = (btrim(requester_department_name) <> '')
  AND (requester_object_id IS NOT NULL) = (btrim(requester_object_name) <> '')
);

-- Пометка «рекомендована замена» существует только у ОТМЕНЁННОЙ заявки: она объясняет, почему
-- заявку закрыли без ремонта (Н3). У живой заявки та же пометка означала бы «чинить не будем», но
-- заявка при этом продолжала бы двигаться по циклу — то есть противоречила бы сама себе.
--
-- Проверка идёт по `status`, а НЕ по эффективному статусу с `held_from_status`: отложенная заявка
-- под заменой не бывает по устройству — заморозка ведёт назад в рабочий статус (`0162` запрещает
-- `held_from_status = 'cancelled'`), а замена закрывает заявку насовсем.
--
-- Прямое следствие для кода: возврат отменённой заявки в «Новую» обязан гасить пометку — это
-- делает матрица сброса `serviceResetOnTransition`, и без неё откат упрётся в это ограничение
-- (§8 плана, тест 9).
ALTER TABLE service_requests ADD CONSTRAINT service_requests_replacement_check
  CHECK (NOT replacement_recommended OR status = 'cancelled');

-- Индексов по новым ссылкам НЕТ намеренно. Отбора по подразделению заявителя нет ни в одном
-- списке: область видимости считается по технике и отделу-заказчику и этим полем не меняется
-- (Н11), а карточка читает его по первичному ключу заявки. Единственный оставшийся потребитель —
-- проверка `RESTRICT` при удалении отдела или площадки, но удаляют их поштучно и вручную, а
-- таблица заявок измеряется тысячами строк. Индекс, заведённый «на всякий случай», обошёлся бы
-- дороже: он оплачивается каждой вставкой и правкой заявки, а отвечает на вопрос, которого пока
-- никто не задаёт. Понадобится отчёт по подразделениям — он и принесёт свой индекс, зная, каким
-- условием его отбирают.
