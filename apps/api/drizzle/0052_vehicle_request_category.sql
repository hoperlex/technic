-- Категория ТС в заявке (ADR 0028; развивает ADR 0016 §14 «Отложено»).
--
-- Заявка заказывала тип ТС — «нужен автокран». Грузоподъёмность при этом выяснялась звонком,
-- хотя она давно заведена в справочнике: тип «Автокраны» раскрыт категориями «г/п 25 т»,
-- «г/п 130 т» (ADR 0016). Теперь заказывают конечную позицию классификатора: категорию, если
-- у типа она есть, либо сам тип — если ТТХ у него нет и категорий быть не может («Ямобур»).
--
-- Колонка nullable, и это не «поле необязательно»: пусто значит «у типа нет категорий» либо
-- «заявка заведена до этой миграции». Обязательность решает сервер — он один видит, есть ли у
-- типа активные категории, и без них требовать выбор было бы нечего.

-- 1. Категория заявки. Составной FK, а не ссылка на id: пара (категория, тип) физически
--    запрещает категорию чужого типа — тем же приёмом, что держит «модель того же типа, что
--    машина» (vehicles_model_type_fk) и «машина того же типа, что заказан»
--    (vehicle_request_assignments_vehicle_type_fk).
--    RESTRICT: пока на категорию ссылается хотя бы одна заявка, из справочника её не удалить —
--    заявка обязана показывать, что именно заказывали, и через год после закрытия.
ALTER TABLE vehicle_requests
  ADD COLUMN vehicle_category_id uuid;

ALTER TABLE vehicle_requests
  ADD CONSTRAINT vehicle_requests_category_type_fk
  FOREIGN KEY (vehicle_category_id, vehicle_type_id)
  REFERENCES vehicle_categories (id, vehicle_type_id) ON DELETE RESTRICT;

-- 2. «Какие заявки на эту категорию» — вопрос со стороны справочника (и проверка перед
--    удалением категории). Частичный: у заявок без категории спрашивать нечего.
CREATE INDEX vehicle_requests_vehicle_category_idx
  ON vehicle_requests (vehicle_category_id)
  WHERE vehicle_category_id IS NOT NULL;

-- Задним числом категории не проставляются. Заявка — документ: в ней записано то, что заказывали
-- на самом деле, а какая у той машины была грузоподъёмность, задним числом не выяснить. Старые
-- заявки так и остаются заказом типа и показываются чистым типом.
