-- Приёмка заявки оргтехники: источник становится обязательной половиной пары. Миграция M9 плана
-- переработки заявок (`docs/office-equipment-requests-rework-plan.md`, §5), выпуск 2 «Contract».
--
-- ЧТО ЗАКРЫВАЕТ. Выпуск 1 (`0176`) завёл `acceptance_source` — «кто закрыл заявку: человек или
-- система» — и поставил МЯГКОЕ ограничение: «источник, если он есть, бывает только `human` или
-- `auto`, и у `auto` не бывает автора». Строгую половину — «источник есть РОВНО у принятой» —
-- поставить тогда было нельзя: старый код в окне выката принимал заявки, ничего не зная про
-- источник, и упёрся бы в неё на первой же приёмке.
--
-- ПОЧЕМУ ЭКВИВАЛЕНТНОСТЬ, А НЕ ОДНОСТОРОННЯЯ ПРОВЕРКА. Две дыры разной природы:
--   · принятая заявка БЕЗ источника — отчёт «сколько закрыли руками, сколько само» молча теряет
--     строку, и разница списывается на «прочее»;
--   · источник У НЕПРИНЯТОЙ — след прошлой приёмки, переживший откат заявки на доработку. Он
--     соврёт в тот момент, когда заявку примут заново: старое значение выглядит как новое.
-- Обе закрываются одним равенством `(accepted_at IS NULL) = (acceptance_source IS NULL)`.

-- ── 1. Backfill: две стороны окна выката ──
--
-- ПЕРВАЯ — принятые старым кодом. Дата приёмки есть, источника нет, и по смыслу это `human`:
-- автозакрытия старый код не умел вовсе, значит за каждой такой заявкой стоит живой человек.
UPDATE service_requests SET acceptance_source = 'human'
 WHERE accepted_at IS NOT NULL AND acceptance_source IS NULL;

-- ВТОРАЯ — откаченные старым кодом, и без неё накат упал бы. Старый код, возвращая принятую заявку
-- на доработку, чистил `accepted_by/at`, а про `acceptance_source` не знал и оставлял его стоять.
-- Такая строка — «не принята, но источник приёмки есть» — и есть та самая ложь, которую
-- ограничение ниже запрещает; сперва её надо убрать.
UPDATE service_requests SET acceptance_source = NULL WHERE accepted_at IS NULL;

-- ── 2. Строгая связка ──

ALTER TABLE service_requests DROP CONSTRAINT service_requests_acceptance_source_check;

ALTER TABLE service_requests ADD CONSTRAINT service_requests_acceptance_source_check CHECK (
  -- Пара «принята ⟺ известно кем закрыта». Ни одна половина не бывает без другой.
  (accepted_at IS NULL) = (acceptance_source IS NULL)
  AND (acceptance_source IS NULL OR acceptance_source IN ('human','auto'))
  -- У автозакрытия автора нет и быть не может: за него не отвечает ни один человек, а подставлять
  -- туда «систему» учёткой значило бы завести пользователя, которого нет (обоснование — в `0176`).
  AND (acceptance_source <> 'auto' OR accepted_by IS NULL)
  -- Обратное направление прежней парной проверки сохраняется: «кто-то принял, но когда —
  -- неизвестно» было бессмыслицей и осталось ею.
  AND (accepted_by IS NULL OR accepted_at IS NOT NULL)
);

-- ТРЕБОВАНИЯ «у принятой человеком есть автор» здесь НЕТ, и это намеренно — та же причина, что в
-- `0176`: ссылка на автора объявлена `ON DELETE SET NULL`, и увольнение сотрудника обнуляет её у
-- всех его приёмок разом. Заявка при этом остаётся принятой, и `human` остаётся правдой: закрыл её
-- человек, просто учётки этого человека больше нет. Жёсткая проверка сделала бы увольнение
-- невозможным без правки истории.

COMMENT ON CONSTRAINT service_requests_acceptance_source_check ON service_requests IS
  'Приёмка и её источник — одна пара (решение 7 ADR 0133, M9 плана переработки заявок): принята '
  'ровно тогда, когда известно, кем закрыта. У auto автора нет; у human он может отсутствовать '
  'после увольнения (SET NULL).';
