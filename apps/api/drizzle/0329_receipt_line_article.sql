-- Артикул позиции в строке чека на автозапчасти.
--
-- План — docs/auto-part-receipt-ocr-plan.md, Р2а (решение заказчика от 21.09.2026). Поле заводится
-- раньше распознавания и живёт самостоятельно: артикул набирают руками, и им же ищут чек.
--
-- ЗАЧЕМ ОТДЕЛЬНАЯ КОЛОНКА, А НЕ ХВОСТ НАИМЕНОВАНИЯ. Наименование в чеке дословное (ADR 0154, Р7),
-- и написание у двух продавцов не совпадёт никогда: «Шланг d=18x27мм маслобензостойкий» и «Шланг
-- 18х27 МБС» — одна деталь. Артикул совпадёт. Дописать его в конец имени значило бы хранить два
-- разных утверждения в одном поле и искать по нему подстрокой вперемешку со словами.
--
-- ПУСТАЯ СТРОКА, А НЕ NULL. Графы артикула нет у доброй половины бумаг — товарный чек из магазина
-- её не печатает вовсе, — и «артикула нет» здесь норма, а не пропуск. Два представления одного и
-- того же (NULL и '') пришлось бы отличать в каждом чтении; у соседних `unit` и `note` то же
-- правило.
--
-- ОТКУДА НОМЕР. Снимок ls apps/api/drizzle 21.09.2026: последней в дереве стоит
-- 0328_device_mail_intake_enable.sql, файлов 0329 нет.
--
-- ОКНО НАКАТА. Миграция аддитивна и идёт при работающем портале: старый код колонки не знает,
-- пишет строки без неё и получает умолчание. Обратная сторона названа в плане и закрыта не
-- схемой, а порядком выката: правка чека пересоздаёт строки целиком, поэтому СТАРАЯ ВКЛАДКА,
-- не присылающая артикул, обнулила бы его у всех строк правимого чека. Против этого поднимается
-- пол клиента (MIN_CLIENT_CONTRACT, ADR 0146) отдельной фазой после раздачи новой статики —
-- `deploy-auto --client-floor=6`.
--
-- ОБРАТИМОСТЬ: ALTER TABLE auto_part_receipt_lines DROP COLUMN article. Данные при этом теряются
-- безвозвратно, поэтому откат кода делается БЕЗ отката колонки: пустая лишняя колонка старому
-- коду не мешает ничем.

ALTER TABLE auto_part_receipt_lines
  ADD COLUMN article text NOT NULL DEFAULT '';
