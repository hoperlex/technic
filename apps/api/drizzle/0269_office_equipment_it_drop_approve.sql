-- Из набора «Оргтехника: ИТ-служба» снимается мёртвое право `serviceRequests.approveIt` — миграция
-- E плана `docs/office-equipment-access-profiles-plan.md` (Р9, §8 находка Н3, §9.1 строка E, этап
-- Э9). Последняя миграция каталога этого плана.
--
-- ОТКУДА НОМЕР. Проверено `ls apps/api/drizzle/*.sql` непосредственно перед созданием файла
-- (04.09.2026): последняя миграция в дереве — `0268_releases_vehicle_readings_fuel_levels.sql`
-- соседнего потока, свободен 0269. Номера не резервируются заранее (§14 плана): пока шли Э6–Э8,
-- соседи заняли 0263, 0264, 0267 и 0268 незакоммиченными файлами.
--
-- ПОЧЕМУ ПРАВО МЁРТВОЕ. Виза ИТ упразднена планом упрощения цикла (Р10, ответ В2): ручки
-- `PATCH /:id/it-approval` не существует, строки под неё в манифесте доступа нет, коридор визы был
-- пуст целиком, и держатель права не получал по нему ни одной двери и ни одного хода. Вопрос
-- «чинить за эти деньги или менять аппарат» задаёт себе тот же человек, что смотрит на объём работ.
--
-- ПОЧЕМУ ЭТО МОЖНО БЫЛО СДЕЛАТЬ ТОЛЬКО СЕЙЧАС, И ЭТО ГЛАВНОЕ СВОЙСТВО ЭТОЙ МИГРАЦИИ. Сторона
-- обсуждения «Системный администратор» держалась РОВНО НА ЭТОМ ПРАВЕ (`matchesServiceChatSide`,
-- случай `it`). Сними его кто-нибудь раньше — и профиль погас бы молча: пропала бы яркая метка в
-- обсуждении, пропал бы адресат реплики «ИТ-службе», а вместе с ним и адресат письма. Этап Э3
-- перевёл опознание стороны на КОД набора (`office_equipment_it_approver`, Р9), и только после
-- этого право стало снимаемым. Порядок «сперва опознание, потом уборка» — часть решения Р9, а не
-- пожелание; обратный порядок ловила переходная часть теста Т14, снятая тем же выпуском.
--
-- ЧТО МИГРАЦИЯ ДЕЛАЕТ И ЧЕГО НЕ ДЕЛАЕТ.
--
--   · снимает ОДНУ строку `grant_permissions` — по коду набора и по имени права. Точечным
--     `DELETE`, а не «почистить право везде»: набор, собранный администратором руками, может
--     содержать `serviceRequests.approveIt` законно, и трогать чужой состав миграция каталога не
--     вправе;
--   · переписывает описание набора: прежний текст (миграция 0262) обещал администратору, что тот
--     «подписывает визу ИТ», — а подписывать нечего и нечем. Описание читают на экране каталога, и
--     оставленное как есть, оно стало бы единственным местом портала, которое врёт про работу.
--     Целиком, а не конкатенацией: `description || '…'` на повторном накате пришил бы фразу второй
--     раз;
--   · НЕ ТРОГАЕТ НИ ОДНОЙ СТРОКИ `user_grants`. Ни одна выдача не отзывается, ни одна не создаётся:
--     держатели профиля остаются при своих двух кодах, и караул ниже проверяет это счётом «до» и
--     «после», а не обещанием в комментарии;
--   · НЕ СНИМАЕТ ПРАВО ИЗ СЛОВАРЯ. `serviceRequests.approveIt` остаётся в `PERMISSIONS`, в
--     `PERMISSION_CATALOG`, в матрице администратора и в `PERMISSION_REQUIRES`. Это отдельная
--     работа с другими последствиями — осиротевшие строки `grant_permissions` у собранных наборов
--     и чистка каталога прав, — и этот план её не заказывал.
--
-- ГДЕ ЖИВЁТ ОБЪЯВЛЕННЫЙ СОСТАВ: `ROLE_ADDON_PERMISSIONS.office_equipment_it_approver`
-- (`packages/contracts/src/permissions.ts`) — единственное место объявленного состава, страж
-- каталога строит ожидание оттуда. Правка контрактов едет ТОЙ ЖЕ волной, что эта миграция (§9.3
-- п. 1): разъехавшись, они дали бы одному человеку разные права в зависимости от того, каким
-- источником пришёл доступ. Обе стороны сверяет `apps/api/test/grants-catalog.db.test.ts`.
--
-- ОБРАТИМОСТЬ. Схема не меняется, трогаются две строки каталога. Откат — вернуть строку состава
-- (`INSERT INTO grant_permissions … 'serviceRequests.approveIt'`) и прежнее описание, но ТОЛЬКО
-- вместе с откатом контрактов: состав, разошедшийся со стражем, роняет прогон в тот же день.

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 0. Снимок держателей набора ДО правки — ради утверждения «ни одной строки `user_grants`».
--
-- `ON COMMIT DROP`: таблица живёт до конца транзакции миграции и в базе не остаётся. Сверяются
-- множества, а не только счёт: обмен одного держателя на другого дал бы то же число.

CREATE TEMP TABLE it_holders_0269 ON COMMIT DROP AS
SELECT ug.user_id
FROM user_grants ug
JOIN grants g ON g.id = ug.grant_id
WHERE g.code = 'office_equipment_it_approver';

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 1. Само снятие. Набор ищется по коду: коды стабильны навсегда, по ним его находят миграции
--    каталога, журнал действий и реестр выдач.
--
-- Повторный накат на базу, восстановленную из копии, — обычное дело: `DELETE` идемпотентен по
-- построению, второй раз он просто не найдёт строки.

DELETE FROM grant_permissions gp
USING grants g
WHERE gp.grant_id = g.id
  AND g.code = 'office_equipment_it_approver'
  AND gp.permission = 'serviceRequests.approveIt';

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 2. Описание — абзац для администратора, который читается на экране каталога рядом с названием:
--    оно объясняет РАБОТУ, а не перечисляет права (перечень он видит и так). От текста миграции
--    0262 отличается ровно одним: обещания визы в нём больше нет.

UPDATE grants
   SET description = 'Координирует модуль «Орг.техника» сквозным взглядом: видит заявки всех '
                     'площадок и отделов, решает по смете «чинить или менять», назначает '
                     'исполнителей (в том числе себя) и откладывает заявку. '
                     'Видит суммы и объём работ заявок: строки сметы с ценами, итог, счёт и акт, '
                     'сумму ремонта в истории обслуживания аппарата. Заводит заявку без аппарата — '
                     'на работу, у которой предмета в справочнике нет вовсе. Ходов исполнителя и '
                     'документов в наборе НЕТ: их открывает отдельный набор «Оргтехника: '
                     'исполнитель», и системному администратору выдают оба сразу.',
       updated_at = now()
 WHERE code = 'office_equipment_it_approver';

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 3. Караул: состав набора, его системность и неприкосновенность выдач.
--
-- Страж-тест сверяет каталог с контрактами, но живёт он в репозитории, а этот блок — в накате:
-- оператор выката увидит расхождение сразу, а не через прогон тестов.
--
-- Права названы ПОИМЁННО, а не сосчитаны: счёт «их семь» сошёлся бы и у набора, собранного из
-- чужих прав. Отдельной строкой — сама виза: равенство перечня её отсутствие уже доказывает, но
-- сообщение об отказе должно называть виновника, а не заставлять оператора сличать два списка.
--
-- Числа взяты по факту кода после правки контрактов, а не переписаны из плана: в ИТ-наборе семь
-- прав — восемь после миграции 0262 минус снятое здесь одно. СЛЕДУЮЩАЯ МИГРАЦИЯ КАТАЛОГА обязана
-- вести счёт от СЕМИ (и от 15 у «Ведения», 3 у исполнителя, 6 у «Заявителя»), а не выводить его из
-- головы.

DO $$
DECLARE trouble text;
BEGIN
  SELECT string_agg(msg, '; ')
    INTO trouble
    FROM (
      SELECT format('набора нет или он не системный (найдено строк: %s вместо одной)', count(*))
             AS msg
        FROM grants
       WHERE code = 'office_equipment_it_approver' AND is_system AND deleted_at IS NULL
      HAVING count(*) <> 1
      UNION ALL
      SELECT format('office_equipment_it_approver: состав %s',
                    coalesce(string_agg(gp.permission, ', ' ORDER BY gp.permission), 'пуст'))
        FROM grants g
        LEFT JOIN grant_permissions gp ON gp.grant_id = g.id
       WHERE g.code = 'office_equipment_it_approver'
      HAVING coalesce(array_agg(gp.permission ORDER BY gp.permission), ARRAY[]::text[])
               <> ARRAY['officeEquipment.read', 'serviceRequests.assign',
                        'serviceRequests.create', 'serviceRequests.createWithoutEquipment',
                        'serviceRequests.finance', 'serviceRequests.hold', 'serviceRequests.read']
      UNION ALL
      SELECT 'office_equipment_it_approver: мёртвая виза `serviceRequests.approveIt` осталась в '
             'составе'
        FROM grants g
        JOIN grant_permissions gp ON gp.grant_id = g.id
       WHERE g.code = 'office_equipment_it_approver'
         AND gp.permission = 'serviceRequests.approveIt'
      UNION ALL
      SELECT format('описание набора всё ещё обещает визу: %s', g.description)
        FROM grants g
       WHERE g.code = 'office_equipment_it_approver' AND g.description ILIKE '%визу ИТ%'
      UNION ALL
      SELECT format('держатели набора изменились: было %s, стало %s — миграция тронула user_grants',
                    (SELECT count(*) FROM it_holders_0269),
                    (SELECT count(*) FROM user_grants ug
                       JOIN grants g2 ON g2.id = ug.grant_id
                      WHERE g2.code = 'office_equipment_it_approver'))
       WHERE EXISTS (SELECT user_id FROM it_holders_0269
                     EXCEPT SELECT ug.user_id FROM user_grants ug
                       JOIN grants g2 ON g2.id = ug.grant_id
                      WHERE g2.code = 'office_equipment_it_approver')
          OR EXISTS (SELECT ug.user_id FROM user_grants ug
                       JOIN grants g2 ON g2.id = ug.grant_id
                      WHERE g2.code = 'office_equipment_it_approver'
                     EXCEPT SELECT user_id FROM it_holders_0269)
    ) AS bad;
  IF trouble IS NOT NULL THEN
    RAISE EXCEPTION 'Уборка мёртвой визы из набора «Оргтехника: ИТ-служба» прошла не так, как '
                    'объявлено — %', trouble;
  END IF;
END $$;
