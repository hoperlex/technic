-- Право `officeEquipment.move` («Подтверждает перемещение техники») в каталоге полномочий: два
-- системных набора модуля получают его по коду, а собранные администратором — по содержимому (план
-- `docs/office-equipment-move-from-request-plan.md`, Р1, Р2, §7 строка `N`; этап Э2).
--
-- ОТКУДА НОМЕР. `ls apps/api/drizzle` непосредственно перед созданием файла (04.09.2026, вечер):
-- 0274 успел занять соседний поток — `0274_releases_service_request_quick_status.sql` (запись
-- выпуска о быстрой смене статуса заявки, коммит b7946fd), — хотя часом раньше свободным был он.
-- Свободен 0275, он и взят; парная миграция схемы этой же волны заняла 0277 (0276 успел уйти
-- соседям, пока она писалась). Это ровно тот случай, о котором предупреждают соседние планы: снимок
-- свободного номера живёт часы, и брать его надо в момент создания каждого файла, а не
-- резервировать на волну вперёд.
--
-- ЗАЧЕМ ПРАВО. `officeEquipment.write` открывает разом заведение карточек, правку, типы, модели,
-- архив И перемещение. Ответственный за оргтехнику ведёт парк, а подтверждает переезд тот, кто
-- приехал по заявке и видел аппарат на месте, — это разные обязанности, и до сих пор сузить круг
-- подтверждающих было нечем: ведение либо выдано целиком, либо не выдано вовсе. Отдельное право
-- снимает выбор «либо весь парк, либо ничего».
--
-- ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ УСЛОВИЯ В МАРШРУТЕ. Право видно в витрине прав, выдаётся поимённо строкой
-- реестра (ADR 0021, 0106) и снимается тем же способом; условие «а вот этому человеку можно» не
-- знает ни витрина, ни журнал выдач. Отсюда же исполняется буквально требование задания «никаких
-- исключений по ФИО»: исключений нет вовсе — есть право.
--
-- ЧТО МИГРАЦИЯ ДЕЛАЕТ.
--
--   · дописывает право ДВУМ СИСТЕМНЫМ НАБОРАМ ПО КОДУ — «Оргтехника: ведение»
--     (`office_equipment_operator`) и «Оргтехника: ИТ-служба» (`office_equipment_it_approver`).
--     Первому — чтобы выпуск, отделивший перемещение от ведения, НЕ ОТОБРАЛ у него работающую
--     сегодня операцию (`officeEquipment.write` в составе есть). Второму — как целевую новую: у
--     ИТ-службы ведения справочника нет и не появится (план профилей, §5.2), и в этом весь смысл
--     Р1. Найти второй набор «по содержимому» было бы нечем — именно потому, что `write` у него
--     нет;
--   · дописывает право КАЖДОМУ СОБРАННОМУ АДМИНИСТРАТОРОМ НАБОРУ, где уже есть
--     `officeEquipment.write`, — ПО СОДЕРЖИМОМУ. Выбирай мы их списком имён, список устарел бы
--     молча: наборы собирают в интерфейсе, и о каждом новом миграция не узнает. Условие
--     `is_system = false` здесь обязательно: состав системных наборов живёт в коде и сверяется
--     стражем `apps/api/test/grants-catalog.db.test.ts` — дописанное «по содержимому» лишнее право
--     уронило бы его в тот же день;
--   · НЕ ТРОГАЕТ РОЛИ. Менеджер, диспетчер и администратор получают право матрицей
--     (`ROLE_PERMISSIONS`, `admin: [...PERMISSIONS]`) — она в коде и приезжает выкатом сервера,
--     миграции для этого не нужно и быть не может: `grant_roles` отвечает на другой вопрос — «кому
--     набор можно назначить»;
--   · НЕ СОЗДАЁТ И НЕ ОТЗЫВАЕТ НИ ОДНОЙ СТРОКИ `user_grants`. Кому набор достался, решает
--     администратор поимённо, с автором и временем (ADR 0106); эта миграция правит состав, а не
--     выдачи, и в таблицу выдач не пишет вовсе.
--
-- ДОСТУП РАСШИРЯЕТСЯ, И ЭТО ОСОЗНАННО (§7, колонка «расширяет доступ» — «да»). Новую дверь право
-- открывает ровно одному кругу — держателям набора «Оргтехника: ИТ-служба»: они смогут записать
-- перемещение, не получив при этом ни одной другой двери в справочник. Остальным получателям
-- (роли офиса, «Ведение», собранные наборы с ведением) перемещение было доступно и вчера — по
-- `officeEquipment.write`, — и строки здесь ровно затем, чтобы после выката оно осталось доступно
-- (критерий К9: ни у одной учётки не пропала возможность, которая у неё была). Сузить круг —
-- отдельное решение заказчика (развилка В1), и делается оно снятием права, а не правкой кода.
--
-- ТРЕБОВАНИЕ ПРАВА — только `officeEquipment.read` (`PERMISSION_REQUIRES`, контракты): перемещать
-- вслепую нельзя — подтверждают то, что видят, — а вести справочник ради подтверждения переезда не
-- обязательно. `officeEquipment.write` требованием НЕ объявлен намеренно: потребуй он его, круг
-- держателей остался бы прежним, то есть право не сузило бы ничего. Барьер требований считает по
-- ИТОГУ учётки, поэтому ни один из наборов от новой строки не становится невыдаваемым: чтение
-- справочника есть и в самих наборах (миграция 0261), и у всех совместимых ролей.
--
-- ГДЕ ЖИВЁТ ОБЪЯВЛЕННЫЙ СОСТАВ СИСТЕМНЫХ НАБОРОВ: `ROLE_ADDON_PERMISSIONS`
-- (`packages/contracts/src/permissions.ts`) — надстройка ADR 0086 остаётся живым источником доступа
-- до шага 1e реформы, и набор в базе её отражение. Правка контрактов едет ТОЙ ЖЕ волной, что эта
-- миграция, и это условие, а не порядок удобства: разъехавшись, они дали бы одному человеку разные
-- права в зависимости от того, каким источником пришёл доступ. Обе стороны сверяет
-- `apps/api/test/grants-catalog.db.test.ts`.
--
-- ОБРАТИМОСТЬ. Схема не меняется, трогается одна таблица каталога. Откат — `DELETE` строк с
-- `permission = 'officeEquipment.move'`, и делать его нужно ВМЕСТЕ с откатом контрактов: право,
-- снятое из словаря выкатом, оставило бы в базе строки-сироты (их отсеивает читатель на границе
-- `isPermission`, но страж каталога упал бы). Круг после отката прежний: перемещение снова
-- открывает `officeEquipment.write`, и никто ничего не теряет, кроме ИТ-службы, которая до выката
-- этой двери и не имела.

-- ── 1. Системные наборы модуля — по коду ──
--
-- Право хранится текстом: справочника прав в базе нет намеренно (`grant_permissions`, миграция
-- 0145), словарь `PERMISSIONS` закрыт и живёт в контрактах. `ON CONFLICT DO NOTHING` делает шаг
-- идемпотентным: повторный накат на базу, восстановленную из копии, — обычное дело.
--
-- Коды наборов не меняются никогда: по коду набор находят миграции каталога, журнал действий,
-- реестр выдач и таблица сквозной области (`GRANT_MODULE_WIDE_SCOPE`).

INSERT INTO grant_permissions (grant_id, permission)
SELECT g.id, 'officeEquipment.move'
FROM grants g
WHERE g.code IN ('office_equipment_operator', 'office_equipment_it_approver')
ON CONFLICT (grant_id, permission) DO NOTHING;

-- ── 2. Собранные администратором наборы — по содержимому ──
--
-- «У кого есть ведение справочника, у того остаётся и перемещение». Мягко удалённые наборы
-- пропускаются: выдавать и отражать в них нечего, а восстановление удалённого набора — отдельное
-- решение администратора, которое он принимает глядя на состав.

INSERT INTO grant_permissions (grant_id, permission)
SELECT g.id, 'officeEquipment.move'
FROM grants g
WHERE g.is_system = false
  AND g.deleted_at IS NULL
  AND EXISTS (
    SELECT 1 FROM grant_permissions gp
     WHERE gp.grant_id = g.id AND gp.permission = 'officeEquipment.write'
  )
ON CONFLICT (grant_id, permission) DO NOTHING;

-- ── 3. Караул: составы после правки ──
--
-- Страж-тест сверяет каталог с контрактами, но живёт он в репозитории, а этот блок — в накате:
-- оператор выката увидит расхождение сразу, а не через прогон тестов. Считается ПОСЛЕ вставки,
-- поэтому повторный накат проходит его так же, как первый.
--
-- Числа взяты по факту кода после правки контрактов: в «Ведении» шестнадцать прав (пятнадцать по
-- счёту миграции 0261 плюс одно здесь), в «ИТ-службе» восемь (семь по счёту миграции 0269 плюс
-- одно). СЛЕДУЮЩАЯ МИГРАЦИЯ КАТАЛОГА обязана вести счёт от ШЕСТНАДЦАТИ и ВОСЬМИ (и от 3 у
-- исполнителя, 6 у «Заявителя»), а не выводить его из головы.
--
-- Третьей строкой проверяется то, ради чего сделан шаг 2: собранный набор с ведением, оставшийся
-- без перемещения, — это учётка, у которой выкат отобрал работу (К9).

DO $$
DECLARE trouble text;
BEGIN
  SELECT string_agg(msg, '; ')
    INTO trouble
    FROM (
      SELECT format('наборов нет или они не системные (найдено строк: %s вместо двух)', count(*))
             AS msg
        FROM grants
       WHERE code IN ('office_equipment_operator', 'office_equipment_it_approver')
         AND is_system AND deleted_at IS NULL
      HAVING count(*) <> 2
      UNION ALL
      SELECT format('%s: прав %s вместо %s, подтверждение перемещения среди них: %s',
                    g.code,
                    count(gp.permission),
                    CASE g.code WHEN 'office_equipment_operator' THEN 16 ELSE 8 END,
                    CASE WHEN count(gp.permission) FILTER (
                           WHERE gp.permission = 'officeEquipment.move') = 1
                         THEN 'да' ELSE 'нет' END)
        FROM grants g
        LEFT JOIN grant_permissions gp ON gp.grant_id = g.id
       WHERE g.code IN ('office_equipment_operator', 'office_equipment_it_approver')
       GROUP BY g.code
      HAVING (g.code = 'office_equipment_operator'    AND count(gp.permission) <> 16)
          OR (g.code = 'office_equipment_it_approver' AND count(gp.permission) <> 8)
          OR count(gp.permission) FILTER (WHERE gp.permission = 'officeEquipment.move') <> 1
      UNION ALL
      SELECT format('собранный набор «%s» ведёт справочник, но перемещения не получил', g.code)
        FROM grants g
       WHERE g.is_system = false
         AND g.deleted_at IS NULL
         AND EXISTS (SELECT 1 FROM grant_permissions gp
                      WHERE gp.grant_id = g.id AND gp.permission = 'officeEquipment.write')
         AND NOT EXISTS (SELECT 1 FROM grant_permissions gp
                          WHERE gp.grant_id = g.id AND gp.permission = 'officeEquipment.move')
    ) AS bad;
  IF trouble IS NOT NULL THEN
    RAISE EXCEPTION 'Право перемещения разложено по наборам не так, как объявлено — %', trouble;
  END IF;
END $$;
