-- Ролевая часть стартового каталога полномочий (план реструктуризации модели доступа, §10
-- «замещающие упразднённые роли» и §15, этап 4б; ADR 0112).
--
-- Три набора, в которые переезжает различие между четырьмя упраздняемыми ролями: «Заказ техники» и
-- «Виза объекта» разбирают на части площадочную тройку, «Виза отдела» — пару ролей отдела. После
-- этапа 8 таблица соответствия плана §9 читается по ним:
--
--   shtab           = site + «Заказ техники»
--   rukstroy        = site + «Заказ техники» + «Виза объекта»
--   commandant      = site                                    (расширение на оргтехнику — решение №1)
--   department_head = department + «Виза отдела»
--
-- **Миграция не расширяет доступ ни одной живой учётке, и это её главное свойство.** Наборы
-- заводятся, но не выдаются: ни одной строки `user_grants` здесь нет и быть не должно (§10 — «этапы
-- 4 и 4б заводят наборы, никому их не выдавая»). Роль `site`, заведённая миграцией 0152, к этому
-- моменту тоже не назначена никому: расширение доступа коменданту — событие этапа 8, а не этого
-- файла. Права держателей до и после наката совпадают до единого.
--
-- **Почему роль вводится этим этапом, а не вместе с переводом учёток.** Колонка `grant_roles.role` —
-- значение enum'а `role`, и строку с несуществующим значением база не примет. Отложи мы роль до
-- этапа 8 — каталог пришлось бы заводить либо без совместимых ролей (два набора, которые никому
-- нельзя выдать), либо двумя частями, что нарушает правило реформы «наборы заводятся ровно один
-- раз: этапы 8 и 9 их не создают» (§16.1). Оба варианта отвергнуты ADR 0112.
--
-- Миграция аддитивная: она добавляет строки в три таблицы каталога и ничего не переключает.
-- Протокол выката необратимых миграций (`docs/schema-cutover-protocol.md`) к ней не применяется —
-- схема не меняется вовсе. Откат этапа — снятие посеянного (§15): удалить наборы можно ровно пока у
-- них нет держателей, что и обеспечивает `RESTRICT` на `user_grants`.

-- Состав объявлен в контрактах (`ROLE_GRANTS`, `packages/contracts/src/grants.ts`) и переписан сюда
-- строками: словаря прав в базе нет намеренно (см. `grant_permissions` в миграции 0145), а миграция
-- не умеет спрашивать TypeScript. Что копии не разъедутся, следит страж
-- `apps/api/test/grants-catalog.db.test.ts` — он сверяет базу с контрактами по каждому набору.
--
-- Описание — единственное, что живёт только здесь: это абзац для администратора на экране каталога,
-- он объясняет работу, а не доступ, и сверять его не с чем.
