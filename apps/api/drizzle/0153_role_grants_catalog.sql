INSERT INTO grant_permissions (grant_id, permission)
SELECT g.id, s.permission
FROM grants g
JOIN (VALUES
  -- Заказ техники: ведение заказа ТС и ведение недели одним набором. Два модуля, а решение одно —
  -- недельный пакет это документ-основание над заказами, и площадка, которая заказывает технику,
  -- тем же решением говорит, что из стоящей на ней остаётся. Хода заказа (`vehicleRequests.status`)
  -- в наборе нет: «в работе» и «выполнена» решают те, кто исполняет (ADR 0025).
  ('vehicle_ordering'   , 'vehicleRequests.read'),
  ('vehicle_ordering'   , 'vehicleRequests.create'),
  ('vehicle_ordering'   , 'vehicleRequests.update'),
  ('vehicle_ordering'   , 'vehicleRequests.delete'),
  ('vehicle_ordering'   , 'weeklyRequests.read'),
  ('vehicle_ordering'   , 'weeklyRequests.create'),
  ('vehicle_ordering'   , 'weeklyRequests.update'),
  -- Виза объекта: обе подписи площадки вместе. Это одна должность и одна ответственность —
  -- руководитель строительства подписывает и отдельный заказ, и недельный пакет, который заказы
  -- порождает; развести их значило бы завести подпись, которой в жизни никто не ставит отдельно.
  ('site_approval'      , 'vehicleRequests.approve'),
  ('site_approval'      , 'weeklyRequests.approve'),
  -- Виза отдела: только заказ. Две визы, а не одна, потому что составы разные, и состав, зависящий
  -- от роли держателя, был бы неявным доступом (§10).
  ('department_approval', 'vehicleRequests.approve')
) AS s (code, permission) ON s.code = g.code;

-- Совместимые роли — «кому набор можно назначить», а не «кому он выдан» (§10).
--
-- У площадочных наборов роль одна и новая: `site` (миграция 0152). Старые `shtab`, `rukstroy` и
-- `commandant` здесь не перечислены намеренно — эти права у них уже есть от роли, и строка
-- `grant_roles` означала бы набор, выдача которого ничего не меняет (страж в
-- `grants-contracts.test.ts` такую строку и ловит). У «Визы отдела» роль — `department`:
-- `department_head` не перечислен по той же причине, виза у него уже есть.
--
-- Барьеры выдачи каждая пара «роль × право» проходит (`validateGrantAssignment`, проверено тестом
-- `grants-contracts.test.ts`): у `site` объектная ось, у `department` — отдельская, и модули
-- `vehicle` и `weekly` дают обеим клетку `scoped` — заказы и недели фильтруются по площадкам учётки
-- (`vehicleRequestVisibilityWhere`, `weeklyRequestReadScope`), и набор открывает держателю ровно его
-- объекты, а не данные компании.
INSERT INTO grant_roles (grant_id, role)
SELECT g.id, s.role::role
FROM grants g
JOIN (VALUES
  ('vehicle_ordering'   , 'site'),
  ('site_approval'      , 'site'),
  ('department_approval', 'department')
) AS s (code, role) ON s.code = g.code;

