-- Ревизионная виза ИТ у заявки оргтехники (план `docs/office-equipment-requests-rework-plan.md`,
-- §4.1 и §5, миграция M1; решение Н3 набросков). Выпуск 1 «Цикл и полномочия», волна В2.
--
-- ЗАЧЕМ. Виза ИТ-службы сегодня стоит НА ВХОДЕ заявки (`0119`): «чинить или не чинить» решают до
-- того, как известна цена. Новый цикл переносит её НА СМЕТУ — визируют конкретную сумму, — и
-- поэтому подпись обязана помнить, к какой ревизии сметы она относится. Смета версионируется:
-- `estimate_revision` растёт при каждом предъявлении, и виза, поставленная на первую ревизию,
-- о третьей не говорит ничего. Без номера ревизии рядом с подписью «виза ИТ есть» перестаёт быть
-- ответом на вопрос «согласована ли ТА смета, которую сейчас утверждают».
--
-- ЧТО ЗАВОДИТСЯ: одна nullable-колонка и один `CHECK`. Триггеров здесь нет.
--
-- ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ. Барьера «подпись записывается только вместе с ревизией» в этой миграции
-- нет намеренно (§3, п. 3 плана). Штатный деплой накатывает миграции ДО перезапуска сервисов
-- (`docs/schema-cutover-protocol.md`, §1), поэтому между накатом и перезапуском на новой схеме
-- работает СТАРЫЙ код — а он ставит входную визу и о ревизиях не знает. Любое требование ревизии,
-- поставленное здесь, уронило бы ему визирование в самом окне выката. Барьер записи — триггер
-- `service_requests_it_signature_guard` — приезжает выпуском 2 (M10), когда старого кода в проде
-- уже нет.
--
-- ПУСТАЯ РЕВИЗИЯ ПРИ ЗАПОЛНЕННОЙ ПОДПИСИ ЗАКОННА, и это не временная поблажка на окно выката: так
-- выглядит входная виза старого образца у всех сегодняшних заявок. Код выпуска 1 читает пустую
-- ревизию как «виза старого образца» и визой текущей сметы её не считает.
--
-- ОБРАТИМОСТЬ. Миграция аддитивна: новая nullable-колонка и ограничение, которому все существующие
-- строки удовлетворяют как есть — колонка у них пуста. Данные не читаются и не меняются, поэтому
-- блокировки первой строкой здесь нет. Протокол выката необратимых миграций
-- (`docs/schema-cutover-protocol.md`) к ней не применяется.

ALTER TABLE service_requests ADD COLUMN it_approved_estimate_revision integer;

-- Ограничение состоит из двух половин одного смысла, и ни одна из них не запрещает того, что
-- делает старый код:
--
--   · `it_approved_by IS NOT NULL` — РЕВИЗИЯ БЕЗ ПОДПИСИ НЕ ЗНАЧИТ НИЧЕГО: номер, которого никто не
--     подписывал, отвечает на вопрос «что именно завизировали» пустотой. Проверка идёт по автору, а
--     не по дате, потому что `0119` уже держит их парой (`service_requests_it_approval_check`
--     требует `(it_approved_by IS NULL) = (it_approved_at IS NULL)`), и любая из двух колонок здесь
--     равносильна другой;
--
--   · `<= estimate_revision` — РЕВИЗИЯ НЕ МОЖЕТ ОПЕРЕЖАТЬ САМУ СМЕТУ: подпись на ревизию, которую
--     ещё не предъявляли, означала бы согласование будущего. Именно `<=`, а не равенство. Равенство
--     («подписывают ТЕКУЩУЮ смету») — правило ПУТИ ЗАПИСИ, и ставит его триггер M10; `CHECK` же
--     проверяется при любом изменении строки, а ревизия сметы растёт после визы совершенно законно:
--     предъявили новую смету — прежняя виза обесценилась, но незаконной строка от этого не стала.
--     Равенство здесь заперло бы такую заявку целиком: её нельзя было бы ни отложить, ни
--     прокомментировать, ни отменить, пока кто-нибудь не тронет визу.
ALTER TABLE service_requests ADD CONSTRAINT service_requests_it_revision_check CHECK (
  it_approved_estimate_revision IS NULL
  OR (it_approved_by IS NOT NULL AND it_approved_estimate_revision <= estimate_revision)
);
