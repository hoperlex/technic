-- Вид заявки оргтехники: ремонт или расходники (план
-- `docs/office-equipment-requests-rework-plan.md`, §4.1 и §5, миграция M3; решения Н1 и В12
-- набросков). Выпуск 1 «Цикл и полномочия», волна В2.
--
-- ЗАЧЕМ. «Нужен картридж» и «принтер не печатает» проходят через один и тот же стол, но это разные
-- работы: у первой нет ни сметы, ни визы ИТ, ни закрывающего документа, зато есть строки
-- номенклатуры и списание со склада. Отличить их сегодня нечем — все заявки в таблице одинаковы, —
-- и без вида нельзя ни развести коридоры статусов, ни повесить на «Решена» планку акта только для
-- ремонта, ни завести заявки на расходники выпуском 3.
--
-- ЧТО ЗАВОДИТСЯ: колонка вида с умолчанием, `CHECK` словаря и замена одного уникального индекса
-- двумя частичными — по одному на вид. Триггеров здесь нет.
--
-- ОКНО ВЫКАТА (§3 плана). Штатный деплой накатывает миграции ДО перезапуска сервисов
-- (`docs/schema-cutover-protocol.md`, §1), и старый код в это время вставляет заявку без вида.
-- Он получает `repair` умолчанием — то есть попадает ровно под тот индекс, который его и
-- ограничивал раньше, и разницы не замечает вовсе.
--
-- `DEFAULT 'repair'` ОСТАЁТСЯ НАВСЕГДА, а не снимается выпуском 2 вместе с прочей совместимостью:
-- снятие умолчания сломало бы окно выката, а «вид по умолчанию — ремонт» верно и после него.
--
-- СХЕМА РАЗРЕШАЕТ `consumable` С ЭТОЙ МИГРАЦИИ, А API — НЕТ (§7.3 плана). До выпуска 3 у такой
-- заявки нет ни строк номенклатуры, ни формы, ни списания: заведённая раньше времени, она была бы
-- заявкой без предмета. Держит это контракт создания, а не схема, — и запрет снимается вместе с
-- M12. Писать его сюда `CHECK`'ом нельзя: тогда M12 пришлось бы снимать собственное ограничение
-- ради того, ради чего колонка и заводилась.
--
-- ОБРАТИМОСТЬ. Колонка аддитивна и с умолчанием (`ADD COLUMN ... DEFAULT` таблицу не переписывает,
-- PostgreSQL 11+); один индекс заменяется двумя, покрывающими вместе ровно тот же набор строк, что
-- и снятый. Смысл существующих данных не меняется: все заявки, что были, — ремонты, и после
-- миграции они так и записаны. Протокол выката необратимых миграций
-- (`docs/schema-cutover-protocol.md`) к ней не применяется.

ALTER TABLE service_requests ADD COLUMN kind text NOT NULL DEFAULT 'repair';

-- Словарь `text` + `CHECK`, а не enum: у вида два значения, третьего не предвидится, а enum платит
-- за это пересозданием типа со всеми зависимостями при любой правке (цена видна на
-- `service_request_status`, где мёртвые значения приходится закрывать `CHECK`'ом, а не удалять).
ALTER TABLE service_requests ADD CONSTRAINT service_requests_kind_check
  CHECK (kind IN ('repair','consumable'));

-- ── Одна открытая заявка НА ВИД ──
--
-- Снятый индекс держал «одну открытую заявку на аппарат» целиком: две параллельные означали бы два
-- сервиса, два акта и две гарантии на одну работу (`0105`). С появлением вида это правило стало
-- слишком широким: заявка на картридж не мешает идущему ремонту и не спорит с ним ни за акт, ни за
-- гарантию, а вот два открытых ремонта или две открытых заявки на картриджи по одному аппарату
-- по-прежнему бессмысленны (В12).
--
-- Условие открытости у обоих индексов дословно то же, что у снятого, и это намеренно: `on_hold`
-- в нём не перечислен, то есть отложенная заявка считается ОТКРЫТОЙ (Р109, см. комментарий в
-- `0162`) — техника ждёт того же ремонта, и вторую заявку на неё заводить нечем. Разойдись новые
-- индексы со старым хоть в одном статусе — и миграция тихо поменяла бы правило, которого никто не
-- просил менять.
--
-- Обычное построение индекса, без `CONCURRENTLY`: каждая миграция идёт одной транзакцией
-- (`apps/api/src/db/migration-journal.ts`), где `CONCURRENTLY` невозможен в принципе, а таблица
-- заявок измеряется тысячами строк — построение занимает миллисекунды.
DROP INDEX service_requests_open_per_equipment_unique;

CREATE UNIQUE INDEX service_requests_open_repair_unique
  ON service_requests (office_equipment_id)
  WHERE deleted_at IS NULL AND kind = 'repair' AND status NOT IN ('accepted','cancelled');

CREATE UNIQUE INDEX service_requests_open_consumable_unique
  ON service_requests (office_equipment_id)
  WHERE deleted_at IS NULL AND kind = 'consumable' AND status NOT IN ('accepted','cancelled');
