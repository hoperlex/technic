-- Поимённые исполнители заявки оргтехники (план `docs/office-equipment-requests-rework-plan.md`,
-- §4.2 и §5, миграция M4; решение Н5 набросков). Выпуск 1 «Цикл и полномочия», волна В2.
--
-- ЗАЧЕМ. Исполнитель у заявки сегодня ровно один и всегда внешний — сервисная компания в колонке
-- `service_counterparty_id` (`0105`). Правка заказчика от 21.08.2026 разделила два случая, которые
-- одной ссылкой не выражаются:
--
--   · СВОИ сисадмины назначаются ПОИМЁННО и по нескольку сразу — работу делят люди, и «Ждут меня»
--     обязано отвечать каждому из них персонально;
--   · СЕРВИСНАЯ КОМПАНИЯ назначается ЦЕЛИКОМ, контрагентом: кто из её инженеров поедет, решает
--     она сама, и заводить учётки чужим сотрудникам портал не станет. На ссылке контрагента висят
--     видимость его заявок, смета и акт — разобрать компанию на людей значило бы переписать всё
--     это и вдобавок следить, кто у подрядчика уволился.
--
-- Поэтому слоя два и живут они ОДНОВРЕМЕННО: «наш сисадмин + КопиЛайт» — обычная постановка, а не
-- исключение. Отсюда же разное правило отказа (§4.2 плана): свой снимает свою строку и заявка
-- продолжает жить у остальных, оператор сервиса снимает всю компанию — «часть подрядчика»
-- отказаться не может.
--
-- ЧТО ЗАВОДИТСЯ: таблица назначений, индекс по учётке, снятие старого `CHECK` и инвариант «в
-- рабочем статусе у заявки есть хотя бы один исполнитель» — отложенными constraint-триггерами на
-- обеих таблицах.
--
-- ОКНО ВЫКАТА (§3 плана). Штатный деплой накатывает миграции ДО перезапуска сервисов
-- (`docs/schema-cutover-protocol.md`, §1), то есть какое-то время старый код работает на новой
-- схеме. Здесь это выдержано с запасом: таблица новая и старому коду попросту не видна, а новый
-- инвариант СЛАБЕЕ снятого `CHECK` — он принимает и контрагента (ровно то, что пишет старый код),
-- и поимённые строки. Ни одного движения старого кода эта миграция не запрещает.
--
-- ОБРАТИМОСТЬ. Миграция аддитивна, кроме одного снятого ограничения: новая пустая таблица, индекс,
-- функции и триггеры. Существующие строки заявок не читаются и не меняются — снятие `CHECK` их не
-- касается, а новые триггеры срабатывают только на будущих изменениях. Блокировки первой строкой
-- здесь поэтому нет. Протокол выката необратимых миграций (`docs/schema-cutover-protocol.md`) к ней
-- не применяется: снятие ограничения ничего не ломает ни в одну сторону — вернуть его обратно
-- можно ровно до тех пор, пока не появилась первая заявка со своим исполнителем и без контрагента.

-- ── 1. Таблица назначений ──
CREATE TABLE service_request_executors (
  -- `CASCADE`: назначение — не история, а текущий состав исполнителей. Кто и когда работу вёл,
  -- рассказывает `service_request_status_history`, и удаление заявки её не трогает; держать же
  -- строки назначений мёртвой заявки незачем. Заявки удаляются мягко (`deleted_at`), так что путь
  -- этот и без того редкий — жёсткое удаление остаётся уборкой опечатки первого дня.
  request_id uuid NOT NULL REFERENCES service_requests (id) ON DELETE CASCADE,
  -- `RESTRICT`, а не `SET NULL` и не `CASCADE`: назначенный исполнитель — половина ответа на
  -- вопрос «кто это ведёт», и молча терять её вместе с учёткой нельзя. `SET NULL` тут невозможен
  -- физически (колонка входит в первичный ключ), а `CASCADE` снял бы назначение — то есть уронил
  -- бы заявку в «без исполнителя» удалением постороннего объекта. Учётки в портале и так не
  -- удаляют, а гасят флагом; наткнувшись на `RESTRICT`, человек разберётся с заявками руками.
  user_id uuid NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  -- Кто назначил. `SET NULL`, в отличие от самого исполнителя: это подробность назначения, а не
  -- его суть, и переживать увольнение назначавшего заявка обязана.
  assigned_by uuid REFERENCES users (id) ON DELETE SET NULL,
  assigned_at timestamptz NOT NULL DEFAULT now(),
  -- Ключ — пара «заявка + учётка»: одного человека на одну заявку назначают один раз, повторное
  -- назначение это не второй исполнитель, а ошибка формы. Он же обслуживает главный вопрос
  -- таблицы — «кто ведёт вот эту заявку», — и проверку инварианта ниже.
  PRIMARY KEY (request_id, user_id)
);

COMMENT ON TABLE service_request_executors IS
  'Поимённые исполнители заявки оргтехники (docs/office-equipment-requests-rework-plan.md §4.2): '
  'свои сотрудники строками, сервисная компания остаётся ссылкой service_counterparty_id.';

-- Вторая сторона связи, и вопрос по ней задаётся чаще первой: «Ждут меня» — очередь исполнителя,
-- то есть отбор ПО УЧЁТКЕ, и он же решает доступ («я значусь в исполнителях этой заявки»). Ключ
-- выше начинается с заявки и на такой отбор не работает. Он же закрывает `RESTRICT` при попытке
-- удалить учётку.
CREATE INDEX service_request_executors_user_idx ON service_request_executors (user_id);

-- ── 2. Снятие старого инварианта ──
--
-- `service_requests_executor_check` (`0105`, перевыпущен в `0119` и `0162`) требует непустого
-- КОНТРАГЕНТА в каждом рабочем статусе. Заявка, которую делает свой сисадмин, в него не проходит
-- вовсе — а именно она и есть предмет этой миграции. Снятие ограничения старому коду не мешает:
-- он по-прежнему назначает контрагента, и новый инвариант ниже его назначение принимает.
--
-- Снятие идёт уже в выпуске 1, хотя жёсткие проверки плана вынесены в выпуск 2 (§3, п. 4): снять
-- ограничение — не то же, что поставить. Снятое не запрещает ничего и уронить старый код не может
-- по устройству.
ALTER TABLE service_requests DROP CONSTRAINT service_requests_executor_check;

-- ── 3. Ядро инварианта: у заявки в рабочем статусе есть исполнитель ──
--
-- ПОЧЕМУ НЕ `CHECK`. `CHECK` в Postgres видит только собственную строку и заглянуть в таблицу
-- исполнителей не может. Денормализованный счётчик в заявке под обычным `CHECK` завёл бы второе
-- место, где живёт правда о составе исполнителей, и синхронизировать его пришлось бы тем же
-- триггером. Прецедент приёма — `0035` (полнота категории по значениям ТТХ) и `0172` (покрытие
-- остатка событиями журнала): задача та же — «состояние строки согласовано со строками другой
-- таблицы».
--
-- ФУНКЦИЯ ПРИНИМАЕТ ИДЕНТИФИКАТОР И ПЕРЕЧИТЫВАЕТ ПО НЕМУ СОСТОЯНИЕ — ни `NEW`, ни любой другой
-- снимок ряда в ней не участвуют, и это условие правильности, а не стиль. Внутри одной транзакции
-- законны несколько шагов подряд («сняли исполнителя, вернули статус в „Новую“, назначили другого»),
-- отложенные триггеры срабатывают на коммите все, и любой из них, сверяя свой снимок, дал бы отказ
-- на ровном месте. Перечитанное состояние у всех одно и то же — и оно верное.
--
-- ОНА ЖЕ ВЫЗЫВАЕТСЯ НЕ ТОЛЬКО ТРИГГЕРОМ: ею сверяют базу одним запросом после выката (§11.2) и в
-- db-тестах, а функция, умеющая работать лишь изнутри триггера, для этого недоступна.
--
-- `FOR UPDATE` — не перестраховка, а ФИКСИРОВАННЫЙ ПОРЯДОК БЛОКИРОВОК (§12 плана, риск взаимных
-- блокировок): сначала строка заявки, потом строки исполнителей — никогда наоборот. Маршрут берёт
-- их в том же порядке (Н5 набросков), и повторный `FOR UPDATE` в той же транзакции ему ничего не
-- стоит; а вот назначение, пришедшее скриптом «от исполнителей», без этой блокировки встретилось
-- бы со сменой статуса, идущей «от заявки», — и они заперли бы друг друга.
CREATE FUNCTION service_request_executor_present(p_request_id uuid) RETURNS void
  LANGUAGE plpgsql SECURITY INVOKER SET search_path = public, pg_temp AS $$
DECLARE
  r record;
  n integer;
BEGIN
  SELECT s.status, s.held_from_status, s.service_counterparty_id INTO r
    FROM service_requests s
   WHERE s.id = p_request_id
   FOR UPDATE;

  -- Заявку удалили в этой же транзакции (её назначения ушли по `CASCADE`) — проверять нечего. Тот
  -- же выход, что в `0035` и `0172`: требовать от удалённой строки соответствия невозможно, а
  -- молчаливый `NULL` вместо статуса пропустил бы проверку мимо смысла.
  IF NOT FOUND THEN
    RETURN;
  END IF;

  -- Статусы, в которых исполнителя нет и быть не должно. Проверка идёт по ЭФФЕКТИВНОМУ статусу —
  -- тому, откуда заявку отложили (`0162`): отложенная из «Новой» исполнителя не имеет, и `status`
  -- в этот момент равен `on_hold`, который сам по себе ничего о ведении заявки не говорит.
  --
  -- `it_approved` перечислен НАМЕРЕННО, хотя новый цикл в него не заводит: виза ИТ переехала со
  -- входа на смету (Н3), но в окне выката старый код ещё двигает заявки в этот статус — а он
  -- исполнителя не подразумевает. После выпуска 2 (M8 переводит остаток в «Новую») строк с ним не
  -- остаётся вовсе, и перечисление становится безвредным пережитком, а не ослаблением.
  IF coalesce(r.held_from_status, r.status) IN ('new', 'it_approved', 'cancelled') THEN
    RETURN;
  END IF;

  -- Контрагент — исполнитель сам по себе: сервисная компания назначается целиком, поимённых строк
  -- у неё нет и быть не может.
  IF r.service_counterparty_id IS NOT NULL THEN
    RETURN;
  END IF;

  SELECT count(*) INTO n FROM service_request_executors WHERE request_id = p_request_id;
  IF n = 0 THEN
    -- `check_violation`, а не безымянный `raise_exception` (приём `0035` и `0172`): нарушение
    -- инварианта схемы обязано и по коду ошибки читаться как нарушение ограничения — по нему
    -- маршрут отличает «данные не сходятся» от аварии.
    RAISE EXCEPTION 'Заявка % в рабочем статусе осталась без исполнителя', p_request_id
      USING ERRCODE = 'check_violation';
  END IF;
END
$$;

-- ── 4. Две обёртки: стороны две, и вход у них разный ──
--
-- Обёртки объявляются отдельно от самой проверки, потому что `CREATE TRIGGER` принимает только
-- функцию `RETURNS trigger`, а «функция по идентификатору» триггером быть не может. `RETURN NULL`
-- у обеих: значение `AFTER`-триггера не используется.
CREATE FUNCTION service_requests_executor_present_trg() RETURNS trigger
  LANGUAGE plpgsql SECURITY INVOKER SET search_path = public, pg_temp AS $$
BEGIN
  PERFORM service_request_executor_present(NEW.id);
  RETURN NULL;
END
$$;

-- Сторона исполнителей слушает и `UPDATE`, и проверяет ОБЕ стороны — `OLD.request_id` и
-- `NEW.request_id`. Через маршрут такого пути нет, но прямой `UPDATE … SET request_id = …`
-- перевесил бы исполнителя на другую заявку и оставил прежнюю без единого — а инвариант обязан
-- держаться и против скрипта, иначе он не свойство базы, а договорённость кода.
CREATE FUNCTION service_request_executors_present_trg() RETURNS trigger
  LANGUAGE plpgsql SECURITY INVOKER SET search_path = public, pg_temp AS $$
BEGIN
  IF TG_OP <> 'INSERT' THEN
    PERFORM service_request_executor_present(OLD.request_id);
  END IF;
  IF TG_OP <> 'DELETE' THEN
    PERFORM service_request_executor_present(NEW.request_id);
  END IF;
  RETURN NULL;
END
$$;

-- ── 5. Триггеры: отложенные, а не немедленные ──
--
-- ОТЛОЖЕННЫЕ — потому что законный порядок шагов внутри транзакции бывает любым: «сняли последнего
-- исполнителя и вернули статус в „Новую“» — обычный отказ исполнителя (В17 набросков), и
-- немедленная проверка отбила бы его на первом же шаге, между удалением строки и записью статуса.
-- Симметрично законно и обратное — «перевели в работу и тут же назначили».
--
-- `UPDATE OF status, held_from_status, service_counterparty_id` — а не любой `UPDATE`: инвариант
-- зависит ровно от этих трёх колонок, и гонять проверку на каждом комментарии, правке сметы или
-- подшитом документе значило бы блокировать строку заявки на ровном месте. `INSERT` в списке
-- обязателен: заявка, заведённая сразу в рабочем статусе и без исполнителя, — то же нарушение,
-- вошедшее другой дверью.
CREATE CONSTRAINT TRIGGER service_requests_executor_present
  AFTER INSERT OR UPDATE OF status, held_from_status, service_counterparty_id ON service_requests
  DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION service_requests_executor_present_trg();

CREATE CONSTRAINT TRIGGER service_request_executors_present
  AFTER INSERT OR UPDATE OR DELETE ON service_request_executors
  DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION service_request_executors_present_trg();

-- `ENABLE ALWAYS` — ОТДЕЛЬНОЙ командой: в `CREATE TRIGGER` такого слова нет, а без него на
-- реплике-приёмнике проверка не сработает вовсе. Приём тот же, что у управляющих триггеров `0167`
-- и журнала расходников `0172`.
ALTER TABLE service_requests
  ENABLE ALWAYS TRIGGER service_requests_executor_present;
ALTER TABLE service_request_executors
  ENABLE ALWAYS TRIGGER service_request_executors_present;
