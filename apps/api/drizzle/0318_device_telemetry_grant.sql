-- Право разбора очереди «Письма устройств» и его выдача набору ИТ-службы.
--
-- План — docs/office-equipment-mail-telemetry-plan.md, Р30. Вторая миграция волны и отдельная от
-- таблиц намеренно: таблицы едут этапом приёма, а право нужно только к этапу, на котором появляется
-- очередь. Раньше оно не нужно никому, позже — действия очереди окажутся закрыты для всех.
--
-- ПОЧЕМУ НЕ ОБОШЛИСЬ СУЩЕСТВУЮЩИМ `officeEquipment.review`. Оно подписано «проверяет сообщения об
-- отсутствующей технике» и требует `officeEquipment.write` — ведения всего парка. Выдать очередь
-- через него значило бы либо закрыть её от ИТ-службы, для которой она и заводится (у той `write`
-- нет намеренно), либо раздать ИТ-службе запись во весь справочник ради одной кнопки.
--
-- ЧТЕНИЕ СЮДА НЕ ВХОДИТ: показания в карточке открыты по `officeEquipment.read` всем, кому открыта
-- сама карточка. Право закрывает ДЕЙСТВИЯ очереди — те, что решают, чья наработка чьей карточке
-- принадлежит.
--
-- ВЫКАТ БЕЗОПАСЕН ПРИ РАБОТАЮЩЕМ ПОРТАЛЕ: право хранится текстом и сверяется со словарём при
-- чтении, незнакомый ключ старый код отбрасывает, а старой реализации за новым правом нет вовсе.

INSERT INTO grant_permissions (grant_id, permission)
SELECT g.id, s.permission
FROM grants g
JOIN (VALUES
  ('office_equipment_it_approver', 'officeEquipment.telemetry')
) AS s (code, permission) ON s.code = g.code
ON CONFLICT (grant_id, permission) DO NOTHING;
