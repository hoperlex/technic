-- Техника из «Списка автотранспорта строительно-дорожных машин, обслуживающих строительные
-- объекты АО "СУ-10", на 31.07.2026» — те строки, которых в парке портала нет.
--
-- Сверка: 61 строка списка против живых записей `vehicles` по нормализованному госномеру
-- (vehicle_reg_normalize, 0015). 43 машины уже заведены сидами 0028 и 0073: разное написание
-- номера («Е 022 СТ 77» против «Е022СТ77», латинское «O263BO777» против кириллического)
-- нормализация схлопывает, и повторно они не заводятся. Оставшиеся 18 — здесь.
--
-- Решения по строкам:
--
-- 1. Реквизитов, кроме наименования и госномера, в списке нет вовсе: ни заводского номера, ни
--    ПСМ/ПТС, ни года выпуска, ни изготовителя, ни инвентарного номера. Машины заводятся с
--    пустыми реквизитами — так они попадают в справочник и доступны для заявок, а паспортные
--    данные дозаполняются через портал, когда появятся. Достать их из каталогов изготовителей
--    нельзя: открытые источники в этом проекте питают ТТХ модели, а не реквизиты конкретного
--    экземпляра (ADR 0023 §1).
--
-- 2. Пятнадцать телескопических погрузчиков (Manitou, Weidemann, Wacker Neuson) — первое
--    наполнение типа `telescopic_loaders`: сам тип заведён миграцией 0079, машин в нём не было
--    ни одной. Ради этих строк тип и отделяли от вилочных погрузчиков.
--
-- 3. Два МАЗ-МКМВ9В (У702АС777, У782АС777) заведены тяжёлыми манипуляторами. Отчёт
--    классификации помечал их мультилифтами, но тип «Бункеровозы, мультилифты» в плоский
--    классификатор сознательно не заведён — его принадлежность к виду не определена (ADR 0007
--    §8, 0016). Список называет обе машины «Бортовая с манипулятором», и это то же, что
--    исходное сопоставление 0010 («Тяжелые манипуляторы … фактически мультилифты»). Появится
--    решение по виду — тип сменится через справочник, смена типа у машины разрешена.
--
-- 4. Седельный тягач КАМАЗ (Е646СК799) — первая машина типа `tractor_trailers` в парке. Индекс
--    модели список не называет, поэтому марка перенесена дословно, одним словом: потерять
--    единственное, что о машине известно, хуже, чем держать в справочнике запись, которую
--    уточнят по ПТС. Так же переносил наименования сид 0028 («780745, автомобиль»).
--
-- 5. Категория (ТТХ) не проставляется ни одной машине: у телескопических погрузчиков ТТХ не
--    привязаны вовсе (0079), у тяжёлых манипуляторов г/п стрелы по индексу надстройки не
--    находится (0048), у тягача характеристик нет. Требование к категории прав, наоборот,
--    берётся у типа — тем же правилом, что в 0059: тягачу CE, манипуляторам C, спецтехнике
--    ничего (за неё садятся по удостоверению тракториста-машиниста, его категории не заведены).
--
-- 6. Написание, где источник сам себе противоречит. Manitou в списке записан и слитно
--    («MT1233»), и через пробел («MT 1337»): vehicle_model_normalize пробел не схлопывает, и
--    буквальный перенос развёл бы одну серию по разным записям справочника — то, что миграция
--    0043 потом разбирала руками. Записано единообразно, как в каталоге изготовителя.
--    Номера двух Weidemann набраны цифрами вперёд («5865ХМ 50», «9252 ХО 50») — записаны в том
--    же порядке, что и шесть десятков номеров спецтехники в базе: серия, номер, регион.
--    Нормализация эти две формы не сводит, поэтому порядок здесь — решение, а не косметика.
--
-- Список — срез техники на объектах, а не весь парк: около шестидесяти машин базы (самосвалы,
-- легковые, катки, часть погрузчиков) в него не входят. Их статусы миграция не трогает:
-- отсутствие в рабочем списке не означает выбытия из парка.
--
-- Расхождение, оставленное к сверке по ПСМ и здесь НЕ правящееся: список числит JCB TLT30C на
-- ХО 4344 50, тогда как в базе на этом номере MUSTANG 2700 V (зав. MMC02700А00041820,
-- ПСМ ТС 383122), а JCB TLT30C — на ХО 4345 50 (зав. JCBTLT30C71175444, ПСМ TT 274729). Номера
-- соседние, и это похоже на опечатку в одном из двух документов; какой из них прав, решается по
-- паспорту машины, а не миграцией.
--
-- Идемпотентность: вставляются только госномера, которых нет среди живых записей. Повторный
-- накат на базу, где машину уже завели руками через справочник, не создаёт дубля и не трогает
-- заведённое.

-- ── 1. Марки/модели ─────────────────────────────────────────────────────────────────────────
-- Изготовитель не заполняется: в списке его нет, а выводить из марки — то же придумывание
-- реквизита, что и год выпуска.
INSERT INTO vehicle_models (vehicle_type_id, name)
SELECT t.id, x.name
FROM (VALUES
  ('tractor_trailers',   'КАМАЗ'),
  ('heavy_manipulators', 'МАЗ-МКМВ9В'),
  ('telescopic_loaders', 'Manitou MT 1233'),
  ('telescopic_loaders', 'Manitou MT 1337'),
  ('telescopic_loaders', 'Manitou MT 1740'),
  ('telescopic_loaders', 'Weidemann T5522'),
  ('telescopic_loaders', 'Wacker Neuson TH522')
) AS x(type_code, name)
JOIN vehicle_types t ON t.code = x.type_code
ON CONFLICT (vehicle_type_id, normalized_name) DO NOTHING;

-- ── 2. Машины ───────────────────────────────────────────────────────────────────────────────
-- Порядок строк повторяет список: тягач (6), манипуляторы (9–10), телескопические
-- погрузчики (36–50).
INSERT INTO vehicles (
  vehicle_type_id, vehicle_model_id, ownership, registration_number,
  required_qualification_category_id, status, source_name
)
SELECT
  t.id,
  m.id,
  'own'::vehicle_ownership,
  x.reg,
  t.default_qualification_category_id,
  'active'::vehicle_status,
  'Список автотранспорта АО "СУ-10" на 31.07.2026'
FROM (VALUES
  ('tractor_trailers',   'КАМАЗ',               'Е646СК799'),
  ('heavy_manipulators', 'МАЗ-МКМВ9В',          'У702АС 777'),
  ('heavy_manipulators', 'МАЗ-МКМВ9В',          'У782АС 777'),
  ('telescopic_loaders', 'Manitou MT 1233',     'ХО 4576 50'),
  ('telescopic_loaders', 'Manitou MT 1337',     'ХО 4491 50'),
  ('telescopic_loaders', 'Manitou MT 1740',     'ХО 4572 50'),
  ('telescopic_loaders', 'Weidemann T5522',     'ХО 4631 50'),
  ('telescopic_loaders', 'Weidemann T5522',     'ХО 4654 50'),
  ('telescopic_loaders', 'Weidemann T5522',     'ХО 8004 50'),
  ('telescopic_loaders', 'Weidemann T5522',     'ХМ 5865 50'),
  ('telescopic_loaders', 'Weidemann T5522',     'ХО 9252 50'),
  ('telescopic_loaders', 'Wacker Neuson TH522', 'ХМ 1888 50'),
  ('telescopic_loaders', 'Wacker Neuson TH522', 'ХМ 1886 50'),
  ('telescopic_loaders', 'Wacker Neuson TH522', 'ХМ 0763 50'),
  ('telescopic_loaders', 'Wacker Neuson TH522', 'ХМ 0764 50'),
  ('telescopic_loaders', 'Wacker Neuson TH522', 'ХМ 9009 50'),
  ('telescopic_loaders', 'Wacker Neuson TH522', 'ХМ 9010 50'),
  ('telescopic_loaders', 'Wacker Neuson TH522', 'ХМ 9014 50')
) AS x(type_code, model_name, reg)
JOIN vehicle_types t ON t.code = x.type_code
JOIN vehicle_models m
  ON m.vehicle_type_id = t.id AND m.normalized_name = vehicle_model_normalize(x.model_name)
WHERE NOT EXISTS (
  SELECT 1 FROM vehicles v
  WHERE v.registration_number_normalized = vehicle_reg_normalize(x.reg)
    AND v.deleted_at IS NULL
);
