-- Учётка после архива (ADR 0063): email и физлицо занимает действующая запись, а не строка,
-- лежащая в архиве.
--
-- До этой миграции индексы были полными, и уход в архив выжигал адрес навсегда: человек, которому
-- отказали в регистрации, не мог зарегистрироваться заново, а администратор не мог завести ему
-- учётку сам. Приём тот же, что у ИНН контрагента (ADR 0010): натуральный ключ освобождается
-- вместе с уходом записи из работы.
--
-- Данные чистить не нужно — частичный индекс освобождает архивные адреса задним числом. Дублей
-- среди действующих учёток не появится: до сих пор их не допускал полный индекс.
DROP INDEX users_email_unique;
CREATE UNIQUE INDEX users_email_unique ON users (email) WHERE deleted_at IS NULL;

-- «Одна учётная запись на человека» — тоже про действующие. Иначе вернувшийся сотрудник обходил
-- бы первую блокировку и упирался во вторую: физлицо у него то же самое.
DROP INDEX users_person_unique;
CREATE UNIQUE INDEX users_person_unique ON users (person_id)
  WHERE person_id IS NOT NULL AND deleted_at IS NULL;

