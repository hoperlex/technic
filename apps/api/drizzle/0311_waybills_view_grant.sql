-- Набор полномочия «Путевые листы: просмотр и печать» (ADR 0192) — журнал листов площадке и отделу.
--
-- ЧТО ОТКРЫВАЕТ. Одно право, `waybills.read`, и в модуле оно открывает ровно то, что заказчик
-- просил: журнал листов, печать бланка в PDF, выгрузку его же файлом и сканы, подшитые к листу.
-- Подшивка (`waybills.files`), списание номера (`waybills.cancel`), пустой бланк
-- (`waybills.issueBlank`) и коррекция задним числом (`waybills.correct`) в набор не входят и
-- площадке не выдаются ничем: бумагу она видит, а ведёт её диспетчерская.
--
-- ПОЧЕМУ ЭТОТ НАБОР СТАЛ ВОЗМОЖЕН ТОЛЬКО СЕЙЧАС. До этого выката клетки `waybills × object` и
-- `waybills × department` в `GRANT_SCOPE_MATRIX` стояли `forbidden`, и журнал листов был в том
-- файле ПРИМЕРОМ модуля без области: закрытость держалась не предикатом, а тем, что площадочным
-- ролям право не выдают. Набор с `waybills.read`, выданный тогда, отдал бы держателю листы всей
-- компании вместе с персональными данными водителей. Поэтому порядок работы был обратный
-- привычному: сперва у модуля появилась область (`waybillVisibilityWhere`, `lib/access.ts`) —
-- по талонам листа (`waybill_requests` → `vehicle_requests`) и по заявке-основанию ЭСМ-2
-- (`waybills.source_request_id`), — и только вслед за ней сменились клетки матрицы. Барьер выдачи
-- читает матрицу: верни предикат обратно — и выдача этого набора перестанет проходить сама.
--
-- ПЕРСОНАЛЬНЫЕ ДАННЫЕ УХОДЯТ ВМЕСТЕ С БУМАГОЙ, И ЭТО ОБЪЯВЛЕННОЕ РАСШИРЕНИЕ. В бланке печатаются
-- СНИЛС и номер водительского удостоверения (ADR 0037), а решение реформы доступа от 18.08.2026
-- гласило «ПДн водителей вне объектных ролей: наборов „Гараж“ и „Ведение парка“ в каталоге нет».
-- ADR 0192 отменяет тот пункт ровно в одной части — путевой лист площадка получает, потому что
-- работает по нему на объекте. Карточки водителей (`drivers.read`), парк и гараж ей по-прежнему
-- закрыты, и наборов под них в каталоге нет.
--
-- РОЛЕЙ ШЕСТЬ, И ТРИ ИЗ НИХ УПРАЗДНЯЕМЫЕ. `site`, `department`, `department_head` — целевые роли
-- реформы; `shtab`, `rukstroy`, `commandant` — те, на которых площадки живут СЕГОДНЯ: роль `site`
-- на момент этого выката не назначена ни одной учётке, перевод идёт отдельными этапами 8 и 9
-- (`drizzle/pending/stage8-*`). Без трёх упраздняемых имён набор было бы некому выдать, а заказчику
-- бумага нужна сейчас. Ровно поэтому набор объявлен МОДУЛЬНЫМ (`MODULE_GRANT_CODES`), а не ролевым:
-- ролевые участвуют в тождествах перевода и с упраздняемой ролью совместимыми не объявляются
-- (страж `role-migration-contracts`).
--
-- СЛЕД, КОТОРЫЙ ОБЯЗАН СРАБОТАТЬ НА CLEANUP'Е. `pending/stage8-cleanup-site-role.sql` снимает
-- `grant_roles` упраздняемых ролей целиком (`DELETE ... WHERE role IN ('shtab','rukstroy',
-- 'commandant')`), то есть заберёт и три здешние строки. Тем же релизом эти имена обязаны уйти из
-- `MODULE_GRANTS.waybills_view` в контрактах: страж каталога (`grants-catalog.db.test.ts`) сверяет
-- обе стороны и покраснеет, если они разъедутся. Отдельной правки миграции при этом не нужно —
-- каталог в базе приводит к объявленному составу тот же cleanup.
--
-- `manager`, `dispatcher`, `mechanic`, `chief_mechanic` и `admin` в списке отсутствуют намеренно:
-- `waybills.read` у них уже есть от матрицы ролей, и строка совместимости означала бы набор, выдача
-- которого не меняет ничего. `driver` — по общему правилу: наборов эта роль не принимает вовсе.
--
-- ЧЕГО ЗДЕСЬ НЕТ. Ни одной строки `user_grants`. Миграция заводит набор, его состав и совместимые
-- роли; кому поставить галочку в окне учётки — решает администратор портала поимённо, и решение это
-- остаётся в реестре выдач с автором и временем.
--
-- КОД НАБОРА НЕ МЕНЯЕТСЯ НИ ПРИ КАКИХ УСЛОВИЯХ: по нему набор находят миграции каталога, журнал
-- действий и реестр выдач. Правятся название, описание и состав.
--
-- ОБРАТИМОСТЬ. Трогаются только три таблицы каталога, схема не меняется. Откат — удаление набора,
-- пока у него нет держателей (`RESTRICT` на `user_grants`).

-- ── 1. Набор ──

INSERT INTO grants (code, name, description, is_system) VALUES
  (
    'waybills_view',
    'Путевые листы: просмотр и печать',
    'Журнал путевых листов в пределах своей области: площадка видит листы, выписанные по заявкам '
    'её объектов, отдел — по заявкам своего отдела и площадок своего отдела. Лист, в котором есть '
    'хотя бы один свой талон, виден целиком — вместе с номерами чужих заявок в соседних строках '
    'задания. Держатель печатает бланк, выгружает его файлом и открывает подшитые к листу сканы; '
    'выписать, аннулировать, подшить документ или исправить лист задним числом он не может. В '
    'бланке печатаются персональные данные водителя — СНИЛС и номер удостоверения; каждая печать и '
    'каждая выгрузка пишутся в журнал действий пофамильно. Лист, к которому не привязано ни одной '
    'заявки (пустой бланк, рейс-перегон), держателю набора не виден: область считать не по чему.',
    true
  )
ON CONFLICT (code) DO UPDATE
   SET name = EXCLUDED.name, description = EXCLUDED.description, updated_at = now();

-- ── 2. Состав: одно право ──

INSERT INTO grant_permissions (grant_id, permission)
SELECT g.id, s.permission
FROM grants g
JOIN (VALUES
  ('waybills_view', 'waybills.read')
) AS s (code, permission) ON s.code = g.code
ON CONFLICT (grant_id, permission) DO NOTHING;

-- ── 3. Совместимые роли ──
--
-- «Кому набор можно назначить», а не «кому он выдан».

INSERT INTO grant_roles (grant_id, role)
SELECT g.id, s.role::role
FROM grants g
JOIN (VALUES
  ('waybills_view', 'site'),
  ('waybills_view', 'department'),
  ('waybills_view', 'department_head'),
  ('waybills_view', 'shtab'),
  ('waybills_view', 'rukstroy'),
  ('waybills_view', 'commandant')
) AS s (code, role) ON s.code = g.code
ON CONFLICT (grant_id, role) DO NOTHING;

-- ── 4. Караул: состав в базе равен объявленному ──
--
-- То же, что сверяет страж-тест, но на глазах у оператора выката. Проверяется и то, что миграция
-- никому ничего не выдала: строка `user_grants`, дописанная сюда позже, и есть то расширение
-- доступа, которого в миграции быть не должно.
DO $$
DECLARE trouble text;
BEGIN
  SELECT string_agg(msg, '; ')
    INTO trouble
    FROM (
      SELECT format('набора нет или он не системный (найдено строк: %s)', count(*)) AS msg
        FROM grants
       WHERE code = 'waybills_view' AND is_system AND deleted_at IS NULL
      HAVING count(*) <> 1
      UNION ALL
      SELECT format('прав в наборе %s вместо одного', count(*))
        FROM grant_permissions gp
        JOIN grants g ON g.id = gp.grant_id
       WHERE g.code = 'waybills_view'
      HAVING count(*) <> 1
      UNION ALL
      SELECT format('совместимых ролей %s вместо шести', count(*))
        FROM grant_roles gr
        JOIN grants g ON g.id = gr.grant_id
       WHERE g.code = 'waybills_view'
      HAVING count(*) <> 6
      UNION ALL
      SELECT format('набор кому-то выдан (строк user_grants: %s)', count(*))
        FROM user_grants ug
        JOIN grants g ON g.id = ug.grant_id
       WHERE g.code = 'waybills_view'
      HAVING count(*) <> 0
    ) AS checks;
  IF trouble IS NOT NULL THEN
    RAISE EXCEPTION 'Каталог набора «Путевые листы: просмотр и печать» собран не так: %', trouble;
  END IF;
END $$;
