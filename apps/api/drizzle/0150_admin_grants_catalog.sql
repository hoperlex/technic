-- Административная часть стартового каталога полномочий (план реструктуризации модели доступа,
-- §10 «разгружающие администратора» и §15, этап 4).
--
-- Четыре набора, которые снимают с администратора работу, не требующую администратора: обмен
-- справочниками, архив, журнал действий и пустой бланк. Все девять «запертых» прав, кроме трёх
-- объявленных неотчуждаемыми (`records.purge`, `users.manage`, `waybills.correctBeyondLimit`),
-- после этой миграции существуют в каталоге и могут быть выданы поимённо.
--
-- **Миграция не расширяет доступ ни одной живой учётке, и это её главное свойство.** Наборы
-- заводятся, но не выдаются: ни одной строки `user_grants` здесь нет и быть не должно (§10 —
-- «этапы 4 и 4б заводят наборы, никому их не выдавая»). Права держателей до и после этой миграции
-- совпадают до единого; изменится только содержимое каталога, который видит администратор.
--
-- Почему административная часть ехала отдельно от ролевой (§16.1): она не зависела ни от одного
-- открытого вопроса, тогда как «Заказ техники» и обе визы ждали решения о роли `site`. Наборы
-- «Коррекция», «Откат статуса» и «Рассылки» в каталоге не появятся вовсе: они заводились ради
-- перевода менеджеров в диспетчеры, а перевод отменён решением №2 (17.08.2026) — без него это были
-- бы права, вынутые из роли без единого получателя.
--
-- Миграция аддитивная: она добавляет строки в три таблицы каталога и ничего не переключает.
-- Протокол выката необратимых миграций (`docs/schema-cutover-protocol.md`) к ней не применяется —
-- схема не меняется вовсе. Откат этапа — снятие того, что посеяла миграция (§15): удалить четыре
-- набора можно ровно пока у них нет держателей, что и обеспечивает `RESTRICT` на `user_grants`.

