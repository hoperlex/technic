INSERT INTO grant_permissions (grant_id, permission)
SELECT g.id, s.permission
FROM grants g
JOIN (VALUES
  -- Обмен справочниками: выгрузка и загрузка вместе. Загрузка без выгрузки — правка справочника
  -- вслепую: не посмотрев, что в нём лежит, файл готовят наугад.
  ('directory_exchange'  , 'directories.export'),
  ('directory_exchange'  , 'directories.import'),
  -- Архивариус: чтение архива и возврат из него. `archive.restore` в одиночку бесполезен —
  -- удалённая запись без `archive.read` отвечает 404 (`archiveWhere`, план §2).
  ('archivist'           , 'archive.read'),
  ('archivist'           , 'archive.restore'),
  -- Аудитор: одно право, и оно входное — `PERMISSION_REQUIRES['audit.read']` объявляет это прямо,
  -- чтобы набор не потребовал `users.manage` (входное право модуля витрины `admin`), которое не
  -- выдаётся полномочиями ни при каких условиях.
  ('auditor'             , 'audit.read'),
  -- Бланки: одно право. Ручки выписки закрыты `waybills.read` и `vehicleRequests.status`, поэтому
  -- набор осмыслен только у того, кто журнал уже ведёт; обе совместимые роли ведут.
  ('strict_report_blanks', 'waybills.issueBlank')
) AS s (code, permission) ON s.code = g.code;

-- Совместимые роли — «кому набор можно назначить», а не «кому он выдан» (§10).
--
-- Обе диспетчерские роли у всех четырёх наборов: менеджер — живая должность с тем же кругом
-- работы, разошлись они четырьмя правами (`waybills.correct`, `requests.rollbackStatus`, обе
-- рассылки), и ни одно административное право в эту четвёрку не входит. Оставить набор одному
-- диспетчеру значило бы, что администратора разгружает половина диспетчерской.
--
-- Строки постоянные, а не переходные. Решением заказчика от 17.08.2026 менеджер и диспетчер
-- **остаются двумя ролями** (§16, решение №2): тройка расхождений признана сутью различия
-- должностей, слияние отменено вместе с этапом 7. Прежняя редакция этого комментария обещала, что
-- `manager` станет мёртвым значением enum и строка уйдёт вместе с ним, — обещание снято.
--
-- Барьеры выдачи каждая пара «роль × право» проходит (`validateGrantAssignment`, проверено тестом
-- `grants-contracts.test.ts`): у обеих ролей своей оси области нет, и модули `directories`,
-- `records`, `admin`, `waybills` дают им клетку `global` — сужать нечего, набор не открывает данных
-- сверх тех, что модуль показывает целиком по построению.
INSERT INTO grant_roles (grant_id, role)
SELECT g.id, s.role::role
FROM grants g
JOIN (VALUES
  ('directory_exchange'  , 'dispatcher'),
  ('directory_exchange'  , 'manager'),
  ('archivist'           , 'dispatcher'),
  ('archivist'           , 'manager'),
  ('auditor'             , 'dispatcher'),
  ('auditor'             , 'manager'),
  ('strict_report_blanks', 'dispatcher'),
  ('strict_report_blanks', 'manager')
) AS s (code, role) ON s.code = g.code;

