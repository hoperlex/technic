-- Бланк путевого листа — умолчание, а не пустое место (ADR 0065).
--
-- Колонка заведена [0060](0060_waybill_organization_and_vehicle_fields.sql) кодом формы, а не
-- флагом, и это решение остаётся. Меняется другое: NULL означал «на такую технику лист не
-- выписывается», и это оказалось неверным ответом на вопрос, которого справочник не задавал.
--
-- Пустое значение получал КАЖДЫЙ тип, заведённый администратором через портал: `waybill_form_code`
-- нет ни в форме заведения типа, ни в схеме правки, ни в DTO — проставить его можно было только
-- миграцией. Тип «Полуприцеп низкорамный», заведённый так, молча выпал из документа целиком:
-- форма перевода в работу не поднимала блок «Маршрут», рейс не заводился, лист выписывать было
-- нечем и не с чего. Софтлок на уровне интерфейса: администратор видит заведённый тип, работает
-- им заявка, а бумаги у неё нет и появиться не может.
--
-- Поэтому: у собственной техники лист есть ВСЕГДА, и по умолчанию это 4-П. Отсутствие листа
-- осталось признаком одной-единственной вещи — принадлежности (`vehicles.ownership`): на арендную
-- машину лист выписывает арендодатель. Тип отвечает не на «выписывается ли», а только на «каким
-- бланком»: 4-П либо форма № 3 у легковых.
--
-- Спецтехника попадает под backfill вместе со всеми, и это не натяжка: её перегон на объект уже
-- сегодня печатается по 4-П (`routeWaybillForm`, ADR 0057 п. 7) — значение совпадает с тем, что
-- портал делает и без него. Прежний запрет «типам спецтехники бланк проставлять нельзя» держался
-- на том, что заполненная колонка читалась как пропуск в грузовой рейс (`assertRouteVehicle`);
-- эта вторая роль с колонки снята, а вид ТС границей замены быть перестал.
--
-- Идемпотентно: повторный накат не найдёт NULL, а DEFAULT и NOT NULL уже стоят.

UPDATE vehicle_types SET waybill_form_code = '4p' WHERE waybill_form_code IS NULL;

ALTER TABLE vehicle_types
  ALTER COLUMN waybill_form_code SET DEFAULT '4p',
  ALTER COLUMN waybill_form_code SET NOT NULL;

-- CHECK держал «NULL либо один из трёх» — первая половина условия больше не нужна.
ALTER TABLE vehicle_types DROP CONSTRAINT vehicle_types_waybill_form_check;
ALTER TABLE vehicle_types
  ADD CONSTRAINT vehicle_types_waybill_form_check
    CHECK (waybill_form_code IN ('4p', 'leg3', 'esm2'));
