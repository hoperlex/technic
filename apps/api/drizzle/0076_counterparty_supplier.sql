-- Поставщик как роль контрагента (ADR 0010, ADR 0051).
--
-- Материалы возят сторонние организации, и хранить их было негде: типы контрагентов покрывали
-- стройку, вывоз мусора и аренду техники. Отдельная таблица не нужна — набор полей тот же, что
-- у прочих ролей, различает их колонка `type` (решение 1 ADR 0010). ИНН остаётся обязательным:
-- идентичность контрагента держится на нём (решение 2), и поставщик — сторона договора, у которой
-- реквизиты есть по определению.
--
-- Значение enum используется только со следующей миграции: применить его в той же транзакции, где
-- оно добавлено, Postgres не даёт (приём 0022/0023 и 0032/0033 — раннер выполняет файл целиком
-- в одной транзакции).
ALTER TYPE counterparty_type ADD VALUE IF NOT EXISTS 'supplier';
