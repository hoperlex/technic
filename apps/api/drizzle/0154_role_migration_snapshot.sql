-- Снимок перевода ролей: таблица `user_role_migration` плюс внешний ключ и CHECK на происхождение
-- назначения (план реструктуризации модели доступа, §13 «снимок исходных ролей» и §13.2 «перевод
-- ролей — тоже три релиза»; ADR 0113, ADR 0106 решение 3).
--
-- Это первая из двух миграций шага **prepare** этапа 8. Здесь только структура; строки в неё пишет
-- следующая (0155), а этап 9 добавляет свои (0156).
--
-- ЗАЧЕМ СНИМОК ВООБЩЕ. После перевода `shtab → site` происхождение учётки теряется безвозвратно:
-- три роли площадки становятся одной, и «был штабом, а не комендантом» больше нигде не записано.
-- «Обратный UPDATE» после этого неоднозначен — вернуть-то роль можно, но какую именно? Полномочия
-- ответа не дают: «Заказ техники» есть и у бывшего штаба, и у бывшего руководителя строительства.
-- Поэтому роль до перевода записывается ДО него, а не выводится после.
--
-- ПОЧЕМУ ЗАВОДИТСЯ СЕЙЧАС, А НЕ В 1a ВМЕСТЕ С `user_grants`. Решение 3 ADR 0106 отвергло «завести
-- пустой сразу»: таблица без единого писателя пережила бы несколько релизов и к моменту, когда
-- понадобится, потеряла бы смысл в глазах читающего схему, а внешний ключ на несуществующую
-- сущность база и вовсе не приняла бы. Поэтому в 1a колонка `user_grants.migration_id` заведена
-- как `uuid NULL` без ключа — и этот файл её достраивает.
--
-- ОБРАТИМОСТЬ. Файл аддитивен: новая таблица и два ограничения на существующей. Откат — снять
-- ограничения и удалить таблицу; данных, кроме тех, что посеют 0155 и 0156, в ней нет, а те
-- откатываются вместе с назначениями, на которые ссылаются. Ни одной строки `users` файл не
-- трогает: доступ после наката ровно тот же, что до.

CREATE TABLE user_role_migration (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- CASCADE: снимок отвечает на «кем человек был и что ему выдали вместо этого», и у удалённой
  -- насовсем учётки (`records.purge`) обоих вопросов не существует — возвращать роль некому.
  -- След самого действия при этом не пропадает: он в журнале (ADR 0088), который append-only.
  user_id uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  -- Номер этапа плана: 8 — три роли площадки, 9 — руководитель отдела. Числом, а не enum'ом:
  -- значение служит пометкой «каким переводом», перечнем не управляет ничего, а новый этап не
  -- должен требовать ALTER TYPE. CHECK на конкретные номера не ставится по той же причине.
  stage smallint NOT NULL,
  -- Роль ДО перевода — то, ради чего таблица заведена. NOT NULL: снимок без прежней роли не
  -- отвечает ни на один из трёх вопросов, ради которых он существует.
  role_before role NOT NULL,
  -- Роль ПОСЛЕ перевода, известная уже сейчас: переводом управляет эта таблица, а не список ролей
  -- внутри миграции. Отсюда и условность перевода, и условность отката — оба сравнивают текущую
  -- роль учётки с одной из этих двух колонок и молча пропускают ту, которую успели сменить руками.
  role_after role NOT NULL,
  -- Когда выданы замещающие наборы (шаг prepare). Не момент перевода: между ними проходит релиз.
  prepared_at timestamptz NOT NULL DEFAULT now(),
  -- Когда учётка переведена; NULL — наборы выданы, роль ещё прежняя. Это и есть состояние, в
  -- котором система живёт весь релиз между prepare и migrate, и по нему же считается диффом
  -- «кто ещё остался на старой роли».
  migrated_at timestamptz,
  -- Одна учётка — один снимок на этап. Ограничение несёт двойную службу: делает повторный накат
  -- prepare безвредным (`ON CONFLICT DO NOTHING`) и запрещает второй снимок того же перевода, по
  -- которому непонятно, какую роль возвращать. Имя задано явно — по нему ограничение находят
  -- схема приложения и тесты; автоматическое (`..._user_id_stage_key`) с ними бы разошлось.
  CONSTRAINT user_role_migration_user_stage_unique UNIQUE (user_id, stage)
);

-- Отдельного индекса по `stage` нет намеренно: строк здесь столько же, сколько площадочных и
-- отдельских учёток, то есть сотни, и перебор дешевле лишнего индекса, который придётся
-- поддерживать вечно ради трёх запросов выката.

-- Внешний ключ назначения на снимок — та самая связь, которой в 1a не было, потому что не на что
-- было ссылаться.
--
-- NO ACTION, а не RESTRICT, и различие здесь не стилистическое. Оба запрещают удалить снимок,
-- пока на него ссылаются назначения, но RESTRICT проверяется немедленно, а NO ACTION — в конце
-- оператора. Удаление учётки каскадом сносит и `user_grants`, и `user_role_migration` одним
-- оператором: с RESTRICT такое удаление упало бы на полпути, с NO ACTION к моменту проверки
-- ссылающихся строк уже нет. Ручное же удаление снимка при живых назначениях по-прежнему
-- отклоняется — а именно оно и есть тот случай, ради которого ключ ставится: откат перевода
-- сначала снимает свои назначения, и только потом убирает снимок.
ALTER TABLE user_grants
  ADD CONSTRAINT user_grants_migration_fk
  FOREIGN KEY (migration_id) REFERENCES user_role_migration (id);

-- Согласованность происхождения: «выдано переводом» и «известно, каким переводом» — одно и то же
-- утверждение, и разъехаться половинам нельзя ни в одну сторону. `origin = 'migration'` без
-- ссылки означал бы назначение, которое откат не найдёт и не снимет; ссылка при `origin = 'manual'`
-- — назначение, которое откат снял бы, хотя выдал его администратор своей рукой.
--
-- Существующие строки условию удовлетворяют: до этого файла писателя у `origin = 'migration'` не
-- было вовсе (`backfill-grants.ts` ставит `manual` и `migration_id` не заполняет), и проверка
-- накатывается без `NOT VALID`.
ALTER TABLE user_grants
  ADD CONSTRAINT user_grants_migration_origin_check
  CHECK ((origin = 'migration') = (migration_id IS NOT NULL));
