-- Реквизиты заказчика путевых листов (план `docs/waybill-forms-corrections-plan.md`, §5.1, этап 2).
--
-- ЧТО ПОЧИНЕНО. Графа «В чьё распоряжение (наименование и адрес заказчика)» в 4-П и графа
-- «Заказчик» в ЭСМ-2 печатали объект заявки: наименование стройки, её адрес и телефон
-- ответственного за встречу машины. Это не заказчик — это площадка, куда машину послали. Заказчик
-- у всех листов один: генподрядчик, в чьё распоряжение техника и поступает.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ КОЛОНКИ У ОБЪЕКТА ИЛИ КОНТРАГЕНТА. У объекта строительства
-- (`construction_objects`) есть только код, наименование и адрес — самой стройки, а не заказчика;
-- у контрагента (`counterparties`, сид 0025) нет ни адреса, ни телефона, и ООО «СУ-10» заведено там
-- без реквизитов. Заводить реквизиты бумаги в справочнике внешних сторон значило бы, что правка
-- карточки контрагента меняет шапку будущих бланков за спиной у бухгалтерии.
--
-- ПОЧЕМУ ОДИНОЧКА. Строка ровно одна — как `organizations.is_primary` отвечает «чей это лист», так
-- эта отвечает «в чьё распоряжение он выписан». Вторую строку запрещает первичный ключ с CHECK:
-- сборщику снимка не нужно выбирать между двумя ответами, а «выбирать не из чего» лучше выражать
-- схемой, чем договорённостью. Настройка верна, пока генподрядчик один; появится второй — реквизит
-- переезжает к объекту строительства, и это отдельная работа, названная в ADR прямо.
--
-- ПОЧЕМУ РЕКВИЗИТЫ ЗАВОДИТ СИД. Тем же рассуждением, каким миграция 0075 завела основную
-- организацию: «шаг настройки администратора» существует только на бумаге, если выполнить его
-- нечем. Экрана у этой настройки нет, ручек CRUD в API нет, и оставленный на администратора шаг
-- кончился бы пустой графой на каждом напечатанном бланке. Значения известны точно — их называет
-- заказчик (§4 плана), а не миграция угадывает.
--
-- ПРАВИТСЯ SQL, а не формой: тем же порядком, каким правятся реквизиты организации (справочник
-- юрлиц с экраном остаётся в бэклоге ADR 0037), и описан этот порядок в runbook'е. `updated_by`
-- заведён под будущий экран и под ручную правку: кто менял шапку бланков — вопрос, который задают.
--
-- ТЕЛЕФОН ХРАНИТСЯ КАК ЗАПИСАН, а печатается через `formatPhone` (ADR 0066) — тем же ходом, что и
-- телефон организации в шапке: единый вид у обеих граф бланка, и нормализация не трогает записи,
-- в которых реквизит бухгалтерии не один номер.
--
-- СТАРЫЕ ЛИСТЫ НЕ ПЕРЕПИСЫВАЮТСЯ. Лист печатается из снимка (ADR 0037 п. 10), и выданные бланки
-- остаются с тем, что в них напечатано, — объектом заявки. Перевыписки эта миграция не вызывает:
-- сверка ЭСМ-2 (`esm2SyncPlan`) смотрит на набор недель, машину и машиниста, а реквизитов бланка
-- не знает вовсе.
--
-- ОБРАТИМОСТЬ. Миграция аддитивная: одна таблица и одна строка в ней, ни одной перезаписи
-- существующих данных. Откат кода схему не ломает — прежняя сборка этой таблицы не знает.

CREATE TABLE IF NOT EXISTS waybill_customer (
  -- Одиночка: строка ровно одна, вторую запрещает первичный ключ с CHECK. Умолчание избавляет
  -- вставку от необходимости знать про этот ключ вовсе.
  id         boolean PRIMARY KEY DEFAULT true CHECK (id),
  -- Пусто, а не NULL: графа бланка либо заполнена, либо печатается пустой под запись от руки
  -- (ADR 0064). Два пустых значения на одно состояние развели бы проверку надвое.
  name       text NOT NULL DEFAULT '',
  address    text NOT NULL DEFAULT '',
  phone      text NOT NULL DEFAULT '',
  -- Кто правил шапку бланков. `SET NULL` при удалении учётки: реквизит переживает человека, и
  -- терять из-за увольнения саму настройку нельзя.
  updated_by uuid REFERENCES users(id) ON DELETE SET NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE waybill_customer IS
  'Реквизиты заказчика путевых листов (docs/waybill-forms-corrections-plan.md §5.1): графа '
  '«В чьё распоряжение» 4-П и графа «Заказчик» ЭСМ-2. Строка одна на портал, правится SQL по runbook''у.';

