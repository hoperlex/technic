-- ── Запись журнала обновлений (ADR 0077) ──
--
-- Выпуски заводит миграция — та же, что выкатывает саму работу (ADR 0077 §3).
--
-- `seq` = 30, а не 21, как значилось в плане: между согласованием и этой миграцией журнал догнала
-- миграция 0159 (девять записей за 10–18 августа), и последним выпуском стал 29 — `0.1.23.0117`.
-- Номер берётся с конца по тому же правилу, по которому берётся номер миграции. Что 0158
-- сортируется раньше 0159 и на пустой базе вставит тридцатую запись прежде двадцать первой, роли
-- не играет: `seq` — первичный ключ и порядок показа, а не счётчик вставок, и пропусков в нём
-- после наката обеих миграций не остаётся.
--
-- Хвост версии — `0118` по номеру решения выпуска (ADR 0118), третье число растёт на единицу от
-- `0.1.23`: порядок выпусков назначается по последнему ADR блока, и хвост монотонен по построению.
