-- Руководства пользователя: справочник ссылок на документы (`docs/manuals-plan.md`, этапы 2 и 5).
--
-- Портал получает третий пункт служебного меню рядом с «Техподдержкой» и «Обновлениями». За
-- пунктом — окно со списком внешних ссылок; ведёт список держатель `manuals.manage` на своей
-- вкладке в «Администрировании», без правки кода и выката.
--
-- ПОЧЕМУ ТАБЛИЦА, А НЕ СПИСОК В КОДЕ. Руководства пишет не тот, кто выкатывает портал, и меняются
-- они чаще, чем схема: константа в коде означала бы деплой на каждую новую ссылку. Тем же
-- рассуждением журнал обновлений (ADR 0077) решён наоборот — его заводит миграция, потому что
-- выпуск и есть выкат. Здесь связи с выкатом нет вовсе.
--
-- ФАЙЛОВ ПОРТАЛ НЕ ХРАНИТ (§6 плана): в строке лежит адрес, документ живёт в Яндекс.Диске.
-- Отсюда единственная проверка ссылки — `https://`, и она не про безопасность адреса, а про то,
-- что документ откроется у всех: по `http` браузер вместо руководства показал бы предупреждение.
-- Правило «`/i/` — просмотр, `/edit/` — правка» принадлежит Яндексу и, зашитое в CHECK, сломалось
-- бы на первой же смене их адресов — отказав в заведении рабочей ссылки уже после выката.
--
-- ДВА ПРИЗНАКА РАЗВОДЯТ «ЧТО ПОКАЗЫВАТЬ» И «В КАКОМ ПОРЯДКЕ». `is_active` выводит руководство из
-- обращения, не теряя строку (снятое видит только держатель права), `sort_order` задаёт порядок
-- показа числом — переставить одну строку можно, не трогая соседей. Умолчание `100`, как у
-- справочников портала: заведённое без раздумий руководство встаёт в общий ряд, а не в начало.
--
-- ОТБОРА ПО РОЛЯМ НЕТ намеренно (решённая развилка плана): список у всех вошедших один, и колонки,
-- по которой его можно было бы сузить, в схеме нет. Это не забывчивость — «как пользоваться
-- порталом» одинаково нужно всем, а появится нужда делить, делить будет чем: обе колонки на месте.
--
-- ОБРАТИМОСТЬ. Миграция аддитивная: одна новая таблица, одна строка в ней и одна запись журнала
-- выпусков. Ни одной перезаписи существующих данных; откат кода схему не ломает — прежняя сборка
-- этих объектов не знает. Обратной миграции репозиторий не держит (`migrate.ts` только
-- накатывает); при необходимости таблица снимается вручную.

CREATE TABLE app_manuals (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  title       text NOT NULL,
  -- Пусто, а не NULL: в окне описание — вторая строка пункта, и «без пояснения» показывается её
  -- отсутствием. Два пустых значения на одно состояние развели бы проверку показа надвое.
  description text NOT NULL DEFAULT '',
  url         text NOT NULL,
  sort_order  integer NOT NULL DEFAULT 100,
  is_active   boolean NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  -- Название — единственное, чем строка представлена в окне: пустое оставило бы ссылку без
  -- подписи, и нажимать пришлось бы наугад. `btrim`, а не `<> ''`: строка из пробелов пуста.
  CONSTRAINT app_manuals_title_not_blank CHECK (btrim(title) <> ''),
  CONSTRAINT app_manuals_url_https CHECK (url ~ '^https://')
);

COMMENT ON TABLE app_manuals IS
  'Руководства пользователя (docs/manuals-plan.md): ссылки на документы во внешнем хранилище. '
  'Читают все вошедшие, ведёт держатель manuals.manage.';

COMMENT ON COLUMN app_manuals.is_active IS
  'Снятое с публикации руководство видно только держателю manuals.manage: из обращения строка '
  'выводится этим признаком, а не удалением.';

-- Порядок выборки повторён индексом целиком: ручка сначала отбирает по публикации, затем строит
-- список порядком справочника (`sort_order`, затем название). Отдельного индекса по `sort_order`
-- нет — он был бы префиксом этого.
CREATE INDEX app_manuals_list_idx ON app_manuals (is_active, sort_order, title);

