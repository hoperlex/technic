-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 5. Заявка: источник подписи, происхождение ожидания, порог автоприёмки и вид заморозки.

ALTER TABLE service_requests
  -- `human` — согласовал человек, `auto` — подпись проставлена заявлением об освобождении. `NULL`
  -- читается как `human`: так выглядят все подписи до этого выпуска и все, что поставит старый код в
  -- окне выката.
  ADD COLUMN estimate_approval_source text,
  -- `submit` — обычное предъявление, `dispute` — ожидание, открытое исходом разрешённого спора.
  -- Поле завелось из-за подписи в статусе «Решена»: разрешить её по статусу было нельзя — предикат
  -- согласования пустил бы к подписи ЛЮБОЕ ожидание, случайно оказавшееся в «Решена», в том числе
  -- наследственное. `NULL` читается как `submit`.
  ADD COLUMN estimate_pending_source text,
  -- Порог автоприёмки: раньше этого момента автозакрытие заявку не берёт. Явным полем, а не
  -- вычитанием времени заморозки из срока — заявка, простоявшая в споре неделю, созревала бы на
  -- первом же прогоне после возврата; «отсчёт от даты разрешения спора» тоже неверен, потому что при
  -- исходе `require_signature` подпись ставят через два дня, и заявка закрылась бы сразу после неё.
  ADD COLUMN auto_close_not_before timestamptz,
  -- Вид заморозки: `NULL` — обычное «ждём запчасть», `estimate_exemption_dispute` — остановка спором.
  -- Отдельным полем, а не разбором `hold_reason`: по виду заперты возврат из заморозки, закрытие
  -- работ и приёмка, а запрет, прочитанный из свободного текста причины, снимался бы правкой этого
  -- текста.
  ADD COLUMN hold_kind text;

-- ── 5.1. Backfill источника подписи (ответ В7) ──
--
-- Подписанные до выката: ревизия и дата согласования есть, источника нет, и по смыслу это `human` —
-- автоподписи старый код не умел вовсе, значит за каждой такой подписью стоит живой человек. Ровно
-- та же правка, что делала 0198 для приёмки.
--
-- Проверяется ДАТА, а не автор: автор обнуляется увольнением (`SET NULL`), и отбор по нему потерял бы
-- подписи уволенных сотрудников — то есть назвал бы их автопринятыми, когда выпуск B начнёт читать
-- источник строго.
--
-- Второй половины — чистки «источник без подписи», которая в 0198 была обязательной, — здесь нет и
-- быть не может: источник только что появился и стоит у всех `NULL`. Она понадобится выпуску B, и
-- именно там, потому что гасить подпись старый код умеет, а про источник не знает.
--
-- BACKFILL ИДЕМПОТЕНТЕН и НЕ ОБЯЗАН быть исчерпывающим: портал в это время работает, и подписи
-- продолжают появляться без источника. Для выпуска A это законно (`NULL` = `human`), а выпуск B
-- повторит обе правки непосредственно перед строгой связкой.
UPDATE service_requests SET estimate_approval_source = 'human'
 WHERE estimate_approved_at IS NOT NULL AND estimate_approval_source IS NULL;

-- ── 5.2. Ослабление снимка подписи ──
--
-- ЗАЧЕМ. Прежняя редакция требовала, чтобы автор, дата и ревизия были заполнены вместе или никак, —
-- то есть «принято без подписавшего» записать было нельзя (находка Н3 плана). Автопринятию автора
-- взять негде: за него не отвечает ни один человек, а подставить туда заявителя освобождения значило
-- бы записать, что оператор сервиса согласовал смету сам себе, — ровно то, что предикат согласования
-- запрещает явно.
--
-- ПОПУТНО СНИМАЕТСЯ МИНА, СТОЯВШАЯ У ОБЫЧНОЙ ПОДПИСИ. Ссылка `estimate_approved_by` объявлена
-- `ON DELETE SET NULL`: удаление уволенной учётки обнуляло её у согласованной заявки и упиралось в
-- это же ограничение — то есть увольнение было невозможно без правки истории. Тот же разбор, что в
-- 0198 про `accepted_by`.
--
-- ЧТО ОСТАЁТСЯ. Пара «когда + что именно» нерушима: дата без ревизии не говорит, ЧТО согласовали, а
-- ревизия без даты — что согласование вообще было. И уцелевшее направление прежней тройки: «кто-то
-- согласовал, но когда — неизвестно» было бессмыслицей и осталось ею.
--
-- СТРОГОЙ СВЯЗКИ «подпись ⇔ источник» ЗДЕСЬ НЕТ НАМЕРЕННО — она выпуска B (этап Э9, образец 0198):
-- старый код в окне выката ставит подпись, про источник не зная.
--
-- Ослабление безопасно по построению: всякая строка, законная до миграции, остаётся законной после.
ALTER TABLE service_requests DROP CONSTRAINT service_requests_approval_check;

ALTER TABLE service_requests ADD CONSTRAINT service_requests_approval_check CHECK (
  (estimate_approved_at IS NULL) = (approved_estimate_revision IS NULL)
  AND (estimate_approved_by IS NULL OR estimate_approved_at IS NOT NULL)
);

COMMENT ON CONSTRAINT service_requests_approval_check ON service_requests IS
  'Снимок подписи под объёмом работ: «когда» и «что именно» ходят парой, автор необязателен — у '
  'автопринятия (estimate_approval_source = auto) его нет вовсе, у человеческой подписи он '
  'обнуляется увольнением. План освобождения от согласования, Р11; строгая связка с источником — '
  'выпуск B.';

-- ── 5.3. Мягкие ограничения новых колонок ──
--
-- Все три — перечни значений и ничего больше. Ни одной межколоночной связки: старый код пишет и
-- гасит подпись, ожидание и заморозку, про новые поля не зная, и любое равенство уронило бы у него
-- первую же такую операцию. Перечни при этом обязаны быть: цена опечатки здесь не «кривая надпись»,
-- а молча снятый замок.
ALTER TABLE service_requests
  -- Дословно как у приёмки (0176): перечень значений и запрет автора у автоподписи — всё, что можно
  -- потребовать в выпуске A. «У `human` автор непустой» не требуется по той же причине, что там:
  -- ссылка `SET NULL`, и увольнение обнулило бы её, оставив подпись человеческой правдой.
  ADD CONSTRAINT service_requests_estimate_approval_source_check CHECK (
    estimate_approval_source IS NULL
    OR (estimate_approval_source IN ('human','auto')
        AND (estimate_approval_source <> 'auto' OR estimate_approved_by IS NULL))
  ),
  -- Связку с `estimate_pending_revision` нельзя поставить ни в одну сторону, пока в проде живёт
  -- старый код: он открывает ожидание без происхождения («ожидание без источника») и гасит ожидание,
  -- не убрав источник («источник без ожидания»), — в окне выката законны оба перекоса.
  ADD CONSTRAINT service_requests_estimate_pending_source_check CHECK (
    estimate_pending_source IS NULL OR estimate_pending_source IN ('submit','dispute')
  ),
  -- По виду заморозки заперты возврат из неё, закрытие работ и приёмка: незнакомое значение сняло бы
  -- все три замка молча — заявка выглядела бы обычной отложенной. Связки со статусом нет: старый код
  -- возвращает заявку из заморозки, про вид не зная, и равенство «вид есть ровно у отложенной»
  -- уронило бы у него первый же возврат. Гасить вид обязана матрица сброса (этап Э5).
  ADD CONSTRAINT service_requests_hold_kind_check CHECK (
    hold_kind IS NULL OR hold_kind IN ('estimate_exemption_dispute')
  );

-- ИНДЕКСА ПОД `auto_close_not_before` ЗДЕСЬ НЕТ, и это замер, а не забывчивость. Отбор автозакрытия
-- ведёт статус («Решена» + возраст), и порог в нём — остаточное условие у горстки строк: непустым он
-- бывает только у заявок, прошедших спор. Частичный индекс по такой колонке планировщик не возьмёт
-- вовсе, а полный повторил бы `service_requests_status_changed_idx` худшей стороной. Понадобится —
-- придёт отдельной миграцией по плану запроса, а не по догадке.

COMMENT ON COLUMN service_requests.estimate_approval_source IS
  'Источник подписи под объёмом работ: human — человек, auto — заявление об освобождении. NULL '
  'читается как human (выпуск A). План освобождения от согласования, Р11.';

COMMENT ON COLUMN service_requests.auto_close_not_before IS
  'Порог автоприёмки: раньше этого момента автозакрытие заявку не берёт. Ставится исходом '
  'разрешённого спора (Р9), у остальных заявок пусто.';

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 6. Карантин файла (Р6).
--
-- ЗАЧЕМ. Основание денежного решения не снимается никогда — ни автором, ни правом `files.manageAny`
-- (запрет в ручке и замки Р6). Значит у ошибочно загруженного секретного или чужого документа нет
-- обычного выхода, и без аварийного он стал бы неустранимым инцидентом с персональными данными.
-- Карантин — не метка в карточке: сегодня ссылку выдаёт `GET /files/:id/download` по обычной
-- видимости заявки, и «скрытый» документ продолжал бы скачиваться по прямой ссылке. Запрет обязан
-- читаться в `canAccessFile` РАНЬШЕ любой ветки видимости, включая автора файла.
--
-- Строка ревизии, её сумма и след освобождения при этом остаются: «доказательство скрыто по
-- обращению» и «доказательства не было» — разные факты, и второй был бы неправдой.
--
-- ПОЧЕМУ НЕ `deleted_at` И НЕ `status`. Удаление уносит объект из хранилища (а он обязан остаться
-- для разбора инцидента по праву аудита), а статус загрузки отвечает на другой вопрос — дошёл ли файл
-- до хранилища вообще.
ALTER TABLE files
  ADD COLUMN quarantined_at timestamptz,
  -- Хеш содержимого, посчитанный сервером при постановке в карантин: разбор инцидента обязан
  -- доказать, что по праву аудита смотрят тот самый файл, а не подменённый за это время объект.
  -- Пусто у всех остальных файлов — считать его всем подряд незачем, вопрос задаётся один раз.
  ADD COLUMN content_hash text;

COMMENT ON COLUMN files.quarantined_at IS
  'Файл скрыт по обращению (Р6 плана освобождения от согласования): ссылка не выдаётся никому, '
  'включая автора, содержимое доступно только по праву аудита. Объект в хранилище остаётся.';

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 7. Караул: схема заведена так, как объявлена.
--
-- Проверка выглядит избыточной ровно до дня, когда файл накатят на базу, восстановленную из копии,
-- или переиграют руками. Сверяется то, на чём стоят новые правила: три таблицы с их ключами, три
-- составных внешних ключа, каждый со СВОИМ правилом удаления: у заявления и спора `CASCADE` (с
-- `RESTRICT` они сломали бы необратимое удаление заявки, с `SET NULL` — невозможны, колонки входят в
-- первичный ключ и в `NOT NULL`), у связи файла `RESTRICT` (раздел 4). Далее — оба частичных
-- уникальных индекса (без них состояние ревизии и единственность открытого спора расходятся молча),
-- семь новых колонок и четыре новых ограничения, а также ослабленная редакция снимка подписи — без
-- неё автоподпись физически не записывается, и обнаружится это на первом же освобождении в проде.
--
-- ДАННЫХ КАРАУЛ НЕ ПРОВЕРЯЕТ НАМЕРЕННО. Напрашивающееся «после backfill не осталось подписанных
-- заявок без источника» здесь было бы миной: портал работает, и подпись, поставленная старым кодом
-- между `UPDATE` и этой проверкой, уронила бы весь накат. Для выпуска A такая строка законна
-- (`NULL` = `human`), а исчерпывающей правку делает выпуск B перед строгой связкой.
--
-- Правило удаления сверяется по `pg_constraint.confdeltype`: `c` — cascade, `r` — restrict,
-- `n` — set null.

DO $$
DECLARE trouble text;
BEGIN
  SELECT string_agg(msg, '; ')
    INTO trouble
    FROM (
      SELECT format('таблицы %s нет', t.name) AS msg
        FROM (VALUES
          ('service_request_estimate_revisions'),
          ('service_request_estimate_exemptions'),
          ('service_request_estimate_disputes')
        ) AS t (name)
       WHERE to_regclass('public.' || t.name) IS NULL
      UNION ALL
      SELECT format('у таблицы %s нет первичного ключа', t.name)
        FROM (VALUES
          ('service_request_estimate_revisions'),
          ('service_request_estimate_exemptions'),
          ('service_request_estimate_disputes')
        ) AS t (name)
       WHERE to_regclass('public.' || t.name) IS NOT NULL
         AND NOT EXISTS (
               SELECT 1 FROM pg_constraint c
                WHERE c.conrelid = ('public.' || t.name)::regclass AND c.contype = 'p')
      UNION ALL
      SELECT format('составная ссылка «%s» ведёт на «%s» с правилом «%s» вместо «%s»',
                    e.name, c.confrelid::regclass, c.confdeltype, e.rule)
        FROM (VALUES
          ('service_request_estimate_exemptions_revision_fk', 'service_request_estimate_exemptions', 'c'),
          ('service_request_estimate_disputes_revision_fk',   'service_request_estimate_disputes',   'c'),
          -- Третья ссылка — от связи файла, и правило у неё своё (`r`, см. раздел 4). Сверяется именно
          -- правило, а не наличие ключа: `CASCADE` здесь унёс бы страницы основания вместе с удалённой
          -- руками строкой ревизии — то есть выглядел бы работающим ключом, защищая обратное.
          ('service_request_files_estimate_revision_fk',      'service_request_files',               'r')
        ) AS e (name, tbl, rule)
        LEFT JOIN pg_constraint c
               ON c.conname = e.name
              AND c.contype = 'f'
              AND c.conrelid = ('public.' || e.tbl)::regclass
       WHERE c.oid IS NULL
          OR c.confrelid <> 'public.service_request_estimate_revisions'::regclass
          OR c.confdeltype <> e.rule
          OR array_length(c.conkey, 1) <> 2
      UNION ALL
      SELECT format('частичного уникального индекса «%s» нет — правило разошлось бы молча', i.name)
        FROM (VALUES
          ('service_request_estimate_revisions_active_unique'),
          ('service_request_estimate_disputes_open_unique')
        ) AS i (name)
       WHERE NOT EXISTS (
               SELECT 1 FROM pg_index x
                WHERE x.indexrelid = to_regclass('public.' || i.name)
                  AND x.indisunique
                  AND x.indpred IS NOT NULL)
      UNION ALL
      SELECT format('индекса «%s» нет', i.name)
        FROM (VALUES
          ('service_request_files_closing_idx'),
          ('service_request_estimate_disputes_request_idx')
        ) AS i (name)
       WHERE to_regclass('public.' || i.name) IS NULL
      UNION ALL
      SELECT format('колонки %s.%s нет', c.tbl, c.col)
        FROM (VALUES
          ('service_request_files', 'purpose'),
          ('service_request_files', 'estimate_revision'),
          ('service_request_files', 'page_no'),
          ('service_requests', 'estimate_approval_source'),
          ('service_requests', 'estimate_pending_source'),
          ('service_requests', 'auto_close_not_before'),
          ('service_requests', 'hold_kind'),
          ('files', 'quarantined_at'),
          ('files', 'content_hash')
        ) AS c (tbl, col)
       WHERE NOT EXISTS (
               SELECT 1 FROM pg_attribute a
                WHERE a.attrelid = ('public.' || c.tbl)::regclass
                  AND a.attname = c.col
                  AND a.attnum > 0
                  AND NOT a.attisdropped)
      UNION ALL
      SELECT format('ограничения «%s» нет', k.name)
        FROM (VALUES
          ('service_request_files_purpose_check'),
          ('service_request_files_basis_check'),
          ('service_requests_estimate_approval_source_check'),
          ('service_requests_estimate_pending_source_check'),
          ('service_requests_hold_kind_check')
        ) AS k (name)
       WHERE NOT EXISTS (SELECT 1 FROM pg_constraint c WHERE c.conname = k.name AND c.contype = 'c')
      UNION ALL
      -- Подпись без автора обязана быть законной: иначе автопринятие не записывается, и узнается это
      -- на первом освобождении в проде, а не здесь.
      SELECT 'снимок подписи не ослаблен — автопринятие записать нельзя'
       WHERE EXISTS (
               SELECT 1 FROM pg_constraint c
                WHERE c.conname = 'service_requests_approval_check'
                  AND c.conrelid = 'public.service_requests'::regclass
                  AND pg_get_constraintdef(c.oid) LIKE '%estimate_approved_by IS NULL) = (%')
      UNION ALL
      -- Умолчание роли — половина совместимости со старым кодом: без него первая же подшивка старым
      -- сервером упала бы на `NOT NULL`.
      SELECT 'у service_request_files.purpose нет умолчания closing_evidence'
       WHERE NOT EXISTS (
               SELECT 1
                 FROM pg_attribute a
                 JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
                WHERE a.attrelid = 'public.service_request_files'::regclass
                  AND a.attname = 'purpose'
                  AND a.attnotnull
                  AND pg_get_expr(d.adbin, d.adrelid) LIKE '%closing_evidence%')
    ) AS bad;
  IF trouble IS NOT NULL THEN
    RAISE EXCEPTION 'Схема форматов предъявления заведена не так, как объявлена — %', trouble;
  END IF;
END $$;
