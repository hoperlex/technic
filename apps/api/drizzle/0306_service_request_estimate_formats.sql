-- Форматы предъявления объёма работ, освобождение от подписи и спор о нём — схема выпуска A
-- (план `docs/office-equipment-on-site-and-invoice-estimate-plan.md`, редакция 5, решения Р2–Р6,
-- Р9, Р11; этап Э2).
--
-- ОТКУДА НОМЕР. Снимок `ls apps/api/drizzle` непосредственно перед созданием файла (11.09.2026):
-- последним в дереве стоит `0305_releases_manager_service_requester.sql` — запись выпуска соседнего
-- потока, — свободен `0306`, он и взят. Номер берётся в момент создания файла и не резервируется на
-- волну вперёд: параллельные потоки занимают номера незакоммиченными файлами (как это выглядит на
-- практике, рассказывают 0261 и 0262).
--
-- ЧТО ЗАКРЫВАЕТ. Заказчик просит две вещи (разбор 10.09.2026): чекбокс «Согласование не требуется»,
-- делающий подпись под объёмом работ автопринятием, и подачу объёма работ ПРИЛОЖЕННЫМ СЧЁТОМ вместо
-- заполнения формы. Вторая просьба впервые ломает сегодняшнюю модель: у документного предъявления
-- нет ни строк, ни суммы — счёт приложен, содержимое его системе пока неизвестно (ответы заказчика
-- В5 и В9: «сумму не требовать, придёт от разбора документа», «не требовать полноту данных до
-- ИИ-распознавания»). Значит формат предъявления, его автора и будущую разобранную сумму класть
-- некуда, и нужен свой носитель — три таблицы ниже.
--
-- ЧТО ОБЕЩАЕТ. Место для формата ревизии и её реквизитов; роль файла в заявке, по которой предикат
-- отличает закрывающую бумагу от основания денежного решения, и ссылку этой роли на существующую
-- ревизию (замок Р6 п. 2, раздел 4); след заявления об освобождении с его
-- исходом; запись спора; четыре колонки в самой заявке под источник подписи, происхождение ожидания,
-- порог автоприёмки и вид заморозки; карантин файла. Плюс ослабление
-- `service_requests_approval_check` — без него автоподпись (подпись без автора) физически не
-- записывается.
--
-- ЧЕГО НЕ ОБЕЩАЕТ, И ЭТО СКАЗАНО ЗДЕСЬ ВСЛУХ:
--   · СТРОГОЙ СВЯЗКИ «подпись ⇔ источник» в файле НЕТ. Она — выпуск B (этап Э9 плана, образец —
--     миграция 0198): пока в проде живёт старый код, он ставит и гасит подпись, про источник не
--     зная, и равенство уронило бы у него первое же согласование. До выпуска B пустой источник у
--     подписанной заявки читается как `human` — этого обязан держаться весь код выпуска A;
--   · ни одна новая колонка не связана со статусом заявки и не образует пары с существующей. Те же
--     причины и тот же разбор: старый код возвращает заявку из заморозки, гасит ожидание подписи и
--     подшивает файлы, ничего не зная о новых полях, — любая межколоночная связка превратила бы
--     окно выката в отказ работающего портала;
--   · реквизиты счёта и сумма документной ревизии остаются пустыми: их положит разбор документа
--     (Р12), которого в этом выпуске нет вовсе. Дубль счёта система до него не видит — цена решения
--     названа в плане вслух (В13);
--   · денежного контроля у освобождения нет: ни лимита, ни политики, ни перечня контрагентов (В2,
--     В12). Таблица заявлений — единственный след, по которому освобождения разбирают постфактум;
--   · рубильников здесь нет. Их два («service_estimate_document_mode» и
--     «service_estimate_exemption», §7 плана), и они едут СВОИМ файлом — 0307: схема едет один раз, а
--     ключи переключаются `UPDATE`-ом по живой базе и снимаются третьим выпуском, и одна строка
--     журнала наката на две такие работы означала бы, что откат схемы уносит перечень ключей.
--
-- ПОЧЕМУ ПРАВКА ПЕРЕЖИВАЕТ ОКНО ВЫКАТА (миграция идёт ПРИ РАБОТАЮЩЕМ ПОРТАЛЕ и ДО перезапуска, см.
-- `AGENTS.md` и `docs/runbook.md`) — по пунктам, потому что проверять это оптом бессмысленно:
--   1. три новые таблицы старому коду не видны вовсе: он в них не пишет и не читает, уронить его они
--      не могут. Все их ограничения — внутренние;
--   2. `service_request_files.purpose` — `NOT NULL DEFAULT 'closing_evidence'`, то есть старая
--      подшивка «без роли» получает ровно сегодняшний смысл. `estimate_revision` и `page_no`
--      необязательны и у старого кода остаются пустыми. `CHECK` про `estimate_basis` старому коду
--      недостижим: роль он не пишет, а умолчание ему противоречить не может;
--   3. четыре новые колонки заявки необязательны и без умолчаний: старый код оставляет `NULL`, и
--      `NULL` удовлетворяет каждому новому `CHECK` при любом значении соседей;
--   4. `service_requests_approval_check` ОСЛАБЛЯЕТСЯ, а не усиливается: всякая строка, законная до
--      миграции, остаётся законной после — новая редакция лишь разрешает то, чего раньше не могла
--      записать ни одна сторона. Старый код пишет снимок подписи целиком и в новую редакцию
--      укладывается без изменений;
--   5. `files.quarantined_at` и `files.content_hash` необязательны; пустой карантин означает
--      «файл не скрыт», то есть сегодняшнее поведение, и старый сервер продолжает выдавать ссылки
--      так же, как выдавал.
--
-- ЧТО БУДЕТ ДЕЛАТЬ НОВЫЙ КОД, ПОКА РУБИЛЬНИКИ ВЫКЛЮЧЕНЫ: только читать. Выпуск A по §7 плана — это
-- выпуск ЧИТАТЕЛЕЙ: ручка предъявления документный формат ещё не принимает, и строк
-- `purpose = 'estimate_basis'` в базе появиться не может. Порядок этот обязателен: старый сервер и
-- старый воркер роль файла не читают, и для них любой `invoice` снова закрывающая бумага — то есть
-- документная подача, выкаченная раньше читателей, обошла бы планку акта.
--
-- ОБРАТИМОСТЬ. Миграция аддитивная: ни одной существующей колонки не переписывает, ни одной строки
-- не удаляет, протокол выката необратимых миграций (`docs/schema-cutover-protocol.md`) к ней не
-- применяется. Откат схемы — `DROP TABLE` трёх таблиц (`service_request_estimate_revisions`,
-- `..._exemptions`, `..._disputes`), `DROP COLUMN` ДЕВЯТИ колонок и возврат прежней редакции
-- `service_requests_approval_check`. Колонки перечислены по таблицам нарочно: счёт «семь», стоявший
-- здесь в первой редакции шапки, терял карантинную пару в `files` — а откат по неполному рецепту
-- хуже отсутствующего, потому что выглядит проверенным, и повторный накат упёрся бы в
-- `ADD COLUMN` уже существующей колонки:
--   · `service_request_files` — `purpose`, `estimate_revision`, `page_no`;
--   · `service_requests` — `estimate_approval_source`, `estimate_pending_source`,
--     `auto_close_not_before`, `hold_kind`;
--   · `files` — `quarantined_at`, `content_hash`.
-- Возврат прежней тройки в `service_requests_approval_check` возможен ровно до первой автоподписи,
-- и потому откат к коду СТАРШЕ этого выпуска требует разбора активных документных ревизий и
-- автоподписей службой (§7 плана, «Откат»). Единственное изменение данных — backfill ниже, и он
-- идемпотентен.
--
-- Прод — PostgreSQL 17, дев — 16. Версионно-спорного здесь нет: ни функций в индексах, ни
-- `NULLS NOT DISTINCT`, ни новых типов. `ADD COLUMN ... DEFAULT` не перезаписывает таблицу с
-- PostgreSQL 11, поэтому умолчание роли файла — операция каталога, а не переливка; `CREATE INDEX`
-- идёт без `CONCURRENTLY` (раннер катит файл одной транзакцией,
-- `apps/api/src/db/migration-journal.ts`), и блокировка записи на время построения — доли секунды:
-- вложений заявок обслуживания десятки тысяч, а не миллионы.

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 1. Ревизии объёма работ: формат предъявления и его реквизиты (Р4).
--
-- ПОЧЕМУ ТАБЛИЦА, А НЕ КОЛОНКИ В ЗАЯВКЕ. Ревизия — история: у заявки их столько, сколько было
-- предъявлений, и именно в этой истории лежит ответ, на чём стояло денежное решение. Колонками в
-- `service_requests` поместилась бы только последняя, а предикат закрывающего документа спрашивает
-- про ДЕЙСТВУЮЩУЮ ревизию, которая не равна последней по номеру: возврат в правку (`reopen`) отзывает
-- предъявление, не стирая того, что было предъявлено.
--
-- ПОЧЕМУ ФОРМАТ ХРАНИТСЯ, А НЕ ВЫВОДИТСЯ ИЗ ДАННЫХ. Догадка «строк нет — значит документная»
-- разошлась бы с правдой на первой же раскладке «Ведения»: она переиздаёт документную ревизию в
-- построчную, и признак обязан это пережить. Ошибка в формате не портит надпись, а открывает дверь:
-- от него зависит, какая бумага закрывает заявку (у документной — только акт, ответ заказчика В10).
--
-- ПОЧЕМУ НОСИТЕЛЬ ОДИН ДЛЯ ДВУХ СЦЕНАРИЕВ. Счёт подают и с обычной подписью — освобождение от неё
-- лишь ссылается на ревизию (таблица 2). Прежняя редакция плана держала данные документа внутри
-- таблицы освобождений, и там они исчезали вместе с отказом от автоподписи.

CREATE TABLE service_request_estimate_revisions (
  -- `cascade`, как у всех частей заявки: ревизия — её история, а не самостоятельная запись. Заявки
  -- удаляются мягко (`deleted_at`), необратимое удаление — право `records.purge`, и оно обязано
  -- проходить целиком.
  request_id uuid NOT NULL REFERENCES service_requests (id) ON DELETE CASCADE,
  -- Номер — тот же, что в `service_requests.estimate_revision`. Суррогатного `id` нет намеренно: на
  -- ревизию ссылаются трое (связь файла, заявление, спор), и все трое знают её номером — с
  -- суррогатом каждая ссылка требовала бы второго запроса, чтобы узнать, ту ли ревизию назвала.
  revision integer NOT NULL,
  format text NOT NULL,
  -- Действующая ровно одна (частичный уникальный индекс ниже), прежние — `superseded`. Отдельным
  -- полем, а не сравнением с номером в заявке: отозванная возвратом в правку ревизия остаётся тем,
  -- на чём стояло денежное решение (Р6), и «последняя по номеру» перестаёт означать «действующая».
  state text NOT NULL DEFAULT 'active',
  -- Автор предъявления: парного `estimate_submitted_by` в заявке нет (находка Н5 плана), и теперь он
  -- не нужен. `SET NULL`, а не `RESTRICT`: увольнение не должно упираться в денежный след, а сам
  -- след — формат, время, сумма — остаётся правдой и без имени; имя события живёт в аудите (тот же
  -- довод, что у `estimate_approved_by` и у источника приёмки, 0198).
  submitted_by uuid REFERENCES users (id) ON DELETE SET NULL,
  -- `DEFAULT now()` — не удобство, а правило: строка пишется той же транзакцией, что предъявление
  -- (аудит модуля идёт после `COMMIT`, и второго источника времени у события нет).
  submitted_at timestamptz NOT NULL DEFAULT now(),
  -- Снимок суммы, а не производная: у построчной ревизии её считает сервер из строк, у документной
  -- её нет до разбора документа. Ноль вместо неизвестного ставить нельзя — он читается как «работы
  -- бесплатны» (Р2, тот же запрет, что у итога по акту).
  total_amount numeric(14,2),
  -- Реквизиты счёта при подаче не требуют (В13), их положит разбор документа (Р12). `NULL`, а не
  -- пустая строка: «в счёте номера нет» и «счёт ещё не разобран» — разные факты.
  invoice_number text,
  invoice_date date,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (request_id, revision)
);

ALTER TABLE service_request_estimate_revisions
  ADD CONSTRAINT service_request_estimate_revisions_format_check
    CHECK (format IN ('items','document','warranty')),
  -- Состояние закрыто перечнем по цене опечатки: незнакомое значение не сработало бы как
  -- `superseded` — оно вывело бы ревизию из-под уникального индекса, и у заявки стало бы две
  -- действующие, то есть правило «какая бумага закрывает заявку» начало бы зависеть от плана запроса.
  ADD CONSTRAINT service_request_estimate_revisions_state_check
    CHECK (state IN ('active','superseded')),
  -- Нулевая ревизия — это «предъявления не было»: счёт ревизий начинается с первого предъявления.
  ADD CONSTRAINT service_request_estimate_revisions_revision_check CHECK (revision >= 1),
  -- Как у сумм самой заявки (`service_requests_amounts_check`): отрицательная сумма объёма работ —
  -- это скидка, а её путь один, через корректировку акта с причиной.
  ADD CONSTRAINT service_request_estimate_revisions_amount_check
    CHECK (total_amount IS NULL OR total_amount >= 0);

-- Одна действующая ревизия на заявку — индексом, а не аккуратностью маршрута: вторая `active` — это
-- гонка двух предъявлений, а от неё предикат закрывающего документа расходится молча и в сторону
-- лишнего. Частичный: `superseded` у заявки сколько угодно, и индекс остаётся размером с число живых
-- предъявлений, а не с историей модуля. Условие константное, без функций, — одинаково ложится на
-- прод (17) и на дев (16).
CREATE UNIQUE INDEX service_request_estimate_revisions_active_unique
  ON service_request_estimate_revisions (request_id)
  WHERE state = 'active';

COMMENT ON TABLE service_request_estimate_revisions IS
  'Ревизии объёма работ заявки оргтехники: формат предъявления (items/document/warranty), автор, '
  'сумма и реквизиты счёта. План освобождения от согласования, Р4. Формат хранится, а не выводится: '
  'от него зависит, какая бумага закрывает заявку.';

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 2. Заявление об освобождении от подписи (Р1, Р3).
--
-- ЗАЯВЛЕНИЕ И ИСХОД РАЗВЕДЕНЫ. Заявляет оператор сервисной компании (ответ В1), а исход считает
-- сервер по рубильнику: `applied` — подпись проставлена, ожидание не открывалось; `observed` —
-- рубильник выключен, заявление записано, подпись собирают как обычно. Исход пишется в ОБА случая, и
-- это главное свойство таблицы: до включения рубильника служба видит, сколько таких заявлений и на
-- какие суммы приходит, не теряя при этом ни одной подписи.
--
-- ЧЕГО ЗДЕСЬ НЕТ. Ни перечня оснований (В4 — один пункт без выбора), ни лимита суммы (В2), ни
-- ссылки на договор (В12): политики, которую такие поля обещали бы, в системе не существует.

CREATE TABLE service_request_estimate_exemptions (
  request_id uuid NOT NULL,
  revision integer NOT NULL,
  -- `SET NULL` по тому же доводу, что у автора ревизии: увольнение не упирается в денежный след, а
  -- событие с именем остаётся в аудите.
  declared_by uuid REFERENCES users (id) ON DELETE SET NULL,
  declared_at timestamptz NOT NULL DEFAULT now(),
  -- Пояснение необязательно: «по условиям договора» портал не пишет вовсе (Р1) — обещание, которого
  -- система не проверяет, в подписи кнопки было бы ложью. Этой строкой исполнитель скажет «мелкий
  -- ремонт на месте», если захочет.
  note text NOT NULL DEFAULT '',
  outcome text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  -- Ключ — пара «заявка + ревизия»: заявление предъявляют вместе с ревизией, а повторное
  -- предъявление поднимает номер — второго заявления по той же ревизии взяться неоткуда.
  -- Суррогатный `id` дал бы таблице вид хронологии заявлений, которой нет, и пустил бы два разных
  -- исхода под одну подпись. Он же поддерживает внешний ключ ниже.
  PRIMARY KEY (request_id, revision)
);

-- Ссылка составная, и она же причина, по которой собственной ссылки на заявку у таблицы нет:
-- освобождение без ревизии не существует — оно заявлено ПОД конкретным предъявлением. `CASCADE`
-- продолжает цепочку «заявка → ревизия → заявление». `RESTRICT` был бы здесь прямой ошибкой: он
-- останавливает удаление даже тогда, когда ссылающаяся строка уходит тем же каскадом, то есть сломал
-- бы необратимое удаление заявки (`records.purge`).
ALTER TABLE service_request_estimate_exemptions
  ADD CONSTRAINT service_request_estimate_exemptions_revision_fk
    FOREIGN KEY (request_id, revision)
    REFERENCES service_request_estimate_revisions (request_id, revision) ON DELETE CASCADE,
  -- Исходов ровно два: `fallback_to_human` прежней редакции плана исчез вместе с лимитом (В2) —
  -- ветка, которая никогда не срабатывает, врёт отчёту убедительнее, чем её отсутствие.
  ADD CONSTRAINT service_request_estimate_exemptions_outcome_check
    CHECK (outcome IN ('applied','observed'));

COMMENT ON TABLE service_request_estimate_exemptions IS
  'Заявление «Согласование не требуется» под ревизией объёма работ: кто заявил, пояснение и исход '
  '(applied — подпись проставлена, observed — рубильник выключен, подпись собирают обычно). План '
  'освобождения от согласования, Р1 и Р3; единственный след для разбора постфактум.';

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 3. Спор об освобождении (Р9).
--
-- Оспаривает «Ведение», до приёмки заявки (ответ В3). Механика остановки — `on_hold` с
-- `hold_kind = 'estimate_exemption_dispute'` (колонка в разделе 5), коридор для этого уже есть,
-- включая вход из «Решена». Исход решает, куда заявка вернётся: `keep` — освобождение остаётся,
-- `require_signature` — автоподпись снята и ожидание открыто заново, `cancel` — заявка отменена.
--
-- СУРРОГАТНЫЙ КЛЮЧ, в отличие от заявления выше, и это решение, а не небрежность. Спор по одной и той
-- же ревизии бывает не один: исход `keep` заявку не меняет, и через неделю, с новыми доводами, её
-- оспаривают снова. С парным ключом второй спор затёр бы первый — стёр бы, кто настаивал раньше и
-- чем это кончилось, а именно эта история и есть весь постфактумный контроль над освобождениями.

CREATE TABLE service_request_estimate_disputes (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  request_id uuid NOT NULL,
  revision integer NOT NULL,
  opened_by uuid REFERENCES users (id) ON DELETE SET NULL,
  opened_at timestamptz NOT NULL DEFAULT now(),
  -- Причина обязательна: спор останавливает работающую заявку, и разрешать его без сказанного вслух
  -- основания пришлось бы догадкой о том, что именно оспаривали.
  reason text NOT NULL,
  state text NOT NULL DEFAULT 'open',
  -- Пусто у открытого спора; связку держит `..._resolution_check` ниже.
  outcome text,
  resolved_by uuid REFERENCES users (id) ON DELETE SET NULL,
  resolved_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE service_request_estimate_disputes
  -- Та же составная ссылка и тот же `CASCADE`, что у заявления, и по тем же причинам: спор всегда о
  -- конкретном предъявлении, своей ссылки на заявку ему не нужно.
  ADD CONSTRAINT service_request_estimate_disputes_revision_fk
    FOREIGN KEY (request_id, revision)
    REFERENCES service_request_estimate_revisions (request_id, revision) ON DELETE CASCADE,
  ADD CONSTRAINT service_request_estimate_disputes_reason_not_blank_check
    CHECK (btrim(reason) <> ''),
  ADD CONSTRAINT service_request_estimate_disputes_state_check
    CHECK (state IN ('open','resolved')),
  -- Разрешённый спор отвечает «чем кончилось и когда», открытый — не отвечает вовсе. Исход у
  -- открытого означал бы принятое, но не применённое решение: заявка осталась бы в заморозке с
  -- готовым ответом, которого никто не исполнил. Разрешённый без исхода — снятую заморозку без
  -- объяснения, то есть спор, проигранный молчанием.
  --
  -- Якорь пары — ВРЕМЯ, а не автор: `resolved_by` обнуляется увольнением (`SET NULL`), и равенство по
  -- автору уронило бы удаление учётки — ровно та мина, которую раздел 5 снимает у подписи.
  ADD CONSTRAINT service_request_estimate_disputes_resolution_check CHECK (
    (state = 'resolved') = (outcome IS NOT NULL)
    AND (state = 'resolved') = (resolved_at IS NOT NULL)
    AND (outcome IS NULL OR outcome IN ('keep','require_signature','cancel'))
    AND (resolved_by IS NULL OR resolved_at IS NOT NULL)
  );

-- Не больше одного открытого спора на заявку. Второй открытый означал бы два разбора одной
-- остановки, и разрешение первого сняло бы заморозку при живом втором — заявка уехала бы в приёмку
-- со спором, который никто не закрывал. Частичный: разрешённых у заявки сколько угодно.
CREATE UNIQUE INDEX service_request_estimate_disputes_open_unique
  ON service_request_estimate_disputes (request_id)
  WHERE state = 'open';

-- Карточка показывает историю споров заявки, а каскад от ревизии ходит по этой же паре: ключ по
-- суррогатному `id` ни на один из двух вопросов не отвечает.
CREATE INDEX service_request_estimate_disputes_request_idx
  ON service_request_estimate_disputes (request_id, revision);

COMMENT ON TABLE service_request_estimate_disputes IS
  'Спор об освобождении от подписи: кто и почему остановил заявку, как разрешено (keep / '
  'require_signature / cancel). План освобождения от согласования, Р9. Открытым бывает ровно один '
  'спор на заявку, история прежних сохраняется.';

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 4. Роль файла в заявке (Р5) и связь файла с ревизией (Р4).
--
-- ЗАЧЕМ РОЛЬ. Сегодня закрывающими считаются три вида — `act`, `invoice`, `warranty_card`, — и вид
-- отвечает на вопрос «что это за бумага», но не на вопрос «зачем она здесь». Счёт, поданный ВМЕСТО
-- формы объёма работ, для сегодняшнего предиката — закрывающая бумага, то есть заявка закрывалась бы
-- собственным основанием. Роль — вторая половина правила; первая, перечень видов, зависит от формата
-- действующей ревизии (у документной закрывает только акт, В10).
--
-- ПОЧЕМУ ТРИ КОЛОНКИ В САМОЙ СВЯЗИ, А НЕ ОТДЕЛЬНАЯ ТАБЛИЦА СТРАНИЦ (замечание ревью принято, но
-- решено иначе). Отдельная таблица ломала бы главное ограничение: «роль `estimate_basis` бывает
-- только у счёта и только с ревизией» обычным `CHECK` не выразить, если ревизия лежит в другой
-- таблице, — понадобился бы отложенный триггер, а роль и страницы смогли бы разойтись.
--
-- ССЫЛКА НА РЕВИЗИЮ — СОСТАВНОЙ ВНЕШНИЙ КЛЮЧ (замок Р6 п. 2), и он отвечает ровно на один вопрос:
-- НЕ БЫВАЕТ ОСНОВАНИЯ, ССЫЛАЮЩЕГОСЯ НА РЕВИЗИЮ, КОТОРОЙ НЕТ. Без ключа `UPDATE … SET
-- estimate_revision = 99` оставлял бы страницу счёта висеть на небывшем предъявлении, и замок
-- «основание не снимается никогда» искал бы её по номеру, которого ни в одной ревизии нет, — то есть
-- доказательство денежного решения пропадало бы, не будучи удалённым. `CHECK` выше этого не ловит: он
-- требует лишь НЕПУСТОГО номера.
--
-- ЧЕГО КЛЮЧ НЕ ДЕЛАЕТ И НЕ МОЖЕТ СДЕЛАТЬ: он не запрещает удалить САМУ СВЯЗЬ. Внешний ключ сторожит
-- ссылаемую строку, а не ссылающуюся, — `DELETE FROM service_request_files` законен при любом правиле
-- удаления. Значит замок Р6 п. 1 (запрет снятия в ручке под той же блокировкой, которой идёт удаление)
-- ключом не заменяется и обязан быть написан в Э4; здесь сказано вслух потому, что db-тест 8 плана
-- ждёт от ключа именно этого, а получить от него можно только отказ на «ревизию, которой нет».
--
-- ПОЧЕМУ `RESTRICT`, А НЕ `CASCADE`, хотя у заявления и спора выше стоит `CASCADE`. У тех таблиц
-- своей ссылки на заявку нет вовсе: их строки уходят ТОЛЬКО каскадом от ревизии, и `RESTRICT` у них
-- остановил бы необратимое удаление заявки. У связи файла ссылка на заявку своя и тоже `CASCADE` —
-- `records.purge` делает один `DELETE FROM service_requests` (`apps/api/src/routes/service-requests.ts`),
-- и обе ветви каскада уходят в нём одним оператором. Проверка `RESTRICT` — отложенный до конца
-- ОПЕРАТОРА триггер, и к этому моменту ссылающихся строк уже нет; проверено исполнением на
-- PostgreSQL 17 и 16 в обоих порядках создания ограничений (порядок важен: `pg_dump` восстанавливает
-- их не в том порядке, в котором они заведены миграциями). `CASCADE` здесь был бы хуже: удаление
-- строки ревизии руками унесло бы с собой и страницы основания — молча и без следа, то есть ровно то
-- исчезновение доказательства, против которого стоит Р6.
--
-- ПОРЯДОК ВСТАВОК В Э4 ЭТИМ ЗАДАН, И ЭТО ТРЕБОВАНИЕ К КОДУ, А НЕ ПОЖЕЛАНИЕ: ключ немедленный
-- (`DEFERRABLE` схема drizzle не выражает, а расхождение файла схемы с базой дороже удобства),
-- поэтому строка ревизии пишется ПЕРВОЙ, страницы — после неё. Р7 плана перечисляет шаги в обратном
-- порядке; внутри одной транзакции это перестановка без наблюдаемой разницы, а обратный порядок дал бы
-- отказ на первом же документном предъявлении.
--
-- Снятие основания стережёт по-прежнему запрет в ручке (Р6 п. 1), а не ключ: объект из хранилища
-- уходит только через `scheduleFilesDeletion`, и она обновляет лишь файлы без единой связи
-- (`WHERE NOT file_is_linked(id)`).

ALTER TABLE service_request_files
  -- Умолчание `closing_evidence` — требование окна выката: старый код подшивает файлы, про роль не
  -- зная, и роль обязана получаться та же, что была до выката. `ADD COLUMN ... DEFAULT` с
  -- PostgreSQL 11 таблицу не перезаписывает, поэтому работающему порталу эта правка стоит одной
  -- записи в каталоге.
  ADD COLUMN purpose text NOT NULL DEFAULT 'closing_evidence',
  -- Чьим основанием файл является. Номером ревизии, а не ссылкой на строку: у документной ревизии
  -- страниц несколько, и связь «файл → ревизия» живёт здесь же.
  ADD COLUMN estimate_revision integer,
  -- Порядок страниц одного документа: счёт сканируют по листам, и «страница 2» обязана знать, что
  -- она вторая, — иначе распознавание (Р12) привяжет предложение не к тому листу.
  ADD COLUMN page_no integer;

ALTER TABLE service_request_files
  ADD CONSTRAINT service_request_files_purpose_check
    CHECK (purpose IN ('closing_evidence','estimate_basis')),
  -- Роль основания не раздаётся сама, и оба условия закрывают разные дыры. Без вида любая подшивка —
  -- фотография поломки, акт, гарантийный талон — смогла бы стать «основанием» и выпала бы из
  -- закрывающих бумаг, то есть заявка перестала бы закрываться. Без ревизии счёт стал бы беспризорным
  -- основанием: замок «основание не снимается никогда» (Р6) ищет страницы по ревизии, и файл без неё
  -- снялся бы обычной кнопкой вместе с доказательством денежного решения.
  --
  -- Старому коду ограничение недостижимо: роль он не пишет вовсе, а умолчание `closing_evidence`
  -- противоречить ему не может — первая же ветвь условия истинна.
  ADD CONSTRAINT service_request_files_basis_check
    CHECK (purpose <> 'estimate_basis' OR (kind = 'invoice' AND estimate_revision IS NOT NULL)),
  -- Нулевая и отрицательная страница — не порядок, а опечатка: нумерация листов начинается с 1.
  ADD CONSTRAINT service_request_files_page_no_check CHECK (page_no IS NULL OR page_no >= 1),
  -- Пара целиком, а не один номер: ревизии нумеруются внутри заявки, и ссылка «ревизия 3» без заявки
  -- не означает ничего. `MATCH SIMPLE` (умолчание) — то, что здесь и нужно: у вложения
  -- `estimate_revision` пуст, и пустая половина пары снимает проверку, а непустую её половину уже
  -- держит `service_request_files_basis_check`.
  --
  -- Проверка существующих строк при добавлении ключа бесплатна: колонка появилась этой же миграцией и
  -- у всех строк пуста. Блокировка — та же `ACCESS EXCLUSIVE`, которую этот `ALTER TABLE` уже держит
  -- предыдущими ограничениями, поэтому `NOT VALID` с отдельным `VALIDATE` не купил бы работающему
  -- порталу ничего, а оставил бы непроверенное ограничение — ту самую тихую дыру.
  ADD CONSTRAINT service_request_files_estimate_revision_fk
    FOREIGN KEY (request_id, estimate_revision)
    REFERENCES service_request_estimate_revisions (request_id, revision) ON DELETE RESTRICT;

-- Отбор закрывающих документов после появления роли: предикат спрашивает «есть ли у этой заявки
-- бумага такого вида в такой роли», и обе половины правила теперь в ключе — `EXISTS` закрывается
-- индексом, не заглядывая в таблицу. Читателей семь (находка Н8 плана), двое из них — SQL-ем в
-- очереди «Ожидаются документы» и в отборе автозакрытия, то есть в фоновом воркере, где медленный
-- план заметят последним.
--
-- Ведёт `request_id`: правило всегда спрашивают про одну заявку. ПОЛНЫЙ, а не частичный по роли:
-- про роль спрашивают с обеих сторон — и «закрывающие бумаги заявки», и «страницы основания этой
-- ревизии», — и частичный индекс по одному значению оставил бы вторую половину читателей без
-- индекса. Соседний `service_request_files_doc_idx` остаётся: он меньше и отвечает тем, кто про роль
-- не спрашивает вовсе.
CREATE INDEX service_request_files_closing_idx
  ON service_request_files (request_id, kind, purpose);

COMMENT ON COLUMN service_request_files.purpose IS
  'Роль файла: closing_evidence — вложение и закрывающая бумага (умолчание, поведение до выпуска), '
  'estimate_basis — страница счёта, на котором стоит денежное решение. План освобождения от '
  'согласования, Р5; назначает только сервер.';

-- BACKFILL РОЛИ ОТДЕЛЬНЫМ `UPDATE` НЕ НУЖЕН: умолчание `closing_evidence` проставлено каждой
-- существующей строке самим `ADD COLUMN ... DEFAULT` — именно таким существующие связи и были
