-- Комментарий исполнителя: вторая сторона заявки на вывоз.
--
-- Комментарий у заявки был один, и писала его площадка. Оператору писать было некуда: правки
-- заявки он не ведёт (ADR 0038), а текст при смене статуса уходит в историю статусов и в списке
-- не виден — «будем после 15:00» доходило до диспетчера звонком и там же терялось.
--
-- Отдельная колонка, а не журнал сообщений: сторон две, и от каждой нужно актуальное примечание,
-- а не переписка. Кто и когда его правил, отвечает история заявки (ADR 0012).
--
-- NOT NULL DEFAULT '' без CHECK на непустоту: примечание необязательно с обеих сторон, пустая
-- строка означает «не сказали ничего», и отличать её от NULL незачем — тем же приёмом, что и
-- соседний `comment`.

ALTER TABLE waste_requests
  ADD COLUMN operator_comment text NOT NULL DEFAULT '';

COMMENT ON COLUMN waste_requests.comment IS 'Комментарий площадки (стороны заказчика)';
COMMENT ON COLUMN waste_requests.operator_comment IS 'Комментарий контрагента-исполнителя (оператора вывоза)';
