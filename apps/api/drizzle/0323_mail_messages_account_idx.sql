-- Индекс под журнал отправки писем (ADR 0199): подвкладка «Аудит» раздела «Рассылки».
--
-- Список читается ровно одним способом — «письма этого канала, новые сверху», — и другого у него
-- нет: канал в запросе обязателен (умолчание в схеме), сортировка по умолчанию `created_at DESC`.
-- Существующие индексы очереди на этот запрос не ложатся: `mail_messages_status_idx` начинается со
-- статуса, который в журнале чаще всего не задан вовсе, а `user`/`person`/`run` — частичные и про
-- другие вопросы.
--
-- Очередь не чистится по сроку и растёт на сотни строк в день (задания водителям — письмо на
-- человека на рейс), поэтому без индекса каждый показ страницы означал бы полный проход по таблице
-- вместе с телами писем.
--
-- ОТКУДА НОМЕР. Снимок `ls apps/api/drizzle` 18.09.2026: последней в дереве стоит
-- `0322_assignment_transition_without_actor.sql` (соседний поток, ADR 0198). Свободны 0323 и 0324,
-- оба взяты подряд одной работой — индекс и запись выпуска.
--
-- CONCURRENTLY НЕ ИСПОЛЬЗУЕТСЯ, И ЭТО ОСОЗНАННО. Миграции накатываются в транзакции, а
-- `CREATE INDEX CONCURRENTLY` в ней запрещён; отдельный внетранзакционный шаг ради таблицы, где
-- десятки тысяч строк, а не десятки миллионов, стоил бы дороже, чем блокировка записи на секунды.
-- Письма в это время не теряются: постановка письма — часть транзакции бизнес-операции, она просто
-- подождёт индекса.
--
-- ОБРАТИМОСТЬ: `DROP INDEX mail_messages_account_idx`. Данных не трогает, схему не меняет.

CREATE INDEX IF NOT EXISTS mail_messages_account_idx
  ON mail_messages (account, created_at DESC);
