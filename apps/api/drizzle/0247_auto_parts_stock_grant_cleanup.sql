-- Уборка права `autoParts.stock` из состава назначаемых полномочий (план
-- `docs/auto-part-receipts-plan.md`, §5 «Модель данных», миграция C; решения Р4б, Р25, Р26, Р28;
-- ADR 0154). Выкат 3 «Уборка» — последний из трёх, и первый, который трогает данные.
--
-- ЭТО МИГРАЦИЯ SCHEMA+DATA, и сказано это прямо, а не выведено из содержимого: она заводит
-- постоянную таблицу `auto_parts_stock_grant_removed` и тем же файлом меняет данные —
-- снимает строки `grant_permissions`. Data-only она быть не может: снимок удаляемого обязана
-- сделать сама миграция, непосредственно перед `DELETE` (§5). Между этапом 0, где держателей
-- выявляли `SELECT`-ом на проде, и этим выкатом проходят два выката: состав наборов за это время
-- меняется, и вывод этапа 0 предобразом удаления не является.
--
-- ПОЧЕМУ ПРАВА УЖЕ НЕТ В СЛОВАРЕ. Его сняло выпуском 2 «Заморозка» (коммит `600fb4e`) — из
-- `PERMISSIONS` в `packages/contracts/src/permissions.ts`. Это был код, а не данные, и потому у
-- выпуска 2 не было ни одной миграции: любая из них применилась бы раньше, чем барьер пустоты
-- склада успел бы сказать «стоп», и отняла бы у отказа дешёвый откат (Р26). Строки таблицы
-- пережили выпуск и лежат сиротами ровно один выкат — этот.
--
-- СИРОТА ДОСТУПА НЕ ДАВАЛА, и уборка не про безопасность. Право, которого нет в словаре,
-- отсекается фильтром `isPermission` при сборке принципала (`apps/api/src/auth/principal.ts`) —
-- молча и на границе «база → код». Ни одной ручки такая строка не открывала ни дня.
--
-- ЧИСТИТСЯ ОНА РАДИ КАТАЛОГА. Набор, в котором числится несуществующее право, показывается
-- администратору как дающий больше, чем даёт: в окне полномочия стоит строка, по которой человек
-- судит о выданном доступе, а доступа за ней нет. Это расхождение между тем, что написано в
-- каталоге, и тем, что делает код, — и живёт оно, пока строку не убрать.
--
-- УДАЛЕНИЕ БЕЗУСЛОВНОЕ, без «если найдём» (Р4б). Состав миграции не может зависеть от результата
-- чужого запроса: с условием накат в деве и на проде перестаёт быть одним и тем же накатом — там
-- нашлись строки, здесь нет, и что именно применилось, узнаётся только по факту. Пустое удаление
-- при этом не стоит ничего: индекс `grant_permissions_permission_idx` отвечает на вопрос «в каких
-- наборах есть это право» прямо.
--
-- ОБРАТИМОСТЬ: ОТКАТА У ЭТОГО ВЫКАТА НЕТ, и это названо заранее (§5). `deploy-auto --previous` не
-- поможет — журнал станет новее образа выпуска 2, и тот не поднимется (`assertMigrationsApplied`);
-- восстановление дампа отобьёт `restore_gate` дважды. Остаются PITR (`docs/runbook.md`) и починка
-- вперёд, и выбирается вторая. Чинить при этом нужно ровно одно — набор, состоявший из одного
-- только `autoParts.stock`: он становится пустым, ничего не даёт и путает в окне учётки, поэтому
-- его либо пересобирают осмысленным составом, либо удаляют. Само право восстановлению не подлежит
-- и не должно: конструктор полномочий строит список из `PERMISSIONS`, схема состава — `z.enum`
-- по нему же, и вернуть снятое нельзя ни портальным окном, ни запросом.
--
-- КОМУ ВЫДАН ОПУСТЕВШИЙ НАБОР — спрашивается сразу после наката, соединением архива с живыми
-- назначениями (запрос целиком — в §5 плана): `auto_parts_stock_grant_removed` LEFT JOIN
-- `user_grants` при `NOT EXISTS (SELECT 1 FROM grant_permissions ...)`. `LEFT JOIN` — чтобы увидеть
-- и никому не выданный набор, `NOT EXISTS` — чтобы не потянуть держателей наборов, где после
-- уборки осталось живое.
--
-- ПОРЯДОК ВЫКАТА сторожит не человек: миграция катится только после того, как заморозка развёрнута,
-- признана здоровой и переход подтверждён (Р28) — проверка стоит в `deploy-auto`, а имена файлов
-- этого набора перечислены в `deploy/requires-frozen-release.list`. Накатанная мимо заморозки,
-- она отбивается отсутствием отметки перехода.
--
-- ОТКУДА НОМЕР. Проверено `ls apps/api/drizzle` непосредственно перед созданием файла (03.09.2026):
-- последняя миграция в дереве — `0246_releases_waste_ticket_auto_confirm.sql`. Отсюда `0247`;
-- запись выпуска едет соседним файлом `0248`. Ориентир плана (§13) не переносился: потоки номеров
-- миграций и ADR параллельны, и за время работы над планом они уезжали пять раз.

-- ── 1. Архив снятого ──
--
-- FK НА `grants` ЗДЕСЬ НЕТ, И ЭТО РЕШЕНИЕ, А НЕ ПРОПУСК. Починка вперёд разрешает опустевший набор
-- двумя способами, и один из них — удалить его. С `ON DELETE CASCADE` удаление унесло бы за собой
-- снимок, то есть единственную запись о том, что и у кого было снято; с `RESTRICT` — упёрлось бы в
-- собственный архив, и починка требовала бы сперва подчистить журнал уборки. Архив обязан пережить
-- предмет, о котором он рассказывает.
--
-- КОД НАБОРА ЛЕЖИТ СНИМКОМ, а не берётся соединением при чтении: набор к моменту чтения может быть
-- уже удалён, и `JOIN` ответил бы на вопрос «чей это был набор» пустотой. `code`, а не `name`:
-- по коду набор находят код приложения, миграции каталога и журнал действий, и он не меняется.
--
-- ТАБЛИЦА ОСТАЁТСЯ НАВСЕГДА. Выбор был из трёх: снять её руками после выката — получился бы schema
-- drift, о котором журнал миграций не знает и который всплывёт на первой же сверке; снять
-- отдельной последующей миграцией — значит завести четвёртый выкат ради двух-трёх строк;
-- сложить снимок файлом на хосте — значит вернуть состояние, живущее вне журнала и теряемое вместе
-- с машиной. Постоянная таблица с этим комментарием дешевле всех трёх. Если она когда-нибудь
-- начнёт мешать, её снимет обычная миграция — но это будет отдельное решение, а не хвост этого.
CREATE TABLE auto_parts_stock_grant_removed (
  -- Без FK (см. выше). NOT NULL даёт первичный ключ.
  grant_id uuid NOT NULL,
  grant_code text NOT NULL,
  -- Что снято. Сегодня всегда `autoParts.stock`, но колонка общая: следующая уборка права ляжет
  -- сюда же, а таблица «архив одного права» потребовала бы второй такой при первом же повторе.
  permission text NOT NULL,
  removed_at timestamptz NOT NULL DEFAULT now(),
  -- Пара уникальна по построению: в наборе право лежит один раз — это первичный ключ
  -- `grant_permissions`.
  PRIMARY KEY (grant_id, permission)
);

COMMENT ON TABLE auto_parts_stock_grant_removed IS
  'След одноразовой уборки: строки grant_permissions с правом autoParts.stock, снятые миграцией '
  '0247 (выкат 3 плана docs/auto-part-receipts-plan.md, ADR 0154). Право сняло из словаря '
  'выпуском 2 «Заморозка», доступа сирота не давала (isPermission в auth/principal.ts), убрана она '
  'ради каталога полномочий. Код набора лежит снимком, FK на grants нет намеренно: архив обязан '
  'читаться и после того, как опустевший набор удалили. Таблица постоянная — снятие её руками дало '
  'бы schema drift мимо журнала миграций; убрать её может только отдельная миграция, и это будет '
  'отдельное решение.';

-- ── 2. Снимок и удаление ──
--
-- Оба запроса — в одной транзакции: файл миграции целиком выполняется внутри `BEGIN`/`COMMIT`
-- (`applyMigrations`, `apps/api/src/db/migration-journal.ts`), поэтому «снято, но не записано»
-- невозможно ни при каком исходе. Своего `BEGIN` здесь нет намеренно — он превратил бы транзакцию
-- наката во вложенную и оставил бы журнал `_migrations` за её пределами.
--
-- Границы `>>> УБОРКА` / `<<< УБОРКА` — часть договора с тестом: db-случай
-- (`apps/api/test/auto-parts-stock-grant-cleanup.db.test.ts`) вырезает по ним ИМЕННО ЭТОТ SQL и
-- прогоняет его на своей сцене. Пересказ запроса рядом с тестом зеленел бы ровно до первой правки
-- оригинала. Метки не переименовывать не глядя: тест на их отсутствии падает нарочно, а не
-- проверяет пустоту молча.
-- >>> УБОРКА
-- `JOIN`, а не `LEFT JOIN`: `grant_permissions.grant_id` — внешний ключ на `grants` с каскадом,
-- строки без набора не бывает, и `LEFT JOIN` завёл бы в архив `NULL` в NOT NULL-колонке кода.
INSERT INTO auto_parts_stock_grant_removed (grant_id, grant_code, permission)
SELECT gp.grant_id, g.code, gp.permission
  FROM grant_permissions gp
  JOIN grants g ON g.id = gp.grant_id
 WHERE gp.permission = 'autoParts.stock';

DELETE FROM grant_permissions WHERE permission = 'autoParts.stock';
-- <<< УБОРКА
