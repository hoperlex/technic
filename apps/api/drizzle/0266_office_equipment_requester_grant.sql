-- Заводится набор «Оргтехника: заявитель» (`office_equipment_requester`) — последний из четырёх
-- профильных наборов модуля (план `docs/office-equipment-access-profiles-plan.md`, Р4, Р5, Р6,
-- §9.1 строка D, этап Э7).
--
-- ОТКУДА НОМЕР. Проверено `ls apps/api/drizzle/*.sql` непосредственно перед созданием файла
-- (04.09.2026): последняя миграция в дереве — `0265_office_equipment_operator_office_roles.sql`
-- (строка B того же этапа), свободен 0266. Номер берётся в момент создания файла и не
-- резервируется заранее: за время работы над этим же этапом соседний поток занял 0264.
--
-- ПОРЯДОК ВЫКАТА (§9.3 п. 3) СОБЛЮДЁН, И ОН ЗДЕСЬ НЕ ФОРМАЛЬНОСТЬ. Перед этой миграцией обязаны
-- стоять три вещи, и все три стоят:
--
--   · серверные двери плана карточки заявителя — проекция по аудитории, видимость видов файлов,
--     история и прямая ссылка (ADR 0160). Без них держатель набора видел бы суммы, сметы и счета
--     всех заявок компании: право `serviceRequests.finance` в наборе не нужно, но карточка до
--     разделения аудиторий отдавала деньги каждому читателю;
--   · страж авторства `actsAsRequestCustomer` (Р6) — та же волна, `packages/contracts/src/
--     service-requests.ts` и `apps/api/src/lib/access.ts`. Без него роль без оси, получившая этот
--     набор, правила и удаляла бы ЛЮБУЮ чужую «Новую»: предикат видимости ей ничего не сужает;
--   · миграция B (0265) — она открыла офисным ролям «Ведение». Порядок между B и D безразличен,
--     общее у них одно: обе разрешают выдачу ролям без оси, и обе ждут стража.
--
-- ЗАЧЕМ НАБОР, ЕСЛИ ЗАЯВИТЕЛЬ УЖЕ ЕСТЬ. Для `shtab`, `site`, `department` (и упраздняемых
-- `rukstroy`/`department_head`) «Заявитель» — это то, что даёт сама роль: заявку на свой принтер
-- они заводят без всякой выдачи, и им набор не положен вовсе. Он заведён ровно ради того случая,
-- ради которого пункт разбора и написан: менеджер и диспетчер видят справочник оргтехники, но
-- завести заявку не могут, — а именно они сидят в офисе рядом с принтером.
--
-- ОТВЕРГНУТО: дописать `serviceRequests.*` в роли `manager`/`dispatcher`. Это раздало бы модуль
-- всей диспетчерской разом, и обратно его было бы не забрать: право, пришедшее ролью, снимается
-- только выкатом. Набор снимается галочкой, с автором и временем в реестре выдач.
--
-- СОСТАВ — ШЕСТЬ ПРАВ, РОВНО ПО Р4, и каждое отвечает за свой шаг заказчика: `officeEquipment.read`
-- (выбрать аппарат в справочнике), `serviceRequests.read`, `.create`, `.update`, `.delete` (завести
-- свою заявку, поправить и удалить, пока её не отдали исполнителю) и `.files` (подшить фотографию
-- поломки). Ни срочности, ни назначения, ни статусов, ни объёма работ, ни `serviceRequests.finance`:
-- на каждое из них у профиля «Заявитель» в матрице §5 стоит «нет», и держат эти «нет»
-- отрицательные тесты, а не отсутствие строки в этом файле.
--
-- САМОДОСТАТОЧЕН (Р4): `PERMISSION_REQUIRES` объявляет `update`, `delete` и `files` зависимыми от
-- `serviceRequests.read`, и он в составе. Опирайся набор на базовую роль, как опирались наборы до
-- миграции 0261, — барьер требований отклонил бы выдачу ровно тем двум ролям, ради которых набор и
-- заводится: прав модуля заявок у них нет ни одного.
--
-- РОЛИ — `manager` и `dispatcher`, И ТОЛЬКО ОНИ (Р5). Ролям-заказчикам набор не нужен: права у них
-- уже есть, и набор, ничего не дающий, запрещён тестом каталога («набор обязан что-то давать
-- каждой перечисленной роли») — строка `grant_roles` под штабом была бы выдачей, не меняющей ни
-- одного права. Роль `operator` (внешний исполнитель) не перечисляется ни в одном наборе
-- оргтехники никогда (Р11): её права приходят типом контрагента, а набор раздал бы их по базовой
-- области, которой у подрядчика нет.
--
-- ЧТО ОТКРЫВАЕТСЯ ДЕРЖАТЕЛЮ, А ЧТО НЕТ. Чтение у роли без оси ГЛОБАЛЬНО — держатель видит заявки
-- всех площадок компании, в редактированной аудитории (без сумм, смет, счетов и актов). Это
-- действующая модель, а не дыра: у роли без оси так работает всякое право во всяком модуле, и
-- сузить её набором нельзя — область есть свойство роли, а не набора (ADR 0106, решение 2).
-- Изменяющие же действия сужены до СВОИХ строк стражем авторства (Р6): правка и удаление «Новой»,
-- подшивка и снятие своего вложения, письмо в обсуждение от лица заказчика. На чужой глобально
-- видимой строке все они отвечают 403 с причиной `side`, и отказ попадает в журнал.
--
-- ЧЕГО МИГРАЦИЯ НЕ ДЕЛАЕТ, И ЭТО ГЛАВНОЕ ЕЁ СВОЙСТВО ПО §13 ПЛАНА КАРТОЧКИ. Она НЕ ТРОГАЕТ НИ
-- ОДНОГО СУЩЕСТВУЮЩЕГО НАБОРА: ни состава, ни ролей, ни описаний. Соседний план требовал, чтобы
-- вставки в существующие наборы шли `ON CONFLICT DO NOTHING` (его §13, тест §7.2.15, критерий 14),
-- — здесь таких вставок нет вовсе, единственный `INSERT` в `grant_permissions` и `grant_roles`
-- бьёт по новому коду, а `serviceRequests.finance`, ради которого оговорка и писалась, приехал в
-- «Ведение» и ИТ-набор ещё миграцией 0259. Караул ниже проверяет это как утверждение, а не как
-- намерение: составы трёх соседних наборов сверяются по числу прав.
--
-- Ни одной строки `user_grants` тоже не создаётся: набор выдаёт администратор поимённо, с автором
-- и временем в реестре. Автоматическое назначение во всём плане было ровно одно — backfill 0262,
-- и там оно было ВЫНУЖДЕННЫМ (разделение отобрало бы работу у живых держателей).
--
-- ГДЕ ЖИВЁТ ОБЪЯВЛЕННЫЙ СОСТАВ: `MODULE_GRANTS` (`packages/contracts/src/grants.ts`), рядом с
-- исполнителем, номенклатурой и аудитом талонов. Правка контрактов едет ТОЙ ЖЕ волной, что эта
-- миграция, — разъехавшись, они дали бы одному человеку разные права в зависимости от того, каким
-- источником пришёл доступ. Обе стороны сверяет страж `apps/api/test/grants-catalog.db.test.ts`.
--
-- ОБРАТИМОСТЬ. Схема не меняется, трогаются три таблицы каталога, и все три — только по новому
-- коду. Откат: снять `grant_roles`, затем `user_grants` набора (если администратор успел выдать),
-- затем `grant_permissions`, затем сам набор — в этом порядке, `user_grants.grant_id` объявлен
-- `RESTRICT`.

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 0. Снимок назначений набора ДО правки — ради утверждения «миграция никому его не выдаёт».
--
-- На первом накате он пуст по построению (набора ещё нет), и вся ценность снимка — во ВТОРОМ:
-- миграция повторяется на базе, восстановленной из копии, где набор уже выдан живым учёткам, и
-- проверка «назначений ноль» соврала бы про собственную работу. Сравнение с «до» правдиво в обоих
-- случаях. `ON COMMIT DROP`: таблица живёт до конца транзакции миграции и в базе не остаётся.

CREATE TEMP TABLE requester_holders_0266 ON COMMIT DROP AS
SELECT ug.user_id
FROM user_grants ug
JOIN grants g ON g.id = ug.grant_id
WHERE g.code = 'office_equipment_requester';

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 1. Сам набор. Описание — абзац для администратора, который читается на экране каталога рядом с
--    названием: оно объясняет РАБОТУ, а не перечисляет права (перечень он видит и так).
--
-- `ON CONFLICT (code) DO UPDATE` — не «на всякий случай»: повторный накат на базу, восстановленную
-- из копии, обычное дело, и миграция обязана довести каталог до объявленного состояния, а не
-- упасть на первой строке.

INSERT INTO grants (code, name, description, is_system) VALUES
  (
    'office_equipment_requester',
    'Оргтехника: заявитель',
    'Открывает работу заказчика в модуле «Орг.техника» тем должностям, у которых модуля нет вовсе: '
    'посмотреть справочник и выбрать аппарат, завести по нему заявку, поправить и удалить её, пока '
    'её не взяли в работу, приложить фотографию поломки и переписываться по своей заявке. Набор '
    'нужен офису — менеджеру и диспетчеру: у штаба, площадки и отдела всё это есть по роли, и '
    'выдавать им его не нужно. Ход заявки, назначение исполнителя, срочность, объём работ, суммы и '
    'закрывающие документы набор НЕ открывает — это работа «Ведения» и исполнителя. Заявки '
    'компании держателю видны все (у его должности нет своей площадки), но денег в них он не '
    'видит, а править, удалять и подшивать может ТОЛЬКО в тех, которые завёл сам.',
    true
  )
ON CONFLICT (code) DO UPDATE
   SET name = EXCLUDED.name, description = EXCLUDED.description, updated_at = now();

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 2. Состав — шесть прав по Р4. Набор ищется по коду: коды стабильны навсегда, по ним его находят
--    миграции каталога, журнал действий и реестр выдач.

INSERT INTO grant_permissions (grant_id, permission)
SELECT g.id, s.permission
FROM grants g
JOIN (VALUES
  ('office_equipment_requester', 'officeEquipment.read'),
  ('office_equipment_requester', 'serviceRequests.read'),
  ('office_equipment_requester', 'serviceRequests.create'),
  ('office_equipment_requester', 'serviceRequests.update'),
  ('office_equipment_requester', 'serviceRequests.delete'),
  ('office_equipment_requester', 'serviceRequests.files')
) AS s (code, permission) ON s.code = g.code
ON CONFLICT (grant_id, permission) DO NOTHING;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 3. Совместимые роли — ПОСЛЕДНИМ шагом, тем же приёмом, что у 0262: до этой строки набор
--    существует, но не действует ни у кого (гейт `grantPermissionsExpr` соединяется с
--    `grant_roles`), и пока он не действует, заведение обратимо одним `DELETE`.

INSERT INTO grant_roles (grant_id, role)
SELECT g.id, s.role::role
FROM grants g
JOIN (VALUES
  ('office_equipment_requester', 'manager'),
  ('office_equipment_requester', 'dispatcher')
) AS s (code, role) ON s.code = g.code
WHERE g.deleted_at IS NULL
ON CONFLICT (grant_id, role) DO NOTHING;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 4. Караул: состав и роли нового набора — плюс НЕПРИКОСНОВЕННОСТЬ трёх соседних.
--
-- Страж-тест сверяет каталог с контрактами, но живёт он в репозитории, а этот блок — в накате:
-- оператор выката увидит расхождение сразу, а не через прогон тестов.
--
-- Права нового набора названы ПОИМЁННО, а не сосчитаны: счёт «их шесть» сошёлся бы и у набора,
-- собранного из чужих прав. Соседние наборы, наоборот, проверяются числом — их составы этот файл
-- не трогает вовсе, и утверждение здесь ровно одно: «столько же, сколько было». Числа взяты по
-- факту базы после 0259, 0261 и 0262: «Ведение» — 15, ИТ-служба — 8, исполнитель — 3.
--
-- СЛЕДУЮЩАЯ МИГРАЦИЯ КАТАЛОГА обязана вести счёт от этих чисел, а не выводить его из головы.
-- Ближайшая известная — E того же плана: она снимет мёртвое `serviceRequests.approveIt`, и в
-- ИТ-наборе останется семь.

DO $$
DECLARE trouble text;
BEGIN
  SELECT string_agg(msg, '; ')
    INTO trouble
    FROM (
      SELECT format('набора нет или он не системный (найдено строк: %s вместо одной)', count(*))
             AS msg
        FROM grants
       WHERE code = 'office_equipment_requester' AND is_system AND deleted_at IS NULL
      HAVING count(*) <> 1
      UNION ALL
      SELECT format('office_equipment_requester: состав %s',
                    coalesce(string_agg(gp.permission, ', ' ORDER BY gp.permission), 'пуст'))
        FROM grants g
        LEFT JOIN grant_permissions gp ON gp.grant_id = g.id
       WHERE g.code = 'office_equipment_requester'
      HAVING coalesce(array_agg(gp.permission ORDER BY gp.permission), ARRAY[]::text[])
               <> ARRAY['officeEquipment.read', 'serviceRequests.create', 'serviceRequests.delete',
                        'serviceRequests.files', 'serviceRequests.read', 'serviceRequests.update']
      UNION ALL
      SELECT format('роли набора «Заявитель»: %s',
                    coalesce(string_agg(gr.role::text, ', ' ORDER BY gr.role::text), 'ни одной'))
        FROM grants g
        LEFT JOIN grant_roles gr ON gr.grant_id = g.id
       WHERE g.code = 'office_equipment_requester'
      HAVING coalesce(array_agg(gr.role::text ORDER BY gr.role::text), ARRAY[]::text[])
               <> ARRAY['dispatcher', 'manager']
      UNION ALL
      SELECT format('держателей набора «Заявитель» стало %s вместо %s: миграция кому-то его выдала',
                    (SELECT count(*) FROM user_grants ug
                       JOIN grants g ON g.id = ug.grant_id
                      WHERE g.code = 'office_equipment_requester'),
                    (SELECT count(*) FROM requester_holders_0266))
       WHERE (SELECT count(*) FROM user_grants ug
                JOIN grants g ON g.id = ug.grant_id
               WHERE g.code = 'office_equipment_requester')
             <> (SELECT count(*) FROM requester_holders_0266)
      UNION ALL
      SELECT format('состав соседнего набора «%s» изменился: прав %s вместо %s',
                    g.code, count(gp.permission), e.expected)
        FROM grants g
        JOIN (VALUES
          ('office_equipment_operator', 15),
          ('office_equipment_it_approver', 8),
          ('office_equipment_executor', 3)
        ) AS e (code, expected) ON e.code = g.code
        LEFT JOIN grant_permissions gp ON gp.grant_id = g.id
       GROUP BY g.code, e.expected
      HAVING count(gp.permission) <> e.expected
    ) AS bad;
  IF trouble IS NOT NULL THEN
    RAISE EXCEPTION 'Заведение набора «Оргтехника: заявитель» прошло не так, как объявлено — %',
                    trouble;
  END IF;
END $$;
