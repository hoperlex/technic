-- Тип ТС «Телескопические погрузчики» (ADR 0005).
--
-- В старой иерархии (0010) такой подтип был — `telescopic_loader` под «Погрузчиками», — но
-- уплощение 0013 свело его вместе с вилочным и мини-погрузчиком в один плоский тип «Вилочные
-- погрузчики и минипогрузчики»: так эта строка называлась в бухвыгрузке, а классификатор
-- собирался по ней. Для учёта машин слияние было безобидным, для заявки — нет: технику под
-- заявку подбирают по типу (ADR 0045), а телескопом и вилочным погрузчиком делают разную
-- работу — подать груз на этаж мачтовым вылетом вилочный не может. Заказчику нужен тип, который
-- называет именно эту машину.
--
-- Вид — «Спецтехника», по тому же правилу, что в 0016 и 0044: машина работает на объекте, а не
-- перевозит груз по дорогам.
--
-- ТТХ не привязываются: тип сам является конечной классификацией (ADR 0016 §2, привязки в 0045).
-- Грузоподъёмность у соседей по погрузчикам есть, но телескоп различает не она, а высота подачи
-- при вылете стрелы, и одним числом эти две величины не заменяются. Пока техника этого типа не
-- заведена, придумывать ей характеристику не из чего; появится потребность различать позиции —
-- ТТХ привяжется отдельно, вместе с категориями.
--
-- sort_order 55 — свободный слот между «Фронтальными погрузчиками» (50) и «Экскаватором
-- колесным» (60): в списке спецтехники три погрузчика стоят рядом, а не расходятся по краям.
--
-- Заведённые машины сюда не переносятся. В «Вилочных погрузчиках и минипогрузчиках» есть
-- телескопические (Manitou M26-4 помечен таким в 0048), но у них проставлены категории по
-- грузоподъёмности, а у нового типа категорий нет вовсе — перенос означал бы снять категорию
-- машине, на которую уже ссылаются заявки. Разбор конкретных машин — отдельным решением, через
-- справочник (смена типа у машины разрешена).
--
-- Идемпотентно по `code` (vehicle_types_code_unique).
INSERT INTO vehicle_types (kind_id, code, name, is_active, sort_order) VALUES
  ((SELECT id FROM vehicle_kinds WHERE code = 'special_equipment'),
   'telescopic_loaders', 'Телескопические погрузчики', true, 55)
ON CONFLICT (code) DO NOTHING;
