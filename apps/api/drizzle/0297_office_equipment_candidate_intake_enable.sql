-- Включение приёма сообщений о технике — рубильник `office_equipment_candidate_intake` (ADR 0165,
-- ADR 0177 решение 8; планы `docs/office-equipment-candidate-plan.md` §14 и
-- `docs/office-equipment-request-subject-plan.md` Р10). Это ПОСЛЕДНИЙ невыполненный шаг выпуска B
-- волны кандидатов: код написан 04.09.2026, права разложены и письма включены 09.09.2026, а третья
-- ветвь формы заявки с тех пор закрыта одной строкой состояния.
--
-- ОТКУДА НОМЕР. `ls apps/api/drizzle` непосредственно перед созданием файла (10.09.2026): последним
-- в дереве стоит `0296_releases_office_equipment_request_subject.sql` — запись выпуска 88 этой же
-- волны, — незакоммиченных миграций у соседних потоков в дереве нет. Свободен 0297, он и взят.
--
-- ПОЧЕМУ МИГРАЦИЯ, А НЕ ТОТ РУЧНОЙ `UPDATE`, КОТОРЫЙ ОБЕЩАЛИ ADR 0177 И ЗАПИСЬ ВЫПУСКА 88. Обещание
-- сформулировано ради ПОРЯДКА («после health и smoke»), а не ради ручного способа, и ручной способ
-- этот порядок обеспечивает единственной ценой: включение не оставляет следа нигде. Его нет ни в
-- журнале миграций, ни в репозитории, ни в истории — только в памяти того, кто набрал команду. Три
-- последствия, и все три уже случались в этом проекте:
--
--   · база, поднятая из резервной копии старше дня включения, возвращается с ЗАКРЫТЫМ приёмом, и
--     отличить это состояние от «так и задумано» снаружи нечем — читатель трактует и выключенную
--     строку, и отсутствующую одинаково (fail-closed, миграция 0293);
--   · дев и любой второй контур остаются в другом состоянии, чем прод, — сегодня это ровно так и
--     есть: на `technic_dev` рубильник щёлкнут руками 09.09.2026 при разборе вопроса «где этот
--     интерфейс», а на проде нет, и разница эта нигде не записана;
--   · «шаг после выката» — самая теряемая часть выката: волна ЭСМ-2 уже теряла работу на шаге
--     `deploy-auto` ровно потому, что та жила вне наката.
--
-- Миграция делает тот же самый `UPDATE`, но записанный: журнал `_migrations` отвечает «когда»,
-- файл — «почему», а любая база, доведённая до этого номера, приходит во включённое состояние сама.
--
-- ПОРЯДОК «ПОСЛЕ HEALTH И SMOKE» СОБЛЮДЁН, И СОБЛЮДЁН СИЛЬНЕЕ, ЧЕМ ПРОСИЛ ADR. Код волны работает
-- на проде с 09.09.2026 (выпуск 88, версия `0.1.77.0177`, коммит `521857c`): health и smoke того
-- выката пройдены сутки назад, и этот файл едет СЛЕДУЮЩИМ выкатом, то есть накатывается на сервер,
-- который о кандидатах уже знает. В том, вчерашнем выкате миграцией это было бы нельзя: миграции
-- применяются ДО перезапуска приложения, и старый сервер, ничего не знающий о рубильнике, принимал
-- бы кандидатов раньше, чем появился код, который их разбирает. Сегодня этого разрыва нет вовсе.
--
-- ЧЕГО МИГРАЦИЯ ЖДЁТ ПЕРЕД СОБОЙ — и проверяет это утверждением, а не полагается на порядок
-- номеров: строку рубильника (0293), права `officeEquipment.propose` и `officeEquipment.review` в
-- каталоге наборов (0294) и включённые письма кандидата (0295). Ни одно из трёх не является
-- «формальностью выката»: без прав дверь открылась бы в пустоту, без писем проверяющие не узнали бы
-- о первом же сообщении, а без строки включать было бы нечего.
--
-- ЧТО МЕНЯЕТСЯ У ЛЮДЕЙ В МИНУТУ НАКАТА. Заявитель (пять ролей-заказчиков, администратор и держатели
-- набора «Оргтехника: заявитель»), не нашедший аппарат в справочнике, получает под полем «Какой
-- аппарат» вторую дверь — «Заполнить самостоятельно»: шесть реквизитов наблюдения уходят вместе с
-- заявкой одной транзакцией. Сообщения попадают в очередь «Техника → На проверке» к держателям
-- `officeEquipment.review`, и с первого же сообщения начинают уходить два письма — `…_pending`
-- проверяющим и `…_decided` автору. Перезапуск приложения не нужен: значение читается на каждый
-- ответ сессии без кэша, намеренно (`apps/api/src/services/feature-flags.ts`).
--
-- ЧЕГО МИГРАЦИЯ НЕ ДЕЛАЕТ.
--
--   · НЕ ВЫДАЁТ И НЕ ОТЗЫВАЕТ НИ ОДНОГО ПРАВА. Рубильник открывает приём тем, кому он разрешён, а
--     не вместо разрешения: у кого права нет, тот по-прежнему видит третью ветвь — обращение в
--     техподдержку;
--   · НЕ ЗАВОДИТ АДРЕСАТОВ КОПИЙ. `module_mail_recipients` — работа администратора, принимаемая
--     осознанно;
--   · НЕ ПИШЕТ ЗАПИСЬ ВЫПУСКА, и это единственное решение здесь, требующее защиты. Лента уже
--     обещала эту дверь третьим пунктом выпуска 88 («Если аппарата нет в справочнике вовсе, опишите
--     его сами»), и сегодняшний накат не добавляет обещания, а делает вчерашнее правдой. Вторая
--     запись сообщала бы человеку о перемене, которой с его стороны не происходит: он не знает и не
--     обязан знать, что сутки читал обещание закрытой двери;
--   · НЕ МЕНЯЕТ СХЕМУ. Аддитивная правка одной строки состояния; протокол выката необратимых
--     миграций (`docs/schema-cutover-protocol.md`) к ней не применяется.
--
-- ОБРАТИМОСТЬ И АВАРИЙНОЕ ВЫКЛЮЧЕНИЕ. Приток кандидатов прекращается тем же `UPDATE … SET
-- is_enabled = false` по живому серверу — без выката, без отката этого файла и без перезапуска.
-- Очередь проверки, уже принятые сообщения и три решения по ним рубильник не ограждает намеренно:
-- прекратить приток обязаны, а запереть принятое — нет, иначе люди, уже отправившие сообщение,
-- остались бы без ответа.

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 1. Караул предусловий: три вещи, без которых включать нечего и незачем.
--
-- Проверяется СОСТОЯНИЕ БАЗЫ, а не наличие миграций в журнале: на восстановленной из копии базе
-- номера те же, а состав каталога полномочий и рубильников мог разъехаться — и разъехавшись, он
-- превратил бы включение приёма в открытую дверь без проверяющих.

DO $$
DECLARE trouble text;
BEGIN
  SELECT string_agg(msg, '; ')
    INTO trouble
    FROM (
      SELECT 'строки рубильника нет — миграция 0293 не накачена, включать нечего' AS msg
       WHERE NOT EXISTS (
         SELECT 1 FROM feature_flags WHERE key = 'office_equipment_candidate_intake')
      UNION ALL
      SELECT format('в наборе «%s» нет права «%s» — миграция 0294 не накачена', s.code, s.permission)
        FROM (VALUES
          ('office_equipment_requester', 'officeEquipment.propose'),
          ('office_equipment_operator', 'officeEquipment.review')
        ) AS s (code, permission)
       WHERE NOT EXISTS (
         SELECT 1
           FROM grants g
           JOIN grant_permissions gp ON gp.grant_id = g.id
          WHERE g.code = s.code AND gp.permission = s.permission)
      UNION ALL
      SELECT format('письмо «%s» выключено — миграция 0295 не накачена', e.event)
        FROM (VALUES
          ('office_equipment_candidate_pending'),
          ('office_equipment_candidate_decided')
        ) AS e (event)
       WHERE NOT EXISTS (
         SELECT 1
           FROM module_mail_event_settings s
          WHERE s.event = e.event AND s.is_enabled)
    ) AS bad;
  IF trouble IS NOT NULL THEN
    RAISE EXCEPTION
      'Приём сообщений о технике включать рано — %', trouble;
  END IF;
END $$;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 2. Предупреждение о некому разбирать — ЗАМЕЧАНИЕМ, А НЕ ОТКАЗОМ, и разница здесь содержательная.
--
-- Пустой набор «Оргтехника: ведение» означает, что сообщения будут копиться, а письмо проверяющим
-- уйдёт в `no_recipients`, — это плохо, но это состояние ВЫДАЧ, а не выката: набор выдают живым
-- учёткам в любой день, в том числе через час после наката. Упади миграция здесь, она остановила бы
-- весь выкат из-за работы администратора, а на деве, где наборы не выдают вовсе, не проходила бы
-- никогда. Право считается по набору, а не по итоговым правам учётки: администратору `review`
-- приходит полным словарём, и, посчитай мы его, проверяющие «нашлись» бы на любой базе — при том
-- что письмо очереди администраторам намеренно не шлётся.

DO $$
DECLARE holders bigint;
BEGIN
  SELECT count(*)
    INTO holders
    FROM user_grants ug
    JOIN grants g ON g.id = ug.grant_id
    JOIN users u ON u.id = ug.user_id
   WHERE g.code = 'office_equipment_operator'
     AND g.deleted_at IS NULL
     AND u.is_active
     AND u.deleted_at IS NULL;
  IF holders = 0 THEN
    RAISE NOTICE
      'Приём сообщений о технике включён, но набор «Оргтехника: ведение» не выдан ни одной активной учётке: очередь проверки разбирать некому, письмо проверяющим уйдёт в no_recipients';
  END IF;
END $$;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 3. Сам рубильник.
--
-- Условие `is_enabled = false` — не про идемпотентность (результат обоих накатов один и тот же, и
-- караул ниже проверяет именно результат), а про `updated_at`: столбец отвечает на вопрос «когда
-- дверь открыли», и повторный накат на уже включённой базе не должен переписывать этот ответ
-- сегодняшним днём. Дев, где рубильник щёлкнут руками, миграцию так и пройдёт — молча и не тронув
-- строки.

UPDATE feature_flags
   SET is_enabled = true,
       updated_at = now()
 WHERE key = 'office_equipment_candidate_intake'
   AND is_enabled = false;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 4. Караул результата: дверь открыта, и открыта ровно одна.
--
-- Второе утверждение не про сегодня, а про завтра: `CHECK` таблицы держит перечень ключей одним
-- значением, и появись в ней второй рубильник, включённый заодно с этим, — узнать об этом лучше на
-- накате, чем по звонку.

DO $$
DECLARE opened text;
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM feature_flags
     WHERE key = 'office_equipment_candidate_intake' AND is_enabled)
  THEN
    RAISE EXCEPTION 'Рубильник приёма сообщений о технике остался выключенным — включение не сработало';
  END IF;
  SELECT string_agg(key, ', ' ORDER BY key)
    INTO opened
    FROM feature_flags
   WHERE is_enabled AND key <> 'office_equipment_candidate_intake';
  IF opened IS NOT NULL THEN
    RAISE EXCEPTION 'Вместе с приёмом сообщений оказались включены чужие рубильники: %', opened;
  END IF;
END $$;
