-- Переклассификация техники разрешена: служебная копия типа в назначении едет за машиной (ADR 0061).
--
-- `vehicle_request_assignments.vehicle_type_id` — копия типа НАЗНАЧЕННОЙ машины (миграция `0083`).
-- Её не читает ни один запрос: колонка существует ровно ради составного FK на `vehicles`, которым
-- «в назначении записан тип той машины, которая назначена» держится физически.
--
-- `ON UPDATE` у ключа задан не был, то есть `NO ACTION`. Из-за этого справочник техники не давал
-- сменить тип у машины, на которую хоть раз назначали заявку: `PATCH /vehicles/:id` падал с 23503
-- («violates foreign key constraint … is still referenced»), маршрут ошибку целостности не
-- переводил, и человек читал «Внутренняя ошибка сервера» — про поле, которое он правит руками.
--
-- Переклассификация парка при этом обычная работа справочника, а не исключение: машину заводят по
-- накладной («Грузовой малотоннажный»), а с ПТС в руках выясняется, что это манипулятор, и
-- заказывать её нужно из другой позиции классификатора (ADR 0028). Запрета на это нигде не
-- объявляли — он получился побочно, из умолчания внешнего ключа.
--
-- Каскад здесь не послабление, а смысл колонки: копия обязана совпадать с оригиналом, и следовать
-- за ним ей нечем, кроме каскада. Приём и прецедент те же, что у `vehicles_lessor_fk` (ADR 0018):
-- активность арендодателя в строке техники ведёт не приложение, а каскад FK.
--
-- Чего каскад НЕ касается:
--   · заказанный тип заявки — у него свой ключ `vehicle_request_assignments_ordered_type_fk`, и он
--     намеренно остаётся `NO ACTION`: сменить заказ под назначенной машиной нельзя, и сервер
--     отвечает на это 422 словами, а не ошибкой целостности (миграция `0083`, ADR 0059);
--   · выданные путевые листы — бланк в них собственный снимок (`waybills.form_code`), и
--     переклассификация машины прошлые документы не переписывает.
--
-- `ON DELETE RESTRICT` сохраняется: назначенную технику из справочника по-прежнему не удалить.
--
-- Backwards-compatible: предыдущий релиз кода на такой ключ не опирается — он этой правки просто
-- не делал (и падал на ней). Пересоздание сканирует `vehicle_request_assignments` (одна строка на
-- заявку), блокировка короткая.

ALTER TABLE vehicle_request_assignments
  DROP CONSTRAINT vehicle_request_assignments_vehicle_type_fk;

ALTER TABLE vehicle_request_assignments
  ADD CONSTRAINT vehicle_request_assignments_vehicle_type_fk
  FOREIGN KEY (vehicle_id, vehicle_type_id)
  REFERENCES vehicles (id, vehicle_type_id)
  ON UPDATE CASCADE ON DELETE RESTRICT;

COMMENT ON COLUMN vehicle_request_assignments.vehicle_type_id IS
  'Копия типа НАЗНАЧЕННОЙ машины (цель составного FK на vehicles; ON UPDATE CASCADE — едет за машиной при переклассификации, ADR 0061). С заказанным типом заявки совпадать не обязан — ADR 0059.';
