-- Индекс аудита по сущности: история одной заявки.
--
-- Карточка заявки показывает её историю — создание, правки, смены статусов. Смены берутся из
-- request_status_history (там свой индекс по request_id с миграции 0001), а правки — из
-- audit_log по паре (entity_type, entity_id). Существующий audit_log_created_at_idx для такой
-- выборки бесполезен: без индекса по сущности каждое открытие карточки читало бы весь аудит,
-- который растёт по всем модулям сразу.
--
-- created_at DESC в индексе — потому что история читается «свежие сначала» с лимитом.

CREATE INDEX audit_log_entity_idx ON audit_log (entity_type, entity_id, created_at DESC);
