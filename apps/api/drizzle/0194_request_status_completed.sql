-- Статус «Завершена» у заявки на вывоз (ADR 0135): бумага разобрана, сверка сошлась, спрашивать
-- по заявке больше нечего. «Выполнена» отвечает на «вывезли», «Завершена» — на «приняли».
--
-- ФАЙЛ ДЕЛАЕТ ОДНО: добавляет значение в enum. Разделение с наполнением (0195) вынужденное, а не
-- стилистическое: раннер применяет каждый файл одной транзакцией (`migration-journal`), а
-- PostgreSQL запрещает ИСПОЛЬЗОВАТЬ значение enum'а в той же транзакции, где оно добавлено
-- («unsafe use of new value»). UPDATE со свежим значением и CHECK, который на него ссылается,
-- упали бы прямо здесь — оба уехали в соседний файл.
--
-- `BEFORE 'cancelled'` — не косметика: порядок значений enum'а задаёт `ORDER BY status`, столбец
-- «Статус» в списке сортируется именно им, и приписанное в конец значение поставило бы
-- «Завершена» после «Отменена» — то есть цикл в таблице читался бы неверно. Тот же порядок стоит
-- в `REQUEST_STATUSES` контрактов и в `requestStatusEnum` drizzle-схемы.
--
-- Тип общий на два модуля (`waste_requests.status` и `vehicle_requests.status`), и значение
-- становится доступно обоим. Перехода в него у заказа техники нет ни в одном коридоре, а запрет
-- на уровне базы ставит 0195 — здесь его поставить нечем по той же причине, что и UPDATE.

ALTER TYPE request_status ADD VALUE IF NOT EXISTS 'completed' BEFORE 'cancelled';
