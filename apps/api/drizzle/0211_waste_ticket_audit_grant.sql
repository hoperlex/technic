-- Одноцелевой системный набор «Вывоз мусора: аудит распознавания» (ADR 0137, план
-- `docs/waste-ticket-audit-plan.md` §4.1).
--
-- ЗАЧЕМ НАБОР, А НЕ СТРОКА В МАТРИЦЕ РОЛЕЙ. Право `wasteRequests.ticketAudit` сквозное: держатель
-- видит адреса всех площадок и сканы талонов всех исполнителей — иначе доля исправлений считалась
-- бы по куску выборки и мерила бы не модель, а объект. Раздай его матрица роли — сквозная картина
-- досталась бы всей диспетчерской разом; заказчик просил обратного: назвать человека. Набор —
-- единственный в модели ADR 0106 способ выдать право поимённо, с автором, временем и записью в
-- реестре выдач: прямой персональной выдачи она не знает вовсе, а `NON_GRANTABLE_PERMISSIONS` дал
-- бы противоположное — право, которое не выдать никому.
--
-- ПОЧЕМУ ОДНОЦЕЛЕВОЙ, ТО ЕСТЬ ИЗ ОДНОГО ПРАВА. Аудит открывает шесть читающих ручек и одно окно
-- поверх реестра вывоза; резать это на «смотрит сводку» и «смотрит споры» значило бы предложить
-- администратору выбор, которого в работе не существует. Прецедент рядом — «Аудитор» (`auditor`) с
-- одним `audit.read`.
--
-- РОЛИ — ДИСПЕТЧЕР И МЕНЕДЖЕР, и это две причины сразу. Первая: аудит меряет качество машинного
-- чтения теми правками, которые делает человек при разборе талонов, а разбор ведёт диспетчерская
-- (`wasteRequests.ticketReview` выдан ей матрицей) — смотреть на свои же исправления со стороны её
-- работа. Вторая жёстче: журнал наблюдений не фильтруется предикатами вывоза вовсе (он переживает и
-- талон, и заявку, §4.2), поэтому набор обязан уходить только ролям без своей области — у роли с
-- осью он открыл бы данные всей компании, а барьер выдачи промолчал бы, потому что матрица осей
-- смотрит на модуль, а не на отдельное право. Ролей без оси, работающих с вывозом, ровно две.
-- Администратора в списке нет намеренно: право у него уже есть от матрицы, и строка совместимости
-- под ним означала бы набор, выдача которого ничего не меняет.
--
-- ЧЕГО ЗДЕСЬ НЕТ. Ни одной строки `user_grants`. Миграция заводит набор, его состав и совместимые
-- роли; кому он достанется — решает администратор портала поимённо. Дописанная сюда выдача «чтобы
-- сразу работалось» была бы расширением доступа миграцией: молча, мимо журнала выдач и мимо того,
-- кто за него отвечает.
--
-- КОД НАБОРА НЕ МЕНЯЕТСЯ НИ ПРИ КАКИХ УСЛОВИЯХ. По коду набор находят миграции каталога, журнал
-- действий и реестр выдач; `UPDATE grants SET code = ...` не переименовывает набор, а отвязывает
-- его от кода. Правятся название, описание и состав.
--
-- ГДЕ ЖИВЁТ ОБЪЯВЛЕННЫЙ СОСТАВ. В `MODULE_GRANTS` (`packages/contracts/src/grants.ts`); обе стороны
-- сверяет страж `apps/api/test/grants-catalog.db.test.ts` — разъедься копии, он назовёт набор и обе
-- стороны расхождения.
--
-- ОБРАТИМОСТЬ. Трогаются только три таблицы каталога, схема не меняется; протокол выката
-- необратимых миграций (`docs/schema-cutover-protocol.md`) к ней не применяется. Откат — удаление
-- набора, пока у него нет держателей (`RESTRICT` на `user_grants`).

-- ── 1. Набор ──
--
-- `ON CONFLICT` — не «на всякий случай»: повторный накат на базу, восстановленную из копии, обычное
-- дело, и миграция обязана довести каталог до объявленного состояния, а не упасть на первой строке.

INSERT INTO grants (code, name, description, is_system) VALUES
  (
    'waste_ticket_audit',
    'Вывоз мусора: аудит распознавания',
    'Открывает окно «Аудит распознавания» поверх реестра вывоза: насколько верно портал читает '
    'контрольные талоны, по каким полям ошибается, что приходится править человеку и как это '
    'меняется от конфигурации к конфигурации. Показывает скан любого талона и выгружает наблюдения '
    'в CSV — обе операции пишутся в журнал действий. Набор сквозной: держатель видит адреса всех '
    'площадок и талоны всех исполнителей, а не только своих. Заявки им не ведут и не правят: все '
    'ручки только читают.',
    true
  )
ON CONFLICT (code) DO UPDATE
   SET name = EXCLUDED.name, description = EXCLUDED.description, updated_at = now();

-- ── 2. Состав: одно право ──
--
-- Право хранится текстом — справочника прав в базе нет намеренно (`grant_permissions`, миграция
-- 0145): словарь `PERMISSIONS` закрыт и живёт в контрактах.

INSERT INTO grant_permissions (grant_id, permission)
SELECT g.id, s.permission
FROM grants g
JOIN (VALUES
  ('waste_ticket_audit', 'wasteRequests.ticketAudit')
) AS s (code, permission) ON s.code = g.code
ON CONFLICT (grant_id, permission) DO NOTHING;

-- ── 3. Совместимые роли ──
--
-- «Кому набор можно назначить», а не «кому он выдан». Только роли без собственной области: журнал
-- наблюдений сквозной, и роли с осью он открыл бы компанию целиком. Из таких ролей с вывозом
-- работают две — диспетчер и менеджер; наблюдатель решений о качестве не принимает, а обе роли
-- службы главного механика вывоза не касаются вовсе (без `wasteRequests.read` барьер требований
-- отклонил бы им выдачу и без этой строки).

INSERT INTO grant_roles (grant_id, role)
SELECT g.id, s.role::role
FROM grants g
JOIN (VALUES
  ('waste_ticket_audit', 'dispatcher'),
  ('waste_ticket_audit', 'manager')
) AS s (code, role) ON s.code = g.code
ON CONFLICT (grant_id, role) DO NOTHING;

-- ── 4. Караул: состав в базе равен объявленному ──
--
-- Страж-тест сверяет то же самое, но живёт он в репозитории, а этот блок — в накате: оператор
-- выката увидит расхождение сразу, а не через прогон тестов. Проверяются все три обещания разом —
-- набор системный, право ровно одно и роли ровно две, — и отдельно то, что миграция никому ничего
-- не выдала: строка `user_grants`, дописанная сюда позже, и есть то расширение доступа, которого в
-- миграции быть не должно.
DO $$
DECLARE trouble text;
BEGIN
  SELECT string_agg(msg, '; ')
    INTO trouble
    FROM (
      SELECT format('набора нет или он не системный (найдено строк: %s)', count(*)) AS msg
        FROM grants
       WHERE code = 'waste_ticket_audit' AND is_system AND deleted_at IS NULL
      HAVING count(*) <> 1
      UNION ALL
      SELECT format('прав в наборе %s вместо одного', count(*))
        FROM grant_permissions gp
        JOIN grants g ON g.id = gp.grant_id
       WHERE g.code = 'waste_ticket_audit'
      HAVING count(*) <> 1
         OR count(*) FILTER (WHERE gp.permission = 'wasteRequests.ticketAudit') <> 1
      UNION ALL
      SELECT format('роли набора: %s', coalesce(string_agg(gr.role::text, ', ' ORDER BY gr.role::text), 'ни одной'))
        FROM grant_roles gr
        JOIN grants g ON g.id = gr.grant_id
       WHERE g.code = 'waste_ticket_audit'
      HAVING coalesce(array_agg(gr.role::text ORDER BY gr.role::text), ARRAY[]::text[])
               <> ARRAY['dispatcher', 'manager']
      UNION ALL
      SELECT format('набор кому-то выдан: держателей %s', count(*))
        FROM user_grants ug
        JOIN grants g ON g.id = ug.grant_id
       WHERE g.code = 'waste_ticket_audit'
      HAVING count(*) <> 0
    ) AS bad;
  IF trouble IS NOT NULL THEN
    RAISE EXCEPTION 'Набор «Вывоз мусора: аудит распознавания» собран не так, как объявлен — %', trouble;
  END IF;
END $$;
