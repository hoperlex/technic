-- Роль «Комендант»: заказчик на объекте, ведущий только вывоз мусора.
--
-- На площадке контейнерами и вывозом занимается комендант, а технику заказывают штаб и
-- руководитель строительства. До сих пор коменданту заводили учётку штаба, и вместе с мусором он
-- получал весь модуль «Заказ ТС» — чужие заявки на технику по всему своему объекту.
--
-- Роль устроена как штаб без модуля техники: та же область (объекты учётки, ADR 0025 и 0039), тот
-- же запрет вести ход заявок — «в работе» и «выполнена» решают те, кто исполняет. Что именно у
-- роли есть, живёт в матрице @technic/contracts (ADR 0021), а не в БД: сюда добавляется только
-- значение enum, как у 'observer' (0054) и ролей отдела (0065).
--
-- Второе значение — пожелание при саморегистрации (ADR 0034): комендант называет себя своей
-- должностью, и по пожеланию администратор видит, какую роль назначать. Отдельным вариантом, а не
-- внутри «сотрудника объекта»: это разные роли с разным доступом.
--
-- Только значения enum, отдельным файлом: добавленное значение нельзя использовать в той же
-- транзакции, которая его добавила, — а CHECK на обязательный объект в пожелании ссылается на
-- него литералом (миграция 0068). Тем же приёмом заводились 'rukstroy' (0049), 'observer' (0054)
-- и роли отдела (0065).
--
-- Порядок значений имеет смысл только для сортировки по колонке роли: комендант ставится рядом с
-- остальными ролями объекта — он такой же заказчик с площадки, только в одном модуле.
ALTER TYPE role ADD VALUE 'commandant' AFTER 'rukstroy';

ALTER TYPE registration_role_request ADD VALUE 'commandant' AFTER 'site_staff';
