-- Назначаемые полномочия (ADR 0106; план реструктуризации модели доступа, §13, шаг 1a).
--
-- Надстройка роли (ADR 0086, миграция 0106) доказала, что работа сверх должности существует:
-- к «Оператору (оргтехника)» добавилось «Согласование ИТ». Но каталог остался закрытым
-- перечислением — enum `role_addon` в базе и матрица состава в коде, — а значение enum нельзя ни
-- создать из интерфейса, ни удалить вовсе. Поэтому набор прав перестаёт быть значением типа и
-- становится записью: четыре таблицы вместо одной.
--
-- Миграция аддитивная и ничего не переключает. `user_role_addons` не трогается и остаётся
-- единственным источником чтения: это шаг expand — «таблицы рядом», — и он такой потому, что
-- деплой накатывает миграции ДО перезапуска приложения. Переименование сломало бы работающую
-- версию, которая читает старую таблицу, а обычный откат кода схему не вернул бы. Протокол выката
-- необратимых миграций (`docs/schema-cutover-protocol.md`) к этой миграции не применяется: смысл
-- существующих данных не меняется.

CREATE TABLE grants (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Стабильный код набора. На него ссылаются код приложения (`GRANT_MODULE_WIDE_SCOPE` — сквозная
  -- область системного набора объявляется в контрактах, а не в базе), миграции каталога и журнал
  -- действий. Название и состав меняются администратором, код — нет.
  code text NOT NULL,
  name text NOT NULL,
  description text NOT NULL DEFAULT '',
  -- Системный набор заводится миграцией, не редактируется и не удаляется из интерфейса; только он
  -- может нести объявленный в коде scope-эффект (ADR 0106, решение 2). Пользовательская копия
  -- системного набора этого эффекта не наследует — потому он и не колонка здесь.
  is_system boolean NOT NULL DEFAULT false,
  -- Версия состава. Подтверждение правки проверяется отпечатком последствий (решение 7), и версия
  -- входит в него слагаемым. Счёт с единицы: «набор без единой правки» — это уже состояние, на
  -- которое ссылается предпросмотр, а не отсутствие состояния.
  version integer NOT NULL DEFAULT 1,
  -- Автор набора. SET NULL, а не CASCADE: удаление учётки администратора не должно уносить набор,
  -- которым пользуются живые люди, — тот же приём, что у `granted_by` в `user_role_addons`.
  created_by uuid REFERENCES users (id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  -- Мягкое удаление: удалить пользовательский набор можно только после отзыва у всех держателей
  -- (решение 6), но строка остаётся — иначе реестр выдач и журнал не смогут объяснить прошлые
  -- назначения, а `user_grants.grant_id` стоит под RESTRICT именно ради этого.
  deleted_at timestamptz,
  CONSTRAINT grants_code_not_blank_check CHECK (btrim(code) <> ''),
  CONSTRAINT grants_name_not_blank_check CHECK (btrim(name) <> '')
);

-- Код уникален по всей таблице, а не среди живых наборов, — и это осознанное отличие от
-- справочников с мягким удалением (`office_equipment_serial_unique`, миграция 0104). Там номер
-- освобождается: списанная карточка не должна мешать перезавести ту же единицу. Здесь наоборот —
-- код читают код приложения, журнал и реестр выдач, и новый набор под кодом удалённого рассказывал
-- бы историю за него.
--
-- Частичный индекс `(code) WHERE deleted_at IS NULL` рядом с этим ограничением не заводится
-- намеренно. Уникальностью он ничего не добавляет — она уже следует из более сильной общей; как
-- путь доступа он повторяет тот же индекс по тому же столбцу, то есть вторую копию, которую база
-- обновляет на каждой записи и не выбирает никогда. Частичный уникальный индекс уместен ровно там,
-- где общий был бы неверен (`users_person_unique`), — здесь не тот случай.
CREATE UNIQUE INDEX grants_code_unique ON grants (code);

CREATE TABLE grant_permissions (
  grant_id uuid NOT NULL REFERENCES grants (id) ON DELETE CASCADE,
  -- Право — текст, и справочника прав в базе нет намеренно. Словарь `PERMISSIONS` закрыт и живёт в
  -- контрактах (ADR 0021): новое право требует кода, стража маршрута и тестов, и строка в базе его
  -- не создаёт. Таблица-справочник была бы второй копией словаря — она разъезжается с кодом ровно
  -- в тот выкат, где право переименовали, и тогда база начинает утверждать про доступ то, чего в
  -- коде нет. Enum не годится по той же причине, что и `role_addon`: значения меняются выкатом.
  --
  -- Отсюда и отсутствие CHECK по списку прав: после выката, снявшего право, здесь остаются
  -- строки-сироты. Правило ADR 0106 (решение 3) — при чтении такая строка игнорируется (доступа не
  -- даёт), а витрина показывает её как «право больше не существует». Ограничение превратило бы
  -- снятие права в отказ базы, то есть в падение каждой проверки доступа.
  permission text NOT NULL,
  PRIMARY KEY (grant_id, permission)
);

-- «В каких наборах есть это право» — обратный проход, и он не витринная роскошь: по нему считается
-- предпросмотр последствий и ищутся держатели права при пересмотре словаря. PK покрывает только
-- проход от набора к его правам.
CREATE INDEX grant_permissions_permission_idx ON grant_permissions (permission);

CREATE TABLE grant_roles (
  grant_id uuid NOT NULL REFERENCES grants (id) ON DELETE CASCADE,
  -- Роль — существующий enum: перечень ролей закрыт и меняется только выкатом, в отличие от набора
  -- прав. Здесь тип на месте.
  role role NOT NULL,
  PRIMARY KEY (grant_id, role)
);
-- Отдельной таблицей, а не массивом внутри `grants`: роль убирают из списка совместимых чаще, чем
-- правят сам набор, и жизненный цикл требует различать «нельзя назначать впредь» и «уже выданное
-- сохраняется» (план, §13.1). Кроме того, инвариант «ось роли × модуль» проверяется на декартовом
-- произведении `grant_roles × grant_permissions` — соединением, а не разбором массива.

CREATE TABLE user_grants (
  -- Собственная идентичность назначения, а не PK «учётка + набор». На неизменяемый `id` опирается
  -- откат будущего перевода ролей: он снимает только созданные им строки и не трогает то, что
  -- администратор выдал позже своей рукой (ADR 0106, решение 3). Отзыв удаляет строку, повторная
  -- выдача создаёт новую — переиспользовать прежнюю нельзя ни при каких обстоятельствах.
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- CASCADE: удалённая учётка не держатель ничего, и её назначения не переживают её саму.
  user_id uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  -- RESTRICT, а не CASCADE. Каскад означал бы, что удаление набора молча снимает доступ у живых
  -- учёток — и снимает его в базе, мимо пересчёта эффективных прав, `authVersion` и журнала.
  -- Портал обязан ответить на такую попытку 409 со списком держателей (решение 6), а системный
  -- набор не удаляется вовсе; RESTRICT — последняя опора этого правила на уровне базы.
  grant_id uuid NOT NULL REFERENCES grants (id) ON DELETE RESTRICT,
  -- Кто и когда выдал — как у надстройки роли: расширение доступа должно читаться в журнале так же
  -- ясно, как смена роли. Перенос старых надстроек сохранит эти значения, а не проставит момент
  -- переноса: миграция меняет способ хранения, а не бизнес-причину выдачи.
  granted_by uuid REFERENCES users (id) ON DELETE SET NULL,
  granted_at timestamptz NOT NULL DEFAULT now(),
  -- Почему выдано: `manual` — администратором, `migration` — переводом роли (этап 7 плана). Поле
  -- неизменяемо и нужно откату перевода: выданное вручную он не трогает никогда. Перечень закрыт
  -- поведением, а не реестром, — поэтому здесь CHECK уместен, в отличие от списка прав выше.
  origin text NOT NULL DEFAULT 'manual',
  -- Каким переводом ролей выдано — БЕЗ внешнего ключа, и это записано решением, а не упущение
  -- (ADR 0106, решение 3). Таблица `user_role_migration`, на которую ключ указывал бы, хранит
  -- снимок перевода ролей и появится миграцией prepare на этапе перевода; ссылка на
  -- несуществующую таблицу база и не примет. Завести её здесь пустой — значит везти в первую
  -- поставку механику, которой никто не пользуется: пустая таблица без единого писателя переживёт
  -- три релиза и к своему этапу потеряет смысл для того, кто читает схему.
  --
  -- Тем же этапом придёт и CHECK согласованности — `origin = 'migration'` тогда и только тогда,
  -- когда `migration_id IS NOT NULL`. До того момента он не подразумевается: писателя у
  -- `migration_id` пока нет вовсе.
  migration_id uuid,
  CONSTRAINT user_grants_origin_check CHECK (origin IN ('manual', 'migration')),
  -- Одно живое назначение на пару «учётка + набор». Без этого перенос назначений (шаг 1b) не имеет
  -- на что опереться своим `ON CONFLICT DO NOTHING`, а у учётки заводятся две строки одного набора.
  CONSTRAINT user_grants_user_grant_unique UNIQUE (user_id, grant_id)
);

-- Держатели набора: правка набора блокирует и пересчитывает их всех одной транзакцией (решение 7),
-- а удаление отвечает их списком. Этот же индекс обслуживает проверку RESTRICT при удалении
-- набора. Обратного прохода — «полномочия учётки» — индекс не требует: его закрывает префикс
-- `user_id` уникального ограничения выше.
CREATE INDEX user_grants_grant_idx ON user_grants (grant_id);

