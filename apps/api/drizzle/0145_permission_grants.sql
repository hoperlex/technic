  ('office_equipment_operator'   , 'serviceRequests.assign'),
  ('office_equipment_operator'   , 'serviceRequests.approveEstimate'),
  ('office_equipment_operator'   , 'serviceRequests.status'),
  -- Согласование ИТ: право ровно одно. Чтение модуля и справочника приходит от базовой роли —
