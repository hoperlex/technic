-- ── Назначения (`user_grants`) здесь НЕ переносятся ──
--
-- Это не забытый шаг, а условие корректности перехода (ADR 0106, решение 9; план, §13). Миграция
-- выполняется до перезапуска приложения: скопируй она назначения сейчас — между копированием и
-- стартом новой версии продолжает работать старый код, который выдаёт и отзывает надстройки
-- ТОЛЬКО в `user_role_addons`. Всё, что случится в эти минуты, в новые таблицы не попадёт и
-- потеряется навсегда: второй раз копировать никто не будет.
--
-- Порядок поэтому обратный: сперва релиз с двойной атомарной записью в обе схемы (шаг 1a), затем
-- отдельный идемпотентный перенос `INSERT ... SELECT` под краткой блокировкой `user_role_addons`
-- со сверкой в обе стороны (шаг 1b). Перенос нельзя делать и чтением в приложение: между чтением
-- и вставкой параллельный отзыв успел бы удалить назначение из обеих таблиц, и оно воскресло бы в
-- новой схеме, где его никто не ищет.
--
-- Переносу останется поставить перенесённым строкам `origin = 'manual'` и сохранить исходные
-- `granted_by` и `granted_at`: их действительно выдавал администратор, а `migration`
-- зарезервирован за переводом ролей.
