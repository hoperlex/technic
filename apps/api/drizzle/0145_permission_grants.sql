SELECT g.id, s.permission
FROM grants g
JOIN (VALUES
  -- Оператор: справочник ведёт он сам (ADR 0085), плюс решения по заявке. Права сметы в наборе
  -- нет намеренно — смету пишет исполнитель, а оператор её согласует; вместе они превратили бы
  -- согласование в подпись под собственной работой.
