-- Талон запоминает НАПИСАНИЕ даты, а не только разобранную дату (план
-- `docs/waste-ticket-date-escalation-plan.md`, Р12; ADR 0166, п. 7).
--
-- ОТКУДА НОМЕР. `ls apps/api/drizzle` перед созданием файла (07.09.2026): последней в дереве
-- стояла `0279_service_request_bulk_operations.sql`. Номер живёт часы — параллельные потоки
-- занимают их без предупреждения, поэтому он взят по файлам дерева, а не по журналу базы и не по
-- `max(seq)` из technic_dev, где часть закоммиченных миграций просто не накатана.
--
-- ЗАЧЕМ. Модель теперь возвращает два ответа про дату: `issuedOn` в формате `YYYY-MM-DD` и
-- `issuedOnRaw` — символы, которые она прочитала в графе «Дата» дословно («17.08.25», «17 авг 26»,
-- «17.08»). Век двузначного года выбирает портал по дате заявки, а не модель по своему
-- представлению о «сегодня» — и человеку, сверяющему талон с бумагой, нужно видеть обе величины:
-- что написано и что из этого получилось. Без колонки написание жило бы только в сыром ответе
-- попытки, который убирается по сроку (`TICKET_OCR_ATTEMPT_TTL_DAYS`), тогда как талон живёт
-- вместе с заявкой.
--
-- ПОЧЕМУ `NOT NULL DEFAULT ''` И БЕЗ БЭКФИЛА. Пустая строка означает «написания у этой строки
-- нет»: у ручного талона его не бывает вовсе (человек вписал дату сам), у машинных талонов
-- прошлых разборов модель о нём не спрашивали. Заполнить задним числом нечем — сырьё старых
-- попыток отвечает на другой вопрос, а `NULL` рядом с `''` завёл бы третье состояние, которое
-- интерфейсу нечем отличить от второго.
--
-- Миграция приезжает ДО воркера, который начнёт писать колонку: старый воркер её не знает и
-- пишет талоны без неё, старые API и клиент — игнорируют. Откат совместим: колонка со значением
-- по умолчанию не мешает ни одной прежней вставке.
ALTER TABLE waste_tickets
  ADD COLUMN IF NOT EXISTS issued_on_raw text NOT NULL DEFAULT '';
