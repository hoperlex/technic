-- «Оргтехника: ведение» становится выдаваемой офисной паре ролей: `grant_roles` набора
-- `office_equipment_operator` дополняется ролями `manager` и `dispatcher`
-- (план `docs/office-equipment-access-profiles-plan.md`, Р5, §9.1 строка B, этап Э7).
--
-- ОТКУДА НОМЕР. Проверено `ls apps/api/drizzle/*.sql` непосредственно перед созданием файла
-- (04.09.2026): последняя миграция в дереве — `0264_office_equipment_candidates.sql` соседнего
-- потока, свободен 0265. Утренний снимок этого же дня показывал 0263: соседи заняли номер
-- незакоммиченным файлом за время работы над этапом, ровно как предупреждает §14 плана. Номер
-- берётся в момент создания файла и не резервируется заранее.
--
-- ЗАЧЕМ. Ведение оргтехники бывает не только площадочным. Заказчик просит централизованного
-- оператора — человека в офисе, к которому и так идут со сломанным принтером, — а выдать ему
-- «Ведение» было нельзя: строк `grant_roles` под офисными ролями не существовало, и барьер выдачи
-- отвечал `roleNotAllowed` (409) в прямой выдаче и `incompatible` (400, поле `grants`) в форме
-- учётки. Эта миграция снимает именно этот запрет и больше ничего.
--
-- ПРАВИЛО, ПО КОТОРОМУ РОЛЬ СЮДА ПОПАДАЕТ, ЗАПИСАНО ОДИН РАЗ (Р5) и проверяется тестом
-- (`grants-catalog.db.test.ts`, Т10), а не подразумевается:
--
--   1. ось роли обязана иметь клетку НЕ `forbidden` по каждому модулю, права которого есть в
--      составе набора. У «Ведения» модулей два — `service` и `officeEquipment`, — ось обеих
--      офисных ролей `none`, и обе клетки в `GRANT_SCOPE_MATRIX` стоят `global`: роль без своей
--      оси не ограничена ничем по построению, сужать ей нечего;
--   2. итог обязан удовлетворять `PERMISSION_REQUIRES`. Выполняется СОСТАВОМ, а не ролью: набор
--      самодостаточен с миграции 0261 (Р4) — `serviceRequests.read` и `officeEquipment.read` лежат
--      в нём самом, и требования пятнадцати прав закрыты им же;
--   3. набор обязан ЧТО-ТО давать каждой перечисленной роли. Даёт: у `manager`/`dispatcher` из
--      прав модуля заявок нет ни одного (`ROLE_PERMISSIONS`), справочник они читают и правят, а
--      заявку завести не могут вовсе;
--   4. роль `operator` не перечисляется ни в одном наборе оргтехники НИКОГДА (Р11): её права
--      приходят типом контрагента, а набор раздал бы их по базовой области, которой у подрядчика
--      нет. Эта миграция такой строки не создаёт, и отдельный случай стража за этим следит.
--
-- ЧТО ЭТО ОТКРЫВАЕТ ДИСПЕТЧЕРУ СВЕРХ ЦИКЛА ЗАЯВКИ — НАЗВАНО ЗАРАНЕЕ И ПРИНЯТО ЗАКАЗЧИКОМ (Р5).
-- Откат статуса спрашивается ПАРОЙ прав: `requests.rollbackStatus` **и** `serviceRequests.status`.
-- Первое у диспетчера уже есть по роли (ADR 0101 — «чинит тот, кому звонят»), второго не было.
-- Выдав ему «Ведение», мы вместе с ходом заявки открываем и ОТКАТ статуса — в этом модуле, не во
-- всех сразу. Это не побочный эффект набора, а сегодняшнее правило пары, и решение здесь было
-- одно из двух: либо заказчик соглашается («откатывает тот, кому звонят» — та же причина, по
-- которой право у диспетчера есть в заказе ТС), либо профиль диспетчеру не выдаётся. Умолчание
-- плана — первое, и §12 у этого этапа стоит «расширяет доступ: да» именно из-за этой строки.
-- Записано здесь, а не обнаружено потом.
--
-- ПОЧЕМУ ЭТА МИГРАЦИЯ ЕДЕТ ЭТАПОМ Э7, А НЕ Э5, КАК ПИСАЛ §12. Уточнение 04.09.2026: строка §9.1
-- привязывает её к серверному стражу Р6 (`actsAsRequestCustomer`), и второе строже. Пока стража
-- нет, роль без оси, получившая набор модуля, не ограничена ничем, кроме своей должности:
-- предикат видимости ей ничего не сужает — так устроена роль без оси. Открывать это раньше
-- предиката значило бы расширять доступ вслепую. Страж выкачен той же волной, что и эта миграция.
-- Самого «Ведения» правило автора при этом НЕ КАСАЕТСЯ (Р6): оператор ведёт и чужие заявки — ради
-- этого профиль и существует, а смешать два слоя значило бы отменить централизованное ведение в
-- тот же день, когда его разрешили.
--
-- ЧЕГО МИГРАЦИЯ НЕ ДЕЛАЕТ. Не трогает состав набора (пятнадцать прав после 0261 и 0259 остаются
-- как есть), не трогает другие наборы, не создаёт ни одной строки `user_grants`: сама по себе она
-- не выдаёт ничего никому — она РАЗРЕШАЕТ администратору выдать. Последнее проверяется караулом
-- ниже, а не обещанием.
--
-- ГДЕ ЖИВЁТ ОБЪЯВЛЕННЫЙ СПИСОК РОЛЕЙ. В `ROLE_ADDON_BASE_ROLES`
-- (`packages/contracts/src/role-addons.ts`): пока надстройка ADR 0086 остаётся живым источником
-- доступа (до шага 1e реформы ADR 0106), страж каталога строит ожидание строк `grant_roles`
-- оттуда. Правка контрактов едет ТОЙ ЖЕ волной, что эта миграция (§9.3 п. 1) — разъехавшись, они
-- дали бы одному человеку разные права в зависимости от того, каким источником пришёл доступ.
--
-- ОБРАТИМОСТЬ. Схема не меняется, трогается одна таблица каталога. Откат — `DELETE` тех же двух
-- строк; выданные к тому моменту назначения при этом не удаляются, а перестают действовать
-- (`grantPermissionsExpr` соединяется с `grant_roles`), то есть откат закрывает доступ сразу, но
-- оставляет строки в реестре выдач — их снимает администратор.

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 1. Снимок держателей «Ведения» ДО правки.
--
-- Нужен ради одного утверждения шапки — «миграция не создаёт ни одной строки `user_grants`», — и
-- снимается он до, потому что проверяемо только сравнение с «до». Утверждать это тем, что в файле
-- нет `INSERT INTO user_grants`, значило бы проверять текст файла глазами; снимок проверяет базу.
-- `ON COMMIT DROP`: таблица живёт до конца транзакции миграции и в базе не остаётся.

CREATE TEMP TABLE operator_holders_0265 ON COMMIT DROP AS
SELECT ug.user_id
FROM user_grants ug
JOIN grants g ON g.id = ug.grant_id
WHERE g.code = 'office_equipment_operator';

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 2. Две строки совместимости. Набор ищется по коду: коды стабильны навсегда, по ним его находят
--    миграции каталога, журнал действий, реестр выдач и таблица сквозной области.
--
-- `ON CONFLICT (grant_id, role) DO NOTHING` — не «на всякий случай»: повторный накат на базу,
-- восстановленную из копии, обычное дело, и миграция обязана довести каталог до объявленного
-- состояния, а не упасть на первой строке. Существующих строк (`shtab`, `site`, `department`) она
-- при этом не переписывает вовсе — они не в списке.

INSERT INTO grant_roles (grant_id, role)
SELECT g.id, s.role::role
FROM grants g
JOIN (VALUES
  ('office_equipment_operator', 'manager'),
  ('office_equipment_operator', 'dispatcher')
) AS s (code, role) ON s.code = g.code
WHERE g.deleted_at IS NULL
ON CONFLICT (grant_id, role) DO NOTHING;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 3. Караул состава — как у 0261 и 0262: страж-тест сверяет каталог с контрактами, но живёт он в
--    репозитории, а этот блок в накате, и оператор выката увидит расхождение сразу.
--
-- Проверяется три вещи, и каждая — своё утверждение миграции:
--
--   · роли набора стали ровно пятью названными. Счёт «их пять» сошёлся бы и у набора, которому
--     дописали чужую роль вместо своей, поэтому список сравнивается поимённо;
--   · роли `operator` среди них нет (Р11) — отдельной строкой, потому что это запрет НАВСЕГДА, а
--     не следствие сегодняшнего списка;
--   · состав набора не изменился ни на одно право: пятнадцать после 0259 и 0261, и держатели те
--     же, что были в снимке шага 1. Караул стоит здесь именно потому, что миграция состава и
--     выдач не трогает, — утверждение «не трогает» проверяемо ровно так же, как «трогает».
--
-- Числа взяты по факту базы после 0261 (`ROLE_ADDON_PERMISSIONS.office_equipment_operator`):
-- `officeEquipment.read`, `.write`, `serviceRequests.read`, `.create`, `.createWithoutEquipment`,
-- `.update`, `.delete`, `.assign`, `.approveEstimate`, `.status`, `.hold`, `.urgency`, `.files`,
-- `.finance`, `officeEquipmentPurchases.manage`. Следующая миграция каталога, трогающая этот
-- набор, обязана вести счёт от ПЯТНАДЦАТИ.

DO $$
DECLARE trouble text;
BEGIN
  SELECT string_agg(msg, '; ')
    INTO trouble
    FROM (
      SELECT format('набора нет или он не системный (найдено строк: %s вместо одной)', count(*))
             AS msg
        FROM grants
       WHERE code = 'office_equipment_operator' AND is_system AND deleted_at IS NULL
      HAVING count(*) <> 1
      UNION ALL
      SELECT format('роли набора «Ведение»: %s',
                    coalesce(string_agg(gr.role::text, ', ' ORDER BY gr.role::text), 'ни одной'))
        FROM grants g
        LEFT JOIN grant_roles gr ON gr.grant_id = g.id
       WHERE g.code = 'office_equipment_operator'
      HAVING coalesce(array_agg(gr.role::text ORDER BY gr.role::text), ARRAY[]::text[])
               <> ARRAY['department', 'dispatcher', 'manager', 'shtab', 'site']
      UNION ALL
      SELECT 'набору «Ведение» разрешена роль внешнего исполнителя (operator)' AS msg
        FROM grant_roles gr
        JOIN grants g ON g.id = gr.grant_id
       WHERE g.code = 'office_equipment_operator' AND gr.role = 'operator'
      UNION ALL
      SELECT format('состав набора «Ведение» изменился: прав %s вместо пятнадцати',
                    count(gp.permission))
        FROM grants g
        LEFT JOIN grant_permissions gp ON gp.grant_id = g.id
       WHERE g.code = 'office_equipment_operator'
      HAVING count(gp.permission) <> 15
      UNION ALL
      SELECT format('держателей «Ведения» стало %s вместо %s: миграция выдала набор кому-то',
                    (SELECT count(*) FROM user_grants ug
                       JOIN grants g ON g.id = ug.grant_id
                      WHERE g.code = 'office_equipment_operator'),
                    (SELECT count(*) FROM operator_holders_0265))
       WHERE (SELECT count(*) FROM user_grants ug
                JOIN grants g ON g.id = ug.grant_id
               WHERE g.code = 'office_equipment_operator')
             <> (SELECT count(*) FROM operator_holders_0265)
    ) AS bad;
  IF trouble IS NOT NULL THEN
    RAISE EXCEPTION 'Расширение совместимых ролей «Ведения» прошло не так, как объявлено — %',
                    trouble;
  END IF;
END $$;
