-- Набор «Оргтехника: заявитель» перестаёт выдаваться менеджеру: круг заказчика приезжает этой роли
-- матрицей (ADR 0181, решение заказчика 10.09.2026). Из `grant_roles` уходит строка `manager`, а
-- висящие выдачи менеджерам снимаются — обещать выдачу, не меняющую ни одного права, каталог не
-- вправе.
--
-- ОТКУДА НОМЕР. `ls apps/api/drizzle` непосредственно перед созданием файла (10.09.2026): последней
-- в дереве стоит `0303_releases_free_estimate_and_executor_scope.sql`, свободен `0304`. Номера
-- берутся в момент создания файла и не резервируются заранее: за один день соседние потоки уводят
-- дерево на три-четыре номера вперёд.
--
-- ЗАЧЕМ. До этого выпуска у `manager` не было ни одного права модуля заявок, и набор существовал
-- ровно ради него и диспетчера (план профилей, Р5, Р6). Теперь круг заказчика — шесть прав плюс
-- сообщение о ненайденном аппарате — стоит у менеджера прямо в `ROLE_PERMISSIONS`, и набор ему не
-- добавляет НИЧЕГО. Такая строка в каталоге хуже, чем бесполезна: администратор ставит галочку,
-- реестр пишет автора и время, доступ не меняется ни на одно право — а инвариант каталога «набор
-- обязан что-то давать каждой перечисленной роли» (`grants-catalog.db.test.ts`, Т10) с этого дня
-- нарушен прямо в поставке.
--
-- ПОЧЕМУ РОЛЬ, А НЕ НАБОР, ДЕРЖИТ ТЕПЕРЬ ЭТОТ ДОСТУП. `manager` — временная роль-заплатка, которую
-- заказчик убирает целиком; всё, что она раздаёт, обязано уходить вместе с её строкой в матрице.
-- Набор пережил бы удаление роли двумя следами — строкой `grant_roles` и выдачами `user_grants`, —
-- и вычищать их пришлось бы отдельной миграцией в тот день, когда о них никто уже не помнит.
-- Диспетчер на наборе остаётся: его роль постоянная, и поимённая выдача с автором и временем — то,
-- чем этот доступ и должен оставаться.
--
-- ЧТО ЭТО НЕ ЗАБИРАЕТ. Ни одного действия у менеджера. Права модуля приходят ему кодом того же
-- выпуска, и порядок здесь жёсткий: сперва выкат кода (матрица + страж), потом эта миграция. В
-- обратном порядке между накатом и выкатом менеджеры остались бы без модуля заявок целиком.
--
-- СУЖЕНИЕ ДО СВОИХ СТРОК ПРИ ЭТОМ СОХРАНЕНО, и держит его тот же страж `actsAsRequestCustomer`.
-- Он опознавал заявителя КОДОМ набора, поэтому вместе с матрицей правится и он: роль названа в
-- `OFFICE_EQUIPMENT_ROLE_REQUESTERS` (`packages/contracts/src/service-requests.ts`). Не будь этой
-- половины выпуска, менеджер получил бы вместе с кругом заказчика право править, удалять и
-- подшивать бумаги к ЛЮБОЙ чужой заявке компании — область роли без оси не сужает ничего.
--
-- ГАШЕНИЕ СЕССИЙ. Держателям снятого набора поднимается `auth_version`: набор перестаёт числиться
-- за учёткой, и ответы `/auth/me`, login и refresh обязаны рассказывать про доступ одинаково. Прав
-- у человека при этом не убавляется — их отдаёт роль, — так что цена гашения ровно одна: следующий
-- запрос приходит за новым токеном.
--
-- ОБРАТИМОСТЬ. Схема не меняется. Откат — обратный `INSERT` строки `grant_roles`; снятые выдачи
-- восстанавливать не нужно и нечем (автор и время у них были свои), а доступ они не держали.
-- Аварийный порядок отката выпуска обратный накату: сперва вернуть строку, потом откатывать код.

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 1. Снимок держателей-менеджеров ДО правки: им поднимается версия, и по ним же караул шага 4
--    проверяет, что снято ровно столько, сколько было.

CREATE TEMP TABLE requester_managers_0304 ON COMMIT DROP AS
SELECT ug.user_id
FROM user_grants ug
JOIN grants g ON g.id = ug.grant_id
JOIN users u ON u.id = ug.user_id
WHERE g.code = 'office_equipment_requester' AND u.role = 'manager';

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 2. Снятие выдач. Условие по РОЛИ учётки, а не по всем держателям: у диспетчера набор остаётся
--    единственным источником круга заявителя, и снять его значило бы отобрать модуль целиком.

DELETE FROM user_grants ug
USING grants g, users u
WHERE ug.grant_id = g.id
  AND ug.user_id = u.id
  AND g.code = 'office_equipment_requester'
  AND u.role = 'manager';

UPDATE users SET auth_version = auth_version + 1
WHERE id IN (SELECT user_id FROM requester_managers_0304);

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 3. Совместимость: строка `manager` уходит из каталога. Набор ищется по коду — коды стабильны
--    навсегда, и по ним его находят и остальные миграции каталога.

DELETE FROM grant_roles gr
USING grants g
WHERE gr.grant_id = g.id
  AND g.code = 'office_equipment_requester'
  AND gr.role = 'manager';

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 4. Караул: то же, что сверяет страж каталога в репозитории, но в момент наката — оператор выката
--    увидит расхождение сразу, а не по красному тесту следующего дня.
--
--   · роль у набора осталась ровно одна, и названа она поимённо: счёт «их одна» сошёлся бы и у
--     набора, которому вместо диспетчера оставили чужую роль;
--   · состав не изменился ни на одно право — семь после 0266 (`officeEquipment.read`, `.propose`,
--     `serviceRequests.read`, `.create`, `.update`, `.delete`, `.files`). Миграция состава не
--     трогает, и «не трогает» проверяется так же, как «трогает»;
--   · ни один менеджер не остался держателем — иначе в реестре висела бы выдача, не дающая ничего.

DO $$
DECLARE trouble text;
BEGIN
  SELECT string_agg(msg, '; ')
    INTO trouble
    FROM (
      SELECT format('набора нет или он не системный (найдено строк: %s вместо одной)', count(*))
             AS msg
        FROM grants
       WHERE code = 'office_equipment_requester' AND deleted_at IS NULL
      HAVING count(*) <> 1
      UNION ALL
      SELECT format('роли набора «Заявитель»: %s',
                    coalesce(string_agg(gr.role::text, ', ' ORDER BY gr.role::text), 'ни одной'))
        FROM grants g
        LEFT JOIN grant_roles gr ON gr.grant_id = g.id
       WHERE g.code = 'office_equipment_requester'
      HAVING coalesce(array_agg(gr.role::text ORDER BY gr.role::text), ARRAY[]::text[])
               <> ARRAY['dispatcher']
      UNION ALL
      SELECT format('состав набора «Заявитель»: %s прав вместо семи', count(*))
        FROM grants g
        JOIN grant_permissions gp ON gp.grant_id = g.id
       WHERE g.code = 'office_equipment_requester'
      HAVING count(*) <> 7
      UNION ALL
      SELECT format('менеджеров с набором «Заявитель» осталось: %s', count(*))
        FROM user_grants ug
        JOIN grants g ON g.id = ug.grant_id
        JOIN users u ON u.id = ug.user_id
       WHERE g.code = 'office_equipment_requester' AND u.role = 'manager'
      HAVING count(*) > 0
    ) AS checks;
  IF trouble IS NOT NULL THEN
    RAISE EXCEPTION 'Миграция 0304: %', trouble;
  END IF;
END $$;
