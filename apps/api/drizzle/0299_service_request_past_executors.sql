-- След снятого исполнителя и индекс по автору заявки — две половины одной новой оси видимости
-- (план `docs/office-equipment-free-estimate-and-executor-scope-plan.md`, Р3 и Р5, этапы Э4 и Э6;
-- выпуск A по §8).
--
-- ОТКУДА НОМЕР. `ls apps/api/drizzle` непосредственно перед созданием файла (10.09.2026): последним
-- в дереве стоит `0298_service_request_estimate_rewrite_grant.sql` — право раскладки объёма работ,
-- соседний файл этой же волны. Свободен 0299, он и взят. Номер берётся в момент создания КАЖДОГО
-- файла и не резервируется на волну вперёд: параллельные потоки занимают номера незакоммиченными
-- файлами, и снимок свободного номера живёт часы (миграции 0261 и 0262 рассказывают, как это
-- выглядит на практике).
--
-- ЗАЧЕМ. Заказчик просит сузить сисадмина до его собственных заявок (просьба 2 разбора 09.09.2026),
-- и на вопрос «а что тогда с заявками, которые у меня забрали?» ответил прямо (развилка В6):
-- бывший исполнитель обязан их ВИДЕТЬ. Сегодня ответить нечем — снятие исполнителя физически
-- удаляет строку `service_request_executors`: три логических пути (сброс состава, переназначение,
-- отказ исполнителя) и ЧЕТЫРЕ ветки `DELETE`, потому что отказ снимает либо свою строку, либо весь
-- состав. Эта таблица — след, который пишется непосредственно ПЕРЕД каждым из четырёх удалений.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ КОЛОНКА `removed_at` В САМОЙ `service_request_executors`. Это
-- главное решение файла, и отвергнутый вариант выглядит дешевле ровно до первого чтения.
-- Назначения читают 65 раз в восьми файлах: письма (`service-request-mail.ts`,
-- `service-request-mail-audience.ts`), обсуждение и его адресация (`service-request-chat.ts`,
-- `service-request-audience.ts`), доступ к файлам (`routes/files.ts`), область (`lib/access.ts`),
-- DTO и предикаты карточки (`routes/service-requests.ts`), блоки карточки единицы
-- (`office-equipment-blocks.ts`). Каждое из этих чтений спрашивает одно и то же — «кто ведёт
-- заявку», — и мягкое снятие означало бы, что в каждом из 65 мест обязан появиться фильтр
-- `removed_at IS NULL`. Забытый хотя бы в одном, он оставил бы снятому письма-задания, кнопки
-- исполнителя и адресацию в обсуждении: ошибка молчаливая и в сторону ЛИШНЕГО доступа.
--
-- Отдельная таблица по построению не открывает ничего: её единственный читатель — область ЧТЕНИЯ
-- (`serviceRequestVisibilityWhere`), а область ДЕЙСТВИЙ (`assertServiceRequestActionable`) в неё не
-- смотрит вовсе (Р7). Цена решения названа вслух: запись живёт в четырёх ветках снятия, и забытая
-- ветка — это потерянный след, то есть недостача видимости, а не открытая дверь. Из двух видов
-- ошибки выбран тот, который замечает пользователь, а не тот, который не замечает никто.
--
-- BACKFILL НЕВОЗМОЖЕН, И ЭТО СВОЙСТВО, А НЕ УМОЛЧАНИЕ (находка Н13 плана). Восстанавливать след
-- неоткуда: старые строки назначений удалены физически, а аудит `serviceRequest.reassign` хранит
-- ИМЕНА участников, а не идентификаторы учёток, — сопоставить их обратно можно только догадкой, и
-- догадка эта открывала бы людям чужие заявки. Семантика поэтому «только вперёд, с даты выката»:
-- заявки, переданные другому исполнителю раньше, бывшему исполнителю не видны. Портал обязан
-- сказать это словами в пустом списке, а не молчать, — иначе первый же вопрос «где мои прошлые
-- ремонты» будет задан как о дефекте.
--
-- ИСТОРИИ СНЯТИЙ ТАБЛИЦА НЕ ВЕДЁТ, и первичный ключ по паре — это решение, а не экономия. Цикл
-- «сняли → назначили снова → сняли» обновляет `removed_at` вместо второй строки: на вопрос «кто и
-- когда передал заявку» отвечает аудит и история статусов, а здесь нужен ровно один факт — «этот
-- человек её вёл». Суррогатный `id` дал бы таблице вторую жизнь в виде неполной, зато похожей на
-- правду хронологии.
--
-- ЧЕГО В ФАЙЛЕ НЕТ. Ни строки данных (backfill невозможен, см. выше), ни триггеров: инвариант «в
-- рабочем статусе у заявки есть исполнитель» держат отложенные constraint-триггеры соседней
-- таблицы (`service_request_executors_present`, `service_requests_executor_present`, миграция
-- 0178), и след к нему отношения не имеет — он говорит о прошлом. Ни прав: дверей эта таблица не
-- открывает вовсе, её читает область. Ни рубильника: рубильник — соседний файл волны, и до его
-- включения таблица просто наполняется, ни на что не влияя. Это, кстати, и есть правильный порядок
-- (§8 плана): след обязан копиться РАНЬШЕ, чем сужение начнёт действовать, иначе первые снятые
-- окажутся без исключения из правила.
--
-- Аддитивная миграция: существующих данных не касается, ни одной колонки не переписывает. Протокол
-- выката необратимых миграций (`docs/schema-cutover-protocol.md`) к ней не применяется. Откат —
-- `DROP TABLE service_request_past_executors` и `DROP INDEX service_requests_created_by_idx`; код
-- прошлого выпуска о таблице не знает, а новый при выключенном рубильнике её не читает.

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 1. Таблица следа.

CREATE TABLE service_request_past_executors (
  -- `CASCADE`, как у живого назначения (0178): след — часть заявки, а не самостоятельная история.
  -- Заявки удаляются мягко (`deleted_at`), так что путь этот и без того редкий — жёсткое удаление
  -- остаётся уборкой опечатки первого дня; переживать заявку следу незачем.
  request_id uuid NOT NULL REFERENCES service_requests (id) ON DELETE CASCADE,
  -- `RESTRICT`, ровно как у `service_request_executors.user_id`: «кто вёл этот ремонт» — часть
  -- истории заявки, и удаление учётки, за которой такой след есть, портал обязан отклонить
  -- словами, а не унести его молча. `SET NULL` тут невозможен и физически — колонка входит в
  -- первичный ключ. Учётки в портале и так не удаляют, а гасят флагом.
  user_id uuid NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  -- Когда сняли. `DEFAULT now()` — не удобство, а правило: запись делает та же транзакция, что и
  -- `DELETE`, и второго источника времени у события нет.
  removed_at timestamptz NOT NULL DEFAULT now(),
  -- Кто снял. `SET NULL`, в отличие от самого исполнителя: это подробность события, а не его суть.
  -- След обязан пережить увольнение того, кто переназначил заявку; событие с автором остаётся в
  -- аудите. Колонка не `NOT NULL` ещё и потому, что снятие бывает системным — сброс состава при
  -- откате статуса делает не человек.
  removed_by uuid REFERENCES users (id) ON DELETE SET NULL,
  -- Ключ — пара «заявка + учётка»: повторное снятие того же человека с той же заявки обновляет
  -- `removed_at` (`ON CONFLICT … DO UPDATE`), а не заводит вторую строку. См. абзац «истории
  -- снятий таблица не ведёт» выше.
  PRIMARY KEY (request_id, user_id)
);

-- Со стороны УЧЁТКИ: «с каких заявок меня снимали» — ровно третье слагаемое области чтения
-- бывшего исполнителя (назначен ∨ автор ∨ снят). Первичный ключ читается только слева направо, от
-- заявки, и на этот вопрос не отвечает вовсе. Вторая колонка в индексе не ради сортировки, а ради
-- index-only scan: `EXISTS` по паре закрывается индексом, не заглядывая в таблицу, — а вопрос этот
-- задаётся на каждую страницу списка заявок и на каждый счётчик.
--
-- Форма списана с соседа `service_request_executors_user_idx` (0178), у которого та же роль в той
-- же дизъюнкции.
CREATE INDEX service_request_past_executors_user_idx
  ON service_request_past_executors (user_id, request_id);

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 2. Индекс по автору заявки.
--
-- ЕГО СЕГОДНЯ НЕТ, и до этой волны он и не был нужен: авторство читали уже загруженной строкой —
-- «моя ли это заявка» в страже заказчика, — то есть запроса по колонке не было ни одного. Новая
-- ось спрашивает иначе: область бывшего исполнителя — дизъюнкция «назначен ∨ АВТОР ∨ снят», и
-- считается она по всей таблице заявок.
--
-- Две крайние ветви закрыты своими индексами (`service_request_executors_user_idx` и заведённый
-- выше `service_request_past_executors_user_idx`), а средняя без индекса означала бы
-- последовательное чтение `service_requests` целиком: планировщик собирает такую дизъюнкцию из
-- `BitmapOr`, и одна неиндексированная ветвь обесценивает обе соседние. Цена растёт вместе с
-- историей модуля, а платит её самый частый запрос портала — список заявок, его счётчик и бейдж
-- непрочитанного.
--
-- ПОЛНЫЙ, А НЕ ЧАСТИЧНЫЙ. `created_by` заполнен у каждой строки (`NOT NULL`), а живость заявки
-- (`deleted_at IS NULL`) отсекает соседнее условие предиката. Сузить индекс этим условием значило
-- бы закрыть его для соседей — «что завёл этот человек» спрашивают и отчёты, и карточка учётки, —
-- а частичный индекс обязан быть ШИРЕ любого своего читателя, иначе первый же соседний запрос
-- уедет на seq scan (тот же довод, что у `service_requests_urgent_idx`, миграция 0286).
--
-- БЕЗ `CONCURRENTLY`: раннер катит файл одной транзакцией (`apps/api/src/db/migration-journal.ts`),
-- а `CREATE INDEX CONCURRENTLY` внутри транзакции запрещён. Блокировка записи на время построения —
-- доли секунды: заявок на обслуживание в таблице тысячи, а не миллионы. Функций в индексе нет
-- вовсе, поэтому известная разница прода (PostgreSQL 17) и дева (16) по функциональным индексам
-- здесь ни при чём.

CREATE INDEX service_requests_created_by_idx ON service_requests (created_by);

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 3. Караул: обе половины на месте и связаны с тем, с чем объявлены.
--
-- Проверка выглядит избыточной для аддитивного файла ровно до дня, когда его накатят на базу,
-- восстановленную из копии, или переиграют руками. Проверяется то, на чём стоит область: таблица
-- есть, ключ у неё по паре, обе внешние ссылки ведут куда объявлено и с объявленным правилом
-- удаления (`CASCADE` на заявку, `RESTRICT` на учётку — перепутанные местами, они означали бы либо
-- потерю следа вместе с уволенной учёткой, либо запрет на удаление заявки), и оба индекса созданы.
--
-- Правило удаления сверяется по `pg_constraint.confdeltype`: `c` — cascade, `r` — restrict,
-- `n` — set null. Это единственное место, где ошибка в `ON DELETE` заметна на накате, а не через
-- полгода на первой попытке удалить учётку.

DO $$
DECLARE trouble text;
BEGIN
  SELECT string_agg(msg, '; ')
    INTO trouble
    FROM (
      SELECT 'таблицы service_request_past_executors нет' AS msg
       WHERE to_regclass('public.service_request_past_executors') IS NULL
      UNION ALL
      SELECT format('первичный ключ следа собран из %s колонок вместо пары «заявка + учётка»',
                    array_length(c.conkey, 1))
        FROM pg_constraint c
       WHERE c.conrelid = 'public.service_request_past_executors'::regclass
         AND c.contype = 'p'
         AND c.conkey <> ARRAY[
               (SELECT a.attnum FROM pg_attribute a
                 WHERE a.attrelid = 'public.service_request_past_executors'::regclass
                   AND a.attname = 'request_id'),
               (SELECT a.attnum FROM pg_attribute a
                 WHERE a.attrelid = 'public.service_request_past_executors'::regclass
                   AND a.attname = 'user_id')]::int2[]
      UNION ALL
      SELECT format('ссылка следа по колонке «%s» ведёт на «%s» с правилом «%s» вместо «%s»',
                    a.attname, c.confrelid::regclass, c.confdeltype, e.deltype)
        FROM (VALUES
          ('request_id', 'service_requests', 'c'),
          ('user_id',    'users',            'r'),
          ('removed_by', 'users',            'n')
        ) AS e (colname, reftable, deltype)
        LEFT JOIN pg_constraint c
               ON c.conrelid = 'public.service_request_past_executors'::regclass
              AND c.contype = 'f'
              AND c.conkey = ARRAY[
                    (SELECT a2.attnum FROM pg_attribute a2
                      WHERE a2.attrelid = 'public.service_request_past_executors'::regclass
                        AND a2.attname = e.colname)]::int2[]
        LEFT JOIN pg_attribute a
               ON a.attrelid = 'public.service_request_past_executors'::regclass
              AND a.attname = e.colname
       WHERE c.oid IS NULL
          OR c.confrelid <> ('public.' || e.reftable)::regclass
          OR c.confdeltype <> e.deltype
      UNION ALL
      SELECT format('индекса «%s» нет — новая ось видимости поехала бы по таблице', i.name)
        FROM (VALUES
          ('service_request_past_executors_user_idx'),
          ('service_requests_created_by_idx')
        ) AS i (name)
       WHERE to_regclass('public.' || i.name) IS NULL
    ) AS bad;
  IF trouble IS NOT NULL THEN
    RAISE EXCEPTION 'След снятого исполнителя заведён не так, как объявлен — %', trouble;
  END IF;
END $$;
