-- Шаг cleanup этапа 9: `department_head` уходит из модели (план реструктуризации модели доступа
-- §13.2, §15 этап 9; ADR 0113).
--
-- ПОДГОТОВЛЕН, НО НЕ ВЫКАЧЕН — см. `pending/README.md`. Обоснования — в
-- `stage8-cleanup-site-role.sql`, здесь только различия.
--
-- УСЛОВИЕ ГОТОВНОСТИ: `migrate` этапа 9 выкачен предыдущим релизом; держателей роли нет; снимков
-- этапа 9 с `migrated_at IS NULL` нет либо они разобраны поимённо.
--
-- ЧЕМ ОТЛИЧАЕТСЯ ОТ ЭТАПА 8. В `ROLE_ADDON_BASE_ROLES` роли `department_head` нет вовсе — базовой
-- ролью надстроек оргтехники всегда была `department`, — поэтому системных строк под удаление
-- здесь ноль, и правка кода ограничена перечнем ролей, подписями и `DEPARTMENT_SCOPED_ROLES`.
-- Признак руководителя отдела (`user_departments.is_head`, миграция `0149`) от упразднения роли не
-- зависит: справочник спрашивает признак, а не имя роли, — этап 5 затем и стоял до переводов.

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 1. Предохранитель: держателей упраздняемой роли не должно быть.
DO $$
DECLARE
  holders text;
BEGIN
  SELECT string_agg(u.email, ', ' ORDER BY u.email)
    INTO holders
    FROM users u
   WHERE u.role = 'department_head';
  IF holders IS NOT NULL THEN
    RAISE EXCEPTION
      'Упразднение роли этапа 9 невозможно: держатели ещё есть (%). '
      'Сначала выкатите migrate этапа 9 и убедитесь, что check:role-migration возвращает 0',
      holders;
  END IF;
END $$;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 2. Вычитающая половина правки `grant_roles`: строки пользовательских наборов, собранных под
--    упраздняемую роль (аддитивную половину сделал `0156`).
DELETE FROM grant_roles WHERE role = 'department_head';
