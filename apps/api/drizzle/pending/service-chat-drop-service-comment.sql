-- Обсуждение заявки на обслуживание оргтехники, ВЫПУСК C (contract схемы): повторный прогон
-- переноса «Примечания исполнителя», проверка «текущее значение перенесено» и снятие колонки
-- `service_requests.service_comment` (ADR 0141; план `docs/office-equipment-chat-plan.md`, §3.9
-- «Перенос примечания», §3.10 «Выкат», этап 8 в §4).
--
-- ПОДГОТОВЛЕНА, НО НЕ ВЫКАЧЕНА — см. `pending/README.md`. Номера у файла нет, и потому мигратор его
-- не видит: `listMigrationFiles()` фильтрует входы каталога по `.sql`, а внутрь `pending` не
-- заглядывает. Номер и имя (`NNNN_service_chat_drop_service_comment.sql`) присваиваются в день
-- выката — по факту занятых номеров, а не по памяти: номера в проекте идут параллельными потоками,
-- и за одни сутки их занимает сразу несколько работ. Содержимое при переносе не правится.
--
-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ РЕЛИЗ, А НЕ ХВОСТ МИГРАЦИИ 0216
--
-- Штатный деплой накатывает миграции ДО перезапуска контейнеров (`deploy/deploy-auto.sh`: сперва
-- накат, затем `up -d`; там же прямая запись «up -d авто-отката кода НЕ делаем — иначе „старый код
-- + новая схема“»). Значит `DROP COLUMN` встречается с ЕЩЁ РАБОТАЮЩИМ сервером предыдущего
-- выпуска. И встреча эта фатальна не из-за одной снятой ручки: `requestQuery` выбирает
-- `r: serviceRequests` — строку ЦЕЛИКОМ (`routes/service-requests.ts`), то есть drizzle
-- перечисляет в `SELECT` все колонки схемы. Снеси колонку под кодом, который её ещё перечисляет, —
-- и у модуля перестанет отвечать ВСЁ: список, карточка, каждый переход.
--
-- Отсюда три выпуска, и границы между ними проведены по тому, что именно перестаёт существовать:
--
--   A — миграция `0216`: таблицы ленты, триггеры, первый перенос. Ручка-адаптер
--       `PATCH /:id/service-comment`, поле `serviceComment` в DTO и колонка в `schema.ts` — ЖИВЫ:
--       их зовёт старый бандл в чужом браузере, которому до нового портала дела нет;
--   B — ТОЛЬКО КОД: адаптер, поле DTO и колонка уходят из `schema.ts`, база не трогается.
--       Поимённый список того, что снимает B, — в §3.10 плана, подраздел «Что именно снимает
--       выпуск B»;
--   C — эта миграция: код выпуска B колонку уже не выбирает, и снять её можно незаметно.
--
-- УСЛОВИЕ ГОТОВНОСТИ. Выкачен и перезапущен код выпуска B — тот, что о колонке не знает вовсе.
-- Между A и B обязано пройти окно совместимости: пока в браузерах жив бандл A, ручка-адаптер
-- нужна. C идёт СЛЕДУЮЩИМ релизом после B, не одновременно с ним: одновременность вернула бы ту
-- самую встречу `DROP COLUMN` с живым кодом A, ради которой выпуски и разведены.
--
-- ПОЧЕМУ ПОВТОРНЫЙ ПЕРЕНОС СТОИТ ЗДЕСЬ, А НЕ В ВЫПУСКЕ B. Миграции идут до перезапуска, поэтому в
-- окне выката B — между накатом и стартом нового кода — адаптер выпуска A ещё жив и ещё пишет в
-- колонку. Перенос, выполненный миграцией B, этой записи не увидел бы, и она осталась бы только в
-- колонке, которую C собирается снести. К моменту C адаптера нет уже нигде: код B колонку не
-- трогает, — и перенос забирает последнее, что в неё попало.
--
-- ПОЧЕМУ МИГРАЦИЯ ОБЯЗАНА УПАСТЬ, А НЕ СНЕСТИ ДАННЫЕ. `DROP COLUMN` необратим по содержимому:
-- откатить его можно только восстановлением дампа. Поэтому между переносом и сносом стоит
-- проверка, и она спрашивает не «есть ли у заявки хоть какая-нибудь перенесённая реплика», а
-- перенесено ли ТЕКУЩЕЕ значение колонки — хешем И равенством текста. Расплывчатое «есть
-- импортированная реплика» пропустило бы ровно тот случай, ради которого проверка и заводится:
-- примечание перенесли в выпуске A, потом исполнитель переписал его через адаптер, и последнее
-- значение осталось только в колонке — а старая реплика формально «есть». Не прошедшая проверка
-- роняет накат `RAISE EXCEPTION` с числом расхождений: упавшая миграция — это отложенный выкат,
-- прошедший `DROP` с неперенесённым примечанием — потерянный текст, и выбор между ними не стоит
-- обсуждения.
--
-- ВСЕ ТРИ ШАГА — ОДНОЙ ТРАНЗАКЦИЕЙ, и своего `BEGIN` файлу для этого не нужно: раннер оборачивает
-- каждую миграцию сам (`applyMigrations` в `db/migration-journal.ts`: `BEGIN`, файл, запись в
-- `_migrations`, `COMMIT`). Упавшая проверка откатывает и перенос: половины сделанного после себя
-- она не оставляет.
--
-- ОТКАТ. До этой миграции откат кода свободен в обе стороны — колонка на месте, схема совместима с
-- A и с B. После неё откат кода к B безопасен (он колонки не знает), а откат «через шаг», к коду
-- выпуска A, невозможен: его `SELECT` упрётся в отсутствующую колонку на первом же обращении к
-- модулю. Терять при этом уже нечего: содержимое колонки к этому моменту лежит в ленте — за это
-- отвечает проверка ниже.
--
-- ПОЧЕМУ НЕ `--cutover`. У портала есть протокол необратимых миграций с остановкой записи
-- (`docs/schema-cutover-protocol.md`), и им это делается за один выпуск. Он здесь не нужен и
-- вреден: cutover проходит точку невозврата, после которой откат кода запрещён, — а у нас нет ни
-- одной причины отказываться от отката. Три обычных выпуска дают ту же безопасность без
-- необратимости.
-- ─────────────────────────────────────────────────────────────────────────────────────────────

-- ── 1. Повторный прогон переноса (§3.9) ──
--
-- Блок ниже — ДОСЛОВНАЯ КОПИЯ шага 6 миграции `0216`, от `DO $migrate$` до конца; там он и помечен
-- как копируемый. Дословность — не аккуратность ради аккуратности: перенос идемпотентен по
-- `imported_hash = md5(service_comment)`, и стоит здесь пересказу разойтись с оригиналом хоть на
-- строку — повторный прогон либо создаст дубли, либо пропустит написанное адаптером в окне выката
-- B. Тем же требованием живёт db-тест `service-request-chat.db.test.ts` (п. 12): он вырезает этот
-- блок из файла миграции `0216`, а не переписывает его у себя.
--
-- Что перенос переносит и о чём честно молчит — в шапке шага 6 миграции `0216` и в §3.9 плана:
-- `origin = 'import'`, `author_id = NULL` (автора у примечания взять неоткуда), приблизительное
-- время `COALESCE(updated_at, created_at)`, адресат `all`, мягко удалённые заявки — наравне с
-- живыми.
DO $migrate$
DECLARE
  r record;
  v_body text;
  v_created timestamptz;
  v_hash text;
  v_seq integer;
  v_message_id uuid;
  v_moved integer := 0;
  v_skipped integer := 0;
BEGIN
  FOR r IN
    SELECT sr.id FROM service_requests sr WHERE btrim(sr.service_comment) <> '' ORDER BY sr.id
  LOOP
    -- Шаг 1. Текст перечитывается ПОД блокировкой, а не берётся из внешней выборки: между ней и
    -- блокировкой адаптер мог и переписать примечание, и стереть его.
    SELECT sr.service_comment, COALESCE(sr.updated_at, sr.created_at)
      INTO v_body, v_created
      FROM service_requests sr
     WHERE sr.id = r.id
     FOR UPDATE;

    IF NOT FOUND OR btrim(v_body) = '' THEN
      CONTINUE;
    END IF;

    v_hash := md5(v_body);

    -- Шаг 2. Перепроверка под блокировкой.
    IF EXISTS (
      SELECT 1 FROM service_request_messages m
       WHERE m.request_id = r.id AND m.origin = 'import' AND m.imported_hash = v_hash
    ) THEN
      v_skipped := v_skipped + 1;
      CONTINUE;
    END IF;

    -- Шаг 3.
    SELECT COALESCE(MAX(m.seq), 0) + 1 INTO v_seq
      FROM service_request_messages m WHERE m.request_id = r.id;

    -- Шаг 4. `v_message_id` обнуляется самим `INTO`, когда `DO NOTHING` не вернул строки.
    INSERT INTO service_request_messages
      (request_id, seq, author_id, origin, imported_hash, body, created_at)
    VALUES (r.id, v_seq, NULL, 'import', v_hash, v_body, v_created)
    ON CONFLICT (request_id, imported_hash) WHERE origin = 'import' DO NOTHING
    RETURNING id INTO v_message_id;

    IF v_message_id IS NULL THEN
      v_skipped := v_skipped + 1;
      CONTINUE;
    END IF;

    -- Шаг 5. Адресат `all`: у перенесённого примечания получателя не знает никто, а «всем
    -- участникам» — ровно то, чем оно было в карточке.
    INSERT INTO service_request_message_addressees (message_id, side)
    VALUES (v_message_id, 'all');

    v_moved := v_moved + 1;
  END LOOP;

  RAISE NOTICE 'Перенос примечаний исполнителя: перенесено %, пропущено как уже перенесённые %',
    v_moved, v_skipped;
END
$migrate$;

-- ── 2. Проверка «текущее значение перенесено» (§3.10) ──
--
-- Условие — то же, что в §3.10 плана и в db-тесте `service-request-chat.db.test.ts` (константа
-- `CUTOVER_CHECK_SQL` п. 12): пустое примечание переносить нечего, а у непустого обязана найтись
-- импортированная реплика с ТЕМ ЖЕ хешем И ТЕМ ЖЕ текстом.
--
-- Равенство `body` стоит рядом с хешем не для красоты: `md5` — не криптографическая гарантия, и
-- совпадение хешей у разных текстов обязано ловиться, пока колонка ещё цела. После `DROP COLUMN`
-- сверять будет не с чем.
--
-- Если проверка не прошла, значит выкат B состоялся не везде, либо в колонку писали мимо
-- приложения, либо перенос выше по какой-то причине не сработал, — и сносить колонку в этом
-- состоянии нельзя: она ещё может оказаться единственным местом, где чей-то текст записан. Число в
-- сообщении — подстановкой, чтобы админ сразу видел масштаб расхождения, а не шёл за ним запросом.
DO $check$
DECLARE n integer;
BEGIN
  SELECT count(*) INTO n FROM service_requests sr
   WHERE btrim(sr.service_comment) <> ''
     AND NOT EXISTS (
       SELECT 1 FROM service_request_messages m
        WHERE m.request_id = sr.id
          AND m.origin = 'import'
          AND m.imported_hash = md5(sr.service_comment)
          AND m.body = sr.service_comment
     );
  IF n > 0 THEN
    RAISE EXCEPTION 'Примечание исполнителя не перенесено у % заявок', n;
  END IF;
END
$check$;

-- ── 3. Снятие колонки ──
--
-- К этому месту транзакция дошла, только если каждое непустое примечание лежит в ленте своим
-- текстом. Индексов и ограничений на колонке нет — уходит она одна. Код выпуска B её не
-- перечисляет, поэтому снятие проходит незаметно для работающего сервера.
ALTER TABLE service_requests DROP COLUMN service_comment;
