-- Этап 9 работы «площадки отдела множеством» (ADR 0144, решение 4): снятие совместимой проекции.
--
-- ПОДГОТОВЛЕН, НО НЕ ВЫКАЧЕН — см. `pending/README.md`. Номера у файла нет, мигратор его не видит.
-- Номер и имя (`NNNN_department_object_column_drop.sql`) присваиваются в день выката — по факту,
-- как и всё остальное в этой работе: за одни сутки три параллельных потока заняли миграции
-- 0216–0223.
--
-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- ЧТО СНИМАЕТСЯ И ПОЧЕМУ ЭТО НЕ ОДИН РЕЛИЗ
--
-- Колонка `departments.construction_object_id` с ADR 0144 не источник, а совместимая проекция:
-- набор из одной площадки пишется в неё, набор из нескольких даёт NULL, а записи предыдущей версии
-- зеркалит обратно триггер. Она нужна была ровно на один переходный релиз — чтобы правка отдела
-- старым кодом в окне деплоя не потерялась, а откат версии не воскресил снятую площадку.
--
-- Выкат идёт ДВУМЯ релизами, и порядок обратный привычному: сначала код, потом схема.
--
--   Релиз A (только код, схему не трогает):
--     · `replaceDepartmentObjects` перестаёт писать проекцию — вместе с предупреждением
--       «⚠ ШАГИ 5 И 6 МЕСТАМИ НЕ МЕНЯТЬ», которое после этого теряет смысл;
--     · из контракта уходят `normalizeLegacyObjectId` / `withLegacyObjectId` и deprecated `object`
--       в `DepartmentDto`;
--     · из маршрута — `markLegacyObjectId`, `legacyObjectIdRequests`, ветка 409 и `object` в `toDto`;
--     · из веб-фикстур — поле `object`;
--     · из `department-objects.db.test.ts` — группы «старая вкладка» (алиас, 409) и проверка
--       проекции в колонку. Группа «триггер совместимости» остаётся: триггер ещё жив.
--
--   Релиз B (эта миграция + мелочь в коде):
--     · сама миграция;
--     · `departments.constructionObjectId` из `apps/api/src/db/schema.ts`;
--     · строка `departments: 'площадки отделов'` из `REFERENCING_TABLE_LABELS`
--       (`services/directory-purge.ts`) — после `DROP COLUMN` у отдела остаётся ровно одна ссылка
--       на объект, и подпись становится мёртвой;
--     · группа «триггер совместимости» из `department-objects.db.test.ts`.
--
-- ПОЧЕМУ НЕЛЬЗЯ ОДНИМ РЕЛИЗОМ. `deploy-auto` накатывает миграции ДО перезапуска приложения
-- (`docs/schema-cutover-protocol.md` §1). Приехавшая вместе с кодом миграция снесла бы колонку
-- под работающей предыдущей версией — той самой, которая пишет в неё проекцию при каждой правке
-- набора: любая правка отдела в окне выката отвечала бы 500 «column does not exist». Разнесённые
-- по релизам, эти шаги безопасны: после A колонку не пишет никто, и B сносит мёртвое.
--
-- Одним релизом это возможно только через `--cutover` (остановка записи на время окна), и оно того
-- не стоит: пауза между A и B ничем не ограничена, а сама колонка ничего не стоит.
--
-- ОТКАТ. Между A и B откат к текущей версии безопасен: колонка на месте, проекция снова пишется,
-- триггер жив. После B откат к A безопасен тоже — код A колонки не касается. А вот откат «через
-- шаг», к версии с проекцией, после B невозможен: она упрётся в отсутствующую колонку на первой же
-- правке набора. Это и есть точка невозврата этой работы, и проходится она по протоколу выката.
--
-- УСЛОВИЕ ГОТОВНОСТИ: релиз A выкачен и приложение перезапущено; в журнале приложения нет обращений
-- к `construction_object_id` (проверяется сверкой ниже — она обязана вернуть 0 строк расхождения).
-- ─────────────────────────────────────────────────────────────────────────────────────────────

-- Сверка перед сносом: колонка обязана быть согласована с таблицей связи там, где набор состоит из
-- одной площадки, и пуста везде, где их несколько. Расхождение означает, что релиз A выкачен не
-- везде или кто-то писал колонку мимо приложения, — и сносить колонку в этом состоянии нельзя:
-- она ещё может оказаться единственным местом, где чья-то площадка записана.
DO $$
DECLARE
  mismatched integer;
BEGIN
  SELECT count(*) INTO mismatched
  FROM departments d
  LEFT JOIN LATERAL (
    SELECT array_agg(dco.construction_object_id) AS ids
    FROM department_construction_objects dco
    WHERE dco.department_id = d.id
  ) s ON true
  WHERE d.construction_object_id IS DISTINCT FROM (
    CASE WHEN coalesce(array_length(s.ids, 1), 0) = 1 THEN s.ids[1] ELSE NULL END
  );

  IF mismatched > 0 THEN
    -- Число отдельной подстановкой, а не в тексте про «% отделов»: русское согласование
    -- числительного в формате не выразить, а «у 1 отделов» в аварийном сообщении читается как
    -- вторая ошибка поверх первой.
    RAISE EXCEPTION
      'Колонка-проекция разошлась с набором площадок. Отделов с расхождением: %. Снимать колонку нельзя, пока не ясно, чья это запись',
      mismatched;
  END IF;
END $$;

DROP TRIGGER IF EXISTS department_object_sync_trg ON departments;
DROP FUNCTION IF EXISTS department_object_sync();

-- Индекс `departments_construction_object_idx` уходит вместе с колонкой сам: он частичный и
-- построен по ней одной.
ALTER TABLE departments DROP COLUMN construction_object_id;

COMMENT ON TABLE department_construction_objects IS
  'Площадки отдела (ADR 0144): на них его сотрудники ведут вывоз мусора наравне со штабом. '
  'Единственный источник с этого релиза — совместимая проекция `departments.construction_object_id` '
  'и её триггер сняты. Единственный писатель — `replaceDepartmentObjects`.';
