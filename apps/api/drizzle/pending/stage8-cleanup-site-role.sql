-- Шаг cleanup этапа 8: `shtab`, `rukstroy` и `commandant` уходят из модели (план реструктуризации
-- модели доступа §13.2 «роли», §15 этап 8; ADR 0113).
--
-- ПОДГОТОВЛЕН, НО НЕ ВЫКАЧЕН — см. `pending/README.md`.
--
-- ЕДЕТ ОДНИМ РЕЛИЗОМ С ПРАВКАМИ КОДА, И ЭТО НЕ ПОЖЕЛАНИЕ. Роли уходят из `ROLES`, подписи — в
-- `ARCHIVED_ROLE_LABELS`, `shtab` снимается из `ROLE_ADDON_BASE_ROLES` обоих оргтехнических
-- наборов. Последняя правка и здешний `DELETE` — две половины одного утверждения, и разъехаться им
-- нельзя: страж каталога (`grants-catalog.db.test.ts`) сверяет `grant_roles` системных наборов с
-- `ROLE_ADDON_BASE_ROLES` построчно и покраснеет на любой половине без второй.
--
-- УСЛОВИЕ ГОТОВНОСТИ:
--   1. `migrate` этапа 8 выкачен ПРЕДЫДУЩИМ релизом и приложение перезапущено — между шагами
--      обязан пройти выкат: до него откат перевода ещё разрешён, а этот файл делает его
--      невозможным (см. ниже);
--   2. `SELECT count(*) FROM users WHERE role IN ('shtab','rukstroy','commandant')` возвращает 0;
--      предохранитель ниже проверяет это сам, но узнать заранее дешевле, чем уронить деплой;
--   3. `SELECT count(*) FROM user_role_migration WHERE stage = 8 AND migrated_at IS NULL` — 0 или
--      разобранный поимённо список: непереведённые снимки означают учётки, которым роль меняли
--      руками, и после этого файла вернуть их будет некуда.
--
-- ЭТО ТОЧКА НЕВОЗВРАТА ДЛЯ ОТКАТА ПЕРЕВОДА, а не для схемы. Схема остаётся обратимой полностью:
-- ни одного значения enum файл не удаляет и ни одной таблицы не трогает. Необратимо другое —
-- смысл: после снятия `grant_roles` неизвестно, какие пользовательские наборы были собраны под
-- старые роли (prepare добавлял целевую роль, а не запоминал, кому добавил), и возврат учётки на
-- `shtab` оставил бы её без прав такого набора молча. Отсюда и правило «cleanup — последний шаг».

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 1. Предохранитель: держателей упраздняемых ролей не должно быть.
--
-- Тот же приём, что в `migrate` (и в `0074`): деплой лучше уронить, чем отобрать доступ молча.
-- Здесь он ловит два случая сразу — «migrate не выкатывали вовсе» и «после migrate кому-то
-- поставили старую роль руками в базе» (через форму и API это уже невозможно с prepare).
DO $$
DECLARE
  holders text;
BEGIN
  SELECT string_agg(u.email, ', ' ORDER BY u.email)
    INTO holders
    FROM users u
   WHERE u.role IN ('shtab', 'rukstroy', 'commandant');
  IF holders IS NOT NULL THEN
    RAISE EXCEPTION
      'Упразднение ролей этапа 8 невозможно: держатели ещё есть (%). '
      'Сначала выкатите migrate этапа 8 и убедитесь, что check:role-migration возвращает 0',
      holders;
  END IF;
END $$;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 2. Вычитающая половина правки `grant_roles` — обе, системная и пользовательская, разом.
--
-- Аддитивную сделал prepare: рядом со старой ролью в наборе появилась целевая (`0155`, пункты 1 и
-- 1b). Держателей у старых ролей больше нет — значит строки не дают прав никому и остались
-- мусором: администратор видел бы в редакторе набора галочку роли, которой в перечне нет, а
-- каталог молча выкидывал бы её из ответа (`grant-catalog.ts`: `ROLES.filter(...)`) — то есть
-- показывал бы состав, не равный содержимому базы.
--
-- Одним запросом по списку ролей, а не поимённо по наборам: разделять здесь нечего — после
-- предохранителя выше любая строка с этими ролями заведомо мертва, чей бы набор она ни описывала.
-- Системных строк под удаление ровно две (`office_equipment_operator` и
-- `office_equipment_it_approver` × `shtab`, миграция `0145`), остальные — пользовательские.
DELETE FROM grant_roles WHERE role IN ('shtab', 'rukstroy', 'commandant');

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- Чего файл НЕ делает.
--
-- НЕ УДАЛЯЕТ ЗНАЧЕНИЯ ENUM. В Postgres нет `ALTER TYPE ... DROP VALUE`, а пересоздание типа
-- задевает `users.role` и `mailing_schedule_roles.role` (там роль входит в первичный ключ) и
-- попадает под протокол необратимого выката, механики которого в деплое нет. Значения остаются
-- мёртвыми: ноль миграций, полная обратимость, прецедент — `0054`. Мёртвые они не бесполезны:
-- `user_role_migration.role_before` хранит именно их, и без них снимок перестал бы читаться.
--
-- НЕ ТРОГАЕТ `mailing_schedule_roles`. Прежняя адресация рассылок ролями с этапа 7 не читается и
-- не пишется, а строки сохранены намеренно — ими откатывается седьмой этап. Удаляет таблицу своя
-- миграция, и связь этих ролей с ней ровно одна: значение enum, которое здесь и не удаляется.
--
-- НЕ ТРОГАЕТ `user_role_migration`. Снимок — след перевода и часть аудита «кем человек был»;
-- переживает cleanup целиком.
--
-- НЕ ТРОГАЕТ `user_grants`. Взведённые переводом назначения после `migrate` работают и дают
-- держателям их прежние права — снимать их значило бы отобрать ровно то, ради сохранения чего
-- весь этап и делался.
