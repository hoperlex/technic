-- Шаг migrate этапа 8: три площадочные роли переводятся в `site` (план реструктуризации модели
-- доступа §13.2 «перевод ролей — тоже три релиза», §15 этап 8; ADR 0113).
--
-- ПОДГОТОВЛЕН, НО НЕ ВЫКАЧЕН: файл лежит в `drizzle/pending/` и миграцией не является — номера у
-- него нет, мигратор его не видит (`pending/README.md`). Номер он получает в релизе своего шага,
-- и только после того, как выполнено условие готовности ниже.
--
-- УСЛОВИЕ ГОТОВНОСТИ — три пункта, все обязательны:
--   1. релиз prepare (`0154`–`0156`) выкачен и приложение перезапущено: вход в упраздняемые роли
--      закрыт (`retiringRoleIssue`), новых держателей не появляется;
--   2. `pnpm --filter @technic/api check:role-migration` возвращает 0 — прогнанный
--      НЕПОСРЕДСТВЕННО перед этим выкатом, а не тот, что гоняли после prepare: за релиз между
--      шагами могли отозвать взведённое назначение или сменить кому-то роль руками;
--   3. этап 7 (адресация рассылок правом) выкачен — иначе перевод сольёт три аудитории в одну.
--
-- ЧТО ЗДЕСЬ ПРОИСХОДИТ. Один `UPDATE` по снимку и ничего больше: наборы, которые сохраняют
-- прежние права, выданы релизом раньше и до этой минуты бездействуют — гейт совместимости
-- (`grant_roles`, соединение в `grantPermissionsExpr`) стоит на роли `site` и открывается ровно
-- вместе с ней. Поэтому перевод не добавляет и не отнимает прав ни у кого, кроме объявленного
-- расширения: комендант получает оргтехнику (решение №1 заказчика от 17.08.2026,
-- `ROLE_MIGRATIONS[].gains`).
--
-- ОБРАТИМОСТЬ. Откат — тот же запрос наоборот и по тому же снимку:
--
--   UPDATE users u SET role = m.role_before, auth_version = u.auth_version + 1, updated_at = now()
--     FROM user_role_migration m
--    WHERE m.user_id = u.id AND m.stage = 8 AND m.migrated_at IS NOT NULL
--      AND u.role = m.role_after;
--   UPDATE user_role_migration SET migrated_at = NULL WHERE stage = 8;
--
-- Условие `u.role = m.role_after` обязательно: учётка, которой роль сменили руками ПОСЛЕ перевода,
-- в откат не попадает — её разбирают отдельно, а не переписывают. Взведённые назначения откат
-- перевода не снимает: они принадлежат шагу prepare и с возвратом роли просто снова перестают
-- действовать. Полностью посеянное снимается откатом prepare (runbook).

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 1. Перевод учёток и отметка в снимке — одним оператором.
--
-- `WHERE u.role = m.role_before` — условность перевода из §13.2: учётка, у которой роль успели
-- сменить руками между prepare и этим релизом, пропускается молча и уходит в ручной разбор
-- (сверка называет её поимённо). Второй эффект того же условия — идемпотентность: на повторном
-- накате все переведённые уже стоят на `role_after`, условие не выполняется ни для кого, и файл
-- не делает ничего.
--
-- `migrated_at` проставляется тем же оператором через `RETURNING`, а не отдельным `UPDATE` по
-- `u.role = m.role_after`: второй запрос пометил бы заодно и учётку, которую на целевую роль
-- перевели руками раньше выката, — то есть соврал бы про то, чья это работа, а откат снял бы с
-- неё роль, которой не ставил.
--
-- `auth_version + 1` гасит выданные access-токены переведённых, и это не про права на сервере:
-- принципал читает роль и наборы из базы на каждом запросе (`loadPrincipal`), а `payload.role` в
-- токене не участвует ни в одной проверке. Гасится **клиентский снимок**: портал держит роль и
-- список прав из `/auth/me` и по ним рисует меню и формы — у бывшего коменданта иначе не появилась
-- бы оргтехника до истечения токена. Разлогина при этом не происходит: 401 «токен устарел» ловит
-- `shared/api/http.ts`, молча дёргает `/refresh` (refresh-сессия к `auth_version` не привязана) и
-- повторяет запрос уже с новой ролью в ответе. Цена — по одному лишнему обмену на переведённую
-- учётку, и только на них: `WHERE` тот же.
WITH moved AS (
  UPDATE users u
     SET role = m.role_after,
         auth_version = u.auth_version + 1,
         updated_at = now()
    FROM user_role_migration m
   WHERE m.user_id = u.id
     AND m.stage = 8
     AND u.role = m.role_before
  RETURNING m.id AS migration_id
)
UPDATE user_role_migration m
   SET migrated_at = now()
  FROM moved
 WHERE m.id = moved.migration_id;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 2. Предохранитель: на упраздняемых ролях не должно остаться никого.
--
-- Прецедент — `0074` (непереносённая история рейсов прерывает деплой). Здесь он нужен по той же
-- причине и стоит **после** перевода: пройти мимо может только учётка БЕЗ снимка, то есть
-- заведённая между накатом prepare и перезапуском приложения — в те минуты работала версия,
-- которая старую роль ещё принимала. Такую учётку перевод не увидит, а cleanup отберёт у неё
-- доступ целиком и молча: роли, под которой она живёт, в `ROLES` уже не будет.
--
-- Ронять деплой вместо «пропустить и сообщить» — сознательный выбор: миграции катятся ДО
-- перезапуска, поэтому отказ здесь оставляет работать прежнюю версию с прежней схемой, а это
-- ровно то состояние, из которого шаг повторяют. Тихий пропуск оставил бы человека без сигнала до
-- жалобы «пропал доступ».
--
-- Лечение названо в тексте ошибки, потому что читать её будут в логе деплоя: посевные запросы
-- `0155` идемпотентны (`ON CONFLICT DO NOTHING`) и добирают только недостающие снимки.
--
-- Список ролей выписан руками — тот же, что в `0155`, и по той же причине: миграция не умеет
-- спрашивать `ROLE_MIGRATIONS`. Что копии не разъедутся, следит
-- `role-migration-prepare.db.test.ts`.
DO $$
DECLARE
  left_behind text;
BEGIN
  SELECT string_agg(u.email, ', ' ORDER BY u.email)
    INTO left_behind
    FROM users u
   WHERE u.role IN ('shtab', 'rukstroy', 'commandant');
  IF left_behind IS NOT NULL THEN
    RAISE EXCEPTION
      'Перевод этапа 8 не полон: на упраздняемых ролях остались учётки без снимка (%). '
      'Досейте снимки повторным накатом посевных запросов 0155 и повторите выкат',
      left_behind;
  END IF;
END $$;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- Чего файл НЕ делает — и это границы шага, а не забытые строки.
--
-- НЕ ТРОГАЕТ `grant_roles`. Аддитивную половину («рядом со старой ролью дописать целевую») сделал
-- prepare; вычитающая — дело cleanup'а, и вот почему она не здесь, хотя соблазн велик. Строку
-- `('пользовательский набор', 'shtab')` восстановить неоткуда: какие наборы её имели, нигде не
-- записано — prepare добавлял `site`, а не запоминал, кому добавил. Снеси её этим файлом — и
-- откат перевода (возврат роли по снимку) вернул бы человека на `shtab` уже без прав его
-- собранного набора, молча. Между `migrate` и `cleanup` откат ещё разрешён, поэтому вычитание
-- ждёт релиза, в котором роль исчезает насовсем и откатывать становится нечего.
--
-- НЕ ТРОГАЕТ РОЛИ В КОДЕ. `ROLES`, подписи, `ROLE_ADDON_BASE_ROLES` — всё это cleanup. Между
-- шагами обе роли рабочие, и это ровно то состояние, в котором перевод ничего не ломает.
--
-- НЕ УДАЛЯЕТ СНИМОК. `user_role_migration` — единственный ответ на «кем человек был до перевода»
-- (три роли стали одной, полномочия происхождения не различают) и единственная опора отката.
-- Живёт он и после cleanup: значение enum остаётся в типе мёртвым как раз затем, чтобы
-- `role_before` продолжал храниться.
