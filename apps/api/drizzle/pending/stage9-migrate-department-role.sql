-- доступа §13.2, §15 этап 9; ADR 0113).
--
-- ПОДГОТОВЛЕН, НО НЕ ВЫКАЧЕН — см. `pending/README.md`.
--
-- Тот же шаг, что `stage8-migrate-site-role.sql`, и по тем же правилам; обоснования запросов —
-- там, здесь только различия. Этап отдельный, потому что снимок хранит номер и откатываются
-- переводы по отдельности; ехать при этом два файла могут одним релизом — как ехал prepare.
--
-- УСЛОВИЕ ГОТОВНОСТИ: prepare (`0156`) выкачен и приложение перезапущено; `check:role-migration`
-- возвращает 0 непосредственно перед выкатом. Требования «после этапа 7», в отличие от этапа 8,
-- здесь нет: в адресации рассылок роль `department_head` не сливается ни с чем.
--
-- РАСШИРЕНИЯ ДОСТУПА НЕТ ВОВСЕ. Пара «`department` + «Виза отдела»» равна прежней роли поимённо —
-- вся разница между ролями одно право `vehicleRequests.approve`, и набор с ним выдан релизом
-- раньше (`ROLE_MIGRATIONS`, строка этапа 9: `gains: []`).
--
-- ПРИЗНАК РУКОВОДИТЕЛЯ ОТДЕЛА ПЕРЕВОД НЕ ЗАТРАГИВАЕТ. «Кто руководит отделом» с этапа 5 живёт в
-- `user_departments.is_head` (миграция `0149`), а не в имени роли: справочник и карточка отдела
-- спрашивают признак и о роли не знают. Этап 5 затем и стоял до переводов.
--
-- ОБРАТИМОСТЬ. Тот же откат по снимку, что у этапа 8, с `m.stage = 9`.

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 1. Перевод учёток и отметка в снимке — одним оператором (обоснование в файле этапа 8).
WITH moved AS (
  UPDATE users u
     SET role = m.role_after,
         auth_version = u.auth_version + 1,
         updated_at = now()
    FROM user_role_migration m
   WHERE m.user_id = u.id
     AND m.stage = 9
     AND u.role = m.role_before
  RETURNING m.id AS migration_id
)
UPDATE user_role_migration m
   SET migrated_at = now()
  FROM moved
 WHERE m.id = moved.migration_id;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 2. Предохранитель: на упраздняемой роли не должно остаться никого.
--
-- Лечится повторным накатом посевных запросов `0156` — они идемпотентны.
DO $$
DECLARE
  left_behind text;
BEGIN
  SELECT string_agg(u.email, ', ' ORDER BY u.email)
    INTO left_behind
    FROM users u
   WHERE u.role = 'department_head';
  IF left_behind IS NOT NULL THEN
    RAISE EXCEPTION
      'Перевод этапа 9 не полон: на упраздняемой роли остались учётки без снимка (%). '
      'Досейте снимки повторным накатом посевных запросов 0156 и повторите выкат',
      left_behind;
  END IF;
END $$;
