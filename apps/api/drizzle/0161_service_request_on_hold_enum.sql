-- Статус «Отложена» — значение перечисления (план `docs/office-equipment-cycle-changes-plan.md`,
-- Р103, этап 2, миграция A).
--
-- Отдельной миграцией и без использования значения в ней самой: раннер применяет файл целиком в
-- одной транзакции (`apps/api/src/db/migration-journal.ts`), а PostgreSQL не разрешает
-- пользоваться новым значением enum до её фиксации. Колонки, CHECK'и и индекс, которым `on_hold`
-- нужен по имени, живут в следующей миграции `0162`. Тот же приём — в миграциях 0054, 0065, 0103,
-- 0114, 0117.
--
-- `AFTER 'in_work'` — не косметика: список заявок сортируется по колонке статуса, а порядок
-- сортировки у enum задаётся порядком объявления значений. Без `AFTER` «Отложена» встала бы в
-- конец, после «Отменена», и сортировка по статусу показывала бы заморозку за пределами цикла —
-- тогда как она останавливает заявку посреди рабочих статусов.
ALTER TYPE service_request_status ADD VALUE IF NOT EXISTS 'on_hold' AFTER 'in_work';

-- Аддитивная миграция: смысл существующих данных не меняется, ни одна строка нового значения не
-- получает. Протокол выката необратимых миграций (`docs/schema-cutover-protocol.md`) к ней не
-- применяется.
