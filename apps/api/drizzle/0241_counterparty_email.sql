-- Адрес электронной почты контрагента: куда портал пишет самой организации, а не её учёткам.
--
-- ОТКУДА НОМЕР. `0240` зарезервирован соседней работой и в этот коммит не входит; текущий выпуск
-- занимает 0241 этой миграцией и 0242 записью выпуска. Номера миграций и ADR идут параллельными
-- потоками, поэтому отсутствие файла соседней работы в этом коммите не выдаётся за проверенный
-- файл дерева.
--
-- ЗАЧЕМ. Письмо о назначении заявки на обслуживание оргтехники (ADR 0096, `service_request_assigned`)
-- до сих пор искало адресатов среди УЧЁТОК: `users.counterparty_id = <подрядчик>` и роль из
-- `COUNTERPARTY_SCOPED_ROLES`. У сервисной компании, которая в портал не входит вовсе, таких учёток
-- нет ни одной — и заявка, отданную ей, доезжала до неё голосом, а портал отвечал `no_recipients`.
-- Подрядчик без доступа в портал — обычное дело (так и записано в комментарии к отбору
-- операторов), значит адрес обязан лежать у самой организации.
--
-- ПОЧЕМУ КОЛОНКА, А НЕ ТАБЛИЦА АДРЕСОВ. У сервисной компании один ящик заявок — это и есть смысл
-- «общего адреса»: письмо кладут туда, а внутри его разбирает диспетчер. Несколько адресов на
-- организацию — другая задача (кому какие события), и решать её строкой в `module_mail_recipients`
-- нельзя: та таблица адресует СОБЫТИЕ, а не контрагента, и её адрес получает все назначения
-- портала, включая чужие. Понадобится несколько — заведётся своя таблица; расширение колонки в
-- таблицу дешевле, чем таблица, которой никто не пользуется.
--
-- ПОЧЕМУ У ВСЕХ ТИПОВ, А НЕ ТОЛЬКО У `service`. Тип контрагента меняют (ADR 0010: одна запись на
-- ИНН, роль — поле), и CHECK «адрес только у сервисной компании» превратил бы смену типа в отказ
-- сохранения с необъяснимой формулировкой. Адрес организации сам по себе осмыслен у любого типа;
-- письма по нему сегодня шлёт только модуль оргтехники, и это свойство КОДА, а не данных.
--
-- ПОЧЕМУ `citext` И БЕЗ ПРОВЕРКИ ФОРМАТА. `citext` — как у `users.email` и `persons.email`: адрес
-- сравнивают нечувствительно к регистру, и третьего правила на то же самое быть не должно. Формата
-- в БД нет там же и по той же причине: разбирает адрес `optionalEmailSchema` (общий на портал —
-- учётки, водители, кадровый импорт), а регулярное выражение в CHECK'е разошлось бы с ним на
-- первой же правке и отвергало бы адреса, которые форма приняла.
--
-- ПУСТАЯ СТРОКА, А НЕ `NULL` — соглашение необязательного адреса в этой базе (`persons.email`,
-- `module_mail_recipients.reply_to_email`): «не указан» и «указан пустым» — не два разных
-- состояния, и `NULL` завёл бы второе.
ALTER TABLE counterparties ADD COLUMN email citext NOT NULL DEFAULT '';

COMMENT ON COLUMN counterparties.email IS
  'Общий почтовый ящик организации. Сегодня по нему уходят письма модуля «Орг.техника» сервисной '
  'компании — назначение заявки, отзыв назначения и отмена (ADR 0153): подрядчик читает почту, а '
  'учёток в портале у него может не быть вовсе. Пусто — адреса нет, письмо получат только '
  'учётки-операторы.';
