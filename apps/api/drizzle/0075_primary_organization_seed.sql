-- Основная организация-владелец транспорта: АО «Служба механизации» (ADR 0037, миграция 0060).
--
-- Миграция 0060 оставила `organizations` пустой намеренно: «реквизиты заводит администратор — это
-- шаг настройки, а не данные, которые можно угадать миграцией». Расчёт не сошёлся: заводить
-- организацию в портале нечем. Ручек CRUD у справочника нет ни в API (`routes/waybills.ts` только
-- читает), ни экрана в вебе, ни сид-скрипта — администратор физически не может выполнить шаг,
-- который на него оставили. `vehicles.owner_organization_id` по той же причине пуст у всех машин.
--
-- Отсюда и отказ: `resolveOrganization` не находит владельца у машины, не находит основную
-- организацию и бросает «Не заведена организация-владелец транспорта: путевой лист выписывать не
-- от кого» — на каждой попытке выписать лист, то есть на всех.
--
-- Реквизиты не угаданы: они напечатаны в шапке бланков, по которым портал и делали (форма № 4-П,
-- форма № 3). ОКПО 81390365 и ОГРН 5077746884771 — то же юрлицо в обеих формах. Ровно тот случай,
-- когда данные известны точно, а «шаг настройки» существовал только на бумаге; заводит их сид —
-- как парк техники (0028, 0073) и серию листов (0061).
--
-- ИНН не заводится: на бланках его нет, а выдумывать реквизит с контрольной суммой нельзя. Графа
-- необязательна (`inn = ''` проходит CHECK) и на печать не идёт. Правится он, как и остальные
-- реквизиты, пока только SQL — справочник юрлиц с экраном остаётся в бэклоге ADR 0037; порядок
-- правки описан в runbook'е.
-- ОКУД в организации не хранится вовсе — это код формы, а не юрлица: 0345005 у 4-П и 0345001 у
-- формы № 3 напечатаны в самих бланках.

-- Уже заведённую организацию с этим ОГРН не дублируем, а отмечаем основной: администратор мог
-- успеть вписать реквизиты руками через SQL, и его запись — та же самая.
UPDATE organizations
SET is_primary = true,
    is_active = true,
    updated_at = now()
WHERE id = (
    SELECT id FROM organizations WHERE ogrn = '5077746884771' ORDER BY created_at LIMIT 1
  )
  AND NOT EXISTS (SELECT 1 FROM organizations WHERE is_primary);

-- Основная уже есть — не трогаем: у неё могут быть выверенные бухгалтерией реквизиты, и
-- перезаписать их сидом значит менять шапку будущих листов за спиной у того, кто их вписал.
INSERT INTO organizations (name, address, phone, okpo, ogrn, is_primary, comment)
SELECT
  'АО «Служба механизации»',
  '141006, Московская обл., г. Мытищи, Проспект Олимпийский, Северная промзона, вл. 3, литер А-А1, офис 19',
  '(495) 616-23-21, +7-985-211-27-24',
  '81390365',
  '5077746884771',
  true,
  'Заведена миграцией 0075 по шапке бланков 4-П и № 3; ИНН не заполнен — правка SQL по runbook''у'
WHERE NOT EXISTS (SELECT 1 FROM organizations WHERE is_primary);
