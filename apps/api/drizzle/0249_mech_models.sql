-- Справочник моделей малой механизации (план `docs/mechanization-models-directory-plan.md`,
-- редакция 2, этап Э1). Первая из двух миграций этапа: здесь таблица, в 0250 — присланные позиции.
--
-- ОТКУДА НОМЕР. Проверено `ls apps/api/drizzle/*.sql` непосредственно перед созданием файлов
-- (03.09.2026): последняя миграция в дереве — `0248_releases_auto_parts_freeze.sql`. Номера
-- миграций и ADR идут параллельными потоками, поэтому сверка сделана заново, а не взята из шапки
-- плана.
--
-- ЗАЧЕМ. Вид техники в заявке механизации сейчас свободная строка с подсказкой ранее введённого
-- (ADR 0152, решение 5: «справочника видов заказчик пока не захотел — перечень не устоялся»).
-- Перечень приехал — 104 строки от заказчика, — и решение снимается им же: выбор должен быть
-- строгим, из справочника. Слово «модели» тоже названо заказчиком, поэтому таблица `mech_models`,
-- а не `mech_kinds`: в списке модели техники, а не виды и не отдельные машины.
--
-- ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ. `mech_requests` эта миграция не трогает ни колонкой: ссылку
-- `mech_model_id`, перенос живых строк и снятие подсказки делает этап Э2 отдельным выкатом.
-- Разведено это не из осторожности, а потому что `deploy-auto` накатывает миграции ДО перезапуска:
-- добавь сюда обязательную ссылку — и всё окно выката заявка механизации не заводится вовсе, а
-- причиной в ответе стояло бы имя ограничения. Справочник же сам по себе никому не мешает: пока
-- Э2 не выкачен, о нём знают только «Справочники» и обмен файлом.
--
-- ОБРАТИМОСТЬ. Миграция аддитивная — одна новая таблица, ни одной правки существующих. Протокол
-- выката необратимых миграций (`docs/schema-cutover-protocol.md`) к ней не применяется.

CREATE TABLE mech_models (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Системный ключ строки: латиница из наименования, человеку не показывается. Существует ради
  -- двух вещей — обмена файлом (ADR 0073 ищет строку по коду, а не по идентификатору) и
  -- переименования: поправив «Виброплита реверсивная Wacker DPU 3070Н», код не меняют, и строка
  -- остаётся той же самой для всех, кто на неё уже сослался.
  code text NOT NULL,
  -- Как модель называется человеку — дословно так, как её прислал заказчик, вместе с «(см)»,
  -- «(компл)», серийным номером и «б/у» (разбор — в шапке 0250).
  name text NOT NULL,
  -- По чему модель ОПОЗНАЁТСЯ: регистр и повторные пробелы написание не различают. Считает БД
  -- (STORED), потому что под ключом живёт UNIQUE ниже, а второй точки правды по написанию быть не
  -- должно — разойдясь с индексом, она завела бы вторую строку справочника, глазами не отличимую
  -- от первой.
  --
  -- ВЫРАЖЕНИЕ ПОВТОРЯЕТ `mech_requests.kind_key` (0238) ЗНАК В ЗНАК, и это не совпадение: этап Э2
  -- переносит живые заявки на ссылку сопоставлением `kind_key = name_key`. Нормализуй здесь иначе
  -- (сними «ё», выброси знаки препинания, как это делает `waste_type_name_key`) — и заявка
  -- «Виброплита реверсивная Wacker DPU 3070Н» не найдёт свою модель, а перенос молча оставит её
  -- строкой. Выражение проверено на обеих живых версиях (прод — PostgreSQL 17, дев — 16):
  -- `lower`, `btrim` и четырёхаргументный `regexp_replace` IMMUTABLE в обеих, иначе генерируемая
  -- колонка не создалась бы вовсе.
  name_key text GENERATED ALWAYS AS (lower(btrim(regexp_replace(name, '\s+', ' ', 'g')))) STORED,
  -- Порядок показа. Сид кладёт позиции по алфавиту с шагом 10 — чтобы вставленную завтра строку
  -- можно было поставить между соседями, не переписывая весь справочник.
  sort_order integer NOT NULL DEFAULT 100,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  -- Формат кода — kebab-case латиницей: коды порождаются транслитерацией наименования, а оно
  -- состоит из слов. Разделитель прописан в самом выражении (`-` только МЕЖДУ частями), поэтому
  -- «vibroplita--wacker» и «vibroplita-» база не примет: такие коды получаются из ошибки
  -- генератора, и ловить их лучше здесь, чем глазами в файле обмена.
  CONSTRAINT mech_models_code_format_check CHECK (code ~ '^[a-z][a-z0-9]*(-[a-z0-9]+)*$'),
  -- Непустота имени — та же пара проверок, что у типов мусора (0021, 0036): `name` без пробелов
  -- по краям и `name_key`, который отличает одну модель от другой. Наименование из одних знаков
  -- препинания даёт пустой ключ и перестало бы ловиться как дубль.
  CONSTRAINT mech_models_name_not_blank_check CHECK (btrim(name) <> ''),
  CONSTRAINT mech_models_name_key_not_blank_check CHECK (name_key <> '')
);

CREATE UNIQUE INDEX mech_models_code_unique ON mech_models (code);
-- Двух одинаково названных моделей в справочнике не бывает — на этом держится и строгий выбор в
-- заявке, и перенос Э2: сопоставление по имени имеет смысл, только пока имя одно на строку.
CREATE UNIQUE INDEX mech_models_name_key_unique ON mech_models (name_key);

COMMENT ON TABLE mech_models IS
  'Модели малой механизации: что можно взять в аренду (план mechanization-models-directory-plan)';
