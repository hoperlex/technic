-- Новый тип заявки: «Вывоз металлолома» (ADR 0067).
--
-- Лом копится на площадке так же, как мусор, и увозит его такой же исполнитель по такой же
-- заявке — отдельного модуля тут нет. Отличается заявка тем, чего у неё нет: ни типа мусора, ни
-- объёма, ни цены. Прайс задан в ₽/м³ на пару «тип мусора × техника» (ADR 0009), и лом в эту
-- пару не встаёт: его не заказывают кубометрами и не считают по вместимости кузова.
--
-- Значение enum добавляется отдельной миграцией: использовать его в той же транзакции, где оно
-- добавлено, Postgres не даёт, а раннер выполняет файл целиком в одной (приём 0006, 0022/0023,
-- 0032/0033, 0076/0077). CHECK-и, которые на это значение ссылаются, идут следующей миграцией.
