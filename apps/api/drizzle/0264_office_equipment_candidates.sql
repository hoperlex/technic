-- ОКНО ВЫКАТА. Миграция аддитивна: новая таблица старому коду неизвестна, новая колонка заявки
-- необязательна и без умолчания, а расширение `CHECK` для строк без кандидата сохраняет
-- сегодняшнее правило ДОСЛОВНО — старый код в окне выката таких строк не пишет вовсе и потому
-- ограничения не замечает. Замена ограничения (`DROP` + `ADD`) идёт двумя командами, но в ОДНОЙ
-- транзакции: раннер оборачивает каждый файл в `BEGIN`/`COMMIT` (`src/db/migration-journal.ts`), и
-- окна «предмет заявки не сторожит никто» не возникает. `ADD CONSTRAINT` при этом валидирует все
-- существующие строки под кратким `ACCESS EXCLUSIVE` — на таблице заявок модуля это тысячи строк,
-- то есть доли секунды; для миллионной таблицы пришлось бы городить `NOT VALID` + `VALIDATE`.
--
-- ОБРАТИМОСТЬ ПОЛНАЯ, пока не заведён ни один кандидат: снять индекс и колонку заявки, вернуть
-- прежнее двусоставное ограничение, удалить таблицу. После первой пары «кандидат + заявка» откат
-- колонки потеряет связь, а прежнее ограничение отвергнет такие строки — как и положено, откат
-- схемы не должен молча терять данные. Протокол выката необратимых миграций
-- (`docs/schema-cutover-protocol.md`) к этому файлу не применяется: окна останова он не требует.
--
-- POSTGRESQL 17 (прод) И 16 (дев). Version-specific здесь нет ничего. Частичные уникальные индексы
-- по ВЫРАЖЕНИЮ `upper(btrim(...))` — тот же приём и те же функции (обе `immutable`), что уже
-- работают в проде на номерах парка с `0105`; `ADD COLUMN` без умолчания таблицу не переписывает с
-- 11-й версии. Караул в конце файла проверяет ограничения ПОИМЁННО, а не считает их по
-- `pg_constraint`: каталогизация `NOT NULL` в этом каталоге разная у 16-й и 18-й версий, и счёт
-- «сколько всего ограничений» разошёлся бы между дев-базой и продом на ровном месте.

-- ── 1. Таблица кандидатов (Р3) ──
--
-- Реквизитов ШЕСТЬ и ни одного из учёта (Р7): тип, модель текстом, серийный/инвентарный, объект,
-- место, комментарий. Отдела-владельца, даты покупки, гарантии, признака активности и ссылки на
-- модель здесь нет намеренно — это реквизиты учёта, а не наблюдения: заявитель их не знает, и
-- спросив их, форма получила бы выдуманные ответы. Проставляет их проверяющий в форме
-- подтверждения — полной форме карточки парка (Р13).
CREATE TABLE office_equipment_candidates (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),

  -- Четыре состояния (Р3): `pending` («На проверке») → одно из трёх решений проверяющего:
  -- `confirmed` (по сообщению завели новую карточку), `duplicate` (аппарат уже был в справочнике, и
  -- кандидат объединён с существующей карточкой), `rejected` (аппарата в названном месте нет либо
  -- сообщение недостоверно). Все три конечны: «передумал» оформляется новой парой «кандидат +
  -- заявка», а не переписыванием прошлой.
  --
  -- Текстом с `CHECK`, а не своим `enum`: у типа в Postgres нет `DROP VALUE`, и мёртвое значение
  -- остаётся в нём навсегда (модуль уже носит четыре таких — `0197` и `0224`). Приём и довод — от
  -- закупки (`0227`).
  --
  -- Меняется он УСЛОВНОЙ ЗАПИСЬЮ `UPDATE … WHERE id = ? AND status = 'pending' AND
  -- content_version = ?` с обязательным `ROW_COUNT = 1` (Р11): ноль строк означает «решение уже
  -- принято или форма устарела» и отвечает 409. Без этого «Подтвердить» и «Отклонить», нажатые
  -- одновременно, перетёрли бы друг друга, и в базе оказался бы подтверждённый кандидат с причиной
  -- отказа.
  status text NOT NULL DEFAULT 'pending',

  -- Тип — ссылкой на обычный справочник: перечень из десятка строк, и без типа проверяющий не
  -- знает, какую форму открывать. `RESTRICT`, как у карточки парка: тип, на который ссылается хоть
  -- одно сообщение, не удаляют, а гасят.
  equipment_type_id uuid NOT NULL REFERENCES office_equipment_types (id) ON DELETE RESTRICT,

  -- Модель ТЕКСТОМ — «Kyocera ECOSYS M3145» с шильдика (Р7), и это решение, а не упрощение формы.
  -- Справочник моделей — такая же запись справочника, и открыв его заявителю, мы вернули бы
  -- отобранный `write` боковой дверью: перечень моделей пополнялся бы теми, кто карточки вести не
  -- должен. Ссылку на модель проставляет проверяющий, и живёт она уже в заведённой карточке, а не
  -- здесь: заявленное остаётся заявленным навсегда.
  declared_model text NOT NULL,
  serial_number text NOT NULL DEFAULT '',
  inventory_number text NOT NULL DEFAULT '',

  -- Физическое место аппарата — площадка. Обязательно: у сообщения о технике адрес есть всегда, его
  -- называет сам заявитель, и он же становится объектом связанной заявки (Р5). Сервер сверяет его с
  -- осью роли автора (объектная — из привязок к объектам, отдельская — из объектов отдела,
  -- сквозная — из справочника); чужой объект — 422 до всякой записи.
  object_id uuid NOT NULL REFERENCES construction_objects (id) ON DELETE RESTRICT,

  -- «каб. 214». Обязательно и непусто — в отличие от карточки парка, где место бывает пустым: там
  -- единицу уже нашли и завели, а здесь место — единственное, по чему проверяющий физически найдёт
  -- аппарат, чтобы посмотреть на шильдик своими глазами.
  location text NOT NULL,
  -- «стоит у бухгалтерии, наклейки нет» — необязательное уточнение к пяти реквизитам выше.
  comment text NOT NULL DEFAULT '',

  -- Подразделение автора СНИМКОМ на момент отправки — отдельская ось области проверяющего (Р9).
  -- Снимком, а не соединением с сегодняшними привязками учётки: переведённый в другой отдел человек
  -- не должен уносить свои прошлые сообщения из чужой очереди — тот же приём и тот же довод, что у
  -- трёх снимков области в заявке. `NULL` законен и означает «у автора отделов нет» (администратор,
  -- роль без привязок), а не «неизвестно»: такие кандидаты видны по объекту.
  requester_department_id uuid REFERENCES departments (id) ON DELETE RESTRICT,

  -- Кто сообщил. `RESTRICT`, как у автора закупки: «кто сообщил» и «кто решил» — единственные
  -- вопросы, ради которых строка и хранится после решения, и `SET NULL` заставил бы её отвечать
  -- «неизвестно» ровно на них. Справочники в портале переживают увольнение своего автора
  -- (`SET NULL`), свидетельства — нет.
  created_by uuid NOT NULL REFERENCES users (id) ON DELETE RESTRICT,

  -- ── Идемпотентность заведения пары «кандидат + заявка». Приём и оба поля — от закупки (`0227`) и,
  -- через неё, от кабинета водителя (ADR 0103): ключ описывает ПОПЫТКУ отправки, отпечаток — саму
  -- команду. Тот же ключ с тем же отпечатком возвращает уже созданную пару без второго аудита и
  -- второго письма; тот же ключ с другим телом — это другая команда под старым ключом, и молча
  -- подтверждать её нельзя.
  --
  -- Тонкость, которой у закупки не было: одинаковое тело одновременно конфликтует и по ключу, и по
  -- номеру ожидающего кандидата, а PostgreSQL не обещает, какой из уникальных индексов сообщит об
  -- этом первым. Поэтому маршрут разбирает `23505` по ИМЕНИ ограничения и сначала перечитывает
  -- победителя по ключу — имена всех трёх заданы руками именно ради этого разбора, а не для стиля.
  idempotency_key uuid NOT NULL,
  -- Отпечаток НОРМАЛИЗОВАННОГО тела заявки целиком, включая кандидата и `fileIds`: строки обрезаны,
  -- необязательные значения приведены к одному виду, множества идентификаторов отсортированы и
  -- дедуплицированы. Нормализация обязательна до отпечатка — иначе переставленные местами вложения
  -- той же заявки дали бы «другую команду под тем же ключом», и честный повтор получил бы 409.
  idempotency_fingerprint text NOT NULL,

  -- Версия содержимого (Р11, Р12). Статус и версия отвечают на РАЗНЫЕ вопросы, и одним полем на два
  -- не ответить: статус — «принято ли решение», версия — «не изменил ли строку кто-то другой».
  -- Статуса не хватает именно правке реквизитов: она идёт ВНУТРИ `pending`, где статус неподвижен и
  -- ничего не стережёт, — двое проверяющих, открывших одну строку очереди, перетёрли бы исправления
  -- друг друга молча. Растёт и при правке, и при решении. Считается с единицы: отправленный
  -- кандидат — это уже первая редакция свидетельства.
  content_version integer NOT NULL DEFAULT 1,

  created_at timestamptz NOT NULL DEFAULT now(),

  -- Правка реквизитов проверяющим до решения (Р12): «заявитель списал `O` вместо `0`». Автору
  -- правка закрыта после отправки намеренно — кандидат есть свидетельство о том, что человек видел
  -- в кабинете, и переписанное задним числом свидетельство ничего не доказывает; уточнения идут
  -- репликой в обсуждении заявки (ADR 0141).
  --
  -- `SET NULL` здесь, а не `RESTRICT` соседей, и это не небрежность: «кто поправил опечатку» —
  -- служебный след, ради которого держать учётку уволенного не нужно, а «кто сообщил» и «кто решил»
  -- составляют предмет самой записи. Пустая пара означает «сообщение приняли как есть».
  updated_by uuid REFERENCES users (id) ON DELETE SET NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),

  -- Кто и когда решил. Пара пишется той же транзакцией, что и статус, и вместе с парой заведения и
  -- парой правки образует ленту жизни кандидата — её строят ЭТИ колонки, а не журнал аудита. Довод
  -- от закупки: общий помощник `writeAudit` глотает ошибку записи (`catch` + `logger.error`), то
  -- есть гарантией истории не является, и лента из такого источника показывала бы путь сообщения с
  -- дырами. Строгий аудит решения при этом пишется тоже, но он отвечает на другой вопрос — «что
  -- вообще происходило в портале».
  decided_by uuid REFERENCES users (id) ON DELETE RESTRICT,
  decided_at timestamptz,
  -- Причина решения. Обязательна у отказа (`…_reason_check` ниже) и уходит заявителю ДОСЛОВНО — и в
  -- карточку заявки, и в письмо (Р15): общее «сообщение отклонено, подробности в портале» экономило
  -- бы проверяющему выбор слов ценой второго действия человека. Пустая строка означает «причины не
  -- было»; `NULL` рядом с ней был бы вторым именем того же состояния.
  decision_reason text NOT NULL DEFAULT '',

  -- Чем кончилась проверка: карточка, заведённая по сообщению (`confirmed`), либо та, с которой
  -- кандидата объединили (`duplicate`). Ею же отвечается срез «что завели через проверку» —
  -- отдельного признака происхождения у карточки парка поэтому НЕТ: он был бы третьим хранением
  -- одного факта и разошёлся бы с этой ссылкой на первом же объединении, где карточка заведена
  -- вовсе не по сообщению. `RESTRICT`: карточку, на которую ссылается решение, нельзя снести
  -- насовсем, не потеряв ответ «откуда она взялась»; мягкое удаление ссылку не трогает.
  result_equipment_id uuid REFERENCES office_equipment (id) ON DELETE RESTRICT,

  -- ── Инварианты. КАЖДЫЙ ОТДЕЛЬНЫМ ИМЕНЕМ, приём от закупки: имя сработавшего ограничения читает
  -- человек, и «нарушено office_equipment_candidates_reason_check» говорит, что именно не сошлось, а
  -- общее имя потребовало бы разбирать выражение. Держит их база, а не порядок вызовов: ручной
  -- `UPDATE`, скрипт обслуживания или забытая ветка маршрута оставили бы сообщение в состоянии,
  -- которого не бывает.

  -- Словарь состояний. Значение вне четвёрки — не «новый статус», а опечатка скрипта. Те же четыре
  -- слова стоят в `OFFICE_EQUIPMENT_CANDIDATE_STATUSES` контрактов и в `$type` колонки схемы.
  CONSTRAINT office_equipment_candidates_status_check
    CHECK (status IN ('pending', 'confirmed', 'duplicate', 'rejected')),

  -- Хотя бы один номер — тот же инвариант, что у парка (`office_equipment_identity_check`), и по
  -- той же причине: по номеру аппарат опознают. Здесь у него есть и вторая работа: по номеру ищется
  -- дубль на всех трёх рубежах (Р10), и сообщение без обоих номеров не с чем сверить.
  CONSTRAINT office_equipment_candidates_identity_check
    CHECK (btrim(serial_number) <> '' OR btrim(inventory_number) <> ''),

  -- Заявленная модель и место непусты. Через `btrim`, а не `<> ''`: строка из пробелов — это
  -- отсутствие ответа, набранное иначе, и «модель: „   “» проверяющему говорит ровно столько же,
  -- сколько пустое поле.
  CONSTRAINT office_equipment_candidates_model_not_blank_check
    CHECK (btrim(declared_model) <> ''),
  CONSTRAINT office_equipment_candidates_location_not_blank_check
    CHECK (btrim(location) <> ''),

  -- Пустой отпечаток сделал бы ключ бессмысленным: повтор с ЛЮБЫМ телом совпал бы с ним и вернул бы
  -- чужую пару «кандидат + заявка» как свою.
  CONSTRAINT office_equipment_candidates_fingerprint_not_blank_check
    CHECK (btrim(idempotency_fingerprint) <> ''),

  -- Ноль означал бы строку без единой редакции, а она создаётся сразу заполненной.
  CONSTRAINT office_equipment_candidates_content_version_check
    CHECK (content_version > 0),

  -- Решение — это пара «кто и когда», и живёт она РОВНО у решённого кандидата. Обе стороны
  -- равенства важны: «заполнено только у решённого» не запрещает решённого без автора, а «у
  -- решённого заполнено» — автора решения у ожидающего. Второе равенство держит саму пару: время без
  -- автора и автор без времени — половина ответа на вопрос, ради которого колонки заведены.
  CONSTRAINT office_equipment_candidates_decision_check
    CHECK ((status = 'pending') = (decided_by IS NULL)
       AND (decided_by IS NULL) = (decided_at IS NULL)),

  -- Результат есть РОВНО у двух положительных исходов. Отсюда обязательный порядок шагов в
  -- транзакции подтверждения (Р13): карточка вставляется ДО перевода статуса — иначе промежуточное
  -- состояние «confirmed без результата» не прошло бы это ограничение, — а отказ ссылки на карточку
  -- иметь не может, потому что карточки не появилось.
  CONSTRAINT office_equipment_candidates_result_check
    CHECK ((status IN ('confirmed', 'duplicate')) = (result_equipment_id IS NOT NULL)),

  -- Отказа без причины не бывает (Р15): её читает заявитель, и «отклонено» без слов через месяц
  -- читается как «передумали». У остальных исходов причина свободна — подтверждение объясняет себя
  -- самой заведённой карточкой.
  CONSTRAINT office_equipment_candidates_reason_check
    CHECK (status <> 'rejected' OR btrim(decision_reason) <> ''),

  -- УНИКАЛЬНОСТЬ КЛЮЧА — ОБЫЧНАЯ И С ЯВНЫМ ИМЕНЕМ. Обычная, а не частичная: ключ обязателен, и
  -- частичный индекс по одной колонке обещал бы, что ключа может не быть. БЕЗ УСЛОВИЯ ПО СТАТУСУ, в
  -- отличие от двух индексов ниже, и это не забывчивость: потерянный успешный ответ повторяют и
  -- через час, когда кандидат уже решён, — а частичный индекс ожидающих к тому времени освободился
  -- бы и создал вторую пару «кандидат + заявка». Пара с автором, а не ключ сам по себе: ключ
  -- описывает попытку КОНКРЕТНОГО человека.
  CONSTRAINT office_equipment_candidates_idempotency_unique UNIQUE (created_by, idempotency_key)
);

COMMENT ON TABLE office_equipment_candidates IS
  'Сообщение заявителя об аппарате, которого нет в справочнике (план office-equipment-candidate-plan, '
  'Р1–Р3). Не запись парка: в активные селекторы, статистику, обмен файлом и чужую область не '
  'попадает по построению, а карточку парка создаёт только решение держателя officeEquipment.write.';

-- ГОНКУ ДВУХ ЗАЯВИТЕЛЕЙ ЛОВЯТ ЭТИ ДВА ИНДЕКСА, А НЕ SELECT МАРШРУТА (Р10, рубеж 2). Двое в одну
-- минуту сообщают об одном принтере: проверка «нет ли такого кандидата» проходит у обоих, а отбивает
-- второго уникальность — его транзакция откатывается целиком, и маршрут переводит `23505` в 409
-- «Этот аппарат уже отправлен на проверку». Тот же расклад и по той же причине, что у замка «одна
-- открытая заявка на единицу» (`service_requests_open_repair_unique`): словами отвечает маршрут, а
-- держит правило индекс.
--
-- ЧАСТИЧНЫЕ ПО `status = 'pending'`: решённый кандидат номер НЕ держит — новый факт можно сообщить
-- новой парой «кандидат + заявка», в том числе после отказа. Пустой номер не сравнивается вовсе: он
-- законен, пока заполнен второй, и «пусто = пусто» запретило бы второе сообщение с одним лишь
-- серийным.
--
-- `upper(btrim(...))` — ровно как у номеров парка: человек набирает номер с пробелом или в другом
-- регистре, и без нормализации замок обходился бы опечаткой.
CREATE UNIQUE INDEX office_equipment_candidates_serial_pending_unique
  ON office_equipment_candidates (upper(btrim(serial_number)))
  WHERE status = 'pending' AND btrim(serial_number) <> '';

CREATE UNIQUE INDEX office_equipment_candidates_inventory_pending_unique
  ON office_equipment_candidates (upper(btrim(inventory_number)))
  WHERE status = 'pending' AND btrim(inventory_number) <> '';

-- Очередь проверки: «что ждёт дольше всех». Частичный по `pending` — решённые выпадают из него
-- навсегда, и стоимость главного вопроса модуля не растёт вместе с архивом сообщений.
CREATE INDEX office_equipment_candidates_pending_idx
  ON office_equipment_candidates (created_at)
  WHERE status = 'pending';

-- Две оси, которыми очередь сужается до области смотрящего (Р9), и «мои кандидаты» у автора.
-- Третьей, отдельской, своего индекса пока НЕ дано осознанно: очередь площадочного и отдельского
-- оператора отбирается из `…_pending_idx` — она короткая, — а полный перебор решённых сообщений
-- отдела спрашивают редко. Заводить третий индекс до первого замера значило бы платить за вставку
-- ради вопроса, которого никто не задал.
CREATE INDEX office_equipment_candidates_object_idx ON office_equipment_candidates (object_id);
CREATE INDEX office_equipment_candidates_author_idx ON office_equipment_candidates (created_by);

-- ── 2. Ссылка из заявки: своя колонка и пара строго 1:1 (Р4) ──
--
-- Своей колонкой, а не переиспользованным `office_equipment_id`: кандидат — не запись справочника, и
-- общая колонка означала бы, что предмет заявки иногда указывает не туда. `RESTRICT`: необратимый
-- purge заявки удаляет её единственного кандидата той же транзакцией явным шагом — молчаливый
-- каскад унёс бы решение проверяющего вместе с ним.
--
-- Колонка НЕОБЯЗАТЕЛЬНА и без умолчания: у подавляющего большинства заявок кандидата нет и не
-- будет. `ADD COLUMN` без умолчания таблицу не переписывает и в окне выката ничего не ломает —
-- старый код о колонке не знает и оставляет её пустой.
ALTER TABLE service_requests
  ADD COLUMN equipment_candidate_id uuid REFERENCES office_equipment_candidates (id) ON DELETE RESTRICT;

-- ПАРА СТРОГО 1:1, и держит её именно индекс, а не аккуратность маршрута: вторая ссылка на чужого
-- кандидата — это гонка, а гонку ловит база. Подшивать второе свидетельство к чужой строке нельзя и
-- по существу: два наблюдения могут различаться местом и реквизитами, а общая строка раскрыла бы
-- второму автору чужой объект через основание видимости `related`.
--
-- Частичный по непустому значению: заявок БЕЗ кандидата сколько угодно (в B-tree `NULL` не равен
-- `NULL`, так что строгий `UNIQUE` дал бы тот же результат), но условие названо явно — оно задаёт
-- размер индекса: он остаётся размером с число сообщений, а не с архивом всех заявок модуля.
--
-- `deleted_at` в условие НЕ идёт, и это решение: мягкий архив заявки связь не рвёт — пара остаётся
-- парой, — а необратимый purge удаляет заявку вместе с её единственным кандидатом. Исключи мы
-- архивные, освободившееся место занял бы второй кандидат, и восстановление заявки из архива
-- упёрлось бы в уникальность.
CREATE UNIQUE INDEX service_requests_equipment_candidate_unique
  ON service_requests (equipment_candidate_id)
  WHERE equipment_candidate_id IS NOT NULL;

-- ── 3. Третья ветвь «предмет заявки назван» (Р5) ──
--
-- ЗАМЕНОЙ ОГРАНИЧЕНИЯ, А НЕ ВТОРЫМ РЯДОМ. Два `CHECK` на одной таблице соединяются `AND`, то есть
-- прежний продолжал бы требовать «аппарат или один заказчик» и отверг бы всякую заявку с
-- кандидатом, — новое правило не расширило бы старое, а оказалось бы им запрещено. Обе команды идут
-- в одной транзакции файла, поэтому окна «предмет заявки не сторожит никто» не возникает.
--
-- СЕГОДНЯШНЕЕ ПРАВИЛО СОХРАНЕНО ДОСЛОВНО и целиком уехало под внешнюю скобку
-- `equipment_candidate_id IS NULL`: у заявок без кандидата ничего не изменилось — ни ослабления, ни
-- ужесточения. Сама скобка — не оформление, а половина правила: без неё база приняла бы сразу два
-- входных способа назвать предмет.
--
-- Первая ветвь читается так: у заявки с кандидатом площадка названа ВСЕГДА (её называет сам
-- заявитель), а аппарат при этом либо ещё не назначен (`pending`), либо уже проставлен решением
-- проверяющего. Отсюда законная асимметрия хранимой строки после подтверждения: заполнены и
-- кандидат (происхождение), и `office_equipment_id` (решённый предмет). Запрет «два входных способа
-- сразу» относится только к КОМАНДЕ СОЗДАНИЯ и держится схемой контракта; конечного состояния этот
-- `CHECK` намеренно не запрещает.
--
-- XOR объекта и отдела к ветви кандидата не применяется — тоже намеренно: заявку от лица отдела
-- заводят и на кандидата, и тогда `customer_department_id` держит заказчика, а `equipment_object_id`
-- физическое место аппарата. Иначе сотрудник отдела после отправки потерял бы собственную заявку по
-- правилу ADR 0146.
ALTER TABLE service_requests DROP CONSTRAINT service_requests_subject_check;

ALTER TABLE service_requests ADD CONSTRAINT service_requests_subject_check CHECK (
  (equipment_candidate_id IS NOT NULL AND equipment_object_id IS NOT NULL)
  OR (
    equipment_candidate_id IS NULL
    AND (
      (office_equipment_id IS NOT NULL AND equipment_object_id IS NOT NULL)
      OR (
        office_equipment_id IS NULL
        AND (equipment_object_id IS NOT NULL) <> (customer_department_id IS NOT NULL)
      )
    )
  )
);

COMMENT ON CONSTRAINT service_requests_subject_check ON service_requests IS
  'Предмет заявки назван одним из трёх способов: кандидат на проверке (тогда площадка обязательна), '
  'аппарат справочника (тогда площадка обязательна тоже) либо ни того ни другого — и тогда заказчик '
  'ровно один, объект ИЛИ отдел (ADR 0146, решение 6; план кандидатов, Р5). Внешняя скобка '
  'equipment_candidate_id IS NULL обязательна: без неё сошлись бы два входных способа сразу.';

-- ── 4. Караул: схема стала такой, как обещано ──
--
-- Страж-тест сверяет то же самое, но живёт он в репозитории, а этот блок — в накате: оператор
-- выката увидит расхождение сразу, а не через прогон тестов. Проверяется ровно обещанное:
--
--   · девять ограничений кандидата на месте и ПРОВЕРЕНЫ (`convalidated`), а не висят `NOT VALID` —
--     невалидированное ограничение сторожит будущие строки и молчит о существующих, то есть
--     выглядит выполненной работой, не будучи ею;
--   · пять индексов кандидата и уникальность ключа существуют — без них гонка двух заявителей и
--     повтор потерянного ответа не отбиваются ничем;
--   · колонка заявки появилась, осталась НЕОБЯЗАТЕЛЬНОЙ и несёт ключ в режиме `RESTRICT`;
--   · частичный уникальный индекс пары 1:1 существует;
--   · ограничение предмета ровно одно, проверено И УПОМИНАЕТ КАНДИДАТА. Последнее — единственный
--     дешёвый способ доказать, что замена состоялась: одноимённое старое ограничение прошло бы все
--     остальные проверки этого блока, ничего не зная о третьей ветви.
--
-- Чего блок НЕ доказывает, и это названо честно: что старое правило сохранено дословно. Валидация
-- `ADD CONSTRAINT` этого не доказывает тоже — она отвергла бы только ужесточение, наткнувшееся на
-- живую строку, а ослабление прошло бы молча. Доказывают его контрактный и db-тест плана (§15),
-- перебирающие обе сегодняшние ветви предмета.
DO $$
DECLARE trouble text;
BEGIN
  SELECT string_agg(msg, '; ')
    INTO trouble
    FROM (
      SELECT format('ограничений кандидата проверено %s из 9', count(*)) AS msg
        FROM pg_constraint
       WHERE conrelid = 'office_equipment_candidates'::regclass
         AND contype = 'c'
         AND convalidated
         AND conname IN ('office_equipment_candidates_status_check',
                         'office_equipment_candidates_identity_check',
                         'office_equipment_candidates_model_not_blank_check',
                         'office_equipment_candidates_location_not_blank_check',
                         'office_equipment_candidates_fingerprint_not_blank_check',
                         'office_equipment_candidates_content_version_check',
                         'office_equipment_candidates_decision_check',
                         'office_equipment_candidates_result_check',
                         'office_equipment_candidates_reason_check')
      HAVING count(*) <> 9
      UNION ALL
      SELECT format('индексов кандидата %s из 7', count(*))
        FROM pg_indexes
       WHERE tablename = 'office_equipment_candidates'
         AND indexname IN ('office_equipment_candidates_pkey',
                           'office_equipment_candidates_idempotency_unique',
                           'office_equipment_candidates_serial_pending_unique',
                           'office_equipment_candidates_inventory_pending_unique',
                           'office_equipment_candidates_pending_idx',
                           'office_equipment_candidates_object_idx',
                           'office_equipment_candidates_author_idx')
      HAVING count(*) <> 7
      UNION ALL
      SELECT 'колонка equipment_candidate_id не появилась или стала обязательной'
       WHERE NOT EXISTS (
         SELECT 1 FROM pg_attribute
          WHERE attrelid = 'service_requests'::regclass
            AND attname = 'equipment_candidate_id'
            AND NOT attnotnull
            AND NOT attisdropped)
      UNION ALL
      SELECT 'ключа кандидата у заявки нет или он не RESTRICT'
       WHERE NOT EXISTS (
         SELECT 1 FROM pg_constraint c
          WHERE c.conrelid = 'service_requests'::regclass
            AND c.contype = 'f'
            AND c.confrelid = 'office_equipment_candidates'::regclass
            AND c.confdeltype = 'r')
      UNION ALL
      SELECT 'нет уникального индекса пары «заявка — кандидат»'
       WHERE NOT EXISTS (
         SELECT 1 FROM pg_indexes
          WHERE tablename = 'service_requests'
            AND indexname = 'service_requests_equipment_candidate_unique')
      UNION ALL
      SELECT format('ограничение предмета не заменено (проверенных с кандидатом: %s)', count(*))
        FROM pg_constraint
       WHERE conrelid = 'service_requests'::regclass
         AND conname = 'service_requests_subject_check'
         AND contype = 'c'
         AND convalidated
         AND pg_get_constraintdef(oid) LIKE '%equipment_candidate_id%'
      HAVING count(*) <> 1
    ) AS bad;
  IF trouble IS NOT NULL THEN
    RAISE EXCEPTION 'Кандидаты на добавление техники легли не так, как объявлены — %', trouble;
  END IF;
END $$;
