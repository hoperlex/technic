-- Возврат заявок, которые в «Завершена» перевёл выкат, а не человек (ADR 0135).
--
-- ЧТО НЕ ТАК С ОТБОРОМ 0195. Условие перевода было отрицанием реестра «требуют разбора» (ADR 0114,
-- Р24): нет неподтверждённых и спорных талонов, нет нечитаемых файлов и мёртвых задач, нет
-- страниц с отказом, нет слепых перепроверок. Все четыре условия спрашивают про СОСТОЯНИЕ РАЗБОРА
-- и ни одно — про то, есть ли вообще приложенная бумага. Поэтому заявка, к которой талон приложен,
-- но не распознан ни один (распознавание в работу не пущено — allowlist прокси закрыт, `0195`
-- сама это оговаривает), проходила отбор как «разбирать нечего». Разбирать в ней ровно всё:
-- бумага лежит нетронутой, а заявка объявлена принятой — и заперта, потому что у завершённой
-- заявки правка талонов закрыта (`assertReviewOpen` в `routes/waste-tickets.ts`). Пусти
-- распознавание после этого — оно пришло бы в базу, где вся прошлая бумага уже принята.
--
-- ЧТО ДЕЛАЕТ ЭТА МИГРАЦИЯ. Возвращает в «Выполнена» те переведённые выкатом заявки, у которых
-- приложен хотя бы один живой файл-талон (`request_files.kind = 'ticket'`, ADR 0024) и нет ни
-- одного ПОДТВЕРЖДЁННОГО талона. «Подтверждён» и есть «разобран»: `unconfirmed` — талон, который
-- ещё смотрят, `dismissed` — «это не талон» (шапка бланка, второй кадр той же бумаги), и ни то,
-- ни другое не отвечает на вопрос «бумагу приняли?».
--
-- КОГО НЕ ТРОГАЕТ, И ЭТО ЧАСТЬ РЕШЕНИЯ:
--   * заявку без единого файла-талона — закрытую до того, как талон стал обязательным (ADR 0020),
--     либо ту, чей файл снесён насовсем: разбирать в ней действительно нечего, и её завершение
--     верно. Возвращать её значило бы вернуть в рабочий список хвост, ради удаления которого
--     вкладку «История» и заводили;
--   * заявку любого типа, кроме вывоза мусора. Распознавание ставится единственному типу
--     (`enqueueTicketRecognition`, ADR 0114 Р1): у контейнерных операций вывезенного объёма нет
--     вовсе, металлолом закрывается весовой квитанцией, и ни одна из четырёх сверок к их бумаге
--     не применима. Талон при закрытии обязателен всем пяти типам (ADR 0020), поэтому без этого
--     условия возврат забрал бы и те заявки, разбирать которые никто никогда не будет, — а с
--     правилом завершения, которое их бумагу теперь считает неразобранной, они остались бы в
--     работе навсегда;
--   * заявку с подтверждённым талоном: бумага принята человеком, разбор состоялся;
--   * заявку, завершённую человеком. Отбор смотрит на ПОСЛЕДНИЙ переход по статусу: `changed_by
--     IS NULL` пишет только `0195` (портал показывает такую строку как «Портал»). Условие
--     «последний», а не «есть такой», бережёт заявку, которую после выката откатили и завершили
--     руками, — там уже стоит решение человека.
--
-- ЧИСТАЯ БАЗА ЭТОГО НЕ ЗАМЕТИТ: переводить `0195` там было нечего, и `UPDATE` не тронет ни строки.
-- Повторный накат журнал `_migrations` не допускает, но и он ничего бы не сделал: у возвращённой
-- заявки статус уже `done`, а последний переход — в `done`.
--
-- ВЕРСИЯ КАРТОЧКИ РАСТЁТ, и это не косметика: у заявки оптимистическая блокировка, и штатный
-- переход версию двигает (`routes/waste-requests.ts`). `0195` про неё забыла — открытая у кого-то
-- вкладка сохранила бы поверх, не заметив смены статуса. `updated_by` не трогается намеренно:
-- возврат сделал не человек, и приписывать его живой учётке значило бы соврать в карточке.

WITH last_move AS (
  -- Последний переход каждой заявки. `DISTINCT ON` по времени, вторым ключом `id`: перевод
  -- выкатом проставил всем строкам один `changed_at` (одна транзакция), и без второго ключа
  -- порядок внутри такой пары был бы недетерминированным.
  SELECT DISTINCT ON (h.request_id) h.request_id, h.to_status, h.changed_by
    FROM request_status_history h
   ORDER BY h.request_id, h.changed_at DESC, h.id DESC
), reverted AS (
  UPDATE waste_requests r
     SET status = 'done', version = r.version + 1, updated_at = now()
    FROM last_move l
   WHERE l.request_id = r.id
     AND r.status = 'completed'
     AND l.to_status = 'completed'
     AND l.changed_by IS NULL
     AND r.request_type = 'waste_removal'
     AND EXISTS (
       SELECT 1 FROM request_files rf
         JOIN files f ON f.id = rf.file_id
        WHERE rf.request_id = r.id AND rf.kind = 'ticket' AND f.status = 'active')
     AND NOT EXISTS (
       SELECT 1 FROM waste_tickets t
        WHERE t.request_id = r.id AND t.status = 'confirmed')
  RETURNING r.id
)
-- Возврат попадает в историю тем же порядком, что и перевод: строкой без автора, которую портал
-- подпишет «Портал». Запись перевода при этом остаётся на месте — история заявки ничего не
-- стирает, и порядок событий читается целиком.
INSERT INTO request_status_history (request_id, from_status, to_status, changed_by, comment)
SELECT id, 'completed', 'done', NULL, 'Возврат выкатом: талон приложен, но не разобран'
  FROM reverted;
