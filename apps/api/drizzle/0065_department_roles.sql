-- Роли отдела (ADR 0040): «Отдел» — сотрудник офисного подразделения, «Руководитель отдела» —
-- тот, кто визирует его заявки.
--
-- Только значения enum, отдельным файлом: добавленное значение нельзя использовать в той же
-- транзакции, которая его добавила, — а следующая миграция заводит справочник отделов и связь
-- учёток с ним. Тем же приёмом заводились 'rukstroy' (0049) и 'observer' (0054).
--
-- Порядок значений имеет смысл только для сортировки по колонке роли: отдел ставим рядом с
-- объектными ролями, потому что это такой же заказчик, только со стороны офиса.
ALTER TYPE role ADD VALUE 'department' AFTER 'rukstroy';
ALTER TYPE role ADD VALUE 'department_head' AFTER 'department';
