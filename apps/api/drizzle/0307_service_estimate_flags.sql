-- Два рубильника волны «объём работ документом и освобождение от подписи»: ключи
-- `service_estimate_document_mode` и `service_estimate_exemption` в перечне таблицы `feature_flags`
-- и их ВЫКЛЮЧЕННЫЕ строки (план `docs/office-equipment-on-site-and-invoice-estimate-plan.md`,
-- редакция 5, Р2, Р3 и §7 — шаги 3 и 4 порядка выката; этап Э2).
--
-- ОТКУДА НОМЕР. `ls apps/api/drizzle` непосредственно перед созданием файла (11.09.2026): последним
-- в дереве стоит `0306_service_request_estimate_formats.sql` — схема этой же волны, соседний файл
-- того же этапа, — свободен `0307`, он и взят. Номер берётся в момент создания КАЖДОГО файла:
-- параллельные потоки занимают номера незакоммиченными файлами, и снимок свободного номера живёт
-- часы (чем это кончается, рассказывают 0261 и 0262).
--
-- ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ ОТ 0306. Схема волны и её рубильники разного возраста: схема едет один
-- раз, а ключи переключаются `UPDATE`-ом по живой базе и снимаются третьим выпуском (приём
-- соседа — 0293, 0297, 0300). Сложенные в один файл, они дали бы одну строку журнала наката на две
-- разные работы — и откат схемы унёс бы перечень ключей вместе с ней.
--
-- ЗАЧЕМ СТРОКИ ВООБЩЕ, ЕСЛИ ЧИТАТЕЛЬ И ТАК FAIL-CLOSED. Читатель (`hasFeature` в контрактах,
-- `isFeatureEnabled` на сервере) трактует «нет строки» и «выключено» одинаково — это и позволяет
-- выпуску A ехать закрытым. Но ВКЛЮЧАТЬ выпуском обязаны СУЩЕСТВУЮЩУЮ строку, а не догадку о ней:
-- `UPDATE feature_flags SET is_enabled = true WHERE key = '…'` по отсутствующей строке обновит ноль
-- рядов и промолчит, и оператор решит, что включил, — то самое «выключение выглядит включением», от
-- которого перечень и закрыт. Шаги 3 и 4 §7 плана без этих двух строк выполнять не на чем.
--
-- ПОЧЕМУ ПРАВКА `CHECK`, А НЕ ПРОСТО `INSERT`. Перечень ключей у таблицы закрыт (0293) и обязан
-- совпадать с реестром `FEATURE_FLAGS` в `packages/contracts/src/feature-flags.ts` и с `check` в
-- `apps/api/src/db/schema.ts`. Без правки ограничения новые ключи физически невставимы: перечень
-- отбил бы `INSERT` ниже, и волна осталась бы невключаемой при полностью выкаченном коде. Все три
-- носителя перечня правятся ТОЙ ЖЕ волной — расхождение поймает караул в конце файла, но ловить его
-- лучше на ревью.
--
-- `DROP CONSTRAINT` + `ADD CONSTRAINT`, а не `ALTER … ALTER CONSTRAINT`: изменить условие `CHECK` на
-- месте PostgreSQL не умеет. Пересборка проверяет существующие строки — их две, и обе новому
-- перечню удовлетворяют (он только расширяется). `NOT VALID` не нужен и был бы вреден: таблица
-- размером в перечень рубильников, а непроверенное ограничение — та самая тихая дыра, ради закрытия
-- которой `CHECK` и стоит.
--
-- ПОЧЕМУ КЛЮЧЕЙ ДВА, А НЕ ОДИН (решение плана, §7). Подача счётом полезна и при обычном
-- согласовании: исполнитель прикладывает документ, а подпись ставит «Ведение» руками. Обход подписи —
-- отдельное продуктовое решение, у которого нет ни лимита, ни политики по контрагенту (Р13), и цена
-- ошибки у него денежная. Слитый ключ открывал бы автоподпись тем же `UPDATE`, которым включают
-- документную подачу, а выключение документной подачи гасило бы работающий сценарий с человеческой
-- подписью.
--
-- ПОРЯДОК ВКЛЮЧЕНИЯ ОБЯЗАТЕЛЕН И ЗАПИСАН В §7 ПЛАНА: выпуск читателей (схема 0306 и код, читающий
-- роль файла и формат ревизии) → убедиться, что старых узлов не осталось → `UPDATE` ключа
-- документного режима → `UPDATE` ключа освобождения. Смысл второй стрелки не в аккуратности: старый
-- сервер и старый воркер роли файла не читают, и для них ЛЮБОЙ `invoice` снова закрывающая бумага —
-- включённая раньше времени документная подача обошла бы планку акта.
--
-- ОКНО ВЫКАТА. Правка переживает работающий портал: старый код таблицу не читает вовсе, новый читает
-- её без кэша (`apps/api/src/services/feature-flags.ts`) и на выключенном ключе ведёт себя ровно как
-- сегодня. Строки заводятся ВЫКЛЮЧЕННЫМИ — в этом весь смысл их появления в выпуске A.
--
-- ОБРАТИМОСТЬ. Схема меняется одним ограничением, данные — двумя строками; откат — вернуть прежний
-- `CHECK` и удалить строки, и делать его в одиночку безопасно (читатель отвечает «выключено» и на
-- отсутствие строки). Аварийное выключение уже включённого рубильника откатом ЭТОГО файла не
-- делается: `UPDATE … = false` по живой базе быстрее и не трогает журнал наката.

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 0. Снимок рубильников ДО правки — ради утверждения «чужих ключей не трогали».
--
-- Приём 0297 и 0300: снимком, а не константой, потому что значения прочих ключей на проде, в деве и
-- на восстановленной из копии базе разные, а утверждение одно. `ON COMMIT DROP` — таблица живёт до
-- конца транзакции миграции и в базе не остаётся.
--
-- Снимок берётся ЦЕЛИКОМ, вместе со своими будущими ключами, и это не избыточность: по нему караул
-- отличает первый накат (строки не было — обязана появиться выключенной) от повторного на базе, где
-- рубильник уже открыт (строка была — значение обязано остаться нетронутым). Без снимка эти два
-- случая неразличимы.

CREATE TEMP TABLE feature_flags_0307 ON COMMIT DROP AS
SELECT key, is_enabled
FROM feature_flags;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 1. Перечень ключей: их становится четыре.

ALTER TABLE feature_flags DROP CONSTRAINT feature_flags_key_check;

ALTER TABLE feature_flags ADD CONSTRAINT feature_flags_key_check
  CHECK (key IN (
    'office_equipment_candidate_intake',
    'service_request_executor_scope',
    'service_estimate_document_mode',
    'service_estimate_exemption'
  ));

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 2. Строки рубильников — обе выключенные.
--
-- `ON CONFLICT DO NOTHING` делает шаг идемпотентным и — важнее — не гасит уже ВКЛЮЧЁННЫЙ ключ:
-- повторный накат на базу, где рубильник открыт (восстановление из копии старше дня включения плюс
-- добежавший накат), не имеет права закрыть работающую волну молча.

INSERT INTO feature_flags (key, is_enabled) VALUES
  ('service_estimate_document_mode', false),
  ('service_estimate_exemption', false)
ON CONFLICT (key) DO NOTHING;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 3. Караул: перечень принял четыре ключа, строки есть и выключены, чужие ключи не тронуты.
--
-- Перечень проверяется не текстом ограничения, а ПОВЕДЕНИЕМ — попыткой вставить заведомо чужой ключ
-- во временной точке сохранения. Сравнение исходника `CHECK` строкой сломалось бы от лишнего пробела
-- и ничего бы не доказало; попытка вставки доказывает ровно то, ради чего ограничение стоит:
-- посторонний ключ в таблицу не попадает. Обратная половина — попытка вставить СВОИ ключи — не нужна:
-- их вставил раздел 2, и отсутствие строки караул ловит ниже.

DO $$
DECLARE trouble text;
BEGIN
  BEGIN
    INSERT INTO feature_flags (key) VALUES ('__guard_0307_not_a_flag__');
    RAISE EXCEPTION 'перечень ключей рубильников не запирает таблицу: посторонний ключ вставился';
  EXCEPTION
    WHEN check_violation THEN NULL;
  END;

  SELECT string_agg(msg, '; ')
    INTO trouble
    FROM (
      SELECT format('строки рубильника «%s» нет — включать будет нечего', k.key) AS msg
        FROM (VALUES
          ('service_estimate_document_mode'),
          ('service_estimate_exemption')
        ) AS k (key)
       WHERE NOT EXISTS (SELECT 1 FROM feature_flags f WHERE f.key = k.key)
      UNION ALL
      -- Только для ПЕРВОГО наката: строки в снимке не было, значит завела её эта миграция — и
      -- завести обязана выключенной. На базе, где рубильник уже открыт (восстановленная копия,
      -- добежавший накат), утверждение другое — оно строкой ниже.
      SELECT format('рубильник «%s» заведён ВКЛЮЧЁННЫМ — выпуск A обязан ехать закрытым', f.key)
        FROM feature_flags f
       WHERE f.key IN ('service_estimate_document_mode', 'service_estimate_exemption')
         AND f.is_enabled
         AND NOT EXISTS (SELECT 1 FROM feature_flags_0307 s WHERE s.key = f.key)
      UNION ALL
      -- Ни один ключ, БЫВШИЙ в таблице до наката, значения не меняет — включая свои собственные:
      -- повторный накат не имеет права ни погасить работающую волну, ни включить погашенную.
      SELECT format('ключ «%s» изменился: было %s, стало %s — миграция трогала живой рубильник',
                    s.key, s.is_enabled, f.is_enabled)
        FROM feature_flags_0307 s
        JOIN feature_flags f ON f.key = s.key
       WHERE f.is_enabled IS DISTINCT FROM s.is_enabled
      UNION ALL
      SELECT format('ключ «%s» исчез из таблицы', s.key)
        FROM feature_flags_0307 s
       WHERE NOT EXISTS (SELECT 1 FROM feature_flags f WHERE f.key = s.key)
    ) AS bad;
  IF trouble IS NOT NULL THEN
    RAISE EXCEPTION 'Рубильники волны освобождения заведены не так, как объявлены — %', trouble;
  END IF;
END $$;
