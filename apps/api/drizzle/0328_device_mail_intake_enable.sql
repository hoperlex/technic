-- Открытие приёма писем от аппаратов: рубильник `device_mail_intake` включается для пилота.
--
-- Решения — docs/adr/0197-device-mail-telemetry.md (сам приём) и
-- docs/adr/0200-device-mail-identity-ui.md (ключи и правила). Строку завела выключенной миграция
-- 0317, и выключена она была не из осторожности: код приезжал раньше ящика, а принимать письма без
-- настроенного контура значит копить строки «письмо сдано под чужим ящиком».
--
-- ЧТО ИЗМЕНИЛОСЬ К ЭТОМУ ДНЮ. Ящик настроен: общий ящик проекта плюс отдельная папка MFP, куда
-- правило почтовой службы складывает письма аппаратов (docs/guide-device-mail.md, §1). Доступ по
-- IMAP проверен, путь к папке спрошен у самого сервера. Портал читает ТОЛЬКО эту папку — входящие
-- ящика приёмник не трогает ни одним письмом.
--
-- ОТКУДА НОМЕР. Снимок ls apps/api/drizzle 21.09.2026: последней в дереве стоит
-- 0327_releases_department_special_equipment.sql, файлов 0328 нет ни в одной ветке.
--
-- ЧТО НАЧНЁТСЯ ПОСЛЕ НАКАТА. Приёмник перестаёт получать паузу и начинает сдавать письма: сырьё
-- ложится в хранилище на тридцать дней, строка — в очередь «Письма устройств», курсор ящика едет
-- вперёд, письма в папке помечаются прочитанными. Перезапуск не нужен — рубильник читается точечно
-- на каждое письмо.
--
-- ПИСЬМА ПИЛОТА ПРИДУТ НЕ ОТ АППАРАТА, и это ожидаемый ход, а не беда. Профиль такого письма не
-- узнает, и оно ляжет со статусом «Формат не распознан» — законный исход по ADR 0197: из этой
-- очереди и берут образцы для следующего профиля. Ошибкой было бы обратное — молча выбросить
-- письмо, которого мы не поняли.
--
-- ОТБОР ОТПРАВИТЕЛЕЙ НЕ ВКЛЮЧАЕТСЯ ЭТОЙ МИГРАЦИЕЙ. DEVICE_MAIL_ALLOWED_SENDERS живёт в prod.env и
-- на пилоте пуст намеренно: письма идут со стороннего адреса, и список, заполненный заранее,
-- закрыл бы ровно ту проверку, ради которой приём и открывают. Заполнять его — после пилота,
-- адресами настоящих аппаратов.
--
-- ОБРАТИМОСТЬ. Схема не меняется, трогается одна строка одной таблицы. Закрыть приём обратно —
-- UPDATE feature_flags SET is_enabled = false WHERE key = 'device_mail_intake', и выката это не
-- требует. Письма при этом остаются в папке непрочитанными и дождутся следующего включения: портал
-- не помечает письмо, пока не принял его.

UPDATE feature_flags
   SET is_enabled = true,
       updated_at = now()
 WHERE key = 'device_mail_intake'
   AND is_enabled = false;

-- Караул: рубильник включён, и строка у него есть.
--
-- Проверяется РЕЗУЛЬТАТ, а не число обновлённых рядов: повторный накат на уже открытой базе
-- обновит ноль строк и обязан пройти. А вот отсутствие строки — молчаливый провал, ради которого
-- этот блок и стоит: `UPDATE` по несуществующему ключу обновляет ноль рядов и не жалуется, и
-- оператор ушёл бы с уверенностью, что приём открыт, тогда как портал продолжал бы молчать
-- fail-closed.

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM feature_flags WHERE key = 'device_mail_intake' AND is_enabled
  ) THEN
    RAISE EXCEPTION
      'Приём писем от аппаратов не открылся: строки рубильника device_mail_intake нет или она выключена (миграция 0317 не накатана?)';
  END IF;
END $$;
