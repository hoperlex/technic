-- Вариант A политики модели выводит попытки из кэша целиком (ADR 0114, Р7).
--
-- `TICKET_OCR_MODEL=proxy` означает «слаг выбирает оператор прокси»: за одной и той же строкой
-- `model = 'proxy'` в разное время стоит разная модель. Кэш попыток на таком ключе склеил бы
-- ответы разных моделей, а метрики качества, привязанные к модели, стали бы выдумкой — поэтому
-- воркер такие попытки в кэше НЕ ищет.
--
-- Но одного лишь «не искать» мало: частичный уникальный индекс кэша не давал записать вторую
-- успешную попытку с тем же ключом, и второй проход по той же странице падал на нарушении
-- уникальности. То есть выключенный на чтение кэш оставался включённым на запись — и вариант A не
-- работал вовсе.
--
-- Условие `model <> 'proxy'` и есть выражение решения: попытки варианта A не участвуют в кэше ни
-- одной стороной. Значение сравнивается со строкой, а не с перечислением, потому что это ЗАКАЗ, а
-- не справочник: `proxy` — заглушка «выбирает оператор», всё остальное — слаги каталога, которых
-- портал не перечисляет (`PROXY_CHOOSES_MODEL` в `engine/keys.ts`).
--
-- Дедупа прокси это не касается: `X-Idempotency-Key` у непринудительного прохода остаётся
-- стабильным, и повтор задачи после разрыва сети по-прежнему схлопывается оператором, а не
-- оплачивается второй раз.
DROP INDEX IF EXISTS waste_ticket_recognition_attempts_cache_unique;

CREATE UNIQUE INDEX waste_ticket_recognition_attempts_cache_unique
  ON waste_ticket_recognition_attempts (
    page_sha256, engine, model, prompt_version, preprocessing_version
  )
  WHERE status = 'done' AND NOT forced AND model <> 'proxy';
