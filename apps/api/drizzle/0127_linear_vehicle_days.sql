-- Линейная техника: тип, который вечером возвращается на базу.
-- План — `docs/linear-vehicle-type-plan.md`, §3.
--
-- До этой миграции заказ техники на объект был неделей стояния машины на площадке, и обе половины
-- этого утверждения записаны в схеме. Первая — 0087: недельный лист ЭСМ-2 с ключом «заявка +
-- неделя» (ADR 0060), который портал выписывает сам на каждую неделю срока, потому что документ у
-- стоящей на объекте машины ровно один на неделю. Вторая — 0072: состав рейса с
-- `UNIQUE (request_id)` под правилом «в рейс ходят только грузоперевозки» (ADR 0050), из-за
-- которого заказ на объект в маршрут не попадал вовсе — ехать с площадки было некуда.
--
-- Линейная техника ломает обе половины сразу. Она ночует в гараже, за день объезжает несколько
-- площадок и вечером уходит домой: недели стояния у неё нет и выписывать ЭСМ-2 наперёд не за что,
-- а документ её дня — тот же 4-П, что у грузового рейса. Значит заказ такого типа ведётся днями:
-- каждый день срока — отдельный выезд, который кладут в маршрут дня, и разные дни одной заявки
-- законно закрываются разными экземплярами техники.
--
-- Отсюда всё, что делает миграция, — три новых факта и ни одной перезаписи: у типа есть признак,
-- у строки состава рейса бывает день, а у недельного листа бывает соседний по той же заявке — на
-- другой машине. `boolean NOT NULL DEFAULT false` и `date NULL` PostgreSQL 16/17 добавляет
-- метаданными, таблицы не переписываются.
--
-- Обратимость. Пока признак не проставлен ни одному типу, схема после миграции ведёт себя ровно
-- как до неё: `work_date` у всех строк NULL, два частичных индекса вместе равны снятому UNIQUE,
-- индекс по листам строже не стал. Поэтому миграция выкатывается отдельным релизом раньше кода, а
-- откат кода (`deploy-auto --previous`) отката схемы не требует. Обратной миграции репозиторий не
-- держит (`migrate.ts` только накатывает) — до неё признак снимается с типов из портала.

-- 1. Признак типа.
--
-- Колонкой у типа, а не у машины: как ведётся заявка, решает ЗАКАЗ — какую технику просили, — а не
-- то, какую единицу под него потом нашли. Тип известен с подачи заявки, назначенная машина
-- появляется только при переводе в работу, и до этого момента заказ уже обязан знать, выписывать
-- ему ЭСМ-2 или нет. Соседний `waybill_form_code` (0094, ADR 0065) лежит здесь же и по той же
-- причине: документооборот заявки задаёт справочник.
--
-- Снимка признака в самой заявке нет намеренно. Тип заявки неизменяем под назначенной машиной
-- (ADR 0028 §9), поэтому справочник и есть то место, где на этот вопрос отвечают; копия
-- потребовала бы каскада из справочника и превращала бы переключение признака в перезапись
-- истории. Плата известна: смена `is_linear` у типа с живыми заявками в работе поменяла бы их
-- режим на ходу. Запрещает это сервер (422 с числом таких заявок), а не схема — «в работе» есть
-- состояние заявки, и ключом в справочнике его не выразить.
--
-- Умолчание false: поведение всех заведённых типов не меняется, и накатить миграцию можно раньше
-- кода, который признак читает.
ALTER TABLE vehicle_types
  ADD COLUMN is_linear boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN vehicle_types.is_linear IS
  'Линейная техника: вечером возвращается на базу и за день работает на нескольких объектах. '
  'Заказ такого типа на объект ведётся по дням — 4-П на каждый день, ЭСМ-2 только по требованию.';

-- 2. Цель составного ключа: рейс отвечает за свой день.
--
-- Ниже строка состава хранит день, и он обязан совпадать с днём рейса, в котором стоит. Держать
-- это сервисом нельзя: рейс переносят на другую дату отдельным действием, и день переезжает
-- вместе с заявками (ADR 0082) — код, забывший переписать `work_date`, оставил бы день вчерашним
-- молча, а обнаружилось бы это уже напечатанным листом. Составной FK делает совпадение
-- физическим — тем же приёмом, каким строка недельной заявки держит неделю шапки (0107), а
-- назначение — заказанный тип заявки (0083).
--
-- Индекс под этим ограничением дублирует первичный ключ по `id`, и иначе нельзя: PostgreSQL
-- требует, чтобы цель составного FK была уникальна именно этим набором колонок. Цена — один
-- индекс на таблице, которая растёт по рейсу в день.
ALTER TABLE vehicle_routes
  ADD CONSTRAINT vehicle_routes_id_date_unique UNIQUE (id, route_date);

-- 3. День в составе рейса.
--
-- Отдельной таблицы «дни заявки» нет и не заводится: день линейного заказа существует ровно
-- постольку, поскольку существует срок заявки (`date_from..date_to`), — тем же способом, каким
-- уже выводятся дни смен (0086, там причина записана в комментарии к таблице: заготовки на весь
-- период пришлось бы синхронизировать с правкой срока, досрочным завершением и откатом в
-- «Новую»). Материализуется не день, а факт «этот день поставлен в такой-то рейс», и ложится он в
-- уже существующий состав: строка задания рейса осталась тем же объектом, что и была, просто
-- теперь отвечает ещё и на вопрос «чей это день».
--
-- Второй таблицей это было бы хуже ровно тем, что у рейса стало бы два источника состава: позиция
-- строки задания сквозная на весь бланк (1..7 у 4-П, ADR 0068), и её уникальность, ёмкость и
-- снимок листа пришлось бы собирать двумя запросами вместо одного.
--
-- NULL — грузоперевозка, как было: день несёт сам рейс, и заявка стоит ровно в одном рейсе.
-- Заполнен — день линейного заказа: заявка стоит в стольких рейсах, сколько дней распланировано,
-- но в каждый день — ровно в одном (п. 4).
ALTER TABLE vehicle_route_requests
  ADD COLUMN work_date date;

COMMENT ON COLUMN vehicle_route_requests.work_date IS
  'День линейного заказа, ради которого строка стоит в рейсе; NULL — грузоперевозка (день несёт рейс).';

-- MATCH SIMPLE — умолчание PostgreSQL: при NULL хотя бы в одной колонке составной ключ не
-- проверяется вовсе. Это ровно то, что нужно грузовым строкам, у которых дня нет и быть не
-- должно; тем же свойством пользуется nullable-ключ заказанного типа в назначении (0083).
--
-- ON UPDATE CASCADE — перенос рейса на другую дату (ADR 0082) тянет день строки за собой, и
-- забыть об этом коду негде. Каскад при этом может упереться в частичный UNIQUE из п. 4 — если у
-- заявки на новой дате уже стоит другой рейс, — поэтому переносимость проверяет сервер заранее и
-- отвечает словами, а не 23505 из глубины транзакции.
--
-- ON DELETE CASCADE повторяет каскад существующего FK по `route_id` (0072): удалённый рейс уносит
-- свой состав, и два ключа к одному родителю обязаны быть согласованы — иначе RESTRICT одного из
-- них сделал бы удаление рейса невозможным.
ALTER TABLE vehicle_route_requests
  ADD CONSTRAINT vehicle_route_requests_route_date_fk
    FOREIGN KEY (route_id, work_date) REFERENCES vehicle_routes (id, route_date)
    ON UPDATE CASCADE ON DELETE CASCADE;

-- 4. Уникальность вместо прежней.
--
-- «Заявка ровно в одном рейсе» (0072) остаётся правдой для грузоперевозки и перестаёт быть ею для
-- линейного заказа: там то же правило звучит как «в один день — ровно один рейс». Два частичных
-- индекса вместо одного ограничения: третьего состояния у строки нет (день либо есть, либо его
-- нет), и оба правила читаются глазом. Одним выражением это записалось бы через подставное
-- значение в `COALESCE`, по которому смысл пришлось бы восстанавливать.
--
-- Имя прежнего ограничения переиспользуется намеренно: правило не сменилось, у него сузилась
-- область действия, — и вставка, упавшая на нём, обязана называться в логе так же, как называлась
-- раньше. Уникальным ОГРАНИЧЕНИЕМ первый индекс при этом быть перестал — частичных ограничений в
-- PostgreSQL нет, — но разбору 23505 это безразлично: имя приходит тем же полем `constraint`,
-- каким его читают `asEmailConflict` и разбор конфликтов справочников.
ALTER TABLE vehicle_route_requests
  DROP CONSTRAINT vehicle_route_requests_request_unique;

CREATE UNIQUE INDEX vehicle_route_requests_request_unique
  ON vehicle_route_requests (request_id)
  WHERE work_date IS NULL;

-- Он же отвечает на вопрос «какие дни этой заявки распланированы», которым карточка заявки рисует
-- таблицу дней, — отдельного индекса под чтение заводить не потребовалось.
CREATE UNIQUE INDEX vehicle_route_requests_request_day_unique
  ON vehicle_route_requests (request_id, work_date)
  WHERE work_date IS NOT NULL;

-- 5. Неделя ЭСМ-2 — на пару «заявка + машина», а не на одну заявку.
--
-- «Одна неделя — один действующий лист» (0087, ADR 0060) молчаливо опиралось на то, что машина у
-- заявки одна: назначение (`vehicle_request_assignments`) физически одномашинное — `request_id` в
-- первичном ключе. У линейного заказа это перестаёт быть правдой: неделю на объекте закрывают две
-- разные единицы, у каждой свои моточасы и свой машинист, и один лист на двоих был бы документом,
-- который нечем заполнить. Там, где машина по-прежнему одна, новое правило совпадает со старым —
-- тройка вырождается в пару, и ни один уже выписанный лист не становится лишним.
--
-- Аннулированные по-прежнему не мешают: испорченный бланк списан, и сверка выписывает на ту же
-- неделю новый номер. `vehicle_id` у листа NOT NULL, поэтому дыры «NULL не равен NULL» в новом
-- условии не появляется.
DROP INDEX waybills_source_request_period_unique;

CREATE UNIQUE INDEX waybills_source_request_period_unique
  ON waybills (source_request_id, period_from, vehicle_id)
  WHERE status <> 'cancelled';
