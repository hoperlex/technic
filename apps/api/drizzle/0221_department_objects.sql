-- Площадки отдела множеством: связь «отдел ↔ объект» вместо колонки
-- `departments.construction_object_id` (план `docs/department-objects-set-plan.md`, этап 1;
-- решения Р1, Р2, Р9). ADR 0144 развивает ADR 0062 и отменяет его решение 1 в части
-- кардинальности — всё остальное в нём остаётся в силе.
--
-- ЗАЧЕМ ТАБЛИЦА, А НЕ КОЛОНКА. ADR 0062 прочитал связь как «у объекта отделов несколько, у отдела
-- объект — один», и пока площадка была у снабжения одна, это было правдой. Гарантийный отдел ломает
-- её предметно: его сотрудники заказывают вывоз мусора с НЕСКОЛЬКИХ гарантийных объектов, а список
-- меняется — редко, но меняется, и константой не заводится. Прав на модуль у роли отдела хватает
-- целиком; не хватает ровно области, а область приходит из этой одной колонки
-- (`departmentObjectIdsExpr`). Вторая колонка «ещё одна площадка» отвечала бы на вопрос ровно до
-- третьего объекта, а массив внутри `departments` лишил бы привязку собственных реквизитов: набор
-- правят люди — из карточки отдела и обменом файлами, — и у каждой строки есть свои `created_by` и
-- `created_at`, как у объектов учётки (`0063`, ADR 0039). Отсюда и образец: таблица устроена как
-- `user_construction_objects` — вопрос у них один и тот же, только с разных осей.

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 1. Таблица связи.
--
-- ВНЕШНИЕ КЛЮЧИ РАЗНЫЕ, И ЭТО НАМЕРЕННО (Р2).
--
-- Отдел — `CASCADE`: набор площадок не самостоятельная сущность, а часть карточки отдела; удалили
-- отдел — защищать в его наборе нечего, и `RESTRICT` здесь означал бы «отдел не удаляется, пока
-- кто-то не почистит невидимую таблицу».
--
-- Объект — `RESTRICT`, и это сохранение поведения ADR 0062, а не копия `0063` (там у учётки стоит
-- `CASCADE`). Разница в цене ошибки: каскад по объекту молча снял бы площадку у ЦЕЛОГО отдела —
-- мимо карточки, в которой её задавали, и мимо человека, который об этом узнал бы по пропавшим
-- заявкам. Удаление объекта насовсем (ADR 0060) на такую связь отказывает СООБЩЕНИЕМ — счёт по
-- этой таблице заводит этап 4 плана, — а `RESTRICT` стоит за ним последней преградой: сообщение
-- живёт в коде и может отстать от схемы, ограничение — нет.
CREATE TABLE department_construction_objects (
  department_id uuid NOT NULL REFERENCES departments (id) ON DELETE CASCADE,
  construction_object_id uuid NOT NULL REFERENCES construction_objects (id) ON DELETE RESTRICT,
  -- Кто выдал площадку отделу. Пусто у переноса (см. ниже) и у записи, сделанной триггером
  -- совместимости: там автора нет — есть код предыдущей версии, писавший колонку.
  created_by uuid REFERENCES users (id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  -- Пара и есть запись: дважды выдать отделу одну площадку нельзя. Дубли UUID в приходящем наборе
  -- упрутся сюда, поэтому канонизация набора лежит на единственном писателе (этап 2, шаг 1).
  PRIMARY KEY (department_id, construction_object_id)
);

-- Обратная сторона связи («какие отделы у этой площадки») — отдельным индексом: PK покрывает
-- только проход от отдела, а от объекта идут карточка объекта и проверка перед удалением
-- насовсем. Индекс полный, а не частичный: строк без объекта здесь не бывает по определению —
-- частичность прежнего `departments_construction_object_idx` держалась на `NULL`, которого в
-- таблице связи нет.
CREATE INDEX department_construction_objects_object_idx
  ON department_construction_objects (construction_object_id);

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 2. Перенос: одна площадка отдела становится набором из одной площадки.
--
-- `created_by` пуст — привязку завёл не человек, а миграция, и приписывать её администратору было
-- бы неправдой в аудите (тот же довод и то же решение, что в `0063`).
INSERT INTO department_construction_objects (department_id, construction_object_id)
SELECT id, construction_object_id
FROM departments
WHERE construction_object_id IS NOT NULL;

COMMENT ON TABLE department_construction_objects IS
  'Площадки отдела (ADR 0144, развивает ADR 0062): набор объектов, на которых сотрудники отдела '
  'работают наравне со штабом — заказывают вывоз мусора. Источник области departmentObjectIds; '
  'пустой набор — рабочее состояние, отдел без площадок объектных прав не даёт вовсе. '
  'Единственный писатель — replaceDepartmentObjects: он держит порог, разницу для аудита, '
  'auth_version и отзыв сессий одной транзакцией.';

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 3. Колонка остаётся — совместимой проекцией набора (Р9).
COMMENT ON COLUMN departments.construction_object_id IS
  'СОВМЕСТИМАЯ ПРОЕКЦИЯ набора площадок (ADR 0144, Р9), снимается релизом N+1. Источник области — '
  'department_construction_objects; здесь лежит единственная площадка набора, если она одна, и '
  'NULL, если площадок ноль или больше одной. Прямое направление (колонка → набор) держит триггер '
  'department_object_sync_trg, обратное (набор → колонка) — replaceDepartmentObjects. Не читать и '
  'не писать новым кодом.';

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 4. Триггер совместимости: старый код продолжает писать колонку, и это не должно теряться.
--
-- Штатный выкат накатывает миграции ДО перезапуска приложения (`docs/schema-cutover-protocol.md`,
-- §1), то есть какое-то время предыдущая версия кода работает на новой схеме и о таблице связи
-- ничего не знает. Всё, что она делает с площадкой отдела, — это `UPDATE departments SET
-- construction_object_id = …` из карточки справочника и из обмена файлами. Без триггера такая
-- правка в окне выката легла бы в колонку, которую новый код уже не читает, и пропала бы молча:
-- площадку назначили, а заявки на неё не заводятся. То же и при откате кода назад.
--
-- Триггер закрывает прямое направление (колонка → набор). Обратное (набор → колонка) держит
-- `replaceDepartmentObjects` (этап 2): он пишет проекцию в колонку ПЕРВЫМ шагом, а набор — вторым,
-- потому что свою же запись колонки триггер отразит в таблицу, и полный набор обязан лечь после
-- него. Оба направления вместе и делают колонку проекцией, а не замороженным полем.
--
-- ПОЧЕМУ ОТСЕЧКА ВНУТРИ ФУНКЦИИ, А НЕ В `WHEN`. Естественная форма
-- `WHEN (NEW.construction_object_id IS DISTINCT FROM OLD.construction_object_id)` не создаётся
-- вовсе: PostgreSQL отвечает «INSERT trigger's WHEN condition cannot reference OLD values» —
-- у INSERT-триггера `OLD` в `WHEN` недоступен (проверено на dev-базе PG 16; на проде PG 17
-- ограничение то же). Развести на два триггера — INSERT без `WHEN` и UPDATE с ним — можно, но
-- тогда одно правило живёт в двух местах, и правка одного из них молча разойдётся со вторым.
--
-- А сама отсечка нужна не ради экономии двух запросов: `UPDATE OF construction_object_id`
-- срабатывает от одного УПОМИНАНИЯ колонки в `SET`, а не от смены значения. Без неё любая правка,
-- переписавшая колонку тем же самым `NULL` (правка названия отдела старой формой, импорт),
-- снесла бы набор из нескольких площадок, у которого колонка-проекция как раз и равна `NULL`.
CREATE FUNCTION department_object_sync() RETURNS trigger
  LANGUAGE plpgsql SECURITY INVOKER SET search_path = public, pg_temp AS $$
BEGIN
  IF TG_OP = 'UPDATE'
     AND NEW.construction_object_id IS NOT DISTINCT FROM OLD.construction_object_id THEN
    RETURN NULL;
  END IF;
  -- Замена, а не дополнение: намерение писавшего колонку — «площадка у отдела вот эта», и в
  -- момент такой записи оно и есть источник правды. Набор из нескольких схлопывается в одну —
  -- иначе старая версия кода показывала бы одно, а область считалась бы по другому.
  DELETE FROM department_construction_objects WHERE department_id = NEW.id;
  IF NEW.construction_object_id IS NOT NULL THEN
    INSERT INTO department_construction_objects (department_id, construction_object_id)
    VALUES (NEW.id, NEW.construction_object_id);
  END IF;
  RETURN NULL;
END $$;

COMMENT ON FUNCTION department_object_sync() IS
  'Зеркалит departments.construction_object_id в набор department_construction_objects на время '
  'переходного релиза (ADR 0144, Р9): старый код пишет колонку и о таблице не знает. Снимается '
  'вместе с колонкой и триггером department_object_sync_trg.';

-- `AFTER`, а не `BEFORE`: функция правит ДРУГУЮ таблицу, а не строку-источник, и делать это до
-- того, как сама правка отдела состоялась, незачем. `RETURN NULL` у AFTER-триггера ничего не
-- отменяет — возвращаемое значение там просто игнорируется.
CREATE TRIGGER department_object_sync_trg
  AFTER INSERT OR UPDATE OF construction_object_id ON departments
  FOR EACH ROW EXECUTE FUNCTION department_object_sync();

COMMENT ON TRIGGER department_object_sync_trg ON departments IS
  'AFTER INSERT OR UPDATE OF construction_object_id: исполняет department_object_sync(). Живёт '
  'один релиз — до снятия колонки-проекции (этап 9 плана площадок отдела).';

-- `ENABLE ALWAYS` здесь НЕ ставится, в отличие от барьеров `0167`, `0171`, `0178`, `0186`, `0187`,
-- `0216`: те держат инвариант и обязаны срабатывать при любой записи, откуда бы она ни пришла.
-- Этот — зеркало записи ПРИЛОЖЕНИЯ на время переходного релиза; на реплике-приёмнике обе таблицы
-- приезжают потоком уже согласованными, и зеркалирование поверх него дублировало бы работу и
-- расходилось бы с источником.

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 5. Почему колонка и её частичный индекс не удаляются ЗДЕСЬ.
--
-- `DROP COLUMN` необратим: откатить код на предыдущую версию после него нельзя ничем, кроме
-- восстановления из дампа. Пока колонка на месте, эта миграция аддитивна — она ничего не удаляет и
-- не переписывает, — и обычный выкат (миграция до перезапуска, окна без записи не требуется) для
-- неё безопасен. Снятие колонки идёт СВОИМ релизом по протоколу выката
-- (`docs/schema-cutover-protocol.md`), вместе с триггером, функцией, частичным индексом
-- `departments_construction_object_idx` и обеими половинами входного/выходного алиаса в контракте
-- (этап 9, Р11). Прецедент ровно этого разделения — `due_date` в `0162`: nullable-колонка, которую
-- после работы никто не читает, ничего не стоит, а необратимый шаг едет отдельно.

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- ОБРАТИМОСТЬ. Миграция добавляет таблицу, индекс, функцию и триггер, ничего не удаляя и не
-- переписывая; исходная колонка остаётся источником, годным для чтения предыдущей версией кода.
-- Обратной миграции репозиторий не держит (`migrate.ts` только накатывает); при необходимости
-- снимается в обратном порядке: `DROP TRIGGER department_object_sync_trg ON departments`,
-- `DROP FUNCTION department_object_sync()`, `DROP TABLE department_construction_objects`.
--
-- ЧТО ДАЁТ ОТКАТ КОДА, пока колонка жива:
--   * набор из одной площадки — колонка равна ей же, предыдущая версия видит ровно ту область,
--     что и новая: расхождения нет вовсе;
--   * набор из нескольких — колонка `NULL`, и откат даёт отделу ПУСТУЮ область. Это сужение, а не
--     доступ: сотрудники временно не видят своих площадок, но ни одна снятая площадка не
--     воскресает. Обратный размен (заморозить колонку и оставить в ней старое значение) как раз и
--     воскрешал бы отобранную площадку — то есть откат возвращал бы доступ, который человек
--     сознательно снял, и заметить это было бы нечем.
--
-- ВЫКАТ. Порядок обычный: миграция, затем сервер и портал парой. Окно между накатом и перезапуском
-- безопасно в обе стороны — за него отвечает триггер: предыдущая версия пишет колонку, набор
-- едет следом сам.
