-- Контактный телефон учётной записи (ADR 0043).
--
-- Почтовых уведомлений у портала нет (ADR 0034), поэтому единственный способ связаться с
-- человеком по его заявке на регистрацию или по его учётке — позвонить. Номера не было нигде:
-- телефон в базе есть только у физлица из справочника (`persons.phone`) и у ответственного по
-- заявке, а учётка — это не физлицо: связь `users.person_id` не заполнена почти ни у кого.
--
-- Колонка, а не связь с `persons`: пока учётки с физлицами не сведены, ссылаться не на что, а
-- контакт нужен уже сейчас. Когда связь появится (п. 1 ADR 0008), телефон учётки останется тем,
-- чем он и является, — номером, который человек оставил для входящих по порталу.
--
-- Формат свободный, как у `responsible_phone` в заявках (миграция 0062): в поле переносят номер
-- из переписки — с добавочным, городской, — и единый вид заставлял бы человека его переделывать.
-- Достаточность цифр проверяют контракты; CHECK не ставится, чтобы правило можно было менять без
-- миграции, а живые записи не роняли её.
--
-- NOT NULL DEFAULT '' — как у остальных необязательных текстовых полей проекта: пустая строка
-- означает «не указан», и читающему коду не приходится различать её и NULL.
ALTER TABLE users
  ADD COLUMN phone text NOT NULL DEFAULT '';
