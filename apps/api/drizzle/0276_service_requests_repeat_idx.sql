-- Частичный индекс под признак повторного обращения по аппарату
-- (план `docs/office-equipment-repeat-request-plan.md`, Р7; правило — Р1, этап Э1).
--
-- ЧТО ИМЕННО ОН ПОКРЫВАЕТ. Признак спрашивает у каждой ремонтной заявки одно и то же: «есть ли по
-- ЭТОМУ аппарату закрытая либо отменённая ремонтная заявка, вставшая в свой статус в окне
-- `[created_at − W; created_at]`». Ключи идут ровно по порядку чтения предиката: аппарат —
-- равенство, вид — равенство, `status_changed_at` — диапазон и он же последний. Без индекса
-- боковое соединение страницы (`LEFT JOIN LATERAL` в `services/service-request-repeat.ts`) и
-- `EXISTS` отбора «только повторные» брали бы весь набор заявок аппарата и отбрасывали бы лишнее
-- сортировкой в памяти — на технике с длинной историей это заметно уже сегодня.
--
-- ЧАСТИЧНЫЙ, И УСЛОВИЕ ЕГО — ДВЕ ПОСТОЯННЫЕ ПРАВИЛА, А НЕ ТРИ. В индекс попадают только живые
-- терминальные заявки: архивные (`deleted_at IS NOT NULL`) совпадением не считаются никогда (Р11),
-- незакрытые — тоже (на вопрос «уже чиним?» отвечают другие индексы,
-- `service_requests_open_repair_unique` и его пара). Это отсекает подавляющую часть таблицы:
-- индекс остаётся размером с историю закрытых работ, а не с самой таблицей.
--
-- ВИД ЗАЯВКИ СТОИТ КЛЮЧОМ, А НЕ В УСЛОВИИ, и это осознанное отличие от чернового индекса Р7.
-- Первая версия признака считает только ремонт (Р3), и `kind = 'repair'` в предикате сделало бы
-- индекс чуть у́же. Но вопрос «что закрывали по этому аппарату» задают и соседи — история единицы,
-- блок «Связанные заявки» (п. 13), будущий отчёт по расходникам, — а ключ отвечает и им, и правилу
-- повтора одинаково: равенство по второму столбцу стоит один переход по дереву. Переложи мы вид в
-- условие, расширение правила на расходники (если о нём однажды попросят) означало бы миграцию
-- индекса, а не строку в предикате.
--
-- `status IN (…)` В УСЛОВИИ ЧАСТИЧНОГО ИНДЕКСА — КОНСТАНТНЫЙ ПРЕДИКАТ, функций в нём нет вовсе,
-- поэтому известная разница прода (PostgreSQL 17) и дева (16) по функциональным индексам здесь ни
-- при чём. Форма та же, что у соседних `service_requests_open_*_unique` и
-- `service_requests_urgent_idx`, — этот способ сравнивать статус на обеих версиях уже работает.
--
-- ПЕРЕЧЕНЬ СТАТУСОВ ОБЯЗАН СОВПАДАТЬ С `SERVICE_REQUEST_REPEAT_TERMINAL_STATUSES` в контрактах:
-- оттуда его берёт предикат. Разъедься они — индекс перестанет покрывать отбор молча, потерей
-- скорости, а не ошибкой. Сузит ли заказчик правило до одной `accepted` (развилка В3) — решается в
-- обоих местах разом.
--
-- БЕЗ `CONCURRENTLY`: раннер катит файл в транзакции (`migration-journal.ts`), а `CREATE INDEX
-- CONCURRENTLY` внутри неё запрещён. Блокировка записи на время построения — доли секунды: заявок
-- на обслуживание в таблице тысячи, а не миллионы.
--
-- ОТКУДА НОМЕР. `ls apps/api/drizzle` перед созданием файла (04.09.2026): последняя миграция в
-- дереве — `0274_releases_service_request_quick_status.sql` соседнего потока, `0275` занят соседним
-- агентом этой же волны, и номер `0276` выдан этой работе координатором заранее — именно затем,
-- чтобы параллельные потоки не заняли его, пока пишется предикат.
--
-- ОБРАТИМОСТЬ ПОЛНАЯ И ДЕШЁВАЯ: `DROP INDEX service_requests_repeat_idx;`. Данных файл не трогает
-- вовсе, и снятие индекса ничего не ломает — признак останется верным, но станет дороже. Порядок
-- выключения самого признака при этом другой и к миграции отношения не имеет:
-- `SERVICE_REQUEST_REPEAT_WINDOW_DAYS = 0` гасит его целиком без единого шага по базе (Р5, К6).
--
-- ЧЕГО ЗДЕСЬ НЕТ: записи выпуска (признак выкатывается выключенным — обещать в журнале нечего),
-- прав, колонок и перекладки данных. Аддитивная миграция, протокол выката необратимых миграций
-- (`docs/schema-cutover-protocol.md`) к ней не применяется.

CREATE INDEX service_requests_repeat_idx
  ON service_requests (office_equipment_id, kind, status_changed_at DESC)
  WHERE deleted_at IS NULL AND status IN ('accepted', 'cancelled');
