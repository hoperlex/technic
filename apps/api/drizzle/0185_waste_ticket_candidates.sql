-- Спорные поля талона: что именно прочитал каждый проход каскада (ADR 0114, Р14).
--
-- Поле, по которому два прохода разошлись, остаётся ПУСТЫМ — портал не выбирает за человека, —
-- а `needs_review_fields` говорит, что вопрос открыт. Но сам вопрос без вариантов не задать:
-- «объём спорный» отправляет человека к скану вслепую, тогда как «первая модель прочитала 20,
-- вторая 28» решается взглядом.
--
-- Варианты хранятся снимком РЯДОМ С ТАЛОНОМ, а не собираются на лету из `raw` попыток. Причины
-- две. Первая: сопоставление талонов между проходами делает воркер (номер → дата и объём → место
-- на странице), и повторять это в API значило бы завести второй алгоритм сопоставления, который
-- разъедется с первым молча. Вторая: сырьё попыток убирается по сроку (Р31), а спорное поле живёт
-- до тех пор, пока его не разберут, — и обязано оставаться читаемым после уборки.
ALTER TABLE waste_tickets
  ADD COLUMN candidates jsonb NOT NULL DEFAULT '[]'::jsonb;

-- Массив, а не объект: у одного талона спорных полей бывает несколько, и у каждого — по варианту
-- от каждого прохода. Пустой массив — «спорить не о чем», то же самое, что пустой
-- `needs_review_fields`.
ALTER TABLE waste_tickets
  ADD CONSTRAINT waste_tickets_candidates_check
  CHECK (jsonb_typeof(candidates) = 'array');

-- Варианты без вопроса — мусор, вопрос без вариантов — законен (ручная правка номера снимает
-- варианты, оставляя поле разобранным человеком). Поэтому проверка односторонняя.
ALTER TABLE waste_tickets
  ADD CONSTRAINT waste_tickets_candidates_need_review_check
  CHECK (jsonb_array_length(candidates) = 0 OR array_length(needs_review_fields, 1) > 0);
