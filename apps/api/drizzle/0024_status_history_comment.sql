-- Причина смены статуса заявки на вывоз мусора.
--
-- Отмена заявки требует объяснения: заявка закрывается без результата, и без причины ни автор,
-- ни следующий диспетчер не поймут, почему её сняли. Причина хранится в истории статусов, а не
-- колонкой в waste_requests: отмена — событие, у него есть автор и время, и второй точки правды
-- рядом с историей быть не должно. Заявку могут отменить и повторно (после отката админом) —
-- в истории останутся обе причины, актуальна последняя.
--
-- Обязательность причины держит приложение, а не CHECK: ограничение вида «to_status='cancelled'
-- ⇒ comment <> ''» запретило бы дописывать историю задним числом при переносе данных, а никакой
-- защиты сверх серверной валидации не даёт — записи в историю пишет только сервер.
--
-- Аналогичная колонка у заявок на технику существует с миграции 0012 (vehicle_request_status_
-- history.comment); здесь схемы двух модулей выравниваются.

ALTER TABLE request_status_history ADD COLUMN comment text NOT NULL DEFAULT '';

COMMENT ON COLUMN request_status_history.comment IS
  'Комментарий к смене статуса; при переходе в cancelled — обязательная причина отмены';
