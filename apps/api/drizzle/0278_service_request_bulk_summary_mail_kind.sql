--
-- ОТКУДА НОМЕР. `ls apps/api/drizzle | tail -3` непосредственно перед созданием файла (04.09.2026):
-- последней в дереве стояла `0277_office_equipment_movements_place.sql`. Номер живёт часы —
-- соседние потоки занимают его незакоммиченными файлами, — поэтому он сверялся перед созданием
-- ЭТОГО файла, а не перед волной.
--
-- ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ, И ПОЧЕМУ ОН ПЕРВЫЙ В ВОЛНЕ. `mail_kind` — это `pgEnum`, а раннер применяет
-- файл миграции целиком в ОДНОЙ транзакции (`apps/api/src/db/migration-journal.ts`); PostgreSQL же
-- не разрешает пользоваться новым значением enum до её фиксации. Значение поэтому добавляется
-- своим файлом и в нём же не используется — тот самый приём, которым в модуль уже приезжали виды
-- писем (0257, 0180, 0142, 0122, 0114). `IF NOT EXISTS` — оттуда же: повторный прогон миграций не
-- должен падать.
--
-- ЗАЧЕМ ВИД ВООБЩЕ. Потолок частоты писем модуля считается по тройке «заявка + адрес + час»
-- (`service-request-mail.ts`) и от пачки по РАЗНЫМ заявкам не спасает: пятьдесят отменённых заявок
-- дали бы одному адресату пятьдесят обычных писем. Строки пачки поэтому складывают почтовые
-- намерения в `service_request_bulk_mail_items` (следующая миграция волны), а финализатор шлёт
-- один digest на пару «адресат + аудитория» — этим видом.
--
-- ВИД ТЕХНИЧЕСКИЙ, как и `service_request_activity_summary`: в перечне `MODULE_MAIL_EVENTS` его
-- нет, рубильника у него нет, администратор его не включает. Он появляется вместо уже включённых
-- событий и только у пакетной ручки.
--
-- Свой вид обязателен, а не общий с соседним: `mail_messages` уникальна по паре
-- `(kind, dedupe_key)`, и сводка, притворившаяся событийным письмом, молча подавила бы его по той
-- же строке истории — пропадало бы одно из двух, и без единого следа.
--
-- ОБРАТИМОСТЬ. Аддитивна, смысл существующих данных не меняется. Обратного шага нет и быть не
-- может — значение enum в PostgreSQL не удаляется; откат кода просто перестаёт его писать. Само по
-- себе появление вида ничего не рассылает: письма ставит только финализатор пачки.

ALTER TYPE mail_kind ADD VALUE IF NOT EXISTS 'service_request_bulk_summary';
