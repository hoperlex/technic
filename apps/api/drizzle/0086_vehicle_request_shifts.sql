-- Подтверждение смен по заказу спецтехники.
--
-- Техника стоит на объекте неделями, а работа считается по дням. До сих пор заявка отвечала
-- только итогом — «26 ч» или «3 смены» в факте выполнения (ADR 0029), — и вводил его один
-- человек при закрытии, по бумажкам, собранным с площадки. Теперь у каждого дня заказа своя
-- строка: время смены, машиночасы, заправка и подпись объекта, что этот день был именно таким.
--
-- Строка появляется при первом заполнении, а не заготавливается на весь период: срок правят,
-- сокращают досрочно (ADR 0044) и обнуляют откатом в «Новую» (ADR 0058) — заготовки пришлось бы
-- синхронизировать с каждым из этих действий, а пустую заготовку потом не отличить от «день не
-- заполнили». На этом различии держится и запрет закрытия заявки без подписей, и то, что заявка
-- с неподтверждёнными днями не уходит из среза «На объекте» (ADR 0036).

CREATE TABLE vehicle_request_shifts (
  -- Одна заявка — один день — одна смена. Вторая смена в тех же сутках в модель не помещается
  -- намеренно: день здесь — заказанный день заявки, и ключ говорит об этом прямо.
  request_id uuid NOT NULL REFERENCES vehicle_requests (id) ON DELETE CASCADE,
  shift_date date NOT NULL,
  -- Время смены: «08:00 – 20:00». Ночная переходит через полночь и относится к дню начала.
  -- Пусто — часы записали одним числом, не проставляя границ.
  started_at time,
  ended_at time,
  machine_hours numeric(5, 2) NOT NULL,
  -- Заправка свободным текстом: «120 л», «залили полный», «по талону». Пока непонятно, что
  -- именно записывают, и число вместо текста заставило бы человека выдумывать формат.
  refuel text NOT NULL DEFAULT '',
  comment text NOT NULL DEFAULT '',
  filled_by uuid NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  -- Подпись объекта: кто принял этот день работы и когда. Пусто — день ещё не согласован, и
  -- именно такие дни не дают заявке закрыться.
  approved_by uuid REFERENCES users (id) ON DELETE RESTRICT,
  approved_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT vehicle_request_shifts_pkey PRIMARY KEY (request_id, shift_date),
  -- Сутки длиннее суток не бывают, а опечатка в разряде («115» вместо «11,5») иначе уезжает
  -- прямиком в счёт. Ноль — законное значение: простой тоже часть учёта.
  CONSTRAINT vehicle_request_shifts_hours_check
    CHECK (machine_hours >= 0 AND machine_hours <= 24),
  -- Нулевой день объясняется: «дождь», «не открыли фронт работ», «сломалась». Молчание портала
  -- здесь хуже нуля — за такой день с арендодателем разговаривают отдельно.
  CONSTRAINT vehicle_request_shifts_idle_comment_check
    CHECK (machine_hours > 0 OR btrim(comment) <> ''),
  -- Половина смены не описывает ничего: «с 08:00» без конца — это не время работы.
  CONSTRAINT vehicle_request_shifts_time_check
    CHECK ((started_at IS NULL) = (ended_at IS NULL)),
  -- «Кто» без «когда» — не подпись (тем же CHECK устроена виза заявки, миграция 0049).
  CONSTRAINT vehicle_request_shifts_approval_check
    CHECK ((approved_by IS NULL) = (approved_at IS NULL))
);

-- «Что по этой заявке не подтверждено» — главный вопрос к таблице: по нему считается сводка в
-- строке списка, и он же не даёт заявке закрыться.
CREATE INDEX vehicle_request_shifts_unapproved_idx
  ON vehicle_request_shifts (request_id)
  WHERE approved_at IS NULL;

-- Принадлежность дня сроку заявки CHECK'ом не выражается — нужен join с
-- special_equipment_request_details, — и держит её сервис, как и остальные межтабличные правила
-- модуля. Снимка назначенной машины в строке нет намеренно: пока смены подтверждены, машину не
-- меняют, и второго ответа на «чья это работа» быть не может.
