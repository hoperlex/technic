-- Объект отдела (ADR 0062): за частью отделов закреплена площадка, и на ней их сотрудники
-- работают наравне со штабом — заказывают вывоз мусора.
--
-- Колонка у отдела, а не набор у учётки: у объекта отделов бывает несколько, у отдела объект —
-- не больше одного. Привязка со стороны учётки означала бы, что «снабжение работает на объекте 7»
-- вносится в каждую учётку снабжения отдельно и расходится с первой же новой площадкой.
--
-- NULL — рабочее состояние, а не незаполненность: отдел без площадки (ПТО, АХО) остаётся, и
-- объектных прав его сотрудники не получают вовсе.
ALTER TABLE departments
  ADD COLUMN construction_object_id uuid REFERENCES construction_objects (id) ON DELETE RESTRICT;

-- RESTRICT, а не SET NULL: объект из справочника деактивируют, а не удаляют, и снятие привязки
-- каскадом молча отобрало бы область у сотрудников отдела — мимо карточки, в которой её задавали.
-- Удаление объекта насовсем (ADR 0060) отказывает по этой же причине, но сообщением, а не
-- нарушением целостности.

-- «Какие отделы у объекта» — вопрос со стороны карточки объекта и производной области учётки
-- (departmentObjectIdsExpr). Частичный: отделы без площадки в этот запрос не входят никогда.
CREATE INDEX departments_construction_object_idx
  ON departments (construction_object_id)
  WHERE construction_object_id IS NOT NULL;
