-- Водители: СНИЛС и наполнение классификатора водительских удостоверений (ADR 0037).
--
-- ADR 0008 отказался от СНИЛС как от «лишних персональных данных» — он не был нужен ни одной
-- функции портала. Путевой лист сделал его обязательным реквизитом (приказ Минтранса № 390):
-- без него документ недействителен. Побочно он закрывает то, ради чего пункт и писался: у
-- человека появляется надёжный ключ, и предупреждение о дублях перестаёт держаться на одном
-- ФИО с датой рождения, которое ломается на однофамильцах-ровесниках.
--
-- Справочники ADR 0008 оставил пустыми — «по решению заказчика сидов в миграциях нет». Решение
-- касалось бизнес-справочников: их состав заказчик определяет сам. Здесь другое — вид документа
-- «Водительское удостоверение» и 16 категорий по ст. 25 ФЗ «О безопасности дорожного движения»:
-- их не ведут и не меняют, а без них человека нельзя отметить водителем вообще.

-- 1. СНИЛС. Хранятся 11 цифр, форматирование «XXX-XXX-XXX YY» — на выводе: разделители в номер
--    не входят, а два представления одного значения дали бы два способа не найти дубль.
--    Пустая строка = не заполнен: persons рассчитаны не на одних водителей (ADR 0008), и
--    обязательность держит сервис — она свойство роли «водитель», а не таблицы.
--    Контрольную сумму проверяет сервис — тем же приёмом, что ИНН контрагента (0022): формат
--    ловит длину, контрольная сумма ловит опечатку в одной цифре, и в CHECK её не выразить.
ALTER TABLE persons
  ADD COLUMN snils text NOT NULL DEFAULT '',
  ADD CONSTRAINT persons_snils_format_check CHECK (snils = '' OR snils ~ '^[0-9]{11}$');

-- Ключ человека: один СНИЛС — один живой person. Удалённых условие не касается: после
-- soft-delete человека заводят заново, и номер должен освобождаться вместе с ним.
CREATE UNIQUE INDEX persons_snils_unique ON persons (snils)
  WHERE snils <> '' AND deleted_at IS NULL;

-- 2. Специализация «Водитель». Отдельной таблицы drivers нет: водитель — это выборка по
--    specializations.code='driver' с ended_on IS NULL (ADR 0008).
INSERT INTO specializations (code, name, description, sort_order) VALUES
  ('driver', 'Водитель', 'Управление транспортным средством по путевому листу', 10)
ON CONFLICT (code) DO NOTHING;

-- 3. Вид документа. has_categories: категориями и отбирают водителя под конкретную машину
--    (ADR 0037). expiry_required: национальное ВУ выдаётся на десять лет.
INSERT INTO credential_types (code, name, description, has_categories, expiry_required, sort_order)
VALUES (
  'driver_license',
  'Водительское удостоверение',
  'Национальное водительское удостоверение (ФЗ «О безопасности дорожного движения», ст. 25)',
  true, true, 10
)
ON CONFLICT (code) DO NOTHING;

