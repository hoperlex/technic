-- Порядок ролей внутри точки маршрута. План — `docs/route-trips-plan.md`, решения Р11, Р12, Р14,
-- Р20; таблица — §5.3.
--
-- ЧТО СЛОМАНО СЕГОДНЯ. Порядок строк задания печатного листа задан ключом из четырёх полей (Р11):
-- позиция первой точки строки, позиция второй, номер заявки, номер ездки. Первых двух хватает не
-- всегда: две строки задания законно стоят на ОДНОЙ И ТОЙ ЖЕ паре точек — либо это две повторные
-- ездки `A→B` одной заявки, либо две разные заявки, у которых совпали адрес и ответственный, и
-- автосборка переиспользовала точку (Р8). Тогда решает третий ключ — номер заявки, то есть
-- порядок, в котором записи завели в базу.
--
-- А порядок строк задания — это порядок ОТРЫВНЫХ ТАЛОНОВ ЗАКАЗЧИКОВ (Р12, Р20:
-- `waybill_requests.slot` — первая строка задания заявки). ADR 0068 п. 2 говорит об этом прямо:
-- «Порядок заявок в маршруте перестал быть вопросом удобства и стал решением, кто из заказчиков
-- подпишет талон». До перехода на точки такой порядок задавал диспетчер стрелками состава; после
-- перехода — номер заявки, то есть никто.
--
-- ЧТО ЗАВОДИТСЯ. Роль на точке получает `position` — своё место в порядке работ ЭТОЙ остановки.
-- Вопрос «какая из двух строк раньше» превращается в вопрос «какую ездку на карьере грузим первой»,
-- и это осмысленно само по себе, а не только как способ разрулить сортировку: машина действительно
-- грузится по очереди, и водителю в задании видно, в какой.
--
-- Ключ сортировки строк задания получает позицию роли ТРЕТЬИМ полем — после позиции второй точки, а
-- не перед ней. Разница существенная: строки, делящие только ПЕРВУЮ точку (грузимся в одном карьере,
-- везём в разные места), объезд различает — их порядок задан тем, куда машина поедет дальше, — и
-- перестановка ролей на общей погрузке не вправе его переписать. Иначе одно и то же переставлялось
-- бы двумя разными способами, причём второй — молча.
--
-- ПОРЯДОК СУЩЕСТВУЮЩИХ ЛИСТОВ НЕ МЕНЯЕТСЯ. Бэкфил (§3 ниже) раздаёт позиции внутри точки по номеру
-- заявки и номеру ездки — тем самым порядком, который сегодня и действует третьим ключом. Значит у
-- строк, стоящих на одной паре точек, новый третий ключ упорядочивает их так же, как прежде
-- упорядочивал номер заявки, а у остальных он вообще недостижим: их разводят первые два ключа.
-- Заодно тем же бэкфилом сохраняется и порядок графы «заказчик, телефон»: в ней позиция роли
-- заменила номер заявки хвостом сортировки внутри вида роли (`pointContacts`), а раз позиции
-- раздаются по номерам, порядок контактов остаётся прежним.

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 1. Колонка.
--
-- Заводится NULL-able: колонку NOT NULL к непустой таблице без умолчания не добавить, а умолчание
-- здесь и не годится — позиция обязана быть РАЗНОЙ у ролей одной точки, а константа сделала бы её
-- одинаковой и упёрлась бы в уникальность на первой же точке с двумя ролями.
ALTER TABLE vehicle_route_point_trips ADD COLUMN position smallint;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 2. Бэкфил: 1..N внутри каждой точки.
--
-- Порядок раздачи — номер заявки, затем номер ездки: ровно тот, каким сегодня решается ничья строк
-- задания (Р11, ключи 3 и 4) и каким сегодня же упорядочены контакты точки внутри вида роли
-- (`pointContacts`). Так выкат не переставляет ничего — ни строк в бумаге, ни ответственных в графе.
--
-- Хвосты ключа (вид роли, затем `id`) нужны для полной определённости: у ездки, чьи погрузка и
-- разгрузка стоят на одной точке (данные, испорченные до Р6), номер заявки и номер ездки совпадают,
-- а `row_number()` обязан выдать двум строкам разные значения. Виды роли перечислены в том же
-- порядке, в каком их читает бумага, — `load → work → unload` (Р9б).
--
-- Линейный день участвует наравне: у него нет ездки, и `tripNum` берётся нулём — тем же нулём,
-- каким его считает строка задания («ездок не бывает», Р11).
UPDATE vehicle_route_point_trips AS t
SET position = v.position
FROM (
  SELECT
    pt.id,
    row_number() OVER (
      PARTITION BY pt.point_id
      ORDER BY
        r.num,
        COALESCE(tr.num, 0),
        CASE pt.role WHEN 'load' THEN 0 WHEN 'work' THEN 1 ELSE 2 END,
        pt.id
    ) AS position
  FROM vehicle_route_point_trips pt
  JOIN vehicle_requests r ON r.id = pt.request_id
  LEFT JOIN vehicle_request_trips tr ON tr.id = pt.trip_id
) AS v
WHERE t.id = v.id;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 3. Ограничения.
--
-- Потолок тот же, что у точек: ролей в маршруте не больше двадцати — десять строк задания
-- (ADR 0068) по две роли, — и все двадцать могут оказаться на одной остановке, если день целиком
-- грузится и разгружается в одном месте.
ALTER TABLE vehicle_route_point_trips ALTER COLUMN position SET NOT NULL;

ALTER TABLE vehicle_route_point_trips
  ADD CONSTRAINT route_point_trips_position_check CHECK (position BETWEEN 1 AND 20);

-- DEFERRABLE INITIALLY IMMEDIATE — тот же приём, что у порядка точек (0136) и порядка строк состава
-- (0072): перестановка переписывает позиции одним запросом, и построчная проверка упала бы на первой
-- же строке; транзакция перестановки откладывает ограничение через `SET CONSTRAINTS`.
ALTER TABLE vehicle_route_point_trips
  ADD CONSTRAINT route_point_trips_position_unique UNIQUE (point_id, position)
  DEFERRABLE INITIALLY IMMEDIATE;

COMMENT ON COLUMN vehicle_route_point_trips.position IS
  'Порядок роли внутри своей точки, 1..N: «сначала грузим эту ездку, потом ту». Им же решается '
  'порядок талонов у строк задания, стоящих на одной и той же паре точек, — объезд их не различает.';
