-- Арендодатель ТС как роль контрагента (ADR 0010).
--
-- Техника берётся в аренду у сторонних организаций, и хранить их было негде: типы контрагентов
-- покрывали только стройку и вывоз мусора. Отдельная таблица не нужна — набор полей тот же, что
-- у прочих ролей, различает их колонка `type` (решение 1 ADR 0010). ИНН остаётся обязательным:
-- идентичность контрагента держится на нём (решение 2), и послабление размыло бы её ради записей,
-- у которых реквизиты просто ещё не запросили.
--
-- Значение enum используется только со следующей миграции: применить его в той же транзакции, где
-- оно добавлено, Postgres не даёт (приём из 0022/0023 — раннер выполняет файл целиком в одной
-- транзакции).
ALTER TYPE counterparty_type ADD VALUE IF NOT EXISTS 'vehicle_lessor';
