-- Два события кандидата в рубильнике почты модуля — ВЫКЛЮЧЕННЫМИ
-- (план `docs/office-equipment-candidate-plan.md`, §10 и §14, миграция M3; таблица заведена
-- миграцией `0258`, механика — ADR 0159).
--
-- ОТКУДА НОМЕР. Тот же снимок `ls apps/api/drizzle`, что и у `0272` (04.09.2026, 15:05): последним
-- в дереве стоял `0271_esm2_machinist_name_backfill.sql` соседнего потока, свободны `0272` и `0273`.
-- Оба файла созданы подряд одной работой ровно затем, чтобы между ними не встал третий поток и не
-- развёл «словарь видов» и «настройку событий» по разным выкатам.
--
-- ПОЧЕМУ ОТДЕЛЬНО ОТ `0272`, ХОТЯ ЗДЕСЬ И НЕТ НИ ОДНОГО ЗНАЧЕНИЯ `mail_kind`. Файлы разделены по
-- ГРАНИЦЕ ОТКАТА, а не по технической необходимости: значения enum необратимы навсегда, а строки
-- настройки удаляются обычным `DELETE`. Слитые в один файл, они означали бы, что откат настройки
-- невозможен вместе с ними. Плюс правило §14 плана, ради которого пара и разнесена: `ALTER TYPE …
-- ADD VALUE` и пользование новым значением в одной транзакции PostgreSQL не разрешает — и хотя
-- ключ рубильника текстовый, держать эту пару файлов в одном порядке дешевле, чем каждый раз
-- доказывать, что вот в этом случае можно.
--
-- ОБА СОБЫТИЯ ЗАВОДЯТСЯ ВЫКЛЮЧЕННЫМИ, и это не осторожность ради осторожности. Выпуск A волны
-- кандидатов — закрытый precursor: приём сообщений закрыт серверным рубильником `candidate_intake`,
-- портала ещё нет, а составы наборов (право `officeEquipment.review`) приезжают только выпуском B.
-- Включённое событие означало бы письма о сообщениях, которых никто не заводил, — либо, хуже,
-- письма проверяющим, которых ещё не назначили. Включают их по одному и с окном наблюдения (Э8), и
-- порядок включения задан планом: сначала `pending`, затем `decided`.
--
-- Аварийное выключение читается там же: сначала гасится `pending`, сразу за ним — `candidate_intake`;
-- `decided` остаётся включённым до тех пор, пока последний накопленный кандидат не разобран, иначе
-- заявители остались бы без ответа по уже отправленным сообщениям.
--
-- `CHECK` ЗАМЕНЯЕТСЯ ЦЕЛИКОМ, А НЕ ДОПИСЫВАЕТСЯ: перечень значений в ограничении не расширяется —
-- ограничение снимается и ставится заново. Обе команды идут в ОДНОЙ транзакции (раннер оборачивает
-- каждый файл в `BEGIN`/`COMMIT`), поэтому окна «таблица без ограничения» не существует. Перечень
-- обязан совпадать с `MODULE_MAIL_EVENTS` в контрактах и с `check` в `apps/api/src/db/schema.ts` —
-- три места, и расходиться им нечем: строка события без своей записи здесь трактуется fail-closed,
-- то есть событие молчит, а строка без своего события в контрактах не отобразится в админке вовсе.
--
-- ЧЕГО ЗДЕСЬ НЕТ: строк `module_mail_recipients` (копии заводит администратор осознанно, а не
-- выкат), прав, записи выпуска. Аддитивная миграция: существующих строк не касается, протокол
-- выката необратимых миграций (`docs/schema-cutover-protocol.md`) к ней не применяется. Откат —
-- удаление двух строк и возврат прежнего `CHECK`; код прошлого выпуска о событиях не знает и в
-- список админки их не выводит.

ALTER TABLE module_mail_event_settings DROP CONSTRAINT module_mail_event_settings_event_check;

ALTER TABLE module_mail_event_settings ADD CONSTRAINT module_mail_event_settings_event_check
  CHECK (event IN (
    'service_request_waiting_it',
    'service_request_cancelled',
    'service_request_assigned',
    'service_request_status_changed',
    'service_request_estimate',
    'service_request_document',
    'service_request_comment',
    'office_equipment_candidate_pending',
    'office_equipment_candidate_decided'
  ));

-- Строка на каждое событие реестра: отсутствие строки трактуется приложением fail-closed, как
-- выключенность, и снаружи это неотличимо от «администратор выключил». Заводятся обе явно, чтобы
-- рубильник в админке был живым выключателем, а не пунктом «выката не хватает».
INSERT INTO module_mail_event_settings (event, is_enabled) VALUES
  ('office_equipment_candidate_pending', false),
  ('office_equipment_candidate_decided', false);
