-- Модуль «Механизация»: заявка на аренду малой механизации (план
-- `docs/mechanization-module-plan.md`, редакция 12 — §6 «Модель данных», решения Р1, Р2, Р5–Р8,
-- Р14, Р17, Р18). Этап Э1 — только схема; контракты, маршруты, права и портал едут той же волной
-- отдельными коммитами.
--
-- ОТКУДА НОМЕР. Проверено `ls apps/api/drizzle` непосредственно перед созданием файлов
-- (01.09.2026): последняя миграция в дереве — `0236_esm2_month_split_backfill.sql`. Этап занимает
-- два соседних номера (Р18): 0237 — значение `counterparty_type`, 0238 — эта. Номера миграций и
-- ADR идут параллельными потоками (§11 плана), поэтому сверка сделана заново, а не взята из шапки
-- плана: пока писались редакции, соседняя работа заняла четыре номера миграций и три номера ADR.
--
-- ПОРЯДОК. Строго после 0237: `mech_requests_lessor_type_check` называет `mech_lessor` поимённо, а
-- использовать значение enum'а в транзакции, где оно добавлено, Postgres не даёт.
--
-- ЗАЧЕМ ОДНА ТАБЛИЦА НА ПРОСЬБУ, ДОГОВОРЁННОСТЬ, АРЕНДУ И ИТОГ (Р1). Отдельная запись состояния
-- понадобилась бы, если бы одна заявка порождала несколько аренд или аренда переживала свою заявку;
-- ни того, ни другого в постановке нет. Цена решения названа вслух: одна заявка — одна единица и
-- одна аренда навсегда, а частичный возврат станет миграцией с переносом строк, а не дописанной
-- колонкой.
--
-- ПОЧЕМУ ЗДЕСЬ СТОЛЬКО CHECK'ОВ (Р8). Статусы названы заказчиком, и четвёртого выдумывать нельзя:
-- «договорились» и «техника стоит на объекте» разводятся не статусом, а полями. Значит смысл строки
-- держится не на одной колонке, а на сочетании статуса, договорённости и факта — и каждое
-- невозможное сочетание, не запрещённое здесь, рано или поздно окажется в базе прямым запросом или
-- ошибкой будущей правки. Коридор статусов — это код, а колонка принимает что угодно из типа.

-- ── 1. Единица ставки ──
--
-- Enum, а не текст: значений ровно два, они входят в расчёт `actual_units × rate` и в подписи
-- итогов («часы» и «смены» не складываются между собой, §12 плана). Третьего («сутки», «месяц») в
-- постановке нет; появится — приедет `ADD VALUE` отдельным файлом по той же причине, что и 0237.
CREATE TYPE mech_rate_unit AS ENUM ('hour', 'shift');

-- ── 2. Заявка ──
CREATE TABLE mech_requests (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Сквозной человекочитаемый номер; показывается как «МХ-<num>» (Р4). Тем же приёмом, что номера
  -- заявок вывоза (`0005`) и заказов ТС (`0012`): раздаёт его база, а не клиент и не счётчик в коде.
  num integer GENERATED ALWAYS AS IDENTITY,
  -- Площадка эксплуатации, она же ОСЬ ОБЛАСТИ (Р10, Р17): по этой одной колонке считается вся
  -- видимость модуля — объектная роль сравнивает со своими объектами, отдельская — с площадками
  -- своих отделов. Место обязательно: заявка без него не отвечает ни «куда везти», ни «чья она».
  object_id uuid NOT NULL REFERENCES construction_objects (id) ON DELETE RESTRICT,
  -- Заявитель-отдел; NULL означает «заявку завела сама площадка». Колонки НЕ взаимоисключающие, в
  -- отличие от «Заказа ТС» (`vehicle_requests_customer_check`), и это осознанное расхождение: там
  -- объект и отдел — два разных заказчика, здесь объект это МЕСТО, а отдел — тот, кто просит и на
  -- кого относятся расходы. Заявитель выводится: отдел, если заполнен, иначе объект.
  --
  -- Что пара «отдел — площадка» связана в справочнике, здесь не проверяется и проверено быть не
  -- может: состав площадок отдела меняется, а перепроверка старой заявки запретила бы офису
  -- поправить у неё комментарий (Р17). Сервер стережёт пару в момент, когда её НАЗНАЧАЮТ.
  department_id uuid REFERENCES departments (id) ON DELETE RESTRICT,
  -- Вид техники — свободная строка: справочника видов заказчик пока не захотел (Р5).
  kind_name text NOT NULL,
  -- Ключ группировки для подсказки и отчётов. Считает БД (STORED): второй точки правды по
  -- написанию быть не должно, иначе подсказка и список разойдутся на первой же правке кода.
  --
  -- Схлопывает РЕГИСТР И ПОВТОРНЫЕ ПРОБЕЛЫ — и только. «Виброплита» и «Вибро плита» остаются
  -- разными позициями: разделять слова — работа справочника, а его нет. Выражение проверено на
  -- обеих живых версиях (прод — PostgreSQL 17, дев — 16): `lower`, `btrim` и четырёхаргументный
  -- `regexp_replace` IMMUTABLE в обеих, иначе генерируемая колонка не создалась бы вовсе.
  kind_key text GENERATED ALWAYS AS (lower(btrim(regexp_replace(kind_name, '\s+', ' ', 'g')))) STORED,
  -- Когда техника нужна по просьбе. Это ПЛАН: факт живёт в `actual_from`/`actual_to` и с планом
  -- сходиться не обязан — продление двигает `planned_to`, а вернуть могут раньше срока.
  planned_from date NOT NULL,
  planned_to date NOT NULL,
  -- Кто встречает технику на площадке. Телефон — десять цифр без кода страны (ADR 0066), как у
  -- ответственного в вывозе и в заказе ТС; формат держит CHECK ниже.
  responsible_name text NOT NULL,
  responsible_phone text NOT NULL,
  comment text NOT NULL DEFAULT '',
  -- Тип `request_status` общий на все модули заявок. Механизация ходит по своему коридору
  -- `new → confirmed → done` с отменой; «Завершена» у неё нет вовсе — запрещено CHECK'ом ниже.
  status request_status NOT NULL DEFAULT 'new',
  -- ── Договорённость: с кем и почём (Р6, Р7) ──
  -- Пять колонок, живущих вместе: арендодатель, его тип, его активность, ставка и её единица.
  lessor_id uuid,
  -- Служебная: приложение всегда пишет фактический тип контрагента. Существует ради составного FK
  -- — им инвариант «арендодатель именно арендодатель» становится физическим (приём ADR 0018).
  lessor_type counterparty_type,
  -- Служебная: пишет не приложение, а каскад FK (`ON UPDATE CASCADE`). Денормализованная копия
  -- активности нужна затем же, зачем `vehicles.lessor_is_active`: сверять «его можно выбрать
  -- сегодня» без обращения к справочнику и не дать ключу разойтись с ним молча.
  lessor_is_active boolean,
  -- Цена договаривается на каждую аренду: прайса у механизации нет (Р7).
  rate numeric(12, 2),
  rate_unit mech_rate_unit,
  -- ── Факт: что случилось на площадке (Р2) ──
  -- Выдача. Она же признак присутствия — вместе со статусом и пустым `actual_to`, всеми тремя
  -- частями сразу: откат «Выполнена → В работе» факт БЕРЕЖЁТ, и проверка по одному `actual_from`
  -- вернула бы уже возвращённую технику в действующие аренды.
  actual_from date,
  actual_to date,
  -- Сколько отработано, в тех же единицах, что ставка. Обязателен при завершении: только с ним
  -- расчёт `actual_units × rate` есть всегда и расхождение с введённой суммой видно всегда.
  actual_units numeric(10, 2),
  -- Итог вводит человек, портал его НЕ считает: сколько смен отработала техника за две недели,
  -- знает площадка, а не календарь.
  final_cost numeric(14, 2),
  --
  -- ЗАПРЕТА БУДУЩИХ ФАКТИЧЕСКИХ ДАТ ЗДЕСЬ НЕТ, И ЭТО РЕШЕНИЕ, А НЕ УПУЩЕНИЕ (§6 плана). База такой
  -- CHECK приняла бы (`d <= CURRENT_DATE` проверено на dev-Postgres), и условие даже монотонно —
  -- прошедшая проверку строка завтра невалидной не станет. Не годится он по другой причине:
  -- `CURRENT_DATE` считает день по часовому поясу СЕССИИ, а сессии приложения живут в UTC, тогда
  -- как бизнес-сутки портала — `Europe/Moscow`. С 00:00 до 03:00 МСК даты расходятся на сутки, и
  -- запись «выдана сегодня», сделанная в 00:30, была бы отвергнута как будущая. Правило момента
  -- записи держит сервис, явно вычислив московский день, — тем же приёмом и по той же причине, что
  -- время доставки в вывозе мусора.
  created_by uuid NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  updated_by uuid REFERENCES users (id) ON DELETE SET NULL,
  -- Архив по ADR 0070: `deleted_at` — мягкое удаление с восстановлением и `records.purge`.
  -- `SET NULL` у авторов правки и удаления — учётку удаляют, а заявка остаётся; `RESTRICT` у автора
  -- заведения — заявка без автора не отвечает на «кто её просил».
  deleted_by uuid REFERENCES users (id) ON DELETE SET NULL,
  deleted_at timestamptz,
  -- Оптимистическая блокировка (Р21): все мутации модуля идут одним протоколом — замок, перепроверка
  -- состояния, сверка версии.
  version integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),

  -- Вид техники — единственное, чем заявка отличается от соседней: пустая строка не описывает
  -- ничего, а `NOT NULL` от неё не спасает.
  CONSTRAINT mech_requests_kind_not_blank_check CHECK (btrim(kind_name) <> ''),
  -- Технику принимает человек, которому звонят с дороги. Формат телефона — ровно десять цифр
  -- (ADR 0066): здесь, в отличие от вывоза и заказа ТС, старых строк нет ни одной, и требование
  -- ставится сразу базой, а не одним сервером.
  CONSTRAINT mech_requests_responsible_check CHECK (
    btrim(responsible_name) <> '' AND responsible_phone ~ '^[0-9]{10}$'
  ),
  CONSTRAINT mech_requests_period_check CHECK (planned_to >= planned_from),
  -- Про факт то же самое, но обе даты необязательны: пока техника не возвращена, `actual_to` пуст.
  CONSTRAINT mech_requests_actual_period_check CHECK (
    actual_to IS NULL OR actual_from IS NULL OR actual_to >= actual_from
  ),
  -- ДОГОВОРЁННОСТЬ ЦЕЛИКОМ ИЛИ ЕЁ НЕТ ВОВСЕ — и это не косметика, а заплата на дыре составного
  -- ключа. PostgreSQL проверяет внешний ключ в режиме MATCH SIMPLE: если хотя бы одна колонка ключа
  -- `NULL`, ключ НЕ ПРОВЕРЯЕТСЯ ВООБЩЕ. Без этого условия прямой SQL сохранил бы заявку с любым
  -- `lessor_id`, правдоподобным типом и `lessor_is_active = NULL` — то есть с арендодателем,
  -- которого никто не сверял. У рабочего образца ту же дыру закрывает отдельный
  -- `vehicles_lessor_active_pair_check` (0038); здесь одна проверка закрывает и её, и половинчатую
  -- договорённость (цена без арендодателя, арендодатель без цены) — в том числе у отменённой
  -- заявки. Проверяется прямым INSERT: через маршрут эта дыра не видна.
  CONSTRAINT mech_requests_deal_parts_check CHECK (
    num_nonnulls(lessor_id, lessor_type, lessor_is_active, rate, rate_unit) IN (0, 5)
  ),
  -- Оба типа названы поимённо (Р6): компания, уже заведённая арендодателем ТС, сдаёт механизацию
  -- под своим типом — менять ей тип значило бы сломать права её учёток и её технику в парке.
  -- Остальные роли контрагента арендодателями не бывают, и FK один их не отсёк бы.
  CONSTRAINT mech_requests_lessor_type_check CHECK (
    lessor_type IS NULL OR lessor_type IN ('mech_lessor', 'vehicle_lessor')
  ),
  -- «Новая» — это просьба и ничего больше. Условие держит модульное правило Р2: договорённость
  -- стирается при ЛЮБОМ входе в «Новую», в том числе цепочкой `confirmed → cancelled → new`, — а
  -- значит откатом заявку не превратить в чистый лист с сохранённой ценой.
  CONSTRAINT mech_requests_new_empty_check CHECK (
    status <> 'new'
    OR (num_nonnulls(lessor_id, lessor_type, lessor_is_active, rate, rate_unit) = 0
        AND actual_from IS NULL)
  ),
  -- В работе и выполнена — только с полной договорённостью: «взяли в работу, а с кем и почём
  -- договорились, не записали» — это не состояние заявки, а потерянные деньги.
  CONSTRAINT mech_requests_deal_check CHECK (
    status NOT IN ('confirmed', 'done')
    OR num_nonnulls(lessor_id, lessor_type, lessor_is_active, rate, rate_unit) = 5
  ),
  -- Закрытая заявка отвечает на все четыре вопроса: когда выдали, когда вернули, сколько
  -- отработали и во что это обошлось. Без любого из них закрывать нечего.
  CONSTRAINT mech_requests_done_check CHECK (
    status <> 'done'
    OR (actual_from IS NOT NULL AND actual_to IS NOT NULL
        AND actual_units IS NOT NULL AND final_cost IS NOT NULL)
  ),
  -- Отменить выданное нельзя: за технику, простоявшую на объекте, выставят счёт, и отмена означала
  -- бы, что аренды не было. Такую заявку завершают, а не отменяют.
  CONSTRAINT mech_requests_cancel_check CHECK (status <> 'cancelled' OR actual_from IS NULL),
  -- Возврата без выдачи не бывает: пока техники не выдавали, ни дата возврата, ни отработанные
  -- единицы, ни сумма смысла не имеют.
  CONSTRAINT mech_requests_issue_first_check CHECK (
    actual_from IS NOT NULL
    OR (actual_to IS NULL AND actual_units IS NULL AND final_cost IS NULL)
  ),
  -- ФАКТ ВОЗВРАТА ЦЕЛИКОМ ИЛИ ЕГО НЕТ. Проверки статусов стерегут только `done`, и без этого условия
  -- строка `confirmed` с заполненными `actual_units` и `final_cost`, но пустым `actual_to`,
  -- проходила бы всё: она считалась бы ДЕЙСТВУЮЩЕЙ АРЕНДОЙ с уже проставленной итоговой стоимостью.
  -- Симметрично разрешался бы `actual_to` без единиц и суммы — возврат без денег. Вместе с
  -- `issue_first_check` допустимых состояний факта остаётся ровно три: «фактов нет», «только
  -- выдача», «выдача плюс полный возврат». Лестница без промежуточных ступеней.
  CONSTRAINT mech_requests_return_parts_check CHECK (
    num_nonnulls(actual_to, actual_units, final_cost) IN (0, 3)
  ),
  -- Бесплатной аренды в постановке нет: ноль в ставке — это не «дали даром», а незаполненное поле,
  -- и отличить одно от другого потом будет нечем.
  CONSTRAINT mech_requests_rate_positive_check CHECK (rate IS NULL OR rate > 0),
  -- Ноль отработанных единиц означает, что техника стояла, — такую аренду закрывают отменой выдачи,
  -- а не нулевым фактом.
  CONSTRAINT mech_requests_units_positive_check CHECK (actual_units IS NULL OR actual_units > 0),
  -- А вот нулевой ИТОГ законен и осмыслен: работу простили или списали на арендодателя. Запрещено
  -- здесь только отрицательное — это не скидка, а ошибка ввода.
  CONSTRAINT mech_requests_cost_check CHECK (final_cost IS NULL OR final_cost >= 0),
  -- Статуса «Завершена» у механизации не бывает вовсе. Барьер обязателен по той же причине, по
  -- которой он появился у заказа ТС (`vehicle_requests_status_check`, миграция 0195): тип
  -- `request_status` общий на все модули, перехода в «Завершена» нет ни в одном коридоре
  -- механизации, НО коридор — это код, а колонка принимает любое значение типа. Без этого CHECK'а
  -- строка со статусом «Завершена» прошла бы мимо всех проверок выше — без договорённости и без
  -- факта, — потому что они спрашивают `confirmed` и `done` поимённо.
  CONSTRAINT mech_requests_status_check CHECK (status <> 'completed'),
  -- Составной ключ вместо простого (Р6, приём ADR 0018 §15): им проверяется не только «такой
  -- контрагент есть», но и «он именно арендодатель и он активен». `ON UPDATE CASCADE` держит
  -- денормализованную активность в синхронности — деактивация арендодателя сама перепишет
  -- `lessor_is_active` у всех его заявок, и рассинхронизироваться копия не может. `ON DELETE
  -- RESTRICT` — контрагента, на которого ссылается заявка, из справочника не удалить; смену его
  -- ТИПА отклоняет `assertTypeChangeAllowed` своим сообщением, не доводя до ошибки ограничения.
  --
  -- Инварианта «у неактивного арендодателя не бывает действующих аренд» здесь НЕТ, в отличие от
  -- vehicles (0038), и это решение: заявка — это история, а не предложение. Арендодателя погасили
  -- посреди аренды — техника всё равно стоит на объекте, и её надо вернуть и оплатить.
  -- Назначаемость на сегодня («существует, не удалён, активен, нужного типа») проверяет сервис при
  -- ВЫБОРЕ арендодателя, по образцу `assertOperatorAssignable`.
  CONSTRAINT mech_requests_lessor_fk FOREIGN KEY (lessor_id, lessor_type, lessor_is_active)
    REFERENCES counterparties (id, type, is_active) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- Номер показывают человеку и по нему ищут; `IDENTITY` раздаёт значения без повторов, но
-- уникальность номера — свойство модуля, а не последовательности, и держать его должна база.
CREATE UNIQUE INDEX mech_requests_num_unique ON mech_requests (num);
-- Реестр открывается вкладками по статусу, а сводка считает по нему же.
CREATE INDEX mech_requests_status_idx ON mech_requests (status);
-- Вход области: любой список модуля начинается с отбора по площадкам роли (Р10).
CREATE INDEX mech_requests_object_idx ON mech_requests (object_id);
-- Второй вход области — отдельский; частичный, потому что у заявок площадок колонка пуста, и в
-- отборе по отделу такие строки не участвуют никогда.
CREATE INDEX mech_requests_department_idx ON mech_requests (department_id)
  WHERE department_id IS NOT NULL;
-- ДЕЙСТВУЮЩИЕ АРЕНДЫ — предикат из трёх частей, тот же самый, что во вкладке «В аренде», в сводке,
-- в расчёте просрочки и в проверке права на продление (Р2). Пятое место, где он написан, — этот
-- индекс, и разойтись с остальными четырьмя ему нельзя: расходится — и просрочка считается по
-- одному набору строк, а показывается по другому. По `planned_to`, потому что вопрос к вкладке
-- всегда один: у кого срок вышел или выходит.
CREATE INDEX mech_requests_active_rent_idx ON mech_requests (planned_to)
  WHERE status = 'confirmed' AND actual_from IS NOT NULL AND actual_to IS NULL;
-- Вход со стороны справочника: «что арендовали у этой компании» и проверка `RESTRICT` при попытке
-- её удалить. Частичный — у заявки без договорённости колонка пуста по построению.
CREATE INDEX mech_requests_lessor_idx ON mech_requests (lessor_id) WHERE lessor_id IS NOT NULL;
-- Подсказка видов и группировка отчётов идут по нормализованному ключу, а не по написанию (Р5).
CREATE INDEX mech_requests_kind_key_idx ON mech_requests (kind_key);
-- Умолчательная сортировка реестра — свежие сверху.
CREATE INDEX mech_requests_created_at_idx ON mech_requests (created_at);

-- Архив (ADR 0070) отбирается ровно по этой колонке — `archive=only` не имеет других условий, —
-- и без индекса вкладка читала бы всю таблицу ради десятка удалённых строк. Частичный: живых
-- заявок в разы больше, а спрашивают их всегда с `deleted_at IS NULL`, для которого индекс не
-- нужен. В §6 плана его не было; добавлен по итогам сборки, когда стало видно, чем отбирают архив.
CREATE INDEX mech_requests_deleted_at_idx ON mech_requests (deleted_at)
  WHERE deleted_at IS NOT NULL;

-- ── 3. История статусов ──
--
-- СВОЯ ТАБЛИЦА, А НЕ ОБЩАЯ `request_status_history`: та ссылается внешним ключом прямо на
-- `waste_requests` и вторым модулем не делится — ровно так же в своё время завелась
-- `vehicle_request_status_history`. Переход туда пишется вместе с причиной: у отмены она
-- обязательна, и без неё «заявку отменили» не объясняет ничего.
CREATE TABLE mech_request_status_history (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- `CASCADE`: история — это часть заявки, а не самостоятельный документ. Удалили заявку насовсем
  -- (`records.purge`) — истории существовать не от чего; то, что должно пережить строку, уходит в
  -- общий журнал аудита снимком.
  request_id uuid NOT NULL REFERENCES mech_requests (id) ON DELETE CASCADE,
  -- Пусто у самой первой записи: у заведения предыдущего статуса нет.
  from_status request_status,
  to_status request_status NOT NULL,
  -- `NOT NULL`, в отличие от соседней `request_status_history`, где 0195 обязательность снял. Там
  -- она мешала записать перевод ВЫКАТОМ — переход без человека; у механизации таких переходов нет
  -- ни одного, все они — решения людей, и запись без автора означала бы потерянную историю.
  changed_by uuid NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  changed_at timestamptz NOT NULL DEFAULT now(),
  comment text NOT NULL DEFAULT ''
);

-- Единственный вопрос к таблице — «что было с этой заявкой»: лента карточки читает её по заявке.
CREATE INDEX mech_request_status_history_request_idx
  ON mech_request_status_history (request_id);

-- ── 4. Вложения ──
--
-- По образцу `vehicle_request_files` (Р14): PK — пара, `UNIQUE(file_id)` — файл не в двух заявках
-- механизации сразу; кросс-модульную уникальность обеспечивает общий файловый сервис.
CREATE TABLE mech_request_files (
  request_id uuid NOT NULL REFERENCES mech_requests (id) ON DELETE CASCADE,
  -- `CASCADE` на файл: строка связи без файла не значит ничего. Обратная сторона — удаление самих
  -- файлов при снятии вложения, физическом удалении «Новой» и `purge` — работа маршрутов, и путей
  -- там ТРИ, а не два (Р14): забытый путь оставит в `files` живую и ничью запись.
  file_id uuid NOT NULL REFERENCES files (id) ON DELETE CASCADE,
  added_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (request_id, file_id)
);

CREATE UNIQUE INDEX mech_request_files_file_unique ON mech_request_files (file_id);

-- ── 5. Реестр файловых связей ──
--
-- Модуль, о котором не знает `file_is_linked(uuid)`, отдаёт свои вложения загрузившему их человеку
-- БЕССРОЧНО: `decideFileAccess` считает такой файл ничьим, а ничей файл доступен автору загрузки.
-- Однажды это уже случилось — миграция 0225 чинила ровно это у сканов аудита талонов.
--
-- `CREATE OR REPLACE` повторяет полный актуальный перечень из 0225 (последней версии функции) плюс
-- новую ветку. Тело SQL-функции заменяется ЦЕЛИКОМ: пропущенная прежняя ветка молча сняла бы защиту
-- с чужого модуля — и заметили бы это не по ошибке, а по чужому файлу, открывшемуся постороннему.
CREATE OR REPLACE FUNCTION file_is_linked(p_file_id uuid) RETURNS boolean
  LANGUAGE sql STABLE PARALLEL SAFE
AS $$
  SELECT
    -- Вложения и талоны заявок на вывоз мусора (ADR 0024).
    EXISTS (SELECT 1 FROM request_files WHERE file_id = p_file_id)
    -- Вложения заявок на технику.
    OR EXISTS (SELECT 1 FROM vehicle_request_files WHERE file_id = p_file_id)
    -- Сканы, подшитые к путевому листу (миграция 0087).
    OR EXISTS (SELECT 1 FROM waybill_files WHERE file_id = p_file_id)
    -- Документы заявок на обслуживание оргтехники (ADR 0084, миграция 0105).
    OR EXISTS (SELECT 1 FROM service_request_files WHERE file_id = p_file_id)
    -- Фотографии показаний техники (миграция 0132).
    OR EXISTS (SELECT 1 FROM vehicle_reading_files WHERE file_id = p_file_id)
    -- Сканы документов работника (миграция 0019).
    OR EXISTS (SELECT 1 FROM person_credential_files WHERE file_id = p_file_id)
    -- Сканы актов ТО (миграция 0147).
    OR EXISTS (SELECT 1 FROM vehicle_maintenance_files WHERE file_id = p_file_id)
    -- Исходный скан наблюдения качества распознавания (ADR 0137, миграция 0210).
    OR EXISTS (SELECT 1 FROM waste_ticket_field_events WHERE file_id = p_file_id)
    -- Вложения заявок на аренду малой механизации (эта миграция).
    OR EXISTS (SELECT 1 FROM mech_request_files WHERE file_id = p_file_id)
$$;

COMMENT ON FUNCTION file_is_linked(uuid) IS
  'Файл привязан хоть к одной сущности портала или событию аудита распознавания. Единственный '
  'источник правды для проверки привязываемости, доступа, явного удаления и фоновой уборки. '
  'Скан наблюдения освобождается явно только при полном удалении заявки.';
