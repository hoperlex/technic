-- Журнал распознавания и разбора талонов: событие на ПОЛЕ (ADR 0114, Р30/Р31).
--
-- Зачем отдельная таблица, когда есть попытки, талоны и общий `audit_log`.
--
-- Попытка знает, ЧТО ответила модель, но не знает, что с этим стало: подтвердил человек цифру или
-- переписал. Талон знает итог, но помнит только последнее значение — прежнее затирается правкой.
-- `audit_log` фиксирует факт («правили объём»), но не значения: по нему нельзя ответить, как часто
-- модель путает 38 с 3. То есть самый сильный сигнал качества — исправление оператора — сегодня
-- пропадает целиком.
--
-- СОБЫТИЕ НА ПОЛЕ, А НЕ НА ТАЛОН. Метрика нужна по полям: номер читается типографский и почти не
-- ошибается, объём стоит денег, адрес путается чаще всех. Строка на талон заставила бы разбирать
-- jsonb в каждом запросе и не дала бы индекса по полю.
--
-- ЗНАЧЕНИЯ ТЕКСТОМ, КАК ПОКАЗАНО ЧЕЛОВЕКУ. Не числом и не датой: смысл журнала в том, чтобы
-- увидеть «прочитано 3, верно 38» и «прочитано 2020-08-18, верно 2026-08-18». Приведение к типу
-- стёрло бы половину случая — обрезанный номер `262` и пустая строка выглядели бы одинаково.
--
-- ПОДТВЕРЖДЕНИЕ НЕ ПИШЕТСЯ. Соблазн записывать «человек согласился с полем» велик — казалось бы,
-- вот и знаменатель. Но это пять строк на каждый талон ради слабейшего из сигналов: человек
-- смотрит на подставленное значение и склонен согласиться (Р31), так что «подтверждено» не
-- означает «прочитано верно». Знаменатель берётся по `recognized`: сколько модель прочитала, из
-- них столько-то исправили. Согласие остаётся видно и без событий — по `confirmed_at` талона.
--
-- СРОК ХРАНЕНИЯ НЕ ЗАДАН, и уборки по времени здесь НЕТ намеренно (в отличие от попыток, Р31).
-- Метрика тем полезнее, чем длиннее ряд: сравнить модель в августе и в феврале можно, только имея
-- февраль. Строка весит десятки байт, поток — сотни талонов в месяц; когда объём станет заметен,
-- уборка добавляется отдельным решением. Чтобы этот момент не пропустить, размер таблицы выведен
-- метрикой `technic_ticket_field_events`.
--
-- СОБЫТИЕ ПЕРЕЖИВАЕТ ОТКАТ ЗАЯВКИ. Распознанное уносится при откате (Р22), но качество модели —
-- свойство содержимого, а не заявки: талон, прочитанный неверно и потому откаченный, для метрики
-- ценнее прочих. Ссылки на талон и заявку поэтому `ON DELETE SET NULL`, как у попыток (Р12).
CREATE TABLE waste_ticket_field_events (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),

  -- Кто и о чём. Ссылки обнуляемые: строка живёт дольше и заявки, и талона.
  ticket_id uuid REFERENCES waste_tickets (id) ON DELETE SET NULL,
  request_id uuid REFERENCES waste_requests (id) ON DELETE SET NULL,
  -- Хэш растра страницы: единственная связь, которую нельзя потерять. По нему событие
  -- сопоставляется с попыткой, даже когда талон уже удалён откатом.
  page_sha256 char(64) NOT NULL DEFAULT '',

  -- Что случилось с полем.
  --   recognized — модель прочитала (значение — то, что записано в талон);
  --   disputed   — проходы каскада разошлись, поле осталось пустым (Р14);
  --   edited     — человек исправил значение;
  --   proposal   — принято предложение перераспознавания (Р13);
  --   arbitrated — арбитр слепой перепроверки назвал верное значение (сильный сигнал, Р31);
  --   dismissed  — талон снят как «не талон».
  event text NOT NULL,
  field text NOT NULL,

  old_value text,
  new_value text,

  -- Чем читали. Заказанная и фактическая модель — разные величины (Р7), и метрика качества
  -- привязана к фактической: при варианте A за одним слагом стоят разные модели.
  model text NOT NULL DEFAULT '',
  model_reported text NOT NULL DEFAULT '',
  prompt_version integer,
  preprocessing_version integer,
  -- Сколько проходов каскада отработало по этой странице (1 — только дешёвая, 2 — с эскалацией) и
  -- была ли эскалация. Без этих двух чисел нельзя ответить, окупается ли вторая ступень.
  passes smallint NOT NULL DEFAULT 0,
  escalated boolean NOT NULL DEFAULT false,

  -- Кто из людей. `NULL` у машинных событий — их совершила модель, а не человек.
  actor_id uuid REFERENCES users (id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT waste_ticket_field_events_event_check CHECK (
    event IN ('recognized', 'disputed', 'edited', 'proposal', 'arbitrated', 'dismissed')
  ),
  CONSTRAINT waste_ticket_field_events_field_check CHECK (
    field IN ('number', 'issuedOn', 'volumeM3', 'workKind', 'addressRaw')
  ),
  -- Правка обязана назвать обе стороны: «стало» без «было» не отвечает на вопрос, чью ошибку
  -- исправили. Пустое прежнее значение при этом законно — модель могла вернуть `null`.
  CONSTRAINT waste_ticket_field_events_edit_check CHECK (
    event <> 'edited' OR new_value IS NOT NULL
  ),
  -- Машинное событие с человеком — неправда: `recognized` и `disputed` совершила модель.
  --
  -- Обратное НЕ проверяется, и это не забывчивость. Ссылка на учётку объявлена `ON DELETE SET
  -- NULL`: удалили сотрудника — у его прошлых правок актор обнулился. Требуй мы человека у каждого
  -- человеческого события, удаление учётки падало бы нарушением ограничения, то есть журнал
  -- качества запрещал бы кадровые действия. «След потерян» — приемлемая цена; кто именно правил,
  -- остаётся в общем `audit_log`.
  CONSTRAINT waste_ticket_field_events_actor_check CHECK (
    event NOT IN ('recognized', 'disputed') OR actor_id IS NULL
  ),
  CONSTRAINT waste_ticket_field_events_passes_check CHECK (passes BETWEEN 0 AND 2),
  CONSTRAINT waste_ticket_field_events_sha_check CHECK (
    page_sha256 = '' OR page_sha256 ~ '^[0-9a-f]{64}$'
  )
);

-- Выгрузка идёт по модели и полю за период — это её единственный запрос.
CREATE INDEX waste_ticket_field_events_model_idx
  ON waste_ticket_field_events (model_reported, field, created_at DESC);
-- Разбор конкретного талона: «что с ним делали» — второй по частоте вопрос.
CREATE INDEX waste_ticket_field_events_ticket_idx
  ON waste_ticket_field_events (ticket_id, created_at)
  WHERE ticket_id IS NOT NULL;
-- Уборка по сроку ходит по времени.
CREATE INDEX waste_ticket_field_events_created_idx
  ON waste_ticket_field_events (created_at);
