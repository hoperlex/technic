-- Справочник ТТХ и их привязка к типам ТС (ADR 0016, наполнение — ADR 0023).
--
-- Состав характеристик выведен из двух прайсов аренды и из открытых данных по собственному парку:
-- берём ровно те величины, которыми документы РАЗЛИЧАЮТ технику внутри типа. Всё, что различает
-- позиции навеской («ковш», «гидромолот», «вилы», «щётка») или базой («вездеход», «низкорамный»),
-- в ТТХ не идёт: в v1 значение только числовое (ADR 0016 §8), а место таким признакам —
-- в `vehicles.description` предложения аренды, которое и так входит в ключ уникальности.
--
-- Привязка = обязательность (ADR 0016 §2): каждая категория типа обязана иметь значение по
-- каждому привязанному ТТХ. Поэтому у типов, которые прайс не различает числом
-- (экскаваторы-погрузчики, ямобуры, поливомоечные машины, тягачи, легковые), ТТХ нет вовсе —
-- такой тип сам является конечной классификацией.
--
-- Идемпотентно: по `code` у ТТХ, по PK (vehicle_type_id, spec_id) у привязок.

-- ── 1. Характеристики ───────────────────────────────────────────────────────────────────────
-- `unit` и `decimals` замораживаются после первого значения (ADR 0016 §9) — оба выбраны с запасом.
--
-- Один знак после запятой у грузоподъёмности — сознательно. Она общая для автокрана 130 т и
-- мини-погрузчика 0,8 т, а источники по мини-погрузчикам дают номинальную и максимальную г/п с
-- разбросом в десятки килограммов (Mustang 2086 — 1179/1315 кг): второй знак развёл бы одинаковые
-- по смыслу машины по разным категориям.
INSERT INTO vehicle_specs (code, name, short_name, unit, decimals, min_value, max_value, description, sort_order) VALUES
  ('lift_capacity',    'Грузоподъёмность',         'г/п',        'т',  1, 0.1, 500, 'Паспортная грузоподъёмность машины: крана, погрузчика, бортового автомобиля', 10),
  ('boom_capacity',    'Грузоподъёмность стрелы',  'стрела г/п', 'т',  1, 0.1,  50, 'Грузоподъёмность крано-манипуляторной установки — отдельно от г/п самой машины', 20),
  ('lift_height',      'Высота подъёма',           'высота',     'м',  1,   1, 100, 'Максимальная высота подъёма рабочей платформы', 30),
  ('body_volume',      'Объём кузова',             'кузов',      'м³', 1, 0.5,  60, 'Геометрический объём самосвальной платформы', 40),
  ('operating_weight', 'Эксплуатационная масса',   'масса',      'т',  1, 0.1, 200, 'Масса машины в рабочем состоянии — по ней различают катки, бульдозеры и экскаваторы', 50),
  ('hammer_count',     'Количество молотков',      'молотков',   '',   0,   1,  10, 'Число отбойных молотков, обслуживаемых компрессором', 60)
ON CONFLICT (code) DO NOTHING;

-- ── 2. Привязка к типам ─────────────────────────────────────────────────────────────────────
-- У кранов только грузоподъёмность, без длины стрелы: восемь из десяти арендных позиций стрелу
-- не называют («Автокран г/п 70 т»), и привязка стрелы оставила бы их без категории вовсе.
-- Названную в прайсе стрелу сохраняет описание предложения.
--
-- У фронтальных погрузчиков — грузоподъёмность, а не объём ковша: ковш сменный, и открытые
-- источники по одной и той же SDLG LG936L дают 1,8 / 2 / 3 м³, тогда как г/п у неё всегда 3500 кг.
INSERT INTO vehicle_type_specs (vehicle_type_id, spec_id, sort_order)
SELECT t.id, s.id, x.sort_order
FROM (VALUES
  ('truck_cranes',          'lift_capacity',    10),
  ('pneumatic_wheel_crane', 'lift_capacity',    10),
  ('mobile_crane',          'lift_capacity',    10),
  ('heavy_manipulators',    'lift_capacity',    10),
  ('heavy_manipulators',    'boom_capacity',    20),
  ('light_trucks',          'lift_capacity',    10),
  ('flatbed_trucks',        'lift_capacity',    10),
  ('forklift_miniloaders',  'lift_capacity',    10),
  ('front_loaders',         'lift_capacity',    10),
  ('aerial_platforms',      'lift_height',      10),
  ('dump_trucks',           'body_volume',      10),
  ('wheeled_excavators',    'operating_weight', 10),
  ('crawler_excavators',    'operating_weight', 10),
  ('road_rollers',          'operating_weight', 10),
  ('bulldozers',            'operating_weight', 10),
  ('compressors',           'hammer_count',     10)
) AS x(type_code, spec_code, sort_order)
JOIN vehicle_types t ON t.code = x.type_code
JOIN vehicle_specs s ON s.code = x.spec_code
ON CONFLICT (vehicle_type_id, spec_id) DO NOTHING;
