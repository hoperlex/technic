-- Роль «Площадка» (`site`) — значение перечисления. ADR 0112; план реструктуризации модели
-- доступа, §9 (пересмотр ролей), §11 (слой области) и §15, этап 4б.
--
-- Целевая объектная роль реформы: одна вместо трёх. После этапа 8 её получат учётки «Штаба»,
-- «Руководителя строительства» и «Коменданта», а различие между тремя должностями переедет в
-- полномочия — «Заказ техники» и «Виза объекта» (миграция 0153).
--
-- ОТДЕЛЬНЫМ ФАЙЛОМ, И ЭТО ЕДИНСТВЕННАЯ ПРИЧИНА ЕГО СУЩЕСТВОВАНИЯ. Раннер применяет миграцию целиком
-- в одной транзакции (`apps/api/src/db/migration-journal.ts`), а PostgreSQL не разрешает
-- пользоваться новым значением enum до её фиксации: `ALTER TYPE role ADD VALUE 'site'` рядом с
-- `INSERT INTO grant_roles ... 'site'::role` отвечает «unsafe use of new value "site" of enum type
-- role». Тот же приём — в миграциях 0049/0050, 0065, 0067, 0130 и 0138.
--
-- ПРАВ И ОБЛАСТИ ЗДЕСЬ НЕТ, И ЭТО НЕ ПРОПУСК. Права роли живут в матрице `@technic/contracts`
-- (ADR 0021), а не в базе; область — в `user_construction_objects` (миграция 0063), и обязательность
-- объекта у объектной роли держит приложение с тех пор, как оттуда ушёл `users_rukstroy_object_check`
-- (0063 его снял вместе с колонкой). Ни CHECK, ни таблиц связей вторым шагом роли поэтому не нужно.
--
-- ОБРАТИМОСТЬ. Значение перечисления в PostgreSQL штатно не удаляется, и обратимым файл не
-- становится. Пока роль никому не назначена — а этап 4б её не назначает, — схема ведёт себя ровно
-- как до наката, и откат кода безопасен: прежняя сборка про роль не знает, но и не встретит её ни в
-- одной строке `users`. Небезопасен откат кода станет после этапа 8, когда учётки переведут.

ALTER TYPE "role" ADD VALUE IF NOT EXISTS 'site' AFTER 'commandant';

-- Пожелание при регистрации (`registration_role_request`) новым значением НЕ пополняется, и это
-- решение, а не забытая строка. Пожелание — то, как человек называет себя в заявке («Сотрудник
-- объекта», «Комендант»), а не роль, которую ему назначат: таблица соответствия «пожелание →
-- предлагаемая роль» переезжает своим этапом (план §11.1, этап 5), и до перевода учёток умолчанием
-- обязана оставаться действующая роль. Подставь она `site` сегодня — администратор, приняв
-- умолчание, завёл бы сотруднику объекта учётку без заказа техники.
