COMMENT ON FUNCTION office_equipment_consumable_stock_chain() IS
  'Сверка цепочки журнала остатка (Р7): проверяет ОБА конца события — «было» против хвоста журнала '
  '(по seq), «стало» против остатка карточки, которую берёт FOR UPDATE сама, не полагаясь на '
