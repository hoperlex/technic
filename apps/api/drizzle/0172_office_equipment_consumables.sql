-- Расходники оргтехники: картриджи и тонеры (план `docs/office-equipment-consumables-plan.md`,
-- §5 «Модель данных», решения Р5–Р7 и Р11; этап 2, волна В5).
--
-- ЗАЧЕМ. Вопрос «чем заправить вот этот аппарат и сколько таких картриджей на складе» портал
-- сегодня не отвечает вовсе: справочник оргтехники (`0104`) знает парк, `0171` свёл его к моделям,
-- а самого расходника, его совместимости и остатка в базе нет. Ведут это письмом и таблицей, и
-- цена ошибки — вставший принтер: остаток 12 при 68 аппаратах и при 2 аппаратах означает разное
-- (Р15).
--
-- ЧТО ЗАВОДИТСЯ: карточка расходника, связь «расходник — модель» много-ко-многим, журнал движения
-- остатка, IMMUTABLE-функция правила написания кода и ТРИ триггера.
--
-- ПОРЯДОК ОТНОСИТЕЛЬНО СОСЕДА. Миграция обязана идти ПОСЛЕ `0171`: связь ссылается на
-- `office_equipment_models`, которых до неё не существует. Обратной зависимости нет — `0171`
-- о расходниках не знает.
--
-- ПОЧЕМУ ТРИГГЕРОВ ТРИ, А НЕ ОДИН. Обещание «каждое изменение остатка попадает в журнал, а журнал
-- не врёт» распадается на три разные двери, и одна проверка закрывает ровно одну из них:
--
--   цепочка (`BEFORE INSERT` на журнале) ....... ловит НЕВЕРНОЕ событие — «было» не то, что
--                                                оставило предыдущее, или «стало» не то, что лежит
--                                                в карточке; но молчит там, где события нет вовсе;
--   неизменяемость (`BEFORE UPDATE OR DELETE`) . запрещает подчистить прошлое: `RESTRICT` со
--                                                стороны расходника историю целиком защищает,
--                                                а построчную правку — нет;
--   покрытие (отложенный constraint-триггер) ... ловит ОТСУТСТВИЕ события: `UPDATE ... SET quantity
--                                                = 7` скриптом проходит мимо первых двух насквозь.
--
-- Вместе они замыкают круг: событие без правки карточки не проходит цепочку (её «стало» обязано
-- равняться остатку, а «стало» ≠ «было» требует `CHECK`), правка карточки без события не проходит
-- покрытие, а исправить задним числом уже записанное нельзя. Границу стоит назвать честно:
-- `TRUNCATE` строковых триггеров не вызывает вовсе — от него защищают права, а не схема.
--
-- ОБРАТИМОСТЬ. Миграция аддитивная: три новые таблицы, одна функция правила и триггеры на этих же
-- новых таблицах. Существующие данные не читаются и не меняются, поэтому и блокировки первой
-- строкой здесь нет — в отличие от `0171`, где снимок парка обязан был читаться уже под ней.
-- Протокол выката необратимых миграций (`docs/schema-cutover-protocol.md`) к ней не применяется.

-- ── 1. Правило написания кода ──
--
-- Код номенклатуры учётной системы («Б0000014256», «Д0000337741») — это буква серии и десять
-- цифр, склеенных в одно слово. Уникальность по нему нужна всегда: две строки с одним кодом — это
-- не два расходника, а один, заведённый дважды, и заказ по такому справочнику уедет вдвое меньшим.
--
-- ПРАВИЛО ДЛЯ КОДА ДРУГОЕ, ЧЕМ ДЛЯ ИМЕНИ МОДЕЛИ (`office_equipment_model_key`, `0171`), и это не
-- небрежность:
--
--   · пробелы УДАЛЯЮТСЯ, а не схлопываются в один. В коде их не бывает вовсе, поэтому пробел
--     внутри — всегда мусор переноса (Excel, письмо, выгрузка из учётной системы), а не часть кода.
--     Схлопывание оставило бы «Д000 0093569» отдельной строкой справочника — двойником, которого
--     глазами не отличить, потому что различие в нём и есть невидимый символ;
--   · регистр поднимается. У модели он значащий («ECOSYS», «i-Sensys» — фирменные написания), у
--     кода — нет: серия набирается вручную, и «б0000014256» с маленькой буквы — опечатка ввода, а
--     не другой код. Ровно это и просит Р5, описывая уникальность как `upper(btrim(code))`.
--
-- Класс символов шире `\s` по той же причине, что и в `0171`: неразрывные пробелы U+00A0 и U+202F
-- в локали базы пробелами НЕ считаются, а приезжают они постоянно — Word ставит U+00A0
-- автозаменой, а разряды в выгрузках разделяет узкий U+202F. В тексте они записаны escape-видом
-- `\uXXXX`, который понимает регулярное выражение Postgres, а не собой: невидимый байт в файле
-- миграции нельзя вычитать на ревью, а любой редактор способен его потерять или заменить.
--
-- Чего правило НЕ делает — не сводит визуальных двойников: кириллическая «В» и латинская «B»
-- остаются разными кодами. Это сознательная граница: подмена буквы на похожую — уже угадывание, а
-- не нормализация, и ошибиться в ней означало бы склеить две настоящие номенклатуры в одну. Такой
-- двойник ловится сверкой со счётом, ради которой наименование и хранится дословно (Р5).
--
-- ФУНКЦИЯ, А НЕ ПОВТОРЁННОЕ ВЫРАЖЕНИЕ — по тем же причинам, что у моделей: правило нужно в трёх
-- местах сразу (уникальный индекс, `CHECK` ниже и проверка занятости кода в маршруте, которая
-- обязана ответить «расходник с таким кодом уже заведён», а не 500 с именем индекса). Разойдясь
-- хоть на символ, маршрут перестанет находить то, что отвергает индекс, — и человек получит ровно
-- ту пятисотку, ради которой проверку и писали.
--
-- `IMMUTABLE` — требование индекса по выражению. Отсюда же и цена: `CREATE OR REPLACE` этой функции
-- молча меняет смысл индекса и `CHECK` ниже, а построенный индекс продолжает считать по-старому.
-- Менять правило можно только миграцией, которая перестраивает индекс и заново сводит справочник.
CREATE FUNCTION office_equipment_consumable_code_key(t text) RETURNS text
  LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE
AS $$
  SELECT upper(regexp_replace(t, '[\s\u00a0\u202f]+', '', 'g'))
$$;

COMMENT ON FUNCTION office_equipment_consumable_code_key(text) IS
  'Ключ кода номенклатуры (docs/office-equipment-consumables-plan.md Р5): верхний регистр, все '
  'пробелы выброшены, включая неразрывные. По нему уникальность кода держит индекс '
  'office_equipment_consumables_code_unique, его же зовёт маршрут, отвечая «код уже заведён». '
  'IMMUTABLE ради индекса по выражению: правка функции меняет смысл индекса, но не его содержимое.';

-- ── 2. Карточка расходника (Р5) ──
CREATE TABLE office_equipment_consumables (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Код номенклатуры учётной системы. Хранится уже нормализованным (см. `CHECK` ниже), то есть в
  -- верхнем регистре и без пробелов.
  code text NOT NULL,
  -- Наименование ДОСЛОВНО как в учётной системе, вместе с хвостом «(шт)»: справочник сверяют
  -- глазами со счётом и выгрузкой, и «причёсанное» наименование эту сверку ломает (Р5). Поэтому
  -- никакой нормализации у имени нет — ни свёртки пробелов, ни регистра, ни обрезки хвоста.
  -- Отдельного поля «единица измерения» нет: штуки единственная.
  name text NOT NULL,
  -- Остаток на складе. Портал его не вычисляет — складского учёта у ИТ-службы нет (Р7); он вводится
  -- человеком, но не формой карточки, а отдельной ручкой, пишущей событие в журнал. Три триггера
  -- ниже и делают это правилом базы, а не договорённостью маршрута.
  quantity integer NOT NULL DEFAULT 0,
  -- Расходник, который больше не покупают, гасят флагом (Р11): у него остаются привязки к моделям
  -- и, скорее всего, история движения.
  is_active boolean NOT NULL DEFAULT true,
  -- Цвет позиции (Р5). Свойство КАРТОЧКИ, а не строки заявки: складская позиция определяется кодом,
  -- и если учётная система ведёт чёрный, голубой, пурпурный и жёлтый отдельными кодами — это четыре
  -- позиции, у каждой свой остаток. Код на комплект заводится позицией с цветом «комплект»: один
  -- комплект нельзя разложить на четыре виртуальных остатка, не имея четырёх исходных кодов.
  --
  -- Текстом, а не перечнем: источник приносит не только CMYK, но и «комплект», и поставщицкие
  -- названия. В уникальность цвет не входит и код не заменяет — он помогает выбрать позицию в
  -- заявке. Отсутствие цвета — это `NULL`; пустая строка запрещена ограничением ниже, иначе
  -- «нет цвета» имело бы два разных представления.
  color text,
  -- Свободный текст: особенности позиции, которых нет в номенклатуре поставщика.
  comment text NOT NULL DEFAULT '',
  -- Авторы правки карточки. `SET NULL`, как у карточек техники (`0104`): справочник переживает
  -- увольнение своего автора, и удерживать учётку ради строки справочника незачем. У СОБЫТИЯ
  -- остатка правило противоположное и объяснено на своём месте.
  created_by uuid REFERENCES users (id) ON DELETE SET NULL,
  updated_by uuid REFERENCES users (id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  -- Пустой код проверяется той же функцией, а не `btrim`: строка из одного неразрывного пробела для
  -- `btrim` не пуста, а кодом при этом не является.
  CONSTRAINT office_equipment_consumables_code_not_blank_check
    CHECK (office_equipment_consumable_code_key(code) <> ''),
  -- Код хранится уже нормализованным. Без этой проверки правило держал бы только индекс — то есть
  -- ключ; а в самой карточке остался бы «Д000 0093569 » с хвостом и внутренним пробелом:
  -- уникальность соблюдена, дефект тихий, и ломает он ровно ту сверку глазами со счётом, ради
  -- которой наименование хранится дословно. Отказ здесь — это 500 у маршрута, поленившегося
  -- нормализовать ввод, и он честнее испорченного справочника: функция маршруту доступна.
  CONSTRAINT office_equipment_consumables_code_normalized_check
    CHECK (code = office_equipment_consumable_code_key(code)),
  -- В наименовании обязан быть хотя бы один НАСТОЯЩИЙ знак, и меряется это непустотой строки после
  -- удаления пробельных, а не `btrim`. `btrim` без второго аргумента снимает только края и только
  -- обычные пробелы: имя из одного U+00A0 он считает непустым, и в справочник встала бы строка,
  -- выглядящая пустой, — с кодом, остатком и привязками, но без имени, по которому её ищут.
  -- Сегодня такую строку отбивает форма (zod `.trim()` в JS неразрывные снимает, а `min(2)`
  -- добивает), и это ровно тот случай, который в этом выкате уже чинили у моделей: инвариант,
  -- держащийся совпадением двух РАЗНЫХ правил на двух языках, обязан жить в схеме — дверей в
  -- справочник больше одной (форма, обмен файлом, скрипт), и договариваться с каждой порознь не
  -- выйдет.
  --
  -- Выражением на месте, а не функцией: правило нужно ровно здесь и больше нигде. Функция означала
  -- бы, что наименование где-то нормализуют, — а Р5 запрещает это прямо: имя хранится дословно,
  -- вместе с хвостом «(шт)» и любыми внутренними пробелами, включая неразрывные. «Тонер<NBSP>Ricoh
  -- 201» законен и остаётся как есть — схлопывать его, в отличие от кода, портал не собирается.
  --
  -- Функцию кода звать для этого нельзя, и не только из-за верхнего регистра, который к вопросу о
  -- пустоте отношения не имеет: она отвечает «один ли это код», а здесь спрашивают «есть ли в
  -- строке хоть что-нибудь». Общий у них только класс пробельных символов, объяснённый один раз — в
  -- разделе 1; расходиться этим двум местам не страшно, потому что и вопросы у них разные.
  CONSTRAINT office_equipment_consumables_name_not_blank_check
    CHECK (regexp_replace(name, '[\s\u00a0\u202f]+', '', 'g') <> ''),
  -- Отрицательный остаток не бывает даже промежуточно: «минус два картриджа» — это не долг, а
  -- ошибка ввода, и записать её значило бы соврать заказу.
  CONSTRAINT office_equipment_consumables_quantity_check CHECK (quantity >= 0),
  -- «Нет цвета» пишется `NULL` и только им. Пустая строка означала бы то же самое вторым способом,
  -- а два представления одного состояния расходятся на первом же отборе «позиции без цвета».
  CONSTRAINT office_equipment_consumables_color_not_blank_check
    CHECK (color IS NULL OR btrim(color) <> '')
);

COMMENT ON TABLE office_equipment_consumables IS
  'Расходники оргтехники — картриджи и тонеры (docs/office-equipment-consumables-plan.md §5): код '
  'номенклатуры, дословное наименование и остаток, который правится только событием журнала.';

-- Ключ по ФУНКЦИИ, хотя `CHECK` выше и делает его сегодня равносильным `UNIQUE (code)`: раз код
-- хранится уже нормализованным, одинаковые ключи означают одинаковые строки. Равносильность — это
-- следствие соседнего ограничения, а не свойство ключа, и записывать её в индекс нельзя: первая же
-- миграция, ослабившая `CHECK` (например, ради дословного регистра из учётной системы), молча
-- превратила бы уникальность в регистрозависимую — то есть пустила бы в справочник двойника ровно
-- тем движением, которое казалось послаблением. Заодно правило сравнения видно в самом ключе, а
-- маршруту есть с чем сойтись в `ON CONFLICT`: арбитра Postgres сопоставляет с индексом дословно.
CREATE UNIQUE INDEX office_equipment_consumables_code_unique
  ON office_equipment_consumables (office_equipment_consumable_code_key(code));

-- Поиск идёт по наименованию подстрокой («тонер 201»), тем же способом, что в остальных
-- справочниках (`0022`, `0104`). Кода в индексе нет намеренно: его ищут целиком, и на это работает
-- уникальный индекс выше, а `ILIKE` по коду на полутора десятках строк дешевле любого индекса.
CREATE INDEX office_equipment_consumables_name_trgm
  ON office_equipment_consumables USING gin (name gin_trgm_ops);

-- ── 3. Совместимость — связь много-ко-многим (Р6) ──
--
-- Связь именно много-ко-многим, и это не запас на будущее, а разбор присланной таблицы: PC-211EV
-- подходит трём моделям Pantum, а одной C2011SP годятся и чёрный, и цветной. Любая из односторонних
-- связей списала бы половину случаев из того же самого списка.
CREATE TABLE office_equipment_consumable_models (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- `CASCADE`: привязка — разметка совместимости, а не история. Удаляют расходник только пока по
  -- нему нет движения (журнал ниже держит это `RESTRICT`), и тащить за собой разметку в этот момент
  -- нечего — она осмысленна ровно пока жив расходник.
  consumable_id uuid NOT NULL REFERENCES office_equipment_consumables (id) ON DELETE CASCADE,
  -- `RESTRICT`: модель, к которой привязан расходник, не удаляется (Р11). Иначе картридж молча
  -- потерял бы половину ответа на вопрос «к чему подходит», и заметить это было бы нечем.
  model_id uuid NOT NULL REFERENCES office_equipment_models (id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT office_equipment_consumable_models_unique UNIQUE (consumable_id, model_id)
);

COMMENT ON TABLE office_equipment_consumable_models IS
  'Совместимость «расходник — модель аппарата» (docs/office-equipment-consumables-plan.md Р6): '
  'разметка, а не история — снимается свободно с обеих сторон.';

-- Индекс по второй стороне связи. В §5 плана его нет, но обе задачи, которые ходят от модели,
-- читают именно её: «чем заправлять вот этот аппарат» в карточке единицы (Р15) и срез «модели без
-- расходника» в окне моделей, плюс проверка `RESTRICT` при попытке удалить модель. Уникальный ключ
-- выше начинается с расходника и на эти вопросы не работает.
CREATE INDEX office_equipment_consumable_models_model_idx
  ON office_equipment_consumable_models (model_id);

-- ── 4. Журнал движения остатка (Р7) ──
CREATE TABLE office_equipment_consumable_stock_entries (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Порядок держит счётчик, а не время: две правки одной секунды по `created_at` неразличимы, а
  -- цепочка «было — стало» обязана строиться однозначно (приём `app_releases.seq`). По этому номеру
  -- обе проверки журнала находят его хвост — `ORDER BY seq DESC LIMIT 1` и в сверке цепочки, и в
  -- отложенной проверке покрытия ниже.
  --
  -- `GENERATED ALWAYS` означает здесь «номер раздаёт база, и назначать его не приходится», но НЕ
  -- означает «назначить нельзя»: `INSERT ... OVERRIDING SYSTEM VALUE` вписывает свой номер, и эта
  -- оговорка ему не помеха (проверено на dev-базе). Порядок держится не запретом, а тем, куда
  -- смотрят обе проверки: событие с подложенным маленьким номером сверку цепочки ПРОХОДИТ — та
  -- сравнивает его «было» с хвостом, — но отложенная проверка покрытия на коммите сверяет остаток
  -- карточки со «стало» ХВОСТА, а не подложенной строки, и отменяет транзакцию целиком. Ровно на
  -- это есть тест: «номер события назначить вставкой можно, а порвать хвост журнала — нельзя».
  seq bigint GENERATED ALWAYS AS IDENTITY,
  -- `RESTRICT`, а не `CASCADE`: правило «появилось движение — только гашение флагом» (Р11) держит
  -- схема, а не вежливость маршрута. Пока журнал пуст, расходник удаляется совсем — так убирают
  -- опечатку первого дня.
  consumable_id uuid NOT NULL REFERENCES office_equipment_consumables (id) ON DELETE RESTRICT,
  -- Вид события (план переработки заявок, §2.1 и Р4): `manual` — ручная правка кладовщика,
  -- `issue` — выдача по заявке, `return` — возврат выданного. `DEFAULT 'manual'` сохраняет контракт
  -- ручной ручки: вид она пишет сама, клиент его не выбирает и выдать правку за списание не может.
  entry_kind text NOT NULL DEFAULT 'manual',
  -- Заявка, по которой прошло движение. Связь ссылкой, а не разбором текста причины: по тексту не
  -- построить ни отчёт «сколько выдано по заявкам за период», ни адресное сторно, ни запрет удалить
  -- заявку, за которой числится движение. `RESTRICT` и обеспечивает последнее.
  service_request_id uuid REFERENCES service_requests (id) ON DELETE RESTRICT,
  -- Строка заявки, из которой выдали. Пока БЕЗ внешнего ключа — таблицы `service_request_consumables`
  -- ещё не существует, её создаёт M12 плана переработки заявок и той же миграцией достраивает
  -- СОСТАВНОЙ ключ `(service_request_consumable_id, service_request_id, consumable_id)`. Составной,
  -- чтобы событие не могло указывать на строку другой заявки или другой позиции; `MATCH SIMPLE`
  -- (умолчание) там обязателен — ручное событие законно имеет пустые ссылки на заявку при
  -- заполненном `consumable_id`.
  --
  -- До M12 приложение не создаёт ни `issue`, ни `return`, поэтому колонка стоит пустой у всех строк,
  -- и отсутствие ключа ничего не ослабляет.
  service_request_consumable_id uuid,
  quantity_before integer NOT NULL,
  quantity_after integer NOT NULL,
  -- Причина обязательна: журнал без неё отвечает «стало 8» на вопрос «почему стало 8».
  reason text NOT NULL,
  -- `RESTRICT`, как `moved_by` у перемещений: запись «кто изменил остаток», теряющая автора вместе
  -- с увольнением, отвечает на свой единственный вопрос словом «неизвестно». Здесь это не строка
  -- справочника, а событие, и `SET NULL` карточки ему не годится.
  changed_by uuid NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT office_equipment_consumable_stock_reason_check CHECK (btrim(reason) <> ''),
  -- Событие обязано что-то менять. Отсюда прямое следствие для заведения расходника: первая строка
  -- журнала пишется только при ненулевом остатке, а заведение с нулём — не событие, а отсутствие
  -- событий, и «0 → 0» это ограничение не пропустило бы.
  CONSTRAINT office_equipment_consumable_stock_change_check
    CHECK (quantity_after <> quantity_before),
  -- Оба конца неотрицательны: «было −1» не бывает так же, как «стало −1». Проверять только «стало»
  -- значило бы разрешить записать в историю то, чего не могло быть в карточке.
  CONSTRAINT office_equipment_consumable_stock_amount_check
    CHECK (quantity_after >= 0 AND quantity_before >= 0),
  CONSTRAINT office_equipment_consumable_stock_kind_check
    CHECK (entry_kind IN ('manual', 'issue', 'return')),
  -- Вид события и ссылки на заявку — одно утверждение, а не два соседних поля: «ручная правка» и
  -- «списано по заявке СО-1234» не бывают наполовину. Ручное событие обязано иметь ОБЕ ссылки
  -- пустыми, событие по заявке — обе заполненными; иначе в журнале появилась бы выдача, не знающая
  -- своей заявки, или ручная правка, притворяющаяся выдачей.
  CONSTRAINT office_equipment_consumable_stock_request_links_check
    CHECK (
      (entry_kind = 'manual'
        AND service_request_id IS NULL
        AND service_request_consumable_id IS NULL)
      OR (entry_kind IN ('issue', 'return')
        AND service_request_id IS NOT NULL
        AND service_request_consumable_id IS NOT NULL)
    ),
  -- Направление движения задано видом события. Без этого «возврат», уменьшающий остаток, прошёл бы
  -- в журнал и сделал отчёт по расходу неверным при верной цепочке: сумма `issue − return` считает
  -- по видам, а не по знаку разницы.
  CONSTRAINT office_equipment_consumable_stock_direction_check
    CHECK (
      entry_kind = 'manual'
      OR (entry_kind = 'issue' AND quantity_after < quantity_before)
      OR (entry_kind = 'return' AND quantity_after > quantity_before)
    )
);

COMMENT ON TABLE office_equipment_consumable_stock_entries IS
  'Журнал движения остатка расходников (docs/office-equipment-consumables-plan.md Р7): append-only '
  'физически, порядок держит seq, цепочку «было — стало» сверяет триггер.';

-- Индекс отвечает на единственный частый вопрос журнала — «чем кончилось предыдущее событие этого
-- расходника»: `ORDER BY seq DESC LIMIT 1` в цепочке и в проверке покрытия, а также лента журнала в
-- окне карточки. `DESC` в определении ради них и стоит. Уникальность здесь — следствие, а не цель:
-- `seq` и так уникален на всю таблицу, но ключом сказано, что двух событий с одним номером у одного
-- расходника не бывает — то есть цепочка ветвиться не может.
-- Он же обслуживает `RESTRICT` при удалении расходника: `consumable_id` идёт первым столбцом.
CREATE UNIQUE INDEX office_equipment_consumable_stock_seq_idx
  ON office_equipment_consumable_stock_entries (consumable_id, seq DESC);

-- Второй вопрос журнала — «что списали по этой заявке»: его задаёт карточка заявки и сторно при
-- правке факта выдачи. Индекс частичный: у ручных событий ссылка пуста, и держать их в нём незачем —
-- он остаётся размером с историю выдач, а не всего журнала.
CREATE INDEX office_equipment_consumable_stock_request_idx
  ON office_equipment_consumable_stock_entries (service_request_id)
  WHERE service_request_id IS NOT NULL;

-- ── 5. Триггер цепочки: событие не врёт (Р7) ──
--
-- Функция САМА берёт строку расходника `FOR UPDATE` — не потому, что маршрут этого не делает
-- (делает, первым шагом транзакции, Р7), а потому что защита, работающая только когда её вызвали
-- правильно, защищает не схему, а вежливых: прямая вставка скриптом или из миграции проходила бы
-- мимо. Повторный `FOR UPDATE` в той же транзакции бесплатен, а вставке мимо маршрута достаётся та
-- же блокировка и та же проверка. Без блокировки два кладовщика прочитали бы 12, записали «12 → 10»
-- и «12 → 8», и цепочка стала бы враньём при верном итоге.
--
-- ПРОВЕРЯЮТСЯ ОБА КОНЦА, и это главное в функции. Сверка только со «стало» пропустила бы строку
-- «999 → 12» при остатке 12: итог верен, а в журнале навсегда осталось бы выдуманное «было», по
-- которому потом считают расход. Сверка только с «было» пропустила бы событие, не доехавшее до
-- карточки. Поэтому:
--
--   `quantity_before` = «стало» предыдущего события этого расходника (по `max(seq)`), а для первой
--     строки — ноль: до первого события расходник заведён нулём. Заведение с ненулевым остатком —
--     это и есть первое событие «0 → N», и другого способа получить непустую карточку нет;
--   `quantity_after`  = фактический остаток карточки, то есть правка карточки обязана идти ПЕРЕД
--     вставкой события. Порядок «карточка → событие» — тот же, что у маршрута (Р7).
--
-- Отсюда же и то, чего в функции нет: события без правки карточки. Оно не проходит не отдельной
-- проверкой, а этими двумя вместе — «было» равно остатку (иначе цепочка уже порвана), «стало» тоже
-- обязано равняться остатку, а `CHECK` требует их различия.
CREATE FUNCTION office_equipment_consumable_stock_chain() RETURNS trigger
  LANGUAGE plpgsql SECURITY INVOKER SET search_path = public, pg_temp AS $$
DECLARE
  v_quantity integer;
  v_previous integer;
BEGIN
  SELECT c.quantity INTO v_quantity
    FROM office_equipment_consumables c
   WHERE c.id = NEW.consumable_id
   FOR UPDATE;

  -- Несуществующий расходник поймал бы и внешний ключ, но позже и не теми словами: ключи
  -- проверяются после `BEFORE`-триггеров, то есть первым сюда приходит наш `SELECT`, и молчать о
  -- пустом результате значило бы сравнивать «стало» с `NULL` — то есть пропустить строку.
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Расходник % не найден: событие остатка не на что записать', NEW.consumable_id
      USING ERRCODE = 'foreign_key_violation';
  END IF;

  SELECT e.quantity_after INTO v_previous
    FROM office_equipment_consumable_stock_entries e
   WHERE e.consumable_id = NEW.consumable_id
   ORDER BY e.seq DESC
   LIMIT 1;

  -- Первому событию сверяться не с чем — до него остаток был нулём. `coalesce`, а не `IF NOT FOUND`:
  -- `quantity_after` объявлен `NOT NULL`, поэтому пустой результат отличим от значения однозначно,
  -- и одна строка честнее ветки.
  v_previous := coalesce(v_previous, 0);

  IF NEW.quantity_before <> v_previous THEN
    RAISE EXCEPTION
      'Событие остатка расходника %: «было %», а предыдущее событие оставило %',
      NEW.consumable_id, NEW.quantity_before, v_previous
      USING ERRCODE = 'check_violation';
  END IF;

  IF NEW.quantity_after <> v_quantity THEN
    RAISE EXCEPTION
      'Событие остатка расходника %: «стало %», а в карточке %',
      NEW.consumable_id, NEW.quantity_after, v_quantity
      USING ERRCODE = 'check_violation';
  END IF;

  RETURN NEW;
END
$$;

CREATE TRIGGER office_equipment_consumable_stock_chain
  BEFORE INSERT ON office_equipment_consumable_stock_entries
  FOR EACH ROW EXECUTE FUNCTION office_equipment_consumable_stock_chain();

-- `ENABLE ALWAYS` — ОТДЕЛЬНОЙ командой: в `CREATE TRIGGER` такого слова нет, а без него на
-- реплике-приёмнике проверка не сработает вовсе. Приём тот же, что у управляющих триггеров `0167`
-- и зеркала моделей `0171`.
ALTER TABLE office_equipment_consumable_stock_entries
  ENABLE ALWAYS TRIGGER office_equipment_consumable_stock_chain;

-- ПОДПИСИ ОБЪЕКТОВ КАТАЛОГА. Дальше у каждой функции и каждого триггера этой миграции стоит
