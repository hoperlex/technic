-- ── 6. Триггер неизменяемости: прошлое не подчищают (Р11) ──
--
-- `RESTRICT` со стороны расходника защищает историю целиком, но не построчно: прямой `UPDATE` или
-- `DELETE` по самим строкам он не запрещает, а «журнал, который нельзя подчистить» обязан означать
-- именно это. Ошибку исправляют не строкой, а следующим событием: «ошиблись, вернули 15» с
-- причиной — так исправление остаётся видимым, а не заменяет собой то, что было.
--
-- Запрет безусловный, исключений нет и быть не может: законного пути, который сносил бы строки
-- журнала, в схеме не существует — расходник с движением не удаляется вовсе, и каскада сюда не
-- ведёт ни одного.
CREATE FUNCTION office_equipment_consumable_stock_immutable() RETURNS trigger
  LANGUAGE plpgsql SECURITY INVOKER SET search_path = public, pg_temp AS $$
BEGIN
  RAISE EXCEPTION
    'Журнал остатка расходников неизменяем: ошибку исправляют следующим событием, а не правкой'
    USING ERRCODE = 'check_violation';
END
$$;

CREATE TRIGGER office_equipment_consumable_stock_immutable
  BEFORE UPDATE OR DELETE ON office_equipment_consumable_stock_entries
  FOR EACH ROW EXECUTE FUNCTION office_equipment_consumable_stock_immutable();

ALTER TABLE office_equipment_consumable_stock_entries
  ENABLE ALWAYS TRIGGER office_equipment_consumable_stock_immutable;

COMMENT ON FUNCTION office_equipment_consumable_stock_immutable() IS
  'Безусловный отказ: журнал остатка неизменяем (Р11). Тела у проверки нет и быть не должно — '
  'законного пути, который правил бы или сносил строки журнала, в схеме не существует. '
  'Вызывается только триггером office_equipment_consumable_stock_immutable.';

COMMENT ON TRIGGER office_equipment_consumable_stock_immutable
  ON office_equipment_consumable_stock_entries IS
