-- ── 7. Отложенный триггер покрытия: остаток без события невозможен (Р7) ──
--
-- Цепочка ловит неверное событие, но молчит там, где события нет: `UPDATE
-- office_equipment_consumables SET quantity = 7` скриптом прошёл бы насквозь, и обещание «каждое
-- изменение остатка попадает в журнал» осталось бы обещанием маршрута. Эта проверка и есть то, что
-- делает его свойством базы.
--
-- ОТЛОЖЕННЫЙ, а не немедленный: внутри транзакции порядок «правка карточки → вставка события»
-- законен и обязателен (цепочка сверяет «стало» с карточкой), и немедленная проверка отбивала бы
-- саму правку остатка на первом же шаге — то есть запрещала бы единственный правильный путь.
--
-- ФУНКЦИЯ ПРИНИМАЕТ ИДЕНТИФИКАТОР И ПЕРЕЧИТЫВАЕТ ПО НЕМУ СОСТОЯНИЕ — ни `NEW.quantity`, ни любой
-- другой снимок ряда в ней не участвуют, и это не стиль, а условие правильности. Две правки в одной
-- транзакции (12 → 10 → 8, каждая со своим событием) законны; отложенные триггеры срабатывают на
-- коммите оба, и первый из них, сравнивая свой снимок «стало 10» с журналом, где уже 8, дал бы
-- отказ на ровном месте. Перечитанное состояние у обоих одно и то же — и оно верное.
--
-- Приём взят у проверки полноты категории в `0035`: та так же читает состояние по `p_category_id` и
-- молча выходит, если строку удалили в этой же транзакции. Здесь нужен ровно такой же выход —
-- расходник без движения удаляется законно, и требовать от удалённой карточки соответствия журналу
-- значило бы запретить удаление опечатки первого дня.
CREATE FUNCTION office_equipment_consumable_stock_covered(p_consumable_id uuid) RETURNS void
  LANGUAGE plpgsql SECURITY INVOKER SET search_path = public, pg_temp AS $$
DECLARE
  v_quantity integer;
  v_last integer;
BEGIN
  SELECT c.quantity INTO v_quantity
    FROM office_equipment_consumables c
   WHERE c.id = p_consumable_id;

  -- Карточку удалили в этой же транзакции — проверять нечего.
  IF NOT FOUND THEN
    RETURN;
  END IF;

  SELECT e.quantity_after INTO v_last
    FROM office_equipment_consumable_stock_entries e
   WHERE e.consumable_id = p_consumable_id
   ORDER BY e.seq DESC
   LIMIT 1;

  -- Пустой журнал допустим только при нуле: «заведён и ещё ничего не приходило» — это отсутствие
  -- событий, а не событие (`CHECK` не пропустил бы «0 → 0»). А вот ненулевой остаток при пустом
  -- журнале — это ровно тот случай, ради которого проверка стоит: остаток взялся ниоткуда.
  IF v_last IS NULL THEN
    IF v_quantity <> 0 THEN
      RAISE EXCEPTION
        'Остаток расходника % равен %, но в журнале нет ни одного события',
        p_consumable_id, v_quantity
        USING ERRCODE = 'check_violation';
    END IF;
    RETURN;
  END IF;

  IF v_quantity <> v_last THEN
    RAISE EXCEPTION
      'Остаток расходника % равен %, а последнее событие журнала оставило %',
      p_consumable_id, v_quantity, v_last
      USING ERRCODE = 'check_violation';
  END IF;
END
$$;

-- Триггерная обёртка отделена от самой проверки нарочно: проверку зовут не только триггером — ею
-- же сверяют базу одним запросом (сверка после выката, §12, и db-тесты), а функция, умеющая
-- работать только изнутри триггера, для этого недоступна. Тот же расклад, что у
-- `vehicle_category_assert_consistent` в `0035`.
CREATE FUNCTION office_equipment_consumable_stock_covered_trg() RETURNS trigger
  LANGUAGE plpgsql SECURITY INVOKER SET search_path = public, pg_temp AS $$
BEGIN
  PERFORM office_equipment_consumable_stock_covered(NEW.id);
  RETURN NULL;
END
$$;

-- `UPDATE OF quantity` — а не любой `UPDATE`: правка наименования, комментария или гашения флагом
-- остатка не касается, и гонять по ним проверку значило бы читать журнал на каждое переименование.
-- `INSERT` в списке обязателен: карточка, заведённая сразу с ненулевым остатком и без события, —
-- это тот же остаток из ниоткуда, только вошедший другой дверью.
CREATE CONSTRAINT TRIGGER office_equipment_consumable_stock_covered
  AFTER INSERT OR UPDATE OF quantity ON office_equipment_consumables
  DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION office_equipment_consumable_stock_covered_trg();

ALTER TABLE office_equipment_consumables
  ENABLE ALWAYS TRIGGER office_equipment_consumable_stock_covered;

-- Три объекта контура покрытия носят почти одно имя — подписи разводят их поимённо.
COMMENT ON FUNCTION office_equipment_consumable_stock_covered(uuid) IS
  'ЧИСТАЯ проверка «остаток без события невозможен» (Р7): по идентификатору расходника ПЕРЕЧИТЫВАЕТ '
  'и карточку, и хвост журнала — снимка ряда не берёт вовсе. Иначе две правки в одной транзакции '
  '(12 в 10, затем 10 в 8) дали бы ложный отказ: событие первой правки сработало бы на коммите со '
  'снимком «стало 10» против законных 8 в карточке. Карточка, удалённая в этой же транзакции, — '
  'молчаливый выход. Годится и для сверки базы одним запросом, а не только изнутри триггера.';

COMMENT ON FUNCTION office_equipment_consumable_stock_covered_trg() IS
  'Обёртка constraint-триггера office_equipment_consumable_stock_covered: передаёт NEW.id в чистую '
  'функцию office_equipment_consumable_stock_covered(uuid) и ничего больше не делает. Разделены '
  'нарочно — проверку зовут и запросом, а функция, умеющая работать только изнутри триггера, для '
  'этого недоступна.';

