-- Работа исполнителем в оргтехнике отделяется от координации: заводится набор
-- `office_equipment_executor`, и из «Оргтехника: ИТ-служба» уезжают `serviceRequests.execute` и
-- `.files` (план `docs/office-equipment-access-profiles-plan.md`, Р2, Р4, Р5, §9.1 строка C,
-- этап Э6; план `docs/office-equipment-executor-access-audit-plan.md`, находка Н1 и этап Э8 —
-- одна и та же работа, названная в двух планах и сделанная здесь один раз).
--
-- ОТКУДА НОМЕР. Проверено `ls apps/api/drizzle/*.sql` непосредственно перед созданием файла
-- (04.09.2026): последняя миграция в дереве — `0261_office_equipment_grants_self_sufficient.sql`
-- того же плана (этап Э4). Свободен 0262. Номер берётся в момент создания файла и не резервируется
-- заранее: соседние потоки занимают номера незакоммиченными файлами, и утренний снимок к вечеру
-- врёт — 0261 сама об этом и рассказывает.
--
-- ЗАЧЕМ. Сегодня `serviceRequests.execute` приходит ровно из одного набора — ИТ-службы, — а у того
-- сквозная область модуля (`GRANT_MODULE_WIDE_SCOPE`: `serviceRequests`, `officeEquipment`).
-- Отсюда следствие, ради которого миграция и написана: **право исполнителя неотделимо от сквозной
-- видимости**. Назначить сотрудника исполнителем можно было только вместе с правом читать предмет,
-- переписку, сметы и суммы ЛЮБОЙ заявки компании; исполнителя без сквозной области назначали, а
-- работать он не мог — область отказывала после назначения. Разделение разносит координацию (виза,
-- назначение, заморозка, сквозная область) и работу руками (ходы исполнителя, документы) на два
-- набора. Профиль «Системный администратор» выдаётся обоими сразу (реестр
-- `packages/contracts/src/office-equipment-profiles.ts`), и в правах он не теряет ничего.
--
-- ПОЧЕМУ НАБОР МОДУЛЬНЫЙ, А НЕ СИСТЕМНЫЙ. `SYSTEM_GRANT_CODES` объявлен
-- `satisfies readonly RoleAddon[]` и принимает только коды ПЕРЕНЕСЁННЫХ надстроек; надстройки
-- «исполнитель» не было и не будет — набор заводится сразу набором. Вторая половина причины важнее
-- первой: системный код требует ключа в `GRANT_MODULE_WIDE_SCOPE`, а сквозная область — ровно то,
-- от чего исполнителя отделяют. Модульный код туда не примет компилятор, и это защита решения, а
-- не комментарий о нём. Заявку держателю открывает третья ось видимости — «я назначен поимённо»
-- (план аудита, Р1, выкачен этапом Э4 того плана), и работает она без всякого набора.
--
-- ЧЕГО В СОСТАВЕ НЕТ. `serviceRequests.finance` — решение записано заранее миграцией 0259 и не
-- изменилось: право сквозное по области, и выданное набором, оно показало бы держателю суммы всех
-- заявок его площадки и отдела, а не тех, на которые он назначен. Деньги назначенной заявки
-- открывает та же ось назначения, что и ходы. `serviceRequests.read` в составе, наоборот, есть —
-- по самодостаточности (Р4, миграция 0261): `PERMISSION_REQUIRES` объявляет и `execute`, и `files`
-- зависимыми от чтения, и набор без него не прошёл бы барьер требований у роли без модуля.
--
-- СОВМЕСТИМЫЕ РОЛИ — `shtab`, `site`, `department`, и только они (Р5). У `manager`/`dispatcher` ось
-- области `none`, то есть заявки видны им целиком по компании: scope-neutral набор дал бы такому
-- сотруднику чтение всех заявок ещё ДО первого назначения — ту самую дыру, которую разделение и
-- закрывает. Роль `operator` (внешний исполнитель) не перечисляется ни в одном наборе оргтехники
-- никогда: его права приходят типом контрагента, и набор раздал бы их по базовой области, которой
-- у подрядчика нет.
--
-- ПОРЯДОК ВНУТРИ ФАЙЛА ЗНАЧИМ, И ОН ЗАЩИЩЁН КАРАУЛАМИ (§9.1). Набор и состав → свежий снимок
-- держателей ИТ → идемпотентный backfill им же → караул «держатели ИТ ⊆ держатели исполнителя» →
-- только теперь два точечных `DELETE` из ИТ-набора и публикация `grant_roles` исполнителя →
-- финальный караул составов. Строки `grant_roles` печатаются ПОСЛЕДНИМИ намеренно: до них набор
-- существует, но не выдаётся никем и никому — гейт совместимости с ролью (`grantPermissionsExpr`
-- соединяется с `grant_roles`) держит его недействующим, и окно между заведением набора и снятием
-- прав с ИТ не открывает исполнителя посторонним. Любое расхождение — `RAISE EXCEPTION`, и вся
-- миграция откатывается целиком: файл катится одной транзакцией (`applyMigrations`).
--
-- ПОЧЕМУ BACKFILL ВООБЩЕ ЕСТЬ. Это единственное автоматическое назначение набора во всём плане, и
-- без него разделение отобрало бы у живых держателей ИТ-набора работу исполнителя в момент выката:
-- права ушли бы из одного набора, а второй никому ещё не выдан. Backfill не удаляет ручных строк,
-- не трогает чужих наборов и ни одной строки `user_grants` сверх себя не создаёт — последнее
-- проверяется караулом равенства множеств, а не обещанием.
--
-- ПРОИСХОЖДЕНИЕ ВЫДАЧИ — `manual`, А НЕ `migration`, И ЭТО ВЫНУЖДЕННОЕ ОТСТУПЛЕНИЕ ОТ ТЕКСТА ПЛАНА.
-- План §9.1 просил `origin = 'migration'`; поставить его нельзя двумя причинами сразу, и обе
-- жёсткие:
--
--   1. СХЕМА НЕ ПОЗВОЛЯЕТ. `user_grants_migration_origin_check` (миграция 0154) требует
--      `(origin = 'migration') = (migration_id IS NOT NULL)`, а `migration_id` — внешний ключ на
--      `user_role_migration`, снимок ПЕРЕВОДА РОЛЕЙ со своими `stage`, `role_before`, `role_after`
--      (ADR 0113). Никакого перевода роли здесь не происходит; выдуманная строка снимка соврала бы
--      и `check:role-migration`, который читает эту таблицу целиком, и откату этапов 8/9.
--   2. СНЯТЬ БЫЛО БЫ НЕЛЬЗЯ ФОРМОЙ. Назначение с `origin = 'migration'` заперто правилом
--      `migration_locked` (`apps/api/src/services/grant-catalog.ts`): форма учётки отказывается
--      его снимать (400, «взведены переводом ролей»), а портал рисует чекбокс запертым
--      (`lockedGrantIds`) и вешает метку «перевод ролей». Профиль ИТ обязан сниматься ЦЕЛИКОМ, а
--      снялась бы у него только половина — и вторая осталась бы у человека с объяснением, которого
--      не было.
--
-- `granted_by` берётся у ИСХОДНОЙ строки ИТ-набора, а не оставляется пустым: администратор, выдавший
-- профиль ИТ, ровно эту работу исполнителем человеку и выдал — сегодня она называется вторым
-- кодом. `granted_at` при этом момент наката, а не задним числом: правда о том, когда строка
-- появилась (тот же выбор, что у 0155).
--
-- ДОСТУП ЭТА МИГРАЦИЯ НЕ РАСШИРЯЕТ НИ У ОДНОГО ДЕЙСТВУЮЩЕГО ДЕРЖАТЕЛЯ. Состав пары «ИТ + новый
-- набор» после равен составу ИТ-набора до, права соединены `OR`, и backfill идёт в той же
-- транзакции, что `DELETE`. Расширение появляется в другом месте и позже: набор становится
-- выдаваемым САМОСТОЯТЕЛЬНО — так администратор впервые получает возможность назначить внутреннего
-- исполнителя, не отдавая ему сквозную видимость модуля. Ради этого всё и делалось.
--
-- BACKFILL ЗАХВАТЫВАЕТ ВСЕХ ДЕРЖАТЕЛЕЙ, В ТОМ ЧИСЛЕ С НЕСОВМЕСТИМОЙ РОЛЬЮ, неактивных и архивных.
-- Прав это никому не добавляет: гейт `grant_roles` не даёт набору действовать у роли, которой он
-- не положен, — ровно так же, как не даёт действовать и самому ИТ-набору. Отфильтруй мы таких, у
-- вернувшегося из отпуска сотрудника, которому роль поменяли и вернули, половина профиля пропала
-- бы молча.
--
-- КОДЫ НАБОРОВ НЕ МЕНЯЮТСЯ НИКОГДА: по коду набор находят миграции каталога, журнал действий,
-- реестр выдач и таблица сквозной области. Наборы ищутся по коду и здесь.
--
-- ГДЕ ЖИВЁТ ОБЪЯВЛЕННЫЙ СОСТАВ. У ИТ-набора — в `ROLE_ADDON_PERMISSIONS`
-- (`packages/contracts/src/permissions.ts`): надстройка ADR 0086 остаётся живым источником доступа
-- до шага 1e реформы. У нового набора — в `MODULE_GRANTS` (`packages/contracts/src/grants.ts`),
-- рядом с «Оргтехника: номенклатура» и аудитом талонов. Правка контрактов едет ТОЙ ЖЕ волной, что
-- эта миграция: разъехавшись, они дали бы одному человеку разные права в зависимости от того,
-- каким источником пришёл доступ. Обе стороны сверяет страж `apps/api/test/grants-catalog.db.test.ts`.
--
-- ВЕРСИЯ ИТ-НАБОРА НЕ РАСТЁТ, хотя состав уменьшился: системный набор из интерфейса не правится
-- (`GRANT_CONFLICT_CODES.isSystem`), а отпечаток последствий выдачи считается от СОСТАВА вместе с
-- версией — состав изменился, и устаревшая карточка формы не сойдётся и без прибавки. Тот же
-- выбор сделали 0259 и 0261.
--
-- ОБРАТИМОСТЬ. Схема не меняется, трогаются три таблицы каталога и одна таблица назначений;
-- протокол выката необратимых миграций (`docs/schema-cutover-protocol.md`) к ней не применяется.
-- Откат — вернуть две строки состава ИТ-набору, снять `grant_roles` исполнителя, удалить его
-- назначения и сам набор (в этом порядке: `user_grants.grant_id` — `RESTRICT`). Откатывать её в
-- одиночку, оставив выкаченным код, безопасно: до Э8 профиль ИТ выдаётся администратором вручную,
-- а прав у пары наборов ровно столько же, сколько у одного прежнего.

