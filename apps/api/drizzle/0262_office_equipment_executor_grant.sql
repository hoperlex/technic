-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 2. Свежий снимок держателей ИТ-набора.
--
-- Отдельной временной таблицей, а не подзапросом в трёх местах, и причина не в удобстве: backfill
-- и караул обязаны говорить об ОДНОМ И ТОМ ЖЕ множестве. Внутри одной транзакции подзапрос дал бы
-- то же самое, но правило «снимок снимается один раз и им же проверяется» переживёт правку файла,
-- а совпадение трёх одинаковых подзапросов — нет.
--
-- `ON COMMIT DROP`: таблица живёт ровно до конца транзакции миграции и в базе не остаётся.
-- `deleted_at IS NULL` у набора — потому что мягко удалённый набор прав не даёт, и держателей у
-- него не бывает; условий по учётке нет намеренно (см. шапку про неактивных и архивных).
--
-- МЕТКИ `>>> BACKFILL` / `<<< BACKFILL` — часть договора с db-тестом
-- (`apps/api/test/office-equipment-profiles.db.test.ts`). Миграция одноразовая: к прогону она уже
-- накатана, второй раз журнал её не пустит, а работа у неё ровно та, которую надо проверить на
-- живых строках. Тест вырезает по меткам ИМЕННО эти три шага (снимок, backfill, караул) и гоняет
-- их на своей сцене внутри транзакции, которую откатывает. Пересказ тех же запросов рядом с тестом
-- зеленел бы ровно до первой правки оригинала; переименуют метки — тест упадёт с объяснением, а не
-- продолжит проверять пустоту.

-- >>> BACKFILL
CREATE TEMP TABLE it_holders_0262 ON COMMIT DROP AS
SELECT ug.user_id, ug.granted_by
FROM user_grants ug
JOIN grants g ON g.id = ug.grant_id
WHERE g.code = 'office_equipment_it_approver' AND g.deleted_at IS NULL;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 3. Backfill: каждому держателю ИТ-набора — выдача исполнителя.
--
-- `ON CONFLICT (user_id, grant_id) DO NOTHING` по уникальному ключу `user_grants_user_grant_unique`
-- делает шаг идемпотентным и заодно бережёт строку, которую администратор мог выдать раньше своей
-- рукой: её `granted_by`, `granted_at` и происхождение остаются как были. Права от этого не
-- страдают — набор тот же самый.
--
-- Счёт `выдано/пропущено` печатается вслух: оператор выката сверяет его с §9.2 плана («число
-- держателей нового набора равно числу держателей ИТ до backfill») прямо по логу наката, не
-- дожидаясь отдельного запроса. NOTICE, а не таблица: это отчёт о шаге, а не данные.

DO $$
DECLARE
  holders  integer;
  inserted integer;
BEGIN
  SELECT count(*) INTO holders FROM it_holders_0262;

  WITH ins AS (
    INSERT INTO user_grants (user_id, grant_id, granted_by, origin)
    SELECT h.user_id, g.id, h.granted_by, 'manual'
    FROM it_holders_0262 h
    CROSS JOIN grants g
    WHERE g.code = 'office_equipment_executor' AND g.deleted_at IS NULL
    ON CONFLICT (user_id, grant_id) DO NOTHING
    RETURNING 1
  )
  SELECT count(*) INTO inserted FROM ins;

  RAISE NOTICE 'Разделение набора ИТ-службы: держателей %, выдано %, пропущено (уже было) %',
               holders, inserted, holders - inserted;
END $$;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 4. Караул ДО снятия прав: держатели ИТ ⊆ держатели исполнителя.
--
-- Стоит между backfill'ом и `DELETE` намеренно: он и есть та проверка, из-за которой окна без
-- ходов исполнителя не бывает. Не сойдись множества — снимать `execute`/`files` нельзя, и вся
-- миграция откатывается, оставив прод ровно там, где он был.
--
-- В сообщение попадают первые пять учёток: полный список на проде мог бы оказаться в сотни строк,
-- а для разбора хватает и «сколько + кто именно» на образец.

DO $$
DECLARE
  missing integer;
  sample  text;
BEGIN
  SELECT count(*), string_agg(user_id::text, ', ' ORDER BY user_id::text)
    INTO missing, sample
    FROM (
      SELECT h.user_id
        FROM it_holders_0262 h
       WHERE NOT EXISTS (
               SELECT 1
                 FROM user_grants ug
                 JOIN grants g ON g.id = ug.grant_id
                WHERE ug.user_id = h.user_id AND g.code = 'office_equipment_executor')
       ORDER BY h.user_id
       LIMIT 5
    ) AS lost;

  IF missing > 0 THEN
    RAISE EXCEPTION 'Backfill не покрыл держателей ИТ-набора (не меньше %): % — снимать ходы '
                    'исполнителя нельзя, разделение отобрало бы работу у живых учётных записей',
                    missing, sample;
  END IF;
END $$;

