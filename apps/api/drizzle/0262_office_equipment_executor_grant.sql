-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 6. Финальный караул: составы, роли и множества держателей.
--
-- Страж-тест сверяет составы с контрактами, но живёт он в репозитории, а этот блок — в накате:
-- оператор выката увидит расхождение сразу, а не через прогон тестов.
--
-- Числа взяты по факту кода после правки контрактов, а не переписаны из плана. В ИТ-наборе восемь
-- прав: десять после миграции 0261 (`officeEquipment.read`, `serviceRequests.read`, `.create`,
-- `.approveIt`, `.assign`, `.hold`, `.execute`, `.files`, `.finance`, `.createWithoutEquipment`)
-- минус снятые здесь два. В наборе исполнителя — три, и все три названы поимённо: счёт без имён
-- сошёлся бы и у набора, собранного из чужих прав.
--
-- СЛЕДУЮЩАЯ МИГРАЦИЯ КАТАЛОГА обязана вести счёт от ВОСЬМИ и ТРЁХ, а не выводить его из головы.
-- Ближайшая известная — D того же плана (`serviceRequests.finance` уже стоит, набор
-- `office_equipment_requester`), затем E, снимающая мёртвое `serviceRequests.approveIt`: после неё
-- в ИТ-наборе останется семь.
--
-- Множества держателей сверяются В ОБЕ СТОРОНЫ. Прямая сторона повторяет караул шага 4 уже после
-- всех правок; обратная доказывает обещание «ни одной строки `user_grants` сверх backfill'а»:
-- держатель нового набора, которого нет среди держателей ИТ, означал бы, что миграция выдала набор
-- кому-то ещё.
DO $$
DECLARE trouble text;
BEGIN
  SELECT string_agg(msg, '; ')
    INTO trouble
    FROM (
      SELECT format('наборов нет или они не системные (найдено строк: %s вместо двух)', count(*))
             AS msg
        FROM grants
       WHERE code IN ('office_equipment_it_approver', 'office_equipment_executor')
         AND is_system AND deleted_at IS NULL
      HAVING count(*) <> 2
      UNION ALL
      SELECT format('office_equipment_it_approver: прав %s вместо восьми, ходы исполнителя среди '
                    'них: %s', count(gp.permission),
                    CASE WHEN count(gp.permission) FILTER (
                           WHERE gp.permission IN ('serviceRequests.execute',
                                                   'serviceRequests.files')) = 0
                         THEN 'нет' ELSE 'ДА' END)
        FROM grants g
        LEFT JOIN grant_permissions gp ON gp.grant_id = g.id
       WHERE g.code = 'office_equipment_it_approver'
      HAVING count(gp.permission) <> 8
          OR count(gp.permission) FILTER (
               WHERE gp.permission IN ('serviceRequests.execute', 'serviceRequests.files')) <> 0
      UNION ALL
      SELECT format('office_equipment_executor: состав %s',
                    coalesce(string_agg(gp.permission, ', ' ORDER BY gp.permission), 'пуст'))
        FROM grants g
        LEFT JOIN grant_permissions gp ON gp.grant_id = g.id
       WHERE g.code = 'office_equipment_executor'
      HAVING coalesce(array_agg(gp.permission ORDER BY gp.permission), ARRAY[]::text[])
               <> ARRAY['serviceRequests.execute', 'serviceRequests.files', 'serviceRequests.read']
      UNION ALL
      SELECT format('роли набора исполнителя: %s',
                    coalesce(string_agg(gr.role::text, ', ' ORDER BY gr.role::text), 'ни одной'))
        FROM grants g
        LEFT JOIN grant_roles gr ON gr.grant_id = g.id
       WHERE g.code = 'office_equipment_executor'
      HAVING coalesce(array_agg(gr.role::text ORDER BY gr.role::text), ARRAY[]::text[])
               <> ARRAY['department', 'shtab', 'site']
      UNION ALL
      SELECT format('держателей ИТ без исполнителя: %s', count(*))
        FROM it_holders_0262 h
       WHERE NOT EXISTS (
               SELECT 1 FROM user_grants ug JOIN grants g ON g.id = ug.grant_id
                WHERE ug.user_id = h.user_id AND g.code = 'office_equipment_executor')
      HAVING count(*) <> 0
      UNION ALL
      SELECT format('держателей исполнителя сверх backfill: %s', count(*))
        FROM user_grants ug
        JOIN grants g ON g.id = ug.grant_id
       WHERE g.code = 'office_equipment_executor'
         AND NOT EXISTS (SELECT 1 FROM it_holders_0262 h WHERE h.user_id = ug.user_id)
      HAVING count(*) <> 0
    ) AS bad;
  IF trouble IS NOT NULL THEN
    RAISE EXCEPTION 'Разделение наборов оргтехники прошло не так, как объявлено — %', trouble;
  END IF;
END $$;
