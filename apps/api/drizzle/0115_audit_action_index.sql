-- Индекс под выборку журнала действий (план `docs/registration-reject-mail-plan.md`, ADR 0088).
--
-- Существующий `audit_log_entity_idx` обслуживает другой вопрос — историю одной сущности («что
-- было с этой заявкой»), — и ведёт по паре «тип + id». Подвкладка «Аудит» спрашивает обратное:
-- последние записи из перечисленного набора действий по учёткам, свежие сначала, без привязки к
-- одной строке. Такой выборке первый индекс не помогает вовсе, и без второго она идёт полным
-- проходом по таблице, а таблица растёт с каждой операцией портала — заявкой, рейсом, входом.
--
-- Порядок колонок именно такой: набор действий сужает выборку (`action IN (...)`), а `created_at
-- DESC` внутри каждого действия отдаёт готовый порядок страницы, и сортировать её отдельно не
-- приходится.
--
-- Аддитивная миграция: данные не меняются, протокол выката необратимых миграций
-- (`docs/schema-cutover-protocol.md`) к ней не применяется.
CREATE INDEX audit_log_action_created_idx ON audit_log (action, created_at DESC);
