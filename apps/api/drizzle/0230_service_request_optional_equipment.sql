-- Аппарат у заявки на обслуживание становится необязательным, а предмет заявки — названным
-- двусоставным `CHECK` (план `docs/office-equipment-consumables-and-purchase-plan.md`, Р5 и Р7;
-- ADR 0146, решение 6; выпуск 2б, этап Э17).
--
-- ОТКУДА НОМЕР. Проверено `ls apps/api/drizzle` непосредственно перед созданием файла (01.09.2026):
-- последняя миграция в дереве — `0229_releases_office_equipment_purchases.sql` (запись выпуска 65,
-- версия `0.1.56.0146`). Отсюда 0230 — этой, схемной, и 0231 — соседней, каталогу полномочий.
-- Номера миграций и ADR идут параллельными потоками и за время работы над планом уходили вперёд не
-- раз (§10 плана), поэтому сверка сделана заново, а не взята из шапки плана.
--
-- ЗАЧЕМ. Половина работы модуля предметом в справочнике не описывается вовсе: «поставьте розетку»,
-- «настройте почту новому сотруднику», «принтер привезли, инвентарного номера ещё нет». Сегодня
-- такую заявку заводят на посторонний аппарат — тот, что подвернулся под руку в выпадающем списке,
-- — и вся история обслуживания этой единицы после этого врёт. Аппарат поэтому перестаёт быть
-- обязательным, а на вопрос «чья эта заявка» отвечает заказчик: объект или отдел.
--
-- ПОЧЕМУ `CHECK` ДВУСОСТАВНЫЙ, А НЕ «ХОТЬ ЧТО-НИБУДЬ». Первая редакция плана писала «аппарат ИЛИ
-- объект ИЛИ отдел». Такое условие слабее обоих правил сразу:
--
--   * оно разрешает АППАРАТ БЕЗ ОБЪЕКТА — заявку, которой не бывало ни разу за всю жизнь модуля.
--     До этой миграции запрет держали два `NOT NULL`, и снятие одного из них не должно утаскивать
--     за собой второе: правку «аппарат необязателен» никто не просил превращать в «объект при
--     аппарате необязателен»;
--   * оно разрешает ДВУХ ЗАКАЗЧИКОВ СРАЗУ — заявку, которую роль площадки и роль отдела считают
--     своей каждая. Предикат области `serviceRequestScopeWhere` читает ровно эти три колонки, и
--     такая строка попадает в оба среза; спор «кто её ведёт» решался бы тем, кто первым открыл
--     список.
--
-- Ноль заказчиков у заявки без аппарата запрещён тем же условием и по зеркальной причине: все три
-- колонки пустые выпадают из области ЛЮБОЙ роли — заявку не увидит никто, кроме автора и
-- администратора, а автор увидит её только потому, что предикат отдельно пускает к своим.
--
-- Закупок в условии нет вовсе: у плановой закупки своя таблица (`office_equipment_purchases`,
-- миграция 0227, Р9), и оговорок ради неё здесь не нужно.
--
-- ЧТО БУДЕТ С СУЩЕСТВУЮЩИМИ ЗАЯВКАМИ. Ни одной правки данных: до этой миграции обе колонки стоят
-- `NOT NULL`, то есть КАЖДАЯ существующая строка удовлетворяет первой ветви условия по построению.
-- Поэтому `ADD CONSTRAINT` идёт сразу валидируемым, без `NOT VALID` + `VALIDATE`: сканирование
-- таблицы обязано пройти, а раздели мы шаги, накат сообщал бы об успехе там, где данные ещё не
-- проверены. Проверено на копии непустой базы перед выкатом.
--
-- ОТЛОЖЕННЫЕ ПРОВЕРКИ ТРИГГЕРА ЗДЕСЬ НЕ МЕШАЮТ, и это не догадка, а урок миграции 0224: на
-- `service_requests` висит `service_requests_executor_present` — CONSTRAINT TRIGGER `DEFERRABLE
-- INITIALLY DEFERRED` (0178), и `ALTER TABLE` отказывается работать по таблице с непустой очередью
-- его событий («cannot ALTER TABLE … because it has pending trigger events»). Очередь наполняют
-- `INSERT` и `UPDATE OF status, held_from_status, service_counterparty_id`; эта миграция ни одной
-- строки не трогает — только определение таблицы, — поэтому очередь пуста и на боевых данных.
-- `SET CONSTRAINTS ALL IMMEDIATE` здесь поэтому не нужен: опустошать нечего.
--
-- САМ ТРИГГЕР ПУСТОГО АППАРАТА НЕ ЗАМЕЧАЕТ: он читает `status`, `held_from_status`,
-- `service_counterparty_id` и строки `service_request_executors` — ни одной из двух колонок в его
-- условии нет. Заявка без аппарата подчиняется тому же правилу «в рабочем статусе есть
-- исполнитель», и это верно: чинить розетку тоже кто-то должен.
--
-- ЧАСТИЧНЫЕ УНИКАЛЬНЫЕ ИНДЕКСЫ ОСТАЮТСЯ КАК ЕСТЬ, И ЭТО РЕШЕНИЕ, А НЕ УМОЛЧАНИЕ.
-- `service_requests_open_repair_unique` и `service_requests_open_consumable_unique` (0224/M3)
-- держат «одна открытая заявка вида на аппарат» и построены по `office_equipment_id`. В B-tree
-- `NULL` не равен `NULL`, поэтому строки с пустым аппаратом друг с другом НЕ сталкиваются:
-- открытых заявок без аппарата может быть сколько угодно — и это правильно, потому что запирать их
-- нечем и незачем. «Не заводите вторую розетку в тот же кабинет» — не инвариант схемы, а работа
-- диспетчера модуля. `NULLS NOT DISTINCT` тут был бы прямой ошибкой: он разрешил бы одну заявку без
-- аппарата на весь портал.
--
-- ОБРАТИМОСТЬ. Пока заявок без аппарата нет, откат полный: снять ограничение и вернуть два
-- `NOT NULL`. После первой такой заявки обратный `SET NOT NULL` упрётся в её строку — как и
-- положено, откат схемы не должен молча терять данные. Протокол выката необратимых миграций
-- (`docs/schema-cutover-protocol.md`) к этой миграции не применяется: окна останова она не требует,
-- старый код в окне выката пишет обе колонки заполненными и первой ветви условия удовлетворяет.

-- ── 1. Аппарат и его объект перестают быть обязательными ──
--
-- Двумя отдельными командами, а не одной: `ALTER TABLE … ALTER COLUMN … DROP NOT NULL` в Postgres
-- принимает одну колонку за раз. Обе идут до `ADD CONSTRAINT` — иначе ограничение легло бы на
-- таблицу, где пустых значений всё равно не бывает, и его первая ветвь ничего бы не сторожила.
ALTER TABLE service_requests ALTER COLUMN office_equipment_id DROP NOT NULL;
ALTER TABLE service_requests ALTER COLUMN equipment_object_id DROP NOT NULL;

-- ── 2. Предмет заявки назван ──
--
-- `(a IS NOT NULL) <> (b IS NOT NULL)` — это XOR над двумя булевыми: ровно один из двух заказчиков.
-- Записано так, а не парой `NOT (… AND …) AND (… OR …)`: вторая форма читается вдвое дольше и на
-- ревью первой редакции именно в ней и потерялось «ровно один».
ALTER TABLE service_requests ADD CONSTRAINT service_requests_subject_check CHECK (
  (office_equipment_id IS NOT NULL AND equipment_object_id IS NOT NULL)
  OR (office_equipment_id IS NULL
      AND (equipment_object_id IS NOT NULL) <> (customer_department_id IS NOT NULL))
);

COMMENT ON CONSTRAINT service_requests_subject_check ON service_requests IS
  'Предмет заявки назван: у аппарата объект обязателен всегда, у заявки без аппарата заказчик '
  'ровно один — объект ИЛИ отдел (ADR 0146, решение 6). Условие «аппарат или объект или отдел» '
  'было бы слабее: оно разрешает и аппарат без объекта, и двух заказчиков сразу.';

-- ── 3. Караул: схема стала такой, как обещано ──
--
-- Страж-тест сверяет то же самое, но живёт он в репозитории, а этот блок — в накате: оператор
-- выката увидит расхождение сразу, а не через прогон тестов. Проверяется ровно обещанное — обе
-- колонки приняли `NULL`, ограничение существует и ПРОВЕРЕНО (`convalidated`), а не висит
-- `NOT VALID`. Последнее не придирка: невалидированное ограничение сторожит будущие строки и
-- молчит о существующих, то есть выглядит выполненной работой, не будучи ею.
DO $$
DECLARE trouble text;
BEGIN
  SELECT string_agg(msg, '; ')
    INTO trouble
    FROM (
      SELECT format('колонка %s осталась NOT NULL', a.attname) AS msg
        FROM pg_attribute a
       WHERE a.attrelid = 'service_requests'::regclass
         AND a.attname IN ('office_equipment_id', 'equipment_object_id')
         AND a.attnotnull
      UNION ALL
      SELECT format('ограничения предмета нет или оно не проверено (найдено проверенных: %s)',
                    count(*))
        FROM pg_constraint c
       WHERE c.conrelid = 'service_requests'::regclass
         AND c.conname = 'service_requests_subject_check'
         AND c.contype = 'c'
         AND c.convalidated
      HAVING count(*) <> 1
    ) AS bad;
  IF trouble IS NOT NULL THEN
    RAISE EXCEPTION 'Заявка не научилась жить без аппарата — %', trouble;
  END IF;
END $$;
