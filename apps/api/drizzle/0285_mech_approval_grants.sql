-- Виза механизации в наборах каталога «Виза объекта» и «Виза отдела» (план
-- `docs/mechanization-approval-and-grants-plan.md`, Р2; ADR 0171).
--
-- ЧТО ЗДЕСЬ ПРОИСХОДИТ. По одной строке `grant_permissions` каждому из двух системных наборов
-- подписи. Ни наборов, ни назначений, ни совместимых ролей файл не создаёт — состав правится, а
-- каталог остаётся прежним.
--
-- ЗАЧЕМ ЭТО МИГРАЦИЕЙ. Состав системных наборов хранится в базе (`grant_permissions`, миграция
-- 0145), а в контрактах живёт его копия (`ROLE_GRANTS`, `packages/contracts/src/grants.ts`), по
-- которой считается матрица. Расходиться им нельзя, и следит за этим страж
-- `grants-catalog.db.test.ts`: он сверяет базу с контрактами по каждому набору. Правка одной
-- стороны без другой красит его немедленно — это и есть механизм, ради которого файл существует.
--
-- КОМУ ЭТО ЧТО МЕНЯЕТ — разбор по обоим наборам, потому что ответы у них РАЗНЫЕ.
--
--   1. «Виза объекта» (`site_approval`) — не меняет никому. Совместимая роль у набора одна и
--      целевая (`site`, миграция 0153), а ни одной учётки на ней с выданным набором сегодня нет:
--      взведённые назначения рукстроев (миграция 0155) до перевода не действуют — гейт
--      совместимости (`grantPermissionsExpr`) спрашивает роль держателя. Право поэтому доедет до
--      людей ровно на этапе 8 реформы, вместе с ролью.
--
--   2. «Виза отдела» (`department_approval`) — МЕНЯЕТ, и это объявленное расширение доступа.
--      Совместимая роль у него живая (`department`), и у кого набор выдан, тот с этой минуты
--      визирует аренду механизации своего отдела. Ровно этого требует ответ заказчика от
--      08.09.2026 («заявку отдела визирует руководитель отдела»), но список держателей смотрят
--      глазами ПЕРЕД выкатом (§8 плана, п. 3): набор мог быть выдан раньше и по другому поводу.
--
-- Роль `department_head` право визы получает не отсюда, а из матрицы (`ROLE_PERMISSIONS`): её
-- взведённый `department_approval` (миграция 0156) до этапа 9 тоже не действует.
--
-- ОБРАТИМОСТЬ: удаление тех же двух строк.
--
--   DELETE FROM grant_permissions gp USING grants g
--    WHERE gp.grant_id = g.id AND gp.permission = 'mechRequests.approve'
--      AND g.code IN ('site_approval', 'department_approval');
--
-- Откат обязан идти вместе с откатом кода: право, снятое из базы при живом коде, отберёт визу у
-- держателей «Визы отдела», а снятое из кода при живой строке — оставит сироту, на которую страж
-- каталога и укажет.

INSERT INTO grant_permissions (grant_id, permission)
SELECT g.id, 'mechRequests.approve'
FROM grants g
WHERE g.code IN ('site_approval', 'department_approval')
  AND g.deleted_at IS NULL
ON CONFLICT (grant_id, permission) DO NOTHING;
