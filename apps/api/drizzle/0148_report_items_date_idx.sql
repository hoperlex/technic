-- Индекс под запрос одного дня по всему парку: строки ожидания за день, из которых растёт реестр
-- приёма. План — `docs/vehicle-readings-stats-plan.md`, §3.4 (решение Р22), этап 5.
--
-- ИНДЕКС ЗАВОДИТСЯ ПО ЗАМЕРУ И ВМЕСТЕ СО СВОИМ ПОТРЕБИТЕЛЕМ, А НЕ «НА ВСЯКИЙ СЛУЧАЙ» (Р22). Лишний
-- индекс дорожает каждую запись показания, поэтому у него обязан быть измеренный выигрыш и живой
-- читатель. Здесь есть оба.
--
-- Замер (синтетический годовой объём: 151 тыс. строк ожидания, 138 тыс. показаний, 200 машин,
-- 146 тыс. рейсов; боевой базы с данными нет) сказал про этот индекс три вещи сразу:
--
--   * СТАТИСТИКЕ ОН НЕ НУЖЕН. Годовому запросу он не помогает вовсе — условие за год отбирает все
--     строки таблицы, и последовательное чтение дешевле; месячному даёт 3 %, то есть шум. Поэтому
--     миграция `0140` его и не завела: у неё не было потребителя, оправдывающего цену.
--   * ЗАПРОСУ ОДНОГО ДНЯ ПО ВСЕМУ ПАРКУ — НУЖЕН: 20,5 → 7,3 мс и вчетверо меньше прочитанных
--     буферов. Это ровно тот запрос, которым живёт реестр приёма: «кто и что сдал за 14 августа».
--     Ведущая колонка у существующих индексов не та — `report_items_chain_key` начинается с машины
--     (`vehicle_id, report_date, shift_order`) и на «весь парк за день» не ложится.
--   * ЦЕНА У НЕГО РЕАЛЬНАЯ: около 4 МБ и +13 % на вставку строки ожидания.
--
-- Вторая колонка (`vehicle_id`) — не для отбора, а для порядка и для покрытия: строки дня приходят
-- на экран сгруппированными по машине, и без неё чтение упиралось бы в сортировку.
--
-- CONCURRENTLY здесь нет намеренно: раннер миграций (`src/db/migrate.ts`) выполняет файл одной
-- транзакцией, а `CREATE INDEX CONCURRENTLY` внутри транзакции запрещён. Таблица невелика (строка
-- на смену), и блокировка на время построения измеряется секундами.
CREATE INDEX IF NOT EXISTS report_items_date_idx
  ON driver_daily_report_items (report_date, vehicle_id);
