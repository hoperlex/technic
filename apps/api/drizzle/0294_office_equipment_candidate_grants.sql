-- Права волны «сообщение о технике» в каталоге полномочий: `officeEquipment.propose` — набору
-- «Оргтехника: заявитель» (`office_equipment_requester`), `officeEquipment.review` — набору
-- «Оргтехника: ведение» (`office_equipment_operator`). Это выпуск B готовой, но закрытой волны
-- ADR 0165 (план `docs/office-equipment-candidate-plan.md`, §14, миграции M4 и M4а; план
-- `docs/office-equipment-request-subject-plan.md`, Р10–Р11, этап Э6).
--
-- ОТКУДА НОМЕР. `ls apps/api/drizzle` непосредственно перед созданием файла (09.09.2026): последним
-- в дереве стоял `0293_feature_flags.sql` — рубильник приёма сообщений о технике, выпуск A этой же
-- волны, — а `0292_completion_actual_end_date.sql` держит соседний, ещё не закоммиченный поток.
-- Свободен 0294, он и взят. Номер берётся в момент создания каждого файла и не резервируется на
-- волну вперёд: план называл 0294 и 0295 предположительно, и совпало это по удаче, а не по резерву
-- — за один день 04.09.2026 план кандидата дважды потерял зарезервированный номер ровно так.
--
-- ЧЕГО ЖДЁТ ЭТА МИГРАЦИЯ ПЕРЕД СОБОЙ, И ЭТО НЕ ФОРМАЛЬНОСТЬ (Р11 плана предмета заявки). Выпуск A
-- обязан УЖЕ РАБОТАТЬ на сервере, куда она едет: рубильник `office_equipment_candidate_intake`
-- (миграция 0293) заведён выключенным, и `POST /service-requests` с телом кандидата отвечает 403
-- даже держателю права. Приедь права раньше перезапуска приложения — старый сервер, который о
-- рубильнике не знает, принимал бы кандидатов от каждого, кому набор уже выдан, а портал держал бы
-- третью ветвь формы открытой. Порядок здесь такой: сначала выпуск A целиком (код + 0293), потом
-- эта миграция, потом включение рубильника одним `UPDATE` — после health и smoke.
--
-- ЧТО МИГРАЦИЯ ДЕЛАЕТ.
--
--   · дописывает `officeEquipment.propose` набору «Оргтехника: заявитель». Это M4а плана
--     кандидатов, и ждала она ровно одного — чтобы набор появился в каталоге; его завела миграция
--     0266, ворота сняты. Набор существует ради менеджера и диспетчера: сломанный принтер стоит у
--     них, и не найти его в справочнике им случается чаще всех — парк офиса размечен хуже прочего;
--   · дописывает `officeEquipment.review` набору «Оргтехника: ведение». Это M4, и получатель здесь
--     ровно один — тот, у кого есть `officeEquipment.write`. Проверка ЗАКАНЧИВАЕТСЯ записью в парк,
--     то есть делает ровно то, что `write` и охраняет; `PERMISSION_REQUIRES` так его и объявляет.
--     ИТ-службе (`office_equipment_it_approver`) право не достаётся намеренно: ведения справочника
--     у неё нет и не появится (план профилей, §5.2), и выдать ей проверку значило бы открыть в парк
--     второй, необъявленный вход — тот самый, ради устранения которого волна и затевалась.
--
-- ЧЕГО МИГРАЦИЯ НЕ ДЕЛАЕТ.
--
--   · НЕ ТРОГАЕТ РОЛИ — ни `ROLE_PERMISSIONS`, ни `grant_roles`. Пять базовых ролей-заказчиков
--     (`shtab`, `rukstroy`, `site`, `department`, `department_head`) получают `propose` КОДОМ —
--     через `SERVICE_REQUEST_CUSTOMER_PERMISSIONS` в `packages/contracts/src/permissions.ts`, а
--     администратор — полным перечнем (`admin: [...PERMISSIONS]`). Матрица живёт в коде и приезжает
--     выкатом сервера; `grant_roles` отвечает на другой вопрос — «кому набор можно назначить», — и
--     совместимые роли обоих наборов эта волна не меняет;
--   · НЕ ДОПИСЫВАЕТ ПРАВА СОБРАННЫМ АДМИНИСТРАТОРОМ НАБОРАМ «по содержимому», в отличие от миграции
--     0275. Там право ВЫДЕЛЯЛОСЬ из `officeEquipment.write`, и не раздай его миграция каждому, у
--     кого ведение уже есть, выкат отобрал бы работающую операцию. Здесь обе двери новые: до этой
--     строки `propose` и `review` не открывали никому ничего, и отбирать нечего. Кому их выдать
--     сверх системных наборов — решение администратора, принимаемое поимённо;
--   · НЕ СОЗДАЁТ И НЕ ОТЗЫВАЕТ НИ ОДНОЙ СТРОКИ `user_grants`. Караул ниже проверяет это как
--     утверждение, а не как намерение: число держателей обоих наборов сверяется со снимком «до»;
--   · НЕ ВКЛЮЧАЕТ ПРИЁМ КАНДИДАТОВ. Рубильник — отдельная строка состояния (0293), и после этой
--     миграции он по-прежнему выключен. Права без рубильника не открывают ни одной двери: сервер
--     клиенту не доверяет и отбивает тело кандидата 403 независимо от прав;
--   · НЕ ВКЛЮЧАЕТ ПИСЬМА. Оба события кандидата заведены выключенными (0273), включает их
--     соседний файл этой же волны.
--
-- ДОСТУП РАСШИРЯЕТСЯ, И ЭТО СМЫСЛ ВЫПУСКА. Держатель «Заявителя» получает третью ветвь предмета
-- заявки («аппарата нет в справочнике»), держатель «Ведения» — очередь проверки, правку заявленных
-- реквизитов и три решения по сообщению: завести карточку, объединить с существующей, отклонить с
-- причиной. Ни ведения справочника, ни денег, ни хода заявки ни одно из двух прав не добавляет.
--
-- БАРЬЕР ТРЕБОВАНИЙ ПРОЙДЕН ОБОИМИ НАБОРАМИ, И СЧИТАЕТСЯ ОН ПО ИТОГУ УЧЁТКИ. `propose` требует
-- `serviceRequests.create` и `officeEquipment.read` — оба лежат в составе «Заявителя» (миграция
-- 0266), поэтому набор остаётся выдаваемым ровно тем двум ролям, ради которых заведён, — у них прав
-- модуля нет ни одного. `review` требует `officeEquipment.write` — он в составе «Ведения». Ни один
-- набор от новой строки не становится невыдаваемым.
--
-- ГДЕ ЖИВЁТ ОБЪЯВЛЕННЫЙ СОСТАВ: `ROLE_ADDON_PERMISSIONS` для «Ведения» (надстройка ADR 0086
-- остаётся живым источником доступа до шага 1e реформы) и `MODULE_GRANTS` для «Заявителя» — оба
-- в `packages/contracts/src`. Правка контрактов едет ТОЙ ЖЕ волной, что эта миграция, и это
-- условие, а не порядок удобства: разъехавшись, они дали бы одному человеку разные права в
-- зависимости от того, каким источником пришёл доступ. Обе стороны сверяет страж
-- `apps/api/test/grants-catalog.db.test.ts`.
--
-- ОБРАТИМОСТЬ. Схема не меняется, трогается одна таблица каталога двумя строками. Откат — `DELETE`
-- строк с `permission IN ('officeEquipment.propose', 'officeEquipment.review')` у этих двух
-- наборов, и делать его нужно ВМЕСТЕ с откатом контрактов, иначе страж каталога покраснеет на
-- расхождении. Полностью откат волны им, однако, НЕ ДЕЛАЕТСЯ: `can()` читает права роли первыми, и
-- кодовое `propose` пяти ролей-заказчиков миграцией не отзывается ничем — понадобился бы
-- согласованный откат приложения и базы. Ровно поэтому у волны есть рубильник: аварийное выключение
-- делается одним `UPDATE … = false`, а не откатом этого файла.

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 0. Снимок числа держателей ДО правки — ради утверждения «миграция правит состав, а не выдачи».
--
-- `ON COMMIT DROP`: таблица живёт до конца транзакции миграции и в базе не остаётся. Снимок нужен
-- именно снимком, а не константой «столько-то»: наборы выдают живым учёткам каждый день, и число
-- «до» на проде, в деве и на восстановленной из копии базе разное, а утверждение одно.

CREATE TEMP TABLE grant_holders_0294 ON COMMIT DROP AS
SELECT g.code, count(*)::bigint AS holders
FROM user_grants ug
JOIN grants g ON g.id = ug.grant_id
WHERE g.code IN ('office_equipment_operator', 'office_equipment_requester')
GROUP BY g.code;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 1. Сообщение о технике — «Заявителю» (M4а).
--
-- Право хранится текстом: справочника прав в базе нет намеренно (`grant_permissions`, миграция
-- 0145), словарь `PERMISSIONS` закрыт и живёт в контрактах. Набор ищется по коду — коды стабильны
-- навсегда, по ним его находят миграции каталога, журнал действий и реестр выдач.
-- `ON CONFLICT DO NOTHING` делает шаг идемпотентным: повторный накат на базу, восстановленную из
-- копии, — обычное дело, и миграция обязана довести каталог до объявленного состояния, а не упасть.

INSERT INTO grant_permissions (grant_id, permission)
SELECT g.id, 'officeEquipment.propose'
FROM grants g
WHERE g.code = 'office_equipment_requester'
ON CONFLICT (grant_id, permission) DO NOTHING;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 2. Проверка сообщений — «Ведению», и только ему (M4).
--
-- Второй набор здесь не появится ни сегодня, ни следующей волной: перечень получателей задан не
-- удобством, а требованием `officeEquipment.write`, и караул ниже проверяет отсутствие права у
-- прочих СИСТЕМНЫХ наборов отдельной строкой. Собранных администратором наборов запрет не касается
-- — модель ADR 0106 позволяет выдать `review` в собранном наборе, но барьер требований примет его
-- только вместе с ведением справочника в итоговых правах учётки.

INSERT INTO grant_permissions (grant_id, permission)
SELECT g.id, 'officeEquipment.review'
FROM grants g
WHERE g.code = 'office_equipment_operator'
ON CONFLICT (grant_id, permission) DO NOTHING;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 3. Караул: составы после правки, замок `review` и неприкосновенность выдач.
--
-- Страж-тест сверяет каталог с контрактами, но живёт он в репозитории, а этот блок — в накате:
-- оператор выката увидит расхождение сразу, а не через прогон тестов. Считается ПОСЛЕ вставки,
-- поэтому повторный накат проходит его так же, как первый.
--
-- Числа взяты по факту кода после правки контрактов и продолжают счёт миграции 0275 (там было 16 и
-- 8): в «Ведении» СЕМНАДЦАТЬ прав, в «ИТ-службе» по-прежнему ВОСЕМЬ, у исполнителя ТРИ, у
-- «Заявителя» СЕМЬ (шесть по счёту 0266 плюс одно здесь). СЛЕДУЮЩАЯ МИГРАЦИЯ КАТАЛОГА обязана
-- вести счёт от этих четырёх чисел, а не выводить его из головы.
--
-- Соседние два набора проверяются числом именно затем, что этот файл их не трогает вовсе:
-- утверждение здесь ровно одно — «столько же, сколько было».

DO $$
DECLARE trouble text;
BEGIN
  SELECT string_agg(msg, '; ')
    INTO trouble
    FROM (
      SELECT format('системных наборов модуля найдено %s вместо четырёх', count(*)) AS msg
        FROM grants
       WHERE code IN ('office_equipment_operator', 'office_equipment_it_approver',
                      'office_equipment_executor', 'office_equipment_requester')
         AND is_system AND deleted_at IS NULL
      HAVING count(*) <> 4
      UNION ALL
      SELECT format('%s: прав %s вместо %s', g.code, count(gp.permission), e.expected)
        FROM grants g
        JOIN (VALUES
          ('office_equipment_operator', 17),
          ('office_equipment_it_approver', 8),
          ('office_equipment_executor', 3),
          ('office_equipment_requester', 7)
        ) AS e (code, expected) ON e.code = g.code
        LEFT JOIN grant_permissions gp ON gp.grant_id = g.id
       GROUP BY g.code, e.expected
      HAVING count(gp.permission) <> e.expected
      UNION ALL
      SELECT format('в наборе «%s» нет права «%s» — вставка не сработала', s.code, s.permission)
        FROM (VALUES
          ('office_equipment_requester', 'officeEquipment.propose'),
          ('office_equipment_operator', 'officeEquipment.review')
        ) AS s (code, permission)
       WHERE NOT EXISTS (
         SELECT 1
           FROM grants g
           JOIN grant_permissions gp ON gp.grant_id = g.id
          WHERE g.code = s.code AND gp.permission = s.permission)
      UNION ALL
      SELECT format('проверка сообщений оказалась в системном наборе «%s» — замок волны сорван',
                    g.code)
        FROM grants g
        JOIN grant_permissions gp ON gp.grant_id = g.id
       WHERE gp.permission = 'officeEquipment.review'
         AND g.is_system
         AND g.code <> 'office_equipment_operator'
      UNION ALL
      SELECT format('сообщение о технике оказалось в системном наборе «%s», которому не объявлено',
                    g.code)
        FROM grants g
        JOIN grant_permissions gp ON gp.grant_id = g.id
       WHERE gp.permission = 'officeEquipment.propose'
         AND g.is_system
         AND g.code <> 'office_equipment_requester'
      UNION ALL
      SELECT format('держателей набора «%s» стало %s вместо %s: правится состав, а не выдачи',
                    c.code,
                    (SELECT count(*) FROM user_grants ug
                       JOIN grants g ON g.id = ug.grant_id
                      WHERE g.code = c.code),
                    coalesce((SELECT h.holders FROM grant_holders_0294 h WHERE h.code = c.code), 0))
        FROM (VALUES ('office_equipment_operator'), ('office_equipment_requester')) AS c (code)
       WHERE (SELECT count(*) FROM user_grants ug
                JOIN grants g ON g.id = ug.grant_id
               WHERE g.code = c.code)
             <> coalesce((SELECT h.holders FROM grant_holders_0294 h WHERE h.code = c.code), 0)
    ) AS bad;
  IF trouble IS NOT NULL THEN
    RAISE EXCEPTION
      'Права волны «сообщение о технике» разложены по наборам не так, как объявлено — %', trouble;
  END IF;
END $$;
