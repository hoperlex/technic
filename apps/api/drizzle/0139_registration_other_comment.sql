-- Пожелание «Другое» объясняется словами (продолжение ADR 0034).
--
-- «Другое» — единственный вариант, которому в портале не соответствует никакая роль
-- (`registrationRoleRequestRole.other = null`). До сих пор он ничего не уточнял, и заявка
-- приходила ровно с тем, что было до пожеланий: ФИО, адрес, телефон. Рассматривать её
-- приходилось звонком — тем самым, ради отмены которого пожелание и заводили. Теперь такой
-- заявитель пишет строкой, кем работает.
--
-- Свободный текст, как объект и компания (0057): справочники неаутентифицированному не отдаются,
-- да и отображать это не на что — «Другое» на роль не отображается по определению.

ALTER TABLE users
  ADD COLUMN requested_comment text NOT NULL DEFAULT '';

-- CHECK на непустоту здесь **не** заводится — в отличие от `users_requested_object_check` и
-- `users_requested_company_check` (0057). Те появились вместе с самим `requested_role`, когда
-- строк с пожеланием в таблице не было ни одной; заявки «Другое» существуют уже сейчас, и
-- заполнить им комментарий задним числом нечем. Такой CHECK проверял бы строку при **любом** её
-- обновлении, и старая заявка перестала бы двигаться вовсе: ни активировать, ни назначить роль,
-- ни привязать человека, ни сменить адрес. `NOT VALID` не спасает по той же причине — он не
-- проверяет старые строки только до первого их обновления (то же рассуждение, что в 0118).
--
-- Обязательность требует `registerSchema` в контрактах — там же, где обязательность объекта и
-- компании: она и решает, что попадёт в базу через регистрацию.
