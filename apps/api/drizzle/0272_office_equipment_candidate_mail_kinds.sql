-- (план `docs/office-equipment-candidate-plan.md`, §10 и §14, миграция M2; общая механика — ADR
-- 0159, миграция-предшественница `0257`).
--
-- ОТКУДА НОМЕР. `ls apps/api/drizzle` непосредственно перед созданием файла (04.09.2026, 15:05):
-- последняя миграция в дереве — `0271_esm2_machinist_name_backfill.sql` соседнего потока, которой
-- полчаса назад ещё не было. За сегодня соседи заняли `0263`, `0265`–`0268`, `0270` и `0271`,
-- поэтому план в §14 номера намеренно не резервирует: снимок свободного номера живёт часы, и
-- берётся он в момент создания файла. Свободны `0272` (этот файл) и `0273` (M3, следующий).
--
-- ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ, В КОТОРОМ ОДНИ ЛИШЬ ДВА ЗНАЧЕНИЯ. Раннер применяет файл миграции целиком в
-- ОДНОЙ транзакции (`apps/api/src/db/migration-journal.ts`), а PostgreSQL не разрешает пользоваться
-- новым значением enum до её фиксации. Строки рубильника (`module_mail_event_settings`) значениями
-- `mail_kind` не пользуются — их ключ текстовый, — но `CHECK` тамошнего перечня и сами строки едут
-- следующим файлом по другой причине: два файла разделяют «словарь видов» и «настройку событий», и
-- откатывать их приходится по-разному (см. ниже). Тот же приём — в `0257`, `0180`, `0142`, `0122`,
-- `0114`, `0103`, `0065`, `0054`.
--
-- ПОЧЕМУ ВИД У КАЖДОГО СОБЫТИЯ СВОЙ. Очередь уникальна по паре `(kind, dedupe_key)`, и событие,
-- притворившееся соседним, молча подавляло бы его письмо: `ON CONFLICT DO NOTHING` не отличает «эта
-- работа уже сделана» от «мы столкнулись ключами». Здесь это не теория — заведение пары «кандидат +
-- заявка» ОДНОЙ транзакцией ставит рядом `service_request_waiting_it`: службе «заявку надо
-- разобрать», проверяющим «сообщение надо проверить». Один вид на два факта потерял бы одно из двух
-- писем и без единого следа.
--
-- ЧЕГО ЗДЕСЬ НЕТ:
--   · ни одной строки `module_mail_event_settings` и ни одной правки её `CHECK` — это M3 (`0273`);
--   · ни одного `grant_permissions`: составы наборов волны кандидатов едут выпуском B (M4/M4а);
--   · ни одной записи `app_releases`: рассказывать в журнале обновлений пока нечего — оба события
--     заводятся ВЫКЛЮЧЕННЫМИ, и до включения (Э8) человек не увидит ни одного письма.
--
-- ОБРАТИМОСТЬ: аддитивна, смысл существующих данных не меняется. Обратного шага нет и быть не
-- может — значение enum в PostgreSQL не удаляется; откат кода просто перестаёт его писать. Само по
-- себе появление видов писем не шлёт: события заводятся выключенными миграцией `0273`.

ALTER TYPE mail_kind ADD VALUE IF NOT EXISTS 'office_equipment_candidate_pending';
ALTER TYPE mail_kind ADD VALUE IF NOT EXISTS 'office_equipment_candidate_decided';
