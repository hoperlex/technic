-- Виды писем полного контура модуля «Орг.техника»
-- (план `docs/office-equipment-mail-expansion-plan.md`, § 3 и §5.1, этап Э1).
--
-- Сегодня подрядчик получает три письма из семи фактов жизни заявки: назначение, отзыв назначения
-- и отмену. Остальное движение — приняли в работу, отложили, предъявили объём работ, приложили акт,
-- написали в обсуждении — для него не существует вовсе. Четыре событийных вида закрывают эти
-- факты, пятый технический: сводка ограничения частоты (§5.11), которая ставится вместо
-- очередного письма, когда по паре «заявка + адресат» за час набирается предел.
--
-- Свой вид каждому событию обязателен, а не общий на всех: `mail_messages` уникальна по паре
-- `(kind, dedupe_key)`, и событие, притворившееся соседним, молча подавляло бы его письмо по той же
-- строке истории статуса — пропадало бы одно из двух, и без единого следа. У сводки вид отдельный
-- ещё и потому, что она не бизнес-событие: в перечне `MODULE_MAIL_EVENTS` и в админке её нет,
-- рубильника у неё тоже нет — она появляется только вместо уже включённого события.
--
-- Значения добавляются отдельной миграцией и в той же транзакции кодом не используются: раннер
-- применяет файл миграции целиком в одной транзакции (`apps/api/src/db/migration-journal.ts`), а
-- PostgreSQL не разрешает пользоваться новым значением enum до её фиксации. Тот же приём — в
-- миграциях 0180, 0142, 0122, 0114, 0103, 0065, 0054.
--
-- Обратимость: аддитивна, смысл существующих данных не меняется. Обратного шага нет и быть не
-- может — значение enum в PostgreSQL не удаляется; откат кода просто перестаёт его писать. Само по
-- себе появление видов писем не шлёт: события заводятся выключенными (миграция 0258).

ALTER TYPE mail_kind ADD VALUE IF NOT EXISTS 'service_request_status_changed';
ALTER TYPE mail_kind ADD VALUE IF NOT EXISTS 'service_request_estimate';
ALTER TYPE mail_kind ADD VALUE IF NOT EXISTS 'service_request_document';
ALTER TYPE mail_kind ADD VALUE IF NOT EXISTS 'service_request_comment';
ALTER TYPE mail_kind ADD VALUE IF NOT EXISTS 'service_request_activity_summary';
