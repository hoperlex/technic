-- Включение четырёх почтовых событий модуля «Орг.техника» — `service_request_status_changed`,
-- `service_request_estimate`, `service_request_document`, `service_request_comment`
-- (план `docs/office-equipment-mail-expansion-plan.md`, этап Э8; механика рубильника — ADR 0159).
--
-- Строки завела выключенными миграция 0258, и выключены они были не из осторожности: раздел
-- «Орг.техника» стоял под заплаткой `temporarySectionLock`, а письма этих событий уходят НАРУЖУ —
-- сервисной компании, у которой портала нет вовсе. Заплатка снята 09.09.2026
-- (`office-equipment-section-hidden`), барьер включения из § 6 плана пройден: split набора
-- исполнителя закрыт миграцией 0262 (Э8 плана аудита / Э6 плана профилей), финансовая аудитория и
-- видимость файлов — планом карточки заявителя (ADR 0160, миграции 0259/0260).
--
-- ОТКУДА НОМЕР. Снимок `ls apps/api/drizzle` 18.09.2026: последней в дереве стоит
-- `0319_releases_device_telemetry.sql`, в истории всех веток файлов `032*` нет. Свободны 0320 и
-- 0321, оба взяты подряд одной работой — включение и запись выпуска не должны разъехаться по
-- разным выкатам.
--
-- ПОЧЕМУ ВСЕ ЧЕТЫРЕ СРАЗУ, ХОТЯ ПЛАН ОБЕЩАЛ ВКЛЮЧАТЬ ПО ОДНОМУ. Обещание про окно наблюдения
-- остаётся в силе, но окном распоряжается администратор, а не эта миграция: рубильник правится
-- ручкой `PATCH /admin/mail/events/:event` из админки в любую сторону и в любой момент, без
-- выката. Миграция отвечает на другой вопрос — каким контур приезжает на КАЖДУЮ базу (dev, стенд,
-- восстановленная копия, новое развёртывание), — и четыре строки, оставленные выключенными там,
-- означали бы, что проверенное на проде поведение нигде больше не воспроизводится.
--
-- ЧТО МЕНЯЕТСЯ У ЛЮДЕЙ. До этой миграции подрядчик получал три письма: заявка назначена,
-- назначение отозвано, заявка отменена. После — ещё четыре: заявка сменила состояние (принята в
-- работу, отложена, выполнена, принята), движение по объёму работ (предъявлен, согласован, возвращён
-- в правку), приложенные документы и реплики обсуждения. Адресатов сверх этого миграция не заводит:
-- строки `module_mail_recipients` (копии) — работа администратора, а не выката.
--
-- ЧЕГО МИГРАЦИЯ НЕ ДЕЛАЕТ: не трогает три работающих события и два события кандидата (караул
-- сверяет их со снимком «до»), не заводит ящики контрагентов, не меняет схему и `CHECK` перечня —
-- все четыре значения стоят в нём с 0258.
--
-- `version` БЬЁТСЯ НАМЕРЕННО. Столбец — замок одновременной правки: админка шлёт `UPDATE` с той
-- версией, которую показала форма, и не сдвинь мы её здесь, администратор, открывший экран писем до
-- выката, вернул бы рубильники в выключенное положение своим «Сохранить» — молча. Со сдвинутой
-- версией его сохранение честно отвечает конфликтом. `updated_by` остаётся `NULL`: щёлкнул выкат, а
-- не человек, и выдавать одно за другое в журнале рубильника нельзя.
--
-- ОБРАТИМОСТЬ. Схема не меняется, трогаются четыре строки одной таблицы. Откат — `UPDATE … SET
-- is_enabled = false, version = version + 1` по тем же ключам, и делать его выкатом не обязательно:
-- зашумевшее событие гасится из админки за один щелчок. Строки при этом остаются — их отсутствие
-- приложение трактует fail-closed, то есть так же молчаливо, но неотличимо от «миграции не хватает».

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 0. Снимок остальных рубильников ДО правки — ради утверждения «чужих событий не трогали».
--
-- `ON COMMIT DROP`: таблица живёт до конца транзакции миграции и в базе не остаётся. Именно снимок,
-- а не константа: три события заявки включены с 0258, два события кандидата — с 0295, и щёлкнуть их
-- администратор мог в любую сторону в любой день; на проде, в деве и на восстановленной из копии
-- базе картина разная.

CREATE TEMP TABLE mail_events_0320 ON COMMIT DROP AS
SELECT event, is_enabled
FROM module_mail_event_settings
WHERE event NOT IN ('service_request_status_changed',
                    'service_request_estimate',
                    'service_request_document',
                    'service_request_comment');

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 1. Сами четыре рубильника.
--
-- Условие `is_enabled = false` — не защита от повторного наката, а защита ВЕРСИИ: без него повторный
-- накат на уже включённой базе сдвинул бы `version` ещё раз и уронил бы открытую форму
-- администратора, ничего при этом не изменив. Идемпотентность от этого не страдает: результат обоих
-- накатов один, и караул ниже проверяет именно результат, а не число обновлённых строк.

UPDATE module_mail_event_settings
   SET is_enabled = true,
       version = version + 1,
       updated_at = now()
 WHERE event IN ('service_request_status_changed',
                 'service_request_estimate',
                 'service_request_document',
                 'service_request_comment')
   AND is_enabled = false;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 2. Караул: четыре включены, остальные — как были.
--
-- Страж-тест сверяет реестр событий с контрактами, но живёт он в репозитории, а этот блок — в
-- накате: оператор выката увидит расхождение сразу, а не через прогон тестов.

DO $$
DECLARE trouble text;
BEGIN
  SELECT string_agg(msg, '; ')
    INTO trouble
    FROM (
      SELECT format('рубильник «%s» не включён или его строки нет вовсе', s.event) AS msg
        FROM (VALUES ('service_request_status_changed'),
                     ('service_request_estimate'),
                     ('service_request_document'),
                     ('service_request_comment')) AS s (event)
       WHERE NOT EXISTS (
         SELECT 1 FROM module_mail_event_settings m
          WHERE m.event = s.event AND m.is_enabled)
      UNION ALL
      SELECT format('чужой рубильник «%s» изменился: было %s, стало %s',
                    b.event, b.is_enabled, m.is_enabled)
        FROM mail_events_0320 b
        JOIN module_mail_event_settings m ON m.event = b.event
       WHERE m.is_enabled <> b.is_enabled
      UNION ALL
      SELECT format('строк рубильника стало %s вместо %s: событие завелось или пропало мимо волны',
                    (SELECT count(*) FROM module_mail_event_settings),
                    (SELECT count(*) + 4 FROM mail_events_0320))
       WHERE (SELECT count(*) FROM module_mail_event_settings)
             <> (SELECT count(*) + 4 FROM mail_events_0320)
    ) AS bad;
  IF trouble IS NOT NULL THEN
    RAISE EXCEPTION
      'Включение почтовых событий заявки прошло не так, как объявлено — %', trouble;
  END IF;
END $$;
