-- Частичный индекс под возврат просроченных задач в очередь.
--
-- Воркер получил аренду: задачу, взятую упавшим процессом, забирает обратно `reclaimExpiredJobs`
-- запросом `WHERE status = 'running' AND locked_until < now()`. Существующий `jobs_due_idx`
-- построен по `(status, next_run_at)` и такому запросу помогает только префиксом `status`: внутри
-- «running» строки лежат по `next_run_at`, то есть по величине, к аренде отношения не имеющей.
--
-- Пока в работе единицы строк, разницы нет — но возврат зовётся каждым тактом воркера, а очередь
-- растёт вместе с модулями: письма, уборка файлов, распознавание талонов (ADR 0114). Индекс на
-- «сколько-то строк в running» дешевле любого из этих тактов.
--
-- Частичный, а не общий: строк со статусом `running` в очереди всегда меньшинство, и незачем
-- держать в индексе весь журнал выполненных.
CREATE INDEX IF NOT EXISTS jobs_lease_idx ON jobs (locked_until) WHERE status = 'running';
