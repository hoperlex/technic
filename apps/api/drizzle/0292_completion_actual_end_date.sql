-- Закрытие заказа фактической датой: снимок факта у закрытия и след сокращения у листа ЭСМ-2
-- (план `docs/vehicle-request-actual-end-date-plan.md`, §4, Р12, Р23; этап Э2). Парная правка
-- декларации — `apps/api/src/db/schema.ts`, таблицы `vehicleRequestCompletions` и `waybills`.
--
-- ОТКУДА НОМЕР. `ls apps/api/drizzle/*.sql | tail` перед созданием файла (09.09.2026): последней в
-- дереве стоит `0291_releases_mech_ordering_grant.sql` соседнего потока, свободен 0292. План
-- номер за собой НЕ закреплял и правильно делал: в волне миграций три — эта и две записи выпуска
-- (Э0 и Э14), — а между ними работают соседние потоки. Номер спрашивается у ФАЙЛОВ дерева, а не у
-- журнала базы: на technic_dev часть закоммиченных миграций не накатана, и `max(seq)` там врёт в
-- меньшую сторону. Проверены и рабочие копии соседних веток (`git worktree list`): 0292 свободен
-- во всех.
--
-- ЗАЧЕМ. Недельная заявка продлевает технику до воскресенья, работы кончаются в среду. Сегодня
-- закрыть заказ средой можно только отдельным действием с визой, и сверка на это ПЕРЕОФОРМЛЯЕТ
-- недельный лист ЭСМ-2: сжигает номер, печатает новый бланк и просит площадку расписаться заново
-- за уже отработанные дни. Волна заводит третий исход бумажного плана — `trim`, правку периода
-- того же бланка (Р5, Р6), — и оба следа этой правки: чем закрыли заказ и чем сокращён лист.
--
-- ПОЧЕМУ ЭТОТ ФАЙЛ ЕДЕТ ОТДЕЛЬНО ОТ КОДА, ЧТО ЕГО ЧИТАЕТ. Миграция чисто аддитивная: пять колонок
-- листу, две закрытию, два CHECK и частичный индекс. Ни одна существующая строка не переписывается
-- и ни одно существующее правило не ослабляется, поэтому накат на работающий прод старую версию
-- приложения не задевает — она новых колонок просто не видит. Обратный порядок (код раньше схемы)
-- невозможен и не рассматривается: дверь закрытия пишет снимок первой же командой.
--
-- ЧТО НЕ ПРАВИТСЯ И ПОЧЕМУ. `waybill_corrections_kind_check` остаётся прежним: вид операции
-- выводится из исхода, и закрытие получает `crew` либо `assignment_tail` — оба значения в CHECK
-- уже есть (миграции 0129, 0157 и далее). Своего вида `completion` не заводим (Р20): дверь
-- различается `journalDoor` и payload, а не третьим словом в журнале.
--
-- ОБРАТИМОСТЬ. Откат — снятие добавленного, в обратном порядке; данных, которых больше нигде нет,
-- на момент отката ещё не появляется (дверей, пишущих эти колонки, в этом выпуске нет):
--   DROP INDEX waybills_period_trimmed_idx;
--   ALTER TABLE waybills DROP CONSTRAINT waybills_period_trim_check;
--   ALTER TABLE waybills
--     DROP COLUMN period_trim_correction_id, DROP COLUMN period_trim_reason,
--     DROP COLUMN period_trimmed_by, DROP COLUMN period_trimmed_at, DROP COLUMN period_to_original;
--   ALTER TABLE vehicle_request_completions
--     DROP CONSTRAINT vehicle_request_completions_ended_on_check,
--     DROP COLUMN previous_date_to, DROP COLUMN ended_on;
-- После выката дверей откат схемы означает потерю следа правки бланков строгой отчётности —
-- откатывать придётся вместе с кодом и с решением, что делать с уже сокращёнными листами.
--
-- БЛОКИРОВКИ. Весь файл идёт одной транзакцией раннера. `ADD COLUMN` с константным умолчанием на
-- PostgreSQL 11+ таблицу не переписывает, а `ADD CONSTRAINT ... CHECK` требует полного прохода по
-- обеим таблицам под `ACCESS EXCLUSIVE`. Проход этот здесь холостой — новые колонки у всех
-- существующих строк пусты, и оба ограничения на них истинны по построению, — поэтому
-- `NOT VALID` + `VALIDATE CONSTRAINT` не заводим: журнал листов для одного прохода мал (тем же
-- рассуждением шла миграция 0129).

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 1. Снимок фактической даты у закрытия заявки (Р2, Р23).
--
-- `ended_on` — день, которым заказ закрыт. Той же командой он становится и сроком заявки (Р4),
-- поэтому сразу после закрытия совпадает с `vehicle_requests.date_to`. Снимок заведён именно
-- поэтому, а не вопреки: `date_to` живёт дальше своей жизнью — откат в работу, продление,
-- следующее сокращение, — а вопрос «каким числом закрыли» задают к закрытию.
--
-- `previous_date_to` — каким срок был до закрытия. Пара отвечает «было 09.08, закрыли 05.08» и
-- продолжает отвечать после любой следующей правки срока, когда разность из соседних полей уже не
-- восстановить. Тем же приёмом живёт снимок досрочного завершения
-- (`vehicle_request_early_endings.previous_date_to`, миграция 0071).
--
-- ЧЕМ ЗАПОЛНЯЕТСЯ У ОДНОДНЕВНОГО ЗАКАЗА. `vehicle_requests.date_to` нullable, и пустая означает
-- ОДНОДНЕВНЫЙ срок с эффективным концом `date_from` — так её читают срез, подписи присутствия и
-- `earlyEndBlocker`. Сервер поэтому пишет сюда `date_to ?? date_from`, а не сырое поле: сырой
-- `null` уронил бы CHECK ниже на самом обычном заказе на один день. Правило исполняется кодом —
-- CHECK через таблицы не ходит, — и доказывается db-тестом «однодневный заказ с `date_to = null`»
-- (Э12).
ALTER TABLE vehicle_request_completions
  ADD COLUMN ended_on         date,
  ADD COLUMN previous_date_to date;

COMMENT ON COLUMN vehicle_request_completions.ended_on IS
  'Фактический конец работ: день, которым закрыт заказ. Пусто у закрытий до этой волны, у '
  'грузоперевозки и у арендодательской ветви закрытия.';
COMMENT ON COLUMN vehicle_request_completions.previous_date_to IS
  'Срок заявки до закрытия — эффективный конец (`date_to ?? date_from`), а не сырое поле. Пара с '
  '`ended_on` отвечает «было 09.08, закрыли 05.08» после любой следующей правки срока.';

-- Пара или ничего. «Закрыли 05.08» без «было 09.08» не отвечает на вопрос, ради которого снимок
-- заведён, а «было 09.08» без факта не объясняет ничего вовсе.
--
-- Второе условие — граница самого понятия (Р15): закрыть позже утверждённого срока нельзя, это
-- продление, на новые дни нужна бумага, а выписка её задним числом и есть коррекция. Равенство
-- законно и обыденно: заказ, отработанный ровно по сроку, закрывается своим последним днём и
-- бумаги не трогает вовсе.
--
-- NULL здесь не проходит мимо: первое условие уже связало пустоту обеих колонок, поэтому во
-- втором `previous_date_to` заведомо заполнена.
ALTER TABLE vehicle_request_completions
  ADD CONSTRAINT vehicle_request_completions_ended_on_check CHECK (
    (ended_on IS NULL) = (previous_date_to IS NULL)
    AND (ended_on IS NULL OR ended_on <= previous_date_to)
  );

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 2. След сокращения периода у листа (Р12).
--
-- `period_to_original` — каким лист был ВЫДАН. Заполняется первым сокращением и дальше не
-- трогается никогда, в том числе повторным: `period_to` отвечает «до какого числа лист действует
-- сейчас», а «до какого числа его выписали» после правки не восстановить ниоткуда — номер тот же,
-- снимок `data` приведён к факту, печатный экземпляр остался на площадке прежним (Р13).
--
-- `period_trimmed_at` / `period_trimmed_by` / `period_trim_reason` — тройка «когда, кто, почему»
-- про ПОСЛЕДНЮЮ правку, а не про первую: прежние читаются в событиях `waybill.esm2_sync` и в
-- снимках операций коррекции, и второй их копии здесь не заводим.
--
-- Причина отдельной колонкой, а не отсылкой к журналу операций, — по той же причине, по какой
-- рядом уже лежат `cancel_reason` и `correction_reason`: двух разных ответов на вопрос «почему
-- этот бланк не такой, каким выдан» быть не должно. Отсылкой тут и не обойтись — обычное закрытие
-- сегодняшним днём операции не создаёт вовсе (Р8), и причина у такого листа осталась бы
-- ненаписанной.
--
-- `period_trim_correction_id` — операция журнала у ЛЮБОЙ неординарной правки, а не только у
-- заднего числа: условие то же, каким сегодня связывают лист отмена и выпуск
-- (`context.kind <> 'ordinary'` в `apps/api/src/services/waybill-esm2.ts`). Третья ссылка рядом с
-- `correction_id` (кто лист породил) и `cancel_correction_id` (кто списал), и свести их в одну
-- нельзя: у листа бывают все три сразу — рождён перевыпиской, через неделю сокращён, ещё через
-- неделю списан. Обычная последующая правка ссылку СНИМАЕТ: она описывает ту же, последнюю
-- правку, что и тройка.
--
-- RESTRICT у обеих ссылок — как у `issued_by`, `cancelled_by` и обеих ссылок на коррекцию: правку
-- бланка строгой отчётности обязано пережить и увольнение автора, и любую чистку журнала.
ALTER TABLE waybills
  ADD COLUMN period_to_original date,
  ADD COLUMN period_trimmed_at  timestamptz,
  ADD COLUMN period_trimmed_by  uuid REFERENCES users (id) ON DELETE RESTRICT,
  ADD COLUMN period_trim_reason text NOT NULL DEFAULT '',
  ADD COLUMN period_trim_correction_id uuid REFERENCES waybill_corrections (id) ON DELETE RESTRICT;

COMMENT ON COLUMN waybills.period_to_original IS
  'Каким лист был выдан: `period_to` на момент выписки. Ставится первым сокращением и больше не '
  'трогается — в том числе повторным.';
COMMENT ON COLUMN waybills.period_trimmed_at IS
  'Когда лист приведён к нынешнему виду. Тройка «когда, кто, почему» описывает последнюю правку.';
COMMENT ON COLUMN waybills.period_trimmed_by IS 'Кто сократил период листа.';
COMMENT ON COLUMN waybills.period_trim_reason IS
  'Почему период укоротили: «Заказ ТС-123 закрыт фактической датой 05.08.2026».';
COMMENT ON COLUMN waybills.period_trim_correction_id IS
  'Операция журнала коррекций, в рамках которой лист сокращён, — у любой неординарной правки. '
  'Обычная последующая правка ссылку снимает.';

-- Комплект или ничего. Держит это схема, а не сервис, по той же причине, по какой схема держит
-- причину перевыписки (`waybills_correction_reason_check`): сокращение приезжает из общего
-- исполнителя бумаги, а зовут его несколько дверей — закрытие, правка срока, обе применяющие
-- ветви досрочного завершения, — и достаточно одной забыть причину или автора, чтобы в журнале
-- появился бланк, не такой, каким выдан, и без объяснения. Это ровно то состояние, ради закрытия
-- которого заводился журнал коррекций.
--
-- Условия по порядку:
--   · «когда» и «кто» ходят парой — метка без автора не отвечает, с кого спрашивать;
--   · «когда» и «каким выдан» ходят парой — без прежнего конца метка не показывает правку, а без
--     метки прежний конец нечем датировать;
--   · причина непуста ровно у сокращённого и пуста у всех прочих: объяснение правки у листа,
--     который не правили, означало бы, что правку потеряли;
--   · ссылка на операцию бывает только у сокращённого — обратное означало бы лист, который
--     операция правила, а следов правки нет;
--   · `period_to_original` строго больше нынешнего конца: равенство назвало бы сокращённым лист,
--     который не сокращали, а меньшее — расширение выданного бланка, которого правка не умеет ни
--     при каких входных данных, включая возврат к исходному периоду (Р6).
--
-- `period_to IS NOT NULL` в последнем условии — СВЕРХ ТЕКСТА ПЛАНА, и намеренно. В плановой
-- редакции сравнение у листа без периода даёт NULL, а NULL в CHECK проходит: сокращённым мог бы
-- числиться рейсовый 4-П или форма № 3, у которых недели нет вовсе
-- (`waybills_form_source_check`). Сокращают только ЭСМ-2, и ограничение обязано это сказать, а не
-- промолчать трёхзначной логикой.
ALTER TABLE waybills ADD CONSTRAINT waybills_period_trim_check CHECK (
  (period_trimmed_at IS NULL) = (period_trimmed_by IS NULL)
  AND (period_trimmed_at IS NULL) = (period_to_original IS NULL)
  AND (period_trimmed_at IS NULL) = (btrim(period_trim_reason) = '')
  AND (period_trimmed_at IS NOT NULL OR period_trim_correction_id IS NULL)
  AND (period_to_original IS NULL
       OR (period_to IS NOT NULL AND period_to_original > period_to))
);

-- Третий источник метки «коррекция» в журнале листов (Р12) — рядом с двумя такими же частичными
-- индексами по ссылкам на операцию (`waybills_correction_idx`, `waybills_cancel_correction_idx`).
-- Условие держит индекс размером с долю сокращённых листов, а не с таблицей.
--
-- Оговорка на будущее, честная: отбор «только коррекции» спрашивает ТРИ колонки через `OR`, и
-- один частичный индекс такой запрос сам по себе не закрывает. Индекс заведён ради второго входа
-- — «какие бланки не такие, какими выданы», отдельным вопросом и в порядке правки, — и ради
-- симметрии с соседями. Снимать его, как и соседние, следует по `EXPLAIN` на производственной
-- статистике, а не по догадке.
CREATE INDEX waybills_period_trimmed_idx ON waybills (period_trimmed_at DESC)
  WHERE period_trimmed_at IS NOT NULL;
