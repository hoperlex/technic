-- Форма ЭСМ-2 (лист на неделю работы строительной машины) и вложения к бланку.
--
-- До этой миграции путевой лист был документом одной поездки одного дня: он рождался с рейса,
-- держал ссылку на него NOT NULL (0074) и жил ровно столько, сколько жил рейс. ЭСМ-2 устроен
-- иначе — это документ на неделю стояния машины на площадке: семь строк «пн…вс», недельные итоги
-- моточасов и топлива, оборот «Заполняется заказчиком». Ни рейса, ни маршрута, ни груза у него
-- нет; есть заявка спецтехники, объект, период работ и машинист.
--
-- Отсюда всё, что делает миграция: лист учится жить без рейса, но с заявкой-основанием и
-- периодом, и получает свою серию номеров. Плюс — общее для всех трёх бланков — к номеру можно
-- подшить скан: заполненный заказчиком оборот, отметки, акт.

-- 1. Лист без рейса.
--
-- Инвариант «листа без рейса не бывает», объявленный 0074, отменяется: у недели работы
-- экскаватора на площадке рейса нет и быть не может. Взамен появляется заявка-основание — тем же
-- приёмом, которым 0082 привязала к заявке рейс-перегон.
ALTER TABLE waybills
  ALTER COLUMN route_id DROP NOT NULL,
  -- RESTRICT: заявку, ради которой выписан бланк строгой отчётности, из базы не удаляют.
  ADD COLUMN source_request_id uuid REFERENCES vehicle_requests (id) ON DELETE RESTRICT,
  -- Фактические рабочие дни недели — то, что печатается в графе «Период работы: с __ по __».
  -- Не понедельник с воскресеньем: заявка с 06.08 даёт лист 06.08–09.08 со строками ср…вс,
  -- заполненными по своим дням, и пустыми пн и вт.
  ADD COLUMN period_from date,
  ADD COLUMN period_to date;

-- Источник документа ровно один. У 4-П и формы № 3 это рейс, у ЭСМ-2 — заявка с периодом;
-- третьего сочетания не бывает, и без CHECK лист мог бы оказаться сразу и рейсовым, и недельным.
ALTER TABLE waybills
  ADD CONSTRAINT waybills_form_source_check
    CHECK (
      (form_code = 'esm2'
        AND route_id IS NULL
        AND source_request_id IS NOT NULL
        AND period_from IS NOT NULL
        AND period_to IS NOT NULL)
      OR (form_code <> 'esm2'
        AND route_id IS NOT NULL
        AND source_request_id IS NULL
        AND period_from IS NULL
        AND period_to IS NULL)
    ),
  -- Лист не выходит за календарную неделю: в бланке семь строк, пн…вс, и восьмой день печатать
  -- некуда. Границей месяца неделя при этом не режется — графа «месяца» принимает «08–09».
  --
  -- date_trunc(text, timestamp) IMMUTABLE (в отличие от варианта от timestamptz), и в CHECK его
  -- пускают. Неделя у date_trunc начинается с понедельника — ровно как в бланке.
  ADD CONSTRAINT waybills_period_check
    CHECK (
      period_from IS NULL
      OR (period_to >= period_from
        AND date_trunc('week', period_from::timestamp) = date_trunc('week', period_to::timestamp))
    );

-- Одна неделя — один действующий лист. Аннулированные не мешают: испорченный бланк списан, и
-- сверка выписывает на ту же неделю новый номер (так же устроен waybills_route_unique, 0074).
CREATE UNIQUE INDEX waybills_source_request_period_unique
  ON waybills (source_request_id, period_from)
  WHERE status <> 'cancelled';

-- «Какие листы у этой заявки» — вопрос и карточки заявки, и сверки, которая читает их при каждом
-- изменении срока.
CREATE INDEX waybills_source_request_idx ON waybills (source_request_id)
  WHERE source_request_id IS NOT NULL;

-- 2. Своя серия номеров.
--
-- Заявка на месяц забирает пять бланков разом, а каждое досрочное завершение сжигает и выписывает
-- ещё столько же: в общей серии журнал 4-П получал бы дыры от документов, которых в нём нет.
-- Ширина номера та же, что у основной серии, — журнал читают одинаково.
INSERT INTO waybill_series (code, name, number_width, comment) VALUES
  ('esm2', 'Серия ЭСМ-2', 8, 'Заведена миграцией 0087: у недельных листов спецтехники своя нумерация')
ON CONFLICT (code) DO NOTHING;

-- 3. Вложения к бланку.
--
-- Лист уходит на объект бумагой и возвращается заполненным: у ЭСМ-2 заказчик пишет на обороте
-- часы, простои и стоимость машино-часа и ставит штамп. Портал этих значений не разбирает —
-- журнал учёта отвечает, чем кончился выданный номер, и скан подшивается к номеру.
--
-- Файл крепится к листу, а не к заявке: заявок у листа бывает четыре (талоны 4-П), а неделя работ
-- распадается на несколько листов — «чей это скан» отвечает только номер бланка.
CREATE TABLE waybill_files (
  waybill_id uuid NOT NULL REFERENCES waybills (id) ON DELETE CASCADE,
  file_id uuid NOT NULL REFERENCES files (id) ON DELETE CASCADE,
  added_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (waybill_id, file_id)
);

-- Файл живёт максимум в одном месте — так же, как у заявок обоих модулей (ADR 0024). Уникальность
-- здесь только внутри таблицы; кросс-модульную держит linkedFileIds в request-files.ts, и третью
-- таблицу он обязан знать.
CREATE UNIQUE INDEX waybill_files_file_unique ON waybill_files (file_id);
