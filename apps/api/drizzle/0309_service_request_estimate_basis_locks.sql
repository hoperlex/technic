-- Двусторонние ограничения связи «файл ↔ ревизия объёма работ»: роль без ревизии и ревизия без роли
-- невозможны, адрес страницы основания однозначен
-- (план `docs/office-equipment-on-site-and-invoice-estimate-plan.md`, редакция 5, решения Р4 и Р6,
-- находка §8 «Узкие места реализации»; этап Э4).
--
-- ОТКУДА НОМЕР. Снимок `ls apps/api/drizzle` непосредственно перед созданием файла (11.09.2026):
-- последним в дереве стоит `0308_files_quarantine_grant.sql` — файл параллельной волны карантина, —
-- свободен `0309`, он и взят. Номер берётся в момент создания и не резервируется на волну вперёд:
-- рядом идут сразу два потока (карантин файла и эта волна), и занятый незакоммиченным файлом номер
-- виден только в дереве.
--
-- ЧТО ЗАКРЫВАЕТ. Сверка волны Э1/Э2 нашла, что оба замка миграции 0306 односторонние, и каждая
-- половина молчит по-своему:
--
--   1. `service_request_files_basis_check` требует ревизию У ОСНОВАНИЯ, но не запрещает ревизию
--      закрывающей бумаге. То есть акт или фотография поломки вправе нести `estimate_revision` —
--      поле, которое для них не означает ничего, — и это не косметика. Замок «основание не
--      снимается никогда» (Р6 п. 1) спрашивает РОЛЬ, а составной внешний ключ держит РЕВИЗИЮ: у
--      такой строки ключ запрещает удалить строку ревизии (`ON DELETE RESTRICT`), а ручка снятия
--      файл отдаёт — и сброс сметы по переназначению отбивается 422 ради бумаги, основанием
--      никогда не бывшей. Обратная половина — основание без ревизии — уже запрещена 0306, и
--      двусторонняя редакция просто делает из двух половин одно правило.
--   2. Две страницы одной ревизии могут получить ОДИН И ТОТ ЖЕ `page_no`. Сегодня их нумерует
--      порядок присланного списка, то есть один `INSERT`, и столкнуться номерам нечем; но на этот
--      номер будет опираться разбор документа (Р12): предложение привязывается к листу, и «лист 1»
--      в двух экземплярах означает, что распознанное некуда класть. Такое расхождение не
--      отбивается ничем и обнаруживается позже всего — данными, которые уже нельзя разложить.
--
-- ПОЧЕМУ ОТДЕЛЬНОЙ МИГРАЦИЕЙ, А НЕ ПРАВКОЙ 0306. Обе правки ПЕРЕЖИВАЮТ ОКНО ВЫКАТА, и ровно это
-- позволило не держать их в выпуске A: миграции идут при работающем портале и до перезапуска
-- приложения, то есть какое-то время в `service_request_files` пишет ТОЛЬКО СТАРЫЙ КОД. Старый код
-- обеих колонок не пишет вовсе — роль ему достаётся умолчанием `closing_evidence`, а
-- `estimate_revision` и `page_no` остаются пустыми, — и для его строк новое условие истинно обеими
-- половинами: `(purpose = 'estimate_basis') = (estimate_revision IS NOT NULL)` сводится к
-- `false = false`. Новый код (ручка предъявления, Э4) пишет обе колонки только вместе с ролью
-- основания и нумерует страницы с единицы внутри одного оператора. Значит ограничение не отказывает
-- ни одной из двух работающих редакций, и катить его можно в любой момент окна.
--
-- ПРОД — PostgreSQL 17, ДЕВ — 16. Версионно-спорного здесь одно: `NULLS NOT DISTINCT` у
-- уникального индекса (PostgreSQL 15+, в дереве уже применён миграцией 0037). Функций в индексе
-- нет. `CREATE INDEX` идёт без `CONCURRENTLY` — раннер катит файл одной транзакцией
-- (`apps/api/src/db/migration-journal.ts`), — и блокировка записи на время построения это доли
-- секунды: частичный индекс строится по связям-основаниям, которых в базе единицы.
--
-- ОТКАТ — возврат односторонней редакции `service_request_files_basis_check` и `DROP INDEX
-- service_request_files_basis_page_unique`. Данных миграция не меняет (см. backfill ниже: он
-- вычищает то, чего в базе быть не должно), поэтому откат ничего не теряет.

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 1. Backfill: снять следы ревизии с закрывающих бумаг.
--
-- НУЖЕН ЛИ ОН ВООБЩЕ. Из сегодняшнего кода такая строка не берётся: оба писателя связи
-- (`POST /:id/files` и заведение заявки) колонок не касаются, а третий — ручка предъявления —
-- пишет их только вместе с ролью основания. Но к этой миграции документные ревизии в dev-базах уже
-- существуют: волна Э4 разрабатывалась и прогонялась на живой схеме, и строки там правились руками
-- — в том числе `UPDATE`-ами, обходившими одностороннюю редакцию. Поэтому `UPDATE` стоит здесь, а
-- не в караульном блоке: караул уронил бы накат, заставив чинить dev-базу вручную, а правда про
-- такую строку известна однозначно — роль `closing_evidence` означает, что основанием файл не был,
-- и ссылка на ревизию у него лишняя.
--
-- Обратную половину чистить нечем и не нужно: основание без ревизии запрещала уже 0306, то есть
-- таких строк в базе нет по построению.
--
-- `page_no` снимается тем же оператором: он часть того же правила (ниже в `CHECK`), и оставленный
-- номер страницы у вложения означал бы порядок в документе, которого нет.
UPDATE service_request_files
   SET estimate_revision = NULL, page_no = NULL
 WHERE purpose <> 'estimate_basis'
   AND (estimate_revision IS NOT NULL OR page_no IS NOT NULL);

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 2. Правило роли — двустороннее, и имя у него прежнее.
--
-- ИМЯ СОХРАНЕНО НАМЕРЕННО (`service_request_files_basis_check`): на него ссылается караул миграции
-- 0306 и комментарий в `schema.ts`, а заведи мы второе ограничение рядом — правило «роль основания»
-- стало бы жить в двух строках каталога, и следующая правка поменяла бы одну из них.
--
-- Три условия одного правила, и каждое закрывает свою дыру:
--   · `(purpose = 'estimate_basis') = (estimate_revision IS NOT NULL)` — равенство, а не импликация:
--     основание обязано знать свою ревизию (иначе замок Р6 не найдёт страницу, ищущую по ревизии),
--     а закрывающая бумага не вправе ссылаться на ревизию, к которой отношения не имеет (иначе
--     `ON DELETE RESTRICT` сторожит её как доказательство денежного решения);
--   · `page_no` только у основания — номер листа вне документа не означает ничего;
--   · вид `invoice` у основания — без него любая подшивка смогла бы стать «основанием» и выпала бы
--     из закрывающих бумаг, то есть заявка перестала бы закрываться.
--
-- Обе половины равенства не бывают `NULL`: `purpose` объявлен `NOT NULL`, а `IS NOT NULL` — всегда
-- булево. Значит третьего исхода у условия нет, и `CHECK` не пропускает строку «по неизвестности».
ALTER TABLE service_request_files
  DROP CONSTRAINT IF EXISTS service_request_files_basis_check;

ALTER TABLE service_request_files
  ADD CONSTRAINT service_request_files_basis_check
    CHECK (
      (purpose = 'estimate_basis') = (estimate_revision IS NOT NULL)
      AND (purpose = 'estimate_basis' OR page_no IS NULL)
      AND (purpose <> 'estimate_basis' OR kind = 'invoice')
    );

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 3. Адрес страницы основания однозначен.
--
-- Ключ — тройка «заявка, ревизия, лист»: ревизии нумеруются внутри заявки, и «лист 2 ревизии 1» без
-- заявки не адрес. Частичный по роли — у вложений этих колонок нет вовсе (раздел 2), и полный
-- индекс хранил бы для них одни пустоты.
--
-- `NULLS NOT DISTINCT` (PostgreSQL 15+) обязателен: пустой `page_no` у основания схема допускает —
-- одностраничный счёт порядка листов не имеет, — а без этого модификатора `NULL <> NULL`, и ДВА
-- беспорядковых основания одной ревизии прошли бы оба. Это тот же самый неоднозначный адрес, ради
-- которого индекс и заводится: «страница у этой ревизии одна» — утверждение, на которое обопрётся
-- разбор документа (Р12).
--
-- Уникальность, а не проверка в ручке: страницы пишет один `INSERT` одной команды, и любая
-- будущая — догрузка листа, перенумерация, разбор — будет другой командой, про это правило не
-- знающей.
CREATE UNIQUE INDEX service_request_files_basis_page_unique
  ON service_request_files (request_id, estimate_revision, page_no) NULLS NOT DISTINCT
  WHERE purpose = 'estimate_basis';

COMMENT ON COLUMN service_request_files.estimate_revision IS
  'Чьим основанием файл является: номер ревизии объёма работ этой же заявки. Непуст РОВНО У РОЛИ '
  'estimate_basis (service_request_files_basis_check) — закрывающая бумага ревизию не несёт. '
  'План освобождения от согласования, Р4 и Р6.';

COMMENT ON COLUMN service_request_files.page_no IS
  'Порядок листов одного документа, с единицы. Только у роли estimate_basis и не повторяется внутри '
  'ревизии (service_request_files_basis_page_unique): на этот номер опирается разбор документа (Р12).';

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 4. Караул: замки стоят двусторонними, а не только заведёнными.
--
-- Проверяется не наличие имён — 0306 завела их обоих, — а именно РЕДАКЦИЯ: односторонний `CHECK`
-- существует под тем же именем и выглядел бы работающим замком, защищая половину правила. Поэтому
-- условие читается из `pg_get_constraintdef`, а у индекса сверяются уникальность, частичность и
-- `indnullsnotdistinct`: уникальный индекс, различающий пустоты, пропустил бы ровно тот случай,
-- ради которого заведён.
--
-- Данных караул не проверяет: backfill выше идемпотентен, а портал в окне выката продолжает писать
-- связи — строка, появившаяся между `UPDATE` и проверкой, уронила бы весь накат, ничего не
-- обнаружив (старый код этих колонок не пишет).
DO $$
DECLARE trouble text;
BEGIN
  SELECT string_agg(msg, '; ')
    INTO trouble
    FROM (
      SELECT 'правило роли осталось односторонним — закрывающая бумага вправе нести ревизию' AS msg
       WHERE NOT EXISTS (
               SELECT 1 FROM pg_constraint c
                WHERE c.conname = 'service_request_files_basis_check'
                  AND c.conrelid = 'public.service_request_files'::regclass
                  AND c.contype = 'c'
                  -- Равенство, а не вхождение подстроки: односторонняя редакция тоже содержит
                  -- `estimate_revision IS NOT NULL`, и искать её было бы всё равно что не искать.
                  AND pg_get_constraintdef(c.oid) LIKE '%) = (estimate_revision IS NOT NULL)%'
                  AND pg_get_constraintdef(c.oid) LIKE '%page_no IS NULL%')
      UNION ALL
      SELECT 'уникального индекса страницы основания нет — адрес листа неоднозначен'
       WHERE NOT EXISTS (
               SELECT 1 FROM pg_index x
                WHERE x.indexrelid = to_regclass('public.service_request_files_basis_page_unique')
                  AND x.indisunique
                  AND x.indpred IS NOT NULL)
      UNION ALL
      SELECT 'уникальный индекс страницы различает пустоты — два беспорядковых основания пройдут оба'
       WHERE EXISTS (
               SELECT 1 FROM pg_index x
                WHERE x.indexrelid = to_regclass('public.service_request_files_basis_page_unique')
                  AND NOT x.indnullsnotdistinct)
    ) AS checks;
  IF trouble IS NOT NULL THEN
    RAISE EXCEPTION 'Миграция 0309: %', trouble;
  END IF;
  RAISE NOTICE 'Миграция 0309: замки связи «файл ↔ ревизия» двусторонние, адрес страницы однозначен.';
END $$;
