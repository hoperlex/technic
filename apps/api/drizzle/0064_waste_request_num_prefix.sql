-- Номер заявки на мусор с префиксом: «М-128» вместо «128-ВМ».
--
-- Номер собирался как «число + буква типа»: буква отвечала на «что это за заявка» раньше, чем
-- открывали карточку. Рядом появились заявки на технику с номером «ТС-128» — префикс впереди, и
-- «сто двадцать восьмая» в разговоре перестала быть однозначной: счётчики у мусора и у техники
-- свои сквозные, одно и то же число называет две разные заявки. Поэтому префикс получает и
-- мусор — «М-». Буква типа из номера уходит: тип заявки стоит отдельной колонкой и в фильтрах,
-- в номере он её дублировал.
--
-- Счётчик не сбрасывается: `num` остаётся сквозной identity-колонкой, «М-» — только отображение.
-- Перенумеровывать заведённые заявки не с чего: их номера уже в талонах, актах и переписке.
--
-- Заведённые заявки и показываются прежним форматом — по той же причине. Формат хранится флагом
-- на строке, а не выводится порогом номера: порог пришлось бы зашить константой, а он свой в
-- каждой базе (dev, stage, прод), и промах порога переименовал бы чужие заявки.

ALTER TABLE waste_requests ADD COLUMN legacy_num_format boolean NOT NULL DEFAULT false;

-- Все строки, существующие на момент миграции, — «до префикса». Новые получат default false.
UPDATE waste_requests SET legacy_num_format = true;
