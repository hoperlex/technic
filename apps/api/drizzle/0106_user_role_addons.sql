-- Надстройка роли (ADR 0086): третья ось субъекта доступа.
--
-- Права в портале выдаются паре «роль + тип контрагента» (ADR 0038). «Оператор (оргтехника)» в эту
-- пару не помещается: человек остаётся штабом своего объекта или сотрудником отдела и продолжает
-- вести свои заявки, а сверх этого получает набор действий в одном модуле. Роль у учётки одна, и
-- вторая означала бы вторую учётку и второй вход; право у роли `shtab` сделало бы оператором
-- каждый штаб компании.
--
-- Таблица, а не колонка-флаг: следующая надстройка иначе потребует миграции и `if` в каждом месте,
-- где спрашивают доступ. Совместимость надстройки с базовой ролью держит сервер
-- (`ROLE_ADDON_BASE_ROLES` в контрактах), а не CHECK: условие читало бы колонку соседней таблицы —
-- тот же случай, из-за которого миграция 0063 сняла `users_rukstroy_object_check`.

CREATE TYPE role_addon AS ENUM ('office_equipment_operator');

CREATE TABLE user_role_addons (
  user_id uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  addon role_addon NOT NULL,
  -- Кто и когда выдал: надстройка расширяет доступ, и в журнале учёток это должно читаться так же
  -- ясно, как смена роли.
  granted_by uuid REFERENCES users (id) ON DELETE SET NULL,
  granted_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, addon)
);
