-- Журнал переходов режима: условие «активация опирается на поколение и аттестацию» смотрело на
-- состояние после перехода, а не на сам переход (план assignment-periods, §6, О4).
--
-- ЧТО ЛОМАЛОСЬ. Порядок cutover — три шага: заморозить запись, переключить чтение, разморозить.
-- К третьему шагу чтение уже `history`, поколения и аттестации у разморозки нет и быть не может
-- (они относятся только к включению истории — сервис отвергает их у перехода записи), и строка
-- журнала не проходила `CHECK`. То есть **после переключения запись невозможно было разморозить
-- ни одной командой**: портал остаётся замороженным, а снять заморозку нечем.
--
-- Найдено репетицией cutover на копии базы 25.08.2026 — тем самым прогоном, ради которого
-- репетиция и делается: до неё все три шага проверялись порознь и каждый проходил.
--
-- КАК ПРАВИЛЬНО. Доказательств требует **переход** `legacy → history`, а не всякая запись, у
-- которой чтение уже включено. Условие переписано парой границ: `from_read_mode <> to_read_mode
-- AND to_read_mode = 'history'`. Переход, не меняющий чтения (обе заморозки и разморозка), под
-- условие не подпадает вовсе; возврат `history → legacy` — как и прежде, доказательств не требует.
--
-- Данные не трогаются: строки, записанные до этой миграции, условию удовлетворяют — новое условие
-- строго слабее прежнего.

ALTER TABLE assignment_periods_mode_transitions
  DROP CONSTRAINT assignment_periods_mode_transitions_history_check;

ALTER TABLE assignment_periods_mode_transitions
  ADD CONSTRAINT assignment_periods_mode_transitions_history_check
    CHECK (
      from_read_mode = to_read_mode
      OR to_read_mode <> 'history'
      OR (run_id IS NOT NULL AND attestation_id IS NOT NULL)
    );

COMMENT ON CONSTRAINT assignment_periods_mode_transitions_history_check
  ON assignment_periods_mode_transitions IS
  'Включение истории (legacy → history) обязано опираться на поколение сверки и аттестацию деплоя. '
  'Переход, не меняющий чтения (заморозка и разморозка записи), доказательств не требует — иначе '
  'после cutover запись нельзя было бы разморозить вовсе.';
