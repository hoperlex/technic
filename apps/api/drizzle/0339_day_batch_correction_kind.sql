-- Вид операции «пачка дней»: выписка 4-П на весь период заказа техники на объект.
--
-- Решение — docs/adr/0207-vehicle-request-day-batch.md, план —
-- docs/vehicle-request-day-batch-plan.md (Р9).
--
-- ЗАЧЕМ СВОЙ ВИД, А НЕ `issue`. `issue` отвечает на «этот номер выписан задним числом по вот этому
-- рейсу»: цель у него одна и адресуется рейсом. У пачки цель другая — заказ и его срок, а листов
-- под одной причиной рождается до пятидесяти, каждый на своём рейсе. Сложи их в `issue` — и
-- журнал коррекций перестанет отвечать на вопрос «что за одно решение задним числом сделали»:
-- пятьдесят строк вместо одной, и связать их между собой будет нечем. Тем же доводом заведён
-- `weekly` (миграция 0157): одно решение — одна строка операции.
--
-- Снимка авторизации (`authorization_scope`) у нового вида нет и не требуется:
-- `waybill_corrections_authorization_scope_check` спрашивает его только у `crew` и
-- `assignment_tail`, заведённых историей назначения (миграция 0166). Пачка авторизуется тем же
-- путём, что и обычная выписка задним числом, — правом и глубиной на каждый день.
--
-- ОБРАТИМОСТЬ: расширение CHECK обратносовместимо — прежний код нового значения не пишет, и
-- откат кода отката схемы не требует. Протокол выката необратимых миграций
-- (docs/schema-cutover-protocol.md) здесь не нужен: обычный deploy-auto, teardown не требуется.
-- Полный откат — вернуть прежний список значений, предварительно убедившись, что строк с
-- `kind = 'day_batch'` в таблице нет.

ALTER TABLE waybill_corrections DROP CONSTRAINT waybill_corrections_kind_check;
ALTER TABLE waybill_corrections ADD CONSTRAINT waybill_corrections_kind_check
  CHECK (kind IN ('route', 'transfer', 'esm2', 'cancel', 'issue',
                  'request_date', 'weekly', 'crew', 'assignment_tail', 'day_batch'));
