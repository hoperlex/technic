-- Материализованное состояние разбора талонов вывоза (план `docs/waste-ticket-auto-confirm-plan.md`,
-- редакция 6, решения Р19–Р21; выпуск A, этап Э2). Здесь только схема: пересчёт, граф
-- инвалидирования, предикат реестра и прогрев едут той же волной отдельными файлами.
--
-- ОТКУДА НОМЕР. Проверено `ls apps/api/drizzle | tail` непосредственно перед созданием файла
-- (02.09.2026): в дереве уже лежат 0241/0242 (почта подрядчику, соседняя незакоммиченная сессия) и
-- 0243/0244, занятые планом `docs/auto-part-receipts-plan.md`. Первый свободный — 0245. Номера
-- миграций и ADR идут параллельными потоками, поэтому сверка сделана заново, а не взята из шапки
-- плана: пока писались редакции, соседние работы заняли четыре номера.
--
-- ТАБЛИЦА ЗАВОДИТСЯ ПУСТОЙ, И ЭТО РЕШЕНИЕ, А НЕ ЛЕНЬ (Р19). Посчитать числа значка на SQL значило
-- бы написать правило сверки второй раз — со всеми допусками, отклонёнными талонами, снятыми
-- принятиями и их отпечатками. Второе определение расходится с первым молча и именно в ту сторону,
-- где список успокаивает, а карточка показывает расхождение. Наполняет таблицу прогрев
-- (`pnpm --filter @technic/api recompute:ticket-review`), запускаемый ПОСЛЕ перезапуска API: до
-- перезапуска он считал бы правилами прежней версии. Пока прогрев идёт, реестр показывает лишнее,
-- а не прячет нужное — пустая строка читается предикатом как «не знаем» (Р21).
--
-- ОТКАТ ВЫПУСКА БЕЗОПАСЕН: старый код таблицу не читает, новый переживает промах кэша.

CREATE TABLE waste_ticket_review_state (
  -- Одна строка на заявку, своего `id` нет: это свойство заявки, а не запись о ней. `CASCADE` —
  -- состояние разбора удалённой заявки не отвечает ни на один вопрос.
  request_id uuid PRIMARY KEY REFERENCES waste_requests (id) ON DELETE CASCADE,

  -- Шесть чисел значка — ровно те, что возвращает `wasteTicketChecks`, и в том же смысле.
  -- Разъехаться им не даёт единственный писатель: пересчёт зовёт ту же сверку.
  errors integer NOT NULL DEFAULT 0,
  warnings integer NOT NULL DEFAULT 0,
  pending_confirmation integer NOT NULL DEFAULT 0,
  failures integer NOT NULL DEFAULT 0,
  unreviewed_paper integer NOT NULL DEFAULT 0,
  confirmable integer NOT NULL DEFAULT 0,

  -- Отпечаток готового к подтверждению набора: его присылает обратно кнопка списка, и сервер
  -- сверяет под замком заявки (Р23). Числа для этого мало — между отрисовкой строки и нажатием
  -- один талон может исчезнуть, а другой появиться, и счёт совпадёт при другом наборе.
  confirmable_fingerprint text NOT NULL DEFAULT '',

  -- Версия правил сверки, версия самой этой формы и действующие допуски — одной строкой. Не тремя
  -- колонками: обесценивать строку приходится по любой из причин сразу, и предикату реестра нужно
  -- одно условие сравнения вместо трёх (Р21).
  input_fingerprint text NOT NULL DEFAULT '',

  -- «Числа могли устареть» — ставят те, кому пересчитать нечем: воркер распознавания, мутация
  -- соседней заявки, правка адреса объекта. Умолчание `true`, потому что строку обычно и заводит
  -- пометка: посчитанной она становится позже и другим кодом.
  stale boolean NOT NULL DEFAULT true,

  -- Счётчик записей строки. Пишут её только условно — `WHERE revision = $прочитанная` (Р19):
  -- безусловный upsert стирал бы чужую пометку «устарело», оставляя `stale = false` с числами,
  -- посчитанными по прежнему состоянию соседа.
  revision bigint NOT NULL DEFAULT 0,

  -- `NULL` — строку ещё не считали: наблюдаемость прогрева и признак «здесь одна пометка».
  computed_at timestamptz,

  -- Одним ограничением на все шесть, а не шестью именными: отрицательное число в любом из них
  -- означает одну и ту же ошибку — сверка вернула бессмыслицу, — и разбираться по имени
  -- ограничения всё равно пойдут в неё.
  CONSTRAINT waste_ticket_review_state_counts_check CHECK (
    errors >= 0 AND warnings >= 0 AND pending_confirmation >= 0
    AND failures >= 0 AND unreviewed_paper >= 0 AND confirmable >= 0
  )
);

-- Индекс инвалидации соседей (Р20). Замечание о повторе живёт в заявке Б, а вызывает его талон
-- заявки А — значит мутация А обязана пометить Б устаревшей, а для этого найти её по `number_key`
-- среди НЕОТКЛОНЁННЫХ талонов. Два имеющихся индекса по этой колонке для такого поиска не годятся:
-- `waste_tickets_operator_number_unique` и `waste_tickets_number_unique` частичные по
-- `status = 'confirmed'` и по неснятому клапану, то есть покрывают ровно ту бумагу, которую человек
-- уже признал, — а искать надо и ту, которую он ещё не смотрел. Без индекса каждая правка номера
-- читала бы `waste_tickets` целиком.
--
-- Условие `<> ''` — потому что пустой ключ есть у каждого талона без прочитанного номера, и в
-- индексе такие строки заняли бы место, ничего не отвечая: по пустому ключу соседей не ищут.
--
-- Без `CONCURRENTLY`: раннер катит файл в транзакции (`migration-journal.ts`), а таблица здесь
-- размером в тысячи строк — блокировка записи на время построения измеряется долями секунды.
CREATE INDEX waste_tickets_number_key_idx ON waste_tickets (number_key) WHERE number_key <> '';

-- Индекс по `waste_ticket_pages(page_sha256)` для поиска соседа по скану уже существует
-- (`waste_ticket_pages_sha256_idx`, миграция 0206), второй такой же здесь не заводится. Кандидат
-- `waste_tickets(page_id)` — соединение талона со страницей — берётся по `EXPLAIN` на живом плане
-- запроса инвалидации, а не заранее: имеющийся `waste_tickets_page_seq_unique` частичный
-- (`page_id IS NOT NULL AND origin = 'ocr'`), и покроет ли он запрос, решает планировщик (Р20).
