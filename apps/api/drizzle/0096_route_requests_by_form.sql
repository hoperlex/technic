-- Заявок в маршруте столько, сколько строк задания в бланке (ADR 0068).
--
-- До сих пор состав маршрута упирался в четыре талона заказчика 4-П — на них ссылался и CHECK
-- позиции, и CHECK талона у выданного листа. Но задание водителю бланками этим не исчерпывается:
--
--   · в 4-П под таблицей на четыре строки стоит блок «Дополнительное задание водителю», и три его
--     нижние строки — пустые полосы во всю ширину блока: рейсы 5–7 печатаются там одной строкой
--     «откуда — куда, груз, контакты», без талона (талонов в бланке ровно четыре);
--   · в форме № 3 (легковой) таблица оборота разграфлена и пронумерована на десять строк — там
--     заявки 5–10 встают такими же графами, как первые четыре.
--
-- Отсюда и потолок: десять — наибольшая ёмкость по бланкам. Сколько заявок влезет в конкретный
-- маршрут, решает его бланк (`ROUTE_REQUEST_CAPACITY` в контрактах): база держит общий предел, а
-- отказ «в листе N строк задания» выдаёт сервер, зная бланк рейса. Разводить это на два CHECK
-- нечем — бланк лежит не в этих таблицах, а в типе машины рейса, и меняется справочником.
--
-- Обе проверки только расширяются, и это делает миграцию безопасной в обе стороны. Штатный деплой
-- накатывает миграции ДО перезапуска API: старый код в этот момент пишет позиции 1–4 и в
-- расширенное условие проходит. Откат кода (`deploy-auto --previous`) схему не трогает — но
-- маршрут, уже собранный на семь или десять заявок, старый код напечатает четырьмя строками и
-- покажет в интерфейсе «10 из 4»; переставить состав в нём тоже не выйдет, схема запроса режет
-- список на четырёх. Данные при этом целы: чинится всё возвратом кода вперёд.

-- 1. Состав маршрута.
ALTER TABLE vehicle_route_requests DROP CONSTRAINT vehicle_route_requests_position_check;
ALTER TABLE vehicle_route_requests
  ADD CONSTRAINT vehicle_route_requests_position_check CHECK (position BETWEEN 1 AND 10);

-- 2. Задание выданного листа. Имя колонки осталось от четырёх талонов, а значит она теперь место
--    в задании: у 4-П 1–4 — талон заказчика, 5–7 — строка доп. задания; у формы № 3 — строка её
--    таблицы. Уникальность внутри листа (`waybill_requests_slot_unique`) остаётся прежней: две
--    заявки в одну строку не встают.
ALTER TABLE waybill_requests DROP CONSTRAINT waybill_requests_slot_check;
ALTER TABLE waybill_requests
  ADD CONSTRAINT waybill_requests_slot_check CHECK (slot BETWEEN 1 AND 10);
