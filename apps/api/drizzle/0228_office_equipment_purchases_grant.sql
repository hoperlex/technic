-- Право «вести плановые закупки расходников» в наборе «Оргтехника: ведение» (план
-- `docs/office-equipment-consumables-and-purchase-plan.md`, Р12; ADR 0146, этап Э6).
--
-- ЗАЧЕМ. Плановая закупка — новый документ модуля «Орг.техника»: список позиций, которые пора
-- заказать у снабжения, со своим коридором из четырёх состояний. Заводит, правит, проводит,
-- закрывает и отменяет её одно право — `officeEquipmentPurchases.manage`, и достаётся оно тому, кто
-- ведёт модуль. Это решение заказчика, а не следствие состава: «Оргтехника: номенклатура» ведёт
-- перечень картриджей и остаток на полке, а закупка — бумага снабжению, и подписывает её тот, кто
-- отвечает за модуль целиком.
--
-- ПОЧЕМУ СВОЁ ПРАВО, А НЕ `serviceRequests.*`. У закупки своя таблица и свои ручки, а первая
-- редакция плана предлагала право внутри модуля заявок — и упиралась в статический страж
-- `POST /service-requests`: субъект с парой «закупка + чтение», но без `serviceRequests.create`, не
-- завёл бы ничего. Своей ручке чужое право заведения не нужно вовсе.
--
-- ПОЧЕМУ ПРАВО ЕДЕТ РАНЬШЕ РУЧЕК. Маршрутов закупки в этом выкате ещё нет — их везёт следующая
-- волна (этапы Э7–Э10 плана). Разнести можно ровно потому, что право без ручки не открывает ничего:
-- держатель набора не получает этой миграцией ни одной новой двери. Обратный порядок — ручки раньше
-- права — был бы запрещён, а этот безопасен и держит состав набора в контрактах и в базе одной
-- волной, а не двумя.
--
-- ЧЕГО ЗДЕСЬ НЕТ. Ни одной строки `user_grants`: миграция правит каталог — состав набора и его
-- описание, — а кому набор достанется, решает администратор портала поимённо, с автором, временем и
-- записью в реестре выдач (ADR 0106). Держатели набора у этой правки уже есть, и права им
-- прибавляются ровно на одно объявленное здесь — это и есть весь эффект наката на живые учётки.
--
-- КОД НАБОРА НЕ МЕНЯЕТСЯ НИ ПРИ КАКИХ УСЛОВИЯХ. По коду набор находят миграции каталога, журнал
-- действий, реестр выдач и таблица сквозной области (`GRANT_MODULE_WIDE_SCOPE`):
-- `UPDATE grants SET code = ...` не «переименовывает набор», а отвязывает его от кода. Правятся
-- название, описание и состав — здесь описание и состав.
--
-- ГДЕ ЖИВЁТ ОБЪЯВЛЕННЫЙ СОСТАВ. У этого набора — в `ROLE_ADDON_PERMISSIONS`
-- (`packages/contracts/src/permissions.ts`): надстройка ADR 0086 остаётся живым источником доступа
-- до шага 1e реформы, и набор в базе — её отражение. Правка надстройки уехала той же волной, что
-- эта миграция, и это обязательное условие: иначе один и тот же человек получил бы разные права в
-- зависимости от того, пришёл к нему доступ надстройкой или набором. Обе стороны сверяет страж
-- `apps/api/test/grants-catalog.db.test.ts`.
--
-- СОВМЕСТИМЫЕ РОЛИ НЕ ТРОГАЮТСЯ. У набора они те же — штаб, площадка, отдел
-- (`ROLE_ADDON_BASE_ROLES`), и требование нового права (`officeEquipment.read`,
-- `PERMISSION_REQUIRES`) выполняется у каждой из трёх: чтение справочника оргтехники есть у всех
-- трёх ролей матрицей. Барьер выдачи поэтому не начнёт отклонять то, что вчера выдавалось.
--
-- ОБРАТИМОСТЬ. Трогаются две таблицы каталога, схема не меняется; протокол выката необратимых
-- миграций (`docs/schema-cutover-protocol.md`) к ней не применяется. Откат — `DELETE` строки состава
-- и прежний текст описания.

-- ── 1. Описание набора ──
--
-- Описание перечисляет, что набор умеет, и потому правится вместе с составом: набор, открывающий
-- новый документ и молчащий о нём, заставляет администратора угадывать по списку прав. Текст
-- переписывается целиком, а не дописывается конкатенацией: `description || '…'` на повторном накате
-- пришил бы фразу второй раз.

UPDATE grants
   SET description = 'Ведёт модуль «Орг.техника» целиком: справочник техники, распределение заявок '
                     'по исполнителям, согласование сметы, приёмку работы, срочность и заморозку. '
                     'Это единственный набор, которым заявку принимают и отменяют из любого '
                     'статуса; ходов исполнителя в нём нет — их открывает назначение. Им же ведут '
                     'плановые закупки расходников: заводят документ для снабжения, правят '
                     'черновик, проводят, закрывают и отменяют. Перечень картриджей и остаток на '
                     'складе правит другой набор — «Оргтехника: номенклатура».',
       updated_at = now()
 WHERE code = 'office_equipment_operator';

-- ── 2. Состав: одно новое право ──
--
-- Право хранится текстом — справочника прав в базе нет намеренно (`grant_permissions`, миграция
-- 0145): словарь `PERMISSIONS` закрыт и живёт в контрактах. `ON CONFLICT DO NOTHING` делает шаг
-- идемпотентным, а не «на всякий случай»: повторный накат на базу, восстановленную из копии, —
-- обычное дело.

INSERT INTO grant_permissions (grant_id, permission)
SELECT g.id, s.permission
FROM grants g
JOIN (VALUES
  ('office_equipment_operator', 'officeEquipmentPurchases.manage')
) AS s (code, permission) ON s.code = g.code
ON CONFLICT (grant_id, permission) DO NOTHING;

-- ── 3. Караул: состав в базе равен объявленному ──
--
-- Страж-тест сверяет то же самое, но живёт он в репозитории, а этот блок — в накате: оператор
-- выката увидит расхождение сразу, а не через прогон тестов. Проверяется ровно то, что миграция
-- обещала: набор существует и системный, прав в нём семь (шесть после миграции 0183 плюс закупка), и
-- закупка среди них именно та, что объявлена в контрактах. Строк `user_grants` этот блок не
-- считает — в отличие от миграции 0211: там набор заводился новым и держателей у него быть не
-- могло, здесь набор живой, и его держатели — обычное дело.
DO $$
DECLARE trouble text;
BEGIN
  SELECT string_agg(msg, '; ')
    INTO trouble
    FROM (
      SELECT format('набора нет или он не системный (найдено строк: %s)', count(*)) AS msg
        FROM grants
       WHERE code = 'office_equipment_operator' AND is_system AND deleted_at IS NULL
      HAVING count(*) <> 1
      UNION ALL
      SELECT format('прав в наборе %s вместо семи, закупка среди них: %s',
                    count(*),
                    CASE WHEN count(*) FILTER (
                           WHERE gp.permission = 'officeEquipmentPurchases.manage') = 1
                         THEN 'да' ELSE 'нет' END)
        FROM grant_permissions gp
        JOIN grants g ON g.id = gp.grant_id
       WHERE g.code = 'office_equipment_operator'
      HAVING count(*) <> 7
          OR count(*) FILTER (WHERE gp.permission = 'officeEquipmentPurchases.manage') <> 1
    ) AS bad;
  IF trouble IS NOT NULL THEN
    RAISE EXCEPTION 'Набор «Оргтехника: ведение» собран не так, как объявлен — %', trouble;
  END IF;
END $$;
