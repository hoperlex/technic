-- Шаг prepare этапа 8: замещающие наборы выдаются держателям трёх площадочных ролей заранее, за
-- релиз до перевода (план реструктуризации модели доступа, §13.2 «перевод ролей — тоже три
-- релиза», §15 этап 8; ADR 0113).
--
-- ЧТО ЗДЕСЬ ПРОИСХОДИТ. Каждой учётке с ролью `shtab`, `rukstroy` или `commandant` заводится снимок
-- (`user_role_migration`, миграция 0154) и выдаётся ровно то, чем её роль отличается от `site`:
--
--   shtab      → «Заказ техники»
--   rukstroy   → «Заказ техники» + «Виза объекта»
--   commandant → ничего (это и есть `site` без полномочий)
--
-- ДОСТУП НЕ МЕНЯЕТСЯ НИ У КОГО, И ЭТО СВОЙСТВО ФАЙЛА, А НЕ ПОЖЕЛАНИЕ. Права по набору считаются
-- через соединение с `grant_roles` (`grantPermissionsExpr`, `services/user-scopes.ts`), а в
-- `grant_roles` у обоих наборов стоит одна роль — `site`. У держателя, который сегодня `shtab`,
-- гейт закрыт: назначение существует, прав не даёт, и дать не может — те же права у него и так есть
-- от роли. Открывается гейт ровно в тот момент, когда роль становится `site`, то есть в миграции
-- перевода. Назначение поэтому не «лишнее право», а взведённая заранее замена: `UPDATE` роли
-- перестаёт быть моментом, в который доступ меняется, — в этом и есть весь смысл шага prepare.
--
-- ПОЧЕМУ СТАРЫЕ РОЛИ НЕ ДОПИСАНЫ В `grant_roles`. Соблазн велик — тогда назначение действовало бы
-- сразу и не выглядело бы в реестре «роль не в списке». Отвергнуто, и по двум причинам сразу.
-- Первая: `grant_roles` отвечает на «кому набор можно назначить ВПРЕДЬ», а впредь эти роли не
-- назначаются вовсе — этим же релизом вход в них закрыт (`retiringRoleIssue` в контрактах).
-- Вторая, и она тяжелее: строка `('site_approval', 'rukstroy')` открыла бы администратору выдачу
-- визы объекта рядовому штабу — доступ, которого сегодня нет ни у кого и который реформа никому не
-- обещала. Релиз, объявляющий «доступ не изменился ни у кого», не должен расширять множество того,
-- что вообще можно выдать.
--
-- ПОЧЕМУ МИГРАЦИЕЙ, А НЕ СКРИПТОМ МЕЖДУ РЕЛИЗАМИ. Порядок 1a/1b (двойная запись → перенос) был
-- продиктован тем, что миграция накатывается ДО перезапуска приложения, а старый код продолжал бы
-- писать мимо новой таблицы. Здесь этой беды нет: файл ничего не переносит и ни от какой записи не
-- отстаёт — он добавляет строки, которые до перевода никем не читаются. Единственное окно —
-- учётка со старой ролью, заведённая между накатом и перезапуском: её снимок никто не создаст.
-- Закрывает окно шаг выката `pnpm --filter @technic/api check:role-migration`, который считает
-- обе стороны поимённо и возвращает ненулевой код, — тот же приём, что у сверки аудитории
-- рассылок (`check:mailing-audience`, ADR 0111).
--
-- ОБРАТИМОСТЬ. Откат — удаление посеянного: `DELETE FROM user_grants WHERE origin = 'migration'`
-- по снимкам этапа, затем сами снимки (порядок задаёт внешний ключ 0154). Прав это ни у кого не
-- отнимает: до перевода назначения не действуют. Роли, объекты, отделы и надстройки файл не
-- трогает вовсе.

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 1. Площадка становится базовой ролью надстроек оргтехники.
--
-- Граница, найденная на этапе 4б: оба перенесённых из надстроек набора совместимы с ролями
-- `shtab` и `department` (`ROLE_ADDON_BASE_ROLES`, миграция 0145), а после перевода `shtab` в этой
-- паре не останется никого. Не допиши мы `site` заранее — перевод отобрал бы у оператора
-- оргтехники его надстройку МОЛЧА: гейт `grant_roles` закрылся бы вместе со сменой роли, а
-- `canAttachAddon` перестал бы отвечать «да» на ту же пару в матрице.
--
-- Строки идут этим шагом, а не переводом, по той же причине, по которой роль завели на 4б: править
-- системный набор миграцией перевода — ровно то, чего план §10 требует избегать. Здесь же правка
-- проверяема заранее: страж каталога (`grants-catalog.db.test.ts`) сверяет `grant_roles` с
-- `ROLE_ADDON_BASE_ROLES` по каждому набору, и обе стороны меняются одним релизом.
--
-- Расширением доступа строки не являются: роль `site` не назначена ни одной учётке, а надстройка
-- сама по себе прав не даёт — её выдают поимённо.
INSERT INTO grant_roles (grant_id, role)
SELECT g.id, 'site'::role
FROM grants g
WHERE g.code IN ('office_equipment_operator', 'office_equipment_it_approver')
ON CONFLICT (grant_id, role) DO NOTHING;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 1b. То же для наборов, собранных администратором.
--
-- Беда, которую план называет отдельно (§13.2): конструктор включён с этапа 3, переводы идут с
-- восьмого, и за пять этапов администратор успевает собрать наборы, у которых в `grant_roles` стоит
-- `shtab`, а `site` — нет. Перевод такой учётки погасил бы её собранный набор молча: гейт
-- совместимости закрывается вместе со сменой роли, а сообщить об этом некому — миграция роли о
-- наборах не знает.
--
-- План поручает переписывание `old → new` миграции перевода. Здесь оно сделано **добавлением**, и
-- на релиз раньше: `site` дописывается рядом с прежней ролью, а не вместо неё. Причина в том же
-- гейте — переписав роль сейчас, мы отобрали бы права у держателей на весь релиз до перевода, пока
-- роль у них ещё старая. Аддитивная половина безопасна в обе стороны: до перевода набор действует
-- по старой роли, после — по новой, а лишнюю строку снимает cleanup вместе с самой ролью.
--
-- Системные наборы сюда не попадают: у двух оргтехнических строка уже добавлена выше поимённо, у
-- ролевых и административных упраздняемых ролей в списке нет вовсе, а править их состав вслепую
-- запросом по маске — ровно тот способ, которым системный набор однажды и разъедется с кодом.
INSERT INTO grant_roles (grant_id, role)
SELECT DISTINCT gr.grant_id, 'site'::role
FROM grant_roles gr
JOIN grants g ON g.id = gr.grant_id
WHERE gr.role IN ('shtab', 'rukstroy', 'commandant')
  AND NOT g.is_system
  AND g.deleted_at IS NULL
ON CONFLICT (grant_id, role) DO NOTHING;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 2. Снимок: кем человек был и кем станет.
--
-- Ни `is_active`, ни `deleted_at` в условии нет, и это требование §13.2: перевод захватывает
-- неактивные и архивные учётки тоже. Деактивированный комендант вернётся через полгода — и роли,
-- под которой его выключили, к тому времени в `ROLES` уже не будет.
--
-- `role_after` заполняется сразу: переводом управляет снимок, а не список ролей внутри будущей
-- миграции, и условный `UPDATE ... WHERE u.role = m.role_before` вместе с условным откатом
-- `WHERE u.role = m.role_after` читаются из одной строки.
INSERT INTO user_role_migration (user_id, stage, role_before, role_after)
SELECT u.id, 8, u.role, 'site'::role
FROM users u
WHERE u.role IN ('shtab', 'rukstroy', 'commandant')
ON CONFLICT (user_id, stage) DO NOTHING;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 3. Взведённые назначения.
--
-- Соответствие «прежняя роль → наборы» объявлено в контрактах (`ROLE_MIGRATIONS`,
-- `packages/contracts/src/role-migration.ts`) и переписано сюда строками — миграция не умеет
-- спрашивать TypeScript. Что копии не разъедутся, следит `role-migration-prepare.db.test.ts`.
--
-- `granted_by` остаётся NULL: выдачи не было — не было и того, кто её сделал. Происхождение
-- называет не человека, а перевод (`origin = 'migration'`), и реестр выдач показывает это отдельной
-- пометкой. `granted_at` — момент наката: это правда о том, когда назначение появилось, и подменять
-- её задним числом незачем.
--
-- `ON CONFLICT (user_id, grant_id) DO NOTHING` делает повторный накат безвредным и заодно бережёт
-- назначение, которое администратор мог выдать своей рукой раньше: его `origin` останется `manual`,
-- и откат перевода его не тронет. Права от этого не пострадают — набор тот же самый.
INSERT INTO user_grants (user_id, grant_id, granted_by, origin, migration_id)
SELECT m.user_id, g.id, NULL, 'migration', m.id
FROM user_role_migration m
JOIN (VALUES
  ('shtab'   , 'vehicle_ordering'),
  ('rukstroy', 'vehicle_ordering'),
  ('rukstroy', 'site_approval')
) AS s (role_before, code) ON s.role_before = m.role_before::text
JOIN grants g ON g.code = s.code AND g.deleted_at IS NULL
WHERE m.stage = 8
ON CONFLICT (user_id, grant_id) DO NOTHING;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- Чего файл НЕ делает — и это границы шага, а не забытые строки.
--
-- НЕ ПЕРЕВОДИТ УЧЁТКИ. `UPDATE users SET role = 'site'` — следующий релиз, и до него обе роли
-- рабочие. Между выдачей наборов и переводом обязан пройти целый релиз: миграция накатывается до
-- перезапуска приложения, и «выдали и тут же перевели» означало бы, что часть минут доступ
-- считает версия, для которой снимка ещё не существовало.
--
-- НЕ ТРОГАЕТ `auth_version`. Права ни у кого не изменились: гейт совместимости закрыт, а токен и
-- так не хранит ни роли, ни наборов — принципал читает их из базы на каждом запросе. Поднять
-- версию значило бы разлогинить компанию ради строк, которые ничего не делают.
--
-- НЕ СНИМАЕТ СТАРЫЕ РОЛИ ИЗ `grant_roles`. Аддитивная половина сделана здесь (пункт 1b),
-- вычитающая — дело cleanup'а, где роль уходит из `ROLES` целиком. Между ними в списке
-- совместимых ролей набора стоят обе, и это ровно то состояние, в котором перевод не отнимает
-- ничего.
