-- Кабинет водителя: значения перечислений.
-- План — `docs/driver-portal-plan.md`, §2 (Р1) и §6 (Р28); ADR 0102.
--
-- Отдельным файлом и без использования значений в нём самом: раннер применяет миграцию целиком в
-- одной транзакции (`apps/api/src/db/migration-journal.ts`), а PostgreSQL не разрешает
-- пользоваться новым значением enum до её фиксации. Тот же приём — в миграциях 0054, 0065, 0103,
-- 0114 и 0117.
--
-- ОБРАТИМОСТЬ. Данные миграция не переписывает, но обратимой от этого не становится: значение
-- перечисления в PostgreSQL штатно не удаляется, а после того, как первая учётка получит роль
-- `driver`, небезопасен и откат кода — прежняя сборка такой роли не знает и упрётся в неё при
-- разборе принципала. Поэтому файл катится отдельным релизом РАНЬШЕ кода: пока роль никому не
-- назначена, схема ведёт себя ровно как до него.

-- Роль водителя. Прав основного портала у неё нет вовсе — она открывает кабинет `/driver` и
-- ничего больше; область видимости у роли своя, четвёртая: «строка про самого работника».
ALTER TYPE role ADD VALUE IF NOT EXISTS 'driver';

-- Пожелание при регистрации. Порядок значений здесь ни на что не влияет: пожелания показываются
-- по своему словарю подписей, а не по порядку типа. Отдельной кнопки «Я водитель» на экране входа
-- нет — человек выбирает себя в общем списке, и это единственное пожелание, чья роль совпадает
-- с ним буквально.
ALTER TYPE registration_role_request ADD VALUE IF NOT EXISTS 'driver';
