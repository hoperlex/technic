-- для какого аппарата», 15 строк.
--
-- ИТОГ: позиций — 15, привязок к моделям — 16, остаток у всех нулевой. По этим числам сид и
-- принимается.
--
-- ПОЧЕМУ ОСТАТОК НУЛЕВОЙ, А НЕ «СКОЛЬКО ЛЕЖИТ НА ПОЛКЕ». Остаток по решению Р7 меняется только
-- событием, у которого есть автор и причина; у строки таблицы нет ни того, ни другого, а
-- отложенная проверка `office_equipment_consumable_stock_covered` отменила бы вставку с ненулевым
-- количеством и пустым журналом прямо на коммите. Первый пересчёт делает кладовщик окном
-- «Изменить остаток» — тогда у числа появляется автор, причина и строка журнала.
--
-- ПОЧЕМУ НАИМЕНОВАНИЯ ПЕРЕНЕСЕНЫ ДОСЛОВНО, вместе с хвостом «(шт)» и опечаткой «Ricon» в одной
-- строке (Д0000344697): справочник сверяют глазами со счётом и выгрузкой учётной системы, и
-- «причёсанное» наименование эту сверку ломает. Опечатка правится в учётной системе, а сюда
-- приезжает следом — порталу править её самому нечем и незачем.
--
-- ЧТО ОСТАЛОСЬ БЕЗ ПРИВЯЗКИ и почему это не потеря разбора (§7 плана):
--
--   * Samsung Xpress SL-M2020 (Д0000222226), Xerox Phaser 3250 (Д0000019705), Xerox Phaser 3052NI
--     (Д0000075288), Ricoh Aficio MP W2401 (Д0000023107) — этих аппаратов в портале нет вовсе.
--     Позиция заводится без совместимости: пустая привязка честнее выдуманной, а картриджи на
--     складе лежат независимо от того, заведён ли аппарат.
--   * «Тонер Ricoh P501H» (Д0000198613) — в таблице аппарат не назван. Спросить у ИТ-службы.
--
-- ЧТО ПОДТВЕРЖДЕНО ПРИ РАЗБОРЕ (вопросы задавались ИТ-службе, §7 плана):
--
--   * «МФУ HP LaserJet Pro MFP» без индекса — это HP LaserJet Pro MFP M428fdn: другого аппарата
--     этой серии в парке нет.
--   * «МФУ HP Neverstop Laser 1200W» — в справочнике модель называется «HP Neverstop Laser 1200W
--     MFP», хвост из названия карточки.
--   * «Тонер MP 301» привязан к Ricoh Aficio MP 301SP. В парке есть и MP 301SPF (2 карточки) —
--     подходит ли к нему тот же тонер, ИТ-служба не подтвердила, поэтому привязка одна.
--   * Цвет у двух тонер-картриджей записан строкой «комплект: чёрный, голубой, пурпурный, жёлтый»
--     (в таблице — «все цвета»); «розовый» назван пурпурным, как в спецификациях.
