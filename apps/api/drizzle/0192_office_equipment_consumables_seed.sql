    ('Д0000175417', 'Ricoh Aficio MP 301SP'),
    ('Д0000344697', 'Ricoh M C2000'),
    ('Д0000062210', 'Ricoh Aficio MP C2011SP')
  ) AS pair(code, model_name)
  JOIN office_equipment_consumables c
    ON office_equipment_consumable_code_key(c.code) = office_equipment_consumable_code_key(pair.code)
  JOIN office_equipment_models m
    ON office_equipment_model_key(m.name) = office_equipment_model_key(pair.model_name)
ON CONFLICT DO NOTHING;

-- Караул. Позиций обязано стать 15; привязок — 15 из перечня выше, если весь парк на месте.
-- Меньше привязок — значит модель переименовали или парк разобран иначе, и это надо увидеть на
-- накате, а не через месяц по жалобе «картридж не находится».
DO $$
DECLARE
  items bigint;
  links bigint;
BEGIN
  SELECT count(*) INTO items FROM office_equipment_consumables;
  SELECT count(*) INTO links FROM office_equipment_consumable_models;
  IF items < 15 THEN
    RAISE EXCEPTION 'Расходников после сида: % (ожидалось не меньше 15)', items;
  END IF;
  IF links < 15 THEN
    RAISE WARNING 'Привязок расходник→модель: % (ожидалось 15). Проверьте, все ли модели парка на месте', links;
  END IF;
END
$$;
