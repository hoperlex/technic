-- Совместимость. Модель ищется по паре «тип + ключ наименования» — так же, как её ищут маршрут и
-- обмен файлом; тип у всех один (`mfp`), потому что весь парк оргтехники сегодня из МФУ. Строка,
-- для которой модели нет, просто не даёт привязки: `JOIN` её отбрасывает, отдельного караула здесь
-- не нужно — четыре таких случая названы в шапке поимённо и ожидаемы.
INSERT INTO office_equipment_consumable_models (consumable_id, model_id)
