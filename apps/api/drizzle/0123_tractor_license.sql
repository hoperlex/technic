-- Удостоверение тракториста-машиниста (ADR 0008, ADR 0049, ADR 0095).
--
-- Схему миграция не трогает: двухуровневый справочник документов заведён миграцией 0019 ровно для
-- этого случая — «C» водительского и «C» тракториста разводятся принадлежностью категории к виду
-- документа, а составные внешние ключи person_credential_categories не дают положить в документ
-- категорию чужого вида. Не хватало только второй строки в credential_types и её категорий.
--
-- Должности отдельной сущностью не заводятся: они лежат в person_employments.job_title, который
-- заполняет кадровая выгрузка, а какой документ по должности требуется, решает сервер (ADR 0095).
-- Поэтому здесь нет ни ALTER TABLE, ни backfill: миграция наполняет справочник, и только.
--
-- Заведённых документов миграция не трогает. У машиниста, заведённого загрузкой после ADR 0049,
-- документа нет вовсе — переносить нечего; у заведённого раньше в ВУ может лежать что угодно, и
-- отличить настоящее ВУ машиниста автокрана от категорий тракторного удостоверения строкой SQL
-- нельзя: буквы те же. Такие карточки разбирают глазами и правят загрузкой файла.

-- 1. Вид документа. has_categories: удостоверение открывает самоходные машины по группам, и
--    портал обязан уметь их различать. expiry_required: выдаётся на десять лет.
INSERT INTO credential_types (code, name, description, has_categories, expiry_required, sort_order)
VALUES (
  'tractor_license',
  'Удостоверение тракториста-машиниста',
  'Удостоверение тракториста-машиниста (тракториста) — допуск к самоходным машинам (Правила допуска, ПП РФ № 796)',
  true, true, 20
)
ON CONFLICT (code) DO NOTHING;

-- 2. Категории. `name` — как напечатано в удостоверении («A I»), расшифровка живёт в `description`;
--    код в нижнем регистре без пробелов — этого требует CHECK формата (^[a-z][a-z0-9_]*$). Порядок
--    — как графы на бланке, а не по алфавиту: человек сверяет список с документом в руках.
--
--    Коды пересекаются с водительскими по букве и не обязаны от них отличаться: они уникальны
--    внутри вида документа (qualification_categories_code_unique), а не глобально. В этом и был
--    смысл двухуровневого справочника.
INSERT INTO qualification_categories (credential_type_id, code, name, description, sort_order)
SELECT ct.id, v.code, v.name, v.description, v.sort_order
FROM credential_types ct,
  (VALUES
    ('a1', 'A I',   'Внедорожные мототранспортные средства',                                             10),
    ('a2', 'A II',  'Внедорожные автотранспортные средства разрешённой максимальной массой до 3500 кг',  20),
    ('a3', 'A III', 'Внедорожные автотранспортные средства разрешённой максимальной массой свыше 3500 кг', 30),
    ('a4', 'A IV',  'Внедорожные автотранспортные средства для перевозки пассажиров, более восьми мест', 40),
    ('b',  'B',     'Гусеничные и колёсные машины с двигателем мощностью до 25,7 кВт',                   50),
    ('c',  'C',     'Колёсные машины с двигателем мощностью от 25,7 до 110,3 кВт',                       60),
    ('d',  'D',     'Колёсные машины с двигателем мощностью свыше 110,3 кВт',                            70),
    ('e',  'E',     'Гусеничные машины с двигателем мощностью свыше 25,7 кВт',                           80),
    ('f',  'F',     'Самоходные сельскохозяйственные машины',                                            90)
  ) AS v(code, name, description, sort_order)
WHERE ct.code = 'tractor_license'
ON CONFLICT (credential_type_id, code) DO NOTHING;
