-- Строки заявки на расходники и составной ключ журнала остатка (план
-- `docs/office-equipment-requests-rework-plan.md`, §4.3 и §5, миграция M12; решения Р1–Р11
-- набросков `docs/office-equipment-requests-rework-draft.md`). Выпуск 3 «Заявки на расходники»,
-- волна В11.
--
-- ЗАЧЕМ. Вид заявки `consumable` схема принимает с `0177`, но предмета у такой заявки нет: что
-- именно просят («два тонера Ricoh 201»), сколько из этого выдали и почему выдали не столько,
-- сколько просили, записать сегодня негде. Отсюда и главное следствие — постановку «при переводе в
-- „Решена“ выданные картриджи списываются со склада» исполнить нечем: списывать нечего и не с чего.
--
-- ЧТО ЗАВОДИТСЯ: таблица строк заявки, индекс со стороны позиции, СОСТАВНОЙ внешний ключ журнала
-- остатка на строку заявки (обещанный `0172`) и инвариант «выдано по строке равно тому, что об этой
-- строке говорит журнал» — двумя отложенными constraint-триггерами.
--
-- ПОЧЕМУ СВОЕЙ ТАБЛИЦЕЙ, А НЕ В `service_request_items`. Там цена, сумма, скидка акта и гарантия —
-- то есть смета ремонта, которую согласует заказчик и по которой платят подрядчику. У строки
-- расходника нет ни одного из этих полей и не появится: картридж берут со своего склада, и
-- «согласовать сумму» по нему не у кого. Слить их в одну таблицу значило бы завести строку, у
-- которой половина колонок обязана быть пустой по виду заявки, — и проверять это тем же CHECK'ом,
-- который сегодня держит связность сметы.
--
-- ПОРЯДОК ОТНОСИТЕЛЬНО СОСЕДЕЙ, и переставить его нельзя. Миграция обязана идти ПОСЛЕ `0172`
-- (журнал остатка с колонкой `service_request_consumable_id`, объявленной там nullable uuid БЕЗ
-- внешнего ключа — ключ достраивается здесь) и ПОСЛЕ `0177` (`kind`, ради которого всё и затеяно).
-- Обратной зависимости нет: `0172` о строках заявки не знает, а `0177` — о расходниках.
--
-- ОКНО ВЫКАТА (§3 плана). Штатный деплой накатывает миграции ДО перезапуска сервисов
-- (`docs/schema-cutover-protocol.md`, §1), и какое-то время старый код работает на новой схеме.
-- Здесь это выдержано с запасом: таблица новая и старому коду не видна, составной ключ журнала
-- срабатывает только у событий по заявке, а таких старый код не создаёт вовсе (§2.1 плана: до этой
-- миграции приложение пишет только `manual`). Ни одного движения старого кода миграция не
-- запрещает.
--
-- ОБРАТИМОСТЬ. Аддитивна целиком: новая пустая таблица, индекс, ключ на пустом множестве событий
-- по заявке, функции и триггеры. Существующие строки не читаются и не меняются — ключ проверяется
-- при накате, но проверять ему нечего: `service_request_consumable_id` пуст у всех строк журнала.
-- Протокол выката необратимых миграций к ней не применяется; снять всё заведённое здесь можно
-- ровно до тех пор, пока не закрыта первая заявка на расходники.

-- ── 1. Строки заявки ──
CREATE TABLE service_request_consumables (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- `CASCADE`, как у поимённых исполнителей (`0178`): строки — это состав самой заявки, а не её
  -- история; удалили заявку — списку просимых картриджей жить незачем. Заявку, за которой уже
  -- числится движение склада, каскад при этом не уносит: ссылки журнала объявлены `RESTRICT` — и
  -- прямая на заявку (`0172`), и составная на строку (ниже), — так что жёсткое удаление упрётся в
  -- них. Мягкому удалению это не мешает: заявку гасят `deleted_at` и только в «Новой», то есть
  -- до всякой выдачи.
  request_id uuid NOT NULL REFERENCES service_requests (id) ON DELETE CASCADE,
  -- `RESTRICT`: позиция, которую просили, не имеет права исчезнуть из-под заявки. Иначе строка
  -- «выдано 2» осталась бы без ответа на вопрос «чего именно 2», а отчёт по расходу — с дырой на
  -- месте удалённой номенклатуры. Уборка опечатки первого дня при этом остаётся возможной: пока на
  -- позицию никто не сослался ни строкой заявки, ни событием журнала, она удаляется совсем.
  consumable_id uuid NOT NULL REFERENCES office_equipment_consumables (id) ON DELETE RESTRICT,
  requested_quantity integer NOT NULL,
  -- Сколько числится ВЫДАННЫМ. Три состояния, и они разные (В9б):
  --   NULL — работу ещё не закрывали, факта у строки нет вовсе;
  --   0    — закрыли, но не выдали («съездили, тонер оказался цел»);
  --   N    — выдали N, и ровно столько списано со склада.
  -- Ни `NOT NULL`, ни `DEFAULT` здесь быть не должно — иначе просимое читалось бы как выданное,
  -- ровно тот же приём и та же причина, что у `performed` в строке сметы (`0105`).
  issued_quantity integer,
  -- Причина расхождения факта с запрошенным. Живёт В СТРОКЕ ЗАЯВКИ, а не только в событии журнала:
  -- её читают в карточке заявки и в отчёте, а событие журнала — это склад, и ходить за объяснением
  -- туда пришлось бы каждому, кто открыл заявку.
  --
  -- `NOT NULL DEFAULT ''`, а не nullable: «объяснять нечего» обязано иметь одно представление.
  -- Пустая строка и NULL рядом дали бы два имени одному состоянию и заставили бы каждую проверку
  -- писать `coalesce`.
  issue_note text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  -- Просят хотя бы штуку: строка «прошу ноль картриджей» — это отсутствие строки, а не строка.
  CONSTRAINT service_request_consumables_requested_check CHECK (requested_quantity > 0),
  -- Факт неотрицателен, но ноль законен — в отличие от запрошенного. Это и есть «съездили, а
  -- менять не пришлось»: работа сделана, отменять заявку не за что, списывать нечего.
  CONSTRAINT service_request_consumables_issued_check
    CHECK (issued_quantity IS NULL OR issued_quantity >= 0),
  -- Любое расхождение факта с запрошенным объясняется причиной — и выдача СВЕРХ заявки (В9а,
  -- «привезли три вместо двух»), и недодача, и ноль (В9б). Совпал факт с заявкой — объяснять
  -- нечего, и требовать текст было бы требованием писать «всё как просили» две тысячи раз в год.
  --
  -- Условие написано от факта: `issued_quantity IS NULL` — это «ещё не закрывали», и причины у
  -- незаполненного факта не бывает по определению.
  CONSTRAINT service_request_consumables_note_check CHECK (
    issued_quantity IS NULL
    OR issued_quantity = requested_quantity
    OR btrim(issue_note) <> ''
  ),
  -- Одна строка на позицию в заявке: две строки «Тонер Ricoh 201» — это не два расходника, а
  -- ошибка формы, и сложить их в одну обязан клиент, а не склад при списании. Ключ же отвечает на
  -- главный вопрос таблицы — «что просят по этой заявке».
  CONSTRAINT service_request_consumables_unique UNIQUE (request_id, consumable_id),
  -- Цель этого ключа ровно одна — быть АДРЕСАТОМ составного внешнего ключа журнала (§3 ниже).
  -- Postgres требует, чтобы набор колонок, на который ссылается FOREIGN KEY, был накрыт уникальным
  -- ограничением целиком; `PRIMARY KEY (id)` для тройки не годится, хотя и делает её уникальной.
  -- Читать по нему ничего не читают.
  CONSTRAINT service_request_consumables_row_unique UNIQUE (id, request_id, consumable_id)
);

COMMENT ON TABLE service_request_consumables IS
  'Строки заявки на расходники (docs/office-equipment-requests-rework-plan.md §4.3): что просили, '
  'что выдали и почему разошлось. Списание со склада идёт событиями журнала '
  'office_equipment_consumable_stock_entries, привязанными к этим строкам составным ключом.';

-- Индекс со стороны ПОЗИЦИИ, а не заявки. Ключ `service_request_consumables_unique` начинается с
-- `request_id` и вопрос «что просят по этой заявке» закрывает сам — отдельный индекс по заявке был
-- бы его точной копией с обрезанным хвостом (в §5 плана он назван, но заводить его незачем).
--
-- А вот со стороны позиции спрашивают дважды, и оба раза всерьёз: «в каких заявках просили этот
-- картридж» (отчёт по расходу, Р10) и `RESTRICT` при попытке удалить позицию справочника — без
-- индекса каждая такая попытка читала бы таблицу строк целиком. Тот же расклад, что у связи
-- «расходник — модель» в `0172`.
CREATE INDEX service_request_consumables_consumable_idx
  ON service_request_consumables (consumable_id);

-- ── 2. Составной ключ журнала: обещание, данное в `0172` ──
--
-- Событие журнала «списано по заявке СО-1234, позиция Ricoh 201, строка X» состоит из трёх
-- реквизитов, и все три уже лежат в строке журнала. Ключ на ОДНУ колонку (`service_request_consumable_id`)
-- проверял бы только существование строки — то есть разрешал бы событию по заявке СО-1234
-- указывать на строку заявки СО-5678 или на строку с другим расходником. Оба состояния молча
-- разваливают всё, ради чего связь заводилась: отчёт «сколько выдано по заявке» считал бы чужое, а
-- сторно правило бы не ту строку.
--
-- Поэтому ключ СОСТАВНОЙ: копии реквизитов родителя в дочерней строке — приём ADR 0007 §2, тот же,
-- что у ездок на точках маршрута и у снимка показаний.
--
-- РЕЖИМ `ON UPDATE` — «замок» (умолчание `NO ACTION`), и это решение, а не молчание: ни
-- идентификатор строки, ни её заявка, ни её позиция не меняются никогда. Строку не переносят между
-- заявками и не переназначают на другой картридж — её удаляют и заводят другую (`PUT
-- /:id/consumables` заменяет состав целиком). Зеркало здесь было бы прямо опасно: каскад по
-- `consumable_id` переписал бы в журнале позицию у уже случившегося движения склада, то есть
-- задним числом объявил бы, что выдавали не то, что выдавали. Род ключа назван поимённо в
-- `EXPECTED` теста `apps/api/test/schema-copy-keys.test.ts`.
--
-- `MATCH SIMPLE` (умолчание Postgres) ЗДЕСЬ ОБЯЗАТЕЛЕН и выбран сознательно. Составной ключ в этом
-- режиме не проверяется вовсе, если хоть одна его колонка пуста, — а у РУЧНОЙ правки остатка
-- `consumable_id` заполнен всегда (это же событие склада), обе ссылки на заявку пусты, и ключ
-- проходит мимо неё. `MATCH FULL` означал бы обратное: он требует либо все три колонки пустыми,
-- либо все три заполненными, и первая же ручная правка остатка упёрлась бы в него. Писать его
-- здесь нельзя ни при каких обстоятельствах.
--
-- `ON DELETE RESTRICT`: строку заявки, за которой числится движение склада, не удаляет ни маршрут,
-- ни каскад от заявки, ни скрипт. Журнал не должен уметь показывать на пустоту — иначе на вопрос
-- «по какой строке ушли эти два тонера» он однажды ответит «строки больше нет».
ALTER TABLE office_equipment_consumable_stock_entries
  ADD CONSTRAINT office_equipment_consumable_stock_row_fk
  FOREIGN KEY (service_request_consumable_id, service_request_id, consumable_id)
  REFERENCES service_request_consumables (id, request_id, consumable_id)
  ON DELETE RESTRICT;

COMMENT ON CONSTRAINT office_equipment_consumable_stock_row_fk
  ON office_equipment_consumable_stock_entries IS
  'Составной ключ «строка + заявка + позиция» на service_request_consumables (M12 плана '
  'переработки заявок): событие не может указывать на строку другой заявки или другого расходника. '
  'MATCH SIMPLE (умолчание) обязателен — у ручной правки остатка ссылки на заявку пусты, и ключ её '
  'не проверяет. ON UPDATE NO ACTION — «замок»: тройка неизменяема.';

-- ── 3. Ядро инварианта: «выдано» равно тому, что об этой строке говорит журнал ──
--
-- ЗАЧЕМ ЭТО ВООБЩЕ. Остаток расходника уже закрыт от прямого `UPDATE` отложенным триггером
-- `office_equipment_consumable_stock_covered` (`0172`): изменить количество на карточке, не написав
-- события, нельзя. Оставить строку заявки без такой же двери значило бы завести асимметрию, в
-- которой одна половина учёта защищена схемой, а вторая — вежливостью маршрута: `UPDATE
-- service_request_consumables SET issued_quantity = 5` скриптом прошёл бы насквозь, и склад с
-- заявкой разошлись бы навсегда, причём молча — обе стороны выглядели бы правдоподобно.
--
-- ЧТО ИМЕННО ПРОВЕРЯЕТСЯ. К концу транзакции факт строки равен сумме её событий: `issue` со знаком
-- плюс, `return` со знаком минус. Пустой набор событий законен только при незаполненном факте или
-- нуле — «работу не закрывали» и «закрыли, но не выдали» складом не двигают.
--
-- ПОЧЕМУ НЕ `CHECK`. `CHECK` видит только собственную строку и в журнал заглянуть не может.
-- Денормализованный счётчик «сколько списано» рядом с фактом завёл бы второе место, где живёт
-- правда о выдаче, и синхронизировать его пришлось бы тем же триггером. Прецеденты приёма —
-- `0035` (полнота категории), `0172` (покрытие остатка), `0178` (исполнитель у заявки).
--
-- ФУНКЦИЯ ПРИНИМАЕТ ИДЕНТИФИКАТОР И ПЕРЕЧИТЫВАЕТ ПО НЕМУ СОСТОЯНИЕ — ни `NEW.issued_quantity`, ни
-- любой другой снимок ряда в ней не участвуют, и это условие правильности, а не стиль. Правка
-- факта вниз и вверх в одной транзакции («поставили 3, тут же исправили на 2, оба события
-- записаны») законна; отложенные триггеры срабатывают на коммите все, и первый из них, сверяя свой
-- снимок «выдано 3» с журналом, где уже 2, дал бы отказ на ровном месте. Перечитанное состояние у
-- всех одно и то же — и оно верное.
--
-- ОНА ЖЕ ВЫЗЫВАЕТСЯ НЕ ТОЛЬКО ТРИГГЕРОМ: ею сверяют базу одним запросом после выката и в
-- db-тестах, а функция, умеющая работать лишь изнутри триггера, для этого недоступна. Отсюда и
-- разделение на чистую проверку и две обёртки — приём `0035`, `0172` и `0178`.
--
-- `FOR UPDATE` ЗДЕСЬ НЕТ, и это отличие от `0178` намеренное. Там блокировка задавала ПОРЯДОК
-- захвата («сначала заявка, потом исполнители»), потому что к одной заявке ходят с двух сторон.
-- Здесь порядок задан маршрутом и он про другое: заявка → карточки склада в порядке возрастания
-- `consumable_id` → события (Р5). Взять на коммите ещё одну блокировку, которой в этом порядке нет,
-- значило бы добавить единственное неупорядоченное звено — ровно то, из-за чего и случается
-- `40P01`. Обе стороны инварианта транзакция к этому моменту и так держит: строку — своим
-- `UPDATE`, события — своей вставкой.
CREATE FUNCTION service_request_consumable_issued_covered(p_line_id uuid) RETURNS void
  LANGUAGE plpgsql SECURITY INVOKER SET search_path = public, pg_temp AS $$
DECLARE
  v_issued integer;
  v_net integer;
  v_events integer;
BEGIN
  SELECT c.issued_quantity INTO v_issued
    FROM service_request_consumables c
   WHERE c.id = p_line_id;

  -- Строку удалили в этой же транзакции — проверять нечего. Тот же молчаливый выход, что в `0035`,
  -- `0172` и `0178`: строка с событиями не удаляется вовсе (`RESTRICT` ключа выше), а строка без
  -- событий — это правка состава заявки, законная и не касающаяся склада.
  IF NOT FOUND THEN
    RETURN;
  END IF;

  -- Сумма движений по строке. Считается ПО ВИДУ события, а не по знаку разницы: `…_direction_check`
  -- в `0172` эти две записи сегодня уравнивает (`issue` только уменьшает остаток, `return` только
  -- увеличивает), но правило расхода сформулировано именно как «issue минус return» — и останется
  -- верным, даже если то ограничение когда-нибудь ослабят.
  SELECT count(*),
         coalesce(sum(
           CASE e.entry_kind
             WHEN 'issue'  THEN e.quantity_before - e.quantity_after
             WHEN 'return' THEN -(e.quantity_after - e.quantity_before)
             ELSE 0
           END
         ), 0)
    INTO v_events, v_net
    FROM office_equipment_consumable_stock_entries e
   WHERE e.service_request_consumable_id = p_line_id;

  -- Незаполненный факт означает «работу ещё не закрывали», и события по такой строке невозможны —
  -- со склада не выдают по заявке, которую не закрывали. Проверяется НАЛИЧИЕ событий, а не их
  -- сумма: сумма нуль бывает и у пары «выдали две, вернули две», а это уже закрытая работа с
  -- фактом 0, и объявлять её незакрытой строка права не имеет.
  IF v_issued IS NULL THEN
    IF v_events > 0 THEN
      RAISE EXCEPTION
        'Строка заявки %: выдача не заполнена, но по строке уже есть событий журнала: %',
        p_line_id, v_events
        USING ERRCODE = 'check_violation';
    END IF;
    RETURN;
  END IF;

  IF v_issued <> v_net THEN
    RAISE EXCEPTION
      'Строка заявки %: выдано %, а журнал остатка отдаёт по ней %',
      p_line_id, v_issued, v_net
      USING ERRCODE = 'check_violation';
  END IF;
END
$$;

-- ── 4. Две обёртки: стороны две, и вход у них разный ──
--
-- Обёртки объявляются отдельно от самой проверки, потому что `CREATE TRIGGER` принимает только
-- функцию `RETURNS trigger`, а «функция по идентификатору» триггером быть не может. `RETURN NULL`
-- у обеих: значение `AFTER`-триггера не используется.
CREATE FUNCTION service_request_consumables_issued_covered_trg() RETURNS trigger
  LANGUAGE plpgsql SECURITY INVOKER SET search_path = public, pg_temp AS $$
BEGIN
  PERFORM service_request_consumable_issued_covered(NEW.id);
  RETURN NULL;
END
$$;

CREATE FUNCTION office_equipment_consumable_stock_issued_covered_trg() RETURNS trigger
  LANGUAGE plpgsql SECURITY INVOKER SET search_path = public, pg_temp AS $$
BEGIN
  PERFORM service_request_consumable_issued_covered(NEW.service_request_consumable_id);
  RETURN NULL;
END
