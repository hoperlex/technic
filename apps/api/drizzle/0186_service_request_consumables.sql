-- ── 5. Триггеры: две стороны одного инварианта ──
--
-- ПОЧЕМУ ИХ ДВА. Односторонний триггер закрывает ровно половину дверей, и вторая половина не
-- гипотетическая:
--
--   на строках заявки ..... ловит ПРЯМУЮ ПРАВКУ ФАКТА без события — `UPDATE … SET issued_quantity`
--                           скриптом или из вкладки, которая «поправила опечатку»;
--   на журнале ............ ловит ОБРАТНОЕ — транзакцию, которая подвинула склад законным `issue`
--                           и не изменила факт строки. Триггер строки в ней не сработал бы вовсе:
--                           строку никто не трогал, а склад уже уехал.
--
-- ОТЛОЖЕННЫЕ, а не немедленные: внутри транзакции закрытия порядок «правка карточки склада →
-- событие журнала → факт строки» законен и обязателен (цепочка `0172` сверяет «стало» с карточкой),
-- и немедленная проверка отбивала бы первый же шаг — то есть запрещала бы единственный правильный
-- путь. Ровно та же причина, что у покрытия остатка и у инварианта исполнителя.
--
-- `UPDATE OF issued_quantity` — а не любой `UPDATE`: инвариант зависит от одной колонки, и гонять
-- проверку на правке причины или количества значило бы читать журнал на каждое изменение состава
-- заявки. `INSERT` в списке обязателен: строка, заведённая сразу с непустым фактом и без события, —
-- то же нарушение, вошедшее другой дверью.
CREATE CONSTRAINT TRIGGER service_request_consumables_issued_covered
  AFTER INSERT OR UPDATE OF issued_quantity ON service_request_consumables
  DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION service_request_consumables_issued_covered_trg();

-- Только `INSERT`: журнал неизменяем физически — правку и удаление строки отбивает
-- `office_equipment_consumable_stock_immutable` (`0172`), и других дверей у этой стороны нет.
--
-- `WHEN` вместо `IF` внутри функции: у ручных событий ссылки на заявку пусты, проверять по ним
-- нечего, и вызывать функцию на каждую правку остатка кладовщиком незачем. Оговорка Postgres — у
-- constraint-триггера условие `WHEN` вычисляется в момент вставки, а не на коммите — здесь
-- безвредна ровно потому, что журнал неизменяем: `service_request_consumable_id` вставленной
-- строки к коммиту тот же, что был.
CREATE CONSTRAINT TRIGGER office_equipment_consumable_stock_issued_covered
  AFTER INSERT ON office_equipment_consumable_stock_entries
  DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW
  WHEN (NEW.service_request_consumable_id IS NOT NULL)
  EXECUTE FUNCTION office_equipment_consumable_stock_issued_covered_trg();

-- `ENABLE ALWAYS` — ОТДЕЛЬНОЙ командой: в `CREATE TRIGGER` такого слова нет, а без него на
-- реплике-приёмнике проверка не сработает вовсе. Приём тот же, что у `0167`, `0172` и `0178`.
ALTER TABLE service_request_consumables
  ENABLE ALWAYS TRIGGER service_request_consumables_issued_covered;
ALTER TABLE office_equipment_consumable_stock_entries
  ENABLE ALWAYS TRIGGER office_equipment_consumable_stock_issued_covered;

-- Четыре объекта контура носят почти одно имя — подписи разводят их поимённо.
COMMENT ON FUNCTION service_request_consumable_issued_covered(uuid) IS
  'ЧИСТАЯ проверка «выдано по строке равно сумме issue минус return по её событиям» (M12 плана '
  'переработки заявок оргтехники): по идентификатору строки ПЕРЕЧИТЫВАЕТ и факт, и журнал — снимка '
  'ряда не берёт вовсе, иначе две правки факта в одной транзакции дали бы ложный отказ. '
  'Незаполненный факт требует полного отсутствия событий, а не нулевой суммы: «выдали две, вернули '
  'две» — это закрытая работа с фактом 0. Строка, удалённая в этой же транзакции, — молчаливый '
  'выход. Годится и для сверки базы одним запросом.';

COMMENT ON FUNCTION service_request_consumables_issued_covered_trg() IS
  'Обёртка со стороны СТРОКИ ЗАЯВКИ: передаёт NEW.id в service_request_consumable_issued_covered'
  '(uuid). Ловит прямую правку issued_quantity, не сопровождённую событием журнала.';

COMMENT ON FUNCTION office_equipment_consumable_stock_issued_covered_trg() IS
  'Обёртка со стороны ЖУРНАЛА: передаёт NEW.service_request_consumable_id в '
  'service_request_consumable_issued_covered(uuid). Ловит обратный случай — событие issue или '
  'return, не изменившее факт строки заявки; триггер самой строки в такой транзакции не сработал '
  'бы, её никто не трогал.';

COMMENT ON TRIGGER service_request_consumables_issued_covered ON service_request_consumables IS
  'Отложенный constraint-триггер AFTER INSERT OR UPDATE OF issued_quantity: на коммите сверяет '
  'факт строки с журналом остатка. Отложенный потому, что внутри транзакции закрытия порядок '
  '«карточка склада, событие, факт» законен. ENABLE ALWAYS.';

COMMENT ON TRIGGER office_equipment_consumable_stock_issued_covered
  ON office_equipment_consumable_stock_entries IS
  'Вторая сторона того же инварианта: отложенный constraint-триггер AFTER INSERT (журнал '
  'неизменяем, других дверей нет) с условием WHEN на непустую ссылку на строку заявки — ручные '
  'правки остатка мимо. ENABLE ALWAYS.';
