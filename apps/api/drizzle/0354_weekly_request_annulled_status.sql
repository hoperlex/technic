-- Состояние «Аннулирована» у недельной заявки (ADR 0218): виза была, следствия развёрнуты
-- обратно. От «Снята» отличается тем, что следствия были — сроки двигались, номера бланков
-- сгорели, — и путать их нельзя: «Снята» отвечает «решения не было», «Аннулирована» — «решение
-- было и отменено».
--
-- ФАЙЛ ДЕЛАЕТ ОДНО: добавляет значение в enum. Разделение с использованием (0355) вынужденное, а
-- не стилистическое: раннер применяет каждый файл одной транзакцией (`migration-journal`), а
-- PostgreSQL запрещает ИСПОЛЬЗОВАТЬ значение enum'а в той же транзакции, где оно добавлено
-- («unsafe use of new value»). CHECK'и и предикат частичного индекса, ссылающиеся на свежее
-- значение, упали бы прямо здесь — все уехали в соседний файл.
--
-- `BEFORE 'cancelled'` — не косметика, причина та же, что у миграции 0194: порядок значений
-- enum'а задаёт `ORDER BY status`, и приписанное в конец значение поставило бы «Аннулирована»
-- после «Снята», то есть цикл документа читался бы неверно. Тот же порядок стоит в
-- `WEEKLY_REQUEST_STATUSES` контрактов и в `weeklyRequestStatusEnum` drizzle-схемы.

ALTER TYPE weekly_request_status ADD VALUE IF NOT EXISTS 'annulled' BEFORE 'cancelled';
