-- Виды писем модуля «Орг.техника»
-- (план `docs/office-equipment-mail-and-history-plan.md`, Р65).
--
-- Два значения, потому что события два и в журнале писем их ищут именно событиями: «что ушло
-- службе, когда заявка встала в очередь на визу» и «что ушло, когда её отменили». Кому какое
-- письмо адресовано, видно по `to_email`, а различает письма одного события `dedupe_key` —
-- в него входят строка истории статуса и адресат.
--
-- Значения добавляются отдельной миграцией и в той же транзакции кодом не используются: раннер
-- применяет файл миграции целиком в одной транзакции (`apps/api/src/db/migration-journal.ts:94`),
-- а PostgreSQL не разрешает пользоваться новым значением enum до её фиксации. Тот же приём — в
-- миграциях 0122, 0114, 0103, 0065, 0054.
--
-- Аддитивная миграция: смысл существующих данных не меняется.

ALTER TYPE mail_kind ADD VALUE IF NOT EXISTS 'service_request_waiting_it';
ALTER TYPE mail_kind ADD VALUE IF NOT EXISTS 'service_request_cancelled';
