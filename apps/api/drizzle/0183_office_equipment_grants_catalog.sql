-- Каталог полномочий модуля «Орг.техника»: три набора вместо двух (план переработки заявок
-- `docs/office-equipment-requests-rework-plan.md`, §7.2; волна В5).
--
-- ЗАЧЕМ. Постановка заказчика сводит работу с оргтехникой к трём должностям: тот, кто ведёт модуль
-- («Ведение»), ИТ-служба — она же инхаус-исполнитель, и тот, кто ведёт справочник картриджей.
-- Первые две в каталоге уже есть под старыми именами и с прежним, узким составом; третьей не было
-- вовсе.
--
-- ЧЕГО ЗДЕСЬ НЕТ. Ни одной строки `user_grants`: наборы заводятся и пересобираются, а выдаёт их
-- администратор портала поимённо — с автором, временем и происхождением (ADR 0106). Права живых
-- учёток эта миграция меняет только у держателей ДВУХ существующих наборов, и ровно на то, что
-- перечислено ниже.
--
-- ПОЧЕМУ СОСТАВ РАСШИРЯЕТСЯ ИМЕННО СЕЙЧАС, А НЕ РАНЬШЕ. Новые права (`hold`, `urgency`, `execute`)
-- открывают маршруты, которых до волны В3 не существовало: выдать право раньше ручки значит обещать
-- держателю действие, на которое сервер ответит 404. Поэтому §9 плана ставит этап полномочий после
-- этапов маршрута и автозакрытия — и порядок здесь не пожелание, а условие.
--
-- КОДЫ НАБОРОВ НЕ МЕНЯЮТСЯ НИ ПРИ КАКИХ УСЛОВИЯХ. По коду набор находят миграции каталога, журнал
-- действий, реестр выдач и типизированная таблица сквозной области (`GRANT_MODULE_WIDE_SCOPE`):
-- `UPDATE grants SET code = ...` не «переименовывает набор», а отвязывает его от кода — виза ИТ
-- потеряла бы сквозную область, оставаясь на вид выданной. Меняются название, описание и состав.
--
-- ГДЕ ЖИВЁТ ОБЪЯВЛЕННЫЙ СОСТАВ. У этих двух наборов — в `ROLE_ADDON_PERMISSIONS`
-- (`packages/contracts/src/permissions.ts`), потому что надстройки ADR 0086 остаются живым
-- источником доступа до шага 1e реформы, и набор в базе — их отражение; у нового —
-- в `MODULE_GRANTS` (`packages/contracts/src/grants.ts`). Обе стороны сверяет страж
-- `apps/api/test/grants-catalog.db.test.ts`: разъедься копии — он назовёт набор и обе стороны
-- расхождения. Правка надстроек уехала той же волной, что эта миграция, и это обязательное условие:
-- иначе один и тот же человек получил бы разные права в зависимости от того, пришёл к нему доступ
-- надстройкой или набором.
--
-- ОБРАТИМОСТЬ. Миграция трогает только три таблицы каталога, схему не меняет; протокол выката
-- необратимых миграций (`docs/schema-cutover-protocol.md`) к ней не применяется. Откат — снятие
-- посеянного: новый набор удаляется, пока у него нет держателей (`RESTRICT` на `user_grants`), а
-- состав двух существующих возвращается прежним `DELETE`/`INSERT`.

-- ── 1. Названия и описания двух существующих наборов ──
--
-- Названия приведены к тому, что видит человек в списке учёток: подпись надстройки правится той же
-- волной (`roleAddonLabels`), и «Оператор (оргтехника)» против «Оргтехника: ведение» читались бы как
-- два разных доступа.

UPDATE grants
   SET name = 'Оргтехника: ведение',
       description = 'Ведёт модуль «Орг.техника» целиком: справочник техники, распределение заявок '
                     'по исполнителям, согласование сметы, приёмку работы, срочность и заморозку. '
                     'Это единственный набор, которым заявку принимают и отменяют из любого '
                     'статуса; ходов исполнителя в нём нет — их открывает назначение.',
       updated_at = now()
 WHERE code = 'office_equipment_operator';

UPDATE grants
   SET name = 'Оргтехника: ИТ-служба',
       description = 'Решает по смете «чинить или менять» и работает исполнителем: берёт заявку в '
                     'работу, ведёт её, откладывает, подшивает документы и передаёт внешнему '
                     'сервису. Ходы исполнителя доступны только на заявках, где держатель назначен '
                     'поимённо. Виза ИТ и сквозная видимость модуля идут вместе с набором: '
                     'подписывают по всем площадкам сразу.',
       updated_at = now()
 WHERE code = 'office_equipment_it_approver';

-- ── 2. Состав двух существующих наборов ──
--
-- Дописываются только новые права; `ON CONFLICT DO NOTHING` делает шаг идемпотентным, а не
-- «на всякий случай»: повторный накат на базу, где часть строк уже есть, — обычное дело при
-- восстановлении стенда из копии.

INSERT INTO grant_permissions (grant_id, permission)
SELECT g.id, s.permission
FROM grants g
JOIN (VALUES
  -- «Ведение»: заморозка и срочность возвращаются тому, у кого и были. Раньше «Отложена» приходила
  -- внутри `serviceRequests.status`, а флаг «Срочная» — внутри `update`; оба выделены своими
  -- правами (§7.1), и без этих двух строк правка матрицы отобрала бы у «Ведения» то, чем оно
  -- пользуется каждый день.
  ('office_equipment_operator'   , 'serviceRequests.hold'),
  ('office_equipment_operator'   , 'serviceRequests.urgency'),
  -- ИТ-служба: четыре права работы исполнителем. `execute` сам по себе не даёт ничего — ходы
  -- открывает пара «назначен поимённо + это право», и решает её коридор, а не страж маршрута.
  -- `assign` нужно, чтобы взять чужую заявку, назначив себя; `hold` — придержать её, пока ждут
  -- запчасть; `files` — подшить бумагу.
  ('office_equipment_it_approver', 'serviceRequests.assign'),
  ('office_equipment_it_approver', 'serviceRequests.hold'),
  ('office_equipment_it_approver', 'serviceRequests.execute'),
  ('office_equipment_it_approver', 'serviceRequests.files')
) AS s (code, permission) ON s.code = g.code
ON CONFLICT (grant_id, permission) DO NOTHING;

-- ── 3. Новый набор «Оргтехника: номенклатура» ──
--
-- Отдельным набором, а не строкой в «Ведении», по прямой просьбе заказчика: справочник картриджей
-- ведёт один человек, а заявки может вести кто-то ещё. Держится это разделение двумя правами
-- номенклатуры — до них она правилась общим `officeEquipment.write`, и набор не был отделён ничем:
-- выдав его, выдали бы заодно ведение всего парка техники и моделей.

INSERT INTO grants (code, name, description, is_system) VALUES
  (
    'office_equipment_consumables',
    'Оргтехника: номенклатура',
    'Ведёт перечень картриджей и тонеров: заводит позиции с кодом учётной системы, привязывает их к '
    'моделям аппаратов, гасит вышедшие из обращения и правит остаток на складе — каждое изменение '
    'остатка пишется событием с причиной и автором. Заявки этим набором не ведут, техника в нём не '
    'правится.',
    true
  )
ON CONFLICT (code) DO UPDATE
   SET name = EXCLUDED.name, description = EXCLUDED.description, updated_at = now();

INSERT INTO grant_permissions (grant_id, permission)
SELECT g.id, s.permission
FROM grants g
JOIN (VALUES
  -- Права два, а не одно: завести позицию и пересчитать коробки на полке — разные работы, и делают
  -- их не обязательно одни руки. В наборе они вместе, потому что администратору выбор из двух
  -- половин одной работы не нужен; разведены они в словаре, чтобы будущая точечная выдача могла
  -- дать только остаток.
  ('office_equipment_consumables', 'officeEquipmentConsumables.manage'),
  ('office_equipment_consumables', 'officeEquipmentConsumables.stock')
) AS s (code, permission) ON s.code = g.code
ON CONFLICT (grant_id, permission) DO NOTHING;

-- Совместимые роли — «кому набор можно назначить», а не «кому он выдан». Список тот же, что у двух
-- соседних наборов оргтехники: работа с ней идёт на площадке и в офисе. Ролей с чтением справочника
-- в портале больше (менеджер, диспетчер, руководитель строительства, руководитель отдела,
-- наблюдатель) — требование `officeEquipment.read` их не отсеивает, оно лишь проверяет, что каждая
-- перечисленная ему удовлетворяет: набор, выданный роли без чтения, отвечал бы
-- `requirement_missing`.
INSERT INTO grant_roles (grant_id, role)
SELECT g.id, s.role::role
FROM grants g
JOIN (VALUES
  ('office_equipment_consumables', 'shtab'),
  ('office_equipment_consumables', 'site'),
  ('office_equipment_consumables', 'department')
) AS s (code, role) ON s.code = g.code
ON CONFLICT (grant_id, role) DO NOTHING;

-- ── 4. Караул: состав в базе равен объявленному ──
--
-- Страж-тест сверяет то же самое, но он живёт в репозитории, а этот блок — в накате: оператор
-- выката увидит расхождение сразу, а не через прогон тестов. Проверяется только то, что миграция
-- обещала сделать, — три набора и их размеры.
DO $$
DECLARE missing text;
BEGIN
  SELECT string_agg(format('%s: %s прав', code, cnt), ', ')
    INTO missing
    FROM (
      SELECT g.code, count(gp.permission) AS cnt
        FROM grants g
        LEFT JOIN grant_permissions gp ON gp.grant_id = g.id
       WHERE g.code IN ('office_equipment_operator', 'office_equipment_it_approver',
                        'office_equipment_consumables')
       GROUP BY g.code
      HAVING (g.code = 'office_equipment_operator'     AND count(gp.permission) <> 6)
          OR (g.code = 'office_equipment_it_approver'  AND count(gp.permission) <> 5)
          OR (g.code = 'office_equipment_consumables'  AND count(gp.permission) <> 2)
    ) AS bad;
  IF missing IS NOT NULL THEN
    RAISE EXCEPTION 'Каталог оргтехники собран не полностью — %', missing;
  END IF;
END $$;
