-- Три новых пожелания при регистрации: сотрудник отдела, руководитель отдела и представитель
-- сервисной компании (продолжение ADR 0034, план docs/registration-wishes-and-activation-plan.md).
--
-- Перечень пожеланий (0057) писался, когда ни отделов-заказчиков, ни оргтехники, ни сервисных
-- компаний в портале не было вовсе. Сегодня офисный сотрудник выбирает «Другое», а представитель
-- сервисной компании — «Оператор по вывозу мусора» или то же «Другое», и администратор снова
-- выясняет звонком, кто пришёл и что ему открывать: ровно тот звонок, ради отмены которого
-- пожелание и заводили.
--
-- Это по-прежнему ПОЖЕЛАНИЕ, А НЕ РОЛЬ: прав новые значения не дают никаких, `users.role` остаётся
-- за администратором (0057), а признак «заявка = не активна и без роли» — на месте. Соответствие
-- «пожелание → роль плюс наборы полномочий» живёт в контрактах @technic/contracts, а не в базе, —
-- как и вся матрица прав (ADR 0021). Сюда добавляются только значения перечисления.
--
-- ПОДПИСИ НАЗЫВАЮТ ДОЛЖНОСТЬ, А НЕ РОЛЬ ПОРТАЛА, и этим значения переживают реформу ролей: после
-- слияния упраздняемые `rukstroy` и `commandant` из `role` исчезнут, а руководитель строительства и
-- комендант так и продолжат называть себя своей должностью. По той же причине новые значения
-- названы должностями, а не ролями `department` и `operator`, в которые ведут: в роль `operator`
-- ведут сразу три внешних пожелания, и различает их тип контрагента, а не роль (ADR 0038).
--
-- ПОРЯДОК ЗНАЧЕНИЙ НЕ ЗАДАЁТСЯ — `BEFORE`/`AFTER` здесь нет, в отличие от 0067, где комендант
-- ставился рядом с ролями объекта. Довод там был про сортировку по колонке; по пожеланию в портале
-- не сортируется ни один список — порядок на экране задаёт массив в контрактах, а сверка кода с
-- базой сравнивает множества значений, а не их последовательность.
--
-- ЗНАЧЕНИЯ ОТДЕЛЬНЫМ ФАЙЛОМ, А CHECK'И — СЛЕДУЮЩИМ (0219). Раннер катит файл целиком в одной
-- транзакции (`apps/api/src/db/migration-journal.ts`), а PostgreSQL не разрешает пользоваться
-- добавленным значением enum до её фиксации; ограничение же сравнивает `requested_role` с
-- литералом. Ровно по этой причине разошлись 0067 и 0068, тем же приёмом заведены 0130 и 0138.
--
-- ДАННЫХ МИГРАЦИЯ НЕ ТРОГАЕТ и требований ни к одной строке не предъявляет: перечень расширяется,
-- прежние заявки остаются на своих значениях. Обратимой она при этом не становится — значение enum
-- в PostgreSQL штатно не удаляется (`ALTER TYPE ... DROP VALUE` не существует), а после первой
-- заявки с новым пожеланием небезопасен и откат кода: прежняя сборка такого значения не знает.
-- Поэтому файл безопасно катится раньше кода: пока новое пожелание никто не выбрал, схема ведёт
-- себя ровно как до него.

-- Сотрудник отдела и руководитель отдела. Подразделение у них — отдел (ADR 0040), и пишется он в ту
-- же колонку `requested_object`, что и объект: та расширяет смысл до «где человек работает» (0219).
ALTER TYPE registration_role_request ADD VALUE IF NOT EXISTS 'department_staff';
ALTER TYPE registration_role_request ADD VALUE IF NOT EXISTS 'department_head';

-- Представитель сервисной компании по оргтехнике (ADR 0085). Значение называет ЧЕЛОВЕКА —
-- сотрудника или представителя компании, а не саму организацию: регистрируется он как все
-- остальные, а «Компания» свободным текстом называет контрагента, от лица которого он работает.
ALTER TYPE registration_role_request ADD VALUE IF NOT EXISTS 'service_company';
