-- Инвариант роли «Руководитель строительства» (ADR 0025): учётка всегда привязана к объекту.
--
-- Без объекта роль не ограничена ничем и одновременно не видит ни одной заявки: и область
-- видимости, и право визировать считаются от `construction_object_id`. У «Штаба» то же правило
-- держится только приложением (исторически); здесь оно физическое — роль заводится сейчас, и
-- строк, которые пришлось бы чинить, нет.
--
-- Отдельный файл, а не хвост 0049: значение 'rukstroy' добавлено в enum `role` там же, а новое
-- значение нельзя использовать в транзакции, которая его добавила.
ALTER TABLE users
  ADD CONSTRAINT users_rukstroy_object_check
  CHECK (role IS DISTINCT FROM 'rukstroy' OR construction_object_id IS NOT NULL);
