-- Рубильник области исполнителя: ключ `service_request_executor_scope` в перечне таблицы
-- `feature_flags` и его ВЫКЛЮЧЕННАЯ строка (план
-- `docs/office-equipment-free-estimate-and-executor-scope-plan.md`, Р4, этап Э5; выпуск A по §8).
--
-- ОТКУДА НОМЕР. `ls apps/api/drizzle` непосредственно перед созданием файла (10.09.2026): последним
-- в дереве стоит `0299_service_request_past_executors.sql` — след снятого исполнителя, соседний
-- файл этой же волны. Свободен 0300, он и взят. Номер берётся в момент создания КАЖДОГО файла:
-- параллельные потоки занимают номера незакоммиченными файлами, и снимок свободного номера живёт
-- часы (миграции 0261 и 0262 рассказывают, чем это кончается).
--
-- ЗАЧЕМ КЛЮЧ, ЕСЛИ ВОЛНА И ТАК ЕДЕТ ОДНИМ ВЫПУСКОМ. Волна СУЖАЕТ видимость: сисадмин перестаёт
-- видеть заявки компании и видит свои — назначенные, заведённые им самим и те, с которых его сняли.
-- Сужение доступа отличается от расширения тем, что ошибка в нём немедленно мешает работать людям,
-- а откат выката — это перезапуск с раскаткой кода, то есть минуты и координация. Ключ
-- переворачивает порядок: код едет ЗАКРЫТЫМ, включает его `UPDATE` по работающему серверу, а
-- аварийное выключение — тот же `UPDATE … = false` за секунды и без выката.
--
-- ВЫКЛЮЧЕННОЕ СОСТОЯНИЕ ОБЯЗАНО ОЗНАЧАТЬ СЕГОДНЯШНЕЕ ПОВЕДЕНИЕ — это главное требование к ключу, и
-- оно продиктовало волне порядок работ. Первая редакция плана снимала `serviceRequests` из карты
-- сквозной области (`GRANT_MODULE_WIDE_SCOPE`) сразу — и тем обессмысливала рубильник: выключенный
-- ключ не вернул бы прежнюю видимость, потому что карта была бы уже сужена самим выкатом. Поэтому
-- уборка карт отложена в выпуск B (Р4), а этот ключ управляет РАЗВИЛКОЙ: включён — область
-- считается по новым правилам и карта не читается вовсе, выключен — всё как вчера, включая широкую
-- видимость ИТ-набора. Проверяется это тестом (Т19), а не обещанием: отдельный случай на «строки
-- ключа нет вовсе» — тоже сегодняшнее поведение (fail-closed).
--
-- ПОРЯДОК ВКЛЮЧЕНИЯ ЗАПИСАН В §8 ПЛАНА И ОБЯЗАТЕЛЕН: миграции → ПОЛНОЕ переключение API → портал →
-- `UPDATE` ключа. Смысл каждой стрелки:
--
--   · при постепенной выкатке старые экземпляры API отдают все заявки И НЕ ПИШУТ СЛЕД СНЯТИЯ
--     (миграция 0299) — то есть сужение и его собственное исключение разъезжаются ровно в окне
--     выката: сняли исполнителя старым экземпляром, включили ключ — заявка исчезла у него навсегда;
--   · портал переключается ДО включения: старый портал о ключе не знает и рисовал бы кнопки, на
--     которые новый сервер уже отвечает 403 (Р11);
--   · включение — `UPDATE feature_flags SET is_enabled = true, updated_at = now() WHERE key =
--     'service_request_executor_scope'` по живой базе, после health и smoke. Открытые сессии
--     подхватывают признак следующим ответом сессии (значение читается без кэша, намеренно —
--     `apps/api/src/services/feature-flags.ts`), поэтому включение сопровождается принудительным
--     обновлением сессии на клиентах и smoke-проверкой СУЩЕСТВУЮЩЕЙ сессией, а не только свежим
--     входом: сервер безопасен сразу, а уже открытый портал до обновления рисует прежние кнопки.
--
-- ПОЧЕМУ ПРАВКА `CHECK`, А НЕ ПРОСТО `INSERT`. Перечень ключей у таблицы закрыт (миграция 0293) и
-- обязан совпадать с реестром `FEATURE_FLAGS` в контрактах и с `check` в
-- `apps/api/src/db/schema.ts`. Причина запрета та же, что у рубильника писем, — цена опечатки:
-- лишняя строка выглядела бы настройкой («рубильник включён»), пока настоящий ключ сидит без строки
-- и молчит fail-closed, то есть выключение выглядело бы включением. Обе стороны — контракты и
-- схема — правятся ТОЙ ЖЕ волной; расхождение поймает страж, но ловить его лучше на ревью.
--
-- `DROP CONSTRAINT` + `ADD CONSTRAINT`, а не `ALTER … ALTER CONSTRAINT`: изменить условие `CHECK`
-- на месте PostgreSQL не умеет. Пересборка проверяет обе существующие строки — их две, и обе
-- перечню удовлетворяют. `NOT VALID` не нужен и был бы вреден: таблица размером в перечень
-- рубильников, а непроверенное ограничение — та самая тихая дыра, ради закрытия которой `CHECK` и
-- стоит.
--
-- СТРОКА ЗАВОДИТСЯ ВЫКЛЮЧЕННОЙ, и это весь смысл её появления в выпуске A: сужение приезжает
-- мёртвым. Строка нужна именно строкой, а не отсутствием: читатель трактует «нет строки» и
-- «выключено» одинаково (fail-closed), но включать выпуском обязаны СУЩЕСТВУЮЩУЮ строку, а не
-- догадку о ней, — иначе `UPDATE` тихо обновит ноль рядов и оператор решит, что включил.
--
-- ЧЕГО МИГРАЦИЯ НЕ ДЕЛАЕТ: не выдаёт и не отзывает ни одного права, не трогает карты сквозной
-- области (это выпуск B), не включает сужение и не касается соседнего ключа
-- `office_equipment_candidate_intake` — караул ниже проверяет его значение снимком «до».
--
-- ОБРАТИМОСТЬ. Схема меняется одним ограничением, данные — одной строкой. Откат — вернуть прежний
-- `CHECK` и удалить строку; делать его в одиночку безопасно, потому что код, читающий ключ,
-- отвечает «выключено» и на отсутствие строки. Аварийное выключение уже включённого рубильника
-- откатом ЭТОГО файла не делается: `UPDATE … = false` по живой базе быстрее и не трогает журнал
-- наката.

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 0. Снимок прочих рубильников ДО правки — ради утверждения «чужих ключей не трогали».
--
-- Приём соседа (0297): снимком, а не константой, потому что значения прочих ключей на проде, в деве
-- и на восстановленной из копии базе разные, а утверждение одно. `ON COMMIT DROP` — таблица живёт
-- до конца транзакции миграции и в базе не остаётся.
--
-- Снимок берётся ЦЕЛИКОМ, вместе со своим будущим ключом, и это не избыточность: по нему караул
-- отличает первый накат (строки не было — обязана появиться выключенной) от повторного на базе,
-- где рубильник уже открыт (строка была — значение обязано остаться нетронутым). Без снимка эти
-- два случая неразличимы, и утверждение «едет закрытым» пришлось бы либо ослабить до «строка
-- есть», либо превратить в ложную тревогу на каждой восстановленной копии.

CREATE TEMP TABLE feature_flags_0300 ON COMMIT DROP AS
SELECT key, is_enabled
FROM feature_flags;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 1. Перечень ключей: их становится два.

ALTER TABLE feature_flags DROP CONSTRAINT feature_flags_key_check;

ALTER TABLE feature_flags ADD CONSTRAINT feature_flags_key_check
  CHECK (key IN ('office_equipment_candidate_intake', 'service_request_executor_scope'));

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 2. Строка рубильника — выключенная.
--
-- `ON CONFLICT DO NOTHING` делает шаг идемпотентным и — важнее — не гасит уже ВКЛЮЧЁННЫЙ ключ:
-- повторный накат на базу, где рубильник открыт (восстановление из копии старше дня включения плюс
-- добежавший накат), не имеет права закрыть работающее сужение молча.

INSERT INTO feature_flags (key, is_enabled) VALUES
  ('service_request_executor_scope', false)
ON CONFLICT (key) DO NOTHING;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 3. Караул: перечень принял оба ключа, строка есть, чужой ключ не тронут.
--
-- Перечень проверяется не текстом ограничения, а ПОВЕДЕНИЕМ — попыткой вставить заведомо чужой
-- ключ во временной точке сохранения. Сравнение исходника `CHECK` строкой сломалось бы от лишнего
-- пробела и ничего бы не доказало; попытка вставки доказывает ровно то, ради чего ограничение
-- стоит: посторонний ключ в таблицу не попадает.

DO $$
DECLARE trouble text;
BEGIN
  BEGIN
    INSERT INTO feature_flags (key) VALUES ('__guard_0300_not_a_flag__');
    RAISE EXCEPTION 'перечень ключей рубильников не запирает таблицу: посторонний ключ вставился';
  EXCEPTION
    WHEN check_violation THEN NULL;
  END;

  SELECT string_agg(msg, '; ')
    INTO trouble
    FROM (
      SELECT 'строки рубильника области исполнителя нет' AS msg
       WHERE NOT EXISTS (
         SELECT 1 FROM feature_flags WHERE key = 'service_request_executor_scope')
      UNION ALL
      -- Только для ПЕРВОГО наката: строки в снимке не было, значит завела её эта миграция — и
      -- завести обязана выключенной. На базе, где рубильник уже открыт (восстановленная копия,
      -- добежавший накат), утверждение другое — оно строкой ниже.
      SELECT 'рубильник области исполнителя заведён ВКЛЮЧЁННЫМ — выпуск A обязан ехать закрытым'
        FROM feature_flags f
       WHERE f.key = 'service_request_executor_scope'
         AND f.is_enabled
         AND NOT EXISTS (SELECT 1 FROM feature_flags_0300 s
                          WHERE s.key = 'service_request_executor_scope')
      UNION ALL
      -- Ни один ключ, БЫВШИЙ в таблице до наката, значения не меняет — включая свой собственный:
      -- повторный накат не имеет права ни погасить работающее сужение, ни включить погашенное.
      SELECT format('ключ «%s» изменился: было %s, стало %s — миграция трогала живой рубильник',
                    s.key, s.is_enabled, f.is_enabled)
        FROM feature_flags_0300 s
        JOIN feature_flags f ON f.key = s.key
       WHERE f.is_enabled IS DISTINCT FROM s.is_enabled
      UNION ALL
      SELECT format('ключ «%s» исчез из таблицы', s.key)
        FROM feature_flags_0300 s
       WHERE NOT EXISTS (SELECT 1 FROM feature_flags f WHERE f.key = s.key)
    ) AS bad;
  IF trouble IS NOT NULL THEN
    RAISE EXCEPTION 'Рубильник области исполнителя заведён не так, как объявлен — %', trouble;
  END IF;
END $$;
