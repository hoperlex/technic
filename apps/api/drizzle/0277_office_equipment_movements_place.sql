-- Журнал перемещений оргтехники запоминает УТОЧНЕНИЕ МЕСТА обеими сторонами и умеет сказать, что
-- этим переездом разобрано заявленное расхождение (план
-- `docs/office-equipment-move-from-request-plan.md`, Р5 и Р8; находки Н5 и Н6; этап Э3, §7 строка
-- `N+1`).
--
-- ОТКУДА НОМЕР, И ПОЧЕМУ ОН БРАЛСЯ ДВАЖДЫ. `ls apps/api/drizzle` перед созданием файла (04.09.2026,
-- вечер): последней в дереве стояла `0274_releases_service_request_quick_status.sql` соседнего
-- потока — она заняла номер, свободный часом раньше и выданный этой волне планом. Парная миграция
-- каталога полномочий взяла 0275, эта — сперва 0276; пока файл писался, тот же 0276 занял
-- незакоммиченный `0276_service_requests_repeat_idx.sql` соседнего потока (он появился на две
-- минуты раньше), и файл переименован в 0277. Тот же урок в третий раз за вечер: номер живёт часы,
-- и сверять его надо не перед волной, а перед созданием КАЖДОГО файла.
--
-- Катятся обе миграции волны вместе; порядок между ними не важен (разные таблицы), но обе обязаны
-- приехать ДО сервера, который пишет новые колонки и спрашивает новое право.
--
-- ЧТО ДОБАВЛЯЕТСЯ И ПОЧЕМУ.
--
--   · `from_state_note` / `to_state_note` (Н5). В журнале есть `from_state`/`to_state` — «на
--     складе», «у сотрудника», — но нет уточнения, а карточка хранит только ТЕКУЩЕЕ его значение.
--     Через год вопрос «у кого была эта техника в марте» не читается ниоткуда: журнал отвечает
--     «была у сотрудника», не отвечая, у какого. `NOT NULL DEFAULT ''`, как соседние
--     `from_location`/`to_location`: пустая строка означает «уточнения не было», а не
--     «неизвестно». Бэкфила нет и быть не может — у строк, записанных до этой миграции, уточнения
--     не спрашивали вовсе, и проставить его задним числом значило бы придумать за человека, где
--     стоял аппарат;
--   · `confirms_declared_place` (Н6, Р8). Расхождение «заявитель сказал, что аппарат стоит не
--     там» флагом не хранится: оно СЧИТАЕТСЯ сравнением снимка заявки с карточкой (миграция 0224)
--     и потому гаснет само, когда единицу переносят ТУДА, где её заявили. Но заявитель говорит
--     «стоит на B», ответственный проверяет и находит аппарат на C — и после переноса снимок `B`
--     по-прежнему не равен карточке `C`, то есть разобранная заявка висит в очереди ИТ-службы
--     навсегда, до самого закрытия. Колонка и есть ответ: «расхождение разобрано ВОТ ЭТИМ
--     действием», с автором, датой и причиной. `DEFAULT false` — у всех прежних строк `false`, и
--     очередь ведёт себя ровно как раньше.
--
-- ПОЧЕМУ ФЛАГ, А НЕ «ЛЮБОЕ ПЕРЕМЕЩЕНИЕ ПО ЗАЯВКЕ ЗАКРЫВАЕТ ОЧЕРЕДЬ». Перемещение по заявке бывает
-- служебным — «увезли в сервис», «вернулась», — и на вопрос «где аппарат стоит на самом деле» оно
-- не отвечает. И почему не отметкой в самой заявке: заявка — свидетельство о том, что заявили, и
-- гасить её поля задним числом означало бы править показания; перемещение же — отдельное событие
-- со своим автором и временем, и «разобрано вот этим» читается прямо.
--
-- CHECK ЗДЕСЬ НА ФЛАГ НЕ СТАВИТСЯ, И ЭТО РЕШЕНИЕ, А НЕ ПРОПУСК. Правило «подтверждение бывает
-- только вместе с заявкой» держат схема запроса (`moveOfficeEquipmentSchema`) и маршрут. Ограничение
-- в базе выглядело бы строже, а стоило бы дороже: `service_request_id` гасится `ON DELETE SET NULL`,
-- когда заявку сносят насовсем (`records.purge`), — и такой CHECK отбил бы саму уборку архива
-- нарушением целостности. Факт «этим действием разобрали расхождение» при этом переживает удаление
-- заявки, и правильно: он про перемещение, а не про неё (развилка В4 плана).
--
-- ПРАВКА CHECK «ЧТО-ТО ИЗМЕНИЛОСЬ» (Р5). Смена ОДНОГО ЛИШЬ уточнения — «был у Иванова, стал у
-- Петрова» — сегодня отбивается как «ничего не изменилось», и единственным способом оформить такой
-- переход остаётся тихая правка карточки, то есть ровно то, ради чего журнал и заведён. Новое
-- условие СЛАБЕЕ прежнего: к четырём его дизъюнктам добавлен пятый, поэтому всякая уже лежащая
-- строка ему удовлетворяет и замена проходит заведомо.
--
-- ЧАСТИЧНЫЙ ИНДЕКС `(service_request_id, created_at DESC, id DESC) WHERE confirms_declared_place`
-- (Р8) обслуживает обе стороны гашения: коррелированный `NOT EXISTS` «нет подтверждающего
-- перемещения» в list/detail заявок и поиск ПОСЛЕДНЕГО подтверждения для подписи «расхождение
-- разобрано, и вот кем». Частичный — потому что подтверждений на порядок меньше, чем перемещений:
-- индекс по всем строкам был бы больше при той же пользе. Порядок колонок — порядок вопроса:
-- заявка, затем свежесть; `id DESC` в хвосте делает выбор последнего детерминированным, когда две
-- записи попали в одну миллисекунду.
--
-- ПОЧЕМУ ПРЯМАЯ ВЕТКА, БЕЗ `expand → validate → swap`. Таблица маленькая и растёт событиями
-- переезда, а не потоком: три колонки с неволатильными умолчаниями (PG 11+) метаданные не
-- переписывают, замена CHECK требует одного прохода по тем же нескольким тысячам строк, индекс
-- строится по подмножеству, где до выката ноль строк. Всё сведено в один `ALTER TABLE`: одна
-- блокировка и один проход вместо четырёх захватов. `lock_timeout` файл не меняет.
--
-- ОБРАТИМОСТЬ. Откат — снять индекс, вернуть прежний CHECK (без дизъюнкта по уточнению) и удалить
-- три колонки; делать его нужно вместе с откатом сервера, иначе ручка перемещения будет писать
-- колонки, которых нет. Данных откат стоит: записанные уточнения и отметки о разборе исчезнут
-- насовсем — восстановить их неоткуда, потому что карточка хранит только текущее место.

ALTER TABLE office_equipment_movements
  ADD COLUMN from_state_note text NOT NULL DEFAULT '',
  ADD COLUMN to_state_note text NOT NULL DEFAULT '',
  ADD COLUMN confirms_declared_place boolean NOT NULL DEFAULT false,
  DROP CONSTRAINT office_equipment_movements_change_check,
  ADD CONSTRAINT office_equipment_movements_change_check CHECK (
    from_object_id <> to_object_id
    OR from_state <> to_state
    OR from_location <> to_location
    -- Пятый дизъюнкт: смена одного лишь уточнения — тоже переезд (Р5).
    OR from_state_note <> to_state_note
    OR from_department_id IS DISTINCT FROM to_department_id
  );

-- «Разобрано ли расхождение по этой заявке» и «каким именно действием» — один индекс на оба
-- вопроса (Р8).
CREATE INDEX office_equipment_movements_confirms_idx
  ON office_equipment_movements (service_request_id, created_at DESC, id DESC)
  WHERE confirms_declared_place IS TRUE;

-- ── Караул: колонки, условие и индекс на месте ──
--
-- Проверяется то, что миграция обещала, и на накате: оператор выката увидит расхождение сразу.
-- Отдельной строкой — новый дизъюнкт в тексте условия: сам факт существования CHECK с прежним
-- именем ничего не доказывает, ведь имя мы и переиспользовали.

DO $$
DECLARE trouble text;
BEGIN
  SELECT string_agg(msg, '; ')
    INTO trouble
    FROM (
      SELECT format('обязательных колонок журнала на месте %s из 3', count(*)) AS msg
        FROM pg_attribute
       WHERE attrelid = 'office_equipment_movements'::regclass
         AND NOT attisdropped
         AND attnotnull
         AND attname IN ('from_state_note', 'to_state_note', 'confirms_declared_place')
      HAVING count(*) <> 3
      UNION ALL
      SELECT format('условие «что-то изменилось» не знает про уточнение места (проверенных: %s)',
                    count(*))
        FROM pg_constraint
       WHERE conrelid = 'office_equipment_movements'::regclass
         AND conname = 'office_equipment_movements_change_check'
         AND contype = 'c'
         AND convalidated
         AND pg_get_constraintdef(oid) LIKE '%from_state_note%'
      HAVING count(*) <> 1
      UNION ALL
      SELECT 'частичного индекса подтверждений нет'
       WHERE NOT EXISTS (
         SELECT 1 FROM pg_indexes
          WHERE tablename = 'office_equipment_movements'
            AND indexname = 'office_equipment_movements_confirms_idx')
    ) AS bad;
  IF trouble IS NOT NULL THEN
    RAISE EXCEPTION 'Журнал перемещений собран не так, как объявлено — %', trouble;
  END IF;
END $$;
