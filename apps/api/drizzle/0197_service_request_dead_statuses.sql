-- Мёртвые статусы заявки оргтехники: перевод остатка и запрет заводить новые. Миграция M8 плана
-- переработки заявок (`docs/office-equipment-requests-rework-plan.md`, §5), выпуск 2 «Contract».
--
-- ЧТО ЗАКРЫВАЕТ. Решение 1 ADR 0133 убрало из цикла два состояния: `it_approved` («Согласована ИТ»)
-- — виза ИТ уехала со входа заявки на смету, и отдельного статуса под неё больше нет; `diagnostics`
-- («Диагностика») — то же самое состояние, что «В работе», названное у ремонта вторым именем.
-- Выпуск 1 перестал их СОЗДАВАТЬ и научился их ЧИТАТЬ; этот выпуск переводит остаток и закрывает
-- дверь совсем.
--
-- ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ВЫПУСК, А НЕ ЧАСТЬ ПЕРВОГО (§3). Штатный деплой накатывает миграции ДО
-- перезапуска сервисов, и между этими двумя моментами на новой схеме работает СТАРЫЙ код — тот,
-- что ставит визу ИТ на входе и пишет `it_approved`. Ограничение ниже, поставленное в выпуске 1,
-- отвечало бы ему ошибкой БД посреди рабочего дня.
--
-- РЕШЕНИЕ ЗАКАЗЧИКА 24.08.2026: выпуски 1, 2 и 3 катятся ОДНИМ накатом. Основание — в боевой базе
-- по модулю одна тестовая заявка, переводить нечего, а окно выката проходит в согласованное время,
-- когда модулем никто не пользуется. Риск окна назван и принят: пока сервисы не перезапущены,
-- старый код на визе ИТ и на приёмке получит отказ базы. Плата за слияние — невозможность отката
-- кода назад: на contract-схеме старый код не работает вовсе.
--
-- УСЛОВИЕ §11.3 ПРИ ЭТОМ ВЫПОЛНЕНО ПО ПОСТРОЕНИЮ, А НЕ ПО НАБЛЮДЕНИЮ. План требовал недели без
-- единого перехода в мёртвый статус — как страховки от забытой ветки нового кода. Ветки
-- пересчитаны машинно: целевых статусов у шести коридоров (`packages/contracts/src/service-requests.ts`)
-- восемь, и ни `it_approved`, ни `diagnostics` среди них нет; все 24 упоминания этих значений в
-- коде — чтение, ни одной записи. Новый код завести мёртвый статус не может, и неделя наблюдения
-- не добавила бы к этому знанию ничего.

-- ── 1. Перевод остатка ──
--
-- «Согласована ИТ» была шагом ПЕРЕД распределением, и её содержательный эквивалент сегодня —
-- «Новая»: заявка ждёт того, кто назначит исполнителей. «Диагностика» — шаг ПОСЛЕ распределения,
-- её эквивалент — «В работе»: исполнитель уже взялся.
UPDATE service_requests SET status = 'new'     WHERE status = 'it_approved';
UPDATE service_requests SET status = 'in_work' WHERE status = 'diagnostics';

-- Заморозка: значения ПРЕОБРАЗУЮТСЯ, а не очищаются. `service_requests_hold_check` требует
-- непустой `held_from_status` у заявки в `on_hold`, и `NULL` здесь уронил бы саму миграцию.
-- Отложенная заявка помнит, откуда её отложили, и вернуться обязана в живой статус.
UPDATE service_requests SET held_from_status = 'new'     WHERE held_from_status = 'it_approved';
UPDATE service_requests SET held_from_status = 'in_work' WHERE held_from_status = 'diagnostics';

-- История переходов НЕ ПЕРЕПИСЫВАЕТСЯ. Строка «Новая → Согласована ИТ» от 12.08 — правда о том,
-- что тогда произошло, и заявка, прошедшая через визу на входе, обязана это показывать. Журнал
-- переходов — свидетельство, а не текущее состояние; переписанный, он соврал бы о прошлом. Тем же
-- журналом проверяется условие §11.3, и подчищенный он лишил бы проверку предмета.

-- ── 2. Дверь ──
--
-- Перевод без запрета — половина работы: значения остаются в типе, и любой прямой `UPDATE`, скрипт
-- обслуживания или забытая legacy-ветка вернут заявку в мёртвый статус, а прочитать его новый
-- портал уже не умеет.
--
-- Значения enum при этом НЕ УДАЛЯЮТСЯ. `ALTER TYPE … DROP VALUE` в Postgres не существует, а
-- пересоздание типа означает переписывание всех зависимостей — колонок, `CHECK`ов, индексов,
-- функций — при нулевом выигрыше: место в типе ничего не стоит. Прецедент — `due_date` после
-- ADR 0125: колонка осталась, а логика с неё снята. Дверь закрывает `CHECK`, а не отсутствие
-- значения.
ALTER TABLE service_requests ADD CONSTRAINT service_requests_dead_status_check CHECK (
  status NOT IN ('it_approved','diagnostics')
  AND (held_from_status IS NULL OR held_from_status NOT IN ('it_approved','diagnostics'))
);

COMMENT ON CONSTRAINT service_requests_dead_status_check ON service_requests IS
  'Мёртвые статусы цикла (решение 1 ADR 0133): «Согласована ИТ» и «Диагностика» из цикла убраны, '
  'значения остались в enum только потому, что DROP VALUE в Postgres нет. Заводить их нельзя ни '
  'заявке, ни её заморозке.';
