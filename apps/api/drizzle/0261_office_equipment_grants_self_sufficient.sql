-- Наборы модуля «Орг.техника» становятся самодостаточными: чтение своего модуля и ведение заявки
-- уезжают из базовой роли в состав набора (план `docs/office-equipment-access-profiles-plan.md`,
-- решение Р4, находка Н4; этап Э4 — «аддитивный предшественник»).
--
-- ОТКУДА НОМЕР. Проверено `ls apps/api/drizzle` непосредственно перед созданием файла (03.09.2026,
-- вечер): последняя миграция в дереве — `0260_releases_service_request_requester_card.sql` соседнего
-- потока (карточка заявки по аудиториям). Свободен 0261. Утром того же дня этот план записал в свой
-- §14 «следующий свободный 0257» — и к вечеру 0257–0260 заняли два соседних потока. Номер поэтому
-- берётся в момент создания файла, а не резервируется заранее: снимок свободного номера живёт часы.
--
-- ЗАЧЕМ. Ни один набор модуля не давал чтения того, чем управляет: «Ведение» открывало
-- `officeEquipment.write` без `.read` и решения по заявке без её чтения, «ИТ-служба» —
-- `serviceRequests.execute` без `.read`. Работало это не по замыслу, а потому, что совместимых
-- базовых ролей ровно три (`ROLE_ADDON_BASE_ROLES`: штаб, площадка, отдел) и у каждой чтение есть
-- по матрице. То есть состав набора держался на совпадении с ролью, и у этого три последствия,
-- каждое из которых уже стоило бы отдельного разбора:
--
--   1. набор нельзя выдать роли без прав модуля — а именно это делает этап Э6 плана, расширяя
--      `grant_roles` на менеджера и диспетчера (они видят справочник оргтехники по роли, но не
--      имеют ни одного `serviceRequests.*`);
--   2. барьер требований (`PERMISSION_REQUIRES`, миграции реформы ADR 0106) проверял не то, что
--      кажется: он считает по ИТОГУ учётки, и требование «действие над заявкой требует её чтения»
--      выполнялось базовой ролью, а не набором;
--   3. снятие права из роли молча выключило бы половину набора — без единой правки самого набора.
--
-- ЧТО ДОБАВЛЯЕТСЯ. «Ведению» шесть прав: чтение справочника и полный круг заказчика по заявке
-- (`read`, `create`, `update`, `delete`, `files`) — ровно то, чем оно и так пользуется каждый день
-- от базовой роли. «ИТ-службе» три: чтение справочника, чтение заявок и заведение. Последнее — не
-- симметрия ради симметрии: `PERMISSION_REQUIRES` объявляет `serviceRequests.createWithoutEquipment`
-- (оно у ИТ-службы есть) зависимым именно от `serviceRequests.create`, потому что ручка у права
-- чужая — `POST /service-requests`, — и набор без заведения обещал бы то, чего сервер не пустит.
--
-- ДОСТУП НЕ РАСШИРЯЕТСЯ НИ У ОДНОГО ДЕРЖАТЕЛЯ, и это проверяемое утверждение, а не обещание. Все
-- девять дописываемых прав даёт любая из трёх совместимых ролей, а источники прав соединены `OR`
-- (инвариант модели: «отобрать» означает «не выдать»). Пустоту разницы эффективных прав по каждой
-- паре «роль + набор» доказывает `apps/api/test/grants-contracts.test.ts`; здесь же, на накате,
-- сходится караул состава ниже.
--
-- ЧЕГО ЗДЕСЬ НЕТ — и это границы этапа, а не недоделка:
--   · ни одной строки `user_grants`: миграция правит каталог, а кому набор достанется, решает
--     администратор поимённо, с автором и временем (ADR 0106);
--   · ни одного изменения `grant_roles`: расширение совместимых ролей — этап Э6, и едет он отдельным
--     выпуском, потому что это единственный этап плана, расширяющий доступ;
--   · ни одного `DELETE` из состава: `serviceRequests.execute`, `.files` и мёртвое `.approveIt`
--     остаются у ИТ-службы. Первые два уезжают в набор `office_equipment_executor` этапом Э6 —
--     атомарно, с backfill'ом действующим держателям, иначе разделение отобрало бы у них работу
--     исполнителя в момент выката; третье снимает этап Э9, и только после того, как сторона `it` в
--     обсуждении перестанет опознаваться этим правом (это уже сделано этапом Э3);
--   · ни одной правки описаний наборов: описание перечисляет, что набор УМЕЕТ, а умений не
--     прибавилось — прибавилась независимость состава от роли. Соседняя миграция 0259 описания как
--     раз переписала под право видеть деньги, и дублировать её текст здесь незачем.
--
-- КОДЫ НАБОРОВ НЕ МЕНЯЮТСЯ НИКОГДА: по коду набор находят миграции каталога, журнал действий,
-- реестр выдач и таблица сквозной области (`GRANT_MODULE_WIDE_SCOPE`). Наборы поэтому ищутся по
-- коду и здесь.
--
-- ГДЕ ЖИВЁТ ОБЪЯВЛЕННЫЙ СОСТАВ. У обоих наборов — в `ROLE_ADDON_PERMISSIONS`
-- (`packages/contracts/src/permissions.ts`): надстройка ADR 0086 остаётся живым источником доступа
-- до шага 1e реформы, и набор в базе — её отражение. Правка контрактов едет ТОЙ ЖЕ волной, что эта
-- миграция, и это обязательное условие, а не порядок удобства: разъехавшись, они дали бы одному
-- человеку разные права в зависимости от того, пришёл к нему доступ надстройкой или набором. Обе
-- стороны сверяет страж `apps/api/test/grants-catalog.db.test.ts`.
--
-- ОБРАТИМОСТЬ. Трогается одна таблица каталога, схема не меняется; протокол выката необратимых
-- миграций (`docs/schema-cutover-protocol.md`) к ней не применяется. Откат — `DELETE` девяти строк
-- состава. Откатывать её в одиночку безопасно: права, которые она добавляет, держатели имеют и от
-- базовой роли, поэтому откат каталога никому ничего не закрывает.

-- ── Состав: девять строк, обоим наборам ──
--
-- Право хранится текстом — справочника прав в базе нет намеренно (`grant_permissions`, миграция
-- 0145): словарь `PERMISSIONS` закрыт и живёт в контрактах. `ON CONFLICT DO NOTHING` делает шаг
-- идемпотентным, а не «на всякий случай»: повторный накат на базу, восстановленную из копии, —
-- обычное дело; того же требовала от будущих миграций каталога и соседняя 0259.

INSERT INTO grant_permissions (grant_id, permission)
SELECT g.id, s.permission
FROM grants g
JOIN (VALUES
  ('office_equipment_operator'   , 'officeEquipment.read'),
  ('office_equipment_operator'   , 'serviceRequests.read'),
  ('office_equipment_operator'   , 'serviceRequests.create'),
  ('office_equipment_operator'   , 'serviceRequests.update'),
  ('office_equipment_operator'   , 'serviceRequests.delete'),
  ('office_equipment_operator'   , 'serviceRequests.files'),
  ('office_equipment_it_approver', 'officeEquipment.read'),
  ('office_equipment_it_approver', 'serviceRequests.read'),
  ('office_equipment_it_approver', 'serviceRequests.create')
) AS s (code, permission) ON s.code = g.code
ON CONFLICT (grant_id, permission) DO NOTHING;

-- ── Караул: состав в базе равен объявленному ──
--
-- Страж-тест сверяет то же самое, но живёт он в репозитории, а этот блок — в накате: оператор выката
-- увидит расхождение сразу, а не через прогон тестов. Проверяется ровно то, что миграция обещала:
-- оба набора существуют и системны, прав в «Ведении» пятнадцать (девять после миграции 0259 плюс
-- шесть здесь), в «ИТ-службе» десять (семь плюс три), и чтение своего модуля есть у обоих. Счёт
-- ведётся ПОСЛЕ вставки, поэтому повторный накат проходит его так же, как первый.
--
-- Числа записаны от состояния 0259 намеренно — она сама об этом и просила: «счёт прав в обоих
-- наборах вести от девяти и семи». Следующая миграция каталога обязана вести его от пятнадцати и
-- десяти, а не выводить из головы, — и обязана помнить, что Э6 из ИТ-набора ДВА права снимает.
-- Строк `user_grants` блок не считает: наборы живые, и держатели у них — обычное дело.
DO $$
DECLARE trouble text;
BEGIN
  SELECT string_agg(msg, '; ')
    INTO trouble
    FROM (
      SELECT format('наборов нет или они не системные (найдено строк: %s вместо двух)', count(*))
             AS msg
        FROM grants
       WHERE code IN ('office_equipment_operator', 'office_equipment_it_approver')
         AND is_system AND deleted_at IS NULL
      HAVING count(*) <> 2
      UNION ALL
      SELECT format('%s: прав %s вместо %s, чтение модуля среди них: %s',
                    g.code,
                    count(gp.permission),
                    CASE g.code WHEN 'office_equipment_operator' THEN 15 ELSE 10 END,
                    CASE WHEN count(gp.permission) FILTER (
                           WHERE gp.permission IN ('officeEquipment.read',
                                                   'serviceRequests.read')) = 2
                         THEN 'да' ELSE 'нет' END)
        FROM grants g
        LEFT JOIN grant_permissions gp ON gp.grant_id = g.id
       WHERE g.code IN ('office_equipment_operator', 'office_equipment_it_approver')
       GROUP BY g.code
      HAVING (g.code = 'office_equipment_operator'    AND count(gp.permission) <> 15)
          OR (g.code = 'office_equipment_it_approver' AND count(gp.permission) <> 10)
          OR count(gp.permission) FILTER (
               WHERE gp.permission IN ('officeEquipment.read', 'serviceRequests.read')) <> 2
    ) AS bad;
  IF trouble IS NOT NULL THEN
    RAISE EXCEPTION 'Наборы оргтехники собраны не так, как объявлены — %', trouble;
  END IF;
END $$;
