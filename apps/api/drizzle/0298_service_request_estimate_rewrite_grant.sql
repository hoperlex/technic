-- Право `serviceRequests.estimateRewrite` в каталоге полномочий: раскладка свободного объёма работ
-- по графам уходит набору «Оргтехника: ведение» (`office_equipment_operator`) и больше никому
-- (план `docs/office-equipment-free-estimate-and-executor-scope-plan.md`, Р2, этап Э3; выпуск A
-- по §8).
--
-- ОТКУДА НОМЕР. `ls apps/api/drizzle` непосредственно перед созданием файла (10.09.2026): последним
-- в дереве стоит `0297_office_equipment_candidate_intake_enable.sql` — включение приёма сообщений о
-- технике соседней волны, — незакоммиченных миграций у параллельных потоков в дереве нет. Свободен
-- 0298, он и взят. Номер берётся в момент создания КАЖДОГО файла и не резервируется на волну
-- вперёд: за один день 04.09.2026 план кандидата дважды потерял зарезервированный номер ровно так,
-- а 0261 рассказывает про утренний снимок, совравший к вечеру.
--
-- ЗАЧЕМ ОТДЕЛЬНОЕ ПРАВО, А НЕ `serviceRequests.estimate`. Свободный объём работ (одна строка:
-- перечень текстом плюс общая стоимость) заказчик просит потом переносить в графы — «позже
-- переносится в графы ведением». Делает это НЕ исполнитель: у «Ведения» нет сегодня ни
-- `serviceRequests.estimate`, ни `.execute`, и объём работ оно не правит вовсе — оно его
-- СОГЛАСУЕТ (`serviceRequests.approveEstimate` в составе набора). Выдать ему `estimate` значило бы
-- отдать тому же человеку и написание сметы, и подпись под ней — то есть превратить согласование в
-- подпись под собственной работой; состав набора этот запрет держит прямым комментарием в
-- `ROLE_ADDON_PERMISSIONS`. Поэтому дверь узкая: она открывает ровно раскладку уже собранного
-- перечня по графам (`PUT /:id/estimate/breakdown`), а не написание сметы с нуля.
--
-- ЧТО ЭТО ПРАВО ОТКРЫВАЕТ ФАКТИЧЕСКИ, СКАЗАНО ВСЛУХ — потому что третья ветвь ручки трогает
-- ПОДПИСАННОЕ. Инвариант модуля (ADR 0133) неизменен: содержимое согласованной ревизии под прежним
-- номером не меняется. Раскладка согласованного объёма работ поэтому поднимает ревизию, снимает
-- снимок согласования, пересчитывает итог по строкам и ставит новое предъявление — заявка ждёт
-- НОВОЙ подписи (развилка В9). Это равно «reopen + правка + предъявление» одной кнопкой; ни
-- `reopen`, ни `submit` держателю набора при этом не выдаются — их и незачем: обе половины делает
-- сама ручка, и делает их атомарно.
--
-- ТРЕБОВАНИЕ БАРЬЕРА. `PERMISSION_REQUIRES` объявляет `estimateRewrite` зависимым от
-- `serviceRequests.read`, и оно выполняется составом самого набора (`serviceRequests.read` уехало
-- туда миграцией 0261, когда наборы модуля стали самодостаточными), а не базовой ролью держателя.
-- Набор остаётся выдаваемым тем же ролям, что и вчера, и невыдаваемым не становится ни для одной.
--
-- ЧЕГО МИГРАЦИЯ НЕ ДЕЛАЕТ.
--
--   · НЕ СОЗДАЁТ И НЕ ОТЗЫВАЕТ НИ ОДНОЙ СТРОКИ `user_grants`: миграция правит каталог, а кому набор
--     достанется — решение администратора, принимаемое поимённо, с автором и временем (ADR 0106).
--     Караул ниже проверяет это утверждением, а не намерением: число держателей сверяется со
--     снимком «до»;
--   · НЕ ТРОГАЕТ РОЛИ — ни `ROLE_PERMISSIONS` (матрица живёт в коде и приезжает выкатом сервера),
--     ни `grant_roles` (совместимые роли набора эта волна не меняет). Администратор получает право
--     полным словарём (`admin: [...PERMISSIONS]`), и строки в базе ему не нужно;
--   · НЕ РАЗДАЁТ ПРАВО «по содержимому» держателям соседних наборов, в отличие от миграции 0275.
--     Там право ВЫДЕЛЯЛОСЬ из `officeEquipment.write`, и не раздай его миграция каждому, у кого
--     ведение уже есть, выкат отобрал бы работающую операцию. Здесь дверь новая: до этой строки
--     раскладки не существовало вовсе, и отбирать нечего;
--   · НЕ МЕНЯЕТ СХЕМУ. Свободная запись едет обычной строкой сметы (`kind = 'service'`,
--     `quantity = 1`, цена — общая стоимость), колонка `service_request_items.name` — `text` без
--     ограничения длины, и предел в 2000 символов живёт в контрактах. Миграции под свободный ввод
--     волне не нужно вовсе.
--
-- ГДЕ ЖИВЁТ ОБЪЯВЛЕННЫЙ СОСТАВ: `ROLE_ADDON_PERMISSIONS` в `packages/contracts/src/permissions.ts`
-- (надстройка ADR 0086 остаётся живым источником доступа до шага 1e реформы). Правка контрактов
-- едет ТОЙ ЖЕ волной, что эта миграция, и это условие, а не порядок удобства: разъехавшись, они
-- дали бы одному человеку разные права в зависимости от того, каким источником пришёл доступ. Обе
-- стороны сверяет страж `apps/api/test/grants-catalog.db.test.ts`.
--
-- ОБРАТИМОСТЬ. Схема не меняется, трогается одна таблица каталога одной строкой. Откат — `DELETE`
-- строки с `permission = 'serviceRequests.estimateRewrite'` у этого набора, и делать его нужно
-- ВМЕСТЕ с откатом контрактов, иначе страж каталога покраснеет на расхождении. Право без ручки и
-- ручка без права одинаково безопасны: `can()` отвечает отказом на неизвестное право, а ручка при
-- откате приложения исчезает целиком.

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 0. Снимок числа держателей ДО правки — ради утверждения «миграция правит состав, а не выдачи».
--
-- `ON COMMIT DROP`: таблица живёт до конца транзакции миграции и в базе не остаётся. Снимок нужен
-- именно снимком, а не константой «столько-то»: набор выдают живым учёткам, и число «до» на проде,
-- в деве и на восстановленной из копии базе разное, а утверждение одно (приём миграции 0294).

CREATE TEMP TABLE grant_holders_0298 ON COMMIT DROP AS
SELECT g.code, count(*)::bigint AS holders
FROM user_grants ug
JOIN grants g ON g.id = ug.grant_id
WHERE g.code = 'office_equipment_operator'
GROUP BY g.code;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 1. Раскладка по графам — «Ведению», и только ему.
--
-- Право хранится текстом: справочника прав в базе нет намеренно (`grant_permissions`, миграция
-- 0145), словарь `PERMISSIONS` закрыт и живёт в контрактах. Набор ищется по коду — коды стабильны
-- навсегда, по ним его находят миграции каталога, журнал действий и реестр выдач.
-- `ON CONFLICT DO NOTHING` делает шаг идемпотентным: повторный накат на базу, восстановленную из
-- копии, — обычное дело, и миграция обязана довести каталог до объявленного состояния, а не упасть.

INSERT INTO grant_permissions (grant_id, permission)
SELECT g.id, 'serviceRequests.estimateRewrite'
FROM grants g
WHERE g.code = 'office_equipment_operator'
ON CONFLICT (grant_id, permission) DO NOTHING;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 2. Караул: составы после правки, замок «и больше никому» и неприкосновенность выдач.
--
-- Страж-тест сверяет каталог с контрактами, но живёт он в репозитории, а этот блок — в накате:
-- оператор выката увидит расхождение сразу, а не через прогон тестов. Считается ПОСЛЕ вставки,
-- поэтому повторный накат проходит его так же, как первый.
--
-- Числа продолжают счёт миграции 0294 (там было 17, 8, 3 и 7) и проверены по составу в контрактах
-- перед написанием файла: в «Ведении» ВОСЕМНАДЦАТЬ прав (семнадцать плюс одно здесь), в «ИТ-службе»
-- по-прежнему ВОСЕМЬ, у исполнителя ТРИ, у «Заявителя» СЕМЬ. СЛЕДУЮЩАЯ МИГРАЦИЯ КАТАЛОГА обязана
-- вести счёт от этих четырёх чисел, а не выводить его из головы.
--
-- Три соседних набора проверяются числом именно затем, что этот файл их не трогает вовсе:
-- утверждение здесь ровно одно — «столько же, сколько было».
--
-- Замок «и больше никому» проверяется отдельной строкой и по СИСТЕМНЫМ наборам: собранных
-- администратором наборов запрет не касается — модель ADR 0106 позволяет положить право в
-- собранный набор, а барьер требований примет его только вместе с чтением заявок в итоговых правах
-- учётки.

DO $$
DECLARE trouble text;
BEGIN
  SELECT string_agg(msg, '; ')
    INTO trouble
    FROM (
      SELECT format('системных наборов модуля найдено %s вместо четырёх', count(*)) AS msg
        FROM grants
       WHERE code IN ('office_equipment_operator', 'office_equipment_it_approver',
                      'office_equipment_executor', 'office_equipment_requester')
         AND is_system AND deleted_at IS NULL
      HAVING count(*) <> 4
      UNION ALL
      SELECT format('%s: прав %s вместо %s', g.code, count(gp.permission), e.expected)
        FROM grants g
        JOIN (VALUES
          ('office_equipment_operator', 18),
          ('office_equipment_it_approver', 8),
          ('office_equipment_executor', 3),
          ('office_equipment_requester', 7)
        ) AS e (code, expected) ON e.code = g.code
        LEFT JOIN grant_permissions gp ON gp.grant_id = g.id
       GROUP BY g.code, e.expected
      HAVING count(gp.permission) <> e.expected
      UNION ALL
      SELECT 'в наборе «office_equipment_operator» нет права «serviceRequests.estimateRewrite» — '
             || 'вставка не сработала'
       WHERE NOT EXISTS (
         SELECT 1
           FROM grants g
           JOIN grant_permissions gp ON gp.grant_id = g.id
          WHERE g.code = 'office_equipment_operator'
            AND gp.permission = 'serviceRequests.estimateRewrite')
      UNION ALL
      SELECT format('раскладка по графам оказалась в системном наборе «%s» — замок волны сорван',
                    g.code)
        FROM grants g
        JOIN grant_permissions gp ON gp.grant_id = g.id
       WHERE gp.permission = 'serviceRequests.estimateRewrite'
         AND g.is_system
         AND g.code <> 'office_equipment_operator'
      UNION ALL
      SELECT format('держателей набора «office_equipment_operator» стало %s вместо %s: '
                    || 'правится состав, а не выдачи',
                    (SELECT count(*) FROM user_grants ug
                       JOIN grants g ON g.id = ug.grant_id
                      WHERE g.code = 'office_equipment_operator'),
                    coalesce((SELECT h.holders FROM grant_holders_0298 h
                               WHERE h.code = 'office_equipment_operator'), 0))
       WHERE (SELECT count(*) FROM user_grants ug
                JOIN grants g ON g.id = ug.grant_id
               WHERE g.code = 'office_equipment_operator')
             <> coalesce((SELECT h.holders FROM grant_holders_0298 h
                           WHERE h.code = 'office_equipment_operator'), 0)
    ) AS bad;
  IF trouble IS NOT NULL THEN
    RAISE EXCEPTION 'Право раскладки объёма работ разложено по наборам не так, как объявлено — %',
                    trouble;
  END IF;
END $$;
