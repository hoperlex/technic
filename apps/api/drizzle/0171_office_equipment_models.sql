-- Модели аппаратов оргтехники, выпуск A — expand (план `docs/office-equipment-consumables-plan.md`,
-- §5 «Выпуск A»; этап 1, волна В1).
--
-- ЗАЧЕМ. Картридж подходит МОДЕЛИ, а не конкретному аппарату: «Тонер Ricoh 201» одинаково годится
-- всем 68 карточкам Ricoh Aficio MP 201SPF и любой 69-й, которую заведут завтра (Р1). Пока модель
-- живёт строкой в карточке, ответить на вопрос «чем заправить вот этот аппарат» можно только
-- поиском по подстроке — то есть промахиваться на каждом «Ricon», «НР» с кириллической Н и
-- «Aficio MP 301SP» против «301SPF». Разнописание в этом парке уже случалось: сид `0143` отдельно
-- выправлял кириллические двойники в шести строках и латиницу в серийных номерах в двадцати
-- четырёх. Поэтому модель становится записью справочника, а `office_equipment.name` — её копией.
--
-- ЧТО ЗАВОДИТСЯ: таблица `office_equipment_models`, ссылка `office_equipment.model_id`, составной
-- ключ «тип модели равен типу карточки», две IMMUTABLE-функции правила написания (по ним модель
-- опознаётся во всех пяти местах сразу) и два триггера, которые держат копию имени и разбирают
-- запись старым кодом.
--
-- ПОЧЕМУ ССЫЛКА NULLABLE (Р2). `deploy-auto` накатывает миграции ДО перезапуска, и в этом окне
-- живой старый код вставляет карточку без `model_id` — `routes/office-equipment.ts` пишет только
-- `name`. `NOT NULL` в этом выкате означал бы, что всё окно выката не заводится ни одна единица
-- техники и не проходит ни одна заливка файлом, а причиной в ответе было бы имя ограничения.
-- Поэтому переход разведён на три выпуска: A расширяет (эта миграция), B закрывает `NOT NULL`
-- следующим релизом, C снимает legacy-ветку резолва. Приём в репозитории отработан: `0072`
-- добавила рейсы, ничего не убирая, а лишнее сняла `0074`.
--
-- ПОРЯДОК ШАГОВ ВНУТРИ МИГРАЦИИ ОБЯЗАТЕЛЕН и объясняется на каждом шаге ниже. Коротко: миграция
-- идёт одной транзакцией (`src/db/migration-journal.ts`), и снимок парка обязан читаться уже под
-- блокировкой. Переставишь шаги — миграция сломается не сразу, а на глазах у оператора выката.
--
-- ОБРАТИМОСТЬ. Миграция аддитивная: новая таблица, новая nullable-колонка, два триггера.
-- Существующие данные не теряются, `name` не удаляется ни здесь, ни в B, ни в C — она остаётся
-- зеркалом модели, и девять её нынешних читателей работают как работали. Протокол выката
-- необратимых миграций (`docs/schema-cutover-protocol.md`) к ней не применяется.

-- ── 1. Блокировка и колонка ──
--
-- `LOCK TABLE` первой строкой (Р2). Ту же блокировку `ALTER TABLE ... ADD COLUMN` взял бы и сам, но
-- полагаться на побочный эффект в файле, который будут править через год, не стоит: эта строка
-- говорит следующему автору, что перестановка шагов ломает миграцию. А ломает она так: между
-- снимком парка и блокировкой старый код успевает завести карточку с моделью, которой в снимке
-- нет, — backfill оставит ей `NULL`, и караул ниже отменит всю миграцию.
--
-- ACCESS EXCLUSIVE, а не что-то мягче: снимок парка должен быть согласован не только со вставками,
-- но и с правкой имени в уже существующей карточке — иначе модель заведётся по старому написанию,
-- а карточка уедет на новое, и backfill опять оставит `NULL`.
LOCK TABLE office_equipment IN ACCESS EXCLUSIVE MODE;

-- Nullable — это и есть выпуск A. `NOT NULL` ставит выпуск B, когда код A уже стоит в проде и
-- проставляет ссылку всегда (руками триггера ниже, а не сам).
ALTER TABLE office_equipment ADD COLUMN model_id uuid;

-- ── 2. Справочник моделей ──
--
-- Модель существует НЕЗАВИСИМО ОТ ПАРКА: в присланном списке расходников есть картриджи для
-- Xerox Phaser 3250, Samsung Xpress SL-M2020 и Ricoh Aficio MP W2401, которых в портале нет вовсе.
-- Требовать «сначала заведите аппарат» было бы отказом внести то, что уже лежит на складе.
--
-- ПРАВИЛО НАПИСАНИЯ — ДВЕ IMMUTABLE-ФУНКЦИИ, А НЕ ПОВТОРЁННОЕ ВЫРАЖЕНИЕ. Одно и то же правило
-- нужно в пяти местах: уникальный индекс, разбор парка, backfill, поиск модели в триггере и
-- `ON CONFLICT` там же. Написанное выражением, оно живёт пятью копиями, и первая же правка
-- расходится: индекс продолжает считать «Ricoh␣␣IM 350» и «Ricoh IM 350» одной моделью, а резолв
-- перестаёт её находить — и заводит вторую, которую индекс тут же отвергает. Приём в портале уже
-- принят: наименования контрагентов и адреса складов нормализует общая
-- `counterparty_name_normalize` (0022, 0077) — «вторая функция с той же логикой разошлась бы с
-- первой».
--
-- Функций две, потому что правил тоже два, и путать их нельзя:
--
--   `office_equipment_model_name_normalize` — как модель ПИШЕТСЯ: края обрезаны, любая череда
--     пробельных символов свёрнута в один пробел. Регистр не трогается — «ECOSYS» и «i-Sensys»
--     фирменные написания, и приводить их к одному виду означало бы портить справочник;
--   `office_equipment_model_key` — по чему модель ОПОЗНАЁТСЯ: то же написание в верхнем регистре.
--
-- Почему схлопывание, а не `btrim`: `btrim` снимает только края, и «Ricoh␣␣IM 550F» с двойным
-- внутренним пробелом заводит вторую строку справочника — не разово при разборе, а навсегда, потому
-- что правило живёт в уникальном индексе. Глазами эти две строки не различить, а расходник
-- привяжут к одной из них.
--
-- ПОРЯДОК ВНУТРИ `office_equipment_model_name_normalize` ОБЯЗАТЕЛЕН: сначала схлопывание, потом
-- обрезка краёв. Обратный порядок кажется тем же самым, но `btrim` без второго аргумента снимает
-- ТОЛЬКО пробелы — краевой таб или перевод строки он не трогает, а схлопывание после него делает
-- из них краевой пробел, убирать который уже некому. Функция перестаёт быть идемпотентной, и это
-- не теория: `CHECK` ниже отверг бы её собственный результат, то есть маршрут, нормализовавший ввод
-- ровно как велено, получил бы отказ; а разбор парка (шаг 3) зовёт эту же функцию — одного имени
-- карточки с краевым табом хватило бы, чтобы отменить весь накат на глазах у оператора выката.
--
-- ПОЧЕМУ КЛАСС ШИРЕ, ЧЕМ `\s`. `\s` в Postgres опирается на ctype локали базы, и НЕРАЗРЫВНЫЕ
-- пробелы он пробелами НЕ считает (проверено на `en_US.utf8`, PostgreSQL 16): ни U+00A0, ни узкий
-- U+202F. А приезжают они постоянно — Word ставит U+00A0 автозаменой и по Ctrl+Shift+Space, Excel
-- отдаёт его же в выгрузках, а свежие сборки Windows разделяют разряды узким U+202F. Обмен файлом
-- (ADR 0073) кормит справочник ровно из этих документов.
--
-- Без них «Ricoh<NBSP>IM 350» и «Ricoh IM 350» дают РАЗНЫЕ ключи, уникальный индекс пропускает обе
-- строки, и человек видит в списке две одинаковых модели, не понимая, какая настоящая; картриджи
-- привяжутся к одной из них наугад. Невидимый двойник хуже отказа, поэтому оба неразрывных пробела
-- схлопываются наравне с обычным.
--
-- Чего в классе НЕТ и почему: символы нулевой ширины (U+200B, U+FEFF) и мягкий перенос (U+00AD)
-- пробелами не являются — они отмечают место возможного переноса ВНУТРИ слова. Схлопни их в
-- пробел, и «Ricoh<U+00AD>IM» превратится в «Ricoh IM», то есть правило само испортит
-- наименование. Такой символ оставляется как есть и даёт свою модель: это редкость, и лучше
-- лишняя строка, чем тихо изменённое имя. Прочие типографские пробелы (U+2009, U+2002, U+3000)
-- добавлять не нужно — их `\s` в этой локали ловит сам.
--
-- Записаны символы escape-последовательностями `\uXXXX`, которые понимает регулярное выражение
-- Postgres, а не собой: невидимый байт в тексте миграции нельзя вычитать на ревью, и любой
-- редактор способен его потерять или заменить.
--
-- `IMMUTABLE` — требование индекса по выражению: значение обязано зависеть только от аргумента,
-- иначе индекс укажет не туда. Отсюда же и цена: `CREATE OR REPLACE` этих функций молча меняет
-- смысл индекса и обеих проверок ниже, а уже построенный индекс остаётся считать по-старому.
-- Менять правило можно только миграцией, которая перестраивает индекс и заново сводит справочник.
CREATE FUNCTION office_equipment_model_name_normalize(t text) RETURNS text
  LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE
AS $$
  SELECT btrim(regexp_replace(t, '[\s\u00a0\u202f]+', ' ', 'g'))
$$;

CREATE FUNCTION office_equipment_model_key(t text) RETURNS text
  LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE
AS $$
  SELECT upper(office_equipment_model_name_normalize(t))
$$;

COMMENT ON FUNCTION office_equipment_model_name_normalize(text) IS
  'Как модель ПИШЕТСЯ (docs/office-equipment-consumables-plan.md Р4): любая череда пробельных '
  'символов, включая неразрывные, сворачивается в один пробел, края обрезаются, регистр не '
  'трогается. Порядок внутри обязателен — сначала свёртка, потом обрезка, иначе краевой таб '
  'превратился бы в краевой пробел и функция перестала бы быть идемпотентной.';

COMMENT ON FUNCTION office_equipment_model_key(text) IS
  'По чему модель ОПОЗНАЁТСЯ: написание в верхнем регистре. Одна и та же функция стоит в уникальном '
  'индексе office_equipment_models_name_unique, в разборе парка, в backfill и в резолве триггера '
  'office_equipment_model_mirror (включая ON CONFLICT, где выражение обязано совпасть с индексным). '
  'IMMUTABLE ради индекса по выражению: правка функции меняет смысл индекса, но не его содержимое.';

CREATE TABLE office_equipment_models (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Тип обязателен и неизменяем: он половина ключа уникальности и половина «замка» ниже.
  equipment_type_id uuid NOT NULL REFERENCES office_equipment_types (id) ON DELETE RESTRICT,
  -- Наименование модели — «Ricoh Aficio MP 201SPF». Это то же самое, что сегодня лежит в
  -- `office_equipment.name`, только в одном экземпляре на все карточки модели.
  name text NOT NULL,
  -- Производитель отдельным полем, потому что спрашивать его будут отдельно («все Ricoh»), а
  -- вытаскивать первым словом из наименования — гадание: «HP LaserJet» и «Hewlett-Packard» первым
  -- словом не совпадают. Пусто по умолчанию и пусто у всего, что заведёт разбор парка ниже:
  -- миграция не выдумывает то, чего в источнике нет, — производителя проставит ИТ-служба руками.
  manufacturer text NOT NULL DEFAULT '',
  -- Модель, которую больше не покупают, гасят флагом, а не удаляют (Р11): у неё остаются карточки
  -- в парке и, скорее всего, картриджи на складе.
  is_active boolean NOT NULL DEFAULT true,
  comment text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT office_equipment_models_name_not_blank_check
    CHECK (office_equipment_model_key(name) <> ''),
  -- Написание в справочнике хранится уже свёрнутым. Без этой проверки правило держал бы только
  -- индекс — то есть ключ; а маршрут (волна В2) завёл бы модель «Ricoh␣␣IM 350» с двойным пробелом
  -- в самом наименовании, и оно уехало бы зеркалом во все её карточки. Ровно тот же дефект, ради
  -- которого правило и меняли, только вошедший другой дверью. Отказ здесь — это 500 у маршрута,
  -- который поленился нормализовать ввод, и он честнее молча испорченного справочника: обе функции
  -- маршруту доступны, вызвать их — одна строка.
  CONSTRAINT office_equipment_models_name_normalized_check
    CHECK (name = office_equipment_model_name_normalize(name)),
  -- Ключ существует ровно ради одной цели — быть адресатом составного FK карточки. Своего смысла
  -- «id вместе с типом уникален» у него нет: `id` и так первичный ключ.
  CONSTRAINT office_equipment_models_type_unique UNIQUE (id, equipment_type_id)
);

COMMENT ON TABLE office_equipment_models IS
  'Модели аппаратов оргтехники (docs/office-equipment-consumables-plan.md §5): к модели, а не к '
  'карточке, привязываются расходники. office_equipment.name — копия имени модели.';

-- Уникальность по паре «тип + ключ написания», а не по одному имени: пара разводит одинаково
-- названный принтер и МФУ и делает разбор парка однозначным. Ключ обязателен — без него
-- «Ricoh IM 350», «RICOH IM 350» и «Ricoh␣␣IM 350» стали бы тремя моделями, то есть ровно тем
-- разнописанием, ради устранения которого справочник и заводится.
--
-- Этот индекс — и есть то место, где правило написания становится обязательным для всех дверей
-- сразу. Всё остальное (разбор, backfill, резолв в триггере) обязано звать ТУ ЖЕ функцию: стоит
-- одному месту посчитать ключ иначе — и оно перестанет находить то, что завело соседнее.
CREATE UNIQUE INDEX office_equipment_models_name_unique
  ON office_equipment_models (equipment_type_id, office_equipment_model_key(name));

-- ── 3. Перечень строится из парка каноном написания (Р4) ──
--
-- Разбор нельзя писать как `SELECT DISTINCT btrim(name)`: индекс выше сводит имена ключом, а
-- `DISTINCT` — нет, и первая же пара «Ricoh IM 350» / «RICOH IM 350» уронила бы миграцию
-- нарушением уникальности. Поэтому канон выбирается явно и детерминированно: самым частым
-- написанием в группе, при равенстве частот — лексикографически первым
-- (`ORDER BY cards DESC, spelling`).
--
-- Частота считается по СВЁРНУТОМУ написанию, а не по исходной строке: три карточки
-- «Ricoh␣␣IM 550F» и две «Ricoh IM 550F» — это пять карточек одного написания, а не два варианта.
-- Иначе лишний пробел не только делил бы группу, но и выигрывал бы ничью: при равных частотах
-- сравнение пошло бы по строке, где пробел стоит раньше буквы, и в справочник уехало бы написание
-- с двойным пробелом.
--
-- Живые и архивные карточки идут вместе, `deleted_at` не фильтруется: карточка обязана вернуться
-- из архива со ссылкой на модель, а не с `NULL`, который выпуск B запретит.
--
-- Чего правило НЕ ловит: смысловых двойников. «Ricoh MP W6700SP» и «Ricoh Aficio MP W6700SP» —
-- почти наверняка один аппарат, но для базы это две разные строки. Их вычитывает ИТ-служба ДО
-- наката (этап 0 плана), пока модель — ещё текст в карточке и правка стоит одного нажатия.
--
-- `ON CONFLICT DO NOTHING` на пустой таблице не срабатывает никогда и стоит здесь ради выпуска B:
-- тот повторяет этот же запрос по уже наполненному справочнику, и оба разбора обязаны быть
-- идемпотентными.
WITH variants AS (
  SELECT equipment_type_id,
         office_equipment_model_key(name) AS key,
         office_equipment_model_name_normalize(name) AS spelling,
         count(*) AS cards
    FROM office_equipment
   GROUP BY 1, 2, 3
), canon AS (
  SELECT DISTINCT ON (equipment_type_id, key) equipment_type_id, key, spelling
    FROM variants
   ORDER BY equipment_type_id, key, cards DESC, spelling
)
INSERT INTO office_equipment_models (equipment_type_id, name)
SELECT equipment_type_id, spelling FROM canon
ON CONFLICT DO NOTHING;

-- ── 4. Backfill ссылок ──
--
-- Сопоставление идёт по той же паре, по которой построен перечень, — «тип + нормализованное имя»,
-- поэтому непривязанной карточки остаться не может (это проверяет караул ниже).
--
-- Вместе со ссылкой выравнивается и написание: с этого момента `name` — копия модели (Р3), и
-- оставить часть карточек с «RICOH IM 350» при модели «Ricoh IM 350» значило бы выкатить инвариант
-- уже нарушенным. Потери данных здесь нет: группа собрана по ключу написания, то есть от канона
-- карточка отличается только регистром и пробелами. Написание, отличающееся чем-то ещё, в эту
-- группу не попало и осталось своей моделью.
--
-- Триггеры создаются НИЖЕ, а не выше, именно ради этого шага: массовый `UPDATE` под зеркалом
-- прогнал бы через функцию весь парк — все триста с лишним карточек, — чтобы получить то, что этот
-- запрос делает одним проходом, и сделал бы порядок шагов ещё и вопросом производительности.
UPDATE office_equipment e
   SET model_id = m.id,
       name = m.name
  FROM office_equipment_models m
 WHERE m.equipment_type_id = e.equipment_type_id
   AND office_equipment_model_key(m.name) = office_equipment_model_key(e.name)
   AND (e.model_id IS DISTINCT FROM m.id OR e.name IS DISTINCT FROM m.name);

-- «Замок» (ADR 0061): тип модели обязан совпадать с типом карточки, и приписать МФУ модель принтера
-- нельзя физически. `ON UPDATE NO ACTION` (умолчание) выбран сознательно: тип модели неизменяем
-- by design, менять его маршрут не даёт, и каскадить здесь нечему — приём тот же, что у
-- `vehicles_model_type_fk` (0017).
--
-- MATCH SIMPLE (умолчание) — то, что делает выпуск A возможным: при `model_id IS NULL` проверка не
-- выполняется вовсе, поэтому карточка, заведённая старым кодом в окне выката, не упирается в ключ.
--
-- `ON DELETE RESTRICT`: модель, на которую ссылается хоть одна карточка — живая или архивная, —
-- не удаляется. Правило Р11 держит схема, а не вежливость маршрута.
ALTER TABLE office_equipment
  ADD CONSTRAINT office_equipment_model_type_fk
  FOREIGN KEY (model_id, equipment_type_id)
  REFERENCES office_equipment_models (id, equipment_type_id) ON DELETE RESTRICT;

-- Караул наката. Карточка без модели после backfill — это ошибка разбора, а не «потом доделаем»:
-- на такой базе выпуск B не встанет никогда, а инвариант «имя — копия модели» окажется
-- необязательным ровно там, где он и нужен. Отменить миграцию с числом в тексте дешевле, чем
-- обнаружить это через месяц.
DO $$
DECLARE
  orphans bigint;
BEGIN
  SELECT count(*) INTO orphans FROM office_equipment WHERE model_id IS NULL;
  IF orphans > 0 THEN
    RAISE EXCEPTION 'Карточек оргтехники без модели: %. Разбор парка неполон — миграция отменена',
      orphans;
  END IF;
END
$$;

-- ── 5. Зеркало имени и резолв старой записи (Р3) ──
--
-- `name` перестаёт быть тем, что вводит человек, и становится копией модели (приём ADR 0007 §2).
-- Копия, которую поддерживает маршрут, разошлась бы тремя способами: переименование прошло бы
-- только по живым карточкам, а восстановленная из архива приехала бы со старым именем;
-- параллельная вставка успела бы записать имя, которое уже переименовали; заливка файлом, миграции
-- и любой скрипт пишут мимо маршрута вовсе. Поэтому инвариант ставится в схему.
--
-- Функция — это state-машина из пяти случаев, и три из них существуют ровно ради выпуска A:
--
--   INSERT, `model_id` задан ....................... зеркало: `name` из модели;
--   INSERT, `model_id` пуст ........................ резолв по «тип + ключ написания»;
--   UPDATE, `model_id` изменился .................... зеркало: `name` из новой модели;
--   UPDATE, `model_id` тот же, изменились имя/тип ... legacy-резолв: карточка переезжает на модель,
--                                                    найденную (или заведённую) по новому имени;
--   UPDATE, не изменилось ни то, ни другое .......... зеркало (страховка от правки `name` в обход).
--
-- Четвёртый случай и есть ответ на старый `PATCH` и старую заливку файлом: у существующей карточки
-- после backfill ссылка уже стоит, и наивное зеркало вернуло бы имя ТЕКУЩЕЙ модели — то есть старая
-- правка молча не сработала бы. Человек правит модель так, как умеет сегодня, — текстом, — и
-- карточка обязана переехать по-настоящему. Разбирает это триггер, а не маршрут: путей записи
-- четыре, и договориться с каждым порознь не выйдет.
--
-- Ветка резолва снимается выпуском C, и не раньше: миграция B тоже накатывается до перезапуска, и
-- в её окне работает код A, чья правка модели держится ровно на ней.
CREATE FUNCTION office_equipment_model_mirror() RETURNS trigger
  LANGUAGE plpgsql SECURITY INVOKER SET search_path = public, pg_temp AS $$
DECLARE
  -- Решение принимается один раз и в одном месте: резолвим карточку по имени или зеркалим имя из
  -- модели. Разложить те же условия по веткам исполнения значило бы получить пять путей, три из
  -- которых делают одно и то же.
  resolve boolean;
  model_name text;
BEGIN
  IF TG_OP = 'INSERT' THEN
    resolve := NEW.model_id IS NULL;
  ELSIF NEW.model_id IS NULL THEN
    -- Ссылку обнулили правкой. Пустой она не остаётся: выпуск B ставит `NOT NULL`, и ронять на нём
    -- запись, которая до сих пор проходила, нельзя — карточка резолвится по своему имени.
    resolve := true;
  ELSIF NEW.model_id IS DISTINCT FROM OLD.model_id THEN
    -- Ссылку сменили явно — это говорит новый код, и он главнее имени, которое могло приехать в том
    -- же запросе старым.
    resolve := false;
  ELSE
    resolve := NEW.name IS DISTINCT FROM OLD.name
            OR NEW.equipment_type_id IS DISTINCT FROM OLD.equipment_type_id;
  END IF;

  IF resolve THEN
    -- Пустое имя ловится здесь, а не ограничением: без этой строки резолв пошёл бы заводить модель
    -- с пустым именем, и человек получил бы отказ про `office_equipment_models_name_not_blank_check`
    -- — про справочник, которого он не касался.
    IF office_equipment_model_key(coalesce(NEW.name, '')) = '' THEN
      RAISE EXCEPTION 'Наименование модели пусто: карточку оргтехники не на что сослать'
        USING ERRCODE = '23514';
    END IF;

    -- `FOR KEY SHARE`, чтобы не подхватить имя, которое прямо сейчас переименовывают: блокировка
    -- несовместима с `FOR UPDATE`, который берёт дверь переименования, и одна из двух транзакций
    -- честно ждёт вторую вместо того, чтобы разложить по карточкам разные имена.
    SELECT m.id, m.name INTO NEW.model_id, model_name
      FROM office_equipment_models m
     WHERE m.equipment_type_id = NEW.equipment_type_id
       AND office_equipment_model_key(m.name) = office_equipment_model_key(NEW.name)
     FOR KEY SHARE;

    IF NOT FOUND THEN
      -- Недостающая модель заводится конкурентно безопасно. `DO UPDATE` с записью самой себя, а не
      -- `DO NOTHING`: `DO NOTHING` конфликтующую строку в `RETURNING` не отдаёт вовсе, и при гонке
      -- двух заведений одной модели второй транзакции нечего подставить в `model_id`. `DO UPDATE`
      -- возвращает строку в обоих исходах — и там, где вставил сам, и там, где наткнулся на соседа,
      -- причём во втором исходе возвращает ЕГО написание, что и требуется зеркалу.
      -- Выражение в `ON CONFLICT` обязано совпасть с индексным ДОСЛОВНО: Postgres сопоставляет
      -- арбитра с индексом по выражению, а не по смыслу, и любое расхождение — не тихая ошибка, а
      -- «no unique or exclusion constraint matching the ON CONFLICT specification» на первой же
      -- вставке. Общая функция снимает и этот риск: сравнивать нечему.
      INSERT INTO office_equipment_models (equipment_type_id, name)
      VALUES (NEW.equipment_type_id, office_equipment_model_name_normalize(NEW.name))
      ON CONFLICT (equipment_type_id, office_equipment_model_key(name))
        DO UPDATE SET name = office_equipment_models.name
      RETURNING id, name INTO NEW.model_id, model_name;
    END IF;
  ELSE
    -- Зеркало. Модель читается той же блокировкой и по той же причине.
    SELECT m.name INTO model_name
      FROM office_equipment_models m
     WHERE m.id = NEW.model_id
     FOR KEY SHARE;

    -- Несуществующую модель поймал бы и составной ключ, но позже и не теми словами: `name` к тому
    -- моменту был бы уже пуст, и человек получил бы отказ про `NOT NULL` наименования, а не про
    -- неизвестную модель.
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Модель оргтехники % не найдена', NEW.model_id USING ERRCODE = '23503';
    END IF;
  END IF;

  NEW.name := model_name;
  RETURN NEW;
END
$$;

CREATE TRIGGER office_equipment_model_mirror
  BEFORE INSERT OR UPDATE ON office_equipment
  FOR EACH ROW EXECUTE FUNCTION office_equipment_model_mirror();

-- `ENABLE ALWAYS` — ОТДЕЛЬНОЙ командой: в `CREATE TRIGGER` такого слова нет, а без него на
-- реплике-приёмнике зеркало просто не сработает и карточка приедет туда с чужим именем. Приём тот
-- же, что у управляющих триггеров `0167`.
ALTER TABLE office_equipment
  ENABLE ALWAYS TRIGGER office_equipment_model_mirror;

-- ПОДПИСИ ОБЪЕКТОВ КАТАЛОГА: триггер и его функция здесь тёзки, и по `\d+` или `pg_trigger` их не
-- различить — подпись отвечает на месте, вместо похода по файлам миграций. То же правило действует
-- у расходников (`0172`), где почти одно имя носят сразу три объекта.
COMMENT ON FUNCTION office_equipment_model_mirror() IS
  'State-машина зеркала и резолва (Р3): держит office_equipment.name копией имени модели, а записи '
  'старого кода (INSERT без model_id, PATCH одного name) переводит в ссылку — находя модель по паре '
  '«тип + ключ написания» или заводя недостающую. Legacy-ветка живёт до выпуска C. Вызывается только '
  'триггером office_equipment_model_mirror.';

COMMENT ON TRIGGER office_equipment_model_mirror ON office_equipment IS
  'BEFORE INSERT OR UPDATE: исполняет функцию office_equipment_model_mirror(). ENABLE ALWAYS — '
  'на реплике-приёмнике зеркало обязано работать так же, иначе карточка приедет туда с чужим именем.';

-- Переименование модели раскладывается по ВСЕМ её карточкам, `deleted_at` не фильтруется: архивная
-- карточка обязана вернуться из архива с текущим именем, а не с тем, которое было в день списания.
--
-- Карточки проходят через зеркало ещё раз — своим `BEFORE`-триггером, по legacy-ветке (имя
-- изменилось, ссылка нет). Ветка находит по новому имени ровно ту модель, которую сейчас
-- переименовали: уникальный индекс не позволяет существовать второй модели того же типа с этим
-- именем. То есть проход безвреден, а не случаен, — но переставлять условия state-машины, не
-- проверив этот путь, нельзя.
--
-- `updated_at` карточки намеренно не трогается: правка написания в справочнике — не редактирование
-- карточки, и после переименования самой ходовой модели весь парк не должен выглядеть только что
-- отредактированным.
CREATE FUNCTION office_equipment_models_rename_mirror() RETURNS trigger
  LANGUAGE plpgsql SECURITY INVOKER SET search_path = public, pg_temp AS $$
BEGIN
  UPDATE office_equipment e
     SET name = NEW.name
   WHERE e.model_id = NEW.id
     AND e.name IS DISTINCT FROM NEW.name;
  RETURN NULL;
END
$$;

-- `WHEN` отсекает правку прочих полей модели (производителя, комментария, гашения) и — что важнее —
-- запись «имя в самоё себя», которой резолв выше разрешает гонку заведения: без условия каждая
-- такая вставка тащила бы за собой `UPDATE` по всем карточкам модели.
CREATE TRIGGER office_equipment_models_rename_mirror
  AFTER UPDATE OF name ON office_equipment_models
  FOR EACH ROW WHEN (OLD.name IS DISTINCT FROM NEW.name)
  EXECUTE FUNCTION office_equipment_models_rename_mirror();

ALTER TABLE office_equipment_models
  ENABLE ALWAYS TRIGGER office_equipment_models_rename_mirror;

COMMENT ON FUNCTION office_equipment_models_rename_mirror() IS
  'Раскладка нового имени модели по ВСЕМ её карточкам, deleted_at не фильтруется: архивная карточка '
  'обязана вернуться из архива с текущим именем. Вызывается только триггером '
  'office_equipment_models_rename_mirror.';

COMMENT ON TRIGGER office_equipment_models_rename_mirror ON office_equipment_models IS
  'AFTER UPDATE OF name WHEN имя изменилось: исполняет функцию office_equipment_models_rename_mirror(). '
  'Условие WHEN отсекает правку прочих полей и запись имени в самоё себя, которой резолв разрешает '
  'гонку заведения модели. ENABLE ALWAYS.';

-- Индекс по ссылке. Его нет в §5 плана, но он нужен обеим сторонам связи: по нему идёт раскладка
-- имени по карточкам модели (68 строк у самой ходовой) и проверка `ON DELETE RESTRICT` при попытке
-- удалить модель. Без индекса каждое переименование и каждое удаление читало бы весь парк целиком.
-- `deleted_at` не в условии: архивные карточки участвуют и в раскладке имени, и в запрете удаления.
CREATE INDEX office_equipment_model_idx ON office_equipment (model_id);
