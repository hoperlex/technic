-- Талоны у контейнерных операций: разделение вложений заявки на «документы» и «талоны».
--
-- Талоны предъявляются при закрытии заявки — это доказательство вывоза, а не сопроводительный
-- документ. У вывоза самосвалами они висят на машинах (ADR 0011): рейсов несколько, у каждого
-- свой талон. Контейнерные операции (установка, замена, снятие) выполняются одной ходкой —
-- машины там нет и заводить её только ради талона значило бы придумывать сущность под файл.
-- Поэтому талон таких заявок крепится к самой заявке, в ту же request_files.
--
-- Отличить их колонкой, а не отдельной таблицей: связь та же (заявка ↔ файл), правила привязки
-- и удаления те же, а вторая таблица заставила бы дублировать их целиком. Разделять нужно
-- потому, что смысл разный: документы прикладывают при заведении и правят свободно, талон
-- приходит с фактом выполнения и в списке вложений заявки теряться не должен.

ALTER TABLE request_files
  ADD COLUMN kind text NOT NULL DEFAULT 'attachment',
  ADD CONSTRAINT request_files_kind_check CHECK (kind IN ('attachment', 'ticket'));

-- Все существующие связи заведены до появления талонов заявки — это документы, и default
-- проставил им верное значение. Обратной засыпки не требуется.

COMMENT ON COLUMN request_files.kind IS
  'attachment — документ заявки; ticket — талон, приложенный при переводе в «Выполнена»';

-- Под выборку талонов заявки отдельно от документов (карточка заявки, окно выполнения).
CREATE INDEX request_files_ticket_idx ON request_files (request_id) WHERE kind = 'ticket';
