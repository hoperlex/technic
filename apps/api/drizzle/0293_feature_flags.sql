-- Рубильник приёма сообщений о технике: одна строка состояния, выключенная
-- (план `docs/office-equipment-request-subject-plan.md`, Р10–Р11, этап Э4; контракт рубильника —
-- `docs/office-equipment-candidate-plan.md`, §14).
--
-- ОТКУДА НОМЕР. Снимок `ls apps/api/drizzle` 09.09.2026: последним в дереве стоял
-- `0292_completion_actual_end_date.sql` соседнего потока (ещё не закоммиченный), свободен `0293`.
-- Потоки параллельные, поэтому номер взят непосредственно перед созданием файла, а не из плана: за
-- один день 04.09.2026 план кандидата дважды потерял зарезервированный номер ровно так.
--
-- ЗАЧЕМ ЭТА СТРОКА ВООБЩЕ. Волна кандидатов (ADR 0165) реализована и лежит в main закрытой: права
-- не выданы, письма выключены. Открывает её выдача прав — а миграция прав применяется ДО
-- перезапуска приложения, и в это окно старый сервер уже принимает `equipmentCandidate`, а старый
-- портал держит `intakeOpen = true` жёстко. То есть без рубильника выдача права немедленно открыла
-- бы приём мимо всякого включения. Рубильник переворачивает порядок: код едет закрытым, а
-- открывает его `UPDATE` по работающему серверу.
--
-- ЭТО НЕ ПОЛНЫЙ РЕЗОЛВЕР ФЛАГОВ. План кандидата ждал общего механизма — с пилотными областями,
-- аудитом переключения и административной ручкой; его в репозитории нет, и эта волна его не пишет.
-- Здесь один вопрос — «включён ли ключ», — одинаковый для всех учёток, и переключается он миграцией
-- или `UPDATE`-ом, а не экраном. Отвергнуто вслух: ждать общий резолвер (волна встала бы на внешней
-- задаче, а выкатывать её без серверного fail-closed нельзя); строить пилотные области «на вырост»
-- (механизм без читателя расходится с будущими требованиями быстрее, чем пишется).
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ СТРОКА В `module_mail_event_settings`. Приём соседа повторён —
-- ключ и флаг, — но сущности разные: там рубильник ПИСЬМА по событию модуля, здесь рубильник
-- ПРИЁМА данных. Слитые в одну таблицу, они дали бы `CHECK` из двух несвязанных перечней и админку
-- писем, показывающую строку, которая писем не шлёт вовсе. Общего у них ровно форма, а не смысл.
--
-- ЧЕГО В ТАБЛИЦЕ НЕТ И ПОЧЕМУ. Ни `updated_by`, ни `version`: у почтовой настройки они стоят из-за
-- экрана администратора (кто щёлкнул и чья правка победила), а у этого ключа экрана нет и в этой
-- волне не будет — колонки описывали бы несуществующую ручку. Аудита переключения тоже нет: его
-- обязан принести общий резолвер вместе с ручкой, а `UPDATE` рукой оператора запуска и так виден в
-- журнале выката.
--
-- ИМЯ ТАБЛИЦЫ ОБЩЕЕ НАМЕРЕННО: когда общий резолвер появится, ему расти отсюда (пилотные области —
-- соседние таблицы к этой), а не сносить узкую табличку с именем одного модуля. Обещанием
-- резолвера имя при этом не является — см. абзац выше.
--
-- `CHECK` ПО ПЕРЕЧНЮ КЛЮЧЕЙ СТОИТ, и по той же причине, что у `module_mail_event_settings`: цена
-- опечатки. Лишняя строка выглядела бы настройкой («рубильник включён»), пока настоящий ключ сидит
-- без строки и молчит fail-closed — то есть выключение выглядело бы включением. Перечень обязан
-- совпадать с `FEATURE_FLAGS` в контрактах и с `check` в `apps/api/src/db/schema.ts`; новый ключ
-- приходит со своей строкой, то есть со своей миграцией.
--
-- СТРОКА ЗАВОДИТСЯ ВЫКЛЮЧЕННОЙ, и это весь смысл выпуска A: приём кандидатов закрыт, права никому
-- не выданы, письма молчат. Включает её выпуск B одним `UPDATE … = true` по работающему серверу,
-- после health и smoke; аварийное выключение — тот же `UPDATE … = false`, и очередь проверки,
-- чтение уже принятых кандидатов и три решения им не ограждаются: прекратить приток обязаны, а
-- запереть принятое — нет.
--
-- Аддитивная миграция: существующих данных не касается, протокол выката необратимых миграций
-- (`docs/schema-cutover-protocol.md`) к ней не применяется. Откат — `DROP TABLE`; код прошлого
-- выпуска о таблице не знает, а новый на её отсутствии отвечает «выключено» (fail-closed), то есть
-- ведёт себя как прошлый.

CREATE TABLE feature_flags (
  -- Ключ строки — сам рубильник: второму рубильнику одного ключа взяться неоткуда.
  key text PRIMARY KEY,
  -- Умолчание выключенное: ключ, добравшийся до продакшена без своей строки, обязан молчать, а не
  -- открывать приём. Читатель трактует отсутствие строки так же — одним ответом на оба случая.
  is_enabled boolean NOT NULL DEFAULT false,
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE feature_flags ADD CONSTRAINT feature_flags_key_check
  CHECK (key IN ('office_equipment_candidate_intake'));

-- Строка на каждый ключ реестра: пустая таблица означала бы то же «выключено», но неотличимо от
-- недокаченного выката — а включать выпуском B нужно существующую строку, а не догадку о ней.
INSERT INTO feature_flags (key, is_enabled) VALUES
  ('office_equipment_candidate_intake', false);
