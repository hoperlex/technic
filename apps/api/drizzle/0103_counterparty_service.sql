-- Сервисная компания как роль контрагента (ADR 0010 §1, §13; ADR 0085 Р1).
--
-- Значением enum, а не отдельной таблицей: набор реквизитов у неё тот же, что у остальных ролей
-- (наименование, ИНН, синонимы, комментарий, активность), а различает её роль в проекте — тем же
-- ходом заводились арендодатель ТС (0032) и поставщик (0076).
--
-- Использовать значение можно только со следующей миграции: применить его в той же транзакции,
-- где оно добавлено, Postgres не даёт, а раннер выполняет файл целиком в одной транзакции.
ALTER TYPE counterparty_type ADD VALUE IF NOT EXISTS 'service';
