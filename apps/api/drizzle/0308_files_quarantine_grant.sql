-- Одноцелевой системный набор «Файлы: разбор карантина» (план
-- `docs/office-equipment-on-site-and-invoice-estimate-plan.md`, Р6, п. 4).
--
-- ЧТО ЗАКРЫВАЕТ ПРАВО. Карантин — аварийный выход для ошибочно загруженного секретного или чужого
-- документа: основание денежного решения снять нельзя НИКОГДА (замки 1–2 того же Р6), поэтому
-- ошибочно загруженные персональные данные закрываются, а не удаляются. Закрываются они ОТ ВСЕХ —
-- от автора загрузки, исполнителя, «Ведения» и держателя области, — приоритетным запретом в
-- `canAccessFile` раньше любой ветки видимости. Право `files.quarantineAudit` отвечает на
-- единственный оставшийся вопрос: кому карантинный файл всё-таки открыт, потому что инцидент
-- кто-то обязан разобрать. Им же ставится и снимается сам карантин: запирать наугад, не видя
-- содержимого, нельзя, а «закрыть может один, открыть другой» — не разделение обязанностей, а
-- способ потерять документ.
--
-- ЗАЧЕМ НАБОР, А НЕ СТРОКА В МАТРИЦЕ РОЛЕЙ. Право сквозное НАСКВОЗЬ: карантин ставят по файлу, а
-- файл приходит из любого модуля портала — вывоз, техника, оргтехника, путевые листы, парк, — и ни
-- одна область держателя его не сужает. Раздай такое право матрица — содержимое любого запертого
-- документа досталось бы всей диспетчерской разом; разбор инцидента с персональными данными ведёт
-- НАЗВАННЫЙ человек. Набор — единственный в модели ADR 0106 способ выдать право поимённо, с
-- автором, временем и строкой в реестре выдач: прямой персональной выдачи она не знает вовсе, а
-- `NON_GRANTABLE_PERMISSIONS` дал бы противоположное — право, которое не выдать никому, кроме
-- администратора.
--
-- ПОЧЕМУ НЕ `files.manageAny`. Тот приходит матрицей роли (менеджер, диспетчер) и отвечает на
-- другой вопрос — «кто удаляет ничейный чужой файл». Требуй набор его (строкой в
-- `PERMISSION_REQUIRES`), и разбор инцидента стал бы следствием права на удаление; положи карантин
-- в него — и запереть основание денежного решения могла бы вся диспетчерская, а открыть запертое не
-- смог бы никто из них.
--
-- РОЛИ — ДИСПЕТЧЕР И МЕНЕДЖЕР, и выбор про область, а не про должность. Клетка
-- `files × object | department | counterparty` — `forbidden` (`GRANT_SCOPE_MATRIX`): предиката
-- области у файлового слоя нет ни одного, и набор с правом этого модуля, выданный роли с осью,
-- отдал бы ей документы всей компании. Из ролей без оси отпадают водитель (наборов не принимает
-- вовсе), наблюдатель (по построению ничего не решает) и обе роли службы главного механика
-- (инциденты с персональными данными разбирает не ОГМ). Остаются две, и обе уже отвечают за
-- файловый слой правом `files.manageAny`. Администратора в списке нет намеренно: право у него уже
-- есть от матрицы (`admin: [...PERMISSIONS]`), и строка совместимости под ним означала бы набор,
-- выдача которого не меняет ничего.
--
-- ЧЕГО ЗДЕСЬ НЕТ. Ни одной строки `user_grants`. Миграция заводит набор, его состав и совместимые
-- роли; кому он достанется — решает администратор портала поимённо. Дописанная сюда выдача «чтобы
-- сразу работалось» была бы расширением доступа миграцией: молча, мимо журнала выдач и мимо того,
-- кто за него отвечает.
--
-- КОД НАБОРА НЕ МЕНЯЕТСЯ НИ ПРИ КАКИХ УСЛОВИЯХ. По коду набор находят миграции каталога, журнал
-- действий и реестр выдач; `UPDATE grants SET code = ...` не переименовывает набор, а отвязывает
-- его от кода. Правятся название, описание и состав.
--
-- ГДЕ ЖИВЁТ ОБЪЯВЛЕННЫЙ СОСТАВ. В `MODULE_GRANTS` (`packages/contracts/src/grants.ts`); обе стороны
-- сверяет страж `apps/api/test/grants-catalog.db.test.ts`.
--
-- ОБРАТИМОСТЬ. Трогаются только три таблицы каталога, схема не меняется: колонки карантина
-- (`files.quarantined_at`, `files.content_hash`) пришли миграцией 0306. Откат — удаление набора,
-- пока у него нет держателей (`RESTRICT` на `user_grants`).

-- ── 1. Набор ──
--
-- `ON CONFLICT` — не «на всякий случай»: повторный накат на базу, восстановленную из копии, обычное
-- дело, и миграция обязана довести каталог до объявленного состояния, а не упасть на первой строке.

INSERT INTO grants (code, name, description, is_system) VALUES
  (
    'files_quarantine_audit',
    'Файлы: разбор карантина',
    'Разбор инцидента с ошибочно загруженным документом: ставит файл в карантин (содержимое '
    'перестаёт выдаваться по ссылке всем, включая автора загрузки и «Ведение»), снимает карантин и '
    'открывает содержимое запертого файла. Набор сквозной: карантин ставят по файлу, а файл '
    'приходит из любого модуля портала, и область держателя его не сужает. Каждое открытие '
    'карантинного файла и каждая постановка со снятием пишутся в журнал действий с причиной. '
    'Удалить запертый файл нельзя — ни держателю набора, ни автору: это предмет разбора.',
    true
  )
ON CONFLICT (code) DO UPDATE
   SET name = EXCLUDED.name, description = EXCLUDED.description, updated_at = now();

-- ── 2. Состав: одно право ──
--
-- Право хранится текстом — справочника прав в базе нет намеренно (`grant_permissions`, миграция
-- 0145): словарь `PERMISSIONS` закрыт и живёт в контрактах.

INSERT INTO grant_permissions (grant_id, permission)
SELECT g.id, s.permission
FROM grants g
JOIN (VALUES
  ('files_quarantine_audit', 'files.quarantineAudit')
) AS s (code, permission) ON s.code = g.code
ON CONFLICT (grant_id, permission) DO NOTHING;

-- ── 3. Совместимые роли ──
--
-- «Кому набор можно назначить», а не «кому он выдан». Только роли без собственной области: у файлов
-- предиката области нет вовсе, и роли с осью набор открыл бы компанию целиком.

INSERT INTO grant_roles (grant_id, role)
SELECT g.id, s.role::role
FROM grants g
JOIN (VALUES
  ('files_quarantine_audit', 'dispatcher'),
  ('files_quarantine_audit', 'manager')
) AS s (code, role) ON s.code = g.code
ON CONFLICT (grant_id, role) DO NOTHING;

-- ── 4. Караул: состав в базе равен объявленному ──
--
-- Страж-тест сверяет то же самое, но живёт он в репозитории, а этот блок — в накате: оператор
-- выката увидит расхождение сразу, а не через прогон тестов. Проверяются все три обещания разом —
-- набор системный, право ровно одно и роли ровно две, — и отдельно то, что миграция никому ничего
-- не выдала: строка `user_grants`, дописанная сюда позже, и есть то расширение доступа, которого в
-- миграции быть не должно.
DO $$
DECLARE trouble text;
BEGIN
  SELECT string_agg(msg, '; ')
    INTO trouble
    FROM (
      SELECT format('набора нет или он не системный (найдено строк: %s)', count(*)) AS msg
        FROM grants
       WHERE code = 'files_quarantine_audit' AND is_system AND deleted_at IS NULL
      HAVING count(*) <> 1
      UNION ALL
      SELECT format('прав в наборе %s вместо одного', count(*))
        FROM grant_permissions gp
        JOIN grants g ON g.id = gp.grant_id
       WHERE g.code = 'files_quarantine_audit'
      HAVING count(*) <> 1
         OR count(*) FILTER (WHERE gp.permission = 'files.quarantineAudit') <> 1
      UNION ALL
      SELECT format('роли набора: %s', coalesce(string_agg(gr.role::text, ', ' ORDER BY gr.role::text), 'ни одной'))
        FROM grant_roles gr
        JOIN grants g ON g.id = gr.grant_id
       WHERE g.code = 'files_quarantine_audit'
      HAVING coalesce(array_agg(gr.role::text ORDER BY gr.role::text), ARRAY[]::text[])
               <> ARRAY['dispatcher', 'manager']
      UNION ALL
      SELECT format('набор кому-то выдан: держателей %s', count(*))
        FROM user_grants ug
        JOIN grants g ON g.id = ug.grant_id
       WHERE g.code = 'files_quarantine_audit'
      HAVING count(*) <> 0
    ) AS bad;
  IF trouble IS NOT NULL THEN
    RAISE EXCEPTION 'Набор «Файлы: разбор карантина» собран не так, как объявлен — %', trouble;
  END IF;
END $$;
