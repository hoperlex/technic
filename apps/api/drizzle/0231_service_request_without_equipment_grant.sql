-- Право «завести заявку без аппарата» в двух наборах модуля «Орг.техника» (план
-- `docs/office-equipment-consumables-and-purchase-plan.md`, Р5; ADR 0146, решение 6; выпуск 2б,
-- этап Э16).
--
-- ОТКУДА НОМЕР. Проверено `ls apps/api/drizzle` непосредственно перед созданием файла (01.09.2026):
-- последняя миграция в дереве — `0229_releases_office_equipment_purchases.sql` (запись выпуска 65).
-- Свободны 0230 и 0231; 0230 занята схемной правкой той же волны (снятие `NOT NULL` и двусоставный
-- `CHECK` предмета), этому файлу достался 0231. Порядок между ними значения не имеет — таблицы у
-- них разные, — но записан он именно так: сначала схема, потом каталог.
--
-- ЗАЧЕМ. Половина работы модуля предметом в справочнике не описывается: «поставьте розетку»,
-- «настройте почту новому сотруднику», «принтер привезли, инвентарного номера ещё нет». Миграция
-- 0230 разрешила такой заявке жить без аппарата, а кому её заводить — отвечает право
-- `serviceRequests.createWithoutEquipment`.
--
-- ПОЧЕМУ ПРАВОМ, А НЕ ПРОВЕРКОЙ НАБОРА ПО МЕСТУ. Набор отвечает на вопрос «кто», право — на «что
-- можно». Условие «у автора есть надстройка», написанное в маршруте, невидимо витрине прав, не
-- снимается составом набора и не выдаётся поимённо — смешение этих слоёв уже стоило модулю
-- оргтехники двух дыр. Право же видно в сетке «Права», выдаётся и отбирается тем же способом, что
-- остальные.
--
-- ПОЧЕМУ ДВА НАБОРА. «Ведение» — потому что такие заявки приходят к тому, кто ведёт модуль.
-- «ИТ-служба» — потому что половина из них заводится её же руками, и заводить их через заказчика
-- значило бы просить человека оформить работу, о которой он и сам не просил. Оба состава — решение
-- заказчика, а не следствие правила.
--
-- ТРЕБОВАНИЕ `serviceRequests.create` (`PERMISSION_REQUIRES` в `packages/contracts/src/grants.ts`)
-- выполняется у держателей обоих наборов любой из трёх базовых ролей (`ROLE_ADDON_BASE_ROLES`:
-- штаб, площадка, отдел) — заведение заявки есть у каждой как у заказчика. Барьер выдачи поэтому не
-- начнёт отклонять то, что вчера выдавалось. Требование объявлено на ЗАВЕДЕНИЕ, а не на чтение, и
-- это единственная такая строка модуля: право не открывает своей двери вовсе, ручка у него чужая —
-- `POST /service-requests`, — и её статический страж спрашивает `serviceRequests.create`. Держатель
-- без него получил бы право, которое сервер не пустит ни разу.
--
-- ЧЕГО ЗДЕСЬ НЕТ. Ни одной строки `user_grants`: миграция правит каталог — состав наборов и их
-- описания, — а кому набор достанется, решает администратор портала поимённо, с автором, временем и
-- записью в реестре выдач (ADR 0106). Держатели у обоих наборов уже есть, и права им прибавляются
-- ровно на одно объявленное здесь — это и есть весь эффект наката на живые учётки.
--
-- ПОЧЕМУ ПРАВО ЕДЕТ РАНЬШЕ МАРШРУТА. Стража права на `POST /service-requests` в этом выкате ещё
-- нет — его везёт следующая волна (этап Э18 плана). Разнести можно ровно потому, что право без
-- маршрута не открывает ничего: схема заведения пустой аппарат пока не принимает, и держатель
-- набора не получает этой миграцией ни одной новой двери. Обратный порядок — маршрут раньше права —
-- был бы запрещён, а этот безопасен и держит состав наборов в контрактах и в базе одной волной.
--
-- КОДЫ НАБОРОВ НЕ МЕНЯЮТСЯ НИ ПРИ КАКИХ УСЛОВИЯХ. По коду набор находят миграции каталога, журнал
-- действий, реестр выдач и таблица сквозной области (`GRANT_MODULE_WIDE_SCOPE`):
-- `UPDATE grants SET code = ...` не «переименовывает набор», а отвязывает его от кода. Правятся
-- название, описание и состав — здесь описания и состав.
--
-- ГДЕ ЖИВЁТ ОБЪЯВЛЕННЫЙ СОСТАВ. У обоих наборов — в `ROLE_ADDON_PERMISSIONS`
-- (`packages/contracts/src/permissions.ts`): надстройка ADR 0086 остаётся живым источником доступа
-- до шага 1e реформы, и набор в базе — её отражение. Правка надстроек уехала той же волной, что эта
-- миграция, и это обязательное условие: иначе один и тот же человек получил бы разные права в
-- зависимости от того, пришёл к нему доступ надстройкой или набором. Обе стороны сверяет страж
-- `apps/api/test/grants-catalog.db.test.ts`.
--
-- СОВМЕСТИМЫЕ РОЛИ НЕ ТРОГАЮТСЯ: у обоих наборов они те же — штаб, площадка, отдел.
--
-- ОБРАТИМОСТЬ. Трогаются две таблицы каталога, схема не меняется; протокол выката необратимых
-- миграций (`docs/schema-cutover-protocol.md`) к ней не применяется. Откат — `DELETE` двух строк
-- состава и прежний текст описаний.

-- ── 1. Описания наборов ──
--
-- Описание перечисляет, что набор умеет, и потому правится вместе с составом: набор, открывающий
-- новую возможность и молчащий о ней, заставляет администратора угадывать по списку прав. Текст
-- переписывается целиком, а не дописывается конкатенацией: `description || '…'` на повторном
-- накате пришил бы фразу второй раз.

UPDATE grants
   SET description = 'Ведёт модуль «Орг.техника» целиком: справочник техники, распределение заявок '
                     'по исполнителям, согласование сметы, приёмку работы, срочность и заморозку. '
                     'Это единственный набор, которым заявку принимают и отменяют из любого '
                     'статуса; ходов исполнителя в нём нет — их открывает назначение. Им же ведут '
                     'плановые закупки расходников: заводят документ для снабжения, правят '
                     'черновик, проводят, закрывают и отменяют. Им же заводят заявку без аппарата '
                     '— на работу, у которой предмета в справочнике нет вовсе. Перечень картриджей '
                     'и остаток на складе правит другой набор — «Оргтехника: номенклатура».',
       updated_at = now()
 WHERE code = 'office_equipment_operator';

UPDATE grants
   SET description = 'Решает по смете «чинить или менять» и работает исполнителем: берёт заявку в '
                     'работу, ведёт её, откладывает, подшивает документы и передаёт внешнему '
                     'сервису. Ходы исполнителя доступны только на заявках, где держатель назначен '
                     'поимённо. Заводит заявку без аппарата — на работу, у которой предмета в '
                     'справочнике нет вовсе. Виза ИТ и сквозная видимость модуля идут вместе с '
                     'набором: подписывают по всем площадкам сразу.',
       updated_at = now()
 WHERE code = 'office_equipment_it_approver';

-- ── 2. Состав: одно новое право, обоим наборам ──
--
-- Право хранится текстом — справочника прав в базе нет намеренно (`grant_permissions`, миграция
-- 0145): словарь `PERMISSIONS` закрыт и живёт в контрактах. `ON CONFLICT DO NOTHING` делает шаг
-- идемпотентным, а не «на всякий случай»: повторный накат на базу, восстановленную из копии, —
-- обычное дело.

INSERT INTO grant_permissions (grant_id, permission)
SELECT g.id, s.permission
FROM grants g
JOIN (VALUES
  ('office_equipment_operator'   , 'serviceRequests.createWithoutEquipment'),
  ('office_equipment_it_approver', 'serviceRequests.createWithoutEquipment')
) AS s (code, permission) ON s.code = g.code
ON CONFLICT (grant_id, permission) DO NOTHING;

-- ── 3. Караул: состав в базе равен объявленному ──
--
-- Страж-тест сверяет то же самое, но живёт он в репозитории, а этот блок — в накате: оператор
-- выката увидит расхождение сразу, а не через прогон тестов. Проверяется ровно то, что миграция
-- обещала: оба набора существуют и системны, прав в «Ведении» восемь (семь после миграции 0228 плюс
-- заявка без аппарата), в «ИТ-службе» шесть (пять после 0183 плюс она же), и новое право есть в
-- каждом. Строк `user_grants` этот блок не считает: наборы живые, и держатели у них — обычное дело.
DO $$
DECLARE trouble text;
BEGIN
  SELECT string_agg(msg, '; ')
    INTO trouble
    FROM (
      SELECT format('наборов нет или они не системные (найдено строк: %s вместо двух)', count(*))
             AS msg
        FROM grants
       WHERE code IN ('office_equipment_operator', 'office_equipment_it_approver')
         AND is_system AND deleted_at IS NULL
      HAVING count(*) <> 2
      UNION ALL
      SELECT format('%s: прав %s вместо %s, заявка без аппарата среди них: %s',
                    g.code,
                    count(gp.permission),
                    CASE g.code WHEN 'office_equipment_operator' THEN 8 ELSE 6 END,
                    CASE WHEN count(gp.permission) FILTER (
                           WHERE gp.permission = 'serviceRequests.createWithoutEquipment') = 1
                         THEN 'да' ELSE 'нет' END)
        FROM grants g
        LEFT JOIN grant_permissions gp ON gp.grant_id = g.id
       WHERE g.code IN ('office_equipment_operator', 'office_equipment_it_approver')
       GROUP BY g.code
      HAVING (g.code = 'office_equipment_operator'    AND count(gp.permission) <> 8)
          OR (g.code = 'office_equipment_it_approver' AND count(gp.permission) <> 6)
          OR count(gp.permission) FILTER (
               WHERE gp.permission = 'serviceRequests.createWithoutEquipment') <> 1
    ) AS bad;
  IF trouble IS NOT NULL THEN
    RAISE EXCEPTION 'Наборы оргтехники собраны не так, как объявлены — %', trouble;
  END IF;
END $$;
