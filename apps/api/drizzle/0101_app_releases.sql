-- Журнал обновлений портала (ADR 0077).
--
-- Одна таблица и никакой админки: выпуск заводит тот же человек, который его выкатывает, и делает
-- это тем же способом, что и остальные изменения схемы, — миграцией. Три решения внутри таблицы
-- стоит назвать явно, потому что каждое отвергает более очевидный вариант.
--
-- `seq` отдельно от `version`. Порядок здесь хранится, а не выводится: дата выпуски не
-- упорядочивает — за неделю с 1 по 6 августа блоков закрылось семь, и пять из них доехали 6-го;
-- строка версии не упорядочивает тоже — '0.1.10' меньше '0.1.9' как текст. Тем же `seq` фронт
-- отмечает прочитанное, и он переживает смену второго числа версии, когда счёт выпусков в линии
-- начнётся заново.
--
-- `adrs` массивом, а не счётчиком. Количество получается длиной, а рядом остаётся след «какие
-- именно решения» — по нему сверяются с `docs/adr`, когда через полгода спрашивают, откуда взялась
-- строка в журнале. Счётчик знает «сколько», но не знает «что». Наружу при этом идёт только длина.
--
-- `items` в jsonb, а не второй таблицей. Пункты читаются только целиком вместе с выпуском и
-- никогда не ищутся по отдельности: вторая таблица дала бы join ради строк одного экрана.
--
-- Число 60 встречается в `adrs` двух разных выпусков, и это не опечатка сида: в `docs/adr` два
-- файла с этим номером — `0060-directory-record-purge` и `0060-esm2-weekly-waybill` (номер заняли
-- в параллельных потоках работы). Решения разные и вошли в разные блоки.

CREATE TABLE app_releases (
  seq         integer PRIMARY KEY,
  version     text NOT NULL UNIQUE,
  -- Дата выкладки: справочная, порядок задаёт `seq`.
  released_on date NOT NULL,
  title       text NOT NULL,
  adrs        smallint[] NOT NULL,
  items       jsonb NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT app_releases_title_not_blank CHECK (btrim(title) <> ''),
  -- Пункты — всегда массив: пустой законен (бывает выпуск из одних исправлений схемы), объект на
  -- его месте сломал бы разбор в контрактах уже после того, как миграция уехала на сервер.
  CONSTRAINT app_releases_items_is_array CHECK (jsonb_typeof(items) = 'array'),
  CONSTRAINT app_releases_adrs_not_empty CHECK (array_length(adrs, 1) >= 1)
);

-- Первые семь выпусков собраны задним числом за 1–6 августа (ADR 0077 §7): пустое окно в день
-- включения выглядело бы поломкой, а не новой возможностью. Границы нарезаны ретроспективно,
-- поэтому часть пунктов одинаково честно ложилась бы в соседний блок.

