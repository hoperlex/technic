-- Почтовый канал у письма
-- (план `docs/office-equipment-mail-and-history-plan.md`, Р85).
--
-- До этой колонки контур был одноканальным: воркер поднимал один транспорт из `env` на весь
-- процесс, а `MAIL_FROM` был строкой конфигурации, а не свойством письма. Второго отправителя
-- выразить было нечем — и письмо от ящика службы ремонта уйти не могло: почтовые службы отвергают
-- чужой `From`, а SPF и DKIM домена подписывает его собственный сервер.
--
-- Канал выбирает API, который письмо и составляет; воркер по этой колонке берёт транспорт. Правило
-- «письма такого вида — таким каналом», зашитое в воркер, разъехалось бы с тем, что API кладёт в
-- тело и в `From`, и разошлось бы молча.
--
-- Значение по умолчанию — прежний канал: письма, лежащие в очереди с прошлых выпусков, уходят так
-- же, как уходили. Реестр ключей живёт в контрактах (`MAIL_ACCOUNTS`), и CHECK по перечню здесь не
-- ставится по той же причине, что у событий в миграции 0141: третий канал не должен стоить
-- миграции.
--
-- Аддитивная миграция: смысл существующих данных не меняется, протокол выката необратимых
-- миграций (`docs/schema-cutover-protocol.md`) к ней не применяется.

ALTER TABLE mail_messages ADD COLUMN account text NOT NULL DEFAULT 'default';

-- Разбор очереди идёт по каналу: «что не ушло у службы ремонта» — вопрос к одному каналу, а не ко
-- всей очереди, и лимит писем в минуту у каждого канала свой.
CREATE INDEX mail_messages_account_status_idx ON mail_messages (account, status, created_at);
