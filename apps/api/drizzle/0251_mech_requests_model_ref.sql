-- Заявка механизации ссылается на справочник моделей, а не хранит написание (план
-- `docs/mechanization-models-directory-plan.md`, §5, этап Э2; ADR 0156).
--
-- ОТКУДА НОМЕР. Проверено `ls apps/api/drizzle/*.sql | tail -3` непосредственно перед созданием
-- файла (03.09.2026): последняя миграция в дереве — `0250_mech_models_seed.sql`, своя же, этапа Э1.
-- Между Э1 и Э2 в дереве идёт чужая параллельная работа, поэтому сверка сделана заново, а не взята
-- из шапки плана.
--
-- ЧТО ЗДЕСЬ ПРОИСХОДИТ. Появляется `mech_model_id` — ссылка на `mech_models`, — и живые заявки
-- переносятся на неё сопоставлением `kind_key = name_key`. Ключи совпадают ЗНАК В ЗНАК не случайно:
-- обе колонки считаются выражением `lower(btrim(regexp_replace(…,'\s+',' ','g')))`, и симметрия
-- заведена ровно ради этого переноса (ADR 0156, решение 3; миграции 0238 и 0249). Разойдись
-- выражения — часть заявок молча осталась бы без модели.
--
-- ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ:
--
--   * `NOT NULL` на новой колонке. Заявка, чьё наименование в справочнике не нашлось, остаётся со
--     строкой и показывается как есть (план §5, Э2). Поставь ограничение сейчас — миграция упала бы
--     на первой же такой заявке, а `deploy-auto` катит миграции ДО перезапуска: окно выката
--     кончилось бы неподнявшимся сервером.
--   * `kind_name`/`kind_key` не тронуты ни одной буквой. Они уходят этапом Э3 отдельным выкатом по
--     протоколу необратимых миграций (`docs/schema-cutover-protocol.md`), и до тех пор служат
--     двум вещам: показывают заявку, не нашедшую свою модель, и держат `NOT NULL`, из-за которого
--     сервер пишет в `kind_name` наименование ВЫБРАННОЙ модели.
--
-- ОБРАТИМОСТЬ. Миграция аддитивная: одна новая колонка, один индекс, одно проставление ссылки.
-- Откат — `ALTER TABLE mech_requests DROP COLUMN mech_model_id`, и ничего из прежних данных при
-- этом не теряется: написание всё ещё лежит в `kind_name`. Протокол необратимых миграций к ней
-- поэтому не применяется — он ждёт Э3.
--
-- СКОЛЬКО ПЕРЕНЕСЛОСЬ. На деве (03.09.2026) в таблице пять демонстрационных заявок, и модель нашла
-- ИЗ НИХ НИ ОДНА: заявки названы обобщённо («Компрессор дизельный 5 м³/мин», «Виброплита
-- реверсивная 90 кг»), а в справочнике — конкретные модели («Компрессор XAS970 Dd Euro Box
-- сер.№06253380730709»). Перенесено 0, осталось со строкой 5. Это не поломка сопоставления, а
-- ответ про сами данные: обобщённое написание модели не равно и равняться не может — такие заявки
-- и есть тот случай, ради которого `NOT NULL` отложен до Э3. Числа прода посчитает `RAISE NOTICE`
-- ниже в момент наката; читать их надо в выводе `deploy-auto`.

-- Ссылка на справочник. `ON DELETE RESTRICT` — та же строгость, что у арендодателя: заявка это
-- история аренды, и удаление строки справочника не имеет права унести из неё предмет аренды.
-- Отказ по этому ключу переводится человеку в `services/directory-purge.ts` («на запись ссылаются
-- заявки механизации») — без строки в той карте держатель справочника получил бы безликое «на
-- запись ссылаются другие данные».
ALTER TABLE mech_requests
  ADD COLUMN mech_model_id uuid REFERENCES mech_models(id) ON DELETE RESTRICT;

COMMENT ON COLUMN mech_requests.mech_model_id IS
  'Модель из справочника mech_models; пусто — заявка старше Э2 и показывается по kind_name';

-- Вход со стороны справочника: отбор списка и журнала по модели (он заменил отбор по ключу
-- написания) и проверка `RESTRICT` при попытке модель снести. Индекс полный, а не частичный, в
-- отличие от `mech_requests_lessor_idx`: пустая ссылка здесь — временное состояние на один выкат,
-- и после Э3 предикат `IS NOT NULL` пришлось бы снимать пересозданием индекса.
CREATE INDEX mech_requests_mech_model_idx ON mech_requests (mech_model_id);

-- Перенос живых заявок. Сопоставление по нормализованному ключу, а не по `name`: написание
-- различается регистром и повторными пробелами, и сравнение строк оставило бы без модели заявку,
-- набранную с маленькой буквы. `mech_model_id IS NULL` в условии — не осторожность ради
-- осторожности: миграция обязана быть безвредна при повторном накате на базу, где ссылки уже
-- проставлены (например, после отката и наката заново).
UPDATE mech_requests r
   SET mech_model_id = m.id
  FROM mech_models m
 WHERE m.name_key = r.kind_key
   AND r.mech_model_id IS NULL;

-- Итог наката словами, а не догадкой по числу строк: сколько заявок нашли свою модель и сколько
-- осталось со строкой до Э3. Второе число — рабочее задание держателю справочника: пока оно не
-- ноль, Э3 снимать `kind_name` нельзя.
DO $$
DECLARE
  v_linked integer;
  v_orphan integer;
BEGIN
  SELECT count(*) FILTER (WHERE mech_model_id IS NOT NULL),
         count(*) FILTER (WHERE mech_model_id IS NULL)
    INTO v_linked, v_orphan
    FROM mech_requests;
  RAISE NOTICE 'Механизация: заявок с моделью %, осталось со строкой % (их разбирает Э3)',
    v_linked, v_orphan;
END $$;
