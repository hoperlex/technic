-- Путевой лист формы № 3 для легковых автомобилей (ADR 0037 п. 1, бэклог «Форма № 3»).
--
-- Бланк 0060 объявил колонкой, а не флагом, ровно ради этого случая: «легковые и спецтехника
-- добавятся значением в колонке, а не второй схемой». Значение и добавляется — кода эта правка
-- не требует, шаблон `templates/waybill-leg3.xlsx` размечен и получил задание на обороте.
--
-- Второго входа выдачи не понадобилось, хотя ADR 0037 его предполагал («на служебную машину
-- заявок не заводят, и лист ей пришлось бы рождать другим путём»). Тип `passenger_cars` стоит
-- под видом ТС «Грузоперевозки» с уплощения 0013, поэтому заявка на грузоперевозку легковой
-- машиной заводится сегодняшней формой, кладётся в маршрут и выписывает лист тем же путём, что
-- самосвал. Отличается только бланк.
--
-- Требуемая категория водителя (B) уже проставлена 0059 — и типу, и заведённым машинам, поэтому
-- отбор водителей заработает без правок.
--
-- Идемпотентно: повторный прогон перезапишет то же значение.
UPDATE vehicle_types
SET waybill_form_code = 'leg3'
WHERE code = 'passenger_cars';
