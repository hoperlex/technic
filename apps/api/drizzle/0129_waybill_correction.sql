-- Коррекция задним числом: документ приводится к тому, что было на самом деле.
-- План — `docs/waybill-backdated-correction-plan.md`, §7 (решения Р12, Р16, Р31, Р32, Р35).
--
-- Правка выданного листа как была запрещена, так и остаётся (ADR 0037 п. 10): бланк строгой
-- отчётности с исправленными графами — не документ. Коррекция — это «аннулировать и выписать
-- заново», то есть два номера вместо одного, и схеме от неё нужны ровно три новых факта: у самой
-- операции есть строка, у листа — ссылка на эту операцию и на заменённый номер, у заявки — отметка
-- о том, что операция её задела.
--
-- Почему у операции своя таблица, а не событие аудита. Обоснование правки БСО — единственное, чем
-- эта правка отличается от подделки, и носитель у него обязан быть транзакционным.
-- `writeAudit` (`apps/api/src/lib/audit.ts`) пишет через глобальный `db`, то есть ОТДЕЛЬНЫМ
-- соединением — вне транзакции коррекции, — и заворачивает вставку в try/catch, гасящий ошибку в
-- лог. Значит запись аудита может не появиться при успешной коррекции и, наоборот, остаться после
-- отката: обе стороны этого расхождения одинаково недопустимы, когда речь о том, почему сгорел
-- номер. Аудит пишется по-прежнему, но как дополнение, а не как источник правды (Р16).
--
-- Обратимость. Миграция аддитивная: новая колонка либо необязательна, либо имеет умолчание, новые
-- таблицы пусты, и на пустых значениях все три CHECK'а выполняются тождественно. Откат кода на
-- предыдущую версию схему не ломает — прежний код новых колонок не пишет, а `correction_reason`
-- получает `''` по умолчанию. Обратной миграции репозиторий не держит: `migrate.ts` только
-- накатывает.

-- 1. Операция коррекции.
--
-- Строка на операцию, а не на изменённую сущность: «на рейс выехала другая машина с другим
-- водителем, и это переписало назначения семи заявок» — одно событие, у которого одна причина и
-- один автор (Р2). Разложив его по затронутым строкам, мы получили бы семь копий причины, которые
-- со временем разъедутся, и ни одного места, где видно, что это была одна команда.
CREATE TABLE waybill_corrections (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),

  -- Ключ идемпотентности от клиента (Р31). Коррекция сжигает номер серии, а сеть между порталом и
  -- API рвётся: повтор после таймаута обязан вернуть прежний результат, а не выписать второй лист
  -- взамен уже выписанного. Ключ приходит снаружи, потому что решает его именно клиент — он один
  -- знает, что это ретрай той же кнопки, а не второе нажатие.
  operation_id uuid NOT NULL,

  -- Отпечаток нормализованного тела (Р31): цель, все значения, причина. Одного ключа мало —
  -- ключ отвечает только на «это тот же запрос?», и без отпечатка клиент, переиспользовавший uuid,
  -- молча получил бы чужой результат вместо выполнения своей команды. Тот же ключ с другим телом —
  -- не повтор, а ошибка, и сервер отвечает 409.
  --
  -- Хранится отпечаток, а не тело: сравнение идёт на равенство, длина ответа не важна, а тело
  -- целиком уже лежит в `payload` — в форме, пригодной для чтения человеком.
  fingerprint text NOT NULL,

  -- Что это была за операция. Текст, а не enum, по той же причине, что и разделы дайджеста (0100):
  -- список входов заднего числа прирастает этапами (§11 плана), и добавление нового не должно
  -- требовать ALTER TYPE — реестр допустимых значений живёт в контрактах, сервер отвергает
  -- незнакомые до записи, а CHECK ниже держит нижнюю границу от опечатки.
  kind text NOT NULL,

  -- Причина обязательна и непуста — ради неё таблица и заведена. Пустая строка здесь означала бы
  -- «номер сгорел, объяснения нет», то есть ровно то состояние, которое фича закрывает.
  reason text NOT NULL,

  -- RESTRICT: учётку автора коррекции удалить нельзя, пока за ней числятся правки бланков. Право
  -- у диспетчера и администратора (Р4), увольнение диспетчера — обычное дело, и «кто это сделал»
  -- обязано пережить его уход. Деактивация учётки этому не мешает: строки `users` портал не
  -- удаляет.
  actor_user_id uuid NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),

  -- «Было → стало» снимком. Ссылками это не выражается: справочники живут своей жизнью — машину
  -- переклассифицируют, водителя переводят, ставки пересматривают, — а объяснять операцию придётся
  -- через месяцы, когда спросят «кто принял 11,5 машиночаса за 12 августа». Сюда же уходят снятые
  -- подписи смен с прежними `approved_by`/`approved_at` (Р5): в `vehicle_request_shifts` после
  -- снятия их уже нет, и восстановить их будет неоткуда.
  --
  -- Ответ HTTP из снимка НЕ собирается (Р31): DTO протухнет при первой же правке контракта.
  -- Повтор пересобирает ответ из текущего состояния листов, рейса и заявок, а `payload` существует
  -- ради разбирательств.
  payload jsonb NOT NULL DEFAULT '{}',

  CONSTRAINT waybill_corrections_kind_check
    CHECK (kind IN ('route', 'transfer', 'esm2', 'cancel', 'issue', 'request_date')),
  CONSTRAINT waybill_corrections_reason_check CHECK (btrim(reason) <> '')
);

COMMENT ON TABLE waybill_corrections IS
  'Операция коррекции задним числом (ADR 0101): причина, автор, ключ идемпотентности и снимок '
  '«было → стало». Транзакционный носитель обоснования правки БСО — в отличие от аудита, который '
  'пишется вне транзакции и best-effort.';

-- Уникальность ключа — единственное, что делает повтор безопасным: две параллельные попытки одного
-- ретрая упрутся здесь, а не выпишут по номеру каждая.
CREATE UNIQUE INDEX waybill_corrections_operation_unique
  ON waybill_corrections (operation_id);

-- 2. След операции в самом листе.
--
-- Четыре колонки, потому что вопросов к листу четыре и ответы на них разные.
--
-- `correction_id` — «этот номер РОЖДЁН коррекцией», и `cancel_correction_id` — «этот номер ЕЮ
-- СПИСАН». Две колонки, а не одна: у листа бывают обе операции сразу — рождён перевыпиской, а
-- через неделю списан следующей коррекцией, — и одна колонка заставила бы выбирать, какую из них
-- забыть. Забывалась бы при этом операция рождения, к которой относится `correction_reason`, и
-- строка журнала стала бы говорить причину одной операции со ссылкой на другую.
--
-- Признак коррекции для фильтра (Р28) — любая из двух: списание без перевыписки (Р20) заполняет
-- вторую, выписка задним числом без замены (дыры 1 и 3) — первую, и обе обязаны попадать в
-- «только коррекции».
--
-- `correction_reason` — причина в самом листе, поверх записи операции. Дублирование намеренное и
-- симметричное существующему: у аннулированного листа причина уже лежит своей колонкой
-- (`cancel_reason`, обязательна при аннулировании), и класть причину перевыписки в другое место
-- значило бы завести два разных ответа на один вопрос «почему этот номер такой» (Р35).
--
-- `corrects_waybill_id` — заменённый номер. Хронология журнала при коррекции рвётся неизбежно
-- (Р10: номер берётся из хвоста серии, вставить его в середину нельзя), и ссылка — то
-- единственное, чем разрыв объясняется читателю.
ALTER TABLE waybills
  ADD COLUMN correction_id uuid REFERENCES waybill_corrections (id) ON DELETE RESTRICT,
  ADD COLUMN cancel_correction_id uuid REFERENCES waybill_corrections (id) ON DELETE RESTRICT,
  ADD COLUMN correction_reason text NOT NULL DEFAULT '',
  ADD COLUMN corrects_waybill_id uuid;

COMMENT ON COLUMN waybills.correction_id IS
  'Операция коррекции, породившая этот лист (ADR 0101). К ней же относится `correction_reason`.';
COMMENT ON COLUMN waybills.cancel_correction_id IS
  'Операция коррекции, списавшая этот лист. Рядом с `cancelled_by`/`cancel_reason`, которые '
  'отвечают на тот же вопрос для обычного списания.';
COMMENT ON COLUMN waybills.corrects_waybill_id IS
  'Заменённый номер: этот лист выписан взамен указанного. Пусто у backdated-выписки без замены.';

-- Самоссылка отдельным именованным ограничением, а не инлайном: имя `..._fkey` от PostgreSQL
-- ничего не сказало бы в тексте ошибки, а разбирать 23503 по этой связи придётся — цепочки
-- коррекций (Р32) собирает и портал, и выгрузка.
--
-- RESTRICT: листы портал не удаляет вовсе (испорченный аннулируют), но если такой путь когда-нибудь
-- появится, рвать цепь A → B → C посередине нельзя — от B останется ссылка в никуда, и журнал
-- перестанет объяснять разрыв нумерации.
ALTER TABLE waybills
  ADD CONSTRAINT waybills_corrects_waybill_fk
    FOREIGN KEY (corrects_waybill_id) REFERENCES waybills (id) ON DELETE RESTRICT;

-- 3. Инварианты связи.
--
-- Колонки выше PostgreSQL добавляет метаданными (nullable и константное умолчание, PG 11+), а вот
-- каждый CHECK ниже — однократный проход по таблице под ACCESS EXCLUSIVE. `NOT VALID` намеренно не
-- используется: он оставил бы старые строки непроверенными и потребовал бы второй миграции с
-- `VALIDATE CONSTRAINT` ради того же результата, а журнал листов для одного прохода мал.

-- Лист не заменяет сам себя. Без этого цикл длиной один прошёл бы: FK самоссылки его не ловит.
ALTER TABLE waybills
  ADD CONSTRAINT waybills_corrects_self_check
    CHECK (corrects_waybill_id IS NULL OR corrects_waybill_id <> id);

-- Замена всегда объяснена (Р35). Проверять это сервисом мало: перевыписка идёт из нескольких
-- входов (коррекция рейса, перенос между рейсами, сверка ЭСМ-2), и достаточно одному из них
-- забыть про причину, чтобы в журнале появился номер, заменивший другой номер неизвестно почему.
ALTER TABLE waybills
  ADD CONSTRAINT waybills_correction_reason_check
    CHECK (corrects_waybill_id IS NULL OR btrim(correction_reason) <> '');

-- Всякий лист, рождённый операцией, объяснён — включая тот, у которого замены нет: выписку на
-- прошедший день по существующему рейсу и неделю ЭСМ-2 задним числом (дыры 1 и 3).
--
-- Оговорки про аннулированный здесь нет и не нужно: с разделением колонок `correction_id` значит
-- ровно «рождён операцией», а списавшая операция ушла в `cancel_correction_id`. Списанный
-- задним числом лист, который сам родился обычным порядком, эту проверку не задевает вовсе — его
-- объясняет `cancel_reason`, куда причина операции и пишется (Р35).
ALTER TABLE waybills
  ADD CONSTRAINT waybills_correction_issue_reason_check
    CHECK (correction_id IS NULL OR btrim(correction_reason) <> '');

-- Замена номера рождается только операцией. Без этого правила схема допускает лист, заменивший
-- другой лист вне какой бы то ни было коррекции: причина у него есть (проверка выше), а кто её
-- написал, когда и в рамках чего — ответить нечем, и связать такую замену со вторым рейсом
-- переноса тоже нечем. Инвариант держит схема, а не сервис, по той же причине, по какой его
-- держат остальные CHECK'и этой миграции: входов у коррекции несколько, и достаточно одному
-- забыть про запись операции.
ALTER TABLE waybills
  ADD CONSTRAINT waybills_corrects_operation_check
    CHECK (corrects_waybill_id IS NULL OR correction_id IS NOT NULL);

-- 4. Индексы.
--
-- Каждый номер заменён не более одного раза. Цепочка A → B → C этим не запрещена — в ней у каждого
-- звена свой предшественник, — а запрещено разветвление: два действующих листа, объявляющих себя
-- заменой одному и тому же номеру, сделали бы вопрос «чем в итоге закрыт день» неразрешимым.
-- Аннулированные из индекса не исключаются намеренно: попытка скорректировать уже аннулированный
-- лист — отказ сервиса (Р32), и второй замены у списанного номера быть не должно тем более.
CREATE UNIQUE INDEX waybills_corrects_unique
  ON waybills (corrects_waybill_id)
  WHERE corrects_waybill_id IS NOT NULL;

-- «Какие листы родила эта операция» — вопрос карточки коррекции и ответа на повтор (Р31: ответ
-- пересобирается из текущего состояния, а не из снимка). Частичный: у подавляющего большинства
-- листов коррекции нет и не будет.
CREATE INDEX waybills_correction_idx
  ON waybills (correction_id)
  WHERE correction_id IS NOT NULL;

-- То же со стороны списания: фильтр «только коррекции» (Р28) спрашивает обе колонки, потому что
-- списание без перевыписки (Р20) заполняет лишь эту.
CREATE INDEX waybills_cancel_correction_idx
  ON waybills (cancel_correction_id)
  WHERE cancel_correction_id IS NOT NULL;

-- 5. Какие заявки задела операция.
--
-- Связь многие-ко-многим, потому что у коррекции рейса это весь его состав — до десяти заявок в
-- форме № 3 (ADR 0068), — а у переноса между рейсами ровно одна, зато операция одна на два рейса
-- (Р30). Ссылкой из заявки такое не выражается: заявку корректируют не один раз за жизнь.
CREATE TABLE vehicle_request_corrections (
  correction_id uuid NOT NULL REFERENCES waybill_corrections (id) ON DELETE CASCADE,
  -- CASCADE, как у прочих спутников заявки (смены — 0086, факт закрытия — 0053, досрочное
  -- завершение — 0071): строка здесь — указатель «операция задела эту заявку», а не носитель
  -- обоснования. Обоснование лежит в `waybill_corrections` вместе со снимком «было → стало» и
  -- переживает уборку заявки целиком; RESTRICT здесь сделал бы неудаляемой саму заявку ради
  -- указателя, который без неё ни на что не указывает.
  request_id uuid NOT NULL REFERENCES vehicle_requests (id) ON DELETE CASCADE,
  PRIMARY KEY (correction_id, request_id)
);

-- Первичный ключ отвечает на «какие заявки в этой операции», а обратный вопрос — «что делали с
-- этой заявкой задним числом» — задаёт карточка заявки при каждом открытии, и по ведущей колонке
-- ключа на него не ответить.
CREATE INDEX vehicle_request_corrections_request_idx
  ON vehicle_request_corrections (request_id);
