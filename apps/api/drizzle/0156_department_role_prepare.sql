-- Шаг prepare этапа 9: «Виза отдела» выдаётся руководителям отделов заранее, за релиз до перевода
-- (план реструктуризации модели доступа, §13.2 и §15 этап 9; ADR 0113).
--
-- Тот же шаг, что 0155, и по тем же правилам — отдельным файлом, потому что этап другой:
--
--   department_head → department + «Виза отдела»
--
-- Расширения доступа здесь нет вовсе: пара «роль + набор» равна прежней роли поимённо, вся разница
-- между ними — одно право `vehicleRequests.approve`. Комендант, единственное объявленное расширение
-- реформы, живёт в этапе 8 и в этот файл не заходит.
--
-- ПОЧЕМУ ЭТАП ОТДЕЛЬНЫЙ, А РЕЛИЗ ОДИН. Этапы 8 и 9 переводят разные роли и откатываются по
-- отдельности — снимок хранит номер этапа именно затем. Шаг prepare у них при этом одинаков и
-- ничего не переключает, поэтому едет одним релизом: два релиза подряд с одинаковым содержимым
-- ничего не проверяют, а срок между prepare и переводом каждый этап отсчитывает свой.
--
-- ЧТО ЗДЕСЬ НЕ НУЖНО, В ОТЛИЧИЕ ОТ 0155. Роль `department` — не новая и базовой ролью надстроек
-- оргтехники была всегда (`ROLE_ADDON_BASE_ROLES`), так что дописывать её никуда не надо. А вот
-- собранные администратором наборы под роль `department_head` — та же беда §13.2, и половина её
-- решается так же: `department` дописывается рядом со старой ролью, а не вместо неё.

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 1. Наборы, собранные администратором под роль руководителя отдела.
--
-- Аддитивно и на релиз раньше перевода — обоснование в 0155, пункт 1b: переписав роль сейчас, мы
-- погасили бы права держателей на весь релиз, пока роль у них ещё прежняя.
INSERT INTO grant_roles (grant_id, role)
SELECT DISTINCT gr.grant_id, 'department'::role
FROM grant_roles gr
JOIN grants g ON g.id = gr.grant_id
WHERE gr.role = 'department_head'
  AND NOT g.is_system
  AND g.deleted_at IS NULL
ON CONFLICT (grant_id, role) DO NOTHING;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 2. Снимок.
--
-- Без фильтров по активности и архиву — по той же причине, что в 0155: выключенный руководитель
-- отдела вернётся с ролью, которой в `ROLES` уже не будет.
INSERT INTO user_role_migration (user_id, stage, role_before, role_after)
SELECT u.id, 9, u.role, 'department'::role
FROM users u
WHERE u.role = 'department_head'
ON CONFLICT (user_id, stage) DO NOTHING;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 3. Взведённое назначение.
--
-- Гейт совместимости у «Визы отдела» стоит на роли `department` (миграция 0153), поэтому до
-- перевода назначение прав не даёт: виза у руководителя отдела и так есть от матрицы. Действовать
-- набор начнёт ровно в тот момент, когда роль сменится, — и перевод не отнимет подпись, ради
-- сохранения которой шаг и делается.
INSERT INTO user_grants (user_id, grant_id, granted_by, origin, migration_id)
SELECT m.user_id, g.id, NULL, 'migration', m.id
FROM user_role_migration m
JOIN grants g ON g.code = 'department_approval' AND g.deleted_at IS NULL
WHERE m.stage = 9
ON CONFLICT (user_id, grant_id) DO NOTHING;
