-- Автозапчасти: склад гаража (план `docs/auto-parts-plan.md`, §5 «Модель данных», миграция A;
-- решения Р2, Р3, Р7—Р9, Р11—Р13).
--
-- ЗАЧЕМ. Вопрос «есть ли у нас этот фильтр и сколько» портал сегодня не отвечает вовсе: парк он
-- знает (`vehicles`, `vehicle_models`), обслуживание знает (`vehicle_maintenance`, `0147`), а
-- детали, которые при этом обслуживании ставят, живут в тетради механика. Цена ошибки та же, что у
-- расходников оргтехники, только предмет дороже: машина стоит в гараже, пока не выяснится, что
-- ремня на складе нет, — а выясняется это в момент, когда он понадобился.
--
-- ЧТО ЗАВОДИТСЯ: две IMMUTABLE-функции правил написания (код и наименование), карточка позиции с
-- остатком, разметка применимости «позиция — модель ИЛИ тип техники», журнал движения остатка и
-- ТРИ триггера, делающие остаток свойством базы, а не обещанием маршрута.
--
-- ЧЕГО ЗДЕСЬ НЕТ. Ни одной строки данных: справочник наполняют руками механики по ходу работы
-- (Р17), и выдумывать за них номенклатуру миграции нечем. Расхода по обслуживанию тоже нет — он
-- целиком в миграции B, вместе с колонкой `maintenance_id` журнала.
--
-- ПОРЯДОК ОТНОСИТЕЛЬНО СОСЕДЕЙ. Эта миграция обязана идти ПОСЛЕ `0032` (`vehicle_models`) и
-- `0004` (`vehicle_types`): на них ссылается разметка применимости. И строго ПЕРЕД миграцией B
-- (`0188`) — та достраивает журнал ссылкой на акт обслуживания и заводит инвариант расхода, а
-- достраивать нечего, пока журнала не существует. Обратной зависимости нет: ни один прежний
-- объект схемы про автозапчасти не знает, и накат A в одиночку оставляет базу в рабочем виде —
-- склад с ручной корректировкой, без расхода.
--
-- ПОЧЕМУ ТРИГГЕРОВ ТРИ, А НЕ ОДИН. Приём целиком перенесён из `0172` (расходники оргтехники)
-- вместе с обоснованием: обещание «каждое изменение остатка попадает в журнал, а журнал не врёт»
-- распадается на три разные двери, и одна проверка закрывает ровно одну из них:
--
--   цепочка (`BEFORE INSERT` на журнале) ....... ловит НЕВЕРНОЕ событие — «было» не то, что
--                                                оставило предыдущее, или «стало» не то, что лежит
--                                                в карточке; но молчит там, где события нет вовсе;
--   неизменяемость (`BEFORE UPDATE OR DELETE`) . запрещает подчистить прошлое: `RESTRICT` со
--                                                стороны позиции защищает историю целиком, а
--                                                построчную правку — нет;
--   покрытие (отложенный constraint-триггер) ... ловит ОТСУТСТВИЕ события: `UPDATE auto_parts SET
--                                                quantity = 7` скриптом проходит мимо первых двух
--                                                насквозь.
--
-- Вместе они замыкают круг: событие без правки карточки не проходит цепочку (её «стало» обязано
-- равняться остатку, а «стало» ≠ «было» требует `CHECK`), правка карточки без события не проходит
-- покрытие, а исправить задним числом уже записанное нельзя. Граница названа честно и там же, где
-- у оргтехники: `TRUNCATE` строковых триггеров не вызывает вовсе — от него защищают права, а не
-- схема.
--
-- ПОЧЕМУ ПРАВИЛА НАПИСАНИЯ СВОИ, А НЕ ЧУЖИЕ (Р12). Функции `office_equipment_consumable_code_key`
-- (`0172`) и `office_equipment_model_name_normalize` (`0171`) сегодня делают ровно то же, что
-- нужно здесь, и соблазн позвать их велик. Взять их нельзя: хозяин у них другой — ИТ-служба со
-- своей выгрузкой из учётной системы, — и первая же правка ради дословного регистра оттуда молча
-- изменила бы уникальность автозапчастей. Уникальный индекс при этом остался бы построенным по
-- старому правилу (см. ниже про `IMMUTABLE`), и справочник гаража разошёлся бы сам с собой, не
-- уронив ни одного запроса. Копия правила намеренная; её цена — две функции вместо одной, и она
-- меньше цены общего владения.
--
-- ОБРАТИМОСТЬ. Миграция аддитивная: три новые таблицы, две функции правил и триггеры на этих же
-- новых таблицах. Существующие данные не читаются и не меняются, поэтому и блокировки первой
-- строкой здесь нет. Протокол выката необратимых миграций (`docs/schema-cutover-protocol.md`) к
-- ней не применяется. Обратной миграции репозиторий не держит (`migrate.ts` только накатывает);
-- при необходимости объекты снимаются вручную, и порядок снятия обратен порядку заведения.

-- ── 1. Правила написания: код и наименование ──
--
-- Правил ДВА, потому что вопросов два, и путать их нельзя.
--
--   `auto_part_code_key`  — артикул: «21126-1006040», «MANN W914/2», «06A115561B». Пробелов в нём
--     не бывает вовсе, поэтому пробел внутри — всегда мусор переноса (письмо, Excel, прайс
--     поставщика), а не часть кода: он УДАЛЯЕТСЯ, а не схлопывается. Схлопывание оставило бы
--     «MANN W914 /2» отдельной строкой справочника — двойником, которого глазами не отличить.
--     Регистр поднимается: артикул набирают и строчными, «mann w914/2» — тот же самый фильтр.
--
--   `auto_part_name_key`  — наименование: «Фильтр масляный», «Ремень генератора». Здесь пробел
--     значащий и потому СХЛОПЫВАЕТСЯ в один, а края обрезаются. Плюс `ё` сводится к `е`:
--     «Крёстовина» и «Крестовина» — одна деталь, и различие между ними в портале не видно никому,
--     кроме уникального индекса.
--
-- ЧЕГО НИ ОДНО ИЗ ПРАВИЛ НЕ ДЕЛАЕТ — не трогает дефисы и точки. В артикулах и в названиях они
-- значащие («W914/2», «М10х1.25»), и «нормализация», выбрасывающая их, склеила бы две настоящие
-- номенклатуры в одну. По той же причине не сводятся визуальные двойники: кириллическая «В» и
-- латинская «B» остаются разными кодами — подмена буквы на похожую это уже угадывание.
--
-- ПОЧЕМУ КЛАСС СИМВОЛОВ ШИРЕ, ЧЕМ `\s`. `\s` в Postgres опирается на ctype локали базы, и
-- неразрывные пробелы U+00A0 и U+202F он пробелами НЕ считает (проверено на `en_US.utf8`), а
-- приезжают они постоянно: Word ставит U+00A0 автозаменой, свежие сборки Windows разделяют
-- разряды узким U+202F. Записаны они escape-видом `\uXXXX`, который понимает регулярное выражение
-- Postgres, а не собой: невидимый байт в файле миграции нельзя вычитать на ревью, а любой
-- редактор способен его потерять или заменить.
--
-- `IMMUTABLE` — требование индекса по выражению, и отсюда же цена: `CREATE OR REPLACE` любой из
-- этих функций молча меняет смысл индекса и `CHECK`, а построенные индексы продолжают считать
-- по-старому. Менять правило можно только миграцией, которая перестраивает индексы и заново
-- сводит справочник.
--
-- `SET search_path = pg_catalog` — отличие от образца `0172`, и оно осознанное: ключ, по которому
-- строится уникальный индекс, не должен зависеть от того, что стоит в `search_path` у сессии,
-- позвавшей функцию. Все её составные части (`upper`, `regexp_replace`, `translate`, `btrim`)
-- живут в `pg_catalog`, и прибить разрешение имён к нему — единственный способ сказать это схемой,
-- а не соглашением. Цена — функция перестаёт быть встраиваемой в план; на полутора тысячах строк
-- справочника это не измеряется.
CREATE FUNCTION auto_part_code_key(t text) RETURNS text
  LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE SET search_path = pg_catalog
AS $$
  SELECT upper(regexp_replace(t, '[\s\u00a0\u202f]+', '', 'g'))
$$;

COMMENT ON FUNCTION auto_part_code_key(text) IS
  'Ключ артикула автозапчасти (docs/auto-parts-plan.md Р12): верхний регистр, все пробелы '
  'выброшены, включая неразрывные. По нему уникальность кода держит частичный индекс '
  'auto_parts_code_unique, он же входит второй половиной в пару «имя + код», и его же зовёт '
  'маршрут, отвечая «позиция с таким артикулом уже заведена». Своя, а не общая с расходниками '
  'оргтехники: правила совпадают, а хозяева разные. IMMUTABLE ради индекса по выражению.';

-- Порядок внутри ОБЯЗАТЕЛЕН: сначала `ё → е`, потом схлопывание пробелов, потом обрезка краёв и
-- только затем регистр. Обратный порядок «сначала btrim, потом схлопывание» кажется тем же самым,
-- но `btrim` без второго аргумента снимает ТОЛЬКО обычные пробелы — краевой таб или неразрывный он
-- не трогает, а схлопывание после него делает из них краевой пробел, убирать который уже некому.
-- Функция перестала бы быть идемпотентной, и `CHECK` пустоты ниже отверг бы её собственный
-- результат. Урок дословно из `0171`, где на этом уже спотыкались.
CREATE FUNCTION auto_part_name_key(t text) RETURNS text
  LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE SET search_path = pg_catalog
AS $$
  SELECT upper(btrim(regexp_replace(translate(t, 'ёЁ', 'еЕ'), '[\s\u00a0\u202f]+', ' ', 'g')))
$$;

COMMENT ON FUNCTION auto_part_name_key(text) IS
  'Ключ наименования автозапчасти (docs/auto-parts-plan.md Р12): ё сведено к е, любая череда '
  'пробельных символов (включая неразрывные) свёрнута в один пробел, края обрезаны, регистр '
  'поднят. Дефисы и точки НЕ трогаются — в артикулах и названиях они значащие. Служит первой '
  'половиной пары «имя + код» в auto_parts_name_code_unique и проверкой непустоты имени. В отличие '
  'от кода, наименование хранится ДОСЛОВНО: ключ — то, по чему опознают, а не то, что показывают.';

-- ── 2. Карточка позиции (Р2, Р9, Р12) ──
--
-- Склад виртуальный: остаток — одно число в карточке, мест хранения нет (Р2). Таблица `warehouses`
-- в портале описывает склады ПОСТАВЩИКОВ (ADR 0051) и к этому вопросу отношения не имеет.
CREATE TABLE auto_parts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Артикул. НЕОБЯЗАТЕЛЕН (Р12) — и это главное отличие от расходников оргтехники, где код
  -- обязателен, потому что приезжает выгрузкой из учётной системы. Здесь справочник заводит
  -- механик по ходу работы, и требовать артикул значило бы запретить ему завести «Ремень
  -- генератора» до того, как бухгалтерия пришлёт номенклатуру. Хранится уже нормализованным
  -- (см. `CHECK` ниже): в верхнем регистре и без пробелов.
  code text,
  -- Наименование ДОСЛОВНО, как его написал механик. Нормализуется только КЛЮЧ (по нему ищут
  -- двойника), а не хранимое значение: «Фильтр масляный MANN W914/2» показывают человеку, и
  -- поднятый регистр на экране был бы криком.
  name text NOT NULL,
  -- Единица измерения (Р9). У расходников оргтехники её нет вовсе — «(шт)» живёт внутри
  -- наименования, потому что оно дословно из учётной системы. Здесь так нельзя: на складе гаража
  -- лежат штуки, литры, комплекты и метры, и «5» без единицы — это не число, а загадка.
  --
  -- Текстом со свободным вводом, а не перечнем: перечень пришлось бы вести отдельным экраном, а
  -- набор единиц заранее неизвестен и на счёт никак не влияет — единица подписывает число, а не
  -- участвует в нём. Умолчание «шт» — самый частый случай.
  unit text NOT NULL DEFAULT 'шт',
  -- Остаток. Портал его не вычисляет и формой карточки не правит: правка идёт отдельной ручкой
  -- `POST /auto-parts/:id/stock`, пишущей событие в журнал (Р3). Три триггера ниже делают это
  -- правилом базы, а не соглашением маршрута.
  quantity integer NOT NULL DEFAULT 0,
  -- Позиция, которую больше не покупают, гасят флагом (Р11): у неё остаются разметка применимости
  -- и, скорее всего, история движения. Погашенная не попадает в подбор и новой строкой акта не
  -- добавляется, но уже стоящую в акте строку можно уменьшить или снять (Р24) — это возврат на
  -- склад, и запрещать его незачем.
  is_active boolean NOT NULL DEFAULT true,
  comment text NOT NULL DEFAULT '',
  -- Авторы правки карточки. `SET NULL`, как у карточек техники: справочник переживает увольнение
  -- своего автора, и удерживать учётку ради строки справочника незачем. У СОБЫТИЯ остатка правило
  -- противоположное и объяснено на своём месте.
  created_by uuid REFERENCES users (id) ON DELETE SET NULL,
  updated_by uuid REFERENCES users (id) ON DELETE SET NULL,
  -- `created_at` здесь не только реквизит: это ориентир предупреждения о двойном списании (Р20).
  -- Открывающий остаток вводят числом «сколько лежит сейчас», и в нём уже учтено всё, что
  -- установлено раньше; значит строка в акте, датированном РАНЬШЕ заведения позиции, может списать
  -- одну и ту же деталь дважды. Портал об этом предупреждает, сравнивая `performed_on` акта с этой
  -- датой, — и не запрещает: заказчик выбрал свободу ввода задним числом.
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  -- Пустой код проверяется той же функцией, а не `btrim`: строка из одного неразрывного пробела
  -- для `btrim` не пуста, а артикулом при этом не является. Пустая строка вместо `NULL` дала бы
  -- второе представление состояния «кода нет» — и первый же отбор «позиции без артикула» разошёлся
  -- бы с уникальностью пары ниже, где `NULL` заменяется пустой строкой ровно один раз.
  CONSTRAINT auto_parts_code_not_blank_check
    CHECK (code IS NULL OR auto_part_code_key(code) <> ''),
  -- Код лежит уже нормализованным. Без этой проверки правило держал бы только индекс, то есть
  -- ключ, — а в самой карточке остался бы «mann w914 /2 » с хвостом и внутренним пробелом:
  -- уникальность соблюдена, дефект тихий, и ломает он сверку глазами с прайсом. Отказ здесь — это
  -- 500 у маршрута, поленившегося нормализовать ввод, и он честнее испорченного справочника:
  -- функция маршруту доступна, вызвать её — одна строка.
  CONSTRAINT auto_parts_code_normalized_check
    CHECK (code IS NULL OR code = auto_part_code_key(code)),
  -- В наименовании обязан быть хотя бы один НАСТОЯЩИЙ знак, и меряется это ключом, а не `btrim`:
  -- имя из одного U+00A0 `btrim` считает непустым, и в справочник встала бы строка, выглядящая
  -- пустой, — с артикулом, остатком и разметкой, но без имени, по которому её ищут. Инвариант,
  -- держащийся сегодня формой (zod `.trim()` в JS неразрывные снимает), обязан жить в схеме:
  -- дверей в справочник больше одной.
  CONSTRAINT auto_parts_name_not_blank_check CHECK (auto_part_name_key(name) <> ''),
  -- Единица без единого знака означала бы то же, что её отсутствие, только незаметно: «5 ␣» на
  -- экране читается как «5» и снова превращает число в загадку. Здесь `btrim` достаточен — от
  -- единицы не требуется ни уникальности, ни ключа, и вопрос к ней ровно один: «написано ли хоть
  -- что-нибудь».
  CONSTRAINT auto_parts_unit_not_blank_check CHECK (btrim(unit) <> ''),
  -- Отрицательный остаток не бывает даже промежуточно (Р7): «минус два фильтра» — это не долг, а
  -- ошибка ввода, и записать её значило бы соврать следующему, кто придёт за деталью. Маршрут
  -- отвечает 409 «на складе 3, списываете 5» до того, как это ограничение сработает пятисоткой.
  CONSTRAINT auto_parts_quantity_check CHECK (quantity >= 0)
);

COMMENT ON TABLE auto_parts IS
  'Автозапчасти — складская позиция гаража (docs/auto-parts-plan.md §5, миграция A): '
  'необязательный артикул, дословное наименование, единица и остаток, который правится только '
  'событием журнала auto_part_stock_entries. Склад виртуальный: мест хранения нет (Р2).';

-- Артикул уникален, КОГДА ОН ЕСТЬ. Индекс частичный, потому что `NULL` в обычном уникальном
-- индексе не конфликтует сам с собой — то есть позиции без артикула прошли бы и так, — но
-- частичность говорит это словами, а не полагается на знание тонкости про `NULL`. Ключ по ФУНКЦИИ,
-- хотя `CHECK` выше делает его сегодня равносильным `UNIQUE (code)`: равносильность — следствие
-- соседнего ограничения, а не свойство ключа, и первая же миграция, ослабившая `CHECK`, молча
-- превратила бы уникальность в регистрозависимую. Заодно маршруту есть с чем сойтись в
-- `ON CONFLICT`: арбитра Postgres сопоставляет с индексом дословно.
CREATE UNIQUE INDEX auto_parts_code_unique
  ON auto_parts (auto_part_code_key(code)) WHERE code IS NOT NULL;

-- Уникальна ПАРА «ключ имени + ключ кода», и каждая половина по отдельности не годится (Р12):
--
--   не одно имя — «Фильтр масляный» разных производителей с разными артикулами это законные разные
--     позиции, и запрет второй строки заставил бы механика выдумывать имена;
--   не один код — у позиций без артикула его нет вовсе, а два «Ремня генератора» без артикула это
--     как раз двойник, которого надо отбить.
--
-- `coalesce(..., '')` превращает «артикула нет» в значение, которое индекс умеет сравнивать: без
-- него `NULL` в ключе снова сделал бы все безартикульные строки неконфликтующими, и правило пары
-- не работало бы ровно там, ради чего заведено. Пустая строка на месте артикула безопасна —
-- `CHECK` выше не пропускает её в саму колонку, значит спутать «кода нет» с «код пустой» нельзя.
CREATE UNIQUE INDEX auto_parts_name_code_unique
  ON auto_parts (auto_part_name_key(name), coalesce(auto_part_code_key(code), ''));

-- Поиск идёт по наименованию подстрокой («фильтр масл»), тем же способом, что в остальных
-- справочниках. Артикула в индексе нет намеренно: его ищут целиком, и на это работает уникальный
-- индекс выше.
CREATE INDEX auto_parts_name_trgm ON auto_parts USING gin (name gin_trgm_ops);

-- ── 3. Применимость: к чему подходит деталь (Р8) ──
--
-- Вопрос звучит с двух сторон, и обе законны: «к каким машинам подходит эта деталь» (карточка
-- позиции) и «что подходит вот этой машине» (форма акта). Отвечать на них поиском по подстроке
-- нельзя — это промах на разнописании, который в портале уже разбирали.
--
-- ССЫЛОК ДВЕ, И ЭТО НЕ ЗАПАС. Привязки к модели недостаточно: `vehicles.vehicle_model_id`
-- необязателен (в источнике есть машины без марки), и машина без модели осталась бы без ответа
-- вовсе. Кроме того, половина расходуемого — масло, антифриз, фильтры общего применения —
-- применима к ТИПУ, а не к модели: «всем самосвалам» это утверждение о типе.
--
-- ОДНА ТАБЛИЦА, А НЕ ДВЕ: разметка одна и ведётся одним экраном, а два места ведения одного
-- свойства расходятся при первой же правке. Пустая разметка законна — деталь завели, а к чему она
-- подходит вопрос к механику, и ждать ответа, не заводя позицию, значит потерять её совсем.
CREATE TABLE auto_part_applicability (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- `CASCADE`: разметка — свойство живой позиции, а не история. Удаляют позицию только пока по ней
  -- нет движения (журнал ниже держит это `RESTRICT`), и тащить за собой разметку в этот момент
  -- нечего.
  auto_part_id uuid NOT NULL REFERENCES auto_parts (id) ON DELETE CASCADE,
  -- `RESTRICT` у обеих сторон (Р11): модель или тип, на которые ссылается разметка, не удаляются.
  -- Иначе деталь молча потеряла бы половину ответа «к чему подходит», и заметить это было бы
  -- нечем — строка просто исчезла бы каскадом.
  vehicle_model_id uuid REFERENCES vehicle_models (id) ON DELETE RESTRICT,
  vehicle_type_id uuid REFERENCES vehicle_types (id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  -- РОВНО ОДНА ссылка, и записано это через `<>` булевых значений, а не длинным `OR`: «одна из
  -- двух» и «не обе и не ни одной» — одно утверждение. Строка с обеими ссылками означала бы
  -- «подходит этой модели И всем машинам этого типа», то есть второе поглощает первое и
  -- уникальность обеих пар ниже перестаёт что-либо гарантировать; строка с пустыми ссылками —
  -- разметка, не размечающая ничего.
  CONSTRAINT auto_part_applicability_target_check
    CHECK ((vehicle_model_id IS NULL) <> (vehicle_type_id IS NULL))
);

COMMENT ON TABLE auto_part_applicability IS
  'Применимость автозапчасти (docs/auto-parts-plan.md Р8): одна разметка на две оси — модель ИЛИ '
  'тип техники, ровно одна ссылка в строке. Две оси потому, что модель у машины необязательна, а '
  'масла и фильтры общего применения — свойство типа. Разметка, а не история: снимается свободно.';

-- Пара уникальна на каждой оси: «подходит» — это да или нет, и вторая такая же строка ничего не
-- добавляет, зато удвоила бы позицию в подборе по машине (Р21 считает ранг через `EXISTS` именно
-- поэтому). Индексы частичные, потому что в каждой строке заполнена ровно одна ссылка, и в общем
-- уникальном индексе по двум колонкам `NULL` снова не конфликтовал бы сам с собой.
CREATE UNIQUE INDEX auto_part_applicability_model_unique
  ON auto_part_applicability (auto_part_id, vehicle_model_id) WHERE vehicle_model_id IS NOT NULL;
CREATE UNIQUE INDEX auto_part_applicability_type_unique
  ON auto_part_applicability (auto_part_id, vehicle_type_id) WHERE vehicle_type_id IS NOT NULL;

-- Обратная сторона связи. По ней идут два вопроса, которые ключи выше не обслуживают (те читаются
-- слева направо, от позиции): ранг подбора «что подходит этой машине» (Р21) и проверка `RESTRICT`
-- при попытке удалить модель или тип.
CREATE INDEX auto_part_applicability_model_idx
  ON auto_part_applicability (vehicle_model_id) WHERE vehicle_model_id IS NOT NULL;
CREATE INDEX auto_part_applicability_type_idx
  ON auto_part_applicability (vehicle_type_id) WHERE vehicle_type_id IS NOT NULL;

-- ── 4. Журнал движения остатка (Р3) ──
--
-- Журнал здесь не след действия (для этого есть аудит), а сам предмет: на вопрос «куда делись
-- двенадцать фильтров» отвечает только он.
--
-- ССЫЛКИ НА АКТ ОБСЛУЖИВАНИЯ ЗДЕСЬ ЕЩЁ НЕТ — колонку `maintenance_id` и оба `CHECK` про виды
-- добавляет миграция B. До неё приложение не создаёт ни `issue`, ни `return`, поэтому вид события
-- у всех строк остаётся `manual`, и отсутствие ссылки ничего не ослабляет.
CREATE TABLE auto_part_stock_entries (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Порядок держит счётчик, а не время: две правки одной секунды по `created_at` неразличимы, а
  -- цепочка «было — стало» обязана строиться однозначно. По этому номеру обе проверки журнала
  -- находят его хвост — `ORDER BY seq DESC LIMIT 1` и в сверке цепочки, и в проверке покрытия.
  --
  -- `GENERATED ALWAYS` означает «номер раздаёт база», но НЕ означает «назначить нельзя»:
  -- `INSERT ... OVERRIDING SYSTEM VALUE` вписывает свой. Порядок держится не запретом, а тем, куда
  -- смотрят обе проверки: событие с подложенным маленьким номером сверку цепочки пройдёт, а
  -- отложенная проверка покрытия сверит остаток карточки со «стало» ХВОСТА и отменит транзакцию.
  seq bigint GENERATED ALWAYS AS IDENTITY,
  -- `RESTRICT`, а не `CASCADE`: правило «появилось движение — только гашение флагом» (Р11) держит
  -- схема, а не вежливость маршрута. Пока журнал пуст, позиция удаляется совсем — так убирают
  -- опечатку первого дня.
  auto_part_id uuid NOT NULL REFERENCES auto_parts (id) ON DELETE RESTRICT,
  -- Вид события: `manual` — ручная корректировка механика, `issue` — списание по акту
  -- обслуживания, `return` — возврат по акту (снятие строки, уменьшение количества, аннулирование
  -- акта). `DEFAULT 'manual'` сохраняет контракт ручной ручки: вид она проставляет сама, клиент
  -- его не выбирает и выдать корректировку за расход не может.
  entry_kind text NOT NULL DEFAULT 'manual',
  quantity_before integer NOT NULL,
  quantity_after integer NOT NULL,
  -- Причина обязательна: журнал без неё отвечает «стало 8» на вопрос «почему стало 8». У движений
  -- по акту она НЕЙТРАЛЬНАЯ и пишется сервером («Списание по акту обслуживания»), а реквизиты акта
  -- в текст не вписываются намеренно (Р5): дату, номер и машину акта правят после движения, и
  -- снимок разошёлся бы с документом, на который сам же и ссылается. Ручная корректировка
  -- по-прежнему требует причины от человека — там снимка нет вовсе.
  reason text NOT NULL,
  -- `RESTRICT`: запись «кто изменил остаток», теряющая автора вместе с увольнением, отвечает на
  -- свой единственный вопрос словом «неизвестно». Здесь это не строка справочника, а событие, и
  -- `SET NULL` карточки ему не годится.
  changed_by uuid NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  -- Дата СКЛАДСКОГО учёта — когда движение отражено в портале (Р20). Она сознательно отличается от
  -- `vehicle_maintenance.performed_on`, даты ХОЗЯЙСТВЕННОЙ: акт задним числом законен, и
  -- расхождение этих двух дат — норма, а не дефект. Всякий будущий отчёт обязан назвать, какую из
  -- них берёт: склад считается по дате движения, обслуживание — по дате акта.
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT auto_part_stock_reason_check CHECK (btrim(reason) <> ''),
  -- Событие обязано что-то менять. Отсюда прямое следствие для заведения позиции: первая строка
  -- журнала пишется только при ненулевом начальном остатке, а заведение с нулём — не событие, а
  -- отсутствие событий, и «0 → 0» это ограничение не пропустило бы.
  CONSTRAINT auto_part_stock_change_check CHECK (quantity_after <> quantity_before),
  -- Оба конца неотрицательны: «было −1» не бывает так же, как «стало −1». Проверять только «стало»
  -- значило бы разрешить записать в историю то, чего не могло быть в карточке.
  CONSTRAINT auto_part_stock_amount_check CHECK (quantity_after >= 0 AND quantity_before >= 0),
  CONSTRAINT auto_part_stock_kind_check CHECK (entry_kind IN ('manual', 'issue', 'return'))
);

COMMENT ON TABLE auto_part_stock_entries IS
  'Журнал движения остатка автозапчастей (docs/auto-parts-plan.md Р3): append-only физически, '
  'порядок держит seq, цепочку «было — стало» сверяет триггер. created_at — дата СКЛАДСКОГО учёта, '
  'она же отличается от даты акта обслуживания при вводе задним числом (Р20).';

-- Индекс отвечает на единственный частый вопрос журнала — «чем кончилось предыдущее событие этой
-- позиции»: `ORDER BY seq DESC LIMIT 1` в цепочке и в проверке покрытия, а также лента журнала в
-- карточке. `DESC` в определении ради них и стоит. Уникальность здесь следствие, а не цель: `seq`
-- и так уникален на всю таблицу, но ключом сказано, что двух событий с одним номером у одной
-- позиции не бывает — то есть цепочка ветвиться не может. Он же обслуживает `RESTRICT` при
-- попытке удалить позицию: `auto_part_id` идёт первым столбцом.
CREATE UNIQUE INDEX auto_part_stock_seq_idx ON auto_part_stock_entries (auto_part_id, seq DESC);

-- ── 5. Триггер цепочки: событие не врёт (Р3) ──
--
-- Функция САМА берёт строку позиции `FOR UPDATE` — не потому, что маршрут этого не делает (делает,
-- первым шагом транзакции), а потому что защита, работающая только когда её вызвали правильно,
-- защищает не схему, а вежливых: прямая вставка скриптом или из миграции проходила бы мимо.
-- Повторный `FOR UPDATE` в той же транзакции бесплатен. Без блокировки два механика прочитали бы
-- 12, записали «12 → 10» и «12 → 8», и цепочка стала бы враньём при верном итоге.
--
-- ПРОВЕРЯЮТСЯ ОБА КОНЦА, и это главное в функции. Сверка только со «стало» пропустила бы строку
-- «999 → 12» при остатке 12: итог верен, а в журнале навсегда осталось бы выдуманное «было», по
-- которому потом считают расход. Сверка только с «было» пропустила бы событие, не доехавшее до
-- карточки. Поэтому:
--
--   `quantity_before` = «стало» предыдущего события этой позиции (по `max(seq)`), а для первой
--     строки — ноль: до первого события позиция заведена нулём. Заведение с ненулевым остатком —
--     это и есть первое событие «0 → N», и другого способа получить непустую карточку нет;
--   `quantity_after`  = фактический остаток карточки, то есть правка карточки обязана идти ПЕРЕД
--     вставкой события. Порядок «карточка → событие» — тот же, что у маршрута (Р3).
--
-- Отсюда же и то, чего в функции нет: события без правки карточки. Оно не проходит не отдельной
-- проверкой, а этими двумя вместе — «было» равно остатку (иначе цепочка уже порвана), «стало» тоже
-- обязано равняться остатку, а `CHECK` требует их различия.
CREATE FUNCTION auto_part_stock_chain() RETURNS trigger
  LANGUAGE plpgsql SECURITY INVOKER SET search_path = public, pg_temp AS $$
DECLARE
  v_quantity integer;
  v_previous integer;
BEGIN
  SELECT p.quantity INTO v_quantity
    FROM auto_parts p
   WHERE p.id = NEW.auto_part_id
   FOR UPDATE;

  -- Несуществующую позицию поймал бы и внешний ключ, но позже и не теми словами: ключи проверяются
  -- после `BEFORE`-триггеров, то есть первым сюда приходит наш `SELECT`, и молчать о пустом
  -- результате значило бы сравнивать «стало» с `NULL` — то есть пропустить строку.
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Автозапчасть % не найдена: событие остатка не на что записать', NEW.auto_part_id
      USING ERRCODE = 'foreign_key_violation';
  END IF;

  SELECT e.quantity_after INTO v_previous
    FROM auto_part_stock_entries e
   WHERE e.auto_part_id = NEW.auto_part_id
   ORDER BY e.seq DESC
   LIMIT 1;

  -- Первому событию сверяться не с чем — до него остаток был нулём. `coalesce`, а не
  -- `IF NOT FOUND`: `quantity_after` объявлен `NOT NULL`, поэтому пустой результат отличим от
  -- значения однозначно, и одна строка честнее ветки.
  v_previous := coalesce(v_previous, 0);

  IF NEW.quantity_before <> v_previous THEN
    RAISE EXCEPTION
      'Событие остатка автозапчасти %: «было %», а предыдущее событие оставило %',
      NEW.auto_part_id, NEW.quantity_before, v_previous
      USING ERRCODE = 'check_violation';
  END IF;

  IF NEW.quantity_after <> v_quantity THEN
    RAISE EXCEPTION
      'Событие остатка автозапчасти %: «стало %», а в карточке %',
      NEW.auto_part_id, NEW.quantity_after, v_quantity
      USING ERRCODE = 'check_violation';
  END IF;

  RETURN NEW;
END
$$;

CREATE TRIGGER auto_part_stock_chain
  BEFORE INSERT ON auto_part_stock_entries
  FOR EACH ROW EXECUTE FUNCTION auto_part_stock_chain();

-- `ENABLE ALWAYS` — ОТДЕЛЬНОЙ командой: в `CREATE TRIGGER` такого слова нет, а без него на
-- реплике-приёмнике проверка не сработает вовсе. Приём тот же, что у `0167`, `0171` и `0172`.
ALTER TABLE auto_part_stock_entries ENABLE ALWAYS TRIGGER auto_part_stock_chain;

-- ПОДПИСИ ОБЪЕКТОВ КАТАЛОГА. Дальше у каждой функции и каждого триггера стоит `COMMENT ON`, и это
-- не украшение: контур покрытия ниже состоит из ТРЁХ объектов с почти одним именем
-- (`auto_part_stock_covered` зовут и триггер на карточке, и чистую функцию, а исполняется
-- `auto_part_stock_covered_trg`). Пространства имён у них разные, поэтому база не возражает, — а
-- человек, открывший `\d+` или `pg_trigger`, видит одно слово трижды. Подпись отвечает ему там,
-- где он смотрит.
COMMENT ON FUNCTION auto_part_stock_chain() IS
  'Сверка цепочки журнала остатка автозапчастей (Р3): проверяет ОБА конца события — «было» против '
  'хвоста журнала (по seq), «стало» против остатка карточки, которую берёт FOR UPDATE сама, не '
  'полагаясь на маршрут. Вызывается только триггером auto_part_stock_chain.';

COMMENT ON TRIGGER auto_part_stock_chain ON auto_part_stock_entries IS
  'BEFORE INSERT: исполняет функцию auto_part_stock_chain(). ENABLE ALWAYS — проверка работает и '
  'на реплике-приёмнике.';

-- ── 6. Триггер неизменяемости: прошлое не подчищают (Р3, Р11) ──
--
-- `RESTRICT` со стороны позиции защищает историю целиком, но не построчно: прямой `UPDATE` или
-- `DELETE` по самим строкам он не запрещает, а «журнал, который нельзя подчистить» обязан означать
-- именно это. Ошибку исправляют не строкой, а следующим событием: «ошиблись, вернули 15» с
-- причиной — так исправление остаётся видимым, а не заменяет собой то, что было.
--
-- Запрет безусловный, исключений нет и быть не может: законного пути, который сносил бы строки
-- журнала, в схеме не существует — позиция с движением не удаляется вовсе, и каскада сюда не ведёт
-- ни одного. Миграция B добавит журналу ссылку на акт, но и та `RESTRICT`: акт с движениями
-- аннулируют, а не удаляют (Р6).
CREATE FUNCTION auto_part_stock_immutable() RETURNS trigger
  LANGUAGE plpgsql SECURITY INVOKER SET search_path = public, pg_temp AS $$
BEGIN
  RAISE EXCEPTION
    'Журнал остатка автозапчастей неизменяем: ошибку исправляют следующим событием, а не правкой'
    USING ERRCODE = 'check_violation';
END
$$;

CREATE TRIGGER auto_part_stock_immutable
  BEFORE UPDATE OR DELETE ON auto_part_stock_entries
  FOR EACH ROW EXECUTE FUNCTION auto_part_stock_immutable();

ALTER TABLE auto_part_stock_entries ENABLE ALWAYS TRIGGER auto_part_stock_immutable;

COMMENT ON FUNCTION auto_part_stock_immutable() IS
  'Безусловный отказ: журнал остатка автозапчастей неизменяем (Р3). Тела у проверки нет и быть не '
  'должно — законного пути, который правил бы или сносил строки журнала, в схеме не существует. '
  'Вызывается только триггером auto_part_stock_immutable.';

COMMENT ON TRIGGER auto_part_stock_immutable ON auto_part_stock_entries IS
  'BEFORE UPDATE OR DELETE: отбивает правку и удаление строк журнала, исполняя функцию '
  'auto_part_stock_immutable(). ENABLE ALWAYS.';

-- ── 7. Отложенный триггер покрытия: остаток без события невозможен (Р3) ──
--
-- Цепочка ловит неверное событие, но молчит там, где события нет: `UPDATE auto_parts SET
-- quantity = 7` скриптом прошёл бы насквозь, и обещание «каждое изменение остатка попадает в
-- журнал» осталось бы обещанием маршрута. Эта проверка и есть то, что делает его свойством базы.
--
-- ОТЛОЖЕННЫЙ, а не немедленный: внутри транзакции порядок «правка карточки → вставка события»
-- законен и обязателен (цепочка сверяет «стало» с карточкой), и немедленная проверка отбивала бы
-- саму правку остатка на первом же шаге — то есть запрещала бы единственный правильный путь.
--
-- ФУНКЦИЯ ПРИНИМАЕТ ИДЕНТИФИКАТОР И ПЕРЕЧИТЫВАЕТ ПО НЕМУ СОСТОЯНИЕ — ни `NEW.quantity`, ни любой
-- другой снимок ряда в ней не участвуют, и это не стиль, а условие правильности. Здесь оно дороже,
-- чем у расходников: правка строк акта пишет НЕСКОЛЬКО движений по одной позиции в одной
-- транзакции (сняли две штуки, добавили одну), отложенные триггеры срабатывают на коммите все, и
-- первый из них, сравнивая свой снимок «стало 10» с журналом, где уже 8, дал бы отказ на ровном
-- месте. Перечитанное состояние у всех одно и то же — и оно верное.
--
-- Приём взят у проверки полноты категории в `0035`: та так же читает состояние по идентификатору и
-- молча выходит, если строку удалили в этой же транзакции. Здесь нужен ровно такой же выход —
-- позиция без движения удаляется законно, и требовать от удалённой карточки соответствия журналу
-- значило бы запретить удаление опечатки первого дня.
CREATE FUNCTION auto_part_stock_covered(p_auto_part_id uuid) RETURNS void
  LANGUAGE plpgsql SECURITY INVOKER SET search_path = public, pg_temp AS $$
DECLARE
  v_quantity integer;
  v_last integer;
BEGIN
  SELECT p.quantity INTO v_quantity
    FROM auto_parts p
   WHERE p.id = p_auto_part_id;

  -- Карточку удалили в этой же транзакции — проверять нечего.
  IF NOT FOUND THEN
    RETURN;
  END IF;

  SELECT e.quantity_after INTO v_last
    FROM auto_part_stock_entries e
   WHERE e.auto_part_id = p_auto_part_id
   ORDER BY e.seq DESC
   LIMIT 1;

  -- Пустой журнал допустим только при нуле: «завели и ничего не приходило» — это отсутствие
  -- событий, а не событие (`CHECK` не пропустил бы «0 → 0»). А вот ненулевой остаток при пустом
  -- журнале — ровно тот случай, ради которого проверка стоит: остаток взялся ниоткуда.
  IF v_last IS NULL THEN
    IF v_quantity <> 0 THEN
      RAISE EXCEPTION
        'Остаток автозапчасти % равен %, но в журнале нет ни одного события',
        p_auto_part_id, v_quantity
        USING ERRCODE = 'check_violation';
    END IF;
    RETURN;
  END IF;

  IF v_quantity <> v_last THEN
    RAISE EXCEPTION
      'Остаток автозапчасти % равен %, а последнее событие журнала оставило %',
      p_auto_part_id, v_quantity, v_last
      USING ERRCODE = 'check_violation';
  END IF;
END
$$;

-- Триггерная обёртка отделена от самой проверки нарочно: проверку зовут не только триггером — ею
-- же сверяют базу одним запросом после выката (§14 плана: `SELECT auto_part_stock_covered(id) FROM
-- auto_parts;`) и в db-тестах, а функция, умеющая работать только изнутри триггера, для этого
-- недоступна. Тот же расклад, что у `vehicle_category_assert_consistent` в `0035`.
CREATE FUNCTION auto_part_stock_covered_trg() RETURNS trigger
  LANGUAGE plpgsql SECURITY INVOKER SET search_path = public, pg_temp AS $$
BEGIN
  PERFORM auto_part_stock_covered(NEW.id);
  RETURN NULL;
END
$$;

-- `UPDATE OF quantity` — а не любой `UPDATE`: правка наименования, единицы, комментария или
-- гашения флагом остатка не касается, и гонять по ним проверку значило бы читать журнал на каждое
-- переименование. `INSERT` в списке обязателен: карточка, заведённая сразу с ненулевым остатком и
-- без события, — это тот же остаток из ниоткуда, только вошедший другой дверью.
CREATE CONSTRAINT TRIGGER auto_part_stock_covered
  AFTER INSERT OR UPDATE OF quantity ON auto_parts
  DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION auto_part_stock_covered_trg();

ALTER TABLE auto_parts ENABLE ALWAYS TRIGGER auto_part_stock_covered;

-- Три объекта контура покрытия носят почти одно имя — подписи разводят их поимённо.
COMMENT ON FUNCTION auto_part_stock_covered(uuid) IS
  'ЧИСТАЯ проверка «остаток без события невозможен» (Р3): по идентификатору позиции ПЕРЕЧИТЫВАЕТ и '
  'карточку, и хвост журнала — снимка ряда не берёт вовсе. Иначе несколько движений одной '
  'транзакции (правка строк акта пишет их пачкой) дали бы ложный отказ: первый триггер сработал бы '
  'на коммите со своим устаревшим снимком. Карточка, удалённая в этой же транзакции, — молчаливый '
  'выход. Годится и для сверки базы одним запросом, а не только изнутри триггера.';

COMMENT ON FUNCTION auto_part_stock_covered_trg() IS
  'Обёртка constraint-триггера auto_part_stock_covered: передаёт NEW.id в чистую функцию '
  'auto_part_stock_covered(uuid) и ничего больше не делает. Разделены нарочно — проверку зовут и '
  'запросом, а функция, умеющая работать только изнутри триггера, для этого недоступна.';

COMMENT ON TRIGGER auto_part_stock_covered ON auto_parts IS
  'Отложенный constraint-триггер (DEFERRABLE INITIALLY DEFERRED) AFTER INSERT OR UPDATE OF '
  'quantity: на коммите исполняет auto_part_stock_covered_trg(), а та зовёт чистую '
  'auto_part_stock_covered(uuid). Отложенный потому, что внутри транзакции порядок «правка '
  'карточки, затем событие» законен, и немедленная проверка отбивала бы саму правку. ENABLE ALWAYS.';
