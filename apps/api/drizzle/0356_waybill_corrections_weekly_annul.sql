-- Восьмой вид операции журнала коррекций — `weekly_annul` (ADR 0218 решение 5).
--
-- Свой вид, а не `weekly` (его завела 0157 для проведения просроченной недели): предмет разный.
-- Проведение двигает сроки состава вперёд и выписывает бумагу за прошедшие дни; аннулирование
-- двигает их назад и бумагу гасит. На вопрос «что делали с этим бланком задним числом» журнал
-- обязан отвечать двумя разными словами — одно слово на два противоположных события отвечало бы
-- одинаково там, где спрашивают разное.
--
-- `CHECK` вместо `ALTER TYPE` — по решению, принятому там, где колонка заведена (миграция 0129):
-- список входов заднего числа прирастает этапами, реестр значений живёт в контрактах и в `$type`
-- drizzle-схемы, а цена выбора — вот такая аддитивная миграция на каждый новый вид.
--
-- Снимка авторизации (`authorization_scope`) этот вид не требует, как и `weekly`: его
-- авторизацией служит `authorize` в `runCorrection`, который спрашивает право на каждой попытке,
-- включая повтор по ключу. Соответствующий CHECK перечисляет только `crew` и `assignment_tail` и
-- здесь не трогается.

ALTER TABLE waybill_corrections
  DROP CONSTRAINT waybill_corrections_kind_check,
  ADD CONSTRAINT waybill_corrections_kind_check CHECK (
    kind IN (
      'route', 'transfer', 'esm2', 'cancel', 'issue', 'request_date', 'weekly',
      'crew', 'assignment_tail', 'day_batch', 'weekly_annul'
    )
  );
