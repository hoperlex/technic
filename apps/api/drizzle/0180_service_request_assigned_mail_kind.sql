-- Вид письма «заявка на обслуживание назначена исполнителю»
-- (план `docs/office-equipment-requests-rework-plan.md`, §7.3, Н13; решение опроса В16).
--
-- Третье письмо модуля и первое, адресованное **людям**, а не ящику службы: получают его
-- назначенные поимённо сотрудники и оператор сервисной компании. Своим значением `mail_kind`, а не
-- под видом соседнего: `mail_messages` уникальна по паре `(kind, dedupe_key)`, и письмо о
-- назначении, притворившееся письмом о визе, подавляло бы соседа по той же строке истории статуса —
-- пропадало бы одно из двух, и молча.
--
-- Значение добавляется отдельной миграцией и в той же транзакции кодом не используется: раннер
-- применяет файл миграции целиком в одной транзакции, а PostgreSQL не разрешает пользоваться новым
-- значением enum до её фиксации. Тот же приём — в миграциях 0142, 0122, 0114, 0103, 0065, 0054.
--
-- Обратимость: аддитивна, смысл существующих данных не меняется. Обратного шага нет и быть не
-- может — значение enum в PostgreSQL не удаляется; откат кода просто перестаёт его писать.

ALTER TYPE mail_kind ADD VALUE IF NOT EXISTS 'service_request_assigned';
