-- Учётка водителя невозможна без карточки человека.
-- План — `docs/driver-portal-plan.md`, §2 (Р2); ADR 0102.
--
-- Водитель в портале — это `person`, у которого появилась учётка, а не учётка, которой приписали
-- человека. Карточка первична: из неё берутся ФИО, телефон и СНИЛС, по ней же считается задание
-- дня (рейсы и листы ссылаются на `persons`, а не на `users`). Живая учётка роли `driver` без
-- `person_id` не ответит НИ НА ОДИН вопрос кабинета — ни какое у человека задание, ни на какой
-- машине он работал, — а выяснится это в шесть утра, когда он полез смотреть рейс.
--
-- Условие про архив — не смягчение правила, а его необходимая часть. Учётки уходят в архив мягко
-- (ADR 0063), а `users.person_id` объявлен `ON DELETE SET NULL` (миграция 0018): удаление человека
-- обнуляет ссылку у его архивной учётки. Без ветки `deleted_at IS NOT NULL` такая строка стала бы
-- неудаляемой и непочинимой — CHECK не дал бы ни обновить её, ни снести человека. Обратная
-- сторона решения записана в API: восстановление архивной учётки роли `driver` требует выбрать
-- человека той же транзакцией, иначе `restore` упрётся в это же условие (Р8).
--
-- Аддитивная: на существующих строках условие выполняется тождественно — роли `driver` до этого
-- релиза ни у кого нет.
ALTER TABLE users
  ADD CONSTRAINT users_driver_person_check
  CHECK (role <> 'driver' OR person_id IS NOT NULL OR deleted_at IS NOT NULL);
