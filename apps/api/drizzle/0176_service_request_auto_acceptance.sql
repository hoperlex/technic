-- Автоматическое закрытие заявки оргтехники: чем оно записывается (план
-- `docs/office-equipment-requests-rework-plan.md`, §4.1, §4.4 и §5, миграция M2; решение Н7
-- набросков). Выпуск 1 «Цикл и полномочия», волна В2.
--
-- ЗАЧЕМ. Заявка, простоявшая сутки в «Решена», закрывается порталом сама. Записать это сегодня
-- нечем, и упирается оно в две разные стены:
--
--   · в самой заявке приёмка — это ПАРА «кто принял + когда», и `service_requests_accepted_check`
--     требует их вместе или никак. У автоматического закрытия автора-человека нет вовсе, и первая
--     же автозакрытая заявка упёрлась бы в это ограничение;
--   · в истории статусов `changed_by` объявлен `NOT NULL` — событие без человека туда не ложится,
--     а лента истории обязана показывать «Портал (автоматически)», а не пропуск.
--
-- ЧТО ЗАВОДИТСЯ: колонка источника приёмки с backfill'ом, замена парного ограничения на мягкое и
-- пара «nullable-автор + источник действия» в истории статусов. Триггеров здесь нет.
--
-- ГЛАВНОЕ ПРАВИЛО ЭТОЙ МИГРАЦИИ — ОКНО ВЫКАТА (§3 плана). Штатный деплой накатывает миграции ДО
-- перезапуска сервисов (`docs/schema-cutover-protocol.md`, §1), и между накатом и перезапуском на
-- новой схеме работает СТАРЫЙ код: он принимает заявку парой «автор + дата», не зная про источник,
-- и откатывает приёмку, очищая ту же пару и снова не зная про источник. Ни одно ограничение ниже
-- не запрещает ему ни того, ни другого. Жёсткая связка «источник есть ровно у принятой» приезжает
-- выпуском 2 (M9), когда старого кода в проде уже нет.
--
-- ОБРАТИМОСТЬ. Аддитивна, кроме одного снятого ограничения: смысл существующих данных не меняется,
-- backfill проставляет уже принятым заявкам то значение, которое они и означали («принял человек»).
-- `DROP NOT NULL` и `ADD COLUMN ... DEFAULT` таблицу не переписывают (PostgreSQL 11+), так что
-- долгой блокировки на записи здесь нет. Протокол выката необратимых миграций
-- (`docs/schema-cutover-protocol.md`) к ней не применяется.

-- ── 1. Источник приёмки в заявке ──
--
-- ПОРЯДОК ЧЕТЫРЁХ ШАГОВ НИЖЕ ОБЯЗАТЕЛЕН: колонка → backfill → снятие старого ограничения → новое.
-- Переставь backfill за ограничение — и оно упало бы на уже принятых заявках; сними старое
-- ограничение раньше, чем нужно, — ничего не изменится, но порядок «сначала данные, потом правило»
-- держится по всему репозиторию, и нарушать его ради экономии одной строки незачем.

ALTER TABLE service_requests ADD COLUMN acceptance_source text;

-- Всё, что принято до этой миграции, принято человеком: автоматического закрытия до неё не было.
UPDATE service_requests SET acceptance_source = 'human' WHERE accepted_at IS NOT NULL;

-- Старое парное ограничение («автор и дата заполнены вместе или никак») снимается ЗДЕСЬ, а не
-- выпуском 2: автозакрытие приезжает уже в выпуске 1 и пишет `accepted_at` без автора. Снятие
-- ограничения — не то же самое, что установка нового (§3, п. 4 плана): старому коду оно не нужно,
-- он по-прежнему пишет пару целиком, а новому мешает. Обратное направление парной проверки —
-- «автор без даты приёмки невозможен» — не теряется, а возвращается в M9 вместе со связкой
-- источника: пока идёт окно выката, лишних ограничений на этой колонке быть не должно.
ALTER TABLE service_requests DROP CONSTRAINT service_requests_accepted_check;

-- Мягкое ограничение выпуска 1. Оно проверяет ровно две вещи и намеренно не проверяет третью:
--
--   · значение из словаря — `human` либо `auto`, третьего источника приёмки не бывает;
--   · у `auto` НЕ МОЖЕТ БЫТЬ АВТОРА-ЧЕЛОВЕКА: «портал закрыл сам, а закрыл Иванов» — это не
--     подробность, а противоречие, и такая строка врала бы в ленте истории и в отчёте.
--
-- Чего проверки НЕТ, и оба раза это решение, а не забывчивость:
--
--   · `human` НЕ ТРЕБУЕТ непустого `accepted_by`. Ссылка объявлена `ON DELETE SET NULL`, и удаление
--     уволенного сотрудника обнулило бы её — с требованием автора такое удаление упёрлось бы в это
--     ограничение, то есть учётку нельзя было бы убрать из-за заявки, принятой год назад. Источник
--     отвечает на вопрос «человек или портал», имя — отдельная и теряемая вместе с учёткой
--     подробность;
--   · СВЯЗКИ «источник есть ровно у принятой» здесь нет (§3, п. 2 плана). Старый код в окне выката
--     откатывает приёмку, очищая `accepted_by/at` и не зная про источник, — связка уронила бы ему
--     откат. Она встаёт в M9, и та же миграция подчищает остаток: проставляет `human` принятым в
--     окне и обнуляет источник у откаченных.
--
-- Отсюда требование к коду выпуска 1, без которого миграция бессмысленна: пустой источник у
-- принятой заявки читается как «принято человеком» (заявка, принятая старым кодом после наката,
-- живёт так до M9, то есть неделю), а откат приёмки очищает источник вместе с парой.
ALTER TABLE service_requests ADD CONSTRAINT service_requests_acceptance_source_check CHECK (
  acceptance_source IS NULL
  OR (acceptance_source IN ('human','auto')
      AND (acceptance_source <> 'auto' OR accepted_by IS NULL))
);

-- ── 2. Автор события в истории статусов ──
--
-- Пара «nullable-автор + источник действия», а не строка-заглушка «система» в `changed_by`:
-- заглушка означала бы учётку, которой нет, и её пришлось бы заводить, прятать из списков, не
-- давать войти и помнить о ней в каждом отчёте по людям.

ALTER TABLE service_request_status_history ALTER COLUMN changed_by DROP NOT NULL;
ALTER TABLE service_request_status_history ADD COLUMN actor_source text NOT NULL DEFAULT 'user';

-- Ограничение здесь ЖЁСТКОЕ, и это не противоречит §3: старый код пишет историю только с автором и
-- про `actor_source` не знает — умолчание `'user'` попадает ровно в разрешённую половину. Запрещает
-- оно две бессмыслицы сразу: событие человека без человека и событие портала с автором.
-- Существующие строки проходят как есть: автор у них есть, источник им проставлен умолчанием.
ALTER TABLE service_request_status_history
  ADD CONSTRAINT service_request_status_history_actor_check CHECK (
    actor_source IN ('user','system') AND (actor_source = 'user') = (changed_by IS NOT NULL)
  );
