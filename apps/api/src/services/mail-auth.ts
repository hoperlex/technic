import { roleLabels, type Role } from '@technic/contracts';
import { config } from '../config';
import { assertOwnOrigin, type MailContent } from './mail-templates';

/**
 * Письма про доступ к порталу: подтверждение адреса, сброс пароля, уведомление о смене пароля,
 * решение администратора по заявке на регистрацию и заведение учётной записи вручную.
 *
 * Чего в этих письмах нет и не будет: пароля — ни нового, ни временного. Ссылка подтверждает
 * владение ящиком, а пароль человек задаёт сам на странице портала; отправленный почтой пароль
 * остаётся в ящике навсегда и годится для входа любому, кто до этого ящика доберётся.
 *
 * Имя получателя в письмах не используется намеренно: на этапе «забыли пароль» портал отвечает
 * одинаково и существующему адресу, и чужому, а обращение по имени выдало бы, что учётка есть.
 */

/**
 * Адрес страницы портала. Проверка живёт здесь, а не у каждого шаблона: ссылка обязана вести на
 * свой портал — письмо с чужим адресом, подписанное порталом, это фишинг с нашей подписью, а
 * `PUBLIC_ORIGIN` берётся из окружения и может быть задан неверно.
 */
function portalLink(path = '/'): string {
  const href = `${config.publicOrigin}${path}`;
  assertOwnOrigin(href, config.publicOrigin);
  return href;
}

/**
 * Ссылка с одноразовым токеном. Origin проверяется у адреса без токена: на origin токен не влияет,
 * а в текст возможной ошибки — и дальше в журнал — он бы попал.
 */
function link(path: string, token: string): string {
  return `${portalLink(path)}?token=${encodeURIComponent(token)}`;
}

function hours(seconds: number): string {
  const h = Math.round(seconds / 3600);
  if (h <= 1) return 'час';
  return h < 5 ? `${h} часа` : `${h} часов`;
}

