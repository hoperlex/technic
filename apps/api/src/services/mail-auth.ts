import { config } from '../config';
import { assertOwnOrigin, type MailContent } from './mail-templates';

/**
 * Письма про доступ к порталу: подтверждение адреса, сброс пароля, уведомление о смене пароля.
 *
 * Чего в этих письмах нет и не будет: пароля — ни нового, ни временного. Ссылка подтверждает
 * владение ящиком, а пароль человек задаёт сам на странице портала; отправленный почтой пароль
 * остаётся в ящике навсегда и годится для входа любому, кто до этого ящика доберётся.
 *
 * Имя получателя в письмах не используется намеренно: на этапе «забыли пароль» портал отвечает
 * одинаково и существующему адресу, и чужому, а обращение по имени выдало бы, что учётка есть.
 */

function link(path: string, token: string): string {
  const href = `${config.publicOrigin}${path}?token=${encodeURIComponent(token)}`;
  // Ссылка обязана вести на свой портал: письмо с чужим адресом, подписанное порталом, — это
  // фишинг с нашей подписью, а `PUBLIC_ORIGIN` берётся из окружения и может быть задан неверно.
  assertOwnOrigin(href, config.publicOrigin);
  return href;
}

function hours(seconds: number): string {
  const h = Math.round(seconds / 3600);
  if (h <= 1) return 'час';
  return h < 5 ? `${h} часа` : `${h} часов`;
}

export const VERIFY_SUBJECT = 'Подтвердите адрес электронной почты';

export function verifyEmailContent(token: string): MailContent {
  return {
    title: 'Подтверждение адреса',
    blocks: [
      {
        kind: 'paragraph',
        text: 'В портале «Техник» заведена заявка на регистрацию с этим адресом. Подтвердите, что ящик ваш, — после этого администратор сможет выдать доступ.',
      },
      { kind: 'link', href: link('/verify-email', token), label: 'Подтвердить адрес' },
      {
        kind: 'note',
        text: `Ссылка действует ${hours(config.mail.verifyTtl)}. Если заявку подавали не вы, письмо можно не читать: без подтверждения доступ не выдаётся.`,
      },
    ],
    footer: 'Письмо отправлено автоматически, отвечать на него не нужно.',
  };
}

