import { eq } from 'drizzle-orm';
import { config } from '../config';
import type { db } from '../db/client';
import {
  wasteTicketCheckResolutions,
  wasteTicketFiles,
  wasteTicketPages,
  wasteTickets,
} from '../db/schema';
import { enqueueJob, JOB_RECOGNIZE_WASTE_TICKET_FILE } from '../lib/jobs';

// Стык цикла заявки на вывоз с распознаванием талонов (ADR 0114, план `docs/waste-ticket-ocr-plan.md`).
//
// Здесь только две операции, которые делает сторона API: поставить работу при закрытии заявки и
// унести распознанное при откате. Ни чтения, ни сверки, ни разбора: замечания считаются в
// `waste-ticket-checks.ts`, обработка файла живёт в воркере. Маршрут статуса зовёт обе функции
// одной строкой каждую — по образцу `request-files.ts` и `waybill-issue.ts`: сам он про статусы
// заявки, и перечень таблиц распознавания в нём был бы вторым местом, где этот перечень надо
// помнить.
//
// ОБЕ функции принимают `tx` и обязаны идти внутри транзакции закрытия/отката — той самой, что
// первым действием взяла `waste_requests FOR UPDATE` (Р11). Это общий замок контура: без него
// откат проигрывает фоновой задаче, и заявка, выглядящая только что заведённой, остаётся с
// бумагой, которую никто не прикладывал.

type Tx = Parameters<Parameters<typeof db.transaction>[0]>[0];

/**
 * Поставить распознавание талонов, приложенных этим закрытием (ADR 0114, решение 4; Р11).
 *
 * По задаче на файл: страниц в этот момент не существует — их заводит воркер после скачивания и
 * растеризации, и одна из них может оказаться шестой при лимите в пять (Р10).
 *
 * `tx` обязателен и передаётся дальше в `enqueueJob`. Задача и связь талона появляются вместе или
 * не появляются вовсе: задача, записанная отдельным соединением, уехала бы в очередь до коммита
 * закрытия — воркер не нашёл бы ни выполненной заявки, ни связи, — а при откате транзакции она
 * осталась бы искать талон, которого никто не приложил.
 *
 * Ставится только на файлы **этого** закрытия. Талоны, приложенные прошлым закрытием (заявку
 * вернули в работу и закрывают снова), уже несут свои файловые строки и разобранные талоны:
 * вторая задача на них перераспознавала бы бумагу, которую человек уже подтвердил, — а
 * перераспознавание это отдельная кнопка со своей политикой (Р13).
 */
export async function enqueueTicketRecognition(
  tx: Tx,
  requestId: string,
  fileIds: string[],
  /**
   * `forced` — кнопка «перераспознать» (Р13): попытка обходит кэш и уходит в прокси со своим
   * ключом идемпотентности. Признак едет в payload, а не в отдельный тип задачи: работа та же,
   * отличается только отношение к кэшу, и второй тип пришлось бы регистрировать в двух местах.
   */
  opts: { forced?: boolean } = {},
): Promise<void> {
  if (fileIds.length === 0) return;
  // Выключенное распознавание — не «работа впрок». Задачи копились бы в очереди типом, которого
  // никто не разбирает, а после включения модуля разом ушли бы в модель пачкой месячной давности:
  // деньги за вызовы и сканы, отправленные наружу, — за заявки, которые давно закрыты и сверены
  // руками. Ставить работу имеет смысл ровно тогда, когда её есть кому взять (Р29).
  if (!config.ticketOcr.enabled) return;
  // ТИП ЗАЯВКИ БОЛЬШЕ НЕ ОТБИРАЕТ БУМАГУ (ADR 0150, снимает Р1 и решение 1 ADR 0114). Раньше здесь
  // стоял `requestType !== 'waste_removal'`, и довод был про сверки: металлолом принимают по весу
  // (ADR 0067), у контейнерных операций вывезенного нет вовсе — считать им объём нечем. Довод
  // остался верным и ничего не решает: талон это прежде всего НОМЕР и ДАТА, а уникальность номера
  // в области перевозчика (Р17) и сверка дня вывоза (Р19) применимы к любой бумаге, чем бы её ни
  // мерили. Отказ читать талон металлолома означал не «нечего проверить», а «повторно
  // предъявленную бумагу никто не заметит».
  //
  // Проверки, которым нечего сравнивать, молчат сами и без фильтра по типу: `collectVolume`
  // сверяет сумму талонов с `waste_request_completions.volume_m3`, а у металлолома вывезенное
  // лежит в `weight_tons` и колонка объёма пуста (миграция 0091) — условие `fact != null`
  // не выполняется. Так же молчит перегруз против заявки, у которой заказанного объёма нет.
  // Отдельного «отключить объёмные сверки для типа X» не заводится: это была бы вторая копия
  // знания, которое уже выражено пустой колонкой.
  // Последовательно, а не пачкой: талонов у закрытия единицы (общий потолок вложений — 20,
  // ADR 0024), а транзакция drizzle параллельных запросов не допускает.
  for (const fileId of fileIds) {
    await enqueueJob(
      JOB_RECOGNIZE_WASTE_TICKET_FILE,
      opts.forced ? { requestId, fileId, forced: true } : { requestId, fileId },
      { tx },
    );
  }
}

/**
 * Унести распознанное вместе с талонами при возврате заявки в «Новую» (Р22; ADR 0114, решение 12).
 *
 * Заявка после сброса обязана выглядеть только что заведённой (ADR 0020): «Новая», за которой
 * числятся талоны прошлого закрытия, держала бы чужой номер занятым — а номер талона это область
 * уникальности перевозчика (Р17), и следующая бумага с тем же номером упёрлась бы в конфликт с
 * заявкой, которую никто не закрывал.
 *
 * ПОПЫТКИ РАСПОЗНАВАНИЯ (`waste_ticket_recognition_attempts`) НЕ УДАЛЯЮТСЯ — и это не недосмотр.
 * Попытка принадлежит **содержимому**, а не заявке: ключ у неё `page_sha256 + движок + модель +
 * версии промпта и предобработки`, заявки в ключе нет вовсе (Р12). Она же служит кэшем, и
 * благодаря ему повторное закрытие тем же листом — самый частый исход отката — не стоит ни копейки
 * и не отправляет скан наружу второй раз. Снесённый вместе с заявкой кэш означал бы, что каждая
 * ошибка диспетчера оплачивается заново.
 *
 * Порядок удаления идёт от зависимых к родителям намеренно. Талоны — первыми: у них составной
 * внешний ключ на страницу с `ON DELETE SET NULL (page_id)`, то есть удаление страниц их не
 * уносит, а лишь обнуляет ссылку — талон пережил бы уборку и остался бы висеть на заявке. Файловые
 * строки и страницы ушли бы и каскадом от `request_files` при отвязке (`waste_ticket_files_link_fk`),
 * но полагаться на это здесь нельзя: уборка обязана быть верной независимо от того, в каком
 * порядке маршрут делает отвязку, и обязана читаться одним куском, а не собираться из каскадов.
 *
 * Предложения перераспознавания (`waste_ticket_proposals`) и слепые перепроверки
 * (`waste_ticket_blind_checks`) уходят каскадом от талона: их родитель — талон, и без него они
 * бессмысленны. Принятия расхождений (`waste_ticket_check_resolutions`) висят на заявке и своего
 * каскада не имеют, поэтому удаляются явно: принятое расхождение — это решение человека по
 * конкретным цифрам, и пережить закрытие, которого больше нет, оно не должно (Р21).
 *
 * Отменять уже поставленные задачи не нужно: воркер перепроверяет состояние под тем же замком
 * заявки, и опоздавшая задача становится no-op — в том числе уже взятая в работу (Р11).
 */
export async function purgeRequestRecognition(tx: Tx, requestId: string): Promise<void> {
  await tx.delete(wasteTickets).where(eq(wasteTickets.requestId, requestId));
  await tx.delete(wasteTicketPages).where(eq(wasteTicketPages.requestId, requestId));
  await tx.delete(wasteTicketFiles).where(eq(wasteTicketFiles.requestId, requestId));
  await tx
    .delete(wasteTicketCheckResolutions)
    .where(eq(wasteTicketCheckResolutions.requestId, requestId));
}
