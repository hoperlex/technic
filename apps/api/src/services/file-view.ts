import type { AttachedFileDto, FileDto, FileStatus } from '@technic/contracts';

/**
 * ОДНО МЕСТО, ГДЕ РЕШАЕТСЯ СУДЬБА ИМЕНИ ВЛОЖЕНИЯ: у карантинного файла имя наружу не уходит, а
 * признак карантина — уходит (план освобождения от подписи, Р6, п. 4).
 *
 * Почему модуль отдельный, а не условие в каждом сборщике. Вложения перечисляют десять сборщиков
 * разных модулей — вывоз мусора, заказы техники, путевые листы, талоны, механизация, ТО, чеки
 * автозапчастей, журнал показаний, заявки оргтехники, — и все они собирают DTO своим кодом. Девять
 * копий проверки `quarantinedAt` разошлись бы на первой же новой ручке: автор нового сборщика
 * повторяет соседа, а у соседа условия нет, потому что его дописали позже. Ровно так уже терялись
 * запреты при переделке циклов, и поэтому правило здесь одно, а сборщики его спрашивают.
 *
 * Чего здесь НЕТ и почему. Ссылку и идентификатор файла карантин не прячет: содержимое закрыто
 * замком в `canAccessFile` — приоритетным запретом раньше любой ветки видимости, включая автора
 * файла, — и второй запрет в DTO только раздвоил бы правило доступа. Сама строка вложения тоже
 * остаётся: «документ скрыт по обращению» и «документа не было» — разные факты, и стирать строку
 * значило бы переписывать историю заявки.
 */

/** Что сборщик обязан прочитать из `files`, чтобы решить судьбу имени. */
export interface FileNameRow {
  /** `null` бывает только у внешнего соединения: строки файла нет вовсе. */
  filename: string | null;
  quarantinedAt: Date | null;
}

/**
 * Имя и признак карантина — парой, потому что по отдельности они врут.
 *
 * Имя заменяется ПУСТОЙ СТРОКОЙ, а не словом-заглушкой: «Документ скрыт» в списке файлов читается
 * как имя файла — и первый же человек пойдёт искать такой документ у себя. Пустая строка вместе с
 * признаком читается как состояние, и портал рисует ею объяснение, а не подпись.
 *
 * Признак обязателен именно поэтому: без него в списке осталась бы строка без имени и без причины,
 * то есть «файл, у которого что-то сломалось», вместо «файл скрыт по обращению». В ответе он
 * появляется ТОЛЬКО у карантинного файла: отсутствие признака и есть «обычный файл», а ставить
 * `false` каждому вложению портала значило бы менять ответ всем ручкам сразу.
 */
export function fileNameView(row: FileNameRow): { filename: string; quarantined?: boolean } {
  if (row.quarantinedAt) return { filename: '', quarantined: true };
  return { filename: row.filename ?? '' };
}

/** Подшитый файл глазами читающего экрана (`AttachedFileDto`): имя — через общее правило. */
export function attachedFileView(
  row: FileNameRow & { id: string; contentType: string | null; size: number },
): AttachedFileDto {
  return {
    id: row.id,
    ...fileNameView(row),
    contentType: row.contentType ?? '',
    size: row.size,
  };
}

/** Вложение в полном виде (`FileDto`, со статусом загрузки): имя — через то же правило. */
export function fileView(
  row: FileNameRow & {
    id: string;
    contentType: string | null;
    size: number;
    status: FileStatus;
    createdAt: Date;
  },
): FileDto {
  return {
    ...attachedFileView(row),
    status: row.status,
    createdAt: row.createdAt.toISOString(),
  };
}
