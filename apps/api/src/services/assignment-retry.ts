/**
 * Протокол повторов на ошибке сериализации — решение **В4** плана
 * (`docs/assignment-periods-plan.md`, §14c В4, «Протокол повторов (В4)», «Исчерпание повторов (В4,
 * уточнено спайком)»; измерения — [отчёт спайка](../../../../docs/assignment-periods-spike.md), §4).
 *
 * ЗАЧЕМ ОН ВООБЩЕ. Двери истории назначения работают общим планом и общим каноном §8, и под
 * конкурентной записью PostgreSQL законно отвечает им `40001`: снимок транзакции устарел, пока она
 * ждала чужой блокировки. Это не ошибка человека и не поломка портала — это очередь. Без протокола
 * каждый такой отказ выходит наружу пятисоткой: корректная конкурентная работа выглядит
 * периодическими внутренними ошибками, а диспетчер, ничего не сделавший неправильно, видит
 * «внутреннюю ошибку сервера» и не знает, повторять ли ему команду.
 *
 * ПОВТОРЯЕТСЯ ВСЯ ТРАНЗАКЦИЯ ВМЕСТЕ С ПЛАНИРОВАНИЕМ, И ЭТО ГЛАВНОЕ ЗДЕСЬ. Соблазн повторить один
 * упавший запрос велик — он и дёшев, и выглядит безобидно, — но план, посчитанный на устаревшем
 * снимке, применять повторно нельзя ни в каком виде: пока мы стояли в очереди, соседняя команда
 * могла сменить машину, погасить строку истории или выписать лист, и наш план описывает состояние,
 * которого больше нет. Записав его, портал оформил бы бумагу строгой отчётности по решению,
 * которого человек не принимал. К тому же в `REPEATABLE READ` иначе и нельзя: снимок абортированной
 * транзакции не оживить, все её чтения обязаны повториться в новой. Поэтому единица повтора —
 * замыкание целиком: `executor.transaction(...)` со всеми четырнадцатью шагами внутри.
 *
 * ЧТО ПОВТОРЯЕТСЯ, А ЧТО ВЫХОДИТ НАРУЖУ СРАЗУ. Ловятся ровно два кода — `40001` (конфликт
 * сериализации) и `40P01` (взаимоблокировка): оба означают «повтори то же самое, и на этот раз
 * получится». Всё остальное выходит наружу первым же броском, и это не экономия, а требование
 * правильности:
 *
 * - **409 после повторного планирования** — состояние действительно изменилось, и отпечаток
 *   предпросмотра разошёлся (шаг 7 канона). Повторять такое значило бы перепробовать один и тот же
 *   отказ пять раз подряд, а человеку всё равно ответить «посмотрите последствия заново». Это и
 *   есть разделение исходов, которого требует В4: **409 — изменившееся состояние, 503 — исчерпание
 *   попыток**, и путать их нельзя ни в одну сторону;
 * - **422, 403, 500** — отказ по существу, по правам или нарушение канона: повтор не изменит
 *   ничего, кроме времени ответа;
 * - **`23505`** (нарушение частичного `UNIQUE` истории) не ловится намеренно. Спайк (§4.4) показал,
 *   что этим кодом отвечает `READ COMMITTED` там, где порядок захвата нарушен: вторая транзакция
 *   дописывает актуальную строку по уже устаревшему решению. Это признак ошибки в коде двери, а не
 *   конкуренции, и заглушив его повтором, мы спрятали бы единственное, что о ней сообщает.
 *
 * УСЛОВИЕ БЕЗОПАСНОСТИ ПОВТОРА. Повторять замыкание можно ровно потому, что всё, что оно делает,
 * оно делает **внутри транзакции**: строки истории, номер бланка (строка серии `waybill_series`, а
 * не `nextval`), журнал коррекций и события аудита откатываются вместе с ней, и вторая попытка
 * начинается с того же состояния базы, что первая. Появится у двери внешний побочный эффект —
 * письмо, файл в S3, запись в чужой сервис — и его придётся выносить за пределы повторяемого
 * замыкания: он повторится столько раз, сколько было попыток.
 *
 * СЧЁТЧИКИ ПРОЦЕССНЫЕ, КАК У ИСХОДОВ КОМАНД. Повтор следа в базе не оставляет вовсе — транзакция
 * откатилась, — и посчитать его можно только там, где он происходит.
 */

/** Код отказа при исчерпании попыток. Портал разбирает 503 по коду, а не по тексту. */
export const ASSIGNMENT_RETRY_EXHAUSTED_CODE = 'assignment_retry_exhausted';

/**
 * `Retry-After` в секундах.
 *
 * Секунда — не оценка, а минимальная единица заголовка: конфликт живёт миллисекунды (планирование
 * 2,2–2,6 мс на попытку, §3 спайка), и честнее всего это читается как «повторяйте прямо сейчас».
 * Ноль в `Retry-After` допустим синтаксически, но означал бы «немедленно» для кода, который тут же
 * вернётся в ту же очередь, — секунда даёт общей строке разойтись.
 */
const RETRY_AFTER_SECONDS = 1;

/** Во сколько раз пауза растёт от попытки к попытке и где перестаёт расти. */
const BACKOFF_GROWTH_CAP = 8;

/**
 * Потолок повторов и пауза между ними — настройкой, а не константой.
 *
 * ПОЧЕМУ НЕ «ТРИ» ЧИСЛОМ В КОДЕ (уточнение Я2). Первая редакция В4 говорила «до трёх раз», и спайк
 * (§4.3) это опроверг измерением: при `W` одновременных писателях по одной строке распределение
 * идеально ровное — один проходит с первой попытки, один со второй, …, один с `W`-й, потому что
 * коммит победителя выбивает `40001` всем остальным разом. Значит потолок `N` покрывает ровно
 * `W ≤ N`: при трёх попытках и четырёх писателях 503 получают 25 %, при шести — 50 %, при восьми —
 * 62,5 %. И `W` здесь **не** «сколько диспетчеров правят одну заявку»: строка серии бланков ЭСМ-2
 * одна на весь портал, и межзаявочный конфликт на счётчике номеров даёт ту же гистограмму. Число,
 * зависящее от боевого профиля, которого никто не измерял, обязано правиться `prod.env`, а не
 * релизом, — и подбираться по собственной метрике исчерпаний.
 */
export interface AssignmentRetryPolicy {
  /** Сколько всего попыток, **включая первую**: `1` — протокол выключен, повторов нет. */
  attempts: number;
  /** Основание паузы перед повтором, мс; `0` — повторять без пауз. */
  backoffMs: number;
}

/** Умолчание портала: то, что прочитано из окружения (`ASSIGNMENT_RETRY_*`). */
export function assignmentRetryPolicy(): AssignmentRetryPolicy {
  return config.assignment.retry;
}

/**
 * Отказ при исчерпании попыток: `503` с `Retry-After`, а не 500 и не 409.
 *
 * Наследник `AppError` ради двух вещей, которых у фабрики `err.unavailable` нет: своего кода (от
 * общего «сервис временно недоступен» этот отказ отличается тем, что повторять команду **стоит** —
 * и прямо сейчас) и `retryAfterSeconds`, который обработчик ошибок кладёт в заголовок.
 *
 * Последняя ошибка PostgreSQL остаётся в `cause`, и это не украшение лога: по ней `classifyFailure`
 * каркаса относит исход к `serialization`, то есть исчерпание считается там же, где считалось до
 * появления протокола, — метрика исходов не разрывается на «до» и «после».
 */
export class AssignmentRetryExhaustedError extends AppError {
  constructor(
    /** Сколько попыток было сделано — столько же, сколько отказов `40001`. */
    public readonly attempts: number,
    /** Через сколько секунд просить повторить; уходит в заголовок `Retry-After`. */
    public readonly retryAfterSeconds: number,
    cause: unknown,
  ) {
    super(
      503,
      ASSIGNMENT_RETRY_EXHAUSTED_CODE,
      'Заявку в этот момент меняют рядом — попробуйте повторить через несколько секунд',
    );
    this.name = 'AssignmentRetryExhaustedError';
    this.cause = cause;
  }
}

/**
 * Та ли это беда, которую лечит повтор.
 *
 * Конфликт сериализации и взаимоблокировка разведены PostgreSQL на два кода, но лечатся одинаково,
 * и человек между ними не различает ничего: он не сделал ничего плохого, а операция не прошла.
 * Предикат один на протокол и на классификацию исходов — вторая копия этих двух кодов разошлась бы
 * с первой ровно тогда, когда счётчик показывал бы неправду о собственном протоколе.
 */
export function isSerializationFailure(error: unknown): boolean {
  const code = pgErrorOf(error)?.code;
  return code === '40001' || code === '40P01';
}

/** Ключ — имя двери: метка у обоих счётчиков одна и та же, и графики совмещаются. */
const retries = new Map<string, number>();
const exhaustions = new Map<string, number>();

function bump(counter: Map<string, number>, door: string): void {
  counter.set(door, (counter.get(door) ?? 0) + 1);
}

/**
 * Повторы и исчерпания с момента старта процесса — в `/metrics`.
 *
 * Двумя числами в одной строке, а не двумя метками одной метрики: «сколько раз повторили» и
 * «сколько раз не помогло» читаются вместе. Ненулевые повторы при нулевых исчерпаниях — протокол
 * работает и людям об этом знать незачем; ненулевые исчерпания — потолок тесен для боевого профиля
 * либо общая строка перегружена, и оба вывода делаются по одной паре чисел.
 */
export function assignmentRetryCounters(): {
  door: string;
  retries: number;
  exhaustions: number;
}[] {
  return [...new Set([...retries.keys(), ...exhaustions.keys()])].sort().map((door) => ({
    door,
    retries: retries.get(door) ?? 0,
    exhaustions: exhaustions.get(door) ?? 0,
  }));
}

/** Обнуление — только тестам: прогон не должен зависеть от порядка файлов. */
export function resetAssignmentRetryCounters(): void {
  retries.clear();
  exhaustions.clear();
}

/**
 * Пауза перед очередной попыткой: полный джиттер по растущему потолку.
 *
 * ПОЧЕМУ ПАУЗА МАЛЕНЬКАЯ. Спайк (§4.3) показал, что проигравшие не «перегружают базу», а стоят в
 * очереди за одной строкой: их будит коммит победителя, и порядок им задаёт сам PostgreSQL. Ждать
 * долго тут нечего — ожидание не разгружает ничего и только добавляет человеку секунды к операции,
 * которая по существу уже упорядочена.
 *
 * ПОЧЕМУ ПАУЗА ВООБЩЕ ЕСТЬ И ПОЧЕМУ СЛУЧАЙНАЯ. Нулевая пауза отправляет всех `W` проигравших
 * планировать заново **одновременно** — они выбрасывают одну и ту же работу в один и тот же момент
 * и приходят к строке ровно тем же стадом. Случайная задержка в пределах потолка их расцепляет, а
 * полный джиттер (равномерно от нуля) — самый простой из способов, у которого нет собственного
 * резонанса. Потолок удваивается от попытки к попытке и перестаёт расти на восьмикратном: дальше
 * растёт только время ответа.
 */
function backoffMsFor(attempt: number, backoffMs: number): number {
  if (backoffMs <= 0) return 0;
  const ceiling = backoffMs * Math.min(2 ** (attempt - 1), BACKOFF_GROWTH_CAP);
  return Math.round(Math.random() * ceiling);
}

function pause(ms: number): Promise<void> {
  if (ms <= 0) return Promise.resolve();
  return new Promise((resolve) => {
    setTimeout(resolve, ms);
  });
}

/**
 * Провести транзакцию с ограниченным повтором на ошибке сериализации.
 *
 * `run` — **вся** транзакция вместе с планированием: этот модуль ничего не знает о её содержимом и
 * знать не должен, он знает только, что её законно исполнить ещё раз с чистого листа.
 *
 * Политика приходит аргументом с умолчанием из настроек: умолчание одно на портал, а своё значение
 * передают те, у кого свой профиль конкуренции, — тесты протокола (им нужны пауза в ноль и
 * предсказуемый потолок) и однопоточные служебные прогоны, которым спайк велел сериализоваться
 * снаружи, а не поднимать потолок.
 */
export async function withAssignmentRetry<T>(
  door: string,
  run: () => Promise<T>,
  policy: AssignmentRetryPolicy = assignmentRetryPolicy(),
): Promise<T> {
  const attempts = Math.max(1, Math.trunc(policy.attempts));
  let lastFailure: unknown;

  for (let attempt = 1; attempt <= attempts; attempt += 1) {
    try {
      return await run();
    } catch (error) {
      // Всё, кроме конфликта сериализации, — ответ по существу: он уже правильный и повтора не
      // ждёт. Сюда же приходит 409 «состояние изменилось», посчитанный повторным планированием.
      if (!isSerializationFailure(error)) throw error;
      lastFailure = error;
      if (attempt === attempts) break;
      bump(retries, door);
      await pause(backoffMsFor(attempt, policy.backoffMs));
    }
  }

  bump(exhaustions, door);
  throw new AssignmentRetryExhaustedError(attempts, RETRY_AFTER_SECONDS, lastFailure);
}
