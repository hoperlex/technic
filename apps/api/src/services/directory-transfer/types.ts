import type { DirectoryKey } from '@technic/contracts';
import type { db } from '../../db/client';

/**
 * Как описывается справочник, участвующий в обмене файлом Excel (ADR 0073).
 *
 * Одно описание обслуживает и выгрузку, и загрузку. Это не экономия строк, а единственный способ
 * не дать колонкам разъехаться: выгрузи справочник одним набором колонок, прими другим — и файл,
 * который портал только что отдал, он же и отвергнет. По той же причине сравнение «что изменится»
 * считается не по полям таблицы, а по ячейкам файла: то, чего файл не показывает, он и не меняет.
 *
 * Ключевое понятие здесь — **модель**: строка справочника в том виде, в каком её видит человек в
 * файле. Ссылки в ней — кодами и ИНН, а не идентификаторами, даты и флаги — текстом. Из строки
 * базы модель собирает `model()`, из строки файла — колонки своими `set()`, и обе стороны потом
 * сравниваются одними и теми же `get()`. Разбор в идентификаторы и запись остаются в `create()`
 * и `update()`, где для этого есть окружение.
 */

/** Транзакция drizzle — тот же приём, что в `services/directory-purge.ts`. */
export type Tx = Parameters<Parameters<typeof db.transaction>[0]>[0];

/** Ячейки строки файла по заголовкам колонок. Отсутствующая колонка — отсутствующий ключ. */
export type RowCells = Readonly<Record<string, string>>;

/**
 * Копилка замечаний по одной строке файла. Ошибки не бросаются, а собираются: человек с файлом в
 * руках правит его один раз, а не выясняет следующую опечатку каждым новым заходом (приём
 * `services/driver-import.ts`).
 */
export interface RowContext {
  /** Номер строки на листе «Данные» — тот, который человек видит слева в редакторе таблиц. */
  readonly row: number;
  /** Строка негодна. Пока есть хоть одна такая, файл не применяется целиком. */
  fail(message: string): void;
  /** Замечание, которое применению не мешает, но прочитать его нужно. */
  warn(message: string): void;
}

/**
 * Колонка файла. `get` отвечает за выгрузку и за сравнение, `set` — за разбор.
 *
 * Колонка без `set` справочная: она выгружается, чтобы человеку было по чему ориентироваться, но
 * загрузка её не читает и в сравнении «что изменится» не участвует — иначе всякая загрузка
 * показывала бы правку поля, которого никто не менял.
 */
export interface DirectoryColumn<Model> {
  header: string;
  /**
   * Как колонка называлась раньше. Выгрузка пишет только `header`, загрузка принимает и его, и
   * прежние имена.
   *
   * Нужно это потому, что незнакомый заголовок отвергает файл целиком (`engine.ts`, `mapHeader`), и
   * без псевдонимов всякое переименование колонки означало бы: ранее скачанный файл больше не
   * грузится. Отказ ради наглядности — плохой размен: колонку переименовывают, чтобы человеку было
   * понятнее, а расплачивается он тем, что его файл не приняли.
   *
   * Механизм общий, а не частный случай одного справочника: следующее переименование в любом из
   * восемнадцати стоит одной строки. Файл, где стоят и прежнее имя, и нынешнее, по-прежнему
   * отвергается как повтор колонки — какую из двух читать, действительно неизвестно.
   */
  aliases?: string[];
  /** Ширина в знаках: оформление выгрузки, на разбор не влияет. */
  width?: number;
  get(model: Model): string;
  /**
   * Разбор ячейки в модель. Вызывается только для колонок, которые в файле есть, и всегда поверх
   * уже собранной модели существующей записи — поэтому «пустая ячейка ничего не делает» и
   * «пустая ячейка стирает поле» решаются здесь же, по смыслу конкретной колонки.
   */
  set?(model: Model, text: string, ctx: RowContext): void;
  /** Строка на лист «Справка»: чем колонку заполняют. */
  hint?: string;
}

/**
 * Описание справочника. Параметры: `Row` — строка базы, `Model` — та же строка глазами человека,
 * `Env` — то, что подгружается один раз на весь файл (словари ссылок, соседние справочники).
 */
export interface DirectoryDefinition<Row, Model, Env> {
  key: DirectoryKey;
  /**
   * Что нужно знать про остальной портал, чтобы разобрать и записать файл: коды видов ТС, ИНН
   * контрагентов, заведённые ТТХ. Читается один раз на загрузку — иначе на каждую строку файла
   * приходился бы запрос в базу.
   */
  env(): Promise<Env>;
  /**
   * Колонки листа «Данные» без служебного идентификатора — его добавляет движок сам, первым.
   * Зависят от окружения: у категорий типов ТС состав колонок задают заведённые ТТХ.
   */
  columns(env: Env): DirectoryColumn<Model>[];
  /** Пояснения на лист «Справка»: чем справочник является и что делает загрузка. */
  help(env: Env): string[];
  /** Строки справочника в порядке выгрузки, включая погашенные: файл — это весь справочник. */
  load(env: Env): Promise<Row[]>;
  /** Идентификатор строки: он же значение служебной колонки. */
  id(row: Row): string;
  model(row: Row, env: Env): Model;
  /** Пустая модель: с неё начинается строка, которой в справочнике ещё нет. */
  blank(): Model;
  /**
   * Ключ строки — то, чем строка файла ищется среди заведённых, когда идентификатор не проставлен
   * (код, ИНН, госномер, СНИЛС, составные ключи прайса). Пустая строка означает «ключ не
   * собрался»: об этом уже сказала ошибка разбора, и повторять её движку незачем.
   */
  keyOf(model: Model): string;
  /** Как строка называется в отчёте: код, наименование, ФИО. */
  titleOf(model: Model): string;
  /**
   * Проверки, которые не помещаются в одну ячейку: существование ссылок, взаимоисключающие поля,
   * обязательность там, где она зависит от других колонок. Выполняются на предпросмотре — до
   * записи, а не в момент, когда половина файла уже применена.
   *
   * Вызывается ровно один раз на строку, когда все колонки уже разобраны и до того, как считано
   * «что изменится» и вызваны `create`/`update`. Поэтому здесь же место решениям, которые зависят
   * от строки целиком и меняют модель: правка отсюда попадёт и в отчёт предпросмотра, и в запись —
   * человек прочитает её, а не узнает о ней из базы (так справочник водителей раскладывает
   * категории по видам документов).
   */
  check?(model: Model, ctx: RowContext, env: Env): void;
  /**
   * Догрузка окружения тем, что зависит от ПРИСЛАННОГО, а не от справочника, и что обязана считать
   * база. Вызывается один раз на файл — после разбора строк и до `check()` — и дополняет `env` на
   * месте.
   *
   * Заведено ради колонки «Модель» оргтехники (`defs/office.ts`): по чему модель опознаётся, знает
   * IMMUTABLE-функция Postgres, а её копия в TypeScript расходится с оригиналом молча — `upper()` и
   * `toUpperCase()` по-разному поступают с «ß» и турецкой «i». Причём расходятся они в обе стороны,
   * и одна из них хуже отказа: JS схлопывает в один ключ две законные записи справочника, и строка
   * привязывается не к той, которую назвали. Спрашивать базу построчно нельзя — в файле сотни
   * строк; поэтому описание спрашивает один раз обо всём файле сразу.
   *
   * Модели приходят разобранными начисто, поверх `blank()`: это перечень присланного, а не итог
   * разбора, и ошибки этого прохода повторит разбор в `planRows`. Значит, того, чего в файле нет,
   * здесь не видно вовсе — колонка, которую человек удалил, приедет пустой, и описание обязано
   * уметь ответить на такую строку без догрузки.
   */
  resolveRows?(models: readonly Model[], env: Env): Promise<void>;
  create(tx: Tx, model: Model, env: Env, actorUserId: string): Promise<void>;
  update(tx: Tx, row: Row, model: Model, env: Env, actorUserId: string): Promise<void>;
}

/**
 * Описание справочника, спрятавшее свои типы. Реестр хранит разные справочники в одном списке, а
 * движку содержимое строки безразлично: он перекладывает модели между `get`, `set` и `create`, ни
 * разу не заглядывая внутрь.
 */
export type AnyDirectory = DirectoryDefinition<unknown, unknown, unknown>;

/**
 * Единственное место, где типы описания скрываются. Приведение здесь, а не в реестре: так оно
 * одно на весь модуль и стоит рядом с объяснением, зачем нужно.
 */
export function directory<Row, Model, Env>(
  def: DirectoryDefinition<Row, Model, Env>,
): AnyDirectory {
  return def as unknown as AnyDirectory;
}
