import { createHash } from 'node:crypto';

// ── Слепая перепроверка: отбор и снимок сравнения (ADR 0114, Р31) ──
//
// Отдельным модулем от маршрута по одной причине: правило отбора — это утверждение о том, ЧТО
// вообще годится в измерение качества распознавания, и проверять его надо без поднятого сервера.
// В маршруте оно жило бы строкой условия внутри транзакции подтверждения, и первый же тест на него
// потребовал бы http, базы и учётки — то есть не писался бы вовсе.

/** Талон глазами отбора: происхождение, факт правки и три сравниваемых поля. */
export interface BlindCheckCandidate {
  origin: 'ocr' | 'manual';
  /** `null` — талон не правили руками. */
  editedAt: Date | null;
  numberKey: string;
  issuedOn: string | null;
  /** Как лежит в базе — строкой `numeric`; `null` у простоя законен. */
  volumeM3: string | null;
}

/**
 * Годится ли талон в выборку и выпал ли жребий.
 *
 * **Только неправленые машинные.** `baseline_*` — это чтение модели, и ручной или уже исправленный
 * талон сравнивал бы человека с человеком: метрика при этом называлась бы «ошибки OCR», меряя
 * совсем другое. Правленый машинный талон остаётся машинным (`origin` не меняется, Р14) — поэтому
 * одного `origin` мало, и `edited_at` проверяется отдельно.
 *
 * **Жребий, а не квота.** Доля задана долей: при квоте попадание конкретной бумаги в выборку
 * зависело бы от того, сколько талонов принесли в тот же день соседи, — и выборка перестала бы
 * быть случайной ровно в те дни, когда работы больше всего.
 *
 * `random` параметром, чтобы правило проверялось детерминированно; в бою это `Math.random`.
 */
export function shouldSampleBlindCheck(
  ticket: BlindCheckCandidate,
  rate: number,
  random: () => number = Math.random,
): boolean {
  if (ticket.origin !== 'ocr') return false;
  if (ticket.editedAt !== null) return false;
  if (!(rate > 0)) return false;
  // Доля 1 означает «каждый», и жребий здесь не нужен: `Math.random()` строго меньше единицы, но
  // полагаться на это в условии — значит зависеть от границы диапазона там, где смысл прямой.
  if (rate >= 1) return true;
  return random() < rate;
}

/**
 * Отпечаток снимка машинного чтения: по нему видно, что сравнивали именно эту версию, а не то, во
 * что талон превратился после правок.
 *
 * Считается от трёх сравниваемых полей — тех же, что присылает проверяющий. Вид работ и адрес в
 * перепроверку не входят (она меряет качество чтения рукописи, а не разметку бланка), и в
 * отпечатке им делать нечего.
 */
export function blindBaselineFingerprint(ticket: BlindCheckCandidate): string {
  return createHash('sha256')
    .update(JSON.stringify([ticket.numberKey, ticket.issuedOn, ticket.volumeM3 ?? null]), 'utf8')
    .digest('hex');
}
