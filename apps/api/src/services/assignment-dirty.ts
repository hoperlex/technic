import { and, eq } from 'drizzle-orm';
import { vehicleRequests } from '../db/schema';
import type { AssignmentModeTx } from './assignment-mode';

/**
 * Метка загрязнения истории назначения внутри дня
 * (план `docs/assignment-periods-plan.md` §6, решение К4; миграция `0166`).
 *
 * ЗАЧЕМ ОНА. Готовность заявки (`assignment_history_state` + `assignment_history_validated_on`)
 * считается на день и лениво устаревает по календарю: сменились сутки — состояние пересчитывается.
 * Внутри одного дня календарь молчит, а бумага и её отменяемость меняются: ручная выписка ЭСМ-2
 * добавляет заказу лист, подпись объекта под днём работы делает бумагу неотменяемой, снятие подписи
 * — наоборот. Прогон сверки, увидевший заявку зелёной утром, к вечеру доказывает уже не то
 * состояние, а `validated_on` при этом остаётся сегодняшним и молчит.
 *
 * Поэтому те двери, которые двигают множество листов или отменяемость бумаги, не пересчитывая
 * историю, поднимают метку сами: **все четыре ручки смен** (сохранение, удаление, подпись и её
 * снятие) и **ручная выписка `on_demand`**. Снимает метку только успешная revalidation, и
 * разморозка модуля её наличие проверяет (`assignment-mode.ts`, `requireNoDirtyRequests`).
 *
 * КТО ЕЁ СНИМАЕТ. Ровно один: `ensureAssignmentHistory`
 * ([assignment-ensure.ts](./assignment-ensure.ts)) — и снимает **той же операцией**, которой пишет
 * пересчитанное состояние и `validated_on` (Р26). Иначе быть не может: метка означает «состояние
 * доказывает уже не то», снять это утверждение вправе лишь тот, кто состояние пересчитал, а из
 * ставящих её путей не пересчитывает историю ни один — на то они её и ставят. Зовут `ensure` три
 * двери истории (шагом 11) и восстановление из архива (Р28); заявки, к которым за день не подошла
 * ни одна из них, разбирает массовый пересчёт перед cutover (Р26, «перед предикатом — revalidation
 * всех `materialized` с единым `asOf`»).
 *
 * ПОРЯДОК ЗАХВАТА. Метка живёт в строке заявки, а значит её `UPDATE` берёт ту же строку, что и
 * `lockRequestRow`. Ставить её обязательно **после** него: иначе дверь смены шла бы
 * `shift → UPDATE request`, а команда истории — `request → shift`, и это прямая взаимная
 * блокировка (Л3). Ради этого порядок захвата и переехал в тот же релиз, что и сама метка.
 */
export async function markAssignmentHistoryDirty(
  tx: AssignmentModeTx,
  requestId: string,
): Promise<void> {
  await tx
    .update(vehicleRequests)
    .set({ assignmentHistoryDirty: true })
    // Условие по самой метке — не оптимизация, а отказ от лишней версии строки: заявку, которую
    // за день правили десять раз, незачем переписывать десять раз ради значения, уже стоящего в
    // ней. Строка к этому моменту всё равно взята `FOR UPDATE`, поэтому гонки здесь нет.
    .where(
      and(eq(vehicleRequests.id, requestId), eq(vehicleRequests.assignmentHistoryDirty, false)),
    );
}
