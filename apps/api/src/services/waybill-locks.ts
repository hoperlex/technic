import { asc, eq, inArray } from 'drizzle-orm';
import type { db } from '../db/client';
import { vehicleRequests, waybillRequests, waybills } from '../db/schema';

/**
 * Общий вход всех писателей листов ЭСМ-2: заявки листа блокируются до первой правки (Р11).
 *
 * **Какую гонку это чинит.** Откат заявки показывает человеку последствия сверки ЭСМ-2 заранее
 * («выпишется 2 листа, аннулируются такие-то») и принимает решение по отпечатку входов плана.
 * Отпечаток отвечает лишь за то, что изменилось **до** него, а дальше в той же транзакции идёт
 * `syncEsm2Waybills` — и между сверкой отпечатка и ею параллельное аннулирование успевало
 * закоммититься: оно берёт лист по его собственному id и правит только `waybills`, родительскую
 * заявку не трогая вовсе. Сверка перечитывала уже другой набор действующих листов и делала не то,
 * что показал диалог. `version` заявки этого не ловит по той же причине: её тоже никто не двигал.
 *
 * **Почему блокируется заявка, а не лист.** Общее у писателей ровно одно — заявка: у одного на
 * руках лист, у другого рейс, у третьего сама заявка, и договориться о встрече они могут только
 * на её строке. Лист не годится и по существу: сверка спрашивает «какие листы у этой заявки
 * сейчас», и тот, о котором она ещё не знает, заблокировать нечем.
 *
 * **Почему сортировка по `id`.** Заявок у листа бывает несколько (`waybill_requests`: талонов в
 * бланке до десяти — ADR 0068), и два встречных аннулирования листов, делящих пару заявок, взяв
 * строки каждое в своём порядке, встали бы в клинч. Единственный порядок на всех писателей — это
 * и есть причина, по которой блокировка живёт отдельным модулем, а не строчкой в каждом из них.
 *
 * **Блокировка постоянная.** Она чинит дыру, которая была в портале и до хотфикса — просто до
 * предпросмотра о ней никто не обещал обратного, — и с уборкой временных колонок (§9 плана
 * переключения режима) не снимается.
 */

type Tx = Parameters<Parameters<typeof db.transaction>[0]>[0];
/** Читающей половине транзакция не нужна: перечень заявок спрашивают и до правки. */
type Reader = Tx | typeof db;

/**
 * Заблокировать заявки листа и вернуть их id.
 *
 * Зовётся первым шагом транзакции — до первого чтения листов: блокировка, взятая после того, как
 * набор уже прочитан, стережёт прошлое.
 *
 * Пустой массив — блокировать было нечего: у пустого бланка (ADR 0071) заявок нет вовсе, его
 * выписывают «на машину и водителя», и списание такого номера ничьему предпросмотру не
 * противоречит.
 *
 * Перечень заявок читается до блокировки, и это не дыра: связь листа с заявками пишется при
 * рождении номера и не меняется больше никогда — её сохраняет даже списание (журнал бланков строгой
 * отчётности обязан помнить, что печаталось).
 */
export async function lockRequestsOfWaybill(tx: Tx, waybillId: string): Promise<string[]> {
  const ids = await requestIdsOfWaybills(tx, [waybillId]);
  if (ids.length === 0) return [];
  const rows = await tx
    .select({ id: vehicleRequests.id })
    .from(vehicleRequests)
    .where(inArray(vehicleRequests.id, ids))
    // Порядок по `id`, а не по слоту талона: одна и та же пара заявок стоит в двух листах разными
    // слотами, и два встречных аннулирования взяли бы строки навстречу друг другу (см. шапку).
    .orderBy(asc(vehicleRequests.id))
    .for('update');
  return rows.map((row) => row.id);
}

/**
 * Заявки листов рейса — тем, кто берёт эту блокировку не по листу, а по рейсу.
 *
 * Коррекция задним числом приходит с рейсом и своих листов ещё не читала: id листа появляется у
 * неё позже, а блокировку надо взять раньше. Поэтому здесь только перечень id, а сам `FOR UPDATE`
 * вызывающий делает своим проходом — вместе с заявками состава и одним общим порядком по `id`. Два
 * отсортированных запроса подряд общего порядка не дают: они дают два своих, и клинч, от которого
 * сортировка спасает, вернулся бы через заднюю дверь.
 *
 * Статус листов не спрашивается: какой из них действующий, коррекция решает уже под блокировкой, а
 * лишняя строка заявки в её же транзакции ничего не стоит.
 */
export async function requestIdsOfRouteWaybills(
  reader: Reader,
  routeIds: readonly string[],
): Promise<string[]> {
  const ids = [...new Set(routeIds)];
  if (ids.length === 0) return [];
  const rows = await reader
    .select({ requestId: waybillRequests.requestId })
    .from(waybillRequests)
    .innerJoin(waybills, eq(waybills.id, waybillRequests.waybillId))
    .where(inArray(waybills.routeId, ids));
  return [...new Set(rows.map((row) => row.requestId))];
}

/** Заявки этих листов по связи `waybill_requests`; дубли снимаются — заявка бывает общей у двух. */
async function requestIdsOfWaybills(
  reader: Reader,
  waybillIds: readonly string[],
): Promise<string[]> {
  const ids = [...new Set(waybillIds)];
  if (ids.length === 0) return [];
  const rows = await reader
    .select({ requestId: waybillRequests.requestId })
    .from(waybillRequests)
    .where(inArray(waybillRequests.waybillId, ids));
  return [...new Set(rows.map((row) => row.requestId))];
}
