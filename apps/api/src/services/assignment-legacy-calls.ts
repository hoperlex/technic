import { sql } from 'drizzle-orm';
// Читатель тот же, что у сводки готовности: счётчик нужен и метрике, и сводке, и аттестации —
// пул, транзакция и maintenance-соединение обязаны звать одну функцию.
import type { ReadinessReader } from './assignment-readiness';

/**
 * Клиентский гейт cutover (И5): вызовы **старого** широкого маршрута с датами срока.
 *
 * ЗАЧЕМ ОН. Срок работ уехал в свою дверь `PATCH /:id/period` (Ж4, З5), но широкий `PATCH /:id`
 * даты пока принимает — иначе выкат портала и API пришлось бы делать одномоментно. После
 * переключения чтения такой запрос получит `409 CLIENT_UPGRADE_REQUIRED`, и переключаться можно
 * только когда живых клиентов старого пути не осталось. «Не осталось» — это измеримое утверждение,
 * и меряется оно здесь.
 *
 * ПОЧЕМУ ЖУРНАЛ, А НЕ СЧЁТЧИК ПРОЦЕССА. Аттестация деплоя снимается сразу после раската — то есть
 * через минуту после перезапуска контейнеров, когда процессный счётчик заведомо нулевой по самой
 * своей природе. Такой гейт доказывал бы не отсутствие старых клиентов, а свежесть процесса.
 * Строка журнала переживает перезапуск, и окно в семь дней отвечает на настоящий вопрос: заходил
 * ли сюда кто-нибудь за прошедшую неделю.
 *
 * ПОЧЕМУ ЗАПИСЬ ЖИВЁТ В СОСЕДНЕМ ФАЙЛЕ. Считать гейт обязаны и метрика, и сводка готовности, и
 * команда аттестации — а последние две ходят **административным** путём, без прикладного конфига:
 * они запускаются, когда портал заморожен или лежит. Запись же тянет журнал, а тот — прикладной
 * пул. Один файл на оба дела означал бы, что сводка не поднимается без конфига приложения.
 *
 * ЧТО СЧИТАЕТСЯ ВЫЗОВОМ. Только тот запрос, который **менял** срок: форма портала присылает заявку
 * целиком на каждой правке, и «прислал те же даты» не означает «не знает новой двери». Иначе гейт
 * не дошёл бы до нуля никогда — его держала бы всякая правка комментария.
 */

/** Действие журнала: `action = 'assignment.legacy_period_call'`. */
export const ASSIGNMENT_LEGACY_PERIOD_ACTION = 'assignment.legacy_period_call';

/** Окно гейта. Неделя — рабочий цикл портала: за это время заявку правит каждая роль, которая её правит. */
export const ASSIGNMENT_LEGACY_WINDOW_DAYS = 7;

/**
 * Сколько раз за окно гейта срок правили старым маршрутом.
 *
 * Одно число на три места: метрику `/metrics`, сводку готовности и аттестацию деплоя. Второй способ
 * его посчитать означал бы два ответа на вопрос «пора ли переключаться», различить которые по
 * значению нельзя.
 */
export async function countLegacyPeriodCalls(reader: ReadinessReader): Promise<number> {
  const { rows } = await reader.execute<{ n: number }>(sql`
    SELECT count(*)::int AS n
      FROM audit_log
     WHERE action = ${ASSIGNMENT_LEGACY_PERIOD_ACTION}
       AND created_at > now() - ${`${ASSIGNMENT_LEGACY_WINDOW_DAYS} days`}::interval`);
  return rows[0]?.n ?? 0;
}
