import { eq } from 'drizzle-orm';
import { FEATURE_FLAGS, type FeatureFlagKey } from '@technic/contracts';
import type { db } from '../db/client';
import { featureFlags } from '../db/schema';

/**
 * Чтение рубильников приёма (план `docs/office-equipment-request-subject-plan.md`, Р10; таблица —
 * миграция 0293).
 *
 * **Зачем модуль на две функции.** Ответ на «включён ли ключ» обязан быть один и у ручки, и у
 * ответа сессии: портал показывает дверь по списку из сессии, а пускает в неё сервер, читая ту же
 * строку. Два места чтения разошлись бы первой же правкой — и разошлись бы тихо, показанной
 * дверью, за которой стоит 403.
 *
 * **Это не резолвер флагов.** Пилотных областей, аудита переключения и административной ручки здесь
 * нет: значение одинаково для всех учёток и меняется `UPDATE`-ом (§14 плана кандидата ждал общего
 * механизма — его в репозитории нет, и эта волна его не пишет). Поэтому у функций нет и аргумента
 * «для кого»: он обещал бы разбор по учёткам, которого не существует.
 *
 * **Кэша нет намеренно.** Соблазн держать значение в памяти процесса велик — таблица из одной
 * строки, а `/auth/me` спрашивают на каждый bootstrap. Но рубильник заведён ради АВАРИЙНОГО
 * выключения по работающему серверу, и кэш превратил бы «выключили» в «выключится через минуту»,
 * причём на каждом инстансе в свою минуту. Запрос по первичному ключу дешевле, чем объяснение,
 * почему выключение не сработало.
 */

/** Транзакция drizzle — рубильник читают и внутри транзакции заведения, до её решения. */
type Tx = Parameters<Parameters<typeof db.transaction>[0]>[0];

/**
 * Кто читает. Транзакция и глобальный `db` равноправны: значение общее и блокировать его нечем —
 * `FOR SHARE`, как у рубильника писем, здесь был бы не защитой, а задержкой чужого `UPDATE` на
 * каждый вход в портал.
 */
export type FeatureFlagReader = Tx | typeof db;

/**
 * Включён ли ключ.
 *
 * Отсутствие строки — `false`, тем же ответом, что и выключенная строка. Это не небрежность:
 * рубильник без строки означает недокаченный выкат, и открывать на нём приём нельзя — снаружи такое
 * состояние неотличимо от «оператор выключил». Ошибкой в лог оно, в отличие от рубильника писем, не
 * пишется: там строку обязана была завести миграция ЛЮБОГО из семи событий, а здесь ключ у таблицы
 * пока один, и «строки нет» — это ещё и «миграция 0293 не накачена», то есть состояние выката, о
 * котором и так кричит стартовая сверка журнала миграций.
 */
export async function isFeatureEnabled(
  reader: FeatureFlagReader,
  key: FeatureFlagKey,
): Promise<boolean> {
  const [row] = await reader
    .select({ isEnabled: featureFlags.isEnabled })
    .from(featureFlags)
    .where(eq(featureFlags.key, key));
  return row?.isEnabled ?? false;
}

/**
 * Список включённых ключей — то, что уезжает в ответ сессии.
 *
 * Список включённых, а не словарь всех: у портала правило одно — «нет ключа, значит выключено», — и
 * третьему состоянию («ключ известен, но значение неизвестно») взяться неоткуда.
 *
 * **Порядок словарный (`FEATURE_FLAGS`), а не тот, что вернула база.** Причина та же, что у списка
 * прав в ответе сессии: клиенту предстоит сравнивать ответы между собой, а сравнение массивов при
 * нестабильном порядке даёт ложное «изменилось» на неизменившемся составе.
 *
 * **Граница «база → код»**: ключ, которого нет в реестре контрактов, дальше не идёт — тем же
 * приёмом, что право-сирота у принципала (`isPermission`). Сегодня такую строку не пустит `CHECK`
 * таблицы, но `CHECK` живёт в базе, а реестр — в коде, и снятый из реестра ключ обязан исчезнуть из
 * ответа, а не приехать в портал строкой, о которой тот ничего не знает.
 */
export async function enabledFeatures(reader: FeatureFlagReader): Promise<FeatureFlagKey[]> {
  const rows = await reader
    .select({ key: featureFlags.key, isEnabled: featureFlags.isEnabled })
    .from(featureFlags);
  const enabled = new Set(rows.filter((r) => r.isEnabled).map((r) => r.key));
  return FEATURE_FLAGS.filter((key) => enabled.has(key));
}
