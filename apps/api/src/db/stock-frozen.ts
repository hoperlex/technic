import { config } from '../config';
import { logger } from '../logger';
import { pool } from './client';

/**
 * Барьер выпуска 2 «Заморозка»: склад автозапчастей замораживается только пустым
 * (`docs/auto-part-receipts-plan.md`, Р2, Р24, Р25).
 *
 * ЗАЧЕМ ОН ВООБЩЕ. Выпуск 2 снимает складскую машинерию с кода: `parts` уходят из DTO акта ТО,
 * маршруты `/auto-parts` перестают отвечать, возврат при аннулировании больше не пишется. Законно
 * это ровно при одном условии — записей нет. Если они есть, заморозка не ломает ничего заметного,
 * а делает хуже: строки перестают приходить в DTO, движения остаются в базе, на экране не меняется
 * ничего, кроме исчезнувшего блока. Это не авария, а ТИХАЯ ПРОПАЖА — её замечают случайно и через
 * месяцы. Отказ стартовать шумит сразу и в понятном месте.
 *
 * ПОЧЕМУ НЕ РУЧНОЙ `SELECT` ПЕРЕД ВЫКАТОМ. Он отвечает на вопрос «пусто ли сейчас», а нужен ответ
 * «пусто ли в момент, когда старый API уже не пишет». Между этими моментами есть окно, и оно не
 * теоретическое: `deploy-auto` накатывает миграции ДО остановки прежнего контейнера, а старый API
 * до самой остановки принимает и `POST /auto-parts/:id/stock`, и строки расхода в акте. Запись,
 * пришедшая в это окно, прошла бы мимо ручной проверки. Поэтому барьер стоит там, где старого API
 * уже нет, — в старте нового.
 *
 * ПОЧЕМУ ОТКАЗ ТОЛЬКО В ПРОДЕ. В деве таблицы НЕ пусты: там лежит след пробного заведения от
 * 01.09.2026 — позиция, три движения, строка акта. Одинаковая строгость означала бы, что `pnpm dev`
 * перестаёт запускаться у всех сразу после выпуска 2, а чистить эти записи незачем: они тестовые.
 * Тот же приём, что у `assertMigrationsApplied()` в `migration-check.ts`, — исключение сделано
 * узко и объяснено словами, а сама функция проверяется db-тестом, который зовёт её напрямую на
 * своей базе.
 *
 * ОТКАТ. У выпуска 2 нет ни одной миграции (Р26) — именно ради этого барьера: `deploy-auto`
 * накатывает миграции до `up -d`, и будь они у выпуска, к моменту отказа журнал был бы уже новее
 * образа выпуска 1, а `assertMigrationsApplied()` отказал бы поднимать и его. С пустым выпуском 2
 * откат — это ровно `deploy-auto --previous`.
 *
 * ЖИВЁТ ДО СНОСА СКЛАДА. Когда таблицы будут удалены насовсем, барьер снимается вместе с ними:
 * сторожить пустоту несуществующих таблиц незачем.
 */

/**
 * Четыре таблицы склада — весь его след в базе, в порядке «от карточки к расходу».
 *
 * Список литеральный и подставляется в SQL текстом (параметром имя таблицы не задать): значения
 * приходят отсюда, а не снаружи, поэтому подстановка безопасна по построению.
 *
 * Экспортирован ради db-теста: тот сверяет каждое имя с настоящей схемой (`to_regclass`), иначе
 * опечатка в списке означала бы «таблицу не считаем вовсе» — барьер молчал бы ровно там, где
 * обязан кричать.
 */
export const STOCK_TABLES = [
  'auto_parts',
  'auto_part_applicability',
  'auto_part_stock_entries',
  'vehicle_maintenance_parts',
] as const;

/** Минимум от клиента БД: и `pg.Pool` сервера, и `pg.Client` db-теста подходят как есть. */
export interface StockQuery {
  query<R extends Record<string, unknown>>(sql: string, params?: unknown[]): Promise<{ rows: R[] }>;
}

export interface StockFrozenOptions {
  /** Чем спрашивать: сервер ходит рабочим пулом, db-тест — своим соединением к своей базе. */
  client?: StockQuery;
  /** Строгость: в проде непустая таблица валит старт, вне прода — пишется предупреждением. */
  strict?: boolean;
}

/** Что нашлось: имя таблицы и число строк в ней. */
interface StockCount {
  table: string;
  rows: number;
}

async function countStockRows(client: StockQuery): Promise<StockCount[]> {
  const sql = STOCK_TABLES.map(
    (table) => `select '${table}' as table_name, count(*)::bigint as row_count from ${table}`,
  ).join(' union all ');
  const { rows } = await client.query<{ table_name: string; row_count: string }>(sql);
  return rows.map((r) => ({ table: r.table_name, rows: Number(r.row_count) }));
}

/** Причина отказа целиком: что нашли, почему это отменяет выкат и что делать дальше (Р25). */
function refusalMessage(found: StockCount[]): string {
  const listed = found.map((c) => `${c.table}: ${c.rows}`).join(', ');
  return (
    `Склад автозапчастей не пуст — ${listed}. Выпуск «Заморозка» снимает эти записи с экрана, ` +
    'не удаляя их из базы: заметить пропажу было бы нечем. Поэтому выкат отменяется, а разбирается ' +
    'вопрос «откуда запись»: склад скрыт из портала с выпуска 1, значит движение пришло прямым ' +
    'запросом к API или из ветки, которую считали мёртвой. Учтите, что «почистить руками» здесь не ' +
    'работает: журнал защищён триггером auto_part_stock_immutable (BEFORE UPDATE OR DELETE ... ' +
    'ENABLE ALWAYS, безусловный RAISE), у которого нет ветки, где DELETE проходит; порядок ' +
    'привилегированной чистки — docs/auto-part-receipts-plan.md, Р25. Вернуть портал: ' +
    'deploy-auto --previous (у выпуска 2 нет миграций, журнал не тронут).'
  );
}

/**
 * Сверка пустоты складских таблиц при старте сервера.
 *
 * Зовётся из `server.ts` строкой рядом с `assertMigrationsApplied()` и ДО `buildApp()`: приложение
 * строят десятки тестов, и проверка, уехавшая в сборку, уронила бы их все — причём по причине, к
 * ним не относящейся.
 */
export async function assertStockFrozenEmpty(options: StockFrozenOptions = {}): Promise<void> {
  const client = options.client ?? pool;
  const strict = options.strict ?? config.isProd;

  let counts: StockCount[];
  try {
    counts = await countStockRows(client);
  } catch (e) {
    // Непрочитанный счёт — это «не знаю, пусто ли», а барьер существует ровно ради этого знания,
    // поэтому в проде он остаётся fail-closed и здесь. В отличие от журнала миграций
    // (`migration-check.ts`), у рабочего пользователя нет причины не читать собственные таблицы
    // портала: он читал их до выпуска 1. Единственный ожидаемый источник такой ошибки — таблицы
    // склада уже удалены; тогда снимать надо не старт, а сам барьер, вместе с остатками склада.
    const message =
      'Не удалось сосчитать строки склада автозапчастей — пустота таблиц не подтверждена. ' +
      'Если таблицы склада уже удалены, снимите вместе с ними и эту проверку (Р24); ' +
      'иначе разберитесь с доступом к ним и повторите выкат.';
    if (strict) throw new Error(message);
    logger.warn({ err: e }, message);
    return;
  }

  const found = counts.filter((c) => c.rows > 0);
  if (found.length === 0) {
    logger.info('Склад автозапчастей пуст — заморозка законна');
    return;
  }

  if (strict) throw new Error(refusalMessage(found));
  logger.warn(
    { found },
    `${refusalMessage(found)} Вне production это предупреждение: в деве таблицы не пусты от ` +
      'пробного заведения, и старт из-за него не валится.',
  );
}
