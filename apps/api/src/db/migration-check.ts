import { pool } from './client';
import { diffMigrations, listMigrationNames } from './migration-journal';
import { logger } from '../logger';

/**
 * Сверка кода со схемой при старте сервера.
 *
 * Причина конкретная: код, ушедший вперёд неприменённой миграции, ломается не при старте, а в
 * первом же действии человека — и ломается пятисоткой из глубины транзакции. Так пропала форма
 * «Взять в работу» заказа спецтехники: сверка листов ЭСМ-2 читала колонки миграции 0087, база их
 * не знала, транзакция откатывалась целиком — заявка оставалась «Новой», перегон не заводился,
 * лист не выписывался. В интерфейсе это выглядит как «форма не работает», а в логе лежит SQL,
 * который читать некому.
 *
 * Поэтому сервер спрашивает журнал сам и до первого запроса. Деплой сверяет то же самое своим
 * `db:migrate:check`, но ловушка не там: она в `pnpm dev` после `git pull`, где миграции
 * применяет человек и забывает это сделать.
 *
 * Расхождение в обе стороны — отказ стартовать (fail-closed), как и у `db:migrate:check`:
 * неприменённая миграция означает «код новее базы», лишняя запись в журнале — «база новее кода»,
 * и работать в обоих случаях одинаково нельзя.
 *
 * Единственное исключение — журнал не прочитался. У рабочего пользователя нет DDL-прав (§8), и
 * права на `_migrations` ему могли не выдать вовсе; отказ стартовать из-за этого превратил бы
 * страховку в аварию. Такое пишется предупреждением и не мешает: тот, кто мог бы её проверить,
 * — миграционный контейнер — сверку уже прошёл.
 */
export async function assertMigrationsApplied(): Promise<void> {
  let diff;
  try {
    diff = await diffMigrations(pool);
  } catch (e) {
    logger.warn(
      { err: e },
      'Не удалось прочитать журнал миграций (_migrations) — сверка схемы пропущена',
    );
    return;
  }

  if (diff.missing.length > 0) {
    throw new Error(
      `База новее кода: в журнале есть миграции, которых нет в образе — ${listMigrationNames(diff.missing)}. ` +
        'Разверните версию, которой эти миграции принадлежат.',
    );
  }
  if (diff.pending.length > 0) {
    throw new Error(
      `Схема отстала от кода: не применено миграций ${diff.pending.length} — ${listMigrationNames(diff.pending)}. ` +
        'Выполните `pnpm db:migrate` (в проде — migrate-контейнер) и запустите сервер снова.',
    );
  }
  logger.info({ applied: diff.applied.length }, 'Схема соответствует коду');
}
