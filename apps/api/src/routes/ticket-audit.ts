/**
 * Аудит распознавания талонов вывоза (ADR 0137, план `docs/waste-ticket-audit-plan.md`, §5.1, §6).
 *
 * **Область объекта и оператора здесь НЕ применяется — и это не забывчивость.** Во всех соседних
 * ручках вывоза она есть: список заявок, карточка, разбор талонов проходят
 * `placeObjectVisibilityWhere` и `operatorVisibilityWhere`, потому что там речь о чужой работе —
 * о заявке конкретной площадки и о бумаге конкретного перевозчика. Здесь речь о другом предмете:
 * ответ на вопрос «где машина ошибается» собирается по всем площадкам сразу. Посчитай его по
 * своему куску выборки — и доля исправлений измерит не модель, а объект: у площадки с двумя
 * талонами в месяц она будет скакать на пятьдесят процентов от одной правки, а у крупной
 * покажет усреднение, к которому первая не имеет отношения. Сквозным аудит выбран заказчиком
 * 26.08.2026 (§4.1), и цена решения названа там же: держатель права видит наблюдения по всем
 * площадкам и по бумаге всех исполнителей.
 *
 * Отсюда и отдельное право `wasteRequests.ticketAudit`. Оно не выдаётся ни одной роли и живёт
 * одноцелевым системным набором `waste_ticket_audit`, который администратор выдаёт поимённо
 * (§4.1). Держатель `wasteRequests.ticketReview` сюда не проходит: разбор — работа над своей
 * заявкой, и открыть ею сквозную картину значило бы отдать её всей диспетчерской разом, то есть
 * мимо поимённой выдачи, ради которой набор и заведён.
 *
 * Отдельным плагином на том же префиксе `/api/v1/waste-requests`, а не веткой `waste-tickets.ts`:
 * тот файл целиком закрыт правом разбора и целиком вложен в заявку, а здесь ни того, ни другого —
 * смешать их в одном файле значило бы держать в нём две разные области доступа.
 *
 * Все ручки раздела — только чтение: инструмент наблюдения, умеющий вмешиваться, однажды
 * вмешается вместо наблюдения (§6).
 */

/** Границы суток московские — те же, что у сводки (`services/ticket-audit.ts`, §1.3). */
const ZONE = 'Europe/Moscow';

/**
 * Умолчание периода — окно из §5.1: `to` — сегодняшние московские сутки, `from` — на 30 суток
 * раньше (в примере плана «27.07.2026 — 26.08.2026»). Считается назад от конца, а не вперёд от
 * начала: экран открывают, чтобы посмотреть на последние недели, и «сегодня» здесь опорная точка.
 */
const DEFAULT_PERIOD_DAYS = 30;

/**
 * Предел периода — 92 календарных дня (§4.3), считая обе границы. Число не круглое, потому что
 * это длина самого длинного квартала (июль + август + сентябрь = 92): целый квартал в отчёт
 * помещаться обязан, а год — нет. Предел стоит и на сводке, хотя §4.3 говорит о выгрузке: сводка
 * читает `waste_ticket_field_events` пятью запросами с коррелированными подзапросами, и годовой
 * период отличается от квартального не размером ответа, а временем счёта.
 */
const MAX_PERIOD_DAYS = 92;

/**
 * Строка запроса всех ручек раздела — одна на всех, а не своя у каждой: период у экранов общий,
 * и человек, сузивший его на сводке, ждёт того же отрезка на когортах.
 *
 * Оба параметра необязательные: без них берётся умолчание §5.1. Формат проверяет схема — до
 * стража, поэтому «12 августа» получит 400 раньше всякой проверки права, и это правильный порядок:
 * разбирать заведомо негодную дату под чужим правом незачем.
 */
const periodQuery = z.object({
  from: z.string().date().optional(),
  to: z.string().date().optional(),
});

/**
 * Строка запроса состояния подсистемы (§5.4) — пустая и СТРОГАЯ.
 *
 * Состояние периода не принимает вовсе: очередь и заявки, ждущие разбора, — это снимок «сейчас», а
 * вызовы, отказы и токены считаются фиксированным окном в `TICKET_AUDIT_OPERATIONS_DAYS` суток по
 * времени вызова (§1.3, §5.4). Вопрос «какова длина очереди за июль» смысла не имеет: очередь не
 * величина за отрезок, а состояние на момент ответа.
 *
 * Отсюда и строгость. Соблазн написать здесь `z.object({})` без `strict` силён — схема тогда просто
 * выбросит лишнее, и ручка ответит. Ответит она при этом НЕ НА ТОТ вопрос, который ей задали:
 * приславший `?from=2026-07-01&to=2026-07-31` получит 200 и числа за последнюю неделю, прочтёт их
 * как июльские и будет прав по-своему — параметр он передал, ошибки не увидел. Молча
 * проигнорированный параметр обманывает убедительнее, чем отказ: у отказа виден повод, у молчания
 * его нет. Поэтому лишний параметр — это 400 с объяснением, что окно здесь своё и почему.
 *
 * Схема стоит до стража, поэтому 400 приходит раньше проверки права: разбирать заведомо негодную
 * строку запроса под чужим правом незачем — так же, как у периода соседних ручек.
 */
const operationsQuery = z.strictObject(
  {},
  {
    error: () =>
      'Состояние подсистемы не считается за период: очередь — это снимок «сейчас», ' +
      `а вызовы и отказы — окно в ${TICKET_AUDIT_OPERATIONS_DAYS} дней. Уберите параметры.`,
  },
);

/** Сегодняшняя календарная дата в Москве: сервер живёт в UTC, а человек — нет. */
function moscowToday(now: Date): string {
  return new Intl.DateTimeFormat('en-CA', {
    timeZone: ZONE,
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).format(now);
}

/**
 * Сдвиг календарной даты на сутки. Считается в UTC намеренно: сдвигается **номер дня**, а не
 * момент времени, и переход на летнее время (которого в Москве нет, но код переживёт и его отмену
 * обратно) не должен превращать 30 суток в 29 или 31.
 */
function shiftDays(dateOnly: string, days: number): string {
  const at = new Date(`${dateOnly}T00:00:00Z`);
  at.setUTCDate(at.getUTCDate() + days);
  return at.toISOString().slice(0, 10);
}

/** Длина периода в календарных днях, считая обе границы: «с 1-го по 1-е» — это одни сутки. */
function periodLength(from: string, to: string): number {
  const span = Date.parse(`${to}T00:00:00Z`) - Date.parse(`${from}T00:00:00Z`);
  return Math.round(span / 86_400_000) + 1;
}

/**
 * Период запроса: умолчание, форма и предел длины.
 *
 * Умолчание достраивается по каждой границе отдельно. Пришёл один `from` — концом берётся
 * сегодняшний день, а не «начало плюс 30»: человек, написавший начало руками, спрашивает «что
 * было с тех пор», и дорисованный конец в прошлом ответил бы на другой вопрос — молча и
 * убедительно.
 */
function periodOf(query: z.infer<typeof periodQuery>, now: Date): TicketAuditPeriod {
  const to = query.to ?? moscowToday(now);
  const from = query.from ?? shiftDays(to, -DEFAULT_PERIOD_DAYS);
  // Форму периода описывает контракт, и собирается она им же: правило «начало не позже конца»
  // живёт там (`ticketAuditPeriodSchema`), и повторять его здесь значило бы завести вторую
  // редакцию правила — ту, которая однажды разойдётся с первой.
  const parsed = ticketAuditPeriodSchema.safeParse({ from, to });
  if (!parsed.success) {
    // Единственное правило схемы, до которого доходит дело: формат дат проверен querystring-схемой
    // раньше. Контракт указывает на `from`, туда же ставится пометка поля формы.
    const message = parsed.error.issues[0]?.message ?? 'Некорректный период';
    throw err.badRequest(`${message}: с ${from} по ${to}`, { from: message });
  }
  const days = periodLength(from, to);
  if (days > MAX_PERIOD_DAYS) {
    throw err.badRequest(
      `Период аудита не длиннее ${MAX_PERIOD_DAYS} дней, а запрошено ${days} ` +
        `(с ${from} по ${to}). Возьмите период покороче — например, квартал.`,
      { from: `Не длиннее ${MAX_PERIOD_DAYS} дней` },
    );
  }
  return parsed.data;
}

// ── Выгрузка ленты (§4.3) ──

/**
 * Предел выгрузки в строках. Стоит РЯДОМ с пределом периода, а не вместо него: 92 дня ограничивают
 * отбор, а это число — то, что из отбора вышло. Одна шумная неделя даёт событий больше, чем
 * спокойный квартал, и период, укладывающийся в предел, сам по себе ничего о размере файла не
 * обещает.
 */
const MAX_EXPORT_ROWS = 50_000;

/**
 * Символы, с которых Excel читает значение как ФОРМУЛУ, а не как текст (§4.3).
 *
 * Опасны они не тем, что портят вид. Талон читают по адресу площадки и номеру, и в файл эти
 * значения идут как есть — вместе с тем, что в них когда-то напечатала чужая рука. Ячейка,
 * начинающаяся с `=`, у открывшего файл человека выполнится: формула умеет и сходить по ссылке
 * наружу, и позвать внешнюю программу через DDE. Поэтому апостроф ставится ВСЕГДА, а не «если
 * похоже на формулу»: разбирать, безобидна ли конкретная строка, значит однажды ошибиться.
 *
 * Табуляция и возврат каретки в списке потому, что Excel их с начала значения молча съедает — и
 * `\t=2+2` доходит до разбора формул тем же `=2+2`, только мимо проверки первого символа.
 */
const FORMULA_LEAD = /^[=+\-@\t\r]/;

/** Символы, из-за которых значение приходится брать в кавычки (RFC 4180). */
const CSV_SPECIAL = /[",\r\n]/;

/**
 * Значение в ячейку: сначала защита от формулы, потом кавычки.
 *
 * Порядок именно такой, и обратный был бы дырой. Закавычив первым, мы получили бы значение,
 * начинающееся с `"`, — под `FORMULA_LEAD` оно больше не подходит, апостроф не поставится, а
 * Excel, сняв кавычки при разборе, увидит прежнее `=…` и посчитает его формулой. То есть защита
 * сработала бы на всём, кроме значений, которые её и требуют.
 */
function csvCell(value: string | number | null): string {
  const text = value === null ? '' : String(value);
  const guarded = FORMULA_LEAD.test(text) ? `'${text}` : text;
  return CSV_SPECIAL.test(guarded) ? `"${guarded.replaceAll('"', '""')}"` : guarded;
}

/** Строка файла: ячейки через запятую, каждая — через `csvCell`. */
function csvRow(cells: readonly (string | number | null)[]): string {
  return cells.map(csvCell).join(',');
}

/**
 * Названия событий по-русски. Живут здесь, а не в контракте, потому что читатель у них один — этот
 * файл: на экране ленты (§5.3) тип события подписан своей вёрсткой, а `edited` в столбце «Событие»
 * прочёл бы только тот, кто и так знает журнал изнутри.
 *
 * Тип `Record<TicketAuditEvent, string>` — не украшение: событие, добавленное в контракт, оставит
 * здесь дыру, и компилятор назовёт её раньше, чем выгрузка отдаст пустую ячейку.
 */
const EVENT_LABELS: Record<TicketAuditEvent, string> = {
  recognized: 'машинное чтение',
  disputed: 'спор проходов',
  edited: 'правка',
  proposal: 'предложение принято',
  proposal_dismissed: 'предложение отклонено',
  arbitrated: 'арбитраж перепроверки',
  dismissed: 'не талон',
};

/**
 * Столбцы файла — те же величины, что в строке ленты (§5.3), и в том же порядке: время, заявка,
 * поле, событие, оба значения, человек, конфигурация чтения.
 *
 * Ссылки на скан в файле нет намеренно: она живёт внутри портала и за его пределами не открывается,
 * а столбец с недействующим адресом читается как обещание.
 */
const CSV_COLUMNS = [
  'Время',
  'Заявка',
  'Поле',
  'Событие',
  'Было',
  'Стало',
  'Кто',
  'Модель',
  'Версия промпта',
  'Версия подготовки',
];

/**
 * Файл целиком: BOM, заголовок, строки.
 *
 * **BOM обязателен.** Без него Excel читает файл в однобайтовой кодировке системы, и кириллица
 * приезжает мусором — то есть выгрузка формально верна и практически нечитаема.
 *
 * Конец строки `\r\n` и последний перевод строки — по RFC 4180.
 *
 * Время идёт как «2026-08-26 14:12:00»: сервис отдаёт московское время в ISO, а `T` посередине
 * Excel датой не считает и кладёт значение текстом — сортировать такой столбец человек уже не
 * сможет. Часовой пояс в ячейку не пишется: он московский у всего раздела, и подпись столбца об
 * этом говорит один раз (§1.3).
 */
function eventsCsv(rows: readonly TicketAuditEventRow[]): Buffer {
  const lines = [
    csvRow(CSV_COLUMNS),
    ...rows.map((row) =>
      csvRow([
        row.at.replace('T', ' '),
        row.requestNum,
        wasteTicketFieldLabels[row.field],
        EVENT_LABELS[row.event],
        row.oldValue,
        row.newValue,
        row.actorName,
        row.model,
        row.promptVersion,
        row.preprocessingVersion,
      ]),
    ),
  ];
  return Buffer.from(`\ufeff${lines.join('\r\n')}\r\n`, 'utf8');
}

/**
 * Фильтры отбора для журнала выгрузок — всё, что сузило выборку, кроме периода и постраничности.
 *
 * Собираются остатком, а не перечислением полей: перечень разошёлся бы с контрактом в тот день,
 * когда у ленты появится шестой фильтр, и журнал молча записал бы выгрузку как более широкую, чем
 * она была. Период пишется своим полем, страницы к полной выгрузке не применяются вовсе.
 */
function exportFilters(query: TicketAuditEventsQuery): Record<string, unknown> {
  const { from: _from, to: _to, page: _page, pageSize: _pageSize, ...filters } = query;
  return filters;
}

export default async function ticketAuditRoutes(app: FastifyInstance): Promise<void> {
  const r = app.withTypeProvider<ZodTypeProvider>();
  const canAudit = {
    preHandler: [
      app.authenticate,
      app.requirePermission(
        'wasteRequests.ticketAudit',
        'Недостаточно прав для аудита распознавания талонов',
      ),
    ],
  };

  /**
   * Ручка раздела: право, строка запроса, разбор периода и его предел — общие; своё у каждой
   * только чтение, которое считает ответ.
   *
   * Помощник, а не копия на каждую ручку, по той же причине, по которой исход наблюдения считается
   * в одном месте: разойдись у сводки и когорт умолчание или предел, два экрана назвали бы
   * «периодом» разные отрезки времени и разошлись бы в числах, ничего об этом не сообщив.
   *
   * `new Date()` берётся на каждый запрос, а не на регистрацию плагина: сервер живёт неделями, и
   * умолчание, посчитанное при старте, показывало бы позапрошлый месяц как «последние 30 суток».
   */
  function auditRoute<T>(path: string, read: (period: TicketAuditPeriod) => Promise<T>): void {
    r.get(path, { ...canAudit, schema: { querystring: periodQuery } }, async (req): Promise<T> =>
      read(periodOf(req.query, new Date())),
    );
  }

  /*
   * Пути двусоставные (`ticket-audit/summary`, `ticket-audit/cohorts`), как у соседнего
   * `ticket-recognition/health`, и это не украшение. Односоставный `ticket-audit` стоял бы на том
   * же уровне, что и `GET /api/v1/waste-requests/:id`: маршрутизатор Fastify предпочитает
   * статический сегмент параметрическому, так что раздел нашёлся бы, — но заявка с идентификатором
   * `ticket-audit` стала бы недостижимой, а сам выбор держался бы на порядке узлов в дереве, о
   * котором в коде не написано ничего. Два сегмента снимают вопрос: параметрических маршрутов вида
   * `/:id/:что-то` в модуле нет вовсе, и перехватывать раздел нечему. Проверено запросом —
   * `test/ticket-audit-route.db.test.ts`.
   *
   * Считает всё до последнего числа сервис (`services/ticket-audit.ts`): исход наблюдения —
   * единственное место, и ручки его не повторяют ни строкой. Разойдись два запроса в том, что
   * считать знаменателем, — два экрана показали бы разные проценты об одном и том же.
   */

  /** Сводка §5.1: наблюдения по исходам, таблица полей, предложения и повторные правки. */
  auditRoute<TicketAuditSummaryDto>('/ticket-audit/summary', ticketAuditSummary);

  /**
   * Когорты §5.2: что происходит в каждой конфигурации конвейера, плюс блок каскада.
   *
   * Отдельной ручкой, а не полем сводки, — и не ради экономии байтов, а потому что вопросы разные:
   * сводка отвечает «сколько правят», когорты — «что менять в конвейере». Сложи их в один ответ, и
   * открытие первого экрана каждый раз оплачивало бы счёт второго: когорты читают те же события
   * своей группировкой, и предел в 92 дня стоит здесь именно из-за времени счёта (§4.3).
   */
  auditRoute<TicketAuditCohortsDto>('/ticket-audit/cohorts', ticketAuditCohorts);

  /**
   * Точность среди неисправленных подтверждённых талонов (§5.5): слепая перепроверка, три поля и
   * три исхода арбитража.
   *
   * Период разбирается ТЕМ ЖЕ помощником, что у сводки, хотя считается по другому времени — по
   * времени ВЫДАЧИ перепроверки (`waste_ticket_blind_checks.created_at`), а не наблюдения. Границы
   * при этом обязаны совпадать: человек, переключивший экран, ждёт того же отрезка, и «те же 30
   * суток» у двух экранов не должны означать разные отрезки.
   *
   * Отдельной ручкой от сводки — по прямому указанию §5.5: экран не соседствует со сводкой и в одну
   * плитку с долей исправлений не сводится. Подтверждение оператора независимым чтением не
   * является, и смешение этих чисел рождает ту самую убедительную неправду, ради которой модуль и
   * переписывается. Сложи их в один ответ — и разделять их на экране пришлось бы вёрсткой, то есть
   * держаться разделение стало бы на договорённости.
   *
   * Смещение выборки ручка не правит и не прячет: в слепую перепроверку попадают только машинные
   * талоны, которых первый оператор не исправлял, поэтому число ожидаемо оптимистично.
   * Предупреждение об этом — часть экрана (§5.5), и стоять оно обязано рядом с процентом.
   */
  auditRoute<TicketAuditAccuracyDto>('/ticket-audit/blind', ticketAuditAccuracy);

  /**
   * Лента §5.3: события за период, с фильтрами и постранично.
   *
   * Мимо помощника `auditRoute`, и не по недосмотру: у ленты своя строка запроса — пять фильтров и
   * страница, — а `periodQuery` знает только границы. Зато период разбирается ТЕМ ЖЕ `periodOf`:
   * умолчание в 30 суток и предел в 92 дня у ленты обязаны совпадать со сводкой, иначе человек,
   * перешедший на ленту с экрана метрик, увидел бы «тот же» период другой длины.
   *
   * ЧТО ЗДЕСЬ ДРУГОЕ — смысл отрезка, а не его границы. Метрики фильтруют по времени НАБЛЮДЕНИЯ,
   * лента — по времени СОБЫТИЯ (§1.3): правка, сделанная сегодня по августовскому чтению, стоит в
   * ленте сегодняшним днём и в августовской доле исправлений одновременно. Это не рассогласование,
   * а два разных вопроса, и различает их сам запрос сервиса — здесь же видно только, что период
   * один и тот же. Ровно поэтому на экране ленты он подписан «события за», а не «наблюдения за».
   *
   * Предел периода стоит и тут, хотя страница ответ и так ограничивает: общее число лента считает
   * оконной функцией по ВСЕЙ выборке, и годовой запрос стоил бы столько же, сколько без страниц.
   */
  r.get(
    '/ticket-audit/events',
    { ...canAudit, schema: { querystring: ticketAuditEventsQuerySchema } },
    async (req): Promise<TicketAuditEventsDto> =>
      ticketAuditEvents({ ...req.query, ...periodOf(req.query, new Date()) }),
  );

  /**
   * Та же выборка файлом (§4.3). Полная: страница из строки запроса к ней не применяется — «первая
   * страница выгрузки» была бы файлом, который выглядит отчётом, а содержит пятьдесят строк.
   *
   * Отсюда и `pageSize` сверх контрактных двухсот. Двести — это предел того, что можно попросить
   * ДЛЯ ЭКРАНА: страница ленты рисуется в браузере, и тысяча строк там не помогает никому. У файла
   * читатель другой — Excel, — и предел ему поставлен свой, `MAX_EXPORT_ROWS`. Схема при этом
   * по-прежнему проверяет всё, что прислал человек; здесь подставляется не его число, а наше.
   *
   * ПРЕДЕЛ СЧИТАЕТСЯ ПО `total` ТОГО ЖЕ ЗАПРОСА, а не отдельным `count(*)` до выборки. Два запроса
   * разошлись бы на любой параллельной записи: посчитали 49 999, выбрали 50 001 — и файл ушёл бы
   * длиннее предела, отчитавшись в журнале о числе, которого в нём нет. Оконный счёт лента ведёт
   * по всей выборке до `LIMIT`, поэтому одного запроса довольно: строк приезжает не больше предела,
   * а `total` называет, сколько их было на самом деле.
   *
   * Журнал ведётся ДО отдачи файла и после проверки предела: записывать надо состоявшуюся выгрузку,
   * а не намерение. Ошибка записи файл не задержит (`writeAudit` её глотает) — и это осознанная
   * сторона компромисса: событие ценно, но человек, которому отказали в выгрузке из-за сбоя
   * журнала, выгрузит те же строки экраном и постраничным чтением, только незаметно.
   */
  r.get(
    '/ticket-audit/events.csv',
    { ...canAudit, schema: { querystring: ticketAuditEventsQuerySchema } },
    async (req, reply) => {
      const period = periodOf(req.query, new Date());
      const data = await ticketAuditEvents({
        ...req.query,
        ...period,
        page: 1,
        pageSize: MAX_EXPORT_ROWS,
      });
      if (data.total > MAX_EXPORT_ROWS) {
        throw err.badRequest(
          `Выгрузка не длиннее ${MAX_EXPORT_ROWS} строк, а по этому отбору их ${data.total} ` +
            `(с ${period.from} по ${period.to}). Сузьте период или добавьте фильтр.`,
          { from: `Не больше ${MAX_EXPORT_ROWS} строк` },
        );
      }

      /*
       * Выгрузка уносит из портала персональные данные: адрес площадки идёт в файл значением поля
       * (§4.3, выгрузка полная), рядом с ним — фамилия того, кто правил. Это учётное событие того
       * же порядка, что выгрузка справочника водителей, и пишется оно всегда, вместе с периодом,
       * фильтрами и числом строк: без них журнал отвечает «выгружал», но не «что именно».
       */
      await writeAudit({
        actorUserId: requirePrincipal(req).id,
        action: 'waste_request.ticket_audit_export',
        entityType: 'waste_request',
        metadata: { period, filters: exportFilters(req.query), rows: data.rows.length },
      });

      const name = `Аудит распознавания талонов ${period.from} — ${period.to}.csv`;
      return reply
        .type('text/csv; charset=utf-8')
        .header('content-disposition', `attachment; filename*=UTF-8''${encodeURIComponent(name)}`)
        .send(eventsCsv(data.rows));
    },
  );

  /**
   * Состояние подсистемы и цена работы (§5.4): окно в 7 суток, очередь, отказы по парам
   * «класс × область», токены и размер журнала.
   *
   * Мимо помощника `auditRoute`, и это как раз тот случай, когда пройти помощником было бы хуже:
   * он даёт ручке период, а здесь периода нет ни в вопросе, ни в ответе. Дай его — и ручка начала
   * бы принимать отрезок, которым ничего не считает.
   *
   * ЭКРАН РЯДОМ С `ticket-recognition/health`, НО ЭТО ДРУГАЯ РУЧКА И ДРУГОЕ ПРАВО. Тот отвечает
   * разбирающему талоны на вопрос «работает ли прямо сейчас» и живёт в окне часа; этот отвечает
   * держателю аудита на вопрос «во что обходится и что копится» — по всему порталу, теми же
   * сквозными числами, что и остальные экраны раздела. Состояние у них общее и считается по одним
   * правилам (сервис), чтобы два экрана не спорили друг с другом.
   *
   * `disabled` — это ОТВЕТ, а не отсутствие ответа: выключенное настройкой распознавание и
   * сломанное различаются словом состояния, и ручка отдаёт полное тело с нулями в обоих случаях.
   * Ответь она пустотой или отказом — дежурный искал бы сбой там, где принято решение.
   */
  r.get(
    '/ticket-audit/operations',
    { ...canAudit, schema: { querystring: operationsQuery } },
    async (): Promise<TicketAuditOperationsDto> => ticketAuditOperations(),
  );
}
