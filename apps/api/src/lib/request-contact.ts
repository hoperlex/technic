import { err } from './errors';

// Контакт ответственного по заявке (миграция 0062). Общий на оба модуля заявок: правило одно —
// у заявки должен быть человек, к которому едут, — а мест, где заявку правят, два.

/**
 * Итоговое значение поля контакта после правки. Не переданное поле означает «не трогали», и
 * прежнее значение сохраняется — но пустым оно остаться не может: у заявок старше миграции 0062
 * контакта нет, и правка — тот момент, когда его есть у кого спросить. Разрешить «сохранить как
 * было» значило бы оставить такие заявки без контакта навсегда.
 *
 * Ошибка идёт полем (`err.validation`), а не текстом: форма показывает её на самом поле, иначе
 * человек не знает, какой из четырёх контактов грузоперевозки он не заполнил.
 */
export function nextRequestContact(
  next: string | undefined,
  prev: string,
  field: string,
  message: string,
): string {
  const value = (next ?? prev).trim();
  if (!value) throw err.validation({ [field]: message });
  return value;
}
