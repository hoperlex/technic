import type { FastifyReply, FastifyRequest } from 'fastify';

/**
 * Срок жизни долгого запроса и его отмена (ADR 0148).
 *
 * Обычная ручка портала отвечает за миллисекунды, и говорить о её сроке незачем. Печать путевого
 * листа — другое дело: она держит соединение, пока чужая программа переводит бланки в PDF, и у
 * такой работы обязаны быть две границы.
 *
 * **Первая — срок.** Без него запрос ограничен лишь тем, кто сдастся раньше, а сдаётся раньше
 * nginx: он рвёт соединение и ничего не объясняет ни человеку, ни серверу. Свой срок позволяет
 * ответить осмысленно и до того, как оборвут снаружи, — ради этого он и стоит ниже проксирующего
 * (`PRINT_BUDGET`).
 *
 * **Вторая — уход того, кто просил.** Fastify не прерывает обработчик, когда клиент закрыл
 * соединение: сборка продолжается, конвертер работает, аудит пишется — и всё это ради ответа,
 * который некому прочитать. На печати цена такой работы — занятое ядро и соединение пула, а
 * человек тем временем жмёт «Печать» снова, добавляя ещё одну брошенную попытку. Отсюда сигнал,
 * который гаснет вместе с соединением.
 *
 * Причины различаются намеренно: `ClientGone` означает «отвечать некому» — молча свернуться;
 * истёкший срок означает «не успели» — и об этом человеку нужно сказать словами.
 */

/** Причина отмены: соединение закрыто тем, кто запрашивал. Отвечать больше некому. */
export class ClientGone extends Error {
  constructor() {
    super('Клиент закрыл соединение');
    this.name = 'ClientGone';
  }
}

/** Ушёл ли клиент — в отличие от «истёк срок». Спрашивают те, кто получил сигнал, а не запрос. */
export function isClientGone(signal: AbortSignal | undefined): boolean {
  return signal?.aborted === true && signal.reason instanceof ClientGone;
}

export interface RequestBudget {
  /** Гаснет по сроку или вместе с соединением. Передаётся всему, что делает долгую работу. */
  readonly signal: AbortSignal;
  /** Снимает слушатели и таймер. Обязателен в `finally`: иначе они переживут сам запрос. */
  dispose(): void;
}

/**
 * Заводит бюджет запроса: сигнал гаснет по сроку `ms` или когда клиент закрыл соединение.
 *
 * `close` на сырых объектах, а не `reply.sent`: событие приходит и при штатной отправке ответа
 * тоже, и отличить уход клиента от нормального завершения можно только по тому, успел ли ответ
 * уйти в сокет (`writableEnded`). Проверка стоит именно так, а не наоборот, потому что ложное
 * «клиент ушёл» на завершённом ответе отменило бы работу, которая уже никому не мешает.
 */
export function requestBudget(req: FastifyRequest, reply: FastifyReply, ms: number): RequestBudget {
  const controller = new AbortController();
  const onClose = () => {
    if (!reply.raw.writableEnded) controller.abort(new ClientGone());
  };
  req.raw.on('close', onClose);

  const timer = setTimeout(() => controller.abort(new Error('Истёк срок запроса')), ms);
  // Таймер не держит процесс: остановка сервера не должна ждать окончания чужого срока.
  timer.unref();

  return {
    signal: controller.signal,
    dispose() {
      clearTimeout(timer);
      req.raw.removeListener('close', onClose);
    },
  };
}
