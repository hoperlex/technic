import fp from 'fastify-plugin';
import type { FastifyPluginCallback } from 'fastify';
import { config } from '../config';
import { AppError } from './errors';

/**
 * Гейт минимальной версии клиента (ADR 0146, решение 7; план
 * `docs/office-equipment-consumables-and-purchase-plan.md`, Р8).
 *
 * **Зачем.** Ответ ручки может перестать читаться старым JS — например, когда обязательное поле
 * DTO становится пустым. Открытая вкладка от этого не спасается баннером обновления: он отменяем
 * кнопкой «Позже» (`apps/web/src/components/AppUpdateBanner.tsx`), и вкладка живёт сколько угодно.
 * Нужен механизм, который откажет, а не попросит.
 *
 * **Почему число контракта, а не сборка.** `BUILD_ID` — короткий commit SHA, и отношения
 * «ниже/выше» у него нет вовсе: `a731bc2` и `f0184de` несравнимы. Поэтому заголовков два, и у
 * каждого своя работа:
 *
 * ```
 * X-Client-Build:    a731bc2   ← диагностика: какая именно сборка пришла
 * X-Client-Contract: 1         ← гейт: монотонное целое, растёт при несовместимости
 * MIN_CLIENT_CONTRACT: 1       ← пол на сервере
 * ```
 *
 * Число вшивается в бандл портала константой (`apps/web/src/shared/api/clientContract.ts`) и
 * поднимается вручную и редко — ровно тогда, когда ответ перестаёт быть читаемым старым кодом.
 * Общего типа у двух сторон намеренно нет: портал вшивает своё число в сборку, сервер читает своё
 * из окружения, и связывать их одним модулем значило бы требовать одновременного выката.
 *
 * **Отсутствующий заголовок читается как контракт 1.** Правило постоянное, а не переходное:
 * клиентов без заголовка после перехода не останется, но правило избавляет гейт от третьего
 * состояния «не знаю». По той же причине как контракт 1 читается и мусор в заголовке.
 *
 * **Две фазы.** Фаза A — пол `1`: не блокируется никто, и в ней выкатывается сборка, которая
 * заголовок начинает слать. Фаза B — пол поднимается до числа новой сборки ОТДЕЛЬНЫМ действием,
 * после того как новая статика проверенно раздаётся. Одношаговое включение дало бы промежуток, в
 * котором старый клиент уже заблокирован, а новой статики ещё нет: `api` и `web` поднимаются одной
 * командой, и `web` зависит от `api` (`deploy/docker-compose.yml`).
 *
 * **Статус отказа — 426 Upgrade Required.** Он единственный в наборе означает ровно это: «запрос
 * правильный, но версия клиента не годится». 400 читался бы как ошибка в теле, 409 — как
 * расхождение данных, а 403 увёл бы разговор к правам.
 */

/** Диагностический заголовок: какая сборка портала прислала запрос. Гейт его не толкует. */
export const CLIENT_BUILD_HEADER = 'x-client-build';

/** Заголовок гейта: монотонное целое, объявляющее версию контракта клиента. */
export const CLIENT_CONTRACT_HEADER = 'x-client-contract';

/**
 * Чем читается запрос без заголовка (и с нечитаемым заголовком). Постоянное правило, а не
 * умолчание переходного периода: третьего состояния «не знаю» у гейта нет.
 */
export const ASSUMED_CLIENT_CONTRACT = 1;

/**
 * Код отказа. Тот же литерал уже носит 409 предпросмотра смены техники
 * (`src/services/assignment-reassign.ts`) — там он означает «клиент не шлёт отпечаток». Разговор
 * у порталов разный, и различает их СТАТУС: гейт отвечает 426, и портал разбирает пару
 * «426 + код», а не код в одиночку.
 */
export const CLIENT_UPGRADE_REQUIRED = 'client_upgrade_required';

/**
 * Тело отказа самодостаточно, и это не украшение. Клиент, собранный до этого выпуска, обработчика
 * 426 не имеет вовсе: он покажет обычное окно ошибки с этим текстом — и прочитает его человек, а
 * не код. Поэтому здесь сказано, что делать, а не «версия клиента ниже минимальной».
 */
export const CLIENT_UPGRADE_MESSAGE =
  'Портал обновился, обновите страницу (Ctrl+R, на Mac ⌘+R): эта вкладка работает на устаревшей версии и продолжать на ней нельзя.';

/** Префикс браузерного API портала. Гейту подлежит только он — см. `isGatedPath`. */
const API_PREFIX = '/api/v1';

/**
 * Ручки, выведенные из-под гейта НАСОВСЕМ. Освобождение постоянное, а не на время перехода, и
 * выдано оно по одной причине: старый клиент читает неуспешный ответ этих ручек не как отказ, а
 * как другое событие, и последствие выходит хуже самого отказа.
 *
 * - **`/auth/refresh`** — `apps/web/src/shared/api/session.ts` читает ВСЯКИЙ неуспешный ответ
 *   обновления как «сессия кончилась» и объявляет её законченной. Попади обновление старой вкладки
 *   в фазу B — человека выкинуло бы из портала посреди работы, и починить это в уже загруженной
 *   вкладке нельзя. Дыры нет: обновление сессии доменных DTO не отдаёт, а тот же клиент упрётся в
 *   426 на первой же доменной ручке.
 * - **`/auth/logout`** — `apps/web/src/api/auth.ts` чистит сессию вкладки ТОЛЬКО после успешного
 *   ответа (`await apiFetch(...); clearSession();`). Отказ гейта оставил бы вкладку считающей себя
 *   вошедшей, а серверную сессию — неотозванной: гейт не должен уметь запереть человека внутри
 *   сессии, из которой тот выходит. Домена в ответе нет вовсе — ответ пустой.
 *
 * **Вход (`/auth/login`) в перечень НЕ входит.** Там та же причина не работает: отказ читается
 * ровно как отказ, портал показывает сообщение из тела, и оно самодостаточно. Больше того, гейт на
 * входе даёт более чистый исход — одно понятное сообщение на форме вместо горсти тостов на первом
 * же экране портала после успешного входа.
 *
 * **Плата за освобождение — обязательство**: ответы этих двух ручек обязаны оставаться обратно
 * совместимыми, потому что гейт их больше не прикрывает. Записано здесь, а не в голове того, кто
 * будет их менять.
 */
const EXEMPT_PATHS: ReadonlySet<string> = new Set([
  `${API_PREFIX}/auth/refresh`,
  `${API_PREFIX}/auth/logout`,
]);

/** Путь запроса без строки запроса и без хвостового слэша. */
function pathOf(url: string): string {
  const cut = url.indexOf('?');
  const path = cut === -1 ? url : url.slice(0, cut);
  return path.length > 1 && path.endsWith('/') ? path.slice(0, -1) : path;
}

/**
 * Подлежит ли путь гейту.
 *
 * Гейт стоит только на браузерном API (`/api/v1/**`) — и это не сужение ради осторожности, а
 * условие работоспособности:
 *
 * - `/health/*` и `/metrics` дёргает healthcheck контейнера обычным `fetch` без заголовков
 *   (`deploy/docker-compose.yml`). Под гейтом в фазе B он читал бы 426 как «сервис не готов», и
 *   исправный `api` числился бы больным;
 * - `/internal/*` ходит worker с общим секретом (`docs` ADR 0075, ADR 0133) — это не браузер, DTO
 *   он не рисует, а отказ остановил бы рассылки и автозакрытие заявок.
 */
export function isGatedPath(url: string): boolean {
  const path = pathOf(url);
  if (path !== API_PREFIX && !path.startsWith(`${API_PREFIX}/`)) return false;
  return !EXEMPT_PATHS.has(path);
}

/**
 * Контракт, объявленный запросом. Отсутствие заголовка, пустая строка и всё, что не разбирается в
 * целое, читаются одинаково — как `ASSUMED_CLIENT_CONTRACT`.
 */
export function readClientContract(raw: string | string[] | undefined): number {
  const value = Array.isArray(raw) ? raw[0] : raw;
  if (typeof value !== 'string') return ASSUMED_CLIENT_CONTRACT;
  const trimmed = value.trim();
  if (!/^-?\d+$/.test(trimmed)) return ASSUMED_CLIENT_CONTRACT;
  return Number(trimmed);
}

export interface ClientContractGateOptions {
  /**
   * Пол контракта. Умолчание — из окружения (`MIN_CLIENT_CONTRACT`); аргументом его задают тесты,
   * которым нужны обе фазы в одном прогоне, а перезапускать процесс ради переменной окружения
   * нечем.
   */
  minContract?: number;
}

const plugin: FastifyPluginCallback<ClientContractGateOptions> = (app, options, done) => {
  const minContract = options.minContract ?? config.clientGate.minContract;

  app.addHook('onRequest', async (req) => {
    if (!isGatedPath(req.url)) return;
    const contract = readClientContract(req.headers[CLIENT_CONTRACT_HEADER]);
    if (contract >= minContract) return;
    /*
     * Сборку называем только в отказе: писать её в каждую запись журнала значило бы платить
     * объёмом за то, что и так одинаково у всех, — а интересна она ровно тогда, когда кто-то не
     * прошёл, и надо понять, какая именно вкладка ещё жива.
     */
    req.log.warn(
      {
        clientContract: contract,
        minContract,
        clientBuild: req.headers[CLIENT_BUILD_HEADER] ?? null,
      },
      'Запрос отбит гейтом версии клиента',
    );
    throw new AppError(426, CLIENT_UPGRADE_REQUIRED, CLIENT_UPGRADE_MESSAGE);
  });

  done();
};

/**
 * Плагин-обёртка `fastify-plugin`: хук обязан стоять на корневом экземпляре, иначе он накрыл бы
 * только маршруты, зарегистрированные внутри этой же области.
 */
export const clientContractGate = fp(plugin, {
  name: 'client-contract-gate',
  fastify: '5.x',
});

export default clientContractGate;
