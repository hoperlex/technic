import type { FastifyInstance } from 'fastify';
import { writeAudit } from './audit';
import { ServiceAccessDenied } from './service-access-denied';

/**
 * Отказы по области и стороне в журнале — вторая половина Р6 (этап Э6 плана
 * `docs/office-equipment-executor-access-audit-plan.md`), пара к `service-access-denied.ts`.
 *
 * ПОЧЕМУ ХУК, А НЕ ВЫЗОВ ИЗ СТРАЖА. Стражи модуля синхронные (`assertSideAllowed`, `assertTransition`,
 * оси видимости), а `writeAudit` — поход в базу. Позови его страж — пришлось бы либо сделать
 * асинхронной каждую проверку модуля и каждого её вызывающего, либо запустить запись «в никуда»
 * необязательным промисом, который никто не ждёт: строка появлялась бы после ответа, а то и после
 * закрытия соединения. Отказ, помеченный причиной, снимает выбор — хук узнаёт его по дороге наружу
 * и пишет журнал сам, ничего не меняя в сигнатурах.
 *
 * ПОЧЕМУ `onError`, А НЕ `errorHandler`. Обработчик ошибок один на весь портал и по построению не
 * знает, чей отказ разбирает; хук же принадлежит плагину. `onError` в Fastify выполняется ПОСЛЕ
 * обработчика ошибок и только если ответ об ошибке и правда уходит клиенту, а ответ отправляется
 * после того, как хук завершится, — то есть строка журнала существует раньше, чем запрос получит
 * свой 403, и тесту не приходится ждать её отдельно. Менять ответ хук не вправе, и не меняет.
 *
 * ЗАПИСЬ НЕ ИМЕЕТ ПРАВА ПРЕВРАТИТЬ ЗАПРЕТ В 500. `writeAudit` глотает сбой вставки и уводит его
 * `error`-логом — ровно то поведение, которое здесь и нужно: журнал отказов ценен, но отказ ценнее,
 * и упавшая база не должна ни открывать данные, ни менять код ответа. Строгая запись
 * (`writeAuditTx`) сюда не годится и в перечень §22 не входит: транзакции у отказа нет, а ронять
 * запрет из-за журнала было бы обменом наоборот.
 *
 * ЧТО В ЖУРНАЛ НЕ ПОПАДАЕТ, И ЭТО РЕШЕНИЕ (порог из Р6):
 *
 *   • отказы стражей маршрута (`requirePermission` в `preHandler`) — там ещё неизвестно, к какой
 *     записи стучались, и «нет права» не то же самое, что «чужая заявка»: правом отбивает и обычную
 *     свою заявку, и такой поток забил бы журнал шумом ровно там, где ищут единичное;
 *   • отказы предикатов действий Р11 (`canStartServiceWork` и родня) — они отвечают состоянием и
 *     стороной СРАЗУ, и записать их причиной `'side'` значило бы врать в половине случаев: чаще
 *     всего там не «чужой ход», а «не тот статус»;
 *   • отказ области при ЗАВЕДЕНИИ заявки — заявки ещё нет, и `entityId` у такого отказа не бывает;
 *   • всё, что бросают соседние модули: хук объявлен внутри плагина заявок на обслуживание, и
 *     контекст маршрута соседа его не содержит (инкапсуляция Fastify). Это не соглашение, а
 *     свойство: доказано прогоном чужого отказа по области в
 *     `test/service-executor-access.db.test.ts`.
 */
export function registerServiceAccessDenialAudit(app: FastifyInstance): void {
  app.addHook('onError', async (req, _reply, error) => {
    // Заявка обязана быть известна: событие заводилось ради попыток прямого запроса к конкретной
    // чужой заявке, и отказ без адреса рассказывал бы не о ней.
    if (!(error instanceof ServiceAccessDenied) || error.entityId === undefined) return;
    const p = req.principal;
    await writeAudit({
      actorUserId: p?.id ?? null,
      action: 'serviceRequest.access_denied',
      entityType: 'serviceRequest',
      entityId: error.entityId,
      metadata: {
        /*
         * Шаблон маршрута вместе с методом — тот же ключ, которым ручки названы в манифесте
         * области (`service-access-manifest.ts`): по нему строка журнала читается вместе со
         * строкой ожидания. Без метода ключ был бы неоднозначен — за одним `/:id` стоят и чтение
         * карточки, и правка, и удаление, а это разные попытки.
         */
        route: `${req.method} ${req.routeOptions.url ?? req.url}`,
        reason: error.reason,
        // Роль и контрагент — снимок субъекта на момент попытки: обе меняются правкой учётки, и
        // спустя месяц по одному `actorUserId` уже не восстановить, кем человек тогда стучался.
        role: p?.role ?? null,
        counterpartyId: p?.counterpartyId ?? null,
      },
    });
  });
}
