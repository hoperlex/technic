import type { FastifyInstance } from 'fastify';
import type { Principal } from '../auth/principal';
import { writeAudit } from './audit';
import { ServiceAccessDenied } from './service-access-denied';

/**
 * ОДНА ЗАПИСЬ ОБ ОТКАЗЕ — ОБЩАЯ У ВСЕХ, КТО ОТКАЗ ЛОВИТ (Р6, критерий К6 плана
 * `docs/office-equipment-executor-access-audit-plan.md`).
 *
 * ПОЧЕМУ ФУНКЦИЯ, А НЕ ТЕЛО ХУКА. Ловцов у отказа двое, и второй появился не от хорошей жизни:
 * хук ниже разбирает отказ, дошедший до ответа, а пакетный исполнитель
 * (`services/service-request-bulk.ts`) — тот, что до ответа не доходит НИКОГДА, потому что
 * становится строкой отчёта. Пока состав записи жил телом хука, пачка была дырой в журнале: за
 * одно обращение перебиралось до пятидесяти чужих идентификаторов, и не оставалось ни строки —
 * ровно тот случай, ради которого журнал и заводили. Скопировать же состав во второе место значило
 * бы завести второй ответ на вопрос «что было в записи»: читаются они одним запросом по одному
 * `action`, и разъезд заметил бы разве что тот, кто спустя месяцы ищет в них перебор.
 *
 * ПОРОГ Р6 ЖИВЁТ ЗДЕСЬ ЖЕ, а не у каждого ловца: заявка обязана быть известна. Событие заводилось
 * ради попыток прямого запроса к КОНКРЕТНОЙ чужой заявке, и отказ без адреса (область при
 * заведении, где строки ещё нет) рассказывал бы не о ней.
 *
 * ЗАПИСЬ НЕ ИМЕЕТ ПРАВА ПРЕВРАТИТЬ ЗАПРЕТ В 500. `writeAudit` глотает сбой вставки и уводит его
 * `error`-логом — ровно то поведение, которое здесь и нужно: журнал отказов ценен, но отказ ценнее,
 * и упавшая база не должна ни открывать данные, ни менять код ответа. Строгая запись
 * (`writeAuditTx`) сюда не годится и в перечень §22 не входит: транзакции у отказа нет вовсе —
 * у хука её не было изначально, а в пачке она к этому времени УЖЕ ОТКАЧЕНА самим отказом, и
 * запись, отданная ей, откатилась бы вместе со строкой. Мимо транзакции — единственный способ
 * пережить откат, которым отказ строки и заканчивается.
 */
export async function writeServiceAccessDenial(params: {
  denied: ServiceAccessDenied;
  /** Субъект попытки. `null` бывает у хука: тип запроса допускает запрос без принципала. */
  actor: Pick<Principal, 'id' | 'role' | 'counterpartyId'> | null;
  /**
   * Адрес попытки — «метод + шаблон пути», тот же ключ, которым ручки названы в манифесте области
   * (`service-access-manifest.ts`): по нему строка журнала читается вместе со строкой ожидания.
   * Без метода ключ был бы неоднозначен — за одним `/:id` стоят и чтение карточки, и правка, и
   * удаление, а это разные попытки.
   */
  route: string;
  /**
   * Приписка пачки (Р8 плана массовых действий) — и её ОТСУТСТВИЕ у одиночной ручки значимо: `null`
   * читался бы одинаково и как «сделано поштучно», и как «запись написана до Р8», а пропущенный
   * ключ не читается никак, кроме как «пачки здесь не было». Та же форма, что у приписки к записям
   * об успешных строках, и тот же идентификатор — иначе «эти пятьдесят отказов сделаны одним
   * движением» перестало бы проверяться сложением.
   */
  bulkOperationId?: string;
}): Promise<void> {
  const { denied, actor, bulkOperationId } = params;
  if (denied.entityId === undefined) return;
  await writeAudit({
    actorUserId: actor?.id ?? null,
    action: 'serviceRequest.access_denied',
    entityType: 'serviceRequest',
    entityId: denied.entityId,
    metadata: {
      route: params.route,
      reason: denied.reason,
      // Роль и контрагент — снимок субъекта на момент попытки: обе меняются правкой учётки, и
      // спустя месяц по одному `actorUserId` уже не восстановить, кем человек тогда стучался.
      role: actor?.role ?? null,
      counterpartyId: actor?.counterpartyId ?? null,
      ...(bulkOperationId === undefined ? {} : { bulkOperationId }),
    },
  });
}

/**
 * Отказы по области и стороне в журнале — вторая половина Р6 (этап Э6 плана
 * `docs/office-equipment-executor-access-audit-plan.md`), пара к `service-access-denied.ts`.
 *
 * ПОЧЕМУ ХУК, А НЕ ВЫЗОВ ИЗ СТРАЖА. Стражи модуля синхронные (`assertSideAllowed`, `assertTransition`,
 * оси видимости), а `writeAudit` — поход в базу. Позови его страж — пришлось бы либо сделать
 * асинхронной каждую проверку модуля и каждого её вызывающего, либо запустить запись «в никуда»
 * необязательным промисом, который никто не ждёт: строка появлялась бы после ответа, а то и после
 * закрытия соединения. Отказ, помеченный причиной, снимает выбор — хук узнаёт его по дороге наружу
 * и пишет журнал сам, ничего не меняя в сигнатурах.
 *
 * ПОЧЕМУ `onError`, А НЕ `errorHandler`. Обработчик ошибок один на весь портал и по построению не
 * знает, чей отказ разбирает; хук же принадлежит плагину. `onError` в Fastify выполняется ПОСЛЕ
 * обработчика ошибок и только если ответ об ошибке и правда уходит клиенту, а ответ отправляется
 * после того, как хук завершится, — то есть строка журнала существует раньше, чем запрос получит
 * свой 403, и тесту не приходится ждать её отдельно. Менять ответ хук не вправе, и не меняет.
 *
 * ЧТО В ЖУРНАЛ НЕ ПОПАДАЕТ, И ЭТО РЕШЕНИЕ (порог из Р6):
 *
 *   • отказы стражей маршрута (`requirePermission` в `preHandler`) — там ещё неизвестно, к какой
 *     записи стучались, и «нет права» не то же самое, что «чужая заявка»: правом отбивает и обычную
 *     свою заявку, и такой поток забил бы журнал шумом ровно там, где ищут единичное;
 *   • отказы предикатов действий Р11 (`canStartServiceWork` и родня) — они отвечают состоянием и
 *     стороной СРАЗУ, и записать их причиной `'side'` значило бы врать в половине случаев: чаще
 *     всего там не «чужой ход», а «не тот статус»;
 *   • отказ области при ЗАВЕДЕНИИ заявки — заявки ещё нет, и `entityId` у такого отказа не бывает;
 *   • всё, что бросают соседние модули: хук объявлен внутри плагина заявок на обслуживание, и
 *     контекст маршрута соседа его не содержит (инкапсуляция Fastify). Это не соглашение, а
 *     свойство: доказано прогоном чужого отказа по области в
 *     `test/service-executor-access.db.test.ts`.
 *
 * ЧЕГО СЮДА НЕ ДОЛЕТАЕТ, ХОТЯ ЗАПИСАНО БЫТЬ ОБЯЗАНО: отказ строки ПАЧКИ. Он перехвачен исполнителем
 * и превращён в строку отчёта, наружу уходит `200` — то есть `onError` не срабатывает вовсе, и
 * дожидаться отказа здесь бессмысленно. Пишет его сама пачка, той же функцией выше и тем же
 * составом записи (`services/service-request-bulk.ts`, `runRow`).
 */
export function registerServiceAccessDenialAudit(app: FastifyInstance): void {
  app.addHook('onError', async (req, _reply, error) => {
    if (!(error instanceof ServiceAccessDenied)) return;
    await writeServiceAccessDenial({
      denied: error,
      actor: req.principal,
      route: `${req.method} ${req.routeOptions.url ?? req.url}`,
    });
  });
}
