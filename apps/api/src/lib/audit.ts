import { db } from '../db/client';
import { auditLog } from '../db/schema';
import { logger } from '../logger';

type Tx = Parameters<Parameters<typeof db.transaction>[0]>[0];

export interface AuditEntry {
  actorUserId?: string | null;
  action: string;
  entityType?: string;
  entityId?: string;
  metadata?: Record<string, unknown>;
}

/** Строка журнала из события: одна на оба способа записи — расходиться им негде. */
function auditValues(entry: AuditEntry): typeof auditLog.$inferInsert {
  return {
    actorUserId: entry.actorUserId ?? null,
    action: entry.action,
    entityType: entry.entityType,
    entityId: entry.entityId,
    metadata: entry.metadata ?? {},
  };
}

/** Аудит критичных событий (§22). Не роняет основную операцию при сбое записи. */
export async function writeAudit(entry: AuditEntry): Promise<void> {
  try {
    await db.insert(auditLog).values(auditValues(entry));
  } catch (e) {
    logger.error({ err: e, action: entry.action }, 'Не удалось записать audit-лог');
  }
}

/**
 * То же событие, но **соединением транзакции и без `catch`**: сбой записи обязан откатить саму
 * операцию (ADR 0106, решение 7 — «запись, `authVersion + 1` и журнал в той же транзакции»; план
 * «полномочия в окне учётки», §5.1).
 *
 * **Почему для доступа компромисс `writeAudit` неверен.** У остального портала он осознан: запись в
 * журнал не должна ронять выписанный путевой лист — событие ценно, но операция ценнее. У доступа
 * стороны меняются местами. Доступ, изменённый без события, — это ровно то состояние, ради которого
 * реестр выдач и заведён: «сотрудник уволился, а полномочие осталось» разбирают вопросом «кто и
 * когда это выдал», и ответить на него можно только журналом. Молчаливо потерянная запись делает
 * реестр неполным не где придётся, а именно в редких случаях — то есть там, где его и читают. Отказ
 * же виден сразу: администратор повторит правку, и доступ останется прежним, а не изменится
 * втихую.
 *
 * Переводятся на строгую запись **только перечисленные области**, и перечень закрытый:
 *
 * 1. **события доступа** — `grant.assign`, `grant.revoke`, `user.create`, `user.update`
 *    (`routes/users.ts`, `routes/user-grants.ts`), ADR 0106, решение 7;
 * 2. **мутации акта обслуживания** — заведение, правка, аннулирование и удаление
 *    (`services/vehicle-maintenance.ts`), ADR 0134, решение 11. Причина приходит от склада: с
 *    выпуском автозапчастей акт стал **основанием списания** — его строки двигают остаток, а дата,
 *    номер и сканы правятся свободно после движения. Журнал склада неизменяем и ссылается на акт;
 *    аудит акта — единственное, чем объясняется расхождение «в журнале списано 2, а в акте сегодня
 *    стоит 1». Потерянная запись делает это объяснение неполным ровно в редком случае, ради
 *    которого журнал и читают, а запись, пережившая откат, рассказывает о правке, которой не было.
 *
 * 3. **сверка листов ЭСМ-2** — `waybill.esm2_sync` (`services/waybill-esm2.ts`,
 *    `applyEsm2SyncPlanAndAudit`), план периодов назначения §7. Причина та же, что у акта: событие
 *    здесь — **единственный** носитель графа замен «какой номер чем заменён». Физическая связь
 *    (`corrects_waybill_id`) хранит одно ребро из многих, а у обычной сегодняшней смены машиниста
 *    строки журнала коррекций нет вовсе, и связи не хранится нигде больше. Потерянная запись
 *    оставила бы сгоревшие бланки строгой отчётности без объяснения — поэтому не записалось
 *    событие, откатывается и выпуск.
 *
 * 4. **набор площадок отдела** — `department.create` и `department.update`
 *    (`routes/departments.ts`, `services/directory-transfer/defs/org.ts`), ADR 0144, решение 8.
 *    Это расширение перечня самое прямое из возможных: перечень заведён ровно ради изменений
 *    доступа (ADR 0106, решение 7), а набор площадок отдела и **есть** область доступа — в её
 *    пределах сотрудники отдела ведут вывоз мусора, и меняется она одной правкой сразу всему
 *    отделу. Разница набора нигде больше не хранится: карточка отдела показывает только «сейчас»,
 *    а вопрос «кто и когда снял отделу эту площадку» задают спустя месяцы. Отказ записи виден
 *    сразу — администратор повторит правку, — а событие, пережившее откат, рассказывало бы о
 *    смене доступа, которой не было. Событие пишется в той же транзакции, что и `authVersion + 1`
 *    с отзывом сессий, то есть ровно тем же приёмом, что и события пункта 1.
 *
 * 5. **предметные события механизации** — `mech_request.deal`, `.issue`, `.issue_revoke`,
 *    `.extend`, `.complete` и `mech_request.purge` (`routes/mech-requests.ts` и сервисы модуля),
 *    план `docs/mechanization-module-plan.md`, Р21. Перечень проверен тем же вопросом, что акт и
 *    сверка: **является ли событие единственным носителем факта**. У пяти предметных является —
 *    строка заявки помнит только «сейчас»: прежняя ставка исправленной договорённости, прежний
 *    срок продлённой аренды, причина снятия отметки о выдаче и числа, перезаписанные повторным
 *    завершением, не хранятся больше нигде. Нагляднее всего снятие отметки: после него строка
 *    снова выглядит невыданной — что выдача была и почему её отменили, помнит одно событие.
 *    У `purge` причина самая сильная из перечня: после него от заявки не остаётся ничего, кроме
 *    строки журнала со снимком, и потерянная запись означает бесследно исчезнувший документ
 *    вместе с деньгами, которые по нему считали. Остальные события модуля (`create`, `update`,
 *    `status`, `soft_delete`, `restore`, `hard_delete`) идут обычным `writeAudit`: расчётного
 *    факта они не несут, и ронять из-за журнала правку комментария не за что.
 *
 * 6. **мутации чека на автозапчасти** — заведение, правка, пометка на удаление, её снятие и
 *    удаление (`services/auto-part-receipts.ts`), план `docs/auto-part-receipts-plan.md`, Р19.
 *    Проверено тем же вопросом, что и остальные: **является ли событие единственным носителем
 *    факта**. У удаления является буквально — после него от денежного документа не остаётся
 *    ничего, и метаданные несут его реквизиты (дата, продавец, номер, сумма); потерянная молча
 *    запись означала бы бесследно исчезнувшие деньги. У правки — потому что чек правят целиком:
 *    прежние дата, продавец, номер и итог не хранятся больше нигде. У пометки и её снятия — потому
 *    что это разговор двух людей о судьбе документа («предлагаю удалить, вот почему» — «удалил»
 *    либо «отказал»): в самой записи остаётся только последнее состояние, а причина снятой
 *    пометки стирается парой `CHECK`. Заведение идёт строгим заодно со всеми: у пяти мутаций
 *    одного документа не должно быть двух разных правил записи в журнал.
 *
 * 7. **пакетное подтверждение талонов вывоза кнопкой из списка** (`waste_request.ticket_auto_confirm`,
 *    `routes/waste-tickets.ts`), ADR 0155, Р23. Тот же вопрос, тот же ответ: событие — единственный
 *    носитель факта. Колонки «чем подтверждено» у талона нет намеренно (Р3), и по строкам
 *    `waste_tickets` кнопка неотличима от разбора в карточке: и там и там стоит `confirmed_by`.
 *    Потерянная запись означала бы бумагу, принятую не глядя и молча. Поштучное подтверждение и
 *    остальные девять мутаций разбора в перечень НЕ входят: там журнал — вторая копия того, что и
 *    так видно в строке талона.
 *
 * 8. **итог планирования письма модуля «Орг.техника»** — `serviceRequest.mailPlanned`
 *    (`services/service-request-mail.ts`) и `officeEquipmentCandidate.mailPlanned`
 *    (`services/office-equipment-candidate-mail.ts`, план кандидатов §10), план расширения почты
 *    §5.10. Два действия в одном пункте, а не два пункта: факт у них один — «письмо по событию
 *    модуля запланировано вот с таким исходом», — и разнеси мы их, второй пункт слово в слово
 *    повторял бы первый, а третье письмо модуля завело бы третий такой же. Проверено тем же вопросом:
 *    **является ли событие единственным носителем факта**. У исхода `no_recipients` — является
 *    буквально: строк `mail_messages` при нём не возникает вовсе, и «письма не было» не остаётся
 *    больше нигде, кроме этой записи. Разбирают её тогда же, когда и всё в этом перечне: месяцем
 *    позже, на вопрос «почему подрядчик не приехал». Запись идёт той же транзакцией, что и само
 *    событие заявки, — иначе она пережила бы откат и рассказывала бы о письме, которого не
 *    планировалось. Цена принята осознанно: отказ вставки журнала откатит бизнес-операцию, ровно
 *    как отказ вставки самой очереди, который этот путь уже принимает.
 *
 * 9. **решения по сообщению об отсутствующей технике** — `officeEquipmentCandidate.confirm`,
 *    `.merge`, `.reject`, парная им `officeEquipment.create` и след решения в истории связанной
 *    заявки (`serviceRequest.candidate_confirm`, `.candidate_merge`, `.candidate_reject`)
 *    (`routes/office-equipment-candidates.ts`), план `docs/office-equipment-candidate-plan.md`, §11.
 *    Проверено тем же вопросом, что и остальные: **является ли событие единственным носителем
 *    факта**. Решение заводит запись в ПАРКЕ и связывает с ней исходную заявку — то есть отвечает на
 *    вопрос «откуда взялась эта карточка», которого не задают, пока всё в порядке, и задают именно
 *    тогда, когда в справочнике нашлись два одинаковых аппарата. Строка `officeEquipment.create`
 *    идёт строгой не по своей природе — у первой двери справочника она обычная и такой остаётся, —
 *    а по РОДСТВУ с решением: карточка, появившаяся без записи о том, кто и по какому сообщению её
 *    завёл, хуже, чем незаведённая карточка, и обе строки обязаны быть атомарны решению. Пара
 *    колонок `decided_by/at` этого не заменяет: она отвечает «кто решил», но не «что при этом
 *    появилось в парке». Правка реквизитов до решения (`officeEquipmentCandidate.update`) и само
 *    заведение сообщения (`.create`) в перечень НЕ входят намеренно: их след есть и в строке
 *    кандидата, и ронять исправление опечатки сбоем журнала не за что.
 *
 *    Третья строка — `serviceRequest.candidate_*` — попадает сюда по тому же родству и отвечает на
 *    свой вопрос, СОСЕДНИЙ первым двум: не «откуда карточка», а «почему у моей заявки вдруг
 *    появился предмет» и «почему он так и не появился». Она единственный носитель этого факта в
 *    истории заявки: лента читает журнал по паре `entity_type = 'serviceRequest'`, а решение
 *    записано на кандидата, и заявка о нём не узнала бы ничего. Обе стороны сбоя одинаково плохи —
 *    строка, пережившая откат, рассказывала бы о подтверждении, которого нет, а потерянная молча
 *    оставила бы предмет заявки появившимся ниоткуда, — и обе снимаются одной транзакцией.
 *
 * Ручная корректировка остатка автозапчасти в перечень не входила, и это было решение, а не
 * недосмотр: там аудит был второй, более бедной копией события — само движение лежит неизменяемой
 * строкой `auto_part_stock_entries` с автором, причиной и обоими концами. Спорить об этом больше
 * не о чем: склад заморожен, ручки сняты (план `docs/auto-part-receipts-plan.md`, Р2), и писать в
 * журнал остатка некому.
 *
 * Перевод всего портального журнала — своя работа со своими рисками, и делать её попутно нельзя
 * (§2 «Граница»). Молча расширять перечень тоже нельзя — на то он и перечислен.
 */
export async function writeAuditTx(tx: Tx, entry: AuditEntry): Promise<void> {
  await tx.insert(auditLog).values(auditValues(entry));
}
