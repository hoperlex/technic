import { db } from '../db/client';
import { auditLog } from '../db/schema';
import { logger } from '../logger';

type Tx = Parameters<Parameters<typeof db.transaction>[0]>[0];

export interface AuditEntry {
  actorUserId?: string | null;
  action: string;
  entityType?: string;
  entityId?: string;
  metadata?: Record<string, unknown>;
}

/** Строка журнала из события: одна на оба способа записи — расходиться им негде. */
function auditValues(entry: AuditEntry): typeof auditLog.$inferInsert {
  return {
    actorUserId: entry.actorUserId ?? null,
    action: entry.action,
    entityType: entry.entityType,
    entityId: entry.entityId,
    metadata: entry.metadata ?? {},
  };
}

/** Аудит критичных событий (§22). Не роняет основную операцию при сбое записи. */
export async function writeAudit(entry: AuditEntry): Promise<void> {
  try {
    await db.insert(auditLog).values(auditValues(entry));
  } catch (e) {
    logger.error({ err: e, action: entry.action }, 'Не удалось записать audit-лог');
  }
}

/**
 * То же событие, но **соединением транзакции и без `catch`**: сбой записи обязан откатить саму
 * операцию (ADR 0106, решение 7 — «запись, `authVersion + 1` и журнал в той же транзакции»; план
 * «полномочия в окне учётки», §5.1).
 *
 * **Почему для доступа компромисс `writeAudit` неверен.** У остального портала он осознан: запись в
 * журнал не должна ронять выписанный путевой лист — событие ценно, но операция ценнее. У доступа
 * стороны меняются местами. Доступ, изменённый без события, — это ровно то состояние, ради которого
 * реестр выдач и заведён: «сотрудник уволился, а полномочие осталось» разбирают вопросом «кто и
 * когда это выдал», и ответить на него можно только журналом. Молчаливо потерянная запись делает
 * реестр неполным не где придётся, а именно в редких случаях — то есть там, где его и читают. Отказ
 * же виден сразу: администратор повторит правку, и доступ останется прежним, а не изменится
 * втихую.
 *
 * Переводятся на строгую запись **только перечисленные области**, и перечень закрытый:
 *
 * 1. **события доступа** — `grant.assign`, `grant.revoke`, `user.create`, `user.update`
 *    (`routes/users.ts`, `routes/user-grants.ts`), ADR 0106, решение 7;
 * 2. **мутации акта обслуживания** — заведение, правка, аннулирование и удаление
 *    (`services/vehicle-maintenance.ts`), ADR 0134, решение 11. Причина приходит от склада: с
 *    выпуском автозапчастей акт стал **основанием списания** — его строки двигают остаток, а дата,
 *    номер и сканы правятся свободно после движения. Журнал склада неизменяем и ссылается на акт;
 *    аудит акта — единственное, чем объясняется расхождение «в журнале списано 2, а в акте сегодня
 *    стоит 1». Потерянная запись делает это объяснение неполным ровно в редком случае, ради
 *    которого журнал и читают, а запись, пережившая откат, рассказывает о правке, которой не было.
 *
 * Ручная корректировка остатка автозапчасти (`routes/auto-parts.ts`) в перечень НЕ входит, и это
 * решение, а не недосмотр: там аудит — вторая, более бедная копия события, потому что само
 * движение уже лежит неизменяемой строкой `auto_part_stock_entries` с автором, причиной и обоими
 * концами, а живёт она вместе с транзакцией по построению (триггеры цепочки и покрытия). Ронять
 * из-за копии правку остатка не за что; зовётся она после успешного коммита, поэтому «аудит о
 * правке, которой не было» там невозможен.
 *
 * Перевод всего портального журнала — своя работа со своими рисками, и делать её попутно нельзя
 * (§2 «Граница»). Молча расширять перечень тоже нельзя — на то он и перечислен.
 */
export async function writeAuditTx(tx: Tx, entry: AuditEntry): Promise<void> {
  await tx.insert(auditLog).values(auditValues(entry));
}
