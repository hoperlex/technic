/**
 * Значения из СЫРОГО SQL (`db.execute`) — туда, где их ждут типизированными.
 *
 * ЗАЧЕМ ЭТО СУЩЕСТВУЕТ. `db.execute` возвращает то, что дал драйвер, БЕЗ разбора схемы: у
 * `timestamptz` это **строка**, а не `Date`, — в отличие от обычного `db.select(...)`, где колонку
 * приводит сам drizzle, и в отличие от голого `pg.query`, где её приводит парсер типов `pg`.
 * Проверено на PostgreSQL 17 замером через оба пути.
 *
 * Обобщённый тип у `db.execute<...>` при этом ничего не проверяет: он обещание вызывающего, а не
 * факт. Объяви он `Date | null` — компилятор промолчит, а `.toISOString()` упадёт пятисоткой из
 * ручки. Так и случилось: баннер состояния распознавания отдавал 500 ровно в тот момент, когда он
 * нужнее всего — при терминальном отказе прокси.
 */

/**
 * Момент из сырого ответа в ISO-строку. Принимает и строку, и `Date`: оба представления законны и
 * зависят от того, каким путём пришёл ответ. Непонятное значение — `null`, а не «Invalid Date» в
 * ответе ручки.
 */
export function isoOf(value: unknown): string | null {
  if (value === null || value === undefined) return null;
  const date = value instanceof Date ? value : new Date(String(value));
  return Number.isNaN(date.getTime()) ? null : date.toISOString();
}
