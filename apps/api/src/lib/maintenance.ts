import fp from 'fastify-plugin';
import type { FastifyPluginCallback } from 'fastify';
import { config } from '../config';
import { AppError } from './errors';

/**
 * Гейт режима технических работ (план `docs/maintenance-mode-plan.md`).
 *
 * **Зачем.** Окно cutover-миграции сегодня выглядит так: контейнеры `api` и `worker` остановлены,
 * статика веба продолжает раздаваться, и человек в открытой вкладке видит форму входа и сетевую
 * ошибку на каждом действии. Портал закрыт, но выглядит сломанным, а не закрытым. Гейт даёт первое
 * из недостающего — внятный ответ «идут работы» **до** остановки контейнеров, пока `api` ещё жив.
 *
 * **Почему переменная окружения, а не строка в базе** (Р1). В окне базу и мигрируют: источник
 * истины о закрытости портала не должен лежать в том, что закрывают. Состояние читается один раз
 * при регистрации плагина — переключает режим пересоздание контейнера, а не запрос, и «сбросить
 * кэш состояния» здесь нечего.
 *
 * **Второй канал — файл, а не этот гейт.** В главном сценарии `api` остановлен, и гейт молчит
 * ровно тогда, когда нужнее всего; заглушку в это время держит `/maintenance.json`, раздаваемый
 * вебом (Р6). Гейт отвечает за другое: за немедленный сигнал живой вкладке, чтобы заглушка
 * появилась, не дожидаясь очередного опроса файла.
 *
 * **Статус отказа — 503 Service Unavailable.** Он единственный означает «сервис временно не
 * обслуживает, приходите позже», и он же единственный, к которому в HTTP полагается `Retry-After`.
 * 403 увёл бы разговор к правам (а сквозь режим не проходит никто, включая администратора, — Р2),
 * 423 говорит о запертом ресурсе, а не о сервисе, и не понимается ничем по дороге.
 *
 * **Сквозь режим не проходит никто** (Р2): ни роль, ни именное полномочие. Выключатель живёт
 * снаружи портала — запереть себя внутри невозможно, — а данные после миграции проверяют доступом
 * `DATABASE_MAINTENANCE_URL`, который у оператора окна и так есть.
 */

/**
 * Код отказа. Портал разбирает пару «503 + код», а не код в одиночку: тем же статусом отвечает
 * `err.unavailable` с кодом `service_unavailable` — там это «почта не настроена», разговор другой.
 */
export const MAINTENANCE_MODE_CODE = 'maintenance_mode';

/**
 * Тело отказа самодостаточно. Заглушку рисует только новая сборка портала (§3); сборка, собранная
 * до этого выпуска, обработчика 503 `maintenance_mode` не имеет вовсе и покажет обычное окно
 * ошибки с этим текстом — прочитает его человек, а не код. Поэтому здесь сказано, что происходит и
 * что делать, а не «сервис недоступен».
 */
export const MAINTENANCE_MESSAGE =
  'Портал закрыт: идут технические работы. Вернитесь позже и обновите страницу (Ctrl+R, на Mac ⌘+R) — ' +
  'входить заново не потребуется.';

/**
 * `Retry-After` при неизвестном или уже прошедшем сроке, секунды.
 *
 * Две минуты — не «примерно столько идут работы», а темп повторов: заголовок обязан быть целым
 * числом секунд, и ноль либо отрицательное значение вкладка прочитала бы как «повторяйте прямо
 * сейчас», то есть заставила бы её молотить по закрытому порталу.
 */
export const MAINTENANCE_RETRY_AFTER_FALLBACK_SECONDS = 120;

/** Префикс браузерного API портала. Гейту подлежит только он — см. `isGatedPath`. */
const API_PREFIX = '/api/v1';

/**
 * Ручки, выведенные из-под гейта НАСОВСЕМ (Р4).
 *
 * Перечень свой, а не общий с гейтом версии клиента (`client-contract.ts`), хотя сегодня они
 * совпадают: причины у освобождений разные, и один перечень на два гейта означал бы, что
 * освобождение, выданное по причине одного, молча достаётся другому.
 *
 * - **`/auth/refresh`** — `apps/web/src/shared/api/session.ts` читает ВСЯКИЙ неуспешный ответ
 *   обновления как «сессия кончилась» и объявляет её законченной необратимо. Отбей режим
 *   обновление — он выбросил бы на форму входа всех, чья вкладка попала в окно, то есть сделал бы
 *   ровно то, чего избегает обнуление токенов эпохой: refresh-сессии живут, гасится только access
 *   (Р3, Р4). Освобождение и даёт нужный исход — вкладка тихо продлевает сессию всё окно и после
 *   снятия режима продолжает работу без пароля и без капчи, уже с токеном новой эпохи.
 * - **`/auth/logout`** — `apps/web/src/api/auth.ts` чистит сессию вкладки ТОЛЬКО после успешного
 *   ответа. Отказ оставил бы вкладку считающей себя вошедшей, а серверную сессию — неотозванной:
 *   режим не должен уметь запереть человека внутри сессии, из которой тот выходит.
 *
 * **Вход (`/auth/login`) и `/auth/me` в перечень НЕ входят**: портал закрыт целиком, и пускать в
 * него по паролю значило бы отменять Р2. Отказ на входе читается ровно как отказ, а `/auth/me` под
 * гейтом обязателен ещё и потому, что заглушка на портале стоит выше `AuthProvider` (§4.5).
 *
 * **Плата за освобождение — обязательство**: ответы этих двух ручек обязаны оставаться
 * совместимыми со старой сборкой — гейт их больше не прикрывает.
 */
const EXEMPT_PATHS: ReadonlySet<string> = new Set([
  `${API_PREFIX}/auth/refresh`,
  `${API_PREFIX}/auth/logout`,
]);

/** Путь запроса без строки запроса и без хвостового слэша. */
function pathOf(url: string): string {
  const cut = url.indexOf('?');
  const path = cut === -1 ? url : url.slice(0, cut);
  return path.length > 1 && path.endsWith('/') ? path.slice(0, -1) : path;
}

/**
 * Подлежит ли путь гейту.
 *
 * Гейт закрывает только браузерное API (`/api/v1/**`), и это не осторожность, а условие
 * работоспособности окна:
 *
 * - `/health/*` и `/metrics` дёргает healthcheck контейнера (`deploy/docker-compose.yml`). Под
 *   гейтом он прочитал бы 503 как «сервис болен», и docker принялся бы перезапускать здоровый
 *   контейнер — посреди окна, ради которого всё и затевалось;
 * - `/internal/*` ходит worker с общим секретом (ADR 0075, ADR 0133). Режим закрывает браузерный
 *   контур, а фоновые задачи гасятся своим порядком — остановкой контейнера в `--cutover` (Р7);
 *   отбивать их здесь значило бы заводить второй выключатель того же самого.
 */
export function isGatedPath(url: string): boolean {
  const path = pathOf(url);
  if (path !== API_PREFIX && !path.startsWith(`${API_PREFIX}/`)) return false;
  return !EXEMPT_PATHS.has(path);
}

/** Состояние окна: то же, что в `config.maintenance`, но передаваемое аргументом (см. опции). */
export interface MaintenanceState {
  enabled: boolean;
  /** Публичный текст объявления; `''` — причина не названа. */
  reason: string;
  /** Ожидаемое окончание в ISO 8601; `''` — срок не назван. */
  until: string;
}

/** Разбор отказа машиной: то же, что видит человек, но порознь и без склейки в предложение. */
export interface MaintenanceDetails {
  reason: string | null;
  until: string | null;
}

/**
 * `Retry-After` в **delta-seconds**, целым числом.
 *
 * HTTP допускает две записи — целое число секунд и HTTP-date; ISO-строка не годится ни в одну из
 * них, и клиент, встретив её, просто не разберёт заголовок. Отсюда и подпись: наружу уходит
 * число, а ISO остаётся в теле, где его читает портал.
 *
 * Округление вверх, а не вниз: округлённый вниз остаток зовёт вкладку вернуться за долю секунды до
 * срока — то есть ровно в момент, когда режим ещё стоит.
 */
export function retryAfterSeconds(until: string, now: Date = new Date()): number {
  if (!until) return MAINTENANCE_RETRY_AFTER_FALLBACK_SECONDS;
  const remainingMs = Date.parse(until) - now.getTime();
  // Срок прошёл, а режим не снят — значит работы затянулись: честнее позвать через две минуты,
  // чем звать немедленно.
  if (!Number.isFinite(remainingMs) || remainingMs <= 0) {
    return MAINTENANCE_RETRY_AFTER_FALLBACK_SECONDS;
  }
  return Math.ceil(remainingMs / 1000);
}

/**
 * Текст отказа для человека. Причина оператора приписывается к постоянному тексту, потому что
 * старая сборка увидит только `message`: `details` она не разбирает вовсе, и без приписки окно
 * «идут работы» осталось бы для неё безымянным.
 */
export function maintenanceMessage(reason: string): string {
  return reason ? `${MAINTENANCE_MESSAGE} Причина: ${reason}` : MAINTENANCE_MESSAGE;
}

export interface MaintenanceGateOptions {
  /**
   * Состояние окна. Умолчание — из окружения (`MAINTENANCE_MODE` и соседи); аргументом его задают
   * тесты, которым нужны оба состояния в одном прогоне, а перезапускать процесс ради переменной
   * окружения нечем.
   */
  maintenance?: MaintenanceState;
}

const plugin: FastifyPluginCallback<MaintenanceGateOptions> = (app, options, done) => {
  const state = options.maintenance ?? config.maintenance;

  app.addHook('onRequest', async (req, reply) => {
    if (!state.enabled) return;
    if (!isGatedPath(req.url)) return;
    /*
     * Заголовок ставится до броска: тело отказа собирает общий обработчик ошибок, а заголовки,
     * выставленные на этом ответе, он сохраняет — своего места под них у `AppError` нет.
     */
    reply.header('Retry-After', String(retryAfterSeconds(state.until)));
    /*
     * Отказ не пишется в журнал ни строкой. В окне под гейт попадает ВЕСЬ трафик портала — каждая
     * вкладка с её фоновыми обновлениями списков, — и предупреждение на запрос превратило бы
     * журнал окна в поток одинаковых записей, в котором тонет всё остальное. Что режим включён,
     * видно из окружения контейнера, а не из журнала (Р1: журнала переходов у режима нет вовсе).
     */
    throw new AppError(503, MAINTENANCE_MODE_CODE, maintenanceMessage(state.reason), undefined, {
      // Пустое значение отдаётся как `null`, а не выбрасывается из тела: обе позиции портал читает
      // всегда, и отличать «ключа нет» от «значение пустое» ему пришлось бы лишним условием.
      reason: state.reason || null,
      until: state.until || null,
    } satisfies MaintenanceDetails);
  });

  done();
};

/**
 * Плагин-обёртка `fastify-plugin`: хук обязан стоять на корневом экземпляре, иначе он накрыл бы
 * только маршруты, зарегистрированные внутри этой же области.
 */
export const maintenanceGate = fp(plugin, {
  name: 'maintenance-gate',
  fastify: '5.x',
});

export default maintenanceGate;
