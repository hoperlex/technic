import { AppError } from './errors';

/**
 * Чем именно отбило запрос. Две причины, а не одна на всё: «заявка не ваша» и «ход не ваш» —
 * разные разговоры с человеком и разные поводы для разбора. Первая означает попытку дотянуться до
 * чужой записи по известному id, вторая — что записи субъект достиг законно, а вот шаг в ней
 * принадлежит другой стороне.
 */
export type ServiceAccessReason = 'scope' | 'side';

/**
 * Отказ доменного стража заявок на обслуживание — тот же 403, но с причиной и адресом заявки
 * (план `docs/office-equipment-executor-access-audit-plan.md`, Р6, этап Э6).
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ТИП, ЕСЛИ `err.forbidden` УЖЕ ЕСТЬ. Отказ по области или стороне не оставлял следа
 * нигде: `errorHandler` для статусов < 500 не пишет ничего, а `writeAudit` зовётся только на успехе
 * (находка Н6). Попытка подрядчика открыть чужую заявку по прямой ссылке была невидима — при том,
 * что в модуле вывоза мусора просмотр мимо области пишется событием уже сегодня
 * (`waste_request.ticket_audit_view`). Записать событие из самого стража нельзя: стражи синхронные,
 * а запись в журнал — поход в базу; зато отказ, помеченный причиной, узнаётся хуком по дороге
 * наружу — и журнал пишет уже он (`service-access-audit.ts`).
 *
 * НАРУЖУ НЕ МЕНЯЕТСЯ НИ БАЙТА. Наследник `AppError` с тем же статусом и тем же кодом: `errorHandler`
 * разбирает его той же веткой `instanceof AppError`, ни `fields`, ни `details` у него нет — как не
 * было и у `err.forbidden`, — и тело ответа выходит прежним. Это условие, а не пожелание: тексты
 * отказов сверяются дословно отрицательными тестами модуля, и наблюдаемость не имеет права стоить
 * ни одного изменённого сообщения.
 *
 * ПОЧЕМУ ЭТО НЕ В `errors.ts`. Там живут отказы всего портала, одинаковые для каждого модуля, а
 * причина `'scope' | 'side'` — понятие этого: у соседей нет ни третьей оси видимости, ни стороны
 * исполнителя. Пара к `service-access-manifest.ts` и по той же причине, что у него.
 *
 * ПОЧЕМУ ЗДЕСЬ НЕТ САМОЙ ЗАПИСИ. Этот модуль читает `lib/access.ts`, чьи предикаты проверяются
 * юнит-тестами без базы; притащи он сюда `writeAudit`, каждый такой тест поднимал бы пул соединений
 * (та же причина, по которой третья ось видимости написана сырым `sql`). Запись поэтому лежит
 * соседним файлом, который зовут только маршруты.
 */
export class ServiceAccessDenied extends AppError {
  constructor(
    /** Чем отбило: областью заявки (`scope`) или стороной хода (`side`). */
    public readonly reason: ServiceAccessReason,
    message: string,
    /**
     * Заявка, о которой судил страж. `undefined` означает «строки ещё нет»: так отвечает область при
     * ЗАВЕДЕНИИ заявки, где спрашивается предмет будущей записи. Такой отказ в журнал не идёт —
     * событие заводится ради попыток прямого запроса к конкретной чужой заявке, а «вам не положено
     * заводить заявку на эту технику» рассказывает не о ней.
     */
    public readonly entityId?: string,
  ) {
    super(403, 'forbidden', message);
    this.name = 'ServiceAccessDenied';
  }
}

/**
 * Отказы стражей модуля. Фабрикой, а не `new` по месту: та же роль, что у `err` в `errors.ts`, —
 * причина читается на месте броска одним словом, а не позиционным аргументом конструктора.
 */
export const serviceDenied = {
  /** Заявка вне области субъекта: чужая площадка, чужой отдел, чужой контрагент. */
  scope: (message: string, entityId?: string): ServiceAccessDenied =>
    new ServiceAccessDenied('scope', message, entityId),
  /** Заявка доступна, а ход в ней — шаг другой стороны. */
  side: (message: string, entityId?: string): ServiceAccessDenied =>
    new ServiceAccessDenied('side', message, entityId),
};
