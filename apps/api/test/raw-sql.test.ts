import { describe, expect, it } from 'vitest';
import { isoOf } from '../src/lib/raw-sql';

/**
 * Значения из сырого SQL (`src/lib/raw-sql.ts`).
 *
 * Файл существует из-за настоящего дефекта, а не ради полноты: `db.execute` возвращает
 * `timestamptz` СТРОКОЙ (в отличие от `db.select` и от голого `pg.query`), а обобщённый тип
 * запроса это лишь обещание вызывающего. Объявленный `Date` компилятор принимал молча, и
 * `.toISOString()` падал пятисоткой в ручке состояния распознавания — ровно при терминальном
 * отказе прокси, то есть когда баннер нужнее всего.
 */
describe('момент из сырого ответа', () => {
  it('принимает оба представления: и строку драйвера, и Date', () => {
    expect(isoOf('2026-09-21T10:15:00.000Z')).toBe('2026-09-21T10:15:00.000Z');
    expect(isoOf(new Date('2026-09-21T10:15:00.000Z'))).toBe('2026-09-21T10:15:00.000Z');
    // Так приходит timestamptz из `db.execute` на сервере с поясом: смещение учитывается.
    expect(isoOf('2026-09-21 15:15:00+05')).toBe('2026-09-21T10:15:00.000Z');
  });

  it('пусто и мусор дают null, а не «Invalid Date» в ответе ручки', () => {
    expect(isoOf(null)).toBeNull();
    expect(isoOf(undefined)).toBeNull();
    expect(isoOf('не дата')).toBeNull();
  });
});
