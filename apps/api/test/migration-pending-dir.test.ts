import { readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { listMigrationFiles, migrationsDir } from '../src/db/migration-journal';

/**
 * `drizzle/pending/` — подготовленный, но не выкатываемый SQL: файл лежит рядом с миграциями, а
 * миграцией не является (план реструктуризации модели доступа §13.2, правило трёх релизов;
 * `apps/api/drizzle/pending/README.md`).
 *
 * **Что здесь охраняется — и почему это стоит теста.** Каталог миграций плоский, и всё, что в нём
 * лежит, мигратор катит ближайшим же деплоем. Правило трёх релизов запрещает ровно это: между
 * `prepare`, `migrate` и `cleanup` обязан пройти выкат, иначе снимок, взведённые назначения и
 * перевод учёток случаются одной транзакцией времени, и откат «через шаг» становится невозможен.
 * Держится невидимость подкаталога на одной строке `listMigrationFiles` — `filter(f =>
 * f.endsWith('.sql'))`, — и цена её потери молчалива: подготовленный `UPDATE` учёток уедет вместе
 * с шагом, который обязан был выехать до него, и узнают об этом по пропавшему доступу.
 *
 * Ломается это тремя способами, и все три ловятся здесь:
 *   1. каталог переименуют во что-нибудь вроде `pending.sql` — и он попадёт под фильтр сам,
 *      а `readFileSync` каталога уронит накат;
 *   2. обход сделают рекурсивным (`readdirSync(dir, { recursive: true })`) — и подготовленные
 *      файлы станут миграциями без единой правки в них;
 *   3. подготовленный файл случайно положат в корень каталога, а не в подкаталог.
 *
 * Пути и имена берутся из самого модуля, а не переписываются сюда: тест обязан проверять то, что
 * читает мигратор, а не свою копию этого списка.
 */

const PENDING_DIR = 'pending';

describe('drizzle/pending: подготовленный SQL не является миграцией', () => {
  it('имя подкаталога не оканчивается на .sql — иначе он попал бы под фильтр как файл', () => {
    expect(PENDING_DIR.endsWith('.sql')).toBe(false);
  });

  it('подкаталог существует и лежит внутри каталога миграций', () => {
    expect(statSync(join(migrationsDir, PENDING_DIR)).isDirectory()).toBe(true);
  });

  it('ни один подготовленный файл не виден мигратору', () => {
    const prepared = readdirSync(join(migrationsDir, PENDING_DIR)).filter((f) =>
      f.endsWith('.sql'),
    );
    // Пустой подкаталог не сигнал: шаги переезжают в миграции и каталог законно пустеет. Сигнал —
    // подготовленный файл, попавший в список наката.
    const listed = listMigrationFiles();
    for (const file of prepared) {
      expect(listed).not.toContain(file);
      expect(listed).not.toContain(`${PENDING_DIR}/${file}`);
    }
  });

  it('в списке наката нет ни одного пути с разделителем — обход остаётся плоским', () => {
    // Рекурсивный `readdirSync` вернул бы `pending/stage8-...sql`; на этом и ловится третий способ
    // сломать невидимость, включая тот, где подкаталог назовут иначе.
    expect(listMigrationFiles().filter((f) => f.includes('/'))).toEqual([]);
  });

  it('каждая миграция в корне — файл с номером: подготовленному SQL там не место', () => {
    for (const name of listMigrationFiles()) {
      expect(name).toMatch(/^\d{4}_[a-z0-9_]+\.sql$/);
    }
  });
});
