import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { describe, expect, it } from 'vitest';
import { collectServiceAccessInventory } from '../scripts/service-access-inventory';

/**
 * Сторож инвентаря доступа в заявках на обслуживание оргтехники — этап Э0 плана
 * `docs/office-equipment-executor-access-audit-plan.md`.
 *
 * Инвентарь снимает скрипт (`scripts/service-access-inventory.ts`), но снятый факт живёт ровно до
 * следующей правки маршрутов: отчёт, который никто не запускает, устаревает молча. Тест держит из
 * него два утверждения — те, на которые опираются следующие этапы.
 *
 * Базы здесь нет и быть не должно: оба утверждения — про текст исходников, а не про данные.
 * Прогон должен оставаться дешёвым, иначе его выключат первым.
 */

const SRC = new URL('../src', import.meta.url).pathname;

/** Маршрутный файл модуля: правило «изменяющая ручка входит через `requireEditable`» — про него. */
const ROUTES = 'src/routes/service-requests.ts';

const MUTATING = ['POST', 'PUT', 'PATCH', 'DELETE'];

/**
 * Общий вход изменяющих ручек: живая заявка в области субъекта. Именно он держит область у всего,
 * что заявку двигает, — карточка получает строку по id, и без него ручка отдала бы её любому, кто
 * этот id знает.
 */
const ENTRY = 'requireEditable';

/**
 * Изменяющие ручки, которые входят иначе, — и почему это осознанно, а не пропуск.
 *
 * Список открыт, но каждая строка объясняет причину: следующий этап переводит модуль на общий
 * предикат области (Р2), и «почему тут не как у всех» обязано быть написано ДО правки, а не
 * восстанавливаться по памяти после.
 */
const OTHER_ENTRY = new Map<string, string>([
  [
    'POST /:id/messages',
    'чат живёт и у закрытой заявки: `requireEditable` отбил бы 404 архивной, а переписку по ней ' +
      'читают и после закрытия. Область спрошена парой `assertArchiveVisible` + `assertScope`, ' +
      'сторона — `canWriteChat` внутри `postChatMessage`, под `FOR UPDATE` (§2.1, эталон Н3)',
  ],
  [
    'POST /:id/messages/read',
    'отметка о прочтении — не ход по заявке: она правит закладку читателя, а не саму заявку, и ' +
      'разрешена там же, где чтение переписки. Вход тот же, что у чата: `assertArchiveVisible` + ' +
      '`assertScope`',
  ],
  [
    'POST /:id/restore',
    'возврат из архива работает ровно с той строкой, которую `requireEditable` отбивает как ' +
      'удалённую. Область спрошена `assertScope` — и до разбора состояния, чтобы живая заявка не ' +
      'отдавалась карточкой в обход `serviceRequests.read`',
  ],
  [
    'DELETE /:id/purge',
    'регистрируется общим помощником `services/directory-purge.ts` за весь портал, и области у ' +
      'него нет вовсе — §2.2 плана держит здесь пустую клетку осознанно (право `records.purge` — ' +
      'администраторское). Это не разрешение молчать: К1 §8 требует для строки отдельного ' +
      'доказательства барьера, и оно появится этапом Э1',
  ],
]);

/**
 * Места, где оси видимости заявки собираются руками, — критерий К2 §8.
 *
 * **Список пуст, и это и есть закрытый критерий.** Правило области было размножено (находка Н4):
 * канон в `lib/access.ts`, а собирали его из двух предикатов шесть мест, и две сборки вышли
 * неполными — карточка единицы оргтехники и её история держали одну ось, заказчика, а недостающую
 * подпирали внешним фактом «сервисной компании закрыт справочник». Этап Э3 перевёл на общий
 * `serviceRequestVisibilityWhere` сначала заявки, файлы и расходники, а последним шагом — эти двое.
 *
 * Константа остаётся не как память о прошлом, а как ЕДИНСТВЕННАЯ дверь: место, которому оси
 * действительно нужны врозь, заводится строкой здесь и объяснением в ревью, а не молча — копипастой
 * соседнего запроса, то есть ровно тем способом, которым Н4 и появилась. Пустой список означает
 * «двери никому не открывали», и снят он вызовами предикатов, а не словами плана.
 */
const MANUAL_AXES: string[] = [];

/**
 * Канон: единственное место, которому оси и положено складывать, — их же объявление. После Э3 пара
 * `serviceRequestVisibilityWhere` / `assertServiceRequestVisible` живёт здесь и ЗОВЁТ обе оси, а не
 * только объявляет их, поэтому одного `(?<!function\s)` для отсечения канона больше не хватает и он
 * назван файлом. Исключение точечное: любое другое место, собравшее оси само, тест по-прежнему
 * ловит — включая новый файл в `lib/`.
 */
const CANON = 'lib/access.ts';

/**
 * Предикаты осей. Обе оси приватны в каноне (Р2), но имена продолжают жить в его тексте, и по ним
 * ручная сборка узнаётся: `apps/api/src` — вся поверхность, где такой запрос вообще возможен (у
 * портала доступа к базе нет, worker про заявки на обслуживание не знает ни строкой, а вызовы в
 * `test/` — это проверки самих предикатов, а не запросы приложения).
 *
 * Имена перечислены поимённо, а не одним регулярным выражением, чтобы каждое проверялось отдельно:
 * переименуй одну ось — и склеенный шаблон продолжил бы находить вторую, то есть сторож наполовину
 * ослеп бы молча.
 */
const AXIS_NAMES = ['serviceRequestScopeWhere', 'serviceExecutorVisibilityWhere'];

/** Вызов оси, но не её объявление: `function` перед именем отсекается. */
function axisCall(name: string): RegExp {
  return new RegExp(String.raw`(?<!function\s)\b${name}\s*\(`);
}

function callsAxis(source: string): boolean {
  return AXIS_NAMES.some((name) => axisCall(name).test(source));
}

/** Комментарий — не запрос: объяснение «область здесь считается иначе» ссылается на те же имена. */
function code(text: string): string {
  return text.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
}

function sourceFiles(dir: string): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) out.push(...sourceFiles(full));
    else if (entry.endsWith('.ts')) out.push(full);
  }
  return out;
}

describe('инвентарь доступа заявок на обслуживание', () => {
  const routes = collectServiceAccessInventory().filter((row) => row.file === ROUTES);

  /**
   * Заведение заявки и статические пути вне правила: у первого ещё нет строки, к которой можно
   * спросить область (её решает разбор предмета), у вторых нет `:id` — они работают со списком, и
   * область им даёт `listWhere`, а не `requireEditable`.
   */
  const guarded = routes.filter(
    (row) => MUTATING.includes(row.method) && row.route.includes(':id'),
  );

  it('модуль вообще разобран: ручки найдены', () => {
    // Молчаливо пустой инвентарь — самый опасный исход: сторож зеленеет, не проверив ничего.
    expect(routes.length, 'разбор маршрутов не нашёл ни одной ручки').toBeGreaterThan(30);
    expect(guarded.length, 'изменяющих ручек с `:id` не нашлось').toBeGreaterThan(20);
  });

  it('каждая изменяющая ручка входит через requireEditable либо названа поимённо', () => {
    const offenders = guarded
      .filter((row) => !row.checks.includes(ENTRY))
      .map((row) => `${row.method} ${row.route}`)
      .filter((name) => !OTHER_ENTRY.has(name));

    expect(
      offenders,
      'изменяющая ручка обязана начинаться с `requireEditable` — живая заявка в области субъекта; ' +
        'иной вход заводится осознанно и с объяснением в OTHER_ENTRY',
    ).toEqual([]);
  });

  it('исключения не протухли: каждое существует и всё ещё исключение', () => {
    for (const [name, why] of OTHER_ENTRY) {
      const row = guarded.find((r) => `${r.method} ${r.route}` === name);
      expect(row, `${name}: такой ручки в модуле нет — список отстал от кода`).toBeDefined();
      expect(
        row!.checks.includes(ENTRY),
        `${name}: ручка уже входит через \`requireEditable\` — строку из списка пора убрать`,
      ).toBe(false);
      expect(why.length, `${name}: причина исключения не названа`).toBeGreaterThan(40);
    }
  });

  it('оси видимости заявки собираются руками только в названных местах (К2)', () => {
    const found = sourceFiles(SRC)
      .filter((file) => callsAxis(code(readFileSync(file, 'utf8'))))
      .map((file) => relative(SRC, file))
      .filter((file) => file !== CANON)
      .sort();

    expect(
      found,
      'запрос к `service_requests`, собирающий оси видимости мимо общего предиката, — это находка ' +
        'Н4: правило области размножается копипастой соседнего запроса и расходится молча. ' +
        'Новое место зовёт `serviceRequestVisibilityWhere`, а не складывает оси само',
    ).toEqual([...MANUAL_AXES].sort());
  });

  /**
   * Сторож самого сторожа: список сокращается правкой кода, а не правкой константы.
   *
   * У сторожа две работы, и вторая появилась ровно тогда, когда список опустел. Пока в `MANUAL_AXES`
   * есть строки, каждая обязана существовать: файл, уехавший на общий предикат, убирается отсюда
   * той же правкой, иначе исключение переживает свою причину. А пустой список делает проверку выше
   * уязвимой с другой стороны: она зеленеет и когда ручной сборки нигде нет, и когда её просто
   * НЕЧЕМ найти — переименуй ось, разбери канон на части, и `found` останется пустым, а сторож
   * молча превратится в тест, который ничего не проверяет.
   *
   * Поэтому детектор проверяется на каноне: `lib/access.ts` — единственное место, которому оси
   * складывать и положено, и обе они там зовутся по определению (`serviceRequestVisibilityWhere`
   * состоит ровно из них). Не нашлись — сломан не код, а сторож, и чинить надо `AXIS_NAMES`.
   */
  it('исключения К2 не протухли, а сам сторож всё ещё видит ручную сборку', () => {
    for (const file of MANUAL_AXES) {
      const source = code(readFileSync(join(SRC, file), 'utf8'));
      expect(
        callsAxis(source),
        `${file}: оси здесь больше не складывают руками — строку из MANUAL_AXES пора убрать`,
      ).toBe(true);
    }

    const canon = code(readFileSync(join(SRC, CANON), 'utf8'));
    for (const name of AXIS_NAMES) {
      expect(
        axisCall(name).test(canon),
        `${name}: в каноне (${CANON}) вызова оси нет — либо ось переименовали, либо общий предикат ` +
          'её больше не зовёт. До правки `AXIS_NAMES` проверка К2 зеленеет, ничего не проверяя',
      ).toBe(true);
    }
  });
});
