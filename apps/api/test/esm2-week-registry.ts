/**
 * Реестр тестов, знающих про недельный лист ЭСМ-2 — рабочий список подэтапа 4b
 * ([план](../../../docs/assignment-periods-plan.md), Ю9, У1;
 * [раздача работы](../../../docs/assignment-periods-regression.md)).
 *
 * ─────────────────────────────────────────────────────────────────────────────────────────────
 * ЗАЧЕМ РЕЕСТР, ЕСЛИ ЕСТЬ ПАДЕНИЯ
 *
 * Потому что самый опасный класс файлов **не падает**. Переключение чтения (Р5, Р6) меняет форму
 * листа: сегодня `period_from` — всегда понедельник, `period_to` — воскресенье, и на неделю у
 * заявки приходится ровно один действующий лист на машину; после переключения `period_from` — любой
 * день, `period_to` — любой день не позже воскресенья той же недели, а внутри одной недели листов
 * может оказаться до семи.
 *
 * Файл, который **проверяет сверку**, после этого краснеет и тем себя называет. А файл, который
 * лист себе **вставляет сам** — с границами, посчитанными руками как «понедельник плюс шесть», —
 * или читает `period_from`, полагаясь, что это понедельник, продолжит проходить. Он будет
 * проверять мир, которого больше нет, и узнать об этом станет неоткуда: набор зелёный.
 *
 * Отсюда реестр: он превращает невидимый класс в перечень, а перечень — в работу, которую можно
 * раздать. У каждой записи есть `status`, и он отвечает ровно на вопрос следующей волны — **этот
 * файл уже посмотрели или ещё нет**.
 *
 * ─────────────────────────────────────────────────────────────────────────────────────────────
 * ЧЕТЫРЕ КЛАССА
 *
 * - `sync` — файл проверяет **поведение сверки**: гоняет дверь, которая пишет ЭСМ-2, и спрашивает,
 *   какие листы выписались, какие сгорели и какие у них границы. После переключения упадёт. Лечится
 *   двумя наборами ожиданий ([assignment-read-mode.ts](assignment-read-mode.ts)).
 *
 * - `consumer` — **потребитель уже выписанной бумаги**. Сверку не проверяет, но зашил «лист =
 *   календарная неделя от понедельника». Не упадёт — соврёт. Лечится прицельной правкой: другого
 *   способа нет, потому что параметризовать тут нечего — файл вообще не про разрез.
 *
 * - `target` — тест **уже отрезкового** движка: границы там предмет проверки, и проверяются они
 *   целевыми. Править нечего, наоборот — это эталон, по которому переписывают остальных.
 *
 * - `mention` — упоминание кода формы, права или комментария. Делать нечего.
 *
 * ─────────────────────────────────────────────────────────────────────────────────────────────
 * ЧТО ЗНАЧИТ `done` И ПОЧЕМУ ЭТО НЕ ЧЕСТНОЕ СЛОВО
 *
 * Пометить `done` мало — [esm2-week-audit.test.ts](esm2-week-audit.test.ts) требует доказательства
 * прямо в файле:
 *
 * - `sync` + `done` — файл зовёт `describeReadModes`, то есть у него действительно два прогона;
 * - `consumer` + `done` — в файле стоит метка `ЭСМ2-РАЗРЕЗ` с объяснением, что именно проверено или
 *   поправлено. Метка живёт рядом с кодом, а не только в реестре: читать её будут те, кто придёт к
 *   этому месту через год и без плана в голове.
 *
 * И отдельно про `mention`: файл, который лист **вставляет**, упоминанием быть не может вовсе, а
 * файл, где границы просто написаны в фикстуре, обязан сказать об этом явным `periodIsDecoration`.
 * Оба правила механические, и обойти их можно только неправдой в отдельном поле — а неправду в
 * отдельном поле видно на ревью, в отличие от неправды в общей куче.
 *
 * Реестр при этом обязан совпадать с деревом: новый файл, тронувший границы листа, красит аудит и
 * требует классификации. Забыть про него нельзя — можно только соврать в `note`, а это уже видно
 * на ревью.
 */

/** Класс файла: чем он платит за переключение чтения. */
export type Esm2WeekClass = 'sync' | 'consumer' | 'target' | 'mention';

/** Посмотрели уже или ещё нет — единственное, что волне 4b.2 нужно знать с одного взгляда. */
export type Esm2WeekStatus = 'pending' | 'done';

export interface Esm2WeekEntry {
  /** Имя файла в `apps/api/test`. */
  readonly file: string;
  readonly klass: Esm2WeekClass;
  readonly status: Esm2WeekStatus;
  /** Что в файле зависит от разреза. Для `mention` — где именно упоминание. */
  readonly note: string;
  /** Что сделать. Обязателен, пока `pending`; у `done` остаётся следом разбора. */
  readonly todo?: string;
  /**
   * Только у `mention`, в котором есть `period_from`/`period_to`: границы там написаны, но ни в
   * одно утверждение не идут. Отдельным полем, а не строкой в `note`, потому что это **claim**:
   * кто-то посмотрел файл и утверждает, что период — декорация. Такое утверждение должно быть
   * видно в диффе отдельной строкой, а не тонуть в пояснении.
   */
  readonly periodIsDecoration?: true;
  /**
   * `sync`-файл, чей предмет к режиму чтения не относится вовсе: порядок захвата блокировок, гонки
   * двух транзакций, перебор прав. Разрез задевает в нём только **адресацию** бумаги в фикстуре, и
   * две половины ожиданий совпадали бы навсегда, а не до этапа 5 — обёртка была бы формальностью.
   *
   * Тоже **claim**, как и `periodIsDecoration`: кто-то посмотрел файл и утверждает это. Храповик
   * требует за него метку `ЭСМ2-РАЗРЕЗ` в коде, иначе категория стала бы лазейкой «оборачивать
   * лень — напишу, что не нужно».
   */
  readonly readModeIrrelevant?: true;
}

