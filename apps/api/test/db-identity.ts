/**
 * Опознаваемые реквизиты для db-тестов: свои у каждого прогона и у каждого файла.
 *
 * **Зачем.** База у db-тестов общая и живёт между прогонами. Пять файлов заводили водителя по одной
 * и той же константе `11111111145`, каждый со своим именем и своим набором документов, и каждый —
 * с охраной «найти по СНИЛС, иначе создать». Кто первым добежал, тот и владеет человеком до конца
 * прогона: `waybill-request-links` падал, найдя `Тестовый Машинист Недельный` вместо своего, и
 * проходил на следующем запуске — потому что менялся порядок файлов.
 *
 * Такие падения хуже обычных: они не воспроизводятся, списываются на «флейк» и **маскируют
 * настоящие**. За эту переработку дважды выходило так, что полный прогон давал полсотни падений, и
 * разбор каждого начинался с вопроса «а моё ли это вообще».
 *
 * Поэтому реквизиты выводятся из зерна — имени файла плюс времени старта, — и два файла не могут
 * столкнуться, даже если побегут одновременно.
 */

/**
 * СНИЛС с верной контрольной суммой из произвольного зерна.
 *
 * Контрольная сумма считается тем же правилом ПФР, что и `isValidSnils` в контрактах: считать её
 * вторым способом значило бы завести второе мнение о том, какой номер верен. Номера ниже
 * `001-001-998` контрольной суммы не имеют вовсе, поэтому в старший разряд ставится единица —
 * сгенерированное число заведомо выше границы.
 */
export function snilsOf(seed: string): string {
  let digits = '';
  for (let i = 0; seed.length > 0 && digits.length < 9; i += 1) {
    digits += String(seed.charCodeAt(i % seed.length) % 10);
  }
  digits = `1${digits.slice(1)}`;
  let sum = 0;
  for (let i = 0; i < 9; i += 1) sum += Number(digits[i]) * (9 - i);
  const rest = sum < 100 ? sum : sum % 101;
  return `${digits}${String(rest === 100 ? 0 : rest).padStart(2, '0')}`;
}

/**
 * Зерно прогона для файла: его имя плюс момент старта.
 *
 * Имя файла — чтобы два файла не столкнулись в одном прогоне; время — чтобы вчерашний человек с
 * тем же именем не всплыл сегодня со вчерашними документами.
 */
export function runSeed(fileName: string): string {
  return `${fileName}-${Date.now().toString(36)}`;
}
