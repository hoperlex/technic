import { describe, expect, it } from 'vitest';
import {
  addDays,
  isoWeekday,
  localDate,
  nextRunAt,
  type SchedulePlan,
  windowOf,
} from '../src/services/mailings/schedule';

/**
 * Расписание рассылок (ADR 0075, ADR 0093).
 *
 * Ошибка в этом расчёте ничего не роняет: портал работает, письма уходят — просто не тогда, когда
 * договаривались, и не про те дни. Рассылка водителям на завтрашние рейсы, ушедшая на сутки позже
 * или второй раз подряд, обнаруживается уже у получателя, и обнаруживает её не разработчик. Поэтому
 * весь расчёт вынесен чистыми функциями и проверяется здесь, без базы и без планировщика.
 *
 * Все ожидания записаны в UTC (`toISOString`), а расписание задаётся местным временем: именно в
 * этом переводе и живут ошибки. Зона — 'Europe/Moscow' (в ней работает портал), летом и зимой
 * +03:00, так что местные 18:00 — это всегда 15:00 UTC.
 */

const MSK = 'Europe/Moscow';

/**
 * Ежедневная рассылка в 18:00 по местному времени — типовое расписание портала. Периодичности у
 * плана больше нет: «ежедневная» — это расписание без выбранных дней недели.
 */
const daily18: SchedulePlan = { sendAt: '18:00' };

/** Список подряд идущих понедельников: фикстура «исключений больше, чем горизонт поиска». */
function mondaysFrom(firstMonday: string, count: number): string[] {
  const [y, m, d] = firstMonday.split('-').map(Number) as [number, number, number];
  const out: string[] = [];
  for (let i = 0; i < count; i += 1) {
    out.push(new Date(Date.UTC(y, m - 1, d + i * 7)).toISOString().slice(0, 10));
  }
  return out;
}

describe('nextRunAt: ежедневное расписание', () => {
  it('утром того же дня ближайший запуск — сегодня вечером', () => {
    // 09:00 МСК 7 августа: сегодняшние 18:00 ещё впереди, переносить запуск на завтра нельзя —
    // иначе рассылка, заведённая утром, начнёт работать только со следующих суток.
    const next = nextRunAt(daily18, new Date('2026-08-07T06:00:00.000Z'), MSK);
    expect(next?.toISOString()).toBe('2026-08-07T15:00:00.000Z');
  });

  it('после отправки следующий запуск — завтра, а не сегодня', () => {
    // 18:30 МСК: сегодняшний запуск уже отработал. Вернуть его же — значит отправить письмо
    // второй раз, как только планировщик пересчитает расписание.
    const next = nextRunAt(daily18, new Date('2026-08-07T15:30:00.000Z'), MSK);
    expect(next?.toISOString()).toBe('2026-08-08T15:00:00.000Z');
  });

  it('ровно в момент срабатывания следующий запуск — завтра', () => {
    // Планировщик считает следующее время сразу после отправки, и `after` совпадает с моментом
    // запуска до секунды. Нестрогое сравнение вернуло бы «сейчас» и зациклило отправку.
    const next = nextRunAt(daily18, new Date('2026-08-07T15:00:00.000Z'), MSK);
    expect(next?.toISOString()).toBe('2026-08-08T15:00:00.000Z');
  });

  it('секунды в `sendAt` не меняют результат', () => {
    // В базе поле хранится типом `time` и приходит как «18:00:00»: разбор обязан понимать обе
    // записи одинаково, иначе одно и то же расписание сработает по-разному.
    const withSeconds: SchedulePlan = { ...daily18, sendAt: '18:00:00' };
    const after = new Date('2026-08-07T06:00:00.000Z');
    expect(nextRunAt(withSeconds, after, MSK)?.toISOString()).toBe(
      nextRunAt(daily18, after, MSK)?.toISOString(),
    );
  });

  it('расписание на 00:30 — это местная полночь, то есть 21:30 UTC предыдущих суток', () => {
    // Полночь — единственное время, у которого местная дата и дата UTC расходятся всегда.
    // Ошибка здесь сдвигает рассылку на сутки, оставаясь незаметной в остальных расписаниях.
    const midnight: SchedulePlan = { sendAt: '00:30' };
    // 21:00 МСК 6 августа: ближайшие местные 00:30 — это уже 7-е, по UTC — вечер 6-го.
    const next = nextRunAt(midnight, new Date('2026-08-06T18:00:00.000Z'), MSK);
    expect(next?.toISOString()).toBe('2026-08-06T21:30:00.000Z');
    expect(localDate(next!, MSK)).toBe('2026-08-07');
  });
});

describe('nextRunAt: дни недели и исключения', () => {
  it('рабочие дни: после пятничной отправки следующий запуск — в понедельник', () => {
    // Рассылка на завтрашние рейсы в субботу и воскресенье никому не нужна, а наивный «+1 день»
    // именно на выходных и ошибается: 7 и 8 августа 2026 — суббота и воскресенье.
    const workdays: SchedulePlan = { ...daily18, runWeekdays: [1, 2, 3, 4, 5] };
    const next = nextRunAt(workdays, new Date('2026-08-07T15:30:00.000Z'), MSK);
    expect(next?.toISOString()).toBe('2026-08-10T15:00:00.000Z');
    expect(isoWeekday(localDate(next!, MSK))).toBe(1);
  });

  it('пустой набор дней означает «по всем», а не «ни по каким»', () => {
    // Расписание без выбранных дней приходит с формы как пустой массив. Считать его запретом —
    // значит молча выключить рассылку, которую пользователь считает работающей.
    const anyDay: SchedulePlan = { ...daily18, runWeekdays: [] };
    const next = nextRunAt(anyDay, new Date('2026-08-07T15:30:00.000Z'), MSK);
    expect(next?.toISOString()).toBe('2026-08-08T15:00:00.000Z');
  });

  it('расписание из одного дня недели ждёт свой день', () => {
    // Прежняя «недельная» рассылка — это набор `[1]`, понедельник, и ничего больше (ADR 0093).
    // Считать от «сегодня» нельзя: с пятницы до ближайшего запуска трое суток, и все
    // промежуточные дни расписание обязано пропустить.
    const weekly: SchedulePlan = { sendAt: '18:00', runWeekdays: [1] };
    const next = nextRunAt(weekly, new Date('2026-08-07T06:00:00.000Z'), MSK);
    expect(next?.toISOString()).toBe('2026-08-10T15:00:00.000Z');
  });

  it('расписание из одного дня в свой день до времени отправки срабатывает сегодня', () => {
    // Утро понедельника: ждать следующей недели незачем — сегодняшнее время ещё не наступило.
    const weekly: SchedulePlan = { sendAt: '18:00', runWeekdays: [1] };
    const next = nextRunAt(weekly, new Date('2026-08-10T06:00:00.000Z'), MSK);
    expect(next?.toISOString()).toBe('2026-08-10T15:00:00.000Z');
  });

  it('исключённая дата пропускается, запуск переносится на следующий подходящий день', () => {
    // Праздники и остановки задаются местными датами. Сравнивать их надо с местным днём запуска:
    // по UTC вечерняя рассылка 8 августа — это всё ещё 8-е, а вот ночная была бы уже 7-м.
    const withHoliday: SchedulePlan = { ...daily18, excludedDates: ['2026-08-08'] };
    const next = nextRunAt(withHoliday, new Date('2026-08-07T15:30:00.000Z'), MSK);
    expect(next?.toISOString()).toBe('2026-08-09T15:00:00.000Z');
  });

  it('когда исключены все дни горизонта, возвращается null, а не бесконечный поиск', () => {
    // Поиск идёт перебором дней вперёд и обязан когда-то остановиться: расписание с годом
    // исключений — валидное состояние, а зависший планировщик — нет. Горизонт в коде 370 дней,
    // 60 понедельников подряд перекрывают его с запасом.
    const weekly: SchedulePlan = {
      sendAt: '18:00',
      runWeekdays: [1],
      excludedDates: mondaysFrom('2026-08-10', 60),
    };
    expect(nextRunAt(weekly, new Date('2026-08-07T06:00:00.000Z'), MSK)).toBeNull();
  });
});

describe('localDate: местная дата момента', () => {
  it('вечер по UTC — это уже следующий день по Москве', () => {
    // +03:00 сдвигает границу суток на 21:00 UTC. Именно из-за неё «сегодняшняя» дата на сервере
    // и в расписании расходятся, а рассылка берёт рейсы не того дня.
    expect(localDate(new Date('2026-08-06T20:30:00.000Z'), MSK)).toBe('2026-08-06');
    expect(localDate(new Date('2026-08-06T21:30:00.000Z'), MSK)).toBe('2026-08-07');
  });

  it('дата отдаётся в формате «YYYY-MM-DD»', () => {
    // Этот же формат хранят исключённые даты и границы окна данных — они сравниваются строками.
    expect(localDate(new Date('2026-01-05T09:00:00.000Z'), MSK)).toBe('2026-01-05');
  });
});

describe('isoWeekday: день недели местной даты', () => {
  it('воскресенье — 7, а не 0', () => {
    // Дни недели приходят с формы как ISO 1..7, а `getUTCDay()` отдаёт 0 для воскресенья.
    // Незакрытый ноль означает, что воскресная рассылка не уйдёт никогда.
    expect(isoWeekday('2026-08-09')).toBe(7);
    expect(isoWeekday('2026-08-10')).toBe(1);
  });

  it('остальные дни считаются от понедельника', () => {
    expect(isoWeekday('2026-08-07')).toBe(5);
    expect(isoWeekday('2026-08-08')).toBe(6);
  });
});

describe('addDays: календарная арифметика', () => {
  it('переходит через границу месяца', () => {
    // Прибавление суток в миллисекундах ломается на разной длине месяцев — проверяется именно
    // календарный переход, а не арифметика.
    expect(addDays('2026-08-31', 1)).toBe('2026-09-01');
    expect(addDays('2026-09-01', -1)).toBe('2026-08-31');
  });

  it('переходит через границу года', () => {
    expect(addDays('2026-12-31', 1)).toBe('2027-01-01');
    expect(addDays('2027-01-01', -1)).toBe('2026-12-31');
  });

  it('знает про високосный февраль', () => {
    // 2028 год високосный: 29 февраля существует, и окно данных обязано его увидеть.
    expect(addDays('2028-02-28', 1)).toBe('2028-02-29');
    expect(addDays('2028-02-29', 1)).toBe('2028-03-01');
    expect(addDays('2027-02-28', 1)).toBe('2027-03-01');
  });

  it('шаг больше месяца считается как календарные сутки', () => {
    expect(addDays('2026-08-07', 30)).toBe('2026-09-06');
  });
});

describe('windowOf: окно данных запуска', () => {
  it('«на завтра» — это начало 1 и длительность 1, то есть один день', () => {
    // Самое частое расписание портала: вечером про завтрашний день. Ошибка в длительности здесь
    // добавляет в письмо чужие сутки, ошибка в начале — отправляет задание на сегодня.
    expect(windowOf(new Date('2026-08-07T15:00:00.000Z'), 1, 1, MSK)).toEqual({
      from: '2026-08-08',
      to: '2026-08-08',
    });
  });

  it('«с сегодняшнего, семь дней» кончается через шесть суток, а не через семь', () => {
    // Конец считается как `from + days - 1`, и это единственное место, где живёт та самая
    // ошибка на единицу: недельная сводка, захватившая восьмой день, показывает работу,
    // о которой в следующем письме расскажут второй раз.
    expect(windowOf(new Date('2026-08-07T15:00:00.000Z'), 0, 7, MSK)).toEqual({
      from: '2026-08-07',
      to: '2026-08-13',
    });
  });

  it('нулевое начало — сам день запуска', () => {
    // Рассылка «на сегодня» тоже допустима, и нулевое начало не должно проваливаться во вчера.
    expect(windowOf(new Date('2026-08-07T15:00:00.000Z'), 0, 1, MSK)).toEqual({
      from: '2026-08-07',
      to: '2026-08-07',
    });
  });

  it('окно считается от местной даты запуска, а не от даты UTC', () => {
    // Ночная рассылка 00:30 МСК 7 августа по UTC приходится на 6-е. Считать окно от даты UTC —
    // значит взять вчерашние данные.
    expect(windowOf(new Date('2026-08-06T21:30:00.000Z'), 1, 1, MSK)).toEqual({
      from: '2026-08-08',
      to: '2026-08-08',
    });
  });

  it('окно переходит через границу месяца целиком', () => {
    // Границы окна сравниваются с датами рейсов строками: «2099-08-32» не найдёт ничего и не
    // упадёт — письмо просто придёт пустым.
    expect(windowOf(new Date('2026-08-30T15:00:00.000Z'), 1, 3, MSK)).toEqual({
      from: '2026-08-31',
      to: '2026-09-02',
    });
  });

  it('окна короче суток не бывает: нулевая длительность — это всё равно один день', () => {
    // Схема и контракт нуля не пропускают, но расчёт не вправе выдать «конец раньше начала»: с
    // такими границами запрос молча не найдёт ни одной строки, и рассылка станет пустой.
    expect(windowOf(new Date('2026-08-07T15:00:00.000Z'), 1, 0, MSK)).toEqual({
      from: '2026-08-08',
      to: '2026-08-08',
    });
  });
});
