import { describe, expect, it } from 'vitest';
import { type FreightAction, type RoutePointAction, pointContacts } from '@technic/contracts';

/**
 * Ответственные точки маршрута (план `docs/route-trips-plan.md`, Р9, Р9б, Р11а).
 *
 * Своим файлом, а не абзацем в общем тесте точек, по одной причине: от этого списка зависит, кого
 * бланк напечатает в графе «заказчик, телефон», а кого свернёт в «+N». Порядок здесь — не
 * оформление, а решение о содержании документа: водитель приедет и позвонит первому, и если
 * первым окажется не тот, у кого пропуск, машина простоит у ворот.
 *
 * Поэтому проверяется ровно три вещи: список **не зависит** от того, в каком порядке роли вернул
 * SQL; одинаковых людей в графе не двое; и разные люди с нечитаемыми номерами не сливаются в
 * одного.
 */

const freight = (
  role: 'load' | 'unload',
  requestNum: number,
  tripNum: number,
  name: string,
  phone: string,
  /**
   * Позиция роли внутри точки (миграция `0146`): ею человек решает, что грузим первым, и она же
   * задаёт порядок контактов **внутри** вида роли. В базе она различна у ролей одной точки
   * (`UNIQUE (point_id, position)`), поэтому и в фикстурах повторяться не должна — иначе тест
   * проверял бы состояние, которого не бывает.
   */
  position: number,
): FreightAction => ({
  position,
  kind: 'freight',
  ref: { kind: 'freight', requestId: `req-${requestNum}`, tripId: `trip-${requestNum}-${tripNum}` },
  role,
  cargoLabel: '10 м³',
  pairPosition: 9,
  displayNumber: `ТС-${requestNum}/${tripNum}`,
  requestNum,
  tripNum,
  customerName: 'ЖК Северный',
  contactName: name,
  contactPhone: phone,
  addressMismatch: false,
});

const load = (
  requestNum: number,
  tripNum: number,
  name: string,
  phone: string,
  position: number,
): FreightAction => freight('load', requestNum, tripNum, name, phone, position);

const unload = (
  requestNum: number,
  tripNum: number,
  name: string,
  phone: string,
  position: number,
): FreightAction => freight('unload', requestNum, tripNum, name, phone, position);

const work = (requestNum: number, name: string, phone: string): RoutePointAction => ({
  position: 1,
  kind: 'linear',
  ref: { kind: 'linear', requestId: `req-${requestNum}`, workDate: '2026-08-12' },
  role: 'work',
  displayNumber: `ТС-${requestNum} · 12.08`,
  requestNum,
  tripNum: 0,
  customerName: 'Объект «Восточный»',
  contactName: name,
  contactPhone: phone,
  addressMismatch: false,
});

describe('порядок ответственных точки', () => {
  /**
   * Порядок ролей повторяет порядок граф «откуда» и «куда» строки задания: сначала те, кто отдаёт
   * груз, потом работа линейного дня, потом те, кто принимает (Р9б). Водитель читает бумагу в том
   * порядке, в котором поедет.
   */
  it('погрузки идут раньше работы, работа — раньше разгрузок', () => {
    const actions = [
      unload(40, 1, 'Петров П.П.', '+7 903 765-43-21', 3),
      work(77, 'Кузнецов К.К.', '+7 900 555-11-22'),
      load(41, 1, 'Иванов И.И.', '+7 916 123-45-67', 1),
    ];

    expect(pointContacts(actions).map((c) => c.name)).toEqual([
      'Иванов И.И.',
      'Кузнецов К.К.',
      'Петров П.П.',
    ]);
  });

  /**
   * Внутри одного вида роли порядок задаёт **позиция роли на точке** (миграция `0146`), а не номер
   * заявки: вопрос «чей ответственный встретит машину первым» — это тот же вопрос «какую ездку
   * грузим первой», и на него отвечает диспетчер, а не порядок заведения заявок. Номер держался
   * здесь только ради детерминизма и осмысленным ответом не был.
   */
  it('внутри роли порядок задаёт позиция на точке, а не номер заявки', () => {
    const actions = [
      load(41, 1, 'Третий', '+7 903 111-11-11', 3),
      load(40, 2, 'Второй', '+7 903 222-22-22', 2),
      load(40, 1, 'Первый', '+7 903 333-33-33', 1),
    ];

    expect(pointContacts(actions).map((c) => c.name)).toEqual(['Первый', 'Второй', 'Третий']);
  });

  /**
   * Главная проверка файла: тот же набор ролей, поданный в обратном порядке, обязан дать **тот же**
   * список. Иначе набор напечатанных контактов зависел бы от того, как строки вернул SQL, — а
   * свёртывание в «+N» решает, кто в бланк попадёт.
   */
  it('обратный порядок входа даёт тот же список', () => {
    const actions = [
      load(40, 1, 'Иванов И.И.', '+7 916 123-45-67', 1),
      work(77, 'Кузнецов К.К.', '+7 900 555-11-22'),
      unload(41, 2, 'Петров П.П.', '+7 903 765-43-21', 4),
      load(41, 1, 'Сидоров С.С.', '+7 905 111-22-33', 2),
    ];

    expect(pointContacts([...actions].reverse())).toEqual(pointContacts(actions));
  });
});

describe('дедупликация ответственных', () => {
  it('один номер в разных написаниях — один контакт', () => {
    const actions = [
      load(40, 1, 'Иванов И.И.', '+7 916 123-45-67', 1),
      unload(41, 1, 'Иванов Иван Иванович', '89161234567', 2),
    ];

    expect(pointContacts(actions)).toHaveLength(1);
  });

  /**
   * Имя берётся у первого вхождения **в порядке печати**, а не в порядке входа: иначе одна и та же
   * точка подписывалась бы по-разному от запроса к запросу. Выдумывать, какое из написаний имени
   * правильнее, портал не берётся.
   */
  it('при одном ключе и разных именах берётся имя первого по порядку печати', () => {
    const actions = [
      unload(40, 1, 'прораб Иванов', '+7 916 123-45-67', 2),
      load(41, 1, 'Иванов И.И.', '8 916 123 45 67', 1),
    ];

    expect(pointContacts(actions).map((c) => c.name)).toEqual(['Иванов И.И.']);
  });

  /**
   * Легаси-номер (ADR 0066 п. 7: миграция `0095` такие записи не трогала) участвует в сравнении
   * наравне — своей строкой. Свести его к «номера нет» значило бы объявить двух разных людей одним
   * и молча собрать две площадки в один заезд.
   */
  it('два разных легаси-номера остаются двумя контактами', () => {
    const actions = [
      load(40, 1, 'Иванов', '8 (495) 123-45-67 доб. 12', 1),
      load(41, 1, 'Петров', '8 (495) 123-45-67 доб. 14', 2),
    ];

    expect(pointContacts(actions).map((c) => c.name)).toEqual(['Иванов', 'Петров']);
  });

  it('один легаси-номер, набранный с разным регистром и пробелами, — один контакт', () => {
    const actions = [
      load(40, 1, 'Иванов', '8 (495) 123-45-67 Доб. 12', 1),
      load(41, 1, 'Иванов И.И.', '8 (495)  123-45-67  доб. 12', 2),
    ];

    expect(pointContacts(actions)).toHaveLength(1);
  });

  /**
   * Контакт без номера в сравнении по телефону не участвует — сравнивать нечем, — но и не
   * выбрасывается: у заявок старше миграции `0062` номера нет вовсе, а имя ответственного —
   * единственное, что водитель о встречающем знает. Так же ведёт себя и печать сегодня:
   * `routeContactsLabel` пропускает строку целиком только когда пусты **оба** поля.
   */
  it('контакт без номера печатается по имени, а совсем пустой не печатается', () => {
    const actions = [
      load(40, 1, 'Весовщик', '', 1),
      load(41, 1, '', '', 2),
      unload(42, 1, 'Весовщик', '', 3),
    ];

    expect(pointContacts(actions)).toEqual([{ name: 'Весовщик', phone: '' }]);
  });
});
