-- Обратная миграция к `0224_office_equipment_cycle.sql` (протокол выката, §7).
--
-- Вызывается только `db:cutover-down` — из `apps/api/drizzle` этот файл намеренно вынесен: раннер
-- берёт оттуда каждый `*.sql`, и лежи teardown там, ближайший `db:migrate` применил бы его следом
-- за миграцией, сняв только что накатанное и молча.
--
-- ПОЧЕМУ ЗДЕСЬ ОБРАЩАЮТСЯ И ДАННЫЕ, А НЕ ТОЛЬКО СХЕМА. Соблазнительный довод «teardown откатывает
-- схему, а не историю — заявка, прошедшая новый цикл, назад не помещается» здесь неприменим, и
-- проверяется это по гейтам самого инструмента: `--cutover-revert` разрешён только в фазе
-- `migrated`, ДО записи границы совместимости, при остановленных сервисах и НЕ ЗАПУСКАВШЕМСЯ
-- кандидате (§3.3 протокола). Значит в этот момент текущие статусы заявок изменила ровно одна
-- сила — сама миграция; нового цикла не проходила ни одна заявка, потому что новый код не
-- отработал ни секунды. Оставь мы статусы как есть, поднявшийся старый код встретил бы данные
-- новой модели: заявку без исполнителей он увидел бы «Новой» с назначенными людьми, а предъявленный
-- счёт — обычной «В работе» без всякого согласования. Ровно та поломка, ради которой окно и
-- городится.
--
-- История переходов при этом действительно не трогается: текущая строка заявки — не история.
-- Строка «Новая → Назначена» от 20.08 остаётся правдой при любом исходе выката.
--
-- ЧЕМ ОБРАТНОЕ ОТОБРАЖЕНИЕ ОДНОЗНАЧНО. Источников два, и оба заведены самой миграцией.
-- «Смета на согласовании» опознаётся по колонке `estimate_pending_revision`: её проставил шаг 2
-- бандла и ровно тем заявкам, которые ждали подписи (у отложенной из настоящей «В работе» колонка
-- пуста, потому что старый код в неё не пишет вовсе). «Назначена» опознаётся по составу
-- исполнителей, и однозначно это лишь потому, что аномальных «Новых с исполнителями» до миграции
-- не было — это ПРОВЕРИЛ fail-fast в начале конверсии (шаг 3 бандла) и отказался работать иначе.
--
-- Снимается ВСЁ, что завела миграция, включая запись журнала выпусков: забытая строка не даст
-- накатить миграцию повторно, то есть откат сделает релиз невыкатываемым. Проверяется репетицией
-- на копии боевой базы (протокол §9), и её главная сверка именно про этот файл — снимок
-- `service_requests` до миграции и после teardown обязан совпасть ЗНАЧЕНИЕ В ЗНАЧЕНИЕ по `status`
-- и `held_from_status`. Без такой сверки обратный перевод остаётся предположением.
--
-- Порядок обратен порядку миграции: сперва открывается дверь, потом возвращаются данные, и только
-- после них сносятся колонки, из которых данные и опознаются.

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 1. Дверь бандла — первой: обратный перевод пишет ровно те статусы, которые она запрещает.
ALTER TABLE service_requests DROP CONSTRAINT service_requests_dead_status_check;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 2. Обратный перевод статусов.
--
-- Четыре `UPDATE` — по одному на каждый перевод бандла, в том же составе и с теми же условиями,
-- прочитанными назад. Заморозки идут отдельными строками по той же причине, по какой шли в
-- миграции: `service_requests_hold_check` требует непустой `held_from_status` у отложенной заявки,
-- и вернуть его обязан тот же файл, который его правил.
UPDATE service_requests SET status = 'estimate_review'
 WHERE status = 'in_work' AND estimate_pending_revision IS NOT NULL;
UPDATE service_requests SET held_from_status = 'estimate_review'
 WHERE status = 'on_hold' AND held_from_status = 'in_work'
   AND estimate_pending_revision IS NOT NULL;

-- «Новая с исполнителями» — это и есть бывшая «Назначена»: до миграции таких заявок не было
-- (fail-fast бандла), а новый код, который мог бы их завести, не запускался. Исполнителем считается
-- и назначенная сервисная компания, и поимённая строка — ровно как в fail-fast, иначе половина
-- заявок вернулась бы не туда.
UPDATE service_requests r SET status = 'assigned'
 WHERE r.status = 'new'
   AND (r.service_counterparty_id IS NOT NULL
        OR EXISTS (SELECT 1 FROM service_request_executors e WHERE e.request_id = r.id));
UPDATE service_requests r SET held_from_status = 'assigned'
 WHERE r.status = 'on_hold' AND r.held_from_status = 'new'
   AND (r.service_counterparty_id IS NOT NULL
        OR EXISTS (SELECT 1 FROM service_request_executors e WHERE e.request_id = r.id));

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 3. Слив очереди отложенных проверок.
--
-- Та же пара, что в миграции (0197, §1а): выше правились `status` и `held_from_status`, на которые
-- подписан отложенный `service_requests_executor_present` (0178), а ниже идут `ALTER TABLE`,
-- берущие ACCESS EXCLUSIVE, — и они откажутся работать по таблице с непустой очередью событий.
-- Пустая база этого не ловит: `UPDATE` без единой затронутой строки в очередь ничего не кладёт.
SET CONSTRAINTS ALL IMMEDIATE;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 4. Колонки и ограничения бандла.
--
-- Ограничения снимаются явно, хотя ушли бы вместе со своими колонками: `service_requests_hold_check`
-- и соседи по таблице остаются на месте, и молчаливое исчезновение чужого имени в этом файле
-- прочиталось бы как недосмотр. `estimate_pending_revision` сносится ПОСЛЕ обратного перевода —
-- она и есть его источник.
ALTER TABLE service_requests DROP CONSTRAINT service_requests_estimate_pending_check;
ALTER TABLE service_requests DROP CONSTRAINT service_requests_rejection_resolution_check;
ALTER TABLE service_requests DROP COLUMN estimate_pending_revision;
ALTER TABLE service_requests DROP COLUMN rejection_resolution;
ALTER TABLE service_requests DROP COLUMN object_overridden;

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 5. Прежняя дверь 0197 — дословно, вместе с её комментарием.
--
-- Дословно, а не «по смыслу»: старый образ поднимается на этой схеме, и мёртвые статусы ADR 0133
-- обязаны остаться запрещёнными ровно так же, как были. Комментарий возвращается вместе с
-- ограничением — снятое ограничение уносит и его, а `\d` таблицы после отката обязан читаться так
-- же, как читался до выката.
ALTER TABLE service_requests ADD CONSTRAINT service_requests_dead_status_check CHECK (
  status NOT IN ('it_approved','diagnostics')
  AND (held_from_status IS NULL OR held_from_status NOT IN ('it_approved','diagnostics'))
);

COMMENT ON CONSTRAINT service_requests_dead_status_check ON service_requests IS
  'Мёртвые статусы цикла (решение 1 ADR 0133): «Согласована ИТ» и «Диагностика» из цикла убраны, '
  'значения остались в enum только потому, что DROP VALUE в Postgres нет. Заводить их нельзя ни '
  'заявке, ни её заморозке.';

-- ─────────────────────────────────────────────────────────────────────────────────────────────
-- 6. Журнал выпусков.
--
-- Строка выпуска — такие же данные миграции, как конверсия статусов: оставь её, и повторный накат
-- упадёт на `app_releases_pkey`, то есть откат сделает релиз невыкатываемым. Удаляется по паре
-- «seq + версия» с проверкой числа строк — молчаливое «удалено ноль» означало бы, что снимают не
-- тот выпуск, а больше одной строки — что журнал не тот.
DO $$
DECLARE
  removed int;
BEGIN
  DELETE FROM app_releases WHERE seq = 63 AND version = '0.1.54.0145';
  GET DIAGNOSTICS removed = ROW_COUNT;
  IF removed <> 1 THEN
    RAISE EXCEPTION
      'Из журнала выпусков удалено строк: %, ожидалась ровно одна (seq 63, версия 0.1.54.0145).',
      removed;
  END IF;
END $$;
