// Импорт статический и намеренно самый первый: `config` валидирует пару ключей уже при загрузке
// модуля (§8 — префиксы `ysc1_`/`ysc2_`, общие 20 символов, «оба или ни одного»). Сломанная пара
// уронит скрипт здесь, до единого сетевого запроса, с текстом самой проверки — и для гейта релиза
// это правильный исход, а не досадная ошибка запуска.
import { config } from '../src/config';

/**
 * Preflight капчи — гейт релиза (план `docs/smart-captcha-plan.md`, §8 и §13).
 *
 * ЗАЧЕМ. У Yandex SmartCaptcha есть ограниченный режим: если платёжный аккаунт не в статусе
 * `ACTIVE`/`TRIAL_ACTIVE`, сервис отвечает `ok` на ВСЕ проверки подряд. Снаружи это выглядит как
 * образцово здоровая капча — сплошные `ok` в метриках, зелёный виджет, — а защиты нет вовсе:
 * форму проходит любой робот с любым мусором в поле токена. Ни один тест портала такого не ловит,
 * потому что ломается не наш код, а ответ чужого сервиса.
 *
 * Проверка одна и предельно простая: послать в `/validate` заведомо не-токен и убедиться, что
 * ответ — `failed`. Настоящий сервис обязан отвергнуть мусор; ограниченный — примет.
 *
 * ГДЕ ЗАПУСКАЕТСЯ. Из `deploy-auto` шагом 2, ДО дампа, миграций и переключения контейнеров:
 * сервисом профиля `tools` из candidate-образа с `TAG=$COMMIT_SHA` (без явного тега `run` взял бы
 * `:latest`, а он до конца выката указывает на прошлый релиз — проверялся бы не тот код). Место
 * выбрано так, что при отказе не сделано ещё ничего: дамп не снят, миграции не накатаны,
 * контейнеры прежние. Ненулевой код останавливает выкат.
 *
 * ЧТО ЭТА ПРОВЕРКА ДОКАЗЫВАЕТ: сервер дотягивается до сервиса, и мусорный токен получает `failed`,
 * то есть ограниченный режим не включён.
 *
 * ЧЕГО ОНА НЕ ДОКАЗЫВАЕТ: что настоящий токен виджета будет принят. `failed` возвращается и
 * роботу, и при ошибке самого запроса; поле `message` документация разрешает использовать только
 * для диагностики, контрактом оно не является. Поэтому отрицательный сценарий сам по себе
 * работоспособность не подтверждает — её показывает только живой E2E после релиза (§13), и из
 * объёма приёмки он не убирается.
 *
 * Одну разновидность «ошибки запроса» гейт всё же отделяет и называет вслух — неверный серверный
 * ключ. Живая проверка показала, что он приходит не двухсоткой: сервис отвечает `403` и телом
 * `{"status":"failed","message":"Authentication failed. Invalid secret."}`. Разбирать этот случай
 * вместе с обрывом связи было бы вредно вдвойне: человек у деплоя пошёл бы чинить сеть вместо
 * `prod.env`, а сам случай — самый опасный из всех, потому что в рантайме код не 200 проходит
 * fail-open (§7), то есть портал с неверным ключом пропускал бы всех, никого не проверив.
 *
 * ПОЧЕМУ ЗДЕСЬ FAIL-CLOSED, А В РАНТАЙМЕ FAIL-OPEN. `verifyCaptcha` при сети, таймауте, коде не
 * 200, битом JSON и неизвестном `status` пропускает запрос (§7): там на другом конце живой человек
 * с формой регистрации, и отказывать ему из-за чужого сбоя — хуже, чем на время сбоя остаться при
 * одних IP-лимитах. Здесь всё наоборот: гейт релиза не имеет права пропускать вслепую. Перед
 * выкатом «проверить не удалось» означает ровно одно — мы не знаем, поедет ли релиз с рабочей
 * капчей, — а выкатывать портал, про защиту которого ничего не известно, нельзя. Поэтому любая
 * невозможность проверить — отказ.
 *
 * КЛЮЧИ В ВЫВОД НЕ ПОПАДАЮТ НИКОГДА — ни целиком, ни хвостом, ни в составе чужого ответа
 * (см. `callValidate`): и репозиторий, и логи деплоя публичные.
 *
 * Использование:
 *   docker compose -f deploy/docker-compose.yml -p technic --profile tools run --rm captcha-check
 *   pnpm --filter @technic/api check:captcha
 */

const EXIT_FAILURE = 1;

/** Ручка проверки токена; адрес фиксирован документацией и в конфигурацию не выносится. */
const VALIDATE_URL = 'https://smartcaptcha.cloud.yandex.ru/validate';

/**
 * Заведомо не токен виджета — тот же приём, что у canary в `src/auth/captcha.ts`. Токен настоящей
 * капчи здесь не нужен и невозможен: его выдаёт браузер, а у гейта браузера нет. Проверяется не
 * «принимает ли сервис хорошее», а «отвергает ли плохое».
 */
const PREFLIGHT_TOKEN = 'technic-preflight-invalid-token';

/** Что делать, когда проверить не удалось: один и тот же совет у всех веток недоступности. */
const UNAVAILABLE_HINT =
  '  Гейт не пропускает вслепую: в рантайме такой случай проходит fail-open (план §7), но перед\n' +
  '  выкатом «проверить не удалось» означает «мы не знаем, поедет ли релиз с рабочей капчей».\n' +
  '  Проверьте связь площадки с smartcaptcha.cloud.yandex.ru и повторите выкат.';

/** Отказ гейта: причина, что с ней делать, и ненулевой код — им деплой и останавливается. */
function reject(reason: string, hint: string): never {
  console.error(`preflight капчи: ОТКАЗ — ${reason}`);
  console.error(hint);
  process.exit(EXIT_FAILURE);
}

type ValidateOutcome =
  /** Ответ разобран; `status` намеренно широкого типа — это чужой JSON, а не наш контракт. */
  | { kind: 'body'; status: unknown }
  /**
   * Код не 200, но тело — внятный отказ самого сервиса (`status: "failed"`). Так SmartCaptcha
   * отвечает на неверный серверный ключ: проверено вживую — 403 и
   * `{"status":"failed","message":"Authentication failed. Invalid secret."}`. Отделено от
   * недоступности не ради красоты вывода: это единственная ветка, где человеку у деплоя надо
   * править `prod.env`, а не искать обрыв связи.
   */
  | { kind: 'rejected'; code: number }
  /** Пригодного к разбору ответа нет: сеть, таймаут, чужой код без тела, нечитаемый JSON. */
  | { kind: 'unavailable'; reason: string };

/** Текст ошибки запроса без стека: в логе деплоя нужен диагноз, а не трассировка. */
function describeError(e: unknown): string {
  // `AbortSignal.timeout` бросает `TimeoutError`; его штатное английское сообщение в логе деплоя
  // ничего не добавляет, а вот величина границы — добавляет.
  if (e instanceof Error && e.name === 'TimeoutError') {
    return `истекли ${config.captcha.timeoutMs} мс таймаута`;
  }
  return e instanceof Error ? e.message : String(e);
}

/**
 * Один голый запрос к `/validate`. Счётчики и метрики `src/auth/captcha.ts` здесь не
 * переиспользуются намеренно: у гейта нет процесса, который эти метрики потом отдаст, а
 * `verifyCaptcha` вдобавок бросает прикладной `badRequest` — исход, который гейту пришлось бы
 * разбирать обратно.
 *
 * Ошибки не бросает: решение «пропустить или отказать» принимает `main`.
 */
async function callValidate(): Promise<ValidateOutcome> {
  const form = new URLSearchParams({
    secret: config.captcha.serverKey,
    token: PREFLIGHT_TOKEN,
  });

  try {
    const res = await fetch(VALIDATE_URL, {
      method: 'POST',
      headers: { 'content-type': 'application/x-www-form-urlencoded' },
      body: form.toString(),
      signal: AbortSignal.timeout(config.captcha.timeoutMs),
    });

    const raw = await res.text();
    let status: unknown;
    try {
      ({ status } = JSON.parse(raw) as { status?: unknown });
    } catch {
      // Тело в вывод не идёт — только его длина. Причина не в аккуратности: нечитаемый ответ
      // пришёл не от сервиса, а от кого-то по дороге (прокси площадки, перехватывающий шлюз), а
      // такие страницы ошибок регулярно повторяют в себе исходный запрос — вместе с `secret=` в
      // теле. Печать «для диагностики» вынесла бы серверный ключ в публичный лог деплоя.
      return {
        kind: 'unavailable',
        reason: `ответ (код ${res.status}, ${raw.length} Б) не разбирается как JSON`,
      };
    }

    if (res.ok) return { kind: 'body', status };
    // Код не 200 с телом отказа — это ответ сервиса, а не обрыв связи: см. `rejected`.
    if (status === 'failed') return { kind: 'rejected', code: res.status };
    return { kind: 'unavailable', reason: `сервис ответил кодом ${res.status}` };
  } catch (e) {
    // Сюда приходят сеть, DNS, TLS и таймаут. Различать их подробнее незачем — исход один.
    return { kind: 'unavailable', reason: `запрос не удался: ${describeError(e)}` };
  }
}

/** Короткая форма чужого `status` для лога: длину задаёт не наш код, значит, её надо ограничить. */
function shortStatus(status: unknown): string {
  const text = String(status);
  return text.length > 40 ? `${text.slice(0, 40)}…` : text;
}

async function main(): Promise<void> {
  // Незаданные ключи для гейта — отказ, а не «нечего проверять». В production они обязательны
  // (§8): без них API просто не стартует, и релиз, дошедший сюда без ключей, — это релиз, который
  // всё равно не поднимется. Молчаливое «ок, пропускаем» на этом месте означало бы гейт, который
  // легче всего обойти, забыв положить ключи в `prod.env`.
  if (!config.captcha.enabled) {
    reject(
      'ключи SmartCaptcha не заданы (SMARTCAPTCHA_CLIENT_KEY и SMARTCAPTCHA_SERVER_KEY пусты)',
      '  В production оба ключа обязательны (план §8) — без них API не стартует вовсе.\n' +
        '  Положите пару ключей боевой капчи в prod.env и повторите выкат.',
    );
  }

  console.log(
    `preflight капчи: спрашиваю ${VALIDATE_URL} заведомо мусорным токеном ` +
      `(таймаут ${config.captcha.timeoutMs} мс)…`,
  );

  const outcome = await callValidate();

  if (outcome.kind === 'unavailable') {
    reject(`проверить не удалось: ${outcome.reason}`, UNAVAILABLE_HINT);
  }

  if (outcome.kind === 'rejected') {
    reject(
      `сервис отверг сам запрос (код ${outcome.code}) — серверный ключ не принят`,
      '  Связь есть, отвечает SmartCaptcha, но проверку он не выполняет: так выглядит неверный\n' +
        '  SMARTCAPTCHA_SERVER_KEY («Authentication failed. Invalid secret.»). Пара ключей уже\n' +
        '  прошла проверки формата при загрузке конфигурации, значит ключ по форме верен, но\n' +
        '  такой капчи в облаке нет — скорее всего, в prod.env лежит ключ удалённой или чужой.\n' +
        '  Отдельно важно, почему это отказ гейта, а не «неудачная попытка»: в рантайме код не 200\n' +
        '  проходит fail-open (план §7), то есть портал с таким ключом пропускал бы ВСЕХ, не\n' +
        '  проверив никого, и внешне выглядел бы защищённым.\n' +
        '  Возьмите ключи нужной капчи в консоли Yandex Cloud и повторите выкат.',
    );
  }

  if (outcome.status === 'ok') {
    reject(
      'мусорный токен ПРИНЯТ (status="ok") — капча не защищает',
      '  Так отвечает ограниченный режим SmartCaptcha: платёжный аккаунт не в статусе\n' +
        '  ACTIVE/TRIAL_ACTIVE, и сервис возвращает `ok` на любые проверки, включая заведомо\n' +
        '  мусорные. Портал при этом выглядел бы исправным — метрики состояли бы из сплошных\n' +
        '  здоровых `ok`, — а три публичные формы стояли бы открытыми (план §8).\n' +
        '  Проверьте статус платёжного аккаунта в консоли Yandex Cloud и повторите выкат.',
    );
  }

  if (outcome.status !== 'failed') {
    // Неизвестный `status` — та же невозможность проверить, что и оборванная сеть: ответ пришёл,
    // но что он означает, мы не знаем, а гадать перед выкатом не за что.
    reject(`неизвестный status "${shortStatus(outcome.status)}"`, UNAVAILABLE_HINT);
  }

  console.log('');
  console.log('preflight капчи: мусорный токен отвергнут (status="failed").');
  console.log('');
  console.log('Что это ДОКАЗЫВАЕТ: сервер дотягивается до SmartCaptcha, и заведомо не-токен');
  console.log('получает отказ, то есть ограниченный режим (план §8) не включён.');
  console.log('');
  console.log('Чего это НЕ доказывает: что настоящий токен виджета будет принят. `failed` значит');
  console.log('лишь «этот токен не годится» — его получает и робот, и любой сорванный запрос, а');
  console.log('поле `message` документация разрешает читать только для диагностики, контрактом оно');
  console.log('не является. Приём настоящего токена показывает только живой E2E после релиза:');
  console.log('регистрация настоящим виджетом на боевом домене (план §13).');
  console.log('');
  console.log('РУЧНОЙ ПУНКТ РЕЛИЗНОГО ЧЕК-ЛИСТА: статус платёжного аккаунта (ACTIVE/TRIAL_ACTIVE)');
  console.log('проверяется руками в консоли Yandex Cloud. Отсюда его не видно: ключ `ysc2_`');
  console.log('доступа к биллингу не даёт, а автоматизация потребовала бы сервисного аккаунта,');
  console.log('IAM-токена, идентификатора платёжного аккаунта и роли на просмотр биллинга —');
  console.log('это в «Отложено» плана (§15).');
  console.log('');
  // Последняя строка — маркер, как у `migration-report`: вывод едет через `docker compose run`, где
  // к нему может подмешаться чужое, и «проверка прошла» обязано отличаться от «команда не
  // отработала» не только кодом возврата.
  console.log('captcha ok');
}

main().catch((e) => {
  console.error('preflight капчи: ОТКАЗ — сбой самой проверки:', e);
  process.exit(EXIT_FAILURE);
});
