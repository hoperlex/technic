import type { DeviceSkipReason } from '@technic/contracts';

/**
 * Приём писем от оргтехники: общий язык транспорта ящика и приёмника
 * (план `docs/office-equipment-mail-telemetry-plan.md`, §7 Р27, §9.1).
 *
 * Здесь нет ни одной строки разбора письма и ни одного обращения к базе или к хранилищу: worker
 * знает про письмо ровно три вещи — какой у него UID, сколько он весит и как отдать его тело в
 * API. Разбор, сырьё в S3 и курсор живут в API (Р2, Р25), потому что там же живут правила,
 * словари и контракты, а второй их экземпляр в worker разошёлся бы с первым молча.
 */

/**
 * Конверт письма — то, что известно о письме ДО скачивания тела.
 *
 * Отделён от тела не ради стройности: письмо сверх потолка не качается вовсе (§9.1, п. 1), и
 * решение «качать или не качать» принимается ровно по этим полям. Оттого же у конверта нет поля
 * `raw`: тело приезжает отдельным вызовом и только когда оно нужно.
 */
export interface DeviceMailEnvelope {
  uid: number;
  /** Размер письма в байтах — так, как его объявляет ящик. */
  size: number;
  /** Заголовок `Date` строкой, как он записан в письме; пусто — ящик его не отдал. */
  dateHeader?: string;
  /** Заголовок `Message-ID`; пусто — письма без него бывают, и это не ошибка. */
  messageIdHeader?: string;
  /** Адрес, на который письмо пришло: по нему ящик различают, когда их станет несколько. */
  envelopeTo?: string;
}

/**
 * Ящик писем. Две реализации (Р27): `imap` — настоящий сервер, `dir` — каталог с `.eml`.
 *
 * Интерфейс один, и это не удобство, а единственный способ проверить приёмник вовсе: IMAP-сервера
 * нет ни в тестах, ни на машине разработчика, а тест на мок библиотеки не доказывает ничего.
 */
export interface DeviceMailbox {
  readonly name: 'imap' | 'dir';
  /**
   * Открыть ящик, назвать его эпоху (`UIDVALIDITY`) и верхнюю границу номеров. Смена эпохи
   * означает «ящик пересоздан»: UID прежнего ящика к новому не относятся ни одним числом.
   *
   * `maxUid` — наибольший номер, занятый в ящике на эту минуту; `null` — граница неизвестна.
   * Отдаётся отсюда, потому что ящик видит только worker, а отметка нужна ручке (Р32). Разница
   * между `null` и нулём здесь несущая: ноль — это «ни одно письмо не ниже», то есть барьер,
   * выключенный навсегда и молча.
   */
  open(): Promise<{ uidValidity: number; maxUid: number | null }>;
  /**
   * Конверты писем с UID не ниже `fromUid`, не больше `limit` штук, по возрастанию UID. Тела
   * здесь нет намеренно — см. `DeviceMailEnvelope`.
   */
  listEnvelopes(fromUid: number, limit: number): Promise<DeviceMailEnvelope[]>;
  /**
   * Тело письма целиком. `null` — письма больше нет в ящике (его убрали руками между заходами);
   * это не ошибка, а штатный исход, и приёмник обязан его пережить.
   */
  fetchRaw(uid: number): Promise<Buffer | null>;
  /**
   * Пометить письмо обработанным: прочитанным или, если задан `processedMailbox`, переложить.
   *
   * Вызывается ТОЛЬКО после успешного ответа ручки (§9.1). Наоборот — значит терять письмо при
   * каждом потерянном ответе: тело выкачано, письмо помечено, а принимать некому.
   */
  markProcessed(uid: number): Promise<void>;
  close(): Promise<void>;
}

/** Настройки приёма — всё, что worker читает из окружения по префиксу `DEVICE_MAIL_*`. */
export interface DeviceMailConfig {
  /** Ключ ящика в журнале портала; он же различает каналы, если ящиков станет несколько. */
  account: string;
  transport: 'imap' | 'dir';
  /** Каталог с `.eml` для транспорта `dir`; при `imap` не читается. */
  dir: string;
  imapHost: string;
  imapPort: number;
  imapSecure: boolean;
  imapUser: string;
  imapPassword: string;
  mailbox: string;
  /** Куда перекладывать обработанное; пусто — не перекладывать, помечать прочитанным. */
  processedMailbox: string;
  pollIntervalMs: number;
  batch: number;
  maxSizeBytes: number;
}

/** Курсор ящика: ответ `GET /internal/device-mail/cursor`. */
export interface DeviceMailCursor {
  uidValidity: number;
  lastUid: number;
  /**
   * Отметка дочитывания архива (Р32) и счётчик застревания (§9.1, п. 7). Worker их не применяет:
   * барьер дедупликации ставит ручка, а застрявшее письмо закрывает она же — в базу worker не
   * ходит вовсе. Здесь они затем, что форма ответа описана в одном месте, и затем, что журнал
   * обхода должен уметь сказать «курсор стоит на письме, у которого столько-то попыток».
   */
  resetUidValidity: number | null;
  resetMaxUid: number | null;
  stuckUidValidity: number | null;
  stuckUid: number | null;
  stuckAttempts: number;
}

/** Что worker сдаёт ручке приёма: письмо телом либо конверт без сырья у переростка. */
export interface DeviceMailSubmission {
  account: string;
  uidValidity: number;
  uid: number;
  size: number;
  messageIdHeader?: string;
  dateHeader?: string;
  envelopeTo?: string;
  /**
   * Наибольший UID, который ящик показал на этом заходе.
   *
   * Отсюда, а не из базы, потому что ящик видит только worker: отметку «максимальный UID на минуту
   * сброса» (Р32, `reset_max_uid`) записать больше некому, а без неё барьер дедупликации не
   * включается никогда — и архив, перечитанный после пересоздания ящика, задваивается целиком.
   *
   * Поля НЕТ, когда верхняя граница неизвестна: молчание означает «не знаю», а не «ноль». Ноль в
   * этой роли — отметка «ни одно письмо не ниже», то есть барьер, выключенный навсегда, причём
   * тихо.
   */
  mailboxMaxUid?: number;
  /** Тело письма целиком; отсутствует ровно в одном случае — вместе со `skipReason`. */
  rawBase64?: string;
  /**
   * Почему тело не приехало. Единственное законное значение — `too_large` (§9.1, п. 1): размер
   * виден в конверте, и тело не качается вовсе. Второго «конверта без сырья» не бывает — иначе
   * вечный цикл просто переезжает на круг позже (§9.1, п. 6).
   */
  skipReason?: DeviceSkipReason;
}

/** Ответ ручки приёма. `existed` — собственный повтор, штатный успех, а не ошибка. */
export interface DeviceMailIntakeResult {
  outcome: 'created' | 'existed';
  status: string;
  lastUid: number;
}

/**
 * Временный отказ ручки (HTTP 503): портал целиком не принимает — рубильник выключен, хранилище
 * недоступно, выкат.
 *
 * Отдельный тип ошибки, потому что он стоп-граница пачки: письмо остаётся в ящике, курсор не
 * двигается. Продолжить пачку после него — значит увести `GREATEST`-курсор за непринятое письмо и
 * потерять его навсегда.
 */
export class DeviceMailPausedError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'DeviceMailPausedError';
  }
}
