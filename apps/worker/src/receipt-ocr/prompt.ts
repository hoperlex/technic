/**
 * Задание модели для чеков на автозапчасти: промпт и схема ответа
 * (план `docs/auto-part-receipt-ocr-plan.md`, Р8).
 *
 * Схему просим, но верим только своей проверке — по той же причине, что у талонов: строгий режим
 * поддержан не всеми моделями каталога, а посредников в цепочке двое. Поэтому схема продублирована
 * в промпте словами, а ответ всё равно валидируется `receiptRecognitionResponseSchema`.
 *
 * Промпт закрывает пять классов ошибок, и каждый назван в плане:
 *
 * 1. **сумма против цены** — в таблице счёта две денежные графы рядом, и «2 шт × 2 830,00 =
 *    5 660,00» модель охотно возвращает ценой. Отсюда прямой пример в тексте;
 * 2. **поставщик против покупателя** — в шапке названы обе стороны, а нужна одна: покупатель у
 *    всех счетов один и тот же, и прочитать его продавцом значит не прочитать ничего;
 * 3. **рукопись** — на полях счетов пишут, к какой машине какая позиция («ПОЗ 1. КРАН КС55713 г.н.
 *    У2250Р777»), ставят резолюции и подписи. В MVP это НЕ распознаётся (Р2): чтобы подставить
 *    машину, мало прочитать номер — надо понять, к какой позиции относится приписка, а ошибка
 *    здесь тихая и портит ровно то число, ради которого раздел существует;
 * 4. **оборванная таблица** — счёт часто не влезает в кадр, и «прочитал пять строк из тридцати»
 *    обязано быть ВИДНО: отсюда `linesTruncated` и два итога, которыми портал сверяет полноту;
 * 5. **догадки** — `null` лучше правдоподобного вымысла; арифметику не пересчитываем.
 */

