#!/usr/bin/env bash
# Переключение чтения истории назначения — то, что делается ВНУТРИ окна техработ.
#
#   deploy/cutover.sh
#
# Место в порядке работ (docs/runbook.md, «Переключение чтения на историю»):
#
#   deploy-auto                                          выкат кода
#   deploy-auto --client-floor=<контракт сборки>          пол версии клиента
#   deploy-auto --maintenance=on --reason=… --until=…     портал закрыт объявлением
#   deploy/cutover.sh                                     ← этот скрипт
#   deploy-auto --maintenance=off                         портал открыт
#
# ЧТО ОН ДЕЛАЕТ. Три вещи, и все три — внутри уже закрытого портала: снимает аттестацию раската,
# переносит её идентификатор в переход и проводит окно. Аттестация годна тридцать минут и
# потребляется однажды, поэтому снимается здесь, а не заранее.
#
# ЧЕГО ОН НЕ ДЕЛАЕТ. Ни выката, ни пола клиента, ни объявления о техработах: у каждого из них своя
# дверь и свои проверки, и вторая дорога к ним означала бы два места, где записан один порядок.
# Решений у скрипта тоже нет — что разрешено переключать, считает `setModuleMode` под блокировкой,
# а шаги окна исполняет `assignment-cutover` (ADR 0196).
#
# Перед каждым шагом печатается сама команда («+ docker compose … assignment-attest …»): из вывода
# видно ровно то, что было бы набрано руками.
#
# Флаги:
#   --build=<sha>    сборка, которой переключаем; по умолчанию — тег запущенного technic-api
#   --actor=<email>  подписать переход учёткой портала. Необязателен (ADR 0198): дверь открывается
#                    доступом к базе, а не сессией, и проверить набранное вручную имя нечем
#   --reason=<текст> причина для журнала переходов
#   --check          только предполёт: что предстоит и что мешает. Ничего не меняет — этим
#                    проверяют готовность ДО окна, при открытом портале
set -euo pipefail

ACTOR='' BUILD='' CHECK=0
REASON='cutover истории назначения'
TOOLS=(docker compose -f deploy/docker-compose.yml -p technic --profile tools run --rm -T)

die() { printf '\nОШИБКА: %s\n' "$*" >&2; exit 1; }
step() { printf '\n== %s ==\n' "$*"; }
run() { printf '+ %s\n' "$*"; "$@"; }

for arg in "$@"; do
  case "$arg" in
    --actor=*) ACTOR="${arg#*=}" ;;
    --build=*) BUILD="${arg#*=}" ;;
    --reason=*) REASON="${arg#*=}" ;;
    --check) CHECK=1 ;;
    -h|--help) sed -n '2,32p' "$0"; exit 0 ;;
    *) die "неизвестный аргумент: $arg" ;;
  esac
done

[ -f deploy/docker-compose.yml ] || die "запускать из каталога портала (/opt/portals/technic)"

# Сборка — тег ЗАПУЩЕННОГО образа, а не HEAD рабочего дерева: раздаётся собранный образ, и дерево
# к этому моменту могло уехать вперёд на несколько коммитов.
if [ -z "$BUILD" ]; then
  # `|| true` обязателен: под `set -e` неудачный `docker inspect` (контейнера нет) завершил бы
  # скрипт прямо на присваивании — молча, до того как объяснение будет напечатано.
  BUILD="$(docker inspect -f '{{.Config.Image}}' technic-api 2>/dev/null | sed 's/.*://' || true)"
  [ -n "$BUILD" ] || die "не читается тег образа technic-api — портал запущен? иначе задайте --build=<sha>"
fi
printf 'сборка     : %s\n' "$BUILD"
[ -n "$ACTOR" ] && printf 'подпись    : %s\n' "$ACTOR"

step "предполёт: что предстоит и что мешает"
run "${TOOLS[@]}" assignment-cutover status --build="$BUILD" \
  || die "предполёт не пройден: препятствия названы выше, переключение не начинается.
  Если портал уже закрыт объявлением — снимите его (deploy-auto --maintenance=off) и разбирайте
  препятствия при работающем портале: это дни работы диспетчеров, а не минуты окна."

if [ "$CHECK" -eq 1 ]; then
  step "проверка закончена: ничего не менялось"
  exit 0
fi

step "аттестация раската (годна 30 минут, тратится однажды)"
ATT_OUT="$(run "${TOOLS[@]}" assignment-attest --build="$BUILD")"
printf '%s\n' "$ATT_OUT"
ATT="$(printf '%s' "$ATT_OUT" | sed -n 's/^аттестация *: *//p' | tr -dc '0-9a-f-')"
printf '%s' "$ATT" | grep -Eq '^[0-9a-f]{8}-[0-9a-f-]{27}$' || die \
  "из вывода аттестации не прочитался идентификатор — переключите руками:
  ${TOOLS[*]} assignment-cutover run --build=$BUILD --attestation=<id>"

step "окно: заморозка → ревалидация → поколение → сводка → переключение → разморозка"
# Заморозку, которую поставит этот шаг, он же и снимет — в том числе при отказе на середине.
# Поэтому своего разбора неудачи здесь нет: он был бы вторым ответом на тот же вопрос.
run "${TOOLS[@]}" assignment-cutover run \
  --build="$BUILD" --attestation="$ATT" --reason="$REASON" ${ACTOR:+--actor="$ACTOR"}

step "режим модуля после перехода"
run "${TOOLS[@]}" assignment-mode status
printf '\nДальше: deploy-auto --maintenance=off\n'
