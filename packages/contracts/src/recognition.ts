/**
 * Общий словарь распознавания бумаги моделью — один на все задания портала.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Заданий у распознавания стало два: талоны вывоза (ADR 0114) и чеки на
 * автозапчасти (план `docs/auto-part-receipt-ocr-plan.md`). Предметы у них разные до последнего
 * поля, а вот «чем читали», «повторится ли сбой» и «чей он» — одно и то же, и описано это было в
 * `waste-tickets.ts` просто потому, что талоны пришли первыми.
 *
 * Второе определение тех же трёх словарей рядом разъехалось бы молча: значения лежат в `CHECK`
 * двух разных таблиц и в текстах на экране, а сверять их было бы нечем. Поэтому словарь здесь
 * один, а талонные имена (`WasteTicketEngine` и соседи) остаются его псевдонимами — на них
 * ссылаются сотни мест, и переименование ничего бы не прибавило.
 */

/**
 * Чем читали страницу: `stub` — заглушка для тестов и разработки без сети, `proxy` — боевой путь
 * через LLM-прокси заказчика, `ocr` — внешний OCR с детерминированным парсером (кандидат замера, а
 * не реализация).
 *
 * Движок входит в ключ кэша попытки, поэтому он не «пометка для журнала»: ответ заглушки и ответ
 * модели не должны склеиться на одной и той же странице.
 */
export const RECOGNITION_ENGINES = ['stub', 'proxy', 'ocr'] as const;
export type RecognitionEngineKind = (typeof RECOGNITION_ENGINES)[number];

/** Чем кончилась попытка. Успешная на ключ кэша одна, неуспешных бывает сколько угодно. */
export const RECOGNITION_ATTEMPT_STATUSES = ['done', 'failed'] as const;
export type RecognitionAttemptStatus = (typeof RECOGNITION_ATTEMPT_STATUSES)[number];

/**
 * Повторится ли сбой сам. `transient` — повтор будет (503, 504, сеть, стоящий воркер);
 * `terminal` — повтора не будет и ждать нечего (403 от nginx, 401, содержательный 400, 413).
 *
 * Различие уезжает прямо в текст на экране: «Ошибка связи, следующая попытка в 14:32» и «Нужен
 * администратор, автоматического восстановления не будет» — разные обещания, и обещать
 * восстановление там, где его нет, это тот же обман, что и молчание.
 */
export const RECOGNITION_ERROR_CLASSES = ['transient', 'terminal'] as const;
export type RecognitionErrorClass = (typeof RECOGNITION_ERROR_CLASSES)[number];

/**
 * Чей сбой. `subsystem` — не отвечает распознавание вообще (эти и поднимают баннер), `item` — не
 * прошёл конкретный файл или скан: один упёршийся в лимит файл не означает, что сервис не настроен.
 */
export const RECOGNITION_ERROR_SCOPES = ['subsystem', 'item'] as const;
export type RecognitionErrorScope = (typeof RECOGNITION_ERROR_SCOPES)[number];

/**
 * Слаг задания — то, ЧТО читает модель на странице, а не чем и не откуда
 * (план `docs/auto-part-receipt-ocr-plan.md`, Р6).
 *
 * Величина нужна ровно в одном месте — в ключе идемпотентности прокси. Кэши попыток у заданий
 * разделены самими таблицами, склеиться их строкам негде; а вот дедуп прокси общий, и один и тот
 * же лист, прогнанный как талон и как чек, ушёл бы туда с одинаковым ключом — второй вызов вернул
 * бы ответ первого, то есть таблицу позиций, разобранную как талон.
 *
 * `waste_ticket` — умолчание, и это не вкусовщина: с ним строка ключа у талонов остаётся прежней
 * БАЙТ В БАЙТ, и выкат нового задания не обесценивает дедуп уже работающего.
 */
export const RECOGNITION_TASKS = ['waste_ticket', 'part_receipt'] as const;
export type RecognitionTaskSlug = (typeof RECOGNITION_TASKS)[number];
export const DEFAULT_RECOGNITION_TASK: RecognitionTaskSlug = 'waste_ticket';
