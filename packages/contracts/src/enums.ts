/**
 * Подписи ролей, упразднённых реформой доступа, — словарь, переживающий сами роли (план
 * реструктуризации §13.2 «след, который не переписать»; ADR 0113).
 *
 * **Зачем отдельный словарь, а не строка в `roleLabels`.** Упразднение роли — это снятие значения
 * из `ROLES` (шаг cleanup этапов 8 и 9), после которого `Record<Role, string>` перестаёт её
 * принимать: тип обязан отвечать за действующие роли и только за них, иначе форма учётки предложит
 * администратору выбрать «Штаб». А знать подпись всё равно нужно — значение никуда не делось.
 *
 * **Где оно остаётся.** Значение enum'а в Postgres не удаляется вовсе (`ALTER TYPE ... DROP VALUE`
 * не существует), и на нём держится `user_role_migration.role_before` — единственный ответ на
 * «кем человек был до перевода», по которому этап откатывается. Роль записана задним числом и в
 * `audit_log.metadata` (append-only), и в текстах отправленных писем.
 *
 * **Сегодня словарь пуст, и это правильное состояние, а не заготовка.** Пуст он ровно до релиза
 * cleanup: тогда четыре подписи переезжают сюда из `roleLabels` тем же коммитом, которым имена
 * уходят из `ROLES`. Заведён заранее затем, что вместе с ним заводится страж (`role-labels`
 * в `apps/api/test/role-migration-pending.db.test.ts`): он требует подпись **на каждое значение
 * enum'а в базе**, а не только на действующую роль, — и покраснеет на cleanup'е, забывшем перенос.
 * Появись словарь тем же релизом, что и перенос, страж проверял бы работу, сделанную минуту назад.
 *
 * Тип ключа — `string`, а не `Role`: в том и смысл, что ключи здесь — значения, которых в `Role`
 * уже нет.
 */
export const ARCHIVED_ROLE_LABELS: Readonly<Record<string, string>> = {};

/**
 * Подпись роли по значению из базы — действующей или упразднённой.
 *
 * Спрашивают этой функцией там, где роль приходит **историей**, а не выбором в форме: журнал
 * изменений учёток (ADR 0109), снимок перевода, письма. Прямой `roleLabels[role]` там ответил бы
 * `undefined` в день, когда роль упразднят, и в журнале вместо «Штаб» появилась бы пустота — в
 * записи, которую уже не переписать.
 *
 * Где роль приходит из формы и типизирована `Role`, обращение остаётся прямым: там подпись обязана
 * существовать, и `undefined` означал бы забытую строку словаря, а не историю.
 *
 * Неизвестное значение возвращается как есть, а не «—»: строка вроде `shtab` в журнале читается
 * хуже подписи, но лучше прочерка — по ней хотя бы видно, о чём речь.
 */
export function roleTitle(role: string): string {
  return roleLabels[role as Role] ?? ARCHIVED_ROLE_LABELS[role] ?? role;
}

