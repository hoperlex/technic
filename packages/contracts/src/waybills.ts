// ── На какой рейс выписывается лист (ADR 0037 п. 1, ADR 0041) ──

export interface WaybillRequirementInput {
  /** Тип заявки: лист выписывается только на грузоперевозку. */
  requestType: VehicleRequestType;
  /** Принадлежность машины: на арендную лист выписывает арендодатель. */
  ownership: VehicleOwnership;
  /** Бланк, закреплённый за типом ТС (`vehicle_types.waybill_form_code`). Пустым не бывает. */
  formCode: WaybillFormCode;
}

export interface WaybillRequirement {
  /** Бланк, по которому выписывается лист; `null` — на этот рейс лист не выписывается. */
  formCode: WaybillFormCode | null;
  /**
   * Почему не выписывается — это показывают человеку вместо отсутствующего блока. `null` при
   * пустом `formCode` означает другое: заявка такого вида путевого листа не знает вовсе, и
   * говорить не о чем — ни блока, ни объяснения (ADR 0041).
   */
  reason: string | null;
}

/** Единственная причина, по которой у рейса не бывает листа при живой заявке-грузоперевозке. */
export const RENTAL_WAYBILL_REASON = 'Путевой лист на арендную технику выписывает арендодатель';

/**
 * Нужен ли на этот рейс путевой лист.
 *
 * Отказов осталось два, и оба — не про тип техники (ADR 0065). Первый: заказ техники на объект
 * листа не знает вовсе — там нет ни рейса, ни маршрута, ни груза, и объяснять в форме нечего
 * (ADR 0041). Второй: арендную машину ведёт арендодатель, и об этом сказать надо.
 *
 * Третьего отказа — «у типа не заведён бланк» — больше не существует: у собственной техники лист
 * есть всегда, а тип отвечает лишь на вопрос, каким бланком (миграция 0094). Прежнее пустое
 * значение означало не решение, а незаполненную колонку, и молча отключало документ у каждого
 * типа, заведённого через справочник.
 */
export function waybillRequirement(input: WaybillRequirementInput): WaybillRequirement {
  if (input.requestType !== 'freight_transport') return { formCode: null, reason: null };
  if (input.ownership !== 'own') return { formCode: null, reason: RENTAL_WAYBILL_REASON };
  return { formCode: input.formCode, reason: null };
}

// ── ЭСМ-2: лист на неделю работы машины на площадке ──

/**
 * Как заявка получает недельные листы (ADR 0100 §5). Ответов три, а не два:
 *
 * - `none` — листов у заявки быть не должно вовсе: не заказ техники на объект, не в работе,
 *   архивная или арендная. Действующие аннулируются.
 * - `auto` — портал ведёт бумагу сам: заявку взяли в работу, и на каждую неделю срока рождается
 *   свой лист (ADR 0060). Так работает вся нелинейная спецтехника.
 * - `on_demand` — линейный заказ: новых недель портал не заводит, но уже выписанные ведёт.
 *
 * Третий режим появился не ради послабления. Линейная машина вечером возвращается на базу и за
 * день успевает поработать на нескольких площадках (ADR 0100): недели стояния на объекте у неё
 * нет, и выписанный наперёд недельный лист утверждал бы работу, которой не было. Кому такой лист
 * всё-таки нужен — решает человек, неделя за неделей.
 */
export const ESM2_MODES = ['none', 'auto', 'on_demand'] as const;
export type Esm2Mode = (typeof ESM2_MODES)[number];

/**
 * В каком режиме ведутся листы ЭСМ-2 этой заявки.
 *
 * Третий вход в то же семейство, что `waybillRequirement` (лист на рейс грузоперевозки) и
 * `routeWaybillForm` (лист на рейс маршрута), и правило здесь своё: бланк выбирается **путём
 * выписки**, а не справочником типов. Проставить `vehicle_types.waybill_form_code='esm2'` типам
 * спецтехники нельзя — заполненный бланк у типа `assertRouteVehicle` считает разрешением заводить
 * грузовой рейс (ADR 0057 Р13).
 *
 * Статус спрашивается наравне с видом заявки: у заявки, ушедшей из работы, действующих листов быть
 * не должно, и «сколько их нужно» — это ноль, а не «столько же, сколько было».
 *
 * Линейность спрашивается последней, и только у тех, кому листы вообще положены: у арендной
 * машины и у отменённой заявки ответ один — `none`, — и признак типа ничего в нём не меняет
 * (ADR 0100: «линейная арендная техника ничего не меняет»).
 */
export function esm2Mode(input: {
  requestType: VehicleRequestType;
  status: RequestStatus;
  ownership: VehicleOwnership | null;
  deletedAt?: string | null;
  /**
   * Линейный ли **заказанный** тип (`vehicle_types.is_linear`, миграция 0127). Именно заказанный,
   * а не тип назначенной машины: заказ решает, как заявка ведётся, ещё до того, как под неё нашли
   * единицу (ADR 0100 §1). Снимка признака в заявке нет — он читается живым из справочника.
   */
  isLinear: boolean;
}): Esm2Mode {
  if (input.requestType !== 'special_equipment') return 'none';
  if (input.status !== 'confirmed' && input.status !== 'done') return 'none';
  if (input.deletedAt) return 'none';
  // Лист на арендную технику выписывает арендодатель — тем же правилом, что и у грузоперевозки.
  if (input.ownership !== 'own') return 'none';
  return input.isLinear ? 'on_demand' : 'auto';
}

/** Неделя работы машины: то, что печатается одним бланком ЭСМ-2. */
export interface Esm2Period {
  /** Первый рабочий день недели — он же дата листа и «Период работы: с». */
  from: string;
  /** Последний рабочий день недели — «Период работы: по». */
  to: string;
}

/**
 * Срок заявки, разрезанный на недели: по листу на каждую.
 *
 * Единица бланка — календарная неделя (семь строк «пн…вс» и недельные итоги), поэтому границ,
 * режущих срок, ровно две: его начало и его конец. По границе месяца неделя **не дробится** —
 * лист остаётся одним документом, а в графе «месяца» печатаются оба номера («08–09»).
 *
 * Пустая дата окончания — однодневный срок: так её читают и отбор среза, и подписи присутствия.
 */
export function esm2Periods(dateFrom: string, dateTo: string | null): Esm2Period[] {
  const last = dateTo || dateFrom;
  if (!dateFrom || last < dateFrom) return [];
  const periods: Esm2Period[] = [];
  let from = dateFrom;
  while (from <= last) {
    const weekEnd = shiftDateKey(weekStartKey(from), 6);
    const to = weekEnd < last ? weekEnd : last;
    periods.push({ from, to });
    from = shiftDateKey(to, 1);
  }
  return periods;
}

/**
 * Семь дней недели листа — от понедельника до воскресенья, независимо от того, какой кусок недели
 * покрывает сам лист: строки «пн…вс» впечатаны в бланк, и сдвигать их нельзя. В дни вне периода
 * заявки печатается только число — графа «Наименование и адрес объекта» остаётся пустой (портал
 * не знает, работала ли машина в субботу).
 */
export function esm2WeekDays(period: Esm2Period): { date: string; inPeriod: boolean }[] {
  const monday = weekStartKey(period.from);
  return dateKeysBetween(monday, shiftDateKey(monday, 6)).map((date) => ({
    date,
    inPeriod: date >= period.from && date <= period.to,
  }));
}

/** Действующий лист ЭСМ-2 заявки — то, с чем сверяется нужный набор недель. */
export interface Esm2Sheet {
  id: string;
  periodFrom: string;
  periodTo: string;
  vehicleId: string;
  driverPersonId: string;
}

/**
 * Недели, которые человек уже попросил, — подрезанные сроком заявки (ADR 0100 §5).
 *
 * Это второй способ ответить на вопрос «какие недели должны быть выписаны», и нужен он режиму
 * `on_demand`. В `auto` набор берётся из срока (`esm2Periods`): портал сам решает, сколько бумаги
 * нужно заявке. У линейного заказа такого решения нет вовсе — недели называет человек, — и
 * единственный след его просьбы это сами выписанные листы.
 *
 * Отсюда правило подрезки, и оно ровно то же, каким срок правит бумагу в `auto`:
 *
 * - неделя, целиком выпавшая из срока (заявку сократили или сдвинули её начало), в ответ не
 *   входит: её лист аннулируется, а замены не выписывается — работы в эти дни не будет;
 * - неделя, пересечённая сроком, возвращается **подрезанной**: лист аннулируется и выписывается
 *   заново по новый последний день, потому что в графе «Период работы» напечатаны прежние даты, а
 *   правке выданный бланк строгой отчётности не подлежит.
 *
 * Расширять неделю подрезка не умеет намеренно: продлённый срок новых листов линейному заказу не
 * приносит (их не заводит и сам режим), а раздвигать границы уже выданного бланка значило бы жечь
 * номер ради дней, которых человек не просил.
 */
export function esm2RequestedPeriods(
  existing: readonly Esm2Sheet[],
  dateFrom: string,
  dateTo: string | null,
): Esm2Period[] {
  // Пустая дата окончания — однодневный срок: так её читают и `esm2Periods`, и отбор среза.
  const last = dateTo || dateFrom;
  if (!dateFrom || last < dateFrom) return [];
  // Ключом — сами границы: неделю закрывают и две машины сразу (ADR 0100 §7), и подрезка даёт им
  // один и тот же отрезок. Дважды выписывать его не надо — в ответе это одна неделя.
  const byBounds = new Map<string, Esm2Period>();
  for (const sheet of existing) {
    const from = sheet.periodFrom < dateFrom ? dateFrom : sheet.periodFrom;
    const to = sheet.periodTo > last ? last : sheet.periodTo;
    if (to < from) continue;
    byBounds.set(`${from}|${to}`, { from, to });
  }
  return [...byBounds.values()].sort((a, b) => (a.from < b.from ? -1 : a.from > b.from ? 1 : 0));
}

/** Что сделать с бумагой, чтобы она сошлась с заявкой. */
export interface Esm2SyncPlan {
  /** Листы под аннулирование: их данные разошлись с заявкой либо недели больше нет. */
  cancel: string[];
  /** Недели, на которые листа не осталось: их выписывают новыми номерами. */
  issue: Esm2Period[];
}

/**
 * Сверка «что должно быть» с «что есть» — сердце ведения ЭСМ-2 порталом.
 *
 * Выданный лист не правится никогда: бланк строгой отчётности с исправленными задним числом
 * графами — не документ. Изменить содержание можно только аннулированием номера и выпиской
 * нового. И столь же твёрдо обратное: сошлось — не трогаем. Пустые списки в ответе означают, что
 * бумага в порядке, и ни один номер не сгорит.
 *
 * Отработанные недели неприкосновенны. Лист, чей последний день уже прошёл (`canCancelWaybill`),
 * не аннулируется и не считается расхождением: машина эти дни отстояла, заказчик заполнил оборот.
 * Больше того — такой лист закрывает свою календарную неделю целиком: выписать на неё второй,
 * «правильный», значило бы выдать два документа на одну работу. Прошедшая неделя, листа не
 * имевшая, теперь тоже не выписывается сама (ADR 0101, Р21).
 *
 * Обе неприкосновенности снимаются коррекцией, и разными ключами: `unlockWaybillIds` называет
 * листы, которые правят, `correction` разрешает выписать прошедшую неделю. Оба приходят от
 * сервера, уже спросившего право и причину.
 *
 * Режим (ADR 0100 §5) меняет в этой работе ровно две вещи — набор недель приходит уже посчитанным
 * (`wanted`), а здесь остаются сверка машиниста и запрет заводить новые недели в `on_demand`.
 * Всё прочее у режимов общее: выданный лист не правится, отработанная неделя не трогается.
 */
export function esm2SyncPlan(input: {
  /** Режим ведения листов (`esm2Mode`): им отличается линейный заказ от обычного. */
  mode: Esm2Mode;
  /**
   * Недели, которые должны быть выписаны; пусто — листов быть не должно. Считает вызывающий:
   * в `auto` это срок заявки (`esm2Periods`), в `on_demand` — уже выписанное, подрезанное сроком
   * (`esm2RequestedPeriods`).
   */
  wanted: readonly Esm2Period[];
  /** Действующие листы заявки. */
  existing: readonly Esm2Sheet[];
  /** Машина, какой она стоит на заявке сейчас. */
  vehicleId: string | null;
  /**
   * Машинист, которого этим действием назвали. `null` в `on_demand` — не называли: см. сверку
   * человека ниже.
   */
  driverPersonId: string | null;
  /** Сегодня по МСК: им отделяются отработанные недели от предстоящих. */
  today: string;
  /**
   * Листы, которые коррекция назвала поимённо, — им отработанная неделя не защита (Р11, ADR 0101).
   *
   * Идентификаторами, а не понедельниками: после линейной техники действующий лист уникален по
   * `(sourceRequestId, periodFrom, vehicleId)` (ADR 0100 п. 7), то есть в одной неделе у заявки
   * законно живут листы двух машин. Понедельник как ключ разблокировал бы не тот лист или сразу
   * оба — и сжёг бы номер машины, к которой коррекция отношения не имеет.
   *
   * Список — перечень намерения, а не авторизация: право (`waybills.correct`), принадлежность
   * листа заявке и границу Р29 сервер проверяет отдельно и всегда.
   *
   * Разблокировка адресная и в другую сторону не растёт: если в той же неделе остался лист, о
   * котором не просили, неделя для выписки закрыта — названный лист аннулируется, а замены ему не
   * будет. Поэтому вызывающий перечисляет все листы недели, которую собирается переоформить, а не
   * первый попавшийся.
   */
  unlockWaybillIds?: readonly string[];
  /**
   * Контекст проверенной операции коррекции (Р21): право спрошено, причина есть, эффективная дата
   * в границе Р29. Только с ним сверка выписывает неделю, которая уже кончилась.
   *
   * Без него прошедшая неделя не выписывается вовсе — и это закрытая дыра, а не новая строгость:
   * сегодня неделя, добавленная сдвигом `dateFrom` назад, выписывается сверкой молча — без права,
   * причины и следа (§1, дыра 3). Признак приходит от сервера, который право уже спросил, а не из
   * тела запроса: тело авторизацией не является.
   */
  correction?: { allowed: true };
}): Esm2SyncPlan {
  const unlocked = new Set(input.unlockWaybillIds ?? []);
  const correcting = input.correction?.allowed === true;
  const locked = new Set<string>();
  const kept = new Set<string>();
  /** Недели, на которые лист уже выписывался: ими ограничен `on_demand`. */
  const requested = new Set<string>();
  const cancel: string[] = [];

  for (const sheet of input.existing) {
    requested.add(weekStartKey(sheet.periodFrom));
    // У ЭСМ-2 дата листа — первый рабочий день недели, а граница аннулирования — последний.
    // Названный коррекцией лист эту границу проходит: его прошедшая неделя и есть предмет правки.
    if (
      !unlocked.has(sheet.id) &&
      !canCancelWaybill({ issuedForDate: sheet.periodFrom, periodTo: sheet.periodTo }, input.today)
    ) {
      locked.add(weekStartKey(sheet.periodFrom));
      continue;
    }
    /*
     * Машинист сверяется не всегда, и это не поблажка, а разная природа графы.
     *
     * В `auto` человек один на всю заявку: его называют переводом в работу, и все недели срока
     * выписываются на него — разошёлся с заявкой, значит лист переписывается.
     *
     * В `on_demand` машиниста называют на каждую неделю отдельно (ADR 0100 §6: графа в бланке
     * одна на неделю, а водитель у линейной машины каждый день свой), и «машиниста заявки» не
     * существует вовсе. Сверять там не с чем, поэтому человек сверяется только тогда, когда его
     * назвали этим же действием: свести две недели к одному имени молча значило бы напечатать в
     * листе того, кто ту неделю не работал (ADR 0083 — портал не подставляет людей молча).
     */
    const sameDriver =
      input.mode === 'on_demand' && input.driverPersonId === null
        ? true
        : sheet.driverPersonId === input.driverPersonId;
    /*
     * Машина сверяется по той же границе, что и человек, и по той же причине.
     *
     * В `auto` машина у заявки одна: её называют переводом в работу, все недели срока выписаны на
     * неё, и разошедшийся лист переписывается — в бланке напечатан госномер, исправить его нельзя.
     *
     * В `on_demand` «машины заявки» для листа не существует: неделю на объекте закрывают две
     * разные единицы, и какая из них стоит в этом бланке, решил человек при выписке (ADR 0100
     * §7). Сверять там не с чем — сравнение с назначением сожгло бы номер, выписанный на вторую
     * машину, и перепечатало бы его на первую, то есть сделало бы ровно то, ради отмены чего
     * заведён режим. Машина заявки остаётся при этом машиной по умолчанию (ADR 0100 §4) — но это
     * про планирование дней, а не про уже выданную бумагу.
     */
    const sameVehicle = input.mode === 'on_demand' ? true : sheet.vehicleId === input.vehicleId;
    const matches =
      sameVehicle &&
      sameDriver &&
      input.wanted.some((p) => p.from === sheet.periodFrom && p.to === sheet.periodTo);
    if (matches) kept.add(sheet.periodFrom);
    else cancel.push(sheet.id);
  }

  const issue = input.wanted.filter(
    (p) =>
      !kept.has(p.from) &&
      !locked.has(weekStartKey(p.from)) &&
      /*
       * Кончившаяся неделя выписывается только проверенной операцией (Р21). Граница считается по
       * концу недели, а не по её понедельнику: тем же концом её считает `canCancelWaybill`, и
       * второй расчёт того же «когда неделя кончилась» разошёлся бы с первым на шесть дней.
       *
       * Проверка стоит рядом с `locked`, а не вместо него: `locked` защищает **выписанную**
       * отработанную неделю от второго документа на ту же работу, а это правило — прошедшую
       * неделю, листа не имевшую вовсе. Случаи разные, и снимаются они разными ключами:
       * `unlockWaybillIds` и `correction`.
       */
      (correcting || p.to >= input.today) &&
      // Своих недель `on_demand` не заводит: выписка — действие человека, и сверке остаётся лишь
      // переоформлять то, что он уже попросил. Правило стоит здесь, а не только в расчёте
      // `wanted`, потому что оно и есть определение режима: ошибись вызывающий набором — портал
      // всё равно не выпишет линейному заказу неделю, которой у него не было.
      (input.mode !== 'on_demand' || requested.has(weekStartKey(p.from))),
  );
  return { cancel, issue };
}

/** Номер бланка с ведущими нулями: «00000004897» при ширине 8 и больше. */
export function formatWaybillNumber(num: number, width: number): string {
  return String(num).padStart(width, '0');
}

/**
 * Как лист называют в журнале и в разговоре: «260604-646-00000004897». Без серии остаётся один
 * номер — префикс печатается в своей графе бланка и у новых серий пуст, пока его не задали.
 */
export function waybillDisplayNumber(prefix: string, num: number, width: number): string {
  return `${prefix}${formatWaybillNumber(num, width)}`;
}

