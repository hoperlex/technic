/**
 * Нормализации номера талона (ADR 0114, план `docs/waste-ticket-ocr-plan.md`, Р16).
 *
 * Живут в контрактах, а не в сервисе портала, по одной причине: строку талона заводят **двое**.
 * Машинную — воркер, разобрав страницу; ручную — API, когда человек вписывает бумагу сам. Оба
 * пишут `number_key`, и на этой колонке стоит ограничение уникальности. Считай их две разные
 * функции — и уникальность разъехалась бы молча: один и тот же номер, заведённый с двух сторон,
 * дал бы два разных ключа и прошёл бы мимо проверки дубля. Общего пакета у API и воркера ровно
 * один, поэтому обе функции здесь.
 */

/**
 * КОНСЕРВАТИВНАЯ нормализация — `number_key`. Регистр, пробелы, знак «№»; **дефисы и ведущие нули
 * сохраняются**. По ней стоит частичный `UNIQUE`, и агрессивное удаление дефисов склеило бы
 * `12-34` с `123-4` — то есть запретило бы заводить настоящий талон из-за чужого номера.
 */
export function wasteTicketNumberKey(raw: string): string {
  return raw.replace(/\s+/gu, '').replace(/№/gu, '').toUpperCase();
}

/**
 * Пары символов, неразличимые на бумаге и в чтении модели. Латиница выбрана канонической у букв, а
 * цифра — у пар «буква против цифры» (`О`/`0`, `З`/`3`): направление сведения не важно, важно, что
 * оно одно на все вызовы, иначе поиск похожего зависел бы от того, чей номер нормализовали первым.
 *
 * Латинская `O` рядом с кириллической `О` намеренно: типографский бланк и рукописная правка
 * приходят из разных раскладок, а на глаз это один и тот же кружок.
 */
const LOOKALIKE_CHARS: Readonly<Record<string, string>> = {
  О: '0',
  O: '0',
  А: 'A',
  З: '3',
  С: 'C',
  Р: 'P',
  Е: 'E',
  Т: 'T',
  М: 'M',
  В: 'B',
  К: 'K',
  Х: 'X',
  У: 'Y',
  Н: 'H',
};

/**
 * ПОИСКОВАЯ нормализация — `number_fuzzy`: консервативный ключ плюс сведение визуально похожих
 * знаков. По ней ищут соседей, и результат поиска **всегда предупреждение** (`similar_number`),
 * никогда не запрет: сведение `О` к `0` — догадка о том, что видел глаз, а запрещать по догадке
 * значит останавливать работу из-за собственной неуверенности.
 *
 * Дефисы и ведущие нули наследуются от ключа и тоже не трогаются: `12-34` и `123-4` не должны
 * становиться похожими даже в предупреждении — человек, которому показали ложную пару, в следующий
 * раз перестанет читать эти предупреждения вовсе.
 */
export function wasteTicketNumberFuzzy(raw: string): string {
  return [...wasteTicketNumberKey(raw)].map((ch) => LOOKALIKE_CHARS[ch] ?? ch).join('');
}
