/**
 * Чеки на автозапчасти (план `docs/auto-part-receipts-plan.md`, выпуск 1: Р1а, Р5—Р13).
 *
 * Раздел отвечает на один вопрос — «сколько вложено в эту машину», — и из него следует всё
 * остальное в файле:
 *
 * 1. **Предмет — бумажный чек, а не складская позиция** (Р7). Наименование вводится дословно,
 *    справочника нет вовсе: он потребовал бы завести номенклатуру **до** ввода чека, то есть
 *    вернул бы ровно ту работу, которую этим выпуском снимают. Цена решения названа честно —
 *    свести «фильтр масляный» из двух чеков в одну позицию портал не сможет и не обещает.
 * 2. **Итог нигде не вводится** (Р11). Сумма чека — `Σ amount` строк, и считает её сервер. Поля
 *    «итог по бумаге» нет ни в одной схеме ввода — не «необязательного», а никакого: две суммы
 *    разошлись бы в первый же день, и дальше пришлось бы в каждом отчёте решать, какая правда.
 * 3. **Машина в строке необязательна** (Р8). Пусто — «не отнесено», законное состояние: общий
 *    инструмент, расходники гаража, позиция, которую механик не стал разбирать. Поэтому у чека два
 *    итога, а сумма по машинам законно меньше суммы чека.
 * 4. **Удаление разведено на два действия и два права** (Р12). Держатель ведения ставит пометку с
 *    причиной, администратор удаляет или пометку снимает. Пометка ничего не прячет и ничего не
 *    пересчитывает — отсюда `deletion` в ответах и **версия у всех четырёх мутаций**.
 *
 * Деньги здесь — `number`, как у смет заявок и стоимости вывоза (`unitPrice`, `totalCost`):
 * `numeric` из Postgres приходит строкой, и приводит её сервер. Двух представлений денег в
 * контрактах портала быть не должно, иначе сравнение сумм зависело бы от того, чей ответ читают.
 *
 * Границы полей объявлены явно, потому что типы их не задают: `z.int()` здешнего zod (4.4.3)
 * пропускает `3_000_000_000`, а PostgreSQL `integer` — нет, и такое количество падало бы
 * пятисоткой из глубины транзакции вместо отказа с именем поля (ADR 0094).
 */

import { z } from 'zod';
import { baseListQuery, booleanFlagSchema, dateOnlySchema, PAGE_SIZES, uuidSchema } from './common';
import type { AttachedFileDto } from './files';
import { moscowDateKeyOf } from './time';

// ── Границы предмета ──
// Числа собраны здесь, а не разбросаны по схемам, потому что их знает и форма: шаг поля
// количества, `max` у суммы и предупреждение «строк больше не влезет» рисуются теми же числами,
// которыми сервер отказывает. Разъехавшись, они дали бы форму, которая пускает то, что отбивает
// маршрут.

/**
 * Потолок количества в строке. Граница не от типа, а от предмета: в чеке на запчасти не бывает ста
 * тысяч штук одной позиции, и число за пределом — опечатка, а не покупка. У `integer` в базе предел
 * втрое с лишним больше, и опереться на него было бы хуже вдвойне — и опечатка прошла бы, и
 * отказ пришёл бы именем CHECK.
 */
export const RECEIPT_MAX_QUANTITY = 100_000;

/** Потолок суммы строки, ₽ — под `numeric(14,2)` с запасом: чек на десять миллионов не чек. */
export const RECEIPT_MAX_AMOUNT = 9_999_999.99;

/**
 * Сколько строк принимает один чек. Предел про форму и ответ, а не про базу: строки правятся
 * целиком одним набором, и сотня — граница того, что человек перечитает глазами перед сохранением.
 *
 * Цена решения: чек с двумястами позиций придётся внести двумя записями. Это законно и ничего не
 * ломает — уникальности у номера чека нет вовсе (Р1а), и обе записи честно назовут один номер.
 */
export const RECEIPT_MAX_LINES = 100;

/** Сканов у чека несколько (длинный чек фотографируют в два кадра), но не двадцать один. */
export const RECEIPT_MAX_FILES = 20;

/** Отказ формы и сервера — одними словами (ADR 0094): человек читает поле, а не код ошибки. */
export const RECEIPT_FUTURE_DATE_MESSAGE = 'Дата чека не может быть в будущем';
export const RECEIPT_NO_FILES_MESSAGE = 'Прикрепите скан чека';
export const RECEIPT_NO_LINES_MESSAGE = 'Добавьте хотя бы одну строку';

// ── Ответы ──

/**
 * Пометка на удаление (Р12) — три поля одним состоянием, а не тремя необязательными.
 *
 * `null` означает «пометки нет», и по нему же карточка решает, какую кнопку показать: «Пометить к
 * удалению» или «Снять пометку». Разложенное на `requestedAt: string | null` плюс отдельная причина
 * состояние допускало бы четвёртое сочетание — «помечен, но неизвестно кем», — которого у документа
 * не бывает; в базе то же самое держат `CHECK`-парами.
 */
export interface AutoPartReceiptDeletionDto {
  requestedAt: string;
  requestedByName: string;
  reason: string;
}

/**
 * Строка чека (Р7—Р10).
 *
 * `vehicleId` пуст у «не отнесено» (Р8), и `vehicleLabel` тогда пуст тоже — пустой строкой, а не
 * `null`: портал здесь подпись **показывает**, а решает по `vehicleId`, и второе поле, по которому
 * можно решать, разъехалось бы с первым.
 *
 * Подпись приходит готовой намеренно: собери её портал из марки, модели и номера — правило
 * «как называется машина» жило бы в каждом экране заново, а окно чека и колонка гаража называли бы
 * одну машину по-разному.
 */
export interface AutoPartReceiptLineDto {
  id: string;
  /** Порядок как в чеке; сервер проставляет `index + 1` (см. схемы ввода). */
  seq: number;
  vehicleId: string | null;
  /** «Е646СК799» либо марка/тип (`vehicleLabel`); пусто — строка не отнесена к машине. */
  vehicleLabel: string;
  name: string;
  /** Целое (Р10): литры и канистры здесь считают упаковками, а объём живёт в наименовании. */
  quantity: number;
  unit: string;
  /** Сумма строки — ровно то, что напечатано в чеке справа (Р9). Ноль законен: акция, гарантия. */
  amount: number;
  /**
   * Цена за единицу — **производная** (Р9): `amount / quantity`, округлённое до копейки сервером.
   *
   * Считает её сервер, а не портал, чтобы формула жила в одном месте: карточка чека, окно машины и
   * будущее распознавание показывали бы иначе три слегка разных числа. Обратный порядок — хранить
   * цену и умножать — отвергнут даже при целом количестве: «3 × 416,67 = 1 250,01» разошлось бы с
   * бумагой на копейку в каждом разговоре о цифрах.
   */
  unitPrice: number;
  note: string;
}

/**
 * Чек целиком: карточка, форма правки и ответ на сохранение (Р11, Р12, Р13).
 *
 * Два итога, а не один: `total` — вся бумага, `unassignedTotal` — та её часть, которую не отнесли
 * к машинам. Второе число не выводится из первого и не считается порталом по строкам: сумма по
 * машинам законно меньше суммы чека (Р8), и объяснять разницу должен ответ, а не читатель.
 *
 * **Авторитетен серверный итог.** Форма считает свою цифру на глазах у вводящего, но это
 * предпросмотр: после сохранения карточка показывает пришедшую сумму, а не досчитанную.
 */
export interface AutoPartReceiptDto {
  id: string;
  /** `YYYY-MM-DD`, дата документа: по ней считаются все суммы, фильтры и периоды (Р13). */
  purchasedOn: string;
  sellerName: string;
  /** Обязателен и набран руками (Р1а); сквозного номера портала у чека нет. */
  documentNumber: string;
  note: string;
  lines: AutoPartReceiptLineDto[];
  /**
   * Сканы с именем, типом и размером (`AttachedFileDto`, тот же тип, что у скана акта ТО). Пустым
   * массив не бывает: без файла чека не существует (Р6) — и при заведении, и после любой правки.
   */
  files: AttachedFileDto[];
  /** `Σ amount` строк — считает сервер (Р11); поля «итог по бумаге» нет вовсе. */
  total: number;
  /** `Σ amount` строк без машины: «не отнесено — 1 240 ₽» в карточке (Р8). */
  unassignedTotal: number;
  /** Пометка на удаление либо `null`. Цифры чека она не меняет — только называет просьбу (Р12). */
  deletion: AutoPartReceiptDeletionDto | null;
  /** Оптимистическая блокировка: версию спрашивают все четыре мутации (Р12). */
  version: number;
  /** Служебная дата — когда чек внесли в портал; хозяйственная это `purchasedOn` (Р13). */
  createdAt: string;
  createdByName: string;
  updatedAt: string;
  /** Пусто, пока чек не правили, — как `updatedByName` у акта ТО: подпись, а не решение. */
  updatedByName: string;
}

/**
 * Строка списка чеков. Разведена с полным DTO честно, а не «полем, которое иногда пустое»: список
 * приходит страницами по сотне, и тянуть строки каждого чека ради колонки «Строк» значило бы
 * читать весь раздел, чтобы показать четыре числа.
 *
 * `vehiclesLabel` — готовая строка «Е646СК799, В120АА77 и ещё 3»: сколько имён поместится в
 * колонку, знает не список, а тот, кто её рисует, но собирать подписи машин из строк чека на
 * клиенте пришлось бы вторым запросом за строками — то есть вернуть то, ради чего тип и разведён.
 */
export interface AutoPartReceiptListItemDto {
  id: string;
  purchasedOn: string;
  sellerName: string;
  documentNumber: string;
  linesCount: number;
  total: number;
  vehiclesLabel: string;
  /** Скрепка в списке: файлов у чека всегда хотя бы один (Р6), поэтому число, а не флаг. */
  filesCount: number;
  deletion: AutoPartReceiptDeletionDto | null;
}

/**
 * Сводка вкладки: четыре числа под фильтрами списка (§7, §8).
 *
 * `deletionMarkedCount` — очередь администратора и его же уведомление: письма по пометке не
 * заводим (Р12 — разговор идёт внутри карточки), а увидеть очередь он обязан, не открывая каждый
 * чек.
 */
export interface AutoPartReceiptsSummaryDto {
  receiptsCount: number;
  total: number;
  unassignedTotal: number;
  deletionMarkedCount: number;
}

/**
 * Строка окна «Запчасти машины» (Р15): что купили этой машине и каким чеком.
 *
 * Реквизиты чека приходят вместе со строкой намеренно — окно отвечает целиком, а не заставляет
 * портал добирать шапку на каждую строку: перечень за год это полсотни запросов ради даты и номера.
 * `receiptId` ведёт в карточку чека — это и есть единственный переход из окна.
 */
export interface VehiclePartsSpendRowDto {
  receiptId: string;
  purchasedOn: string;
  sellerName: string;
  documentNumber: string;
  lineId: string;
  name: string;
  quantity: number;
  unit: string;
  amount: number;
}

/**
 * Окно «Запчасти машины» — один ответ на «что купили этой машине» (Р15). Второго перечня в портале
 * не будет: две цифры разошлись бы в первый же день.
 *
 * Итогов два, потому что вопросов два, и оба задаются одновременно — блок карточки машины (Р16)
 * показывает «За период: N ₽ · Всего: M ₽». Вторым запросом «за всё время» ответ стал бы парой
 * снимков, снятых в разные моменты, а на экране они стоят рядом и читаются как одно утверждение.
 */
export interface VehiclePartsSpendDto {
  vehicleId: string;
  vehicleLabel: string;
  /** Итог за период запроса; период задаёт окно, и по умолчанию его нет — тогда это всё время. */
  total: number;
  /** Итог за всё время, независимо от периода: вторая цифра блока карточки машины (Р16). */
  totalAllTime: number;
  rows: VehiclePartsSpendRowDto[];
}

/**
 * Колонка «Запчасти, ₽» во вкладке «Техника» (Р14) — пакетом на видимую страницу, тем же приёмом,
 * что и колонка «ТО».
 *
 * `lastPurchasedOn` — `null` там, где чеков нет вовсе: колонка рисует прочерк, а не «0 ₽». Ноль был
 * бы утверждением «на машину не тратили», а машина без чеков и машина, по которой чеков ещё не
 * завели, — одно и то же незнание.
 */
export interface VehiclePartsSpendSnapshotDto {
  vehicleId: string;
  total: number;
  receiptsCount: number;
  lastPurchasedOn: string | null;
}

// ── Ввод ──
//
// Все схемы ниже — `.strict()`, как схемы акта ТО. Это и есть механизм обещания «свой итог
// прислать нельзя» (Р11): в обычном `z.object` лишнее поле молча отбрасывается, и «нельзя»
// означало бы всего лишь «не подействует». `.strict()` отвечает 400 и называет поле.

/**
 * Версия в оптимистической блокировке (Р12). `coerce` потому, что у снятия пометки и у удаления
 * версия приходит строкой в адресе (`?version=3`) — тела у DELETE нет; тем же приёмом её принимает
 * удаление акта ТО (`maintenanceVersionQuerySchema`).
 */
const versionSchema = z.coerce.number().int().min(0);

/**
 * Дата чека: не позже сегодняшнего дня по МСК (Р13). Задним числом — законна без ограничений: чек
 * приносят через неделю, и это норма, а не исправление прошлого.
 *
 * Проверки в базе нет и не будет по той же причине, что у фактических дат механизации:
 * `CURRENT_DATE` считает день по часовому поясу сессии, а сессии приложения живут в UTC — чек,
 * внесённый в 00:30 МСК, CHECK отверг бы как будущий. Значит это правило момента записи, и считать
 * день обязан тот, кто знает деловую зону.
 */
const purchasedOnSchema = dateOnlySchema.refine(
  (value) => value <= moscowDateKeyOf(new Date()),
  RECEIPT_FUTURE_DATE_MESSAGE,
);

/**
 * Сумма строки, ₽ — `numeric(14,2)` в базе (Р9).
 *
 * `multipleOf` здесь обязателен, а не аккуратен: без него `1250.355` уехало бы в `numeric(14,2)` и
 * молча округлилось базой — портал показал бы не то, что набрали, и итог чека разошёлся бы с
 * суммой строк на копейки. Отказ должен приходить полем, а не догадкой.
 *
 * Без `coerce`, в отличие от ставки механизации: тут поле обязательное, а `z.coerce.number()`
 * превращает `null` в `0` — «сумма не указана» стало бы законной строкой «за ноль рублей». Число
 * из формы и так приходит числом, а JSON других денег не носит.
 */
export const receiptAmountSchema = z
  .number()
  .min(0, 'Сумма не может быть отрицательной')
  .max(RECEIPT_MAX_AMOUNT, 'Слишком большая сумма')
  .multipleOf(0.01, 'Не более 2 знаков после запятой');

/**
 * Количество в строке (Р10): целое, строго положительное, с потолком предмета.
 *
 * Ноль — это не строка чека, а её отсутствие: снимают её удалением из набора. Дробное отвергнуто
 * вместе с решением заказчика — при целом количестве копейки живут ровно в одном месте, в сумме
 * строки, и «сколько куплено» перестаёт зависеть от того, кто как записал единицу.
 *
 * Верхняя граница обязательна и держит не предмет, а тип: `z.int()` пропускает `3_000_000_000`
 * (это безопасное целое), а `integer` в PostgreSQL — нет, и запись падала бы пятисоткой из глубины
 * транзакции. Ста тысяч штук одной позиции в чеке не бывает — за этим числом опечатка.
 */
const quantitySchema = z
  .int('Количество — целое число')
  .min(1, 'Количество — не меньше единицы')
  .max(RECEIPT_MAX_QUANTITY, 'Проверьте количество: слишком большое число');

/**
 * Строка чека на входе (Р7—Р10).
 *
 * **`seq` здесь нет вовсе**: порядок строк задаёт сам массив, а сервер проставляет `seq = index + 1`
 * при записи. Так порядок в чеке — одно утверждение, а не два: присланный клиентом `seq` пришлось
 * бы сверять с порядком массива и решать, кто прав при расхождении, — а расходятся они на первой же
 * строке, вставленной посередине. В ответах `seq` есть: им карточка печатает нумерацию.
 *
 * `vehicleId` пуст по умолчанию (Р8): «не отнесено» — законное состояние, и требовать от формы
 * явный `null` значило бы описывать умолчание дважды. Что машина **своя** (а не арендная),
 * проверяет сервер и называет номер строки (Р21): справочник техники схеме недоступен, и подбор в
 * форме правилом не является — прямой запрос к API прошёл бы мимо него.
 *
 * Дублей машин и наименований схема не отбивает намеренно, в отличие от строк акта ТО: две строки
 * «фильтр масляный» на одну машину в чеке — обычное дело (разные цены, разные позиции у продавца),
 * и складывать их за механика значило бы переписывать бумагу.
 */
export const receiptLineInputSchema = z
  .object({
    vehicleId: uuidSchema.nullable().default(null),
    name: z.string().trim().min(1, 'Укажите наименование').max(300),
    quantity: quantitySchema,
    /**
     * Единица — текст с умолчанием «шт» (Р10). Справочника единиц нет по той же причине, что и
     * справочника наименований: он потребовал бы вести номенклатуру до ввода чека.
     */
    unit: z.string().trim().min(1, 'Укажите единицу').max(20).default('шт'),
    amount: receiptAmountSchema,
    note: z.string().trim().max(500).default(''),
  })
  .strict();
export type ReceiptLineInput = z.infer<typeof receiptLineInputSchema>;

/**
 * Набор строк чека: не меньше одной. Чек без строк — бумага, о которой портал ничего не говорит:
 * ни суммы, ни машин, ни ответа «сколько вложено», ради которого раздел и заведён.
 */
const receiptLinesSchema = z
  .array(receiptLineInputSchema)
  .min(1, RECEIPT_NO_LINES_MESSAGE)
  .max(RECEIPT_MAX_LINES, `В одном чеке не больше ${RECEIPT_MAX_LINES} строк`);

/**
 * Набор сканов: не меньше одного (Р6). Правило живёт схемой, а не проверкой в обработчике, — тогда
 * мимо него не пройдёт ни форма, ни прямой запрос к API.
 *
 * Скан — не вложение к записи, а сам предмет: без файла запись не чек, а ведомость — перепроверить
 * её не по чему, и распознаванию следующего выпуска не к чему приложиться.
 */
const receiptFileIdsSchema = z
  .array(uuidSchema)
  .min(1, RECEIPT_NO_FILES_MESSAGE)
  .max(RECEIPT_MAX_FILES, `Не больше ${RECEIPT_MAX_FILES} сканов`);

/**
 * Заведение чека целиком: шапка, строки и сканы одним телом (Р12 — форма отдаёт всё вместе).
 *
 * Поля итога тут нет вовсе — ни обязательного, ни необязательного (Р11): сумма приходит только в
 * ответах. Так контракт сам отвечает на вопрос «а можно ли прислать свой итог» — нельзя, и это
 * видно без чтения обработчика.
 *
 * Продавец необязателен, а номер обязателен, и это не непоследовательность (Р1а): номер есть у
 * каждого чека, а название магазина на ленте бывает нечитаемо. Уникальности у номера нет — его
 * выдаёт продавец, и два чека «0001» из разных магазинов обычное дело.
 */
export const createReceiptSchema = z
  .object({
    purchasedOn: purchasedOnSchema,
    sellerName: z.string().trim().max(200).default(''),
    documentNumber: z.string().trim().min(1, 'Номер чека обязателен').max(100),
    note: z.string().trim().max(1000).default(''),
    fileIds: receiptFileIdsSchema,
    lines: receiptLinesSchema,
  })
  .strict();
export type CreateReceiptInput = z.infer<typeof createReceiptSchema>;
/** Тело со стороны портала: поля с умолчанием в нём необязательны (продавец, примечание). */
export type CreateReceiptBody = z.input<typeof createReceiptSchema>;

/**
 * Правка — те же поля плюс версия, которую видел правящий (Р12). Версия в теле, а не в адресе:
 * PATCH и так идёт телом, и разносить два обязательных значения по разным местам незачем.
 *
 * Строки и сканы здесь **обязательны так же, как при заведении**, и умолчания у них нет ни у
 * одного — в отличие от строк акта ТО, где «поля нет» означает «не трогать». Разница в предмете:
 * там правка реквизитов не должна была двигать склад, здесь же правка — это переписанный документ
 * целиком, и «файлы не прислали» означало бы чек без бумаги ровно с той же вероятностью, что и
 * «прислали пустой список». Отсюда же правило Р6 на правке: снять последний скан нельзя, и отказ
 * приходит схемой, а не разметкой кнопки.
 *
 * Пометку на удаление правка не трогает вовсе (Р12, §2.3): её поля в теле нет, и снимают её
 * отдельной ручкой — очередь администратора не должна опустошаться заодно с исправлением опечатки.
 */
export const updateReceiptSchema = createReceiptSchema.extend({ version: versionSchema });
export type UpdateReceiptInput = z.infer<typeof updateReceiptSchema>;
export type UpdateReceiptBody = z.input<typeof updateReceiptSchema>;

/**
 * Пометка на удаление (Р12): причина и версия.
 *
 * Причина обязательна и хранится в самой записи: пометка — просьба к администратору, и «предлагаю
 * удалить, а зачем не скажу» это не просьба, а загадка. То же требует пара `CHECK` в базе: причина
 * есть ровно у помеченного.
 *
 * Версия — потому что пометить чек, который тем временем переписали, это то же расхождение, что и
 * правка: помечают прочитанный документ, а не строку в таблице.
 */
export const receiptDeletionMarkSchema = z
  .object({
    reason: z.string().trim().min(1, 'Укажите причину').max(1000, 'Слишком длинная причина'),
    version: versionSchema,
  })
  .strict();
export type ReceiptDeletionMarkInput = z.infer<typeof receiptDeletionMarkSchema>;

/**
 * `?version=` для снятия пометки и удаления — по образцу `maintenanceVersionQuerySchema` (Р12):
 * тела у DELETE нет, а снимать чужую пометку и удалять чужую правку вслепую нельзя.
 *
 * Снятие пометки без версии позволило бы снять пометку, поставленную уже после того, как экран был
 * открыт, — то есть ответить не на ту просьбу.
 */
export const receiptVersionQuerySchema = z.object({ version: versionSchema }).strict();
export type ReceiptVersionQuery = z.infer<typeof receiptVersionQuerySchema>;

// ── Запросы чтения ──

/**
 * Отбор ленты чеков — один и тот же у списка и у сводки под ним (§8): сводка отвечает про то, что
 * видно, иначе «Сумма» над отфильтрованным списком называла бы чужое число.
 *
 * Период — по **дате чека** (Р13): хозяйственный вопрос «сколько потратили в августе» задаётся
 * бумагой, а не днём, когда её внесли в портал. Обе границы необязательны: «за всё время» —
 * законный вопрос к разделу, который только что завели.
 *
 * `deletionMarked` — три состояния, а не флаг (`booleanFlagSchema`): параметра нет — «не
 * фильтровать», `true` — очередь администратора, `false` — всё остальное. Снятый переключатель и
 * выбранное «нет» отвечают на разные вопросы.
 */
const receiptFilterShape = {
  from: dateOnlySchema.optional(),
  to: dateOnlySchema.optional(),
  /** Чеки, в которых есть строка на эту машину; сам чек при этом остаётся целым. */
  vehicleId: uuidSchema.optional(),
  deletionMarked: booleanFlagSchema,
  /** Продавец, номер чека и наименование строки — три места, где ищут одну и ту же покупку. */
  search: z.string().trim().max(200).optional(),
};

/** Порядок границ периода — одинаково у ленты и у окна машины. */
function checkPeriodOrder(
  v: { from?: string | undefined; to?: string | undefined },
  ctx: z.RefinementCtx,
): void {
  if (v.from && v.to && v.to < v.from) {
    ctx.addIssue({ code: 'custom', message: 'Конец периода раньше начала', path: ['to'] });
  }
}

/**
 * Поля сортировки — только реквизиты шапки. Итога среди них нет намеренно: он складывается из
 * строк, и «самые дорогие чеки» это вопрос не к ленте документов, а к отчёту, которого этот выпуск
 * не заводит (§12). Умолчание задаёт сервер порядком индекса `(purchased_on, created_at, id)`:
 * две покупки одного дня ключом даты неразличимы, и «последний чек» зависел бы от порядка чтения.
 */
export const AUTO_PART_RECEIPT_SORT_FIELDS = [
  'purchasedOn',
  'sellerName',
  'documentNumber',
  'createdAt',
] as const;

export const autoPartReceiptListQuerySchema = baseListQuery(AUTO_PART_RECEIPT_SORT_FIELDS)
  .extend(receiptFilterShape)
  .strict()
  .superRefine(checkPeriodOrder);
export type AutoPartReceiptListQuery = z.infer<typeof autoPartReceiptListQuerySchema>;

/** Сводка вкладки: тот же отбор без страниц и сортировки — считают по всему отобранному. */
export const autoPartReceiptSummaryQuerySchema = z
  .object(receiptFilterShape)
  .strict()
  .superRefine(checkPeriodOrder);
export type AutoPartReceiptSummaryQuery = z.infer<typeof autoPartReceiptSummaryQuerySchema>;

/** Окно «Запчасти машины» (Р15): период необязателен — без него окно показывает всё время. */
export const vehiclePartsSpendQuerySchema = z
  .object({ from: dateOnlySchema.optional(), to: dateOnlySchema.optional() })
  .strict()
  .superRefine(checkPeriodOrder);
export type VehiclePartsSpendQuery = z.infer<typeof vehiclePartsSpendQuerySchema>;

/**
 * Машины пакетного запроса — строкой через запятую, тем же приёмом, что снапшот ТО: повтор
 * `ids=a&ids=b` Fastify разбирает в массив, только пока значений больше одного, и на единственной
 * машине схема получила бы строку.
 *
 * Копия, а не импорт, и это осознанно: у снапшота ТО разбор объявлен приватно, а
 * `vehicle-maintenance.ts` этим выпуском не правится ни одной строкой (§6, Р22) — вынос общего
 * куска туда сделал бы файл замороженного контура зависимостью нового.
 *
 * Потолок — размер страницы портала: снапшот заполняет колонку «Запчасти, ₽» видимой страницы
 * гаража, и списка длиннее неё у него не бывает. Пустое значение законно («на странице нет ни одной
 * машины») и отвечает пустым списком, а не отказом.
 */
const vehicleIdsSchema = z
  .string()
  // 40 символов на UUID с разделителем — с запасом на пробелы вокруг запятой.
  .max(Math.max(...PAGE_SIZES) * 40)
  .transform((v) =>
    v
      .split(',')
      .map((s) => s.trim())
      .filter((s) => s !== ''),
  )
  .pipe(z.array(uuidSchema).max(Math.max(...PAGE_SIZES)));

/**
 * Суммы пакетом на страницу гаража (Р14). `to` — день среза: в сумму идут чеки **не позже** него.
 * Срез марта, показавший августовскую покупку, отвечал бы не на тот вопрос, который задали
 * календарём наверху. Умолчание считает сервер — сегодняшний московский день, как в гараже: часы
 * браузера бывают сбиты, а восточнее Москвы сутки начинаются раньше.
 */
export const vehiclePartsSpendSnapshotQuerySchema = z
  .object({ to: dateOnlySchema.optional(), ids: vehicleIdsSchema })
  .strict();
export type VehiclePartsSpendSnapshotQuery = z.infer<typeof vehiclePartsSpendSnapshotQuerySchema>;
