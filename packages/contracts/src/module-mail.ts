// ── Рубильник события (план `office-equipment-mail-expansion-plan.md`, §5.1) ──
//
// Строки выше отвечают на вопрос «кому уходит копия», строка рубильника — на вопрос «уходит ли
// письмо вообще». Реестр событий закрыт кодом, а включённость события — настройка эксплуатации, и
// нужна она трижды: раздел портала ещё закрыт заплаткой, а API открыт (письма пойдут раньше, чем
// люди увидят модуль); события включают по одному и смотрят, что приходит; аварийное отключение
// зашумевшего события не должно стоить отката релиза.
//
// Строка заводится миграцией на каждое событие реестра. Отсутствие строки трактуется fail-closed —
// как выключенное событие: событие, о котором база не знает, не может начать слать письма наружу
// оттого, что кто-то забыл наполнить настройку.

export interface ModuleMailEventSettingDto {
  event: ModuleMailEvent;
  isEnabled: boolean;
  version: number;
  /**
   * Когда рубильником щёлкали последний раз; `null` — строки настройки в базе **нет вовсе**.
   *
   * Это не то же самое, что «ни разу не правили»: событие без строки сервер трактует fail-closed,
   * как выключенное, и в список оно приходит выключенным, чтобы реестр событий и настройка не
   * расходились молча. Отдельное значение здесь нужно порталу для честной подписи: пустая дата под
   * заведённой строкой читалась бы как «настроено и выключено руками», тогда как включать тут
   * нечего — строки нет, и заводит её миграция вместе с событием.
   */
  updatedAt: string | null;
  /**
   * Кто щёлкал рубильником последним; `null` — учётки уже нет либо строки настройки не существует.
   * Тишина по событию не бывает ничьей.
   */
  updatedByName: string | null;
}

/**
 * Правка рубильника. События в теле нет — оно и есть ключ строки, а «перенести включённость» на
 * другое событие означает щёлкнуть двумя рубильниками, и каждый щелчок обязан остаться в аудите
 * своей строкой.
 *
 * Умолчаний нет по той же причине, что у `updateModuleMailRecipientSchema`: `isEnabled` со
 * значением по умолчанию означал бы, что запрос **без** этого поля включает рассылку наружу, —
 * недостающее поле здесь это 400, а не догадка сервера. `version` обязателен, потому что
 * одновременная правка двумя администраторами не должна тихо победить: проигравший узнал бы о
 * своём щелчке по письмам, которых не ждал.
 */
export const updateModuleMailEventSettingSchema = z.object({
  isEnabled: z.boolean(),
  version: z.number().int().nonnegative(),
});
export type UpdateModuleMailEventSettingInput = z.infer<typeof updateModuleMailEventSettingSchema>;
export type UpdateModuleMailEventSettingBody = z.input<typeof updateModuleMailEventSettingSchema>;

/**
 * Исход почтовой части операции. Продолжает `MAIL_OUTCOMES` (ADR 0087), и все значения, кроме
 * первого, означают одно: «операция удалась, письма нет». Заявка не должна падать из-за почтовой
 * настройки или из-за того, что тело письма не собралось.
 *
 * У писем **службе** исхода «адресаты не настроены» нет: основной получатель известен и без
 * настройки — это ящик самого канала, а строки таблицы задают лишь копии (Р91). Молчание портала
 * там объясняется либо выключенной почтой, либо ненастроенным каналом, и оба ответа — про `env`, а
 * не про базу.
 *
 * `no_recipients` заведён ради **письма о назначении** и только ради него: оно адресовано
 * исполнителю, а не ящику канала, и адресатов у него может не оказаться совсем — заявку отдали
 * сервисной компании, у которой в портале нет ни одной учётки оператора **и** пуст ящик в карточке
 * контрагента (ADR 0153). Слать такое письмо в ящик службы было бы подменой адресата: служба и так
 * назначила, а исполнитель задания не увидит. Молчать при этом молча нельзя — назначивший обязан
 * узнать, что задание никуда не ушло, и позвонить.
 *
 * `not_needed` — **третье состояние рядом с «ушло» и «не дошло»**: письма нет, и это правильно.
 * Так заканчивается правка состава, которая никого не назначила: у заявки сняли сервисную компанию,
 * оставив прежнего исполнителя, либо её вернули из «В работе» тем же составом. Адресатов у задания
 * нет не потому, что ящик не заведён, а потому, что задания не было, — и `no_recipients` тут звал
 * бы заводить адрес там, где он ни при чём. Портал по этому исходу молчит, как по `queued`: пугать
 * человека нечем.
 *
 * `mail_failed` — не тихая ветка: он уходит в лог и в аудит **после** фиксации транзакции, потому
 * что аудит пишется мимо неё и при откате остался бы записью о событии, которого не было.
 *
 * `event_off` — рубильник события выключен (`module_mail_event_settings`, §5.1 плана расширения
 * почты). Приоритет у него **первый**: строка читается сразу после блокировки заявки, до сборки
 * адресатов, — если писать не велено, состояние адресов к делу не относится, и `no_recipients`
 * звал бы заводить ящик там, где его никто не спрашивал. Портал по этому исходу молчит, как по
 * `queued` и `not_needed`: выключенное событие — осознанная настройка, а не беда, о которой надо
 * сообщать нажавшему кнопку. Аудит его пишет: «письма не было и почему» — вопрос, который задают
 * через месяц.
 */
