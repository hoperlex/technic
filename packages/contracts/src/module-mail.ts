/**
 * Исходы **отдельных целей** события (§5.10 плана расширения почты). Общий `mail` отвечает за
 * событие целиком и считается по обязательным целям, а здесь виден разбор: письмо ушло в ящик
 * службы, но у сервисной компании нет ни одного адреса — общий исход `no_recipients`, и относится
 * он ко второй цели, а не к первой. Без разбора человек читал бы «некому отправить» под письмом,
 * которое частью адресатов получено.
 *
 * Поле ответов ручек необязательное и добавляется аддитивно: клиент прошлой волны лишнее поле
 * игнорирует, а общего исхода `partial` ради этого не заводится — он сломал бы разбор `mail` у
 * тех, кто уже обновился. Ключи необязательны каждый: у события есть ровно те цели, которые
 * положены ему по матрице (§ 3), и отсутствие ключа означает «такой цели у события не было», а не
 * «результат неизвестен». `copies` — цель необязательная и на общий исход не влияет никогда.
 */
export interface ServiceMailTargets {
  /** Отзыв задания прежней компании: своё обязательство письма о назначении, своя ячейка. */
  withdrawal?: ModuleMailOutcome;
  /** Ящик канала службы. */
  office?: ModuleMailOutcome;
  /** Сервисная компания целиком: живые операторы, общий ящик карточки, поимённые исполнители. */
  service?: ModuleMailOutcome;
  /** Поимённо адресованная учётка — реплика конкретному исполнителю. */
  user?: ModuleMailOutcome;
  /** Включённые строки `module_mail_recipients` этого события. */
  copies?: ModuleMailOutcome;
}
