import { z } from 'zod';
import { dateOnlySchema } from './common';
import type { RoutePointAction } from './route-points';

/**
 * Кабинет водителя (ADR 0102): задание работника на дату и передача показаний.
 *
 * Второй контур портала. Учётка роли `driver` не имеет ни одного права основного портала —
 * включая `directories.read`, который есть у всех остальных ролей, — и отсюда главное свойство
 * этих типов: **все подписи приходят готовыми**. Идентификаторов типов ТС, контрагентов и
 * объектов кабинет не знает и знать не должен; он рисует строки, собранные сервером.
 *
 * Второе свойство, столь же существенное: **`personId` в запросах кабинета не встречается**.
 * Область видимости роли — четвёртая ось «свой человек», и она держится не предикатом, а
 * отсутствием параметра: сервер берёт человека из принципала, и проверять нечего.
 */

// ── Окна дат ──

/**
 * Чтение задания шире записи показаний, и это не удобство, а граница области: без верхней
 * границы кабинет становится выгрузкой всей истории поездок человека, а планы на месяц вперёд
 * водителю показывать незачем — их ещё правят.
 */
export const DRIVER_ASSIGNMENT_PAST_DAYS = 30;
export const DRIVER_ASSIGNMENT_FUTURE_DAYS = 14;

/**
 * Окно записи — восемь дней, считая сегодняшний: столько нужно, чтобы закрыть всю прошедшую
 * неделю самому («в пятницу вспомнил, что не сдавал с понедельника»). Будущее закрыто вовсе:
 * показание счётчика, которого ещё не сняли, — это не данные.
 */
export const DRIVER_SUBMIT_PAST_DAYS = 7;

/** Персонал вносит показания за водителя в пределах окна чтения прошлого (ADR 0103). */
export const STAFF_SUBMIT_PAST_DAYS = DRIVER_ASSIGNMENT_PAST_DAYS;

// ── Формат локального черновика ──

/**
 * Чем кабинет объявляет серверу формат своего черновика (ADR 0129, решение 8). Заголовком, а не
 * полем тела: объявляет его сама сборка портала, а не человек за рулём, и телу запроса на открытие
 * отчёта принадлежать ему нечем — тела у ручки нет вовсе.
 *
 * Имя в нижнем регистре намеренно: заголовки Fastify отдаёт приведёнными, и сравнение по этому же
 * ключу читает то, что пришло, без лишнего приведения на каждом запросе.
 */
export const DRIVER_DRAFT_FORMAT_HEADER = 'x-driver-draft-format';

/**
 * Формат черновика, с которым работает нынешний кабинет: ключи записей — по источнику выезда, а не
 * по строке ожидания (Р11). Значение здесь одно и сравнивается точно: «неизвестный формат» — это и
 * старая сборка, которая ещё пишет `v1`, и будущая, о которой этот сервер ничего не знает; пускать
 * писать черновик ни ту, ни другую нельзя.
 */
export const DRIVER_DRAFT_FORMAT = 'v2';

/**
 * Код отказа «сборка портала устарела» (Р13). Отдельным кодом, а не текстом: новая сборка по нему
 * предлагает обновление кнопкой, а `version_conflict` она показывает как «откройте заново» — два
 * разных исхода на один код различить было бы нечем.
 *
 * Читать отказ будет как раз та сборка, которая этого кода не знает, — поэтому весь смысл обязан
 * нести текст сообщения, а не код (`apps/api/src/routes/driver.ts`).
 */
export const DRIVER_CLIENT_OUTDATED_CODE = 'client_outdated';

// ── Состав задания ──

/**
 * Чем задан выезд: рейсом или недельным листом ЭСМ-2. Третьего не бывает — у 4-П и формы № 3
 * источник сам ссылается на рейс (`waybills_form_source_check`), и лист таких форм отдельной
 * карточки не даёт: его выезд уже представлен рейсом.
 */
export const READING_SOURCE_KINDS = ['route', 'esm2'] as const;
export type ReadingSourceKind = (typeof READING_SOURCE_KINDS)[number];
export const readingSourceKindSchema = z.enum(READING_SOURCE_KINDS);

/** Контакт остановки: кому на ней звонить. Метки роли у него нет — см. `DriverAssignmentPoint`. */
export interface DriverAssignmentContact {
  name: string;
  phone: string;
}

/**
 * Что машина делает на остановке: грузит чью-то ездку, выгружает её или работает линейный день
 * (план `docs/route-trips-plan.md`, Р5, Р5а).
 *
 * Роль приходит **и** словом, и разметкой, и оба поля нужны: слово печатает письмо, а разметку
 * читает кабинет, когда рисует погрузку иначе, чем разгрузку. Собирает подпись сервер — тем же
 * сборщиком, что кормит оба канала (`services/driver-assignment.ts`): собери её каждый у себя, и
 * водитель, прочитавший письмо с вечера, нашёл бы утром в кабинете другие слова.
 */
export interface DriverAssignmentAction {
  role: RoutePointAction['role'];
  /** Готовая подпись роли: «Грузим», «Выгружаем», «Работа на объекте». */
  roleLabel: string;
  /** «ТС-40/2» — заявка и её ездка; у линейного дня «ТС-77 · 12.08». */
  displayNumber: string;
  customerName: string;
  /** «12 м³» либо «8 т»; у линейного дня пусто — количества у него нет, есть характер работ. */
  cargoLabel: string;
  /**
   * Комментарий **строки** рядом с её ролью: у ездки её собственное примечание, у линейного дня —
   * комментарий заявки, тот самый характер работ, что печатается в графе груза (ADR 0100 §10).
   *
   * Здесь он есть всегда, даже когда бланк его выбросил: в бумаге комментарий отбрасывается первым
   * при нехватке места (Р11а), и не покажи его письмо с кабинетом, «звонить за час до выезда» не
   * доехало бы до водителя нигде. Ценой свёртывания в бланке оплачено ровно это (§8 плана).
   */
  comment: string;
}

/**
 * Одна остановка в порядке объезда: адрес, время, что здесь делают и кто встречает.
 *
 * Блок на **точку**, а не на заявку: у заявки с ездками `A→B` и `A→C` «адреса разгрузки» не
 * существует, а два заезда в один карьер — это одна остановка, а не две (Р4, Р5). Порядок тот же,
 * что в карточке маршрута, — по позициям точек, и разойтись каналам негде: оба читают один сборщик.
 *
 * Свёрнутого здесь нет. Всё, что бланк спрятал в «+N» или обрезал многоточием по ширине графы
 * (Р11а), письмо и кабинет показывают целиком: ширины графы у них нет, а цена свёртывания в бумаге
 * — обещание, что полный текст водитель получит другим каналом (§8 плана).
 */
export interface DriverAssignmentPoint {
  /** Место в порядке объезда, 1..N: им остановки и пронумерованы в письме и в кабинете. */
  position: number;
  location: string;
  /**
   * Время прибытия «08:30» либо пусто. Своё у точки, а нет его — час подачи заявки, которую здесь
   * грузят: время остановки диспетчер задаёт не всегда, а бэкфил маршрутов, собранных до релиза,
   * не задал его ни у одной (§5.6 плана). Без запасного хода водитель разом потерял бы час подачи,
   * который получает сегодня.
   */
  arrivalTime: string;
  /** Что здесь происходит — в том порядке, в каком на этой остановке работают. */
  actions: DriverAssignmentAction[];
  /**
   * **Все**, кто встречает машину на этой остановке (Р9, Р11а): контакты её ролей без повторов.
   * Двое и больше — остановку совместили вручную, и звонить надо обоим.
   */
  contacts: DriverAssignmentContact[];
  /** Записка диспетчера про эту остановку: «пропуск у весовщика», «звонить с ворот». */
  comment: string;
}

/**
 * Строка задания — она же будущая строка ожидания показаний (`itemId`, ADR 0103).
 *
 * `itemId` появляется только после открытия отчёта (`POST /driver/reports/:date/open`): до этого
 * строка описывает задание, но записывать в неё нечего.
 */
export interface DriverAssignmentEntry {
  sourceKind: ReadingSourceKind;
  /** Идентификатор источника: рейса или листа. Нужен серверу, портал им ничего не решает. */
  sourceId: string;
  /** `Р-142` у рейса, `4-П № 000123` у листа — подпись, готовая к показу. */
  sourceLabel: string;
  /** Зачем этот выезд: «Грузоперевозка», «Перегон техники», «Работа на объекте». */
  purposeLabel: string;
  vehicleLabel: string;
  garageNumber: string;
  trailerLabel: string;
  /** Строка ожидания показаний, если отчёт дня уже открыт. */
  itemId: string | null;
  /** Позиция смены в дне машины (ADR 0103): по ней идёт порядок показаний. */
  shiftOrder: number | null;
  /**
   * Порядок объезда рейса: остановки по позициям точек (Р4, §8 плана). У перегона и у недельного
   * листа пуст — точек им не заводится: перегон везёт сам себя («откуда/куда»), а лист накрывает
   * неделю работы на одной площадке.
   */
  points: DriverAssignmentPoint[];
  /** Перегон: откуда и куда едет техника. */
  moveFrom: string;
  moveTo: string;
  /** Комментарий диспетчера — то, что он написал водителю, а не заказчику. */
  comment: string;
  /**
   * Предыдущий снимок счётчиков этой машины. `null` — начало ряда: показаний по машине ещё не
   * сдавали, и сравнивать не с чем.
   *
   * Едет в задание ради подписи под полем и предупреждений во время ввода: водитель сверяет два
   * числа глазами ДО отправки, а не узнаёт об аномалии из ответа сервера. Аномалии при этом
   * никуда не деваются — сервер по-прежнему решает сам (ADR 0103, Р20); здесь подсказка, а не
   * второе правило.
   */
  previous: DriverPreviousReading | null;
}

/** Снимок счётчиков, с которым водитель сверяет свой ввод. */
export interface DriverPreviousReading {
  odometerKm: number | null;
  engineHours: number | null;
  /** День, за который сняли предыдущее показание: «предыдущее: 145 320 (10.08)». */
  measuredOn: string;
  /** Сколько суток прошло — по нему масштабируется порог невероятного прироста. */
  daysAgo: number;
}

/** Задание работника на дату. Пустой список — законное состояние экрана. */
export interface DriverAssignmentDto {
  date: string;
  /** Можно ли передавать показания за этот день (окно записи). */
  canSubmit: boolean;
  entries: DriverAssignmentEntry[];
}

export const driverAssignmentQuerySchema = z.object({ date: dateOnlySchema.optional() }).strict();
export type DriverAssignmentQuery = z.infer<typeof driverAssignmentQuerySchema>;
