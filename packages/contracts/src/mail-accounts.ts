// ── Почтовые каналы портала (план `office-equipment-mail-and-history-plan.md`, Р83–Р87) ──
//
// Канал — именованный набор настроек отправки: сервер, порт, защита, учётка, отправитель и потолок
// писем в минуту. До появления реестра контур был одноканальным: один SMTP из `env` на весь
// процесс, один `MAIL_FROM` на весь портал.
//
// Второй канал понадобился не ради разнообразия. У службы, которая ведёт ремонт оргтехники,
// собственный ящик на собственном сервере компании, и отправить письмо «от его имени» через
// транзакционного провайдера нельзя: почтовые службы отвергают чужой `From`, а SPF и DKIM домена
// подписывает его сервер, а не провайдерский.
//
// Ключ канала живёт здесь, а не в `env`, потому что на него ссылается письмо: письмо знает, каким
// каналом уходить, а воркер только исполняет. Опечатка в имени обязана ломаться при сборке — иначе
// она обнаружится письмом, которое никуда не ушло.

/**
 * Ключи каналов. `default` — то, чем портал шлёт всё остальное (задания водителям, сводки, письма
 * про доступ); он же достаётся письмам, заведённым до появления каналов.
 */
export const MAIL_ACCOUNTS = ['default', 'repair'] as const;
export type MailAccount = (typeof MAIL_ACCOUNTS)[number];

export const DEFAULT_MAIL_ACCOUNT: MailAccount = 'default';

export const mailAccountLabels: Record<MailAccount, string> = {
  default: 'Основной канал портала',
  repair: 'Ящик службы ремонта',
};

/**
 * Чем канал занят — подпись под выбором в отладочной отправке. Реестр закрыт `Record`: новый канал
 * обязан ответить, зачем он заведён, иначе в списке появится строка, про которую администратор не
 * знает, что через неё уходит.
 */
export const mailAccountHints: Record<MailAccount, string> = {
  default:
    'Задания водителям, сводки по ролям и письма про доступ. Настроен переменными SMTP_* и MAIL_FROM.',
  repair:
    'Письма модуля «Орг.техника» службе ремонта: уходят с её ящика и ей же адресованы. ' +
    'Настроен переменными MAIL_ACCOUNT_REPAIR_*.',
};

/**
 * Префикс переменных окружения канала: `MAIL_ACCOUNT_REPAIR_HOST` и далее. У `default` префикса нет
 * — он читается из прежних `SMTP_*` и `MAIL_FROM`, и переименовывать их ради единообразия нельзя:
 * выкат не должен требовать переписывания рабочего `prod.env`, а «переименуем заодно» — это ночная
 * рассылка, которая не ушла.
 */
export function mailAccountEnvPrefix(account: MailAccount): string | null {
  return account === 'default' ? null : `MAIL_ACCOUNT_${account.toUpperCase()}`;
}

/**
 * Методы аутентификации SMTP. `CRAM-MD5` — это и есть «зашифрованный пароль» в терминах почтовых
 * клиентов; `LOGIN` — обычный пароль поверх TLS, и он же умолчание.
 *
 * Перечень нужен именно списком: имя метода уходит в nodemailer как есть, и опечатка в `env`
 * обернулась бы отказом аутентификации на первом письме, а не понятной ошибкой старта.
 */
export const SMTP_AUTH_METHODS = ['LOGIN', 'PLAIN', 'CRAM-MD5'] as const;
export type SmtpAuthMethod = (typeof SMTP_AUTH_METHODS)[number];

export const DEFAULT_SMTP_AUTH_METHOD: SmtpAuthMethod = 'LOGIN';

/** Канал, доступный отладочной отправке: настроен ли он на сервере и чем занят. */
export interface MailAccountStatusDto {
  account: MailAccount;
  /** Настроен ли канал в `env` этого сервера. Ненастроенный показывается, но выбрать его нельзя. */
  configured: boolean;
  /** Отправитель канала — по нему видно, от кого придёт письмо; пусто у ненастроенного. */
  from: string;
}
