import { z } from 'zod';
import { baseListQuery, uuidSchema } from './common';

// ── Плановая закупка расходников (ADR 0146, план
// `docs/office-equipment-consumables-and-purchase-plan.md`: Р9–Р13, Р15–Р18) ──
//
// САМОСТОЯТЕЛЬНЫЙ ДОКУМЕНТ, А НЕ ВИД ЗАЯВКИ (Р9), и это главное, что надо знать про этот файл.
// Довод ADR 0133 об одной таблице заявок был конкретен: «та же техника, та же область видимости, та
// же история, те же письма». У закупки нет первых двух: остаток расходников один на компанию
// (граница ADR 0132), значит потребность, дефицит и заказ по дефициту глобальны — ни площадки, ни
// отдела у такого документа не бывает. Отсюда и то, чего у неё НЕТ и чего в этом файле искать не
// надо: вложений, обсуждения, срочности, заморозки, писем, ФИО и телефона заявителя, области
// видимости. Видна она по праву `officeEquipmentPurchases.manage`, и только по нему.
//
// ОСТАТОК ОНА НЕ ДВИГАЕТ (Р11, решение заказчика на альфу): закупка — бумага для снабжения, приход
// заводится ручной правкой остатка. Порядок «сначала приход, потом закрытие» держится галочкой в
// форме закрытия и записан принятым операционным риском, а не инвариантом: текущий остаток не
// доказывает, что приход именно по ЭТОЙ закупке, — между открытием и закрытием были выдачи,
// корректировки и, возможно, соседняя закупка.

/**
 * Четыре состояния (Р10): «Новая» → «В работе» (бумага у снабжения) → «Закрыта»; из первых двух —
 * «Отменена» с обязательной причиной. Закрытая и отменённая конечные: ошибку исправляют новой
 * закупкой, а не переписыванием прошлой.
 *
 * Перечнем в контрактах, а не тремя строками по месту: те же слова стоят в `CHECK` базы
 * (`office_equipment_purchases_status_check`), и второй список разошёлся бы с ним молча.
 */
export const OFFICE_EQUIPMENT_PURCHASE_STATUSES = [
  'new',
  'in_work',
  'closed',
  'cancelled',
] as const;
export type OfficeEquipmentPurchaseStatus = (typeof OFFICE_EQUIPMENT_PURCHASE_STATUSES)[number];

export const officeEquipmentPurchaseStatusLabels: Record<OfficeEquipmentPurchaseStatus, string> = {
  new: 'Новая',
  in_work: 'В работе',
  closed: 'Закрыта',
  cancelled: 'Отменена',
};

/**
 * Какие закупки считаются ОТКРЫТЫМИ — то есть вычитаются из дефицита (Р15).
 *
 * ЭТОТ ПЕРЕЧЕНЬ — УСЛОВИЕ РАБОТОСПОСОБНОСТИ ЗАПРОСА, а не удобство чтения. Частичный индекс
 * `office_equipment_purchases_open_idx` построен ровно по `status IN ('new', 'in_work')`, и
 * планировщик применяет его, только доказав, что предикат запроса ВЛЕЧЁТ предикат индекса.
 * Записанное иначе — `status <> 'closed' AND status <> 'cancelled'` — той же проверки не проходит:
 * ответ вышел бы верным, а план — seq scan по всему архиву закупок. Поэтому во всех запросах
 * условие пишется этим `IN`-списком и только им.
 */
export const OFFICE_EQUIPMENT_PURCHASE_OPEN_STATUSES = [
  'new',
  'in_work',
] as const satisfies readonly OfficeEquipmentPurchaseStatus[];

/** Префикс сквозного номера: «СО-» у заявки на обслуживание, «ЗК-» у плановой закупки. */
export const OFFICE_EQUIPMENT_PURCHASE_NUMBER_PREFIX = 'ЗК-';

/**
 * Номер в том виде, в каком его показывают людям и называют в отказах («ЗК-14»).
 *
 * Собирает его сервер, а не клиент: тот же номер уезжает в текст отказа при гашении позиции с
 * открытой закупкой (Р18) и в аудит, и склеенный на двух сторонах по-своему, он разошёлся бы на
 * первой же смене префикса — а спор со снабжением разбирают именно по номеру.
 */
export function formatOfficeEquipmentPurchaseNumber(num: number): string {
  return `${OFFICE_EQUIPMENT_PURCHASE_NUMBER_PREFIX}${num}`;
}

/**
 * Поля сортировки списка. Номер и время заведения — по сути одно и то же (номер раздаёт база
 * возрастанием), но спрашивают их по-разному: «покажи свежие» и «найди ЗК-14 рядом с ЗК-15».
 */
export const OFFICE_EQUIPMENT_PURCHASE_SORT_FIELDS = ['num', 'createdAt', 'updatedAt'] as const;

/**
 * Список закупок: страница и отбор по состоянию.
 *
 * Поиска здесь нет вовсе, и это не экономия: искать у закупки нечего — ни ФИО, ни телефона, ни
 * названия у неё не бывает (Р16), а номер спрашивают отбором «Новые» и глазами по одной странице.
 * Заведи мы поиск по комментарию, он обещал бы находить закупку «по картриджам Pantum», чего он не
 * умеет: позиции лежат строками, а не в тексте шапки.
 */
export const officeEquipmentPurchaseListQuerySchema = baseListQuery(
  OFFICE_EQUIPMENT_PURCHASE_SORT_FIELDS,
)
  .omit({ search: true })
  .extend({
    /**
     * Отбор по состоянию. Набором, а не одним значением: рабочий срез снабжения — это «Новая **и**
     * В работе» сразу, то есть все открытые, и одним значением его не выразить. Отсутствие
     * параметра означает «все состояния», пустого набора не бывает.
     *
     * ЗАПЯТОЙ В ОДНОМ ПАРАМЕТРЕ, а не повтором `status=new&status=in_work`, — тем же приёмом, что
     * отбор действий в журнале аудита (`auditActionsSchema`). Повтор параметра разбирается
     * по-разному в зависимости от того, как собран запрос, и схема querystring должна была бы
     * принимать обе формы; строка с запятой одна при любом клиенте. Перечень при этом остаётся
     * закрытым — опечатка в коде состояния видна отказом схемы, а не пустым списком.
     */
    status: z
      .string()
      .max(OFFICE_EQUIPMENT_PURCHASE_STATUSES.join(',').length)
      .transform((v) =>
        v
          .split(',')
          .map((s) => s.trim())
          .filter((s) => s !== ''),
      )
      .pipe(
        z
          .array(z.enum(OFFICE_EQUIPMENT_PURCHASE_STATUSES))
          .nonempty('Укажите хотя бы одно состояние или не присылайте отбор вовсе')
          .max(OFFICE_EQUIPMENT_PURCHASE_STATUSES.length),
      )
      .optional(),
  });
export type OfficeEquipmentPurchaseListQuery = z.infer<
  typeof officeEquipmentPurchaseListQuerySchema
>;

/**
 * Количество в строке закупки. Строго положительное: «заказать ноль» — это отсутствие строки, а не
 * строка, и `CHECK` базы держит то же самое. Верхняя граница — защита от опечатки, как у остатка.
 */
const purchaseQuantitySchema = z
  .number()
  .int('Количество — целое число')
  .min(1, 'Количество в строке — не меньше единицы')
  .max(1_000_000, 'Проверьте количество: слишком большое число');

/** Слагаемое снимка расчёта: неотрицательное целое, как и всё, что считается по складу. */
const snapshotNumberSchema = z.number().int().min(0).max(1_000_000);

/**
 * Строка формы: позиция, количество и СНИМОК РАСЧЁТА, из которого это количество вышло (Р17,
 * шаг 0).
 *
 * ПОЧЕМУ СНИМОК ВОЗВРАЩАЕТСЯ КЛИЕНТОМ, А НЕ БЕРЁТСЯ СЕРВЕРОМ ЗАНОВО. Он и есть предмет сверки:
 * между открытием формы и её отправкой проходит время, за которое остаток двигают выдачи, а
 * потребность правят руками. Сервер пересчитывает те же три числа под блокировкой и сравнивает их
 * с присланными; разошлись — 409 с новыми числами (шаг 6). Взяв свои же свежие числа, сервер
 * сверял бы их сам с собой и не защищал бы ничего.
 *
 * ТРИ ЧИСЛА, А НЕ ОДНО «предложено». Сойтись обязано каждое слагаемое, а не сумма: потребность 20
 * при остатке 5 и потребность 25 при остатке 10 дают одно и то же «к закупке 15», и человек,
 * видевший первое, о втором ничего не знает — а решение «заказать 15» он принимал по первому.
 *
 * `suggestedQuantity` среди полей НЕТ намеренно: оно выводится из трёх присланных одной формулой
 * Р15, и приняв его отдельно, портал мог бы прислать четвёртое число, не сходящееся с тремя
 * первыми, — то есть снимок, противоречащий сам себе. Сервер считает его сам и им же пишет строку.
 */
export const officeEquipmentPurchaseItemInputSchema = z.object({
  consumableId: uuidSchema,
  quantity: purchaseQuantitySchema,
  /** Потребность позиции, какой её видел человек. */
  expectedRequired: snapshotNumberSchema,
  /** Остаток на складе, какой его видел человек. */
  expectedStock: snapshotNumberSchema,
  /** «Уже заказано» открытыми закупками, каким его видел человек. */
  expectedAlreadyOrdered: snapshotNumberSchema,
});
export type OfficeEquipmentPurchaseItemInput = z.infer<
  typeof officeEquipmentPurchaseItemInputSchema
>;

/**
 * Строки закупки: непустой набор без повторов по позиции.
 *
 * ПУСТАЯ ЗАКУПКА НЕ ЗАВОДИТСЯ (Р16): закупка без строк — это отсутствие закупки, а не документ «мы
 * подумали и решили ничего не брать». Отбивается схемой, а не маршрутом, потому что то же самое
 * правило нужно и правке черновика: снять последнюю строку — это то же «заказывать нечего».
 *
 * ПОВТОР ПОЗИЦИИ ОТБИВАЕТСЯ ЗДЕСЬ ЖЕ, а не сводится молча сложением количеств. Две строки «Тонер
 * Ricoh 201» в одной закупке — это ошибка формы, и сложив их, портал показал бы человеку не то,
 * что он набрал; уникальность пары держит и база (`office_equipment_purchase_items_unique`), но её
 * нарушение стало бы 500 с именем ограничения вместо слов.
 */
const purchaseItemsSchema = z
  .array(officeEquipmentPurchaseItemInputSchema)
  .min(1, 'Добавьте хотя бы одну позицию: пустая закупка не заводится')
  .max(500, 'Слишком много позиций в одной закупке')
  .refine((items) => new Set(items.map((i) => i.consumableId)).size === items.length, {
    message: 'Позиция встречается в закупке дважды — оставьте одну строку',
  });

/** «К чему закупка», необязательный и единственный текст документа (Р16). */
const purchaseCommentSchema = z.string().trim().max(2000);

/**
 * Заведение закупки (Р17).
 *
 * КЛЮЧА ИДЕМПОТЕНТНОСТИ В ТЕЛЕ НЕТ: он приходит заголовком `Idempotency-Key`, тем же транспортом,
 * что и у кабинета водителя (ADR 0103). Место у него общее для портала, и переносить его в тело
 * ради одной ручки значило бы завести второе правило на то же самое.
 *
 * ОТПЕЧАТОК ТЕЛА СЧИТАЕТ СЕРВЕР, и клиент его не присылает вовсе: отпечаток — это доказательство
 * «команда та же», и присланный клиентом, он доказывал бы ровно столько, сколько клиент захотел бы
 * доказать.
 */
export const createOfficeEquipmentPurchaseSchema = z.object({
  comment: purchaseCommentSchema.optional().default(''),
  items: purchaseItemsSchema,
});
export type CreateOfficeEquipmentPurchaseInput = z.infer<
  typeof createOfficeEquipmentPurchaseSchema
>;

/**
 * Правка черновика (Р18) — то же тело плюс версия содержимого.
 *
 * ВЕРСИЯ ОБЯЗАТЕЛЬНА И НЕ «ДЛЯ СОВМЕСТИМОСТИ». Состояние и версия отвечают на разные вопросы:
 * состояние — «можно ли править», версия — «не изменил ли документ кто-то другой». Условия по
 * статусу хватает переходам (статус в них и меняется) и НЕ хватает правке полей: она идёт внутри
 * одного статуса, где статус неподвижен и ничего не стережёт. Двое открыли черновик на 10, первый
 * поставил 12 и сохранил, второй ставит 8 — снимок Р17 у второго сходится (внешнее состояние не
 * менялось, а собственный вклад закупки из него и так вычитается), и «8» молча перетёрло бы «12».
 *
 * Строки присылаются ПОЛНЫМ набором, а не разницей: состав документа — это разметка, а не история,
 * и «снять строку» с «изменить количество» одной командой выражается только целым набором.
 */
export const updateOfficeEquipmentPurchaseSchema = z.object({
  contentVersion: z.number().int().min(1),
  comment: purchaseCommentSchema.optional().default(''),
  items: purchaseItemsSchema,
});
export type UpdateOfficeEquipmentPurchaseInput = z.infer<
  typeof updateOfficeEquipmentPurchaseSchema
>;

/**
 * «Провести» — передать бумагу в снабжение (`new` → `in_work`).
 *
 * НЕСЁТ ВЕРСИЮ СОДЕРЖИМОГО (Р18), в отличие от прочих переходов, и это не осторожность: в
 * снабжение уезжает состав, и провести надо ровно тот, который человек видел на экране. Правка
 * соседа, приехавшая между открытием карточки и нажатием кнопки, меняет именно его.
 */
export const submitOfficeEquipmentPurchaseSchema = z.object({
  expectedVersion: z.number().int().min(1),
});
export type SubmitOfficeEquipmentPurchaseInput = z.infer<
  typeof submitOfficeEquipmentPurchaseSchema
>;

/**
 * «Закрыть» (`in_work` → `closed`) с подтверждением «приход занесён» (Р11).
 *
 * ГАЛОЧКА ОБЯЗАТЕЛЬНА И НИЧЕГО НЕ ДОКАЗЫВАЕТ, и обе половины этой фразы важны. Проверить порядок
 * «сначала приход, потом закрытие» портал НЕ может: текущий остаток не доказывает, что приход
 * именно по этой закупке, — между открытием и закрытием были выдачи по заявкам, ручные
 * корректировки и, возможно, приход по соседней закупке. Поэтому подтверждение делает ровно две
 * вещи: заставляет прочитать правило в момент, когда оно применяется, и оставляет имя того, кто
 * это утверждал.
 *
 * `z.literal(true)`, а не `boolean`: снятая галочка — это не «закрыть без подтверждения», а «не
 * закрывать», и принять `false` значило бы завести второй, молчаливый путь мимо правила.
 *
 * СВОИХ КОЛОНОК У ПОДТВЕРЖДЕНИЯ НЕТ (правка редакции 4 плана): `stock_confirmed_by/at` дублировали
 * бы `closed_by/at` — галочку ставит тот же человек тем же действием, и две пары колонок про одно
 * событие рано или поздно разошлись бы. След подтверждения — сама пара закрытия: закупка закрыта,
 * значит подтверждение было.
 */
export const closeOfficeEquipmentPurchaseSchema = z.object({
  stockReceiptConfirmed: z.literal(true, {
    message: 'Подтвердите, что приход занесён в остатки',
  }),
});
export type CloseOfficeEquipmentPurchaseInput = z.infer<typeof closeOfficeEquipmentPurchaseSchema>;

/**
 * «Отменить» (`new` или `in_work` → `cancelled`) с обязательной причиной.
 *
 * Причина обязательна и в схеме, и в базе (`office_equipment_purchases_cancelled_check` меряет её
 * через `btrim`): отменённая закупка без объяснения через месяц читается как «передумали», а
 * отменяют её, как правило, потому, что заказ ушёл другим путём или позиция оказалась не та, — и
 * это ровно то, что нужно знать тому, кто заведёт следующую.
 */
export const cancelOfficeEquipmentPurchaseSchema = z.object({
  reason: z.string().trim().min(3, 'Укажите причину отмены').max(1000),
});
export type CancelOfficeEquipmentPurchaseInput = z.infer<
  typeof cancelOfficeEquipmentPurchaseSchema
>;

/**
 * Строка карточки закупки: что заказано и из чего это вышло.
 *
 * СНИМОК ЛЕЖИТ В СТРОКЕ, А НЕ ПЕРЕСЧИТЫВАЕТСЯ (Р17). Потребность плавающая, остаток движется
 * каждый день, «уже заказано» меняется от каждой соседней закупки — без снимка через месяц на
 * вопрос «почему заказали двенадцать» ответить нечем: сегодняшняя потребность к тому решению
 * отношения уже не имеет, и пересчёт задним числом дал бы другое число при полностью верных
 * данных. Приём тот же, что снимок предмета в заявке, и по той же причине.
 */
export interface OfficeEquipmentPurchaseItemDto {
  id: string;
  consumableId: string;
  code: string;
  name: string;
  color: string | null;
  /** Сколько заказываем: человек мог поправить предложенное руками. */
  quantity: number;
  requiredSnapshot: number;
  stockSnapshot: number;
  alreadyOrderedSnapshot: number;
  /** Что предложил портал на момент отправки: `max(0, потребность − остаток − уже заказано)`. */
  suggestedQuantity: number;
  /**
   * Остаток позиции СЕЙЧАС — не снимок, а сегодняшнее число. Показывает его форма закрытия (Р11):
   * человек утверждает, что приход занесён, и единственное, что портал может ему для этого дать, —
   * текущий остаток рядом с заказанным количеством.
   *
   * Рядом со `stockSnapshot`, а не вместо него: снимок отвечает «сколько было, когда заказывали»,
   * это число — «сколько лежит сейчас», и подменять один ответ другим нельзя.
   */
  currentStock: number;
}

/**
 * Шапка закупки. Лента жизненного пути строится из ЭТИХ колонок, а не из журнала аудита (Р9): общий
 * помощник `writeAudit` глотает ошибку записи, то есть гарантией истории не является, и карточка,
 * показывающая путь документа из такого источника, показывала бы его с дырами. Аудит пишется тоже,
 * но строгий и в той же транзакции — он для вопроса «что вообще происходило в портале», а не для
 * этой ленты.
 */
export interface OfficeEquipmentPurchaseDto {
  id: string;
  num: number;
  /** «ЗК-14» — собранный сервером, чтобы номер в карточке, в отказе и в аудите был один. */
  displayNumber: string;
  status: OfficeEquipmentPurchaseStatus;
  comment: string;
  /**
   * Версия содержимого (Р18): её возвращает форма правки и несёт кнопка «Провести». Растёт при
   * каждой правке черновика и не двигается переходами — переходы стережёт статус.
   */
  contentVersion: number;
  /** Сколько позиций и сколько штук всего: список читают этой парой, не открывая карточку. */
  itemCount: number;
  totalQuantity: number;
  createdById: string;
  createdByName: string;
  createdAt: string;
  submittedByName: string | null;
  submittedAt: string | null;
  closedByName: string | null;
  closedAt: string | null;
  cancelledByName: string | null;
  cancelledAt: string | null;
  /** Пусто у неотменённой: пустая строка означает «отмены не было», и это же держит `CHECK`. */
  cancelReason: string;
  updatedAt: string;
}

