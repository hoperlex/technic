// ── Дверь ремонта истории: `POST /vehicle-requests/:id/assignment-changes/repair` ──

/**
 * Общая часть обеих веток ремонта: рукопожатие и режим.
 *
 * `restore` — не работа, а режим: он выводит заявку из архива **вместе с ремонтом**, одной
 * транзакцией, чтобы не осталось состояния «историю починили, а архив не сняли». Само по себе
 * восстановление делает своя ручка (`POST /vehicle-requests/:id/restore`), и дублировать её здесь
 * незачем.
 */
const repairCommonShape = {
  /**
   * Снять архив той же транзакцией (Р29). Запрошен явно — архив снимается всегда, и post-restore
   * сверка выполняется даже при пустом плане: у дремлющего `assignment_wins` он как раз обычно
   * пуст. Требует права `archive.restore`.
   *
   * У архивной заявки решение хвоста без него запрещено вовсе (Р31): иначе ремонт создал бы
   * дремлющую группу, не сняв архива, а править и отменять её нужно общей дверью, у которой
   * архивной области нет и заводить её незачем.
   */
  restore: z.boolean().optional(),
  unlockFingerprint: assignmentFingerprintSchema.optional(),
  acknowledgements: assignmentAcknowledgementsSchema.optional(),
  version: versionSchema,
  /** Отпечаток последствий; необязателен в схеме по той же причине, что и у команды истории. */
  previewFingerprint: assignmentFingerprintSchema.optional(),
  operation: operationInputSchema.optional(),
};

/**
 * Ремонт: команда **восстанавливает** то, чего история не знает.
 *
 * Работ у двери три, и все они здесь: пробелы машиниста (`anchors`), расхождение хвоста
 * (`tailResolution`, Р31) и заполнение `unknown` известным человеком (`knownFills`, Р29).
 */
export const repairWorkSchema = z
  .object({
    ...repairCommonShape,
    mode: z.literal('repair'),
    anchors: machinistAnchorsSchema.optional(),
    /**
     * Заполнение `unknown` на **заблокированных** днях: история старых заявок доводится до полной.
     *
     * Поле выкатывается отдельным последним релизом (подэтап 6a), после ответа бухгалтерии: там,
     * где листа за эти дни не было вовсе, сверка **выпишет недостающие бланки задним числом**, и
     * расход строгой отчётности реальный. До ответа сервер отвечает `409
     * backdated_issue_not_authorized`, а портал поля не показывает — запрет механический, а не
     * договорённость. В схеме поле при этом есть: без него строгая валидация отклонила бы запрос
     * раньше, чем он дошёл бы до предусмотренного отказа, и человек прочёл бы «лишнее поле» вместо
     * «выписка бланков задним числом не согласована» (Ц4).
     */
    knownFills: knownFillsSchema.optional(),
    tailResolution: tailResolutionSchema.optional(),
  })
  .strict();
export type RepairWorkInput = z.infer<typeof repairWorkSchema>;

/**
 * Отмена заполнения: команда **снимает** ранее заявленное утверждение о факте.
 *
 * Дверь та же, что заполнила: та, что умеет заводить, обязана уметь и снимать. Но команда другая —
 * и живёт она отдельной веткой, а не необязательным полем общей схемы (Ю1). Слейся ветки в одну,
 * `target` можно было бы прислать вместе с якорями, заполнениями и решением хвоста, и смысл команды
 * («восстанавливаю» против «снимаю») пришлось бы выяснять по составу тела — то есть по тому, что
 * человек **не** прислал.
 *
 * Общая часть у веток одна: архивная заявка, версия, отпечаток и рукопожатия нужны отмене ровно
 * так же.
 */
export const cancelFillSchema = z
  .object({
    ...repairCommonShape,
    mode: z.literal('cancel_fill'),
    /**
     * Группа заполнения (Р13, Э2). Отменяемую группу определяет **провенанс, а не состав**: ровно
     * одна актуальная строка `known_fill` плюс не более одной `unknown_remainder`. Группа, не
     * отвечающая этому описанию, отменяется обычным `cancel`, а не как заполнение (422
     * `not_a_known_fill_group`) — иначе отмена превратила бы известного человека в `unknown`.
     */
    target: z.object({ changeGroupId: uuidSchema }).strict(),
  })
  .strict();
export type CancelFillInput = z.infer<typeof cancelFillSchema>;

/**
 * Тело двери ремонта: две взаимоисключающие ветки с дискриминантом `mode` (Ю1).
 *
 * Требование «хотя бы одна работа» стоит на союзе, а не внутри ветки: `z.discriminatedUnion`
 * разбирает объекты по литералу, и ветка, обёрнутая в `superRefine`, перестала бы им быть.
 *
 * Пустой ремонт отвергается схемой, потому что отвергать его больше негде: `restore` работой не
 * является (у него своя ручка), а команда без якорей, заполнений и решения хвоста дошла бы до
 * сервера, прошла бы все проверки и записала бы операцию журнала, ничего не изменив, — то есть
 * оставила бы в журнале коррекций строку с причиной и без предмета.
 */
export const repairSchema = z
  .discriminatedUnion('mode', [repairWorkSchema, cancelFillSchema])
  .superRefine((v, ctx) => {
    if (v.mode !== 'repair') return;
    if (!v.anchors && !v.knownFills && !v.tailResolution) {
      ctx.addIssue({
        code: 'custom',
        message:
          'Ремонт без работы: назовите машинистов на пробелах, заполнение или решение по хвосту',
      });
    }
  });
export type RepairInput = z.infer<typeof repairSchema>;
export type RepairBody = z.input<typeof repairSchema>;

// ── Дверь срока: `POST /vehicle-requests/:id/period/preview` и `PATCH /:id/period` ──

/**
 * Правка срока — своя дверь (Ж4, З5), а не поля широкого `PATCH /:id`.
 *
 * Узкое тело туда не легло бы: `updateVehicleRequestSchema` — строгий union с обязательными типом
 * заявки, техникой, заказчиком, контактами и файлами, и «продлить срок» пришлось бы оформлять как
 * полную правку заявки. Смешанная команда «продлить и заодно поправить комментарий» распадается на
 * две — у них разные последствия и разные рукопожатия.
 */
export const periodCommandSchema = z
  .object({
    version: versionSchema,
    dateFrom: dateOnlySchema.optional(),
    /**
     * `null` — «срок открыт»: заказ на объект живёт без даты окончания, пока его не завершат. Это
     * не «поле не прислали» — то выражается отсутствием ключа.
     */
    dateTo: dateOnlySchema.nullable().optional(),
  })
  .strict();
export type PeriodCommand = z.infer<typeof periodCommandSchema>;

/**
 * Предпросмотр срока знает меньше боевой команды — и это не упущение (Л1): отпечатка, исхода и
 * ключей выпускаемых листов у него ещё нет, он их и вычисляет. Одинакова у двух тел семантическая
 * часть, а не тело целиком.
 */
export const periodPreviewSchema = periodCommandSchema;
export type PeriodPreviewInput = PeriodCommand;

export const periodApplySchema = periodCommandSchema
  .extend({
    /*
     * Необязателен **в схеме**, обязателен на сервере — как у команды машиниста и коррекции.
     * Разница видна человеку: отсутствие отпечатка это 409 «посмотрите последствия заново», а не
     * 400 «поле обязательно». Первое объясняет, что делать; второе выглядит поломкой клиента.
     * Требование само по себе никуда не девается — его держит шаг 7 канона.
     */
    previewFingerprint: assignmentFingerprintSchema.optional(),
    /**
     * Подтверждение перечня групп, которые гасит **сокращение** срока (Д2). Гашение здесь не
     * побочный эффект правки `dateTo`, а изменение истории: оставленная за новым концом срока
     * vehicle-строка ожила бы при следующем продлении — без решения о ставках и занятости, в обход
     * Р7.
     */
    cancelGroupsFingerprint: assignmentFingerprintSchema.optional(),
    unlockFingerprint: assignmentFingerprintSchema.optional(),
    acknowledgements: assignmentAcknowledgementsSchema.optional(),
    operation: operationInputSchema.optional(),
  })
  .strict();
export type PeriodApplyInput = z.infer<typeof periodApplySchema>;
export type PeriodApplyBody = z.input<typeof periodApplySchema>;

// ── Ответы предпросмотра (§7) ──

/**
 * Пробел машиниста, который человек обязан закрыть якорем.
 *
 * Номер заказа здесь нужен, хотя якорь его не называет: тот же тип возвращают **чужие** двери в
 * отказе (Р22), а недельная операция называет сразу несколько заказов — и «назначьте машиниста с
 * 1 марта» без номера заявки не подсказка, а загадка.
 */
export interface RequiredAnchor {
  requestId: string;
  requestNumber: string;
  /** Дата, на которую ждут якорь; только её и примет команда. */
  effectiveDate: string;
  /** Отрезок без машиниста целиком — им окно объясняет, за какие дни спрашивает. */
  from: string;
  to: string;
}

/**
 * Расхождение хвоста (Р31): машина, действующая на конце срока, против машины назначения.
 *
 * Обе названы **и идентификатором, и именем**: идентификатор нужен команде, имя — человеку, а
 * второй запрос за именами из окна отказа означал бы, что портал показывает выбор не сразу.
 */
export interface RequiredVehicleResolution {
  tailVehicleId: string;
  tailVehicleName: string;
  assignmentVehicleId: string;
  assignmentVehicleName: string;
  /** С какого дня расхождение начинает действовать — `dateTo + 1`. */
  since: string;
}

/**
 * Нужна ли операция журнала, какого вида и что для неё спросить (Р32).
 *
 * По нему окно решает, показывать ли поля причины и ключа, — а **не по календарю**: отмена
 * дремлющего решения с прошлогодней датой причину требует, а плановая смена машиниста на будущее —
 * нет. Считать это на клиенте по дате означало бы держать вторую редакцию матрицы Р32, которая
 * разойдётся с серверной на первом же уточнении.
 *
 * `null` — исход `none`: причины не спрашивают вовсе.
 */
export interface OperationRequirement {
  kind: Exclude<AssignmentOperationOutcome, 'none'>;
  /**
   * Оба признака выписаны явно, хотя сегодня оба истинны при любом непустом исходе: окно не должно
   * выводить их из `kind` — в тот день, когда правило разойдётся, разойдётся молча и портал.
   */
  reasonRequired: boolean;
  operationIdRequired: boolean;
}

/** День работы с часами: цена подтверждения должна быть видна, а не подразумеваться. */
export interface AssignmentShiftDay {
  date: string;
  hours: number;
}

/** Лист под разблокировку — номером и неделей: ими окно называет человеку бумагу, о которой спрашивает. */
export interface AssignmentUnlockDto {
  waybillId: string;
  displayNumber: string;
  from: string;
  to: string;
}

/** Аннулируемый лист плана: номер человеку, период — чтобы он узнал свою неделю. */
export interface AssignmentPlanCancelDto {
  waybillId: string;
  displayNumber: string;
  from: string;
  to: string;
}

/**
 * Выпускаемый лист плана — с составом, а не одними границами.
 *
 * До разреза состав добирался из глобальной пары «машина + машинист» заявки, и этого хватало: на
 * календарную неделю приходился один лист. После Р5 пн–вт обязаны выйти как `A + Иван`, а ср–вс —
 * как `B + Пётр`, и восстановить это по ключу недели нечем.
 */
export interface AssignmentPlanIssueDto {
  /**
   * Стабильный ключ, посчитанный **до** записи: индекс элемента в плане, отсортированном по
   * `(from, to, vehicleId, driverPersonId)`. Сортировать по `id` нельзя вовсе — он появится только
   * после расхода номера, а сгенерированные идентификаторы в отпечаток предпросмотра не входят.
   */
  issueKey: number;
  from: string;
  to: string;
  vehicleId: string;
  vehicleName: string;
  driverPersonId: string;
  driverName: string;
}

/** Предупреждения одного выпускаемого листа и их отпечаток — рукопожатие строится по ним (В1). */
export interface AssignmentIssueWarningsDto {
  issueKey: number;
  warnings: WaybillWarning[];
  /**
   * `sha256` от каноникализованных **фактов**, а не от текста: подтверждает человек положение дел,
   * а не формулировку на экране. Его же портал возвращает ключом `issueKey` в `acknowledgements`.
   */
  warningFingerprint: string;
}

/**
 * Общий ответ предпросмотров модуля: что случится, если нажать.
 *
 * Один DTO на пять дверей намеренно. Окно последствий у них одно и то же — сгорающие и
 * выписываемые листы, пробелы машиниста, снимаемые часы, разблокировки, — и своя форма у каждой
 * двери означала бы пять окон, расходящихся по мере правок.
 */
export interface AssignmentPreviewDto {
  /** Бумажный план: что сгорит и что выпишется. Пустой план — законный ответ (дремлющее изменение, Р24). */
  plan: {
    cancel: AssignmentPlanCancelDto[];
    issue: AssignmentPlanIssueDto[];
  };
  /**
   * Пробелы машиниста, которые обязана закрыть та же команда (Р16). Непусты — предпросмотр
   * **первой фазы**: набор последствий ещё неизвестен, подтверждать нечего, и окно спрашивает имена.
   */
  requiredAnchors: RequiredAnchor[];
  /** Расхождение хвоста, запирающее продление (Р31); `null` — хвост согласован. */
  requiredVehicleResolution: RequiredVehicleResolution | null;
  /**
   * Дни, **из-за которых команда невозможна**: часы подписаны объектом, и снимаются они только
   * коррекцией. Смешанный диапазон — 422, и ни одна строка не удаляется.
   */
  blockedShiftDays: AssignmentShiftDay[];
  /**
   * Дни, которые **будут удалены**, если человек подтвердит: часы внесены, но не подписаны, а после
   * смены машины они относились бы к технике, которой в этот день не было. Часы показываются,
   * чтобы объект понимал цену подтверждения.
   *
   * Список отдельный от `blockedShiftDays`, а не флаг внутри одного: «нельзя» и «будет стёрто» —
   * разные ответы, и слитые в один они дали бы окно, которое либо пугает лишним, либо молчит о
   * потере.
   */
  clearedShiftDays: AssignmentShiftDay[];
  /** Отпечаток `clearedShiftDays`; `null` — снимать нечего, и подтверждать нечего. */
  clearedShiftsFingerprint: string | null;
  /** Листы под разблокировку — для показа (Р11). Команда носит не их, а отпечаток. */
  requiredUnlocks: AssignmentUnlockDto[];
  /** Отпечаток серверного множества разблокировок; `null` — множество пусто. */
  unlockFingerprint: string | null;
  /** Предупреждения по каждому выпускаемому листу: из них окно строит рукопожатия (Б4). */
  issues: AssignmentIssueWarningsDto[];
  /** Нужна ли операция журнала и что для неё спросить (Р32); `null` — исход `none`. */
  operationRequirement: OperationRequirement | null;
  /**
   * Календарный день, на который посчитаны последствия (`asOf`, Р32). Он входит в отпечаток, и
   * переход бизнес-даты обесценивает предпросмотр **всегда** — даже когда исход не изменился:
   * предпросмотр 19 августа с командой 20-го просто не сойдётся. Человек увидит 409 и посмотрит
   * последствия заново.
   */
  asOf: string;
  /**
   * Отпечаток последствий. Возвращается боевой ручке полем `previewFingerprint`: между просмотром и
   * нажатием план меняется, не тронув заявку, — чужая команда заняла ту же дату, лист аннулировали
   * своей ручкой, наступила полночь. `version` заявки ни одного из этих случаев не ловит.
   */
  fingerprint: string;
}

/**
 * Группа истории, которую гасит сокращение срока: даты, шкалы и состав (Д2).
 *
 * Состав показывается целиком, потому что гашение групповое: человек, сокращающий срок, должен
 * увидеть, что вместе с майской машиной уходит и её майский машинист.
 */
export interface CancelledAssignmentGroupDto {
  changeGroupId: string;
  rows: {
    effectiveDate: string;
    dimension: AssignmentDimension;
    /** Машина изменения; `null` — строка шкалы `driver`. */
    vehicle: { vehicleId: string; name: string } | null;
    /** Состояние машиниста; `null` — строка шкалы `vehicle`. */
    driver: DriverState | null;
    origin: AssignmentChangeOrigin;
  }[];
}

/** Ответ предпросмотра срока: общие последствия плюс то, что есть только у него. */
export interface PeriodPreviewDto extends AssignmentPreviewDto {
  cancelGroups: CancelledAssignmentGroupDto[];
  /** Отпечаток перечня погашаемых групп; `null` — сокращения нет, гасить нечего. */
  cancelGroupsFingerprint: string | null;
}

/**
 * Ответ двери ремонта — и предпросмотра, и осмотра (`GET .../repair/state`, подэтап 6a).
 *
 * Форма одна на оба запроса нарочно: окно рисует одним компонентом и «что чинить», и «что будет,
 * если нажать». У осмотра работы в теле нет вовсе, поэтому `stateAfter` равен `state`, а план
 * бумаги пуст — это ответ, а не обещание.
 */
export interface RepairPreviewDto extends AssignmentPreviewDto {
  /** Состояние истории **сейчас** (Р26): `materialized` — чинить есть что. */
  state: AssignmentHistoryState;
  /** Каким станет состояние, если нажать (Р27). У осмотра равно `state`. */
  stateAfter: AssignmentHistoryState;
  /** Блокеры до команды интервалами — проекция для карточки, а не единица сравнения. */
  blockedDays: { from: string; to: string }[];
  /**
   * Промежутки `unknown` на **заблокированных** днях — единственные адреса `knownFills` (Ц4).
   *
   * На изменяемых днях та же дыра чинится якорями, и второго способа назвать человека там нет.
   * Отличить одно от другого может только сервер: это зависит от отменяемости бумаги.
   */
  fillableGaps: { from: string; to: string }[];
  /** Заявка в архиве: дверь открыла её по идентификатору (Ц3). */
  archived: boolean;
  /** Пуст ли бумажный план для гипотетического `deleted_at = null` (Р29). */
  paperFree: boolean;
  /** Архивной заявке с непустым планом ремонт разрешён только режимом `restore` (Р29). */
  restoreRequired: boolean;
}

/** Итог боевой ручки ремонта: чем кончилось и в каком состоянии осталась история. */
export interface RepairResultDto {
  ok: true;
  repeated: boolean;
  version: number;
  state: AssignmentHistoryState;
  operationId: string | null;
  archived: boolean;
}

// ── История заявки: `GET /vehicle-requests/:id/assignment-changes` ──

/**
 * Одно изменение истории глазами портала.
 *
 * `id` необязателен намеренно: до материализации история существует только расчётом (Р20) —
 * предпросмотр её не коммитит, — и у расчётных строк идентификаторов нет. Адресовать их можно
 * логическим ключом `{ dimension, effectiveDate }`, ради чего он в цели команды и появился.
 */
export interface AssignmentChangeDto {
  id: string | null;
  effectiveDate: string;
  dimension: AssignmentDimension;
  /** Машина изменения; `null` — строка шкалы `driver`. */
  vehicle: { vehicleId: string; name: string } | null;
  /** Состояние машиниста; `null` — строка шкалы `vehicle`. */
  driver: DriverState | null;
  origin: AssignmentChangeOrigin;
  /** Группа решения: гашение и отмена работают ею, а не отдельной строкой (Р31). */
  changeGroupId: string;
  /** Операция журнала, породившая строку; `null` — обычная работа без коррекции. */
  correctionId: string | null;
  createdAt: string;
  createdByName: string | null;
  /**
   * Как строка перестала быть актуальной; `null` — действует. Погашенные строки показываются
   * наравне с актуальными: журнал заявки читают, чтобы понять, **что** правили, а не только чем
   * дело кончилось.
   */
  supersededKind: AssignmentSupersedeKind | null;
  supersededAt: string | null;
  supersededByName: string | null;
}

/**
 * История назначения заявки целиком — то, из чего портал строит «Состав по датам».
 *
 * Состояние готовности отдаётся вместе с изменениями, а не отдельной ручкой: окно смены машиниста
 * обязано отличить «истории нет» от «история есть, но невалидна», и второй запрос за этим означал
 * бы, что между ними состояние успевает измениться.
 */
export interface RequestAssignmentHistoryDto {
  state: AssignmentHistoryState;
  /**
   * День, на который состояние считалось. Отличается от `asOf`: календарь меняет валидность сам,
   * без всякой двери, — поэтому состояние пересчитывается лениво, под блокировкой заявки, прежде
   * чем на него сошлётся любое решение.
   */
  validatedOn: string | null;
  /**
   * Загрязнение внутри дня (К4): ручки смен меняют отменяемость бумаги, а `validatedOn` при этом
   * остаётся сегодняшним, и ленивое правило устаревания молчало бы.
   */
  dirty: boolean;
  changes: AssignmentChangeDto[];
}
