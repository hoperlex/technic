/**
 * Правило для конкретной роли и модуля — то, что спрашивают проверка выдачи, будущий конструктор и
 * тесты. Роль, а не ось, в параметрах намеренно: ось выводится здесь, одним способом, и вызывающий
 * не получает соблазна вывести её у себя.
 */
export function grantScopeRule(role: Role, module: PermissionModule): GrantScopeRule {
  return GRANT_SCOPE_MATRIX[module][roleScopeAxis(role)];
}
