import type { Role } from './enums';
import { scopeAxisOf, type PermissionModule } from './permission-catalog';

/**
 * Матрица «ось роли × модуль» (план §8, инвариант 4; ADR 0106, решение 6, инвариант 5) — барьер
 * выдачи, который **нельзя проверить по эффективным правам постфактум**: к моменту, когда набор
 * выдан, данные уже показаны, и запоздалый отказ не отменяет показ, а описывает утечку.
 *
 * Смысл барьера в одной фразе плана: *scope-neutral — свойство модуля, а не набора*. Набор не
 * расширяет область только там, где область вообще есть. У путевых листов и гаража объектной
 * фильтрации нет вовсе: сегодня их закрывает не предикат, а то, что площадочным ролям
 * `waybills.read` и `garage.read` просто не выдают (`ROLE_PERMISSIONS`; ADR 0037 — в листе
 * персональные данные водителя). Набор с таким правом, выданный роли с объектной осью, откроет
 * данные всей компании, и `GRANT_MODULE_WIDE_SCOPE` тут ни при чём — расширять нечего, там
 * изначально всё.
 *
 * Отдельным файлом от `grants.ts`, потому что отвечает на другой вопрос. `grants.ts` — «что нельзя
 * выдать, что без чего не имеет смысла и что нельзя свести в одном человеке», то есть свойства
 * прав и наборов. Здесь — «где у модуля вообще есть область», свойство **модуля** и слоя
 * `apps/api/src/lib/access.ts`. Обоснование клетки читается вместе с предикатом, который её
 * оправдывает, и разъезжаться им нельзя: строка матрицы врёт молча.
 *
 * **Значения выведены из фактического состояния кода, а не из замысла.** Каждая клетка `scoped`
 * называет функцию слоя области, которая эту ось в этом модуле действительно фильтрует; каждая
 * `forbidden` означает, что такой функции нет, и до её появления выдача запрещена. Сомнение
 * решается в пользу `forbidden`: неверный запрет виден администратору сразу (набор не сохраняется),
 * неверное разрешение — никогда.
 *
 * **Матрица отвечает только про область.** «Право слишком сильное для этой роли» — вопрос каталога
 * полномочий и конструктора, а не этой таблицы: `directories.import` в клетке `global` разрешён
 * ровно в том смысле, что сужать справочник нечем, а не в том, что его стоит выдавать площадке.
 *
 * **Матрица ограничивает выдачу, а не матрицу ролей.** Роль даёт свои права мимо неё
 * (`ROLE_PERMISSIONS`), и `forbidden` в клетке никогда не означает «у этой роли такого права нет
 * сегодня» — только «набором ей это право не выдают». Обратное соотношение при этом обязано
 * держаться, и оно закреплено тестом: клетка `forbidden` там, где роль с этой осью право уже имеет,
 * была бы запретом на уже открытые данные — то есть ошибкой в матрице, а не защитой.
 */

/**
 * Оси области — четыре живых плюс «своей оси нет» (ADR 0025, 0038, 0040, 0062, 0102). Пятое
 * значение заведено вместо `null` намеренно: `Record` по объединению не даст забыть строку, а
 * `null` в ключе матрицы означал бы клетку, которую компилятор не проверяет, — ровно ту, где
 * стоит `global` и где промах стоит дороже всего.
 */
export const ROLE_SCOPE_AXES = ['object', 'department', 'counterparty', 'person', 'none'] as const;
export type RoleScopeAxis = (typeof ROLE_SCOPE_AXES)[number];

/** Ось словами — для текста отказа: администратор читает «объекты строительства», а не `object`. */
export const roleScopeAxisLabels: Record<RoleScopeAxis, string> = {
  object: 'объекты строительства',
  department: 'отделы',
  counterparty: 'контрагент',
  person: 'работник справочника',
  none: 'своей оси у роли нет',
};

/**
 * Ось роли для проверки выдачи. Обёртка над витринным `scopeAxisOf`, а **не** второй разбор ролей
 * по спискам `enums.ts`: классификация ролей по осям обязана быть одна на портал и на выдачу.
 * Разъехавшись, вторая копия ошибётся в самую дорогую сторону — роль с осью попадёт в строку
 * `none`, где всё `global`, и барьер выключится ровно для той роли, которую он защищает. Поэтому
 * соответствие каждой роли своей оси закреплено тестом по спискам `*_SCOPED_ROLES`, а не доверием
 * к витрине.
 *
 * `null` роли даёт `none` только формально: учётка без роли прав не получает вовсе (`can`
 * спрашивает роль первой), и до матрицы такая выдача не доходит.
 */
export function roleScopeAxis(role: Role | null | undefined): RoleScopeAxis {
  return scopeAxisOf(role) ?? 'none';
}

/**
 * Что матрица говорит про клетку:
 *
 * - `scoped` — у модуля есть предикат области для этой оси, и набор его не отменяет: право можно
 *   выдавать, держатель увидит своё;
 * - `global` — модуль по смыслу общий, сужать нечего: строки не делятся ни по объектам, ни по
 *   отделам, ни по контрагентам, и такой колонки в схеме нет вовсе;
 * - `forbidden` — область у модуля не выражена ничем, а у роли она есть: право этого модуля,
 *   выданное такой роли, отдаст ей данные всей компании. Запрет действует до появления предиката —
 *   выбор ровно один из двух, и второй дороже.
 */
export type GrantScopeRule = 'scoped' | 'global' | 'forbidden';

/**
 * Клетки матрицы, разложенные **по модулям**: обоснование — свойство модуля, а не оси, и живёт оно
 * одним блоком рядом с предикатом, который называет. Разложи таблицу по осям — и объяснение
 * «почему у путевых листов нельзя» пришлось бы повторить в четырёх строках, а расходиться четыре
 * копии начали бы с первой правки.
 *
 * `Record` по обеим осям — обязательное условие барьера: новый модуль витрины и новая ось области
 * не соберутся, пока про них не приняли решение. Забытая клетка иначе означала бы `undefined` —
 * то есть «не запрещено», худшее из трёх значений.
 *
 * **Строка `person` запрещена целиком, и это не осторожность.** Ось `person` — это ровно роль
 * `driver` (`PERSON_SCOPED_ROLES`), а ей наборы не выдаются ни одним способом (план §8,
 * инвариант 6). Вторая причина независима от первой: область этой оси не выражена предикатом
 * вовсе — кабинет не принимает `personId` ни в пути, ни в теле, ни в фильтре и берёт человека из
 * принципала (`routes/driver.ts`). За пределами кабинета фильтрации по работнику нет ни в одном
 * модуле, поэтому любое чужое право ушло бы водителю без области. Клетка `scoped` в этой строке
 * утверждала бы, что есть модуль, куда водителю можно что-то выдать; такого модуля нет.
 *
 * **Строка `none` — `global` везде, кроме кабинета.** Роль без своей оси не ограничена ничем по
 * построению (витринный `UNSCOPED_TEXT`): сужать ей нечего, и `forbidden` был бы запретом без
 * причины — он отрезал бы от наборов ровно диспетчера, менеджера и службу главного механика, то
 * есть тех, ради кого каталог полномочий и собирается.
 */
