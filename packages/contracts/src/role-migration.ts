import { roleLabels, type Role } from './enums';
import { ROLE_GRANTS, type RoleGrantCode } from './grants';
import type { Permission } from './permissions';

/**
 * Перевод упраздняемых ролей — таблица, по которой идут этапы 8 и 9 реформы доступа
 * (`docs/permissions-restructure-plan.md` §9 «было → стало», §13.2 «перевод ролей — тоже три
 * релиза»; ADR 0113).
 *
 * **Здесь только объявление, а не действие.** Файл отвечает на «кого куда переводят и что выдают
 * взамен»; переводит учётки миграция этапа migrate, выдаёт наборы заранее миграция prepare, а
 * сверяет обе стороны на живых данных скрипт `check:role-migration`. Один ответ на четверых:
 * разъехавшись, они выдали бы не тот набор не тем людям — и заметить это было бы нечем, потому что
 * каждая копия проверяла бы сама себя.
 *
 * **Почему таблица, а не разбор по месту.** Три площадочные роли переводятся в одну, и различие
 * между ними целиком переезжает в наборы: `shtab` — «Заказ техники», `rukstroy` — он же плюс «Виза
 * объекта», `commandant` — ничего. Записанное `if`'ами в миграции, в скрипте и в форме, это
 * различие живёт в трёх местах и в первом же исправлении расходится.
 *
 * Порядок строк — порядок этапов: сначала площадка (этап 8), потом отдел (этап 9). На поведение он
 * не влияет, а читается таблица сверху вниз.
 */
export interface RoleMigration {
  /** Этап плана: 8 — три роли площадки, 9 — руководитель отдела. */
  readonly stage: 8 | 9;
  /** Упраздняемая роль. Значение enum остаётся в базе мёртвым — удалять его план не берётся. */
  readonly from: Role;
  /** Роль после перевода. */
  readonly to: Role;
  /**
   * Наборы, которые перевод выдаёт держателю старой роли, — ровно то, чем она отличалась от
   * целевой. Пустой список у коменданта не пропуск: он и есть `site` без полномочий.
   */
  readonly grants: readonly RoleGrantCode[];
  /**
   * Права, которых у старой роли не было и которые перевод **добавляет**, — объявленное расширение
   * доступа, а не побочный эффект.
   *
   * Пустой список у трёх строк из четырёх означает тождество: пара «роль + наборы» равна старой
   * роли поимённо (§9, тест эквивалентности в `grants-contracts.test.ts`). Непустой — только у
   * коменданта, и это единственное расширение всей реформы, принятое решением №1 заказчика от
   * 17.08.2026: заявку на ремонт принтера в бытовке подаёт тот, кто на площадке.
   *
   * Список выписан поимённо, а не вычисляется на месте, потому что его читает сверка на живых
   * данных: расхождение, совпавшее с объявленным, — ожидаемый результат перевода, любое другое —
   * отказ. Вычисляемая разница ответила бы «расширение» на любое расхождение, включая ошибку.
   */
  readonly gains: readonly Permission[];
}

