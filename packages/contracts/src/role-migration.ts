/** Быстрый поиск по упраздняемой роли: таблица короткая, но спрашивают её на каждом сохранении. */
const BY_ROLE: ReadonlyMap<Role, RoleMigration> = new Map(ROLE_MIGRATIONS.map((m) => [m.from, m]));

/** Упраздняемые роли — те, что перечислены в таблице слева. Второго списка рядом не заводится. */
export const RETIRING_ROLES: readonly Role[] = ROLE_MIGRATIONS.map((m) => m.from);

/** Перевод, объявленный для этой роли; `null` — роль остаётся. */
export function roleMigrationOf(role: Role | null | undefined): RoleMigration | null {
  return role ? (BY_ROLE.get(role) ?? null) : null;
}

/** Упраздняется ли роль. Предикат, а не `includes` по месту: спрашивают форма, API и сверка. */
export function isRetiringRole(role: Role | null | undefined): boolean {
  return roleMigrationOf(role) !== null;
}

/**
 * Почему эту роль больше нельзя назначить — текст отказа или `null`, если назначение допустимо.
 *
 * **Закрытый вход — обязательная часть шага prepare, а не предосторожность** (план §13.2). Между
 * выдачей наборов держателям старой роли и переводом учёток проходит целый релиз, и всё это время
 * работающая версия старую роль знает: заведи она нового «штаба» — и перевод, который выдаёт наборы
 * по снимку, о нём не узнает, а `UPDATE` молча отберёт у человека заказ техники. Закрыть вход можно
 * только там, где учётки заводят, и только заранее.
 *
 * **Прежняя роль при этом сохраняется.** Проверяется не «какая роль в теле запроса», а «меняется ли
 * роль на упраздняемую»: правка телефона у действующего штаба присылает его роль обратно, и отказ
 * на неё означал бы, что до перевода такие учётки вообще нельзя редактировать. Отсюда два
 * аргумента, а не один.
 *
 * Текст называет замену поимённо — роль и наборы, — потому что администратору в этот момент нужно
 * не объяснение реформы, а следующее действие.
 */
export function retiringRoleIssue(
  next: Role | null | undefined,
  current: Role | null | undefined,
): string | null {
  if (!next || next === current) return null;
  const migration = roleMigrationOf(next);
  if (!migration) return null;
  const grants = migration.grants.map((code) => `«${ROLE_GRANTS[code].name}»`).join(' и ');
  const replacement = grants
    ? `выберите «${roleLabels[migration.to]}» и выдайте ${grants}`
    : `выберите «${roleLabels[migration.to]}»`;
  return `Роль «${roleLabels[next]}» упраздняется реформой доступа и больше не назначается: ${replacement}.`;
}
