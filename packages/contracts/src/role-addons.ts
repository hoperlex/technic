import { z } from 'zod';
import type { Role } from './enums';

/**
 * Надстройки роли (ADR 0086) — третья ось субъекта доступа.
 *
 * Право в портале выдаётся паре «роль + тип контрагента» (ADR 0038). Есть работа, которая в эту
 * пару не помещается: «Оператор (оргтехника)» остаётся штабом своего объекта или сотрудником
 * отдела — со своими заявками, своей площадкой и своим модулем вывоза, — а сверх этого получает
 * набор действий в одном модуле. Роль у учётки одна, и вторая означала бы вторую учётку и второй
 * вход; право у роли `shtab` сделало бы оператором каждый штаб компании.
 *
 * Отсюда надстройка: не роль и не контрагент, а именованный набор прав, который навешивается на
 * учётку поверх её роли. Область при этом **не меняется** — надстройка отвечает на «что человек
 * дополнительно может», а не на «над какими строками»: смешение слоёв дало бы либо 403 на своей же
 * заявке, либо доступ к чужой (ADR 0021).
 */
export const ROLE_ADDONS = ['office_equipment_operator'] as const;
export const roleAddonSchema = z.enum(ROLE_ADDONS);
export type RoleAddon = (typeof ROLE_ADDONS)[number];

export const roleAddonLabels: Record<RoleAddon, string> = {
  // Подпись называет предмет работы, а не набор прав: в списке учёток её читают рядом с ролью, и
  // «Оператор» без уточнения спорил бы с «Оператором (внешним исполнителем)».
  office_equipment_operator: 'Оператор (оргтехника)',
};

export const roleAddonColors: Record<RoleAddon, string> = {
  // Цвет отличается от цветов ролей: надстройка — не роль, и в списке учёток они не должны
  // выглядеть одинаковыми пометками.
  office_equipment_operator: 'purple',
};

/**
 * К каким базовым ролям надстройка прикрепляется.
 *
 * Таблица, а не проверка по месту: «оператор оргтехники» на арендодателе ТС — это доступ, которого
 * никто не назначал, и запрет должен быть виден там же, где список надстроек. Следующая надстройка
 * добавляется строкой здесь, и компилятор потребует ответить, кому она положена.
 *
 * Список ровно из двух ролей по постановке: оргтехникой в компании занимаются на площадке (штаб) и
 * в офисе (отдел). Понадобятся руководители — это строка в этой таблице, а не переделка.
 */
export const ROLE_ADDON_BASE_ROLES: Record<RoleAddon, readonly Role[]> = {
  office_equipment_operator: ['shtab', 'department'],
};

/** Можно ли навесить надстройку на эту роль. Учётка без роли не получает надстроек вовсе. */
export function canAttachAddon(role: Role | null | undefined, addon: RoleAddon): boolean {
  return !!role && ROLE_ADDON_BASE_ROLES[addon].includes(role);
}

/**
 * Надстройки учётки — набор, а не одно значение: ничто не мешает одному человеку отвечать и за
 * оргтехнику, и за то, что появится следующим. Предел стоит от опечатки в клиенте, а не от
 * рабочего случая.
 */
export const roleAddonsSchema = z.array(roleAddonSchema).max(ROLE_ADDONS.length);

/**
 * Совместим ли набор надстроек с ролью — вопрос формы учётки и сервера сразу. Возвращает первую
 * несовместимую: сообщение об ошибке должно называть виновника, а не «какая-то из надстроек».
 */
export function incompatibleAddon(
  role: Role | null | undefined,
  addons: readonly RoleAddon[],
): RoleAddon | null {
  return addons.find((addon) => !canAttachAddon(role, addon)) ?? null;
}
