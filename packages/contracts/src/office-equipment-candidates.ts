/**
 * Отказ приёмки, пока сообщение о технике ещё на проверке (Р16, §8 последний абзац).
 *
 * В КОНТРАКТАХ, А НЕ ПО КОПИИ НА КАЖДОЙ СТОРОНЕ. Текст говорят двое: сервер — отказом
 * `PATCH /:id/accept` после блокировки заявки и кандидата, портал — причиной выключенного пункта
 * «Принять работу» в меню заявки. Слова у них обязаны совпадать дословно: человек читает причину в
 * меню, жмёт всё равно (быстрая смена статуса переносит `disabled` на тег, но путей к приёмке два)
 * и получает второй, другой по формулировке отказ — и решает, что это две разные поломки. Своя
 * строка на каждой стороне разошлась бы на первой же правке формулировки, и разошлась бы молча.
 *
 * Замок стоит ровно у `pending`. У `rejected` его нет намеренно (Р16): проверка закончена, и
 * заявка, по которой работу уже выполнили, не должна застревать в «Решена» из-за справочника.
 */
export const CANDIDATE_PENDING_ACCEPT_REFUSAL = 'Сначала дождитесь решения по технике';

/**
 * Ответ ТРЁХ РУЧЕК РЕШЕНИЯ (план кандидатов, §10). Тот же кандидат плюс исход почтовой части —
 * аддитивно, двумя необязательными полями, а не новой обёрткой `{ candidate, mail }`.
 *
 * ФОРМА ОТВЕТА НЕ МЕНЯЕТСЯ НАМЕРЕННО. Обёртка была бы честнее по форме и хуже по цене: очередь и
 * карточка читают тот же DTO, портал волны кандидатов пишется прямо сейчас, и смена корня ответа
 * означала бы правку в чужих руках ради двух полей, которые старый клиент просто не заметит.
 * Необязательность здесь — не «может не прийти когда как»: поля стоят у всех трёх решений и
 * отсутствуют ровно там, где кандидат приезжает НЕ решением (очередь, карточка, встроенный блок
 * заявки), — то есть отсутствие поля означает «этот ответ про почту ничего не утверждает».
 *
 * `mail` — общий исход по ОБЯЗАТЕЛЬНОЙ цели письма (автор сообщения), `mailTargets` — разбор по
 * целям: копия, ушедшая наблюдателю, не отменяет того, что сам заявитель о решении не узнал.
 * Правило то же, что у заявок (`ServiceMailTargets`), и второго правила здесь быть не должно.
 */
export interface OfficeEquipmentCandidateDecisionDto extends OfficeEquipmentCandidateDto {
  mail?: ModuleMailOutcome;
  mailTargets?: ServiceMailTargets;
}
