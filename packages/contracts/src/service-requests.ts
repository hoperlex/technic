/**
 * Шаг, которого ждут **от конкретной стороны** в этом статусе. Нужен там, где одного статуса
 * недостаточно, — а после слияния (Р2) таких статусов ровно два: «Новая» без исполнителей ждёт
 * распределения, а с исполнителями — что за неё возьмутся; «В работе» с непогашенным предъявлением
 * ждёт подписи под объёмом работ, без него — самих работ.
 *
 * Признаки Р2 сюда не передаются, и это не срезание угла: сторону ожидания считает по ним же
 * `serviceRequestWaitingOn`, а второй разбор тех же двух колонок здесь разошёлся бы с очередью
 * МОЛЧА — подпись звала бы к одному шагу, а бейдж «ждут меня» отбирал бы заявки по другому
 * правилу. Поэтому аргумента два, и второй — уже посчитанный ответ очереди.
 *
 * Словарь `serviceStepLabels` остаётся: он отвечает на вопрос «что за шаг ждут в этом статусе»
 * вообще — им подписывают чужой ход («Ждёт исполнителя»), где сторона уже названа. Эта функция
 * отвечает на «что делать **мне**».
 */
export function serviceStepLabelFor(
  status: ServiceRequestStatus,
  waiting: ServiceWaitingOn,
): string {
  // «Новая», за которую уже кто-то отвечает: распределять нечего — ход за исполнителем (Р6).
  if (status === 'new' && waiting === 'service') return 'принять в работу';
  // «В работе» с висящим предъявлением: ждут подписи, а не работ (Р3).
  if (status === 'in_work' && waiting === 'approval') return 'согласовать объём работ';
  return serviceStepLabels[status];
}

/**
 * Закрытая заявка: ни ход, ни правка ей больше не положены. Отложенная закрытой не считается
 * (Р109): движение остановлено, но заявка жива — техника ждёт этого же ремонта, и вторую на ту же
 * единицу заводить нельзя.
 */
export function isServiceRequestClosed(status: ServiceRequestStatus): boolean {
  return status === 'accepted' || status === 'cancelled';
}

