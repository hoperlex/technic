/**
 * Есть ли у заявки письмо, которое можно повторить. Одна функция на сервер и портал: разойдись
 * они — кнопка вела бы в 422 либо повтор оставался бы недоступным там, где сервер его позволяет.
 *
 * Событие письма привязано к **входу в статус**, поэтому повторяются ровно два: «Новая» (служба
 * зовётся разобрать заявку) и «Отменена» (чтобы не выезжали зря).
 *
 * Строку, а не голый статус (Р14): у «Новой» письмо зовёт службу РАЗОБРАТЬ заявку, и повторять его
 * после назначения незачем — задание исполнителю ушло своим письмом, привязанным к действию. Пока
 * «Новая» означала «ещё не назначена», на этот вопрос отвечал статус; после слияния он половину
 * ответа потерял бы молча — кнопка осталась бы на месте, а письмо звало бы разбирать заявку,
 * которую уже разобрали.
 */
export function serviceMailRepeatable(
  row: ServiceExecutorsRow & { status: ServiceRequestStatus },
): boolean {
  if (row.status === 'cancelled') return true;
  return row.status === 'new' && !serviceHasExecutors(row);
}

/**
 * Правит ли субъект саму заявку: заказчик — пока её никому не отдали (§6.1). После назначения за
 * заявкой стоят договорённости с исполнителем, и менять её предмет задним числом нельзя.
 *
 * Строку, а не голый статус (Р14). Набор заявок при этом не изменился: прежняя «Новая» и была
 * заявкой без исполнителей — назначение уводило её в «Назначенную», — и условие переписано ровно
 * затем, чтобы остаться верным после слияния. Оставь мы `status === 'new'`, правка молча открылась
 * бы у заявки, которую исполнитель уже прочитал и по которой договорился.
 *
 * `it_approved` из списка ушёл вместе с самим статусом (`0197`): заявок в нём больше не бывает, и
 * ветка под него отвечала бы на вопрос, которого никто не задаёт.
 *
 * `on_hold` в список не входит (Р110): заморозка останавливает ход заявки, и правка её предмета
 * была бы ходом мимо остановки. Отложенную из «Новой» правят, вернув в работу.
 */
export function isServiceRequestEditable(
  row: ServiceExecutorsRow & { status: ServiceRequestStatus },
): boolean {
  return row.status === 'new' && !serviceHasExecutors(row);
}

/**
 * Удаляет ли субъект заявку — в архив. Своё правило, а не «то же, что правка» (В20): удалять можно
 * и заявку, которую уже кому-то назначили, — работа по ней не начиналась, — а править её уже
 * нельзя: предмет заявки исполнитель прочитал и по нему договорился. Переиспользуй мы
 * `isServiceRequestEditable`, два разных решения заказчика держались бы на одном условии и
 * разъехались бы на первой же правке любого из них.
 *
 * ПОВЕДЕНИЕ СЛИЯНИЕ НЕ ИЗМЕНИЛО, и это проверено, а не предположено: удаляли «Новую» и
 * «Назначенную» — то есть заявку до того, как за неё взялись, — оба состояния теперь зовутся
 * «Новой», и один `new` покрывает ровно тот же набор заявок, что покрывала прежняя пара. Записано
 * это здесь затем, чтобы следующая правка не приняла совпадение с `isServiceRequestEditable` за
 * недосмотр и не свела оба правила к одному: условие правки ДРУГОЕ — она требует ещё и отсутствия
 * исполнителей (Р14). Строка сюда поэтому и не передаётся: статуса достаточно.
 *
 * Дальше удаление не идёт ни при каких условиях: с «В работе» по заявке уже могли списать
 * расходники (Р6), и архивная заявка означала бы списание без основания.
 */
export function isServiceRequestDeletable(status: ServiceRequestStatus): boolean {
  return status === 'new';
}

