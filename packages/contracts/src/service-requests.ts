/**
 * Срочность: флаг и объяснение неразрывны (то же CHECK держит и БД). Чекбокс без причины через
 * месяц стоит у всех заявок — отбирать им становится нечего, а очередь, отсортированная по
 * признаку, который есть у каждого, ничем не отличается от несортированной.
 *
 * Проверка вынесена функцией, а не написана схемой на месте: срочность ставят в трёх местах
 * (заведение, правка, своя ручка), и в правке пара приходит наполовину — `PATCH` присылает только
 * изменившееся. Там условие считается по «склеенному» состоянию на сервере, а не по телу запроса.
 */
export const urgencyReasonSchema = z.string().trim().max(500);

export function urgencyIssue(value: { isUrgent: boolean; urgencyReason: string }): string | null {
  const reason = value.urgencyReason.trim();
  if (value.isUrgent && !reason) return 'Объясните, почему заявка срочная';
  if (!value.isUrgent && reason) return 'Причина без отметки «Срочная» ничего не объявляет';
  return null;
}

/** Схема с полной парой: заведение и своя ручка присылают оба поля разом. */
const withUrgency = <T extends z.ZodType<{ isUrgent: boolean; urgencyReason: string }>>(
  schema: T,
): T =>
  schema.superRefine((value, ctx) => {
    const issue = urgencyIssue(value);
    if (issue) {
      ctx.addIssue({ code: z.ZodIssueCode.custom, message: issue, path: ['urgencyReason'] });
    }
  }) as unknown as T;

export const createServiceRequestSchema = withUrgency(
  z.object({
    /**
     * Аппарат — НЕОБЯЗАТЕЛЕН (Р5, ADR 0146, решение 6): половина работы модуля предметом в
     * справочнике не описывается вовсе («поставьте розетку», «настройте почту новому сотруднику»,
     * «принтер привезли, инвентарного номера ещё нет»), и до сих пор такую заявку заводили на
     * посторонний аппарат — после чего вся история обслуживания этой единицы врала.
     *
     * **Пустой аппарат схема принимает ВСЕГДА, а отказывает по нему МАРШРУТ** — правом
     * `serviceRequests.createWithoutEquipment` и кодом 403. Запиши мы условие «поле обязательно у
     * того, у кого нет права», рядовой заявитель получал бы 422 по полю: «заполните аппарат» —
     * то есть ответ «вы ошиблись формой» там, где человек не ошибся ничем, ему просто не положено.
     * Схема к тому же прав не видит и видеть не может: она одна на все учётки.
     *
     * `nullish`, а не `optional`: `null` и «поля нет» означают здесь **одно и то же** — аппарата у
     * заявки нет. Это не тот случай, что у `customerDepartmentId` ниже, где `null` — самостоятельный
     * ответ («заявка от площадки, подсказку не применять»): подсказывать аппарат неоткуда, и
     * различать два вида пустоты было бы различением без последствий.
     */
    officeEquipmentId: uuidSchema.nullish(),
    /**
     * ТРЕТИЙ СПОСОБ НАЗВАТЬ ПРЕДМЕТ — сообщение об аппарате, которого нет в справочнике (план
     * `docs/office-equipment-candidate-plan.md`, Р2, Р5).
     *
     * Кандидат приезжает ТЕМ ЖЕ ЗАПРОСОМ, что и заявка, а не отдельной ручкой «сначала кандидат,
     * потом заявка»: та оставляла бы кандидатов-сирот при каждом обрыве на втором шаге и требовала
     * бы уборки. Обе строки появляются одной транзакцией либо не появляются вовсе.
     *
     * Поле необязательное, потому что способов назвать предмет три и схема сверяет их между собой
     * ниже, в `superRefine`. Право `officeEquipment.propose` при этом спрашивает МАРШРУТ и отвечает
     * 403 — ровно по тому же доводу, что и у пустого аппарата выше: схема одна на все учётки и прав
     * не видит, а «заполните аппарат» в ответ рядовому заявителю означало бы «вы ошиблись формой»
     * там, где человек не ошибся ничем.
     *
     * `lazy`, а не прямая ссылка на схему, — из-за кольца импортов, и это не осторожность впрок:
     * файл кандидата берёт у справочника `createOfficeEquipmentSchema` (полная форма карточки в
     * подтверждении, Р13), справочник берёт отсюда `projectByAudiencePolicy`, и прямая ссылка
     * замкнула бы тройку на ЗНАЧЕНИИ, вычисляемом при загрузке модуля. Порядок вычисления модулей
     * в кольце зависит от того, кто вошёл первым, и одно из направлений входа падало бы с
     * «Cannot access before initialization» — молча и не у всех. `lazy` откладывает обращение к
     * схеме до первого разбора, когда все три модуля уже вычислены.
     */
    equipmentCandidate: z.lazy(() => equipmentCandidateInputSchema).optional(),
    /**
     * «Не тот объект» (Р16, ответ В3): аппарат стоит не там, где записано в его карточке, и объект
     * заявки называет человек. Пара «объект + пометка», а не одно поле, потому что признаков в
     * модели два и делят они работу так: ХРАНИМАЯ пометка — факт заявления («объект в этой заявке
     * указал человек, а не подставила карточка»), она исторична и неизменна, как остальные снимки
     * заявки; РАСХОЖДЕНИЕ — величина вычисляемая, соединением с карточкой техники, и гаснет оно
     * само, когда ИТ-служба перенесёт единицу в справочнике. Хранимый флаг сам не гаснет ничем, и
     * отбор по нему через месяц перестал бы быть очередью, став списком всего, что когда-либо
     * поправляли.
     *
     * Справочник заявка не правит: перенос единицы — решение ИТ-службы после проверки, а карточку
     * заводит всякий заявитель, и опечатка в заявке возила бы аппараты по объектам.
     *
     * Чужой объект отбивает сервер (422): `equipment_object_id` задаёт область видимости роли
     * объекта, и свободный выбор означал бы, что заявку можно отправить в чужую область — и увести
     * из своей. Портал показывает тот же отбор по привязкам автора, но портал не защита.
     *
     * У ЗАЯВКИ БЕЗ АППАРАТА У ЭТОГО ПОЛЯ ВТОРОЙ СМЫСЛ (Р6): оно называет не «где стоит аппарат», а
     * **заказчика** — площадку, от имени которой заявка. Колонка та же (`equipment_object_id`), и
     * это не совпадение: областью роли площадки заведует именно она, и завести туда заявку иначе
     * значило бы завести вторую колонку с тем же назначением. Пометка при этом запрещена (ниже), и
     * потому два смысла не путаются: с пометкой — «не тот объект», без аппарата — «для кого».
     */
    objectId: uuidSchema.optional(),
    objectOverridden: z.boolean().optional().default(false),
    /**
     * Вид заявки (Н1). До выпуска 3 контракт заведения этого поля не имел вовсе, и заявка на
     * расходники была незаводима — не запретом, а отсутствием поля (§7.3 плана): без строк
     * номенклатуры, формы и списания она была бы заявкой без предмета. Поле появляется вместе с
     * M12, то есть вместе со строками, формой и списанием.
     *
     * `optional()` БЕЗ `default('repair')`, и это не небрежность. `default` в zod делает поле
     * обязательным в РАЗОБРАННОМ теле, а его строит портал объектным литералом — то есть каждый
     * существующий вызов заведения пришлось бы дописать полем, которого он не знает. Умолчание при
     * этом никуда не девается: оно стоит колонкой в базе (`DEFAULT 'repair'`, M3) и останется там
     * навсегда. «Поля нет» читается как «ремонт» — ровно так, как читает его старый код в окне
     * выката.
     */
    kind: serviceRequestKindSchema.optional(),
    /**
     * Строки номенклатуры — у заявки на расходники и только у неё (§6.2). Обязательными они быть
     * перестали (Р15): заявитель номенклатуры не знает, и его дело — сказать словами, чего не
     * хватает; состав заполняет исполнитель ручкой `PUT /:id/consumables`.
     *
     * Принимать их заведение продолжает, и это не остаток прежнего правила: заявку заводит и
     * ИТ-служба за сотрудника, зная состав сразу, — запретив, мы заставили бы её делать два шага
     * там, где хватало одного.
     *
     * `optional()` без `default([])` по той же причине, что у вида выше: пустой список и
     * отсутствие поля означают здесь одно и то же — «строк нет», — и платить за их различение
     * правкой каждого существующего вызова заведения не за что.
     */
    consumables: z.array(serviceConsumableLineSchema).max(50).optional(),
    description: descriptionSchema,
    /**
     * Отдел, от имени которого заявка (ADR 0085 §8). Подсказывается владельцем техники либо
     * единственным отделом автора, но выбирается человеком: сотрудник соседнего отдела чинит «чужой»
     * принтер чаще, чем кажется.
     *
     * `null` и «поля нет» — разные ответы, и разница здесь важнее самого поля: `null` означает
     * **заявка от площадки, подсказку не применять** — так отвечает форма, где заказчик обязателен
     * и пустого состояния у него нет; `undefined` означает «клиент про поле не знает», и только
     * тогда сервер подставляет подсказку (Р12, Р12а).
     */
    customerDepartmentId: uuidSchema.nullish(),
    /**
     * Подразделение **заявителя** (Н11) — не заказчик выше: заказчика выбирает человек («чужой»
     * принтер соседнего отдела), а здесь записано, где числится он сам.
     *
     * Присылают эти два поля **только чтобы выбрать одно из своих**: сервер берёт привязки учётки
     * `created_by` и на чужое отвечает 422. Единственная привязка подставляется без вопроса, и
     * тогда полей в теле нет вовсе; выбор требуется лишь у учётки с двумя отделами (или двумя
     * площадками). Прислать оба сразу нельзя — подразделение либо отдел, либо площадка.
     */
    requesterDepartmentId: uuidSchema.nullish(),
    requesterObjectId: uuidSchema.nullish(),
    /**
     * Заявитель и его телефон — обязательны (план модернизации, Р49). До этого обязательность жила
     * только в форме портала (`ResponsibleFields`), а схема принимала пустые строки: заявка без
     * контакта заводилась любым клиентом мимо формы, и именно её сервис получал первой — ехать по
     * адресу, не зная, к кому.
     */
    responsibleName: contactNameSchema,
    responsiblePhone: contactPhoneSchema,
    comment: z.string().trim().max(2000).optional().default(''),
    warrantyClaim: warrantyClaimSchema.optional(),
    isUrgent: z.boolean().optional().default(false),
    urgencyReason: urgencyReasonSchema.optional().default(''),
    fileIds: z.array(uuidSchema).max(20).optional().default([]),
  }),
).superRefine((value, ctx) => {
  /**
   * Правила предмета расходятся НАТРОЕ — ровно как трёхсоставный `service_requests_subject_check`
   * (миграции 0230 и 0264, Р7 ADR 0146 и Р5 плана кандидатов). У заявки С АППАРАТОМ объект — это
   * «где он стоит», и он ходит парой с пометкой; у заявки БЕЗ АППАРАТА тот же `objectId` означает
   * уже другое — **заказчика**, — и пометке там взяться неоткуда; у заявки С КАНДИДАТОМ предмет
   * называет сам заявитель, и место аппарата приезжает внутри кандидата. Одним общим набором
   * условий эти три смысла не описываются: «объект без пометки ничего не объявляет» верно только в
   * первой части и запрещало бы вторую, а XOR «объект либо отдел» верен во второй и запретил бы
   * третью (заявку от лица отдела на кандидата, Р7, последний абзац).
   *
   * ВЕТКА КАНДИДАТА ОТДЕЛЯЕТСЯ ПЕРВОЙ, и порядок здесь содержателен: способы назвать предмет
   * ВЗАИМОИСКЛЮЧАЮЩИ (Р2), и «прислали два сразу» обязано читаться отказом про кандидата, а не
   * молчаливым выбором одного из двух по порядку разбора.
   */
  if (value.equipmentCandidate) {
    /*
     * ЧЕТЫРЕ ЗАПРЕТА ВЕТКИ, и каждый закрывает своё, а не «поле, которое здесь не нужно»:
     *
     *   * АППАРАТ ССЫЛКОЙ — второй способ назвать тот же предмет. Прими мы оба, сервер завёл бы
     *     кандидата на аппарат, который заявитель тут же и выбрал, а проверяющий получил бы в
     *     очередь сообщение о технике, стоящей в справочнике. Отказ до всякой работы (Р2);
     *   * ПОМЕТКА «НЕ ТОТ ОБЪЕКТ» — утверждение о РАСХОЖДЕНИИ снимка заявки с карточкой единицы, а
     *     карточки ещё нет: расходиться не с чем. Место аппарата здесь называет сам кандидат
     *     (`equipmentCandidate.objectId`), и второго способа сказать то же самое не заводится;
     *   * ОБЪЕКТ ВЕРХНЕГО УРОВНЯ — тот же самый второй способ. Молча проигнорировать его нельзя:
     *     человек, приславший заявку с одним объектом снаружи и другим внутри кандидата, обязан
     *     узнать, какой из них не сработал, а не искать потом заявку в чужой области;
     *   * ГАРАНТИЙНОЕ ОБРАЩЕНИЕ — спор о КОНКРЕТНОЙ единице и её гарантии поставщика, которую
     *     читают из карточки парка. У непроверенного предмета карточки нет, и гарантию читать
     *     неоткуда (Р16: тот же запрет держит и сервер, пока кандидат `pending`).
     *
     * А `customerDepartmentId` ЗАКОННЫМ ОСТАЁТСЯ, и это не забытый пятый запрет (Р7, последний
     * абзац). Заявку на кандидата заводят и от лица отдела: тогда `customer_department_id` держит
     * заказчика, а `equipment_object_id` — физическое место аппарата. Запрети мы пару, сотрудник
     * отдела потерял бы собственную заявку сразу после отправки по правилу ADR 0146 — она ушла бы
     * в объектную область, которой у него нет.
     */
    if (value.officeEquipmentId != null) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        message: 'Предмет заявки один: либо аппарат из справочника, либо сообщение о новом',
        path: ['equipmentCandidate'],
      });
    }
    if (value.objectOverridden) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        message: 'Пометка «не тот объект» бывает только у заявки с аппаратом из справочника',
        path: ['objectOverridden'],
      });
    }
    if (value.objectId) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        message: 'Место аппарата называет само сообщение о технике — объект заявки не нужен',
        path: ['objectId'],
      });
    }
    if (value.warrantyClaim?.source) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        message: 'Обращаются по гарантии аппарата из справочника, а этот ещё не проверен',
        path: ['warrantyClaim'],
      });
    }
  } else if (value.officeEquipmentId != null) {
    // Пометка «не тот объект» и сам объект — одно утверждение, а не два соседних поля, и
    // проверяются они парой ровно как срочность с её причиной: пометка без объекта не говорит, где
    // аппарат стоит на самом деле, а объект без пометки — молчаливая подмена области видимости.
    if (value.objectOverridden && !value.objectId) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        message: 'Укажите, на каком объекте стоит аппарат',
        path: ['objectId'],
      });
    }
    if (!value.objectOverridden && value.objectId) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        message: 'Объект без пометки «не тот объект» ничего не объявляет',
        path: ['objectOverridden'],
      });
    }
  } else {
    /*
     * ДВЕ ЗАКРЫТЫЕ ДВЕРИ (Р7). Обе — не «пока не сделали», а «не бывает вовсе»:
     *
     *   * пометка «не тот объект» — утверждение о РАСХОЖДЕНИИ снимка заявки с карточкой единицы;
     *     без единицы расходиться не с чем, а поднятая пометка сделала бы объект-заказчика
     *     похожим на исправление несуществующей карточки — и он попал бы в очередь ИТ-службы
     *     «перенесите аппарат», где переносить нечего;
     *   * гарантийное обращение — спор о КОНКРЕТНОЙ единице: либо о гарантии поставщика на неё,
     *     либо о работе, выполненной на ней же. Сервер отвечает то же самое и по существу
     *     (`resolveWarrantyClaim`), но схема успевает раньше и называет поле.
     */
    if (value.objectOverridden) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        message: 'Пометка «не тот объект» бывает только у заявки с аппаратом',
        path: ['objectOverridden'],
      });
    }
    if (value.warrantyClaim?.source) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        message: 'Обращаются по гарантии конкретного аппарата, а у этой заявки аппарата нет',
        path: ['warrantyClaim'],
      });
    }
    /*
     * ЗАКАЗЧИК РОВНО ОДИН — объект ИЛИ отдел (Р7), тем же XOR, что стоит второй ветвью
     * `service_requests_subject_check`. Обе половины условия обязательны, и обе отвечают на свой
     * вопрос:
     *
     *   * ДВОЕ СРАЗУ — заявка, которую роль площадки и роль отдела считают своей каждая: предикат
     *     области читает те же три колонки, и такая строка попадает в оба среза;
     *   * НИ ОДНОГО — заявка вне области ЛЮБОЙ роли: её не увидит никто, включая автора, если он
     *     сам площадочный или отдельский.
     *
     * Отбивает это схема, а база стоит вторым рубежом: без схемы человек получил бы `23514` вместо
     * фразы, а поля отказ не назвал бы вовсе.
     */
    const byObject = !!value.objectId;
    const byDepartment = !!value.customerDepartmentId;
    if (byObject && byDepartment) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        message: 'У заявки без аппарата заказчик один: либо объект, либо отдел',
        path: ['objectId'],
      });
    }
    if (!byObject && !byDepartment) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        message: 'Укажите, для кого заявка: объект или отдел',
        path: ['objectId'],
      });
    }
  }
  // Требования «хотя бы одна позиция» у расходников больше нет (Р15): предмет такой заявки —
  // описание словами, а номенклатуру заполняет исполнитель. Обратная проверка осталась: строки у
  // ремонта — это состав, который никто не выдаст и не спишет, потому что формы у него нет.
  const lines = value.consumables ?? [];
  if (value.kind !== 'consumable' && lines.length > 0) {
    ctx.addIssue({
      code: z.ZodIssueCode.custom,
      message: 'Строки номенклатуры бывают только у заявки на расходники',
      path: ['consumables'],
    });
  }
  addConsumableDuplicateIssues(lines, ctx, ['consumables']);
});
