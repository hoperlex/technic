// кнопки: «Назначена» — что распределивший уже нажал, а исполнитель ещё нет; «Смета на
// согласовании» — что счёт предъявлен, а ответа на него нет. Оба ожидания видны по самой строке
// заявки, и вместо статусов их называют два признака (Р2): `serviceHasExecutors` и
