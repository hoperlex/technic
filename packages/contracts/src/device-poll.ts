import { z } from 'zod';
import { metricUnits, type MetricCode, type MetricUnit } from './device-telemetry';

/**
 * ОПРОС АППАРАТА ПО СЕТИ (SNMP) — второй способ снять показание, рядом с почтовым приёмом
 * (`device-telemetry.ts`).
 *
 * ЧЕМ ОТЛИЧАЕТСЯ ОТ ПОЧТЫ И ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ФАЙЛ. Письмо приходит само и несёт то, что решил
 * прислать аппарат; опрос спрашивает ровно то, что мы хотим, и ровно тогда, когда нажали кнопку.
 * Отсюда у опроса есть то, чего у письма нет вовсе: адрес, срок ожидания, исход попытки и сверка
 * «по этому адресу отвечает тот самый аппарат». Словарь метрик при этом ОБЩИЙ — второй завести
 * нельзя, иначе ряд наработки разъедется по источникам (см. `metricUnits`).
 *
 * ИСТОЧНИК У ЗАПИСАННОГО ПОКАЗАНИЯ — `collector`, и четвёртого не заводится. `collector` означает
 * «снято опросом», а не «снято отдельной программой на объекте»: когда опрос переедет с сервера на
 * узел в офисной сети (docs/equipment-collector-plan.md), изменится место исполнения, а не способ
 * получения — и ряд наработки не должен об этом переезде узнать.
 */

// ── Что спрашиваем у аппарата ──

/**
 * Пять OID стандартной Printer-MIB v2. Набор взят из §3.1
 * `docs/office-equipment-usage-plan.md` и здесь не расширяется: фирменные OID вендоров — предмет
 * второго этапа, когда цели опроса станут редактируемыми.
 *
 * ПОЧЕМУ СЕРИЙНИК И ЕДИНИЦА СПРАШИВАЮТСЯ ВСЕГДА, хотя нужен один счётчик. Серийник — единственная
 * защита от «по адресу стоит другой аппарат» (DHCP выдал адрес соседу), а единица — от того, что
 * листы лягут в ряд оттисков: у Ricoh единица счётчика настраивается на самом аппарате, и снятое
 * число без неё не значит ничего.
 */
export const DEVICE_POLL_OIDS = {
  /** `sysDescr` — строка, которой аппарат представляется; показывается человеку как есть. */
  sysDescr: '1.3.6.1.2.1.1.1.0',
  /** `sysName` — сетевое имя. */
  sysName: '1.3.6.1.2.1.1.5.0',
  /** `prtGeneralSerialNumber` — серийный номер, которым аппарат сам себя называет. */
  serial: '1.3.6.1.2.1.43.5.1.1.17.1',
  /** `prtMarkerCounterUnit` — в чём считает счётчик: оттиски, листы, что-то ещё. */
  counterUnit: '1.3.6.1.2.1.43.10.2.1.3.1.1',
  /** `prtMarkerLifeCount` — накопительный счётчик за жизнь маркера. */
  counter: '1.3.6.1.2.1.43.10.2.1.4.1.1',
} as const;

export type DevicePollOidKey = keyof typeof DEVICE_POLL_OIDS;

/**
 * Значения `PrtMarkerCounterUnitTC`, которые мы умеем положить в ряд наработки. Перечень намеренно
 * короткий: у метрики единица одна и объявлена реестром (`metricUnits`), поэтому «часы», «символы»
 * и «строки» из той же таблицы MIB нам не метрика, а повод отказаться писать.
 */
export const DEVICE_COUNTER_UNITS: Record<number, MetricCode> = {
  7: 'marker_life_total',
  8: 'printed_sheets_total',
};

/**
 * Какую метрику писать по ответу аппарата.
 *
 * ЕДИНИЦА РЕШАЕТ КОД МЕТРИКИ, А НЕ НАОБОРОТ. Соблазн записать всё в `marker_life_total` велик —
 * это «общий счётчик», и аппарат его так и называет. Но метрика несёт единицу (`metricUnits`), и
 * счётчик, настроенный на листы, попав в ряд оттисков, испортил бы его тихо: числа продолжали бы
 * расти, а месячная дельта считалась бы по двум разным физическим величинам.
 */
export function metricForCounterUnit(unit: number): MetricCode | null {
  return DEVICE_COUNTER_UNITS[unit] ?? null;
}

// ── Исход попытки ──

/**
 * Чем закончился опрос. Перечень закрыт и живёт здесь, потому что подписи к нему нужны и порталу
 * (карточка цели), и базе (ограничение журнала попыток).
 */
export const DEVICE_POLL_OUTCOMES = [
  /** Снято и записано; серийник аппарата совпал с объявленным. */
  'ok',
  /** Снято и записано, но серийник аппарат не сообщил — сверить было нечем. */
  'ok_unverified',
  /**
   * Снято, но записывать некуда: карточки с таким серийным номером в справочнике нет (или у цели
   * номер не задан вовсе). Число видно в журнале попытки и НЕ попадает в ряд наработки — ряд
   * принадлежит аппарату, а не адресу.
   */
  'no_equipment',
  /** Ответил аппарат с другим серийным номером: писать его счётчик в чужую карточку нельзя. */
  'serial_mismatch',
  /** Ответ есть, счётчика по стандартному OID у аппарата нет. */
  'no_counter',
  /** Счётчик есть, но считает в единице, которой у нас нет метрики. */
  'unit_unknown',
  /** Ответа не было вовсе: нет маршрута, аппарат выключен, пакет отфильтрован. */
  'no_answer',
  /** Аппарат ответил отказом SNMP (чаще всего — не та community). */
  'snmp_error',
  /** Ответ пришёл, но разобрать его не удалось. */
  'bad_response',
] as const;
export type DevicePollOutcome = (typeof DEVICE_POLL_OUTCOMES)[number];

export const devicePollOutcomeLabels: Record<DevicePollOutcome, string> = {
  ok: 'Снято',
  ok_unverified: 'Снято, серийник не подтверждён',
  no_equipment: 'Снято, карточка не найдена',
  serial_mismatch: 'Отвечает другой аппарат',
  no_counter: 'Счётчика нет',
  unit_unknown: 'Неизвестная единица счётчика',
  no_answer: 'Нет ответа',
  snmp_error: 'Отказ аппарата',
  bad_response: 'Ответ не разобран',
};

/**
 * Исходы, при которых показание записано в ряд наработки. Спрашивается обеими сторонами: сервер
 * решает по нему, писать ли наблюдение, портал — показывать ли число как снятое.
 */
export const DEVICE_POLL_WRITTEN_OUTCOMES: readonly DevicePollOutcome[] = ['ok', 'ok_unverified'];

export function devicePollWroteValue(outcome: DevicePollOutcome): boolean {
  return DEVICE_POLL_WRITTEN_OUTCOMES.includes(outcome);
}

/**
 * Единица показания берётся из реестра метрик, а не из ответа аппарата: у аппарата спрашивают, ЧТО
 * он считает, а как эта величина называется в портале — знает реестр. Второй носитель единицы
 * разошёлся бы с ним на первой правке.
 */
export function devicePollUnit(metricCode: MetricCode): MetricUnit {
  return metricUnits[metricCode];
}

// ── Ключ цели ──

/**
 * Ключ цели опроса: им цель названа в настройке и им же её зовёт портал. Ограничен строго, потому
 * что едет в путь ручки.
 */
export const devicePollKeySchema = z
  .string()
  .min(1)
  .max(40)
  .regex(/^[a-z0-9][a-z0-9-]*$/, 'Ключ цели — латиница, цифры и дефис');

export const devicePollKeyParamsSchema = z.object({ key: devicePollKeySchema });

// ── Что портал показывает ──

/** Одна попытка опроса: что ответил аппарат и чем это кончилось. */
export interface DevicePollAttemptDto {
  id: string;
  /** Момент начала опроса; он же — время наблюдения, если показание записано. */
  startedAt: string;
  durationMs: number;
  outcome: DevicePollOutcome;
  /** Объяснение исхода словами — то, что показывается человеку вместо кода. */
  message: string;
  sysDescr: string;
  sysName: string;
  /** Серийник, которым назвался ответивший аппарат; пусто — не сообщил. */
  deviceSerial: string;
  metricCode: MetricCode | null;
  /** Снятое число; `null` — снять не удалось (см. `outcome`). */
  value: number | null;
  unit: MetricUnit | null;
  /** Кто нажал кнопку; `null` — учётка снята. */
  requestedBy: string | null;
}

/**
 * Цель опроса — карточка на вкладке.
 *
 * АДРЕС ПОКАЗЫВАЕТСЯ, COMMUNITY — НЕТ, и это не забывчивость. В SNMP v2c community едет открытым
 * текстом и служит паролем чтения: выведенная на экран, она уехала бы в снимок экрана, в переписку
 * и в тикет, а сменить её на парке аппаратов дороже, чем не показывать.
 */
export interface DevicePollTargetDto {
  key: string;
  label: string;
  /** `хост:порт`, как опрашиваем. */
  address: string;
  /** Серийник, который объявлен в настройке: и ключ привязки к карточке, и предмет сверки. */
  expectedSerial: string;
  /** Карточка аппарата, найденная по серийнику; `null` — в справочнике такого номера нет. */
  equipment: { id: string; title: string } | null;
  lastAttempt: DevicePollAttemptDto | null;
}

export interface DevicePollTargetsDto {
  items: DevicePollTargetDto[];
}
