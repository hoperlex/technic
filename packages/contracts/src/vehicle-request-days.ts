// ── Дни заказа техники на объект (ADR 0100) ──
// Линейная техника вечером возвращается на базу, а за день успевает поработать на двух-трёх
// площадках. Ради неё дни и заведены: каждый день срока — отдельный выезд, который кладут в рейс
// машины на эту дату и печатают в его 4-П.
//
// Но дверь в дни линейностью больше не заперта: дни ведутся у ЛЮБОГО заказа техники на объект.
// Замок снят вместе с приходом пакетной выписки «4-П на весь период»: 4-П за день просят и у
// машины, которая неделю стоит на площадке, — выезд за топливом, возврат в гараж, требование
// заказчика, — и отказ по типу техники означал бы «такой бумаги не бывает» там, где её всё равно
// выписывают мимо портала. Признак типа отвечает на вопрос «как заявка ведётся по умолчанию», а не
// «бывает ли у этого дня бумага», и воротить дверь он не вправе.
//
// Цена решения названа прямо: у нелинейного заказа недельный ЭСМ-2 продолжает выписываться сам
// (миграция 0087), и за один и тот же день бумаги бывает две — недельный ЭСМ-2 и дневной 4-П.
// Это принято осознанно: документы разные и считают разное (ЭСМ-2 — машино-часы стояния на
// площадке, 4-П — выезд машины), и глушить один ради другого значило бы решать за диспетчера,
// какой из них ему сегодня нужен.
//
// Своей таблицы у дней нет и не будет (ADR 0100 §2): перечень выводится из срока заявки тем же
// приёмом, каким выводятся дни смен (`shiftDaysOf`), а материализуется только факт «этот день
// поставлен в такой-то рейс» — колонкой `work_date` в составе рейса (миграция 0127).
//
// Правила живут здесь, а не на сервере, по той же причине, что и правила смен и досрочного
// завершения (ADR 0044): портал обязан не предлагать того, что сервер отклонит, — и объяснять
// недоступное теми же словами, которыми откажет API.

/**
 * Заявка глазами правил дней. Структурный тип, а не `Pick` от DTO: модуль стоит в импортах раньше
 * самих заявок, и обратная ссылка замкнула бы круг — тем же порядком устроен `ShiftSubject`.
 */
export interface LinearDaySubject {
  requestType: VehicleRequestType;
  /**
   * Линейный ли **заказанный** тип (ADR 0100 §1). Читается живым признаком справочника: снимка в
   * заявке нет намеренно — заказ решает, как заявка ведётся, а сменить признак под работающими
   * заказами портал не даёт.
   *
   * Доступность дней им больше не решается (`linearDaysBlocker`): поле осталось потому, что по
   * нему выбирают ПОВЕДЕНИЕ — сам ли портал выписывает недельные ЭСМ-2 и чем подписан режим
   * заявки, — а это вопросы соседних модулей, а не этого.
   */
  isLinear: boolean;
  status: RequestStatus;
  deletedAt: string | null;
  dateFrom?: string;
  dateTo?: string | null;
  /** Принадлежность назначенной машины; `null` — техника ещё не назначена. */
  ownership: VehicleOwnership | null;
}

/** Рейс, в который поставлен день: чем и с кем выехали и какая бумага на это выписана. */
export interface VehicleRequestDayRouteDto {
  id: string;
  /** «Р-12» — по нему о рейсе говорят по телефону. */
  displayNumber: string;
  /** Строка задания в бланке; она же `slot` талона заказчика (ADR 0068). */
  position: number;
  vehicleId: string;
  /** «КамАЗ 65201 · Е646СК799» — чем выехали в этот день. */
  vehicleLabel: string;
  /** Пусто — водителя ещё не назначили: рейс собирают заранее, человека ставят утром. */
  driverPersonId: string | null;
  driverName: string;
  /**
   * Лист рейса: действующий замораживает день — снять его с рейса нельзя, бланк уже у водителя
   * (`LINEAR_DAY_FROZEN_MESSAGE`). Аннулированный не держит: испорченный бланк списан.
   */
  waybill: { id: string; number: string; status: WaybillStatus } | null;
  /** Версия рейса — ею снятие дня опознаёт рейс, как перенос заявки опознаёт исходный маршрут. */
  version: number;
}

/**
 * Часы дня и подпись объекта под ними. Ведёт их таблица смен (`vehicle_request_shifts`, ADR 0100
 * §12): ключ `(request_id, shift_date)` у неё уже совпадает с ключом дня, и второй такой таблицы
 * заводить не пришлось. Здесь — короткая выжимка: полную смену показывает своя вкладка.
 */
export interface VehicleRequestDayShiftDto {
  startedAt: string | null;
  endedAt: string | null;
  machineHours: number;
  /** Подпись объекта за этот день; `null` — день ещё не согласован. */
  approvedAt: string | null;
  approvedByName: string | null;
}

/** День заказа техники на объект: сам день, его рейс и то, что за этот день уже подтвердили. */
export interface VehicleRequestDayDto {
  /** `YYYY-MM-DD`. */
  date: string;
  /**
   * День за пределами нынешнего срока. В норме таких не бывает — сверка снимает их с рейсов
   * (`syncLinearRouteDays`), — но замороженный выписанным листом рейс день не отдаёт: срок
   * сократили, а бумага на этот день уже у водителя, и молча спрятать её нельзя.
   */
  outOfTerm: boolean;
  /** Рейс дня; `null` — день ещё не распланирован. */
  route: VehicleRequestDayRouteDto | null;
  /** Смена дня; `null` — часы за этот день ещё не вносили. */
  shift: VehicleRequestDayShiftDto | null;
  /**
   * Машина дня не та, что стоит в назначении заявки. Расхождение законное и помечается, а не
   * отклоняется (ADR 0100 §4): назначение у заказа на объект — машина по умолчанию, а работает в
   * конкретный день та, чьим рейсом день закрыт. Ради этого признак и заведён.
   */
  otherVehicle: boolean;
}

/** Распланированный день до того, как его сверили со сроком: `outOfTerm` считает `linearDaysOf`. */
export type PlannedVehicleRequestDay = Omit<VehicleRequestDayDto, 'outOfTerm'>;

/**
 * Таблица дней заказа и день среза. `blocker` — почему по этой заявке дней не ведут вовсе: у
 * арендной заявки блок дней обязан показывать причину, а не пустую таблицу.
 */
export interface VehicleRequestDaysDto {
  items: VehicleRequestDayDto[];
  /** День среза (`YYYY-MM-DD`) по Москве: его считает сервер — часы клиента бывают сбиты. */
  onDate: string;
  blocker: string | null;
}

/**
 * Почему по этой заявке нельзя вести дни вовсе — текстом, либо `null`, если можно. Одна функция на
 * портал и API: сервер отвечает этой строкой (422), портал ею же объясняет пустую таблицу дней.
 *
 * Порядок — от «это не та заявка» к «этой заявке пока нечем»: первым читается то, что не
 * исправить здесь и сейчас.
 */
export function linearDaysBlocker(r: LinearDaySubject): string | null {
  if (r.requestType !== 'special_equipment') {
    return 'Дни планируют по заказу техники на объект: у грузоперевозки рейс и есть сама работа';
  }
  // Линейности здесь нет намеренно. Прежний отказ «по дням планируют только линейную технику»
  // закрывал дверь по типу заказанной техники, а бумага за день бывает нужна у любого заказа на
  // объект — см. шапку модуля. Признак остался в субъекте, но дверь им больше не воротят: иначе
  // пакетная выписка 4-П на период упиралась бы в запрет, которого продукт уже не держит.
  if (r.deletedAt) return 'Заявка в архиве';
  if (r.status !== 'confirmed') {
    return `Заявка в статусе «${requestStatusLabels[r.status]}» — дни планируют у заявки в работе`;
  }
  // Машина назначения — машина дня по умолчанию (ADR 0100 §4), и без неё непонятно даже, чем
  // заявку взяли в работу. Арендная в рейсы не ходит вовсе: лист на неё выписывает арендодатель,
  // и дней у такого заказа не бывает (план У14).
  if (r.ownership === null) {
    return 'На заявку не назначена техника — дни планировать нечем';
  }
  if (r.ownership !== 'own') {
    return 'Заявку ведут арендной техникой: в рейсы она не ходит, путевой лист на неё выписывает арендодатель';
  }
  if (!r.dateFrom) return 'У заказа не заполнен срок работ — дней у него нет';
  return null;
}

/**
 * Почему нельзя распланировать этот день. Сверх общего запрета — две границы: день обязан
 * принадлежать сроку заявки и не стоять уже в другом рейсе.
 *
 * Будущий день здесь, в отличие от смен, законен и планируется первым делом: рейс на завтра
 * собирают сегодня, ради этого маршруты и заведены. Прошедший — тоже: бумагу оформляют и задним
 * числом, а запрет отправил бы такой выезд мимо портала.
 *
 * Календарной границы у прошедшего дня здесь нет и не будет, но «можно» перестало значить «молча»
 * (ADR 0101 п. 4): день в прошлом сервер планирует только с правом `waybills.correct` и названной
 * причиной — их спрашивает `backdateGuard` в самой ручке, потому что права субъекта этому
 * предикату неизвестны, а он один на портал и сервер. Разделение то же, что у рейса: «есть ли у
 * этого дня основание» отвечает правило, «позволено ли вам прошлое» — право.
 */
export function planDayBlocker(
  r: LinearDaySubject,
  day: string,
  /** Дни этой заявки, уже стоящие в рейсах. */
  plannedDays: readonly string[],
): string | null {
  const blocker = linearDaysBlocker(r);
  if (blocker) return blocker;
  // Те же слова, что у смен (`shiftDayBlocker`): день у них общий, и два разных объяснения одной
  // границы читались бы как две разные границы.
  if (!isShiftDayInTerm(r, day)) return 'День вне срока заявки';
  if (plannedDays.includes(day)) return dayAlreadyPlannedMessage(day);
  return null;
}

/** Можно ли распланировать этот день — тот же разбор, что и `planDayBlocker`. */
export function canPlanDay(
  r: LinearDaySubject,
  day: string,
  plannedDays: readonly string[],
): boolean {
  return planDayBlocker(r, day, plannedDays) === null;
}

/**
 * Отказ снять день с замороженного рейса: бланк уже у водителя, и исчезнуть из него день не
 * может — сначала лист аннулируют. Тем же правилом рейс держит заявку при смене её статуса
 * (`shouldDetachOnStatus`).
 */
export const LINEAR_DAY_FROZEN_MESSAGE =
  'По рейсу этого дня выписан путевой лист — аннулируйте его, чтобы снять день';

/**
 * День, снятый с рейса или оставшийся в нём: им сверка дней объясняется человеку и журналу.
 *
 * Живёт в контрактах, а не на сервере, потому что его показывают: предпросмотр закрытия
 * фактической датой перечисляет им дни, которые уйдут из рейсов, и дни, которых рейс не отдаст
 * (Р11, Р17 плана `docs/vehicle-request-actual-end-date-plan.md`). Исполнимый план — другой тип и
 * остаётся на сервере: там идентификатор рейса и его версия, а здесь то, чем день называют.
 */
export interface LinearDayRef {
  date: string;
  /** «Р-12» — рейс, из которого день сняли или который его не отдал. */
  routeNumber: string;
}

/**
 * Дни срока с приклеенным планом — ими и рисуется таблица «Дни работ».
 *
 * Основа — сам срок: строк в базе на эти дни может не быть вовсе, и пустой день это не пробел, а
 * «на этот день ещё никого не назначили». Распланированные дни за пределами срока не выбрасываются,
 * а помечаются `outOfTerm`: их оставил замороженный лист, и прятать выданную бумагу нельзя.
 */
export function linearDaysOf(
  term: Pick<LinearDaySubject, 'dateFrom' | 'dateTo'>,
  planned: readonly PlannedVehicleRequestDay[],
): VehicleRequestDayDto[] {
  const byDate = new Map(planned.map((day) => [day.date, day]));
  // Дни заказа считаются тем же `shiftDaysOf`, что и дни смен: это один и тот же перечень дней
  // одного и того же срока, и разъехаться им нельзя — иначе таблица дней и таблица смен показали
  // бы разные строки одной заявки.
  const days = new Set(shiftDaysOf(term));
  const items: VehicleRequestDayDto[] = [];
  for (const date of days) {
    const plan = byDate.get(date);
    items.push(plan ? { ...plan, outOfTerm: false } : emptyDay(date));
  }
  for (const plan of planned) {
    if (!days.has(plan.date)) items.push({ ...plan, outOfTerm: true });
  }
  return items.sort((a, b) => a.date.localeCompare(b.date));
}

/** День, на который ещё ничего не назначили: строка в таблице есть, а плана за ней нет. */
function emptyDay(date: string): VehicleRequestDayDto {
  return { date, outOfTerm: false, route: null, shift: null, otherVehicle: false };
}

/**
 * Ответ заказа техники на объект на вопрос рейса о дне (`canJoinRoute`). Собирается одной функцией,
 * а не тремя полями по месту: срок и уже занятые дни — это то, чем такая заявка отличается от
 * грузовой, и складывать их заново в каждом вызывающем значило бы плодить копии правила.
 */
export function linearRouteJoinDay(
  term: Pick<LinearDaySubject, 'dateFrom' | 'dateTo'>,
  plannedDays: readonly string[],
): RouteJoinDay {
  return {
    kind: 'linear',
    dateFrom: term.dateFrom ?? '',
    dateTo: term.dateTo ?? null,
    plannedDays,
  };
}

// ── Схемы ──

/**
 * Поставить день в рейс: в уже заведённый рейс машины на этот день либо в новый, заведённый тут же.
 * Ровно одно из двух — «и то, и другое» означало бы два разных ответа на вопрос, куда едет день.
 *
 * Машина в новом рейсе спрашивается, а не берётся из назначения: у заказа на объект назначение —
 * машина по умолчанию, а на разные дни выходят разные единицы (ADR 0100 §4, §8). Водитель
 * необязателен: рейс собирают заранее, человека ставят утром, — и подставлять вчерашнего портал не
 * вправе (ADR 0083).
 *
 * Дата в теле не передаётся: день — часть адреса (`/days/:date/route`), и второй ответ на «за
 * какой это день» расходился бы с первым — тем же порядком устроены смены.
 *
 * Причина заднего числа (ADR 0101 п. 4) стоит в обеих ветках: планируется день, а не рейс, и
 * прошедшим он бывает независимо от того, заводится маршрут тут же или называется готовый.
 * Обязательной её делает сервер (`backdateGuard`) ровно у прошедшего дня — схема субъекта не знает
 * и требовать объяснение за завтрашний выезд не вправе.
 *
 * Ключа операции здесь нет намеренно: постановка дня в рейс номера строгой отчётности не
 * расходует, строки `waybill_corrections` эта дверь не заводит (§1 плана, уточнение этапа 7), а
 * повторно поставленный день упрётся в свой UNIQUE (миграция 0127) — то есть повтор безопасен и
 * без ключа. Причина у бумаги появится своя: её спросит выписка листа по этому рейсу.
 */
const planDayReasonSchema = z.string().trim().max(2000).optional();

export const planVehicleRequestDaySchema = z.union([
  z.object({ routeId: uuidSchema, reason: planDayReasonSchema }).strict(),
  z
    .object({
      newRoute: z
        .object({
          vehicleId: uuidSchema,
          driverPersonId: uuidSchema.nullable().optional(),
          trip: routeTripFieldsSchema.optional(),
        })
        .strict(),
      reason: planDayReasonSchema,
    })
    .strict(),
]);
export type PlanVehicleRequestDayInput = z.infer<typeof planVehicleRequestDaySchema>;
export type PlanVehicleRequestDayBody = z.input<typeof planVehicleRequestDaySchema>;

// ── Пачка: 4-П на весь период ──
//
// Одно нажатие в карточке заказа техники на объект проходит срок подряд: на каждый день находится
// или заводится рейс назначенной машины, и по нему выписывается 4-П. Своих правил у пачки нет ни
// одного — она повторяет ту же одиночную дверь (`planDayBlocker`, `canJoinRoute`) день за днём, а
// день, который дверь не пускает, пропускает и называет причину строкой отчёта. Второй набор
// правил разошёлся бы с первым молча, и один и тот же день оказался бы то доступен, то нет в
// зависимости от того, какой кнопкой его тронули.
//
// Длинный срок проходится ПОРЦИЯМИ, а не отказывается целиком: за нажатие берётся `DAY_BATCH_LIMIT`
// дней, остаток добирается повторным нажатием (ADR 0207 решение 11).

/**
 * Дней за одно нажатие. Столько же, сколько у пачки печати (`WAYBILL_PRINT_BATCH_LIMIT`) и у
 * массовых операций по заявкам обслуживания (`SERVICE_REQUEST_BULK_LIMIT`), и по той же причине:
 * пачка печатается одним заходом — полсотни бланков это уже стопка в лотке принтера, а не «ещё
 * разок», и столько же транзакций с номерами строгой отчётности выдерживает один запрос.
 *
 * Предел стоит на ПОРЦИИ, а не на сроке: сроку длиннее предела пачка не отказывает, а проходит его
 * за несколько нажатий (`dayBatchPortionMessage` до нажатия, `dayBatchRemainderMessage` после).
 * Отказ всему сроку означал бы, что квартальный заказ — тот самый случай, ради которого пачка и
 * заведена, — кнопкой не закрывается вовсе.
 *
 * В порцию считаются только дни, которые ЕЩЁ НЕ СТОЯТ в рейсах заявки: уже распланированный день
 * пачка всё равно пропустит (`DAY_BATCH_SKIP_PLANNED`), и, займи он место в порции, второе нажатие
 * топталось бы на тех же днях и никогда не дошло бы до хвоста срока.
 */
export const DAY_BATCH_LIMIT = 50;

/**
 * Тело пачки.
 *
 * Машины здесь НЕТ, и это решение, а не пропуск. Одиночная дверь машину спрашивает (`newRoute`):
 * день у заказа на объект бывает закрыт не той единицей, что стоит в назначении (ADR 0100 §4).
 * Пачке такой вопрос задавать нечем — ответ был бы один на весь период, а «этой машиной все
 * пятьдесят дней» портал уже знает из назначения заявки. Поле в окне означало бы второй ответ на
 * тот же вопрос, и выписанные бланки разошлись бы с назначением заказа.
 *
 * Водитель, наоборот, спрашивается и обязателен: без человека лист не выписать, а подставлять
 * вчерашнего портал не вправе (ADR 0083). Один на весь период — смену человека внутри срока ведёт
 * своя дверь, и пачка её не подменяет.
 *
 * ОТПЕЧАТКА ПРЕДПРОСМОТРА здесь нет — ни поля, ни двери. Поле, объявленное схемой и не читаемое
 * сервером ни разу, обещало бы сверку «нажали по той картине, которую показали», которой не
 * происходит; обещание, которого код не держит, дороже отсутствующего удобства. Разошедшийся за
 * время пачки день сверкой и не ловится: картину собирает каждая транзакция дня под своими
 * блокировками, и день, который к этому моменту уже занят чужим рейсом, уходит в отчёт пропуском
 * (`DAY_BATCH_SKIP_*`). Заведётся предпросмотр — поле вернётся вместе со сверяющим его кодом.
 */
export const dayBatchApplySchema = z
  .object({
    /** Один водитель на все дни срока: пачка выписывает бумаги, а не ведёт график смен людей. */
    driverPersonId: uuidSchema,
    /**
     * Выписывать ли листы или только расставить дни по рейсам. Разделение то же, что у одиночной
     * двери: рейс собирают заранее, а номер строгой отчётности расходуют тогда, когда бланк поедет
     * с водителем.
     */
    issueWaybills: z.boolean(),
    /**
     * Причина заднего числа (ADR 0101 п. 4) — одна на пачку: объясняют не каждый день по
     * отдельности, а само решение оформить прошедший период. Обязательной её делает сервер
     * (`backdateGuard`) и только когда в пачке есть прошедшие дни: схема субъекта не знает и
     * требовать объяснение за будущий выезд не вправе.
     */
    reason: planDayReasonSchema,
    /**
     * Ключ повтора. Здесь он нужен, в отличие от одиночной постановки дня: пачка расходует номера
     * бланков, и повтор по оборванной связи выписал бы вторую стопку на те же дни — а UNIQUE дня
     * (миграция 0127) от этого не спасает, листы считаются по рейсу, а не по дню.
     */
    operationId: uuidSchema.optional(),
  })
  .strict();
export type DayBatchApplyInput = z.infer<typeof dayBatchApplySchema>;
export type DayBatchApplyBody = z.input<typeof dayBatchApplySchema>;

/**
 * Чем кончился день пачки. Список закрытый: отчёт читают глазами и сводят числами, и «прочее» в
 * нём было бы строкой, которую не объяснить и не сосчитать.
 *
 * `planned` и `issued` разделены не ради подробности: первый расходует строку рейса, второй — ещё
 * и номер бланка, и в отчёте это разные новости. `skipped` — день, которому отказала та же дверь,
 * что отказала бы и по одному; `failed` — сбой, о котором говорится общими словами, а разбор
 * лежит в логе по `operationId`.
 */
export const DAY_BATCH_OUTCOMES = ['planned', 'issued', 'skipped', 'failed'] as const;
export type VehicleRequestDayBatchOutcome = (typeof DAY_BATCH_OUTCOMES)[number];

/** Подписи исходов: ими отчёт подписан и на портале, и в письме — словарь на обе стороны один. */
export const dayBatchOutcomeLabels: Record<VehicleRequestDayBatchOutcome, string> = {
  planned: 'Рейс заведён',
  issued: 'Лист выписан',
  skipped: 'Пропущен',
  failed: 'Ошибка',
};

/**
 * Строка отчёта — по образцу `ServiceRequestBulkRowResultDto`: исход, причина и то, чем день
 * теперь называют. Позиции (`index`) здесь нет, в отличие от пачки заявок: у дня есть собственное
 * имя — дата, и восстанавливать по ней порядок незачем.
 */
export interface VehicleRequestDayBatchRowDto {
  /** `YYYY-MM-DD`. */
  date: string;
  outcome: VehicleRequestDayBatchOutcome;
  /** Почему пропущен или сорвался; у `planned` и `issued` пусто — рассказывать нечего. */
  reason?: string;
  /** «Р-12» — рейс, в который день встал; у пропущенного — тот, который его не принял. */
  routeNumber?: string;
  /** Номер выписанного листа; пусто — бланк по этому дню не выписывался. */
  waybillNumber?: string;
}

/**
 * Итог пачки: новая таблица дней и построчный отчёт.
 *
 * Дни едут целиком, а не «то, чего коснулись»: после полусотни бумаг карточка обязана показать
 * новую картину сразу — сходив за ней вторым запросом, она рискует показать уже не ту, по которой
 * составлен отчёт.
 *
 * Числа стоят рядом со строками, а не выводятся из них на портале: шапку отчёта («Выписано 12,
 * пропущено 3») читают и там, где строк не показывают вовсе — в письме и в журнале.
 */
export interface VehicleRequestDayBatchResultDto {
  days: VehicleRequestDaysDto;
  rows: VehicleRequestDayBatchRowDto[];
  planned: number;
  issued: number;
  skipped: number;
  failed: number;
  /**
   * Сколько ещё не распланированных дней срока осталось ЗА пределом этого нажатия (`0` — срок
   * пройден целиком).
   *
   * Отдельным числом, а не выводом из строк: строк у нажатия ровно столько, сколько дней в него
   * вошло, и «что осталось снаружи» по ним не считается никак. Им портал говорит человеку
   * «нажмите ещё раз» (`dayBatchRemainderMessage`) — без этого числа длинный срок молча обрывался
   * бы на полусотне дней, и диспетчер узнавал бы о недоделанном хвосте у принтера.
   *
   * Пропущенные внутри порции дни сюда не считаются: они уже прошли через нажатие, и повтор их
   * состояния не изменит — им место в построчном отчёте, а не в остатке.
   */
  remaining: number;
}

/*
 * ТЕКСТЫ ОТКАЗОВ ПАЧКИ.
 *
 * Константами, а не строками по месту, хотя пишет их один сервер — в `reason` строки отчёта, и
 * портал показывает их как есть. Смысл имени в том, что по нему причину узнают, не сличая текст:
 * им отличают ожидаемую помеху от сбоя и им же названы случаи в тестах. Предупреждения о
 * конфликтных днях ДО нажатия портал не показывает — предпросмотра у пачки нет (см.
 * `dayBatchApplySchema`), и человек узнаёт о пропущенном дне из отчёта.
 *
 * Слова у пачки свои, хотя запреты те же, что у одиночной двери (`dayAlreadyPlannedMessage`,
 * `LINEAR_DAY_FROZEN_MESSAGE`). Причина одна: одиночная дверь советует действие — «снимите день»,
 * «аннулируйте лист», — а в отчёте на полсотни строк совет неуместен и неисполним разом. Правило
 * при этом не раздвоилось: пропускать день или нет, решают всё те же предикаты, здесь только то,
 * как названа уже принятая ими причина.
 */

/** День занят своим же рейсом: пачка не переставляет то, что уже спланировано человеком. */
export const DAY_BATCH_SKIP_PLANNED = 'День уже стоит в рейсе этой заявки — пачка его не трогает';

/** Бумага на день уже выдана: второй бланк на тот же выезд — это два документа на одну работу. */
export const DAY_BATCH_SKIP_FROZEN = 'По рейсу этого дня уже выписан действующий путевой лист';

/**
 * Два рейса машины на дату — законное состояние (утро и вечер), и выбор между ними пачка на себя
 * не берёт: ошибись она, день уехал бы в чужое задание, а заметили бы это у принтера.
 */
export const DAY_BATCH_SKIP_AMBIGUOUS_ROUTE =
  'У машины на эту дату несколько рейсов — выберите рейс дня в таблице «Дни работ»';

/** Вместимость задаёт бланк рейса (`routeRequestCapacity`), и пачка её не обходит. */
export const DAY_BATCH_SKIP_NO_ROOM =
  'В рейсе машины на эту дату не осталось строк задания — дню некуда встать';

/**
 * Прошедший день пачка проходит по тому же правилу, что и одиночный (ADR 0101 п. 4): «можно» у
 * него есть, но только с правом `waybills.correct` и названной причиной. Без права день
 * пропускается, а не роняет всю пачку — остальные дни срока к прошлому отношения не имеют.
 */
export const DAY_BATCH_SKIP_BACKDATED =
  'День уже прошёл, а права оформлять документы задним числом у вас нет';

/**
 * Прошлое глубже предела коррекции — второй и последний отказ прошедшему дню (ADR 0207 §7, Р9
 * плана). Текстом он отдельный от `DAY_BATCH_SKIP_BACKDATED`, потому что отдельный он и по сути:
 * там права нет вовсе и выдаётся оно обычным порядком, здесь право есть, а день просто слишком
 * стар — глубину снимает только `waybills.correctBeyondLimit`, которое не назначается никому
 * (ADR 0101 п. 4). Один текст на два случая советовал бы половине людей идти не туда: одним к
 * диспетчеру за правом, которого им и так не дадут, другим — просить право, которое у них есть.
 *
 * Тем же разделением отвечает и одиночная дверь: у `backdateGuard` это разные коды отказа
 * (`permission` и `limit`) с разными текстами.
 */
export const DAY_BATCH_SKIP_BEYOND_LIMIT = `Прошло больше ${WAYBILL_CORRECTION_DAYS} дней — такую давность оформляет администратор`;

/*
 * ТЕКСТЫ ПОРЦИИ — не отказ, а обещание остатка.
 *
 * Прежде на их месте стоял отказ всему сроку (`dayBatchTermLimitMessage`), и он отрезал от кнопки
 * ровно тот случай, ради которого её просили: квартальный заказ. Теперь длинный срок проходится
 * несколькими нажатиями, и оба текста говорят об одном и том же остатке — до нажатия обещанием,
 * после нажатия счётом. Разойдись они словами, человек решил бы, что видит разные вещи.
 */

/**
 * Срок длиннее порции — подсказка ДО нажатия: сколько дней уйдёт сейчас и сколько останется.
 *
 * Число остатка здесь верхняя оценка, а не факт: портал знает длину срока, но не знает, сколько
 * дней уже стоит в рейсах, — их пачка пропустит, а места в порции они не займут. Точный остаток
 * приходит с ответом (`VehicleRequestDayBatchResultDto.remaining`), и потому обещание сказано
 * мягче счёта: «не больше», а не «ровно столько».
 */
export function dayBatchPortionMessage(termDays: number): string {
  return `В сроке заказа ${termDays} дн., а за одно нажатие проходит не больше ${DAY_BATCH_LIMIT}: сейчас пачка возьмёт первые ${DAY_BATCH_LIMIT} нераспланированных дней, а оставшиеся ${termDays - DAY_BATCH_LIMIT} дн. доберёт повторное нажатие — своей операцией и своим отчётом`;
}

/**
 * Остаток ПОСЛЕ нажатия — тем же словом, каким портал обещал его до нажатия. Зовётся только при
 * `remaining > 0`: «осталось 0 дн.» это не новость, а шум в конце удачной пачки.
 */
export function dayBatchRemainderMessage(remaining: number): string {
  return `В это нажатие ушли первые ${DAY_BATCH_LIMIT} нераспланированных дней срока — предел одной пачки. За ними осталось ещё ${remaining} дн.: нажмите «Распланировать период» ещё раз, и пачка продолжит с первого нераспланированного дня`;
}
