/**
 * Прицеп, закреплённый за машиной, — элемент поля `hitched` ответа `GET /vehicle-routes/suggest`
 * (план `docs/vehicle-trailers-plan.md`, §4.2.2, §4.2.3).
 *
 * Полей ровно столько, сколько нужно окну, чтобы заполнить графы бланка и подписать их источник.
 * Марка и госномер — это и есть графы «Прицеп N (марка)» и «(гос. номер)»; `position` говорит, в
 * какую из двух пар их класть; `status` нужен подписи: закрепление прицепа в ремонте законно
 * (§4.2.3 — он физически стоит за тягачом), но подставленный `maintenance` окно обязано назвать
 * вслух, иначе портал молча поставит в рейс то, что стоит в боксе.
 *
 * Карточка прицепа целиком (`VehicleTrailerDto`) здесь не отдаётся намеренно: окну заведения рейса
 * незачем ни массы по СТС, ни собственник, ни примечание, а лишнее поле в подсказке — это лишнее
 * поле, которое однажды покажут.
 */
export interface HitchedTrailerDto {
  id: string;
  /** Слот бланка 4-П: 1 — первая пара граф, 2 — вторая. Тот же номер, что и в реестре прицепов. */
  position: TrailerHitchPosition;
  /** Марка строкой: у прицепа её и хранят строкой — ссылки на справочник моделей у него нет. */
  model: string;
  registrationNumber: string;
  /** Состояние прицепа: `maintenance` подставляется, но с предупреждением (§4.2.3). */
  status: VehicleStatus;
}

/**
 * Ответ `GET /vehicle-routes/suggest`: что портал знает об этой машине на этот день.
 *
 * ПОЧЕМУ ЗАКРЕПЛЁННЫЕ ПРИЦЕПЫ — ОТДЕЛЬНОЕ ПОЛЕ, А НЕ ГРАФЫ ВНУТРИ `trip`. Соблазн был подмешать
 * закрепление в `trip`: одно поле, одно правило чтения, и окнам вообще нечего менять. Цена такой
 * красоты — история прицепа поехала бы туда, где её сегодня нет. `trip` — это графы шапки
 * **прошлого рейса машины** (`lastTripFields`), и читают его не все окна заведения рейса, а два из
 * шести; окно «Новый маршрут» (`VehicleRoutesModal`) сегодня не подставляет **ничего**. Смешай
 * источники — и оно начало бы предлагать вчерашний прицеп, то есть портал стал бы решать за
 * человека там, где вчера молчал. Ровно это запретил ADR 0083 решением 2 («ни вчерашним на этой
 * машине»), и оправдания «оно и так уже было в соседнем окне» ему недостаточно: было — в двух, а
 * стало бы — в шести.
 *
 * Поэтому граница проведена по источнику, а не по окну: `hitched` — это **сегодняшнее закрепление
 * из реестра прицепов**, решение, которое человек уже принял в карточке прицепа, а `trip` остался
 * тем же, чем был. Правило чтения одно на все окна: `hitched` не пуст — графы прицепа берутся
 * оттуда и подписываются «закреплён за машиной»; пуст — новой подстановки нет вовсе, окно ведёт
 * себя ровно как вчера.
 */
export interface VehicleRouteSuggestDto {
  /** Рейсы этой машины на эту дату: ими форма предлагает готовый рейс вместо второго. */
  routes: VehicleRouteDto[];
  /**
   * Графы шапки прошлого рейса машины — гаражный номер, вид сообщения и перевозки, прицепы.
   * `null` — рейсов у машины ещё не было. Поле не изменилось ни на байт: его по-прежнему считает
   * `lastTripFields`, и появление `hitched` рядом на него не влияет.
   */
  trip: RouteTripFields | null;
  /**
   * Закреплённые за машиной прицепы, по возрастанию слота. Пусто — за машиной не закреплено
   * ничего, и это не «данных нет», а полноценный ответ: новой подстановки у такой машины не
   * бывает.
   */
  hitched: HitchedTrailerDto[];
}

