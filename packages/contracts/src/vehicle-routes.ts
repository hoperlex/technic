// ── Схемы коррекции (ADR 0101) ──

/**
 * Ключ идемпотентности операции (Р31): uuid, который клиент придумывает **до** отправки.
 *
 * Обязателен во всех командах коррекции. Повтор после сетевого таймаута обязан вернуть результат
 * прежней операции, а не сжечь следующий номер серии: у бланка строгой отчётности «повторить
 * запрос» не бесплатное действие, и молчаливый дубль виден только в журнале — разрывом нумерации,
 * который потом никто не объяснит.
 */
const operationIdSchema = uuidSchema;

/**
 * Причина коррекции. Обязательна и не пустая: она уходит в запись операции (Р16) и печатается в
 * обоих листах — в старом как причина аннулирования, в новом как причина коррекции (Р35). Именно
 * она отвечает через два месяца на вопрос «почему за 12 августа два номера».
 */
const correctionReasonSchema = z.string().trim().min(1, 'Укажите причину').max(2000);

/**
 * Исправление исполнения рейса (Р2): одно событие, а не пять.
 *
 * Сервер в одной транзакции аннулирует действующий лист, переписывает машину и водителя рейса,
 * тянет за ними назначения **всех** заявок состава, снимает подтверждение затронутых смен и
 * выписывает новый лист. Машина принимается только здесь: обычная правка рейса её по-прежнему не
 * берёт (ADR 0082 п. 5), потому что «поедет другой машиной» в будущем — это другое назначение, а в
 * прошедшем дне рейс состоялся один, и ехала им одна машина.
 *
 * `requestOrder` меняет только порядок талонов внутри рейса. Состав коррекцией не пополняется и не
 * сокращается: приход и уход заявки — это перенос между рейсами со своей командой, своими
 * блокировками и своей версией исходного рейса (`transferCorrectionSchema`). Прежний `requestIds`
 * отвергнут именно поэтому: он позволял потерять талон в чужом рейсе, не назвав его.
 *
 * Водитель — `uuid`, а не `nullable`: пустой водитель у обычного рейса законен (маршрут собирают
 * заранее), но лист без него не выписывается ни с правом, ни без, а коррекция всегда кончается
 * новым листом.
 */
export const correctRouteSchema = z
  .object({
    operationId: operationIdSchema,
    version: versionSchema,
    vehicleId: uuidSchema.optional(),
    driverPersonId: uuidSchema.optional(),
    trip: routeTripFieldsSchema.optional(),
    requestOrder: z.array(uuidSchema).min(1).max(MAX_ROUTE_REQUESTS).optional(),
    reason: correctionReasonSchema,
    /**
     * Подтверждение предупреждений нового листа (Р21а). Коррекция кончается настоящим бланком, и
     * рукопожатие у неё то же самое: пропусти его здесь — и лист, рождённый коррекцией, обошёл бы
     * проверку, которую проходит обычная выписка.
     *
     * Отпечаток считается по **будущему** состоянию рейса — после смены машины, водителя и порядка
     * талонов: подтверждают то, что напечатается, а не то, что было до операции.
     */
    acknowledge: waybillAcknowledgeSchema.optional(),
  })
  .strict()
  .refine((v) => !v.requestOrder || new Set(v.requestOrder).size === v.requestOrder.length, {
    message: 'Заявка не может стоять в рейсе дважды',
    path: ['requestOrder'],
  })
  /*
   * Пустая коррекция отклоняется (Р31): тело с одной причиной сожгло бы номер, ничего не исправив.
   * Схема ловит только заведомо пустое — назвать ли переданные значения новыми, знает лишь сервер,
   * сравнивая их с текущим состоянием рейса под блокировкой. Дальше он же и откажет, но начинать
   * транзакцию ради тела, в котором менять нечего в принципе, незачем.
   */
  .refine(
    (v) =>
      v.vehicleId !== undefined ||
      v.driverPersonId !== undefined ||
      v.trip !== undefined ||
      v.requestOrder !== undefined,
    { message: 'Коррекция должна что-то менять: машину, водителя, реквизиты или порядок талонов' },
  );
export type CorrectRouteInput = z.infer<typeof correctRouteSchema>;
export type CorrectRouteBody = z.input<typeof correctRouteSchema>;

/**
 * Перенос заявки между рейсами прошедших дней (Р30): «оформили средой, а ехали вторником».
 *
 * `:id` в пути — рейс-**приёмник**, `source` — рейс-источник со своей версией. Обе версии
 * спрашиваются, потому что коррекция трогает оба рейса и жжёт оба номера: одной версии хватило бы
 * ровно до первой встречной правки чужого рейса. Заявка называется одна — состав меняется на один
 * талон, и «перенести пачкой» здесь не заводится намеренно: каждый талон это отдельная строка
 * задания в двух бумагах сразу.
 *
 * Сервер одной транзакцией аннулирует оба действующих листа, переносит заявку, уплотняет талоны
 * источника, переписывает назначение на машину приёмника и выписывает листы обоих рейсов — второй
 * только если источник не опустел (Р22: пустой бланк на опустевший рейс не выписывается). Заявка
 * ни на миг не остаётся в работе без маршрута — ради этого команда и атомарна.
 */
export const transferCorrectionSchema = z
  .object({
    operationId: operationIdSchema,
    /** Версия приёмника — того рейса, чей `:id` стоит в пути. */
    version: versionSchema,
    source: z.object({ routeId: uuidSchema, version: versionSchema }).strict(),
    requestId: uuidSchema,
    /** Талон в приёмнике, 1..7; не передан — заявка встаёт последней. */
    position: z.number().int().min(1).max(MAX_ROUTE_REQUESTS).optional(),
    reason: correctionReasonSchema,
    /**
     * Подтверждения обоих листов (Р21а). Двумя полями, а не одним: листов здесь два, предупреждения
     * у них разные — заявка уехала из одного задания в другое, — и отпечаток считается по каждому
     * рейсу отдельно. Один общий отпечаток означал бы, что подтверждение приёмника закрывает и
     * бумагу источника, которой человек не видел.
     *
     * Обе половины необязательны, потому что пустой набор рукопожатия не требует: у рейса без
     * предупреждений подтверждать нечего, и чаще всего такова хотя бы одна из сторон.
     */
    acknowledge: z
      .object({
        target: waybillAcknowledgeSchema.optional(),
        source: waybillAcknowledgeSchema.optional(),
      })
      .strict()
      .optional(),
  })
  .strict();
export type TransferCorrectionInput = z.infer<typeof transferCorrectionSchema>;
export type TransferCorrectionBody = z.input<typeof transferCorrectionSchema>;

export const routeVersionQuerySchema = z.object({ version: versionSchema });
export type RouteVersionQuery = z.infer<typeof routeVersionQuerySchema>;

/**
 * Маршрут при переводе заявки в работу: существующий рейс этой машины на эту дату либо новый.
 * Ровно одно из двух — «и то, и другое» означало бы два разных ответа на вопрос, куда едет заявка.
 *
 * У готового рейса спрашивается и водитель (ADR 0048). Смена назначенной техники переставляет
 * заявку в рейс новой машины, и человек за рулём меняется вместе с ней — а до сих пор сменить его
 * этим же действием было нечем: оставалось второе окно правки рейса (ADR 0082) либо заведение
 * лишнего маршрута «с нужным водителем». Отвергнута как раз вторая дорога: маршрут заводили не
 * ради маршрута, и в плане дня оставалась пустая запись, которую потом убирали руками.
 *
 * Состояния поля три, а не два, и различаются они ровно так же, как у правки рейса
 * (`updateVehicleRouteSchema.driverPersonId`) — один и тот же вопрос не должен иметь двух ответов:
 *
 * - поля нет — водителя не трогать. Умолчание именно такое, потому что рейс общий: в нём стоят
 *   заявки других объектов, и «не сказали — значит снять» стирало бы водителя чужой работы при
 *   каждой смене техники;
 * - `null` — снять водителя: рейс остаётся, за рулём пока никого;
 * - идентификатор — поставить этого человека, и он поедет за всех, кто стоит в рейсе.
 *
 * У новой ветки водитель без `null` — снимать там нечего: рейс рождается этим же запросом, и
 * «завести рейс и тут же снять с него водителя» это просто рейс без водителя.
 *
 * С машинистом заявки (`assignVehicleSchema.driverPersonId`) это разные графы и разные бумаги:
 * тот стоит в недельном листе ЭСМ-2 заказа техники на объект, этот — за рулём рейса. Спорить им
 * не о чем: где выписывается ЭСМ-2, рейса не бывает вовсе (ADR 0041), и наоборот.
 */
export const assignRouteSchema = z.union([
  z.object({ routeId: uuidSchema, driverPersonId: uuidSchema.nullable().optional() }).strict(),
  z
    .object({
      newRoute: z
        .object({
          driverPersonId: uuidSchema.optional(),
          trip: routeTripFieldsSchema.optional(),
        })
        .strict(),
    })
    .strict(),
]);
export type AssignRouteInput = z.infer<typeof assignRouteSchema>;
export type AssignRouteBody = z.input<typeof assignRouteSchema>;

