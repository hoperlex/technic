// ── Объект затрат заявки (план `docs/route-trips-plan.md`, Р25) ──
//
// Заказчик заявки на технику и сегодня ровно один: объект строительства **или** отдел (ADR 0040),
// и это держит CHECK `vehicle_requests_customer_check` (`num_nonnulls(object_id, department_id) = 1`).
// Двойственность возникает не в базе, а в чтении: два десятка мест выводят заказчика сами, из пары
// `objectName`/`departmentName`, и каждое вольно решить иначе — где-то по имени, где-то по
// идентификатору, где-то с кодом, где-то без. Поэтому один тип и две функции на портал и сервер.
//
// Колонкой объект затрат не хранится намеренно: он выводится из пары, которую уже стережёт CHECK,
// а копия рассинхронизировалась бы при первом же переводе заявки с отдела на объект.
//
// Три границы, чтобы двойственность не вернулась:
//
//   - **площадка отдела объект затрат не подменяет.** У отдела бывает закреплённый объект
//     (`departments.construction_object_id`, ADR 0062), но он про **область видимости**, а не про
//     учёт: он открывает сотрудникам отдела вывоз мусора со своей площадки — и только. Заявку
//     завёл отдел — затраты на отдел, даже если у отдела ровно один объект и «всем очевидно», куда
//     их отнести. Записано явно, потому что спор об этом неизбежен: подставить площадку выглядит
//     полезным ровно до первого отдела с площадкой, чьи расходы бухгалтерия ждёт на отделе;
//   - **ездка своего объекта затрат не имеет** — наследует заявкин (Р25). Иначе двойственность
//     переезжает внутрь заявки;
//   - **точка маршрута тоже**: на ней сходятся ездки разных заказчиков, и «объект затрат точки» не
//     существует. Учёт идёт по строкам задания — ездкам и линейным дням, — а не по остановкам.

/**
 * Объект затрат: на кого относятся расходы по заявке.
 *
 * Дискриминированное объединение, а не «объект с необязательным отделом»: у объекта и отдела
 * общие только подпись и код, а вопросы к ним разные — по объекту спрашивают стройку, по отделу
 * подразделение, — и сведённые в одну плоскую запись они дали бы один ответ на два вопроса.
 * Ветвь читается явно (`t.kind === 'object'`), и ни одно место не забудет, что заказчиков два
 * рода.
 *
 * `code` есть у обоих справочников (`construction_objects.code`, `departments.code` — обе
 * колонки `NOT NULL` и `UNIQUE`), поэтому у объекта затрат он есть всегда. Это то, чем его
 * называет бухгалтерия и чем он печатается в ЭСМ-2 (`object_code`).
 */
export type CostTarget =
  | { kind: 'object'; id: string; code: string; name: string }
  | { kind: 'department'; id: string; code: string; name: string };

/** Ключ объекта затрат: `object:<uuid>` либо `department:<uuid>` — тип узкий, как у `AddressKey`. */
export type CostTargetKey = `${CostTarget['kind']}:${string}`;

/**
 * Заявка глазами объекта затрат — ровно те шесть колонок, которыми заказчик описан в базе и в
 * DTO (`VehicleRequestBaseDto`).
 *
 * Плоская шестёрка, а не вложенные `object`/`department`: именно так заказчик приходит отовсюду —
 * из DTO заявки, из строки `leftJoin` на оба справочника (потому и `| null` у всех полей: чужая
 * сторона пары пуста по устройству, а не по недосмотру), из снимка листа. Требовать здесь другую
 * форму значило бы заставить два десятка мест собирать её перед вызовом — и объект затрат,
 * который затевался ради одного правила на всех, стало бы некуда подставить.
 */
export interface CostTargetSource {
  objectId: string | null;
  objectCode: string | null;
  objectName: string | null;
  departmentId: string | null;
  departmentCode: string | null;
  departmentName: string | null;
}

/**
 * Объект затрат заявки: ровно один из пары под CHECK.
 *
 * Спрашивается **идентификатор**, а не имя: CHECK стережёт `object_id`/`department_id`, и только
 * они отвечают «чья заявка» однозначно. Имя годится на подпись, но заявка с пустым наименованием
 * справочника — испорченная запись, а не заявка отдела.
 *
 * `null` — заказчика нет ни одного. По базе такого состояния не бывает, но эта функция читает и
 * то, что собрано запросом: строка, где заказчика просто не выбрали в `select`, и заявка,
 * прочитанная до `join`, приходят сюда неотличимо от пустой. Бросать здесь исключение значило бы
 * ронять список заявок из-за подписи одной строки — поэтому «неизвестно» возвращается значением,
 * а показывают его тем же «—», которым это делает `requestCustomerName` сегодня.
 *
 * Площадка отдела (ADR 0062) результат не меняет: заявку завёл отдел — объект затрат отдел.
 */
export function costTargetOf(r: CostTargetSource): CostTarget | null {
  if (r.objectId) {
    // Код в справочнике `NOT NULL`, и `null` здесь означает лишь то, что колонку не выбрали
    // запросом. Пустая строка честнее выдуманного значения: она видна на экране как пропуск.
    return { kind: 'object', id: r.objectId, code: r.objectCode ?? '', name: r.objectName ?? '' };
  }
  if (r.departmentId) {
    return {
      kind: 'department',
      id: r.departmentId,
      code: r.departmentCode ?? '',
      name: r.departmentName ?? '',
    };
  }
  return null;
}

/**
 * Ключ для сравнения и сводов: `object:<uuid>` | `department:<uuid>`.
 *
 * Род в ключе обязателен, хотя uuid и так уникален: ключ не только сравнивается, но и читается —
 * им сгруппированы затраты листа и им же поднимается `multiple_cost_targets` (Р26), — а
 * голый uuid не говорит, чей он. Кода в ключе нет: коды у объектов и отделов свои и совпасть
 * могут, а сущность за ними разная — сведённые по коду затраты стройки и отдела слились бы в
 * одну строку.
 */
export function costTargetKey(t: CostTarget): CostTargetKey {
  return `${t.kind}:${t.id}`;
}
