import { z } from 'zod';
import { baseListQuery, booleanFlagSchema, sortOrderSchema } from './common';

/**
 * Руководства пользователя — список ссылок на документы во внешнем хранилище
 * (`docs/manuals-plan.md`). Портал знает про руководство только строку: файлы он не хранит и
 * доступность чужого хранилища не контролирует.
 *
 * Отсюда единственная проверка ссылки — `https://`, и она не про безопасность адреса, а про то,
 * что руководство откроется у всех. Правило «`/i/` — просмотр, `/edit/` — правка» принадлежит
 * Яндексу, и зашитое в наш контракт оно сломалось бы на первой же смене их адресов, отказав в
 * заведении рабочей ссылки; а без `https` браузер вместо документа показал бы предупреждение.
 *
 * Читают список все вошедшие, ведёт — держатель `manuals.manage` (ADR 0021: модуль закрывается
 * своим правом, и здесь это же право открывает вкладку ведения). Право на чтение не заводится
 * намеренно: закрыть «как пользоваться порталом» правом, которое пришлось бы выдать всем, значит
 * завести право ни о чём — то же рассуждение, что у журнала обновлений (ADR 0077 §5).
 */

/**
 * Чем сортируется список. `sortOrder` первым, потому что он и есть порядок показа: остальные три
 * поля нужны вкладке ведения, где администратор ищет строку, а не смотрит витрину.
 */
export const MANUAL_SORT_FIELDS = ['sortOrder', 'title', 'isActive', 'createdAt'] as const;

export const manualListQuerySchema = baseListQuery(MANUAL_SORT_FIELDS).extend({
  /**
   * Снятые с публикации показываются только держателю `manuals.manage`: без права обработчик
   * подставляет `true` сам, и параметр из запроса игнорируется. Проверка живёт в ручке, а не в
   * схеме, — схема не знает, кто спрашивает.
   */
  isActive: booleanFlagSchema,
  /**
   * Порядок показа задаёт `sortOrder`, и по возрастанию: базовая схема умолчанием ставит `desc`,
   * с которым список пришёл бы задом наперёд — сотое руководство первым, первое последним.
   */
  sortOrder: sortOrderSchema.default('asc'),
});
export type ManualListQuery = z.infer<typeof manualListQuerySchema>;

/** Ссылка на документ: длина под адрес с параметрами, начало — обязательно `https://`. */
const manualUrlSchema = z
  .string()
  .trim()
  .min(1, 'Укажите ссылку на документ')
  .max(2000)
  .regex(/^https:\/\//, 'Ссылка должна начинаться с https://');

/**
 * Порядок показа, каким он приходит из формы. `nullish()` стоит **до** проверки числа: очищенное
 * поле «Порядок» присылает `null`, а `z.coerce.number()` превратил бы его в `0` (`Number(null)`),
 * и администратор, стёрший число «пусть будет как у всех», молча поставил бы руководство первым в
 * окне у всех. `.default()` эту дверь не закрывает — он срабатывает только на `undefined`.
 *
 * Приём тот же, что у `booleanFlagSchema` в `common.ts`: «значения нет» разбирает сама схема — и
 * разбирает одинаково, что бы ни прислали, `null` или пропуск поля. Что значит «нет», решает уже
 * тело запроса: при заведении — умолчание, при правке — «поле не трогаем».
 */
const manualSortOrderSchema = z.coerce.number().int().nullish();

export const createManualSchema = z
  .object({
    title: z.string().trim().min(1, 'Укажите название руководства').max(200),
    /**
     * Описание необязательно и по умолчанию пусто, а не `null`: в окне это вторая строка пункта,
     * и «нет описания» показывается её отсутствием, а не прочерком. Два пустых значения на одно
     * состояние развели бы проверку показа надвое.
     */
    description: z.string().trim().max(500).default(''),
    url: manualUrlSchema,
    /**
     * Умолчание `100` — то же, что у справочников портала: заведённое без раздумий руководство
     * встаёт в общий ряд, а не в начало и не в конец, и переставить его можно, не трогая соседей.
     * Ставится и на пропущенное поле, и на очищенное (`null`) — см. `manualSortOrderSchema`.
     */
    sortOrder: manualSortOrderSchema.transform((v) => v ?? 100),
    isActive: z.boolean().default(true),
  })
  .strict();
export type CreateManualInput = z.infer<typeof createManualSchema>;

/**
 * Правится всё, включая ссылку: документ в хранилище переезжает, и заводить ради переезда вторую
 * строку значило бы плодить дубли названий. Из обращения руководство выводится `isActive = false`;
 * настоящее удаление отдельным действием под тем же правом (`docs/manuals-plan.md` §3.4).
 */
export const updateManualSchema = z
  .object({
    title: z.string().trim().min(1, 'Укажите название руководства').max(200).optional(),
    description: z.string().trim().max(500).optional(),
    url: manualUrlSchema.optional(),
    /**
     * Очищенное поле — «этой правки нет», а не «поставь ноль» и не «сотри значение»: колонка
     * объявлена `NOT NULL`, и `null` здесь превращается в `undefined`, который до `UPDATE` не
     * доходит вовсе. Умолчание при правке не подставляется намеренно — правка чинит одно поле, а
     * не возвращает остальные к заводскому виду.
     *
     * Хвостовой `.optional()` — про тип тела, а не про разбор: после `transform` ключ считался бы
     * обязательным, и правка одного названия перестала бы собираться.
     */
    sortOrder: manualSortOrderSchema.transform((v) => v ?? undefined).optional(),
    isActive: z.boolean().optional(),
  })
  .strict();
export type UpdateManualInput = z.infer<typeof updateManualSchema>;

/** Строка списка руководств — то, что показывает окно и ведёт вкладка «Руководства». */
export interface ManualDto {
  id: string;
  title: string;
  /** Пояснение под названием; пустая строка — «без пояснения», см. `createManualSchema`. */
  description: string;
  /** Внешний адрес документа: открывается в новой вкладке, портал по нему не ходит. */
  url: string;
  sortOrder: number;
  /** Снятое с публикации руководство видит только держатель `manuals.manage`. */
  isActive: boolean;
  createdAt: string;
  updatedAt: string;
}
