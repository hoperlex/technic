// ── Рубильники приёма (план `docs/office-equipment-request-subject-plan.md`, Р10) ──
//
// Ключ, которым ВЫКАТ отделён от ВКЛЮЧЕНИЯ. Код едет закрытым, а открывает его строка в базе —
// `UPDATE`, а не релиз. Заведено ради одной находки ревью (Р11): миграция прав применяется до
// перезапуска приложения, и без рубильника выдача права немедленно открыла бы СТАРУЮ реализацию,
// которая ни о каком включении не знает.
//
// ЭТО НЕ ПОЛНЫЙ РЕЗОЛВЕР ФЛАГОВ, и называть его так нельзя. План кандидата (§14) требовал общего
// механизма — с пилотными областями, аудитом переключения и административной ручкой; его в
// репозитории нет, и эта волна его не пишет. Здесь ровно один вопрос — «включён ли ключ вообще», —
// одинаковый для всех учёток. Отвергнуто вслух: (1) ждать общий резолвер — волна встала бы на
// внешней задаче, а выкатывать её без серверного fail-closed нельзя вовсе; (2) собрать пилотные
// области «на вырост» — механизм без единого читателя расходится с будущими требованиями быстрее,
// чем пишется; (3) `process.env`/`VITE_*` — сборочная константа не выключается аварийно и разъезжается
// между сервером и порталом на любом частичном выкате.

/**
 * Реестр ключей. Закрыт намеренно: перечень обязан совпадать с `CHECK` таблицы `feature_flags`
 * (миграция 0293) — иначе опечатка в ключе выглядела бы настройкой («рубильник включён»), пока
 * настоящий ключ сидит без строки и молчит.
 *
 * Новый ключ приходит со своей строкой, то есть с миграцией: бесплатным этот реестр не бывает и
 * не должен — рубильник без строки в базе означает «выключён навсегда», а это состояние обязано
 * быть видно на ревью выката, а не в проде.
 */
export const FEATURE_FLAGS = [
  /**
   * Приём сообщений о технике, которой нет в справочнике (план
   * `docs/office-equipment-candidate-plan.md`, §14; ADR 0165).
   *
   * Гасит ВХОД, а не разбор: `POST /service-requests` с `equipmentCandidate` при выключенном ключе
   * отвечает отказом даже держателю `officeEquipment.propose`, а очередь проверки, чтение уже
   * созданных кандидатов и три решения ключом не ограждаются. Аварийное выключение обязано
   * прекратить приток, не заперев то, что уже принято: разобрать накопленное всё равно кто-то
   * должен.
   */
  'office_equipment_candidate_intake',
] as const;

export type FeatureFlagKey = (typeof FEATURE_FLAGS)[number];

/**
 * Включён ли ключ по ответу сессии — **единственное** правило чтения на портале, и живёт оно рядом
 * с реестром, а не в экране.
 *
 * FAIL-CLOSED ДВАЖДЫ, И ОБА РАЗА ПО РАЗНОЙ ПРИЧИНЕ. Ключа нет в списке — сервер посчитал его
 * выключенным. Списка нет вовсе (`features === undefined`) — отвечает СТАРЫЙ сервер, который о
 * рубильнике не знает: так выглядит окно выката, когда портал уже новый, а приложение ещё не
 * перезапущено. Оба случая обязаны означать «выключено»: `?? true` открыл бы приём на старом
 * ответе — ровно тот сценарий, ради которого рубильник и заводился.
 *
 * Портал НЕ имеет собственной копии значения (env, сборочной константы, локального состояния):
 * второй источник ответа разошёлся бы с серверным молча, и выключенный рубильник показывал бы
 * человеку дверь, за которой стоит 403.
 */
export function hasFeature(
  session: { features?: readonly FeatureFlagKey[] } | null | undefined,
  key: FeatureFlagKey,
): boolean {
  return session?.features?.includes(key) ?? false;
}
