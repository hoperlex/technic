/**
 * Разделы портала: что бывает пунктом меню, маршрутом и стартовой страницей.
 *
 * Один список, потому что спрашивающих трое — меню (`AppLayout`), маршруты с их гейтами (`App.tsx`)
 * и стартовая страница (`HomeRedirect`), — и до этого файла каждый знал свой состав разделов
 * (`docs/portal-sections-plan.md` §2). Новый раздел заводили в двух копиях из трёх, и промах
 * выходил наружу только у той роли, для которой пропущенный раздел — единственный: так стартовая
 * страница потеряла «Орг.технику» (ADR 0085) и отправляла оператора сервисной компании на смену
 * пароля. Та же болезнь и тем же лечением уже правилась в `ADMIN_PAGE_PERMISSIONS`
 * (`docs/manuals-plan.md` §3.6).
 *
 * Здесь, а не во фронте, по причине из `links.ts`: адреса портала уже живут в контрактах, и ответ
 * на «какие у портала разделы» обязан быть один. Плюс тест полноты оказывается рядом с
 * `ACCESS_PROFILES` — там, где перебирают всех, кто в портале бывает.
 *
 * React сюда не приходит: иконки и бейджи остаются в каркасе (§4.2 плана). Реестр — данные, и
 * знать про способ отрисовки ему нечем.
 *
 * Что реестром **не** описывается: вкладки внутри разделов, подстраницы со своим правом
 * (`/vehicle-requests/weekly/:id`), публичные маршруты и служебная смена пароля. Раздел — это то,
 * что бывает пунктом меню и стартовой страницей; остальное закрывает `RequirePermission`.
 */

/** Разделы общего каркаса: пункт меню, маршрут в ветке `AppLayout`, страница в `SECTION_PAGES`. */
export type PortalShellSectionId =
  | 'waste'
  | 'vehicle-requests'
  | 'waybills'
  | 'garage'
  | 'office-equipment'
  | 'directories'
  | 'admin';

export type PortalSectionId = PortalShellSectionId | 'driver-cabinet';

interface SectionBase {
  /** Адрес раздела — он же ключ пункта меню и подсветки. */
  path: string;
  label: string;
  /** Подпись нижней навигации: на 360 px пункту достаётся четверть экрана (ADR 0030). */
  short: string;
  /** Раздел открывает ЛЮБОЕ из этих прав. */
  permissions: readonly Permission[];
  /** Дополнительное условие роли; сегодня только у кабинета водителя (ADR 0102). */
  roles?: readonly Role[];
  /** Каким по счёту раздел становится стартовым, если открыт учётке. */
  startOrder: number;
}

/**
 * Раздел каркаса. Отдельным типом от кабинета, а не полем-признаком с фильтром: `SECTION_PAGES` —
 * `Record` по `PortalShellSectionId`, и после `PORTAL_SECTIONS.filter(...)` обращение
 * `SECTION_PAGES[s.id]` перестало бы типизироваться — сужение пришлось бы держать предикатом,
 * то есть руками.
 */
export interface PortalShellSection extends SectionBase {
  id: PortalShellSectionId;
  shell: 'portal';
}

/** Второй контур (ADR 0102): свой каркас, своя ветка маршрутов, в меню не показывается. */
export interface DriverCabinetSection extends SectionBase {
  id: 'driver-cabinet';
  shell: 'own';
}

export type PortalSection = PortalShellSection | DriverCabinetSection;

