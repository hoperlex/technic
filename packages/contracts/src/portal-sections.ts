/** Все разделы портала: кабинет плюс каркас. Порядок массива значения не имеет — его задаёт `startOrder`. */
export const PORTAL_SECTIONS: readonly PortalSection[] = [
  DRIVER_CABINET_SECTION,
  ...SHELL_SECTIONS,
];

/**
 * Разделы в стартовом порядке — **посимвольная копия сегодняшнего перебора `homePath`** (кабинет,
 * вывоз, заказ ТС, гараж, листы, справочники, администрирование), к которой в хвост дописан
 * пропущенный раздел «Орг.техника».
 *
 * Хвост здесь — решение, а не остаток. Поставь «Орг.техника» на её место в меню (пятой), и механик
 * с назначенным `officeEquipment.read` (ADR 0106) уехал бы из «Гаража» в оргтехнику: приоритет
 * стартового раздела — продуктовый вопрос, и менять его побочным эффектом рефакторинга нельзя.
 * Именно этот порядок и есть гарантия совместимости: перебор профилей матрицы её не даёт — со
 * свободной сборкой полномочий набор прав учётки из роли больше не выводится.
 *
 * Считается один раз: список неизменен, а `startSection` зовут на каждом переходе портала.
 */
const SECTIONS_BY_START: readonly PortalSection[] = [...PORTAL_SECTIONS].sort(
  (a, b) => a.startOrder - b.startOrder,
);

/**
 * Чем портал отвечает на «открыт ли раздел». `canUse` передаётся предикатом, а не пересчитывается
 * реестром: права считает сервер (ADR 0106), контрактам их выводить нельзя, а область к `canUse`
 * уже приложена (ADR 0062).
 */
export interface SectionAccess {
  role: Role | null;
  canUse: (permission: Permission) => boolean;
}

/**
 * Открыт ли раздел: любое из его прав вместе с ролью, если раздел её требует.
 *
 * Один предикат на меню, гейты маршрутов и стартовую страницу. До него те же три вопроса задавались
 * тремя способами (`can` где-то, `canUse` где-то, роль плюс право у кабинета) — и живучесть бага
 * была следствием именно этого. Всюду `canUse`: область сужает один модуль (вывоз мусора), для
 * остальных прав `canUse` совпадает с `can`, и три разных ответа были следствием копий, а не смысла.
 */
export function isSectionOpen(section: PortalSection, access: SectionAccess): boolean {
  if (section.roles && (access.role === null || !section.roles.includes(access.role))) return false;
  return section.permissions.some((permission) => access.canUse(permission));
}

/** Пункты меню: только разделы каркаса и в порядке `SHELL_SECTIONS`. */
export function openShellSections(access: SectionAccess): readonly PortalShellSection[] {
  return SHELL_SECTIONS.filter((section) => isSectionOpen(section, access));
}

/**
 * Стартовый раздел учётки — первый открытый по `startOrder`. Кабинет водителя участвует наравне с
 * прочими: у роли `driver` нет ни одного права основного портала, и не будь его в переборе, водитель
 * приземлялся бы на смену пароля — единственное, что осталось бы ему доступным.
 *
 * `null` — это «разделов нет», и он **значение, а не адрес**: подставить сюда служебный маршрут
 * больше негде, а показать это состояние экраном — дело портала (§4.5 плана). Ровно этим отличается
 * «доступ не настроен» от «пароль просрочен», которые до реестра были для человека неразличимы.
 */
export function startSection(access: SectionAccess): PortalSection | null {
  return SECTIONS_BY_START.find((section) => isSectionOpen(section, access)) ?? null;
}
