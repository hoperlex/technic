import { z } from 'zod';

/**
 * Журнал обновлений портала (ADR 0077).
 *
 * Выпуск — законченный блок работы, а не отрезок календаря: границу задаёт готовность темы, а не
 * наступивший вторник. Отсюда две вещи, которые видно прямо в контракте.
 *
 * Первая — версия строкой, а не тремя числами. `0.1.4.0071` читается как «линия 0.1, четвёртый
 * выпуск, последнее решение блока — ADR 0071», и разбирать её потребителю незачем: показывают
 * целиком, сравнивают по `seq`.
 *
 * Вторая — порядок отдельным полем. Дата выпуски не упорядочивает (несколько блоков доезжают в
 * один день), строка версии — тем более (`'0.1.10'` меньше `'0.1.9'` как текст). Сортирует и
 * отвечает на «это новее прочитанного» только `seq`.
 */

// ── Пункт выпуска ──

/**
 * Чем пункт является для того, кто работает в портале: появилось, стало удобнее, перестало ломаться.
 *
 * Три значения, а не подробная классификация: тег стоит слева от строки и должен читаться, не
 * отвлекая от самой строки. Разбираться, «улучшение это или всё-таки исправление», дольше, чем
 * прочитать текст пункта.
 */
export const RELEASE_ITEM_KINDS = ['feature', 'improvement', 'fix'] as const;
export type ReleaseItemKind = (typeof RELEASE_ITEM_KINDS)[number];

export const releaseItemKindLabels: Record<ReleaseItemKind, string> = {
  feature: 'Новое',
  improvement: 'Улучшено',
  fix: 'Исправлено',
};

export const releaseItemKindColors: Record<ReleaseItemKind, string> = {
  feature: 'green',
  improvement: 'blue',
  // Серым намеренно: исправление — не событие выпуска, а возвращение к тому, как должно было быть.
  fix: 'default',
};

/**
 * Разбор пункта из `items` — единственное место, где контракт встречается с содержимым jsonb.
 *
 * `catch` у вида не перестраховка: пункты приходят миграцией, а миграция — это текст, набранный
 * руками. Опечатка в `kind` не должна стоить пользователю всего окна, поэтому незнакомый вид
 * становится нейтральным «Улучшено», а текст пункта — то, ради чего окно открывали, — доезжает.
 */
export const releaseItemSchema = z.object({
  kind: z.enum(RELEASE_ITEM_KINDS).catch('improvement'),
  text: z.string().trim().min(1),
});

/** Пункты выпуска целиком: пустой список законен — бывает выпуск из одних исправлений схемы. */
export const releaseItemsSchema = z.array(releaseItemSchema);

export interface ReleaseItemDto {
  kind: ReleaseItemKind;
  text: string;
}

// ── Выпуск ──

export interface ReleaseDto {
  /** Сквозной порядок выпусков: сортировка списка и отметка прочитанного. */
  seq: number;
  /** `0.1.4.0071` — показывают целиком, с «v» впереди (`releaseVersionLabel`). */
  version: string;
  /** Дата выкладки, `YYYY-MM-DD`. Справочная: порядок задаёт `seq`. */
  releasedOn: string;
  title: string;
  /**
   * Сколько решений вошло в выпуск. Наружу идёт число, а не номера ADR: пользователю нужен вес
   * выпуска, а сами номера — внутренняя ссылка на `docs/adr`, и в окне они были бы шумом.
   */
  adrCount: number;
  items: ReleaseItemDto[];
}

/** Версия в интерфейсе: `v0.1.4.0071`. «v» дорисовывают здесь, в БД её нет. */
export const releaseVersionLabel = (version: string): string => `v${version}`;

/**
 * Подпись веса выпуска: «6 решений». Склонение простое, потому что чисел здесь единицы, а не
 * тысячи, — общего форматтера числительных портал пока не завёл.
 */
export const releaseAdrCountLabel = (count: number): string => {
  const tail = count % 10;
  const teen = count % 100 >= 11 && count % 100 <= 14;
  if (!teen && tail === 1) return `${count} решение`;
  if (!teen && tail >= 2 && tail <= 4) return `${count} решения`;
  return `${count} решений`;
};
