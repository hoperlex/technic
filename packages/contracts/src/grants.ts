import type { Permission } from './permissions';
import type { RoleAddon } from './role-addons';

/**
 * Назначаемые полномочия (ADR 0106) — именованный набор прав, который выдаётся учётке поверх её
 * роли и приходит на смену надстройкам (ADR 0086).
 *
 * Файл — этап 1a реформы и заводит **только структуры**: коды двух системных наборов, границы
 * свободной сборки и таблицы, по которым сервер, миграция и будущий конструктор будут принимать
 * решения. Матрица `ROLE_PERMISSIONS`, список `ROLE_ADDONS` и поведение `can` здесь не меняются ни
 * на одно право — эффективный доступ живых учёток после этого шага прежний.
 *
 * Отдельным файлом от матрицы по той же причине, по которой отделён каталог: `permissions.ts`
 * отвечает на вопрос «кому положено право», а здесь — «что нельзя выдать», «что без чего не имеет
 * смысла» и «что нельзя свести в одном человеке». Зависимость односторонняя: полномочия знают про
 * словарь прав, словарь про полномочия — нет.
 */

/**
 * Коды двух системных полномочий, переносимых из надстроек (ADR 0106, решение 9, шаг 1a).
 *
 * Код — идентификатор набора, а не его название, и стабилен он не из аккуратности: по коду
 * миграция шага 1a создаёт набор и находит его при повторном прогоне; по коду двойная запись
 * отражает выдачу надстройки в `user_grants`; по коду типизированная таблица расширения области
 * (`GRANT_MODULE_WIDE_SCOPE`, ADR 0106, решение 2) вешает на «Согласование ИТ» сквозную область
 * двух модулей оргтехники (ADR 0096). Название, описание и цвет — витрина, их правит выкат;
 * связывает строку в базе с кодом только код, и второго такого ключа нет.
 *
 * Отсюда запрет переименовывать системный набор в базе. `UPDATE grants SET code = ...` не
 * «переименовывает набор», а отвязывает его от кода: таблица области перестаёт его находить, и
 * виза ИТ теряет сквозную область, оставаясь на вид выданной. Отказ при этом молчаливый — прав у
 * держателя ровно столько же, а видит он снова только свой отдел, и объяснить это по журналу
 * выдач невозможно, потому что выдачу никто не трогал. По той же причине системный набор не
 * редактируется и не удаляется из интерфейса вовсе: его состав и код живут в коде, а строка в
 * базе — их отражение, а не источник.
 *
 * `satisfies readonly RoleAddon[]` — мост перехода, а не украшение. Пока идут шаги 1a–1d, код
 * набора обязан совпадать с кодом надстройки, из которой он перенесён: иначе двойной записи некуда
 * вставлять назначение, а сверка шага 1b покажет diff на ровном месте. Проверка уходит вместе с
 * `role-addons.ts` на шаге 1e.
 */
export const SYSTEM_GRANT_CODES = [
  'office_equipment_operator',
  'office_equipment_it_approver',
] as const satisfies readonly RoleAddon[];

export type SystemGrantCode = (typeof SYSTEM_GRANT_CODES)[number];

/**
 * Права, которые не попадают ни в один назначаемый набор — ни в системный, ни в собранный
 * администратором, ни в будущую точечную выдачу (ADR 0106, решение 6, инвариант 1).
 *
 * Пять, и каждое стоит здесь по своей причине:
 *
 * - `records.purge` — удаление записи насовсем, мимо пометки «удалена»: восстановить её уже нечем,
 *   и ошибка держателя набора не лечится ничем, кроме резервной копии;
 * - `users.manage` — ведение учёток, то есть выдача доступов. Право, которым набирают права,
 *   собранное набором, замыкает модель саму на себя: держатель дособирает себе что угодно, и
 *   каталог полномочий перестаёт быть границей;
 * - `waybills.correctBeyondLimit` — правка документов глубже тридцати дней. За пределом начинается
 *   разрыв хронологии журнала БСО, и отвечает за него тот, кто отвечает за журнал (ADR 0101, Р37);
 * - `driverCabinet.read` и `driverCabinet.submit` — **оба** права кабинета. Кабинет показывает
 *   задание конкретного работника и принимает показания от его имени (ADR 0102); достаться
 *   «заодно с пакетом» он не должен ни на чтение, ни на запись.
 *
 * Назначаемых прав поэтому 50 из 55, и число это берётся из константы, а не из текста: реализация,
 * пошедшая за «52 из 55», выдала бы кабинет чужой роли — то есть чужие персональные данные — и
 * сделала бы это молча, пройдя все тесты, написанные по той же тройке.
 *
 * Список обязан быть один на API, интерфейс и тесты. Три копии расходятся не одновременно: сначала
 * форма покажет чекбокс, который сервер отклонит (пользователь увидит непонятный отказ), потом
 * сервер примет то, чего форма не показывает (доступ, которого никто не собирал), а тест, живущий
 * по третьей копии, подтвердит и то и другое. Поэтому константа лежит в контрактах — там же, где
 * сам словарь прав.
 */
export const NON_GRANTABLE_PERMISSIONS = [
  'records.purge',
  'users.manage',
  'waybills.correctBeyondLimit',
  'driverCabinet.read',
  'driverCabinet.submit',
] as const satisfies readonly Permission[];

const NON_GRANTABLE_SET: ReadonlySet<Permission> = new Set(NON_GRANTABLE_PERMISSIONS);

/**
 * Можно ли включить право в назначаемое полномочие. Предикат, а не проверка `includes` по месту:
 * спрашивают его схема запроса, конструктор и тесты, и все трое обязаны получить один ответ.
 */
export function isGrantable(permission: Permission): boolean {
  return !NON_GRANTABLE_SET.has(permission);
}

/**
 * Что должно быть у субъекта, чтобы право имело смысл (ADR 0106, решение 6, инвариант 4).
 *
 * Инвариант ADR 0021 «модуль закрывается чтением» свободная сборка ломает первым: набор из одного
 * `vehicleRequests.status`, выданный коменданту, открывает прямой вызов смены статуса, хотя
 * `vehicleRequests.read` у него нет и раздела он не видит. Отсюда проверка после каждой операции,
 * меняющей доступ: для каждого эффективного права субъекта `PERMISSION_REQUIRES[право]` обязано
 * быть подмножеством его эффективных прав.
 *
 * Проверка идёт по **итоговым правам учётки**, а не внутри набора, и системный «Оператор
 * (оргтехника)» — прямое тому доказательство: `officeEquipment.write` даёт он, а
 * `officeEquipment.read` приходит от базовой роли. Набор сам по себе инвариант нарушает, субъект —
 * нет.
 *
 * **Витринный `MODULE_ENTRY_PERMISSION` границей безопасности служить не может.** Он группирует
 * права для экрана: у модуля `admin` входное право — `users.manage`, то есть ровно то, которое
 * защищено `NON_GRANTABLE_PERMISSIONS`. Проверка «по модулю» потребовала бы его от любого набора с
 * правами этого модуля и отклонила бы будущих «Аудитора» и «Рассылки» целиком — наборы, ради
 * которых реформа и затевалась. Альтернатива «разделить `admin` на три модуля витрины» рабочая, но
 * она чинит витрину ради безопасности, а не наоборот; поэтому требования задаются своей таблицей и
 * по праву, а не по модулю.
 *
 * Строка «требует само себя» проверкой ничего не делает — подмножество из самого права выполняется
 * всегда. Она объявляет, что право **входное**: за ним не стоит ничего, и пустота здесь — решение,
 * а не забытая строка. Ради этого различия таблица и хранит такие строки явно.
 *
 * **Тип — `Partial`, а не полный `Record`, и это осознанный отказ от помощи компилятора.** Полный
 * `Record` заставил бы приписать `[]` сорока девяти правам, и каждая такая строка утверждала бы
 * то, чего решение не утверждало: «это право самодостаточно, его можно выдать в одиночку». Первая
 * же из них — `wasteRequests.create: []` — прямо противоречила бы ADR 0021, где модуль закрывается
 * чтением. Расписать же честные требования всем действиям всех модулей значит принять сейчас
 * решения, которых в ADR 0106 нет, и сделать это в файле, который на этапе 1a обязан только
 * заводить структуры. Поэтому здесь ровно шесть объявленных требований, а отсутствие строки читается
 * как «требование не объявлено», а не как «право ничего не требует»; расширяет таблицу решение, а
 * не молчание. Читают её через `?? []`.
 */
export const PERMISSION_REQUIRES: Partial<Record<Permission, readonly Permission[]>> = {
  // Входные права трёх административных наборов, ради которых заведена таблица: журнал действий и
  // рассылки открываются своим чтением, а не общим `users.manage` модуля витрины.
  'audit.read': ['audit.read'],
  'mailings.read': ['mailings.read'],
  'mailings.manage': ['mailings.read'],
  'users.manage': ['users.manage'],
  // Списание испорченного бланка без журнала — действие вслепую: аннулировать нечего, если листов
  // не видно (ADR 0037).
  'waybills.cancel': ['waybills.read'],
  // Ход заказа без его чтения — тот самый случай коменданта: статус меняется прямым вызовом, а
  // раздела у субъекта нет.
  'vehicleRequests.status': ['vehicleRequests.read'],
};

/**
 * Пара прав, которую нельзя свести в одном субъекте, — разделение обязанностей (ADR 0106,
 * решение 6, инвариант 3). Причина хранится рядом с парой: отказ обязан называть виновников и
 * объяснять запрет теми же словами на API и в конструкторе, а не двумя разными.
 */
export interface GrantConflict {
  readonly permissions: readonly [Permission, Permission];
  readonly reason: string;
}

/**
 * Конфликты обязанностей первой поставки. Таблица, а не пример в тексте и не проверка по месту:
 * следующая пара добавляется строкой здесь, и её увидит всякий, кто читает границы сборки.
 *
 * Проверяется таблица по **итоговым эффективным правам учётки**, а не внутри набора: составление
 * сметы может лежать в одном полномочии, её утверждение — в другом, и по отдельности оба
 * безупречны. Исключение из проверки одно и привязано к роли `admin` (либо к невыдаваемому
 * признаку администратора), а не к объёму прав субъекта: правило «у кого есть весь модуль — того не
 * проверяем» отключало бы себя ровно в той операции, которая дособирает модуль и создаёт
 * запрещённую пару.
 */
export const GRANT_CONFLICTS: readonly GrantConflict[] = [
  {
    // Кто считает смету, тот её не утверждает: слитые в одном человеке, эти два права превращают
    // согласование расходов в подпись под собственной работой (ADR 0085).
    permissions: ['serviceRequests.estimate', 'serviceRequests.approveEstimate'],
    reason: 'Смету составляет и согласует один человек',
  },
  {
    // Виза ИТ отвечает на «зовём ли сервис вообще», и подтверждать необходимость работы, которую
    // сам же продаёшь, — не согласование. Запрет уже действует по ADR 0096; таблица повторяет его
    // там, где выполняется проверка, чтобы он не держался на одном лишь составе ролей.
    permissions: ['serviceRequests.estimate', 'serviceRequests.approveIt'],
    reason: 'Исполнитель сметы визирует необходимость собственной работы',
  },
];

/**
 * Первая нарушенная пара в наборе прав или `null`. Первая, а не все: сообщение об отказе должно
 * называть виновников, и одной пары для этого достаточно — как `incompatibleAddon` называет одну
 * несовместимую надстройку.
 *
 * Принимает права, а не субъект, намеренно. Исключение для администратора — вопрос роли, и решает
 * его вызывающий; получи эта функция субъект, соблазн вывести исключение из объёма его прав
 * появился бы прямо здесь, а такое правило отключает себя в той самой операции, которую и должно
 * ловить.
 */
export function conflictingPermissions(permissions: Iterable<Permission>): GrantConflict | null {
  const held = new Set(permissions);
  return (
    GRANT_CONFLICTS.find(
      ({ permissions: [first, second] }) => held.has(first) && held.has(second),
    ) ?? null
  );
}
