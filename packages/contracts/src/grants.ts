/** Что операция изменит у одной затронутой учётки. */
export interface GrantImpactUserDto {
  userId: string;
  fullName: string;
  role: Role | null;
  /**
   * Права, которые **реально** появятся и **реально** уйдут (`effectiveDelta`), — не разница составов
   * наборов. Снятие набора отбирает право только если его не даёт больше никто: ни роль, ни второй
   * набор, ни тип контрагента. Обе половины пустые — «доступ у этой учётки не изменится», и такая
   * строка в предпросмотре нужна: администратор видит, что человек затронут операцией, но ничего не
   * теряет.
   */
  added: Permission[];
  removed: Permission[];
  /** Роль держателя вне `grant_roles`: набор ему уже не даёт прав, и дельта у него пустая (§13.1). */
  roleMismatch: boolean;
}

/**
 * Предпросмотр последствий: что изменится и отпечаток того, из чего это посчитано (§13.1).
 *
 * Нарушения приходят в теле, а не отказом: предпросмотр — это чтение, и «так сохранить нельзя» он
 * обязан показать до нажатия, а не вместо ответа. Делятся они на два вида по той же границе, что в
 * `validateGrantAssignment`: `violations` — про сам набор, `holders` — про итог у затронутых учёток.
 */
export interface GrantImpactDto {
  operation: GrantImpactOperation;
  grantId: string;
  grantCode: string;
  grantName: string;
  /** Цель у выдачи и отзыва; `null` у правки набора. */
  userId: string | null;
  /** Версия набора, вошедшая в отпечаток. */
  version: number;
  /**
   * Затронутые учётки — то самое «затронет 14 учёток» из §12. У выдачи и отзыва их всегда ровно
   * одна, у правки набора — все держатели, включая тех, у кого дельта пустая.
   */
  users: GrantImpactUserDto[];
  /** Барьеры набора, которые операция нарушит; пустой список — «сохранить можно». */
  violations: GrantViolation[];
  /** Барьеры итога по каждой виновной учётке. */
  holders: GrantHolderViolationsDto[];
  /** Отпечаток: его же операция принимает в `expectedImpactHash`. */
  expectedImpactHash: string;
}

/**
 * Итог выдачи или отзыва.
 *
 * Карточка набора идёт в ответе целиком, а не одним `assignmentId`: реестр выдач обязан показывать
 * актуальное сразу после операции (§12), и второй запрос за ним разошёлся бы с первым ровно в тот
 * момент, когда рядом работает второй администратор.
 */
export interface GrantAssignmentResultDto {
  /**
   * Строка назначения. При повторной выдаче того же набора — **прежняя**, с прежним автором и
   * временем: `id` неизменяем, на нём держится откат перевода ролей (решение 3). У отзыва — та, что
   * удалена; переиспользовать её значение нельзя ни при каких обстоятельствах.
   */
  assignmentId: string;
  userId: string;
  grantId: string;
  /**
   * Изменилось ли состояние. Повторная выдача уже выданного набора отвечает `false`: дубля не
   * возникает (`UNIQUE (user_id, grant_id)`), токены не гаснут, в журнал ничего не уходит.
   */
  changed: boolean;
  /** Что реально изменилось в правах учётки — то же, что показывал предпросмотр. */
  delta: PermissionDelta;
  /** Набор с обновлённым реестром выдач. */
  grant: GrantCardDto;
}
