/**
 * Можно ли включить право в назначаемое полномочие. Предикат, а не проверка `includes` по месту:
 * спрашивают его схема запроса, конструктор и тесты, и все трое обязаны получить один ответ.
 */
export function isGrantable(permission: Permission): boolean {
  return !NON_GRANTABLE_SET.has(permission);
}

