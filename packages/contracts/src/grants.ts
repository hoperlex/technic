/**
 * Назначаемые полномочия (ADR 0106) — именованный набор прав, который выдаётся учётке поверх её
 * роли и приходит на смену надстройкам (ADR 0086).
 *
 * Файл заводит **данные и решения, но не поведение доступа**: коды двух системных наборов, границы
 * свободной сборки, таблицы, по которым сервер, миграция и будущий конструктор принимают решения, и
 * единую проверку выдачи, которая собирает все барьеры в одном месте (`validateGrantAssignment`,
 * этап 3, первая волна). Матрица `ROLE_PERMISSIONS`, список `ROLE_ADDONS` и поведение `can` здесь не
 * меняются ни на одно право — эффективный доступ живых учёток прежний, а проверку выдачи пока никто
 * не спрашивает: маршруты и экран приходят следующими волнами.
 *
 * Отдельным файлом от матрицы по той же причине, по которой отделён каталог: `permissions.ts`
 * отвечает на вопрос «кому положено право», а здесь — «что нельзя выдать», «что без чего не имеет
 * смысла» и «что нельзя свести в одном человеке». Зависимость односторонняя: полномочия знают про
 * словарь прав, словарь про полномочия — нет.
 */

/**
 * Коды двух системных полномочий, переносимых из надстроек (ADR 0106, решение 9, шаг 1a).
 *
 * Код — идентификатор набора, а не его название, и стабилен он не из аккуратности: по коду
 * миграция шага 1a создаёт набор именно под этим кодом; по коду двойная запись
 * отражает выдачу надстройки в `user_grants`; по коду типизированная таблица расширения области
 * (`GRANT_MODULE_WIDE_SCOPE`, ADR 0106, решение 2) вешает на «Согласование ИТ» сквозную область
 * двух модулей оргтехники (ADR 0096). Название, описание и цвет — витрина, их правит выкат;
 * связывает строку в базе с кодом только код, и второго такого ключа нет.
 *
 * Отсюда запрет переименовывать системный набор в базе. `UPDATE grants SET code = ...` не
 * «переименовывает набор», а отвязывает его от кода: таблица области перестаёт его находить, и
 * виза ИТ теряет сквозную область, оставаясь на вид выданной. Отказ при этом молчаливый — прав у
 * держателя ровно столько же, а видит он снова только свой отдел, и объяснить это по журналу
 * выдач невозможно, потому что выдачу никто не трогал. По той же причине системный набор не
 * редактируется и не удаляется из интерфейса вовсе: его состав и код живут в коде, а строка в
 * базе — их отражение, а не источник.
 *
 * `satisfies readonly RoleAddon[]` — мост перехода, а не украшение. Пока идут шаги 1a–1d, код
 * набора обязан совпадать с кодом надстройки, из которой он перенесён: иначе двойной записи некуда
 * вставлять назначение, а сверка шага 1b покажет diff на ровном месте. Проверка уходит вместе с
 * `role-addons.ts` на шаге 1e.
 */
export const SYSTEM_GRANT_CODES = [
  'office_equipment_operator',
  'office_equipment_it_approver',
] as const satisfies readonly RoleAddon[];

export type SystemGrantCode = (typeof SYSTEM_GRANT_CODES)[number];

/**
 * Модуль, в котором набор может снимать сужение области.
 *
 * Псевдоним `AddonScopeModule`, а не второй список из тех же двух имён. Пока идут шаги 1a–1d,
 * таблица области существует в двух видах — по надстройкам и по кодам наборов, — и разъехавшийся
 * перечень модулей означал бы, что «сквозная область» до переключения читателей и после неё
 * означает разное. Собственный список появится здесь на шаге 1e, когда `role-addons.ts` уйдёт
 * целиком и переносить будет уже нечего.
 */
export type ScopeModule = AddonScopeModule;

/**
 * Модули, в которых набор снимает сужение области (ADR 0106, решение 2), — та же таблица, что
 * `ADDON_MODULE_WIDE_SCOPE`, но по **кодам наборов**, а не по значениям enum'а надстроек.
 *
 * Ключ — `SystemGrantCode`, и это не украшение типа, а вся суть решения. Расширение области —
 * кодовое свойство конкретного набора, а не то, что администратор отмечает в конструкторе:
 * пользовательский набор scope-neutral без исключений, и собрать «видеть чужой объект» в
 * интерфейсе невозможно. Держится это тем, что чужой ключ здесь не примет компилятор, — а не
 * проверкой `is_system` при чтении, которую однажды забудут поставить.
 *
 * Пустой список у оператора оргтехники — не забытая строка, а решение 2 ADR 0086 в неизменном
 * виде: он ведёт свою площадку и свой отдел.
 */
export const GRANT_MODULE_WIDE_SCOPE: Record<SystemGrantCode, readonly ScopeModule[]> = {
  office_equipment_operator: [],
  office_equipment_it_approver: ['serviceRequests', 'officeEquipment'],
};

/**
 * Тот же перечень, разложенный по ключу-строке. `Map`, а не индексация `Record` с приведением
 * `code as SystemGrantCode`: приведение пообещало бы, что в наборах учётки бывают только системные
 * коды, а приходят они из базы, где рядом лежат собранные администратором.
 */
const MODULE_WIDE_SCOPE_BY_CODE: ReadonlyMap<string, readonly ScopeModule[]> = new Map(
  Object.entries(GRANT_MODULE_WIDE_SCOPE),
);

/**
 * Видит ли держатель наборов модуль целиком, минуя область своей роли.
 *
 * На вход идут коды **из базы** — обычные строки, а не `SystemGrantCode`. Пользовательский набор,
 * набор с кодом из будущего выката, набор, переименованный в базе руками, — всё это даёт
 * `undefined` в таблице и никакого расширения. Сузить параметр до системных кодов значило бы
 * требовать от читателя разбирать коды до вызова, то есть завести вторую границу там, где хватает
 * промаха по ключу.
 *
 * **Гейта по роли здесь нет, и это осознанно.** Сегодняшний `hasModuleWideScope` роль тоже не
 * спрашивает: совместимость набора с ролью — вопрос выдачи, и стоит он там, где выдают. Добавить
 * проверку заодно с переносом значило бы изменить поведение под видом переезда, а шаг перехода
 * обязан менять способ хранения и ничего больше. Совместимость с ролью на чтении при этом никуда
 * не делась — её держит выражение прав (`grantPermissionsExpr`, соединение с `grant_roles`); здесь
 * же речь про область, и заводить второй гейт с другим ответом нельзя.
 */
export function hasModuleWideScope(
  codes: readonly string[] | null | undefined,
  module: ScopeModule,
): boolean {
  return (codes ?? []).some((code) => MODULE_WIDE_SCOPE_BY_CODE.get(code)?.includes(module));
}

// ── Административная часть стартового каталога (план §10 и §15, этап 4) ──

/**
 * Объявленный состав системного набора — то, что миграция каталога переписывает в базу строками
 * `INSERT`, а страж `grants-catalog.db.test.ts` сверяет обратно.
 *
 * Описания здесь нет намеренно, и это не экономия. Описание — абзац для администратора, который
 * читается на экране каталога рядом с набором и объясняет **работу**, а не доступ; его место — в
 * миграции, где оно стоит вместе с обоснованием строки. Название, состав и роли — другое дело: на
 * них ссылается проверка выдачи (`grantLabel` в тексте отказа), их сверяет страж, и разъехавшись,
 * они меняют доступ. Копия, которую никто не сверяет, хуже отсутствия копии.
 */
export interface CatalogGrant {
  readonly name: string;
  readonly permissions: readonly Permission[];
  readonly roles: readonly Role[];
}

