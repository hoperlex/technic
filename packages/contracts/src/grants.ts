/**
 * Пара прав, которую нельзя свести в одном субъекте, — разделение обязанностей (ADR 0106,
 * решение 6, инвариант 3). Причина хранится рядом с парой: отказ обязан называть виновников и
 * объяснять запрет теми же словами на API и в конструкторе, а не двумя разными.
 */
export interface GrantConflict {
  readonly permissions: readonly [Permission, Permission];
  readonly reason: string;
}

/**
 * Конфликты обязанностей первой поставки. Таблица, а не пример в тексте и не проверка по месту:
 * следующая пара добавляется строкой здесь, и её увидит всякий, кто читает границы сборки.
 *
 * Проверяется таблица по **итоговым эффективным правам учётки**, а не внутри набора: составление
 * сметы может лежать в одном полномочии, её утверждение — в другом, и по отдельности оба
 * безупречны. Исключение из проверки одно и привязано к роли `admin` (либо к невыдаваемому
 * признаку администратора), а не к объёму прав субъекта: правило «у кого есть весь модуль — того не
 * проверяем» отключало бы себя ровно в той операции, которая дособирает модуль и создаёт
 * запрещённую пару.
 */
export const GRANT_CONFLICTS: readonly GrantConflict[] = [
  {
    // Кто считает смету, тот её не утверждает: слитые в одном человеке, эти два права превращают
    // согласование расходов в подпись под собственной работой (ADR 0085).
    permissions: ['serviceRequests.estimate', 'serviceRequests.approveEstimate'],
    reason: 'Смету составляет и согласует один человек',
  },
  {
    // Виза ИТ отвечает на «зовём ли сервис вообще», и подтверждать необходимость работы, которую
    // сам же продаёшь, — не согласование. Запрет уже действует по ADR 0096; таблица повторяет его
    // там, где выполняется проверка, чтобы он не держался на одном лишь составе ролей.
    permissions: ['serviceRequests.estimate', 'serviceRequests.approveIt'],
    reason: 'Исполнитель сметы визирует необходимость собственной работы',
  },
];

/**
 * Первая нарушенная пара в наборе прав или `null`. Первая, а не все: сообщение об отказе должно
 * называть виновников, и одной пары для этого достаточно — как `incompatibleAddon` называет одну
 * несовместимую надстройку.
 *
 * Принимает права, а не субъект, намеренно. Исключение для администратора — вопрос роли, и решает
 * его вызывающий; получи эта функция субъект, соблазн вывести исключение из объёма его прав
 * появился бы прямо здесь, а такое правило отключает себя в той самой операции, которую и должно
 * ловить.
 */
export function conflictingPermissions(permissions: Iterable<Permission>): GrantConflict | null {
  const held = new Set(permissions);
  return (
    GRANT_CONFLICTS.find(
      ({ permissions: [first, second] }) => held.has(first) && held.has(second),
    ) ?? null
  );
}

/**
 * Код нарушения выдачи — то, чем маршрут отвечает, а экран подсвечивает. Строка, а не номер:
 * номера читаются только через таблицу, а `permission_not_grantable` в журнале объясняет себя сам.
 *
 * Пять кодов — пять барьеров чек-листа готовности (план §15), и шестого здесь нет намеренно:
 * `expectedImpactHash`, блокировки «набор → учётки» и запись в журнал — свойства операции, а не
 * данных, и живут они там, где есть транзакция.
 */
export type GrantViolationCode =
  /** Право из `NON_GRANTABLE_PERMISSIONS` (инвариант 5 плана §8). */
  | 'permission_not_grantable'
  /** Роль, которой полномочия не выдаются вовсе, — сегодня это `driver` (инвариант 6). */
  | 'role_not_grantable'
  /** Модуль права помечен `forbidden` для оси этой роли (инвариант 4, матрица `grant-scope.ts`). */
  | 'module_forbidden_for_axis'
  /** У итоговых прав субъекта нет требуемого по `PERMISSION_REQUIRES` (ADR 0021, §13.1). */
  | 'requirement_missing'
  /** Итоговые права субъекта сводят пару из `GRANT_CONFLICTS` (разделение обязанностей). */
  | 'duty_conflict';

/**
 * Нарушение выдачи: код для машины, текст для человека и виновники по отдельным полям — чтобы
 * экрану не приходилось разбирать сообщение обратно.
 *
 * Модуль в полях не повторяется: он однозначно выводится из права через `PERMISSION_CATALOG`, и
 * второе его написание разошлось бы с первым — как только кто-нибудь перенесёт право в другой
 * модуль витрины.
 */
export interface GrantViolation {
  readonly code: GrantViolationCode;
  /** Текст отказа по-русски, называющий виновника: право, роль, набор — а не «недопустимая комбинация». */
  readonly message: string;
  /** Право-виновник: у барьера требований — то, что осталось без поддержки. */
  readonly permission?: Permission;
  /** Чего не хватает итоговым правам субъекта (только `requirement_missing`). */
  readonly requires?: Permission;
  /** Роль-виновник (`role_not_grantable`, `module_forbidden_for_axis`). */
  readonly role?: Role;
  /** Пара разделения обязанностей вместе с её причиной (только `duty_conflict`). */
  readonly conflict?: GrantConflict;
}

/**
 * Вход единой проверки выдачи.
 *
 * `subjectPermissionsAfter` и `subjectRole` объявлены **обязательными и нулевыми**, а не
 * необязательными, и это не педантизм: два барьера из пяти проверяются только по итогу, и
 * вызывающий, забывший прислать итог, получил бы «нарушений нет» на операции, которая как раз
 * ломает инвариант. Обязательное поле заставляет компилятор спросить, и `null` в нём — осознанный
 * ответ «операции над учёткой в этом вызове нет» (так конструктор сохраняет состав набора, ещё
 * никому не выданного).
 */
export interface GrantAssignmentCheck {
  /**
   * Роли, которым набор разрешён (`grant_roles`), — либо роль держателя, если проверяется выдача.
   * Пустой список законен: набор, который ещё никому нельзя выдать, ничего не открывает.
   */
  readonly roles: readonly Role[];
  /** Состав набора (`grant_permissions`). Пустой список законен — он просто ничего не даёт. */
  readonly permissions: readonly Permission[];
  /**
   * **Итоговые** эффективные права субъекта после операции — то, что вернёт `can` по всем
   * источникам (роль, тип контрагента, все наборы), а не состав проверяемого набора. `null` —
   * субъекта в операции нет.
   */
  readonly subjectPermissionsAfter: readonly Permission[] | null;
  /** Роль субъекта операции; нужна ровно для оговорки об администраторе. `null` — субъекта нет. */
  readonly subjectRole: Role | null;
  /** Название набора для текста отказа: администратор читает имя, а не код. */
  readonly grantLabel?: string;
}

/** Право в тексте отказа — подписью и кодом: подпись читают, код ищут в журнале и в форме. */
function permissionTitle(permission: Permission): string {
  return `«${PERMISSION_CATALOG[permission].label}» (${permission})`;
}

/**
 * **Единая проверка выдачи — все барьеры в одном месте.** Список нарушений, а не исключение: одно
 * и то же спрашивают маршрут (чтобы отказать), конструктор (чтобы не дать нажать) и тесты, и
 * бросающая функция заставила бы экран узнавать про второе нарушение после исправления первого.
 * Пустой список означает «выдача законна».
 *
 * Барьеры делятся на два вида, и путать их нельзя.
 *
 * **Барьеры набора** (1–3) считаются по присланным `roles` и `permissions`: невыдаваемое право,
 * роль, не принимающая наборов, и декартово произведение против матрицы осей. Они проверяются до
 * записи, потому что после неё проверять нечего — данные уже показаны (план §8, инвариант 4).
 *
 * **Барьеры итога** (4–5) считаются по `subjectPermissionsAfter`: требования прав друг к другу и
 * разделение обязанностей. Внутри набора их проверять нельзя, и системный «Оператор (оргтехника)» —
 * прямое доказательство: `officeEquipment.write` даёт он, а `officeEquipment.read` приходит от
 * базовой роли. Набор сам по себе инвариант нарушает, субъект — нет (§13.1).
 *
 * **Оговорка об администраторе привязана к роли, а не к объёму прав.** У роли `admin` весь словарь,
 * то есть обе конфликтующие пары есть у неё всегда; без оговорки любая операция над её учёткой
 * (смена области, выключение, правка) отклонялась бы отказом, который никто не может устранить.
 * Формулировка «не проверяем того, у кого есть все права модуля конфликта» отвергнута планом
 * (§13.1) и здесь не реализована: исполнитель-подрядчик `service` уже имеет четыре права модуля
 * обслуживания из десяти, ни одно из недостающих не защищено, — и правило выключало бы проверку
 * ровно в той операции, которая дособирает модуль и создаёт запрещённую пару. Правило, отменяющее
 * себя ростом доступа, — не правило.
 *
 * **Одна причина — одно нарушение.** Невыдаваемое право до матрицы не доходит (иначе `users.manage`
 * ловился бы дважды — запретом и клеткой модуля `admin`), а роль `driver` не проверяется по
 * матрице вовсе: ей отказано целиком, и перечислять вдогонку её запрещённые клетки значило бы
 * выдать администратору список, из которого не видно главного.
 *
 * Порядок нарушений устойчив и объявлен: сначала барьеры набора в порядке барьеров (право → роль →
 * пары «роль × право», роли снаружи), затем барьеры итога, причём требования — в порядке словаря
 * `PERMISSIONS`, а не в том, в каком права субъекта пришли. Иначе один и тот же отказ читался бы
 * по-разному от вызова к вызову.
 */
export function validateGrantAssignment(check: GrantAssignmentCheck): readonly GrantViolation[] {
  const violations: GrantViolation[] = [];
  const where = check.grantLabel ? `Набор «${check.grantLabel}»: ` : '';

  // Барьер 1: право не из `NON_GRANTABLE_PERMISSIONS`. Дубликаты в составе — не два нарушения:
  // право, пришедшее в форме дважды, виновато один раз.
  const grantable: Permission[] = [];
  for (const permission of new Set(check.permissions)) {
    if (isGrantable(permission)) {
      grantable.push(permission);
      continue;
    }
    violations.push({
      code: 'permission_not_grantable',
      permission,
      message: `${where}право ${permissionTitle(permission)} не выдаётся полномочиями ни при каких условиях — ни системным набором, ни собранным администратором.`,
    });
  }

  // Барьер 2: роль `driver` наборов не принимает (план §8, инвариант 6).
  const roles: Role[] = [];
  for (const role of new Set(check.roles)) {
    if (role !== 'driver') {
      roles.push(role);
      continue;
    }
    violations.push({
      code: 'role_not_grantable',
      role,
      message: `${where}роль «${roleLabels.driver}» полномочий не принимает ни одним способом: кабинет открывает задание конкретного работника, и добавить к нему чужие права нельзя.`,
    });
  }

  // Барьер 3: декартово произведение «роль × право» против матрицы осей.
  for (const role of roles) {
    for (const permission of grantable) {
      const { module } = PERMISSION_CATALOG[permission];
      if (grantScopeRule(role, module) !== 'forbidden') continue;
      violations.push({
        code: 'module_forbidden_for_axis',
        permission,
        role,
        message: `${where}право ${permissionTitle(permission)} нельзя выдать роли «${roleLabels[role]}»: у модуля «${permissionModuleLabels[module]}» нет фильтрации по её области (${roleScopeAxisLabels[roleScopeAxis(role)]}), и набор открыл бы данные всей компании.`,
      });
    }
  }

  const after = check.subjectPermissionsAfter;
  if (after === null) return violations;
  const held = new Set<Permission>(after);

  // Барьер 4: «модуль закрывается чтением» — по итоговым правам субъекта (ADR 0021, §13.1).
  for (const permission of PERMISSIONS) {
    if (!held.has(permission)) continue;
    for (const required of PERMISSION_REQUIRES[permission] ?? []) {
      if (held.has(required)) continue;
      violations.push({
        code: 'requirement_missing',
        permission,
        requires: required,
        message: `${where}у учётки есть право ${permissionTitle(permission)}, а ${permissionTitle(required)} — нет: действие открыто в модуле «${permissionModuleLabels[PERMISSION_CATALOG[permission].module]}», которого учётка не видит.`,
      });
    }
  }

  // Барьер 5: разделение обязанностей — по итогу и с оговоркой об администраторе.
  if (check.subjectRole === 'admin') return violations;
  for (const conflict of GRANT_CONFLICTS) {
    const [first, second] = conflict.permissions;
    if (!held.has(first) || !held.has(second)) continue;
    violations.push({
      code: 'duty_conflict',
      conflict,
      message: `${where}права ${permissionTitle(first)} и ${permissionTitle(second)} сходятся в одной учётке: ${conflict.reason}. Итог считается по всем источникам — половину пары может давать роль или другой набор.`,
    });
  }

  return violations;
}

// ── Каталог наборов: запросы, тела и витрина (план §12, этап 3) ──
//
// Выше в файле — решения и барьеры, то есть данные. Ниже — контракт серверного каталога: чем
// администратор спрашивает список, чем создаёт и правит набор и что видит в ответе. Живут они в
// одном файле по той же причине, по которой в одном файле живут словарь прав и его схема: тело
// запроса обязано ссылаться на те же константы, по которым считаются барьеры, — иначе форма покажет
// право, которого проверка не знает.

/**
 * Поля сортировки каталога. Числа держателей здесь нет намеренно: оно считается отдельным
 * агрегатом по `user_grants`, и сортировка по нему потребовала бы соединения в основном запросе
 * ради колонки, которую читают глазами. Появится — придёт вместе с окном реестра выдач.
 */
export const GRANT_SORT_FIELDS = ['code', 'name', 'isSystem', 'createdAt'] as const;

/**
 * Отбор по классу набора (ADR 0106, решение 2). Три значения, а не булев флаг: «все» — обычное
 * состояние экрана, и `system=false` означало бы «только пользовательские», то есть отсутствие
 * фильтра стало бы неотличимо от выбранного «нет».
 */
export const GRANT_KINDS = ['all', 'system', 'custom'] as const;
export type GrantKindFilter = (typeof GRANT_KINDS)[number];

export const grantListQuerySchema = baseListQuery(GRANT_SORT_FIELDS).extend({
  kind: z.enum(GRANT_KINDS).default('all'),
});
export type GrantListQuery = z.infer<typeof grantListQuerySchema>;

/**
 * Код пользовательского набора. Латиница нижнего регистра, цифры и подчёркивание — тот же вид, что
 * у системных кодов, и не из вкуса: код попадает в журнал, в реестр выдач и в ключи типизированных
 * таблиц кода (`GRANT_MODULE_WIDE_SCOPE`), а пробелы и регистр там читаются как две разные записи.
 *
 * Системный код администратору не отдаётся. Уникальный индекс в базе его и так не пустит, пока
 * системная строка жива, — но отказ пришёл бы «код занят», и это была бы неправда о причине:
 * запрет тут не в занятости, а в том, что таблица сквозной области ищет набор **по коду**, и
 * пользовательская строка под кодом визы ИТ получила бы область двух модулей оргтехники, которую
 * решение 2 запрещает пользовательским наборам вовсе.
 *
 * Список — `ALL_SYSTEM_GRANT_CODES`, то есть вместе с административными (§10, этап 4). Область они
 * не расширяют, но код у них тот же ключ: под ним их ищет миграция каталога, и пользовательская
 * копия «Архивариуса» под кодом системного оставила бы будущую правку каталога без строки, которую
 * она правит.
 */
export const grantCodeSchema = z
  .string()
  .trim()
  .min(1)
  .max(100)
  .regex(/^[a-z][a-z0-9_]*$/u, 'Код: латиница в нижнем регистре, цифры и подчёркивание')
  .refine((code) => !(ALL_SYSTEM_GRANT_CODES as readonly string[]).includes(code), {
    message: 'Такой код занят системным полномочием — выберите другой',
  });

export const grantNameSchema = z.string().trim().min(1).max(255);
/** Описание — то, чем набор объясняет себя в каталоге; пустое законно, но короче названия не бывает. */
export const grantDescriptionSchema = z.string().trim().max(2000);

/**
 * Состав набора. Схема принимает **любое** право словаря, включая невыдаваемые, и это осознанно:
 * барьеры считает `validateGrantAssignment`, и отказ обязан называть виновника словами («право
 * „Ведение учётных записей“ не выдаётся полномочиями ни при каких условиях»), а не приходить общим
 * «недопустимое значение перечисления». Схема здесь отвечает только за то, что право существует.
 */
export const grantPermissionListSchema = z.array(z.enum(PERMISSIONS)).max(PERMISSIONS.length);
/** Совместимые роли — по той же причине без отсева `driver`: барьер называет её сам. */
export const grantRoleListSchema = z.array(roleSchema).max(ROLES.length);

// ── Отпечаток последствий (`expectedImpactHash`, ADR 0106, решение 7; план §13.1) ──

/**
 * Операции над учёткой, которые администратор подтверждает по предпросмотру. Две, и обе меняют
 * состав назначений: выдача создаёт строку `user_grants`, отзыв её удаляет.
 */
export const GRANT_ASSIGNMENT_OPERATIONS = ['assign', 'revoke'] as const;
export type GrantAssignmentOperation = (typeof GRANT_ASSIGNMENT_OPERATIONS)[number];

/**
 * Все операции, меняющие доступ через полномочия, — то есть все, у которых бывает предпросмотр.
 * Правка набора стоит рядом с выдачей и отзывом намеренно: отпечаток у них общий, потому что
 * пересекаются они на одних и тех же строках (§13.1, правило блокировок), и два разных отпечатка
 * означали бы, что одна операция не видит подтверждения другой.
 */
export const GRANT_IMPACT_OPERATIONS = ['update', ...GRANT_ASSIGNMENT_OPERATIONS] as const;
export type GrantImpactOperation = (typeof GRANT_IMPACT_OPERATIONS)[number];

/** Затронутая учётка вместе с версией её токенов — слагаемое отпечатка. */
export interface GrantImpactAccount {
  readonly userId: string;
  /** `users.auth_version`: готовый счётчик изменений доступа — он растёт при каждой такой правке. */
  readonly authVersion: number;
}

/**
 * Всё, от чего зависел показанный предпросмотр (§13.1, таблица слагаемых). Пять полей, и ни одно не
 * украшение:
 *
 * | Слагаемое                                | Что ловит                                     |
 * | ---------------------------------------- | --------------------------------------------- |
 * | `operation` + `grantId` / `userId`       | подмену действия при том же состоянии базы     |
 * | `permissions` + `roles` (пост-состав)    | предпросмотр состава A и сохранение состава B  |
 * | `version`                                | правку состава кем-то другим                   |
 * | `assignmentIds`                          | появление и исчезновение держателей            |
 * | `accounts`                               | смену роли или другого набора у держателя       |
 *
 * **Первые две строки — то, без чего отпечаток не работает вовсе.** Отпечаток только из состояния
 * базы не связан с тем, что подтверждали: администратор смотрит предпросмотр состава A, отправляет
 * состав B, база за это время не менялась — хеш совпадает, и сервер применяет то, чего никто не
 * видел.
 *
 * **Заменить пост-состав на `effectiveDelta` нельзя** (§13.1). Delta считает не то, что подтверждают,
 * а то, что из этого следует, и следствие теряет различия: составы `{read, update}` и `{update}`
 * дадут одинаковую delta, если `read` держателю и так приходит от роли, — а это два разных набора, и
 * второй перестанет работать в день, когда роль сменят. Правка `grant_roles` не меняет delta нынешних
 * держателей вовсе: она про то, кому набор можно выдать завтра. Delta допустима только **вдобавок**
 * к каноническому пост-составу, и никогда вместо него.
 */
export interface GrantImpactInput {
  readonly operation: GrantImpactOperation;
  readonly grantId: string;
  /** Цель у выдачи и отзыва; `null` у правки набора — там цель сам набор, а не одна учётка. */
  readonly userId: string | null;
  /** Предлагаемый пост-состав: права. У выдачи и отзыва — нынешний состав, он не меняется. */
  readonly permissions: readonly Permission[];
  /** Предлагаемый пост-состав: совместимые роли. */
  readonly roles: readonly Role[];
  readonly version: number;
  /**
   * Идентификаторы назначений, от которых зависел расчёт: у правки набора — назначения всех его
   * держателей, у выдачи и отзыва — **все** назначения целевой учётки.
   *
   * Все, а не одно правимое: итог считается по сумме наборов учётки (разделение обязанностей
   * возникает суммой, §13.1), и назначение, появившееся у неё между предпросмотром и сохранением,
   * меняет и дельту, и приговор барьеров.
   */
  readonly assignmentIds: readonly string[];
  /** Затронутые учётки: у правки — держатели, у выдачи и отзыва — одна целевая. */
  readonly accounts: readonly GrantImpactAccount[];
}

/**
 * Каноническая строка отпечатка. Именно строка, а не объект: порядок полей формы и порядок галочек
 * в ней на отпечаток влиять не должны, поэтому все списки сортируются, а поля печатаются в
 * объявленном здесь порядке. Требование одно и проверяется тестом: **разный запрос — разный хеш**.
 *
 * Сам хеш считает сервер (`grantImpactHash` в `services/grant-catalog.ts`): у контрактов нет
 * криптографии, которая работала бы одинаково в браузере и в Node, а порталу считать его и не нужно —
 * он получает отпечаток предпросмотром и возвращает его как есть. Каноническая же строка живёт здесь,
 * рядом с барьерами: она описывает, **что** покрыто подтверждением, а это решение модели.
 *
 * Версия в первой строке (`grant-impact/v1`) нужна выкату: правка состава слагаемых обязана обесценить
 * отпечатки, выданные прежней версией, — иначе подтверждение, посчитанное по четырём слагаемым,
 * сошлось бы с проверкой по пяти.
 */
export function grantImpactCanonical(input: GrantImpactInput): string {
  const list = (values: readonly string[]): string => [...new Set(values)].sort().join(',');
  return [
    'grant-impact/v1',
    `op=${input.operation}`,
    `grant=${input.grantId}`,
    `user=${input.userId ?? '-'}`,
    `version=${input.version}`,
    `permissions=${list(input.permissions)}`,
    `roles=${list(input.roles)}`,
    `assignments=${list(input.assignmentIds)}`,
    `accounts=${list(input.accounts.map((a) => `${a.userId}:${a.authVersion}`))}`,
  ].join('\n');
}

/**
 * Отпечаток в теле запроса: шестнадцатеричный sha256, каким его вернул предпросмотр.
 *
 * Формат проверяется схемой, хотя портал отпечаток только передаёт обратно: мусор в поле обязан
 * отвечать 400 («так отпечатки не выглядят»), а не 409 («данные устарели, перечитайте») — второй
 * ответ отправил бы портал в бесконечный цикл перечитывания того, что не изменится.
 */
export const expectedImpactHashSchema = z
  .string()
  .trim()
  .length(64)
  .regex(/^[0-9a-f]+$/u, 'Отпечаток последствий: 64 шестнадцатеричных знака');

/**
 * Создание пользовательского набора. Признака `isSystem` в теле нет и быть не может: системный
 * набор заводит миграция, потому что только он несёт объявленный в коде scope-эффект (решение 2), а
 * поле в схеме означало бы, что признак — вопрос запроса.
 */
export const createGrantSchema = z.object({
  code: grantCodeSchema,
  name: grantNameSchema,
  description: grantDescriptionSchema.default(''),
  permissions: grantPermissionListSchema.default([]),
  roles: grantRoleListSchema.default([]),
});
export type CreateGrantInput = z.infer<typeof createGrantSchema>;

/**
 * Правка набора. Кода здесь нет намеренно — переименование кода не переименовывает набор, а
 * отвязывает его от таблиц кода (см. `SYSTEM_GRANT_CODES`), и для пользовательского набора это
 * та же потеря связи с журналом и реестром выдач.
 *
 * `expectedVersion` обязателен, а не необязателен «для совместимости»: правка состава меняет доступ
 * всем держателям сразу, и запрос без версии — это согласие применить её к состоянию, которого
 * отправитель не видел.
 *
 * **`expectedImpactHash` обязателен рядом с версией, и одно другое не заменяет.** Версии мало по
 * решению 7: состав не менялся, версия та же, а набор тем временем выдали пятнадцатому человеку — или
 * одному из держателей сменили роль либо другой набор. Версия совпадёт, а применится не то, что
 * подтверждали. Отпечаток покрывает и это, и сам присланный состав (см. `GrantImpactInput`).
 *
 * Обратное тоже верно, поэтому версия не убрана: отпечаток отвечает только «показанное устарело», а
 * версия называет причину — «состав правил другой администратор (версия 5, а не 4)». Отказ без этой
 * половины отправлял бы администратора искать, что же изменилось, по всей карточке.
 */
export const updateGrantSchema = z.object({
  expectedVersion: z.number().int().min(1),
  /** Отпечаток последствий, каким его вернул `POST /grants/:id/preview` для **этого** состава. */
  expectedImpactHash: expectedImpactHashSchema,
  name: grantNameSchema.optional(),
  description: grantDescriptionSchema.optional(),
  /** Полный состав; отсутствие поля — «не трогать права», как у наборов в карточке отдела. */
  permissions: grantPermissionListSchema.optional(),
  /** Полный список ролей; отсутствие поля — «не трогать роли». */
  roles: grantRoleListSchema.optional(),
});

/**
 * Тело предпросмотра правки набора — те же поля состава, что у `PATCH`, но без версии и отпечатка:
 * их предпросмотр как раз и выдаёт.
 *
 * Отсутствие поля читается так же, как в правке («не трогать»), и это обязательное свойство, а не
 * совпадение: пост-состав входит в отпечаток, поэтому предпросмотр и сохранение должны достраивать
 * пропущенные поля из строки набора **одинаково**. Разойдись они — отпечаток не совпал бы никогда, и
 * правка стала бы невыполнимой.
 */
export const grantUpdatePreviewSchema = z.object({
  name: grantNameSchema.optional(),
  permissions: grantPermissionListSchema.optional(),
  roles: grantRoleListSchema.optional(),
});
export type GrantUpdatePreviewInput = z.infer<typeof grantUpdatePreviewSchema>;

/**
 * Тело предпросмотра выдачи и отзыва: что собираются сделать и с каким набором. Учётка приходит
 * адресом — предпросмотр висит на её карточке, а не на каталоге.
 *
 * Вид операции в теле, а не два маршрута: ответ у них одинаковый по форме (дельта плюс отпечаток), а
 * вид операции входит в отпечаток слагаемым — «подмену действия при том же состоянии базы» ловит
 * именно он. Два маршрута с одинаковым телом означали бы, что отпечаток выдачи примет отзыв.
 */
export const grantAssignmentPreviewSchema = z.object({
  operation: z.enum(GRANT_ASSIGNMENT_OPERATIONS),
  grantId: z.string().uuid(),
});
export type GrantAssignmentPreviewInput = z.infer<typeof grantAssignmentPreviewSchema>;

/** Тело выдачи набора учётке: какой набор и под какой отпечаток. */
export const assignGrantSchema = z.object({
  grantId: z.string().uuid(),
  expectedImpactHash: expectedImpactHashSchema,
});
export type AssignGrantInput = z.infer<typeof assignGrantSchema>;

/**
 * Отзыв: набор назван в адресе, в строке запроса — только отпечаток. Тем же приёмом удаляются акт ТО
 * и точка маршрута (версия строкой запроса): тело у `DELETE` доходит не через каждый прокси, а
 * подтверждение операции обязано доходить всегда.
 */
export const revokeGrantQuerySchema = z.object({
  expectedImpactHash: expectedImpactHashSchema,
});
export type RevokeGrantQuery = z.infer<typeof revokeGrantQuerySchema>;
export type UpdateGrantInput = z.infer<typeof updateGrantSchema>;

/** Происхождение назначения (`user_grants.origin`): выдал человек или создал перевод ролей. */
export const GRANT_ORIGINS = ['manual', 'migration'] as const;
export type GrantOrigin = (typeof GRANT_ORIGINS)[number];

/**
 * Набор в каталоге. Права разложены на два поля, и это прямое следствие решения 3 ADR 0106:
 * право хранится в базе текстом, справочника прав в базе нет, и выкат, снявший право из словаря,
 * оставляет в наборе строку-сироту. Доступа она не даёт никогда — вычислитель её игнорирует, — но и
 * молчать о ней нельзя: в системном наборе такая строка означает забытую миграцию каталога, а в
 * пользовательском — право, которое администратор когда-то отметил, а портал больше не знает.
 */
export interface GrantDto {
  id: string;
  code: string;
  name: string;
  description: string;
  /** Системный набор: правке и удалению не подлежит, только он несёт scope-эффект (решение 2). */
  isSystem: boolean;
  /** Версия состава — её же присылает обратно правка в `expectedVersion`. */
  version: number;
  /** Состав набора в порядке словаря `PERMISSIONS`: список читают глазами. */
  permissions: Permission[];
  /** Строки состава, которых нет в словаре прав, — «право больше не существует». */
  unknownPermissions: string[];
  /** Роли, которым набор разрешено назначать, в порядке словаря `ROLES`. */
  roles: Role[];
  /** Сколько живых назначений у набора — то, чем удаление отвечает 409. */
  holderCount: number;
  createdAt: string;
  updatedAt: string;
}

/**
 * Держатель набора — строка реестра выдач (§12): кому выдано, кем, когда и на каком основании.
 *
 * `roleMismatch` — то самое «роль больше не в списке» из §13.1: назначение осталось живым, потому
 * что молчаливый массовый отзыв опаснее несоответствия, но новых выдач этой роли уже не будет.
 * Пометка обязана быть в ответе, а не выводиться экраном из пересечения ролей: пересечение экран
 * посчитает по составу набора, а несоответствие — свойство назначения.
 */
export interface GrantHolderDto {
  /** Идентификатор назначения (`user_grants.id`) — им следующая волна отзывает выдачу. */
  assignmentId: string;
  userId: string;
  fullName: string;
  email: string;
  role: Role | null;
  /** Роль держателя не входит в `roles` набора: выдача жива, прав по ней набор не даёт. */
  roleMismatch: boolean;
  /** Доступ в портал у держателя открыт. Выключенная учётка держит набор наравне с действующей. */
  isActive: boolean;
  /** Учётка в архиве (ADR 0070). Назначение остаётся и мешает удалить набор — это не ошибка. */
  isArchived: boolean;
  grantedAt: string;
  /** Кто выдал; `null` — учётку автора удалили насовсем (`granted_by` под `SET NULL`). */
  grantedByName: string | null;
  origin: GrantOrigin;
}

/** Карточка набора: каталожная строка плюс реестр его выдач. */
export interface GrantCardDto extends GrantDto {
  holders: GrantHolderDto[];
}

/** Нарушения по итогу у одного держателя: отказ обязан называть, кем именно операция запрещена. */
export interface GrantHolderViolationsDto {
  userId: string;
  fullName: string;
  violations: GrantViolation[];
}

/**
 * Тело отказа выдачи — то, что портал раскладывает по форме, не разбирая текст обратно.
 *
 * Две половины, потому что барьеров два вида (см. `validateGrantAssignment`): `violations` — про
 * сам набор (невыдаваемое право, роль `driver`, запрещённая клетка матрицы осей), `holders` — про
 * итог у держателей (требования прав и разделение обязанностей). Экран показывает их по-разному:
 * первые подсвечивают галочку в конструкторе, вторые — строку реестра выдач.
 */
export interface GrantValidationDetailsDto {
  violations: GrantViolation[];
  holders: GrantHolderViolationsDto[];
}

/** Тело отказа удаления: набор выдан, и вот кому (§13.1). */
export interface GrantHoldersConflictDetailsDto {
  holders: GrantHolderDto[];
}

/**
 * Коды отказов каталога — рядом с кодами нарушений и по той же причине: исход у каждого свой, и
 * различать их порталу нужно кодом, а не текстом.
 *
 * `version_conflict` здесь не перечислен: это общий код 409 (`err.conflict`), которым портал уже
 * показывает «откройте заново», и второго имени ему не нужно.
 */
export const GRANT_CONFLICT_CODES = {
  /** Правка или удаление системного набора: его состав живёт в коде (решение 2). */
  isSystem: 'grant_is_system',
  /** Удаление набора, у которого есть держатели: сначала отзыв (§13.1). */
  hasHolders: 'grant_has_holders',
  /** Код уже занят другим набором: он держится за набором навсегда, даже за удалённым. */
  codeTaken: 'grant_code_taken',
  /**
   * Отпечаток последствий не совпал: показанный предпросмотр больше не описывает то, что применится
   * (решение 7). Исход свой — «перечитайте и посмотрите предпросмотр заново», — и от `version_conflict`
   * он отличается тем, что состав набора мог вообще не меняться.
   */
  impactChanged: 'grant_impact_changed',
  /**
   * Роль держателя не входит в `grant_roles` набора: выдавать его этой роли нельзя (§13.1 — «новых
   * выдач этой роли уже не будет»).
   *
   * 409, а не 400: список наборов в карточке учётки отфильтрован совместимостью с ролью (§12), и
   * запрос, назвавший несовместимую пару, описывает не ошибку ввода, а устаревший экран — роль сменили
   * либо роль убрали из набора уже после того, как список показали.
   */
  roleNotAllowed: 'grant_role_not_allowed',
} as const;

// ── Предпросмотр последствий и результат назначения (решение 7; план §12, §13.1) ──

/** Что операция изменит у одной затронутой учётки. */
export interface GrantImpactUserDto {
  userId: string;
  fullName: string;
  role: Role | null;
  /**
   * Права, которые **реально** появятся и **реально** уйдут (`effectiveDelta`), — не разница составов
   * наборов. Снятие набора отбирает право только если его не даёт больше никто: ни роль, ни второй
   * набор, ни тип контрагента. Обе половины пустые — «доступ у этой учётки не изменится», и такая
   * строка в предпросмотре нужна: администратор видит, что человек затронут операцией, но ничего не
   * теряет.
   */
  added: Permission[];
  removed: Permission[];
  /** Роль держателя вне `grant_roles`: набор ему уже не даёт прав, и дельта у него пустая (§13.1). */
  roleMismatch: boolean;
}

/**
 * Предпросмотр последствий: что изменится и отпечаток того, из чего это посчитано (§13.1).
 *
 * Нарушения приходят в теле, а не отказом: предпросмотр — это чтение, и «так сохранить нельзя» он
 * обязан показать до нажатия, а не вместо ответа. Делятся они на два вида по той же границе, что в
 * `validateGrantAssignment`: `violations` — про сам набор, `holders` — про итог у затронутых учёток.
 */
export interface GrantImpactDto {
  operation: GrantImpactOperation;
  grantId: string;
  grantCode: string;
  grantName: string;
  /** Цель у выдачи и отзыва; `null` у правки набора. */
  userId: string | null;
  /** Версия набора, вошедшая в отпечаток. */
  version: number;
  /**
   * Затронутые учётки — то самое «затронет 14 учёток» из §12. У выдачи и отзыва их всегда ровно
   * одна, у правки набора — все держатели, включая тех, у кого дельта пустая.
   */
  users: GrantImpactUserDto[];
  /** Барьеры набора, которые операция нарушит; пустой список — «сохранить можно». */
  violations: GrantViolation[];
  /** Барьеры итога по каждой виновной учётке. */
  holders: GrantHolderViolationsDto[];
  /** Отпечаток: его же операция принимает в `expectedImpactHash`. */
  expectedImpactHash: string;
}

/**
 * Итог выдачи или отзыва.
 *
 * Карточка набора идёт в ответе целиком, а не одним `assignmentId`: реестр выдач обязан показывать
 * актуальное сразу после операции (§12), и второй запрос за ним разошёлся бы с первым ровно в тот
 * момент, когда рядом работает второй администратор.
 */
export interface GrantAssignmentResultDto {
  /**
   * Строка назначения. При повторной выдаче того же набора — **прежняя**, с прежним автором и
   * временем: `id` неизменяем, на нём держится откат перевода ролей (решение 3). У отзыва — та, что
   * удалена; переиспользовать её значение нельзя ни при каких обстоятельствах.
   */
  assignmentId: string;
  userId: string;
  grantId: string;
  /**
   * Изменилось ли состояние. Повторная выдача уже выданного набора отвечает `false`: дубля не
   * возникает (`UNIQUE (user_id, grant_id)`), токены не гаснут, в журнал ничего не уходит.
   */
  changed: boolean;
  /** Что реально изменилось в правах учётки — то же, что показывал предпросмотр. */
  delta: PermissionDelta;
  /** Набор с обновлённым реестром выдач. */
  grant: GrantCardDto;
}
