import type { RequestStatus } from './enums';

// ── История заявки (ADR 0012) ──
// Что с заявкой происходило: кто и когда её завёл, правил, менял статус. Собирается из двух
// источников — истории статусов и аудита; третьей таблицы не заводим, обе уже пишутся.
// Форма событий общая для всех модулей заявок: «Вывоз мусора» и «Заказ ТС» показывают историю
// одной и той же таблицей, и расхождение в DTO означало бы два разных рассказа об одном и том же.
// Модульного здесь только подписи полей (`wasteRequestChangeLabels`, `vehicleRequestChangeLabels`).

/**
 * Изменение одного поля при правке. Значения — готовый текст на момент правки, а не ссылки:
 * переименование справочника не должно переписывать прошлое. `from === null` — событие-список
 * («прикреплены файлы»), у него значима только правая часть.
 */
export interface RequestChangeDto {
  field: string;
  from: string | null;
  to: string | null;
}

/**
 * `operator` есть только у вывоза мусора: там исполнителя назначают контрагентом, а не машиной.
 * `approved` / `approvalRevoked` (виза руководителя строительства, ADR 0025), `assigned`
 * (техника со ставками, ADR 0027), `completed` (отработанное время и стоимость, ADR 0029) и
 * четвёрка `earlyEnd*` (досрочное завершение заказа спецтехники, ADR 0044) — наоборот, только у
 * заявок на технику.
 *
 * Досрочное завершение занимает четыре вида, а не один: запрос, виза, отказ и отзыв отвечают на
 * разные вопросы («что попросили», «чем кончилось», «почему отказали»), и в одном виде события
 * читатель истории не отличил бы состоявшееся сокращение срока от несостоявшегося.
 *
 * Пара `shift*` — подтверждение смены объектом: «кто принял 11,5 машиночаса за 12 августа» и
 * «кто эту подпись снял». Заполнение часов события не пишет вовсе — это черновик данных, а не
 * решение, и строка на каждое нажатие превратила бы историю заявки в журнал ввода.
 */
export type RequestHistoryKind =
  | 'created'
  | 'updated'
  | 'status'
  | 'operator'
  | 'approved'
  | 'approvalRevoked'
  | 'assigned'
  | 'completed'
  | 'earlyEndRequested'
  | 'earlyEndApproved'
  | 'earlyEndRejected'
  | 'earlyEndCancelled'
  /**
   * Срок продлён недельной заявкой (ADR 0085). Своё событие, а не «правка заявки»: заказ
   * продлевает не тот, кто его ведёт, а виза руководителя строительства под недельным пакетом, и
   * читателю истории нужен номер этого пакета — иначе срок меняется будто сам собой.
   */
  | 'weeklyExtended'
  /**
   * Заявка переоформлена в другой тип (ADR 0091). Своё событие, а не «правка»: у переоформления
   * меняется не значение поля, а то, из каких полей заявка состоит, — и «Подача: 12.08 08:00 → —»
   * без него читалось бы как потеря данных, а не как смена вида заказа.
   */
  | 'typeChanged'
  | 'shiftApproved'
  | 'shiftApprovalRevoked'
  /**
   * Заявка на обслуживание оргтехники (ADR 0085). Событий у неё больше, чем у соседних модулей,
   * потому что стороны три: заказчик заводит, оператор назначает и согласует, исполнитель ведёт
   * смету и закрывает работы. Каждое из них отвечает на свой вопрос читателя истории — «кого
   * позвали», «почему отказались», «какую ревизию согласовали», «что в итоге не поставили», — и
   * одним видом «изменено» они не заменяются.
   */
  | 'serviceAssigned'
  | 'serviceReassigned'
  | 'serviceDeclined'
  | 'estimateSubmitted'
  | 'estimateApproved'
  | 'estimateRejected'
  | 'estimateReopened'
  | 'accepted'
  | 'returnedToWork'
  | 'documentAttached'
  /**
   * Виза отдела ИТ и отказ по ней (план модернизации оргтехники, Р51, Р53). Два вида, а не один:
   * состоявшееся согласование и закрытая заявка — разные новости для читателя истории, и «решение
   * ИТ» одним словом не отвечает, чем кончилось.
   */
  | 'itApproved'
  | 'itRejected'
  /**
   * Выдача расходников со склада по заявке (план переработки заявок оргтехники, Р10). Своё
   * событие, а не «правка» и не «факт выполнения»: этой строкой заявка перестаёт быть просьбой и
   * становится основанием записи на складе, и читателю истории нужно видеть её отдельно от всего
   * прочего — «сколько тонера ушло по этой заявке» спрашивают именно у неё.
   *
   * Одно на выдачу и на возврат: сторно — это та же отметка факта, сделанная вниз, и различает их
   * не вид события, а перечень изменений («Списано со склада» против «Возвращено на склад»).
   */
  | 'consumablesIssued'
  /**
   * Срочность заявки поставлена или снята (план модернизации оргтехники, Р56). Своё событие, а не
   * правка: срочность меняет порядок работы над заявкой и ставится в том числе тогда, когда саму
   * заявку править уже нельзя, — «Правка» в этом месте истории означала бы, что кто-то менял
   * предмет заявки у сервиса под руками.
   */
  | 'urgencyChanged'
  /**
   * Решение по сообщению об отсутствующей технике (план
   * `docs/office-equipment-candidate-plan.md`, Р6, Р16). Своё событие, а не «правка»: предмет
   * заявки не поправили — его ПРИЗНАЛИ, признали чужой карточкой либо не признали вовсе, и до
   * решения у заявки предмета не было совсем.
   *
   * ОДИН ВИД НА ТРИ ИСХОДА, в отличие от пары `itApproved`/`itRejected`, — и это не экономия. Виза
   * ИТ приезжает в ленту без единого слова, и весь её смысл несёт тег: разведи мы его на два, «чем
   * кончилось» не читалось бы вовсе. Здесь наоборот — событие ГОВОРИТ: «Предмет подтверждён: „…“»,
   * «Предмет объединён с карточкой „…“», «Сообщение о технике отклонено: …». Второй и третий тег
   * повторяли бы то, что уже сказано строкой, а расходиться с ней начали бы на первой же правке
   * формулировок. Тот же довод у `consumablesIssued`, одного на выдачу и на возврат.
   */
  | 'equipmentCandidateDecided'
  /**
   * Реплика обсуждения заявки на обслуживание (ADR 0141, §3.8 плана). Своё событие, а не «правка»:
   * реплика ничего в заявке не меняет — ни поля, ни статуса, ни версии, — и «Заявка отредактирована»
   * в этом месте истории означало бы правку, которой не было.
   *
   * Текст едет в `comment`, а не в `changes`: у реплики нет «было → стало», она сама и есть
   * содержание события. Кому адресовано — там же, одной строкой: «сообщение сервисному центру:
   * „ждём запчасть“» отвечает и на «что сказали», и на «кому», а раскладывать это по двум полям
   * значило бы заставить читателя истории собирать фразу глазами.
   */
  | 'chatMessage'
  /**
   * Аренда механизации (план `docs/mechanization-module-plan.md`, Р11). Четыре вида, и все четыре
   * про деньги — потому и заведены отдельно, а не сведены к «изменено»:
   *
   * - `mechDeal` — договорённость назначена, исправлена или стёрта откатом в «Новую». Без своего
   *   события «была ставка 1200/час, стала 1500» не остаётся нигде: история статусов хранит только
   *   переход и комментарий;
   * - `mechIssued` — отметка выдачи. С неё пошли деньги, и момент этот обязан быть виден в ленте;
   * - `mechIssueRevoked` — снятие ошибочной отметки с причиной: единственное лечение опечатки, и
   *   от выдачи оно отличается не значением поля, а смыслом;
   * - `mechExtended` — продление срока. Причина продления не помещается в комментарий заявки — она
   *   перезаписала бы его, — а обе даты и объяснение нужны тому, кто разбирает счёт.
   *
   * Завершение, правка, архив и восстановление своих видов не получают: у модуля берутся готовые
   * `completed`, `updated`, `deleted` и `restored` с их подписями и тегами. Свести к `updated`
   * архив с восстановлением было бы ошибкой ровно обратного рода — карточка показала бы тег
   * «Правка» и «состав изменений не записан», потому что `changes` у них пуст по существу события.
   */
  | 'mechDeal'
  | 'mechIssued'
  | 'mechIssueRevoked'
  | 'mechExtended'
  | 'deleted'
  | 'restored';

export interface RequestHistoryEntryDto {
  id: string;
  kind: RequestHistoryKind;
  /** Момент события (ISO). */
  at: string;
  /** Автор события; null — учётная запись удалена или действие выполнено системой. */
  actorId: string | null;
  actorName: string | null;
  /** Смена статуса: откуда и куда. У остальных событий — null. */
  fromStatus: RequestStatus | null;
  toStatus: RequestStatus | null;
  /** Комментарий к переходу; при отмене — причина. */
  comment: string;
  /** Изменённые поля у правок; у остальных событий список пуст. */
  changes: RequestChangeDto[];
}
