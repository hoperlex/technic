// ── Отчёт по расходу за период (наброски `office-equipment-requests-rework-draft.md`, Р10; опрос
// В18; план переработки заявок, §7.3) ──
//
// Вопрос отчёта: кто, сколько, на какие аппараты и по каким заявкам израсходовал со склада за
// отрезок времени. Ради него расход и понадобился отдельно от остатка: остаток отвечает «сколько
// лежит сейчас», а заказ на квартал составляют по «сколько ушло за прошлый».
//
// СЧИТАЕТСЯ ПО ЖУРНАЛУ, а не по строкам заявок: сумма событий `issue` за вычетом `return` — тем же
// источником, что и сам остаток. Второй счётчик (например, по `issued_quantity` строк заявок)
// разошёлся бы с остатком на первом же сторно: правка факта вниз пишет `return` на разницу, и
// отчёт, читающий только итоговое «выдано», показал бы расход, которого не было.

/**
 * Период отчёта. Обе границы обязательны и включительны: отчёт «за август» — это отрезок, а не
 * «всё до сегодня», и умолчание «с начала времён» превратило бы его в выгрузку всего журнала.
 *
 * Дни, а не моменты: расход сверяют с накладными и счетами, у которых есть дата и нет времени.
 * Границы суток считает сервер по Москве — часовой пояс браузера иначе отрезал бы утро первого дня.
 *
 * Отбор по позиции необязателен: чаще спрашивают «сколько ушло всего», но «сколько ушло вот этого»
 * спрашивают из карточки самой позиции, и второго экрана ради одного условия заводить незачем.
 */
export const officeEquipmentConsumableUsageQuerySchema = z
  .object({
    from: dateOnlySchema,
    to: dateOnlySchema,
    consumableId: uuidSchema.optional(),
  })
  .refine((q) => q.from <= q.to, {
    message: 'Начало периода позже его конца',
    path: ['to'],
  });
export type OfficeEquipmentConsumableUsageQuery = z.infer<
  typeof officeEquipmentConsumableUsageQuerySchema
>;

/**
 * Строка отчёта — «заявка × позиция × человек», а не одно событие журнала и не одна строка заявки.
 *
 * Событием строка быть не может: обычная выдача одной позиции по одной заявке — это одно событие,
 * а выдача, поправленная дважды, — три, и отчёт показывал бы одну и ту же работу то одной строкой,
 * то тремя. Строкой заявки — тоже: правку факта вниз мог сделать не тот, кто выдавал, и «кто»
 * (вопрос В18) в такой строке пришлось бы выбирать между двумя людьми.
 *
 * Поэтому события группируются по тройке, а внутри группы складываются: `issued` — сумма выдач,
 * `returned` — сумма возвратов, `quantity` — их разность, то самое «сколько израсходовано». Ноль в
 * `quantity` при ненулевых слагаемых законен и значим: съездили, выдали, вернули — работа была,
 * склад не сдвинулся.
 */
export interface OfficeEquipmentConsumableUsageRowDto {
  /** Заявка: идентификатор для ссылки и номер для чтения. */
  requestId: string;
  displayNumber: string;
  /** Аппарат, ради которого расходник выдали (В18: «на какие аппараты»). */
  equipmentId: string;
  equipmentName: string;
  equipmentInventoryNumber: string;
  equipmentSerialNumber: string;
  consumableId: string;
  code: string;
  name: string;
  color: string | null;
  issued: number;
  returned: number;
  /** Расход: `issued - returned`. Отрицательным бывает — возврат прошлого периода. */
  quantity: number;
  /** Кто двигал склад по этой строке. */
  actorName: string;
  /** Позднейшее событие группы — по нему отчёт и упорядочен. */
  at: string;
}

/** Отчёт целиком: строки и итог по обеим сторонам движения. */
export interface OfficeEquipmentConsumableUsageDto {
  from: string;
  to: string;
  rows: OfficeEquipmentConsumableUsageRowDto[];
  /**
   * Итоги считаются по всему периоду, а не по показанным строкам: упёршись в потолок, отчёт
   * обязан остаться верным в сумме — иначе обрезанный список читался бы как весь расход.
   */
  totalIssued: number;
  totalReturned: number;
  /** Строк больше, чем отдано: список обрезан потолком, итоги — нет. */
  truncated: boolean;
}
