// ── Расходники оргтехники: картриджи и тонеры (план `docs/office-equipment-consumables-plan.md`,
// Р5–Р7, Р9, Р11) ──
//
// Подсправочник вкладки «Оргтехника»: код номенклатуры учётной системы, наименование как в ней же,
// остаток на складе и перечень моделей, к которым расходник подходит. Отдельной вкладки в
// «Справочниках» у него нет (Р8) — расходник существует только при технике, и разведённые вкладки
// заставляли бы ходить между ними при каждом вопросе «к чему подходит».
//
// Остаток здесь — не поле формы, а событие с журналом (Р7): вводит его человек, но каждая правка
// приходит своей ручкой, с тем значением, которое человек видел, и с обязательной причиной.

/**
 * Поля сортировки (Р9). «Остаток» в списке сортируют не из любопытства: срез «что заказывать»
 * читается снизу, с нулей.
 *
 * Счётчика привязанных моделей среди них нет намеренно — как и в окне моделей: число аппаратов
 * «в парке» считается в области смотрящего (Р12), и порядок строк, зависящий от того, кто смотрит,
 * читается как ошибка портала.
 */
export const OFFICE_EQUIPMENT_CONSUMABLE_SORT_FIELDS = [
  'name',
  'code',
  'quantity',
  'updatedAt',
  /**
   * «Правка остатка» (план `docs/office-equipment-consumables-and-purchase-plan.md`, Р3). Сортируют
   * по нему ровно затем, ради чего столбец и заведён: найти позиции, полку которых давно не
   * пересчитывали. Пустые значения при этом собираются в один конец списка — у позиции без ручных
   * событий даты нет вовсе, и это ответ, а не пропуск.
   *
   * От `updatedAt` он отличается предметом, а не точностью: карточку двигает и правка комментария,
   * и выдача по заявке, а этот столбец — только ручная сверка склада.
   */
  'lastManualStockAt',
  /**
   * Потребность, «уже заказано» и дефицит (план `docs/office-equipment-consumables-and-purchase-plan.md`,
   * Р13, Р15). Все три сортируются, и вопрос у них один — «с чего начинать заказ»: перечень
   * читается сверху, с самой большой нехватки.
   *
   * Дефицит и «уже заказано» СЧИТАЮТСЯ, а не хранятся, и сортировка по ним идёт тем же самым
   * выражением, которое отдаёт столбец (маршрут). Второе выражение «про то же самое» разошлось бы
   * с первым молча, и список пришёл бы упорядоченным не по тому числу, что показано в ячейке, —
   * ровно тот же довод, что у `lastManualStockAt` выше.
   */
  'requiredQuantity',
  'alreadyOrdered',
  'deficit',
] as const;

/**
 * Фильтр наличия. Экран показывает его переключателем «нет в наличии» (§6) — тем срезом, ради
 * которого в справочник и заходят перед заказом; обратный вопрос «что можно выдать сейчас» стоит
 * ровно одного значения перечисления, и отбирать его вручную глазами по колонке незачем.
 */
export const OFFICE_EQUIPMENT_CONSUMABLE_STOCK_FILTERS = ['in_stock', 'out_of_stock'] as const;
export type OfficeEquipmentConsumableStockFilter =
  (typeof OFFICE_EQUIPMENT_CONSUMABLE_STOCK_FILTERS)[number];

/**
 * Код номенклатуры учётной системы: «Б0000014256», «Д0000337741».
 *
 * Схема снимает только края. Само правило написания — пробельные символы **удаляются** (в коде
 * учётной системы их не бывает вовсе, а неразрывный из Word приезжает регулярно), регистр
 * поднимается — живёт функцией базы `office_equipment_consumable_code_key`, и прогнать через неё
 * ввод обязан маршрут: та же функция стоит в уникальном индексе и в CHECK
 * `office_equipment_consumables_code_normalized_check`. Своя нормализация на TypeScript была бы
 * второй копией правила, а разойдясь с первой, завела бы в справочник второй «тот же» код — ровно
 * то разнописание, ради которого правило и заведено (урок моделей, Р4).
 */
const consumableCodeSchema = z
  .string()
  .trim()
  .min(2, 'Укажите код номенклатуры')
  .max(50, 'Код номенклатуры — не длиннее 50 символов');

/**
 * Наименование — ровно как в учётной системе, вместе с хвостом «(шт)»: справочник сверяют глазами
 * со счётом и выгрузкой, и «причёсанное» наименование эту сверку ломает (Р5).
 */
const consumableNameSchema = z.string().trim().min(2, 'Укажите наименование расходника').max(255);

/**
 * Цвет позиции (Р5). Свободная строка, а не перечень: источник приносит и CMYK, и «комплект», и
 * поставщицкие названия вроде «чёрный увеличенный». Пустая строка приводится к `null` до записи —
 * «нет цвета» обязано иметь одно представление, и это же требует `CHECK` в базе.
 */
const consumableColorSchema = z
  .string()
  .trim()
  .max(60)
  .transform((v) => (v === '' ? null : v))
  .nullable();

const commentSchema = z.string().trim().max(2000);

/**
 * Остаток. Верхняя граница — не учётное правило, а защита от опечатки: склада на миллион картриджей
 * у ИТ-службы нет, а «120» вместо «12» в поле ввода от правды ничем не отличается.
 */
const quantitySchema = z
  .number()
  .int('Остаток — целое число')
  .min(0, 'Остаток не бывает отрицательным')
  .max(1_000_000, 'Проверьте остаток: слишком большое число');

/**
 * Потребность — сколько позиции хотим держать на полке (Р13 плана расходников и закупки).
 *
 * Границы те же, что у остатка, и это не копирование, а одно правило: оба числа про одну и ту же
 * полку, и «потребность 900 при остатке 12» отличалось бы от опечатки ничем. Ноль законен и значим
 * — он означает «не следим», и такие позиции в предзаполнение закупки не попадают вовсе (Р13);
 * отрицательного намерения не бывает, и это же держит `CHECK` базы.
 */
const requiredQuantitySchema = z
  .number()
  .int('Потребность — целое число')
  .min(0, 'Потребность не бывает отрицательной')
  .max(1_000_000, 'Проверьте потребность: слишком большое число');

/**
 * Список (Р9). Поиск — по наименованию и коду: спрашивают и «Pantum», и «Д0000337733», и обе
 * половины карточки обязаны находить одну и ту же строку.
 *
 * `sortOrder` объявлен заново: базовая схема ставит умолчанием `desc`, с которым перечень пришёл бы
 * от «Тонера» к «Картриджу», то есть задом наперёд. Поле сортировки по умолчанию — наименование, и
 * задаёт его маршрут четвёртым аргументом `orderByFrom` (`'name'`): `sortBy` в базовой схеме
 * остаётся необязательным.
 */
export const officeEquipmentConsumableListQuerySchema = baseListQuery(
  OFFICE_EQUIPMENT_CONSUMABLE_SORT_FIELDS,
).extend({
  /** «Что подходит к Ricoh IM 350» — из окна моделей и из карточки аппарата приходят сюда. */
  modelId: uuidSchema.optional(),
  stock: z.enum(OFFICE_EQUIPMENT_CONSUMABLE_STOCK_FILTERS).optional(),
  /**
   * «Есть дефицит» — срез, ради которого на вкладку и заходят перед закупкой (Р15). Три состояния,
   * как у всякого булева отбора списка: параметра нет — не отбираем вовсе, `true` — только позиции
   * с положительным «к закупке», `false` — только те, где заказывать нечего.
   *
   * Отдельным флагом, а не значением `stock`: «нет в наличии» и «не хватает до потребности» — это
   * разные вопросы, и совпадают их ответы редко. Позиция с потребностью 20 и остатком 5 в наличии
   * есть, а заказывать её надо; позиция с нулевой потребностью и нулевым остатком в наличии
   * отсутствует, а дефицита у неё нет — за ней не следят.
   */
  hasDeficit: booleanFlagSchema,
  isActive: booleanFlagSchema,
  sortOrder: sortOrderSchema.default('asc'),
});
export type OfficeEquipmentConsumableListQuery = z.infer<
  typeof officeEquipmentConsumableListQuerySchema
>;

export const createOfficeEquipmentConsumableSchema = z.object({
  code: consumableCodeSchema,
  name: consumableNameSchema,
  /**
   * Начальный остаток. Заведение с нулём — не событие, а отсутствие событий, и строку журнала
   * маршрут пишет только при ненулевом значении (Р7): «0 → 0» ограничение журнала не пропустит.
   * Причину той первой строки составляет маршрут — спрашивать «почему у вас на складе 12 штук» в
   * форме заведения не за что.
   */
  quantity: quantitySchema.optional().default(0),
  /**
   * Потребность (Р13). В отличие от остатка, правом склада она не закрыта и своего журнала не
   * имеет: остаток — предмет учёта, а потребность — намерение, и правит его тот же, кто ведёт коды
   * (`officeEquipmentConsumables.manage`). Умолчание — ноль: «не следим», пока не сказали иначе.
   */
  requiredQuantity: requiredQuantitySchema.optional().default(0),
  /** Гашение вместо удаления (Р11): погашенный расходник не предлагают, но он остаётся в перечне. */
  isActive: z.boolean().optional().default(true),
  /**
   * Цвет позиции (Р5): у цветной серии с отдельными кодами — по позиции на цвет, у кода на
   * комплект — «комплект». Необязателен: у чёрно-белой техники цвета нет, и `null` означает
   * именно это, а не «забыли заполнить».
   */
  color: consumableColorSchema.optional().default(null),
  comment: commentSchema.optional().default(''),
  /**
   * К чему подходит (Р6). Полный набор, а не пара ручек «привязать/отвязать»: совместимость — это
   * разметка, а не история, снимается она свободно с обеих сторон, и держать её одной транзакцией
   * с карточкой дешевле, чем разводить по отдельным запросам. Пустой набор законен: код прислали,
   * а к какому аппарату он подходит — вопрос к ИТ-службе (§7), и ждать ответа, не заводя строку,
   * значит потерять её совсем.
   */
  modelIds: z.array(uuidSchema).optional().default([]),
});
export type CreateOfficeEquipmentConsumableInput = z.infer<
  typeof createOfficeEquipmentConsumableSchema
>;

/**
 * Правка карточки остаток не трогает (Р7) — тот же приём, что с площадкой у карточки техники:
 * поле уехало в свою ручку `POST /:id/stock`, и здесь его нет вовсе. `z.never()`, а не молчаливое
 * отбрасывание: приняв количество и не записав его, форма соврала бы человеку — он увидел бы
 * «сохранено» там, где остаток остался прежним и в журнал ничего не легло.
 *
 * Это не противоречит соседнему приёму у моделей, где неизменяемый тип схема **принимает** ради
 * 422 словами маршрута: там поле шлёт живая форма и человеку нужен ответ о предмете, здесь —
 * только старый код, которому ответ читать некому.
 *
 * `.partial()` снимает обязательность, но не `.default()` — поля со значением по умолчанию
 * объявляются заново, иначе PATCH без поля затирал бы значение (тот же подвох, что у типов).
 */
export const updateOfficeEquipmentConsumableSchema = createOfficeEquipmentConsumableSchema
  .partial()
  .extend({
    quantity: z.never().optional(),
    isActive: z.boolean().optional(),
    /**
     * Потребность правится ЗДЕСЬ, и своей ручки у неё нет (Р13). Две двери к колонке — форма
     * карточки в справочнике и быстрое действие на вкладке «Расходники» — ведут в одну эту ручку:
     * вторая ручка ради одного числа разошлась бы с первой на первой же проверке (например, на
     * праве или на записи в аудит).
     *
     * Тем и отличается от остатка, у которого своя ручка есть: остаток — событие с журналом,
     * причиной и сверкой «того, что человек видел»; потребность — обычное поле карточки, и
     * аудита правки для неё достаточно.
     */
    requiredQuantity: requiredQuantitySchema.optional(),
    color: consumableColorSchema.optional(),
    comment: commentSchema.optional(),
    /** Отсутствие поля — «связи не трогать», пустой массив — «снять все»: это разные просьбы. */
    modelIds: z.array(uuidSchema).optional(),
  });
export type UpdateOfficeEquipmentConsumableInput = z.infer<
  typeof updateOfficeEquipmentConsumableSchema
>;

/**
 * Правка остатка (Р7): новое значение, то значение, которое человек видел, и причина.
 *
 * `expectedQuantity` обязателен и не «для совместимости»: без него два кладовщика, открывшие
 * карточку с числом 12, запишут «12 → 10» и «12 → 8», и цепочка журнала станет враньём при верном
 * итоге. Разошлось — маршрут отвечает 409 «остаток изменил другой человек, сейчас N», то есть
 * превращает молчаливую перезапись в понятный отказ. Блокировку строки это не заменяет, а
 * дополняет: `SELECT … FOR UPDATE` идёт первым шагом транзакции.
 *
 * Равенство нового и текущего схема не отбивает намеренно: это не ошибка ввода, а повторное
 * нажатие кнопки, и маршрут выходит без записи — журнал не должен пухнуть от таких событий.
 */
export const officeEquipmentConsumableStockSchema = z.object({
  quantity: quantitySchema,
  expectedQuantity: quantitySchema,
  /** Причина обязательна (тот же CHECK держит и БД): «12 → 4» без объяснения читать через месяц нечем. */
  reason: z.string().trim().min(3, 'Укажите причину изменения остатка').max(1000),
});
export type OfficeEquipmentConsumableStockInput = z.infer<
  typeof officeEquipmentConsumableStockSchema
>;

export interface OfficeEquipmentConsumableDto {
  id: string;
  code: string;
  name: string;
  quantity: number;
  /**
   * Потребность — сколько хотим держать на полке (Р13). Не минимум и не норматив: её правят по
   * обстоятельствам, и своего журнала у неё нет — правка идёт обычным аудитом карточки.
   *
   * Ноль означает «не следим», а не «нужно ноль штук»: такая позиция в предзаполнение закупки не
   * попадает вовсе — иначе форма предлагала бы заказать всё, чего нет на складе, включая то, что
   * сознательно не держат.
   */
  requiredQuantity: number;
  /**
   * Сколько этой позиции уже заказано ОТКРЫТЫМИ закупками — сумма их строк (Р15). Открытыми
   * считаются «Новая» и «В работе»; закрытая и отменённая не считаются вовсе.
   *
   * СТОИТ В ОТВЕТЕ РЯДОМ С ДЕФИЦИТОМ, А НЕ ПРЯЧЕТСЯ В ФОРМУЛУ, и это требование Р15: число,
   * которое влияет на заказ, обязано быть видно. Иначе «дефицит 0» у позиции с пустой полкой
   * читается как ошибка портала, а не как «уже везут».
   *
   * Закрытие закупки это число уменьшает, и потому Р11 требует заносить приход ДО закрытия:
   * закрыв раньше прихода, портал вернёт дефицит на экран и позовёт заказывать второй раз.
   */
  alreadyOrdered: number;
  /**
   * Сколько надо докупить: `max(0, потребность − остаток − уже заказанное)` (Р15).
   *
   * СЧИТАЕТСЯ, А НЕ ХРАНИТСЯ, и считается ОДНИМ местом — сервером: число меняется от каждого
   * движения склада и от каждой чужой закупки, а заказывают по нему. Два вычислителя (например,
   * второй в портале) разошлись бы на первой же смене формулы, и спор о том, сколько заказывать,
   * пришлось бы разбирать сверкой двух мест вместо одного.
   *
   * Ноль означает «заказывать нечего» и у позиции с нулевой потребностью стоит всегда: за такой не
   * следят вовсе.
   */
  deficit: number;
  isActive: boolean;
  /** Цвет позиции или `null` у чёрно-белой (Р5). */
  color: string | null;
  comment: string;
  /**
   * К чему подходит (Р6). Отдельного счётчика рядом нет: колонка «Модели» в списке — это длина
   * этого набора, и второе число, посчитанное своим запросом, разошлось бы с первым.
   *
   * Сколько аппаратов стоит за каждой моделью по отдельности, здесь не сказано: у набора одно
   * общее число — `equipmentCount` ниже.
   */
  models: OfficeEquipmentModelRefDto[];
  /**
   * Сколько аппаратов расходник кормит — **в области смотрящего** (Р12, Р15). То самое второе
   * число, ради которого расходник и заказывают: остаток 12 при 68 аппаратах и при 2 аппаратах
   * означает разное.
   *
   * ЧИСЛО ЗАВИСИТ ОТ ТОГО, КТО СМОТРИТ, и это не дефект, а правило: право `officeEquipment.read`
   * сквозной видимости не даёт, и роль одной площадки, увидев сквозные 68, узнала бы масштаб
   * чужого парка. Считается тем же предикатом `officeEquipmentScopeWhere`, что и список техники, —
   * тем же самым, а не похожим: у роли объекта это карточки её площадок, у роли отдела — карточки
   * её отделов **и вся неразмеченная техника**. Подпись в интерфейсе обязана проговаривать это
   * прямо: «в вашей области, активных».
   *
   * Считаются АППАРАТЫ, а не пары «расходник — модель»: расходник, подходящий трём Pantum, кормит
   * столько аппаратов, сколько их стоит, — даже если бы один аппарат оказался под двумя его
   * моделями. Живые и активные: вопрос звучит «сколько надо кормить», а архив и выведенная из
   * эксплуатации техника картриджей не просят.
   *
   * Ноль означает «у вас таких аппаратов нет», а не «расходник ничему не подходит»: второе
   * читается по пустому `models`, и подменять один ответ другим нельзя.
   */
  equipmentCount: number;
  /**
   * Есть ли по расходнику хоть одно движение остатка. Это ответ на «удаляема ли карточка» (Р11):
   * пока журнал пуст, запись удаляется совсем — так убирают опечатку первого дня; появилось
   * движение — только гашение флагом, и держит это `ON DELETE RESTRICT` журнала, а не маршрут.
   * Маршрут отвечает тем же признаком лишь затем, чтобы человек прочитал «по расходнику есть
   * движение, снимите „Активен“», а не имя ограничения.
   */
  hasStockHistory: boolean;
  /**
   * Когда остаток последний раз правили РУКАМИ (Р3 плана расходников и закупки). Время последнего
   * события журнала с видом `manual`; `null` — таких событий не было вовсе.
   *
   * СЧИТАЕТСЯ ТОЛЬКО ПО `manual`, и это весь смысл столбца. Вопрос, который им задают, — «когда мы
   * последний раз сверяли полку», а не «когда со склада брали»: выдачи и возвраты по заявкам
   * двигают остаток сами и о достоверности числа ничего не говорят. Считай мы дату по всем видам,
   * позиция, из которой каждый день выдают по заявкам, выглядела бы вечно свежей — то есть столбец
   * отвечал бы «сверено вчера» именно там, где полку не пересчитывали год.
   *
   * `null` показывается прочерком, а не сегодняшней датой и не нулём: у позиции, заведённой с
   * нулевым остатком, ручных событий нет по построению (`0 → 0` журнал не пропускает), и пустая
   * ячейка здесь — ответ «руками не трогали», а не недогруженные данные.
   *
   * Соседний `updatedAt` его не заменяет и не дублирует: карточку двигает любая правка — код,
   * комментарий, совместимость, выдача по заявке, — а этот столбец только сверку склада.
   */
  lastManualStockAt: string | null;
  createdAt: string;
  updatedAt: string;
}

/**
 * Виды событий журнала: ручная правка кладовщика, выдача по заявке, возврат выданного. Перечнем, а
 * не тремя строками по месту, потому что теперь их спрашивают снаружи — отбором ленты (Р4), — и
 * второй список тех же слов разошёлся бы с `CHECK` базы (`…_stock_kind_check`) молча.
 */
export const OFFICE_EQUIPMENT_CONSUMABLE_STOCK_ENTRY_KINDS = ['manual', 'issue', 'return'] as const;
export type OfficeEquipmentConsumableStockEntryKind =
  (typeof OFFICE_EQUIPMENT_CONSUMABLE_STOCK_ENTRY_KINDS)[number];

/**
 * Запрос ленты журнала — страница и необязательный отбор по виду события (Р4 плана расходников и
 * закупки).
 *
 * ПРАВИЛА СТРАНИЦЫ БЕРУТСЯ У ОБЩЕЙ СХЕМЫ, а не пишутся заново: номер с единицы, размер — только из
 * общего перечня (`PAGE_SIZES`). Своя пара полей выглядела бы такой же, но позволила бы клиенту
 * попросить страницу в десять тысяч строк — то есть выгрузить весь журнал одним запросом мимо
 * правила, общего для всех списков портала.
 *
 * А вот `sortBy` и `search` из неё **выброшены**, и это не экономия. Порядок ленты задан жёстко —
 * `seq` вниз (см. DTO ниже), — и поле сортировки, которое сервер обязан игнорировать, было бы
 * обещанием, которого он не выполняет; искать же внутри журнала нечем и незачем: строк у одной
 * позиции десятки, а причину читают глазами.
 */
export const officeEquipmentConsumableStockEntriesQuerySchema = baseListQuery([])
  .pick({ page: true, pageSize: true })
  .extend({
    /**
     * «Покажи только ручные правки» или «только выдачи». Необязателен: чаще ленту читают целиком —
     * она и заведена ради связного рассказа, — а отбор нужен, когда ищут конкретное («кто выдавал
     * этот картридж»). Отсутствие поля значит «все виды», а не какой-то из них.
     */
    entryKind: z.enum(OFFICE_EQUIPMENT_CONSUMABLE_STOCK_ENTRY_KINDS).optional(),
  });
export type OfficeEquipmentConsumableStockEntriesQuery = z.infer<
  typeof officeEquipmentConsumableStockEntriesQuerySchema
>;

/**
 * Строка журнала остатка: было, стало, причина, автор, время (Р7).
 *
 * Строки неизменяемы — правку и удаление отбивает триггер (Р11), — поэтому лента читается как
 * рассказ: ошибку исправляют следующим событием «ошиблись, вернули 15», а не подчисткой прошлого.
 * Порядок задаёт `seq`, а не время: две правки одной секунды по `createdAt` неразличимы.
 */
export interface OfficeEquipmentConsumableStockEntryDto {
  id: string;
  seq: number;
  /**
   * Что это было: ручная правка кладовщика, выдача по заявке или возврат выданного. Различать их
   * лента обязана: «−2» без ответа «почему» — это и есть та строка, ради которой журнал заводили.
   */
  entryKind: OfficeEquipmentConsumableStockEntryKind;
  /**
   * Заявка и её строка, по которым прошло движение; обе `null` у ручной правки, обе заполнены у
   * выдачи и возврата — порознь они не бывают, и это держит `CHECK` связок в базе. Вторая ссылка
   * отдаётся вместе с первой, а не «когда понадобится»: сторно правит конкретную строку заявки, и
   * ответ, в котором её нет, заставил бы клиента искать строку по позиции и количеству.
   */
  serviceRequestId: string | null;
  serviceRequestConsumableId: string | null;
  /**
   * Номер заявки в том виде, в каком его показывают людям («СО-1234»); `null` у ручной правки.
   *
   * Собран сервером, а не клиентом из `num`, по той же причине, что и текст `reason`: журнал
   * склада читают рядом с заявкой, и номер в ленте обязан совпасть с номером в причине символ в
   * символ. Клиент, склеивающий его сам, разошёлся бы с сервером на первой же смене префикса.
   */
  serviceRequestNumber: string | null;
  /**
   * Откроется ли заявка ЭТОМУ смотрящему (Р4). У ручной правки всегда `false` — заявки нет вовсе,
   * и открывать нечего; портал рисует ссылку по этому признаку, а без него показывает номер
   * обычным текстом.
   *
   * СЧИТАЕТ СЕРВЕР, И ИНАЧЕ НЕЛЬЗЯ. Остаток на складе глобален — он один на компанию, — а заявки
   * нет: их видимость складывается из области роли и назначения сервисной компании, и ни того ни
   * другого на портале нет. Отсюда два разных отказа, которые признак и закрывает: у менеджера
   * есть `officeEquipment.read` и нет `serviceRequests.read` — ссылка вела бы в 403; у роли
   * площадки право есть, но событие в журнале может быть по заявке чужой площадки — ссылка вела бы
   * туда же. До Р4 лента рисовала ссылку всегда, и это был существующий дефект, а не новое
   * требование.
   */
  requestAccessible: boolean;
  quantityBefore: number;
  quantityAfter: number;
  reason: string;
  changedByName: string;
  /**
   * Подпись роли автора события («Штаб», «Отдел») и названия выданных ему наборов полномочий
   * модуля «Орг.техника» (Р4). В окне читаются одной строкой: «Иванов И. И. · Штаб · Оргтехника:
   * ведение».
   *
   * РОЛЬ ОДНА И ЕСТЬ ВСЕГДА, А НАБОРОВ БЫВАЕТ НЕСКОЛЬКО — отсюда и разные типы. «Оргтехника:
   * ведение» вместе с «Оргтехника: номенклатура» — обычная пара, приоритета между ними нет
   * никакого, и выбор «главного» набора был бы выдумкой портала.
   *
   * ЗНАЧЕНИЯ СЕГОДНЯШНИЕ, а не на момент события (решение заказчика): историю роли и выдач портал
   * не хранит, и подпись отвечает «кто это сейчас», а не «кем он был в марте». Окно обязано
   * говорить это словами — иначе подпись читается как снимок прошлого.
   *
   * Пустой перечень наборов — обычное дело: остаток правит и тот, у кого права пришли ролью.
   */
  changedByRoleLabel: string;
  changedByGrants: string[];
  createdAt: string;
}

