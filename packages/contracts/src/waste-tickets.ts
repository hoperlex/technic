  proxyRequestId: string;
  /** `x-openrouter-request-id` — для сверки биллинга. */
  upstreamRequestId: string;
  errorCode: string;
  errorClass: WasteTicketErrorClass | null;
  errorScope: WasteTicketErrorScope | null;
  error: string;
  createdAt: string;
