/**
 * Слепая перепроверка — `POST …/tickets/:ticketId/blind-check`: то, что прочитал второй человек,
 * не видя ни распознанного, ни подтверждённого (Р31).
 *
 * Все три поля обязательны в теле и обнуляемы по значению, и это разные вещи. Обязательность
 * означает «проверяющий ответил про каждое поле»: пропущенный ключ был бы неотличим от «поля не
 * было на бланке», и совпадение по нему засчиталось бы само. Номер отвечает пустой строкой —
 * так же, как хранится: `review_number_raw text NOT NULL DEFAULT ''`.
 *
 * Совпало — строка закрывается сама; разошлось — уходит в реестр на арбитраж. Сама по себе
 * перепроверка показывает, что чтения разные, но не кто прав, поэтому метрикой становится только
 * разобранное.
 */
export const wasteTicketBlindCheckSchema = z
  .object({
    number: blindReadingNumberSchema,
    issuedOn: dateOnlySchema.nullable(),
    volumeM3: ticketVolumeSchema.nullable(),
  })
  .strict();
export type WasteTicketBlindCheckInput = z.infer<typeof wasteTicketBlindCheckSchema>;

/**
 * Арбитраж расхождения — `POST …/blind-checks/:id/arbitrate` (Р31).
 *
 * Арбитр вписывает **верные значения по полям**, а не один вердикт: правота бывает разной —
 * номер за машиной, дата за человеком, объём мимо у обоих, — и единым словом такую строку не
 * описать. «Кто прав» по каждому полю считается сравнением итога с машинным чтением и с чтением
 * проверяющего.
 *
 * Ключ поля в теле и его имя в `resolvedFields` обязаны идти **вместе, в обе стороны**:
 *
 * - значение без разбора — тихая выдумка: цифра, вписанная в поле, которое арбитр не объявил
 *   разобранным, попала бы в итог, минуя всё, что метрика считает разбором;
 * - разбор без ключа — потерянное различие: `null`, присланный явно, означает «верного значения
 *   нет вовсе» (объёма на талоне не было), а отсутствие ключа — «поле не разобрано», и `NULL` в
 *   базе их не различает. Требуя ключ, схема заставляет сказать вслух то, что иначе сказалось бы
 *   умолчанием.
 *
 * Чего схема не проверяет: что разобрано **каждое** разошедшееся поле и что арбитр не совпадает с
 * проверяющим или подтвердившим талон. Первое видно только рядом с обоими чтениями, второе —
 * только по строке; и то и другое держат `CHECK` в базе и сервис. Частично закрытая строка хуже
 * неразобранной именно тем, что выглядит законченной.
 */
export const arbitrateWasteTicketBlindCheckSchema = z
  .object({
    resolvedFields: z
      .array(z.enum(WASTE_TICKET_BLIND_CHECK_FIELDS))
      .min(1, 'Укажите, какие поля разобраны'),
    number: ticketNumberSchema.nullable().optional(),
    issuedOn: dateOnlySchema.nullable().optional(),
    volumeM3: ticketVolumeSchema.nullable().optional(),
  })
  .strict()
  .superRefine((value, ctx) => {
    const resolved = new Set<WasteTicketBlindCheckField>(value.resolvedFields);
    if (resolved.size !== value.resolvedFields.length) {
      ctx.addIssue({
        code: 'custom',
        path: ['resolvedFields'],
        message: 'Поле указано дважды',
      });
    }
    for (const field of WASTE_TICKET_BLIND_CHECK_FIELDS) {
      const sent = value[field] !== undefined;
      if (sent && !resolved.has(field)) {
        ctx.addIssue({
          code: 'custom',
          path: [field],
          message: `Поле «${wasteTicketFieldLabels[field]}» не объявлено разобранным`,
        });
      }
      if (!sent && resolved.has(field)) {
        ctx.addIssue({
          code: 'custom',
          path: [field],
          message: `Укажите верное значение поля «${wasteTicketFieldLabels[field]}» или null, если его нет`,
        });
      }
    }
  });
export type ArbitrateWasteTicketBlindCheckInput = z.infer<
  typeof arbitrateWasteTicketBlindCheckSchema
>;

