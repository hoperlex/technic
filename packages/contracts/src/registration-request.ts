  department_head: { role: 'department', grants: ['department_approval'] },
  dispatcher: { role: 'dispatcher', grants: [] },
  /*
   * Три внешних пожелания ведут к одной роли `operator` и с пустыми наборами: что именно исполняет
   * учётка — вывоз мусора, аренду техники или обслуживание оргтехники, — задаёт не роль и не
   * набор, а тип контрагента (ADR 0038). Различить их подстановке всё же нужно, и делает это
   * `expectedCounterpartyType` ниже: он правит подбор организации, а не роль.
   */
  waste_operator: { role: 'operator', grants: [] },
  vehicle_lessor: { role: 'operator', grants: [] },
  service_company: { role: 'operator', grants: [] },
