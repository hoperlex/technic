// диспетчер, внешние исполнители, водитель и «другое». С порядком значений enum'а в базе он не
// совпадает и совпадать не обязан: `ALTER TYPE ... ADD VALUE` дописывает в конец, сортировки по
// этому типу в портале нет ни одной, а сверка кода с базой сравнивает множества.

