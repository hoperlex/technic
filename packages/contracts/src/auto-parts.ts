import { z } from 'zod';
import { baseListQuery, booleanFlagSchema, sortOrderSchema, uuidSchema } from './common';

// ── Автозапчасти: склад гаража (план `docs/auto-parts-plan.md`, Р2, Р3, Р8, Р9, Р12, Р13, Р21) ──
//
// Складская позиция механиков: что лежит на складе и сколько. Склад виртуальный (Р2) — не место на
// полке, а число: есть штуки, значит деталь есть. Расход идёт актом обслуживания (Р4), поэтому
// отдельной «выдачи» здесь нет вовсе — строки акта живут в `vehicle-maintenance.ts`, а сюда
// приходит только их след в журнале остатка.
//
// Контур «остаток не врёт» перенесён целиком от расходников оргтехники
// (`office-equipment-consumables.ts`, Р3): своя ручка правки с `expectedQuantity` и причиной,
// неизменяемый журнал, три триггера в базе. Переписывать его по-своему было бы не экономией, а
// повторением тех же ошибок — они там оплачены пятью ревью.
//
// Три отличия от расходника, и каждое следует из предмета, а не из вкуса:
//
//   * **код необязателен** (Р12): картриджи приезжают выгрузкой из учётной системы, а «Ремень
//     генератора» механик заводит до того, как бухгалтерия пришлёт номенклатуру. Идентичность
//     держит пара «наименование + код»;
//   * **единица измерения — своё поле** (Р9): на складе гаража лежат штуки, литры, комплекты и
//     метры, и «5» без единицы — это не число, а загадка;
//   * **применимость к моделям И типам техники** (Р8): модель у машины необязательна, а масло и
//     фильтры общего применения — утверждение о типе, а не о модели.

/**
 * Поля сортировки (Р13). Остаток сортируют не из любопытства: срез «что заказывать» читают снизу,
 * с нулей, — и он же заменяет собой «минимальный остаток», которого этот выпуск не заводит (§12).
 *
 * Счётчика применимости среди них нет: длина разметки говорит не о детали, а о том, насколько
 * механик успел её разметить, и порядок строк по такому числу читался бы как оценка позиции.
 */
export const AUTO_PART_SORT_FIELDS = ['name', 'code', 'quantity', 'updatedAt'] as const;

/**
 * Фильтр наличия. Тот срез, ради которого во вкладку и заходят перед заказом; обратный вопрос «что
 * можно списать сейчас» стоит ровно одного значения перечисления, и отбирать его глазами по колонке
 * незачем.
 */
export const AUTO_PART_STOCK_FILTERS = ['in_stock', 'out_of_stock'] as const;
export type AutoPartStockFilter = (typeof AUTO_PART_STOCK_FILTERS)[number];

/**
 * Потолок количества — один на модуль: и остаток карточки, и количество в строке акта
 * (`maintenancePartInputSchema`) меряются им же. Это не учётное правило, а защита от опечатки:
 * склада на миллион болтов у гаража нет, а «120» вместо «12» в поле ввода от правды ничем не
 * отличается. Два разных потолка разошлись бы при первой правке — и списать стало бы можно больше,
 * чем позволено хранить.
 */
export const AUTO_PART_MAX_QUANTITY = 1_000_000;

/**
 * Код номенклатуры — необязателен (Р12).
 *
 * Схема снимает только края. Само правило написания — пробельные символы **удаляются** (в артикуле
 * их не бывает, а неразрывный из Word приезжает регулярно), регистр поднимается — живёт функцией
 * базы `auto_part_code_key`, и прогнать через неё ввод обязан маршрут: та же функция стоит в
 * частичном уникальном индексе `auto_parts_code_unique`, в ключе пары `auto_parts_name_code_unique`
 * и в CHECK `auto_parts_code_normalized_check`. Своя нормализация на TypeScript была бы второй
 * копией правила, а разойдясь с первой, завела бы в справочник второй «тот же» код — ровно то
 * разнописание, ради которого правило и заведено.
 *
 * Пустая строка приводится к `null` до записи: «кода нет» обязано иметь одно представление, иначе
 * уникальность пары считалась бы по двум разным «пустым» значениям и двойник прошёл бы насквозь.
 */
const autoPartCodeSchema = z
  .string()
  .trim()
  .max(50, 'Код номенклатуры — не длиннее 50 символов')
  .transform((v) => (v === '' ? null : v))
  .nullable();

/**
 * Наименование. Нормализация — тоже за базой (`auto_part_name_key`: регистр, ё→е, схлопывание
 * пробелов; дефисы и точки не трогаются — в артикулах они значащие), по той же причине, что у кода.
 *
 * Минимум в два символа, а не в один: односимвольное наименование не различает позиции даже для
 * того, кто его завёл, а поиск по нему отбирает половину справочника.
 */
const autoPartNameSchema = z.string().trim().min(2, 'Укажите наименование').max(255);

/**
 * Единица измерения (Р9). Свободная строка, а не перечень: на складе гаража лежат штуки, литры,
 * комплекты, метры и «банка», и перечень пришлось бы править выпуском ради каждой новой единицы —
 * то есть механик ждал бы релиза, чтобы завести антифриз. Умолчание `'шт'` покрывает большинство
 * позиций, и в форме оно стоит заполненным, а не подсказкой: пустая единица законной не бывает
 * (CHECK `auto_parts_unit_not_blank_check`).
 */
const autoPartUnitSchema = z.string().trim().min(1, 'Укажите единицу измерения').max(20);

const autoPartCommentSchema = z.string().trim().max(2000);

/**
 * Количество: целое (Р9). Дробные подтверждённо отвергнуты заказчиком — журнал «было — стало» и все
 * триггеры написаны на `integer`, канистры и литры считают целыми. Переезд на `numeric(12,3)`
 * остаётся возможным, но после выката это уже миграция данных, а не правка типа.
 */
const autoPartQuantitySchema = z
  .number()
  .int('Количество — целое число')
  .min(0, 'Остаток не бывает отрицательным')
  .max(AUTO_PART_MAX_QUANTITY, 'Проверьте количество: слишком большое число');

/**
 * Строка применимости: ровно одна ссылка из двух (Р8) — либо модель техники, либо её тип.
 *
 * Проверка схемой, а не `z.union` двух форм: союз отвечает на ошибку перебором веток («ожидалось
 * одно из…»), и приславший обе ссылки прочитал бы про обе сразу вместо одного внятного «выберите
 * что-то одно». Проверка повторяет CHECK `auto_part_applicability_target_check` намеренно: без неё
 * тело ушло бы в базу и вернулось пятисоткой с именем ограничения — сообщением, адресованным не
 * человеку.
 *
 * `null` обеих ссылок отбивается тем же условием: строка разметки, которая ни к чему не привязана,
 * — не «пустая применимость» (та выражается пустым набором), а мусор.
 */
export const autoPartApplicabilityInputSchema = z
  .object({
    vehicleModelId: uuidSchema.nullable().default(null),
    vehicleTypeId: uuidSchema.nullable().default(null),
  })
  .strict()
  .refine((v) => (v.vehicleModelId === null) !== (v.vehicleTypeId === null), {
    message: 'В строке применимости указывается либо модель, либо тип техники — что-то одно',
  });
export type AutoPartApplicabilityInput = z.infer<typeof autoPartApplicabilityInputSchema>;

/**
 * Разметка целиком (Р8). Полный набор, а не пара ручек «привязать/отвязать»: применимость — это
 * разметка, а не история, снимается она свободно с обеих сторон, и держать её одной транзакцией с
 * карточкой дешевле, чем разводить по отдельным запросам.
 *
 * Дубли отбиваются здесь, а не уникальными индексами базы: индекс ответит именем ограничения, из
 * которого механик не узнает, какую строку он повторил.
 *
 * Потолок — защита от тела, в котором приехал весь справочник моделей: деталь, подходящая двум
 * сотням моделей, размечается их **типом**, и это ровно то, ради чего Р8 завёл вторую ссылку.
 */
const autoPartApplicabilitySetSchema = z
  .array(autoPartApplicabilityInputSchema)
  .max(
    200,
    'Слишком много строк применимости: разметьте деталь типом техники, а не перечнем моделей',
  )
  .refine(
    (rows) => {
      const keys = rows.map((r) =>
        r.vehicleModelId !== null ? `m:${r.vehicleModelId}` : `t:${r.vehicleTypeId}`,
      );
      return new Set(keys).size === keys.length;
    },
    { message: 'Модель или тип указаны в применимости дважды — уберите повтор' },
  );

/**
 * Список (Р13). Поиск — по наименованию и коду сразу: спрашивают и «фильтр масляный», и артикул, и
 * обе половины карточки обязаны находить одну строку.
 *
 * `sortOrder` объявлен заново: базовая схема ставит умолчанием `desc`, с которым перечень пришёл бы
 * задом наперёд — от «Я» к «А». Поле сортировки по умолчанию (наименование) задаёт маршрут, `sortBy`
 * в базовой схеме остаётся необязательным.
 */
export const autoPartListQuerySchema = baseListQuery(AUTO_PART_SORT_FIELDS)
  .extend({
    sortOrder: sortOrderSchema.default('asc'),
    stock: z.enum(AUTO_PART_STOCK_FILTERS).optional(),
    isActive: booleanFlagSchema,
    /** «Что размечено этой моделью» — вопрос со стороны справочника: отрезает, а не ранжирует. */
    vehicleModelId: uuidSchema.optional(),
    /** То же со стороны типа: «что подходит всем самосвалам» (Р8). */
    vehicleTypeId: uuidSchema.optional(),
    /**
     * Подбор под конкретную машину (Р21). Это **не** фильтр: разметка неполна по построению, и
     * отрезать по ней значило бы запретить списать неразмеченную деталь — то есть не дать закончить
     * работу, пока справочник не доведён. Сервер читает модель и тип машины и сортирует по
     * `(ранг, наименование)`, где ранг — 0 по модели, 1 по типу, 2 остальные (`applicabilityRank`
     * в ответе).
     *
     * Ранг считает сервер, а не клиент, потому что список разбит на страницы: досортировать
     * пришедшую страницу значит переставить двадцать строк из полутора тысяч — подходящая деталь
     * так и осталась бы на седьмой странице.
     */
    vehicleId: uuidSchema.optional(),
  })
  .refine((v) => v.vehicleId === undefined || (!v.vehicleModelId && !v.vehicleTypeId), {
    message:
      'Подбор по машине не сочетается с фильтрами по модели и типу: это разные вопросы — ' +
      '«что подходит этой машине» и «что размечено этой моделью»',
    path: ['vehicleId'],
  });
export type AutoPartListQuery = z.infer<typeof autoPartListQuerySchema>;

export const createAutoPartSchema = z.object({
  code: autoPartCodeSchema.optional().default(null),
  name: autoPartNameSchema,
  unit: autoPartUnitSchema.optional().default('шт'),
  /**
   * Начальный остаток — он же инвентаризация (Р17): справочник наполняют руками, сперва тем, что
   * лежит на складе, поэтому отдельной «первичной описи» не заводится. Заведение с нулём — не
   * событие, а отсутствие событий, и строку журнала маршрут пишет только при ненулевом значении
   * («0 → 0» ограничение журнала не пропустит), причину той строки составляет он же.
   *
   * Ненулевое значение здесь — движение склада, и требует оно `autoParts.stock` сверх
   * `autoParts.manage` (Р10, Р19): это единственное поле тела, от которого зависит право.
   */
  quantity: autoPartQuantitySchema.optional().default(0),
  /** Гашение вместо удаления (Р11): погашенную позицию не предлагают, но она остаётся в перечне. */
  isActive: z.boolean().optional().default(true),
  comment: autoPartCommentSchema.optional().default(''),
  /**
   * К чему подходит (Р8). Пустой набор законен: деталь завели, а к чему она подходит — вопрос к
   * механику, и ждать ответа, не заводя позицию, значит потерять её совсем.
   */
  applicability: autoPartApplicabilitySetSchema.optional().default([]),
});
export type CreateAutoPartInput = z.infer<typeof createAutoPartSchema>;
export type CreateAutoPartBody = z.input<typeof createAutoPartSchema>;

/**
 * Правка карточки остаток не трогает (Р3): поле уехало в свою ручку `POST /:id/stock`, и здесь его
 * нет вовсе. `z.never()`, а не молчаливое отбрасывание: приняв количество и не записав его, форма
 * соврала бы человеку — он увидел бы «сохранено» там, где остаток остался прежним, в журнал ничего
 * не легло, а право `autoParts.stock` никто не спросил.
 *
 * `.partial()` снимает обязательность, но **не** `.default()` — поля со значением по умолчанию
 * объявляются заново, иначе PATCH без поля затирал бы значение единицей измерения `'шт'` и
 * поднятым флагом активности.
 */
export const updateAutoPartSchema = createAutoPartSchema.partial().extend({
  quantity: z.never().optional(),
  code: autoPartCodeSchema.optional(),
  unit: autoPartUnitSchema.optional(),
  isActive: z.boolean().optional(),
  comment: autoPartCommentSchema.optional(),
  /** Отсутствие поля — «разметку не трогать», пустой массив — «снять всю»: это разные просьбы. */
  applicability: autoPartApplicabilitySetSchema.optional(),
});
export type UpdateAutoPartInput = z.infer<typeof updateAutoPartSchema>;
export type UpdateAutoPartBody = z.input<typeof updateAutoPartSchema>;

/**
 * Ручная корректировка остатка (Р3): новое значение, то значение, которое человек видел, и причина.
 *
 * `expectedQuantity` обязателен и не «для совместимости»: без него два механика, открывшие карточку
 * с числом 12, запишут «12 → 10» и «12 → 8», и цепочка журнала станет враньём при верном итоге.
 * Разошлось — маршрут отвечает 409 «остаток изменил другой человек, сейчас N», то есть превращает
 * молчаливую перезапись в понятный отказ. Блокировку строки это не заменяет, а дополняет:
 * `SELECT … FOR UPDATE` идёт первым шагом транзакции.
 *
 * Равенство нового и текущего схема не отбивает намеренно: это не ошибка ввода, а повторное нажатие
 * кнопки, и маршрут выходит без записи — журнал не должен пухнуть от таких событий.
 *
 * Этой же ручкой покрывается всё, что не является обслуживанием (Р4): продали, списали брак,
 * пересчитали, отдали на сторону. Отдельных видов события под это не заводится — вид у ручной
 * правки один, а различает случаи причина, написанная человеком.
 */
export const autoPartStockSchema = z
  .object({
    quantity: autoPartQuantitySchema,
    expectedQuantity: autoPartQuantitySchema,
    /** Причина обязательна (тот же CHECK держит и база): «12 → 4» без объяснения читать нечем. */
    reason: z.string().trim().min(3, 'Укажите причину изменения остатка').max(1000),
  })
  .strict();
export type AutoPartStockInput = z.infer<typeof autoPartStockSchema>;

/**
 * Модель в разметке применимости. Тип назван рядом намеренно: имя модели уникально **в пределах
 * типа** (`vehicle_models_type_name_unique`), и одинокий тег «65115» на карточке детали не отвечает,
 * чей это самосвал.
 */
export interface AutoPartVehicleModelRefDto {
  id: string;
  name: string;
  vehicleTypeId: string;
  vehicleTypeName: string;
}

/** Тип техники в разметке применимости: столько, сколько нужно для тега и повторного выбора. */
export interface AutoPartVehicleTypeRefDto {
  id: string;
  name: string;
}

/**
 * Строка применимости раскрытой ссылкой (Р8). Ровно одно поле из двух заполнено — это держит CHECK
 * базы, и порознь они не бывают.
 *
 * Одна лента с двумя видами ссылки, а не два массива `models` и `types`: разметка **одна** и ведётся
 * одним экраном (Р8), а разведённая надвое в ответе, она заставила бы экран считать «+N» суммой двух
 * длин и показывать две пустоты там, где разметки нет вовсе.
 *
 * `id` — идентификатор самой строки разметки, единственный стабильный ключ смешанного перечня:
 * правке он не нужен (набор приходит целиком), но списку тегов нужен ключ, а брать его из
 * `vehicleModelId ?? vehicleTypeId` значило бы вычислять то, что и так есть.
 */
export interface AutoPartApplicabilityDto {
  id: string;
  vehicleModel: AutoPartVehicleModelRefDto | null;
  vehicleType: AutoPartVehicleTypeRefDto | null;
}

/**
 * Насколько позиция подходит машине из запроса (Р21): 0 — размечена её моделью, 1 — её типом,
 * 2 — не размечена ни тем, ни другим.
 *
 * Числом, а не словами: это порядок сортировки, и портал им сортирует список внутри страницы, а не
 * печатает. Слово («подходит по модели») — дело подписи в форме, и заводить его здесь значило бы
 * закрепить формулировку интерфейса в контракте.
 */
export type AutoPartApplicabilityRank = 0 | 1 | 2;

export interface AutoPartDto {
  id: string;
  /** `null` — кода нет (Р12), а не «код пустой»: пустая строка сюда не приходит никогда. */
  code: string | null;
  name: string;
  /** Единица измерения (Р9): «5» без неё — загадка, поэтому поле идёт в каждой строке списка. */
  unit: string;
  quantity: number;
  isActive: boolean;
  comment: string;
  applicability: AutoPartApplicabilityDto[];
  /**
   * Ранг подбора — **только в ответе на запрос с `vehicleId`** (Р21). Поля нет вовсе, когда о машине
   * не спрашивали: ноль по умолчанию означал бы «подходит по модели» и раскрасил бы весь справочник
   * как подходящий этой машине.
   */
  applicabilityRank?: AutoPartApplicabilityRank;
  /**
   * Есть ли по позиции хоть одно движение остатка. Это ответ на «удаляема ли карточка» (Р11): пока
   * журнал пуст, запись удаляется совсем — так убирают опечатку первого дня; появилось движение —
   * только гашение флагом, и держит это `ON DELETE RESTRICT` журнала, а не маршрут. Маршрут отвечает
   * признаком лишь затем, чтобы человек прочитал «по позиции есть движение, снимите „Активна“», а не
   * имя ограничения.
   */
  hasStockHistory: boolean;
  /**
   * Когда позицию завели. Не украшение карточки: на это число опирается предупреждение о двойном
   * списании (Р20) — акт с датой раньше заведения позиции законен, но её расход мог уже войти в
   * начальный остаток, и форма обязана спросить об этом до отправки.
   */
  createdAt: string;
  updatedAt: string;
}

/**
 * Строка журнала остатка: было, стало, причина, автор, время (Р3).
 *
 * Строки неизменяемы — правку и удаление отбивает триггер, — поэтому лента читается как рассказ:
 * ошибку исправляют следующим событием «ошиблись, вернули 15», а не подчисткой прошлого. Порядок
 * задаёт `seq`, а не время: две правки одной секунды по `createdAt` неразличимы.
 */
export interface AutoPartStockEntryDto {
  id: string;
  seq: number;
  /**
   * Что это было: ручная корректировка механика, списание по акту обслуживания или возврат на склад
   * (правка строки вниз, снятие строки, аннулирование акта — Р5, Р6).
   */
  entryKind: 'manual' | 'issue' | 'return';
  /**
   * Акт, по которому прошло движение, и его реквизиты для ленты. Все четыре поля пусты у ручной
   * правки и заполнены у движения по акту — порознь не бывают, это держит CHECK
   * `auto_part_stock_links_check`.
   *
   * Реквизиты читаются соединением с **текущим** актом, а не снимком в момент движения (Р5): дату,
   * номер и подпись машины правят после списания, и застывший «Обслуживание 12.08.2026, В613ВУ197»
   * разошёлся бы с документом, на который сам же и ссылается. По той же причине их нет и в тексте
   * причины — она у движений по акту нейтральная и неизменяемая.
   *
   * `maintenanceVehicleId` нужен не для показа, а для адреса: ссылка ленты ведёт в историю машины
   * (`?tab=vehicles&maintenance=<vehicleId>&record=<maintenanceId>`, Р14), и одного идентификатора
   * акта для неё не хватает.
   */
  maintenanceId: string | null;
  maintenanceVehicleId: string | null;
  maintenanceVehicleLabel: string | null;
  /** `YYYY-MM-DD`, дата **хозяйственная** — когда обслуживали. Складскую дату несёт `createdAt`. */
  maintenancePerformedOn: string | null;
  quantityBefore: number;
  quantityAfter: number;
  reason: string;
  changedByName: string;
  /**
   * Дата **складского учёта** (Р20): когда движение отражено в портале. С `maintenancePerformedOn`
   * они расходятся у актов задним числом, и это норма, а не дефект, — поэтому названы обе, и всякий
   * будущий отчёт обязан сказать, какую из них берёт.
   */
  createdAt: string;
}

/** Карточка позиции целиком: сама запись и лента её журнала (§6, Р14). */
export interface AutoPartDetailDto extends AutoPartDto {
  stockEntries: AutoPartStockEntryDto[];
}

/** Ответ ручки остатка: карточка с новым числом и записанное событие. */
export interface AutoPartStockResultDto {
  part: AutoPartDto;
  /** `null` — новое значение совпало с текущим, и события не было. */
  entry: AutoPartStockEntryDto | null;
}
