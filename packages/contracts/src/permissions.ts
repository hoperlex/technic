/**
 * Кому проверяется право: роль плюс тип контрагента учётки. Принимать сюда одну роль нельзя —
 * у внешнего исполнителя роль без контрагента отвечает только за общую часть прав, и вызов
 * `can(role, ...)` молча возвращал бы «нет» на его собственный модуль. Поэтому субъект —
 * объект: и принципал на сервере, и текущий пользователь на портале подходят под него как есть.
 */
export interface AccessSubject {
  role: Role | null;
  /** Тип контрагента учётки; у ролей вне `COUNTERPARTY_SCOPED_ROLES` не читается. */
  counterpartyType?: CounterpartyType | null;
  /**
   * Надстройки роли (ADR 0086): набор дополнительных прав поверх роли. Необязателен — учёток без
   * надстроек большинство, и требовать пустой массив от каждого вызова `can` значило бы менять
   * все места, где субъектом служит роль как есть.
   */
  addons?: readonly RoleAddon[] | null;
  /**
   * Эффективные права назначенных полномочий (ADR 0106, шаг 1c) — четвёртый источник субъекта.
   *
   * Приходят **готовыми**, а не выводятся здесь из кодов наборов, и это не сокращение: состав
   * набора живёт в базе (`grant_permissions`), матрица его не знает и знать не должна — иначе
   * `permissions.ts` перестал бы быть данными и начал зависеть от таблиц. Считает список сервер
   * (`grantPermissionsExpr`), и там же, в соединении с `grant_roles`, стоит **гейт совместимости с
   * ролью**: набор, выданный до смены роли, прав больше не даёт. Поэтому здесь роль повторно не
   * спрашивается — второй гейт с другим ответом хуже, чем один.
   *
   * Тип — `Permission[]`, хотя в базе право хранится текстом: сироту (право, снятое из словаря
   * выкатом) отсеивает читатель на границе `isPermission`. Матрица получает уже отфильтрованное —
   * иначе `permissionsFor` и витрина начали бы рассказывать про доступ то, чего в коде нет.
   *
   * Необязательное — и это условие совместимости шага, а не удобство. Субъектом по-прежнему бывает
   * «роль как есть»: так его собирают `ACCESS_PROFILES`, тесты матрицы и портал до переключения
   * `/auth/me` на эффективные права (§10.1 плана). Субъект без поля считается ровно как сегодня.
   */
  grantPermissions?: readonly Permission[] | null;
  /**
   * Коды назначенных наборов (ADR 0106) — то, ЧТО учётке выдано, в отличие от `grantPermissions`,
   * которое отвечает, что она в итоге может.
   *
   * **Матрица прав это поле НЕ читает, и это решение, а не недоделка** (план профилей оргтехники,
   * Р9). Состав набора живёт в базе; влияй он на `can`, состав определял бы ответ двумя путями
   * сразу — правами набора и его кодом, — и первый же выкат, поменявший состав, развёл бы эти два
   * пути молча. Поэтому код отвечает только на вопросы, которых у матрицы нет вовсе: «какой у
   * человека бизнес-профиль модуля» (сторона обсуждения, подпись, будущее письмо) и «видит ли он
   * модуль сквозным» (`hasModuleWideScope`, область — не право).
   *
   * Строки, а не `SystemGrantCode`: рядом с системными в базе лежат наборы, собранные
   * администратором, и сузить тип значило бы соврать про содержимое.
   *
   * Необязательное — как `addons` и `grantPermissions`: субъектом по-прежнему бывает «роль как
   * есть», и требовать пустой массив от каждого вызова `can` значило бы менять все места, где
   * права спрашивают у роли.
   */
  grantCodes?: readonly string[] | null;
}

// Проверка прав идёт на каждом запросе, поэтому списки сразу разложены по множествам.
const ROLE_PERMISSION_SETS = new Map<Role, ReadonlySet<Permission>>(
  ROLES.map((role) => [role, new Set(ROLE_PERMISSIONS[role])]),
);

const COUNTERPARTY_PERMISSION_SETS = new Map<CounterpartyType, ReadonlySet<Permission>>(
  COUNTERPARTY_TYPES.map((type) => [type, new Set(COUNTERPARTY_TYPE_PERMISSIONS[type])]),
);

const ROLE_ADDON_PERMISSION_SETS = new Map<RoleAddon, ReadonlySet<Permission>>(
  ROLE_ADDONS.map((addon) => [addon, new Set(ROLE_ADDON_PERMISSIONS[addon])]),
);

/**
 * Есть ли у субъекта право. Учётка без роли не может ничего: доступ выдаётся ролью, и пока её
 * не назначили, пользователь для портала — никто (активировать такую учётку API не даёт).
 * Исполнитель без контрагента — то же самое в своём модуле: без контрагента неизвестно ни что
 * он исполняет, ни чьи заявки видит, поэтому модульных прав у него нет (активировать такую
 * учётку API тоже не даёт).
 *
 * Источников четыре, и спрашиваются они в одном порядке: **роль → надстройки → наборы →
 * тип контрагента**. Порядок влияет только на то, каким источником право объясняется первым
 * (`permissionSource`); на ответ «есть или нет» — нет, потому что источники соединены OR и никакой
 * из них права не отнимает (инвариант 1 §8: «отобрать = не выдать»).
 */
export function can(subject: AccessSubject | null | undefined, permission: Permission): boolean {
  const role = subject?.role;
  if (!role) return false;
  if (ROLE_PERMISSION_SETS.get(role)?.has(permission)) return true;
  // Надстройки роли (ADR 0086) — третий источник прав, и спрашивается он до контрагента:
  // надстройка бывает у любой базовой роли, а тип контрагента читается только у исполнителя.
  // Несовместимую с ролью надстройку сюда не пропускает API учёток, но проверка стоит и здесь:
  // матрица обязана отвечать одинаково на любой субъект, откуда бы он ни пришёл.
  for (const addon of subject?.addons ?? []) {
    if (canAttachAddon(role, addon) && ROLE_ADDON_PERMISSION_SETS.get(addon)?.has(permission)) {
      return true;
    }
  }
  /*
   * Назначенные полномочия (ADR 0106, шаг 1c) — четвёртый источник, и стоит он **рядом с
   * надстройками**, а не на их месте. Причина в самом шаге: 1c переключает чтение на новые таблицы,
   * но старую запись не прекращает (это 1d), а `user_role_addons` живёт до 1e. Значит одна и та же
   * выдача двух системных наборов в этот релиз видна и надстройкой, и набором, и оба источника
   * отвечают «да» на одно право. Совпадение здесь — норма перехода, а не ошибка: OR даёт на него
   * тот же ответ, что каждый источник по отдельности, и снятие любого из двух источников доступ не
   * меняет. Убери мы старый источник заодно с добавлением нового — шаг перестал бы быть
   * переключением чтения и стал бы 1c+1d одним релизом, без возможности откатиться на версию,
   * читающую надстройки.
   *
   * Роль здесь не проверяется намеренно: список уже посчитан сервером с гейтом совместимости
   * (`grantPermissionsExpr`, соединение с `grant_roles`), и второй гейт в матрице означал бы два
   * ответа на один вопрос. Отсутствие поля — «наборов у субъекта нет»: `?? []` ниже, а не приведение
   * к пустому массиву на каждом вызове.
   *
   * `includes` по короткому массиву, а не `Set` на каждый вызов: множество здесь пришлось бы
   * собирать заново при каждом `can` (список приходит на субъекте, а не лежит константой), и это
   * дороже линейного перебора полусотни строк — а больше их не бывает, назначаемых прав всего 53.
   */
  if ((subject?.grantPermissions ?? []).includes(permission)) return true;
  if (!isCounterpartyScopedRole(role)) return false;
  const type = subject?.counterpartyType;
  return !!type && (COUNTERPARTY_PERMISSION_SETS.get(type)?.has(permission) ?? false);
}

/**
 * Откуда у субъекта право: роль, надстройка, назначенное полномочие или тип контрагента. Нужно
 * витрине прав (`docs/permissions-tab-plan.md`): «право есть» и «право пришло полномочием, а не
 * должностью» — разные ответы, и при пересмотре ролей важен второй.
 *
 * Живёт рядом с `can` и повторяет его порядок источников намеренно: вторая копия этого порядка на
 * портале разъехалась бы с первой при первой же правке модели, и витрина начала бы объяснять
 * доступ неправильно — то есть ровно тогда, когда по ней принимают решение.
 */
export interface PermissionOrigin {
  kind: 'role' | 'addon' | 'grant' | 'counterparty';
  /** Надстройка, давшая право; заполнена только при `kind: 'addon'`. */
  addon?: RoleAddon;
  /**
   * Код набора, давшего право; при `kind: 'grant'` заполнен настолько, насколько субъект вообще
   * знает разбивку.
   *
   * На шаге 1c он не заполнен ни у кого, и это не забытая ветка. Субъект несёт **объединение**
   * эффективных прав своих наборов (`grantPermissions`): так их считает SQL — `array_agg(DISTINCT
   * gp.permission)`, — потому что одно право штатно лежит в двух наборах учётки, и на вопрос «есть
   * ли доступ» разбивка не влияет. Поле объявлено здесь потому, что вопрос витрины про наборы
   * звучит иначе — «какой именно набор снять, чтобы право ушло», — и отвечать на него будет тот же
   * тип, когда субъект начнёт нести разбивку по наборам. Тип — `string`, а не `SystemGrantCode`:
   * рядом с двумя системными в базе лежат наборы, собранные администратором, и сузить его значило
   * бы соврать про содержимое; заодно словарь прав не начинает зависеть от `grants.ts` — эта
   * зависимость односторонняя (полномочия знают про права, права про полномочия — нет).
   */
  grantCode?: string;
}

/**
 * **Все** источники, давшие субъекту право, в порядке `can`: роль → надстройки → наборы →
 * контрагент. Пустой список означает «права нет» — ровно то же, что `can(...) === false`.
 *
 * Множественная, а не «первый найденный», и это требование модели, а не удобство (§8 плана). В
 * свободной сборке одно право приходит одновременно от роли и нескольких наборов; на переходных
 * шагах 1a–1d — ещё и от надстройки, из которой набор перенесён. «Первый найденный» на таком
 * субъекте отвечает не неточно, а **неверно**: витрина объясняет доступ должностью, хотя набор даёт
 * то же право, а расчёт «что снимется при отзыве» получается прямо обратным — снятие набора отберёт
 * право только если его не даёт больше никто, и узнать это можно лишь пересчитав все источники
 * (`effectiveDelta`).
 *
 * Надстройка перечисляется по разу на каждую совместимую с ролью надстройку, давшую право; наборы —
 * одной записью на весь их вклад, потому что разбивки по наборам субъект на этом шаге не несёт
 * (см. `grantCode`).
 */
export function permissionSources(
  subject: AccessSubject | null | undefined,
  permission: Permission,
): readonly PermissionOrigin[] {
  const role = subject?.role;
  if (!role) return [];
  const origins: PermissionOrigin[] = [];
  if (ROLE_PERMISSION_SETS.get(role)?.has(permission)) origins.push({ kind: 'role' });
  for (const addon of subject?.addons ?? []) {
    if (canAttachAddon(role, addon) && ROLE_ADDON_PERMISSION_SETS.get(addon)?.has(permission)) {
      origins.push({ kind: 'addon', addon });
    }
  }
  if ((subject?.grantPermissions ?? []).includes(permission)) origins.push({ kind: 'grant' });
  if (isCounterpartyScopedRole(role)) {
    const type = subject?.counterpartyType;
    if (type && COUNTERPARTY_PERMISSION_SETS.get(type)?.has(permission)) {
      origins.push({ kind: 'counterparty' });
    }
  }
  return origins;
}

/**
 * Первый источник права или `null` — обёртка над `permissionSources`, сохранённая ради читателей.
 *
 * Оставлена намеренно, а не «пока не переписали»: её зовут карточка доступа
 * (`apps/web/src/pages/admin/AccessPeopleTab.tsx`, одна строка «откуда право») и тест витрины, и
 * менять их этим шагом нельзя — шаг 1c переключает источник, а не читателей. Обёрткой, а не второй
 * реализацией: разъехавшись, две копии порядка источников дали бы разные ответы на один субъект.
 *
 * Читателям с наборами она отвечает неполно **по построению** — в этом и смысл появления
 * множественной версии рядом. Переходить на `permissionSources` витрина обязана в том же шаге, где
 * начинает показывать наборы; до тех пор ответ у неё прежний, потому что и субъект прежний.
 */
export function permissionSource(
  subject: AccessSubject | null | undefined,
  permission: Permission,
): PermissionOrigin | null {
  return permissionSources(subject, permission)[0] ?? null;
}

/** Что изменится в правах субъекта: только то, что реально появится и реально уйдёт. */
export interface PermissionDelta {
  added: Permission[];
  removed: Permission[];
}

/**
 * Разница эффективных прав двух состояний субъекта — то, что показывает предпросмотр перед
 * сохранением выдачи (§8, §12 плана).
 *
 * Считается по **всем** источникам, а не по спискам прав наборов, и это единственный способ
 * ответить правильно: снятие набора отбирает право только если его не даёт больше никто — ни роль,
 * ни вторая надстройка, ни другой набор, ни тип контрагента. Разница списков наборов на том же
 * субъекте показала бы «уйдёт `officeEquipment.write`» держателю роли «Менеджер», у которого это
 * право ролевое, — то есть напугала бы администратора отзывом, ничего не меняющим, и одновременно
 * промолчала бы о правах, которые действительно уходят вместе с последним их источником.
 *
 * Принимает субъекты целиком, а не пару списков прав: субъект — это роль, надстройки, наборы и
 * контрагент вместе, и «что будет после» строится из него подстановкой одного изменившегося поля
 * (`{ ...subject, grantPermissions: [...] }`), а не пересчётом прав на стороне вызывающего. Второй
 * такой пересчёт и был бы той самой копией конвейера источников, от которой избавляет эта функция.
 *
 * Порядок в обоих списках — словарный (`PERMISSIONS`), а не порядок пришедших наборов: предпросмотр
 * читают глазами, и строки в нём не должны переставляться от того, в каком порядке отмечали
 * галочки. Перебором словаря, а не пересечением множеств: словарь закрыт, прав в нём под шесть
 * десятков — один проход дешевле двух наборов.
 */
export function effectiveDelta(
  before: AccessSubject | null | undefined,
  after: AccessSubject | null | undefined,
): PermissionDelta {
  const added: Permission[] = [];
  const removed: Permission[] = [];
  for (const permission of PERMISSIONS) {
    const had = can(before, permission);
    const has = can(after, permission);
    if (had === has) continue;
    (has ? added : removed).push(permission);
  }
  return { added, removed };
}

/**
 * Субъект вместе с его областью — то, чем открывается раздел портала (`canUse`). Наборы
 * необязательны: под него подходят как есть и принципал на сервере, и текущий пользователь на
 * портале, а роль без области их и не читает.
 */
export interface ScopedSubject extends AccessSubject {
  /** Прямая привязка объектной роли (ADR 0039). */
  constructionObjectIds?: readonly string[];
  /** Производная привязка роли отдела (ADR 0062): объекты её отделов. */
  departmentObjectIds?: readonly string[];
}

/**
 * Объекты, в пределах которых субъект работает в модуле «Вывоз мусора» (ADR 0062): у объектной
 * роли — свои, у роли отдела — площадки её отделов. `null` означает «областью не ограничен» и
 * отличается от пустого набора, как «видит всё» отличается от «не видит ничего».
 *
 * Только этот модуль: в «Заказе ТС» у роли отдела заказчик — отдел, и объектной области у неё
 * там нет вовсе (ADR 0062 п. 3).
 */
export function placeObjectScopeIds(
  subject: ScopedSubject | null | undefined,
): readonly string[] | null {
  const role = subject?.role;
  if (isObjectScopedRole(role)) return subject?.constructionObjectIds ?? [];
  if (isDepartmentScopedRole(role)) return subject?.departmentObjectIds ?? [];
  return null;
}

function hasPlaceObjectScope(subject: ScopedSubject): boolean {
  const ids = placeObjectScopeIds(subject);
  return ids === null || ids.length > 0;
}

/** Права модуля, который весь ходит по площадкам, — одной строкой на модуль. */
const placeScoped = (
  permissions: readonly Permission[],
): [Permission, (subject: ScopedSubject) => boolean][] =>
  permissions.map((permission) => [permission, hasPlaceObjectScope]);

/**
 * Права, применимость которых зависит от области (ADR 0062). Права, которого здесь нет, область
 * не сужает — тот же приём, что в `ROLE_VEHICLE_REQUEST_TYPES`: новое право открыто всем, у кого
 * оно есть, кроме тех, кому его сузили осознанно, строкой здесь.
 */
const MODULE_SCOPE = new Map<Permission, (subject: ScopedSubject) => boolean>([
  ...placeScoped(WASTE_REQUEST_PERMISSIONS),
  /*
   * Механизация (план `docs/mechanization-module-plan.md`, Р10) — та же площадочная область, что
   * у вывоза, и по той же причине: ось модуля одна, `object_id` места эксплуатации, а отдел
   * работает на площадках своего отдела (ADR 0062, ADR 0144).
   *
   * **Именно эти строки и закрывают раздел отделу без площадок** — ответ заказчика «отдел без
   * площадки не увидит даже вкладку модуля». Без них право у роли было бы, а работать им не над
   * чем: `canUse` отвечал бы «да», пункт меню рисовался, а список приходил бы пустым всегда.
   */
  ...placeScoped(MECH_REQUEST_PERMISSIONS),
]);

/**
 * Открыт ли субъекту раздел: право **и** непустая область, в которой это право применимо
 * (ADR 0062). Отделу без площадки вывоз мусора закрыт именно так — право у роли есть, работать
 * им не над чем.
 *
 * Спрашивается там, где решается «показывать ли раздел»: пункт меню, маршрут портала, стартовая
 * страница. Действия внутри раздела спрашивают `can`: область по конкретной строке всё равно
 * проверяет сервер, а пустой она к этому моменту уже не бывает.
 */
export function canUse(subject: ScopedSubject | null | undefined, permission: Permission): boolean {
  if (!subject || !can(subject, permission)) return false;
  const hasScope = MODULE_SCOPE.get(permission);
  return !hasScope || hasScope(subject);
}

/**
 * Работает ли учётка от контрагента указанного типа (ADR 0038) — то есть исполняет ли она
 * заявки этого модуля. Предикат, а не сравнение с ролью: «оператор вывоза» — это роль
 * исполнителя плюс контрагент-оператор, и одна роль без типа означает уже не то же самое.
 */
export function actsForCounterparty(
  subject: AccessSubject | null | undefined,
  type: CounterpartyType,
): boolean {
  return isCounterpartyScopedRole(subject?.role) && subject?.counterpartyType === type;
}

/**
 * Выдан ли субъекту набор с таким кодом (ADR 0106) — вопрос БИЗНЕС-ПРОФИЛЯ, а не доступа.
 *
 * Стоит рядом с `actsForCounterparty` по той же причине: это предикат о субъекте, а не источник
 * прав. `can` его не зовёт и звать не должен (см. `AccessSubject.grantCodes`); зовут его те, кому
 * нужно опознать «кто этот человек в модуле» — сторона обсуждения, подпись, адресат письма.
 * Отдельная функция, а не `includes` по месту: мест таких несколько, и каждое из них обязано
 * одинаково понимать субъекта без кодов («наборов нет»), а не падать на `undefined`.
 */
export function hasGrantCode(subject: AccessSubject | null | undefined, code: string): boolean {
  return (subject?.grantCodes ?? []).includes(code);
}

/** Все права субъекта — для отладки и для страницы учёток. */
export function permissionsFor(subject: AccessSubject | null | undefined): readonly Permission[] {
  const role = subject?.role;
  if (!role) return [];
  return PERMISSIONS.filter((permission) => can(subject, permission));
}

/**
 * Все различимые субъекты доступа: роли без контрагента как есть, роль от контрагента —
 * по разу на каждый тип контрагента с учётками. Список нужен там, где перебирают «всех, кто
 * бывает в портале»: тесты матрицы, обратный поиск по праву.
 */
export const ACCESS_PROFILES: readonly AccessSubject[] = [
  ...ROLES.flatMap((role) =>
    isCounterpartyScopedRole(role)
      ? COUNTERPARTY_TYPES_WITH_ACCOUNTS.map((counterpartyType) => ({ role, counterpartyType }))
      : [{ role }],
  ),
  // Надстройка (ADR 0086) даёт свой различимый субъект: «штаб» и «штаб с надстройкой» отвечают
  // на `can` по-разному, и тесты доступа обязаны перебирать оба. По разу на каждую пару
  // «базовая роль × надстройка» — сочетания надстроек друг с другом прав не меняют.
  /*
   * Коды наборов идут ТЕМИ ЖЕ строками, что надстройки, и это не дубль поля (план профилей
   * оргтехники, Р9). С шага 1c одна и та же выдача видна и надстройкой, и набором: код системного
   * набора совпадает с кодом надстройки по построению — `SYSTEM_GRANT_CODES` объявлен
   * `satisfies readonly RoleAddon[]` ровно ради этого равенства. Перебор обязан нести обе половины,
   * потому что читатели у них разные: права спрашивают надстройку, бизнес-профиль модуля — код
   * (сторона обсуждения `it` и `operator`). Оставь мы здесь одни надстройки — профиль перестал бы
   * опознаваться стороной у КАЖДОГО субъекта перебора, и выглядело бы это дефектом сторон, а не
   * перебора.
   */
  ...ROLE_ADDONS.flatMap((addon) =>
    ROLE_ADDON_BASE_ROLES[addon].map((role) => ({
      role,
      addons: [addon] as const,
      grantCodes: [addon] as const,
    })),
  ),
];

/** Субъекты, у которых есть указанное право (обратный поиск: подсказки интерфейса и тесты). */
export function profilesWith(permission: Permission): AccessSubject[] {
  return ACCESS_PROFILES.filter((subject) => can(subject, permission));
}

/** Человекочитаемое имя субъекта: у исполнителя оно называет предмет работы, а не роль. */
export function accessProfileLabel(subject: AccessSubject): string {
  if (subject.role && isCounterpartyScopedRole(subject.role) && subject.counterpartyType) {
    return `${roleLabels[subject.role]} — ${counterpartyTypeLabels[subject.counterpartyType]}`;
  }
  if (!subject.role) return 'Без роли';
  // Надстройки (ADR 0086) дописываются к роли, а не заменяют её: человек остаётся штабом своего
  // объекта, и в списке учёток это должно читаться именно так — «Штаб + Оператор (оргтехника)».
  const addons = (subject.addons ?? []).map((addon) => roleAddonLabels[addon]);
  return [roleLabels[subject.role], ...addons].join(' + ');
}

/**
 * Роли, которым в модуле «Заказ ТС» доступны не все типы заявки (ADR 0040). Отдел заказывает
 * только грузоперевозки: спецтехника выходит на площадку, а площадки у отдела нет.
 *
 * Таблица, а не право `vehicleRequests.freight` и не `if` по имени роли. Право отвечает «что
 * учётка делает», а здесь ограничение по признаку самой строки — это область; в матрице оно
 * завело бы колонку-исключение, которую пришлось бы читать при каждом новом типе заявки.
 * Отсутствие роли в таблице означает «доступны все типы» — так новый тип заявки открывается
 * всем, кроме тех, кому его закрыли осознанно, строкой здесь.
 */
const ROLE_VEHICLE_REQUEST_TYPES: Partial<Record<Role, readonly VehicleRequestType[]>> = {
  department: ['freight_transport'],
  department_head: ['freight_transport'],
};

/** Типы заявки на технику, доступные субъекту (пустой список невозможен: роли без модуля сюда не доходят). */
export function allowedVehicleRequestTypes(
  subject: AccessSubject | null | undefined,
): readonly VehicleRequestType[] {
  const own = subject?.role ? ROLE_VEHICLE_REQUEST_TYPES[subject.role] : undefined;
  return own ?? VEHICLE_REQUEST_TYPES;
}

export function canOrderVehicleRequestType(
  subject: AccessSubject | null | undefined,
  requestType: VehicleRequestType,
): boolean {
  return allowedVehicleRequestTypes(subject).includes(requestType);
}

/**
 * Роли с собственным коридором статусов: право «менять статус» у них есть, но не на весь
 * рабочий цикл. Таблица, а не исключение в коде: следующая такая роль добавляется строкой.
 */
const ROLE_STATUS_TRANSITIONS: Partial<Record<Role, Record<RequestStatus, RequestStatus[]>>> = {
  // Внешний исполнитель закрывает то, что сам выполнил; подтверждать и отменять — решения
  // заказчика (ADR 0010). Коридор один на оба модуля: закрытие выполненного — это одно и то же
  // действие, что у вывоза мусора, что у аренды техники, поэтому таблица по роли, а не по типу
  // контрагента.
  operator: OPERATOR_STATUS_TRANSITIONS,
};

/**
 * Право «двигать заявку по статусам» — **по модулю** (план `docs/mechanization-module-plan.md`,
 * Р9). Таблицей, а не дизъюнкцией `wasteRequests.status || vehicleRequests.status`, которая стояла
 * здесь до механизации: та знала ровно два права, и третьему модулю его собственное
 * `mechRequests.status` не открыло бы ни одного хода — коридор считался бы по чужим правам, а
 * держатель прав вывоза получил бы ходы в аренде, которой не ведёт.
 *
 * `Record` по модулям: новый модуль заявок не соберётся, пока не ответит, каким правом он ходит.
 */
const REQUEST_STATUS_PERMISSION: Record<RequestModule, Permission> = {
  waste: 'wasteRequests.status',
  vehicle: 'vehicleRequests.status',
  mech: 'mechRequests.status',
};

/**
 * Смена статуса хотя бы в одном модуле заявок — гейт **только** для ролей со своим коридором
 * (`ROLE_STATUS_TRANSITIONS`), то есть сегодня для внешнего исполнителя.
 *
 * Почему он не спрашивает модуль, хотя таблица выше есть. Модуль исполнителю выбирает не право, а
 * тип его контрагента: оператор вывоза видит только заявки вывоза, арендодатель ТС — только
 * заказы со своей машиной (ADR 0038), и до чужого модуля он не доходит ни ручкой, ни выборкой.
 * Спроси мы здесь право модуля, ответ изменился бы ровно для несуществующего случая — «оператору
 * вывоза про заказ техники», — то есть коридор сузился бы там, где его и так нет.
 *
 * Дизъюнкция считается **по той же таблице**, а не вторым перечнем прав: разойдись они, новый
 * модуль открыл бы исполнителю ходы, о которых не спрашивали. Роль без контрагента (`operator` без
 * типа) прав статуса не имеет вовсе — и своего коридора ей этот гейт не открывает.
 */
function canChangeAnyRequestStatus(subject: AccessSubject): boolean {
  return REQUEST_MODULES.some((module) => can(subject, REQUEST_STATUS_PERMISSION[module]));
}

/**
 * Строка таблицы переходов по статусу заявки — единственное место, где эти таблицы читаются.
 *
 * Смотрит на таблицу `Partial`-взглядом сознательно, хотя тип обещает строку на каждый статус.
 * Обещание верно только внутри одной сборки: `RequestStatus` — словарь собранного бандла, а
 * значение приходит из типа `request_status` базы, и на выкате они расходятся. Так и случилось с
 * «Завершена» (ADR 0135, миграции 0194/0195): база получила новое значение и перевела в него
 * выполненные заявки, а у людей в браузере оставался прошлый выпуск портала — статуса такого он
 * не знал, спред `undefined` бросал `TypeError`, и падала не ячейка, а весь список заявок.
 *
 * Неизвестный статус означает «ходов отсюда нет»: строка показывается, меню переходов не
 * открывается, остальной список работает. Смену статуса всё равно решает сервер — портал лишь
 * предлагает ходы, и предложить их по незнакомому статусу ему нечем.
 */
function corridorFrom(
  table: Record<RequestStatus, RequestStatus[]>,
  from: RequestStatus,
): RequestStatus[] {
  return (table as Partial<Record<RequestStatus, RequestStatus[]>>)[from] ?? [];
}

/** Ходы по циклу, открытые правом ведения статусов: без завершения — оно отпирается другим. */
function cycleTransitions(
  from: RequestStatus,
  subject: AccessSubject,
  module: RequestModule,
): RequestStatus[] {
  const ownCorridor = subject.role ? ROLE_STATUS_TRANSITIONS[subject.role] : undefined;
  // Свой коридор заменяет общий целиком — вместе с вопросом о праве: у исполнителя оно приходит
  // типом контрагента, и модуль ему выбирает заявка, а не право (см. `canChangeAnyRequestStatus`).
  if (ownCorridor) return canChangeAnyRequestStatus(subject) ? corridorFrom(ownCorridor, from) : [];
  if (!can(subject, REQUEST_STATUS_PERMISSION[module])) return [];
  const forward = corridorFrom(requestStatusTransitions[module], from);
  return can(subject, 'requests.rollbackStatus')
    ? [...forward, ...corridorFrom(requestStatusRollbacks[module], from)]
    : forward;
}

/**
 * Статусы, доступные субъекту из текущего статуса (пустой список — смена статуса запрещена).
 * Живёт рядом с матрицей, а не с таблицами переходов: «кто может» — это право, а таблицы
 * переходов описывают только «что за чем идёт».
 *
 * Модуль обязателен: с ADR 0135 коридоры «Вывоза мусора» и «Заказа ТС» разошлись, и вопрос
 * «куда отсюда можно» без него не имеет одного ответа.
 *
 * **Завершение отпирает не ведение цикла, а разбор талонов** (`wasteRequests.ticketReview`).
 * Точку в заявке ставит тот, кто признал бумагу: он один видел талоны, сверку и расхождения, —
 * а `wasteRequests.status` есть и у внешнего исполнителя, который эту бумагу принёс. Отсюда и
 * порядок: ход в «Завершена» из таблицы цикла вычитается и возвращается отдельным правом.
 */
export function allowedStatusTransitions(
  from: RequestStatus,
  subject: AccessSubject,
  module: RequestModule,
): RequestStatus[] {
  const cycle = cycleTransitions(from, subject, module).filter((s) => s !== 'completed');
  if (module !== 'waste' || from !== 'done') return cycle;
  return can(subject, 'wasteRequests.ticketReview') ? [...cycle, 'completed'] : cycle;
}

export function canTransitionStatus(
  from: RequestStatus,
  to: RequestStatus,
  subject: AccessSubject,
  module: RequestModule,
): boolean {
  return allowedStatusTransitions(from, subject, module).includes(to);
}
