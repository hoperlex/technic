export type Permission = (typeof PERMISSIONS)[number];

/**
 * Есть ли такое право в словаре — страж границы «база → код» (ADR 0106).
 *
 * Права назначаемого полномочия хранятся в `grant_permissions` **текстом**, и справочника прав в
 * базе нет намеренно: он был бы второй копией закрытого словаря и разъехался бы с ним в первый же
 * выкат, переименовавший право. Обратная сторона решения — сироты: выкат, снявший право из
 * `PERMISSIONS`, оставляет в базе строки, которым в коде больше ничего не соответствует. CHECK по
 * списку прав их бы не допустил, но превратил бы снятие права в отказ базы, то есть в падение
 * каждой проверки доступа.
 *
 * Поэтому сироты живут в таблице и отсеиваются **при чтении**: доступа такая строка не даёт
 * (право, которого нет в словаре, не стоит ни на одном маршруте), а витрина показывает её как
 * «право больше не существует». Предикат, а не `includes` по месту и не `as Permission` на границе:
 * приведение типом пообещало бы, что фильтровать нечего, и первое же снятое право стало бы
 * значением `Permission`, которого в `PERMISSIONS` нет, — с ним `permissionsFor` и витрина начали
 * бы рассказывать про доступ то, чего в коде уже нет.
 */
const PERMISSION_SET: ReadonlySet<string> = new Set(PERMISSIONS);

export const isPermission = (value: string): value is Permission => PERMISSION_SET.has(value);

