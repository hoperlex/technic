/**
 * Ворота старта: годится ли ТЕКУЩЕЕ состояние дерева как начало прогона.
 *
 * ЗАЧЕМ ОТДЕЛЬНОЕ РЕШЕНИЕ. И цикл сходимости, и тяжёлое окно устроены как возврат к стабильной
 * точке: неудачная партия откатывается, и следующий круг начинается с того же места. Место это
 * обязано быть названо — иначе «вернуться туда, где было зелено» означает любое место истории
 * (`architecture/policies/versioning.yaml`, шапка). Сегодня стартовое состояние не спрашивается
 * вовсе, и прогон одинаково охотно начинается с вершины, которая сама не собирается.
 *
 * ЗДЕСЬ НЕТ НИ ОДНОГО ОБРАЩЕНИЯ К ДИСКУ, GIT ИЛИ ПРОЦЕССАМ — по той же причине, что в
 * `convergence.ts` и `deep-window.ts`: правило, которое нельзя проверить, не запустив ворота
 * качества, проверяться не будет. Признаки собирают слои, которым разрешено знать репозиторий
 * (`project/release-anchor.ts`, `analyzers/git.ts`), сюда они приходят значениями.
 *
 * ГЛАВНОЕ РЕШЕНИЕ ФАЙЛА — ЧТО СЧИТАТЬ ЗАПРЕТОМ, А ЧТО ПРЕДУПРЕЖДЕНИЕМ.
 *
 * Буквальное «стартуем только из чистого дерева» здесь неприменимо: дерево общее, рядом почти
 * всегда лежит чужая незавершённая работа, и система, отказывающаяся при ней работать, не
 * заработает ни разу. Объявить чистоту неважной тоже нельзя — тогда непонятно, что именно
 * доказывают зелёные ворота.
 *
 * Середина опирается на то, что система уже умеет и что записано в `docs/maintenance-guide.md`
 * §4 и §6: партия проверяется в ОТДЕЛЬНОМ дереве от `HEAD`, а контрольная точка пофайловая.
 * Значит грязь РЯДОМ не влияет ни на проверку партии, ни на её откат, и запрещать из-за неё
 * нечего. А вот красный сам `HEAD` мешает по-настоящему: проверка партии идёт от него, и красной
 * окажется каждая партия — не по своей вине. Это уже случалось: вершина не собиралась, и все
 * партии откатывались подряд. Отсюда распределение:
 *
 * - красные ворота на вершине — ЗАПРЕТ, и никаким режимом политики он не смягчается: режим
 *   отвечает на вопрос «насколько строго начинать», а не «считать ли красное зелёным»;
 * - непрогнанные ворота — это НЕЗНАНИЕ, а не красный цвет: в мягком режиме предупреждение, в
 *   строгом (`requireGreen`) — запрет;
 * - грязное дерево — предупреждение с числом чужих файлов, чтобы человек видел, чего система не
 *   тронет; запрет только в строгом режиме (`requireClean`), который и заводится для релизного
 *   цикла, где старт обязан совпасть с выпуском;
 * - не названная стабильная точка — предупреждение ВСЕГДА. Тег по политике версий задним числом
 *   не ставится (`retroactive: false`), и запрет за его отсутствие закрыл бы обслуживание всему,
 *   что старше выпуска `0.1.83.0191`.
 *
 * `ready` при этом означает ровно то, что написано, и не выдаётся авансом: ворота прогнаны и
 * зелены, дерево чисто, точка названа. На общем дереве обычный ответ — `warn`, и это честно:
 * начинать можно, но вот чего прогон о себе не знает.
 */

/** Три исхода, потому что «нельзя» и «можно, но с оговоркой» — разные ответы человеку. */
export type StartVerdict = 'ready' | 'warn' | 'blocked';

/** Признаки стартового состояния. Собраны снаружи: ядро их не добывает, а только толкует. */
export interface StartConditions {
  /** Нет изменений отслеживаемых файлов. Неотслеживаемые чистоте не мешают (`GitFacts.clean`). */
  readonly treeClean: boolean;
  /**
   * Ворота прогнаны и зелены. `null` — НЕ ПРОВЕРЯЛИ, и это третье состояние заведено нарочно:
   * подставить здесь `false` значило бы объявить вершину красной, не посмотрев на неё, а `true` —
   * выдать непроверенное за доказанное.
   */
  readonly gatesGreen: boolean | null;
  /** Стабильная точка названа: версия разобрана по политике (тег — не обязателен). */
  readonly anchorNamed: boolean;
  /** Сколько чужих изменённых файлов лежит рядом. Влияет на текст, а не на запрет. */
  readonly foreignWorkInTree: number;
}

/**
 * Режим строгости.
 *
 * Два отдельных флага, а не один «строгий режим»: требование зелёного старта и требование чистого
 * дерева стоят человеку разного, и релизный цикл включает их вместе, а разовая проверка гипотезы
 * может потребовать только зелёного.
 */
export interface StartPolicy {
  readonly requireClean: boolean;
  readonly requireGreen: boolean;
}

export interface StartDecision {
  readonly verdict: StartVerdict;
  /** Почему именно так — человеческим языком, по строке на причину. Никогда не пусто. */
  readonly reasons: readonly string[];
}

export function decideStart(conditions: StartConditions, policy: StartPolicy): StartDecision {
  const blockers: string[] = [];
  const warnings: string[] = [];
  // Счётчик приходит из подсчёта файлов, но признаки собирает чужой слой: отрицательное и дробное
  // здесь означало бы ошибку сбора, и молча печатать её человеку в отчёте не стоит.
  const foreign = Math.max(0, Math.trunc(conditions.foreignWorkInTree));

  if (conditions.gatesGreen === false) {
    blockers.push(
      'Ворота качества на вершине красные. Партия проверяется в отдельном дереве от HEAD, ' +
        'поэтому красной окажется каждая партия — и все они откатятся не по своей вине. ' +
        'Чинить надо вершину, а не начинать прогон.',
    );
  } else if (conditions.gatesGreen === null) {
    const unknown =
      'Ворота качества не прогонялись: зелёная вершина не доказана, и первое же красное ' +
      'доказательство будет не отличить от красной базы.';
    if (policy.requireGreen) {
      blockers.push(`${unknown} Режим прогона требует зелёного старта.`);
    } else {
      warnings.push(unknown);
    }
  }

  if (!conditions.treeClean) {
    const dirty =
      foreign > 0
        ? `Дерево не чисто: рядом лежит чужая незавершённая работа (файлов: ${foreign}). ` +
          'Контрольная точка пофайловая, и этих файлов система не тронет — но состояние старта ' +
          'уже не совпадает с выпуском.'
        : 'Дерево не чисто: изменения отслеживаемых файлов есть, и состояние старта не совпадает ' +
          'с выпуском.';
    if (policy.requireClean) {
      blockers.push(`${dirty} Режим прогона требует чистого дерева.`);
    } else {
      warnings.push(dirty);
    }
  } else if (foreign > 0) {
    // Признаки собираются из одного источника, и такое сочетание означает рассогласование сбора.
    // Промолчать нельзя: «чисто» тут отвечало бы за чужую работу, которой оно не видело.
    warnings.push(
      `Признаки противоречат друг другу: дерево названо чистым, но чужих изменённых файлов ${foreign}. ` +
        'Пока расхождение не объяснено, чистоте верить нечем.',
    );
  }

  if (!conditions.anchorNamed) {
    warnings.push(
      'Стабильная точка не названа: версия в VERSION отсутствует или не разбирается по политике. ' +
        'Откат партии это не ломает — он пофайловый, — но сказать, от какого выпуска шёл прогон, ' +
        'будет нечем.',
    );
  }

  if (blockers.length > 0) {
    // Запреты идут первыми: человек читает верхнюю строку и уже знает, почему прогон не начался.
    return { verdict: 'blocked', reasons: [...blockers, ...warnings] };
  }
  if (warnings.length > 0) return { verdict: 'warn', reasons: warnings };
  return {
    verdict: 'ready',
    reasons: [
      'Дерево чисто, ворота прогнаны и зелены, стабильная точка названа: прогон стартует от неё ' +
        'и к ней же возвращается при откате.',
    ],
  };
}
