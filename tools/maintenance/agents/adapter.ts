/**
 * Контракт доставки задания агенту.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ СЛОЙ. Сегодня задание относит человек: система пишет `task.md`, человек отдаёт
 * его модели в редакторе и кладёт ответ в `results/`. Завтра то же самое делает команда, послезавтра
 * — служба по сети. Меняется только способ ДОСТАВКИ: ни отбор находок, ни проверка поведения, ни
 * откат от него не зависят. Поэтому доставка вынесена в интерфейс с тремя исходами, а всё остальное
 * остаётся в ядре и не знает, кто именно принёс текст.
 *
 * ГРАНИЦА ОТВЕТСТВЕННОСТИ жёсткая: адаптер отдаёт задание и приносит текст. Он не разбирает ответ
 * (это `core/finding-io.ts`), не решает, годится ли находка (это `core/selector.ts`) и не правит
 * дерево. Смешать это — значит получить адаптер, который сам спросил, сам ответил и сам себе
 * поверил.
 */
import type { WorkPacket } from '../work-packets/types.ts';

/**
 * Исход доставки.
 *
 * Исходов ровно три, и третий — не роскошь. «Ответа пока нет» и «агент не отработал» приходится
 * различать: первое означает «ждём человека и ничего не меняем», второе — «прогон остановлен,
 * причину видно». Свести их в один `null` значило бы молча превращать поломку в ожидание, а
 * ожидание — в поломку.
 */
export type AgentReply =
  /** Ответ получен. Текст отдаётся КАК ЕСТЬ: разбирать его будет другой слой. */
  | { readonly kind: 'answer'; readonly text: string }
  /** Ответа пока нет — задание выдано, ждём человека. `where` — где ответ ожидается. */
  | { readonly kind: 'awaiting'; readonly where: string }
  /** Агент не отработал: не запустился, упал, вышел за время или вернул пустоту. */
  | { readonly kind: 'failed'; readonly why: string };

export interface AgentContext {
  readonly root: string;
  /** Куда положено задание. Файл пишется всегда: по нему человек разбирает прогон постфактум. */
  readonly taskFile: string;
  /** Где ожидается ответ — этот же путь назван агенту в самом задании. */
  readonly answerFile: string;
  /**
   * Потолок ожидания. Обязателен: агент без ограничения по времени превращает автоматический
   * цикл в зависший процесс, который некому прервать.
   */
  readonly timeoutMs: number;
}

export interface AgentAdapter {
  readonly id: string;
  readonly title: string;
  /** Выдать задание и, если умеет, получить ответ. */
  deliver(packet: WorkPacket, context: AgentContext): AgentReply;
}
